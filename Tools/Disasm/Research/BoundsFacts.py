def name_operands(region, address, operation):
    if region != "Station":
        return operation
    operation = operation.replace("(#9A82)", "(@InterfaceState.EventEnabled)")
    if address in FUNCTIONS:
        operation = operation.replace("(#9CA6)", "(@DrawListState.HeadOperand)")
        if address == 0xCB7F:
            operation = operation.replace("LD DE, #0010", "LD DE, FInterfaceItem")
            operation = operation.replace("CP #80", "CP @InterfaceTable.EndX")
        fields = {0: "X", 1: "Y", 2: "Width", 3: "Height", 8: "SavedX", 9: "SavedY", 10: "SavedWidth", 11: "SavedHeight"}
        for value, field in fields.items():
            operation = operation.replace(f"(IX + #{value:02X})", "(IX + FInterfaceItem."+field+")")
    return operation
