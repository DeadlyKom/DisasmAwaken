def name_operands(region, function_address, operation):
    if region == 'Action' and function_address == 0xAAE2:
        operation = operation.replace('LD H, #9E', 'LD H, @ActionObjectCopyConst.PointerPage')
        operation = operation.replace('LD A, #14', 'LD A, @ActionObjectCopyConst.DataPage')
        operation = operation.replace('LD A, #10', 'LD A, @ActionBankPage.Runtime')
        operation = operation.replace('LD DE, #9F1C', 'LD DE, @ActionObjectCopyState.Buffer')
        operation = operation.replace('AND #0F', 'AND @ActionObjectCopyConst.LengthMask')
        operation = operation.replace('CALL #AB1B', 'CALL @Action.SelectMemoryPage.Entry')
    return operation


def constants():
    lines = ['', '                ; Исходные параметры копирования OBJECT3D', '                module ActionObjectCopyConst']
    for name, value, note in (('PointerPage', 0x9E, 'страница исходных little-endian указателей'),
                              ('DataPage', 0x14, 'полная конфигурация 7FFD для OBJECT3D банка 4'),
                              ('LengthMask', 0x0F, 'число следующих байтов переменной записи, нуль задаёт конец')):
        lines.append((name.ljust(16) + 'equ #' + format(value, '02X')).ljust(80) + '; ' + note)
    return '\n'.join(lines + ['                endmodule', ''])


