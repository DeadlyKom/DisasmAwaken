def name_operands(region,address,operation):
    if (region,address)==('StationBoot',0x6300):
        operation=operation.replace('LD DE, #4000','LD DE, @StationBoot.InitializeStation.Entry')
        operation=operation.replace('LD HL, #6319','LD HL, @BootstrapMoveConst.StationSource')
        operation=operation.replace('LD BC, #02B5','LD BC, @BootstrapMoveConst.StationBytes')
    if (region,address)==('ActionBoot',0x6000):
        operation=operation.replace('LD DE, #4200','LD DE, @ActionBoot.InitializeFlight.Entry')
        operation=operation.replace('LD HL, #6043','LD HL, @BootstrapMoveConst.ActionSource')
        operation=operation.replace('LD BC, #01FA','LD BC, @BootstrapMoveConst.ActionBytes')
    return operation


