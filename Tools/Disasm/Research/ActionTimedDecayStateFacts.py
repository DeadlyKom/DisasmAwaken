def name_operands(region,function_address,operation):
    if (region,function_address)!=('Action',0xF66A):return operation
    return (operation.replace('(IX+#11)','(IX + @FActionRecord.Unknown11)')
            .replace('(IX+#10)','(IX + @FActionRecord.OffsetScaleLow)')
            .replace('#F394','@Action.MarkRecordForReuse.Entry')
            .replace('#F0F8','@Action.PrepareObjectOffsetTransform.Entry'))
