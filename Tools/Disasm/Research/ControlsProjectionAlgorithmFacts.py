OPERANDS = {0xCEF9:'ControlsSmallBodiesState.Mode',
            0xD17D:'ControlsBodyProjection.Value.OffsetY',0xD17E:'ControlsBodyProjection.Value.OffsetX',
            0xD17F:'ControlsBodyProjection.Value.Flags',0xD180:'ControlsBodyProjection.Value.Radius'}
for component in range(3):
    for offset,field in enumerate(('Low','Middle','High')):
        OPERANDS[0x9B1E+3*component+offset]=f'ActionComponentWork.Component{component}.{field}'

def name_operands(region,function_address,operation):
    if region!='Controls' or function_address not in FUNCTIONS:return operation
    operation=re.sub(r'#([0-9A-F]{4})',lambda m:'@'+OPERANDS[int(m[1],16)] if int(m[1],16) in OPERANDS else m[0],operation)
    for value,name in (('#0003','FirstCoord'),('#A000','DepthLimit'),('#A0','RadiusScale'),('#FF','RadiusMax'),('#7F','HighMask'),('#08','WordBits'),('#17','FullShiftMax'),('#01','ProjectionOK')):
        operation=re.sub(re.escape(value)+r'(?![0-9A-F])','@ControlsProjectConst.'+name,operation)
    for before,name in (('BIT 7, A','SignBit'),('SET 0, B','XPlusBit'),('SET 1, B','YMinusBit'),('SET 2, B','XWithinBit'),('SET 3, B','YWithinBit')):
        if operation==before:
            operation=operation.replace(before.split(',')[0].split()[-1],'@ControlsProjectConst.'+name,1)
    return operation
