def name_operands(region,address,operation):
 if region=='D3D' and address==0xD54C:
  from PreviewQueueFacts import STATE
  for pointer,label in STATE.items():operation=operation.replace('(#'+format(pointer,'04X')+')','(@PreviewQueueState.'+label+')')
  operation=operation.replace('LD IY, #CEFA','LD IY, @PreviewQueueState.Flags')
  for pointer,label in {**SCENE_FIELDS,**COEFFICIENTS}.items():operation=operation.replace('(#'+format(pointer,'04X')+')','(@PreviewMatrixComposeState.'+label+')')
  # Именование непосредственных коэффициентов B, C, D остаётся нулевым дисковым инициализатором.
  for (_,pointer),label in LABELS.items():operation=operation.replace('#'+format(pointer,'04X'),'@D3D.ComposePreviewMatrix.'+label)
  for pointer,register in ((0xD525,'B'),(0xD532,'C'),(0xD53F,'D')):operation=operation.replace('CALL #'+format(pointer,'04X'),'CALL @D3D.LookupPreviewProduct'+register+'.Entry')
  operation=operation.replace('LD H, #C3','LD H, @PreviewModelMatrixConst.ProductPage').replace('AND #3F','AND @PreviewMatrixComposeConst.QuarterMask').replace('BIT 0, (IY+#00)','BIT @PreviewModelMatrixConst.OneAxisBit, (IY+@FPreviewDrawState.Flags)')
 return operation
