def name_operands(region, address, operation):
    if region != "Station":
        return operation
    fields = {0xBD26: "TextWindow.Style", 0xBD73: "TextStreamState.Column2X",
              0xBD7E: "TextStreamState.Column3X", 0xBD89: "TextStreamState.Column4X",
              0xBD94: "TextStreamState.Column5X", 0xBD9F: "TextStreamState.Column6X",
              0xBD4F: "TextStreamState.LineEndCode"}
    if address == 0xC2DF:
        operation = operation.replace("LD A, #C9", "LD A, @TextFlowOpcode.Return")
    if address == 0xC325:
        operation = operation.replace("LD A, #C3", "LD A, @TextFlowOpcode.Continue")
    if address == 0xC34B:
        fields.update({0xAEBB: "TextWindow.OriginXLow", 0xAEBF: "TextWindow.OriginXHigh",
                       0xAEC7: "TextWindow.OriginYLow", 0xAECB: "TextWindow.OriginYHigh",
                       0xAEB3: "TextWindow.Width"})
        operation = (operation.replace("ADD A, #03", "ADD A, @TextWindowConst.OriginInset")
                     .replace("ADD A, #04", "ADD A, @TextWindowConst.CenterYInset")
                     .replace("SUB #04", "SUB @TextWindowConst.WidthInset")
                     .replace("SUB #0B", "SUB @TextWindowConst.HeightInset"))
    if address in FUNCTIONS:
        fields.update({0x6320: "TextWindow.CursorX", 0x6321: "TextWindow.CursorY", 0xAEAB: "TextWindow.Height"})
        operation = operation.replace("#0A", "@TextConst.LineFeed").replace("#0D", "@TextConst.CarriageReturn")
        operation = operation.replace("CP #07", "CP @TextConst.FirstGlyph")
        operation = operation.replace("ADD A, #08", "ADD A, @ScreenConst.PixelsPerChar")
    for value, name in fields.items():
        operation = operation.replace(f"(#{value:04X})", "(@"+name+")")
    return operation


