def name_operands(region, function_address, operation):
    if region == 'Action' and function_address == 0xA85E:
        operation = operation.replace('CALL #F10D', 'CALL @Controls.TickBcdCounter.Entry')
    if region == 'Action' and function_address == 0x6145:
        operation = operation.replace('JP #F142', 'JP @Controls.DrawBcdCounter.Entry')
    if region == 'Controls' and function_address in FUNCTIONS:
        for address, name in ((0xF10E, 'RotateGate'), (0x9BBF, 'LowPairs'), (0x9BBD, 'HighPairs')):
            operation = operation.replace('(#' + format(address, '04X') + ')', '(@ControlsBcdCounterState.' + name + ')')
    return operation
