def name_operands(region,address,operation):
    if region != "Station" or address not in FUNCTIONS:
        return operation
    operation = operation.replace("LD A, #17","LD A, @ScreenUpdateConst.CopyPage")
    operation = operation.replace("LD A, #18","LD A, @ScreenUpdateConst.HiddenPage")
    operation = operation.replace("LD A, #10","LD A, @ScreenUpdateConst.VisiblePage")
    operation = operation.replace("LD HL, #4000","LD HL, @ScreenUpdateConst.BaseScreen")
    operation = operation.replace("LD DE, #C000","LD DE, @ScreenUpdateConst.BankWindow")
    operation = operation.replace("LD BC, #1B00","LD BC, @ScreenUpdateConst.ScreenBytes")
    return operation
