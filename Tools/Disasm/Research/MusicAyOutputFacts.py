def name_operands(region,address,operation):
 if region!='Music':return operation
 if address==0xE2CB:
  return operation.replace('(#E29D)','(@MusicState.SlideCounterC)').replace('(#E2D5)','(@MusicGateState.CounterC)').replace('(#DC0A)','(@MusicGateState.AmplitudeC)').replace('(#E1EE)','(@MusicGateState.StateC)').replace('LD HL, #E1EE','LD HL, @MusicGateState.StateC')
 if address==0xE2EB:
  for a,name in ((0xE2EE,'MusicEnvelopeState.SlideOffset'),(0xE2FA,'MusicEnvelopeState.SlideCounter'),(0xDC0B,'MusicAyState.EnvelopePeriod'),(0xDFE9,'MusicAyState.NoiseSeed')):operation=operation.replace('(#'+format(a,'04X')+')','(@'+name+')')
  operation=operation.replace('LD HL, #DC00','LD HL, @MusicAyState.Registers')
 if address==0xE37C:operation=operation.replace('JR #E43C','JR @Music.UnknownE439.PointE43C')
 return operation
