def name_operands(region, address, operation):
    if region != 'Action' or address != 0x6780:
        return operation
    operation = operation.replace('IY+#', 'IY + #')
    aliases = {
        '9BD2': 'ActionByteLimitCounter.Value.Current',
        '6781': 'ActionBodyMotionState.PhaseWord', '9B81': 'ActionGlyphIndicatorState.Control.FirstMode',
        '68D5': 'ActionBodyMotionState.WideStepX', '68FD': 'ActionBodyMotionState.WideStepY',
        '6925': 'ActionBodyMotionState.WideStepDepth', '7B6B': 'ActionApplyParametersState.SpawnLowLimit',
    }
    for index in range(3):
        base = 0x9B6F + 3 * index
        for offset, field in ((0, 'LowWord'), (1, 'LowWord + 1'), (2, 'High')):
            aliases[f'{base + offset:04X}'] = f'ActionTransformWorkVector.Value.Component{index}.{field}'
        for byte in range(4):
            operation = operation.replace(f'(IY + #{index * 4 + byte:02X})',
                                          f'(IY + @FActionWideVector.Component{index}.Byte{byte})')
    for operand, alias in aliases.items():
        operation = operation.replace(f'(#{operand})', f'(@{alias})')
    return operation.replace('LD IY, #9B27', 'LD IY, @ActionWideVectors.Vector00')
