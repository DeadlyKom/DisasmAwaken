def name_operands(region,address,operation):
 if region!='Map' or address not in FUNCTIONS:return operation
 for value,name in ((0xC7B6,'MapVariantState.Count'),(0xC845,'MapVariantState.SpriteSource'),(0xC777,'MapVariantState.BlinkMask'),
  *zip((0xC6CA,0xC6E7,0xC704,0xC721,0xC73E,0xC75B),('MapVariantState.Cursor'+str(i) for i in range(6)))):
  operation=operation.replace('(#'+format(value,'04X')+')','(@'+name+')')
 if address==0xC677:operation=operation.replace('LD A, #04','LD A, @MapVariantConst.TileBias').replace('LD BC, #0603','LD BC, @MapVariantConst.TargetBias')
 if address in (0xC677,0xC827):operation=operation.replace('LD H, #82','LD H, @StationScreenPage.RowHigh')
 if address in WRAPPERS:
  operation=operation.replace('CP #80','CP @MapVariantConst.EndPath')
  for value,name in ((0xCA45,'Radius7.Point00'),(0xCA7E,'Radius10.Point00'),(0xCACF,'Radius13.Point00'),(0xCB38,'Radius16.Point00'),(0xCBB9,'Radius19.Point00'),(0xCC52,'Radius22.Point00'),
   (0xCAF7,'Radius13.Point20'),(0xCA9A,'Radius10.Point14'),(0xCA51,'Radius7.Point06'),(0xCB74,'Radius16.Point30'),(0xCC1D,'Radius19.Point50')):
   operation=operation.replace('LD HL, #'+format(value,'04X'),'LD HL, @MapVariantPaths.'+name)
 if address==0xC76E:operation=operation.replace('LD DE, #CD93','LD DE, @MapVariantResources.Selected').replace('LD HL, #CD03','LD HL, @MapVariantResources.Default')
 if address==0xC827:operation=operation.replace('AND #07','AND @MapVariantConst.PhaseMask')
 return operation
