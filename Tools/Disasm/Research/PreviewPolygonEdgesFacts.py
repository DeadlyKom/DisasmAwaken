def name_operands(region,address,operation):
 if region!='D3D' or address not in FUNCTIONS:return operation
 old={0xD223:'LeftSubtract',0xD227:'LeftHeight',0xD22F:'RightSubtract',0xD233:'RightHeight',0xD239:'CurrentRow',0xD23F:'LeftEndRow',0xD243:'RightEndRow'}
 for pointer,label in old.items():operation=operation.replace('(#'+format(pointer,'04X')+')','(@PreviewPolygonState.'+label+')')
 for pointer,label in STATE.items():operation=operation.replace('(#'+format(pointer,'04X')+')','(@PreviewPolygonEdgeState.'+label+')')
 for pointer,label in ((0xD242,'CheckRightEnd'),(0xD24A,'DrawRow')):operation=operation.replace('#'+format(pointer,'04X'),'@D3D.StepPreviewPolygonRow.'+label)
 operation=operation.replace('#D4DF','@D3D.DividePreviewSlopeByte.Entry')
 for pointer,(name,_) in FUNCTIONS.items():operation=operation.replace('#'+format(pointer,'04X'),'@D3D.'+name+'.Entry')
 for (_,pointer),label in LABELS.items():
  owner=next(name for start,(name,_) in FUNCTIONS.items() if start<=pointer<ENDS[start])
  operation=operation.replace('#'+format(pointer,'04X'),'@D3D.'+owner+'.'+label)
 operation=operation.replace('ADD A, #20','ADD A, @PreviewPolygonConst.RowStepHigh')
 for register in ('B','D'):operation=operation.replace('LD '+register+', #20','LD '+register+', @PreviewPolygonConst.RowStepHigh')
 for register in ('C','E'):operation=operation.replace('LD '+register+', #20','LD '+register+', @PreviewPolygonConst.PixelStepLo')
 operation=operation.replace('LD L, #01','LD L, @PreviewPolygonConst.FirstRow')
 return operation
