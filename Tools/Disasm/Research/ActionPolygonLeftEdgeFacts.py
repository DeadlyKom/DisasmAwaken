def name_operands(region,function_address,operation):
    if region=='Action' and function_address==0xD272:
        for name,address in (('LeftCursor',0xD275),('LeftEndRow',0xD4C4),('RowLimit',0xD22A),('RowBranch',0xD22C)):
            operation=operation.replace('(#'+format(address,'04X')+')','(@ActionPolygonPreparationState.'+name+')')
        for name,address,_ in STATE_FIELDS:
            operation=operation.replace('(#'+format(address,'04X')+')','(@ActionPolygonLeftEdgeState.'+name+')')
        operation=operation.replace('JP C, #D4C1','JP C, @Action.SelectPolygonRowLimit.Entry')
        operation=operation.replace('LD A, #3B','LD A, @ActionPolygonRowSelectionConst.RightOffset')
    return operation
