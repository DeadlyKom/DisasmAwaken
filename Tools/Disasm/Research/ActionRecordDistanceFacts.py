def name_operands(region,function_address,operation):
    if (region,function_address)!=('Action',0xEAE9):return operation
    for register in ('IX','IY'):
        for offset in range(6):
            name='Components.Component'+str(offset//2)+('.High' if offset&1 else '.Low')
            for old in (f'({register}+#{offset:02X})',f'({register} + #{offset:02X})'):
                operation=operation.replace(old,f'({register} + @FActionRecord.{name})')
    return operation
