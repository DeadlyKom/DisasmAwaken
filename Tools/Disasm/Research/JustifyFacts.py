def name_operands(region, address, operation):
    if region != "Station" or address not in FUNCTIONS:
        return operation
    for value, name in ((0xAEAB, "TextWindow.Height"), (0xAEB3, "TextWindow.Width"),
                        (0x6320, "TextWindow.CursorX"), (0xAD4E, "JustifyState.SkipWidth"),
                        (0xADDA, "JustifyState.PrintWidth")):
        operation = operation.replace(f"(#{value:04X})", "(@"+name+")")
    return (operation.replace("CP #0E", "CP @JustifyConst.MinHeight")
            .replace("LD B, #20", "LD B, @TextConst.Space")
            .replace("ADD A, #02", "ADD A, @JustifyConst.MinGap")
            .replace("SUB #02", "SUB @JustifyConst.MinGap"))
