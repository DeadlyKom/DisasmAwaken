def name_operands(region,address,operation):
    if region!='Station' or address not in FUNCTIONS:return operation
    pairs={'(#757A)':'(@PopupState.PreviousRow)','(#9A89)':'(@MenuCommandState.PeriodicCall)',
           '(#9CAA)':'(@MenuCommandState.Hidden)','(#AEC7)':'(@TextWindow.OriginYLow)',
           'LD HL, #9A58':'LD HL, @Station.EmptyCallback.Entry','LD IX, #F0FD':'LD IX, @StationState.Items',
           'LD DE, #0010':'LD DE, FInterfaceItem','CP #80':'CP @InterfaceTable.EndX',
           'LD HL, #7492':'LD HL, @Station.DrawItem43.Entry','LD HL, #6BA5':'LD HL, @Station.DrawItem41.Entry',
           'LD HL, #7637':'LD HL, @Station.DrawItem42.Entry','LD HL, #751B':'LD HL, @Station.DrawItem44.Entry'}
    if address==0xA7B7:
        for off,field in ((0,'X'),(1,'Y'),(2,'Width'),(3,'Height'),(8,'SavedX'),(9,'SavedY'),(10,'SavedWidth'),(11,'SavedHeight')):
            pairs['IX + #'+format(off,'02X')]='IX + FInterfaceItem.'+field
    if address==0xA781:
        pairs.update({'AND #C0':'AND @InterfaceFlags.CloseTopMask','AND #60':'AND @InterfaceFlags.ClosePairMask'})
    for before,after in pairs.items():operation=operation.replace(before,after)
    return operation
