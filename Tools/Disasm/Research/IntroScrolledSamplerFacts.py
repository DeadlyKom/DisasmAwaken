def name_operands(region,address,operation):
    if region=='Intro' and address in (0x66E2,0x66F3):
        operation=operation.replace('(#66F8)','(@IntroScrolledState.SavedSP)')
        operation=operation.replace('JP #7E00','JP @IntroScrolledConst.ChainEntry')
        operation=operation.replace('LD B, #10','LD B, @IntroScrolledConst.RowCount')
        operation=operation.replace('LD E, #C0','LD E, @IntroScrolledConst.FirstColumn')
    return operation


