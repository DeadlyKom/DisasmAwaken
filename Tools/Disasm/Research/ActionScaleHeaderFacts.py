def name_operands(region,function_address,operation):
    if region=='Action':
        for address,name in ((0xE1C8,'SizeSkip'),(0xE232,'FirstAxisSkip'),(0xE26B,'SecondAxisSkip'),(0xE2C5,'ScaledBound')):
            operation=operation.replace('(#'+format(address,'04X')+')','(@ActionScaleHeaderState.'+name+')')
    return operation
