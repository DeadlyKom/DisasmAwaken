def name_operands(region,function_address,operation):
    if (region,function_address)!=('Action',0xF3C8):return operation
    for literal,name in (('17','PhaseMoveTimer'),('19','TimedResumeCode'),('0A','StateCode'),('11','Unknown11')):
        operation=operation.replace('(IX+#'+literal+')','(IX + @FActionRecord.'+name+')')
    for address,name in ((0xE761,'PrepareLinkedRecordContext'),(0xEB72,'NextRandomWord0'),
                         (0xE804,'CheckAndToggleLinkedOverlay'),(0xF222,'CheckMissileSpawnWindow'),(0xF0F8,'PrepareObjectOffsetTransform')):
        operation=operation.replace('#'+format(address,'04X'),'@Action.'+name+'.Entry')
    return operation
