"""Подтверждённое адресование записей с шагом пять, без догадок о смысле полей."""
ENTRIES={0xC5E9:('ReadStrideFiveWord',0x9803,True),0xC5F9:('ReadStrideFiveByte',0x9802,False),
 0xC609:('Property080',0x9806,False),0xC60F:('Property086',0x9826,True),0xC615:('Property087',0x9829,False)}
FUNCTIONS={a:(name,('Чтение слова' if word else 'Чтение байта')+' по индексу из CPU-стека с шагом пять и базой #'+format(base,'04X')) for a,(name,base,word) in ENTRIES.items()}
DOCUMENTS={('Text',a):('StrideFive','общие входы чтения, пятибайтовый шаг и полный договор флагов') for a in ENTRIES}
LABELS={('Text',0xC5EC):'ReadAtBase',('Text',0xC5FC):'ReadAtBase'}
CONTRACTS={}
for address,(name,base,word) in ENTRIES.items():
 inputs=['на вершине CPU-стека слово индекса, под ним адрес возврата, старший байт индекса игнорируется',
  'вычисленные адреса читаемы, Entry выбирает базу #'+format(base,'04X')]
 if address in (0xC5E9,0xC5F9):inputs+=['отдельный вход ReadAtBase принимает произвольную базу в DE']
 CONTRACTS['Text',address]=(
  inputs,
  ['HL=(база+5*индекс'+('+1' if word else '')+') AND #FFFF, DE='+('слово, младший байт первым' if word else 'прочитанный байт с нулевым D'),
   'BC - исходный младший байт индекса с нулевым B, входной BC не сохраняется',
   'AF - A сохранён, S/Z/PV из входного F, H/C от база+5*индекс, X/Y из старшего байта суммы, N=0',
   'альтернативные и индексные регистры, I и IFF сохранены, память не изменяется',
   'SP равен входному SP+4, индекс и адрес возврата потреблены'],
  ['HL, DE, BC, AF только F'],
  ['индекс не проверяется по числу физических записей, только обрезается до младшего байта',
   'PUSH HL и POP BC временно сохраняют индекс для расчёта 4*индекс+индекс',
   'игровое назначение самих читаемых полей здесь ещё не доказано, доказаны адреса, ширина и алгоритм чтения'])
COMMENTS={}
for entry,base,word,shared in ((0xC5E9,0x9803,True,0xC5EC),(0xC5F9,0x9802,False,0xC5FC)):
 COMMENTS[entry]=(['выбор исходной базы '+format(base,'04X')+', её игровое поле пока не установлено'],None)
 COMMENTS[shared]=(['чтение слова индекса поверх возврата, общий вход принимает базу в DE'],None)
 COMMENTS[shared+1]=(['отбрасывание старшего байта индекса'],None)
 COMMENTS[shared+3]=(['сохранение байтового индекса для сложения с его четырёхкратным значением'],None)
 COMMENTS[shared+4]=(['расчёт четырёхкратного индекса двумя удвоениями'],None)
 COMMENTS[shared+6]=(['восстановление индекса в BC, входной BC заменяется'],None)
 COMMENTS[shared+7]=(['расчёт пятибайтового смещения как 4*индекс+индекс'],None)
 COMMENTS[shared+8]=(['расчёт адреса поля относительно базы DE, итоговые флаги от этого сложения'],None)
 COMMENTS[shared+9]=(['чтение '+('младшего байта слова, затем старшего из соседнего адреса' if word else 'байтового значения с последующим обнулением D')],None)
for address in (0xC609,0xC60F,0xC615):
 COMMENTS[address]=(['выбор собственной базы перед общим пятибайтовым чтением'],None)
