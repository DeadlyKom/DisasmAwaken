def name_operands(region,address,operation):
    if region=='Intro' and address in (0x6983,0x68A4):
        for before,after in (('(#67F2)','(@IntroAttrState.FramePhase)'),('(#692A)','(@IntroAttrState.SavedSP)'),
            ('LD HL, #60C0','LD HL, @IntroAttrConst.FirstMatrix'),('LD HL, #61C0','LD HL, @IntroAttrConst.SecondMatrix')):
            operation=operation.replace(before,after)
    return operation


