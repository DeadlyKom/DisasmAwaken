def name_operands(region,address,operation):
    if (region,address)!=('Intro',0x6BBC):return operation
    for before,after in (('LD IXL, #0D','LD IXL, @IntroLookupRowsConst.FirstRows'),
        ('LD IXL, #19','LD IXL, @IntroLookupRowsConst.SecondRows'),
        ('LD HL, #AD00','LD HL, @IntroLookupRowsConst.FirstWords'),
        ('LD HL, #B380','LD HL, @IntroLookupRowsConst.SecondWords'),
        ('LD BC, #8000','LD BC, @IntroLookupRowsConst.FirstBuffer'),
        ('LD BC, #8340','LD BC, @IntroLookupRowsConst.SecondBuffer')):
        operation=operation.replace(before,after)
    return operation


