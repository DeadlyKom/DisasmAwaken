def name_operands(region,address,operation):
 if region=='Map' and address in (0xD2EE,0xD1AC):
  for value,name in PATCHES:operation=operation.replace('(#'+format(value,'04X')+')','(@MapLinePatch.'+name+')')
  for value,name in ((0xDE2B,'Start.X'),(0xDE2C,'Start.Y'),(0xDE2D,'Finish.X'),(0xDE2E,'Finish.Y'),(0xDE3C,'Mode.PixelOpcode'),(0xDE3D,'Mode.ByteCrossOpcode')):
   operation=operation.replace('(#'+format(value,'04X')+')','(@MapLineWork.'+name+')')
  operation=operation.replace('LD H, #EE','LD H, @MapMarkerConst.RowHighPage').replace('LD A, #D4','LD A, @MapLineConst.MaskPage')
  if address==0xD1AC:
   for value,name in ((0x30A1,'ClearMode'),(0x38B1,'SetMode'),(0x38A9,'XorMode')):operation=operation.replace('LD DE, #'+format(value,'04X'),'LD DE, @MapLineConst.'+name)
 return operation
