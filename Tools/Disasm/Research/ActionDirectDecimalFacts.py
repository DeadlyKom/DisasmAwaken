"""Точные обёртки десятичного вывода и исходное обращение через байты инструкции."""


def make(scroll):
    start=0x6010 if scroll else 0x6029
    name='PrintByteAndScrollBank1' if scroll else 'PrintByteBank1'
    title=('Прямой десятичный вывод байта с обязательной прокруткой окна банка 1' if scroll else
           'Прямой десятичный вывод байта в окне банка 1 с исходной попыткой записи в ПЗУ')
    outputs=[
        'HL=(TextColumn после вывода)*256+000F, этот адрес находится в ROM 010F..180F',
        'DE=0100, BC и F равны результату последнего ScrollTextWindow' if scroll else
        'DE и BC равны результату PrintByteDecimal, F равен INC для байта ROM по вычисленному HL с Carry от PrintByteDecimal',
        'A=10, HL\', IX и IY, I/IM/IFF сохраняются, DE\', BC\' и AF\' равны результату последнего дочернего вызова',
        'число выведено двумя цифрами для 0..99 и тремя для 100..255, колонка соответствует последнему знаку',
        'после числа обязательно выполнена ещё одна прокрутка, TextColumn ею не сбрасывается' if scroll else
        'прокрутка возможна перед цифрами при достижении колонки 24, отдельной прокрутки после числа нет',
        'исходный LD (HL),n пытается записать ноль в ROM, память ПЗУ не меняется' if scroll else
        'исходный LD (HL),A пытается записать в ROM прочитанный байт плюс один, память ПЗУ не меняется',
        'OUT 7FFD получает 11, затем 10, итоговый банк 0 и ROM 1, входная страница не восстанавливается',
        'SP после RET равен входному SP+2, до десяти дополнительных байтов стека используются при выводе и прокрутке',
    ]
    contract=(
        ['HL, DE и BC числовых аргументов не задают, AF задаёт A=0..255, исходный F не используется выводом',
         'подготовлены исходные CONTROL0 и CONTROL банка 1, шрифт и окно после InitializeTextWindow',
         '7FFD разблокирован, общий код Action и обычный CPU-стек доступны, аппаратные IRQ не вмешиваются',
         'операнд TextColumn содержит байт колонки, опкод перед ним остаётся исходным 0E'],
        outputs,
        ['HL, DE, BC, AF, DE\', BC\', AF\', R, экран, TextColumn, SavedScrollSP при прокрутке, paging и временные слова CPU-стека'],
        ['LD HL,(EFD5) читает слово 0E + 256*TextColumn, это не LD HL,EFD5 и не получение адреса переменной',
         'INC HL изменяет младший байт 0E на 0F, старший остаётся текущей колонкой 1..24',
         'обе попытки записи в ROM сохранены как инструкции оригинала, предполагаемое намерение автора не подменяет их действия',
         '3584 сценария проверили все 256 входных байтов, семь колонок и оба входа, реальные дочерние процедуры и оба OUT',
         'экран и события цифр сравнены с независимой моделью, регистры обёртки сверены относительно выхода настоящего последнего дочернего вызова',
         'значения остаточных слов стека и операнда SavedScrollSP не рассчитаны независимо, R, точные T, IRQ и нативный запуск не доказаны',
         'игровой вызывающий путь пока не найден, это не является доказательством невостребованности кода'])
    comments={
        start:(['Сохранение исходного A на время подключения банка текстового окна.'],None),
        start+1:(['Выбор банка 1 и ROM 1, значение входного банка не сохраняется.'],None),
        start+6:(['Восстановление входного байта и передача настоящему десятичному рисователю.'],None),
    }
    if scroll:
        comments.update({
            0x601A:(['Прокрутка текстового окна после числа независимо от его ширины и текущей колонки.'],None),
            0x601D:(['Чтение слова из опкода LD C,n и его байта TextColumn, исходная косвенность сохранена.'],None),
            0x6020:(['Расчёт адреса 256*TextColumn+15, адрес остаётся в ПЗУ.'],None),
            0x6021:(['Попытка записи нуля в ПЗУ, при обычном отображении памяти запись игнорируется.'],None),
            0x6023:(['Возврат в банк 0 и ROM 1 с сохранением флагов последней прокрутки.'],None),
        })
    else:
        comments.update({
            0x6033:(['Чтение слова из опкода LD C,n и текущей колонки, адрес переменной здесь не загружается.'],None),
            0x6036:(['Расчёт адреса ПЗУ 256*TextColumn+15.'],None),
            0x6037:(['Чтение байта ПЗУ по вычисленному адресу, это не чтение счётчика колонки.'],None),
            0x6038:(['Расчёт прочитанного байта плюс один по модулю 256, Carry сохраняется.'],None),
            0x6039:(['Попытка записи результата обратно в ПЗУ, обычная память её игнорирует.'],None),
            0x603A:(['Возврат в банк 0 и ROM 1, A заменяется на 10, флаги INC остаются.'],None),
        })
    return {start:(name,title)},{('Action',start):contract},comments,{}


def name_operands(region,function_address,operation):
    if region!='Action' or function_address not in (0x6010,0x6029):
        return operation
    return (operation.replace('CALL #AB1B','CALL @Action.SelectMemoryPage.Entry')
            .replace('CALL #ECF3','CALL @Controls.PrintByteDecimal.Entry')
            .replace('CALL #ED28','CALL @Controls.ScrollTextWindow.Entry')
            .replace('LD HL, (#EFD5)','LD HL, (@ControlsTextDisplayState.TextColumn - 1)'))
