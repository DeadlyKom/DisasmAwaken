def name_operands(region,function_address,operation):
    if region=='Action' and function_address==0xACEA:
        operation=operation.replace('CALL #AD1D','CALL @Action.SwapCodePatchWords.Entry')
        operation=operation.replace('JP #AF43','JP @Action.ComputePatchedVector.Entry')
        operation=operation.replace('LD IY, #AD07','LD IY, @Action.TransformVectorTransposed.Resume')
        operation=operation.replace('(#AD08)','(@ActionVectorWrapperState.SavedSP)')
        for address,name in ((0xAF48,'Input0'),(0xAF56,'Input1'),(0xAF69,'Input2'),
                             (0xD9B6,'Output0'),(0xD7C4,'Output1'),(0xD7A2,'Output2')):
            operation=operation.replace('(#'+format(address,'04X')+')','(@ActionPatchedVectorState.'+name+')')
    return operation
