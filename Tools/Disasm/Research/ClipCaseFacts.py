def name_operands(region,address,operation):
 if region=='Map' and address in (0xD4DD,0xD48B):
  operation=operation.replace('(#DE3A)','(@MapClipWork.Corners.BlockCode)').replace('(#DE3B)','(@MapClipWork.OutputSize)').replace('LD HL, #DE39','LD HL, @MapClipWork.Corners.SeenFlags')
  for bit,name in ((0,'BottomRight'),(1,'BottomLeft'),(2,'TopRight'),(3,'TopLeft')):
   for opcode in ('BIT','SET'):operation=operation.replace(opcode+' '+str(bit)+', (HL)',opcode+' @MapClipCornerBit.'+name+', (HL)')
  if address==0xD48B:
   operation=operation.replace('CP #F0','CP @MapClipConst.InsideCode').replace('AND #F0','AND @MapClipConst.Complement').replace('AND #0F','AND @MapClipConst.SideMask')
   operation=operation.replace('LD H, #DE','LD H, @MapClipConst.DispatchLowPage').replace('LD DE, #D4DD','LD DE, @Map.MapClipCases.Entry')
 return operation
