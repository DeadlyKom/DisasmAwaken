def name_operands(region,address,operation):
    if region != "Station":
        return operation
    for value,name in ((0xC9BF,"HoldMove"),(0xCADF,"HoldResize"),(0xC9B1,"RestoreOrigin"),(0xC9B4,"RestoreSize"),
                       (0xCA20,"FlagsCache"),(0xCA77,"MinWidthTest"),(0xCA7C,"MinWidthValue"),
                       (0xCAAC,"MinHeightTest"),(0xCAB1,"MinHeightValue")):
        operation = operation.replace(f"(#{value:04X})",f"(@TrackState.{name})")
    if address not in FUNCTIONS:
        return operation
    operation = operation.replace("(#6307)","(@StationState.PointerXY)")
    operation = operation.replace("LD HL, #6080","LD HL, @TrackConst.CenterXY")
    operation = operation.replace("AND #C0","AND @PointerConst.PlainShapeMask")
    operation = operation.replace("CP #40","CP @InterfaceFlags.FrontGroup")
    operation = operation.replace("LD A, #03","LD A, @TrackConst.Class00Min")
    operation = operation.replace("LD A, #02","LD A, @TrackConst.Class40Min")
    operation = operation.replace("AND #04","AND @PointerConst.TopBlockMask").replace("AND #02","AND @PointerConst.BottomBlockMask")
    operation = operation.replace("AND #F8","AND @TrackConst.CellBitsMask").replace("AND #07","AND @PointerConst.Low3Mask")
    for op in ("CP", "SUB"):
        operation = operation.replace(op+" #20",op+" @ScreenConst.ByteColumns").replace(op+" #18",op+" @ScreenConst.CharRows")
        operation = operation.replace(op+" #1F",op+" @ScreenConst.LastColumn").replace(op+" #17",op+" @ScreenConst.CharRows - 1")
    operation = operation.replace("CP #21","CP @ScreenConst.ByteColumns + 1").replace("CP #19","CP @ScreenConst.CharRows + 1")
    operation = operation.replace("LD A, #1F","LD A, @ScreenConst.LastColumn").replace("LD A, #17","LD A, @ScreenConst.CharRows - 1")
    operation = operation.replace("LD A, #1D","LD A, @ScreenConst.LastColumn - 2")
    if address == 0xCA1F:
        operation = operation.replace("CP #03","CP @TrackConst.Class00Min").replace("LD L, #03","LD L, @TrackConst.Class00Min").replace("LD H, #03","LD H, @TrackConst.Class00Min")
    return operation
