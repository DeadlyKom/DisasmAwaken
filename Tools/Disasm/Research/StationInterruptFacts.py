def name_operands(region,address,operation):
    if region=='Station':
        for raw,name in [('(#9C0D)','(@StationIrqState.SavedSP)'),('(#9C11)','(@StationIrqState.ReturnPC)'),
                         ('(#9B62)','(@StationIrqState.ModeOperand)'),('(#9B72)','(@StationIrqState.SavedMixer)'),
                         ('(#9B7E)','(@StationIrqState.Divider)'),('(#9A99)','(@StationIrqState.Pulse)'),
                         ('(#99B2)','(@StationIrqState.MusicMode)')]:operation=operation.replace(raw,name)
    if region=='Station' and address==0x9AEA:
        operation=operation.replace('LD SP, #9C43','LD SP, @StationIrqData.StackTop')
        operation=operation.replace('CALL #DB05','CALL @Music.PlayFrame.Entry')
        for value,name in ((0x10,'StationPage'),(0x13,'MusicPage'),(0x32,'ReloadFrames')):
            operation=operation.replace(f'LD A, #{value:02X}','LD A, @StationIrqConst.'+name)
        operation=operation.replace('CP #81','CP @StationIrqConst.MusicMode')
        fields=tuple(f'Row{i}' for i in range(1,8))+('AfterGroup','TailWord')
        for index,field in enumerate(fields):
            operation=operation.replace(f'(#{0xA104+2*index:04X})','(@WindowFillChain.State + FWindowReturnChain.'+field+')')
        for index in range(7):
            operation=operation.replace(f'LD HL, #{0xA0A6+2*index:04X}','LD HL, @Station.FillWindowBody.Scan'+str(index+1))
        operation=operation.replace('LD HL, #A0B4','LD HL, @Station.FillWindowBody.AfterGroup')
        operation=operation.replace('LD HL, #A0B6','LD HL, @WindowFillConst.TailWordValue')
        for raw,field in ((0x983E,'Low'),(0x983D,'MidLow'),(0x983B,'MidHigh'),(0x983C,'High')):
            operation=operation.replace(f'(#{raw:04X})',f'(@StationTimer.Counter + FStationBcdCounter.{field})')
    return operation
