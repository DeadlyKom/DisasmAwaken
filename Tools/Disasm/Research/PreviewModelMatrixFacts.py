  from PreviewQueueFacts import STATE
  for pointer,label in STATE.items():operation=operation.replace('(#'+format(pointer,'04X')+')','(@PreviewQueueState.'+label+')')
  operation=operation.replace('LD HL, #CEFA','LD HL, @PreviewQueueState.Flags')
  for pointer,label in COEFFICIENTS.items():operation=operation.replace('(#'+format(pointer,'04X')+')','(@PreviewModelMatrixState.'+label+')')
  for (_,pointer),label in LABELS.items():operation=operation.replace('#'+format(pointer,'04X'),'@D3D.BuildPreviewModelMatrix.'+label)
