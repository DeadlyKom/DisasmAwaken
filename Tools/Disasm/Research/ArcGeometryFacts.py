def name_operands(region,address,operation):
 if region=='Map' and address in (0xC000,0xDFC3):
  for value,name in ((0xDFC4,'MapArcPatch.ModeControl'),(0xE426,'MapArcPatch.LowTailJump'),(0xE438,'MapArcPatch.HighTailJump'),
   (0xE44F,'MapArcPatch.RightLowJump'),(0xE460,'MapArcPatch.LeftHighJump'),
   (0xDFAB,'MapArcState.AbsY'),(0xDFAC,'MapArcState.AbsX'),(0xDFAD,'MapArcState.QuadrantCode'),(0xDFAE,'MapArcState.Radius'),
   (0xDFAF,'MapArcState.OffsetY'),(0xDFB0,'MapArcState.OffsetX'),(0xDFB1,'MapArcState.RowY'),(0xDFB2,'MapArcState.CenterX'),
   (0xDFB3,'MapArcState.StartY'),(0xDFBE,'MapArcState.MaxY'),(0xDFBF,'MapArcState.ReferenceX'),(0xDFC0,'MapArcState.HalfY'),
   (0xDFC1,'MapArcState.HalfXLimit'),(0xDFC2,'MapArcState.HalfXSquare')):
   operation=operation.replace('(#'+format(value,'04X')+')','(@'+name+')')
  if address==0xDFC3:operation=operation.replace('LD A, #38','LD A, @MapArcConst.TestSetBit').replace('LD A, #30','LD A, @MapArcConst.TestClearBit')
 return operation
