def name_operands(region, function_address, operation):
    if region=='Action' and function_address==0x6E2B:
        for value, name in ((0x47,'HLower'),(0x4A,'HMiddle'),(0x4E,'HUpper'),
                            (0x34,'LLower'),(0x36,'LInset'),(0x38,'LMiddle'),
                            (0x3A,'LInsetEnd'),(0x3B,'LUpper')):
            operation = operation.replace('CP #'+format(value,'02X'), 'CP @ActionRegionTypeConst.'+name)
        for value, name in ((0,'Code0'),(1,'Code1'),(2,'Code2'),(3,'OutsideCode')):
            operation = operation.replace('LD A, #'+format(value,'02X'), 'LD A, @ActionRegionTypeConst.'+name)
    return operation
