def name_operands(region,address,operation):
 if region=='Station' and address==0x6364:
  for value,name in HEADERS.items():operation=operation.replace('(#'+format(value,'04X')+')','(@PreviewFaceHeaders.'+name+')')
  operation=operation.replace('XOR #60','XOR @PreviewFaceConst.FillToggleMask')
 if region=='D3D' and address==0xE07F:operation=operation.replace('CALL #6364','CALL @Station.TogglePreviewFaceFill.Entry')
 return operation
