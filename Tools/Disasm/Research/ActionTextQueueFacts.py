def name_operands(region, address, operation):
    if region == 'Action' and address in (0x6000, 0x6040):
        operation = operation.replace('LD A, #11', 'LD A, @ActionBankPage.Controls')
        operation = operation.replace('LD A, #10', 'LD A, @ActionBankPage.Runtime')
        operation = operation.replace('CALL #EC56', 'CALL @Controls.QueueNumber.Entry')
        operation = operation.replace('CALL #EC59', 'CALL @Controls.QueueTextItem.Entry')
        operation = operation.replace('CALL #AB1B', 'CALL @Action.SelectMemoryPage.Entry')
    return operation
