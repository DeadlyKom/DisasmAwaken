def name_operands(region, address, operation):
    if region != "Station" or address not in FUNCTIONS:
        return operation
    for value, name in ((0x1F, "DeepLeft"), (0xF8, "DeepRight"), (0x20, "InnerLeft"),
                        (0x04, "InnerRight"), (0xFF, "Solid"), (0x00, "Empty")):
        operation = operation.replace(f"LD E, #{value:02X}", "LD E, @SpanPattern."+name)
        operation = operation.replace(f"LD D, #{value:02X}", "LD D, @SpanPattern."+name)
        operation = operation.replace(f"LD C, #{value:02X}", "LD C, @SpanPattern."+name)
    return operation.replace("(#C17F)", "(@StationRaster.SpanSkip)")
