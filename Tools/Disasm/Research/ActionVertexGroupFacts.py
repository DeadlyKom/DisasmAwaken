def name_operands(region,function_address,operation):
    if region == 'Action' and function_address == 0xD694:
        operation = operation.replace('#D7A0','@Action.ProjectRenderVertex.Entry')
        for label,address,_ in STATE_FIELDS:
            operation = operation.replace('(#'+format(address,'04X')+')','(@ActionVertexGroupState.'+label+')')
        operation = operation.replace('LD SP, #8E00','LD SP, @ActionVertexGroupConst.WorkPage')
        operation = operation.replace('CP #01','CP @ActionVertexGroupConst.SingleCode')
        operation = operation.replace('CP #81','CP @ActionVertexGroupConst.AntipodeCode')
    return operation


def constants():
    lines=['','                ; Исходные коды группы и страница рабочего стека','                module ActionVertexGroupConst']
    for name,value,note in (('WorkPage',0x8E00,'исходная страница рабочего SP'),('WorkHigh',0x8E,'старший байт страницы рабочего стека и кодов'),('SingleCode',1,'одна комбинация 0'),('AntipodeCode',0x81,'комбинация 0 и её покомпонентное отрицание')):
        lines.append((name.ljust(16)+'equ #'+format(value,'04X')).ljust(80)+'; '+note)
    return '\n'.join(lines+['                endmodule',''])


