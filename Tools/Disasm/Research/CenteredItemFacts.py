def name_operands(region, address, operation):
    if region != "Station" or address not in FUNCTIONS:
        return operation
    for value, name in ((0x6320, "TextWindow.CursorX"), (0xAEB3, "TextWindow.Width")):
        operation = operation.replace(f"(#{value:04X})", "(@"+name+")")
    return (operation.replace("LD HL, #E4AA", "LD HL, @InterfaceText.CenterTextBase")
            .replace("CP #0A", "CP @TextConst.LineFeed")
            .replace("CP #0D", "CP @TextConst.CarriageReturn")
            .replace("AND #1F", "AND @InterfaceFlags.FrameMask"))
