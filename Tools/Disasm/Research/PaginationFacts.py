def name_operands(region, address, operation):
    if region != "Station" or address not in FUNCTIONS:
        return operation
    return (operation.replace("(#6320)", "(@TextWindow.CursorX)")
            .replace("(#6321)", "(@TextWindow.CursorY)")
            .replace("LD A, #08", "LD A, @ScreenConst.PixelsPerChar"))
