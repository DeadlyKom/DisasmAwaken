def render(source):
    raw=source[0x3800:0x3900];assert list(raw)==[min(i,255-i)**2//127 for i in range(256)]
    text,labels=render_records(source,TABLE,0x6000)
    return text.replace('[подготовка и обход объектов](../../../Docs/PreviewQueueBuild.md)',
        '[граничный отбор](../../../Docs/ActionProjectionClip.md)'),labels


def parse(text):
    clean=[l.partition(';')[0].strip() for l in text.splitlines()];clean=[l for l in clean if l]
    assert clean.pop(0)=='module ActionProjectionSquares' and clean.pop(0)=='assert $ == #9800'
    for i in range(256):
        assert clean.pop(0)==('Index'+format(i,'02X')+':').ljust(16)+'FSymmetricSquareValue {'
        assert re.fullmatch(r'#[0-9A-F]{2}',clean.pop(0));assert clean.pop(0)=='}'
    assert clean==['assert $ == #9900','endmodule']
    return parse_records(text,TABLE,0x6000)


def name_operands(region,function_address,operation):
    if region=='Action' and function_address==0xE213:
        for address,name in ((0xD9B6,'Output0'),(0xD7C4,'Output1'),(0xD7A2,'Output2')):
            operation=operation.replace('(#'+format(address,'04X')+')','(@ActionPatchedVectorState.'+name+')')
        operation=operation.replace('(#6F59)','(@ActionProjectionClipState.SkipDetail)')
        operation=operation.replace('LD A, #48','LD A, @ActionProjectionClipConst.WidthBase')
        operation=operation.replace('LD A, #42','LD A, @ActionProjectionClipConst.HeightBase')
        operation=operation.replace('LD H, #98','LD H, @ActionProjectionClipConst.SquarePage')
    return operation
