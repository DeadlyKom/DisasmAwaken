def name_operands(region,function_address,operation):
    if region!='Action' or function_address not in FUNCTIONS:return operation
    replacements={'(#A85F)':'(@ActionMissileLaunchState.CommandDelay)',
        '(#9C14)':'(@ActionShipEquipment.MineMx1.Value)',
        '(#ECA9)':'(@ActionAyEffectState.CursorA)',
        'LD HL, #EE1B':'LD HL, @ActionEjectConst.Sound',
        'LD A, #14':'LD A, @ActionEjectConst.Delay',
        'LD HL, #9BD3':'LD HL, @ActionOwnedCargoRows.Row00 - 1',
        'LD B, #1E':'LD B, @ActionEjectConst.ScanBytes',
        'LD DE, #642C':'LD DE, @ActionEjectConst.CargoIndexBias',
        'LD IX, #A780':'LD IX, @ActionLinkedContextConst.SpecialRecord',
        'CALL #6441':'CALL @Action.SpawnClass19AndUpdateList.SpawnPrepared',
        'CALL #6040':'CALL @Action.QueueTextItemBank1.Entry'}
    for address,name in LOCAL.items():
        if function_address<=address<ENDS[function_address]:replacements['#'+format(address,'04X')]='@Action.'+FUNCTIONS[function_address][0]+'.'+name
    for before,after in replacements.items():operation=operation.replace(before,after)
    return operation


