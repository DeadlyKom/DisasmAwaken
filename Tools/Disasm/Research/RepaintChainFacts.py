def name_operands(region,address,operation):
    if region=='Station':
        operation = operation.replace('(#CC17)','(@RepaintState.ExitInstruction)')
    if region=='Station' and address in FUNCTIONS:
        operation = operation.replace('LD A, #A7','LD A, @RepaintConst.AndA').replace('LD A, #37','LD A, @RepaintConst.SetCarry')
    return operation
