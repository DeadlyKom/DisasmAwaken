def name_operands(region,address,operation):
 if region=='Station' and address==0xAC74:
  for raw,name in ((0xAD2D,'RankCaption.Entry'),(0xAD21,'RankThresholds.Score10000'),
   (0xACE3,'RankTexts.Rookie'),(0xACEB,'RankTexts.Score10000'),(0xACF4,'RankTexts.Score3000'),
   (0xACFD,'RankTexts.Score1000'),(0xAD06,'RankTexts.Score300'),(0xAD0F,'RankTexts.Score100'),(0xAD17,'RankTexts.Score30')):
   operation=operation.replace('#'+format(raw,'04X'),'@'+name)
  return operation.replace('(#984C)','(@RankState.Score)').replace('LD B, #06','LD B, @RankConst.ThresholdCount')
 return operation
