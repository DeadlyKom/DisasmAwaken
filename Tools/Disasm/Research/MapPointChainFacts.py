def name_operands(region,address,operation):
 if region=='Map' and address==0xD1AC:
  for base,name in ((0xDE0B,'CurrentPoint'),(0xDE1B,'PreviousPoint')):
   for field,offset in (('X',0),('Y',2),('ClipCodes',4)):
    operation=operation.replace('(#'+format(base+offset,'04X')+')','(@MapChainWork.'+name+'.'+field+')')
  for value,name in ((0x6300,'OriginLow'),(0x6301,'OriginLow + 1'),(0x6302,'OriginHigh'),(0x6303,'OriginHigh + 1')):
   operation=operation.replace('(#'+format(value,'04X')+')','(@MapViewState.'+name+')')
  for offset,name in ((0,'X'),(1,'X + 1'),(2,'Y'),(3,'Y + 1'),(4,'ClipCodes')):
   operation=operation.replace('(IX + #'+format(offset,'02X')+')','(IX + FProjectedPoint.'+name+')')
  operation=operation.replace('AND #0F','AND @MapClipConst.CountMask').replace('AND #F0','AND @MapClipConst.Complement').replace('AND #30','AND @MapChainConst.StyleMask').replace('CP #10','CP @MapChainConst.SetStyle')
  operation=operation.replace('LD DE, #F800','LD DE, @MapClipState.Points').replace('LD IXH, #F8','LD IXH, @MapChainConst.PointPage').replace('LD A, #20','LD A, @MapLineConst.SetMaskLow').replace('LD A, #28','LD A, @MapLineConst.ClearMaskLow')
 return operation
