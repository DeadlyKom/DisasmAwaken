def name_operands(region,function_address,operation):
    if region=='Action' and function_address==0xD3AD:
        for name,address in (('RightCursor',0xD3B0),('LastIndex',0xD3B7),('RightEndRow',0xD387)):
            operation=operation.replace('(#'+format(address,'04X')+')','(@ActionPolygonPreparationState.'+name+')')
        for name,address,_ in STATE_FIELDS:
            operation=operation.replace('(#'+format(address,'04X')+')','(@ActionPolygonRightEdgeState.'+name+')')
        operation=operation.replace('JP #D4C1','JP @Action.SelectPolygonRowLimit.Entry')
        operation=operation.replace('JP C, #D4F5','JP C, @Action.SetShortNegativeRightStep.Entry')
    return operation
