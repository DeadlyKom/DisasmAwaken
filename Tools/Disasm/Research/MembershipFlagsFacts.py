def name_operands(region, address, operation):
    if region != 'Text':
        return operation
    if address == 0xC558:
        return operation.replace('(#9849)', '(@CurrentModels.ShipIndex)')
    if address == 0xC5B2:
        return operation.replace('(#984A)', '(@CurrentModels.SkimmerIndex)')
    if address == 0xC577 and operation == 'LD DE, #988E':
        return 'LD DE, @EquipmentListData.Quantities'
    return operation
