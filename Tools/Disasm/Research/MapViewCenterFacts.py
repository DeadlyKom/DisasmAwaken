def name_operands(region,address,operation):
 if region=='Map' and address in FUNCTIONS:
  for raw,name in ((0x9844,'MapSelection.FirstWord'),(0x9846,'MapSelection.SecondWord'),
   (0x6300,'MapViewState.OriginLow'),(0x6302,'MapViewState.OriginHigh'),(0x6304,'MapViewState.Width'),(0x6305,'MapViewState.Height')):
   operation=operation.replace('(#'+format(raw,'04X')+')','(@'+name+')')
 return operation
