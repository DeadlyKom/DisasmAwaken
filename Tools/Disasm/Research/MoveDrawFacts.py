def name_operands(region, address, operation):
    if region != "Station":
        return operation
    operation = operation.replace("(#9CA6)", "(@DrawListState.HeadOperand)")
    if address == 0xBE38:
        operation = operation.replace("LD BC, #0080", "LD BC, @DrawListLimit.ShiftBytes")
        operation = operation.replace("LD (HL), #01", "LD (HL), @DrawListLimit.EndByte")
    return operation
