def name_operands(region,address,operation):
 if region=='Map' and address in FUNCTIONS:
  for raw,name in ((0x9844,'MapSelection.FirstWord'),(0x9846,'MapSelection.SecondWord'),(0x9848,'MapSelection.Variant')):
   operation=operation.replace('(#'+format(raw,'04X')+')','(@'+name+')')
  if address==0xC40F:
   for raw,name in (('00','FirstWord'),('01','FirstWord + 1'),('02','SecondWord'),('03','SecondWord + 1'),('04','Variant')):
    operation=operation.replace('(IX + #'+raw+')','(IX + @FStoredMapPoint.'+name+')')
  return operation.replace('LD IX, #9905','LD IX, @StoredMapPointsA.Point00 - @FStoredMapPoint').replace('LD BC, #0005','LD BC, @FStoredMapPoint').replace('LD DE, #990A','LD DE, @StoredMapPointsA.Point00').replace('LD DE, #993D','LD DE, @StoredMapPointsB.Point00')
 return operation

