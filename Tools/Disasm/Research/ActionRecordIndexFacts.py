def name_operands(region,function_address,operation):
    if region=='Action' and function_address in FUNCTIONS:
        operation=operation.replace('CALL #E6C7','CALL @Action.RecordAddressToIndex.Entry')
        operation=operation.replace('#A1','@ActionRecordIndexConst.BaseHigh')
    return operation
