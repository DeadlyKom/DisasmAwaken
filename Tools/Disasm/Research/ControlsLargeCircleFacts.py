def name_operands(region, address, operation):
    if region != 'Controls' or address not in FUNCTIONS:
        return operation
    for literal, field in (('D17D', 'ControlsBodyProjection.Value.OffsetY'), ('D17F', 'ControlsBodyProjection.Value.Flags'),
                           ('D181', 'ControlsCircleWork.Value.WorkY'), ('D182', 'ControlsCircleWork.Value.WorkX'),
                           ('D183', 'ControlsCircleWork.Value.CenterY'), ('D184', 'ControlsCircleWork.Value.CenterX')):
        operation = operation.replace('(#'+literal+')', '(@'+field+')')
    for bit, name in enumerate(('XPlusBit', 'YMinusBit', 'XWithinBit', 'YWithinBit')):
        operation = operation.replace(f'BIT {bit}, E', 'BIT @ControlsProjectConst.'+name+', E')
    for literal, name in (('30', 'HalfHeight'), ('80', 'CenterX'), ('F0', 'FullWidth'), ('F8', 'FarCornerX')):
        if operation.endswith(' #'+literal):
            operation = operation[:-3]+'@ControlsLargeCircleConst.'+name
    if operation.endswith(' #78'):
        operation = operation[:-3]+'@ControlsHorizontalCircleConst.OffsetLimit'
    return operation
