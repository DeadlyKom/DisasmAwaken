def name_operands(region,function_address,operation):
    if region == 'Controls' and function_address in FUNCTIONS:
        for address,name in ((0xD18C,'Mode'),(0xD5B5,'RowStep'),(0xD600,'BoundaryLimit')):
            operation = operation.replace('(#'+format(address,'04X')+')','(@ControlsInteriorRowsState.'+name+')')
    return operation
