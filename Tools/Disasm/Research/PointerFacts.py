def name_operands(region, address, operation):
    if region != "Station":
        return operation
    aliases = {0x9B16: "UpdateBlocked", 0x64B3: "SpriteBase", 0x6501: "VisibleRows",
               0x6548: "RestoredFlag", 0x6550: "BackgroundAddr"}
    for value, name in aliases.items():
        operation = operation.replace(f"(#{value:04X})", f"(@PointerState.{name})")
    for value, name in ((0x9A8D, "HoverItem"), (0x9A90, "HoverCallback")):
        operation = operation.replace(f"(#{value:04X})", f"(@InterfaceState.{name})")
    if address in FUNCTIONS:
        operation = operation.replace("(#6307)", "(@StationState.PointerXY)")
        operation = operation.replace("(#6308)", "(@StationState.PointerXY + 1)")
        operation = operation.replace("AND #C0", "AND @PointerConst.PlainShapeMask")
        operation = operation.replace("AND #04", "AND @PointerConst.TopBlockMask")
        operation = operation.replace("AND #02", "AND @PointerConst.BottomBlockMask")
        operation = operation.replace("AND #07", "AND @PointerConst.Low3Mask")
        operation = operation.replace("CP #F8", "CP @PointerConst.PairLimit")
        operation = operation.replace("CP #07", "CP @PointerConst.FullTailRows")
        operation = operation.replace("LD A, #BF", "LD A, @PointerConst.LastScreenY")
        operation = operation.replace("LD DE, #FFFC", "LD DE, 0 - FInterfaceItem.Flags")
        operation = operation.replace("LD B, #08", "LD B, @PointerConst.CellHeight")
        operation = operation.replace("LD A, #08", "LD A, @PointerConst.CellHeight")
        operation = operation.replace("SUB #08", "SUB @PointerConst.CellHeight")
        for value, name in ((0x6000, "NormalShape"), (0x6100, "TopShape"), (0x6200, "BottomShape"), (0x6575, "BackgroundBase")):
            operation = operation.replace(f"#%04X" % value, "@PointerConst."+name)
        operation = operation.replace("CALL #CB52", "CALL @Station.GetLastDraw.Entry")
        fields = {4: "Flags", 6: "EventHandler", 7: "EventHandler + 1", 12: "DrawHandler", 13: "DrawHandler + 1"}
        for value, name in fields.items():
            operation = operation.replace(f"(IX + #{value:02X})", f"(IX + FInterfaceItem.{name})")
    return operation
