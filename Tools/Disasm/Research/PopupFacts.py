def name_operands(region,address,operation):
    if region=='Station':operation=operation.replace('(#9E31)','(@PopupState.SkippedIndex)')
    if region=='Station' and address==0x9E1F:
        operation=operation.replace('LD HL, #FFF0','LD HL, @PopupConst.NoSelection')
        operation=operation.replace('AND #E0','AND @InterfaceFlags.GroupMask').replace('CP #20','CP @PopupConst.GroupCode')
    if region=='Station' and address==0x9E4E:
        operation=operation.replace('CP #0F','CP @PopupConst.MaxY').replace('LD H, #0F','LD H, @PopupConst.MaxY')
        operation=operation.replace('CP #17','CP @PopupConst.MaxX').replace('LD L, #17','LD L, @PopupConst.MaxX')
        operation=operation.replace('(#F385)','(@InterfaceItems.Item40 + FInterfaceItem.SavedX)')
        operation=operation.replace('LD HL, #7583','LD HL, @Station.DrawItem40.Entry')
        operation=operation.replace('JP #CBA9','JP @Station.RestoreItemBounds.Entry')
    if region=='Station' and address==0x7583:operation=operation.replace('LD HL, #E32E','LD HL, @ContextMenuText.Entry')
    return operation
