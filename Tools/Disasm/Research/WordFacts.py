def name_operands(region, address, operation):
    if region != "Station" or address not in FUNCTIONS:
        return operation
    return (operation.replace("#0A", "@TextConst.LineFeed")
            .replace("#0D", "@TextConst.CarriageReturn")
            .replace("CP #20", "CP @TextConst.Space")
            .replace("CP #03", "CP @GlyphStatus.Width"))
