def name_operands(region,address,operation):
 if region=='Map' and address in FUNCTIONS:
  for raw,name in ((0xC7B6,'MapVariantState.Count'),(0xC817,'MapVariantState.Wanted'),
   (0x9844,'MapSelection.FirstWord'),(0x9846,'MapSelection.SecondWord'),(0x9848,'MapSelection.Variant'),
   (0x983F,'SignatureInput.Entry.FirstWord'),(0x9841,'SignatureInput.Entry.SecondWord'),(0x9843,'SignatureInput.Entry.Variant'),
   *[(value,'MapVariantState.Resource'+str(i)) for i,value in enumerate((0xC6C1,0xC6DE,0xC6FB,0xC718,0xC735,0xC752))]):
   operation=operation.replace('(#'+format(raw,'04X')+')','(@'+name+')')
  for value,name in ((0xCD03,'Default'),(0xCD33,'Current'),(0xCD63,'Stored'),(0xCD93,'Selected')):
   operation=operation.replace('LD HL, #'+format(value,'04X'),'LD HL, @MapVariantResources.'+name)
  for raw,name in (('00','FirstWord'),('01','FirstWord + 1'),('02','SecondWord'),('03','SecondWord + 1'),('04','Variant')):
   operation=operation.replace('(IX + #'+raw+')','(IX + @FStoredMapPoint.'+name+')')
  return operation.replace('LD IX, #9938','LD IX, @StoredMapPointsB.Point00 - @FStoredMapPoint').replace('LD BC, #0005','LD BC, @FStoredMapPoint')
 return operation
