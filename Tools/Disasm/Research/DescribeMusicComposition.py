"""Документация физической композиции и двусторонний индекс её 72 исходных частей."""
from pathlib import Path
from MusicCompositionSource import descriptions, records

ROOT = Path(__file__).resolve().parents[3]


def main():
    data = (ROOT/'Tools/Disasm/Extracted/Active/10_MUZ1.C.bin').read_bytes()[0xC00:]
    parts = descriptions(data)
    def link(item):
        return '[' + Path(item['path']).stem + '](../' + item['path'] + ')'
    lines = ['# Исходная композиция Antichrist', '',
        'Композиция занимает 4137 байтов по E700..F728, файловые смещения 0C00..1C28 MUZ1.C. '
        'Все байты оформлены исходными директивами в 72 частях. Обычная сборка включает их непосредственно '
        'из Source/Files/10_MUZ1.inc средствами SjASMPlus, отдельный конвертер не требуется. '
        'Общие потоки не скопированы по числу ссылок, нулевые относительные адреса сохранены.', '',
        'Строка описания буквально содержит ProTracker 3.6, Antichrist, SET/ELLiPSE GROUP и 01.11.2000. '
        'Эта строка сохранена целиком, включая исходные пробелы. Байты остаются источником истины, '
        'название формата не заменяет проверку поведения проигрывателя этой версии.', '',
        '## Заголовок и таблицы относительных адресов', '',
        '| Исходник | Смещение в композиции | Размер | Физическое содержание |',
        '| --- | --- | ---: | --- |']
    meanings = dict(header='FMusicModuleHeader, описание и исходные поля настройки',
        sample_offsets='32 FMusicRelativePointer сэмплов', ornament_offsets='16 FMusicRelativePointer орнаментов',
        positions='28 FMusicPositionByte и отдельный байт End=FF', pattern_offsets='19 FMusicPatternPointers по три относительных слова')
    for item in parts[:5]:
        lines.append('| ' + link(item) + ' | #' + format(item['offset'], '04X') + ' | ' + str(item['length']) + ' | ' + meanings[item['kind']] + ' |')
    lines += ['',
        'FMusicModuleHeader имеет поля Description размером 99 байтов, Unknown63 по смещению 99, '
        'RowTempo по 100, PositionCount по 101, LoopIndex по 102 и слово PatternTable по 103. '
        'Итого 105 байтов. Значения настройки равны 3, 28, 4 и 230 соответственно. '
        'InitializeModule читает PositionCount в F через POP AF, но конец списка выбирает по FF, '
        'не по этому числу. LoopIndex=4 указывает пятый байт списка, а не номер группы паттернов.', '',
        'Unknown63 содержит 02, инициализатор пропускает этот байт. Его назначение по фактическому '
        'потребителю не доказано, поэтому имя Unknown сохранено. Внешнее описание другой версии PT3 '
        'не используется как доказательство для этого байта.', '',
        'FMusicRelativePointer.Offset отсчитывается от E700, InitializeModule добавляет эту базу '
        'и сохраняет абсолютные слова в [таблице проигрывателя](MusicPlayerData.md). '
        'Двадцать записей сэмплов и две записи орнаментов содержат нулевое слово. '
        'Алгоритм превращает его в E700, не в адрес EmptySample. Отдельные записи сэмпла '
        'или орнамента по этому адресу не создаются, там уже лежит заголовок.', '',
        'Байты позиций равны 15, 18, 21, 24, 0, 3, 0, 27, 6, 9, 6, 12, 0, 3, 0, 27, '
        '30, 33, 30, 36, 39, 42, 39, 45, 48, 51, 48, 54, затем FF. Все обычные значения '
        'кратны трём. [AdvancePatternA](MusicPattern.md) прибавляет удвоенный байт позиции '
        'к таблице, поэтому 15 выбирает шестую тройку, а 54 девятнадцатую. '
        'Сам код не умножает номер группы на шесть и не исправляет некратные значения.', '',
        'Каждый FMusicPatternPointers содержит ChannelA, ChannelB, ChannelC со смещениями 0, 2 и 4. '
        'Это относительные слова. Повторяющиеся значения указывают общие физические потоки, '
        'а не отдельные копии с одинаковым содержимым.', '',
        '## Физические потоки паттернов', '',
        'Все 57 ссылок из девятнадцати троек сводятся к 41 физическому потоку. '
        'Границы проверены по адресам ссылок и собственному нулевому байту в конце каждого потока. '
        'Команды оформлены DB с русским пояснением каждой группы, RowXX обозначает начало '
        'очередной декодируемой строки. Это номер строки команд, не число кадров и не значение длительности.', '',
        'Внутри строки отдельно выделены немедленные данные и параметры отложенных эффектов. '
        'Команды 05, 01 и 08 в композиции помещают обработчики в стек, параметры после ноты '
        'либо D0 читаются в порядке RET от последней команды к первой. '
        'Точная грамматика, отличие шумового диапазона B и все регистровые контракты приведены '
        'в [MusicPattern](MusicPattern.md), параметры эффектов в [MusicEffects](MusicEffects.md).', '',
        'End=00 находится вне разобранных строк. Для A вызывающий код использует его '
        'как признак перехода позиции. У B/C тот же физический конечный байт не превращён '
        'в новую команду декодера, поступление на него как на обычную команду было бы '
        'чтением зарезервированного слова эффекта 00. Сценарий смены позиций не следует '
        'подменять универсальным правилом, что любой ноль завершает любой декодер.', '',
        '| Исходник | Смещение | Байтов | Строк команд | Ссылки номер группы и канал |',
        '| --- | --- | ---: | ---: | --- |']
    for item in parts:
        if item['kind'] != 'pattern':
            continue
        count = sum(record['label'].startswith('Row') for record in item['records'])
        aliases = ', '.join(str(ref['pattern']) + ref['channel'] for ref in item['references'])
        lines.append('| ' + link(item) + ' | #' + format(item['offset'], '04X') + ' | ' + str(item['length']) + ' | ' + str(count) + ' | ' + aliases + ' |')
    lines += ['', '## Сэмплы', '',
        'Двенадцать непустых относительных адресов указывают двенадцать непрерывных записей '
        'по смещениям 3720..4051. Каждая начинается физическим FMusicLoopHeader, за ним '
        'расположены Length экземпляров FMusicSampleStep. Всего 77 четырёхбайтовых шагов. '
        'Заголовок задаёт LoopPosition и Length, все значения LoopPosition меньше Length.', '',
        'FMusicSampleStep содержит ShiftControl, LevelModes и little endian ToneDelta. '
        'Схемы разрядов управляющих байтов и действия каждого бита приведены в '
        '[MusicSynthesis](MusicSynthesis.md) и в объявлениях STRUCT. '
        'Тональная поправка складывается по модулю 65536, поправки шума и огибающей '
        'по модулю 256. Имена полей отражают реальное потребление POP DE и POP BC, '
        'порядок байтов не изменён.', '',
        '| Исходник | Смещение | LoopPosition | Length | Байтов |',
        '| --- | --- | ---: | ---: | ---: |']
    for item in parts:
        if item['kind'] == 'sample':
            lines.append('| ' + link(item) + ' | #' + format(item['offset'], '04X') + ' | ' + str(item['loop_position']) + ' | ' + str(item['step_count']) + ' | ' + str(item['length']) + ' |')
    lines += ['', '## Орнаменты', '',
        'Четырнадцать записей занимают смещения 4052..4136. После FMusicLoopHeader '
        'расположены Length физических FMusicOrnamentStep, всего 57 однобайтовых шагов. '
        'Поле NoteDelta является байтовой поправкой индекса ноты. Сложение с текущей '
        'нотой оборачивается, затем исходное ядро проверяет старший разряд суммы. '
        'Отрицательные байтовые значения не пересчитаны и не ограничены новым алгоритмом.', '',
        '| Исходник | Смещение | LoopPosition | Length | Байтов |',
        '| --- | --- | ---: | ---: | ---: |']
    for item in parts:
        if item['kind'] == 'ornament':
            lines.append('| ' + link(item) + ' | #' + format(item['offset'], '04X') + ' | ' + str(item['loop_position']) + ' | ' + str(item['step_count']) + ' | ' + str(item['length']) + ' |')
    lines += ['', '## Проверка и границы', '',
        '[MusicCompositionLayout.py](../Tools/Disasm/Research/MusicCompositionLayout.py) проверяет '
        'все границы без пересечений и пропусков, размеры заголовков и шагов, ссылки общих потоков '
        'и разбор команд с LIFO-параметрами. [Отчёт разметки](../Tools/Disasm/Reports/MusicCompositionLayout.json) '
        'содержит каждую физическую область, команду, ссылку и контрольную сумму.', '',
        '[MusicCompositionSource.py](../Tools/Disasm/Research/MusicCompositionSource.py) строго читает '
        'фактические директивы и экземпляры структур, отвергает лишние строки, неправильное число '
        'полей и изменение порядка записей. VerifySources сравнивает каждый байт с исходной записью '
        'образа, адреса меток и физических полей, размеры и смещения STRUCT. '
        '[Отчёт публикации](../Tools/Disasm/Reports/MusicCompositionClassification.json) фиксирует '
        'сохранение 4137 байтов и удаление только заменённого бинарного ресурса после проверки, '
        'оригинал остаётся в извлечённом MUZ1.C и истории.', '',
        'CheckFilePlacement проверяет прямую цепочку include и каждый физический диапазон. '
        'Нативная сборка не запускалась. Независимые модели исходного проигрывателя совпали '
        'на 5377 кадрах, всех 2304 вызовах декодеров, 1793 исполнениях AdvancePatternA '
        'и 5377 фазах B/C до первого повтора. Это проверка алгоритмов на исходных байтах, '
        'она не подменяет сборку новых текстов, аппаратные IRQ или нативное прослушивание.', '',
        'Назначение Unknown63, выполнение зарезервированных кодов эффектов, аппаратные IRQ '
        'и нативный звук остаются непроверенными. Совпадение байтов не объявлено доказательством '
        'полной смысловой завершённости всего проекта.']
    assert all(item['path'] in '\n'.join(lines) for item in parts)
    (ROOT/'Docs/MusicComposition.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('Composition documentation parts', len(parts), 'typed records', sum(len(records(data, item)) for item in parts))


if __name__ == '__main__':
    main()
