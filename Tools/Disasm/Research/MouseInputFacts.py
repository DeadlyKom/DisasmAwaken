def name_operands(region,address,operation):
    if region!='Station':return operation
    for raw,name in [('(#65C7)','(@MousePollState.SetupJump)'),('(#65CC)','(@MousePollState.FirstOffset)'),
                     ('(#65D1)','(@MousePollState.SecondOffset)'),('(#658C)','(@MouseInput.State + FMouseInput.PreviousX)')]:
        operation=operation.replace(raw,name)
    if address in FUNCTIONS and address<0x6638:
        operation=operation.replace('LD HL, #6585','LD HL, @MouseInput.State')
        operation=operation.replace('LD BC, #FADF','LD BC, @MouseConst.ButtonPort')
        operation=operation.replace('LD BC, #FBDF','LD BC, @MouseConst.XPort')
        operation=operation.replace('CP #FE','CP @MouseConst.MaxX').replace('LD A, #FE','LD A, @MouseConst.MaxX')
        operation=operation.replace('CP #BF','CP @MouseConst.MaxY').replace('LD A, #BF','LD A, @MouseConst.MaxY')
        for value,field in [(0,'Action2'),(1,'Up'),(2,'Down'),(3,'Right'),(4,'Left'),(5,'Action1'),(6,'ExtraButton')]:
            operation=operation.replace(f'IX + #{value:02X}',f'IX + FMouseInput.{field}')
    return operation
