def name_operands(region,function_address,operation):
    if (region,function_address)!=('Action',0xEA00):return operation
    operation=operation.replace('(IX+#12)','(IX + @FActionRecord.ClassCode)')
    for code in (0,4,5,8,1,9):
        operation=operation.replace('CP #'+format(code,'02X'),'CP @ActionCandidateListConst.AllowedClass'+str(code))
    return operation
