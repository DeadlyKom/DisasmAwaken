def name_operands(region, address, operation):
    if region == 'Music' and address in FUNCTIONS:
        operation = re.sub(r'#([0-9A-F]{4})', lambda m: '@' + OPERANDS[int(m[1], 16)]
                           if int(m[1], 16) in OPERANDS else m[0], operation)
    return operation
