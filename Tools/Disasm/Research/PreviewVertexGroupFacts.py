def name_operands(region,address,operation):
 if region=='D3D' and address==0xD908:
  for pointer,label in STATE.items():operation=operation.replace('(#'+format(pointer,'04X')+')','(@PreviewVertexGroupState.'+label+')')
  for (_,pointer),label in LABELS.items():operation=operation.replace('#'+format(pointer,'04X'),'@D3D.ProjectPreviewVertexGroup.'+label)
  operation=operation.replace('#DA14','@D3D.ProjectPreviewVertex.Entry')
  operation=operation.replace('CP #01','CP @PreviewVertexGroupConst.SingleMask').replace('CP #81','CP @PreviewVertexGroupConst.OppositeMask')
  for index in range(8):operation=operation.replace('BIT '+str(index)+', B','BIT @PreviewVertexGroupConst.Vertex'+str(index)+'Bit, B')
 return operation
