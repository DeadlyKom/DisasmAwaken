def name_operands(region, address, operation):
    if region == "Station":
        operation = operation.replace("(#9839)", "(@InterfaceState.EventCode)")
    if (region, address) == ("Station", 0xCC81):
        operation = operation.replace("CALL #9E97", "CALL @Station.GetItemFrameBit.Entry")
        operation = operation.replace("LD HL, #9A58", "LD HL, @Station.EmptyCallback.Entry")
    return operation
