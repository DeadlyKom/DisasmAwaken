def name_operands(region, address, operation):
    if region != "Station" or address != 0xA6C4:
        return operation
    return (operation.replace("CP #21", "CP @ItemRectLimit.EndColumn")
            .replace("CP #19", "CP @ItemRectLimit.EndRow")
            .replace("CP #04", "CP @ItemRectLimit.MinSize"))
