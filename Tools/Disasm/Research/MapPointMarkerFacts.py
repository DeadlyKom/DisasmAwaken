def name_operands(region,address,operation):
 if region=='Map' and address==0xC231:
  for raw,name in ((0x6300,'MapViewState.OriginLow'),(0x6302,'MapViewState.OriginHigh'),(0x6304,'MapViewState.Width'),(0x6305,'MapViewState.Height')):
   operation=operation.replace('(#'+format(raw,'04X')+')','(@'+name+')')
  return operation.replace('LD H, #EE','LD H, @MapMarkerConst.RowHighPage').replace('SUB #08','SUB @MapMarkerConst.RightInset').replace('SUB #07','SUB @MapMarkerConst.BottomInset')
 return operation
