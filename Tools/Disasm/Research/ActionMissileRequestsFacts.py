def name_operands(region,function_address,operation):
    if region!='Action' or function_address not in FUNCTIONS:return operation
    for address,name in ((0x70A4,'CheckMissileLaunch'),(0x60AE,'CreateMissileForTarget'),
        (0x6380,'ApplyIndexedDelta'),(0x70ED,'SelectMissileStock'),(0x70C6,'ConsumeMissileStock'),(0x705D,'CompleteMissileLaunch')):
        operation=operation.replace('#'+format(address,'04X'),'@Action.'+name+'.Entry')
    for i in range(3):operation=operation.replace('(#'+format(0x9B1B+i,'04X')+')','(@ActionMissileTargets.Value.Target'+str(i)+')')
    operation=operation.replace('(#ECA9)','(@ActionAyEffectState.CursorA)')
    operation=operation.replace('LD HL, #EDA8','LD HL, @ActionMissileCreateConst.ActionSound')
    operation=operation.replace('LD HL, #0007','LD HL, FActionRecord.ClassCode - FActionRecord.LinkedIndex')
    return operation

