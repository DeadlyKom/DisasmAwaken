def name_operands(region,function_address,operation):
    if region=='Controls' and function_address==0xE14E:
        for value,name in ((0xF8,'HighMergeMask'),(0xC7,'LowMergeMask'),(7,'LowThreeMask')):
            operation = operation.replace('AND #'+format(value,'02X'),'AND @ControlsThreeRowGlyphConst.'+name)
        operation = operation.replace('ADD A, #20','ADD A, @ControlsThreeRowGlyphConst.CharRowStride')
        operation = operation.replace('SUB #08','SUB @ControlsThreeRowGlyphConst.CharHeight')
    if region=='Controls' and function_address==0xE021:
        for value,name in ((0xE1B1,'Plus00'),(0xE1E1,'Cross00'),(0xE211,'Solid00'),(0xE241,'Hollow00')):
            operation = operation.replace('LD DE, #'+format(value,'04X'),'LD DE, @ControlsThreeRowGlyphs.'+name)
    return operation
