def name_operands(region,address,operation):
    if region!='Station' or address!=0x9C77:return operation
    for before,after in (('(#99C2)','(@InterfaceColors.InkBits + FSettingWord.ValueOrRow)'),
                         ('(#99C4)','(@InterfaceColors.PaperRotate + FSettingWord.ValueOrRow)'),
                         ('(#99C6)','(@InterfaceColors.HighRotate + FSettingWord.ValueOrRow)'),
                         ('(#9D48)','(@BackgroundState.ItemAttribute)'),('(#9CA6)','(@DrawListState.HeadOperand)'),
                         ('LD HL, #9D21','LD HL, @Station.RebuildInterface.AfterDraw'),
                         ('IX + #00','IX + FDrawListEntry.Handler'),('IX + #01','IX + FDrawListEntry.Handler + 1'),
                         ('IX + #03','IX + FDrawListEntry + FDrawListEntry.Handler + 1')):
        operation=operation.replace(before,after)
    return operation
