def name_operands(region,address,operation):
    if region!='Map' or address!=0xC908:return operation
    operation=operation.replace('(#C91D)','(@MapHighlightState.WidthSkip)')
    operation=operation.replace('LD A, #1F','LD A, @SelectionBandConst.Low5Mask')
    operation=operation.replace('LD A, #F8','LD A, @SelectionBandConst.High5Mask')
    operation=operation.replace('AND #07','AND @ScreenConst.PixelOffsetMask')
    operation=operation.replace('LD B, #08','LD B, @ScreenConst.PixelsPerChar')
    operation=operation.replace('ADD A, #20','ADD A, @ScreenConst.ByteColumns')
    operation=operation.replace('SUB #08','SUB @ScreenConst.PixelsPerChar')
    return operation
