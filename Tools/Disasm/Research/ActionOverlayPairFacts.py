def name_operands(region,function_address,operation):
    if (region,function_address)!=('Action',0xEB41):return operation
    for address,name in ((0xADC5,'ProjectOverlayCoordinates'),(0xEC54,'ClassifyProjectedPair'),
                         (0xDBBD,'RenderClippedRecords'),(0xDD23,'RenderInsideRecords')):
        operation=operation.replace('#'+format(address,'04X'),'@Action.'+name+'.Entry')
    for address,offset in ((0x8E00,0),(0x8E02,2),(0x8E05,5),(0x8E07,7)):
        operation=operation.replace('(#'+format(address,'04X')+')','(@ActionVertexGroupConst.WorkPage'+(' + '+str(offset) if offset else '')+')')
    return operation.replace('#EB6E','@ActionOverlayLineData.Line')
