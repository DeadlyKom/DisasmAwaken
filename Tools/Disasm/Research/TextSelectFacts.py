def name_operands(region, address, operation):
    if region != "Station" or address not in FUNCTIONS:
        return operation
    return (operation.replace("(#A397)", "(@TextSelectState.Separator)")
            .replace("LD A, #0D", "LD A, @TextConst.CarriageReturn")
            .replace("LD A, #0A", "LD A, @TextConst.LineFeed"))
