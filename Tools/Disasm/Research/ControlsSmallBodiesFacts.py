def name_operands(region,function_address,operation):
    if region=='Controls' and function_address==0xD9DE:
        for address,field in ((0xD17D,'OffsetY'),(0xD17F,'Flags'),(0xD180,'Radius')):
            operation=operation.replace('(#'+format(address,'04X')+')','(@ControlsBodyProjection.Value.'+field+')')
        for address,name in ((0xCEF9,'Mode'),(0xD240,'Pattern'),(0xDA83,'LeftMask')):
            operation=operation.replace('(#'+format(address,'04X')+')','(@ControlsSmallBodiesState.'+name+')')
        operation=operation.replace('#D990','@ControlsSmallMaskRows.Row00')
        operation=operation.replace('(IX + #00)','(IX + @FSmallMaskRow.Mask)')
        for before,after in (
            ('CP #04','CP @SmallBodyConst.ModeLimit'),('CP #09','CP @SmallBodyConst.RadiusLimit'),('CP #02','CP @SmallBodyConst.RadiusMin'),
            ('LD A, #7F','LD A, @SmallBodyConst.XBias'),('CP #08','CP @SmallBodyConst.BytePixels'),('CP #F8','CP @SmallBodyConst.RightClipFrom'),
            ('LD A, #48','LD A, @SmallBodyConst.YMaxOffset'),('LD A, #30','LD A, @SmallBodyConst.YBias'),
            ('LD H, #04','LD H, @SmallBodyConst.RasterFactor'),('AND #07','AND @SmallBodyConst.PhaseMask'),
            ('SUB #20','SUB @SmallBodyConst.RowBytes'),('CP #60','CP @SmallBodyConst.LowPagePass'),
            ('CP #8C','CP @SmallBodyConst.BufferEndPage'),('CP #80','CP @SmallBodyConst.BufferFirstPage'),
            ('LD B, #08','LD B, @SmallBodyConst.BytePixels'),('LD A, #08','LD A, @SmallBodyConst.BytePixels'),
            ('BIT 7, D','BIT @SmallBodyConst.UpperHalfBit, D'),('SET 7, D','SET @SmallBodyConst.UpperHalfBit, D')):
            operation=operation.replace(before,after)
    return operation
