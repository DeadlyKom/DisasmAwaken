def name_operands(region,address,operation):
    if region!='Station' or address not in FUNCTIONS:return operation
    operation=operation.replace('(#6308)','(@StationState.PointerXY + 1)')
    operation=operation.replace('IX + #01','IX + FInterfaceItem.Y').replace('IX + #03','IX + FInterfaceItem.Height')
    operation=operation.replace('AND #F8','AND @RowSelectConst.CellMask').replace('AND #1F','AND @RowSelectConst.RowMask')
    operation=operation.replace('SUB #05','SUB @RowSelectConst.BottomInset')
    return operation
