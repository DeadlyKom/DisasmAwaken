def name_operands(region,address,operation):
    if region not in ('Station','StationBoot'):return operation
    for raw,name in [('(#6639)','(@PointerInputState.JoyDisabled)'),('(#66CD)','(@PointerInputState.Step)'),
                     ('(#66CF)','(@PointerInputState.MaxY)'),('(#66D1)','(@PointerInputState.MaxX)')]:
        operation=operation.replace(raw,name)
    if region=='Station' and (address in FUNCTIONS or address==0x66D8):
        operation=operation.replace('LD HL, #66E8','LD HL, @InputFlags.State')
        operation=operation.replace('LD HL, #66EE','LD HL, @PointerDirections.None')
        for raw,field in ((0x99B6,'Up'),(0x99B8,'Down'),(0x99BA,'Left'),(0x99BC,'Right'),(0x99BE,'Action2'),(0x99C0,'Action1')):
            operation=operation.replace(f'(#{raw:04X})',f'(@PointerKeys.{field})')
    return operation
