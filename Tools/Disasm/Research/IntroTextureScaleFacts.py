def name_operands(region,address,operation):
    if region=='Intro' and address in (0x6C21,0x6C53):
        for name,value,_ in FIELDS:
            operation=operation.replace('(#'+format(value,'04X')+')','(@IntroScaleState.'+name+')')
    return operation
