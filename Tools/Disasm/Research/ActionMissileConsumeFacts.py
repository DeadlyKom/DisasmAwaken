def name_operands(region,function_address,operation):
    if region=='Action' and function_address==0x70C6:
        for address,name in ((0x6040,'QueueTextItemBank1'),(0x6000,'QueueNumberBank1'),(0x70ED,'SelectMissileStock')):
            operation=operation.replace('CALL #'+format(address,'04X'),'CALL @Action.'+name+'.Entry')
