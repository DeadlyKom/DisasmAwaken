def name_operands(region,function_address,operation):
    if region=='Action' and function_address==0xD4C1:
        for name,address in (('RightEndRow',0xD387),('RowLimit',0xD22A),('RowBranch',0xD22C)):
            operation=operation.replace('(#'+format(address,'04X')+')','(@ActionPolygonPreparationState.'+name+')')
        for value,name in ((0x36,'StopOffset'),(0x45,'LeftOffset'),(0x3B,'RightOffset')):
            operation=operation.replace('LD A, #'+format(value,'02X'),'LD A, @ActionPolygonRowSelectionConst.'+name)
    return operation


