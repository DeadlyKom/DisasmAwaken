def name_operands(region,address,operation):
 if region=='Map' and address==0xC000:
  for value,name in ((0x6300,'MapViewState.OriginLow'),(0x6302,'MapViewState.OriginHigh'),(0x6304,'MapViewState.Width'),(0x6305,'MapViewState.Height'),
   (0x6309,'SecondaryPointState.Cursor'),(0x9844,'MapSelection.FirstWord'),(0x9846,'MapSelection.SecondWord'),
   (0xC22E,'MapScenePatch.SavedStack'),(0xC18B,'MapScenePatch.WidthFirst'),(0xC1E4,'MapScenePatch.WidthSecond'),
   (0xC211,'MapScenePatch.InverseWidthB'),(0xC1B6,'MapScenePatch.InverseWidthA'),(0xC174,'MapScenePatch.HeightPositive'),(0xC1D1,'MapScenePatch.HeightNegative')):
   operation=operation.replace('(#'+format(value,'04X')+')','(@'+name+')')
  for value,name in ((0xCFC3,'Primary'),(0xCDC3,'Selected'),(0xCF43,'Cursor'),(0xD043,'Stored'),(0xCEC3,'ActiveAux'),(0xCE43,'Secondary')):
   operation=operation.replace('LD HL, #'+format(value,'04X'),'LD HL, @MapMarkerSprites.'+name+'.Phase0')
  operation=operation.replace('LD IX, #997B','LD IX, @MapAuxiliaryPoints.Key00').replace('LD HL, #99A3','LD HL, @MapAuxiliaryCodes.State')
  for value,name in ((0,'FirstWord'),(1,'FirstWord+1'),(2,'SecondWord'),(3,'SecondWord+1')):
   operation=operation.replace('(IX + #'+format(value,'02X')+')','(IX + @FMapCoordinateKey.'+name+')')
 return operation
