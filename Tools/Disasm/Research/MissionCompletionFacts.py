def name_operands(region,address,operation):
 if region=='Station' and address==0xAA85:
  for raw,name in ((0x98B0,'MissionOffer.Entry.FirstWord'),(0x98B2,'MissionOffer.Entry.SecondWord'),
   (0x98BC,'MissionOffer.Entry.Reward'),(0x98BE,'MissionOffer.Entry.RequiredTonnage'),
   (0x983F,'SignatureInput.Entry.FirstWord'),(0x9841,'SignatureInput.Entry.SecondWord'),
   (0x99A3,'MissionState.ActiveCode'),(0x99A4,'MissionState.CompletionCode')):
   operation=operation.replace('(#'+format(raw,'04X')+')','(@'+name+')')
  for raw,name in ((0xAB66,'Reminder'),(0xAB82,'Invitation'),(0xAB9E,'Success'),(0xABB1,'TargetCaption'),(0xABC2,'TonnageCaption'),(0xABF8,'RewardCaption'),(0xAC0E,'CurrencySuffix')):
   operation=operation.replace('LD HL, #'+format(raw,'04X'),'LD HL, @MissionTexts.'+name)
  return operation.replace('LD HL, #98BE','LD HL, @MissionOffer.Entry.RequiredTonnage').replace('CALL #C287','CALL @Station.DrawCaptionItem.Entry').replace('CALL #E6AB','CALL @Map.BuildSystemName.Entry').replace('CALL #C000','CALL @Text.RunMarketScript.Entry').replace('LD HL, #630B','LD HL, @SystemNameState.Buffer')
 return operation
