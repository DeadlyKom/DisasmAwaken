def name_operands(region, function_address, operation):
    if region != 'Action' or function_address not in FUNCTIONS:
        return operation
    for address, name in ((0xE021, 'ActionProjectedBoundsState.CompanionMask'),
                          (0x9B19, 'ActionAimFollowState.Position'), (0xAA8E, 'ActionAimFollowState.Request'),
                          (0xECA9, 'ActionAyEffectState.CursorA')):
        operation = operation.replace('(#' + format(address, '04X') + ')', '(@' + name + ')')
    for index in range(3):
        operation = operation.replace('LD DE, #' + format(0x9B1B + index, '04X'), 'LD DE, @ActionMissileTargets.Value.Target' + str(index))
    for before, after in (
        ('(#D9B7)', '(@ActionPatchedVectorState.Output0 + 1)'),
        ('(#D7C5)', '(@ActionPatchedVectorState.Output1 + 1)'),
        ('CP #10', 'CP @ActionAimFollowConst.DistanceLimit'),
        ('ADD A, #77', 'ADD A, @ActionAimFollowConst.CenterX'),
        ('ADD A, #2B', 'ADD A, @ActionAimFollowConst.CenterY'),
        ('LD HL, #EE02', 'LD HL, @ActionAimFollowConst.CaptureSound'),
        ('LD HL, #EE1B', 'LD HL, @ActionAimFollowConst.FullSound'),
        ('LD DE, #F258', 'LD DE, @ActionAimFollowConst.FullText'),
        ('LD BC, #5F00', 'LD BC, @ActionAimFollowConst.RecordBias'),
        ('CALL #6040', 'CALL @Action.QueueTextItemBank1.Entry')):
        operation = operation.replace(before, after)
    return operation
