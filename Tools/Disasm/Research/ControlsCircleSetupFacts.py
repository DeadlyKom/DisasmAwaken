def name_operands(region, function_address, operation):
    if region == 'Controls' and function_address in FUNCTIONS:
        for address, name in ((0xD181, 'WorkY'), (0xD183, 'CenterY'), (0xD185, 'SectionRadius')):
            operation = operation.replace('(#'+format(address, '04X')+')', '(@ControlsCircleSetupState.'+name+')')
        operation = operation.replace('(#D17F)', '(@ControlsBodyProjection.Value.Flags)')
        operation = operation.replace('(#D18C)', '(@ControlsInteriorRowsState.Mode)')
    return operation
