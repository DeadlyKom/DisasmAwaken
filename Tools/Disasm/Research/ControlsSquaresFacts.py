def name_operands(region,function_address,operation):
    if region == 'Controls' and function_address == 0xD30B:
        operation=operation.replace('LD H, #C3','LD H, @ControlsSquareConst.LowPage')
    if region == 'Controls' and function_address == 0xD609:
        operation=operation.replace('(#D188)','(@ControlsSquaresState.SquareDiff)')
        operation=operation.replace('CALL #D30B','CALL @Controls.ReadByteSquare.Entry')
    return operation
