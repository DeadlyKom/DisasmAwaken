def name_operands(region,function_address,operation):
    if region=='Action' and function_address==0xD511:
        for name,address,_ in STATE_FIELDS:
            operation=operation.replace('(#'+format(address,'04X')+')','(@ActionPolygonPreparationState.'+name+')')
        operation=operation.replace('(#9BA3)','(@ActionClipIntersectionsState.OutputSize)')
        operation=operation.replace('LD HL, #9001','LD HL, @ActionPolygonPreparationState.Vertices+1')
    return operation
