def name_operands(region,address,operation):
    if region=='Station':
        operation=operation.replace('(#A0A3)','(@WindowFillState.FillByte)').replace('(#A0C1)','(@WindowFillState.SavedSP)')
    if region=='Station' and address==0xA05B:
        operation=operation.replace('LD HL, #A0C4','LD HL, @Station.FillBodyRow.Entry')
        operation=operation.replace('LD SP, #A104','LD SP, @WindowFillChain.State + FWindowReturnChain.Row1')
        for raw,name in [('(#AEC7)','(@TextWindow.OriginYLow)'),('(#AEBB)','(@TextWindow.OriginXLow)'),
                         ('(#AEB3)','(@TextWindow.Width)'),('(#AEAB)','(@TextWindow.Height)'),('(#99B4)','(@StationRaster.FillMode)')]:
            operation=operation.replace(raw,name)
    if region=='Station' and address==0xA020:
        operation=operation.replace('(#AEC7)','(@TextWindow.OriginYLow)').replace('(#AEBB)','(@TextWindow.OriginXLow)')
    return operation
