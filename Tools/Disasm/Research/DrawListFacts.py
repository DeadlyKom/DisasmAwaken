def name_operands(region, address, operation):
    if region != "Station":
        return operation
    if address in (0x9C59, 0x9C68):
        operation = operation.replace("LD A, #C9", "LD A, @DrawOpcode.Disabled")
        operation = operation.replace("LD A, #21", "LD A, @DrawOpcode.Enabled")
    if address == 0x9EEB:
        operation = operation.replace("LD A, #04", "LD A, FInterfaceItem.Flags")
    return operation
