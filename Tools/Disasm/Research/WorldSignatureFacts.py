def name_operands(region,address,operation):
    valid=address in (FUNCTIONS if region=='Station' else MAP_FUNCTIONS if region=='Map' else {})
    if not valid:return operation
    for before,after in (('(#983F)','(@SignatureInput.Entry + FSignatureInput.FirstWord)'),
                         ('(#9841)','(@SignatureInput.Entry + FSignatureInput.SecondWord)'),
                         ('(#9843)','(@SignatureInput.Entry + FSignatureInput.Variant)'),
                         ('(#631C)','(@SignatureState.WorkKey + FSignatureKey.FirstWord)'),
                         ('(#631E)','(@SignatureState.WorkKey + FSignatureKey.SecondWord)')):
        operation=operation.replace(before,after)
    return (operation.replace('CALL #C9B9','CALL @Map.DescribeKey.Entry')
            .replace('CALL #A9F3','CALL @Station.StepSignatureKey.Entry')
            .replace('CALL #E779','CALL @Map.ClassifyKeyRegion.Entry'))


