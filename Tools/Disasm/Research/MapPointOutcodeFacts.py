def name_operands(region,address,operation):
 if region=='Map' and address==0xD430:
  operation=operation.replace('LD HL, #F801','LD HL, @MapClipState.Points + FProjectedPoint.X + 1').replace('AND #0F','AND @MapClipConst.CountMask').replace('CP #FF','CP @MapClipConst.ExcludedEnd').replace('XOR #F0','XOR @MapClipConst.Complement')
  for bit,name in ((0,'Right'),(1,'Left'),(2,'Bottom'),(3,'Top')):operation=operation.replace('SET '+str(bit)+', C','SET @MapClipBit.'+name+', C')
  return operation
 return operation
