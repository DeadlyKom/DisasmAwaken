def name_operands(region,address,operation):
 if region=='Station' and address==0x7154:
  for value,name in ((0x60,'SaleQuantity'),(0x72,'SalePrice'),(0x88,'OwnedQuantity'),(0x9A,'OwnedPrice'),(0xB0,'Unit')):
   operation=operation.replace('LD A, #'+format(value,'02X'),'LD A, @MarketColumnConst.'+name)
 return operation
