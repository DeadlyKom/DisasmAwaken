def name_operands(region, function_address, operation):
    if region == 'Controls' and function_address in FUNCTIONS:
        operation = operation.replace('(#CA8A)', '(@ControlsBufferCopyState.SavedStack)')
        operation = operation.replace('(#CA84)', '(@ControlsBufferCopyState.RemainingPages)')
    if region == 'Action' and function_address in (0xA85E, 0x6054):
        operation = operation.replace('CALL #C870', 'CALL @Controls.CopyViewportToScreen.Entry')
    return operation
