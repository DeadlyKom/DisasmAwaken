def parse(text):
    clean=[l.partition(';')[0].strip() for l in text.splitlines()];clean=[l for l in clean if l]
    assert clean.pop(0)=='module ActionTypeDeltas' and clean.pop(0)=='assert $ == #634B'
    for i in range(16):
        assert clean.pop(0)==('Index'+format(i,'02X')+':').ljust(16)+'FIndexedDelta {'
        assert re.fullmatch(r'#[0-9A-F]{2}',clean.pop(0));assert clean.pop(0)=='}'
    assert clean==['assert $ == #635B','endmodule']
    return parse_records(text,TABLE,0x5DC3)


def name_operands(region,function_address,operation):
    if region=='Action' and function_address==0x6380:
        operation=operation.replace('LD BC, #634B','LD BC, @ActionTypeDeltas.Index00')
        operation=operation.replace('(#9B83)','(@ActionGlyphIndicatorState.Control.TemplateMode)')
        operation=operation.replace('(#9BCD)','(@ActionFlightStatus.Value.Code)')
        for address,name in LOCAL.items():
            operation=operation.replace('#'+format(address,'04X'),'@Action.ApplyIndexedDelta.'+name)
    return operation
