def name_operands(region,address,operation):
 if region!='Text':return operation
 if address==0xC09F:
  return operation.replace('#CA7B','@AssignmentScratch.Entry').replace('#C0CF','@Text.AssignValue.Resume').replace('#FFFA','-FAssignmentExpression').replace('#FFFB','@AssignmentConst.BackFromHigh')
 if address in DISPATCHERS:
  anchor_name,count_name,anchor,count=DISPATCHERS[address]
  return operation.replace('#'+format(anchor,'04X'),'@ScriptTables.'+anchor_name).replace('LD B, #'+format(count,'02X'),'LD B, @ScriptConst.'+count_name)
 return operation
