def name_operands(region, address, operation):
    if region != "Station" or address not in FUNCTIONS:
        return operation
    operation = operation.replace("(#C570)", "(@XorOutlineState.HorizontalSkip)")
    operation = operation.replace("(#C5F5)", "(@XorOutlineState.VerticalMask)")
    return operation
