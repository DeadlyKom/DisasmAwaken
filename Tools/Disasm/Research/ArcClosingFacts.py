def name_operands(region,address,operation):
 if region=='Map' and address==0xE2AB:
  for value,name in ((0xDFB4,'RasterStack'),(0xDFB9,'RasterDown'),(0xDFBA,'UpperRow'),(0xDFBC,'LowerRow')):
   operation=operation.replace('(#'+format(value,'04X')+')','(@MapState.'+name+')')
 return operation
