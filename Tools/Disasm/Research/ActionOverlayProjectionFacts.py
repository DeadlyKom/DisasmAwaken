def name_operands(region, function_address, operation):
    if region == 'Action' and function_address == 0xADC5:
        operation = operation.replace('CALL #AE73', 'CALL @Action.DivideScaledLogarithmic.Entry')
    if region == 'Controls' and function_address == 0xE97A:
        operation = operation.replace('CALL #ADC5', 'CALL @Action.ProjectOverlayCoordinates.Entry')
    return operation
