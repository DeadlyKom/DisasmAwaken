def name_operands(region,address,operation):
 if region=='Map' and address==0xC38C:
  for value,name in ((0xC3D0,'MapVisiblePatch.Minimum'),(0xC3E8,'MapVisiblePatch.SelectedPoint'),
   (0x6307,'StationState.PointerXY'),(0x6305,'MapViewState.Height'),(0x6304,'MapViewState.Width'),
   (0x6302,'MapViewState.OriginHigh'),(0x9846,'MapSelection.SecondWord'),(0x9844,'MapSelection.FirstWord')):
   operation=operation.replace('(#'+format(value,'04X')+')','(@'+name+')')
  operation=operation.replace('LD HL, #F600','LD HL, @MapVisibleState.Points').replace('LD HL, #FFFF','LD HL, @MapMathConst.InitialMinimum').replace('LD DE, #FFFF','LD DE, @MapMathConst.InitialMinimum')
 return operation
