def name_operands(region, address, operation):
    if region != "Station" or address not in FUNCTIONS:
        return operation
    replacements = {"#0009": "@NumberConst.Max1Digit", "#0063": "@NumberConst.Max2Digits",
                    "#03E7": "@NumberConst.Max3Digits", "#270F": "@NumberConst.Max4Digits",
                    "#03E8": "@NumberConst.Thousand", "#0064": "@NumberConst.Hundred",
                    "#000A": "@NumberConst.Ten", "#4E20": "@NumberConst.TwentyThousand",
                    "#2710": "@NumberConst.TenThousand", "#30": "@NumberConst.DigitZero"}
    for before, after in replacements.items():
        operation = operation.replace(before, after)
    return operation
