def name_operands(region,address,operation):
    if region=='Intro' and address in (0x6BE3,0x6BED):
        operation=operation.replace('(#6BF3)','(@IntroSamplerState.SavedSP)')
        operation=operation.replace('JP #9100','JP @IntroSamplerConst.ChainEntry')
        operation=operation.replace('LD H, #93','LD H, @IntroSamplerConst.LookupPage')
    return operation


