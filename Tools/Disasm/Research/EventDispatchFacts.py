def name_operands(region,address,operation):
    if region!='Station' or address!=0x9DBA:return operation
    return (operation.replace('OR #80','OR @InterfaceEventConst.HeldMask')
            .replace('LD HL, #FFF0','LD HL, @PopupConst.NoSelection')
            .replace('(#9CAA)','(@MenuCommandState.Hidden)'))
