                module Help
                module SelectText
                ; Документация [номер LF-записи и единственный изменяемый байт банка 7](../../Docs/HelpTextSelector.md)
                ; -----------------------------------------
                ; Подготовка номера LF-записи в операнде IndexTextLines без немедленного вывода
                ; исходная запись 8, банк 7, файловые смещения #0057..#005A
                ; In:
                ;   AF содержит A полный байтовый номер LF-записи для следующего IndexTextLines, F произвольный сохраняемый
                ;   HELP из записи 8 выбран в банке 7, операнд LD A по DB01 доступен для записи, обычный CPU-возврат доступен
                ; Out:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, I, IFF и IM сохранены
                ;   HelpTextState.RecordOperand равен входному A, это один байт внутри LD A индексатора, не самостоятельная область данных
                ;   SP после RET равен входному+2, экран, таблица строк и другие операнды не меняются
                ; Corrupt:
                ;   HelpTextState.RecordOperand
                ; Note:
                ;   номер передаётся следующему SkipLfRecords из IndexTextLines, индексирование и печать здесь не выполняются
                ;   существование записи не проверяется, значения 0..255 сохраняются буквально, допустимость последующего обхода задаёт вызывающий код
                ;   проверены все 65536 пар A и F, каждый вызов записывает ровно один байт, одноимённые адреса иных банков не относятся к HELP
                ; -----------------------------------------
                ; подготовка LF-записи, которую следующий индексатор прочитает своим LD A
Entry:          LD (@HelpTextState.RecordOperand), A
                RET

                endmodule
                endmodule
