                module Help
                module PrintCrRecordAndRows
                ; Документация [таблица строк и CR-заголовки](../../Docs/HelpTextOutput.md)
                ; -----------------------------------------
                ; Печать выбранного CR-заголовка и возврат байтового числа занятых строк в A'
                ; запись 8, банк 7, файловые смещения #005B..#007B
                ; In:
                ;   HL содержит L байтовый номер CR-заголовка, H не участвует в выборе
                ;   AF содержит произвольный основной контекст, AF' задаёт сохраняемый F будущего основного AF
                ;   HELP выбран в банке 7, от E37C существуют L+1 ограничителей CR и завершающийся текст
                ;   TextWindow, Station, глифы и стек подготовлены, сохраняются ограничения PrintAfterCR и PrintText
                ; Out:
                ;   HL указывает на остановку PrintAfterCR, DE содержит исходный HL, BC сохранён
                ;   AF содержит A=8, F равен входному F', статус печати не возвращается
                ;   HL', DE', BC', IX, IY, I, IFF и IM сохранены, A' содержит ((Yпечати-8)&FF)/8+1 с целочисленным делением
                ;   F' содержит флаги последнего INC A с Carry третьего SRL, формула приведена в документации
                ;   CursorX сохраняет результат печати, CursorY принудительно равен 8, SP после RET равен входному+2
                ; Corrupt:
                ;   HL, DE, AF, AF', CursorX/Y, bitmap и изменяемые операнды печатателя
                ; Note:
                ;   число строк вычисляется по модулю 256 даже при отказе вывода, отдельной проверки успеха нет
                ;   L=FF пропускает 256 CR, значения не ограничиваются восемью заголовками дискового оригинала
                ;   прежнее имя FormatNumber не соответствовало алгоритму, числового форматирования здесь нет
                ; -----------------------------------------
                ; сохранение полного входного HL в DE, для выбора используется только L
Entry:          EX DE, HL
                LD HL, #0800
                LD (@TextWindow.CursorX), HL
                LD HL, @HelpTextConst.SectionTitles
                LD A, E
                ; поиск L+1 разделителей CR от начала заголовков и печать оставшегося потока
                CALL @Station.PrintAfterCR.Entry
                ; расчёт числа строк по изменению байтового Y, статус печати не проверяется
                LD A, (@TextWindow.CursorY)
                SUB #08
                SRL A
                SRL A
                SRL A
                INC A
                ; сохранение счётчика и его флагов в альтернативном AF
                EX AF, AF'
                ; обновление Y для последующего вывода, X остаётся после печати
                LD A, #08
                LD (@TextWindow.CursorY), A
                RET

                endmodule
                endmodule
