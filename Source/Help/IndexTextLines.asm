                module Help
                module IndexTextLines
                ; Документация [индексирование и предел исходного LDIR](../../Docs/HelpLineIndex.md)
                ; -----------------------------------------
                ; Индексирование выбранной LF-записи по правилам переноса строк и обнуление остатка таблицы
                ; запись 8, банк 7, файловые смещения #0000..#0041
                ; In:
                ;   HELP загружен в банк 7, выбран через порт 7FFD, текст Station и таблица ширин доступны
                ;   HelpTextState.RecordOperand задаёт пропуск A+1 байтов LF от E3E2, все читаемые байты существуют
                ;   TextWindow содержит геометрию, каждый SkipJustifyRow продвигает HL либо возвращает Carry
                ;   число получаемых строк N находится в пределах 1..1023, стек доступен и не пересекает рабочие области
                ; Out:
                ;   HL равен E37B, DE содержит N включая последнюю строку, BC равен нулю
                ;   AF содержит A=68 при Height>=14, иначе A=Height, F=(A&02)*16|(A&08)
                ;   HL', DE', BC', AF', IY, I, IFF и IM сохранены, IX указывает за N заполненными словами
                ;   первые N записей HelpLineCache содержат начала строк, оставшиеся слова обнулены
                ;   SP после RET равен входному+2, страница не переключается, bitmap не меняется
                ; Corrupt:
                ;   HL, DE, BC, AF, IX, HelpLineCache, TextWindow.CursorX, TextWindow.CursorY
                ;   изменяемые операнды и служебный префикс SkipJustifyRow, после прохода префикс равен 68, 48, 26
                ; Note:
                ;   при N=1024 исходный DEC BC даёт FFFF перед LDIR, ограничение не исправлено
                ;   проверка продвижения и ёмкости отсутствует, неподходящая геометрия может зациклить обход
                ;   договор проверен на исходных инструкциях моделью, без ассемблирования, IRQ и нативного запуска
                ; -----------------------------------------
                ; поиск выбранной записи, SkipLfRecords пропускает номер плюс один байт LF
Entry:          LD A, #00
                LD HL, #E3E2
                CALL @Station.SkipLfRecords.Entry
                ; создание списка начал строк, X сбрасывается один раз, Y перед каждой строкой
                LD DE, #0000
                XOR A
                LD (@TextWindow.CursorX), A
                LD IX, @HelpLineCache.Line0000
                ; запись рабочего адреса текущей строки в физическую двухбайтовую запись
StoreLine:      LD (IX+#00), L
                LD (IX+#01), H
                INC IX
                INC IX
                LD A, #08
                LD (@TextWindow.CursorY), A
                PUSH DE
                ; поиск конца визуальной строки без рисования, Carry завершает запись
                CALL @Station.SkipJustifyRow.Entry
                POP DE
                INC DE
                JP NC, @Help.IndexTextLines.StoreLine                           ; переход, если строка закончилась переносом, требуется следующая

                ; обнуление остатка таблицы, исходный код требует от 1 до 1023 занятых слов
                PUSH DE
                PUSH IX
                ; расчёт числа свободных слов и перевод его в байтовый счётчик
                LD HL, @HelpLineConst.Capacity
                OR A
                SBC HL, DE
                ADD HL, HL
                LD B, H
                LD C, L
                POP HL
                LD D, H
                LD E, L
                ; создание первого нулевого байта для перекрывающегося копирования всего остатка
                LD (HL), #00
                INC DE
                ; расчёт числа копируемых байтов, при N=1024 получается FFFF
                DEC BC
                LDIR
                POP DE
                RET

                endmodule
                endmodule
