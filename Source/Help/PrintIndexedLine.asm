                module PrintIndexedLine
; Документация [Help](../../Docs/FunctionDetails/Help.md)
; -----------------------------------------
; Получение указателя по индексу HL и передача непустой строки процедуре печати
; исходная запись 8, файловые смещения #0042..#0056
; In:
;   Unknown, регистровый контракт ещё не доказан
; Out:
;   исходный поток управления, включая переходы в соседние фрагменты
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, консервативная верхняя граница
; Note:
;   граница файла не доказывает границу логической процедуры
;   состояние самомодификации и активной страницы учитывается отдельно
; -----------------------------------------
Entry:          LD BC, #0800
                LD (#6320), BC
                ADD HL, HL
                LD DE, #DB7C
                ADD HL, DE
                LD A, (HL)
                INC HL
                LD H, (HL)
                LD L, A
                OR H
                RET Z                                                           ; выход, если флаг Z установлен

                JP #ADCD


                endmodule
                endmodule
