                module Help
                module PrintIndexedLine
                ; Документация [таблица строк и CR-заголовки](../../Docs/HelpTextOutput.md)
                ; -----------------------------------------
                ; Печать по физическому указателю строки с начальной позицией X=0, Y=8
                ; запись 8, банк 7, файловые смещения #0042..#0056
                ; In:
                ;   HL содержит индекс 0..1023 в HelpLineCache, HELP выбран в банке 7
                ;   ненулевой указатель ведёт на завершающийся текст с запасом просмотра слов, Station и таблица ширин доступны
                ;   TextWindow и пиксельная часть DrawGlyph подготовлены, стек не пересекает исходные данные
                ; Out:
                ;   нулевая запись даёт HL=0, DE=DB7C, BC=0800, AF=0044 без вызова печатателя
                ;   ненулевая запись передаётся PrintJustified при BC=0800, DE=DB7C, результат HL, DE, BC, AF определяется его договором
                ;   HL', DE', BC', AF', IX, IY, I, IFF и IM сохранены, SP после возврата равен входному+2
                ;   CursorX/Y сначала равны 0/8, затем содержат результат печати, таблица указателей не меняется
                ; Corrupt:
                ;   HL, DE, BC, AF, CursorX/Y, bitmap и изменяемые операнды PrintJustified и DrawGlyph на пути вывода
                ; Note:
                ;   индекс и ненулевой указатель не проверяются, OR H проверяет только нулевое слово
                ;   JP в PrintJustified хвостовой, ограничения геометрии и завершения печатателя остаются в силе
                ; -----------------------------------------
                ; подготовка начальной позиции вывода строки независимо от прежнего курсора
Entry:          LD BC, #0800
                LD (@TextWindow.CursorX), BC
                ; расчёт адреса двухбайтовой записи без проверки входного индекса
                ADD HL, HL
                LD DE, @HelpLineCache.Line0000
                ADD HL, DE
                ; чтение рабочего указателя из физической таблицы строк
                LD A, (HL)
                INC HL
                LD H, (HL)
                LD L, A
                ; проверка нулевого слова, оно обозначает неиспользованную запись
                OR H
                RET Z                                                           ; выход, если указатель строки равен нулю

                JP @Station.PrintJustified.Entry

                endmodule
                endmodule
