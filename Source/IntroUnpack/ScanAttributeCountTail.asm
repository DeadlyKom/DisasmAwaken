                module IntroUnpack
                module ScanAttributeCountTail
                ; Документация [условный подсчёт атрибутов и вывод смещения](../../Docs/IntroAttributeCountTail.md)
                ; -----------------------------------------
                ; Чтение PAPER, изменение первого счётчика и вывод смещения максимума в ULA
                ; исходная запись 3, перенесённый хвост AWAKEN.B банка 5, адреса 7497..74CC
                ; In:
                ;   HL указывает на восемь байтов счётчиков с доступом на запись, DE указывает на семь байтов приёмника
                ;   5800..58FE читаются, 8157 доступен на запись, RAM и CPU-стек отделены от кода и счётчиков
                ;   SP указывает на внешнее слово возврата, IRQ в модели не выполняются
                ;   счётчики и приёмник не пересекаются с 5800..58FE, 8157 и восемью временными байтами под SP
                ; Out:
                ;   HL содержит адрес первого максимального счётчика минус входной HL, DE равен входному HL, BC=0
                ;   AF содержит младший байт разности и флаги 16-разрядного вычитания, этот же байт выведен в порт ULA
                ;   HL', DE', BC', AF', IY сохраняются, IX равен входному HL, SP увеличивается на два
                ;   I, IM и IFF сохраняются, R увеличивает младшие семь битов на 2620+2*k modulo 128, старший сохраняется
                ;   LDIR последовательно копирует семь байтов в приёмник, включая перекрытие при DE=HL+1
                ;   после копирования первый счётчик увеличен 255 раз, 8157 получает PAPER из последнего атрибута 58FE
                ; Corrupt:
                ;   HL, DE, BC, AF, IX, R, восемь байтов ниже входного SP, счётчики, приёмник, 8157 и выход ULA
                ; Note:
                ;   первый счётчик получает младший байт своего адреса перед LDIR, совпадение максимумов оставляет прежний адрес
                ;   8157 лежит в исходной копии bitmap, смещение INC (IX+0) по 74B3 сохраняется
                ;   при модельной базе 813B адрес 8157 совпадает со смещением INC, проверено построение гистограммы PAPER
                ;   условный старт по 7494 устанавливает DE=#FF01 и продолжает по 7497
                ;   k число строгих замен максимального кандидата, равенство не увеличивает k, префикс 7494 добавляет один M1
                ;   1792 условных сценария исходного размещения проверяют точный R, отдельные модельные копии по 813B в этот счёт не входят
                ;   проверен условный договор после исходного переноса, штатная передача управления сюда не установлена
                ; -----------------------------------------
                ; Подготовка указателей на первый счётчик, приёмник и рамку восстановления.
Entry:          PUSH HL
                PUSH DE
                PUSH HL
                PUSH HL
                ; Инициализация первого счётчика младшим байтом адреса и копирование семи соседних значений.
                LD BC, #0007
                LD (HL), L
                LDIR
                ; Подготовка обхода 255 атрибутов и восстановление базы счётчиков в IX.
                LD B, #FF
                LD HL, @ScreenUpdateConst.BaseAttributes
                POP IX
                ; Чтение PAPER текущего атрибута, три сдвига и маска удаляют INK, BRIGHT и FLASH.
ReadPaper:      LD A, (HL)
                RRA
                RRA
                RRA
                AND #07
                ; Запись извлечённого PAPER в исходный адрес 8157.
                LD (@IntroTailState.PaperSample), A
                ; Обновление первого счётчика, записанный PAPER не меняет смещение команды после переноса.
                INC (IX+#00)
                INC HL
                DJNZ @IntroUnpack.ScanAttributeCountTail.ReadPaper

                ; Восстановление адреса первого кандидата и начала семи сравниваемых байтов.
                POP DE
                POP HL
                LD B, #07
                ; Проверка нового значения против текущего максимума.
CompareCount:   LD A, (DE)
                CP (HL)
                JR NC, @IntroUnpack.ScanAttributeCountTail.NextCount            ; переход, если текущий максимум не меньше нового значения, сохранить прежнего кандидата

                ; Обновление адреса максимального счётчика.
                LD E, L
                LD D, H
                ; Продвижение к следующему сравниваемому байту.
NextCount:      INC HL
                DJNZ @IntroUnpack.ScanAttributeCountTail.CompareCount

                ; Расчёт смещения найденного счётчика относительно начальной базы.
                POP HL
                OR A
                EX DE, HL
                SBC HL, DE
                ; Вывод младшего байта смещения в ULA, A также задаёт старший байт адреса порта.
                LD A, L
                OUT (@Hardware.BorderPort), A
                RET

                endmodule
                endmodule
