                module IntroUnpack
                module CopyScreenFromBankWindow
                ; Документация [условные входы за концом экранного потока](../../Docs/IntroDetachedTail.md)
                ; -----------------------------------------
                ; Копирование экрана из выбранного окна C000 в 4000
                ; исходная запись 3, перенос хвоста из 8F6B в 746B, адреса 74E4..74EB
                ; In:
                ;   C000 читается, 4000 доступен для записи, 7FFD выбирает окно C000, на стеке возврат
                ; Out:
                ;   HL и DE указывают за исходным и целевым экраном, BC обнулён, A сохранён
                ;   F сохраняет S, Z и Carry, X/Y от A и последнего байта, H, N и P/V сброшены
                ;   перенесены 6912 байтов, 7FFD сохранён, SP увеличен на два
                ; Corrupt:
                ;   HL, DE, BC, F, R и 6912 байтов экрана назначения
                ; Note:
                ;   при выборе банка 5 обе области совпадают, исходный LDIR сохранён
                ;   условный договор, обычный вызов из установленного кода вступления не найден
                ; -----------------------------------------
                ; Выбор верхнего окна как источника и базового экрана как назначения.
Entry:          LD HL, @ScreenUpdateConst.BankWindow
                LD DE, @ScreenUpdateConst.BaseScreen
                ; Передача выбранных указателей общему копировщику с сохранением внешнего возврата.
                JR @IntroUnpack.CopyScreenToBankWindow.CopyBlock

                endmodule
                endmodule
