                module IntroUnpack
                module UnpackTailGate
                ; Документация [условный вход и переходы за экранным потоком](../../Docs/IntroDetachedUnpackGate.md)
                ; -----------------------------------------
                ; Внутренний вызов распаковщика и проверка двух байтов после его возврата
                ; исходная запись 3, перенесённый хвост AWAKEN.B банка 5, адреса 74EC..74FE
                ; In:
                ;   Действует контекст внутреннего ADD HL,DE распаковщика, при штатной подготовке HL=#6E3C и DE=#008F
                ;   Экран и стек доступны по договору UnpackScreen, после возврата читаются (HL) и условно (HL+8)
                ; Out:
                ;   После обычного возврата распаковщика A=#FF, Z=0, первый JP Z пропускается
                ;   При нуле по выходному HL второй JP Z передаёт управление по #68EE, SP остаётся входным
                ;   Иначе IX получает выходной HL, AF задаётся байтом (HL+8) и сравнением с #43
                ;   По #74FF продолжается JR Z, смещение по #7500 находится за физическим концом записи
                ; Corrupt:
                ;   Рабочие регистры и экран по UnpackScreen, затем AF и IX, два байта ниже входного SP
                ;   При переходе #68EE дальнейшие записи и стек зависят от состояния генерируемого писателя
                ; Note:
                ;   Штатная передача управления на этот вход не установлена
                ;   В исходном потоке HL=#5AFF и (HL)=7, поэтому оба абсолютных перехода пропускаются
                ; -----------------------------------------
                ; Вход после подготовки контекста распаковщика.
Entry:          CALL @IntroTailState.UnpackBody
                JP Z, @IntroTailState.WriterTail                                ; переход, если распаковщик вернул Z=1, нормальный терминатор оставляет Z=0

                ; Проверка байта по HL, после нормального возврата INC A получает ноль.
                INC A
                CP (HL)
                JP Z, @IntroTailState.WriterTail                                ; переход, если по выходному HL лежит ноль, передать управление хвосту писателя

                ; Перенос выходного HL в IX для чтения соседнего байта.
ProbeByte:      PUSH HL
                POP IX
                LD A, (IX+@IntroTailState.ProbeOffset)
                ; Проверка значения перед относительным переходом, код JR Z следует по #74FF.
                CP @IntroTailState.ProbeValue
                endmodule
                endmodule
