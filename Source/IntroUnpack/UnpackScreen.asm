                module IntroUnpack
                module UnpackScreen
; Документация [IntroUnpack](../../Docs/FunctionDetails/IntroUnpack.md)
                ; Документация [алгоритм и проверка](../../Docs/IntroScreen.md)
; -----------------------------------------
; Распаковка экранного потока после переноса из #8931 в #6E31
; исходная запись 3, файловые смещения #2631..#26CA
                ; In:
                ;   исходный код перенесён из 8931 в 6E31, исходный битовый поток начинается по 6ECB
                ;   ROM по 1FC6 содержит E1 C8 E9, это POP HL, RET Z и JP (HL), выполняется при гарантированном Z=0
                ;   4000..5AFF доступны для записи, ссылки читают уже выведенную историю, поток достигает нулевого расширения F9
                ;   SP указывает на внешний возврат, два байта ниже него доступны и не пересекаются с кодом, потоком и экраном
                ;   профиль исходного ресурса даёт 6912 байтов, ADD A,00 в MapAttributes остаётся исходным, IRQ не вмешивается
                ; Out:
                ;   для исходного ресурса HL=5AFF, DE=5B00, BC=5AFF, AF=FFA8
                ;   HL'=2758, DE'=108F, BC'=00C0, AF'=5A50 для исходного ресурса
                ;   IXH сохранён, IXL=FF, IY, I/IM/IFF и paging сохраняются, SP после RET равен входному SP+2
                ;   4000..57FF содержат 6144 пиксельных байта после перестановки адресных битов, 5800..5AFF содержат 768 линейных атрибутов
                ;   для других корректных потоков HL рабочий курсор истории, DE=4000+размер вывода, BC физический адрес последнего байта
                ;   AF' содержит последний промежуточный адресный A и F=50 OR Carry перестановки назначения, D' содержит битовый резервуар с единичным маркером
                ;   временные записи ограничены двумя байтами ниже исходного SP, внешнее слово возврата сохранено
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, только IXL, экран и два байта ниже SP
                ; Note:
                ;   первый байт всегда литерал, последующие биты выбирают литерал либо группу длины
                ;   группа даёт 23 значения E9..FF, F9 в позиции длины вводит расширение, расширение ноль завершает поток
                ;   после группы смещения читаются бит направления и младший байт отрицательного смещения, нулевой бит означает прямую ссылку
                ;   при старшем байте смещения меньше FD добавляется один байт длины через DEC IXL, счётчик восьмибитный и 256 с поправкой оборачивается в 1
                ;   пиксельные адреса истории и результата переставляются одинаково, атрибуты остаются линейными
                ;   Carry направления хранится вместе с байтом через EX AF,AF', временный Carry адресной перестановки его не заменяет
                ;   1322 сценария проверили независимый битовый декодер, все группы, оба направления, расширения 1..255, регистры кроме R, RAM, стек и кратность записей
                ;   исходный экран использует 1440 байтов потока, оставшиеся 149 байтов ресурса сохранены без утверждения об их назначении
                ;   повреждённые потоки, иные ROM, отдельная модель всех физических банков, время, аппаратные IRQ и нативный запуск не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Адрес результата и получение собственного PC
                ; Создание логического курсора экрана, рабочий битовый набор выбирается через EXX.
Entry:          LD DE, @ScreenUpdateConst.BaseScreen
                EXX
                ; Подготовка смещения до потока, INC E превращает 8E в 8F и гарантирует Z=0 для ROM RET Z.
                LD DE, @IntroScreenConst.PCDeltaSeed
                INC E
                ; Получение адреса 6E3C из созданного CALL слова, ROM POP HL и JP (HL) возвращают его без обычного RET.
                CALL @IntroScreenConst.GetPC
                ; Расчёт начала потока, 6E3C плюс 008F равно 6ECB.
                ADD HL, DE
                ; -----------------------------------------
                ; Литерал и переключение контекста
                ; Чтение буквального байта из общего потока данных и битовых групп.
ReadLiteral:    LD A, (HL)
                INC HL
                ; Выбор одного байта вывода, FF увеличится в ноль после единственной записи.
                LD IXL, #FF
NextToken:      EXX
                JR NZ, @IntroUnpack.UnpackScreen.MapDestination                 ; переход, если начальный литерал уже прочитан и новый токен пока не требуется


                ; Выбор режима управляющего бита, B=1 после DJNZ даёт обычный токен.
                LD B, #01
                ; Сохранение адресного AF, перенос байта и флага направления между рабочими контекстами.
ReadTokenBit:   EX AF, AF'
                ; Чтение старшего бита резервуара D, единичный маркер определяет необходимость пополнения.
                SLA D
                JR NZ, @IntroUnpack.UnpackScreen.RouteToken                     ; переход, если резервуар ещё содержит биты и пополнение не требуется


                ; Пополнение очередным байтом, SLL добавляет единичный маркер после извлечённого старшего бита.
                LD D, (HL)
                INC HL
                SLL D
                ; После группы смещения B не равен единице, этот бит задаёт направление и далее читается младший байт смещения.
RouteToken:     DJNZ @IntroUnpack.UnpackScreen.ReadOffset

                JR C, @IntroUnpack.UnpackScreen.ReadLiteral                     ; переход, если управляющий бит токена равен единице и требуется литерал


                ; Выбор группы длины, B=1 отличает её от следующей группы смещения.
                INC B
                ; -----------------------------------------
                ; Переменная группа из 23 кодов
                ; Маска 56 чередует управляющие биты и биты значения, полная группа имеет семь битов.
DecodeGroup:    LD C, @IntroScreenConst.GroupMarker
                LD A, @IntroScreenConst.GroupSeed
                ; Извлечение очередного бита группы из общего резервуара.
ReadGroupBit:   SLA D
                JR NZ, @IntroUnpack.UnpackScreen.AddGroupBit                    ; переход, если резервуар ещё содержит биты и пополнение группы не требуется


                ; Чтение нового байта, RL сохраняет единичный маркер от исчерпанного резервуара.
                LD D, (HL)
                INC HL
                RL D
                ; Расчёт накопленного значения из предыдущей части и извлечённого бита.
AddGroupBit:    RLA
                ; Проверка позиции маски группы, Carry выбирает бит данных либо управляющий разряд.
                SLA C
                JR Z, @IntroUnpack.UnpackScreen.FinishGroup                     ; переход, если извлечены все семь битов полной группы


                JR C, @IntroUnpack.UnpackScreen.ReadGroupBit                    ; переход, если текущая позиция маски требует очередного бита данных


                ; Проверка управляющего бита после обратного вращения накопителя.
                RRCA
                JR NC, @IntroUnpack.UnpackScreen.ReadGroupBit                   ; переход, если управляющий бит группы равен нулю и код продолжается


                ; Поправка короткой группы, вычитание восьми и последующее добавление девяти дают увеличение на один.
                SUB #08
                ; Расчёт итогового кода E9..FF, полная группа получает поправку девять.
FinishGroup:    ADD A, #09
                ; Группа длины уменьшает B до нуля, группа смещения оставляет ненулевой B и возвращает чтение бита направления.
                DJNZ @IntroUnpack.UnpackScreen.ReadTokenBit

                ; Проверка специального кода длины F9, только он требует расширения.
                CP @IntroScreenConst.ExtendedCode
                JR NZ, @IntroUnpack.UnpackScreen.FinishLength                   ; переход, если код длины отличается от F9 и расширение не читается


                ; Чтение расширения длины, нулевой байт означает конец потока.
                LD A, (HL)
                INC HL
                ; Расчёт отрицательного восьмибитного счётчика, Carry отделяет продолжение от нулевого расширения.
FinishLength:   ADC A, #FF
                LD IXL, A
                JR C, @IntroUnpack.UnpackScreen.DecodeGroup                     ; переход, если длина не является нулевым расширением и требуется группа смещения


                ; -----------------------------------------
                ; Терминатор и возврат
                ; Установка исходного выходного слова альтернативного HL перед возвратом выходного набора.
                LD HL, @PackedResourceConst.ResultWord
                EXX
                RET


                ; -----------------------------------------
                ; Ссылка на выведенную историю
                ; Чтение младшего байта смещения, старший сохранён в альтернативном AF предыдущей группой.
ReadOffset:     LD A, (HL)
                INC HL
                EXX
                LD L, A
                ; Возврат старшего байта смещения, флаг направления сохраняется в противоположном AF.
                EX AF, AF'
                LD H, A
                ; Расчёт логического адреса истории, отрицательное смещение прибавляется к текущему DE.
                ADD HL, DE
                ; Проверка дальности ссылки, старший байт меньше FD требует дополнительного байта длины.
                CP @IntroScreenConst.LongOffsetLimit
                JR NC, @IntroUnpack.UnpackScreen.MapSource                      ; переход, если старший байт смещения не меньше FD и поправка длины не нужна


                ; Увеличение длины через уменьшение отрицательного счётчика modulo 256, переполнение сохраняется.
                DEC IXL
                ; Проверка логической области источника, пиксели требуют перестановки, атрибуты линейны.
MapSource:      LD A, H
                CP @IntroScreenConst.AttributesHigh
                JR NC, @IntroUnpack.UnpackScreen.MarkSource                     ; переход, если источник относится к атрибутам и перестановка пикселей не нужна


                ; Расчёт старшего физического адреса истории, старшие пять битов H объединяются с тремя младшими битами L.
                XOR L
                AND #F8
                XOR L
                LD B, A
                ; Расчёт младшего физического адреса истории, оставшиеся биты L и H вращаются на две позиции.
                XOR L
                XOR H
                RLCA
                RLCA
                LD C, A
                ; Возврат AF с флагом направления перед чтением байта истории, адресный AF сохраняется отдельно.
ReadHistory:    EX AF, AF'
                LD A, (BC)
                ; Сохранение выбранного байта и направления, дальше вычисляется только физический адрес назначения.
MapDestination: EX AF, AF'
                ; Проверка области результата, D содержит старший байт логического курсора.
                LD A, D
                CP @IntroScreenConst.AttributesHigh
                JR NC, @IntroUnpack.UnpackScreen.MapAttributes                  ; переход, если назначение относится к атрибутам и адрес остаётся линейным


                ; Расчёт старшего физического адреса результата по той же перестановке, что у истории.
                XOR E
                AND #F8
                XOR E
                LD B, A
                ; Расчёт младшего физического адреса результата из оставшихся битов E и D.
                XOR E
                XOR D
                RLCA
                RLCA
                LD C, A
                ; -----------------------------------------
                ; Запись и продвижение курсоров
                ; Возврат выбранного байта и исходного Carry направления перед записью.
WriteOutput:    EX AF, AF'
                ; Запись одного байта по физическому BC, логический DE продолжает линейный счёт вывода.
                LD (BC), A
                INC DE
                JR NC, @IntroUnpack.UnpackScreen.AdvanceCopy                    ; переход, если ссылка прямая и курсор истории увеличивается


                ; Два уменьшения и общее увеличение дают шаг истории минус один для обратной ссылки.
                DEC HL
                DEC HL
                ; Продвижение истории на один либо завершение суммарного обратного шага.
AdvanceCopy:    INC HL
                EX AF, AF'
                ; Проверка окончания пакета, отрицательный счётчик увеличивается до нуля.
                INC IXL
                JR NZ, @IntroUnpack.UnpackScreen.MapSource                      ; переход, если счётчик ещё не обнулился и копирование ссылки продолжается


                JR @IntroUnpack.UnpackScreen.NextToken


                ; -----------------------------------------
                ; Общий линейный адрес атрибутов
                ; Carry=1 помечает источник для общего хвоста, назначение приходит с Carry=0.
MarkSource:     SCF
                ; Сохранение признака источника либо назначения, исходное добавление нуля оставляет старшую страницу прежней.
MapAttributes:  PUSH AF
                ADD A, #00
                LD B, A
                POP AF
                LD C, E
                JR NC, @IntroUnpack.UnpackScreen.WriteOutput                    ; переход, если обрабатывается назначение атрибутов и нужно записать байт


                ; Выбор младшего байта L для линейного источника, у назначения ранее выбран E.
                LD C, L
                JR @IntroUnpack.UnpackScreen.ReadHistory


                endmodule
                endmodule
