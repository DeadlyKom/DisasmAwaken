                module IntroUnpack
                module WaitNonzeroKeyByte
                ; Документация [условные входы за концом экранного потока](../../Docs/IntroDetachedTail.md)
                ; -----------------------------------------
                ; Очистка и ожидание ненулевого байта по 5C08
                ; исходная запись 3, перенос хвоста из 8F6B в 746B, адреса 74CD..74D7
                ; In:
                ;   KeyByte по 5C08 доступен, ROM при IM 1 может обновить LAST_K, на стеке возврат
                ; Out:
                ;   AF содержит ненулевой байт и флаги OR A, остальные рабочие регистры сохранены
                ;   KeyByte очищен перед циклом, при прочитанном ненулевом значении SP увеличен на два
                ; Corrupt:
                ;   AF, R, KeyByte
                ; Note:
                ;   нулевой LAST_K оставляет ожидание в PollKey, проверены писатели ROM 48K и 128K ROM 1 по 0308
                ;   условный договор, обычный вызов из установленного кода вступления не найден
                ; -----------------------------------------
                ; Очистка старого байта до начала ожидания.
Entry:          XOR A
                LD (@IntroTailState.KeyByte), A
                ; Проверка появления нового ненулевого байта после очистки.
PollKey:        LD A, (@IntroTailState.KeyByte)
                OR A
                JR Z, @IntroUnpack.WaitNonzeroKeyByte.PollKey                   ; переход, если байт всё ещё нулевой, повторить чтение

                RET

                endmodule
                endmodule
