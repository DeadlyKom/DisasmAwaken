                module IntroUnpack
                module CopyScreenToBankWindow
                ; Документация [условные входы за концом экранного потока](../../Docs/IntroDetachedTail.md)
                ; -----------------------------------------
                ; Копирование экрана из 4000 в выбранное окно C000
                ; исходная запись 3, перенос хвоста из 8F6B в 746B, адреса 74D8..74E3
                ; In:
                ;   4000 читается, C000 доступен для записи, 7FFD выбирает окно C000, на стеке возврат
                ; Out:
                ;   HL и DE указывают за исходным и целевым экраном, BC обнулён, A сохранён
                ;   F сохраняет S, Z и Carry, X/Y от A и последнего байта, H, N и P/V сброшены
                ;   перенесены 6912 байтов, 7FFD сохранён, SP увеличен на два
                ; Corrupt:
                ;   HL, DE, BC, F, R и 6912 байтов экрана назначения
                ; Note:
                ;   при выборе банка 5 обе области совпадают, исходный LDIR сохранён
                ;   условный договор, обычный вызов из установленного кода вступления не найден
                ; -----------------------------------------
                ; Выбор базового экрана как источника и верхнего окна как назначения.
Entry:          LD HL, @ScreenUpdateConst.BaseScreen
                LD DE, @ScreenUpdateConst.BankWindow
                ; Копирование пикселей и атрибутов одного экрана в прямом порядке.
CopyBlock:      LD BC, @ScreenUpdateConst.ScreenBytes
                LDIR
                RET

                endmodule
                endmodule
