                module ActionBoot
                module LoadFileAtAddress
                ; Проверка [чтение всех физических секторов](../../Docs/ActionBootFileKeys.md#обычная-загрузка-и-возврат-tr-dos)
                ; Документация [ActionBoot](../../Docs/FunctionDetails/ActionBoot.md)
                ; -----------------------------------------
                ; Загрузка выбранного файла по адресу HL через TR-DOS, A=3 и C=#0E
                ; исходная запись 17, файловые смещения #010C..#0112
                ; In:
                ;   HL - адрес загрузки, девятибайтовое имя файла задано системным буфером TR-DOS, системные переменные и стек подготовлены
                ; Out:
                ;   TR-DOS получает A=3 и C=#0E, повторяет поиск имени и читает физические сектора, возврат использует исходное слово CPU-стека
                ; Corrupt:
                ;   HL, DE, BC, AF, R, память файла, буферы и остальные побочные эффекты определяются TR-DOS
                ; Note:
                ;   JP #3D13 передаёт управление хвостовым вызовом, банк выбирает вызывающий код, логическая длина не отсекает хвост последнего сектора
                ; -----------------------------------------
Entry:          LD A, #03
                LD C, #0E
                JP @TrDos.Dispatch


                endmodule
                endmodule
