                module LoadFileAtAddress
; Документация [ActionBoot](../../Docs/FunctionDetails/ActionBoot.md)
; -----------------------------------------
; Загрузка выбранного файла по адресу HL через TR-DOS, A=3 и C=#0E
; исходная запись 17, файловые смещения #010C..#0112
; In:
;   HL - адрес загрузки, текущий файл задан системным буфером TR-DOS
; Out:
;   управление передаётся TR-DOS с A=3 и C=#0E, возврат использует исходный стек вызова
; Corrupt:
;   BC, AF, остальные побочные эффекты определяются TR-DOS
; Note:
;   выполняется JP #3D13, это хвостовой вызов, банк выбирает вызывающий код
; -----------------------------------------
Entry:          LD A, #03
                LD C, #0E
                JP @TrDos.Dispatch


                endmodule
                endmodule
