; Документация [ActionBoot](../../Docs/FunctionDetails/ActionBoot.md)
; -----------------------------------------
; Поиск девятибайтового имени, чтение заголовка каталога и возврат числа секторов и начального положения
; исходная запись 17, файловые смещения #00EE..#0108
; In:
;   HL - адрес девятибайтового имени TR-DOS, файл должен присутствовать на диске
; Out:
;   HL - слово #5CEB с увеличенным на один младшим байтом, AF - A число секторов из #5CEA
; Corrupt:
;   HL, DE, BC, AF, остальные побочные эффекты определяются TR-DOS
; Note:
;   имя копируется в #5CDD, вызываются поиск #0A и чтение записи #08
;   L увеличивается отдельно, результат не является нормализованной парой дорожки и сектора
;   после вызовов нет ветвления по ошибке TR-DOS
; -----------------------------------------
Entry:          LD DE, #5CDD
                LD BC, #0009
                LDIR
                LD C, #0A
                CALL @TrDos.Dispatch
                LD A, C
                LD C, #08
                CALL @TrDos.Dispatch
                LD HL, (#5CEB)
                INC L
                LD A, (#5CEA)
                RET


                endmodule
                endmodule
