                module ActionBoot
                module BuildLogarithmTable
                ; Документация [формула и проверка таблицы](../../Docs/ActionLogarithmTable.md)
                ; -----------------------------------------
                ; Построение двух раздельных страниц приближённого логарифма через сумму 255 точных частных
                ; исходная запись 17, загрузчик 438F..43CE, файловые смещения 01D2..0211
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, альтернативные регистры также аргументов не задают
                ;   исходный загрузчик доступен по 438F..43CE, страницы LowPage=9100 и HighPage=9200 допускают запись всех 256 байтов
                ;   на CPU-стеке внешний возврат, доступны четыре дополнительных байта, IRQ не вмешиваются
                ; Out:
                ;   HL=9100, DE=FFED, BC=007F, AF=0750
                ;   HL'=DB3E, DE'=BAE9, BC'=007F, AF'=0D00, IX, IY, I, IM и IFF сохраняются
                ;   SP=входной SP+2, R получает 69347 M1 с сохранением старшего бита
                ;   LowPage[n] и HighPage[n] содержат младший и старший байты T[n], T[0]=F000, T[1]=0000
                ;   T[n] равен целой части суммы частных q(i) для i от 1 до n-1, делённой на 256
                ;   q(i)=floor(B8AAh*65536 / (8000h*i+3AE9h)), промежуточная сумма хранится в 24 разрядах
                ;   все 512 байтов страниц записываются ровно один раз, портовых операций нет
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', R, LowPage, HighPage, четыре байта временного CPU-стека
                ; Note:
                ;   приближение 256*log2(n) относится только к n от 1 до 255, индекс 0 имеет отдельный специальный код F000
                ;   целочисленная формула задаёт фактические байты, вычисление через плавающий log2 используется только для оценки ошибки
                ;   младший байт накопителя не записывается в таблицу, но участвует в следующем накоплении
                ;   на каждой итерации по 16 шагов восстанавливающего деления, частное дописывается в альтернативный HL
                ;   полный договор потребителя AE73 и обратная таблица по 9300 этим доказательством не устанавливаются
                ; -----------------------------------------
                ; Инициализация отдельных страниц байтов T[n] и нулевого 24-разрядного накопителя A:DE.
Entry:          LD HL, @ActionLogarithmTable.LowPage
                XOR A
                LD E, A
                LD D, A
                ; Сохранение специального T[0]=F000, это не результат логарифма нулевого аргумента.
                LD (HL), A
                INC H
                LD (HL), #F0
                DEC H
                ; Переход к аргументу 1, первое обычное значение таблицы равно нулю.
                INC L
                ; -----------------------------------------
                ; Сохранение очередного значения
                ; Запись старших шестнадцати бит накопителя в раздельные страницы, младший E остаётся для следующей суммы.
NextEntry:      LD (HL), D
                INC H
                LD (HL), A
                DEC H
                ; Сохранение старшего байта накопителя в альтернативном A и двух слов в CPU-стеке.
                EX AF, AF'
                PUSH HL
                PUSH DE
                ; Расчёт 24-разрядного делителя C:DE=8000h*n+3AE9h, исходный E=E9 сохраняется.
                LD DE, #74E9
                LD C, L
                SRL C
                RR D
                ; Подготовка остатка 00B8AA и шестнадцати бит частного в другом наборе HL.
                XOR A
                LD HL, #B8AA
                EXX
                LD H, A
                LD L, A
                LD B, #10
                ; -----------------------------------------
                ; Следующий бит точного частного
                ; Удвоение остатка A:HL перед пробным вычитанием делителя C:DE.
DivideBit:      EXX
                ADD HL, HL
                ADC A, A
                ; Проверка достаточности остатка, вычитание выполняется в двух частях с общим заёмом.
                SBC HL, DE
                SBC A, C
                JR NC, @ActionBoot.BuildLogarithmTable.QuotientBit              ; переход, если остаток не меньше делителя, пробное вычитание принять

                ; Восстановление остатка после недостаточного пробного вычитания.
                ADD HL, DE
                ADC A, C
                ; Обновление частного, инвертированный признак займа становится его очередным битом.
QuotientBit:    EXX
                CCF
                RL L
                RL H
                DJNZ @ActionBoot.BuildLogarithmTable.DivideBit

                ; -----------------------------------------
                ; Накопление точного частного
                ; Восстановление предыдущей суммы, сложение частного с A:DE и возврат указателя страницы.
                POP DE
                EX AF, AF'
                ADD HL, DE
                ADC A, B
                EX DE, HL
                POP HL
                ; Переход к следующему аргументу, нулевой L после FF завершает построение.
                INC L
                JR NZ, @ActionBoot.BuildLogarithmTable.NextEntry                ; переход, если следующий аргумент не обернулся в 00, сохранить очередное значение

                RET

                ; -----------------------------------------
                endmodule
                endmodule
