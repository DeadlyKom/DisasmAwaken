                module ActionBoot
                module BuildBitmapTables
                ; Документация [таблицы и XOR-точки](../../Docs/ControlsBufferPoints.md)
                ; -----------------------------------------
                ; Создание четырёх страниц адресации линейного пиксельного буфера
                ; исходная запись 17, смещения #0212..#023C, рабочий адрес #43CF
                ; In:
                ;   HL, DE, BC, AF входных аргументов не задают
                ;   страницы 9400..97FF общей RAM доступны для записи, на CPU-стеке внешний возврат
                ; Out:
                ;   записаны 1024 байта, RowHigh[Y]=HIGH(8000+32*Y), RowLow[Y]=LOW(8000+32*Y)
                ;   ColumnByte[X]=X DIV 8, ColumnMask[X]=80 >> (X AND 7), все индексы 0..255
                ;   HL=9600, DE=A000, BC=0020, AF=2062
                ;   HL', DE', BC' сохраняются, AF'=8083, IX и IY сохраняются
                ;   I, IM и IFF сохраняются, портовых операций и дополнительных PUSH нет, SP=входной SP+2
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', 1024 байта таблиц, R
                ; Note:
                ;   таблицы создаются во время исполнения, отдельная статическая копия в сборку не добавляется
                ;   страницы имеют иное назначение в других фазах игры, этот договор относится к загрузке Action
                ;   итоговый F=62 содержит бит 5 операнда CP 20, AF'=8083 отражает DEC H после последнего RRCA
                ; -----------------------------------------
                ; выбор таблицы старших байтов линейных адресов строк
Entry:          LD HL, @BufferBitmapTables.RowHigh
                ; подготовка начала растра 8000 и шага 32 байта на строку
                LD DE, #8000
                LD BC, #0020
                ; сохранение старшего и младшего байтов текущего адреса в соседние страницы таблиц
BuildLine:      LD (HL), D
                INC H
                LD (HL), E
                DEC H
                ; вычисление адреса следующей линейной строки без изменения указателя текущего поля
                EX DE, HL
                ADD HL, BC
                EX DE, HL
                ; проверка обхода всех 256 индексов строк по оборачиванию L
                INC L
                JR NZ, @ActionBoot.BuildBitmapTables.BuildLine                  ; переход, если индекс строки ещё не обернулся в нуль, сохранить следующую пару байтов

                ; выбор страниц ColumnByte и ColumnMask после завершения таблиц строк
                INC H
                INC H
                ; подготовка старшей битовой маски и нулевого номера экранного байта
                LD A, #80
                EX AF, AF'
                XOR A
                ; подготовка восьми координат X, делящих один байт растра
BuildColumn:    LD B, #08
                ; сохранение номера экранного байта и соответствующей одноразрядной маски
StoreMask:      LD (HL), A
                EX AF, AF'
                INC H
                LD (HL), A
                ; вычисление маски следующего пикселя циклическим сдвигом без изменения номера байта
                RRCA
                DEC H
                EX AF, AF'
                INC L
                DJNZ @ActionBoot.BuildBitmapTables.StoreMask

                ; вычисление следующего номера байта после восьми пикселей
                INC A
                ; проверка завершения всех 32 байтов горизонтальной строки
                CP #20
                JR C, @ActionBoot.BuildBitmapTables.BuildColumn                 ; переход, если подготовлены не все 32 номера байтов, записать следующие восемь координат

                RET

                endmodule
                endmodule
