                module ActionBoot
                module BuildExponentialTable
                ; Документация [формула и проверка таблицы](../../Docs/ActionExponentialTable.md)
                ; -----------------------------------------
                ; Построение 256 байтов приближённой экспоненты последовательным умножением фиксированной точки
                ; исходная запись 17, загрузчик 4355..438E
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, D сохраняется, E обнуляется
                ;   HL', DE', BC' и AF' аргументов не задают, D' и весь AF' сохраняются, E' обнуляется
                ;   загрузчик доступен по 4355..438E, страница Values=9300 допускает запись 256 байтов
                ;   на CPU-стеке внешний возврат, IRQ не вмешиваются
                ; Out:
                ;   HL=FFE4, D сохраняется, E=0, BC=00B2, AF=E451
                ;   HL'=ECC8, D' сохраняется, E'=0, BC'=00C9, AF' сохраняется
                ;   IX=9300, IY, I, IM и IFF сохраняются, SP=входной SP+2, дополнительных записей CPU-стека нет
                ;   Values[n] равен округлённому вверх при половине w[n]/256 по модулю байта, n от 0 до 255
                ;   w[0]=0, w[n+1]=floor((65536+w[n])*65714/65536) по модулю 65536
                ;   R получает 102375 M1 с сохранением старшего бита, все 256 байтов страницы записываются ровно один раз, OUT отсутствуют
                ; Corrupt:
                ;   HL, E, BC, AF, HL', E', BC', IX, R, страница Values
                ; Note:
                ;   каждый из 256 шагов содержит 24 итерации последовательного умножителя, константа равна 100B2h
                ;   приближение равно 256*2^(n/256)-256, фактические байты определяет целочисленная рекурсия
                ;   внешний цикл меняет активный набор регистров, после чётных 256 шагов оба D сохраняют исходную принадлежность
                ;   это отдельное доказательство генератора, полный алгоритм потребителя AE73 и проекции ещё не установлен
                ; -----------------------------------------
                ; Инициализация указателя страницы Values и нулевого слова фиксированной точки w[0].
Entry:          LD IX, @ActionExponentialTable.Values
                LD HL, #0000
                ; -----------------------------------------
                ; Сохранение округлённого значения
                ; Расчёт округления w/256, бит 7 младшего байта задаёт прибавление единицы при половине и выше.
NextEntry:      LD A, H
                BIT 7, L
                JR Z, @ActionBoot.BuildExponentialTable.StoreEntry              ; переход, если дробная часть w/256 меньше половины, старший байт не увеличивать

                INC A
                ; Обновление очередного физического байта Values, затем очистка накопителя произведения в другом наборе.
StoreEntry:     LD (IX+#00), A
                XOR A
                EXX
                LD L, A
                LD H, A
                LD E, A
                ; Подготовка младшей части множителя 00B2, его старшая часть 01 добавляется через ADC A,1.
                LD BC, #00B2
                EXX
                ; Подготовка числа 01:w в C:HL и счётчика 24 бит, начальный Carry сброшен XOR.
                LD BC, #1801
                ; -----------------------------------------
                ; Следующий бит произведения
                ; Сдвиг числа 01:w и проверка очередного разряда для добавления множителя 100B2h.
MultiplyBit:    RR C
                RR H
                RR L
                EXX
                JR NC, @ActionBoot.BuildExponentialTable.ShiftProduct           ; переход, если очередной бит множимого нулевой, множитель не прибавлять

                ; Обновление частичного произведения на 100B2h, перенос младшего слова учитывается в A.
                ADD HL, BC
                ADC A, #01
                ; Сдвиг накопленного произведения, перенос связывает его сдвиг со следующим сдвигом C:HL.
ShiftProduct:   RRA
                RR H
                RR L
                EXX
                DJNZ @ActionBoot.BuildExponentialTable.MultiplyBit

                ; -----------------------------------------
                ; Расчёт следующего слова фиксированной точки
                ; Выбор средних разрядов произведения, w получает floor((65536+w)*65714/65536) по модулю 65536.
                LD A, C
                RRA
                EXX
                LD H, L
                LD L, A
                ; Переход к следующему байту страницы, оборачивание IXL после FF завершает 256 значений.
                INC IXL
                JR NZ, @ActionBoot.BuildExponentialTable.NextEntry              ; переход, если младший байт указателя не обернулся в 00, сохранить следующее значение

                RET

                ; -----------------------------------------
                endmodule
                endmodule
