                module ActionBoot
                module RelocateBootstrap
                ; Документация [ActionBoot](../../Docs/FunctionDetails/ActionBoot.md)
                ; Документация [алгоритм и проверка](../../Docs/BootstrapRelocation.md)
                ; -----------------------------------------
                ; Подготовка экранов и перенос #01FA байт загрузчика в #4200
                ; исходная запись 17, файловые смещения #0000..#0042
                ; In:
                ;   ACTION загружен по 6000, исходные 6043..623C доступны для чтения
                ;   окно C000..DAFF текущего либо выбранного банка и фиксированные 4000..5AFF доступны для записи
                ;   SP - внешний CPU-стек с двумя доступными байтами ниже него, он не перекрывает очищаемые области, исходный код и 4200..43F9
                ;   для штатного выбора экранов защёлка 7FFD не заблокирована, IRQ не вмешивается в перенос
                ; Out:
                ;   HL=623D, DE=43FA, BC=0, A=18, S=0, Z=1, Carry=0, H, N и PV сброшены
                ;   биты 3 и 5 F от суммы 18 и последнего переносимого байта по правилам LDIR
                ;   HL'=DAFF, DE'=DB00, BC'=0, AF', IX и IY сохранены, I/IM/IFF сохраняются
                ;   порт FE получает 0, 7FFD получает 17 и 18, при доступной защёлке очищен экран банка 7 и выбран банк 0 с теневым экраном
                ;   bitmap 4000..57FF обнулён, 5800..597F заполнены 38, 5980..5AFF заполнены 07
                ;   506 байтов 6043..623C скопированы в 4200..43F9, PC=4200 перед первой инструкцией InitializeFlight
                ;   SP равен входному, внешний возврат не снят, слово 4200 остаётся в двух байтах ниже входного SP
                ;   R сохраняет бит 7, младшие семь бит увеличиваются по модулю 128 на 28684 M1, число десятичное
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', R, порт FE, доступная защёлка 7FFD, экранные области, 506 байтов переноса и два байта ниже SP
                ; Note:
                ;   первое перекрывающееся LDIR очищает 6912 байтов выбранного экранного банка
                ;   очистка видимого экрана временно пишет ноль по 5800, затем 38, а по 5980 сначала пишет 38, затем 07, кратность этих записей сохранена
                ;   PUSH DE и RET передают управление по 4200, HL=623D остаётся указателем исходного ядра для InitializeFlight
                ;   при исходной блокировке 7FFD обе портовые записи не меняют банк, очищается текущий физический банк, штатный выбор экранов не гарантируется
                ;   256 сценариев проверили все шесть битов защёлки и все F, в том числе физические псевдонимы банка 5, все RAM и кратность записей
                ;   инструкции DI здесь нет, аппаратные IRQ, выполнение InitializeFlight, время и нативная загрузка не проверялись
                ;   пошагово сверены все начальные R и полное число M1, T и аппаратные IRQ этим не доказаны
                ; -----------------------------------------
                ; Начальный вывод FE и выбор банкового экрана.
                ; Вывод нуля задаёт исходное состояние порта FE перед очисткой экранов.
Entry:          XOR A
                OUT (#FE), A
                ; Выбор банка 7 с обычным экраном и ROM 1, запрет paging делает эту запись неэффективной.
                LD BC, #7FFD
                LD A, #17
                OUT (C), A
                ; -----------------------------------------
                ; Очистка выбранного банкового окна.
                ; EXX сохраняет BC порта 7FFD в другом наборе, LDIR использует собственные адреса и счётчик.
                EXX
                LD HL, #C000
                LD DE, #C001
                LD BC, #1AFF
                ; Начальный ноль распространяется по C000..DAFF, всего очищается 6912 байтов.
                LD (HL), L
                LDIR
                ; Восстановление BC порта, альтернативные пары сохраняют результат банковой очистки.
                EXX
                ; -----------------------------------------
                ; Подготовка фиксированного экрана.
                ; Выбор банка 0 и показа теневого экрана, при запрете paging остаётся прежнее отображение.
                LD A, #18
                OUT (C), A
                ; Очистка bitmap распространяет ноль также в первый байт атрибутов по 5800.
                LD HL, #4000
                LD DE, #4001
                LD BC, #1800
                LD (HL), L
                LDIR
                ; Верхние 384 атрибута получают 38, перекрывающееся копирование затрагивает также 5980.
                LD (HL), #38
                LD BC, #0180
                LDIR
                ; Нижние 384 атрибута получают 07, начальная запись заменяет временное значение по 5980.
                LD (HL), #07
                LD BC, #017F
                LDIR
                ; -----------------------------------------
                ; Перенос полётного продолжения.
                ; Копируется исходный загрузчик ACTION, адрес и размер заданы его физическим размещением.
                LD HL, @BootstrapMoveConst.ActionSource
                LD DE, @ActionBoot.InitializeFlight.Entry
                ; Создание собственного адреса передачи, внешний адрес возврата не снимается.
                PUSH DE
                LD BC, @BootstrapMoveConst.ActionBytes
                LDIR
                ; Переход в перенесённый InitializeFlight, HL указывает на исходное ядро вслед за загрузчиком.
                RET
                ; -----------------------------------------


                endmodule
                endmodule
