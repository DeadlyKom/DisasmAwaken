                module Station
                module DisableTextWrap
                ; Документация [банк 7, сохранение экранной страницы, счётчик строк и отключение переноса](../../Docs/StationHelpCalls.md)
                ; -----------------------------------------
                ; Отключение переноса текста, при отказе ширины печататель пропускает остаток строки
                ; исходная запись 4, файловые смещения #0D2A..#0D2E
                ; In:
                ;   нет регистровых параметров, существующий операнд TextWindow.Style доступен для записи
                ; Out:
                ;   HL, DE, BC, HL', DE', BC', AF', IX, IY, I, IFF и IM сохранены, AF=0044
                ;   TextWindow.Style равен нулю, SP после RET равен входному+2, остальные данные и страница не меняются
                ; Corrupt:
                ;   AF, TextWindow.Style
                ; Note:
                ;   ноль является политикой пропуска остатка строки при отказе ширины, это не очистка окна или экрана
                ;   проверены все 65536 входных AF и все прежние значения Style
                ; -----------------------------------------
                ; отключение переноса, нулевой Style выбирает пропуск остатка строки при отказе ширины
Entry:          XOR A
                LD (@TextWindow.Style), A
                RET

                endmodule
                endmodule
