                module Station
                module ConfirmShipModelTrade
                ; Документация [события 1..4, фактический сценарий, ранний FF и завершение интерфейса](../../Docs/ShipTrade.md)
                ; -----------------------------------------
                ; Передача выбранной модели событию LANG и закрытие списка с пятью связанными панелями
                ; исходная запись 4, файловые смещения #1C73..#1CC0
                ; In:
                ;   HL, DE, BC и AF не задают действие, строка берётся из PanelHoverState.ShipsRow
                ;   банк станции 0 выбран, D3D находится в банке 4, LANG в банке 6, переключение страниц не заблокировано
                ;   строка FF означает отсутствие выбора, иначе сумма строки с D3DPreviewState.BaseOperand должна задавать доступную запись сценария
                ;   действуют договоры RunMarketScript, BeginScreenUpdate, DrawItem00, EndScreenUpdate и удаления рисователей
                ;   поля состояния игрока и модели, исходные таблицы и тексты подготовлены, шесть изменяемых индексов доступны
                ; Out:
                ;   при ShipsRow=FF немедленный RET, A=0,F=50 OR входной Carry, остальные пары, память, банки, I и IFF сохранены
                ;   иначе байт строки записан в D3DPreviewState.RowOperand банка 4, BaseOperand не меняется этим обработчиком
                ;   EventCode=1+(OwnedMode<>0)+2*(Selector<>0), для любого ненулевого полного байта используется соответствующая единица
                ;   в банке LANG 6 исполняется исходный RunMarketScript, эффекты сделки и очереди сообщения определяются его условиями
                ;   после нормального возврата LANG последовательно выполнены BeginScreenUpdate, DrawItem00 и EndScreenUpdate
                ;   удалены первые совпадения индекса списка моделей и пяти индексов DropShipDetailPanels, даже при отказе сценария
                ;   HL=EmptyCallback, DE=последний индекс Index29, BC и альтернативные общие пары соответствуют выходу LANG и DrawItem00
                ;   AF=0044, AF' по экранному циклу, IX по выходу LANG, IY, I, IFF и IM сохранены при договорах вызываемых процедур
                ;   ActiveItemState.Active=0, PeriodicCall=EmptyCallback, CurrentPage=10 и указатель возобновлён, SP после RET входному+2
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX по LANG, состояние игрока по событию, строка D3D, экран, список и операнды помощников
                ; Note:
                ;   ранний FF не вычисляет событие и не выбирает банк, сохранение Carry относится только к нему
                ;   события 3 и 4 не имеют соответствующих блоков в активном исходном сценарии, общий начальный T всё равно пересчитывает загрузку
                ;   отказ сделки через M не отменяет последующее закрытие панелей вызывающим обработчиком
                ;   сдвиг каждого найденного ключа переносит физические 128 байтов, включая хвост после ограничителя списка
                ;   модель исполняет исходные LANG и статусный рисунок, независимое сравнение всего bitmap статуса и нативный запуск здесь не заявлены
                ; -----------------------------------------
                ; чтение строки подтверждаемой модели независимо от входного селектора A
Entry:          LD A, (@PanelHoverState.ShipsRow)
                ; проверка отсутствия наведения по переполнению FF в ноль
                INC A
                RET Z                                                           ; выход, если строка равна FF, модель и банки не менять

                ; выбор банка D3D для обновления исходного операнда строки
                LD A, #14
                CALL @Station.SelectRamBank.Entry
                LD A, (@PanelHoverState.ShipsRow)
                ; обновление компонента строки, смещение списка BaseOperand сохраняется
                LD (@D3DPreviewState.RowOperand), A
                ; возврат банка станции перед чтением режимов интерфейса
                LD A, #10
                CALL @Station.SelectRamBank.Entry
                ; чтение изменяемого полного режима покупки либо продажи
                LD A, #00
                ; проверка нулевого режима покупки
                OR A
                LD C, #01
                JR Z, @Station.ConfirmShipModelTrade.SelectCategory             ; переход, если OwnedMode равен нулю, оставить событие покупки 1

                ; расчёт события продажи 2 для ненулевого режима
                INC C
SelectCategory: LD A, (@ShipPanelState.Selector)
                ; проверка полного селектора категории модели
                OR A
                LD A, C
                JR Z, @Station.ConfirmShipModelTrade.RunEvent                   ; переход, если Selector равен нулю, оставить корабельное событие 1 либо 2

                ; расчёт события второй категории добавлением двух по модулю 256
                ADD A, #02
                ; обновление события перед входом в исходный LANG
RunEvent:       LD (@ScriptCallState.EventCode), A
                ; выбор банка LANG, исходные события 3 и 4 отдельных ветвей не имеют
                LD A, #16
                CALL @Station.SelectRamBank.Entry
                ; выполнение исходного сценария, отказ сделки не отменяет следующие действия интерфейса
                CALL @Text.RunMarketScript.Entry
                ; возврат банка станции после нормального выхода интерпретатора
                LD A, #10
                CALL @Station.SelectRamBank.Entry
                ; создание снимка экрана перед обновлением статуса игрока
                CALL @Station.BeginScreenUpdate.Entry
                CALL @Station.DrawItem00.Entry
                ; показ обновлённого статуса с возобновлением указателя
                CALL @Station.EndScreenUpdate.Entry
                ; чтение изменяемого индекса списка моделей для удаления
                LD DE, (@ModelListState.ItemIndex)
                ; удаление списка моделей независимо от результата сделки
                CALL @Station.DropItemDraw.Entry
                ; удаление пяти связанных панелей с отключением периодического просмотра
                CALL @Station.DropShipDetailPanels.Entry
                ; обновление активности в ноль после завершения группы
                XOR A
                LD (@ActiveItemState.Active), A
                RET

                endmodule
                endmodule
