                ;   R сохраняет бит 7, младшие семь бит увеличены на 1 M1 по модулю 128, внешний CALL не включён
                ; Corrupt:
                ;   SP и R по обычному возврату
                ; Note:
                ;   Entry 6913 содержит только JP в ReturnModelDescriptionHover, адрес возврата дополнительно не создаётся
                ;   вход действия по EventHandler+3 находится отдельно по 6916, эта ветвь наведения сама в него не переходит
                ; -----------------------------------------
                ; возврат без изменения состояния панели
