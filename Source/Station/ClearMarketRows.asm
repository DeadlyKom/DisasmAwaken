; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [точная формула шага, физические состояния и обмен регистров](../../Docs/RandomState.md)
; -----------------------------------------
; Обнуление шестидесяти байтов тридцати двухбайтовых записей рынка
; исходная запись 4, файловые смещения #490D..#491A
; In:
;   область #9555..#9590 доступна для записи, стек не перекрывает её
; Out:
;   HL=#9590, DE=#9591, BC=0, A сохранён, F от последнего LDIR
;   S, Z и Carry сохранены, H, N и P/V сброшены, бит 3 от A.bit3, бит 5 от A.bit1
;   альтернативные и индексные регистры, I и IFF сохранены, SP восстановлен
;   ровно 60 байтов обнулены, маркер по #9591 и последующий хвост сохранены
; Corrupt:
;   HL, DE, BC, AF только F
; Note:
;   первый байт обнуляется непосредственно, оставшиеся 59 распространяются перекрывающимся LDIR
;   это отдельный вход, его прежнее нахождение в файле генератора не означало общий алгоритм
; -----------------------------------------
                ; выбор первого байта тридцати двухбайтовых записей рынка
Entry:          LD HL, #9555
                ; выбор следующего байта для перекрывающегося заполнения
                LD DE, #9556
                ; выбор оставшихся 59 байтов после первого нулевого
                LD BC, #003B
                ; обнуление первого байта перед распространением
                LD (HL), #00
                ; распространение нуля на весь оставшийся диапазон
                LDIR
                RET

                endmodule
                endmodule
