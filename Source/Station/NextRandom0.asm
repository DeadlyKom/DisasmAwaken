                module NextRandom0
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [точная формула шага, физические состояния и обмен регистров](../../Docs/RandomState.md)
; -----------------------------------------
; Следующее слово независимого трёхбайтового потока 0
; исходная запись 4, файловые смещения #4882..#4888
; In:
;   RandomStates.Seed0 доступно для записи, действует договор StepRandomState
; Out:
;   HL новое младшее слово Seed0, DE и BC сохранены
;   AF - A новый HighByte, F от последнего SBC A,0, HL' адрес Seed0
;   DE' новое слово, B'=0, C' младший байт T из договора ядра
;   AF', IX, IY, I и IFF сохранены, SP восстановлен
; Corrupt:
;   HL, AF, HL', DE', BC'
; Note:
;   входной EXX компенсирует заключительный EXX ядра, остальные три альтернативные пары становятся рабочими
;   потоки используют одно ядро и отдельные состояния, игровое назначение каждого потока устанавливается по потребителям
; -----------------------------------------
                ; передача основного контекста в альтернативный набор перед ядром
Entry:          EXX
                ; выбор физического состояния Seed0 без изменения других потоков
                LD HL, @RandomStates.Seed0
                ; общий шаг с заключительным EXX и возвратом в исходный активный контекст
                JP @Station.StepRandomState.Entry

                endmodule
                endmodule
