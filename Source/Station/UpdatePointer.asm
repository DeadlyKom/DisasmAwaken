; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [указатель и сохранение фона](../../Docs/Pointer.md)
; -----------------------------------------
; Восстановление старого указателя и рисование нового при ненулевых параметрах движения
; исходная запись 4, файловые смещения #06B8..#06BE
; In:
;   X=#6307 в пределах 0..255, Y=#6308 в пределах 0..191, адресные таблицы #8200..#84FF построены
;   активен станционный код и его таблицы, экран #4000..#5FFF и собственные операнды доступны для записи
;   ненулевой код владельца ячейки обязан иметь допустимый индекс FInterfaceItem в таблице #8500
;   при RestoredFlag=0 BackgroundAddr, VisibleRows=1..8 и фон соответствуют последнему рисованию
;   движение определяется OR восьми байтов #6586..#6589 и #66E8..#66EB
; Out:
;   при нулевом OR AF=#0044, прочие регистры и состояние указателя сохранены
;   иначе выполнены RestorePointer и DrawPointer, выход и изменения соответствуют DrawPointer
; Corrupt:
;   HL, DE, BC, AF, AF', IX при ненулевых параметрах, при нулевых только AF
; Note:
;   не проверяет UpdateBlocked самостоятельно, это делает вызывающий периодический код
;   не очищает параметры движения, восстановление использует прежний адрес, рисование текущие X и Y
;   последовательное продолжение после CALL RestorePointer находится в DrawPointer.asm
;   HL', DE', BC', IY, I и IFF сохраняются, SP восстанавливается на допустимом пути владельца
; -----------------------------------------
                ; проверка восьми байтов параметров движения через TestMotionParameters
Entry:          CALL @Station.TestMotionParameters.Entry
                RET Z                                                           ; выход, если все восемь байтов параметров движения равны нулю

                ; восстановление прежнего фона перед последовательным продолжением в DrawPointer
                CALL @Station.RestorePointer.Entry
                ; JP @Station.DrawPointer.Entry, продолжение в DrawPointer.asm

                endmodule
                endmodule
