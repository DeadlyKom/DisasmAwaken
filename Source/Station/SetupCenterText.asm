                module Station
                module SetupCenterText
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [пиксельные параметры центрируемого окна](../../Docs/TextWindow.md)
; -----------------------------------------
; Настройка окна центрируемого текста с отступами X=3 и Y=4 и нулевым курсором
; исходная запись 4, файловые смещения #634B..#639D
; In:
;   DE - D высота и E ширина в знакоместах, BC - B знаковая строка и C знаковая колонка начала
; Out:
;   HL, DE и BC сохранены, CursorX=0, CursorY=0
;   начала координат рассчитываются как в SetupTextWindow, к младшему X прибавляется 3, к младшему Y прибавляется 4 без переноса в старший
;   Width=(T(E)-4) по модулю 256, Height=(T(D)-11) по модулю 256
;   AF - A записанная Height, F соответствует восьмибитному SUB 11 из T(D)
; Corrupt:
;   AF
; Note:
;   T определена в TextWindow.md, для произвольных байтов это исходные два RLCA и RLA, не простое умножение на восемь
;   нет проверки минимальных размеров и исправления переполнения низких байтов начала
;   Style, позиции управляющих колонок и вариант LineEndCode сохраняются, пиксели не записываются
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
; -----------------------------------------
Entry:          PUSH HL
                ; обнуление обеих относительных координат курсора перед настройкой начала
                LD HL, #0000
                LD (@TextWindow.CursorX), HL
                ; проверка знака исходной байтовой колонки знакомест
                LD A, C
                AND A
                JP P, @Station.SetupCenterText.ScaleX                           ; переход, если колонка неотрицательна, модуль уже находится в A

                ; получение байтового модуля отрицательной колонки
                NEG
                ; расчёт младшего X по исходному преобразованию T
ScaleX:         RLCA
                RLCA
                RLA
                ; проверка исходного знака колонки для старшего байта начала
                BIT 7, C
                JP Z, @Station.SetupCenterText.InsetX                           ; переход, если колонка неотрицательна, старший X остаётся нулевым

                ; восстановление отрицательного X и байта знакового расширения
                NEG
                DEC L
                ; расчёт младшего X с внутренним отступом 3 без переноса в старший
InsetX:         ADD A, @TextWindowConst.OriginInset
                LD (@TextWindow.OriginXLow), A
                LD A, L
                LD (@TextWindow.OriginXHigh), A
                ; подготовка нулевого старшего Y перед проверкой вертикального знака
                LD L, #00
                ; проверка знака исходной строки знакомест
                LD A, B
                AND A
                JP P, @Station.SetupCenterText.ScaleY                           ; переход, если строка неотрицательна, модуль уже находится в A

                ; получение байтового модуля отрицательной строки
                NEG
                ; расчёт младшего Y по исходному преобразованию T
ScaleY:         RLCA
                RLCA
                RLA
                ; проверка исходного знака строки для старшего Y
                BIT 7, B
                JP Z, @Station.SetupCenterText.InsetY                           ; переход, если строка неотрицательна, старший Y остаётся нулевым

                ; восстановление отрицательного Y и знакового расширения
                NEG
                DEC L
                ; расчёт младшего Y с отступом 4 без переноса в старший
InsetY:         ADD A, @TextWindowConst.CenterYInset
                LD (@TextWindow.OriginYLow), A
                LD A, L
                LD (@TextWindow.OriginYHigh), A
                ; расчёт пиксельной ширины с уменьшением на четыре
                LD A, E
                RLCA
                RLCA
                RLA
                SUB @TextWindowConst.WidthInset
                LD (@TextWindow.Width), A
                ; расчёт пиксельной высоты с уменьшением на одиннадцать
                LD A, D
                RLCA
                RLCA
                RLA
                SUB @TextWindowConst.HeightInset
                LD (@TextWindow.Height), A
                POP HL
                RET

                endmodule
                endmodule
