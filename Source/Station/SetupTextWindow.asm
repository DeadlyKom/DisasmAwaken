                module Station
                module SetupTextWindow
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [TextWindow.md](../../Docs/TextWindow.md)
; -----------------------------------------
; Настройка пиксельных размеров и знакового начала текстового окна по координатам знакомест
; исходная запись 4, файловые смещения #6039..#6083
; In:
;   DE - D высота и E ширина в знакоместах, BC - B знаковая строка и C знаковая колонка начала окна
; Out:
;   HL, DE и BC сохранены, начало и размеры записаны в изменяемые операнды TextWindow, CursorX и CursorY обнулены
;   AF - A=T(D), F=(#80 при отрицательном B, иначе #44) OR (T(D) AND #28) OR ((D SHR 5) AND 1), исходные B и D
;   T(v)=8*(v AND 31)+4*(v SHR 7)+3*((v SHR 6) AND 1), байтовая формула двух RLCA и одного RLA
; Corrupt:
;   AF
; Note:
;   при модуле координат и размерах меньше 64 преобразование равно умножению на восемь по модулю 256
;   для отрицательных координат сначала преобразуется модуль, затем результат отрицается, старший байт начала равен #FF
;   для неотрицательных координат старший байт начала равен нулю, координаты не отсекаются по экрану
;   для больших байтов T не является обычным умножением на восемь, особенность оригинала сохранена
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   пиксели и глифы не выводятся, режим TextWindow.Style не меняется
; -----------------------------------------
Entry:          PUSH HL
                ; обнуление относительного пиксельного курсора нового текстового окна
                LD HL, #0000
                LD (@TextWindow.CursorX), HL
                ; проверка знака горизонтального начала окна в знакоместах
                LD A, C
                AND A
                JP P, @Station.SetupTextWindow.ScaleX                           ; переход, если горизонтальное начало неотрицательно, модуль уже находится в A

                ; получение модуля отрицательной горизонтальной координаты перед масштабированием
                NEG
                ; расчёт младшего байта горизонтального начала по исходному преобразованию T
ScaleX:         RLCA
                RLCA
                RLA
                ; проверка исходного знака X для восстановления знака пиксельного начала
                BIT 7, C
                JP Z, @Station.SetupTextWindow.StoreX                           ; переход, если X неотрицателен, старший байт начала остаётся нулевым

                ; восстановление отрицательного младшего байта X и его знакового расширения
                NEG
                DEC L
                ; запись горизонтального начала в операнды текстового вывода
StoreX:         LD (@TextWindow.OriginXLow), A
                LD A, L
                LD (@TextWindow.OriginXHigh), A
                ; подготовка нулевого знакового расширения для вертикального начала
                LD L, #00
                ; проверка знака вертикального начала окна в знакоместах
                LD A, B
                AND A
                JP P, @Station.SetupTextWindow.ScaleY                           ; переход, если вертикальное начало неотрицательно, модуль уже находится в A

                ; получение модуля отрицательной вертикальной координаты перед масштабированием
                NEG
                ; расчёт младшего байта вертикального начала по исходному преобразованию T
ScaleY:         RLCA
                RLCA
                RLA
                ; проверка исходного знака Y для восстановления знака пиксельного начала
                BIT 7, B
                JP Z, @Station.SetupTextWindow.StoreY                           ; переход, если Y неотрицателен, старший байт начала остаётся нулевым

                ; восстановление отрицательного младшего байта Y и его знакового расширения
                NEG
                DEC L
                ; запись вертикального начала в операнды текстового вывода
StoreY:         LD (@TextWindow.OriginYLow), A
                LD A, L
                LD (@TextWindow.OriginYHigh), A
                ; расчёт пиксельной ширины по исходному преобразованию T, отсечения здесь нет
                LD A, E
                RLCA
                RLCA
                RLA
                LD (@TextWindow.Width), A
                ; расчёт пиксельной высоты по тому же преобразованию без нормализации больших значений
                LD A, D
                RLCA
                RLCA
                RLA
                LD (@TextWindow.Height), A
                POP HL
                RET

                endmodule
                endmodule
