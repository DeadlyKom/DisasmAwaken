                module Station
                module HandleModelPreviewClick
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [очищенный селектор, прекращение периодического callback и оба банковых шага координаты](../../Docs/PreviewAction.md)
                ; -----------------------------------------
                ; Выбор 3D-панели, закрытие с отключением периодического вызова либо изменение третьей координаты на 32
                ; исходная запись 4, файловые смещения #0AE6..#0B1A
                ; In:
                ;   HL - запасная обёртка, DE - индекс панели, BC - контекст, AF - полный селектор для RepaintAndTrack.Entry
                ;   FInterfaceItem, список рисования, активный callback, FlagsCache и указатель удовлетворяют RepaintAndTrack и CloseMenuOnRow
                ;   банк станции 0 выбран, paging не заблокирован, CPU-стек вне сменяемого окна, исходный D3D находится в банке 4
                ;   ThirdCoordinate и MenuCommandState.PeriodicCall доступны для записи, внешние callback выполняют свои договоры
                ; Out:
                ;   RepaintAndTrack.Entry сначала снимает бит 7 селектора, ExitInstruction получает AND A, общий путь возвращает Carry при выполненном действии геометрии
                ;   при Carry немедленный возврат, локальный код не закрывает панель, не переключает банк и не меняет третью координату
                ;   при отсутствии Carry возвращённый селектор уменьшается, результат ноль выбирает шаг FFE0, то есть минус 32 по модулю 65536
                ;   для остальных значений CloseMenuOnRow удаляет панель при совпадении символьных Y, тогда PeriodicCall получает EmptyCallback.Entry и возврат немедленный
                ;   при несовпадении строк выбирается шаг 0020, плюс 32, обе ветви вызывают реальный D3D.AdjustPreviewThird в банке 4
                ;   после координатной ветви HL вычисленная обёрнутая сумма, DE прежняя координата, BC по предшествующим помощникам, запись суммы только в интервале 512..4095
                ;   AF после возврата в банк 0 принадлежит выбору страницы, A=(исходная CurrentPage AND F8) OR 10 и F от логического OR
                ;   на закрытии HL=EmptyCallback.Entry, DE индекс панели, BC и AF от CloseMenuOnRow, банковых операций локального пути нет
                ;   альтернативные регистры и IY по внешним callback общего входа, координатный помощник их сохраняет, IX восстанавливается, SP обычного возврата равен входному SP+2
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IY согласно выполненным помощникам, список, PeriodicCall либо ThirdCoordinate
                ; Note:
                ;   это действие по EventHandler+3, пустое наведение начинается отдельно по 6837
                ;   старший бит входного селектора не является запретом действия здесь, используется Entry с RES 7,A, а не KeepSelector
                ;   селектор 1 после общего входа уменьшает координату независимо от строки заголовка, ветвь закрытия им не вызывается
                ;   непринятая сумма всё равно возвращается в HL, итоговый AF выбора страницы не сообщает результат проверки диапазона
                ;   единицы и полный игровой смысл третьей координаты ещё не доказаны, название масштаба или расстояния здесь не присваивается
                ;   код этого действия не вызывает ядро кадра E07F, оно относится к рисователю и периодическому callback, I, IFF и IM по договорам помощников
                ; -----------------------------------------
                ; общий выбор с обязательным снятием старшего бита входного селектора
Entry:          CALL @Station.RepaintAndTrack.Entry
                RET C                                                           ; выход, если общий вход завершил действие геометрии и вернул Carry

                ; проверка возвращённого селектора 1 для отрицательного шага координаты
                DEC A
                JR Z, @Station.HandleModelPreviewClick.DecreaseThird            ; переход, если возвращённый селектор равен 1, выбрать шаг минус 32

                ; проверка строки заголовка и удаление панели при совпадении
                CALL @Station.CloseMenuOnRow.Entry
                JR NZ, @Station.HandleModelPreviewClick.IncreaseThird           ; переход, если строки не совпали и панель осталась, выбрать шаг плюс 32

                ; выбор исходного пустого callback после удаления панели
                LD HL, @Station.EmptyCallback.Entry
                ; отключение периодического вызова без резервирования нового адреса
                LD (@MenuCommandState.PeriodicCall), HL
                RET

                ; выбор банка D3D для положительного шага
IncreaseThird:  LD A, #14
                CALL @Station.SelectRamBank.Entry
                ; выбор слова плюс 32 для третьей координаты
                LD HL, @D3DPreviewConst.ThirdStep
                ; применение обёрнутой суммы с проверкой интервала исходным помощником
                CALL @D3D.AdjustPreviewThird.Entry
                ; возврат станционного банка, результат AF координатной проверки заменяется
                LD A, #10
                CALL @Station.SelectRamBank.Entry
                RET

                ; выбор банка D3D для отрицательного шага
DecreaseThird:  LD A, #14
                CALL @Station.SelectRamBank.Entry
                ; выбор слова минус 32 по модулю 65536
                LD HL, @D3DPreviewConst.ThirdBackStep
                ; применение отрицательного шага через тот же исходный помощник
                CALL @D3D.AdjustPreviewThird.Entry
                ; возврат станционного банка с сохранением старших управляющих битов
                LD A, #10
                CALL @Station.SelectRamBank.Entry
                RET

                endmodule
                endmodule
