                module Station
                module HandleDecodedMessageClick
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [отдельные входы наведения и действия, разные фильтры закрытия и изменяемая строка уведомления](../../Docs/MessagePanels.md)
                ; -----------------------------------------
                ; Перерисовка панели расшифровки с исключением селектора 1 и закрытием по текстовой строке
                ; исходная запись 4, файловые смещения #1071..#107E
                ; In:
                ;   HL - запасная обёртка, DE - индекс элемента, BC - сохраняемый только в рамках договоров вызываемых процедур контекст
                ;   AF - A полный селектор RepaintAndFlag, выполнены договоры списка, CloseActiveItem, рисователя и TrackItemGeometry
                ;   станционный банк доступен для самомодификации, при перерисовке доступны экран и пробуждение HALT
                ;   для удаления действует DropItemDraw, PointerY и OriginYLow задают сравниваемые строки
                ; Out:
                ;   сначала выполнен RepaintAndFlag с ExitInstruction=37, при его Carry=1 немедленный выход без местного удаления
                ;   при Carry=0 исходный A=1 даёт AF=0042 и сохраняет панель, остальные селекторы вызывают CloseMenuOnRow
                ;   CloseMenuOnRow удаляет первый совпавший DE-индекс только при PointerY SHR 3=OriginYLow SHR 3, его AF и BC возвращаются
                ;   HL выбранная обёртка после обычного RepaintAndFlag, DE и IX восстановлены, при раннем бите 7 HL исходный
                ;   BC, альтернативные регистры и IY зависят от callback и рисователя внутри RepaintAndFlag
                ;   при соблюдении договоров SP обычного возврата равен входному SP+2, собственный код не меняет I, IFF и IM
                ; Corrupt:
                ;   HL, BC, AF, HL', DE', BC', AF', IY в пределах договоров RepaintAndFlag и закрытия
                ; Note:
                ;   Carry здесь отражает не только интерактивное действие, уже выполненная перерисовка тоже устанавливает его
                ;   на битовом раннем выходе A исходный, F=(A AND A8) OR 1, список не меняется
                ;   модель проверяет все селекторы для последнего элемента и отдельные проходы с настоящей перерисовкой
                ;   в этой модели активный callback отключён и геометрическое действие запрещено, общий договор учитывает их отдельно
                ; -----------------------------------------
                ; выбор панели и возможная перерисовка до решения о закрытии
Entry:          CALL @Station.RepaintAndFlag.Entry
                RET C                                                           ; выход, если перерисовка либо действие уже установили Carry

                ; проверка исходного селектора 1, при нём панель должна остаться открытой
                DEC A
                JP Z, @Station.HandleDecodedMessageClick.KeepPanel              ; переход, если исходный селектор равен 1, сохранить панель

                ; удаление только при совпадении символьной строки указателя и начала текста
                CALL @Station.CloseMenuOnRow.Entry
                RET Z                                                           ; выход, если CloseMenuOnRow вернул Z, в том числе после удаления

                ; возврат при несовпавшей строке, повторного действия нет
                RET

                ; возврат после исключения селектора 1 с AF=0042
KeepPanel:      RET

                endmodule
                endmodule
