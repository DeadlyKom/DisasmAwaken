                module Station
                module ResumePointer
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [указатель и сохранение фона](../../Docs/Pointer.md)
; -----------------------------------------
; Рисование указателя с сохранением регистров и разрешением периодического обновления
; исходная запись 4, файловые смещения #0684..#069C
; In:
;   X=#6307 в пределах 0..255, Y=#6308 в пределах 0..191, адресные таблицы #8200..#84FF построены
;   активен станционный код и его таблицы, экран #4000..#5FFF и собственные операнды доступны для записи
;   ненулевой код владельца ячейки обязан иметь допустимый индекс FInterfaceItem в таблице #8500
;   при RestoredFlag=0 BackgroundAddr, VisibleRows=1..8 и фон соответствуют последнему рисованию
;   стек вмещает динамический FPointerGuardFrame
; Out:
;   HL, DE, BC, AF, HL', DE', BC', IX, IY сохранены, AF' рабочий
;   указатель нарисован при ранее восстановленном фоне, UpdateBlocked=0
; Corrupt:
;   AF'
; Note:
;   перед DrawPointer записывается UpdateBlocked=1, после него 0
;   при уже нарисованном указателе пиксели не меняются, выбор формы и callback всё равно выполняется
;   I и IFF сохраняются, SP восстанавливается на допустимом пути владельца
; -----------------------------------------
                ; сохранение контекста в FPointerGuardFrame перед выбором формы и рисованием
Entry:          PUSH IX
                PUSH AF
                PUSH HL
                PUSH DE
                PUSH BC
                ; временный запрет периодического обновления на время DrawPointer
                LD A, #01
                LD (@PointerState.UpdateBlocked), A
                CALL @Station.DrawPointer.Entry
                ; разрешение периодического обновления после завершения рисователя
                XOR A
                LD (@PointerState.UpdateBlocked), A
                ; восстановление основного контекста и IX, альтернативный AF не сохранялся
                POP BC
                POP DE
                POP HL
                POP AF
                POP IX
                RET

                endmodule
                endmodule
