                module Station
                module LookupMatrixKey
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [одиночный ввод и физическая таблица кодов](../../Docs/MatrixKey.md)
; -----------------------------------------
; Циклический поиск пары строки и маски с преобразованием позиции в код
; исходная запись 4, файловые смещения #414A..#4162
; In:
;   BC - B сигнатура строки, C маска, для штатного ввода одна из 40 пар исходной KeyboardCodes
;   таблица читается от Code1D, Anchor по #96AA пропускается, обычный адрес возврата на CPU-стеке
; Out:
;   HL - двойной индекс первой совпавшей записи относительно Code1D, BC=#6954, DE сохранён
;   A - индекс плюс #1D, F от этого сложения, для штатных 40 пар A=#1D..#5A
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается при найденном совпадении
; Corrupt:
;   HL, BC, AF
; Note:
;   поиск сравнивает сначала RowMask, затем KeyMask, шаг равен двум байтам и выполняется по модулю 65536
;   ограничителя и проверки границ нет, отсутствие пары на всех чётных адресах приводит к бесконечному циклу
;   нулевые пары являются физическими пропусками кодов, не ограничителем, прямой BC=0 находит первый такой пропуск и возвращает #21
;   для совпадения вне штатной таблицы используется только младший байт (MatchAddress+#6954) при вычислении кода
;   исходное слово #6954 равно отрицательному адресу Code1D по модулю 65536, а не произвольному шагу таблицы
; -----------------------------------------
                ; выбор исходного якоря перед первой физической записью Code1D
Entry:          LD HL, @KeyboardCodes.Anchor
                ; поиск следующей двухбайтовой пары без ограничителя и без проверки конца таблицы
FindPair:       INC HL
                INC HL
                LD A, (HL)
                ; проверка совпадения RowMask с входным B
                CP B
                JR NZ, @Station.LookupMatrixKey.FindPair                        ; переход, если строка текущей пары не совпала с B, проверить следующую пару

                INC HL
                LD A, (HL)
                DEC HL
                ; проверка совпадения KeyMask с входным C после совпадения строки
                CP C
                JR NZ, @Station.LookupMatrixKey.FindPair                        ; переход, если маска текущей пары не совпала с C, проверить следующую пару

                ; выбор отрицательного адреса Code1D для преобразования найденного адреса в смещение
                LD BC, @KeyboardConst.TableBias
                ; расчёт байтового смещения найденной записи относительно Code1D
                ADD HL, BC
                LD A, L
                ; расчёт индекса записи делением младшего байта смещения на два
                SRL A
                ; расчёт кода через прибавление исходного кода первой записи #1D
                ADD A, @KeyboardConst.FirstCode
                RET

                endmodule
                endmodule
