                module Station
                module RegisterItemCells
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [CellMap.md](../../Docs/CellMap.md)
; -----------------------------------------
; Замена регистрации элемента индексной парой и заполнение видимого прямоугольника кодом владельца
; исходная запись 4, файловые смещения #5EAE..#5F4D
; In:
;   HL - шестнадцатибитный ключ регистрации элемента, DE - D высота в знакоместах 1..24, E ширина в байтах 1..32, BC - знаковые Y и X
;   прямоугольник имеет ненулевое пересечение с экраном, после InvalidateItemIndex в #8500..#85FF существует свободная пара со старшим байтом #FF
; Out:
;   HL - #8600 + 32*исключённая нижняя видимая строка + видимая левая колонка, DE и BC сохранены
;   AF - A код владельца от 1 до 128, F от последнего ADD HL,DE, его S, Z и PV остаются от последнего INC L либо выбора кода при ширине один
;   AF' - A'=2*(32-видимая ширина), F' от INC E после присвоения E=32-видимая ширина, Carry'=0
;   первая прежняя регистрация снята, первая свободная пара содержит исходный индекс, видимые ячейки прямоугольника содержат номер пары плюс один
; Corrupt:
;   HL, AF, AF'
; Note:
;   поиск свободной пары использует шестнадцатибитные INC HL без ограничителя страницы, отсутствие свободной записи не обрабатывается
;   номер пары вычисляется из её младшего адреса, код ноль не создаётся при свободной записи в пределах исходной страницы
;   ключ сохраняется без проверки, при его старшем байте #FF пара после записи остаётся помеченной свободной для последующего поиска
;   отсечение выполняется по знакоместам, текстовое окно, bitmap и атрибуты не изменяются
;   меняется StationState.CellSpanSkip, 32 развёрнутые записи ограничиваются пропуском 2*(32-видимая ширина)
;   альтернативные HL', DE', BC', индексные регистры, I и IFF сохраняются, SP восстанавливается
;   полностью невидимый прямоугольник и нулевые размеры исключены из подтверждённого контракта, проверок пустоты в коде нет
; -----------------------------------------
Entry:          PUSH DE
                PUSH BC
                ; сохранение геометрии отдельно от исходного ключа регистрации
                PUSH DE
                ; передача ключа в DE для снятия первой прежней регистрации
                EX DE, HL
                CALL @Station.InvalidateItemIndex.Entry
                ; поиск первой пары со старшим байтом #FF, указатель подготовлен за два шага до первого старшего байта
                LD HL, @StationState.ItemIndex - 1
FindFree:       INC HL
                INC HL
                ; проверка признака свободной пары через переполнение #FF в ноль
                LD A, (HL)
                INC A
                JP NZ, @Station.RegisterItemCells.FindFree                      ; переход, если старший байт не равен #FF, поиск свободной пары продолжается без ограничителя страницы

                ; запись ключа регистрации в найденную пару, сначала старший байт
                LD (HL), D
                DEC HL
                LD (HL), E
                ; расчёт однобайтового владельца, половина младшего адреса пары плюс один
                LD A, L
                RRCA
                INC A
                ; восстановление исходной геометрии перед её отсечением по экрану
                POP DE
                ; сохранение кода владельца в альтернативном AF до начала заполнения карты
                EX AF, AF'
                ; проверка знака левой колонки регистрируемого прямоугольника
                LD A, C
                AND A
                JP P, @Station.RegisterItemCells.ClipRight                      ; переход, если левая колонка неотрицательна, проверяется правая граница

                ; расчёт ширины после пропуска отрицательных колонок
                ADD A, E
                LD E, A
                LD C, #00
                JP @Station.RegisterItemCells.ClipY

                ; расчёт исключённой правой колонки прямоугольника
ClipRight:      ADD A, E
                ; проверка, что правая граница не превышает 32 колонки
                CP @ScreenConst.ColumnEndLimit
                JP C, @Station.RegisterItemCells.ClipY                          ; переход, если правая граница не превышает 32, ширина сохраняется

                ; расчёт ширины до правого края экрана
                SUB @ScreenConst.ByteColumns
                NEG
                ADD A, E
                LD E, A
                ; проверка знака верхней строки знакомест прямоугольника
ClipY:          LD A, B
                AND A
                JP P, @Station.RegisterItemCells.ClipBottom                     ; переход, если верхняя строка неотрицательна, проверяется нижняя граница

                ; расчёт высоты после пропуска отрицательных строк знакомест
                ADD A, D
                LD D, A
                LD B, #00
                JP @Station.RegisterItemCells.MapAddress

                ; расчёт исключённой нижней строки прямоугольника
ClipBottom:     ADD A, D
                ; проверка, что нижняя граница не превышает 24 строки
                CP @ScreenConst.RowEndLimit
                JP C, @Station.RegisterItemCells.MapAddress                     ; переход, если нижняя граница не превышает 24, высота сохраняется

                ; расчёт высоты до нижнего края экрана
                SUB @ScreenConst.CharRows
                NEG
                ADD A, D
                LD D, A
                ; получение адреса первого видимого знакоместа в карте владельцев
MapAddress:     CALL @Station.GetCellOwner.Entry
                ; сохранение видимой высоты в счётчике строк карты
                LD B, D
                ; расчёт пропуска развёрнутых записей и шага после последнего байта строки
                LD A, @ScreenConst.ByteColumns
                SUB E
                LD E, A
                ADD A, A
                ; запись смещения JR, ограничивающего заполнение видимой шириной
                LD (@StationState.CellSpanSkip), A
                ; расчёт линейного шага 33 минус видимая ширина после последней записи строки
                INC E
                LD D, #00
                ; возврат сохранённого кода владельца в A для заполнения всей видимой области
                EX AF, AF'
                ; пропуск ненужных записей, операнд JR подготовлен через CellSpanSkip
Row:            JR @Station.RegisterItemCells.SpanBody

                ; заполнение очередной строки карты одним кодом владельца
SpanBody:       LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                INC L
                LD (HL), A
                ; расчёт адреса той же начальной колонки следующей строки карты
                ADD HL, DE
                DJNZ @Station.RegisterItemCells.Row

                POP BC
                POP DE
                RET

                endmodule
                endmodule
