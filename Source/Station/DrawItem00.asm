                module Station
                module DrawItem00
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [порядок текстовых записей, статусное поле 7..5 и числовые вызовы](../../Docs/StatusDraw.md)
; -----------------------------------------
; Заливка статусного элемента и вывод полицейского статуса, денег, тоннажа и ранга
; исходная запись 4, файловые смещения #21E1..#2237
; In:
;   DrawItemState.Opcode00 равен 21 для работы либо C9 для отключения, Index00 содержит индекс FInterfaceItem
;   действует договор RegisterAndFillItem, исходная геометрия имеет видимое пересечение с экраном
;   TextIndex записи выбирает существующий LF-поток от EA89, разделитель SkipLfRecords равен LF
;   исходные тексты статуса EA3B и ранга доступны в банке станции 0, шрифт и текстовый код готовы
;   доступны байт Status984B, денежное слово 984E, байты тоннажа 9850 и 9851, счётчик RankState.Score
; Out:
;   регистрирует и заливает bitmap прямоугольника, TextWindow.Style=1, атрибуты не меняет
;   HL у поля Flags после RegisterAndFillItem, следующий байт TextIndex задаёт первую печатаемую запись
;   выбирает один из четырёх статусов по min(Status984B SHR 5,3), младшие пять бит для выбора не используются
;   после статуса продолжает исходный поток, печатает слово денег с бюджетом нулей A=0
;   ещё раз продолжает поток, печатает байт используемого тоннажа, двоеточие и байт вместимости
;   оба байта тоннажа передаются PrintMin2 как слова с нулевым старшим байтом
;   хвостовой вход PrintPlayerRank даёт окончательные HL, DE, BC и AF по его договору
;   HL', DE', BC', IX, IY, I и IFF сохранены, AF' соответствует RegisterAndFillItem
;   SP обычного возврата равен входному SP+2, выбранная страница не меняется
;   при Opcode00=C9 только RET, регистры и отображаемые данные не меняются
; Corrupt:
;   HL, DE, BC, AF, AF'
; Note:
;   схема Status984B, разряды 7..5 составляют числовой код, разряды 4..0 в данном выборе не участвуют
;   коды старшего поля 0,1,2 выбирают Чистый, Подозреваемый, Розыскиваемый, коды 3..7 выбирают Приговоренный
;   маска старшего поля E0, нулевое поле выбирает Чистый, смысл младших битов отдельно не доказан
;   первый PrintText сохраняет указатель продолжения на стеке вокруг отдельной печати статуса
;   отказы отдельных печатей не прекращают процедуру, исходные возвращённые AF не проверяются
;   ширина 32 знакоместа даёт нулевую байтовую ширину текстового окна по исходному SetupTextWindow
;   это не изменение алгоритма, проверка полного текста использует ширину 31, отсечение остаётся по договорам печати
; -----------------------------------------
                ; чтение изменяемого индекса статусного элемента
Entry:          LD HL, #0000
                ; выбор переноса строк для всей последовательности статусного вывода
                LD A, #01
                LD (@TextWindow.Style), A
                ; регистрация видимых знакомест и заливка bitmap, HL вернётся у Flags
                CALL @Station.RegisterAndFillItem.Entry
                ; переход от Flags к TextIndex и выбор начального потока статусных подписей
                INC HL
                LD A, (HL)
                LD HL, #EA89
                CALL @Station.SkipLfRecords.Entry
                CALL @Station.PrintText.Entry
                ; сохранение продолжения общего потока вокруг отдельного выбора полицейского статуса
                PUSH HL
                ; расчёт числового поля разрядов 7..5 байта Status984B
                LD A, (@PlayerStatusState.Status984B)
                RLCA
                RLCA
                RLCA
                AND #07
                ; проверка кода статуса относительно четырёх имеющихся строк
                CP #04
                JR C, @Station.DrawItem00.SelectStatus                          ; переход, если код статуса меньше 4, выбрать соответствующую строку без ограничения

                ; ограничение кодов 4..7 последней строкой статуса Приговоренный
                LD A, #03
                ; поиск LF-записи полицейского статуса по ограниченному индексу
SelectStatus:   LD HL, #EA3B
                CALL @Station.SkipLfRecords.Entry
                CALL @Station.PrintText.Entry
                ; восстановление продолжения общего потока и печать подписи денег
                POP HL
                CALL @Station.PrintText.Entry
                ; печать денежного слова с нулевым бюджетом ведущих нулей
                LD BC, (#984E)
                XOR A
                CALL @Station.PrintWord.Entry
                ; продолжение общего потока до подписи используемого тоннажа
                CALL @Station.PrintText.Entry
                ; печать только младшего байта используемого тоннажа с минимум двумя цифрами
                LD BC, (#9850)
                LD B, #00
                CALL @Station.PrintMin2.Entry
                ; разделение используемого тоннажа и вместимости исходным двоеточием
                LD A, #3A
                CALL @Station.DrawGlyph.Entry
                ; печать байта вместимости, соседний старший байт слова отбрасывается
                LD BC, (#9851)
                LD B, #00
                CALL @Station.PrintMin2.Entry
                ; хвостовой вывод подписи ранга и выбранного порогового имени
                JP @Station.PrintPlayerRank.Entry

                endmodule
                endmodule
