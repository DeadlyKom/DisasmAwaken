                module Station
                module ParseSettingsLabel
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [обратное преобразование значений и самостоятельный стековый выход прокрутки](../../Docs/SettingsParser.md)
                ; -----------------------------------------
                ; Преобразование нультерминированной подписи обратно в двухбайтовые настройки по прежнему типу записи
                ; исходная запись 4, файловые смещения #4191..#41CC
                ; In:
                ;   HL - сохраняемый контекст, DE - массив двухбайтовых FSettingWord, BC - нультерминированная подпись
                ;   длина подписи соответствует доступному массиву, код, стек, источник и назначение не перекрывают друг друга
                ;   старый ValueOrRow каждой записи определяет ветвь преобразования, вычисляемая область таблицы клавиш читаема
                ; Out:
                ;   HL сохранён, DE за последней записью с шагом два, BC у исходного завершающего нуля, AF=0054
                ;   для старого ValueOrRow<7F записан только байт (символ-30) AND FF, прежний KeyMask сохранён
                ;   для старого ValueOrRow=80 или 81 символ Y даёт 81, N даёт 80, остальные символы идут в ту же числовую ветвь
                ;   для старого ValueOrRow=7F или не меньше 82 записаны оба байта из клавиатурной таблицы по коду символа
                ;   подпись и ограничитель не меняются, при пустой подписи назначения не читаются и не меняются
                ;   HL', DE', BC', AF', IX, IY, I, IFF, IM и страницы сохранены, SP обычного возврата равен входному SP+2
                ; Corrupt:
                ;   DE, BC, AF и обработанные поля FSettingWord
                ; Note:
                ;   выбор ветви зависит от прежнего типа, символ N в числовом поле превращается в 1E, а не в маркер 80
                ;   адрес клавиатурного слова равен 96AC+((2*((символ-1D) AND FF)) AND FF), перенос удвоения теряется до сложения с AC
                ;   таблица индексируется без проверки диапазона, недопустимые коды могут читать соседние подписи вместо клавиатурной сигнатуры
                ;   числовая ветвь не проверяет цифры и не обнуляет второй байт, исходное поведение сохранено
                ;   это не полный обратный оператор для произвольных входов FormatSettingsLabel, корректный круговой проход предполагает штатные значения
                ;   модель прошла 65537 случаев, включая все 255 ненулевых символов и все 256 прежних дискриминаторов
                ; -----------------------------------------
                ; сохранение HL перед временным построением адреса клавиатурной сигнатуры
Entry:          PUSH HL
                ; проверка следующего символа подписи, ноль не преобразуется в настройку
NextCharacter:  LD A, (BC)
                AND A
                JR Z, @Station.ParseSettingsLabel.Finish                        ; переход, если достигнут нулевой ограничитель, вернуть сохранённый HL

                ; расчёт индекса клавиши относительно первого кода 1D с байтовым вычитанием
                SUB @KeyboardConst.FirstCode
                ; расчёт двухбайтового шага в одном байте, перенос этого удвоения далее теряется
                ADD A, A
                ; расчёт младшего адреса от Code1D, только перенос этого сложения добавляется к старшему 96
                ADD A, @SettingsParseConst.TableLow
                LD L, A
                LD A, @SettingsParseConst.TableHigh
                ADC A, #00
                LD H, A
                ; чтение прежнего типа FSettingWord до замены его значения
                LD A, (DE)
                ; проверка числовой ветви 0..126
                CP @SettingsLabelConst.FirstRow
                JR C, @Station.ParseSettingsLabel.Numeric                       ; переход, если прежний ValueOrRow меньше 7F, вычесть код нуля

                JR Z, @Station.ParseSettingsLabel.CopyKey                       ; переход, если прежний ValueOrRow равен 7F, скопировать клавиатурную пару

                ; проверка конца двух маркеров 80 и 81
                CP @SettingsParseConst.AfterTags
                JR NC, @Station.ParseSettingsLabel.CopyKey                      ; переход, если прежний ValueOrRow не меньше 82, скопировать клавиатурную пару

                ; проверка символа Y только для прежнего маркерного типа
                LD A, (BC)
                CP @SettingsLabelConst.YesChar
                LD A, @SettingsLabelConst.YesTag
                JR Z, @Station.ParseSettingsLabel.StoreValue                    ; переход, если символ равен Y, записать маркер 81

                ; проверка символа N после исключения Y
                LD A, (BC)
                CP @SettingsLabelConst.NoChar
                LD A, @SettingsLabelConst.NoTag
                JR Z, @Station.ParseSettingsLabel.StoreValue                    ; переход, если символ равен N, записать маркер 80

                ; преобразование любого оставшегося символа вычетом 30 без проверки диапазона цифр
Numeric:        LD A, (BC)
                SUB @SettingsLabelConst.DigitZero
                ; обновление только ValueOrRow, следующий KeyMask сохраняется прежним
StoreValue:     LD (DE), A
                INC DE
                JR @Station.ParseSettingsLabel.NextRecord

                ; копирование RowMask и KeyMask вычисленной клавиши в полную FSettingWord
CopyKey:        LD A, (HL)
                LD (DE), A
                INC DE
                INC HL
                LD A, (HL)
                LD (DE), A
                ; переход к следующей двухбайтовой записи и следующему однобайтовому символу
NextRecord:     INC DE
                INC BC
                JR @Station.ParseSettingsLabel.NextCharacter

                ; восстановление HL после принятого нуля, AF=0054 от AND A
Finish:         POP HL
                RET

                endmodule
                endmodule
