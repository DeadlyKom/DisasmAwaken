; Проверка присутствия панели систем перед последовательным рисованием её содержимого
; исходная запись 4, файловые смещения #1934..#193A
; In:
;   DrawListState.HeadOperand задаёт список с ограничителем старшего байта 1, HL и BC сохраняемые входы
;   если полный указатель DrawSystemInfoPanel есть в списке, действуют все договоры его рисунка
; Out:
;   при отсутствии указателя HL и BC сохранены, DE=DrawSystemInfoPanel.Entry, AF=0100 либо 0101, рисунка и переключения страниц нет
;   при пустом списке Carry равен входному Carry, иначе результату последнего сравнения указателя
;   при присутствии после проверки Z=1 исполнение без нового CALL переходит в DrawSystemInfoPanel, его результаты возвращаются исходному вызывающему коду
;   альтернативные и индексные регистры сохраняются на раннем выходе, на рисующей ветви действует договор панели, SP обычного возврата равен входному SP+2
; Corrupt:
;   DE, AF на раннем выходе, на рисующей ветви также состояние DrawSystemInfoPanel
; Note:
;   проверяется указатель, не индекс FInterfaceItem, порядок INCLUDE обёртки и панели является жёстким
;   условный RET не исключает последовательное продолжение в следующем файле
; -----------------------------------------
                ; выбор полного указателя панели систем для поиска в текущем списке рисования
