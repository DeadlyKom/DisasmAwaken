                module CloseMenuOnRow
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [выбор команды, фильтр закрытия и сохранение геометрии](../../Docs/MenuCommands.md)
; -----------------------------------------
; Удаление элемента при совпадении строки указателя и текстового начала
; исходная запись 4, файловые смещения #685E..#6872
; In:
;   DE - индекс удаляемого элемента, действует договор DropItemDraw
;   PointerY и младший байт TextWindow.OriginYLow доступны, HL и BC сохраняемый контекст
; Out:
;   если PointerY SHR 3 отличается от TextWindow.OriginYLow SHR 3, HL и DE сохранены, C=PointerY SHR 3
;   при несовпадении A=TextWindow.OriginYLow SHR 3, F от CP C, Z=0, B сохранён
;   при совпадении исполняется общий DropItemDraw, HL и DE сохранены, C номер строки, Z=1
;   альтернативные и индексные регистры, I и IFF сохранены, SP восстановлен
; Corrupt:
;   BC, AF
; Note:
;   сравниваются только символьные Y, X указателя и старший байт текстового начала не читаются
;   последовательное исполнение при совпадении продолжается в DropItemDraw.asm без нового CALL
; -----------------------------------------
                ; чтение текущей пиксельной Y указателя перед сравнением символьных строк
Entry:          LD A, (#6308)
                ; расчёт символьной строки указателя тремя сдвигами вправо
                SRL A
                SRL A
                SRL A
                LD C, A
                ; чтение младшего байта пиксельного начала текстового окна
                LD A, (@TextWindow.OriginYLow)
                ; расчёт символьной строки текстового начала
                SRL A
                SRL A
                SRL A
                ; проверка совпадения строк указателя и текстового начала
                CP C
                RET NZ                                                          ; выход, если строки не совпали, элемент не удалять

                ; JP @Station.DropItemDraw.Entry, продолжение в DropItemDraw.asm

                endmodule
                endmodule
