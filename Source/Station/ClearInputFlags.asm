; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [очистка накопленных входов](../../Docs/InterfaceInput.md)
; -----------------------------------------
; Очистка шести накопленных байтов направлений и действий клавиатуры и джойстика
; исходная запись 4, файловые смещения #0984..#0993
; In:
;   байты #66E8..#66ED доступны для записи, на CPU-стеке обычный адрес возврата
; Out:
;   HL=#66ED, AF=#0044, шесть байтов #66E8..#66ED равны нулю, DE и BC сохранены
; Corrupt:
;   HL, AF
; Note:
;   индексные и альтернативные регистры, I и IFF сохраняются, SP восстанавливается
;   очистка выполняется один раз перед опросом джойстика и клавиатуры в Interrupt, последующие писатели объединяют флаги через OR
; -----------------------------------------
                ; выбор начала шести накопленных флагов перед их очисткой
Entry:          LD HL, @InputFlags.State
                ; создание нулевого значения для всех шести входных флагов
                XOR A
                LD (HL), A
                INC HL
                LD (HL), A
                INC HL
                LD (HL), A
                INC HL
                LD (HL), A
                INC HL
                LD (HL), A
                INC HL
                LD (HL), A
                RET

