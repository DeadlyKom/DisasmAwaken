                module Station
                module SelectEquipmentSale
                ; Документация [целый байт режима, подтверждённые подписи, Carry и реальное переключение контуров](../../Docs/EquipmentTradeMode.md)
                ; -----------------------------------------
                ; Выбор продажи оборудования и переключение контура с покупки на продажу
                ; исходная запись 4, файловые смещения #1DE0..#1DEB
                ; In:
                ;   DE содержит индекс новой кнопки, штатно 36, HL входа отдельного параметра не задаёт
                ;   BC сохраняемый контекст, AF содержит Carry запрета действия, при Carry=1 других условий не требуется
                ;   при Carry=0 доступен банк станции 0, старый Index37 и новый DE задают допустимые FInterfaceItem
                ;   действуют договоры SwitchItemContour, DrawCenteredItem и помощников указателя, стек не перекрывает их данные
                ; Out:
                ;   при Carry=1 сохранены все регистры, флаги, память и порты, SP после RET равен входному+2
                ;   при Carry=0 EquipmentTradeState.OwnedMode=1, HL и DE равны входному DE, BC сохранён
                ;   у старой кнопки Index37 сброшен только Flags.bit0, у новой этот бит установлен, обе рамки перерисованы
                ;   AF содержит A=C3 и F последнего текста, H', DE', BC', IX, IY, I, IFF и IM сохранены, L' и AF' рабочие
                ;   указатель возобновлён, UpdateBlocked=0, страница не меняется, SP обычного возврата равен входному+2
                ; Corrupt:
                ;   HL, DE, AF, L', AF', OwnedMode, Flags двух записей, bitmap, текстовое окно, курсор и карта владельцев
                ; Note:
                ;   OwnedMode является целым режимом, 0 выбирает покупку, 1 продажу, независимые биты не вводятся
                ;   сама смена режима не выполняет сделку, отдельный потребитель по 71EB выбирает EventCode 5 при нуле либо 6 при ненулевом байте
                ;   полный потребитель HandleEquipmentListAction и исходные события 5 и 6 проверены отдельно, сама смена режима сценарий не запускает
                ;   при равных индексах общая процедура рисует запись дважды, итоговый Flags.bit0 установлен, проверки равенства здесь нет
                ; -----------------------------------------
                ; проверка Carry общего действия до изменения режима оборудования
Entry:          RET C                                                           ; выход, если входной Carry установлен, действие запрещено

                ; обновление целого режима оборудования, единица выбирает продажу
                LD A, #01
                LD (@EquipmentTradeState.OwnedMode), A
                ; чтение прежней кнопки покупки, DE новой кнопки продажи сохраняется
                LD HL, (@DrawItemState.Index37)
                JP @Station.SwitchItemContour.Entry

                endmodule
                endmodule
