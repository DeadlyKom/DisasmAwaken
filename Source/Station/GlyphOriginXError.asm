                module Station
                module GlyphOriginXError
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [GlyphRendering.md](../../Docs/GlyphRendering.md)
                ; -----------------------------------------
                ; Обработка ненулевого старшего байта физического начала глифа по X
                ; исходная запись 4, файловые смещения #4E77..#4E7E
                ; In:
                ;   AF - A ненулевой старший байт физического X
                ;   SP - FGlyphFrame, подготовленный DrawGlyph
                ; Out:
                ;   HL, DE, BC восстановлены из кадра, AF задаёт статус, при отрицательном A успех #0045, иначе #0044
                ;   HL', DE', BC', AF' восстановлены из кадра, IX, IY, I, IM и IFF сохраняются
                ;   SP увеличен на #10 после RET, R получает 15 M1
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', R
                ; Note:
                ;   RAM не записывается, семь сохранённых слов и внешний возврат только читаются
                ;   общий выход использует ReturnGlyph.Status либо ReturnGlyph.Entry, дополнительный адрес возврата не создаётся
                ;   IX, IY, I и IFF сохраняются, пиксели не записываются, самостоятельный CALL без кадра недопустим
                ; -----------------------------------------
                ; проверка знака ненулевого старшего байта физического X
Entry:          AND A
                JP M, @Station.ReturnGlyph.Entry                                ; переход, если физическое начало отрицательно по X, глиф пропускается с успешным статусом

                ; выбор нулевого статуса без Carry для положительного выхода X за байтовую координату
                XOR A
                JP @Station.ReturnGlyph.Status

                endmodule
                endmodule
