                module Station
                module DisableDrawList
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [список изменяемых обработчиков](../../Docs/DrawAdapters.md)
; -----------------------------------------
; Отключение обработчиков списка заменой их первого байта на RET
; исходная запись 4, файловые смещения #3C59..#3C67
; In:
;   HL - читаемый список FDrawListEntry, первый указатель со старшим байтом 1 завершает обход
;   указанные обработчики находятся в записываемой памяти и не перекрывают список, стек либо исполняемый изменятель
;   цели принадлежат семейству обёрток, активный первый байт которых должен быть LD HL,nn
; Out:
;   HL - адрес старшего байта ограничителя, то есть начало+2*N+1 для N обработчиков
;   DE - E младший байт ограничителя, D старший байт последнего обработчика, при пустом списке D исходный
;   BC сохранён, AF - A=0, F=#42 OR входной Carry
;   первые байты целей заменены на #C9, остальные байты обёрток не меняются
; Corrupt:
;   HL, DE, AF
; Note:
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   сравнивается только старший байт указателя с единицей, младший байт ограничителя произволен
;   нет встроенного предела числа записей и проверки доступности цели, все указатели до ограничителя обрабатываются
;   EnableDrawList восстанавливает фиксированный код LD HL,nn, произвольный прежний код не запоминается
;   Z=1 сформирован DEC старшего байта ограничителя, список и пиксельный экран напрямую не обрабатываются как графика
; -----------------------------------------
                ; чтение младшего байта указателя FDrawListEntry.Handler
Entry:          LD A, (HL)
                LD E, A
                INC HL
                ; чтение и проверка старшего байта, единица обозначает конец списка
                LD A, (HL)
                DEC A
                RET Z                                                           ; выход, если старший байт равен 1, младший байт ограничителя не проверяется

                INC A
                INC HL
                LD D, A
                ; выбор фиксированного кода первого байта, остальные байты обработчика сохраняются
                LD A, @DrawOpcode.Disabled
                ; изменение только первого байта обработчика по прочитанному указателю
                LD (DE), A
                JP @Station.DisableDrawList.Entry

                endmodule
                endmodule
