                module Station
                module DrawBandSync
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [элемент с верхней полосой и ожиданием HALT](../../Docs/CaptionItem.md)
; -----------------------------------------
; Ожидание пробуждения HALT и рисование полосовой рамки с сохранением HL и альтернативных HL, DE
; исходная запись 4, файловые смещения #6084..#6092
; In:
;   DE - D высота полосовой рамки 3..24, E полная ширина 2..32
;   BC - знаковые координаты с непустым горизонтальным пересечением экрана
;   AF - бит 0 A выбирает заполнение верхней полосы, таблицы и изменяемые коды писателя подготовлены
;   HALT должен получить пробуждение, для обычного IRQ нужен IFF1=1 и действующий источник прерываний
;   пробуждающий обработчик сохраняет параметры и существенное состояние писателя
;   шесть изменяемых слов рамки задают обычный либо заполненный режим из StationSpans.md
; Out:
;   HL, HL' и DE' восстановлены из FBandWaitFrame, BC' и индексные регистры сохраняются при указанном договоре IRQ
;   DE, BC, AF и AF' являются рабочими состояниями DrawBandFrame, видимый bitmap рамки записан
; Corrupt:
;   DE, BC, AF, AF'
; Note:
;   перед HALT на CPU-стеке уже лежат SavedHL, SavedDEAlt и SavedHLAlt
;   обёртка сама не выполняет EI, DI или изменения I, при отсутствии подходящего пробуждения возврат не гарантирован
;   эффекты настоящего обработчика прерывания и время ожидания изолированной моделью не подтверждены
;   атрибуты не записываются, LeftCode, RightCode, SpanSkip и BandPattern подчиняются DrawBandFrame
;   шесть изменяемых операндов имеют обычный набор ResetBandMode либо заполненный набор SetBandFillMode
;   в заполненном режиме строки 3..10 всегда SetCutoutPattern, строки 12 и 13..15 и середина также заполнены
;   нижнее знакоместо заполненного режима содержит пять строк SetCutoutPattern, одну фиксированную SetOutlinePattern, SetSixBitPattern и ClearSpanPattern
;   строки 2,11 и третья снизу сохраняют обычный боковой узор, их фиксированные вызовы не подменяются
; -----------------------------------------
                ; создание FBandWaitFrame.SavedHL для сохранения основного указателя
Entry:          PUSH HL
                EXX
                ; сохранение FBandWaitFrame.SavedDEAlt перед ожиданием и рисованием
                PUSH DE
                ; сохранение FBandWaitFrame.SavedHLAlt, который рабочая рамка может менять
                PUSH HL
                EXX
                ; ожидание пробуждения, обёртка не включает прерывания самостоятельно
                HALT
                CALL @Station.DrawBandFrame.Entry
                ; восстановление альтернативных HL и DE из FBandWaitFrame после рисования
                EXX
                POP HL
                POP DE
                EXX
                ; восстановление основного HL, затем возврат по FBandWaitFrame.ReturnAddress
                POP HL
                RET

                endmodule
                endmodule
