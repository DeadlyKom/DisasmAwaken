                module GetRowHitData
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [байтовые координаты, доступная высота и строка указателя](../../Docs/RowSelection.md)
; -----------------------------------------
; Получение PointerY и байтового начала области строк из Y элемента и отступа
; исходная запись 4, файловые смещения #4280..#428E
; In:
;   DE - E пиксельный отступ от байтового Y элемента, D сохраняемый контекст
;   IX - читаемая FInterfaceItem в станционном банке 0, PointerXY.Y доступен по #6308
; Out:
;   HL и DE сохранены, B=((Item.Y*8) AND #FF)+E по модулю 256, C=PointerXY.Y
;   A=B, F соответствует ADD байта ((Item.Y*8) AND #FF) и E
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
; Corrupt:
;   BC, AF
; Note:
;   три RLCA и AND #F8 отбрасывают обратные младшие биты вращения, результат равен байтовому умножению Y на восемь
;   знаковое расширение отрицательного Y не создаётся, начало является байтом, переполнение сохраняется только в F
;   PointerX не читается, горизонтальное попадание должно проверяться вызывающей стороной
;   память не меняется, флаги результата не являются признаком попадания
; -----------------------------------------
                ; чтение пиксельной Y указателя, горизонтальная координата этому расчёту не нужна
Entry:          LD A, (@StationState.PointerXY + 1)
                LD C, A
                ; чтение байтовой строки элемента из физического FInterfaceItem.Y
                LD A, (IX + FInterfaceItem.Y)
                ; расчёт пиксельного начала через три вращения и отбрасывание младшей тройки
                RLCA
                RLCA
                RLCA
                ; удаление младших битов обратной части вращения Y
                AND @RowSelectConst.CellMask
                ; расчёт байтового начала области добавлением пиксельного отступа E
                ADD A, E
                LD B, A
                RET

                endmodule
                endmodule
