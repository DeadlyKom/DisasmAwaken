                module Station
                module UpdatePixelHover
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [две проверки PointerY, снятие указателя и сохранение выбранной строки](../../Docs/RowHover.md)
; -----------------------------------------
; Обновление XOR-выделения строки верхнего элемента по пиксельной высоте
; исходная запись 4, файловые смещения #4341..#436D
; In:
;   HL - ожидаемый адрес обработчика рисования, сравниваемый с последним словом списка
;   DE - E пиксельный верхний отступ, D ограничение высоты в единицах конкретного входа
;   AF - A прежний номер строки либо #FF при отсутствии выделения
;   IX - FInterfaceItem, действуют договоры XorItemRow, SuspendPointer и ResumePointer
;   список рисования непуст и завершается старшим байтом 1, PointerY в пределах 0..191
; Out:
;   D уже задаёт пиксельную высоту и не ограничивается Item.Height
;   если обработчик не последний, HL=последний-ожидаемый по модулю 65536, DE и BC сохранены, AF=#0044
;   если первое попадание отвергнуто, HL=0, DE ограничение и отступ, B начало области, C=PointerY, AF=#0044
;   если номер совпадает, HL=0, DE ограничение и отступ, B начало области, C=номер, A=прежний номер, F от CP C с Z=1
;   при изменении HL, DE и BC соответствуют последнему XorPointerRow, AF - A итоговый D, F=0 с Z=0
;   при изменении указатель восстановлен через ResumePointer, UpdateBlocked=0, AF' рабочий
;   HL', DE', BC', IX, IY, I и IFF сохранены, SP восстановлен
; Corrupt:
;   HL, DE, BC, AF, AF'
; Note:
;   входной D передаётся GetPointerRow непосредственно, умножения на восемь здесь нет
;   Z=1 означает отсутствие обновления, нулевой номер строки при обновлении возвращается с Z=0
;   равенство проверяется по полному указателю обработчика, а не по номеру или флагам элемента
;   при прежнем A=#FF снятие старой полосы пропускается, иначе выполняется XorItemRow без проверки старого номера
;   после снятия указателя XorPointerRow заново читает PointerY, первое попадание и второе не атомарны
;   UpdateBlocked запрещает периодическое рисование указателя, но не опрос ввода обработчиком прерывания
;   при отказе второго попадания D сохраняет высоту, она возвращается как A с F=0, новый номер не получен
;   при втором попадании в другую строку выбирается именно вторая строка, хотя сравнение с прежней сделано по первой
;   ветви отсутствия обновления не снимают указатель и не меняют порт, фон либо UpdateBlocked
;   вызов ResumePointer допускает изменение AF' даже при сохранении всех прочих альтернативных регистров
; -----------------------------------------
                ; сохранение прежнего номера и входных флагов на стеке
Entry:          PUSH AF
                ; сохранение входного ограничения и отступа перед обменом HL и DE
                PUSH DE
                ; передача ожидаемого адреса в DE для сравнения с последним обработчиком
                EX DE, HL
                ; поиск последнего обработчика в текущем списке рисования
                CALL @Station.GetLastDraw.Entry
                ; сброс Carry перед шестнадцатибитным сравнением адресов
                OR A
                ; проверка равенства последнего и ожидаемого адресов через их разность
                SBC HL, DE
                ; восстановление ограничения высоты и верхнего отступа
                POP DE
                JR NZ, @Station.UpdatePixelHover.NoUpdate                       ; переход, если ожидаемый обработчик не последний, выделение не обновлять

                ; проверка первого вертикального попадания PointerY в область строк
                CALL @Station.GetPointerRow.Entry
                JR NC, @Station.UpdatePixelHover.CompareRow                     ; переход, если PointerY попала в область, сравнить номер с прежним

                ; снятие сохранённого AF перед отказом без графических изменений
NoUpdate:       POP AF
                ; возврат отсутствия обновления через A=0 и Z=1
                XOR A
                RET

                ; восстановление прежнего номера после успешного попадания
CompareRow:     POP AF
                ; проверка изменения номера относительно первой прочитанной PointerY
                CP C
                RET Z                                                           ; выход, если новый номер равен прежнему, XOR-полосы не менять

                ; снятие указателя и запрет его периодического рисования, опрос ввода продолжается
                CALL @Station.SuspendPointer.Entry
                ; проверка маркера #FF через увеличение прежнего номера
                INC A
                JR Z, @Station.UpdatePixelHover.DrawCurrent                     ; переход, если прежний номер равен #FF, старую полосу не снимать

                ; восстановление прежнего номера после проверки маркера
                DEC A
                ; сохранение пиксельной высоты перед её заменой номером старой строки
                PUSH DE
                ; снятие прежней подсветки повторным XOR по старому номеру
                CALL @Station.XorItemRow.Entry
                ; восстановление высоты и отступа для второй проверки PointerY
                POP DE
                ; повторная проверка PointerY и инверсия текущей строки, поздний отказ не проверяется
DrawCurrent:    CALL @Station.XorPointerRow.Entry
                ; рисование указателя поверх полученной сцены и снятие UpdateBlocked
                CALL @Station.ResumePointer.Entry
                ; подготовка флагов успешного обновления независимо от результата повторного попадания
                XOR A
                ; установка NZ, номер нулевой строки также должен сообщать обновление
                INC A
                ; возврат D, при позднем отказе здесь остаётся высота области
                LD A, D
                RET

                endmodule
                endmodule
