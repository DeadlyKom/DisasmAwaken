                module Station
                module UpdateMissionRowHover
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [номер строки, Z и отдельный вход нажатия](../../Docs/MissionHover.md)
; -----------------------------------------
; Обновление подсветки двух строк элемента миссии с хранением номера в операнде
; исходная запись 4, файловые смещения #11F9..#1208
; In:
;   IX запись FInterfaceItem элемента миссии, действуют UpdateRowHover, XorItemRow и ResumePointer
;   список рисования непуст и имеет исходный ограничитель, PointerY=0..191, выбран станционный банк 0
;   MissionHoverState.Row содержит прежнюю строку либо FF, операнд доступен для записи
; Out:
;   до вызова UpdateRowHover HL=DrawItem31.Entry, DE=0203, A=MissionHoverState.Row
;   если UpdateRowHover вернул Z=1, обычный RET оставляет Row прежним, регистры и AF по его пути отказа либо совпадения
;   если UpdateRowHover вернул Z=0, Row получает весь возвращённый A, прочие выходы по этому вызову
;   для обычного попадания двухстрочной области новый A равен 0 либо 1, F=0 даже при A=0
;   HL', DE', BC', IX, IY, I и IFF сохранены по договору дочернего входа, AF' рабочий при перерисовке указателя
;   SP обычного возврата равен входному SP+2, повторный CALL обработчика не создаётся
; Corrupt:
;   HL, DE, BC, AF, AF' на перерисовке
; Note:
;   D=2 задаёт запрос двух строк, он масштабируется и ограничивается ClampRowHeight, E=3 задаёт пиксельный верхний отступ
;   обновление допускается только если DrawItem31 является последним обработчиком списка
;   поздний отказ второй проверки PointerY сохраняет исходный служебный результат высоты, а не превращается в FF
;   RET Z важен, A=0 может обозначать как отказ без изменения, так и успешно выбранную строку 0 с Z=0
;   DrawItem31 сбрасывает Row в FF после перерисовки элемента, чтобы не снимать старую XOR-полосу с нового фона
; -----------------------------------------
                ; выбор двух строк и верхнего отступа 3 пикселя для подсветки элемента миссии
Entry:          LD DE, @MissionHoverConst.LimitAndOffset
                ; выбор ожидаемого последнего обработчика списка, рисователя цели миссии
                LD HL, @Station.DrawItem31.Entry
                ; чтение прежней строки из изменяемого операнда Row, FF означает отсутствие прежней полосы
                LD A, #FF
                ; полный проход проверки положения указателя и возможной смены XOR-полосы
                CALL @Station.UpdateRowHover.Entry
                RET Z                                                           ; выход, если UpdateRowHover вернул Z=1, не заменять сохранённую строку

                ; сохранение нового результата только по Z=0, строка 0 также должна быть записана
                LD (@MissionHoverState.Row), A
                RET

                endmodule
                endmodule
