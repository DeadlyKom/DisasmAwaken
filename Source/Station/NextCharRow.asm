                module Station
                module NextCharRow
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [StationSpans.md](../../Docs/StationSpans.md)
; -----------------------------------------
; Коррекция экранного адреса при переходе после восьми пиксельных строк к следующей строке знакомест
; исходная запись 4, файловые смещения #616F..#617A
; In:
;   HL - рабочий экранный адрес после последовательных пиксельных строк, на видимом пути H уже увеличен на восемь
; Out:
;   HL - L увеличен на 32, при переполнении L старший байт сохранён и A=0, иначе H уменьшен на восемь и A=H
; Corrupt:
;   HL, AF
; Note:
;   DE, BC, альтернативные и индексные регистры сохраняются, SP восстанавливается
;   при переполнении L флаги остаются от восьмибитного сложения, иначе от вычитания восьми из прежнего H
;   сами пиксели не записываются, это коррекция нелинейной экранной адресации
; -----------------------------------------
                ; переход к следующей строке знакомест после обработки её пиксельных строк
Entry:          LD A, L
                ; расчёт следующей группы Y через младшую часть экранного адреса
                ADD A, @ScreenConst.ByteColumns
                LD L, A
                LD A, #00
                RET C                                                           ; выход, если прибавление 32 переполнило младший байт, старшая часть уже соответствует новой трети

                LD A, H
                ; компенсация восьми увеличений H при переходе внутри текущей трети экрана
                SUB @ScreenConst.PixelsPerChar
                LD H, A
                RET

                endmodule
                endmodule
