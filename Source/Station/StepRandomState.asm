                module Station
                module StepRandomState
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [точная формула шага, физические состояния и обмен регистров](../../Docs/RandomState.md)
; -----------------------------------------
; Шаг трёхбайтового состояния с переносами и возвратом слова в другом наборе регистров
; исходная запись 4, файловые смещения #48C1..#490C
; In:
;   HL - доступное для чтения и записи FRandomState, не перекрывающее ядро и CPU-стек
;   DE' и BC' - контекст, который станет основным набором на возврате
; Out:
;   HL - новое младшее слово состояния, DE и BC получают входные DE' и BC'
;   AF - A новый HighByte, F от последнего SBC A,0 с заёмом второго шестнадцатибитного вычитания
;   HL' адрес FRandomState, DE' новое младшее слово, B'=0, C' младший байт T=(75*исходный LowWord-64) AND #FFFF
;   AF', IX, IY, I и IFF сохранены, SP восстановлен, три байта состояния обновлены
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC'
; Note:
;   выход содержит EXX, прямой вызов намеренно меняет активный набор, это не сохраняемая функция обычного соглашения
;   старший байт не умножается на 64, ADC A,0 только суммирует переносы шести удвоений младшего слова минус один
;   переносы предварительного LowWord*8 не добавляются в A, затем добавляются переносы ещё четырёх сумм
;   последний DEC HL не переносит заём в старший байт, при нулевом остатке возвращается #FFFF с прежним HighByte
;   точная формула приведена в RandomState.md, качество, период и равномерность генератора не доказаны
; -----------------------------------------
                ; чтение младшего слова FRandomState перед формулой смешивания
Entry:          LD C, (HL)
                INC HL
                LD B, (HL)
                INC HL
                ; чтение старшего байта состояния и сохранение его адреса на стеке
                LD A, (HL)
                PUSH HL
                ; сохранение старшего байта и копирование исходного слова BC
                LD E, A
                LD H, B
                LD L, C
                ; расчёт LowWord-1 с шестнадцатибитным оборачиванием
                DEC HL
                ; шесть удвоений слова, каждый перенос отдельно добавляется в байтовый аккумулятор
                ADD HL, HL
                ADC A, #00
                ADD HL, HL
                ADC A, #00
                ADD HL, HL
                ADC A, #00
                ADD HL, HL
                ADC A, #00
                ADD HL, HL
                ADC A, #00
                ADD HL, HL
                ADC A, #00
                ; сохранение шестидесятичетырёхкратного младшего слова в DE
                EX DE, HL
                ; восстановление исходного слова перед отдельным расчётом LowWord*8
                LD H, B
                LD L, C
                ; расчёт восьмикратного слова без добавления этих переносов в A
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ; суммирование с сохранённым слагаемым, затем три прибавления исходного LowWord
                ADD HL, DE
                ADC A, #00
                ADD HL, BC
                ADC A, #00
                ADD HL, BC
                ADC A, #00
                ADD HL, BC
                ADC A, #00
                ; сохранение промежуточного слова T в DE
                LD D, H
                LD E, L
                ; создание переставленной пары A:T.high для обратного вычитания T.low
                LD L, H
                LD H, A
                ; подготовка нулевого старшего байта вычитаемого T.low
                LD B, #00
                LD C, E
                ; сброс Carry перед первым шестнадцатибитным вычитанием
                OR A
                ; расчёт промежуточного вычитаемого с заёмом в старший байт A
                SBC HL, BC
                SBC A, #00
                ; возврат T в HL перед вторым вычитанием
                EX DE, HL
                ; сброс Carry перед вычитанием промежуточного слова из T
                OR A
                ; расчёт нового остатка с отдельным заёмом в HighByte
                SBC HL, DE
                SBC A, #00
                ; вычет единицы только из младшего слова без изменения HighByte
                DEC HL
                ; передача нового слова в DE для записи состояния и возврата
                EX DE, HL
                ; восстановление адреса HighByte состояния
                POP HL
                ; обновление трёх физических байтов FRandomState в порядке от старшего к младшим
                LD (HL), A
                DEC HL
                LD (HL), D
                DEC HL
                LD (HL), E
                ; передача нового слова через CPU-стек в другой активный HL
                PUSH DE
                ; возврат к другому набору регистров, входные альтернативные DE и BC становятся основными
                EXX
                POP HL
                RET

                endmodule
                endmodule
