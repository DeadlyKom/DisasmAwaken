                module Station
                module GlyphOriginYError
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [GlyphRendering.md](../../Docs/GlyphRendering.md)
; -----------------------------------------
; Обработка ненулевого старшего байта физического начала глифа по Y
; исходная запись 4, файловые смещения #4E7F..#4E87
; In:
;   AF - A ненулевой старший байт физического Y
;   SP - FGlyphFrame, подготовленный DrawGlyph
; Out:
;   при отрицательном A успех #0045, иначе #0100
;   обычные и альтернативные регистры восстановлены общим выходом, SP увеличен на #10 после RET
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', относительно внутреннего входа восстановлены из кадра
; Note:
;   общий выход использует ReturnGlyph.Status либо ReturnGlyph.Entry, дополнительный адрес возврата не создаётся
;   IX, IY, I и IFF сохраняются, пиксели не записываются, самостоятельный CALL без кадра недопустим
; -----------------------------------------
                ; проверка знака ненулевого старшего байта физического Y
Entry:          AND A
                JP M, @Station.ReturnGlyph.Entry                                ; переход, если физическое начало отрицательно по Y, глиф пропускается с успешным статусом

                ; выбор кода 1 без Carry для положительного выхода Y за байтовую координату
                XOR A
                INC A
                JP @Station.ReturnGlyph.Status

                endmodule
                endmodule
