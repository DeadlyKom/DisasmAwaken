                module Station
                module RepaintItemCore
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [стековая цепочка перерисовки](../../Docs/RepaintChain.md)
; -----------------------------------------
; Закрытие активного элемента, перенос выбранного, скрытая перерисовка и условная интерактивная геометрия
; исходная запись 4, файловые смещения #6BF2..#6C20
; In:
;   HL - запасная обёртка, DE - индекс выбранного элемента, BC - контекст вызывающего кода
;   CloseActiveItem получает допустимый callback, код списка и выбранный рисователь удовлетворяют своим договорам
;   FlagsCache и указатель подготовлены для TrackItemGeometry при ненулевом младшем селекторе
;   станционный банк доступен для записи, стек вне экранов, выполняются ограничения BeginScreenUpdate и EndScreenUpdate
;   AF - A селектор, ExitInstruction ранее установлен в #A7 либо #37 одним из входов
; Out:
;   при раннем выходе по биту 7 A исходный, F=(A AND #A8) OR 1, прочие основные и индексные регистры сохранены
;   при обычном пути DE и IX восстановлены, без рисования HL содержит выбранную обёртку, после рисования результат рисователя
;   BC, альтернативные регистры и IY зависят от callback закрытия и рисователя, их произвольные изменения не отменяются
;   при обычном пути A - селектор после обработки входной обёрткой, перенос списка и закрытие уже выполнены
;   при перерисовке без интерактивного действия F задаёт текущая ExitInstruction
;   при нулевом A без перерисовки AF=#0044, иначе результат определяется соответствующей ветвью
; Corrupt:
;   HL, BC, AF, HL', DE', BC', AF', IY согласно callback и рисователю
; Note:
;   FRepaintFrame содержит SavedAF, SavedDE, SavedIX, ReturnAddress, AF сохраняется после OR A
;   если MoveItemToTail возвращает Z=1, выбранная обёртка уже последняя, рисование и экранные переключения пропускаются
;   обычно Z=1 соответствует нулю следующих указателей, при длинном списке учитывается исходная восьмибитная арифметика MoveItemToTail
;   при Z=0 FRepaintChain кладёт DrawHandler и AfterDraw поверх FRepaintFrame
;   JP BeginScreenUpdate не создаёт возврата, его RET вызывает DrawHandler, RET рисователя ведёт в AfterDraw
;   AfterDraw вызывает EndScreenUpdate, восстанавливает AF, DE, IX и вызывает TrackItemGeometry только при A ненулевом
;   после рисования Carry от TrackItemGeometry немедленно завершает процедуру, иначе исполняется изменяемый ExitCode
;   без рисования ненулевой A передаётся хвостовым JP в TrackItemGeometry, ExitCode не исполняется
;   обработчик прерывания и callback обязаны сохранять доступность кода, корректность произвольных внешних callback моделью не доказывается
;   SP восстанавливается при соблюдении договоров всех вызываемых обработчиков, собственный код не меняет I и IFF
;   модель исполняет исходные 65 байтов, вызываемые процедуры подменены явными договорами, это проверка композиции и стека
; -----------------------------------------
                ; проверка старшего бита селектора до закрытия элемента и создания кадра
Entry:          BIT 7, A
                ; установка Carry для раннего выхода без изменения S,Z,P/V после BIT
                SCF
                RET NZ                                                          ; выход, если бит 7 селектора установлен, вернуть Carry без действий со списком

                ; проверка нулевого селектора и очистка Carry до сохранения AF
                OR A
                ; создание FRepaintFrame с исходными IX, DE и проверенным AF
                PUSH IX
                PUSH DE
                PUSH AF
                ; закрытие прежнего активного элемента, внешний callback может менять несохранённый контекст
                CALL @Station.CloseActiveItem.Entry
                ; поиск выбранного обработчика и перенос к концу списка
                CALL @Station.MoveItemToTail.Entry
                JP Z, @Station.RepaintItemCore.AlreadyLast                      ; переход, если MoveItemToTail вернул Z, пропустить перерисовку уже последнего обработчика

                ; подготовка адреса продолжения после нормального RET выбранного рисователя
                LD DE, #CC0C
                ; создание FRepaintChain, сначала AfterDraw, затем адрес DrawHandler
                PUSH DE
                PUSH HL
                ; переход к снимку экрана, его RET извлечёт DrawHandler вместо обычного адреса вызова
                JP @Station.BeginScreenUpdate.Entry

                ; возобновление указателя и показ обновлённого базового экрана после возврата рисователя
AfterDraw:      CALL @Station.EndScreenUpdate.Entry
                ; снятие FRepaintFrame с восстановлением селектора, исходных DE и IX
                POP AF
                POP DE
                POP IX
                CALL NZ, @Station.TrackItemGeometry.Entry                       ; вызов, если восстановленный A ненулевой, выполнить интерактивную геометрию
                RET C                                                           ; выход, если интерактивная геометрия вернула Carry, сохранить её результат

                ; изменяемый код выхода, исходный SCF либо записанный AND A
ExitCode:       SCF
                RET

                ; восстановление FRepaintFrame на пути без перерисовки
AlreadyLast:    POP AF
                POP DE
                POP IX
                JP NZ, @Station.TrackItemGeometry.Entry                         ; переход, если восстановленный A ненулевой, вернуть результат TrackItemGeometry напрямую

                RET

                endmodule
                endmodule
