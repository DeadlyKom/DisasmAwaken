                module CommitPointerInput
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [опрос, накопление и таблица направлений](../../Docs/PointerInputs.md)
                ; -----------------------------------------
                ; Запись координат после возврата обработчика выбранного направления
                ; исходная запись 4, файловые смещения #097F..#0983
                ; In:
                ;   HL и DE остаются от обработчика направления, BC - итоговые пиксельные координаты, AF остаётся от обработчика
                ;   на стеке исходный адрес возврата, обработчик уже снял адрес CommitPointerInput своим RET
                ; Out:
                ;   HL, DE, BC, AF, альтернативные и индексные регистры сохранены, PointerXY=BC
                ;   SP увеличен на два, R получает три M1 по модулю 128 с сохранением бита 7 при исходных инструкциях без IRQ
                ; Corrupt:
                ;   R и PointerXY
                ; Note:
                ;   собственных записей CPU-стека нет, единственные две записи RAM обновляют PointerXY
                ;   две исходные инструкции LD (PointerXY),BC и RET завершают созданную ApplyPointerInput цепочку
                ;   SP восстанавливается по исходному адресу вызывающей стороны
                ; -----------------------------------------
                ; запись итоговых координат после RET выбранного обработчика направления
Entry:          LD (#6307), BC
                RET

                endmodule
