                module JustifyAfterLF
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [поиск и выбор текстовой записи](../../Docs/TextSelection.md)
; -----------------------------------------
; Пропуск A+1 ограничителей LF и вывод оставшегося текста с выравниванием
; исходная запись 4, файловые смещения #4374..#4379
; In:
;   HL - начало блока текстовых записей с читаемым запасом поиска
;   AF - A задаёт A+1 пропускаемых ограничителей, #FF означает 256
;   TextWindow подготовлен, для выравнивания нужен читаемый запас просмотра слов
; Out:
;   HL, DE, BC, AF - результат PrintJustified после выбранного ограничителя, точные состояния описаны в JustifiedText.md
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   сначала выполняется полный контракт SkipCrRecords либо SkipLfRecords, затем хвостовой JP в печататель
;   у альтернативных и индексных регистров, I и IFF сохраняется исходное состояние, стек сбалансирован
;   все ограничения поиска, состояния курсора, отказов и завершения вызываемых алгоритмов сохраняются
; -----------------------------------------
                ; поиск начала текста за нужным количеством LF перед выравниванием
Entry:          CALL @Station.SkipLfRecords.Entry
                JP @Station.PrintJustified.Entry

                endmodule
                endmodule
