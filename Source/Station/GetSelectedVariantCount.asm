                module Station
                module GetSelectedVariantCount
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [четыре байта ключа, насыщенный декремент и два нулевых выхода](../../Docs/VariantCount.md)
; -----------------------------------------
; Получение количества вариантов 0..6 из младших трёх битов XOR выбранного ключа
; исходная запись 4, файловые смещения #47F5..#4805
; In:
;   MapSelection.FirstWord и SecondWord содержат четыре доступных байта выбранного ключа, входные регистры результат не задают
; Out:
;   HL - MapSelection.FirstWord, DE - MapSelection.SecondWord, BC сохраняется
;   AF - q=(XOR четырёх байтов ключа)AND 7, A=max(q-1,0), диапазон результата 0..6
;   при q=0 AF=0044, при q=1 AF=0042, на остальных q флаги соответствуют DEC q с Carry=0
;   Z установлен ровно при q=0 либо q=1, Carry сброшен на всех выходах
;   все альтернативные и индексные регистры, I и IFF сохраняются, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, AF
; Note:
;   три младших разряда являются числовым кодом количества до декремента, отдельными флагами они не объявляются
;   RET P проверяет результат DEC, у q=0 значение FF не возвращается, следующий XOR A заменяет его на ноль
;   независимый соседний A806 выделен отдельно, его назначение этим договором не подменяется
;   модель проверила 131072 пары слов и точные AF, сам игровой смысл выбора этого количества за пределами доказанных потребителей не предполагается
; -----------------------------------------
                ; чтение обоих слов выбранного ключа для детерминированного количества вариантов
Entry:          LD HL, (@MapSelection.FirstWord)
                LD DE, (@MapSelection.SecondWord)
                ; объединение четырёх байтов ключа через XOR, порядок не влияет на результат
                LD A, H
                XOR L
                XOR E
                XOR D
                ; выделение числового кода 0..7 из младших трёх битов XOR
                AND @MapVariantConst.CountMask
                ; расчёт предварительного количества q-1, при q=0 получится FF со знаком
                DEC A
                RET P                                                           ; выход, если код q ненулевой, вернуть количество q-1 в диапазоне 0..6

                ; замена отрицательного результата FF на ноль для исходного кода q=0
                XOR A
                RET

                endmodule
                endmodule
