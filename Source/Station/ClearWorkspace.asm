; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [CellMap.md](../../Docs/CellMap.md)
; -----------------------------------------
; Обнуление #0300 байт рабочей области начиная с #8600
; исходная запись 4, файловые смещения #3EC4..#3ED6
; In:
;   область StationState.DirtyCells длиной #0300 байт доступна для записи, CPU-стек не перекрывает её
; Out:
;   #8600..#88FF заполнены нулями, A сохранён, H, N и PV сброшены
;   S, Z и Carry сохранены, бит 3 F получает бит 3 исходного A, бит 5 F получает бит 1 исходного A
; Corrupt:
;   AF, только F
; Note:
;   первый нулевой байт берётся из L=#00, остальные 767 распространяются перекрывающимся LDIR
;   HL, DE, BC, альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   очищается карта владельцев, пиксели экрана и индексные пары #8500 не записываются
; -----------------------------------------
Entry:          PUSH HL
                PUSH DE
                PUSH BC
                ; подготовка перекрывающегося заполнения всех 768 ячеек карты нулевым владельцем
                LD HL, @StationState.DirtyCells
                LD DE, @StationState.DirtyCells + 1
                LD BC, @StationTables.WorkspaceTail
                ; обнуление первой ячейки значением младшего байта адреса #8600
                LD (HL), L
                ; распространение первого нуля на оставшиеся 767 байтов карты
                LDIR
                POP BC
                POP DE
                POP HL
                RET

                endmodule
                endmodule
