                module Station
                module MeasureTextRun
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [Font.md](../../Docs/Font.md)
; -----------------------------------------
; Измерение пиксельной ширины текста до CR, LF или разделителя B с продвижением HL
; исходная запись 4, файловые смещения #5DA6..#5DC9
; In:
;   HL - начало читаемого текста, BC - B дополнительный однобайтовый разделитель
;   FontConst.WidthPage - таблица 256 байтов ширины, текст достигает ограничителя или условия насыщения
; Out:
;   HL - адрес ограничителя либо символа, чья ширина вызвала насыщение, AF - A сумма ширин 0..255 либо #FF при насыщении
;   при ограничителе F=#42 OR (код ограничителя AND #28), при насыщении F остаётся от последнего ADD ширины с накопленной суммой
; Corrupt:
;   HL, AF
; Note:
;   CR и LF всегда ограничивают текст, код B проверяется после них, нулевой код сам по себе не ограничитель, если B не равен нулю
;   каждый принятый символ увеличивает HL на один, ограничитель и вызвавший насыщение символ не потребляются
;   насыщение выбирается при Carry=1 либо нулевом результате ADD, сумма ровно 255 допускается и тоже может вернуть A=#FF без насыщения
;   DE, BC, альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   при синтетической нулевой ширине в начале строки возвращается #FF без продвижения, исходная таблица содержит только ширины 2..8
;   пиксели и курсор не меняются, выходной Z относится к последней проверке, а не к возвращённому A
; -----------------------------------------
Entry:          PUSH DE
                PUSH BC
                ; обнуление накопленной ширины перед просмотром текста
                LD C, #00
                LD D, @FontConst.WidthPage
NextChar:       LD A, (HL)
                ; проверка безусловного ограничителя возврата каретки
                CP @TextConst.CarriageReturn
                JR Z, @Station.MeasureTextRun.ReturnWidth                       ; переход, если найден CR, возвращается накопленная ширина

                ; проверка второго безусловного ограничителя перевода строки
                CP @TextConst.LineFeed
                JR Z, @Station.MeasureTextRun.ReturnWidth                       ; переход, если найден LF, возвращается накопленная ширина

                ; проверка дополнительного разделителя, переданного в B
                CP B
                JR Z, @Station.MeasureTextRun.ReturnWidth                       ; переход, если символ равен разделителю B, возвращается накопленная ширина

                ; выбор ширины текущего символа по его восьмибитному коду
                LD E, A
                LD A, (DE)
                ; расчёт новой суммарной ширины в байтовом накопителе
                ADD A, C
                JR C, @Station.MeasureTextRun.Saturate                          ; переход, если сумма ширин превысила 255, возвращается насыщение #FF

                JR Z, @Station.MeasureTextRun.Saturate                          ; переход, если байтовая сумма ширин равна нулю, исходный алгоритм также выбирает насыщение

                ; продвижение только после принятия ширины текущего символа
                INC HL
                LD C, A
                JP @Station.MeasureTextRun.NextChar

                ; выбор #FF без потребления символа, вызвавшего насыщение
Saturate:       LD C, #FF
                ; возврат накопленной ширины с флагами последнего сравнения либо сложения
ReturnWidth:    LD A, C
                POP BC
                POP DE
                RET

                endmodule
                endmodule
