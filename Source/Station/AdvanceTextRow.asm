                module Station
                module AdvanceTextRow
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [GlyphRendering.md](../../Docs/GlyphRendering.md)
; -----------------------------------------
; Продвижение относительного текстового курсора на восемь пикселей с байтовым переполнением
; исходная запись 4, файловые смещения #4E55..#4E6A
; In:
;   TextWindow.CursorY и Height - байтовые пиксельные значения, CursorX - текущая относительная колонка
; Out:
;   BC - B высота окна, C=(прежний CursorY+8) по модулю 256
;   при C<Height CursorY=C, CursorX=0, AF=#0044, иначе курсор сохранён, A=C и Carry установлен
;   при отказе F имеет S, Z и PV от CP(C,Height), биты 5 и 3 от C, Carry=1, H=N=0
; Corrupt:
;   BC, AF
; Note:
;   переполнение Y+8 не проверяется, например 250 переходит в 2 до сравнения высоты
;   HL, DE, альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   пиксели не записываются, равенство C и Height является отказом
; -----------------------------------------
                ; чтение относительной вертикальной позиции текстового курсора
Entry:          LD A, (@TextWindow.CursorY)
                ; расчёт следующей строки через восемь пикселей с исходным байтовым переполнением
                ADD A, @ScreenConst.PixelsPerChar
                LD C, A
                LD A, (@TextWindow.Height)
                LD B, A
                LD A, C
                ; проверка строгой верхней границы относительного курсора
                CP B
                CCF
                RET C                                                           ; выход, если новая относительная строка не меньше высоты окна, курсор сохраняется

                ; обновление принятой строки и возврат курсора к началу окна по X
                LD (@TextWindow.CursorY), A
                XOR A
                LD (@TextWindow.CursorX), A
                RET

                endmodule
                endmodule
