                module AdvanceClipRow
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [StationSpans.md](../../Docs/StationSpans.md)
; -----------------------------------------
; Продвижение знакового счётчика строки рамки с проверкой 24 видимых строк знакомест
; исходная запись 4, файловые смещения #6165..#616E
; In:
;   HL' - L' предыдущий знаковый индекс строки рамки, H' сохраняется
; Out:
;   HL' - L' увеличен на один по модулю 256, AF - для отрицательного индекса A равен индексу и Carry=1, иначе A равен индексу плюс один и Carry означает индекс меньше 24
; Corrupt:
;   AF, HL'
; Note:
;   основные HL, DE, BC, альтернативные DE', BC', AF', IX и IY сохраняются, SP восстанавливается
;   отрицательные строки находятся выше видимой области, Carry позволяет внешнему циклу продолжить их пропуск
;   индекс 24 и выше при сброшенном знаке снимает Carry и завершает видимую обработку
; -----------------------------------------
                ; продвижение знакового индекса строки рамки в альтернативном L
Entry:          EXX
                INC L
                LD A, L
                EXX
                ; подготовка признака продолжения для строк выше видимой области
                SCF
                RET M                                                           ; выход, если индекс строки отрицателен, верхнее отсечение ещё требует продолжения

                ; проверка нижней границы после 24 видимых строк знакомест
                CP @ScreenConst.CharRows
                ; перевод возвращаемого неотрицательного индекса к нумерации от единицы без изменения Carry
                INC A
                RET

                endmodule
                endmodule
