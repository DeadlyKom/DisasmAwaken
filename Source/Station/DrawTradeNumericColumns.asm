                module Station
                module DrawTradeNumericColumns
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [две физические пары полей, маркеры, частичные выходы и счётчик попыток строк](../../Docs/TradeNumericColumns.md)
                ; -----------------------------------------
                ; Наименования товаров и четыре числовые колонки с двумя отдельными байтами количества и цены
                ; исходная запись 4, файловые смещения #1342..#13FF
                ; In:
                ;   HL - начальный индекс строки, оба массива имеют читаемые пары и достижимый FF в первом байте рыночной пары
                ;   имена начинаются в TradeTableText.Names с CR, пропуск по младшему байту индекса допустим и завершается
                ;   TextWindow и шрифт подготовлены для PrintAfterCR, Print4DigitCore и DrawGlyph, Style=0 для штатного табличного вывода
                ;   Column2X..Column6X задают позиции колонок, MarketRows.Row00 и TradeColumnState.OwnedRows доступны
                ;   выбран станционный банк 0, стек вне экрана и обрабатываемых массивов, действуют договоры текстовых процедур
                ; Out:
                ;   сначала CursorX=0, CursorY=32 и PrintAfterCR печатает наименования с младшего байта входного индекса
                ;   после имён CursorY снова 32, DE=MarketRows.Row00+2*индекс, HL=OwnedRows+2*индекс по модулю 65536 перед числовым проходом
                ;   в каждой принятой по рыночному маркеру строке выведены количество продажи, её цена, имеющееся количество и его цена
                ;   количества маскируются 7F, ноль печатается дефисом, цены полные байты, bit7 количества выбирает дополнительный глиф FE
                ;   AF' - A' число начатых числовых строк по модулю 256, F' от его последнего INC с Carry=0, при нуле начатых строк AF'=0044
                ;   счётчик увеличен до первого глифа количества, поэтому включает строку, которая сразу завершилась отказом вывода
                ;   DE и HL показывают достигнутые поля, при выходе на количестве его указатель ещё не увеличен, указатель цены увеличен до её печати
                ;   при FF первого массива A=0, F=50 OR прежний Carry, указатели текущих пар не продвигаются, CursorX уже равен Column2X
                ;   при вертикальном отказе числового поля A=0 после одного либо двух DEC, F соответствует этому DEC, исходная причина 1 либо 2 не возвращается
                ;   при выходе по высоте A=(CursorY+8) AND FF, C=Height, F от CP Height, CursorY остаётся прежним
                ;   BC рабочий по последнему числовому вызову и проверке высоты, HL', DE', BC', IX, IY сохраняются
                ;   SP обычного возврата равен входному SP+2, I, IFF, IM и страницы собственный код не меняет
                ;   сами массивы не меняются, записаны bitmap, курсор и рабочие операнды текстового ядра
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', bitmap, курсор и рабочие операнды по договорам текста
                ; Note:
                ;   наименования выбираются младшим байтом индекса, числовые массивы полным удвоенным словом, выравнивание этих двух выборок предполагается входным диапазоном
                ;   FF завершает только рыночный массив, AND 7F перед INC во втором массиве делает RET Z по 710A недостижимым без внешнего изменения кода
                ;   недостаток ширины не прекращает обход остальных полей, отказы 1 и 2 прекращают, результат отдельного маркера FE вообще не проверяется
                ;   позиции маркеров 109 и 134 пикселя заданы независимо от изменяемых колонок
                ;   bit7 рынка StockAndSaleBan запрещает продажу со штрафом в исходном сценарии, назначение bit7 грузового массива остаётся Unknown
                ;   модель проверяет 962 полных прохода, все байты обоих количеств, bitmap, попытки глифов, счётчик, курсор и указатели
                ;   в модели входной индекс 0, 1 либо 29, аппаратные IRQ и нативная торговля не исполняются
                ; -----------------------------------------
                ; -----------------------------------------
                ; Отдельный проход названий товаров
                ; -----------------------------------------
                ; сохранение полного начального индекса в DE до вывода названий
Entry:          EX DE, HL
                ; выбор CursorX=0 и CursorY=32 перед списком названий
                LD HL, @TradeTableConst.StartCursor
                LD (#6320), HL
                ; выбор исходного CR-списка товаров и единиц измерения
                LD HL, @TradeTableText.Names
                ; сохранение полного индекса, выбор названий ниже использует только младший E
                PUSH DE
                LD A, E
                ; поиск выбранного CR-наименования и вывод всего оставшегося текстового списка по размерам окна
                CALL @Station.PrintAfterCR.Entry
                ; возврат Y к первой числовой строке после отдельного прохода названий
                LD A, @TradeTableConst.StartY
                LD (#6321), A
                POP HL
                ; -----------------------------------------
                ; Адреса пар и счётчик начатых строк
                ; -----------------------------------------
                ; расчёт двухбайтового смещения в обоих массивах по полному индексу
                ADD HL, HL
                LD B, H
                LD C, L
                ; поиск рыночной пары StockAndSaleBan, Price по удвоенному индексу
                LD HL, @MarketRows.Row00
                ADD HL, BC
                EX DE, HL
                ; поиск пары количества и цены из колонки Наличие с тем же смещением
                LD HL, @TradeColumnState.OwnedRows
                ADD HL, BC
                ; создание счётчика попыток числовых строк в A', начальное AF'=0044
                XOR A
                EX AF, AF'
                ; -----------------------------------------
                ; Колонки продажи
                ; -----------------------------------------
                ; выбор X количества продажи, выполняется даже перед конечным FF
Row:            LD A, (@TextStreamState.Column2X)
                LD (#6320), A
                ; проверка целого байта FF до отделения старшего разряда рыночного количества
                LD A, (DE)
                INC A
                RET Z                                                           ; выход, если рыночный StockAndSaleBan равен FF, текущую строку не считать

                ; увеличение счётчика до попытки первого числового глифа, отказавшая строка тоже учтена
                EX AF, AF'
                INC A
                EX AF, AF'
                ; восстановление StockAndSaleBan после проверки FF и выделение семибитового количества
                DEC A
                AND @TradeTableConst.QuantityMask
                JR NZ, @Station.DrawTradeNumericColumns.SaleNumber              ; переход, если количество продажи ненулевое, напечатать число

                ; вывод дефиса вместо нулевого количества продажи
                LD A, @SystemNameConst.Dash
                CALL @Station.DrawGlyph.Entry
                JR @Station.DrawTradeNumericColumns.SaleStatus

                ; вывод семибитового количества без ведущих нулей
SaleNumber:     LD C, A
                LD B, #00
                CALL @Station.Print4DigitCore.Entry
SaleStatus:     JR C, @Station.DrawTradeNumericColumns.SaleMark                 ; переход, если вывод количества успешен, обработать его старший разряд

                ; проверка вертикальной причины 1, ширина 3 сама обход не завершает
                DEC A
                RET Z                                                           ; выход, если рисователь количества вернул причину 1, физический Y недопустим

                ; проверка причины 2 после исключения причины 1
                DEC A
                RET Z                                                           ; выход, если рисователь количества вернул причину 2, достигнута высота окна

                ; повторное чтение полного StockAndSaleBan, переход указателя к цене и проверка исходного bit7
SaleMark:       LD A, (DE)
                INC DE
                RLA
                JR NC, @Station.DrawTradeNumericColumns.SalePrice               ; переход, если запрет продажи снят, пропустить глиф FE

                ; выбор фиксированного X=109 для рыночного значка, независимо от Column3X
                LD A, @TradeTableConst.SaleMarkX
                LD (#6320), A
                LD A, @TradeTableConst.MarkGlyph
                ; вывод глифа FE, его отказ не проверяется перед ценой
                CALL @Station.DrawGlyph.Entry
                ; выбор колонки цены продажи
SalePrice:      LD A, (@TextStreamState.Column3X)
                LD (#6320), A
                ; чтение полного байта цены, указатель сразу переводится к следующей рыночной паре
                LD A, (DE)
                INC DE
                LD C, A
                LD B, #00
                ; вывод цены продажи без ведущих нулей
                CALL @Station.Print4DigitCore.Entry
                JR C, @Station.DrawTradeNumericColumns.OwnedCount               ; переход, если цена продажи выведена успешно, перейти к наличию

                ; проверка физического отказа Y для цены продажи
                DEC A
                RET Z                                                           ; выход, если вывод цены продажи вернул причину 1

                ; проверка высоты окна для цены продажи
                DEC A
                RET Z                                                           ; выход, если вывод цены продажи вернул причину 2

                ; -----------------------------------------
                ; Колонки наличия
                ; -----------------------------------------
                ; выбор колонки имеющегося количества
OwnedCount:     LD A, (@TextStreamState.Column4X)
                LD (#6320), A
                ; выделение семибитового количества до исходной проверки INC, FF здесь превращается в 127
                LD A, (HL)
                AND @TradeTableConst.QuantityMask
                INC A
                RET Z                                                           ; выход, если результат INC равен нулю, после AND 7F это условие недостижимо

                ; возврат количества после проверки INC
                DEC A
                JR NZ, @Station.DrawTradeNumericColumns.OwnedNumber             ; переход, если имеющееся количество ненулевое, напечатать число

                ; вывод дефиса вместо нулевого имеющегося количества
                LD A, @SystemNameConst.Dash
                CALL @Station.DrawGlyph.Entry
                JR @Station.DrawTradeNumericColumns.OwnedStatus

                ; вывод имеющегося количества без ведущих нулей
OwnedNumber:    LD C, A
                LD B, #00
                CALL @Station.Print4DigitCore.Entry
OwnedStatus:    JR C, @Station.DrawTradeNumericColumns.OwnedMark                ; переход, если имеющееся количество выведено успешно, проверить его старший разряд

                ; проверка физического отказа Y для имеющегося количества
                DEC A
                RET Z                                                           ; выход, если вывод имеющегося количества вернул причину 1

                ; проверка высоты окна для имеющегося количества
                DEC A
                RET Z                                                           ; выход, если вывод имеющегося количества вернул причину 2

                ; повторное чтение старшего разряда количества, указатель переводится к его цене
OwnedMark:      LD A, (HL)
                INC HL
                RLA
                JR NC, @Station.DrawTradeNumericColumns.OwnedPrice              ; переход, если bit7 имеющегося количества сброшен, пропустить глиф FE

                ; выбор фиксированного X=134 для значка наличия
                LD A, @TradeTableConst.OwnedMarkX
                LD (#6320), A
                LD A, @TradeTableConst.MarkGlyph
                ; вывод глифа FE без проверки его статуса
                CALL @Station.DrawGlyph.Entry
                ; выбор колонки цены имеющегося товара
OwnedPrice:     LD A, (@TextStreamState.Column5X)
                LD (#6320), A
                ; чтение полного байта цены, указатель переводится к следующей паре до печати
                LD C, (HL)
                LD B, #00
                INC HL
                ; вывод цены имеющегося товара без ведущих нулей
                CALL @Station.Print4DigitCore.Entry
                JR C, @Station.DrawTradeNumericColumns.NextRow                  ; переход, если цена наличия выведена успешно, проверить следующую строку

                ; проверка физического отказа Y для цены наличия
                DEC A
                RET Z                                                           ; выход, если вывод цены наличия вернул причину 1

                ; проверка высоты окна для цены наличия
                DEC A
                RET Z                                                           ; выход, если вывод цены наличия вернул причину 2

                ; -----------------------------------------
                ; Принятие следующей строки
                ; -----------------------------------------
                ; чтение высоты перед расчётом Y следующей строки
NextRow:        LD A, (#AEAB)
                LD C, A
                ; расчёт следующего Y с исходным байтовым сложением восьми пикселей
                LD A, (#6321)
                ADD A, @ScreenConst.PixelsPerChar
                ; проверка следующего Y относительно высоты окна
                CP C
                RET NC                                                          ; выход, если следующий Y не меньше высоты, текущий CursorY оставить прежним

                ; обновление CursorY только после принятой проверки высоты
                LD (#6321), A
                JP @Station.DrawTradeNumericColumns.Row

                ; -----------------------------------------
                endmodule
                endmodule
