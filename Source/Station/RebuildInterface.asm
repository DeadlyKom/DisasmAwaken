                module Station
                module RebuildInterface
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [карта владельцев, группировка списка и динамический кадр рисования](../../Docs/RebuildInterface.md)
; -----------------------------------------
; Перестроение станционного интерфейса, изменение порядка, вызов рисователей и восстановление фона
; исходная запись 4, файловые смещения #3C77..#3D24
; In:
;   ActiveItemState.Active задаёт запрет перестроения, при ненулевом значении другие предусловия не используются
;   при нуле банк 0 выбран, CurrentPage согласован с портом, блокировка bit5 снята, выполняется договор BeginScreenUpdate
;   StationState.DrawList и DrawListState.HeadOperand задают один физический список не более 63 указателей с ограничителем старшего байта 1
;   каждая обёртка допускает замену первого байта на RET либо LD HL,nn, индекс в +1,+2 остаётся читаемым
;   индексы принадлежат FInterfaceItem, Flags доступны, 128 байтов копирования от каждой сдвигаемой позиции и двухбайтовый запас доступны вне кода и стека
;   рисователи возвращаются через RET, сохраняют список, его Flags и доступность кода банка 0, CurrentPage=#18 после каждого
;   договоры рисователей определяют их память и рабочие IX/IY, выполняются договоры RestoreBackground и ResumePointer
; Out:
;   при Active ненулевом A=Active, F от OR A, остальные регистры и память сохранены, SP восстановлен
;   при выполненном перестроении HL=#8900, DE=#5800, BC=#D800, AF=#100C
;   HL'=#5B00, DE'=#DB00, B'=#85, C' итоговый атрибут последнего знакоместа, AF' рабочий
;   IX после последнего рисователя, при пустом списке IX=StationState.DrawList, IY согласно рисователям
;   EventEnabled=1 до рисователей, они могут изменить его по собственному договору
;   первые 128 байтов индексной страницы сброшены в #FF до регистрации, карта очищена до рисования
;   элементы заданной группы перенесены в голову, обёртки включены при Hidden=0 и отключены при Hidden ненулевом
;   экран банка 7 содержит начальный снимок, базовый экран содержит новый интерфейс, фон и указатель
;   I и IFF сохраняются только при таком же договоре рисователей, SP восстановлен
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY согласно рисователям
; Note:
;   атрибут равен InkBits OR ROL8(PaperRotate,3) OR ROR8(HighRotate,2), входные значения не маскируются
;   Hidden является операндом LD A по #9CAA, ноль разрешает EnableDrawList после общего DisableDrawList
;   сортировка рассматривает только элементы перед последним, текущий переносится в голову при Flags AND #E0=#40
;   порядок переносимых элементов обращается, последний указатель не проверяется на группу
;   LDDR сдвигает ровно 128 байтов вправо на два, затем LDIR удаляет дубликат и указатель ставится в начало
;   длина списка не вычисляется и не ограничивается кодом, длинный список может потерять ограничитель
;   FRebuildDrawFrame содержит AfterDraw и NextPointer, RET рисователя не является возвратом всей процедуры
;   AfterDraw снимает NextPointer и продолжает чтение списка, общий стек сохраняет возврат вызывающей стороны
;   модель исполняет настоящий банковый цикл, рисователи в ней синтетические и не доказывают все игровые окна
; -----------------------------------------
                ; чтение признака активного элемента, запрещающего полное перестроение
Entry:          LD A, (@ActiveItemState.Active)
                ; проверка запрета до любых изменений экрана и таблиц
                OR A
                RET NZ                                                          ; выход, если активный элемент запрещает перестроение, сохранить интерфейс

                ; снимок текущего экрана и снятие указателя перед новой сценой
                CALL @Station.BeginScreenUpdate.Entry
                ; чтение младшей цветовой составляющей без ограничения разрядов
                LD A, (@InterfaceColors.InkBits + FSettingWord.ValueOrRow)
                LD C, A
                ; чтение составляющей, переносимой вращением в разряды PAPER
                LD A, (@InterfaceColors.PaperRotate + FSettingWord.ValueOrRow)
                ; расчёт трёхбитового вращения PaperRotate, старшие биты возвращаются в младшие
                RLCA
                RLCA
                RLCA
                ; объединение вращённой составляющей с InkBits
                OR C
                LD C, A
                ; чтение старшей цветовой составляющей
                LD A, (@InterfaceColors.HighRotate + FSettingWord.ValueOrRow)
                ; расчёт двухбитового вращения HighRotate вправо
                RRCA
                RRCA
                ; расчёт итогового атрибута через OR трёх немаскированных байтов
                OR C
                ; обновление операнда атрибута действительных ячеек RestoreBackground
                LD (@BackgroundState.ItemAttribute), A
                ; разрешение событий перед вызовами рисователей новой сцены
                LD A, #01
                LD (@InterfaceState.EventEnabled), A
                ; очистка 768 владельцев перед повторной регистрацией элементов
                CALL @Station.ClearWorkspace.Entry
                ; сброс только первых 64 индексных пар в исходной странице
                CALL @Station.ResetIndexTable.Entry
                ; выбор физического списка всех изменяемых обёрток
                LD HL, @StationState.DrawList
                ; отключение всех обёрток записью первого байта RET
                CALL @Station.DisableDrawList.Entry
                ; восстановление начала списка после обхода отключения
                LD HL, @StationState.DrawList
                ; сохранение начала списка вокруг условного включения
                PUSH HL
                ; чтение операнда Hidden, заданного командой скрытия либо диспетчером
                LD A, #00
                ; проверка разрешения рисователей по нулевому Hidden
                AND A
                CALL Z, @Station.EnableDrawList.Entry                           ; вызов, если Hidden равен нулю, восстановить LD HL,nn во всех обёртках
                ; восстановление начала списка после изменения кодов обёрток
                POP HL
                ; сохранение начала списка до окончания группировки
                PUSH HL
                ; создание указателя обхода IX без изменения сохранённого начала
                PUSH HL
                POP IX
                ; выбор адресной базы для Flags по шестнадцатибайтовому индексу
                LD BC, @StationState.Items + FInterfaceItem.Flags
                ; выбор старшего байта ограничителя списка
                LD A, #01
                ; проверка пустого списка до чтения первой обёртки
                CP (IX + FDrawListEntry.Handler + 1)
                JR Z, @Station.RebuildInterface.StartDrawing                    ; переход, если список сразу ограничен, начать завершающий проход рисования

                ; выбор ограничителя для проверки следующего указателя
NextGroup:      LD A, #01
                ; проверка следующей пары, последний элемент сортировкой не рассматривается
                CP (IX + FDrawListEntry + FDrawListEntry.Handler + 1)
                JR Z, @Station.RebuildInterface.StartDrawing                    ; переход, если следующая пара ограничивает список, закончить группировку

                ; чтение текущей обёртки и её непосредственного индекса
                LD H, (IX + FDrawListEntry.Handler + 1)
                LD L, (IX + FDrawListEntry.Handler)
                INC HL
                LD A, (HL)
                INC HL
                LD H, (HL)
                LD L, A
                ; расчёт шестнадцатибайтового смещения записи элемента
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ; расчёт адреса Flags добавлением исходной базы полей
                ADD HL, BC
                ; чтение Flags текущего элемента
                LD A, (HL)
                ; выделение старшего трёхбитового поля группы
                AND @InterfaceFlags.GroupMask
                ; проверка группы #40, требующей переноса в голову
                CP @InterfaceFlags.FrontGroup
                ; переход IX к следующей паре, при сдвиге списка прежняя запись снова окажется перед ним
                INC IX
                INC IX
                JR NZ, @Station.RebuildInterface.NextGroup                      ; переход, если группа не равна #40, продолжить без перестановки

                ; сохранение базы Flags вокруг двух физических сдвигов
                PUSH BC
                ; чтение начала списка из операнда HeadOperand
                LD HL, (@DrawListState.HeadOperand)
                ; расчёт последнего из 128 сдвигаемых байтов
                LD BC, #007F
                ADD HL, BC
                ; расчёт конечного адреса назначения на два байта правее
                LD D, H
                LD E, L
                INC DE
                INC DE
                ; выбор ровно 128 байтов, длина списка здесь не вычисляется
                LD BC, #0080
                ; сдвиг списка вправо на одну пару, исходный порядок копирования предотвращает затирание
                LDDR
                ; чтение переносимой обёртки после сдвига, она находится по IX
                LD C, (IX + FDrawListEntry.Handler)
                LD B, (IX + FDrawListEntry.Handler + 1)
                ; сохранение выбранного указателя на время удаления его дубликата
                PUSH BC
                ; выбор адреса удаляемого дубликата через IX
                PUSH IX
                POP HL
                LD D, H
                LD E, L
                ; расчёт источника удаления на одну пару дальше
                INC HL
                INC HL
                ; выбор исходного фиксированного размера удаления 128 байтов
                LD BC, #0080
                ; сдвиг остатка влево поверх выбранного указателя
                LDIR
                ; возврат к голове списка для записи выбранного обработчика
                LD HL, (@DrawListState.HeadOperand)
                ; восстановление выбранной пары со стека
                POP BC
                ; обновление первого указателя обработчиком переносимой группы
                LD (HL), C
                INC HL
                LD (HL), B
                ; восстановление исходной базы Flags для продолжения обхода
                POP BC
                JP @Station.RebuildInterface.NextGroup

                ; восстановление сохранённого начала после группировки
StartDrawing:   POP HL
                ; чтение очередного указателя для косвенного вызова рисователя
NextDraw:       LD E, (HL)
                INC HL
                LD A, (HL)
                ; проверка старшего байта указателя на ограничитель 1
                DEC A
                JP Z, @Station.RestoreBackground.Entry                          ; переход, если список рисования завершён, восстановить фон и закончить экранный цикл

                ; восстановление старшего байта адреса обработчика после проверки ограничителя
                INC A
                INC HL
                LD D, A
                ; создание FRebuildDrawFrame.NextPointer для возврата к следующему указателю
                PUSH HL
                ; выбор локального продолжения после RET рисователя
                LD HL, @Station.RebuildInterface.AfterDraw
                ; создание FRebuildDrawFrame.AfterDraw вместо обычного CALL
                PUSH HL
                ; передача адреса обработчика в HL для косвенного перехода
                EX DE, HL
                JP (HL)

                ; снятие NextPointer после возврата рисователя в AfterDraw
AfterDraw:      POP HL
                JP @Station.RebuildInterface.NextDraw

                endmodule
                endmodule
