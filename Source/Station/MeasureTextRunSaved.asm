                module Station
                module MeasureTextRunSaved
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [Font.md](../../Docs/Font.md)
; -----------------------------------------
; Измерение пиксельной ширины текста до CR, LF или разделителя B с сохранением HL
; исходная запись 4, файловые смещения #5DCA..#5DEF
; In:
;   HL - начало читаемого текста, BC - B дополнительный однобайтовый разделитель
;   FontConst.WidthPage - таблица ширины, текст достигает ограничителя или условия насыщения
; Out:
;   HL сохранён, AF - A измеренная ширина либо #FF, правила ограничителей, насыщения и полного F совпадают с MeasureTextRun
; Corrupt:
;   AF
; Note:
;   внутренний указатель увеличивается до проверки суммы, но исходный HL всегда восстанавливается с CPU-стека
;   DE, BC, альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   нулевой код ограничивает текст только при B=0, CR и LF проверяются независимо от B
;   значение A=#FF само по себе не различает принятую ширину 255 и насыщение, условие определяется выполненным путём
; -----------------------------------------
Entry:          PUSH HL
                PUSH DE
                PUSH BC
                ; обнуление накопленной ширины с сохранением исходного указателя на стеке
                LD C, #00
                LD D, @FontConst.WidthPage
NextChar:       LD A, (HL)
                ; проверка безусловного ограничителя CR
                CP @TextConst.CarriageReturn
                JR Z, @Station.MeasureTextRunSaved.ReturnWidth                  ; переход, если найден CR, возвращается накопленная ширина

                ; проверка безусловного ограничителя LF
                CP @TextConst.LineFeed
                JR Z, @Station.MeasureTextRunSaved.ReturnWidth                  ; переход, если найден LF, возвращается накопленная ширина

                ; проверка дополнительного разделителя из B
                CP B
                JR Z, @Station.MeasureTextRunSaved.ReturnWidth                  ; переход, если символ равен разделителю B, измерение завершается

                ; выбор ширины по коду символа, внутренний указатель продвигается до проверки суммы
                LD E, A
                INC HL
                LD A, (DE)
                ; расчёт новой суммарной ширины перед проверкой насыщения
                ADD A, C
                JR C, @Station.MeasureTextRunSaved.Saturate                     ; переход, если сумма ширин превысила 255, возвращается #FF

                JR Z, @Station.MeasureTextRunSaved.Saturate                     ; переход, если байтовая сумма равна нулю, выбирается исходное насыщение #FF

                LD C, A
                JP @Station.MeasureTextRunSaved.NextChar

                ; выбор насыщенной ширины, исходный HL затем восстановится со стека
Saturate:       LD C, #FF
                ; возврат ширины без изменения флагов последней проверки
ReturnWidth:    LD A, C
                POP BC
                POP DE
                POP HL
                RET

                endmodule
                endmodule
