                module Station
                module MoveItemToTail
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [физический сдвиг и порядок обработчиков](../../Docs/MoveDrawItem.md)
; -----------------------------------------
; Поиск обработчика по индексу, перенос к концу списка либо добавление новой обёртки
; исходная запись 4, файловые смещения #5E38..#5E90
; In:
;   HL - указатель новой обёртки, используемой только если совпадение индекса не найдено
;   DE - искомое шестнадцатибитное слово индекса, читаемое из операндов обёрток по адресу Handler+1
;   DrawListState.HeadOperand содержит базу читаемого и записываемого списка FDrawListEntry с ограничителем старшего байта 1
;   за удаляемой записью доступны 128 байтов для чтения и записи сдвига, в конце есть место для указателя и #0101
;   для обычного переноса после найденной записи остаётся не больше 63 других указателей
; Out:
;   HL - найденный существующий обработчик либо исходный указатель новой обёртки
;   DE и BC восстановлены, AF - при добавлении A=1,F=0
;   при совпадении A равно числу указателей после позиции найденного элемента в физически сдвинутом списке по модулю 256
;   при совпадении F соответствует DEC предыдущего байтового счётчика, Carry=0, N=1
;   выбранный указатель записан перед новым ограничителем #0101, предыдущие хвостовые байты меняются исходным LDIR
; Corrupt:
;   HL, AF
; Note:
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   при совпадении копируются ровно 128 байтов из следующей записи на место найденной, длина до ограничителя не вычисляется
;   при 64 и более оставшихся записях ограничитель может не попасть в сдвиг, возникают дубли и изменённая длина списка
;   при отсутствии совпадения список расширяется новой обёрткой, она сама и её слово индекса не меняются
;   первый байт обёртки не проверяется, индекс читается и у временно отключённого RET
;   FDrawMoveFrame содержит Candidate, SavedBC, SavedDE и ReturnAddress, FDrawShiftFrame добавлен только на время LDIR
;   при совпадении первый POP BC отбрасывает Candidate, второй восстанавливает SavedBC, это не лишняя инструкция
;   нет проверки корректности указателя либо свободного места, вмешательство IRQ моделью не подтверждено
; -----------------------------------------
                ; создание FDrawMoveFrame.SavedDE из искомого индекса
Entry:          PUSH DE
                ; сохранение FDrawMoveFrame.SavedBC
                PUSH BC
                ; сохранение указателя новой обёртки в FDrawMoveFrame.Candidate
                PUSH HL
                ; чтение базы текущего списка из изменяемого операнда RebuildInterface
                LD HL, (@DrawListState.HeadOperand)
                ; чтение указателя очередной записи FDrawListEntry
FindKey:        LD C, (HL)
                INC HL
                LD B, (HL)
                ; проверка старшего байта указателя на ограничитель 1
                DEC B
                JR Z, @Station.MoveItemToTail.Append                            ; переход, если достигнут ограничитель без совпадения, добавить новую обёртку

                INC B
                INC HL
                ; переход к младшему байту изменяемого индекса Handler+1
                INC BC
                LD A, (BC)
                ; проверка младшего байта искомого индекса
                CP E
                JP NZ, @Station.MoveItemToTail.FindKey                          ; переход, если младший байт индекса не совпадает, проверить следующую запись

                ; чтение и проверка старшего байта индекса Handler+2
                INC BC
                LD A, (BC)
                CP D
                JP NZ, @Station.MoveItemToTail.FindKey                          ; переход, если старший байт индекса не совпадает, поиск продолжается

                ; возврат от слова индекса к началу найденной обёртки
                DEC BC
                DEC BC
                ; сохранение NextEntry, SearchKey и FoundHandler в FDrawShiftFrame
                PUSH HL
                PUSH DE
                PUSH BC
                ; расчёт адреса найденной записи как следующая запись минус два байта
                LD D, H
                LD E, L
                DEC DE
                DEC DE
                ; выбор фиксированной длины сдвига 128 байтов, ограничитель не определяет эту длину
                LD BC, @DrawListLimit.ShiftBytes
                ; сдвиг физических байтов списка на одну запись влево, включая байты за его ограничителем
                LDIR
                ; восстановление трёх слов FDrawShiftFrame после копирования
                POP BC
                POP DE
                POP HL
                DEC HL
                DEC HL
                ; обнуление байтового счётчика перед повторным поиском конца сдвинутого списка
                XOR A
                ; поиск ограничителя по старшим байтам указателей после физического сдвига
FindEnd:        INC HL
                LD E, (HL)
                INC HL
                INC A
                DEC E
                JP NZ, @Station.MoveItemToTail.FindEnd                          ; переход, если прочитанный старший байт не равен 1, продолжить поиск конца

                ; исключение ограничителя из счётчика и создание нового ограничителя за добавляемым указателем
                DEC A
                LD (HL), @DrawListLimit.EndByte
                INC HL
                LD (HL), @DrawListLimit.EndByte
                DEC HL
                DEC HL
                ; запись найденного обработчика на место старого ограничителя
                LD (HL), B
                DEC HL
                LD (HL), C
                LD H, B
                LD L, C
                ; удаление Candidate, найденный обработчик уже выбран вместо новой обёртки
                POP BC
                ; восстановление SavedBC и SavedDE перед возвратом выбранного HL
                POP BC
                POP DE
                RET

                ; получение Candidate из кадра для добавления новой записи
Append:         POP BC
                ; запись старшего и младшего байтов новой обёртки вместо ограничителя
                LD (HL), B
                DEC HL
                LD (HL), C
                INC HL
                INC HL
                ; создание фиксированного ограничителя #0101 после новой записи
                LD (HL), @DrawListLimit.EndByte
                INC HL
                LD (HL), @DrawListLimit.EndByte
                LD H, B
                LD L, C
                POP BC
                POP DE
                ; формирование статуса добавления AF=#0100 без признака прежнего совпадения
                XOR A
                INC A
                RET

                endmodule
                endmodule
