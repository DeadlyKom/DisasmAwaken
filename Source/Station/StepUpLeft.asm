                module Station
                module StepUpLeft
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [опрос, накопление и таблица направлений](../../Docs/PointerInputs.md)
                ; -----------------------------------------
                ; Ограниченный шаг указателя влево и вверх
                ; исходная запись 4, файловые смещения #09BA..#09C7
                ; In:
                ;   DE - верхний предел Y в D и неотрицательный байтовый шаг в E, BC - исходные X в C,Y в B
                ; Out:
                ;   HL сохраняется
                ;   DE сохранён, BC - координаты после шага влево и вверх, AF рабочий
                ; Corrupt:
                ;   BC, AF, R
                ; Note:
                ;   договор шага заканчивается на адресе, снятом RET, при CommitPointerInput затем записывается PointerXY
                ;   собственных записей RAM и CPU-стека у шага нет
                ;   уменьшение оси ограничивается нулём при займе, увеличение X ограничивается пределом при переносе либо результате не ниже предела
                ;   увеличение Y сравнивает только байтовую сумму с D, переполнение суммы не проверяется
                ;   для штатных E=2,D=191 и Y=0..191 байтового переполнения положительного Y нет
                ;   память, индексные и альтернативные регистры, I и IFF сохраняются, SP восстанавливается обычным RET
                ;   флаги зависят от последней выполненной арифметики, единого признака фактического движения нет
                ; -----------------------------------------
                ; расчёт уменьшенного X перед шагом вверх
Entry:          LD A, C
                SUB E
                JP NC, @Station.StepUpLeft.StoreX                               ; переход, если уменьшение X не дало займа, сохранить вычисленный X

                XOR A
StoreX:         LD C, A
                ; расчёт уменьшенного Y после шага влево
                LD A, B
                SUB E
                LD B, A
                RET NC                                                          ; выход, если уменьшение Y не дало займа, сохранить вычисленный Y

                LD B, #00
                RET

                endmodule
                endmodule
