                module Station
                module CopyWindowIcon
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [иконка, внутреннее тело и заимствованный стек](../../Docs/WindowGraphics.md)
; -----------------------------------------
; Копирование 128 байтов иконки в 32 экранные строки по таблицам адресации
; исходная запись 4, файловые смещения #4020..#405A
; In:
;   HL - начало читаемых 128 байтов иконки, BC - произвольный счётчик, после переноса уменьшается на 128
;   TextWindow настроено SetupInsetTextWindow для неотрицательного начала элемента X=0..27,Y=0..19
;   таблицы #8200,#8300,#8400 подготовлены исходным построителем, стек и источник не пересекают изменяемый экран
; Out:
;   HL увеличен на 128, BC=(входной BC-128) AND #FFFF, AF=#0042, AF' рабочий
;   при X=0..26 скопированы четыре байта каждой из 32 строк от знакоместа X+1,Y+1
;   при X=27 возможен дополнительный рост D из-за переноса четырёх LDI, в том числе запись в атрибуты, это исходное поведение
;   DE - физический адрес после последнего собственного перехода строки, альтернативные HL,DE,BC и индексные регистры сохранены
; Corrupt:
;   HL, DE, BC, AF, AF'
; Note:
;   первоначальный PUSH HL сохраняет источник только на время расчёта адреса, затем POP HL возвращает его до копирования
;   начало пикселей равно OriginXLow+5,OriginYLow+5, для внутреннего окна это знакоместо X+1,Y+1
;   четыре LDI переносят строку, после них E восстанавливается из A, затем D увеличивается
;   перенос младшего байта DE внутри LDI не отменяется восстановлением E, поэтому последний четырёхбайтовый блок знакомест может дать двойное увеличение D
;   счётчик 32 хранится через обмен AF,AF', флаги LDI не управляют числом строк
;   границы модели X=0..27,Y=0..19 включают правый граничный дефект, за ними корректность не заявляется
;   I и IFF сохраняются, SP восстанавливается, прерывания должны сохранять используемые регистры
; -----------------------------------------
                ; сохранение источника иконки на время расчёта экранного адреса
Entry:          PUSH HL
                ; расчёт строки начала иконки с отступом 5 от внутреннего начала Y
                LD A, (@TextWindow.OriginYLow)
                ADD A, #05
                LD L, A
                ; расчёт колонки начала иконки с отступом 5 от внутреннего начала X
                LD A, (@TextWindow.OriginXLow)
                ADD A, #05
                LD E, A
                ; поиск старшего и младшего экранного адреса в исходных таблицах строк и колонок
                LD H, #82
                LD D, (HL)
                INC H
                LD A, (HL)
                INC H
                LD L, E
                ; расчёт младшего адреса первой строки как сумма строки и колонки
                ADD A, (HL)
                LD E, A
                ; возврат источника после окончания расчёта назначения
                POP HL
                ; создание отдельного счётчика 32 строк, далее он сохраняется обменом AF,AF'
                LD A, #20
                ; сохранение счётчика и выбор рабочего AF для переноса одной строки
CopyRow:        EX AF, AF'
                ; сохранение младшего адреса начала строки до четырёх LDI
                LD A, E
                ; перенос четырёх последовательных байтов, возможный перенос DE через #FF не отменяется
                LDI
                LDI
                LDI
                LDI
                ; возврат младшего адреса и переход к следующей пиксельной строке через увеличение D
                LD E, A
                INC D
                ; проверка границы восьмистрочного знакоместа по младшим трём разрядам D
                LD A, D
                AND #07
                JP NZ, @Station.CopyWindowIcon.CountRow                         ; переход, если D ещё не достиг границы знакоместа, продолжить счёт строк

                ; расчёт перехода младшего адреса к следующей строке знакомест
                LD A, E
                ADD A, #20
                LD E, A
                JR C, @Station.CopyWindowIcon.CountRow                          ; переход, если E+32 дало перенос, сохранить уже увеличенный старший адрес

                ; расчёт коррекции старшего адреса на минус восемь при переносе знакоместа без переполнения E
                LD A, D
                SUB #08
                LD D, A
                ; возврат отдельного счётчика строк из альтернативного AF
CountRow:       EX AF, AF'
                ; расчёт оставшегося числа строк иконки
                DEC A
                JP NZ, @Station.CopyWindowIcon.CopyRow                          ; переход, если скопированы ещё не все 32 строки, обработать следующую строку

                RET

                endmodule
                endmodule
