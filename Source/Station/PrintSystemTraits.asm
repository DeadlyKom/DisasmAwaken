                module Station
                module PrintSystemTraits
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [коды DescribeKey, исходные русские строки, относительные позиции и сохранность регистров](../../Docs/SystemTraits.md)
; -----------------------------------------
; Вывод строя, типа экономики и уровня либо двух дефисов для необитаемой и неизвестной системы
; исходная запись 4, файловые смещения #43A1..#43FE
; In:
;   HL - H код строя 0..4, L числовой уровень 1..16 из DescribeKey, DE - E код экономики 0..3, D сохраняемый контекст
;   TextWindow задаёт место первой строки строя, действуют договоры PrintAfterLF, DrawGlyph и PrintWord
;   банк станции 0 и исходные LF-списки EB8D и EBC2 доступны, для обычного полного вывода все три строки и их глифы помещаются
; Out:
;   H=0,1,2 выводят Демократия, Диктатура, Анархия, следующая строка содержит название экономики, последняя десятичный L
;   H=3 выводит Необитаемая, H=4 Неизвестный, в обеих ветвях следующие строки содержат дефисы вместо экономики и уровня
;   следующая строка смещена вниз на 8 от фактического CursorY после предыдущей печати, Y оборачивается по байту
;   X второй строки равен 16 для дефиса либо 18 для экономики, X последней строки всегда 34
;   при полном успешном выводе HL=(начальный CursorY+16)*256+34, DE сохранён, BC сохранён в ветви дефисов и равен 10 в числовой ветви
;   при таком выводе AF=0045, конечный CursorY вырос на 16, CursorX продвинут на ширину последнего дефиса либо десятичных глифов
;   при отказах возвращается статус последней попытки глифа, ранние отказы не прерывают последующие строки, точный курсор зависит от договоров печатателей
;   все альтернативные и индексные регистры, I и IFF сохраняются, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, BC только в числовой ветви, AF, курсор, bitmap и изменяемые операнды печатателей
; Note:
;   D, старые BC, L и E не определяют выбор ветви дефисов, проверяется только H
;   сам помощник не сохраняет и не восстанавливает TextWindow.Style, обычный DrawItem19 перед ним устанавливает ноль
;   коды вне H=0..4 и E=0..3 не проверяются оригиналом, их нельзя объявлять дополнительными известными значениями
;   модель проверила 960 комбинаций с реальными печатателями и независимым XOR всех глифов, переносы и отказы отдельно принадлежат их договорам
; -----------------------------------------
                ; проверка внешней области H=4, для неё читается исходная строка Неизвестный
Entry:          LD A, H
                CP #04
                JR NZ, @Station.PrintSystemTraits.CheckHabited                  ; переход, если H не равен коду неизвестной системы, проверить необитаемую ветвь

                LD A, #04
                ; выбор LF-записи строя с последующим выводом двух дефисов
PrintNoTraits:  LD HL, @SystemTraitsText.GovernmentList
                CALL @Station.PrintAfterLF.Entry
                ; расчёт следующей строки от фактического CursorY и позиции X=16 для дефиса экономики
                LD A, (@TextWindow.CursorY)
                ADD A, #08
                LD H, A
                LD L, #10
                LD (@TextWindow.CursorX), HL
                ; вывод дефиса вместо типа экономики, значение E в этой ветви не используется
                LD A, #2D
                CALL @Station.DrawGlyph.Entry
                ; расчёт следующей строки и позиции X=34 для дефиса уровня
                LD A, (@TextWindow.CursorY)
                ADD A, #08
                LD H, A
                LD L, #22
                LD (@TextWindow.CursorX), HL
                ; вывод дефиса вместо числового уровня, прежнее значение L здесь не печатается
                LD A, #2D
                CALL @Station.DrawGlyph.Entry
                RET

                ; проверка кода необитаемой системы H=3, остальные допустимые коды имеют экономику и уровень
CheckHabited:   CP #03
                JR Z, @Station.PrintSystemTraits.PrintNoTraits                  ; переход, если H равен коду необитаемой системы, вывести её название и два дефиса

                ; сохранение исходного уровня L на стеке на время двух строк текста
                PUSH HL
                ; выбор исходной LF-строки строя по коду H
                LD HL, @SystemTraitsText.GovernmentList
                CALL @Station.PrintAfterLF.Entry
                ; расчёт строки экономики на восемь пикселей ниже и позиции X=18
                LD A, (@TextWindow.CursorY)
                ADD A, #08
                LD H, A
                LD L, #12
                LD (@TextWindow.CursorX), HL
                ; выбор исходной LF-строки экономики по коду E
                LD A, E
                LD HL, @SystemTraitsText.EconomyList
                CALL @Station.PrintAfterLF.Entry
                ; перенос сохранённого уровня L в C без возврата первоначальных HL
                POP BC
                ; расчёт строки уровня на восемь пикселей ниже экономики и позиции X=34
                LD A, (@TextWindow.CursorY)
                ADD A, #08
                LD H, A
                LD L, #22
                LD (@TextWindow.CursorX), HL
                ; расширение исходного уровня до BC и выбор десятичного вывода без дополнительных нулей
                LD B, #00
                XOR A
                CALL @Station.PrintWord.Entry
                RET

                endmodule
                endmodule
