                module Station
                module EndScreenUpdate
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [два физических экрана и указатель](../../Docs/ScreenUpdate.md)
; -----------------------------------------
; Возобновление указателя и переключение отображения на обновлённый базовый экран
; исходная запись 4, файловые смещения #4496..#449E
; In:
;   HL, DE, BC - сохраняемый контекст, AF - исходный F сохраняется
;   обычный Entry продолжает BeginScreenUpdate, базовый экран обновлён, окно станционного банка 0 выбрано
;   для Entry выполняются предусловия ResumePointer, ShowBase по A499 обходит этот вызов, аппаратная блокировка #7FFD.bit5 снята
;   стек и выполняемый код доступны после выбора банка 0
; Out:
;   HL, DE и BC сохранены, A=#10, F исходный, AF' рабочий согласно ResumePointer
;   у Entry указатель возобновлён на базовом экране, UpdateBlocked=0, показан экран банка 5
;   ShowBase сохраняет весь AF', состояние указателя и UpdateBlocked, экраны не перерисовываются
;   CurrentPage=#10, окно #C000 выбирает банк 0, старый снимок банка 7 сохраняется
; Corrupt:
;   AF, AF'
; Note:
;   HL', DE', BC', IX, IY, I и IFF сохраняются, SP восстанавливается
;   у Entry ResumePointer выполняется до OUT=#10, поэтому указатель рисуется до переключения видимого экрана
;   вызов не восстанавливает произвольную прежнюю конфигурацию #7FFD
;   проверка восьми банков использует нулевого владельца указателя, ненулевые владельцы проверены отдельной моделью Pointer
;   ShowBase отдельно проверен для 32 начальных конфигураций порта и всех 256 F без подмены SelectMemoryPage
;   дополнительный вход ShowBase найден через [действия интерфейса](../../Docs/StationEventActions.md)
; -----------------------------------------
                ; возобновление указателя на уже обновлённом базовом экране до его показа
Entry:          CALL @Station.ResumePointer.Entry
                ; выбор базового экрана банка 5, окна банка 0 и ROM 1
ShowBase:       LD A, @ScreenUpdateConst.VisiblePage
                CALL @Station.SelectMemoryPage.Entry
                RET

                endmodule
                endmodule
