                ; Подробный разбор [точный пустой путь наведения, отделённый от действия и рисования 3D](../../Docs/PreviewHover.md)
                ; -----------------------------------------
                ; Пустой вход наведения панели 3D-просмотра с хвостовым переходом к возврату
                ; исходная запись 4, файловые смещения #0AE3..#0AE5
                ; In:
                ;   CPU-стек содержит допустимый адрес возврата, значения регистров данных произвольны
                ; Out:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, I, IFF и IM сохранены
                ;   память и порты не записываются, обычный возврат снимает исходный адрес, SP равен входному SP+2
                ; Corrupt:
                ;   логических изменений регистров данных нет
                ; Note:
                ;   путь 6837 содержит только JP 686F, новый адрес возврата не создаётся, 686F содержит только RET
                ;   код действия по EventHandler+3 расположен отдельно по 683A, наведение в него не переходит
                ;   аппаратный счётчик R меняется при выборках инструкций, он не включён в сохранённый контекст
                ;   это полный разбор пустого пути, алгоритмы действия, DrawItem26 и кадра D3D этим договором не закрываются
                ; -----------------------------------------
                ; передача в пустой возврат наведения без нового кадра стека
Entry:          JP @Station.ReturnModelPreviewHover.Entry

                endmodule
