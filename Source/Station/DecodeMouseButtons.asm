                module DecodeMouseButtons
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [настройка кнопок и аппаратные счётчики](../../Docs/MouseInput.md)
; -----------------------------------------
; Преобразование двух младших кнопок в выбранные настройкой байты действия
; исходная запись 4, файловые смещения #0875..#087E
; In:
;   IX - база MouseInput.State, на стеке FMousePollFrame.SavedIX и ReturnAddress
;   байты PreviousX,PreviousY содержат прежние показания, PointerXY содержит исходные пиксельные координаты
;   AF - A инвертированный байт кнопок после CPL, Carry от IN, флаги семи входов первоначально нулевые
; Out:
;   HL - итоговые пиксельные X в L и Y в H, DE - прежние аппаратные счётчики X в E и Y в D, BC=#FFDF
;   AF - рабочий результат последней ветви Y, единого флага наличия движения нет
;   StationState.PointerXY и PreviousX,PreviousY обновлены, ненулевые разности устанавливают соответствующий байт направления в 1
;   IX восстановлен из FMousePollFrame, IY, альтернативные регистры, I и IFF сохраняются, SP возвращается за адрес вызова
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   первый RRA переносит бит 0 в Carry, RL записывает его в выбранный байт Action2 либо Action1
;   второй RRA использует следующий бит исходного A, RL пишет другой байт действия
;   установленные настройкой смещения являются частью инструкций DD CB displacement 16
;   разность X равна signed8(newX-oldX), разность Y равна signed8(-(newY-oldY)), каждая умножается на два
;   при отрицательной разности применяется max(0,old+2*delta), при положительной min(limit,old+2*delta)
;   limit равен 254 для X и 191 для Y, нулевая разность не нормализует исходную координату
;   отрицательная ветвь не ограничивает сверху, при исходном Y>191 результат может остаться вне экрана
;   байты направлений не очищаются этим продолжением, полный PollMouse очищает семь флагов до чтения портов
;   чтение Y выполняется даже при нулевой разности X, старые оба счётчика загружаются до первого чтения
;   модель задаёт байты трёх портов, реальное устройство и вызов из ISR не проверены
; -----------------------------------------
                ; выделение бита 0 инвертированной выборки в Carry для первого действия
Entry:          RRA
                ; запись Carry в нулевой байт действия через настроенное смещение IX
                RL (IX + FMouseInput.Action2)
                ; выделение следующего бита исходной выборки для второго действия
                RRA
                RL (IX + FMouseInput.Action1)
                ; JP @Station.DecodeThirdButton.Entry, продолжение в DecodeThirdButton.asm

                endmodule
                endmodule
