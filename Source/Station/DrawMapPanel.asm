                module Station
                module DrawMapPanel
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [размеры внутренней области, три запроса, paging и два уровня проверки](../../Docs/MapPanel.md)
; -----------------------------------------
; Рисование полосовой рамки карты, установка трёх запросов и последовательный вход содержимого
; исходная запись 4, файловые смещения #1054..#106D
; In:
;   MapPanelState.ItemIndex является изменяемым индексом FInterfaceItem панели карты, банк станции 0 выбран
;   действуют условия DrawCaptionItem и SetBandFillMode, допустимая рамка Width=2..32,Height=3..24 помещается на экран
;   для успешного содержимого действуют условия DrawMapPanelContents, внешняя защита указателя и договоры HALT обеспечиваются вызывающим окружением
; Out:
;   рамка и заголовок нарисованы в выбранном FillMode, шесть изменяемых слов рамки затем восстановлены в обычное состояние
;   все три запроса ScreenRequest,SectorRequest,ClipRequest установлены в 1 перед последовательным входом DrawMapPanelContents
;   при отказе проверки содержимого все три остаются единицами, рамка к этому моменту уже нарисована
;   при успешном содержимом ScreenRequest и ClipRequest сброшены, SectorRequest=1, итоговый bitmap содержит рамку и слои C000
;   HL, DE, BC, AF, альтернативные пары и IX соответствуют содержимому после рисунка заголовка, IY сохраняется при договоре HALT, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, bitmap, текстовое окно, регистрация, три запроса и таблицы
; Note:
;   переход в содержимое выполняется настоящим JP и не создаёт дополнительного адреса возврата
;   в обычном успешном вызове есть HALT полосовой рамки и отдельный HALT C000, при отказе содержимого исполняется только первый
;   проверка геометрии содержимого не отменяет предыдущую регистрацию и рисунок заголовка
; -----------------------------------------
                ; чтение исходного изменяемого индекса рамки основной панели
Entry:          LD HL, #0000
                ; настройка полосовой рамки по текущему FillMode
                CALL @Station.SetBandFillMode.Entry
                ; рисование заголовка и рамки перед любыми изменениями содержимого карты
                CALL @Station.DrawCaptionItem.Entry
                ; восстановление обычных операндов рамки после текущего рисунка
                CALL @Station.ResetBandMode.Entry
                ; установка всех трёх запросов обновления для следующего прохода содержимого
                LD A, #01
                LD (@MapPanelState.SectorRequest), A
                LD (@MapPanelState.ScreenRequest), A
                LD (@MapPanelState.ClipRequest), A
                ; передача в общий проход содержимого без дополнительного CALL
                JP @Station.DrawMapPanelContents.Entry

                endmodule
                endmodule
