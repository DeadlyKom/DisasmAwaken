                module Station
                module DrawTradePanel
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [зависимость подсветки от рисунка, событие колонки, банковый запуск и дополнительные входы рисователя](../../Docs/TradePanel.md)
                ; -----------------------------------------
                ; Рамка и торговые колонки с сохранением числа начатых строк в операнде подсветки
                ; исходная запись 4, файловые смещения #131D..#1341
                ; In:
                ;   Entry - Opcode равен 21 для обычного рисования либо C9 для отключённого входа, ItemIndex настроен загрузчиком
                ;   при активном Entry действуют DrawCaptionItem, SetMarketTextColumns и исходная таблица заголовка EBF3
                ;   ScriptSelection.CargoBase содержит слово начального индекса, действуют DrawTradeNumericColumns и текстовые договоры
                ;   DrawColumns - дополнительный вход 708E получает HL начального индекса и уже настроенное окно, рамка и заголовок здесь не рисуются
                ;   FinishCounts - общий вход 7091 получает AF' с числом начатых строк и его флагами, основной AF сохраняется в AF' при обмене
                ;   на путях с рамкой пробуждение HALT сохраняет контекст, код и операнды подсветки доступны для записи
                ; Out:
                ;   отключённый Entry C9 сохраняет регистры, память, выбор и счётчик, SP равен входному SP+2
                ;   активный Entry регистрирует и рисует рамку, сбрасывает CargoRow=FF, выбирает Style=0 и торговые колонки
                ;   после PrintText заголовка AF'=0044, флаги заголовка сохранены в основном AF для проверки Carry
                ;   при Carry заголовка числовая часть пропущена, в противном случае HL получает CargoBase и исполняется DrawColumns
                ;   DrawColumns вызывает DrawTradeNumericColumns без повторного рисунка рамки и заголовка
                ;   FinishCounts возвращает основной AF прежнего AF', A число начатых строк, и записывает этот A в HoverRows
                ;   на пропуске чисел AF=0044, HoverRows=0, HL продолжение заголовка, DE и BC сохранены относительно входа активного Entry
                ;   после числового пути HL, DE и BC принадлежат DrawTradeNumericColumns, AF' содержит его основной AF, основной AF содержит счётчик
                ;   HL', DE', BC', IX, IY, I, IFF и IM сохраняются при договорах текста и HALT, собственный код не переключает страницы
                ;   CargoBase сама процедура не меняет, обычный возврат из всех допустимых входов даёт SP=входной SP+2
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', bitmap, окно текста, CargoRow и HoverRows только на активном пути
                ; Note:
                ;   счётчик означает начатые строки, а не только полностью показанные строки, ранний отказ первого глифа уже учтён
                ;   первый C9 отключает лишь Entry, дополнительный DrawColumns по 708E этим байтом не отключается
                ;   CargoBase рисователь читает словом, торговый интерпретатор GetCargoIndex использует только младший байт плюс CargoRow
                ;   модель проверила 48 активных рисунков и 256 отключённых входов, bitmap заголовка и числового тела сравнивается независимо от рамки
                ; -----------------------------------------
                ; -----------------------------------------
                ; Рамка и торговый заголовок
                ; -----------------------------------------
                ; чтение изменяемого ItemIndex, первый C9 отключает лишь этот основной вход
Entry:          LD HL, #0000
                ; регистрация торгового элемента и рисование рамки с заголовком
                CALL @Station.DrawCaptionItem.Entry
                ; настройка пяти торговых колонок и Style=0
                CALL @Station.SetMarketTextColumns.Entry
                ; сброс прежней строки, новый фон не содержит её XOR-полосы
                LD A, @TradePanelConst.NoRow
                LD (@ScriptSelection.CargoRow), A
                ; выбор исходного заголовка с колонками Продажа и Наличие
                LD HL, @TradeTableText.Header
                CALL @Station.PrintText.Entry
                ; обнуление счётчика AF' с сохранением статуса заголовка для проверки Carry
                EX AF, AF'
                XOR A
                EX AF, AF'
                JP C, @Station.DrawTradePanel.FinishCounts                      ; переход, если заголовок вернул Carry, сохранить нулевую высоту подсветки без чисел

                ; чтение полного начального индекса, интерпретатор отдельно использует его младший байт
                LD HL, (@ScriptSelection.CargoBase)
                ; -----------------------------------------
                ; Дополнительный callback числовых колонок
                ; -----------------------------------------
                ; дополнительный вход callback с HL индекса, рисование только названий и чисел без рамки
DrawColumns:    CALL @Station.DrawTradeNumericColumns.Entry
                ; -----------------------------------------
                ; Общий хвост счётчика подсветки
                ; -----------------------------------------
                ; общий хвост возвращает счётчик из AF' и сохраняет его в старшем байте LD DE наведения
FinishCounts:   EX AF, AF'
                LD (@TradePanelState.HoverRows), A
                RET

                ; -----------------------------------------
                endmodule
                endmodule
