                module Station
                module XorItemRow
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [отсечение строки и физический банковый вызов XOR-ядра](../../Docs/RowHighlight.md)
; -----------------------------------------
; Инверсия заданной строки элемента с горизонтальным отсечением через банк 1
; исходная запись 4, файловые смещения #42BB..#4310
; In:
;   DE - E пиксельный отступ, исходный D заменяется номером из A
;   AF - A байтовый номер строки, PointerXY.Y читается для возвращаемого C
;   IX - читаемая FInterfaceItem, Width=2..32, знаковый X от 1-Width до 31, Y байтовый
;   адресные таблицы #8200..#84FF построены, станционный код в банке 0, MAP в банке 1
;   тень CurrentPage соответствует аппаратному #7FFD, банк 0 выбран, блокировка bit5 снята
;   обычный стек не пересекает bitmap, указатель уже снят, повторного входа в XOR-ядро нет
; Out:
;   при отказе HL сохранён, DE - D входной номер, E сохранён, B начало области, C=PointerY
;   при отказе A вычисленный верх, F от CP #B8, Carry=0
;   при рисовании HL адрес той же колонки через восемь строк, DE - D выбранный номер, E маска краёв
;   при рисовании B=0, C младший адрес начала последней строки, AF от последнего SelectRamBank
;   страница после рисования равна (входная CurrentPage AND #F8) OR #10, ROM 1 принудительно выбран
;   альтернативные и индексные регистры, I и IFF сохранены, SP восстановлен
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   общая точка FromHitData принимает B начало области и D номер, номер вращается RLCA трижды без маски
;   верх полосы равен (ROL8(номер,3)+B) AND #FF, значение не меньше 184 отвергается до OUT
;   допустимость номера относительно Height здесь не проверяется, номер 64 даёт слагаемое 2
;   при X>=0 и X+Width<=32 полных байтов Width-2, оба края применяются, E=0
;   при отрицательном X полных байтов Width+X-1, левый край пропущен, E=#55
;   при X+Width>32 полных байтов 31-X, правый край пропущен, E=#AA
;   OUT выбирают сначала банк 1 с ROM 1, затем банк 0 с ROM 1, бит экранной страницы сохраняется
;   в банке 1 меняется операнд MapHighlightState.WidthSkip, одноимённый адрес банка 0 не затрагивается
;   XOR снимает прежнюю подсветку только при совпадающем фоне, текущий признак подсветки не хранится
;   проверка не запрещает прерывания и не фиксирует PointerY для последующих вызовов
; -----------------------------------------
                ; сохранение явно заданного номера, высота элемента его не ограничивает
Entry:          LD D, A
                ; получение байтового начала области из Item.Y и отступа E
                CALL @Station.GetRowHitData.Entry
                LD A, D
                ; расчёт смещения номера тремя вращениями, старшие биты возвращаются в младшую тройку
FromHitData:    RLCA
                RLCA
                RLCA
                ; расчёт пиксельного верха полосы добавлением начала области по модулю 256
                ADD A, B
                ; проверка верхней строки, восемь пикселей должны завершиться до строки 192
                CP #B8
                RET NC                                                          ; выход, если верх полосы не меньше 184, страницу и экран не менять

                LD B, A
                ; чтение знакового X для горизонтального отсечения
                LD A, (IX + FInterfaceItem.X)
                ; проверка отрицательного X перед выбором первой видимой колонки
                AND A
                JP P, @Station.XorItemRow.BuildAddress                          ; переход, если X неотрицателен, использовать его для экранного адреса

                ; отсечение левой колонки до нуля при отрицательном X
                XOR A
                ; расчёт пиксельного X для таблицы младших частей экранного адреса
BuildAddress:   RLCA
                RLCA
                RLCA
                LD C, A
                ; поиск старшей и младшей части адреса по таблицам пиксельного Y и X
                LD H, #82
                LD L, B
                LD B, (HL)
                INC H
                LD A, (HL)
                INC H
                LD L, C
                OR (HL)
                LD L, A
                LD H, B
                ; чтение ширины для расчёта числа полных байтов и масок краёв
                LD B, (IX + FInterfaceItem.Width)
                LD A, (IX + FInterfaceItem.X)
                ; расчёт правой исключённой колонки с байтовым переполнением
                ADD A, B
                ; проверка выхода правой границы за 32 колонки
                SUB @ScreenConst.ColumnEndLimit
                JR C, @Station.XorItemRow.FitRight                              ; переход, если байтовая правая граница меньше 33, правый край виден

                ; расчёт 31-X полных байтов при отсечённом правом крае
                SUB B
                CPL
                DEC A
                ; выбор попарной маски пропуска правого края во всех восьми строках
                LD E, #AA
                JR @Station.XorItemRow.DrawBank1

                ; расчёт Width-2 полных байтов между двумя частичными краями
FitRight:       LD A, B
                SUB #02
                ; выбор обоих частичных краёв для неотсечённой полосы
                LD E, #00
                ; проверка левого отсечения по знаковому биту исходного X
                BIT 7, (IX + FInterfaceItem.X)
                JR Z, @Station.XorItemRow.DrawBank1                             ; переход, если X неотрицателен, сохранить оба частичных края

                ; расчёт Width+X-1 полных байтов после отсечения левого края
                INC A
                ADD A, (IX + FInterfaceItem.X)
                ; выбор попарной маски пропуска левого края во всех восьми строках
                LD E, #55
                ; передача рассчитанной ширины развёрнутому ядру банка 1
DrawBank1:      LD B, A
                ; выбор MAP в банке 1 с установленным битом ROM 1
                LD A, #11
                CALL @Station.SelectRamBank.Entry
                ; инверсия восьми строк реальным кодом MAP в выбранном банке 1
                CALL @Map.XorSelectionBand.Entry
                ; возврат станционного банка 0 с сохранением принудительного ROM 1
                LD A, #10
                CALL @Station.SelectRamBank.Entry
                RET

                endmodule
                endmodule
