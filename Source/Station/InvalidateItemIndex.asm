                module Station
                module InvalidateItemIndex
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [CellMap.md](../../Docs/CellMap.md)
; -----------------------------------------
; Поиск первой совпавшей индексной пары и запись #FF в её старший байт
; исходная запись 4, файловые смещения #5E91..#5EAD
; In:
;   DE - искомая шестнадцатибитная индексная пара, младший байт E, старший D
; Out:
;   при первом совпадении обоих байтов в #8500..#85FF старший байт пары заменён #FF, младший сохранён
;   при совпадении A=D и F=#42 OR (D AND #28), при отсутствии A равен последнему сравнивавшемуся байту, F=#50 OR Carry последнего CP
; Corrupt:
;   AF
; Note:
;   HL, DE, BC, альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   полный обход ограничен переполнением младшего L и охватывает 128 двухбайтовых пар
;   сначала сравнивается младший байт, старший читается только при его совпадении, поздние дубликаты не меняются
;   Z установлен и при успехе, и при исчерпании таблицы, это не возвращаемый признак успеха
;   ResetIndexTable инициализирует только первые 128 байтов, причина различия с длиной поиска требует отдельного разбора
; -----------------------------------------
Entry:          PUSH HL
                ; поиск индексной пары в пределах одной страницы таблицы
                LD HL, @StationState.ItemIndex
                ; чтение и проверка младшего байта очередной пары
NextPair:       LD A, (HL)
                INC L
                CP E
                JR Z, @Station.InvalidateItemIndex.CheckHigh                    ; переход, если младший байт пары совпал, требуется проверка старшего

                ; переход к младшему байту следующей пары с проверкой переполнения страницы
                INC L
                JP NZ, @Station.InvalidateItemIndex.NextPair                    ; переход, если младший адрес не переполнился, поиск продолжается в той же странице

                POP HL
                RET

                ; чтение и проверка старшего байта после совпадения младшего
CheckHigh:      LD A, (HL)
                CP D
                JR Z, @Station.InvalidateItemIndex.Invalidate                   ; переход, если оба байта пары совпали, старший байт помечается свободным

                ; переход к следующей паре после несовпадения старшего байта
                INC L
                JP NZ, @Station.InvalidateItemIndex.NextPair                    ; переход, если младший адрес не переполнился, поиск продолжается

                POP HL
                RET

                ; освобождение первой совпавшей пары заменой её старшего байта на #FF
Invalidate:     LD (HL), @ItemIndexConst.FreeHigh
                POP HL
                RET

                endmodule
                endmodule
