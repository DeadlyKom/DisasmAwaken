                module Station
                module PrintMin4
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [числовой вывод](../../Docs/NumberOutput.md)
; -----------------------------------------
; Вывод старым числовым ядром с дополнением слева минимум до четырёх символов
; исходная запись 4, файловые смещения #5BA8..#5BBD
; In:
;   BC - исходное беззнаковое слово, обычный десятичный результат для 0..9999
;   TextWindow и исходный код DrawGlyph подготовлены для вывода
; Out:
;   BC - значение перед последним вызовом DrawGlyph, при полном успехе равно 10
;   AF - результат последнего DrawGlyph, при успехе #0045, при отказе Carry сброшен и A содержит код причины
;   при полном успехе строка старого ядра дополнена слева кодом #30 минимум до 4 символов
; Corrupt:
;   BC, AF
; Note:
;   HL, DE, альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   вывод выполняется через DrawGlyph с его ограничениями окна и самомодификацией, текстовый курсор продвигается
;   при первом отказе DrawGlyph дальнейшие символы не вызываются, уже выведенные символы не отменяются
;   при допустимом пропуске глифа за отрицательным краем DrawGlyph возвращает успех, это не отказ числового вывода
;   при BC>=10000 первый символ старого ядра равен #30+целая часть BC/1000 и выходит за диапазон цифр
;   переход в PrintMin3.Hundreds использует кадр сохранённых HL и DE входа PrintMin4, отдельного CALL нет
; -----------------------------------------
Entry:          PUSH HL
                PUSH DE
                ; проверка числа относительно 999 для выбора ведущего разряда
                LD HL, @NumberConst.Max3Digits
                OR A
                SBC HL, BC
                JP C, @Station.PrintMin3.Hundreds                               ; переход, если число больше 999, дополнительный ноль четырёхразрядного поля не нужен

                LD A, @NumberConst.DigitZero
                CALL @Station.DrawGlyph.Entry
                JP NC, @Station.PrintMin2.Restore                               ; переход, если DrawGlyph отказал в выводе, возврат с его статусом без последующих разрядов

                JP @Station.PrintMin3.Hundreds

                endmodule
                endmodule
