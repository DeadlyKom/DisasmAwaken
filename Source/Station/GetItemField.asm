                module GetItemField
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [Interface.md](../../Docs/Interface.md)
; -----------------------------------------
; Вычисление адреса поля шестнадцатибайтовой записи станционного интерфейса
; исходная запись 4, файловые смещения #3EED..#3EFE
; In:
;   HL - индекс шестнадцатибайтовой записи FInterfaceItem, AF - A байтовое смещение поля
; Out:
;   HL - (StationState.Items + 16*исходный HL + исходный A) по модулю 65536
;   AF - A=#F0 и F=#A4 при смещении 0..2, A=#F1 и F=#A0 при смещении 3..255
; Corrupt:
;   HL, AF
; Note:
;   база StationState.Items равна #F0FD, перенос младшего байта базы учитывается до прибавления индекса
;   память записи не читается и не изменяется, допустимость индекса и поля этим входом не проверяется
;   DE, BC, альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   четыре удвоения HL соответствуют фактическому размеру FInterfaceItem, переполнение намеренно остаётся шестнадцатибитным
; -----------------------------------------
Entry:          PUSH BC
                ; расчёт смещения записи, индекс умножается на физический размер FInterfaceItem
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ; расчёт младшей части адреса поля от младшего байта базы #F0FD
                LD C, #FD
                ADD A, C
                LD C, A
                ; учёт переноса смещения поля в старший байт базы таблицы
                LD A, #F0
                ADC A, #00
                LD B, A
                ; расчёт полного указателя поля после прибавления смещения записи
                ADD HL, BC
                ; подготовка выходных флагов по старшему байту базы со смещением, Carry сбрасывается
                OR A
                POP BC
                RET

                endmodule
                endmodule
