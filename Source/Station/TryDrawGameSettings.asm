                module Station
                module TryDrawGameSettings
                ; Документация [два CR-списка, общий хвост значений, полный индекс и счётчик обработанных полей](../../Docs/SettingsRowPanels.md)
                ; -----------------------------------------
                ; Условное рисование установок игры при точном указателе панели в списке
                ; исходная запись 4, файловые смещения #18DC..#18E2
                ; In:
                ;   HL и BC сохраняемый контекст TestDrawPointer, список с исходным ограничителем доступен
                ;   для присутствующего исходного рисователя выполняется договор DrawGameSettings
                ; Out:
                ;   при отсутствии HL и BC сохранены, DE содержит точный адрес DrawGameSettings.Entry, AF принадлежит TestDrawPointer
                ;   при совпадении исходного рисователя выполняется весь его договор через физическое продолжение следующего файла
                ;   при совпадении временного C9 рисователя AF=0050, HL и BC сохранены, DE содержит адрес рисователя
                ;   SP после возврата входному+2, остальные регистры по фактически выполненному рисователю либо сохранены на отказе
                ; Corrupt:
                ;   DE, AF, другие регистры и память только по фактически выполненному рисователю
                ; Note:
                ;   алиас с тем же ключом элемента не заменяет точного указателя, порядок include (0), (1) жёсткий
                ; -----------------------------------------
                ; поиск точного адреса панели установок игры в списке рисования
Entry:          LD DE, @Station.DrawGameSettings.Entry
                CALL @Station.TestDrawPointer.Entry
                RET NZ                                                          ; выход, если точный указатель панели установок игры отсутствует

                ; JP @Station.DrawGameSettings.Entry, продолжение в DrawGameSettings.asm

                endmodule
                endmodule
