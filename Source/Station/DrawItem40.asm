                module Station
                module DrawItem40
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [рамка, пустой заголовок и печать настоящего ресурса меню](../../Docs/ContextMenuDraw.md)
; -----------------------------------------
; Регистрация и рамка контекстного меню, сброс выделения и печать восьми команд
; исходная запись 4, файловые смещения #182F..#1844
; In:
;   операнд PopupState.MenuDrawIndex по #7584 установлен загрузчиком в 40, исходный дисковый байт равен нулю
;   Item40 имеет TextIndex=0, Flags=#26, X=0..23, Y=0..15, Width=9, Height=9 для штатного меню
;   действует договор DrawCaptionItem, свободная индексная пара, исходные таблицы адресов и шрифт готовы
;   пробуждение HALT сохраняет регистры согласно договору DrawBandSync, LineEndCode содержит JP
; Out:
;   HL - позиция продолжения в ContextMenuText, при полном выводе #E39A
;   DE и BC сохранены, AF - договор PrintText, полный вывод даёт #0A4A
;   HL', DE', BC', IX и IY сохранены, AF' рабочий, I сохраняется, SP восстановлен при договоре пробуждения
;   рамка и текст нарисованы, прямоугольник зарегистрирован как Item40, атрибуты не меняются
;   PopupState.PreviousRow=#FF, Style=1, курсор содержит результат печати меню
; Corrupt:
;   HL, AF, AF'
; Note:
;   основной HL не сохраняется, исходный HL заменяется непосредственным индексом обработчика
;   CaptionTextBase=#E399 совпадает с последним LF ресурса меню, SkipLfRecords при TextIndex=0 пропускает его
;   следующий #E39A также равен LF, поэтому заголовок пуст, общий граничный байт является используемыми данными
;   DrawCaptionItem возвращает Style=0 и CursorX=0, CursorY=0 при исходном Flags=#26, затем включается Style=1
;   при меньшей синтетической геометрии PrintText может завершиться раньше, договор не обещает полный вывод вне штатного размера
;   пробуждение HALT в модели задаётся явно, оно не доказывает аппаратные IFF и временные параметры IRQ
;   исходный непосредственный индекс #0000 сохраняется в исходнике и образе, загрузочная модификация не переносится в дисковые байты
; -----------------------------------------
                ; чтение индекса из операнда, загрузчик заменяет исходный ноль на номер Item40
Entry:          LD HL, #0000
                ; регистрация Item40 и рисование рамки с пустым заголовком через общую LF-границу
                CALL @Station.DrawCaptionItem.Entry
                ; выбор маркера отсутствия прежней выделенной строки
                LD A, #FF
                ; сброс самомодифицируемого номера перед рисованием нового меню
                LD (@PopupState.PreviousRow), A
                ; выбор режима переноса текста вместо пропуска остатка строки
                LD A, #01
                ; включение переноса для содержимого после нулевого Style заголовка
                LD (@TextWindow.Style), A
                ; выбор исходного CP866-ресурса восьми команд меню
                LD HL, @ContextMenuText.Entry
                ; печать меню с хвостовым возвратом непосредственно вызывающему обработчику
                JP @Station.PrintText.Entry

                endmodule
                endmodule
