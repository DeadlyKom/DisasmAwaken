                module Station
                module HandleHelpTextAction
                ; Документация [полный селектор, закрытие двух ключей, прокрутка и отсутствие проверки FF подсветки](../../Docs/HelpPanelActions.md)
                ; -----------------------------------------
                ; Закрытие связанной пары либо прокрутка LF-текста, выбор единицей ничего не делает
                ; исходная запись 4, файловые смещения #0C27..#0C52
                ; In:
                ;   HL запасной рисователь текущего элемента, DE его ключ, BC и AF контекст RepaintAndFlag
                ;   IX, указатель и геометрия выполняют договор перерисовки, действует договор CloseMenuOnRow и DropItemDraw
                ;   для прокрутки HelpPanelState.LineCount и кэш подготовлены, TopLine допустим, окно и ввод удовлетворяют ScrollWindowRows
                ; Out:
                ;   при Carry RepaintAndFlag немедленно возвращается его контекст, последующие действия подавлены
                ;   при Carry=0 и возвращённом A=1 выполняются DEC A и RET, основной AF=0042, выбор раздела не производится
                ;   при совпадении символьных строк указателя и окна удаляется текущий ключ, затем первый ключ ContentsIndex
                ;   иначе RenderCall=PrintHelpLine, EndLimit=LineCount, A=8 и HL=TopLine передаются ScrollWindowRows
                ;   после прокрутки полный итоговый HL записан в TopLine, остальные выходы определяет договор ScrollWindowRows
                ;   HL, DE, BC, AF, альтернативные и индексные регистры соответствуют фактически выполненным помощникам, SP после возврата входному+2
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', BC' при прокрутке, список, экраны, указатель, TopLine и операнды ScrollWindowRows по ветви
                ; Note:
                ;   удаление ищет первый совпадающий индекс, переносит фиксированные 128 байтов и учитывает алиасы рисователя
                ;   CloseMenuOnRow удаляет текущую панель до второго DropItemDraw, X указателя не участвует в сравнении
                ;   прокрутка принудительно завершает на странице 10 и восстанавливает исходные координаты указателя
                ; -----------------------------------------
                ; перерисовка и обработка геометрии до выбора дальнейшего действия
Entry:          CALL @Station.RepaintAndFlag.Entry
                RET C                                                           ; выход, если RepaintAndFlag вернул Carry, дальнейшее действие подавлено

                ; проверка селектора 1, для текста он не выбирает запись
                DEC A
                JR Z, @Station.HandleHelpTextAction.NoSelection                 ; переход, если возвращённый селектор равен 1, завершить без выбора

                ; условное закрытие текущей панели по совпадению символьных строк Y
                CALL @Station.CloseMenuOnRow.Entry
                JR NZ, @Station.HandleHelpTextAction.ScrollRows                 ; переход, если строки различаются, выполнить прокрутку текста

                ; чтение ключа связанного списка разделов перед вторым удалением
                LD DE, (@HelpPanelState.ContentsIndex)
                JP @Station.DropItemDraw.Entry

                ; обновление callback прокрутки, используется межбанковая печать текста без рамки
ScrollRows:     LD HL, @Station.PrintHelpLine.Entry
                LD (#A265), HL
                ; чтение полного числа индексированных строк как предела прокрутки
                LD HL, #0000
                LD (#A235), HL
                ; подготовка верхнего отступа 8 пикселей и сохранённого индекса TopLine
                LD A, #08
                LD HL, #0000
                CALL @Station.ScrollWindowRows.Entry
                ; сохранение полного итогового индекса верхней строки
                LD (@HelpPanelState.TopLine), HL
                RET

                ; пустая ветвь выбора текста, возвращается результат DEC селектора 1
NoSelection:    RET

                endmodule
                endmodule
