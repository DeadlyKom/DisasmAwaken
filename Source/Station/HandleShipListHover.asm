                module HandleShipListHover
                ; Документация [тот же CPU-возврат, полный договор получателя и изменяемые счётчики строк](../../Docs/ListHoverAdapters.md)
                ; -----------------------------------------
                ; Хвостовая передача наведения списка моделей кораблей в UpdateShipListHover
                ; исходная запись 4, файловые смещения #0A1D..#0A1F
                ; In:
                ;   IX - допустимая FInterfaceItem списка Корабли, подготовлены указатель, шрифт, таблицы адресации и банковое XOR-ядро
                ;   список рисования непуст и завершается исходным маркером, PointerY=0..191, выбран станционный банк 0
                ;   PanelHoverState.ShipsRow содержит прежний номер либо FF, его операнд доступен для записи
                ;   действуют договоры UpdateRowHover, XorItemRow, XorPointerRow, SuspendPointer и ResumePointer
                ; Out:
                ;   перед UpdateRowHover установлены HL=DrawModelListPanel.Entry, DE с младшим отступом 1B и старшим ModelListState.HoverRows, A прежний номер
                ;   D равен текущему ModelListState.HoverRows, исходно 30, E=27 пикселей, фактическую байтовую высоту рассчитывает ClampRowHeight
                ;   при Z=1 возвращённого UpdateRowHover сохранённый номер не меняется, выходные регистры принадлежат соответствующей ветви отказа или совпадения
                ;   при Z=0 весь возвращённый A записан в PanelHoverState.ShipsRow, даже если A=0 либо повторная проверка вернула высоту
                ;   HL, DE, BC и AF принадлежат UpdateRowHover, HL', DE', BC', IX, IY сохраняются, AF' рабочий только на обновлении указателя
                ;   при соблюдении договоров SP обычного возврата равен входному SP+2, I, IFF и IM не меняются
                ; Corrupt:
                ;   HL, DE, BC, AF, AF' на изменении полосы и указателя
                ; Note:
                ;   обновление допускается лишь для точного адреса рисователя в последнем слове списка
                ;   Z показывает отсутствие обновления, он не равнозначен нулю A
                ;   две проверки PointerY не атомарны, обёртка не исправляет служебный результат позднего отказа
                ;   рисователь сбрасывает свой операнд строки в FF после замены фона, эта обёртка сама фон панели не рисует
                ;   названия списков взяты из исходных заголовков и текстов, назначение действий их строк этим контрактом не устанавливается
                ;   DrawModelListPanel записывает вычисленный счётчик в 67D2, поэтому во время игры D не обязан равняться исходному 30
                ;   JP передаёт исходный внешний CPU-возврат в UpdateShipListHover, нового CALL и сохранённых слов нет
                ; -----------------------------------------
                ; передача наведения списка моделей кораблей в UpdateShipListHover с исходным адресом возврата
Entry:          JP #67D0

                endmodule
