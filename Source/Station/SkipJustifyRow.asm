                module Station
                module SkipJustifyRow
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [выравнивание текста по ширине](../../Docs/JustifiedText.md)
; -----------------------------------------
; Пропуск одной выровненной строки через продвижение глифа без пикселей
; исходная запись 4, файловые смещения #4D35..#4DA6
; In:
;   HL - текст с читаемым запасом для просмотра слов за ограничителями
;   TextWindow задаёт исходный курсор и размеры, KernelPrefix должен содержать исходные #68, #48, #26
; Out:
;   HL - положение после пропущенной строки либо границы, определённой PrintTextWord
;   DE - при Height>=14 равно #2648, слово восстановления префикса глифа
;   BC - рабочий разделитель #20 и ширина, либо результат AdvanceTextRow после попытки переноса
;   AF - при Height>=14 A=#68, F от выхода PrintTextWord либо от AND результата завершающего AdvanceTextRow
;   курсор продвинут без записи пикселей, KernelPrefix восстановлен в исходный вариант
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   при Height<14 возврат немедленный, A=Height, F от CP(Height, 14), HL, DE и BC сохранены
;   выбор слов выполняется просмотром вперёд с временным HL, печать возобновляется с сохранённого начала строки
;   LF и CR ограничивают одно измеряемое слово, но не прекращают просмотр набора, за ними должны быть читаемые байты
;   добавление минимального интервала 2 к ширине слова является байтовым, его переполнение не проверяется
;   каждый промежуток равен 2 плюс целая доля свободной ширины, остаток деления не распределяется
;   нулевой код не является завершением этих проходов, действуют ограничители PrintTextWord либо PrintWrapWord
;   попытка переноса сохраняет исходное переполнение Y по модулю 256
;   проход не сохраняет произвольный прежний KernelPrefix, после работы записывает именно исходные три байта
;   после завершённой группы слов AND A сбрасывает Carry, даже если последний перенос отказал
;   если PrintTextWord остановился раньше группы, его F сохраняется при восстановлении кода глифа
; -----------------------------------------
                ; чтение высоты перед проверкой минимального размера окна
Entry:          LD A, (@TextWindow.Height)
                ; проверка минимальной высоты 14 для работы выравнивателя
                CP @JustifyConst.MinHeight
                RET C                                                           ; выход, если высота окна меньше 14, код глифа ещё не менялся

                ; включение штатного пропуска пиксельной части глифа, остаётся продвижение курсора
                LD A, @GlyphOpcode.SkipJump
                LD (@GlyphState.KernelPrefix), A
                LD DE, @Station.ReturnGlyph.Entry
                LD (@GlyphState.KernelPrefix + 1), DE
                ; сохранение ширины окна в непосредственном операнде прохода
                LD A, (@TextWindow.Width)
                LD (@JustifyState.SkipWidth), A
                LD C, #00
                LD B, @TextConst.Space
                LD E, #00
                ; сохранение начала строки перед просмотром будущих слов
                PUSH HL
                XOR A
                ; сохранение ширины уже принятого набора перед измерением очередного слова
FitWords:       LD D, A
                CALL @Station.MeasureTextRun.Entry
                ; расчёт ширины слова с минимальным промежутком 2, переполнение этого сложения не проверяется
                ADD A, @JustifyConst.MinGap
                ; пропуск ограничителя измеренного слова даже для CR либо LF
                INC HL
                INC E
                ; расчёт суммарной ширины просмотренных слов с интервалами
                ADD A, D
                JR C, @Station.SkipJustifyRow.FinishFit                         ; переход, если сумма набора переполнила байт, очередное слово не включается

                ; проверка суммарной ширины относительно ширины окна
                CP C
                JR C, @Station.SkipJustifyRow.FitWords                          ; переход, если набор с промежутками ещё уже окна, просмотреть следующее слово

                ; расчёт ширины без последнего обязательного промежутка
                SUB @JustifyConst.MinGap
                ; проверка ширины последнего слова без конечного промежутка
                CP C
                JR NC, @Station.SkipJustifyRow.FinishFit                        ; переход, если слово без конечного промежутка достигает ширины окна либо превышает её

                ; проверка особого случая первого слова, помещающегося без конечного промежутка
                DEC E
                JR NZ, @Station.SkipJustifyRow.KeepFirst                        ; переход, если просмотрено больше одного слова, сохранить обычный выбор предыдущих слов

                INC E
KeepFirst:      INC E
                ; выбор количества слов перед последним просмотренным, затем возврат к началу строки
FinishFit:      DEC E
                POP HL
                JR NZ, @Station.SkipJustifyRow.Gap                              ; переход, если выбран непустой набор слов, рассчитать выравнивающий промежуток

                CALL @Station.PrintTextWord.Entry
                JR @Station.SkipJustifyRow.RestoreGlyph

                ; расчёт свободной ширины относительно последнего принятого набора
Gap:            LD A, C
                SUB D
                LD D, A
                ; расчёт количества межсловных интервалов, одиночное слово обрабатывается отдельно
                DEC E
                JR Z, @Station.SkipJustifyRow.WordCount                         ; переход, если выбрано одно слово, деление промежутка не требуется

                ; расчёт целой доли свободной ширины повторным вычитанием числа интервалов
                LD D, #FF
DivideGap:      INC D
                SUB E
                JP NC, @Station.SkipJustifyRow.DivideGap                        ; переход, если свободная ширина допускает ещё одну целую долю на каждый интервал

WordCount:      INC E
Word:           CALL @Station.PrintTextWord.Entry
                JR Z, @Station.SkipJustifyRow.RestoreGlyph                      ; переход, если печататель слова вернул Z, завершить проход и восстановить код глифа

                ; чтение позиции после слова для добавления выравнивающего промежутка
                LD A, (@TextWindow.CursorX)
                ; расчёт следующего X с минимальным промежутком 2 и дополнительной долей D
                ADD A, @JustifyConst.MinGap
                ADD A, D
                LD (@TextWindow.CursorX), A
                ; проверка остатка группы слов после продвижения курсора
                DEC E
                JP NZ, @Station.SkipJustifyRow.Word                             ; переход, если в группе остаются слова, продолжить сухой вывод

                CALL @Station.AdvanceTextRow.Entry
                ; сброс Carry после завершающей попытки новой строки, исходный статус переноса здесь не передаётся
                AND A
                ; восстановление трёх исходных байтов пиксельной части, F оставлен от результата прохода
RestoreGlyph:   LD A, @GlyphOpcode.ResumeFirst
                LD (@GlyphState.KernelPrefix), A
                LD DE, @GlyphOpcode.ResumePair
                LD (@GlyphState.KernelPrefix + 1), DE
                RET

                endmodule
                endmodule
