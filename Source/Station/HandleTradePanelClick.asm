                module Station
                module HandleTradePanelClick
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [зависимость подсветки от рисунка, событие колонки, банковый запуск и дополнительные входы рисователя](../../Docs/TradePanel.md)
                ; -----------------------------------------
                ; Закрытие торговой панели с меню, прокрутка либо выбор кода события по колонке
                ; исходная запись 4, файловые смещения #129D..#12EF
                ; In:
                ;   HL - обёртка товаров, DE - её индекс, AF - полный селектор, действуют RepaintAndFlag и его выбранный рисователь
                ;   подготовлены указатель, строки, CargoBase, CargoRow, Index35 меню продажи и действующие договоры списка
                ;   для прокрутки действует ScrollWindowRows, для события RunTradeEventAndRedraw, код доступен для самомодификации
                ; Out:
                ;   сначала выполнен RepaintAndFlag, его Carry немедленно завершает действие без местного закрытия, прокрутки или события
                ;   при Carry=0 и селекторе 1 проверяется только CargoRow=FF, при FF обычный возврат без события
                ;   для выбранной строки относительный X=(PointerX-OriginXLow) AND FF, при X<135 выбран код события 10, иначе 9
                ;   оба кода передаются хвостовому RunTradeEventAndRedraw, дополнительный адрес возврата не создаётся
                ;   прочие селекторы вызывают CloseMenuOnRow, при совпавшей строке удаляются товарная обёртка и затем Index35 меню продажи через DropItemDraw
                ;   при несовпавшей строке установлены торговые колонки, XorRowIfSelected снимает прежнюю полосу при не FF, CargoRow сбрасывается в FF
                ;   для прокрутки RenderCall=DrawTradePanel.DrawColumns, EndLimit=29, A=32, HL читается из изменяемого CargoBase
                ;   после ScrollWindowRows его итоговый HL записан обратно в слово CargoBase, остальные выходы по договору прокрутки
                ;   регистры, экраны, страницы и указатель соответствуют выбранному дочернему пути, SP обычного возврата равен входному SP+2
                ; Corrupt:
                ;   HL, DE, BC, AF и прочие регистры только по соответствующему доказанному дочернему договору, списки, экраны и состояние сценария на выбранных путях
                ; Note:
                ;   выбранная строка проверяется только на FF, отдельного сравнения с HoverRows в этом входе нет
                ;   порог 135 отделяет колонку Продажа от Наличие, вычисление X байтовое, отрицательное смещение оборачивается
                ;   исходный сценарий устанавливает 9 как покупку одной единицы, 10 как продажу одной, 11 как продажу всего текущего груза
                ;   после последнего DEC A исполнение последовательно продолжается в следующем файле RunTradeEventAndRedraw, порядок include обязателен
                ;   модель проверила 66560 вариантов выбора колонки и 1024 развилки, действия сценария не подменяются подтверждением торговли
                ; -----------------------------------------
                ; выбор торговой панели и возможная перерисовка до локального действия
Entry:          CALL @Station.RepaintAndFlag.Entry
                RET C                                                           ; выход, если RepaintAndFlag вернул Carry, действие либо перерисовка уже выполнены

                ; проверка селектора 1 для выбора колонки выбранного товара
                DEC A
                JP Z, @Station.HandleTradePanelClick.SelectedColumn             ; переход, если исходный селектор равен 1, обработать выбранную колонку

                ; проверка строки заголовка и возможное удаление основной товарной панели
                CALL @Station.CloseMenuOnRow.Entry
                JR NZ, @Station.HandleTradePanelClick.StartScroll               ; переход, если строка не совпала, подготовить прокрутку содержимого

                ; чтение индекса связанного меню продажи после закрытия основной панели
                LD DE, (@DrawItemState.Index35)
                ; удаление меню продажи с тем же исходным адресом возврата
                JP @Station.DropItemDraw.Entry

                ; -----------------------------------------
                ; Прокрутка списка после снятия сохранённой полосы
                ; -----------------------------------------
                ; настройка позиций текста до снятия прежней строки
StartScroll:    CALL @Station.SetMarketTextColumns.Entry
                ; чтение изменяемой высоты подсветки и её верхнего отступа
                LD DE, (@TradePanelState.HoverArea)
                ; чтение номера прежней XOR-полосы
                LD A, (@ScriptSelection.CargoRow)
                ; снятие прежней XOR-полосы, если выбранный номер не FF
                CALL @Station.XorRowIfSelected.Entry
                ; выбор FF для сброса номера после снятия полосы
                LD A, @TradePanelConst.NoRow
                ; обновление CargoRow, новая прокрутка начинается без сохранённой полосы
                LD (@ScriptSelection.CargoRow), A
                ; выбор дополнительного входа рисователя без повторного заголовка
                LD HL, @Station.DrawTradePanel.DrawColumns
                ; обновление RenderCall прокрутки
                LD (@ScrollState.RenderCall), HL
                ; выбор исходной границы 29 для проверки шага вниз
                LD HL, @TradePanelConst.EndLimit
                ; обновление EndLimit прокрутки
                LD (@ScrollState.EndLimit), HL
                ; выбор верхнего отступа числовых строк 32 пикселя
                LD A, @TradeTableConst.StartY
                ; чтение изменяемого начального индекса списка из CargoBase
                LD HL, #0000
                ; прокрутка с установленным индексом и callback торговых колонок
                CALL @Station.ScrollWindowRows.Entry
                ; обновление слова CargoBase итоговым индексом прокрутки
                LD (@ScriptSelection.CargoBase), HL
                RET

                ; -----------------------------------------
                ; Выбор торгового события по выбранной строке и колонке
                ; -----------------------------------------
                ; проверка точного FF отсутствующей строки
SelectedColumn: LD A, (@ScriptSelection.CargoRow)
                INC A
                RET Z                                                           ; выход, если CargoRow равен FF, строка не выбрана

                ; чтение PointerXY для расчёта относительного X
                LD HL, (@StationState.PointerXY)
                ; расчёт PointerX-OriginXLow по модулю 256 через вычитание и NEG
                LD A, (@TextWindow.OriginXLow)
                SUB L
                NEG
                ; проверка начала колонки Наличие по X=135
                CP @TradePanelConst.OwnedColumnX
                LD A, @TradeEvent.SellOne
                JR C, @Station.RunTradeEventAndRedraw.Entry                     ; переход, если относительный X меньше 135, продать одну единицу событием 10

                ; выбор покупки одной единицы событием 9, далее исходное продолжение в следующем файле
                DEC A
                ; JP @Station.RunTradeEventAndRedraw.Entry, продолжение в RunTradeEventAndRedraw.asm

                ; -----------------------------------------
                endmodule
                endmodule
