                module Station
                module PrintTextWord
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [вывод слова и статусы переноса](../../Docs/WordOutput.md)
; -----------------------------------------
; Печать до пробела, CR, LF либо отказа с остановкой после переноса по ширине
; исходная запись 4, файловые смещения #4DA7..#4DCC
; In:
;   HL - начало текста, достигающего пробела, CR, LF либо отказа вывода
;   TextWindow и исходные инструкции DrawGlyph подготовлены
; Out:
;   HL - после потреблённого ограничителя либо символа, при отказе ширины остаётся на этом символе
;   DE - D сохранён, E=1 только при CR, иначе исходный E сохранён
;   BC - сохранён, кроме отказа ширины, тогда B=Height, C=(прежний CursorY+8) по модулю 256
;   AF - пробел даёт #2120, CR даёт #0100, вертикальный отказ даёт #0044
;   LF даёт #0A49, любой отказ ширины после попытки перехода строки даёт #0044
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   пробел, CR и LF потребляются, CR здесь не продвигает Y, а устанавливает E=1 для вызывающего кода
;   отказ физического X с кодом 0 пропускает символ и продолжает печать, другие вертикальные отказы останавливают её
;   нулевой код и остальные управляющие байты не обрабатываются отдельно, они проходят в DrawGlyph
;   при отказе ширины вызывается AdvanceTextRow, принятый переход сбрасывает X и сдвигает Y, сам символ не повторяется внутри процедуры
;   переход Y имеет байтовое переполнение, подробности в WordOutput.md
;   разный статус переноса определяет решение вызывающего выравнивателя о продолжении, функции не взаимозаменяемы
; -----------------------------------------
                ; чтение символа слова с предварительным продвижением указателя
Entry:          LD A, (HL)
                INC HL
                ; проверка CR, который должен передать вызывающему признак E=1
                CP @TextConst.CarriageReturn
                JR Z, @Station.PrintTextWord.CarriageReturn                     ; переход, если прочитан CR, вернуть E=1 без сдвига курсора

                ; проверка LF, завершающего текущий текст
                CP @TextConst.LineFeed
                SCF
                RET Z                                                           ; выход, если прочитан LF, Carry принудительно установлен

                ; проверка пробела как границы слова, его ширина не добавляется к курсору
                CP @TextConst.Space
                JR Z, @Station.PrintTextWord.Space                              ; переход, если прочитан пробел, вернуть границу слова без рисования пробела

                CALL @Station.DrawGlyph.Entry
                JR C, @Station.PrintTextWord.Entry                              ; переход, если глиф принят, читать следующий символ слова

                ; проверка особого кода отказа физического X
                AND A
                JR Z, @Station.PrintTextWord.Entry                              ; переход, если отказ глифа имеет код 0 по физическому X, пропустить символ и продолжить

                ; проверка отказа по ширине для попытки перехода строки
                CP @GlyphStatus.Width
                JR NZ, @Station.PrintTextWord.Stop                              ; переход, если отказ глифа не связан с шириной, вернуть остановку без перехода строки

                ; возврат HL к невыведенному символу перед попыткой перехода строки
                DEC HL
                CALL @Station.AdvanceTextRow.Entry
                ; возврат остановки независимо от успеха AdvanceTextRow, повтор выполняет вызывающий код
Stop:           XOR A
                RET

Space:          INC A
                RET

CarriageReturn: XOR A
                INC A
                LD E, A
                RET

                endmodule
                endmodule
