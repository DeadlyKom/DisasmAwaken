                module Station
                module DropItemDraw
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [удаление обработчика по индексу](../../Docs/RemoveDraw.md)
; -----------------------------------------
; Удаление обработчика по индексу с запросом перестроения только при совпадении
; исходная запись 4, файловые смещения #6873..#687B
; In:
;   HL - произвольное сохраняемое значение, DE - удаляемый индекс, BC сохраняется
;   выполняются предусловия RemoveItemDraw, операнд InterfaceState.EventEnabled доступен для записи
; Out:
;   HL, DE и BC сохранены, при совпадении AF=#0044, EventEnabled=0
;   при отсутствии AF соответствует RemoveItemDraw, EventEnabled сохраняет прежний байт
; Corrupt:
;   AF
; Note:
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   Z=1 на обоих выходах, различаются A/F и факт записи EventEnabled
;   нет самостоятельного рисования или обновления карты, ноль EventEnabled запрашивает перестроение позже
; -----------------------------------------
                ; удаление первого обработчика с переданным DE-индексом
Entry:          CALL @Station.RemoveItemDraw.Entry
                RET Z                                                           ; выход, если индекс не найден, не запрашивать перестроение

                ; запрос перестроения только после найденного индекса, итоговый AF=#0044
                XOR A
                LD (@InterfaceState.EventEnabled), A
                RET

                endmodule
                endmodule
