                module Station
                module XorOutlineColumn
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [временный XOR-контур](../../Docs/XorOutline.md)
; -----------------------------------------
; Инверсия вертикальной грани по маске во всех пиксельных строках заданных знакомест
; исходная запись 4, файловые смещения #65F2..#6625
; In:
;   HL - адрес первой пиксельной строки знакоместа, DE - D положительная высота видимой части в знакоместах, E сохраняется
;   диапазон до нижнего края включительно помещается на экран, XorOutlineState.VerticalMask содержит XOR-маску
; Out:
;   HL и DE сохранены, B=VerticalMask,C=0
;   каждый байт вертикальной грани преобразован XOR маской, по восемь пиксельных строк знакоместа
;   AF - при переходе через границу восьми символьных строк A=колонка,F=#43
;   иначе A=старший байт следующей пиксельной строки после грани,F=#42
; Corrupt:
;   BC, AF
; Note:
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   маска загружается из изменяемого операнда LD B, штатный родитель использует #80 и #01
;   нулевая маска допустима, код всё равно записывает прежние значения в экран
;   D=0 отдельно не проверяется и запустил бы 256 знакомест, такой вход не входит в договор
; -----------------------------------------
                ; сохранение начала вертикальной грани и перенос высоты знакомест в C
Entry:          PUSH HL
                LD C, D
                ; операнд LD B содержит ранее выбранную XOR-маску левой либо правой грани
                LD B, #80
                ; восемь пиксельных строк знакоместа, каждое увеличение H выбирает следующую чередующуюся строку
PixelRows:      LD A, B
                XOR (HL)
                LD (HL), A
                INC H
                LD A, B
                XOR (HL)
                LD (HL), A
                INC H
                LD A, B
                XOR (HL)
                LD (HL), A
                INC H
                LD A, B
                XOR (HL)
                LD (HL), A
                INC H
                LD A, B
                XOR (HL)
                LD (HL), A
                INC H
                LD A, B
                XOR (HL)
                LD (HL), A
                INC H
                LD A, B
                XOR (HL)
                LD (HL), A
                INC H
                LD A, B
                XOR (HL)
                LD (HL), A
                INC H
                ; расчёт адреса следующего знакоместа после восьми пиксельных строк
                LD A, L
                ADD A, #20
                LD L, A
                JR C, @Station.XorOutlineColumn.NextCell                        ; переход, если младший адрес дал перенос, следующая треть экрана уже выбрана

                LD A, H
                SUB #08
                LD H, A
                ; уменьшение оставшейся высоты в знакоместах, Carry перехода адреса сохраняется
NextCell:       DEC C
                JP NZ, @Station.XorOutlineColumn.PixelRows                      ; переход, если остаются знакоместа вертикальной грани, продолжить инверсию

                POP HL
                RET

                endmodule
                endmodule
