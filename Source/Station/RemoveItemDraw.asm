                module Station
                module RemoveItemDraw
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [удаление обработчика по индексу](../../Docs/RemoveDraw.md)
; -----------------------------------------
; Удаление первого обработчика с заданным индексом через фиксированный сдвиг 128 байтов
; исходная запись 4, файловые смещения #6B1C..#6B51
; In:
;   HL - произвольное сохраняемое значение, DE - индекс для сравнения с Handler+1,+2, BC сохраняется
;   DrawListState.HeadOperand задаёт читаемый список до старшего байта 1, указатели имеют читаемые слова индекса
;   для найденной позиции доступны 128 байтов записи и 128 байтов чтения из следующей позиции
; Out:
;   HL, DE и BC сохранены, при совпадении AF=#0100, Z=0
;   при отсутствии A=0,F=#42 OR Carry, Z=1, Carry от сравнения последнего индекса с DE, для пустого списка входной
;   при совпадении ровно 128 байтов перемещены на два байта влево, начиная с найденной позиции
; Corrupt:
;   AF
; Note:
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   FRemoveDrawFrame содержит SavedBC, SavedDE, SavedHL, SavedIX, ReturnAddress
;   сравнивается индекс внутри обёртки, её первый код может быть временным RET и не проверяется
;   удаляется первое совпадение, остальные совпадения не ищутся
;   ограничитель по младшему байту не проверяется, его новое значение отдельно не записывается
;   при 64 и более последующих указателях старый ограничитель может остаться вне сдвига, логическая длина не обязана уменьшиться
;   всегда меняются также физические хвостовые байты до конца LDIR, не только видимая часть списка
;   геометрия, карта владельцев, пиксели и EventEnabled самим входом не меняются
; -----------------------------------------
                ; сохранение IX, HL, DE, BC в динамическом FRemoveDrawFrame
Entry:          PUSH IX
                PUSH HL
                PUSH DE
                PUSH BC
                ; чтение базы списка из изменяемого операнда RebuildInterface
                LD IX, (@DrawListState.HeadOperand)
                ; чтение указателя очередного обработчика, его старший байт определяет конец списка
NextHandler:    LD L, (IX + #00)
                LD A, (IX + #01)
                ; проверка старшего байта указателя на ограничитель 1, Carry предыдущего сравнения сохраняется
                DEC A
                JR Z, @Station.RemoveItemDraw.Finish                            ; переход, если достигнут ограничитель, вернуть отсутствие совпадения

                ; восстановление старшего байта указателя и чтение шестнадцатибитного индекса по Handler+1
                INC A
                LD H, A
                INC HL
                LD A, (HL)
                INC HL
                LD H, (HL)
                LD L, A
                ; перемещение IX к следующей записи до сравнения текущего индекса
                INC IX
                INC IX
                ; сравнение прочитанного индекса с требуемым DE после очистки Carry
                OR A
                SBC HL, DE
                JR NZ, @Station.RemoveItemDraw.NextHandler                      ; переход, если индексы различаются, проверить следующий обработчик

                ; расчёт источника сдвига по уже продвинутому IX и назначения на два байта раньше
                PUSH IX
                POP DE
                LD H, D
                LD L, E
                DEC DE
                DEC DE
                ; выбор исходной фиксированной длины LDIR 128 байтов, ограничитель не определяет её
                LD BC, @DrawListLimit.ShiftBytes
                ; физическое удаление позиции с копированием также хвоста списка
                LDIR
                ; формирование AF=#0100, признак найденного и обработанного индекса
                XOR A
                INC A
                ; восстановление FRemoveDrawFrame без изменения итогового AF
Finish:         POP BC
                POP DE
                POP HL
                POP IX
                RET

                endmodule
                endmodule
