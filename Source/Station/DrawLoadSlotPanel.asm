                module Station
                module DrawLoadSlotPanel
                ; Документация [пять физических строк, сброс наведения и отделение рисунка от дискового действия](../../Docs/SaveSlots.md)
                ; -----------------------------------------
                ; Рамка и пять строк выбора позиции чтения, без выполнения дискового протокола
                ; исходная запись 4, файловые смещения #17C7..#17DB
                ; In:
                ;   активный LD HL содержит SaveSlotState.LoadIndex, штатно 44, либо первый байт заменён на C9
                ;   при активном коде действуют договоры DrawCaptionItem и PrintText, шрифт и таблицы подготовлены, банк станции 0 выбран
                ;   FInterfaceItem имеет допустимую геометрию, индексная пара доступна, HALT рамки получает корректный IRQ с сохранением контекста
                ; Out:
                ;   при активном коде зарегистрированы рамка и заголовок, PanelHoverState.FromPositionRow=FF, Style=0
                ;   из SaveSlotText.LoadOptions печатаются пять исходных CR-строк с видимыми номерами 1..5, последняя завершается LF
                ;   HL содержит продолжение PrintText, DE и BC сохранены, AF статус текста, при полном выводе HL=DECB, AF=0A4A
                ;   HL', DE', BC' сохранены, AF' определяется DrawCaptionItem, IX, IY, I, IFF и IM сохранены при договоре IRQ
                ;   обычный RET даёт SP входному+2, страницы 10 и 18 сохраняют экранный бит, никакой DOS-вызов здесь не исполняется
                ;   при временном C9 сохранены все регистры, флаги, память и страницы, строка наведения не сбрасывается
                ; Corrupt:
                ;   HL, AF, AF', bitmap, текстовое окно, курсор, операнды рисования и байт прежней строки при активном коде
                ; Note:
                ;   исходный хвостовой JP PrintText использует внешний CPU-возврат без нового CALL
                ;   пять видимых подписей не заменяют байтовую формулу имени в обработчике действия, возврат наведения зависит от фактического попадания
                ;   модель сверяет весь bitmap тела независимым текстовым и глифовым алгоритмом, bitmap рамки проверяется отдельным договором
                ; -----------------------------------------
                ; чтение изменяемого индекса панели позиций чтения
Entry:          LD HL, #0000
                CALL @Station.DrawCaptionItem.Entry
                ; обновление строки наведения в FF после нового фона
                LD A, #FF
                LD (@PanelHoverState.FromPositionRow), A
                ; запрет автоматического переноса коротких строк выбора
                XOR A
                LD (@TextWindow.Style), A
                ; чтение пяти CR-строк С позиции 1..5 для хвостовой печати
                LD HL, @SaveSlotText.LoadOptions
                JP @Station.PrintText.Entry

                endmodule
                endmodule
