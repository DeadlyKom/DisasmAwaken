                module Station
                module CloseAllItems
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [выбор команды, фильтр закрытия и сохранение геометрии](../../Docs/MenuCommands.md)
; -----------------------------------------
; Удаление разрешённых флагами элементов из текущего списка рисования
; исходная запись 4, файловые смещения #4781..#47B6
; In:
;   физический список по #F3DE совпадает с текущим DrawListState.HeadOperand и заканчивается старшим байтом 1
;   обёртки содержат индексы в +1,+2, доступны Flags соответствующих FInterfaceItem
;   действует договор DropItemDraw, сдвиг 128 байтов вмещает остаток списка
; Out:
;   BC сохранён, IX указывает ограничитель после последнего оставленного обработчика
;   HL - H=0, L остаток последнего указателя Flags, при исходно пустом списке L=#58
;   DE - индекс последнего рассмотренного элемента, при пустом списке сохранён
;   A - результат последней маски, при удалении 0, при пустом списке исходный A
;   F - итоговый DEC H от H=1, Z=1, Carry сохранён от последней обработки
;   периодический CALL получает EmptyCallback, при удалении EventEnabled=0
;   альтернативные регистры, IY, I и IFF сохранены, SP восстановлен
; Corrupt:
;   HL, DE, AF, IX
; Note:
;   удаляются записи с Flags AND #C0=0 либо Flags AND #60=#60, остальные сохраняют порядок
;   после удаления IX уменьшается на два, сдвинутый на его место элемент проверяется повторно
;   это изменение списка с запросом перестроения, рисователи и callbacks закрытия не вызываются
;   без совпадения физического и текущего списка алгоритм не имеет обещанного результата
; -----------------------------------------
                ; выбор пустого периодического callback перед фильтром закрытия
Entry:          LD HL, @Station.EmptyCallback.Entry
                ; сброс операнда периодического вызова MainLoop
                LD (@MenuCommandState.PeriodicCall), HL
                ; поиск закрываемых элементов в физическом списке рисования
                LD IX, @StationState.DrawList
                ; проверка старшего байта очередной обёртки на ограничитель списка
NextDraw:       LD H, (IX + #01)
                DEC H
                RET Z                                                           ; выход, если старший байт указателя равен 1, список завершён

                ; восстановление старшего байта обёртки после проверки ограничителя
                INC H
                ; чтение указателя обёртки и индекса из её непосредственного операнда
                LD L, (IX + #00)
                INC HL
                LD A, (HL)
                INC HL
                LD H, (HL)
                LD L, A
                ; сохранение индекса для удаления после поиска адреса Flags
                PUSH HL
                ; поиск физического Flags элемента по индексу обёртки
                CALL @Station.GetItemFlags.Entry
                ; проверка группы, нулевая старшая пара разрешает удаление
                LD A, (HL)
                AND @InterfaceFlags.CloseTopMask
                POP DE
                ; переход указателя обхода к следующей паре списка
                INC IX
                INC IX
                JR Z, @Station.CloseAllItems.RemoveDraw                         ; переход, если Flags AND #C0 равен нулю, удалить элемент

                ; проверка совместно установленных битов 6 и 5 через инверсию Flags
                LD A, (HL)
                CPL
                AND @InterfaceFlags.ClosePairMask
                JR NZ, @Station.CloseAllItems.NextDraw                          ; переход, если хотя бы один из битов 6 и 5 сброшен, сохранить этот элемент

                ; удаление элемента со сдвигом оставшейся части списка
RemoveDraw:     CALL #C873
                ; возврат к сдвинувшейся на прежнее место паре для повторной проверки
                DEC IX
                DEC IX
                JP @Station.CloseAllItems.NextDraw

                endmodule
                endmodule
