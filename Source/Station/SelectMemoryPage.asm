                module SelectMemoryPage
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [StationCore.md](../../Docs/StationCore.md)
; -----------------------------------------
; Сохранение теневого #7FFD и переключение страницы с сохранением BC
; исходная запись 4, файловые смещения #064B..#0655
; In:
;   AF - A содержит полный байт управления #7FFD
; Out:
;   A записан в StationState.CurrentPage и передан инструкцией OUT в порт #7FFD, все программные регистры и F сохранены
; Corrupt:
;   нет изменяемых регистров
; Note:
;   BC временно занимает номер порта и восстанавливается через стек, SP восстанавливается обычным RET
;   альтернативные и индексные регистры, I и IFF сохраняются, вход сам не запрещает прерывания
;   сначала меняется тень, затем выполняется OUT, модель не доказывает атомарность относительно IRQ или аппаратное переключение
; -----------------------------------------
Entry:          PUSH BC
                ; обновление тени до выполнения аппаратной записи
                LD (@StationState.CurrentPage), A
                ; подготовка полного адреса порта управления страницами
                LD BC, @Hardware.PagingPort
                ; передача полного байта A в порт, прерывания этим входом не запрещаются
                OUT (C), A
                POP BC
                RET

                endmodule
                endmodule
