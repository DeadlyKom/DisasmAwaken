                module Station
                module StopMusic
                ; Документация [полный портовый протокол AY, IFF, страница и входной кадр POP HL затем RET](../../Docs/StopMusic.md)
                ; -----------------------------------------
                ; Глушение AY в банке музыки, установка IM 1 и выход через двухсловную CPU-рамку
                ; исходная запись 4, файловые смещения #0656..#066E
                ; In:
                ;   HL входа заменяется первым словом CPU-стека, DE, BC и AF не задают музыкальные параметры
                ;   на CPU-стеке FStopMusicReturnFrame, HLWord первым словом и ReturnAddress вторым, доступны четыре байта чтения
                ;   все восемь байтов SP-4..SP+3 находятся в фиксированной RAM, не пересекают CurrentPage по 6306 и исполняемый код
                ;   исходный MUZ1.C загружен в банк 3 по DB00, переключение 7FFD не заблокировано
                ;   станционный низкий код 63AA и SelectMemoryPage доступны, действуют договоры Music.Stop и ClearAyRegisters, четыре байта ниже SP доступны для временной записи без перекрытия кода
                ;   точный регистровый и портовый результат ниже относится к исполнению без вмешательства IRQ, собственных DI либо EI здесь нет
                ; Out:
                ;   HL=FStopMusicReturnFrame.HLWord, DE=0, BC=BFFD, AF=1042 OR входной Carry
                ;   основной IX и все альтернативные пары сохранены, IY=5C3A, I=3F, IM=1, IFF сохранён
                ;   страница и тень сначала принудительно 13, затем 10, прежний экранный бит и исходный банк не восстанавливаются
                ;   через реальные FFFD и BFFD записаны нули в AY-регистры 13..0 в убывающем порядке, регистры портов AY 14 и 15 не затронуты
                ;   первое слово входного стека снято в HL, второе становится PC, конечный SP равен входному+4
                ;   глушение не изменяет внутренние данные музыкального синтеза и не запрещает будущий PlayFrame само по себе
                ; Corrupt:
                ;   HL, DE, BC, AF, IY, I, IM, R, страницы, AY 13..0, четыре временных байта стека, SP и PC по двухсловному возврату
                ; Note:
                ;   вход требует двух слов, обычный адрес возврата занимает именно второе слово FStopMusicReturnFrame
                ;   происхождение HLWord в настоящем вызывающем пути пока не установлено, его нельзя без доказательства назвать сохранённым входным HL
                ;   IM 1 и LD I,A не меняют IFF, собственного DI либо EI в процедуре нет
                ;   R получает 143 M1 по модулю 128 с сохранением бита 7 без IRQ, максимальная временная глубина ниже входного SP равна четырём байтам
                ;   окончательный Carry сохраняется от входа через музыкальный DEC D и оба банковых вызова
                ;   модель исполняет исходный Music.Stop без подмены портов, IRQ и нативный выход станции не подтверждены
                ;   в отдельной серии перебраны все 65536 значений HLWord и связанных с ними входных IY, точный перенос слова в HL и установка IY проверены без установления штатного вызывающего пути
                ; -----------------------------------------
                ; выбор абсолютной страницы музыки 3 с ROM 1
Entry:          LD A, @StationIrqConst.MusicPage
                ; обновление тени и аппаратной страницы перед входом MUZ1
                CALL @Station.SelectMemoryPage.Entry
                ; обнуление исходных AY-регистров 13..0 настоящим Music.Stop
                CALL @Music.Stop.Entry
                ; установка режима IM 1 без изменения разрешения прерываний IFF
                IM 1
                ; выбор I=3F для контекста стандартной ROM
                LD A, #3F
                LD I, A
                ; установка системного IY в 5C3A
                LD IY, @LoaderConst.SystemIY
                ; выбор абсолютной страницы станции 10 независимо от прежнего экранного бита
                LD A, @StationIrqConst.StationPage
                CALL @Station.SelectMemoryPage.Entry
                ; снятие первого входного слова HLWord, адрес возврата находится под ним
                POP HL
                ; возврат по второму слову FStopMusicReturnFrame, итоговый SP увеличен на четыре
                RET

                endmodule
                endmodule
