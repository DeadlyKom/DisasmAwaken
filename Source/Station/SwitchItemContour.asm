                module Station
                module SwitchItemContour
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [два индекса, порядок изменения Flags, одинаковые записи и защита указателя](../../Docs/ItemContourSwitch.md)
; -----------------------------------------
; Сброс формы старого элемента, установка формы нового и две перерисовки центрируемых рамок
; исходная запись 4, файловые смещения #4806..#482C
; In:
;   HL - индекс старого FInterfaceItem, DE - индекс нового, индексы могут совпадать
;   в банке 0 доступны DrawCenteredItem и станционные таблицы, действуют договоры его геометрии, текста и регистрации
;   действуют договоры SuspendPointer и ResumePointer, стек вмещает FItemContourFrame и вложенные кадры помощников
; Out:
;   HL и DE содержат входной индекс нового элемента, BC сохраняется
;   сначала у старого Flags сброшен только бит 0 и старый элемент перерисован, затем у нового Flags установлен бит 0 и новый элемент перерисован
;   при равных индексах одна запись рисуется дважды, конечный бит 0 установлен, остальные биты сохранены
;   AF - A=C3, F соответствует последнему проходу текста DrawCenteredItem, ResumePointer сохраняет этот AF
;   HL' рабочий, его старший H' сохраняется, DE', BC', IX, IY, I и IFF сохраняются инструкциями и допустимыми путями помощников
;   обе рамки зарегистрированы, bitmap и текстовое состояние изменены рисователем, указатель возобновлён, UpdateBlocked=0
;   SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, AF, HL', AF', Flags двух записей, bitmap, текстовое состояние и карта владельцев
; Note:
;   новый индекс хранится в двухбайтовом SavedNewIndex на стеке до завершения первой перерисовки
;   перед каждой перерисовкой выполняется SuspendPointer, после неё ResumePointer, вокруг всей пары общего единственного запрета нет
;   функция не проверяет равенство индексов и не отменяет первую перерисовку при последующей проблеме текста
;   интеграционная модель проверила 1280 вызовов с настоящими помощниками, собственный независимый oracle всего итогового bitmap в ней не заявляется
; -----------------------------------------
                ; сохранение нового индекса в FItemContourFrame.SavedNewIndex до рисования старого элемента
Entry:          PUSH DE
                ; сохранение старого индекса в DE, GetItemFlags изменит HL на адрес его поля
                LD E, L
                LD D, H
                CALL @Station.GetItemFlags.Entry
                ; сброс только бита выбора формы контура старой записи
                RES @InterfaceFlags.FrameBit, (HL)
                ; восстановление старого индекса из DE для полного рисователя
                LD H, D
                LD L, E
                ; восстановление фона указателя и запрет его периодического изменения перед первым рисунком
                CALL @Station.SuspendPointer.Entry
                ; перерисовка старой рамки после сброса бита контура
                CALL @Station.DrawCenteredItem.Entry
                ; возобновление указателя после первого завершённого рисунка
                CALL @Station.ResumePointer.Entry
                ; восстановление нового индекса из SavedNewIndex, первый этап больше не использует этот стековый слот
                POP HL
                ; сохранение нового индекса в DE перед получением адреса его Flags
                LD E, L
                LD D, H
                CALL @Station.GetItemFlags.Entry
                ; установка только бита выбора формы контура новой записи
                SET @InterfaceFlags.FrameBit, (HL)
                ; восстановление нового индекса в HL для второй перерисовки
                LD H, D
                LD L, E
                ; повторный запрет указателя и восстановление его фона перед новым рисунком
                CALL @Station.SuspendPointer.Entry
                ; перерисовка новой рамки после установки бита контура
                CALL @Station.DrawCenteredItem.Entry
                ; возобновление указателя с сохранением AF второго текстового прохода
                CALL @Station.ResumePointer.Entry
                RET

                endmodule
                endmodule
