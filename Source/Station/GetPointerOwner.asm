                module GetPointerOwner
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [CellMap.md](../../Docs/CellMap.md)
; -----------------------------------------
; Преобразование пиксельных координат указателя в знакоместо и чтение его владельца
; исходная запись 4, файловые смещения #3D96..#3DA5
; In:
;   StationState.PointerXY - пиксельные X и Y в двух последовательных байтах
; Out:
;   HL - адрес байта карты, BC - B исходный Y SHR 3, C исходный X SHR 3
;   AF - A содержимое байта владельца, F соответствует адресному сложению GetCellOwner
; Corrupt:
;   HL, BC, AF
; Note:
;   каждая координата делится на восемь тремя логическими сдвигами, знаковой обработки нет
;   при Y=192..255 читается четвёртая страница #8900..#89FF вне видимой карты
;   исполнение последовательно продолжается в GetCellOwner, RET использует исходный адрес возврата
;   DE, альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
; -----------------------------------------
                ; чтение пиксельных координат указателя, младший байт X и старший Y
Entry:          LD BC, (@StationState.PointerXY)
                ; расчёт строки знакомест делением пиксельного Y на восемь
                SRL B
                SRL B
                SRL B
                ; расчёт колонки знакомест делением пиксельного X на восемь
                SRL C
                SRL C
                SRL C

                ; JP @Station.GetCellOwner.Entry, продолжение в GetCellOwner.asm

                endmodule
                endmodule
