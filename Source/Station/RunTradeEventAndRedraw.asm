                module Station
                module RunTradeEventAndRedraw
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [зависимость подсветки от рисунка, событие колонки, банковый запуск и дополнительные входы рисователя](../../Docs/TradePanel.md)
                ; -----------------------------------------
                ; Запись торгового кода события, запуск LANG и обновление статуса и торговой панели
                ; исходная запись 4, файловые смещения #12F0..#130C
                ; In:
                ;   AF - A код торгового события, LANG доступен в банке 6, стек вне переключаемого окна
                ;   тень страницы согласована с портом, bit5 снят, действуют RunMarketScript и выбранные им команды
                ;   после сценария выполняются условия BeginScreenUpdate, DrawItem00, DrawTradePanel и EndScreenUpdate
                ;   код, таблицы и геометрия рисователей допустимы, HALT активной торговой рамки пробуждается корректно
                ; Out:
                ;   ScriptCallState.EventCode получает исходный A, затем выбран банк LANG 6 с ROM 1 и запущен RunMarketScript
                ;   после возврата сценария выбран банк 0 с ROM 1, сначала выполнен BeginScreenUpdate, затем DrawItem00 и DrawTradePanel, затем EndScreenUpdate
                ;   HL, DE и BC в конце принадлежат последнему активному рисователю либо сценарию, экранные обёртки сохраняют эти пары
                ;   основной A=10, F от DrawTradePanel, при активном Entry это флаги счётчика строк, AF' рабочий от указателя
                ;   IX и прочие регистры, изменённые сценарием, не восстанавливаются отдельным кадром, последующие изменения строго по договорам рисователей
                ;   CurrentPage и порт=10, показана обновлённая база, UpdateBlocked=0, SP обычного возврата равен входному SP+2
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY и игровое состояние только по исполненным командам RunMarketScript и последующим рисователям, отдельного сохранения этих результатов нет
                ; Note:
                ;   это код события для ReadEventCode, а не адрес начала сценария, интерпретатор всегда начинает в CA8F
                ;   первые два выбора банка сохраняют старшие управляющие биты тени через SelectRamBank, последующее обновление экрана принудительно выбирает 17,18,10
                ;   модель реально исполняет интерпретатор с явно пустым NUL-сценарием в моделируемом LANG, затем оба рисователя
                ;   исходные команды торговли для событий 9 и 10 этой моделью не исполнены, изменения денег и грузов ею не подтверждаются
                ; -----------------------------------------
                ; -----------------------------------------
                ; Код события и банковый сценарий
                ; -----------------------------------------
                ; сохранение кода события для ReadEventCode в торговом интерпретаторе
Entry:          LD (@ScriptCallState.EventCode), A
                ; выбор LANG банка 6 с сохранением остальных управляющих битов страницы
                LD A, @TradePanelConst.LanguagePage
                CALL @Station.SelectRamBank.Entry
                ; запуск общего сценария CA8F, событие будет прочитано его командами
                CALL @Text.RunMarketScript.Entry
                ; возврат станционного банка 0 после завершения сценария
                LD A, @ScreenUpdateConst.VisiblePage
                CALL @Station.SelectRamBank.Entry
                ; -----------------------------------------
                ; Экран после завершения сценария
                ; -----------------------------------------
                ; создание теневого снимка перед обновлением статуса и товарной панели
                CALL @Station.BeginScreenUpdate.Entry
                ; обновление денег, тоннажа, ранга и статуса стандартным рисователем
                CALL @Station.DrawItem00.Entry
                ; перерисовка товарной рамки и содержимого, пересчёт высоты подсветки
                CALL @Station.DrawTradePanel.Entry
                ; возврат указателя и показ обновлённой базы
                CALL @Station.EndScreenUpdate.Entry
                RET

                ; -----------------------------------------
                endmodule
                endmodule
