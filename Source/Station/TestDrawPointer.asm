                module Station
                module TestDrawPointer
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [список указателей и сохранённая геометрия](../../Docs/InterfaceBounds.md)
; -----------------------------------------
; Проверка наличия указателя в текущем списке без изменения исходного HL
; исходная запись 4, файловые смещения #6B64..#6B7E
; In:
;   HL - произвольное сохраняемое значение, DE - искомый указатель обработчика
;   DrawListState.HeadOperand задаёт читаемый список с ограничителем старшего байта 1
; Out:
;   HL, DE и BC сохранены, при совпадении AF=#0050, Z=1
;   при отсутствии A=1,Z=0, Carry равен сравнению последнего указателя с DE, при пустом списке входному Carry
;   при отсутствии остальные биты F равны нулю
; Corrupt:
;   AF
; Note:
;   сравнивается сам указатель Handler, не индекс из его операнда
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   ограничитель обрабатывается до сравнения, указатель со старшим байтом 1 как элемент не проверяется
; -----------------------------------------
                ; сохранение исходного HL, результат поиска возвращается в AF
Entry:          PUSH HL
                ; чтение текущего списка для сравнения указателей с DE
                LD HL, (@DrawListState.HeadOperand)
                ; проверка старшего байта следующего указателя на ограничитель
NextPointer:    INC HL
                LD A, (HL)
                DEC A
                JR Z, @Station.TestDrawPointer.Return                           ; переход, если достигнут ограничитель, вернуть отсутствие совпадения

                INC A
                ; сравнение старшего байта указателя со старшим байтом DE
                CP D
                INC HL
                JR NZ, @Station.TestDrawPointer.NextPointer                     ; переход, если старшие байты различаются, проверить следующий указатель

                ; возврат к младшему байту текущего указателя для полного сравнения
                DEC HL
                DEC HL
                LD A, (HL)
                ; сравнение младшего байта указателя с E
                CP E
                INC HL
                INC HL
                JR NZ, @Station.TestDrawPointer.NextPointer                     ; переход, если младшие байты различаются, продолжить поиск

                ; формирование #FF перед INC, совпадение возвращает A=0,Z=1,H=1
                LD A, #FF
                ; формирование итогового A, ноль при совпадении и единица при отсутствии
Return:         INC A
                POP HL
                RET

                endmodule
                endmodule
