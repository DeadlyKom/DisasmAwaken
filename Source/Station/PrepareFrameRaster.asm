                module Station
                module PrepareFrameRaster
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [StationSpans.md](../../Docs/StationSpans.md)
; -----------------------------------------
; Настройка кодов краёв, обрезка внутренней ширины и табличное вычисление адреса рамки
; исходная запись 4, файловые смещения #5F4E..#5FAC
; In:
;   DE - E внутренняя ширина 0..30, D сохраняется, BC - B знаковая строка знакомест, C знаковая байтовая колонка
;   подготовлены страницы #82 старших байтов строк, #83 младших байтов строк и #84 горизонтальных вкладов адреса
; Out:
;   HL - табличный адрес, DE - E скорректированная ширина, BC - B старший байт адреса, C исходная неотрицательная колонка либо ноль
;   AF - A младший байт адреса, F от OR двух младших вкладов, HL' - L' прежний B минус один по модулю 256
;   AF' равен #0100 без отсечения, #0044 для отрицательной колонки, #0101 при правом отсечении
; Corrupt:
;   HL, DE, BC, AF, HL', AF'
; Note:
;   LeftCode и RightCode восстанавливаются на каждом входе, затем отдельные записи краёв при необходимости заменяются NOP
;   при отрицательной C новый E равен max(0, прежний E плюс знаковый C), C становится нулём, при отрицательной сумме LeftCode обнуляется
;   при неотрицательной C и сумме C+E не меньше 31 новый E равен max(0,30-C), при C больше 30 RightCode обнуляется
;   отрицательный B даёт нулевую строку для таблиц, но L' сохраняет знаковую последовательность исходных строк
;   индексы таблиц получаются тремя циклическими поворотами байта, не обычным 16-битным умножением
;   D, H', альтернативные DE', BC', IX и IY сохраняются, SP восстанавливается, исходные оба AF не сохраняются
;   пиксели не записываются, SpanSkip на этом входе не изменяется
; -----------------------------------------
                ; восстановление записи левого края и шага колонки после предыдущих отсечений
Entry:          LD HL, @SpanOpcode.LeftPair
                LD (@StationRaster.LeftCode), HL
                ; восстановление записи правого края перед настройкой нового прямоугольника
                LD A, @SpanOpcode.WriteRight
                LD (@StationRaster.RightCode), A
                ; начальное разрешение обоих краёв в альтернативных условиях, Z'=0 и Carry'=0
                XOR A
                INC A
                EX AF, AF'
                LD A, C
                ; проверка знака исходной байтовой колонки
                AND A
                JP P, @Station.PrepareFrameRaster.CheckRight                    ; переход, если колонка неотрицательна и требуется проверка правого отсечения

                ; расчёт остатка внутренней ширины после выхода левого края за нулевую колонку
                LD A, E
                ADD A, C
                JP P, @Station.PrepareFrameRaster.LeftWidth                     ; переход, если сумма колонки и внутренней ширины неотрицательна, запись левого края не отключается

                ; отмена левой записи вместе с первым шагом колонки при отрицательном остатке
                XOR A
                LD (@StationRaster.LeftCode), A
                LD (@StationRaster.LeftCode + 1), A
                ; сохранение обрезанной ширины и привязка отрицательной колонки к нулю
LeftWidth:      LD E, A
                LD C, #00
                ; выбор режима Z'=1, левый образец строки будет заменён серединой
                EX AF, AF'
                XOR A
                JR @Station.PrepareFrameRaster.RestoreAF

                ; расчёт положения правой части полосы перед проверкой последней колонки
CheckRight:     LD A, C
                ADD A, E
                ; проверка, помещается ли правый край в 32 байтовые колонки
                CP @ScreenConst.LastColumn
                JP C, @Station.PrepareFrameRaster.RowAddress                    ; переход, если колонка плюс внутренняя ширина меньше 31, правое отсечение не требуется

                ; расчёт допустимой внутренней ширины 30 минус исходная колонка
                SUB @ScreenConst.LastColumn
                CPL
                ADD A, E
                JP P, @Station.PrepareFrameRaster.RightWidth                    ; переход, если допустимая внутренняя ширина неотрицательна, запись правого края сохраняется

                ; отмена правой записи и нулевая внутренняя ширина для колонки правее допустимого края
                XOR A
                LD (@StationRaster.RightCode), A
RightWidth:     LD E, A
                ; выбор режима Carry'=1, правый образец строки будет заменён серединой
                EX AF, AF'
                SCF
RestoreAF:      EX AF, AF'
RowAddress:     LD A, B
                ; проверка отрицательной строки перед выборкой адреса, исходный индекс остаётся в A
                BIT 7, B
                JR Z, @Station.PrepareFrameRaster.RowCounter                    ; переход, если строка неотрицательна, для таблицы используется исходный B

                ; привязка отрицательной строки к нулю только для получения начального адреса
                LD B, #00
                ; подготовка предыдущего знакового индекса строки для AdvanceClipRow
RowCounter:     EXX
                DEC A
                LD L, A
                EXX
                ; расчёт циклического байтового индекса строковой таблицы тремя поворотами
                LD L, B
                RLC L
                RLC L
                RLC L
                ; выбор старшего и младшего байтов строкового вклада адреса из соседних страниц
                LD H, @StationTables.RowHighPage
                LD B, (HL)
                INC H
                LD A, (HL)
                INC H
                ; расчёт циклического байтового индекса горизонтального вклада адреса
                LD L, C
                RLC L
                RLC L
                RLC L
                ; объединение строкового и горизонтального вкладов младшего байта адреса
                OR (HL)
                LD L, A
                LD H, B
                RET

                endmodule
                endmodule
