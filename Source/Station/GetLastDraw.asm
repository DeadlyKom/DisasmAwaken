                module Station
                module GetLastDraw
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [список указателей и сохранённая геометрия](../../Docs/InterfaceBounds.md)
; -----------------------------------------
; Получение последнего указателя перед ограничителем текущего списка рисования
; исходная запись 4, файловые смещения #6B52..#6B63
; In:
;   DrawListState.HeadOperand задаёт читаемый список FDrawListEntry, достигающий старшего байта 1
;   для непустого списка возвращается последний обработчик, при пустом читается слово перед началом
; Out:
;   HL - последнее слово перед ограничителем, DE и BC сохранены
;   AF - A старший байт этого слова, F=#42 OR входной Carry
; Corrupt:
;   HL, AF
; Note:
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   отсутствует проверка пустого списка, результат тогда не обязан быть указателем обработчика
;   младший байт ограничителя не проверяется, обход не имеет встроенного предела
; -----------------------------------------
                ; чтение текущей базы списка из изменяемого операнда RebuildInterface
Entry:          LD HL, (@DrawListState.HeadOperand)
                ; просмотр старших байтов указателей до ограничителя 1
ScanHigh:       INC HL
                LD A, (HL)
                INC HL
                DEC A
                JP NZ, @Station.GetLastDraw.ScanHigh                            ; переход, если старший байт не равен 1, продолжить просмотр

                ; возврат на старший байт слова перед ограничителем, проверка пустого списка отсутствует
                DEC HL
                DEC HL
                DEC HL
                LD A, (HL)
                DEC HL
                LD L, (HL)
                LD H, A
                RET

                endmodule
                endmodule
