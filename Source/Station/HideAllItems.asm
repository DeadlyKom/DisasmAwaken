                module Station
                module HideAllItems
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [выбор команды, фильтр закрытия и сохранение геометрии](../../Docs/MenuCommands.md)
; -----------------------------------------
; Отключение периодического callback и установка состояния скрытого интерфейса
; исходная запись 4, файловые смещения #4770..#4780
; In:
;   код и изменяемые операнды станции доступны, выполняется договор пробуждения пяти HALT
; Out:
;   HL=EmptyCallback, DE и BC сохранены, A=1, F сохранён
;   периодический CALL по #9A88 получает EmptyCallback, состояние #9CAA=1
;   альтернативные и индексные регистры сохранены, SP восстановлен при договоре пробуждения
; Corrupt:
;   HL, AF
; Note:
;   пять HALT не являются пятью вызовами аппаратного ISR в модели
;   сам код не меняет I и IFF, прогресс HALT требует внешнего пробуждения
;   признак #9CAA используется диспетчером при последующем событии вне элемента
; -----------------------------------------
                ; выбор пустого обработчика вместо периодического callback
Entry:          LD HL, @Station.EmptyCallback.Entry
                ; обновление операнда периодического CALL в MainLoop
                LD (@MenuCommandState.PeriodicCall), HL
                ; выбор установленного состояния скрытого интерфейса
                LD A, #01
                ; обновление признака, снимаемого диспетчером при событии вне элемента
                LD (@MenuCommandState.Hidden), A
                ; ожидание пяти внешних пробуждений исходной последовательностью HALT
                HALT
                HALT
                HALT
                HALT
                HALT
                RET

                endmodule
                endmodule
