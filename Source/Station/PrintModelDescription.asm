                module Station
                module PrintModelDescription
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [реальные страницы, выходной AF выбора банка и сохранённая граница прокрутки](../../Docs/DescriptionBankCalls.md)
                ; -----------------------------------------
                ; Банковая печать выбранного описания модели с возвратом в станционный банк
                ; исходная запись 4, файловые смещения #0BFE..#0C0E
                ; In:
                ;   HL - слово прокрутки, младший L задаёт пропускаемые строки по договору PrintPreviewTextRows
                ;   ShipPanelState.Selector, два операнда индекса D3D, окно и глиф подготовлены для выбранного описания
                ;   порт и CurrentPage согласованы, станционный банк 0, paging не заблокирован, CPU-стек вне сменяемого окна
                ; Out:
                ;   HL, DE, BC - результат настоящего D3D.PrintPreviewTextRows, курсор и bitmap соответствуют его договору
                ;   AF - A=(исходная CurrentPage AND F8) OR 10, F от логического OR страницы, статус текста заменён выбором банка
                ;   все альтернативные и индексные регистры, I, IFF и IM сохраняются, SP обычного возврата равен входному SP+2
                ;   порт и CurrentPage выбирают сначала банк 4 с ROM 1, затем станционный банк 0 с ROM 1, верхние управляющие разряды сохраняются
                ; Corrupt:
                ;   HL, DE, BC, AF
                ; Note:
                ;   входной A не выбирает таблицу, он заменяется байтом ShipPanelState.Selector
                ;   прежний номер банка не восстанавливается, договор требует исходный станционный банк 0
                ;   отказы и незавершение печати подчиняются D3D.PrintPreviewTextRows, дополнительной проверки здесь нет
                ; -----------------------------------------
                ; выбор банка 4 для исходного описательного текста и его печатателя
Entry:          LD A, #14
                CALL @Station.SelectRamBank.Entry
                ; чтение селектора из существующего станционного состояния
                LD A, (@ShipPanelState.Selector)
                ; реальная печать с байтовым пропуском строк через D3D
                CALL @D3D.PrintPreviewTextRows.Entry
                ; возврат в банк 0, выходной AF теперь принадлежит выбору страницы
                LD A, #10
                CALL @Station.SelectRamBank.Entry
                RET

                endmodule
                endmodule
