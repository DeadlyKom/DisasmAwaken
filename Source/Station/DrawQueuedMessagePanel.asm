                module Station
                module DrawQueuedMessagePanel
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [отдельные входы наведения и действия, разные фильтры закрытия и изменяемая строка уведомления](../../Docs/MessagePanels.md)
                ; -----------------------------------------
                ; Рамка уведомления и вывод выбранной изменяемым операндом строки с выравниванием
                ; исходная запись 4, файловые смещения #1136..#1144
                ; In:
                ;   QueuedMessageState.ItemIndex содержит индекс допустимой FInterfaceItem
                ;   HL, DE, BC и AF входные значения не являются параметрами, действуют договоры DrawCaptionItem и его HALT
                ;   TextRowState.Row содержит допустимый байтовый индекс LF-записи QueuedMessageText.Entry
                ;   после выбранной строки есть читаемый запас для просмотра слов, выполняются ограничения JustifyAfterLF и PrintJustified
                ; Out:
                ;   сначала зарегистрирована панель, нарисованы рамка и заголовок, Style=0
                ;   TextRowState.Row выбирает запись пропуском Row+1 разделителей LF от CE19, затем исполняется PrintJustified
                ;   HL, DE, BC и AF соответствуют PrintJustified с курсором и размерами, установленными DrawCaptionItem
                ;   HL', DE', BC', IX, IY сохраняются при договоре HALT, AF' рабочий от рамки
                ;   SP обычного возврата равен входному SP+2, I, IFF, IM и страницы собственный код не меняет
                ;   сама процедура не меняет операнды ItemIndex и Row, пишет bitmap, курсор и рабочие операнды выравнивателя
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', bitmap, текстовое окно и рабочие операнды согласно вызываемым процедурам
                ; Note:
                ;   непосредственное значение LD A по 6E91 изменяется QueueTextRow, исходный ноль не является постоянным выбором строки
                ;   это уведомления о сделках, оснащении и других отказах, а не окно справки
                ;   проверены исходные строки 0..13, из этого не выводится размер всей текстовой таблицы
                ;   84 полных прохода сравнивают bitmap содержимого с независимым расчётом слов и исходного шрифта
                ;   рамка имеет отдельный договор, аппаратные IRQ и нативный запуск моделью не подтверждены
                ; -----------------------------------------
                ; чтение изменяемого индекса уведомления для рамки и регистрации
Entry:          LD HL, #0000
                ; рисование рамки и заголовка, установка внутренней области содержимого
                CALL @Station.DrawCaptionItem.Entry
                ; чтение изменяемого номера сообщения, записанного QueueTextRow в операнд Row
                LD A, #00
                ; выбор исходной таблицы уведомлений, начинающейся с LF
                LD HL, @QueuedMessageText.Entry
                ; поиск выбранной LF-записи и вывод с исходным выравниванием слов
                CALL @Station.JustifyAfterLF.Entry
                RET

                endmodule
                endmodule
