; -----------------------------------------
; Подготовка заполненных байтов левого края, середины и правого края полосы
; исходная запись 4, файловые смещения #621F..#6223
; In:
;   нет входных параметров
; Out:
;   DE - D и E равны #FF, BC - C равен #FF, B сохраняется
; Corrupt:
;   DE, BC
; Note:
;   основные HL, AF, альтернативные и индексные регистры сохраняются, SP восстанавливается
;   подготавливаются три части будущей полосы, запись пикселей выполняется отдельно
; -----------------------------------------
                ; выбор полностью заполненной полосы для последующей записи трёх частей строки
Entry:          LD DE, @SpanPattern.SolidPair
                LD C, E
                RET

