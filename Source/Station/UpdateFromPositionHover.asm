                module Station
                module UpdateFromPositionHover
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [точные ограничения, изменяемые строки и различие пиксельного и строчного входов](../../Docs/PanelHover.md)
                ; -----------------------------------------
                ; Обновление XOR-полосы списка С позиции 1..5 с сохранением номера только по Z=0
                ; исходная запись 4, файловые смещения #17B7..#17C6
                ; In:
                ;   IX - допустимая FInterfaceItem списка С позиции 1..5, подготовлены указатель, шрифт, таблицы адресации и банковое XOR-ядро
                ;   список рисования непуст и завершается исходным маркером, PointerY=0..191, выбран станционный банк 0
                ;   PanelHoverState.FromPositionRow содержит прежний номер либо FF, его операнд доступен для записи
                ;   действуют договоры UpdatePixelHover, XorItemRow, XorPointerRow, SuspendPointer и ResumePointer
                ; Out:
                ;   перед UpdatePixelHover установлены HL=DrawItem44.Entry, DE=2803, A прежний номер
                ;   D=40 пикселей передаётся прямо, E=3, высота FInterfaceItem не ограничивает область этого входа
                ;   при Z=1 возвращённого UpdatePixelHover сохранённый номер не меняется, выходные регистры принадлежат соответствующей ветви отказа или совпадения
                ;   при Z=0 весь возвращённый A записан в PanelHoverState.FromPositionRow, даже если A=0 либо повторная проверка вернула высоту
                ;   HL, DE, BC и AF принадлежат UpdatePixelHover, HL', DE', BC', IX, IY сохраняются, AF' рабочий только на обновлении указателя
                ;   при соблюдении договоров SP обычного возврата равен входному SP+2, I, IFF и IM не меняются
                ; Corrupt:
                ;   HL, DE, BC, AF, AF' на изменении полосы и указателя
                ; Note:
                ;   обновление допускается лишь для точного адреса рисователя в последнем слове списка
                ;   Z показывает отсутствие обновления, он не равнозначен нулю A
                ;   две проверки PointerY не атомарны, обёртка не исправляет служебный результат позднего отказа
                ;   рисователь сбрасывает свой операнд строки в FF после замены фона, эта обёртка сама фон панели не рисует
                ;   названия списков взяты из исходных заголовков и текстов, назначение действий их строк этим контрактом не устанавливается
                ; -----------------------------------------
                ; выбор 40 пикселей и отступа 3 для списка С позиции 1..5
Entry:          LD DE, @PanelHoverConst.PositionsPixels
                ; выбор точного рисователя, который должен быть последним в списке
                LD HL, @Station.DrawItem44.Entry
                ; чтение изменяемого номера прежней XOR-полосы, FF означает её отсутствие
                LD A, #FF
                ; проверка положения указателя и обновление полосы через UpdatePixelHover
                CALL @Station.UpdatePixelHover.Entry
                RET Z                                                           ; выход, если UpdatePixelHover вернул Z=1, сохранить прежний номер

                ; сохранение полного результата A только по Z=0, нулевая строка тоже допустима
                LD (@PanelHoverState.FromPositionRow), A
                RET

                endmodule
                endmodule
