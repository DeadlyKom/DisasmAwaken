                ; Документация [физические владельцы пяти пустых наведений и сохранение каждого AF](../../Docs/PassivePanelHovers.md)
                ; -----------------------------------------
                ; Пустая JP-обёртка наведения панели контракта
                ; исходная запись 4, файловые смещения #4A55..#4A57
                ; In:
                ;   нет регистровых параметров, исходный код Entry и обычный CPU-возврат доступны
                ;   IRQ и NMI не вмешиваются между входом и обычным возвратом, точный счёт R относится к этому условию
                ; Out:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, I, IFF и IM сохранены, SP после RET равен входному+2
                ;   память, bitmap, список рисования, курсор, страница и порты не меняются
                ; Corrupt:
                ;   R, SP и PC по обычному возврату
                ; Note:
                ;   физическая FInterfaceItem 32 указывает на эту JP-обёртку, исходный заголовок подтверждает назначение панели
                ;   основное действие Entry+3 не выполняется при наведении, его отдельный алгоритм не подменяется этим пустым контрактом
                ;   обёртка не создаёт нового кадра CALL, обе точки сохраняют все 65536 значений AF
                ;   R увеличивает младшие семь битов на 2 modulo 128, бит 7 сохраняется, IRQ в модели не исполняется
                ; -----------------------------------------
                ; передача наведения панели контракта в её пустой обработчик без нового CPU-кадра
Entry:          JP @Station.IgnoreContractHover.Entry

                endmodule
