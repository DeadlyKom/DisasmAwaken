                module Station
                module DrawDecodedMessagePanel
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [фиксированный ключ расшифрованной системы, неизвестный код 98A0 и реальный перенос в 4000](../../Docs/DecodedPanel.md)
                ; -----------------------------------------
                ; Рисование сообщения расшифровки либо перенос финального загрузчика при точном ключе и коде FE
                ; исходная запись 4, файловые смещения #1080..#10BC
                ; In:
                ;   DecodedPanelState.ItemIndex задаёт допустимую FInterfaceItem, действуют договоры DrawCaptionItem и его HALT, текстовые таблицы и шрифт готовы
                ;   SignatureInput.Entry содержит текущие два слова, DecodedPanelState.Unknown98A0 доступен как числовой проверяемый байт
                ;   для обычного возврата действуют условия PrintDecodedMessage, MessageIndex задаёт допустимую завершающуюся LF-строку
                ;   для финального пути выполняются условия StationFinalExit.LoadFinal после исходного переноса в 4000, MUZ1 загружен и TR-DOS доступен
                ; Out:
                ;   сначала нарисованы рамка и заголовок, затем TextWindow.Style=1 независимо от исходного стиля
                ;   если текущее FirstWord не равно 4B37 либо SecondWord не равно 4E25, выполнен хвостовой PrintDecodedMessage
                ;   если оба слова совпали, только точный Unknown98A0=FE выбирает финальный переход, все другие коды тоже печатают сообщение
                ;   на обычном выходе HL и AF относятся к PrintDecodedMessage, DE=4B37 при несовпавшем первом слове, иначе DE=4E25, BC сохранён
                ;   HL', DE', BC', IX,IY сохраняются на обычном пути, AF' рабочий от DrawCaptionItem, I и IFF сохраняются при договоре HALT
                ;   на финальном пути DI запрещает прерывания, 512 исходных байтов 6E11..7010 копируются в 4000..41FF, затем JP входит в StationFinalExit.LoadFinal
                ;   последующие регистры, страница, AY, системные данные и замена SP соответствуют финальному загрузчику, возврата в панель он не предусматривает
                ;   MessageIndex, оба слова текущего ключа и Unknown98A0 сама панель не меняет
                ; Corrupt:
                ;   HL, DE, AF, AF', bitmap и текстовое окно, на финальной ветви также SP, I, IFF, IM, IY, AY и внешнее состояние загрузчика
                ; Note:
                ;   фиксированный ключ соответствует системе из исходного сообщения, генерация имени даёт Дзета-43/78-Д
                ;   роль и писатели Unknown98A0 ещё не установлены, код FE является доказанным условием этой ветви, а не названным без доказательства счётчиком миссий
                ;   финальный код хранится по 6E11 и исполняется по 4000, эти два контекста не смешиваются
                ;   большой перенос включает соседние процедуры после девятибайтового имени, все 512 байтов сохранены
                ;   модель охватывает все значения обоих сравниваемых слов по отдельности и все байты 98A0, целый bitmap рамки имеет отдельный договор
                ;   полные финальные проходы останавливаются до TR-DOS, загрузка с диска и аппаратные IRQ не проверены
                ; -----------------------------------------
                ; -----------------------------------------
                ; Рамка и режим печати сообщения
                ; -----------------------------------------
                ; чтение изменяемого индекса панели расшифровки
Entry:          LD HL, #0000
                ; рисунок рамки и заголовка с исходным HALT полосы
                CALL @Station.DrawCaptionItem.Entry
                ; включение переноса текста после установки окна заголовком
                LD A, #01
                LD (@TextWindow.Style), A
                ; -----------------------------------------
                ; Проверка ключа расшифрованной системы и финального кода
                ; -----------------------------------------
                ; проверка первого слова текущего ключа по исходной системе Дзета-43/78-Д
                LD HL, (@SignatureInput.Entry.FirstWord)
                LD DE, @DecodedPanelConst.SystemFirst
                XOR A
                SBC HL, DE
                JP NZ, @Station.PrintDecodedMessage.Entry                       ; переход, если первое слово не совпало с расшифрованной системой, вывести обычное сообщение

                ; проверка второго слова только после совпадения первого
                LD HL, (@SignatureInput.Entry.SecondWord)
                LD DE, @DecodedPanelConst.SystemSecond
                XOR A
                SBC HL, DE
                JP NZ, @Station.PrintDecodedMessage.Entry                       ; переход, если второе слово не совпало с расшифрованной системой, вывести обычное сообщение

                ; проверка полного байта 98A0 на FE, его игровое назначение ещё неизвестно
                LD A, (@DecodedPanelState.Unknown98A0)
                CP @DecodedPanelConst.FinalCode
                JP Z, @Station.DrawDecodedMessagePanel.StartFinal               ; переход, если Unknown98A0 равен FE при обоих совпавших словах, начать финальный перенос

                JP @Station.PrintDecodedMessage.Entry

                ; -----------------------------------------
                ; Перенос и вход финального загрузчика
                ; -----------------------------------------
                ; запрет прерываний перед перезаписью фиксированного экрана исполняемой копией
StartFinal:     DI
                ; выбор физического источника 6E11 и доказанного адреса исполнения 4000
                LD HL, @FinalExitCopy.Source
                LD DE, @FinalExitCopy.Destination
                ; выбор исходной длины 512 байтов, она больше 92 байтов кода и девяти байтов имени
                LD BC, @FinalExitCopy.Bytes
                ; копирование всего исходного блока без изменения его хвоста соседних процедур
                LDIR
                ; передача управления фиксированной копии, новый адрес возврата не создаётся
                JP @StationFinalExit.LoadFinal.Entry

                ; -----------------------------------------
                endmodule
                endmodule
