                module Station
                module SelectMapPointAndRefresh
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [пиксельное начало выбора, вложенное сохранение окна и различие двух панелей](../../Docs/MapSelectionPanel.md)
; -----------------------------------------
; Выбор ближайшей видимой точки карты, перерисовка карты и обновление панелей систем и планет
; исходная запись 4, файловые смещения #0FB9..#0FEE
; In:
;   TextWindow содержит внутреннее окно основной панели карты, его младшие начала плюс 5 и 13 задают пиксельное начало видимой области
;   MapViewState, секторные таблицы и предыдущая SelectedPoint удовлетворяют SelectNearestVisiblePoint, в том числе его договору старой ссылки при пустом списке
;   действуют договоры BeginScreenUpdate, ClearAndDrawMapPanel, SaveTextWindow, TryDrawSystemInfo, RestoreTextWindow, MoveItemToTailIfListed, TryDrawVariantPanel и EndScreenUpdate
;   если панели присутствуют, их геометрия и ресурсы пригодны, сохранённые индексы согласованы с обёртками списка рисования
;   код банка 1 и станции доступен, аппаратная блокировка paging снята, пробуждение фактически достигнутых HALT обеспечивается окружением
;   стек вне переключаемого окна и экранных областей, перенос bootstrap уже завершён
; Out:
;   сначала выбран абсолютный порт 11, в SelectNearestVisiblePoint переданы независимые байтовые OriginXLow+5 и OriginYLow+13
;   MapSelection, Minimum, SelectedPoint и буферы F6/F7 соответствуют результату выбора, выход указателя за область не заменяет старую MapSelection
;   после выбора абсолютный порт 10 возвращает станцию, затем создан снимок старого экрана в банке 7 и нарисована карта
;   девять байтов TextWindow сохранены после карты, информационная панель вызывается при её присутствии, затем эти девять байтов восстановлены
;   панель планет переносится в хвост списка по её индексу только после успешной проверки указателя, затем условно рисуется
;   общего восстановления TextWindow после панели планет нет, при её присутствии итоговое окно относится к ней, при отсутствии сохраняется снимок после карты
;   HL, DE, BC и альтернативные общие пары соответствуют последней реально вызванной панели либо её проверке, AF содержит A=10 и F перед EndScreenUpdate
;   IX рабочий по договору выбора и подготовки ресурсов планет, IY, I и IFF сохраняются инструкциями при договоре пробуждения
;   на выходе CurrentPage=10, показан базовый экран с возобновлённым указателем, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, выбор карты, bitmap, снимок банка 7, текстовые состояния, ресурсы и список рисования
; Note:
;   оба начальных выбора страниц абсолютные, старый бит теневого экрана не сохраняется
;   снимок TextWindow не является стеком, вложенный перезаписывающий SaveTextWindow запрещён договором вызываемых панелей
;   при несогласованных указателях и индексах MoveItemToTailIfListed может выбрать другую запись либо добавить входной HL, это поведение не исправляется
;   модель проверила 80 сочетаний позиции, начала мира и присутствия двух панелей, все количества 0..6, независимый выбор ключа и восстановление окна
;   в модели HALT пробуждаются явно, пустой видимый список отдельно относится к проверке SelectNearestVisiblePoint, цельный bitmap всей композиции независимо не моделируется
; -----------------------------------------
                ; выбор абсолютной страницы карты, прежний бит отображаемого экрана не сохраняется
Entry:          LD A, @SystemNameConst.MapPage
                CALL @Station.SelectMemoryPage.Entry
                ; расчёт пиксельного начала выбора по младшим началам TextWindow с внутренними добавками X=5,Y=13
                LD A, (@TextWindow.OriginXLow)
                ADD A, #05
                LD L, A
                LD A, (@TextWindow.OriginYLow)
                ADD A, #0D
                LD H, A
                ; выбор ближайшей точки через настоящие фильтр видимости, минимум расстояния и чтение сохранённого варианта
                CALL @Map.SelectNearestVisiblePoint.Entry
                ; абсолютный возврат станционной страницы после банкового выбора
                LD A, @StationIrqConst.StationPage
                CALL @Station.SelectMemoryPage.Entry
                ; создание снимка старого экрана и начало скрытого обновления
                CALL @Station.BeginScreenUpdate.Entry
                ; очистка внутреннего тела и рисунок карты с новым выбранным ключом
                CALL @Station.ClearAndDrawMapPanel.Entry
                ; сохранение девяти байтов окна карты до возможного изменения информационной панелью
                CALL @Station.SaveTextWindow.Entry
                ; условный рисунок сведений о выбранной и текущей системах
                CALL @Station.TryDrawSystemInfo.Entry
                ; восстановление окна после панели сведений, будущий рисунок планет этим сохранением не охвачен
                CALL @Station.RestoreTextWindow.Entry
                ; чтение индекса панели планет для переноса существующего элемента к концу списка
                LD DE, (@VariantPanelState.ItemIndex)
                ; проверка полного указателя и перенос по индексу при согласованном списке
                CALL @Station.MoveItemToTailIfListed.Entry
                ; условный рисунок панели планет с её собственным текстовым окном и ресурсами
                CALL @Station.TryDrawVariantPanel.Entry
                ; возобновление указателя и показ базового экрана, TextWindow после панели планет не восстанавливается
                CALL @Station.EndScreenUpdate.Entry
                RET

                endmodule
                endmodule
