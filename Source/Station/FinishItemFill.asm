                module Station
                module FinishItemFill
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [Interface.md](../../Docs/Interface.md)
; -----------------------------------------
; Продолжение заполнения интерфейсного элемента, чтение высоты и отсечение прямоугольника
; исходная запись 4, файловые смещения #6000..#6038
; In:
;   HL - адрес поля Height текущей FInterfaceItem, DE - E исходная ширина, BC - исходные знаковые Y и X
;   SP - сохранённый исходный индекс элемента, за ним адрес возврата исходного вызова FillItemBitmap
;   размеры и непустое пересечение соответствуют контракту FillItemBitmap
; Out:
;   HL - снятый со стека индекс элемента, DE - D равен нулю и E видимая ширина, BC - координаты видимой части
;   AF и записанные пиксели соответствуют FillRectangle для отсечённого прямоугольника, текстовое окно соответствует исходной геометрии
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   это продолжение FillItemBitmap, прямой CALL без дополнительного слова на стеке недопустим
;   сначала читается Height и настраивается текстовое окно, затем независимо корректируются горизонтальный и вертикальный интервалы
;   отрицательное начало уменьшает размер и заменяется нулём, правый и нижний выходы уменьшают размер до границы экрана
;   после POP HL хвостовой JP FillRectangle использует исходный адрес возврата, SP увеличивается на четыре относительно входа этого продолжения
;   альтернативные и индексные регистры, I и IFF сохраняются, проверок пустого результата нет
; -----------------------------------------
                ; чтение высоты и переход к адресу Flags без чтения самих флагов
Entry:          LD D, (HL)
                INC HL
                ; настройка текстового окна по исходной геометрии до экранного отсечения
                CALL @Station.SetupTextWindow.Entry
                ; проверка знака левой байтовой колонки элемента
                LD A, C
                AND A
                JP P, @Station.FinishItemFill.ClipRight                         ; переход, если левая колонка неотрицательна, проверяется правый край

                ; расчёт оставшейся ширины после пропуска отрицательных колонок
                ADD A, E
                LD E, A
                LD C, #00
                JP @Station.FinishItemFill.ClipY

                ; расчёт исключённой правой колонки исходного прямоугольника
ClipRight:      ADD A, E
                ; проверка, что правая граница не превышает 32 колонки
                CP @ScreenConst.ColumnEndLimit
                JP C, @Station.FinishItemFill.ClipY                             ; переход, если правая граница не превышает 32, ширина сохраняется

                ; расчёт ширины до правого края экрана, 32 минус исходная колонка
                SUB @ScreenConst.ByteColumns
                NEG
                ADD A, E
                LD E, A
                ; проверка знака верхней строки знакомест элемента
ClipY:          LD A, B
                AND A
                JP P, @Station.FinishItemFill.ClipBottom                        ; переход, если верхняя строка неотрицательна, проверяется нижний край

                ; расчёт оставшейся высоты после пропуска отрицательных строк знакомест
                ADD A, D
                LD D, A
                LD B, #00
                JP @Station.FinishItemFill.RestoreIndex

                ; расчёт исключённой нижней строки исходного прямоугольника
ClipBottom:     ADD A, D
                ; проверка, что нижняя граница не превышает 24 знакоместа
                CP @ScreenConst.RowEndLimit
                JP C, @Station.FinishItemFill.RestoreIndex                      ; переход, если нижняя граница не превышает 24, высота сохраняется

                ; расчёт высоты до нижнего края экрана, 24 минус исходная строка
                SUB @ScreenConst.CharRows
                NEG
                ADD A, D
                LD D, A
                ; восстановление исходного индекса перед хвостовым переходом к заполнению bitmap
RestoreIndex:   POP HL
                JP @Station.FillRectangle.Entry

                endmodule
                endmodule
