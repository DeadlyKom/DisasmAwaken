                module Station
                module DrawItem31
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [полный проход рамки, банкового имени и печати](../../Docs/MissionNameDraw.md)
; -----------------------------------------
; Рамка элемента цели миссии, сброс строки наведения и печать сформированного имени
; исходная запись 4, файловые смещения #1271..#1299
; In:
;   DrawItemState.Opcode31 равен 21 для работы либо C9 для отключения, Index31 актуальный индекс записи, загрузчик записывает 31
;   при активном коде выполнен договор DrawCaptionItem, геометрия целиком видима, таблицы и свободная индексная пара подготовлены
;   MissionOffer.Entry.FirstWord и SecondWord доступны, KARTA загружена в банк 1, действует BuildSystemName
;   порт и CurrentPage согласованы, исходно выбраны станционный банк 0 и ROM 1, bit5 снят, стек вне банкового окна
;   HALT рамки корректно пробуждается с сохранением контекста, первоначальный bootstrap уже завершён
; Out:
;   при активном коде прямоугольник зарегистрирован, рамка и заголовок соответствуют DrawCaptionItem
;   MissionHoverState.Row=FF, TextWindow.Style=0, имя предлагаемого пункта записано в SystemNameState.Buffer
;   последний PrintText использует сформированный LF-поток, HL его продолжение, DE адрес LF в буфере
;   BC содержит десятки и единицы второго числового поля имени по BuildSystemName
;   AF статус последнего PrintText, при завершении LF A=0A, F=4A
;   HL'=MissionOffer.FirstWord AND F0FF, DE'=MissionOffer.SecondWord AND FFF0, BC'=входной основной BC
;   AF' по DrawCaptionItem, последующие BuildSystemName и PrintText сохраняют его
;   IX, IY, I и IFF сохранены при договоре пробуждения, SP обычного возврата равен входному SP+2
;   страницы последовательно выбирают банк 1 и банк 0 через исходный интерфейс, старшие биты сохраняются, ROM 1 принудителен
;   при Opcode31=C9 немедленный RET сохраняет регистры, операнды и буфер, тело рисователя не исполняется
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF' по DrawCaptionItem, только при активной обёртке
; Note:
;   имя строится настоящим BuildSystemName с его обменом общих наборов и пропуском нулевых десятков
;   явный LD HL,Buffer после возврата банка нужен, рабочий HL построителя указывает на исходный префикс
;   Style=0 задаётся после рамки и остаётся на выходе, отбрасывание неуместившегося хвоста соответствует PrintText
;   Row сбрасывается после перерисовки фона, чтобы новая подсветка не снимала старую полосу
;   данный проход не принимает миссию и не начисляет награду, нажатие использует самостоятельный вход Handler+3
; -----------------------------------------
                ; чтение изменяемого Index31, первый байт RET может отключить всю обёртку
Entry:          LD HL, #0000
                ; регистрация элемента, рамка и заголовок через полный DrawCaptionItem
                CALL @Station.DrawCaptionItem.Entry
                ; выбор отсутствующей прежней строки после замены фона элемента
                LD A, @MissionHoverConst.NoRow
                ; сброс сохранённого Row наведения, предыдущая XOR-полоса больше не соответствует новому изображению
                LD (@MissionHoverState.Row), A
                ; выбор режима без автоматического продолжения слишком длинного текста
                XOR A
                LD (@TextWindow.Style), A
                ; чтение обоих слов предлагаемого пункта из физического состояния миссии
                LD HL, (@MissionOffer.Entry.FirstWord)
                LD DE, (@MissionOffer.Entry.SecondWord)
                ; выбор KARTA в банке 1 для формирования имени из упакованных полей
                LD A, @SystemNameConst.MapPage
                CALL @Station.SelectRamBank.Entry
                ; построение LF-имени в общем буфере, основной набор регистров после вызова поменяется
                CALL @Map.BuildSystemName.Entry
                ; возврат станционного банка 0 перед печатью
                LD A, @StationIrqConst.StationPage
                CALL @Station.SelectRamBank.Entry
                ; выбор именно общего буфера, возвращённый HL построителя указывает на другое место
                LD HL, @SystemNameState.Buffer
                ; хвостовая печать имени с исходным адресом возврата вызывающего рисователя
                JP @Station.PrintText.Entry

                endmodule
                endmodule
