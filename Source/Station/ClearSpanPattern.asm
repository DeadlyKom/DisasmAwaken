                module ClearSpanPattern
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [StationSpans.md](../../Docs/StationSpans.md)
; -----------------------------------------
; Подготовка нулевых байтов левого края, середины и правого края полосы
; исходная запись 4, файловые смещения #61ED..#61F1
; In:
;   нет входных параметров
; Out:
;   DE - D и E равны #00, BC - C равен #00, B сохраняется
; Corrupt:
;   DE, BC
; Note:
;   основные HL, AF, альтернативные и индексные регистры сохраняются, SP восстанавливается
;   подготавливаются три части будущей полосы, запись пикселей выполняется отдельно
; -----------------------------------------
                ; выбор полностью нулевой полосы для последующей записи левого края, середины и правого края
Entry:          LD DE, @SpanPattern.EmptyPair
                LD C, E
                RET

