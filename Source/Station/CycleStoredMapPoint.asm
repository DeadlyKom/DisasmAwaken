                module Station
                module CycleStoredMapPoint
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [физические пятибайтовые записи, точные диапазоны сдвигов и общие хвосты](../../Docs/StoredPointEdits.md)
; -----------------------------------------
; Циклический переход по первому списку с пропуском FF и центрированием выбранного ключа
; исходная запись 4, файловые смещения #1F3A..#1F61
; In:
;   StoredPointCycle.Cursor у записи A, по шагу пять достижим конец 7F..FE либо положительная запись, поля читаемы
;   если начальный первый байт A не FF, запись A.Point00 допустима для выбора при оборачивании
;   действуют договоры CenterKeyAndRefreshMap и чтения варианта из A
;   действуют договоры BeginScreenUpdate, TryDrawSystemInfo, DrawMapPanel и EndScreenUpdate, две записи панелей и данные карты готовы
;   paging доступен, указатель согласован с фоном, адресные и индексные таблицы готовы, все фактические HALT пробуждаются окружением
;   стек вне экранных областей и переключаемого окна, банк станции 0 доступен
; Out:
;   Pending=1, если первый байт A.Point00 равен FF, немедленный возврат независимо от последующих занятых записей
;   на этом раннем выходе A=0, Z=1, F от INC FF, HL, DE, BC, индексы и альтернативные пары сохранены, Cursor прежний
;   иначе поиск начинается с Cursor+5, FF пропускаются, первый байт 7F..FE возвращает выбор к Point00 без нового сканирования от начала
;   найденный адрес записан обратно в изменяемый Cursor, первые два слова переданы как DE=FirstWord и HL=SecondWord в общий центрирующий вход
;   вариант не берётся напрямую из выбранной физической позиции, CenterKeyAndRefreshMap повторно находит его по первому совпадению A
;   окончательные результаты соответствуют общему центрированию и рисунку
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, bitmap и рабочие данные общего рисунка, изменяемый Cursor, выбранный ключ, начало карты и Pending
; Note:
;   INC делает 7F концом этого циклического прохода, в отличие от поиска FindStoredMapPoint
;   проверка Point00==FF отключает цикл при дыре в первой записи, это поведение сохранено
;   в модели покрыты все схемы пустот и десять начальных курсоров, наблюдение до общего банкового входа
; -----------------------------------------
                ; запрос обновления планет до проверки доступности циклического выбора A
Entry:          LD A, #01
                LD (@VariantPanelState.RefreshPending), A
                ; проверка первой физической записи A, последующие занятые записи не обходят этот запрет
                LD A, (#990A)
                INC A
                RET Z                                                           ; выход, если первый байт Point00 равен FF, циклический выбор не выполняется

                ; чтение сохранённого самомодифицируемого курсора первого списка
                LD HL, @StoredMapPointsA.Point00
                ; подготовка шага FStoredMapPoint и поиск начинается со следующей физической записи
                LD DE, FStoredMapPoint
                ; расчёт следующей позиции циклического прохода
FindNext:       ADD HL, DE
                ; проверка пустоты и конца через INC первого байта
                LD A, (HL)
                INC A
                JP P, @Station.CycleStoredMapPoint.SkipEmpty                    ; переход, если первый байт 00..7E либо FF, оборачивание к началу не требуется

                ; возврат выбора к Point00 при первом байте 7F..FE без повторного чтения её маркера
                LD HL, @StoredMapPointsA.Point00
SkipEmpty:      JR Z, @Station.CycleStoredMapPoint.FindNext                     ; переход, если исходный первый байт равен FF, пропустить пустоту

                ; обновление изменяемого Cursor фактически выбранным адресом
                LD (@StoredPointCycle.Cursor), HL
                ; чтение FirstWord в DE и SecondWord в HL перед общим центрированием, пятый байт не читается
                LD E, (HL)
                INC HL
                LD D, (HL)
                INC HL
                LD A, (HL)
                INC HL
                LD H, (HL)
                LD L, A
                JR @Station.CenterKeyAndRefreshMap.Entry

                endmodule
                endmodule
