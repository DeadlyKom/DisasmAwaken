                module Station
                module ScrollWindowRows
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [порог направления, перенос двух SBC, теневой экран и кадры callback](../../Docs/ScrollWindow.md)
                ; -----------------------------------------
                ; Прокрутка индекса строк по указателю с теневым снимком, очисткой тела и изменяемым рисователем
                ; исходная запись 4, файловые смещения #41D6..#426E
                ; In:
                ;   HL - начальный индекс, BC - B сохраняемый до расчёта направления, AF - A верхний отступ содержимого в пикселях
                ;   TextWindow, шрифт и таблицы подготовлены, два экрана доступны, станционный банк 0 выбран, bit5 порта 7FFD снят
                ;   ScrollState.EndLimit и RenderCall заранее настроены вызывающим кодом, callback принимает HL нового индекса и возвращается с допустимым стеком и банком 0
                ;   выполнены договоры MergeActionInputs, SuspendPointer, ClearScrollWindowBody, EndScreenUpdate.ShowBase и RestoreScrollPointer
                ;   HALT после показа снимка корректно пробуждается с сохранением контекста, ввод может меняться между опросами
                ;   для штатного ограничения индекс не больше EndLimit, опасная геометрия очищающего ядра исключена его входным договором
                ; Out:
                ;   всегда записан TopOffset, атрибуты базового экрана 5800..5AFF скопированы в банк 7 по D800..DAFF, затем принудительно выбран байт страницы 10
                ;   если исходный Height не больше TopOffset, немедленный возврат без снятия указателя, HL сохранён, DE=DB00, B входной, C=TopOffset, AF от SUB Height,TopOffset
                ;   при положительной разности ClearHeight получает Height-TopOffset, C получает целую часть разности, делённой на восемь, и сохраняется как высота просмотра
                ;   до цикла сохранены исходные PointerXY, указатель снят, нулевой MergeActionInputs завершает через RestoreScrollPointer
                ;   на обычном выходе HL итоговый индекс, DE исходные PointerXY, AF=0044, координаты восстановлены, UpdateBlocked=0
                ;   B сохраняет последний промежуточный центр либо ноль из ветви Down, при отсутствии расчёта направления остаётся входным B
                ;   на каждом принятом шаге 6144 байта базовых пикселей копируются в банк 7, показывается страница 18, после HALT очищено тело и вызван RenderCall с HL нового индекса
                ;   после callback индекс и BC восстановлены из кадра, ShowBase выбирает 10, атрибуты теневого снимка повторно не копируются
                ;   HL и BC callback не повреждают внешний индекс и высоту просмотра, DE и AF затем заменяются общим выходом
                ;   альтернативные и индексные регистры меняются только по договорам callback, очищающего ядра и указателя, C' рабочий очистки, AF' рабочий указателя
                ;   собственный код не меняет I, IFF и IM, SP обычного возврата равен входному SP+2, CurrentPage и порт в конце равны 10
                ; Corrupt:
                ;   HL, DE, BC, AF, BC', AF', экраны, состояние указателя, TopOffset, ClearHeight и операнды очистки, прочие регистры только по договору RenderCall
                ; Note:
                ;   направление вниз выбирается при PointerY больше байтового порога ((Height SHR 1)+OriginYLow+(TopOffset SHR 1)) AND FF, иначе вверх
                ;   вверх при нулевом индексе шаг пропускается, положительный индекс уменьшается без дополнительной проверки диапазона
                ;   вниз второй SBC вычитает C вместе с заёмом первого EndLimit-индекс, приняты только ненулевой результат без Carry
                ;   для штатного индекса не больше EndLimit это индекс+C<EndLimit, за его пределами исходная проверка не является насыщением
                ;   при C=0 и ненулевом вводе цикл только повторяет опрос без HALT и без рисования, отпускание ввода всё равно завершает его
                ;   высота просмотра и ClearHeight фиксируются при входе, порог направления читает текущие Height, OriginYLow и TopOffset на каждом опросе
                ;   процедура не восстанавливает прежнюю страницу, общий байт 10 принудителен и на ранних выходах
                ;   модель проверяет 196608 развилок Down и 204 полных вызова с настоящим торговым callback, включая 180 теневых перерисовок
                ;   ввод изменяется моделью на границе опросов, HALT пробуждается явно, аппаратные IRQ и нативная игра не подтверждены
                ; -----------------------------------------
                ; -----------------------------------------
                ; Снимок атрибутов и высота просмотра
                ; -----------------------------------------
                ; обновление исходного TopOffset очищающего ядра до любых проверок высоты
Entry:          LD (@ClearBodyState.TopOffset), A
                ; сохранение верхнего отступа в C, индекс и BC временно защищены от копирования
                LD C, A
                PUSH BC
                PUSH HL
                ; выбор окна банка 7 при показе базового экрана для снимка атрибутов
                LD A, @ScreenUpdateConst.CopyPage
                CALL @Station.SelectMemoryPage.Entry
                ; копирование только 768 атрибутов, пиксели снимаются позже на каждом принятом шаге
                LD HL, @ScreenUpdateConst.BaseAttributes
                LD DE, @ScreenUpdateConst.BankAttributes
                LD BC, @ScreenUpdateConst.AttributeBytes
                LDIR
                ; возврат станционного банка 0 и показа базового экрана независимо от прежней страницы
                LD A, @ScreenUpdateConst.VisiblePage
                CALL @Station.SelectMemoryPage.Entry
                POP HL
                POP BC
                ; расчёт доступной высоты после исходного верхнего отступа
                LD A, (@TextWindow.Height)
                SUB C
                RET C                                                           ; выход, если Height меньше TopOffset, снимок атрибутов уже выполнен

                RET Z                                                           ; выход, если Height равен TopOffset, доступная высота нулевая

                ; сохранение доступной высоты в операнде будущего вызова очистки
                LD (@ScrollState.ClearHeight), A
                ; расчёт целого числа восьмипиксельных строк, маска удаляет возвращённые вращениями старшие разряды
                RRA
                RRA
                RRA
                AND @RowSelectConst.RowMask
                LD C, A
                ; создание FScrollExitFrame.SavedPointerXY поверх исходного адреса возврата
                LD DE, (@StationState.PointerXY)
                PUSH DE
                ; снятие указателя перед копированием и рисованием содержимого
                CALL @Station.SuspendPointer.Entry
                ; -----------------------------------------
                ; Опрос ввода и выбор направления
                ; -----------------------------------------
                ; чтение объединённого кода, его ноль завершает прокрутку
Poll:           CALL @Station.MergeActionInputs.Entry
                JR Z, @Station.RestoreScrollPointer.Entry                       ; переход, если объединённый ввод нулевой, восстановить исходные координаты и указатель

                ; проверка фиксированной высоты просмотра перед любым шагом
                LD A, C
                AND A
                JR Z, @Station.ScrollWindowRows.Poll                            ; переход, если полных строк нет, ждать отпускания ввода без рисования

                ; чтение текущего Y указателя и младшего начала окна
                LD A, (@StationState.PointerXY+1)
                LD D, A
                LD A, (@TextWindow.OriginYLow)
                LD E, A
                ; расчёт байтового центра от половины текущей высоты и OriginYLow
                LD A, (@TextWindow.Height)
                SRL A
                ADD A, E
                LD B, A
                ; добавление половины текущего TopOffset к порогу направления
                LD A, (@ClearBodyState.TopOffset)
                SRL A
                ADD A, B
                ; проверка PointerY относительно вычисленного порога
                CP D
                JP C, @Station.ScrollWindowRows.Down                            ; переход, если PointerY больше порога, проверить шаг вниз

                ; проверка нулевого индекса перед шагом вверх
                LD A, L
                OR H
                JR Z, @Station.ScrollWindowRows.Poll                            ; переход, если индекс уже нулевой, продолжить опрос без шага вверх

                ; расчёт предыдущего начального индекса
                DEC HL
                JP @Station.ScrollWindowRows.Redraw

                ; -----------------------------------------
                ; Исходная проверка шага вниз двумя SBC
                ; -----------------------------------------
                ; чтение изменяемого EndLimit перед вычитанием индекса
Down:           LD DE, #0000
                EX DE, HL
                ; сброс переноса перед первой разностью EndLimit-индекс
                OR A
                ; расчёт первой разности, её заём передаётся следующему SBC
                SBC HL, DE
                ; выбор BC=C строк просмотра без изменения флага первого займа
                LD B, #00
                ; вычитание высоты просмотра вместе с заёмом первой разности
                SBC HL, BC
                EX DE, HL
                JR Z, @Station.ScrollWindowRows.Poll                            ; переход, если вторая разность нулевая, шаг вниз не выполнять

                JR C, @Station.ScrollWindowRows.Poll                            ; переход, если вторая разность дала заём, шаг вниз не выполнять

                ; расчёт следующего начального индекса после исходной проверки
                INC HL
                ; -----------------------------------------
                ; Теневой снимок и перерисовка принятого шага
                ; -----------------------------------------
                ; создание SavedBC и SavedIndex кадра FScrollDrawFrame поверх FScrollExitFrame
Redraw:         PUSH BC
                PUSH HL
                ; выбор окна банка 7 для копирования прежних базовых пикселей
                LD A, @ScreenUpdateConst.CopyPage
                CALL @Station.SelectMemoryPage.Entry
                ; копирование 6144 пиксельных байтов без повторной замены атрибутов снимка
                LD HL, @ScreenUpdateConst.BaseScreen
                LD DE, @ScreenUpdateConst.BankWindow
                LD BC, @ScreenUpdateConst.BitmapBytes
                LDIR
                ; показ снимка банка 7 с возвратом станционного кода в окно банка 0
                LD A, @ScreenUpdateConst.HiddenPage
                CALL @Station.SelectMemoryPage.Entry
                ; ожидание пробуждения при уже показанном снимке, сам код EI не выполняет
                HALT
                ; чтение доступной высоты, сохранённой в изменяемом ClearHeight на входе
                LD A, #00
                ; очистка скрытого базового тела через ClearScrollWindowBody
                CALL @Station.ClearScrollWindowBody.Entry
                ; возврат принятого индекса и повторное сохранение перед изменяемым callback
                POP HL
                PUSH HL
                ; вызов исходного RenderCall, начальное слово 0000 обязано быть настроено вызывающим кодом
                CALL #0000
                ; восстановление начального индекса после рабочего HL рисователя
                POP HL
                ; показ обновлённого базового экрана без преждевременного возврата указателя
                CALL @Station.EndScreenUpdate.ShowBase
                ; снятие SavedBC, стек снова у FScrollExitFrame для очередного опроса
                POP BC
                JP @Station.ScrollWindowRows.Poll

                ; -----------------------------------------
                endmodule
                endmodule
