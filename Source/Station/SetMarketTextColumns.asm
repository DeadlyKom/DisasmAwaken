                module Station
                module SetMarketTextColumns
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [позиции торговой таблицы и фактическая область условной инверсии](../../Docs/MarketPanelHelpers.md)
                ; -----------------------------------------
                ; Отключение переноса текста и установка пяти пиксельных позиций торговых колонок
                ; исходная запись 4, файловые смещения #1400..#141D
                ; In:
                ;   станционный код и операнды Style, Column2X..Column6X доступны для записи
                ; Out:
                ;   HL, DE и BC сохранены, AF=B044
                ;   TextWindow.Style=0, Column2X=96, Column3X=114, Column4X=136, Column5X=154, Column6X=176 пикселей
                ;   HL', DE', BC', AF', IX, IY, I, IFF, IM и страницы сохранены, SP обычного возврата равен входному SP+2
                ; Corrupt:
                ;   AF и шесть изменяемых операндов текста
                ; Note:
                ;   последовательные LD не меняют F после начального XOR A, поэтому окончательное F=44
                ;   координаты относительны к текущему окну текста, начало окна, размеры и курсор не меняются
                ;   процедура не рисует текст и сама не читает рынок, её потребитель выводит заголовок Продажа и Наличие и строки товаров
                ; -----------------------------------------
                ; выбор текста без автоматического переноса перед торговой таблицей
Entry:          XOR A
                ; обновление Style, остальные параметры окна сохраняются
                LD (@TextWindow.Style), A
                ; выбор пиксельного начала колонки количества продаваемого товара
                LD A, @MarketColumnConst.SaleQuantity
                ; обновление позиции управляющего кода колонки 2
                LD (@TextStreamState.Column2X), A
                ; выбор пиксельного начала колонки продажной цены
                LD A, @MarketColumnConst.SalePrice
                ; обновление позиции управляющего кода колонки 3
                LD (@TextStreamState.Column3X), A
                ; выбор пиксельного начала колонки имеющегося количества
                LD A, @MarketColumnConst.OwnedQuantity
                ; обновление позиции управляющего кода колонки 4
                LD (@TextStreamState.Column4X), A
                ; выбор пиксельного начала колонки цены имеющегося товара
                LD A, @MarketColumnConst.OwnedPrice
                ; обновление позиции управляющего кода колонки 5
                LD (@TextStreamState.Column5X), A
                ; выбор пиксельного начала колонки единицы измерения
                LD A, @MarketColumnConst.Unit
                ; обновление позиции управляющего кода колонки 6
                LD (@TextStreamState.Column6X), A
                RET

                endmodule
                endmodule
