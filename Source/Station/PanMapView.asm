                module Station
                module PanMapView
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [байтовые зоны указателя, знаковое ограничение мирового начала и повторный рисунок](../../Docs/MapPan.md)
; -----------------------------------------
; Прокрутка начала карты шагами по восемь с выбором оси по положению указателя
; исходная запись 4, файловые смещения #0F1A..#0FB8
; In:
;   IX - читаемая геометрия FInterfaceItem, сохраняемая между шагами, банк станции 0 выбран
;   StationState.PointerXY содержит пиксельное положение, MapViewState.OriginLow и OriginHigh содержат чередующиеся байты мирового начала
;   действуют договоры RefreshMapPanel и MergeActionInputs, текстовое окно, таблицы, списки, данные сцены и paging подготовлены
;   пробуждение обоих HALT каждой принятой перерисовки обеспечивается окружением, договоры SP и IFF вложенных рисователей соблюдены
; Out:
;   сначала всегда выполняется один шаг, далее повтор зависит от бита 0 объединённого кода MergeActionInputs
;   на шаге изменяется одна ось на -8 либо +8, результат с установленным битом 15 отменяется обратным вычитанием
;   отмена восстанавливает прежнее значение, отрицательное прежнее значение не исправляется, положительный результат оборачивания принимается
;   SectorRequest получает ровно 0 либо 1 по изменению упакованного OriginHigh, прежний полный байт запроса перезаписывается
;   каждый шаг вызывает RefreshMapPanel с обновлённым началом, его экранные изменения и сброс запросов сохраняются
;   HL, DE, BC и альтернативные пары соответствуют последнему RefreshMapPanel, AF получает RRA результата MergeActionInputs при прежнем Carry=0
;   при возврате Carry=0, S,Z,PV сохранены от OR объединённых входов, H=N=0, биты 3 и 5 относятся к новому A после RRA, A равен коду, сдвинутому вправо
;   IX восстановлен после каждого рисунка, IY, I и IFF сохраняются инструкциями при договоре пробуждения, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', мировое начало, SectorRequest, экраны и рабочее состояние RefreshMapPanel
; Note:
;   начало геометрии умножается на восемь целым словом, перенос из X в Y сохранён
;   порог X равен (((5*Width) AND FF)+(Width>>2))>>1, Carry последнего ADD участвует в RRA
;   верхняя граница Y равна ROL8(Height,2), только для обычных размеров Height<=24 это 4*Height
;   сначала выбираются левая и правая X-зоны, в средней X-зоне всегда выбирается верх либо низ, нейтральной зоны нет
;   ApplyDelta принимает HL с байтом dx в L и dy в H, внешний вход в середину требует отдельного соблюдения договоров
;   модель проверила 96 сценариев по 1, 2 и 3 шага с пустыми списками и нулевым радиусом, живые IRQ и полный диспетчер не проверены
; -----------------------------------------
                ; чтение начала геометрии панели для перевода положения указателя в локальные координаты
Entry:          LD L, (IX + FInterfaceItem.X)
                LD H, (IX + FInterfaceItem.Y)
                ; расчёт пиксельного начала целым словом, возможный перенос из X в Y сохраняется
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                EX DE, HL
                ; расчёт горизонтального порога из ширины панели, промежуточное 5*Width оборачивается по байту
                LD A, (IX + FInterfaceItem.Width)
                LD B, A
                SRL B
                SRL B
                LD C, A
                ADD A, A
                ADD A, A
                ADD A, C
                ; прибавление Width>>2, перенос этой суммы нужен следующему делению через RRA
                ADD A, B
                RRA
                LD C, A
                ; расчёт вертикального порога циклическим сдвигом высоты, для обычной панели это 4*Height
                LD A, (IX + FInterfaceItem.Height)
                RLCA
                RLCA
                LD B, A
                ; чтение указателя и расчёт локальных байтовых X и Y относительно начала панели
                LD HL, (@StationState.PointerXY)
                LD A, H
                SUB D
                LD D, A
                LD A, L
                SUB E
                ; проверка принадлежности левой X-зоне и подготовка шага dx=-8, dy=0
                SUB C
                LD HL, @MapPanConst.NegativeStep
                JR C, @Station.PanMapView.ApplyDelta                            ; переход, если локальный X меньше порога, применить шаг влево

                ; проверка правой X-зоны после повторного вычитания того же порога
                SUB C
                LD L, @MapPanConst.Step
                JR NC, @Station.PanMapView.ApplyDelta                           ; переход, если локальный X не меньше удвоенного порога, применить шаг вправо

                ; выбор вертикальной оси для средней X-зоны, сравнение локального Y с вертикальным порогом
                LD L, #00
                LD A, D
                SUB B
                LD H, @MapPanConst.NegativeStep
                JR C, @Station.PanMapView.ApplyDelta                            ; переход, если локальный Y меньше вертикального порога, применить шаг вверх

                ; выбор шага вниз для оставшейся части средней X-зоны
                LD H, @MapPanConst.Step
                ; перенос байтов dx и dy в DE для обновления мирового начала
ApplyDelta:     EX DE, HL
                ; чтение чередующихся младших и старших байтов X,Y из существующего viewport
                LD HL, (@MapViewState.OriginLow)
                LD BC, (@MapViewState.OriginHigh)
                ; сборка полного X в HL с временным сохранением младшего Y в C
                LD A, H
                LD H, C
                LD C, A
                ; сохранение исходных dx,dy на время знакового расширения горизонтального шага
                PUSH DE
                ; проверка знака dx для расширения до 16 бит
                BIT 7, E
                LD D, #00
                JR Z, @Station.PanMapView.AddX                                  ; переход, если dx неотрицателен, старший байт шага равен нулю

                LD D, #FF
                ; сброс переноса перед расчётом нового 16-битного X
AddX:           OR A
                ADC HL, DE
                JP P, @Station.PanMapView.PrepareY                              ; переход, если результат X неотрицателен, принять оборачиваемую сумму

                ; отмена отрицательного результата обратным вычитанием, исходный X не ограничивается нулём
                OR A
                SBC HL, DE
                ; восстановление dx,dy и сборка полного Y с сохранением нового X
PrepareY:       POP DE
                LD A, H
                LD H, C
                LD C, A
                LD A, H
                LD H, B
                LD B, L
                LD L, A
                ; сохранение исходных шагов перед переносом dy в младший байт знакового слагаемого
                PUSH DE
                LD A, E
                LD E, D
                LD D, A
                ; проверка знака dy для расширения до 16 бит
                BIT 7, E
                LD D, #00
                JR Z, @Station.PanMapView.AddY                                  ; переход, если dy неотрицателен, старший байт шага равен нулю

                LD D, #FF
                ; сброс переноса перед расчётом нового 16-битного Y
AddY:           OR A
                ADC HL, DE
                JP P, @Station.PanMapView.StoreOrigin                           ; переход, если результат Y неотрицателен, принять оборачиваемую сумму

                ; отмена отрицательного результата Y обратным вычитанием шага
                OR A
                SBC HL, DE
                ; восстановление исходных шагов и упаковка новых младших и старших байтов начала
StoreOrigin:    POP DE
                LD A, B
                LD B, H
                LD H, L
                LD L, A
                ; обновление младших байтов начала до проверки перехода между секторами
                LD (@MapViewState.OriginLow), HL
                ; проверка изменения упакованного слова старших координат через его разность с новым BC
                LD HL, (@MapViewState.OriginHigh)
                OR A
                SBC HL, BC
                LD A, #01
                JR NZ, @Station.PanMapView.StoreRequest                         ; переход, если изменился старший байт X либо Y, запросить построение секторов

                XOR A
                ; перезапись полного запроса числом 0 либо 1, сохранение новых старших координат
StoreRequest:   LD (@MapPanelState.SectorRequest), A
                LD (@MapViewState.OriginHigh), BC
                ; сохранение IX геометрии на время полного обновления карты и указателя
                PUSH IX
                CALL @Station.RefreshMapPanel.Entry
                POP IX
                ; чтение объединённых действий после рисунка для решения о следующем шаге
                CALL @Station.MergeActionInputs.Entry
                RRA
                JP C, @Station.PanMapView.Entry                                 ; переход, если бит 0 объединённых действий установлен, повторить выбор оси и шаг

                RET

                endmodule
                endmodule
