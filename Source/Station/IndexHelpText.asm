                module Station
                module IndexHelpText
                ; Документация [банк 7, сохранение экранной страницы, счётчик строк и отключение переноса](../../Docs/StationHelpCalls.md)
                ; -----------------------------------------
                ; Выбор банка HELP, индексирование LF-записи и сохранение полного числа строк
                ; исходная запись 4, файловые смещения #0C64..#0C7A
                ; In:
                ;   HL, DE, BC, AF не задают отдельного параметра, выполняется договор Help.IndexTextLines
                ;   HELP загружен в банк 7, Station в банках 5, 2, 0, CurrentPage соответствует порту и равен 10 либо 18
                ;   номер LF-записи подготовлен через Help.SelectText, каждый проход продвигается, N находится в 1..1023
                ;   операнд HelpPanelState.LineCount доступен для записи, переключение страниц аппаратно не заблокировано
                ; Out:
                ;   HL=E37B, DE=N, BC=0, AF содержит A=исходная страница 10 либо 18, F результата OR этого байта
                ;   HL', DE', BC', AF', IY, I, IFF и IM сохранены, IX=DB7C+2*N
                ;   TextWindow.Style=1, HelpPanelState.LineCount содержит полное слово N, таблица и курсор согласно Help.IndexTextLines
                ;   банк сначала 7, затем всегда 0, бит экранной страницы сохранён, SP после RET равен входному+2
                ; Corrupt:
                ;   HL, DE, BC, AF, IX, Style, LineCount, таблица HELP, курсор и изменяемые операнды индексатора
                ; Note:
                ;   номер банка не восстанавливается из входа, выход фиксирован в банк 0 со старшими управляющими битами
                ;   A=17 и A=10 объединяются со старшими битами тени порта, для страниц 10/18 получаются 17/1F и 10/18
                ;   исходные опасные границы индексатора не исправлены, 1024 строки не являются допустимым завершённым проходом
                ; -----------------------------------------
                ; обновление политики печати справки, ненулевой Style разрешает перенос
Entry:          LD A, #01
                LD (@TextWindow.Style), A
                ; выбор банка 7 с сохранением экранного бита перед обращением к HELP
                LD A, #17
                CALL @Station.SelectRamBank.Entry
                ; создание таблицы визуальных строк выбранной LF-записи
                CALL @Help.IndexTextLines.Entry
                ; возврат банка станции 0, старшие управляющие биты сохранены
                LD A, #10
                CALL @Station.SelectRamBank.Entry
                ; обновление полного 16-битного предела строк в операнде действия панели
                LD (@HelpPanelState.LineCount), DE
                RET

                endmodule
                endmodule
