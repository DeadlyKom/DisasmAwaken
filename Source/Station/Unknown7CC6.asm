                module Station
                module Unknown7CC6
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Частичные доказательства [абсолютные чтения ROM](../../Docs/AuxiliaryCycleReads.md)
; -----------------------------------------
; Unknown, назначение этого фрагмента ещё не установлено
; исходная запись 4, файловые смещения #1F72..#1FA3
; In:
;   Unknown, регистровый контракт ещё не доказан
; Out:
;   исходный поток управления, включая переходы в соседние фрагменты
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, консервативная верхняя граница
; Note:
;   граница файла не доказывает границу логической процедуры
;   состояние самомодификации и активной страницы учитывается отдельно
; -----------------------------------------
                ; выбор предупреждения об иносигнале через MissionOffer.Entry.MessageIndex=1
Entry:          LD A, #01
                LD (@MissionOffer.Entry.MessageIndex), A
                ; чтение изменяемого начального указателя, исходное значение 99A3
                LD HL, #99A3
                ; расчёт следующего адреса, дальнейшая проверка всё же не использует содержимое этого адреса
Point7CCE:      INC HL
                ; чтение абсолютного адреса 0001 по исходным байтам 3A 01 00, это не чтение через HL
                LD A, (#0001)
                ; проверка знака и нуля абсолютного байта 0001
                AND A
                JP P, @Station.Unknown7CC6.Point7CD9                            ; переход, если байт по 0001 неотрицателен, сохранить увеличенный указатель для проверки нуля


                ; замена указателя на 99A3 при установленном бите 7 абсолютного байта
                LD HL, #99A3
Point7CD9:      JR Z, @Station.Unknown7CC6.Point7CCE                            ; переход, если первое чтение 0001 дало ноль, повторить увеличение без сохранения курсора


                ; самомодификация начального указателя только после ненулевого первого чтения
                LD (#7CCC), HL
                ; повторное абсолютное чтение 0001, при изменении отображения ROM значение может отличаться от первого
                LD A, (#0001)
                ; проверка нуля второго абсолютного чтения перед выбором четырёхбайтового ключа
                AND A
                RET Z                                                           ; выход, если второе чтение 0001 дало ноль, сохранённый курсор уже изменён

                ; расчёт разности выбранного адреса и 99A3, а затем четырёхбайтового смещения
                LD DE, #99A3
                SBC HL, DE
                ADD HL, HL
                ADD HL, HL
                LD DE, #98B0
                ; чтение двух слов из 98B0 плюс вычисленное смещение, назначение всей области ещё разбирается
                ADD HL, DE
                LD E, (HL)
                INC HL
                LD D, (HL)
                INC HL
                LD A, (HL)
                INC HL
                LD H, (HL)
                LD L, A
                JR @Station.CenterKeyAndRefreshMap.Entry


                endmodule
                endmodule
