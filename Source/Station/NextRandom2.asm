                module NextRandom2
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [точная формула шага, физические состояния и обмен регистров](../../Docs/RandomState.md)
; -----------------------------------------
; Следующее слово независимого трёхбайтового потока 2
; исходная запись 4, файловые смещения #489E..#48A4
                ; In:
                ;   RandomStates.Seed2 доступно для записи, действует договор StepRandomState
                ; Out:
                ;   HL новое младшее слово Seed2, DE и BC сохранены
                ;   AF - A новый HighByte, F от последнего SBC A,0, HL' адрес Seed2
                ;   DE' новое слово, B'=0, C' младший байт T из договора ядра
                ;   AF', IX, IY, I, IM и IFF сохранены, SP=входной SP+2
                ;   R сохраняет бит 7, младшие семь бит увеличены на 66 M1 по модулю 128, внешний CALL не включён
                ;   три байта выбранного состояния обновлены, два временных байта ниже входного SP содержат новое младшее слово
                ; Corrupt:
                ;   HL, AF, HL', DE', BC', SP, R, три байта выбранного состояния и два временных байта CPU-стека
                ; Note:
                ;   входной EXX компенсирует заключительный EXX ядра, остальные три альтернативные пары становятся рабочими
                ;   потоки используют одно ядро и отдельные состояния, игровое назначение каждого потока устанавливается по потребителям
; -----------------------------------------
                ; передача основного контекста в альтернативный набор перед ядром
Entry:          EXX
                ; выбор физического состояния Seed2 без изменения других потоков
                LD HL, @RandomStates.Seed2
                ; общий шаг с заключительным EXX и возвратом в исходный активный контекст
                JP @Station.StepRandomState.Entry

                endmodule
                endmodule
