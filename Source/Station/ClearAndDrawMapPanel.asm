                module Station
                module ClearAndDrawMapPanel
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [размеры внутренней области, три запроса, paging и два уровня проверки](../../Docs/MapPanel.md)
; -----------------------------------------
; Проверка геометрии и заливка тела перед последовательным общим рисунком карты
; исходная запись 4, файловые смещения #0FFA..#1003
; In:
;   MapPanelState.ItemIndex задаёт запись панели, TextWindow соответствует её внутреннему окну, банк станции 0 выбран
;   действуют договоры FillWindowBody и DrawMapPanelContents, указатель защищён вызывающим окружением
;   геометрия и текстовое окно пригодны на обеих фактических проверках записи
; Out:
;   при Carry=0 от первой CheckItemRect возврат выполнен до заливки, запросы и экран не меняются, регистры соответствуют этому помощнику
;   иначе внутреннее тело залито по FillMode, затем исполнение последовательно переходит в DrawMapPanelContents без нового CALL
;   после успешной композиции возвращаемые регистры, три запроса, страница и SP соответствуют DrawMapPanelContents
;   стек заливки и стек C000 восстанавливаются по отдельным договорам, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, внутреннее тело, состояние заливки и композиции карты
; Note:
;   геометрия проверяется дважды, до заливки и внутри общего содержимого, обе исходные проверки сохранены
;   последовательный вход после CALL FillWindowBody требует жёсткого порядка двух INCLUDE, условный RET не отменяет это продолжение
; -----------------------------------------
                ; чтение текущего индекса панели для проверки перед заливкой
Entry:          LD HL, (@MapPanelState.ItemIndex)
                ; проверка пригодности геометрии до изменения внутреннего тела
                CALL @Station.CheckItemRect.Entry
                RET NC                                                          ; выход, если CheckItemRect не установил Carry, заливку и общий рисунок не выполнять

                ; заливка тела перед последовательным входом DrawMapPanelContents, который повторно читает геометрию
                CALL @Station.FillWindowBody.Entry
                ; JP @Station.DrawMapPanelContents.Entry, продолжение в DrawMapPanelContents.asm

                endmodule
                endmodule
