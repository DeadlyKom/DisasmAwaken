                module Station
                module DrawVariantPanel
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [установка callback, тактовая маска, геометрия указателя и два банковых контекста](../../Docs/PeriodicVariants.md)
; -----------------------------------------
; Рисование полосовой панели, установка периодического callback и подготовка ресурсов вариантов
; исходная запись 4, файловые смещения #1B38..#1B68
; In:
;   VariantPanelState.ItemIndex задаёт индекс FInterfaceItem для полосовой рамки, банк станции 0 выбран
;   действуют договоры DrawCaptionItem, SetBandFillMode и GetSelectedVariantCount, таблицы текста и адресации готовы
;   обычная геометрия рисователя имеет Width=2..32, Height=3..24 и помещается на экран, CheckItemRect может запретить периодический callback при размере меньше четырёх
;   для ненулевого количества действуют условия PrepareVariantResources, аппаратная блокировка paging снята
;   HALT рисователя должен быть пробуждён окружением с сохранением регистров по его отдельному договору
; Out:
;   полосовая рамка и заголовок нарисованы в режиме FillMode, затем шесть операндов рамки восстановлены в обычный набор через ResetBandMode
;   периодическая цель записана в MenuCommandState.PeriodicCall, при Carry CheckItemRect это UpdateVariantPanel, иначе EmptyCallback
;   количество получено из выбранного ключа, при нуле подготовка ресурсов и переключение банка пропущены, HL и DE содержат два слова ключа, BC сохранён
;   у нулевого количества основной AF равен 0044 либо 0042 по коду GetSelectedVariantCount, прежние Count и ресурсные операнды KARTA не сбрасываются
;   при количестве 1..6 подготовлено ровно столько ресурсных указателей, HL содержит последний ресурс, DE рабочий, C сохраняется, B=0 при количестве меньше шести и B=1 при шести
;   после подготовки выбран банк станции 0 с ROM 1, старшие биты CurrentPage сохранены, A содержит итоговый байт страницы, F логического OR этого байта
;   на ненулевой ветви AF' содержит байт выбора банка KARTA и флаги его OR, IY, HL', DE', BC', I и IFF сохраняются инструкциями при договоре HALT
;   IX рабочий на поисковых ветвях селектора, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF, AF', IX, bitmap, текстовое окно, регистрация, цель callback и подготовленные операнды KARTA
; Note:
;   при показе базового экрана вход A11 выбирает страницу 11, внутри BeginScreenUpdate тот же вход сохраняет бит показа теневого экрана и выбирает 19
;   возврат A10 через SelectRamBank даёт соответственно 10 либо 18, произвольная прежняя конфигурация не восстанавливается
;   проверка CheckItemRect выполнена после рисования, она не является предварительным отсечением недопустимой рамки
;   количество ноль не отключает допустимый периодический callback, последующий C677 может нарисовать только центральную метку и потребить первую пару
; -----------------------------------------
                ; чтение исходного изменяемого индекса записи панели
Entry:          LD HL, #0000
                ; настройка шести операндов полосовой рамки по текущему FillMode
                CALL @Station.SetBandFillMode.Entry
                ; рисование панели и заголовка с настоящим HALT вложенного рисователя
                CALL @Station.DrawCaptionItem.Entry
                ; восстановление обычных операндов рамки для последующих элементов
                CALL @Station.ResetBandMode.Entry
                ; проверка текущей геометрии после рисунка для выбора периодической цели
                LD HL, (@VariantPanelState.ItemIndex)
                CALL @Station.CheckItemRect.Entry
                ; подготовка EmptyCallback для неподходящей геометрии
                LD HL, @Station.EmptyCallback.Entry
                JR NC, @Station.DrawVariantPanel.StoreCallback                  ; переход, если CheckItemRect не установил Carry, сохранить EmptyCallback

                ; выбор периодического обновления для принятой геометрии панели
                LD HL, @Station.UpdateVariantPanel.Entry
                ; запись выбранного адреса в операнд периодического CALL главного цикла
StoreCallback:  LD (@MenuCommandState.PeriodicCall), HL
                CALL @Station.GetSelectedVariantCount.Entry
                RET Z                                                           ; выход, если количество вариантов равно нулю, ресурсные операнды не менять

                ; сохранение количества в AF' на время выбора KARTA
                EX AF, AF'
                ; выбор банка KARTA с сохранением текущего бита отображаемого экрана
                LD A, @SystemNameConst.MapPage
                CALL @Station.SelectRamBank.Entry
                ; возврат количества в A перед подготовкой ровно нужных ресурсов
                EX AF, AF'
                CALL @Map.PrepareVariantResources.Entry
                ; возврат банка станции с сохранением текущего показа базового либо теневого экрана
                LD A, @StationIrqConst.StationPage
                CALL @Station.SelectRamBank.Entry
                RET

                endmodule
                endmodule
