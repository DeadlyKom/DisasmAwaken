                module Station
                module PrintJustified
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [выравнивание текста по ширине](../../Docs/JustifiedText.md)
; -----------------------------------------
; Вывод текста с распределением свободной ширины между словами каждой строки
; исходная запись 4, файловые смещения #4DCD..#4E29
; In:
;   HL - текст с читаемым запасом для предварительного просмотра слов
;   TextWindow задаёт курсор и размеры, DrawGlyph подготовлен для требуемого режима вывода
; Out:
;   HL - позиция выхода PrintWrapWord либо начало следующей строки при отказе переноса
;   DE - D последняя накопленная ширина либо дополнительный интервал, E остаток выбранной группы с учётом признака CR
;   BC - #20 и сохранённая ширина при выборе строки, либо результат последней попытки AdvanceTextRow
;   AF - статус завершающего PrintWrapWord либо отказа AdvanceTextRow
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   при Height<14 возврат немедленный, A=Height, F от CP(Height, 14), HL, DE и BC сохранены
;   выбор слов выполняется просмотром вперёд с временным HL, печать возобновляется с сохранённого начала строки
;   LF и CR ограничивают одно измеряемое слово, но не прекращают просмотр набора, за ними должны быть читаемые байты
;   добавление минимального интервала 2 к ширине слова является байтовым, его переполнение не проверяется
;   каждый промежуток равен 2 плюс целая доля свободной ширины, остаток деления не распределяется
;   нулевой код не является завершением этих проходов, действуют ограничители PrintTextWord либо PrintWrapWord
;   попытка переноса сохраняет исходное переполнение Y по модулю 256
;   после успешного переноса выбор набора слов повторяется, при Z из PrintWrapWord процедура возвращается
;   при нулевой ширине и высоте 249..255 возможен цикл повторных переносов, условие описано в JustifiedText.md
;   пиксели выводит DrawGlyph, сам выравниватель меняет курсор и непосредственный операнд кэшированной ширины
; -----------------------------------------
                ; чтение высоты перед проверкой минимального размера окна
Entry:          LD A, (@TextWindow.Height)
                ; проверка минимальной высоты 14 для работы выравнивателя
                CP @JustifyConst.MinHeight
                RET C                                                           ; выход, если высота окна меньше 14, выравнивание не начинается

                ; сохранение ширины окна в непосредственном операнде прохода
                LD A, (@TextWindow.Width)
                LD (@JustifyState.PrintWidth), A
Row:            LD C, #00
                LD B, @TextConst.Space
                LD E, #00
                ; сохранение начала строки перед просмотром будущих слов
                PUSH HL
                XOR A
                ; сохранение ширины уже принятого набора перед измерением очередного слова
FitWords:       LD D, A
                CALL @Station.MeasureTextRun.Entry
                ; расчёт ширины слова с минимальным промежутком 2, переполнение этого сложения не проверяется
                ADD A, @JustifyConst.MinGap
                ; пропуск ограничителя измеренного слова даже для CR либо LF
                INC HL
                INC E
                ; расчёт суммарной ширины просмотренных слов с интервалами
                ADD A, D
                JR C, @Station.PrintJustified.FinishFit                         ; переход, если сумма набора переполнила байт, очередное слово не включается

                ; проверка суммарной ширины относительно ширины окна
                CP C
                JR C, @Station.PrintJustified.FitWords                          ; переход, если набор с промежутками ещё уже окна, просмотреть следующее слово

                ; расчёт ширины без последнего обязательного промежутка
                SUB @JustifyConst.MinGap
                ; проверка ширины последнего слова без конечного промежутка
                CP C
                JR NC, @Station.PrintJustified.FinishFit                        ; переход, если слово без конечного промежутка достигает ширины окна либо превышает её

                ; проверка особого случая первого слова, помещающегося без конечного промежутка
                DEC E
                JR NZ, @Station.PrintJustified.KeepFirst                        ; переход, если просмотрено больше одного слова, сохранить обычный выбор предыдущих слов

                INC E
KeepFirst:      INC E
                ; выбор количества слов перед последним просмотренным, затем возврат к началу строки
FinishFit:      DEC E
                POP HL
                JR NZ, @Station.PrintJustified.Gap                              ; переход, если выбран непустой набор слов, рассчитать выравнивающий промежуток

                CALL @Station.PrintWrapWord.Entry
                RET Z                                                           ; выход, если PrintWrapWord вернул Z, продолжение текста остановлено

                JP @Station.PrintJustified.Row

                ; расчёт свободной ширины относительно последнего принятого набора
Gap:            LD A, C
                SUB D
                LD D, A
                ; расчёт количества межсловных интервалов, одиночное слово обрабатывается отдельно
                DEC E
                JR Z, @Station.PrintJustified.WordCount                         ; переход, если выбрано одно слово, деление промежутка не требуется

                ; расчёт целой доли свободной ширины повторным вычитанием числа интервалов
                LD D, #FF
DivideGap:      INC D
                SUB E
                JP NC, @Station.PrintJustified.DivideGap                        ; переход, если свободная ширина допускает ещё одну целую долю на каждый интервал

WordCount:      INC E
Word:           CALL @Station.PrintWrapWord.Entry
                RET Z                                                           ; выход, если печататель слова вернул Z, оставшаяся группа не обрабатывается

                ; чтение позиции после слова для добавления выравнивающего промежутка
                LD A, (@TextWindow.CursorX)
                ; расчёт следующего X с минимальным промежутком 2 и дополнительной долей D
                ADD A, @JustifyConst.MinGap
                ADD A, D
                LD (@TextWindow.CursorX), A
                ; проверка остатка группы слов после продвижения курсора
                DEC E
                JP NZ, @Station.PrintJustified.Word                             ; переход, если в группе остаются слова, вывести следующее

                CALL @Station.AdvanceTextRow.Entry
                RET C                                                           ; выход, если завершающий перенос достиг высоты окна

                JP @Station.PrintJustified.Row

                endmodule
                endmodule
