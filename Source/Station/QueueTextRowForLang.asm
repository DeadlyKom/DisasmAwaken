                module Station
                module QueueTextRowForLang
; Подробный разбор [подготовка строки текста](../../Docs/QueuedText.md)
; Подготовка строки текста в банке 0 с возвратом банка языка 6
; In:
;   AF - A индекс строки, тень страницы согласована с #7FFD и bit5 снят
;   выполнен договор QueueTextRow после выбора банка 0, стек вне сменяемого окна
;   возврат находится в фиксированной памяти либо в банке LANG 6
; Out:
;   HL, DE и изменения списка/геометрии по QueueTextRow, BC сохранён
;   AF - A=(старое CurrentPage AND F8) OR 16, F от последнего OR выбора страницы
;   альтернативные и индексные регистры, I и IFF сохранены, SP обычного возврата равен входному SP+2
;   порт и тень выбирают сначала банк 0 с ROM 1, затем банк 6 с ROM 1, старшие биты сохраняются
; Corrupt:
;   HL, DE, AF
; Note:
;   A строки сохраняется через первый выбор банка, затем передаётся QueueTextRow
;   последний выбор страницы заменяет основной AF, исходный RAM-банк не восстанавливается
                ; сохранение строки вокруг выбора станционного банка
Entry:          PUSH AF
                ; выбор банка 0 с ROM 1 перед работой со списком и записью элемента
                LD A, #10
                CALL @Station.SelectRamBank.Entry
                ; возврат исходного A строки и F перед основным вызовом
                POP AF
                ; подготовка строки и геометрии настоящими станционными процедурами
                CALL @Station.QueueTextRow.Entry
                ; возврат LANG в банк 6, финальный AF будет результатом выбора страницы
                LD A, #16
                CALL @Station.SelectRamBank.Entry
                RET

                endmodule
                endmodule
