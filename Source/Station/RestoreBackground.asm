                module Station
                module RestoreBackground
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [768 банковых знакомест, карта владельцев, атрибуты и завершение экранного цикла](../../Docs/RestoreBackground.md)
; -----------------------------------------
; Восстановление свободных и потерявших владельца знакомест из банка 3 с обновлением атрибутов
; исходная запись 4, файловые смещения #3D25..#3D95
; In:
;   станционный код в банке 0, блокировка #7FFD.bit5 снята, тень CurrentPage соответствует аппаратному порту
;   банк 3 содержит 768 последовательных восьмибайтовых знакомест по #C000 и 768 атрибутов по #D800
;   карта владельцев #8600..#88FF и индексная страница #8500 доступны, код и таблицы не пересекают стек
;   BackgroundState.ItemAttribute задаёт атрибут сохранившихся ячеек интерфейса, перед вызовом указатель снят
;   действует договор ResumePointer, текущая ячейка указателя имеет нулевого либо допустимого владельца
; Out:
;   HL=#8900, DE=#5800, BC=#D800, A=#10, F от OR последнего SelectRamBank перед EndScreenUpdate
;   HL'=#5B00, DE'=#DB00, B'=#85, C' атрибут последнего обработанного знакоместа
;   AF' рабочий, IX и IY сохранены, I и IFF сохранены, SP восстановлен
;   карта владельцев и банк 3 сохранены, свободные и недействительные ячейки получили фон и его атрибуты
;   действительные ячейки сохранили bitmap и получили ItemAttribute, затем поверх сцены возобновлён указатель
;   CurrentPage=#10, показан экран банка 5, UpdateBlocked=0
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF'
; Note:
;   при владельце 1..128 проверяется старший байт соответствующей пары индекса, #FF означает недействительность
;   вычисление использует RLCA владельца минус один, у значений 129..255 проверяется уже младший байт другой пары
;   для ненулевого владельца смещение проверяемого байта равно (ROL8(владелец-1,1)+1) AND #FF
;   недействительный владелец не обнуляется в карте, восстановление пикселей само по себе таблицу не исправляет
;   для свободной либо недействительной ячейки копируются восемь строк и атрибут, для действительной источник пропускается на восемь байтов
;   порядок источника знакоместный, он не совпадает с нелинейным bitmap Spectrum
;   ItemAttribute является операндом LD C по #9D48, его заранее формирует RebuildInterface
;   порт получает сначала (старое AND #F8) OR #13, затем (старое AND #F8) OR #10, наконец ровно #10
;   последняя запись выполняется EndScreenUpdate после ResumePointer и принудительно выбирает базовый экран
;   F сохраняется EndScreenUpdate от промежуточной страницы, поэтому он может не соответствовать итоговому A=#10
;   модель использует синтетический фон и все байты владельца, не подтверждает загрузку реального сжатого экрана
; -----------------------------------------
                ; выбор банка 3 с фоновыми знакоместами и атрибутами
Entry:          LD A, #13
                CALL @Station.SelectRamBank.Entry
                ; подготовка альтернативных указателей атрибутов экрана и фона
                LD HL, #5800
                LD DE, #D800
                ; выбор страницы индексных пар владельцев
                LD B, #85
                ; перенос указателей атрибутов в альтернативный набор перед обходом пикселей
                EXX
                ; подготовка обхода всех 768 ячеек карты и последовательного источника восьмибайтовых знакомест
                LD HL, @StationState.DirtyCells
                LD DE, #4000
                LD BC, #C000
                ; чтение владельца очередного знакоместа
NextCell:       LD A, (HL)
                ; проверка нулевого владельца, свободная ячейка требует восстановления фона
                AND A
                JR Z, @Station.RestoreBackground.CopyTile                       ; переход, если владелец равен нулю, скопировать фоновое знакоместо

                ; переключение к индексной странице и указателям атрибутов
                EXX
                ; расчёт смещения пары по владельцу минус один
                DEC A
                ; удвоение вращением, значения владельца выше 128 меняют чётность смещения
                RLCA
                LD C, A
                ; переход к проверяемому байту, у штатного владельца это старший байт индекса
                INC C
                ; проверка байта индекса на #FF через увеличение
                LD A, (BC)
                INC A
                ; чтение атрибута интерфейсной ячейки из операнда, заданного RebuildInterface
                LD C, #00
                ; возврат к карте и пиксельным указателям с сохранением результата проверки
                EXX
                JP Z, @Station.RestoreBackground.CopyTile                       ; переход, если проверяемый байт индекса равен #FF, восстановить фоновое знакоместо

                ; расчёт пропуска восьми исходных байтов при сохранении bitmap действительного владельца
                LD A, C
                ADD A, #07
                LD C, A
                INC BC
                ; сохранение старшей части экранного адреса для общего шага знакоместа
                LD A, D
                JP @Station.RestoreBackground.AdvanceCell

                ; сохранение исходного D экранного адреса в AF' перед вертикальной записью восьми строк
CopyTile:       LD A, D
                EX AF, AF'
                ; копирование восьми последовательных исходных байтов в восемь строк знакоместа Spectrum
                LD A, (BC)
                INC C
                LD (DE), A
                INC D
                LD A, (BC)
                INC C
                LD (DE), A
                INC D
                LD A, (BC)
                INC C
                LD (DE), A
                INC D
                LD A, (BC)
                INC C
                LD (DE), A
                INC D
                LD A, (BC)
                INC C
                LD (DE), A
                INC D
                LD A, (BC)
                INC C
                LD (DE), A
                INC D
                LD A, (BC)
                INC C
                LD (DE), A
                INC D
                LD A, (BC)
                INC BC
                LD (DE), A
                ; переключение к атрибутам после переноса пикселей фоновой ячейки
                EXX
                ; чтение фонового атрибута только для восстановленной ячейки
                LD A, (DE)
                LD C, A
                EXX
                ; восстановление старшей части экранного адреса из AF'
                EX AF, AF'
                ; расчёт следующей колонки через младший байт экранного адреса
AdvanceCell:    INC E
                JR NZ, @Station.RestoreBackground.StoreAttribute                ; переход, если младший экранный адрес не обернулся, старшая часть прежняя

                ; расчёт следующей трети bitmap при оборачивании младшего экранного адреса
                ADD A, #08
                ; обновление экранного указателя и переход к следующей ячейке карты
StoreAttribute: LD D, A
                INC HL
                ; переключение к указателям атрибутов для записи выбранного C
                EXX
                ; запись фонового либо интерфейсного атрибута текущего знакоместа
                LD (HL), C
                ; переход обоих атрибутных указателей к следующему знакоместу
                INC HL
                INC DE
                EXX
                ; проверка конца 768-байтовой карты по достижению страницы #89
                LD A, H
                CP #89
                JP C, @Station.RestoreBackground.NextCell                       ; переход, если карта ещё не достигла #8900, обработать следующее знакоместо

                ; возврат станционного банка 0 перед рисованием указателя
                LD A, #10
                CALL @Station.SelectRamBank.Entry
                ; завершение экранного цикла, возобновление указателя и точная запись страницы #10
                JP @Station.EndScreenUpdate.Entry

                endmodule
                endmodule
