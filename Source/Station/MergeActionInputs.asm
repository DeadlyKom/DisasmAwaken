                module Station
                module MergeActionInputs
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [объединение входов и чтение бита контура](../../Docs/InterfaceInput.md)
; -----------------------------------------
; Объединение четырёх входных байтов с удвоением первой пары по модулю 256
; исходная запись 4, файловые смещения #3C43..#3C58
; In:
;   байты #66EC, #6585, #66ED, #658A доступны для чтения
; Out:
;   HL, DE и BC сохранены, A=(((#66EC OR #6585)<<1) OR #66ED OR #658A) AND #FF
;   F соответствует OR A, Carry=0,H=0,N=0, Z=1 ровно при нулевом объединённом коде
; Corrupt:
;   AF
; Note:
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   состояние входных байтов не очищается, старший бит первой объединённой пары отбрасывается
;   физическое назначение отдельных входных разрядов этой формулой не доказывается
; -----------------------------------------
                ; сохранение BC, временные B и C используются для объединения четырёх байтов
Entry:          PUSH BC
                ; чтение первой пары источников для последующего сдвига на один разряд
                LD A, (#66EC)
                LD C, A
                LD A, (#6585)
                OR C
                ; расчёт удвоенного OR первой пары, старший разряд теряется
                ADD A, A
                LD C, A
                ; чтение второй пары источников, добавляемой без сдвига
                LD A, (#66ED)
                LD B, A
                LD A, (#658A)
                OR B
                ; объединение прямой пары со сдвинутой, итоговые флаги относятся к этому OR
                OR C
                POP BC
                RET

                endmodule
                endmodule
