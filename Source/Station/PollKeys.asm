                module Station
                module PollKeys
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [опрос, накопление и таблица направлений](../../Docs/PointerInputs.md)
; -----------------------------------------
; Проверка шести настроенных клавиш и формирование общего байта направлений и действий
; исходная запись 4, файловые смещения #08ED..#0933
; In:
;   PointerXY содержит X=0..255,Y=0..191, шесть InputFlags доступны для чтения и записи
;   PointerInputState.Step=2, MaxY=191 и MaxX=255 подготовлены StartStation
;   таблица PointerDirections содержит исходные 16 указателей, код и CPU-стек доступны
;   шесть FKeyBinding задают байт строки L и маску H, нажатие определяется точным условием (IN AND Mask)==0
; Out:
;   BC - итоговые пиксельные X в C,Y в B, DE=#BF02, HL и AF рабочие
;   PointerXY обновлён выбранным шагом либо прежним BC при отсутствии движения
;   каждый из шести InputFlags получает старое значение OR соответствующий разряд текущей выборки
;   индексные и альтернативные регистры, I и IFF сохраняются, SP восстанавливается
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   порядок клавиш Up,Down,Left,Right,Action2,Action1, итоговые разряды соответственно 3,2,1,0,4,5
;   каждая строка читается отдельно, совпадение адресов строк не сокращает шесть исходных IN
;   при нулевой маске клавиша считается нажатой независимо от значения порта
;   байты действий участвуют в накоплении, но не в выборе одного из 16 направлений
;   противоположные направления по любой оси внутри текущей выборки выбирают NoPointerMotion и отменяют обе оси
;   выбор движения использует текущий A, ранее накопленные флаги не отменяют и не усиливают этот шаг
;   ApplyPointerInput кладёт CommitPointerInput поверх исходного адреса возврата и передаёт управление JP (HL)
;   RET обработчика направления выполняет CommitPointerInput, его RET возвращает исходному вызывающему коду
;   ClearInputFlags выполняется до обоих опросов в Interrupt, сами опросы накопленные флаги не очищают
;   последовательные опросы джойстика и клавиатуры каждый отдельно двигают указатель, одинаковое направление даёт два шага
;   модель задаёт показания портов, не исполняет IRQ и не проверяет реальное устройство
; -----------------------------------------
                ; создание нулевого байта шести настроенных клавиш
Entry:          LD E, #00
                LD C, #FE
                ; чтение FKeyBinding для Up и выбор её строки клавиатуры
                LD HL, (@PointerKeys.Up)
                LD B, L
                IN A, (C)
                ; проверка маски настроенной клавиши Up
                AND H
                JR NZ, @Station.PollKeys.CheckDown                              ; переход, если хотя бы один маскированный разряд ненулевой, не устанавливать Up

                SET 3, E
                ; чтение FKeyBinding для Down и выбор её строки клавиатуры
CheckDown:      LD HL, (@PointerKeys.Down)
                LD B, L
                IN A, (C)
                ; проверка маски настроенной клавиши Down
                AND H
                JR NZ, @Station.PollKeys.CheckLeft                              ; переход, если хотя бы один маскированный разряд ненулевой, не устанавливать Down

                SET 2, E
                ; чтение FKeyBinding для Left и выбор её строки клавиатуры
CheckLeft:      LD HL, (@PointerKeys.Left)
                LD B, L
                IN A, (C)
                ; проверка маски настроенной клавиши Left
                AND H
                JR NZ, @Station.PollKeys.CheckRight                             ; переход, если хотя бы один маскированный разряд ненулевой, не устанавливать Left

                SET 1, E
                ; чтение FKeyBinding для Right и выбор её строки клавиатуры
CheckRight:     LD HL, (@PointerKeys.Right)
                LD B, L
                IN A, (C)
                ; проверка маски настроенной клавиши Right
                AND H
                JR NZ, @Station.PollKeys.CheckAction2                           ; переход, если хотя бы один маскированный разряд ненулевой, не устанавливать Right

                SET 0, E
                ; чтение FKeyBinding для Action2 и выбор её строки клавиатуры
CheckAction2:   LD HL, (@PointerKeys.Action2)
                LD B, L
                IN A, (C)
                ; проверка маски настроенной клавиши Action2
                AND H
                JR NZ, @Station.PollKeys.CheckAction1                           ; переход, если хотя бы один маскированный разряд ненулевой, не устанавливать Action2

                SET 4, E
                ; чтение FKeyBinding для Action1 и выбор её строки клавиатуры
CheckAction1:   LD HL, (@PointerKeys.Action1)
                LD B, L
                IN A, (C)
                ; проверка маски настроенной клавиши Action1
                AND H
                JR NZ, @Station.PollKeys.UseKeys                                ; переход, если хотя бы один маскированный разряд ненулевой, не устанавливать Action1

                SET 5, E
                ; передача объединённого байта клавиш в общий обработчик без дополнительного вызова
UseKeys:        LD A, E
                ; JP @Station.ApplyPointerInput.Entry, продолжение в ApplyPointerInput.asm

                endmodule
                endmodule
