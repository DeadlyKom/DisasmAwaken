                module Station
                module FormatSettingsLabel
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [дискриминатор настройки и две подписи загрузчика](../../Docs/SettingsLabels.md)
; -----------------------------------------
; Замена символов шаблона кодами числовых, N/Y и клавиатурных двухбайтовых настроек
; исходная запись 4, файловые смещения #4163..#4190
; In:
;   HL - сохраняемый контекст, DE - массив двухбайтовых FSettingWord, BC - существующая нультерминированная подпись
;   до нулевого символа подписи имеется читаемая двухбайтовая запись на каждый символ, массив и подпись не перекрываются
;   ValueOrRow меньше #7F означает числовой байт, #80 и #81 маркеры N/Y, остальные значения допустимые строки матрицы с KeyMask
;   для клавиатурных записей выполняется договор LookupMatrixKey, код станции и таблица доступны
; Out:
;   HL сохранён, DE увеличен на два на каждый заменённый символ, BC указывает на прежний нулевой ограничитель
;   AF=#0054, подпись изменена на месте, её ограничитель и длина сохранены
;   массив настроек не меняется, альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
; Corrupt:
;   DE, BC, AF
; Note:
;   пустой шаблон не читает массив настроек и сразу возвращает исходные указатели
;   числовой байт преобразуется прибавлением #30, допустимы все значения 0..126, это не десятичная печать нескольких цифр
;   второй байт не читается при числовом значении и маркерах N/Y, для клавиши он содержит KeyMask
;   перед каждой записью BC сохраняется, поэтому рабочие BC и HL LookupMatrixKey не нарушают обход подписи
;   после возврата из поиска DE увеличивается ровно на два, внутренний INC DE чтения маски предварительно отменяется DEC DE
;   два фактических вызова StartStation используют подписи #9728 и #9736 длиной 13 и 43, настройки начинаются #99AE и #99C8
;   игровое назначение каждой настройки второго блока отдельно не доказано, их физический порядок и тип представления сохраняются
;   модель проверяет преобразование секторных исходных данных без загрузки внешних пользовательских настроек
; -----------------------------------------
                ; сохранение исходного HL поверх исходного возврата, поиск клавиши может менять HL
Entry:          PUSH HL
                ; проверка следующего символа существующего шаблона для определения длины преобразования
NextValue:      LD A, (BC)
                AND A
                JR Z, @Station.FormatSettingsLabel.Finish                       ; переход, если символ шаблона нулевой, закончить без чтения следующей настройки

                ; сохранение указателя назначения на время выбора представления и поиска клавиши
                PUSH BC
                ; чтение ValueOrRow очередного двухбайтового параметра
                LD A, (DE)
                ; проверка числового диапазона 0..126 перед маркерами и строками матрицы
                CP @SettingsLabelConst.FirstRow
                JR NC, @Station.FormatSettingsLabel.CheckMarker                 ; переход, если ValueOrRow не меньше #7F, проверить маркеры N/Y либо сигнатуру клавиши

                ; расчёт одного символа числового параметра прибавлением кода нуля, десятичное разложение не выполняется
                ADD A, @SettingsLabelConst.DigitZero
                JR @Station.FormatSettingsLabel.StoreChar

                ; проверка маркера N перед интерпретацией параметра как аппаратной строки
CheckMarker:    CP @SettingsLabelConst.NoTag
                LD A, @SettingsLabelConst.NoChar
                JR Z, @Station.FormatSettingsLabel.StoreChar                    ; переход, если ValueOrRow равен #80, записать символ N

                ; повторное чтение ValueOrRow для проверки маркера Y
                LD A, (DE)
                CP @SettingsLabelConst.YesTag
                LD A, @SettingsLabelConst.YesChar
                JR Z, @Station.FormatSettingsLabel.StoreChar                    ; переход, если ValueOrRow равен #81, записать символ Y

                ; создание сигнатуры B=ValueOrRow, C=KeyMask из физической двухбайтовой записи
                LD A, (DE)
                LD B, A
                INC DE
                LD A, (DE)
                LD C, A
                DEC DE
                ; поиск кода аппаратной клавиши по общей исходной таблице
                CALL @Station.LookupMatrixKey.Entry
                ; переход к следующей двухбайтовой записи без изменения её содержимого
StoreChar:      INC DE
                INC DE
                ; восстановление указателя назначения и замена одного символа подписи
                POP BC
                LD (BC), A
                INC BC
                JR @Station.FormatSettingsLabel.NextValue

                ; возврат исходного HL после принятого нулевого символа шаблона
Finish:         POP HL
                RET

                endmodule
                endmodule
