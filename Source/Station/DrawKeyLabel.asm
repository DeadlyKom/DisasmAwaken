                module Station
                module DrawKeyLabel
                ; Документация [три физические записи, обёрнутое смещение и статус последнего из четырёх вызовов](../../Docs/KeyLabels.md)
                ; -----------------------------------------
                ; Вывод одного глифа либо четырёх байтов обозначения Enter, Symbol Shift или Space
                ; исходная запись 4, файловые смещения #5DF0..#5E1A
                ; In:
                ;   AF содержит A полный код символа, F не является параметром
                ;   TextWindow, шрифт, пиксельная часть и стек удовлетворяют DrawGlyph
                ;   при A<21 доступны четыре байта от BE1B+((A-1E)*4 по модулю 256), штатные подписи задаются 1E..20
                ; Out:
                ;   HL, DE, BC сохранены, AF является результатом единственного либо последнего из четырёх DrawGlyph
                ;   HL', DE', BC', AF', IX, IY, I, IFF и IM сохранены, SP после RET равен входному+2
                ;   при A>=21 выполнен один DrawGlyph, при A<21 последовательно выполнены все четыре вызова
                ;   курсор и bitmap содержат реально принятые глифы, CursorY не меняется
                ; Corrupt:
                ;   AF, CursorX, bitmap и изменяемый GlyphState.DispatchTarget по договору DrawGlyph
                ; Note:
                ;   после отказа одного из четырёх глифов остальные вызовы всё равно выполняются, возвращается только последний статус
                ;   для A<1E индекс заворачивается в байте и может читать соседние данные и код, диапазон трёх записей не проверяется
                ;   внутренних переносов и завершения по CR/LF нет, все выбранные байты передаются непосредственно DrawGlyph
                ; -----------------------------------------
                ; проверка прямого глифа, порог 21 отделяет печатаемые коды от четырёхсимвольных обозначений
Entry:          CP @KeyLabelConst.FirstDirect
                JR C, @Station.DrawKeyLabel.ExpandLabel                         ; переход, если входной код меньше 21, прочитать четыре байта обозначения

                ; вывод единственного исходного глифа с возвратом его статуса
                CALL @Station.DrawGlyph.Entry
                RET

                ; расчёт байтового смещения четырёхсимвольной записи, вычитание и умножение заворачиваются
ExpandLabel:    SUB @KeyLabelConst.FirstExpanded
                ADD A, A
                ADD A, A
                ; сохранение указателей вызывающего кода на время обхода четырёх символов
                PUSH HL
                PUSH DE
                LD L, A
                LD H, #00
                ; выбор исходной физической таблицы, отдельной проверки её границ нет
                LD DE, @KeyAbbreviations.Enter
                ADD HL, DE
                ; вывод первого символа обозначения, промежуточные отказы не прерывают обход
                LD A, (HL)
                INC HL
                CALL @Station.DrawGlyph.Entry
                ; вывод второго символа обозначения независимо от первого статуса
                LD A, (HL)
                INC HL
                CALL @Station.DrawGlyph.Entry
                ; вывод третьего символа обозначения независимо от прежних статусов
                LD A, (HL)
                INC HL
                CALL @Station.DrawGlyph.Entry
                ; вывод четвёртого символа, только его AF возвращается вызывающему коду
                LD A, (HL)
                CALL @Station.DrawGlyph.Entry
                POP DE
                POP HL
                RET

                endmodule
                endmodule
