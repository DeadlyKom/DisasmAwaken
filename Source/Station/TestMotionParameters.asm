; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [StationCore.md](../../Docs/StationCore.md)
; -----------------------------------------
; Объединение четырёх слов параметров в признак нулевого движения
; исходная запись 4, файловые смещения #069D..#06B7
; In:
;   четыре слова по #6586, #6588, #66E8 и #66EA доступны для чтения
; Out:
;   AF - A побитовое OR восьми входных байтов, F соответствует последнему логическому OR
;   Z установлен только при нулевом значении всех четырёх слов, Carry, HalfCarry и N сброшены
; Corrupt:
;   AF
; Note:
;   HL, DE, BC, альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   вход ничего не записывает и не вызывает обработчиков, типы и единицы отдельных слов требуют дальнейшего разбора
;   S, биты 5 и 3 и чётность определяются объединённым байтом, это не арифметическая сумма слов
; -----------------------------------------
Entry:          PUSH HL
                PUSH DE
                ; чтение первой пары проверяемых слов без изменения их содержимого
                LD HL, (#6586)
                LD DE, (#6588)
                ; объединение байтов первой пары, ненулевой разряд исключает полностью нулевое состояние
                LD A, H
                OR L
                OR E
                OR D
                ; чтение второй пары проверяемых слов
                LD HL, (#66E8)
                LD DE, (#66EA)
                ; объединение второй пары с результатом первой, Carry и HalfCarry сбрасываются
                OR L
                OR H
                OR E
                OR D
                POP DE
                POP HL
                RET

                endmodule
                endmodule
