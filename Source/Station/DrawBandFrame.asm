                module Station
                module DrawBandFrame
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [StationSpans.md](../../Docs/StationSpans.md)
; -----------------------------------------
; Рисование рамки с выбираемой верхней полосой и горизонтальным разделителем
; исходная запись 4, файловые смещения #6093..#60C8
; In:
;   DE - D высота рамки в знакоместах 3..24, E полная ширина в байтах 2..32
;   BC - B знаковая строка знакомест, C знаковая байтовая колонка, рамка имеет горизонтальное пересечение с экраном
;   AF - бит 0 входного A выбирает заполненную полосу, остальные биты A и входные флаги не определяют рисунок
;   таблицы #82..#84 подготовлены загрузчиком, код писателя и CPU-стек доступны для записи и не перекрывают экран
;   шесть изменяемых слов рамки задают обычный либо заполненный режим из StationSpans.md
; Out:
;   видимая часть рамки записана в bitmap #4000..#57FF, атрибуты не изменены
;   HL, DE, BC, AF и L' содержат рабочее состояние последнего участка, не возвращаемые параметры
; Corrupt:
;   HL, DE, BC, AF, HL', AF'
; Note:
;   первые три пиксельные строки используют ClearSpanPattern, SetSixBitPattern и SetOutlinePattern
;   при A.0=0 строки 3..10 используют SetOutlinePattern, при A.0=1 SetCutoutPattern, нумерация от нуля
;   строка 11 содержит боковые пиксели, строка 12 обнуляется, строки 13..15 снова содержат боковые пиксели
;   далее рисуются D-3 полных средних знакомест и нижнее знакоместо по схеме ноль, пять боковых строк, шесть средних битов, ноль
;   исполнение последовательно переходит в FinishBandFrame, без дополнительного CALL и без отдельного адреса возврата
;   H', DE', BC', IX, IY, I и IFF сохраняются, SP восстанавливается, ожидания кадра здесь нет
;   меняются BandPattern, LeftCode, RightCode и SpanSkip, функция не реентерабельна
;   недопустимые размеры, полное отсутствие горизонтального пересечения и вмешательство IRQ моделью не подтверждены
;   шесть изменяемых операндов имеют обычный набор ResetBandMode либо заполненный набор SetBandFillMode
;   в заполненном режиме строки 3..10 всегда SetCutoutPattern, строки 12 и 13..15 и середина также заполнены
;   нижнее знакоместо заполненного режима содержит пять строк SetCutoutPattern, одну фиксированную SetOutlinePattern, SetSixBitPattern и ClearSpanPattern
;   строки 2,11 и третья снизу сохраняют обычный боковой узор, их фиксированные вызовы не подменяются
; -----------------------------------------
                ; перенос бита 0 типа верхней полосы в Carry, остальные биты типа на рисунок не влияют
Entry:          RRA
                ; выбор установщика верхней полосы из изменяемого слова StationRaster.BandDefault
                LD HL, @Station.SetOutlinePattern.Entry
                JR NC, @Station.DrawBandFrame.SetBand                           ; переход, если бит 0 типа сброшен, верхняя полоса остаётся с пустой серединой

                ; выбор заполненной середины верхней полосы с боковыми пропусками
                LD HL, @Station.SetCutoutPattern.Entry
                ; запись установщика узора в операнд первого CALL продолжения FinishBandFrame
SetBand:        LD (@StationRaster.BandPattern), HL
                ; расчёт внутренней ширины без двух крайних байтов рамки
                DEC E
                DEC E
                ; расчёт числа средних знакомест без двух верхних и одного нижнего
                DEC D
                DEC D
                DEC D
                CALL @Station.PrepareFrameRaster.Entry
                ; расчёт смещения пропуска неиспользуемых пар записи средних байтов
                LD A, #1E
                SUB E
                ADD A, A
                ; настройка пропуска лишних средних байтов развёрнутого писателя строки
                LD (@StationRaster.SpanSkip), A
                ; сохранение счётчика высоты до замены DE байтовыми узорами
                LD B, D
                ; проверка видимости первого верхнего знакоместа
                CALL @Station.AdvanceClipRow.Entry
                RET NC                                                          ; выход, если верхнее знакоместо достигло нижней границы экрана

                JP M, @Station.FinishBandFrame.Entry                            ; переход, если верхнее знакоместо выше экрана, его первые три строки пропускаются

                ; обнуление первой пиксельной строки верхней полосы
                CALL @Station.ClearSpanPattern.Entry
                CALL @Station.DrawSpanRow.Entry
                ; рисование шести средних пикселей в крайних байтах второй строки
                CALL @Station.SetSixBitPattern.Entry
                CALL @Station.DrawSpanRow.Entry
                ; выбор боковых пикселей для третьей строки
                CALL @Station.SetOutlinePattern.Entry
                CALL @Station.DrawSpanRow.Entry
                ; сброс Sign перед последовательным продолжением видимой верхней полосы
                XOR A

                ; JP @Station.FinishBandFrame.Entry, продолжение в FinishBandFrame.asm

                endmodule
                endmodule
