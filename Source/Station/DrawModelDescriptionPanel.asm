                module Station
                module DrawModelDescriptionPanel
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [пустое наведение, условный RET с продолжением и полный рисователь описания](../../Docs/DescriptionPanel.md)
                ; -----------------------------------------
                ; Рамка и банковая печать выбранного описания с сохранённой начальной строкой
                ; исходная запись 4, файловые смещения #0BF1..#0BFD
                ; In:
                ;   ModelDescriptionState.ItemIndex содержит актуальный индекс FInterfaceItem, исходный загрузчик назначает 27, Opcode равен 21 либо отключающему C9
                ;   при активном входе действуют договоры DrawCaptionItem и PrintModelDescription, TopRow задаёт сохранённое слово прокрутки
                ;   порт и CurrentPage согласованы, банк станции 0, paging не заблокирован, CPU-стек вне сменяемого окна
                ;   HALT рамки получает корректное пробуждение по договору DrawBandSync
                ; Out:
                ;   HL, DE, BC - результат настоящего PrintModelDescription с входным словом TopRow
                ;   AF - итоговая страница (исходная CurrentPage AND F8) OR 10 и её логические флаги, статус текста не возвращается
                ;   HL', DE', BC' сохраняются, AF' является рабочим выходом рамки и сохраняется банковым печатателем
                ;   IX, IY, I и IFF сохраняются при договоре пробуждения, банк 4 посещается для описания, итоговый банк станции 0
                ;   рамка, заголовок, курсор и bitmap изменены по договорам двух помощников, RowCount и TopRow этим входом не записываются
                ;   при C9 основные, альтернативные и индексные регистры, флаги и память сохраняются, рисунка и банковых операций нет
                ;   SP обычного возврата равен входному SP+2
                ; Corrupt:
                ;   при активном входе HL, DE, BC, AF, AF' и графическое состояние помощников
                ; Note:
                ;   верхний байт TopRow сохраняется в слове, но реальный пропуск текста использует только младший байт
                ;   слово индекса в исходном LD HL первоначально нулевое, это изменяемый код, не физический индекс записи 0
                ;   отказы текста не вызывают дополнительного выхода или исправления курсора в этой обёртке
                ; -----------------------------------------
                ; чтение изменяемого индекса панели, C9 отключает весь вход
Entry:          LD HL, #0000
                ; реальные регистрация, рамка и заголовок по общему договору элемента
                CALL @Station.DrawCaptionItem.Entry
                ; чтение сохранённого слова прокрутки, печататель использует его младший байт
                LD HL, (@ModelDescriptionState.TopRow)
                ; реальный банковый вывод описания с заданным началом
                CALL @Station.PrintModelDescription.Entry
                RET

                endmodule
                endmodule
