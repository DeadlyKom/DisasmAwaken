                module Station
                module RefreshMapPanel
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [размеры внутренней области, три запроса, paging и два уровня проверки](../../Docs/MapPanel.md)
; -----------------------------------------
; Перерисовка карты через снимок банка 7, очистку тела и дополнительный HALT перед показом
; исходная запись 4, файловые смещения #0FF0..#0FF9
; In:
;   действуют договоры BeginScreenUpdate, ClearAndDrawMapPanel и EndScreenUpdate, paging доступен
;   дополнительный HALT этой процедуры пробуждается окружением, вложенный C000 имеет свой отдельный HALT
; Out:
;   старый базовый экран сохранён в банке 7 и показан на время очистки и рисунка карты
;   после ClearAndDrawMapPanel всегда выполнен отдельный HALT, в том числе при раннем отказе геометрии
;   EndScreenUpdate возобновляет указатель и выбирает базовый экран, CurrentPage=10, A=10, F сохранён от ClearAndDrawMapPanel
;   HL, DE, BC, альтернативные общие пары и IX соответствуют результату очистки и композиции, AF' рабочий от указателя
;   IY, I и IFF сохраняются инструкциями при договоре пробуждения, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, оба экрана, таблицы и запросы карты, состояние указателя
; Note:
;   успешный путь имеет два HALT, C000 и завершающий 6D4A, отказ геометрии всё равно исполняет второй
;   финальный показ выбирает фиксированную страницу 10, прежний бит отображаемого экрана не восстанавливается
;   модель проверила 16 очисток и 16 полных обновлений с независимой заливкой, секторным рисунком, указателем и снимком банка 7
; -----------------------------------------
                ; сохранение старого базового экрана и начало обновления с показом снимка банка 7
Entry:          CALL @Station.BeginScreenUpdate.Entry
                ; очистка внутреннего тела и общий банковый рисунок содержимого
                CALL @Station.ClearAndDrawMapPanel.Entry
                ; отдельное ожидание перед показом базового экрана, выполняется и при отказе геометрии
                HALT
                ; передача в EndScreenUpdate с исходным адресом возврата
                JP @Station.EndScreenUpdate.Entry

                endmodule
                endmodule
