                module Station
                module CenterKeyAndRefreshMap
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [физические пятибайтовые записи, точные диапазоны сдвигов и общие хвосты](../../Docs/StoredPointEdits.md)
; -----------------------------------------
; Абсолютный банковый выбор ключа, чтение варианта из A и центрирование перед рисунком
; исходная запись 4, файловые смещения #1FC0..#1FCF
; In:
;   HL - SecondWord выбираемого ключа, DE - FirstWord, размер MapViewState готов для CenterMapView
;   действуют договоры SelectMapPoint и ReadStoredMapVariant, первый список имеет достижимое совпадение либо конец
;   действуют договоры BeginScreenUpdate, TryDrawSystemInfo, DrawMapPanel и EndScreenUpdate, две записи панелей и данные карты готовы
;   paging доступен, указатель согласован с фоном, адресные и индексные таблицы готовы, все фактические HALT пробуждаются окружением
;   стек вне экранных областей и переключаемого окна, банк станции 0 доступен
; Out:
;   выбран абсолютный банк 11, MapSelection получает входные слова и первый совпавший Variant из A либо ноль
;   MapViewState.OriginLow и OriginHigh обновлены по CenterMapView, включая исходное вычитание 256 при нулевом полуразмере
;   выбран абсолютный банк 10, выполнен хвостовой общий рисунок RefreshStoredMapPanels, его результаты являются конечными
;   Pending этот самостоятельный вход не устанавливает, старый бит теневого экрана первыми абсолютными paging не сохраняется
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, bitmap и рабочие данные общего рисунка, MapSelection, начало карты, рабочие данные поиска
; Note:
;   до передачи рисунку HL содержит упакованные старшие координаты начала, DE младшие, BC=FF00 OR отрицательная половина Height, A=10
;   в этой точке F соответствует ADC расчёта Y до отсечения, IY и альтернативные регистры сохранены, IX относится к поиску A
;   модель 2048 комбинаций проверяет все байтовые размеры и наличие либо отсутствие совпадения A до общего рисунка
; -----------------------------------------
                ; абсолютный выбор страницы KARTA, прежний экранный бит здесь не сохраняется
Entry:          LD A, @SystemNameConst.MapPage
                CALL @Station.SelectMemoryPage.Entry
                ; запись выбранных слов, поиск варианта в первом A и центрирование видимого начала
                CALL @Map.SelectMapPoint.Entry
                ; абсолютный возврат станции перед общим рисунком
                LD A, @StationIrqConst.StationPage
                CALL @Station.SelectMemoryPage.Entry
                JP @Station.RefreshStoredMapPanels.Entry

                endmodule
                endmodule
