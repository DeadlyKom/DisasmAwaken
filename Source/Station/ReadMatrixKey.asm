                module Station
                module ReadMatrixKey
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [одиночный ввод и физическая таблица кодов](../../Docs/MatrixKey.md)
; -----------------------------------------
; Ожидание десяти пробуждений HALT и первой нажатой клавиши с табличным кодом
; исходная запись 4, файловые смещения #4116..#4149
; In:
;   порты матрицы доступны по строкам #7F, #BF, #DF, #EF, #F7, #FB, #FD, #FE и младшему адресу #FE
;   HALT получает десять пробуждений от корректного ISR, сохраняющего контекст, затем появляется хотя бы одна нажатая клавиша
;   KeyboardCodes содержит исходные пары, CPU-стек не пересекает таблицу и выполняемый код
; Out:
;   HL, DE и BC восстановлены, A содержит код первой нажатой клавиши в приоритете строк и младших разрядов
;   для штатной таблицы A=#1D..#5A, F от сложения индекса записи с #1D, S, Z, P/V, N, Carry сброшены
;   HalfCarry определяется переносом низшей тетрады индекса плюс #0D, биты 5 и 3 берутся из кода
;   альтернативные и индексные регистры, I и IFF собственным кодом сохраняются, SP восстанавливается
; Corrupt:
;   AF
; Note:
;   сначала выполняются ровно десять HALT, реальная длительность зависит от пробуждений, не от внутреннего цикла опроса
;   после задержки ожидание нажатия выполняется непрерывным опросом без дополнительных HALT
;   порядок строк #7F, #BF, #DF, #EF, #F7, #FB, #FD, #FE, внутри каждой проверяются биты 0..4
;   перед каждой новой строкой E снова получает #80, последовательные RLC превращают его в #01, #02, #04, #08, #10
;   верхние три бита прочитанной строки не проверяются, активный низкий уровень выбранного бита означает нажатие
;   одновременные нажатия выбираются по этому приоритету, ожидания отпускания и комбинирования модификаторов нет
;   LookupMatrixKey получает B строку и C маску, его рабочие HL, BC закрываются внешним сохранением
;   FMatrixKeyFrame содержит SavedDE, SavedHL, SavedBC и ReturnAddress
;   модель задаёт пробуждения HALT явно и не исполняет IRQ или реальное устройство
; -----------------------------------------
                ; создание FMatrixKeyFrame с исходными BC, HL и DE
Entry:          PUSH BC
                PUSH HL
                PUSH DE
                ; выбор задержки в десять пробуждений HALT до опроса нажатия
                LD B, @KeyboardConst.DelayTicks
                ; ожидание очередного пробуждения, фактическое время определяется источником IRQ
Delay:          HALT
                DJNZ @Station.ReadMatrixKey.Delay

                ; выбор первой строки матрицы с младшим адресом порта FE
                LD BC, @KeyboardConst.FirstPort
                ; обнуление позиции внутри очередной строки через исходную вращаемую маску #80
NextRow:        LD E, @KeyboardConst.MaskSeed
                ; чтение пяти проверяемых активных низких разрядов текущей строки
                IN A, (C)
                ; выбор маски бита 0 и проверка его активного низкого уровня
                RLC E
                RRCA
                JR NC, @Station.ReadMatrixKey.Found                             ; переход, если разряд 0 строки нулевой, вернуть код этой клавиши

                ; выбор маски бита 1 и проверка его активного низкого уровня
                RLC E
                RRCA
                JR NC, @Station.ReadMatrixKey.Found                             ; переход, если разряд 1 строки нулевой, вернуть код этой клавиши

                ; выбор маски бита 2 и проверка его активного низкого уровня
                RLC E
                RRCA
                JR NC, @Station.ReadMatrixKey.Found                             ; переход, если разряд 2 строки нулевой, вернуть код этой клавиши

                ; выбор маски бита 3 и проверка его активного низкого уровня
                RLC E
                RRCA
                JR NC, @Station.ReadMatrixKey.Found                             ; переход, если разряд 3 строки нулевой, вернуть код этой клавиши

                ; выбор маски бита 4 и проверка его активного низкого уровня
                RLC E
                RRCA
                JR NC, @Station.ReadMatrixKey.Found                             ; переход, если разряд 4 строки нулевой, вернуть код этой клавиши

                ; выбор следующей строки циклическим сдвигом нулевого бита старшего адреса порта
                RRC B
                JR @Station.ReadMatrixKey.NextRow

                ; создание сигнатуры RowMask=B, KeyMask=E для поиска кода
Found:          LD C, E
                ; поиск табличного кода первой найденной аппаратной сигнатуры
                CALL @Station.LookupMatrixKey.Entry
                ; снятие FMatrixKeyFrame с восстановлением DE, HL и BC поверх результата поиска
                POP DE
                POP HL
                POP BC
                RET

                endmodule
                endmodule
