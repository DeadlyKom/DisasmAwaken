                module Station
                module DrawHelpContents
                ; Документация [рамки, действующие HELP-вызовы, прокрутка и байтовый предел наведения](../../Docs/HelpPanels.md)
                ; -----------------------------------------
                ; Рамка списка разделов справки, сброс подсветки и пересчёт числа видимых CR-заголовков
                ; исходная запись 4, файловые смещения #0D07..#0D29
                ; In:
                ;   Entry с кодом LD HL требует HelpPanelState.ContentsIndex как индекс FInterfaceItem, штатно 22
                ;   геометрия, Flags, шрифт, стек и IRQ удовлетворяют DrawCaptionItem
                ;   HelpPanelState.ContentsTop содержит L номер существующего CR-заголовка, его H сохраняется в DE при печати
                ;   HELP загружен в банк 7, страница 10 либо 18 согласована с портом, переключения не заблокированы
                ; Out:
                ;   HL указывает на остановку PrintCrRecordAndRows, DE равен входному ContentsTop, BC сохранён
                ;   AF содержит число строк и флаги формулы PrintCrRecordAndRows, AF' равен 1000 либо 180C
                ;   HL', DE', BC', IX и IY сохранены, I, IFF и IM сохраняются при договоре IRQ
                ;   IndexRow=FF, Style=0, VisibleTitles получает полный байтовый результат числа строк
                ;   CursorY=8, CursorX после печати, bitmap содержит рамку и оставшиеся заголовки от ContentsTop
                ;   банк 0 и экранный бит восстановлены, SP после RET входному+2
                ;   при временном C9 в Entry сохраняются все регистры, флаги и память, SP после RET входному+2
                ; Corrupt:
                ;   HL, DE, AF, AF', IndexRow, VisibleTitles, курсор, окно, bitmap и изменяемые операнды помощников
                ; Note:
                ;   VisibleTitles является операндом D в UpdateIndexListHover, он ограничивает область вычисления строки
                ;   между CR-заголовками нет LF, печатается остаток потока до общего LF либо отказа окна
                ;   число строк берётся из AF' печатателя после возврата банка, не из его основного A=8
                ; -----------------------------------------
                ; чтение изменяемого индекса панели списка разделов
Entry:          LD HL, #0000
                ; рисование рамки и заголовка до изменения состояния подсветки
                CALL @Station.DrawCaptionItem.Entry
                ; сброс прежней XOR-полосы, фон уже заменён рамкой и содержимым
                LD A, #FF
                LD (@PanelHoverState.IndexRow), A
                ; отключение переноса остатка заголовка при отказе ширины
                CALL @Station.DisableTextWrap.Entry
                ; чтение верхнего CR-заголовка списка, младший байт выбирает запись
                LD HL, (@HelpPanelState.ContentsTop)
                ; выбор банка HELP с сохранением экранного бита
                ; -----------------------------------------
                ; RenderTitles принимает HL номера CR-заголовка, окно и Style подготовлены
                ; рамка и сброс IndexRow пропущены, договор хвоста [действия справки](../../Docs/HelpPanelActions.md)
                ; -----------------------------------------
RenderTitles:   LD A, #17
                CALL @Station.SelectRamBank.Entry
                ; печать CR-потока и расчёт числа строк в альтернативном AF
                CALL @Help.PrintCrRecordAndRows.Entry
                ; возврат банка станции перед чтением альтернативного результата
                LD A, #10
                CALL @Station.SelectRamBank.Entry
                ; получение числа строк, AF переключателя сохраняется в альтернативном наборе
                EX AF, AF'
                ; обновление байтового предела строк в исходном LD DE обработчика наведения
                LD (@HelpPanelState.VisibleTitles), A
                RET

                endmodule
                endmodule
