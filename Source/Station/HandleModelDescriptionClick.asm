                module Station
                module HandleModelDescriptionClick
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [развилки селектора, точная граница текста и сохранение результата реальной прокрутки](../../Docs/DescriptionAction.md)
                ; -----------------------------------------
                ; Выбор панели описания, закрытие по строке заголовка либо прокрутка выбранного текста
                ; исходная запись 4, файловые смещения #0BC2..#0BE8
                ; In:
                ;   HL - запасная обёртка, DE - индекс панели, BC - контекст, AF - полный селектор по договору RepaintAndFlag
                ;   список рисования, активный callback, FlagsCache, указатель и FInterfaceItem удовлетворяют RepaintAndFlag и CloseMenuOnRow
                ;   на пути прокрутки действуют CountModelDescriptionRows, ScrollWindowRows и PrintModelDescription, TopRow содержит исходное слово индекса
                ;   станционный банк 0 доступен для записи, стек вне сменяемого окна, paging не заблокирован, текстовое окно и глиф подготовлены
                ;   ввод может изменяться между опросами, HALT получает допустимое пробуждение, для штатной прокрутки индекс не превышает EndLimit
                ; Out:
                ;   вначале RepaintAndFlag выбирает ExitInstruction=SCF и выполняет свой полный договор, Carry немедленно возвращается без локальных изменений текста
                ;   при исходном бите 7 селектора A сохранён, F=(A AND A8) OR 1, остальное по раннему договору RepaintAndFlag
                ;   при отсутствии Carry возвращённый A уменьшается, нулевой результат завершает действие через SelectionOnly, A=0, F=42
                ;   иначе CloseMenuOnRow сравнивает только символьные Y указателя и начала окна, при Z=1 панель удалена из списка и возврат немедленный
                ;   на оставшемся пути RowCount получает полное DE реального счётчика, RenderCall получает PrintModelDescription.Entry, EndLimit получает RowCount
                ;   ScrollWindowRows вызывается с A=8 и HL=TopRow, после возврата TopRow получает весь итоговый HL, не только младший байт
                ;   при нормальном отпускании прокрутки HL итоговый индекс, DE исходные PointerXY, AF=0044, CurrentPage и порт равны 10, указатель восстановлен
                ;   при Height не больше 8 индекс HL сохраняется и снова записывается в TopRow, остальные выходы по раннему договору ScrollWindowRows
                ;   BC и альтернативные регистры по выполненным помощникам, IX восстанавливается, IY по внешнему callback перерисовки, SP обычного возврата равен входному SP+2
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IY согласно callback RepaintAndFlag и договорам выполненных помощников, списки, экраны и изменяемые операнды
                ; Note:
                ;   наведение начинается отдельно по 6913, этот вход действия расположен по EventHandler+3
                ;   единица относится к A после RepaintAndFlag, а не к флагу мыши или номеру модели
                ;   высота 8 является отступом содержимого в пикселях, не числом строк, защита границы использует полное слово RowCount
                ;   реальный PrintModelDescription пропускает только младший байт индекса, несовпадение с 16-битным ограничением оригинала сохранено
                ;   код не добавляет защиту от незавершения подсчёта, удерживаемого ввода и недопустимой геометрии, I, IFF и IM по договорам помощников и пробуждения
                ; -----------------------------------------
                ; выбор панели и возможная перерисовка до локального действия
Entry:          CALL @Station.RepaintAndFlag.Entry
                RET C                                                           ; выход, если RepaintAndFlag вернул Carry, локальное действие не выполнять

                ; проверка селектора 1 после обработки панели общим входом
                DEC A
                JR Z, @Station.HandleModelDescriptionClick.SelectionOnly        ; переход, если возвращённый селектор равен 1, завершить выбор без закрытия и прокрутки

                ; проверка строки заголовка и удаление панели при совпадении
                CALL @Station.CloseMenuOnRow.Entry
                RET Z                                                           ; выход, если строки совпали и панель уже удалена

                ; подсчёт полного числа проходов выбранного описания до настройки ограничения
                CALL @Station.CountModelDescriptionRows.Entry
                ; выбор банкового рисователя текста для принятого шага прокрутки
                LD HL, @Station.PrintModelDescription.Entry
                ; обновление существующего операнда CALL в цикле прокрутки
                LD (@ScrollState.RenderCall), HL
                ; чтение полного слова границы, записанного CountModelDescriptionRows
                LD HL, #0000
                ; обновление ограничения индекса полным числом проходов
                LD (@ScrollState.EndLimit), HL
                ; выбор восьмипиксельного отступа от верхнего края текстового окна
                LD A, @DescriptionConst.TopOffset
                ; чтение сохранённого слова начального индекса
                LD HL, #0000
                ; прокрутка с реальной печатью описания и восстановлением указателя
                CALL @Station.ScrollWindowRows.Entry
                ; сохранение всего итогового индекса в исходном операнде
                LD (@ModelDescriptionState.TopRow), HL
                RET

                ; завершение выбора без вызова закрытия и подсчёта текста
SelectionOnly:  RET

                endmodule
                endmodule
