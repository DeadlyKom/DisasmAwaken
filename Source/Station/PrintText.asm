                module Station
                module PrintText
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [управляющие коды текстового потока](../../Docs/TextStream.md)
; -----------------------------------------
; Вывод байтового текстового потока с управляющими позициями и переносом строки
; исходная запись 4, файловые смещения #5D08..#5DA5
; In:
;   HL - начало байтового потока, достигающего выхода либо удовлетворяющего ограничениям на завершение
;   BC - B разделитель для хвоста MeasureTextRun при коде 0, остальные значения BC сохраняются
;   TextWindow задаёт курсор, размер и Style, TextStreamState задаёт X для кодов 2..6 и вариант LineEndCode
; Out:
;   HL - позиция продолжения потока либо ограничитель MeasureTextRun после кода 0
;   AF - LF даёт #0A4A, код 1 даёт #0044, отказ высоты или физического Y глифа даёт #0041
;   при отказе нового Y A=(прежний Y+8) по модулю 256, Carry=1, F описан в TextStream.md
;   код 0 возвращает AF измерителя, текстовый курсор и bitmap содержат уже выполненную часть вывода
;   при временном RET в LineEndCode принятый явный CR возвращает #0044, HL после CR, Y продвинут, X=0
; Corrupt:
;   HL, AF
; Note:
;   DE, BC, альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   LF и код 1 потребляются, при отказе DrawGlyph HL возвращён к невыведенному символу
;   при отказе переноса CR уже потреблён, при автоматическом переносе HL остаётся на повторяемом символе
;   Style является целым байтом режима, ноль пропускает остаток строки, любое ненулевое значение разрешает перенос
;   новый Y рассчитывается по модулю 256, при высоте 249..255 некоторые переносы могут зациклиться
;   коды 2..6 берут X из пяти изменяемых операндов, они не читают следующий байт потока как координату
;   нулевой код передаёт управление MeasureTextRun без возврата в печать, это не обычный конец строки
;   LineEndCode по #BD4F содержит исходный JP либо временный RET, остальные два байта цели JP не меняются
;   при RET после принятого явного CR процедура возвращает #0044, автоматический перенос использует другой JP и продолжает поток
;   состояние DrawGlyph и TextWindow подготовлено, код и таблица ширин соответствуют исходному варианту
; -----------------------------------------
                ; чтение очередного управляющего кода либо кода глифа
Entry:          LD A, (HL)
                INC HL
                ; проверка LF, завершающего поток с потреблением ограничителя
                CP @TextConst.LineFeed
                RET Z                                                           ; выход, если прочитан LF, HL указывает на следующий байт

                ; проверка CR для перехода к следующей строке текстового окна
                CP @TextConst.CarriageReturn
                JR Z, @Station.PrintText.NewLine                                ; переход, если прочитан CR, выполнить байтовый шаг Y и сброс X

                ; проверка диапазона управляющих кодов 0..6 перед вызовом глифа
                CP @TextConst.FirstGlyph
                JR C, @Station.PrintText.Control                                ; переход, если код меньше 7, обработать остановку, позицию либо хвост измерения

                CALL @Station.DrawGlyph.Entry
                JP C, @Station.PrintText.Entry                                  ; переход, если глиф принят, читать следующий байт потока

                ; возврат указателя к символу, чей глиф отказал
                DEC HL
                ; проверка кода отказа 0 по физическому X
                AND A
                JR Z, @Station.RecoverTextX.Entry                               ; переход, если DrawGlyph вернул код 0, выбрать пропуск символа либо строки

                ; проверка кода 1 отказа физического Y с преобразованием статуса в A=0
                DEC A
                SCF
                RET Z                                                           ; выход, если исходный код отказа равен 1, HL остаётся на символе

                ; проверка кода 2 отказа относительной высоты с преобразованием статуса в A=0
                DEC A
                SCF
                RET Z                                                           ; выход, если исходный код отказа равен 2, HL остаётся на символе

                ; выбор политики после кода 3 отказа по ширине, режим находится в изменяемом операнде
                LD A, #00
                AND A
                JR NZ, @Station.PrintText.WrapLine                              ; переход, если режим ненулевой, перенести строку и повторить текущий символ

                ; поиск ближайшего CR либо LF с отбрасыванием остальных кодов без обработки
SkipLine:       LD A, (HL)
                INC HL
                ; проверка LF во время пропуска строки
                CP @TextConst.LineFeed
                RET Z                                                           ; выход, если найден LF, остаток потока не печатается

                ; проверка CR во время пропуска строки
                CP @TextConst.CarriageReturn
                JP NZ, @Station.PrintText.SkipLine                              ; переход, если найденный байт не CR, поиск конца строки продолжается

                ; возврат на CR для его обычной обработки в PrintText.Entry
                DEC HL
                JP @Station.PrintText.Entry

                ; чтение относительного Y для явного CR
NewLine:        LD A, (@TextWindow.CursorY)
                ; расчёт нового Y с исходным байтовым переполнением
                ADD A, @ScreenConst.PixelsPerChar
                PUSH BC
                LD C, A
                LD A, (@TextWindow.Height)
                LD B, A
                LD A, C
                ; проверка нового Y относительно высоты окна, BC затем восстанавливается
                CP B
                POP BC
                CCF
                RET C                                                           ; выход, если новый Y не меньше высоты, курсор сохранён

                ; обновление Y и сброс X только после принятия новой строки
                LD (@TextWindow.CursorY), A
                XOR A
                LD (@TextWindow.CursorX), A
                JP @Station.PrintText.Entry

                ; чтение Y для автоматического переноса без потребления отказавшего символа
WrapLine:       LD A, (@TextWindow.CursorY)
                ; расчёт нового Y автоматического переноса по модулю 256
                ADD A, @ScreenConst.PixelsPerChar
                PUSH BC
                LD C, A
                LD A, (@TextWindow.Height)
                LD B, A
                LD A, C
                ; проверка высоты при автоматическом переносе
                CP B
                POP BC
                CCF
                RET C                                                           ; выход, если новый Y не меньше высоты, HL остаётся на повторяемом символе

                ; обновление курсора перед повторной попыткой того же глифа
                LD (@TextWindow.CursorY), A
                XOR A
                LD (@TextWindow.CursorX), A
                JP @Station.PrintText.Entry

                ; распознавание кода 1, затем кодов пяти настроенных колонок
Control:        DEC A
                OR A
                RET Z                                                           ; выход, если исходный управляющий код равен 1

                DEC A
                JR NZ, @Station.PrintText.Column3                               ; переход, если исходный код не равен 2, проверить следующую колонку

                ; выбор настроенного X из операнда Column2X, следующий байт потока не потребляется
                LD A, #00
                LD (@TextWindow.CursorX), A
                JP @Station.PrintText.Entry

Column3:        DEC A
                JR NZ, @Station.PrintText.Column4                               ; переход, если исходный код не равен 3, проверить следующую колонку

                ; выбор настроенного X из операнда Column3X, следующий байт потока не потребляется
                LD A, #00
                LD (@TextWindow.CursorX), A
                JP @Station.PrintText.Entry

Column4:        DEC A
                JR NZ, @Station.PrintText.Column5                               ; переход, если исходный код не равен 4, проверить следующую колонку

                ; выбор настроенного X из операнда Column4X, следующий байт потока не потребляется
                LD A, #00
                LD (@TextWindow.CursorX), A
                JP @Station.PrintText.Entry

Column5:        DEC A
                JR NZ, @Station.PrintText.Column6                               ; переход, если исходный код не равен 5, проверить последнюю колонку

                ; выбор настроенного X из операнда Column5X, следующий байт потока не потребляется
                LD A, #00
                LD (@TextWindow.CursorX), A
                JP @Station.PrintText.Entry

Column6:        DEC A
                JR NZ, @Station.MeasureTextRun.Entry                            ; переход, если исходный код не равен 6, единственный оставшийся код 0 передаёт управление измерителю

                ; выбор настроенного X из операнда Column6X, следующий байт потока не потребляется
                LD A, #00
                LD (@TextWindow.CursorX), A
                JP @Station.PrintText.Entry

                endmodule
                endmodule
