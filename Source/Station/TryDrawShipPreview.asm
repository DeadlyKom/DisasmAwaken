                module Station
                module TryDrawShipPreview
                ; Документация [станционная цепочка, геометрия и настоящее IM2-пробуждение](../../Docs/ShipPreviewCallbacks.md)
                ; -----------------------------------------
                ; Рисование корабельного просмотра только при наличии точного указателя обработчика
                ; исходная запись 4, файловые смещения #0B1C..#0B22
                ; In:
                ;   HL сохраняемый контекст, DE заменяется точным адресом DrawShipPreview.Entry, BC сохраняемый контекст поиска
                ;   AF задаёт входной Carry только для пустого списка, другие флаги не являются параметрами
                ;   DrawListState.HeadOperand задаёт список с ограничителем старшего байта 1, действуют договоры TestDrawPointer и DrawShipPreview
                ; Out:
                ;   при отсутствии точного указателя HL и BC сохранены, DE=DrawShipPreview.Entry, A=1
                ;   F при отсутствии равен Carry последнего сравнения указателя, при пустом списке входному Carry, остальные биты нулевые
                ;   при отсутствии HL', DE', BC', AF', IX и IY сохранены
                ;   при совпадении исполнение последовательно продолжается в DrawShipPreview без дополнительного CALL
                ;   при выключенном C9 найденного рисователя HL и BC сохранены, DE=DrawShipPreview.Entry, AF=0050
                ;   при активном найденном рисователе действует его выходной договор, SP после возврата равен входному+2
                ; Corrupt:
                ;   DE, AF при отказе, остальные регистры и память только по исполненному DrawShipPreview
                ; Note:
                ;   равный индекс записи чужого указателя не является совпадением, проверяется именно адрес обработчика
                ;   условный RET при Z=1 не завершает файл, сохранён жёсткий порядок двух include
                ;   проверены все 65279 допустимых несовпадающих слов и 256 входных F пустого списка
                ; -----------------------------------------
                ; поиск точного адреса рисователя, совпадение одного индекса чужого обработчика недостаточно
Entry:          LD DE, @Station.DrawShipPreview.Entry
                CALL @Station.TestDrawPointer.Entry
                RET NZ                                                          ; выход, если точного DrawShipPreview.Entry нет в текущем списке

                ; JP @Station.DrawShipPreview.Entry, продолжение в DrawShipPreview.asm

                endmodule
                endmodule
