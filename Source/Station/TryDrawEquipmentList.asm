                module Station
                module TryDrawEquipmentList
                ; Документация [параллельные таблицы, счётчик маркера 80, физические кадры и особый EXX-выход](../../Docs/EquipmentListPanels.md)
                ; -----------------------------------------
                ; Условное рисование списка оснащения только при точном указателе в списке
                ; исходная запись 4, файловые смещения #14CC..#14D2
                ; In:
                ;   список рисования читаем до исходного ограничителя, при точном указателе DrawEquipmentList действуют его условия
                ;   входные HL и BC сохраняемый контекст проверки указателя, AF задаёт входной Carry пустого списка
                ; Out:
                ;   при отсутствии точного указателя HL и BC сохранены, DE=DrawEquipmentList.Entry, AF соответствует TestDrawPointer без новых записей
                ;   при наличии исполнение последовательно продолжается в DrawEquipmentList с его активным либо C9-контрактом
                ;   алиас с тем же индексом не считается совпадением, дополнительного CALL рисователя и нового внешнего возврата нет
                ; Corrupt:
                ;   DE, AF, при присутствии остальные изменения по DrawEquipmentList
                ; Note:
                ;   жёсткий порядок include (0) и (1) обязателен для последовательного пути после RET NZ
                ; -----------------------------------------
                ; поиск точного адреса рисователя, равный ключ чужого алиаса не подходит
Entry:          LD DE, @Station.DrawEquipmentList.Entry
                CALL @Station.TestDrawPointer.Entry
                RET NZ                                                          ; выход, если точный указатель DrawEquipmentList отсутствует

                ; JP @Station.DrawEquipmentList.Entry, продолжение в DrawEquipmentList.asm

                endmodule
