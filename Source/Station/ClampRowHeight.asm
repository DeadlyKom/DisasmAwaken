                module Station
                module ClampRowHeight
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [байтовые координаты, доступная высота и строка указателя](../../Docs/RowSelection.md)
; -----------------------------------------
; Перевод числа строк в пиксели и ограничение доступной высотой элемента
; исходная запись 4, файловые смещения #428F..#42A3
; In:
;   DE - D запрошенное число восьмипиксельных строк, E пиксельный верхний отступ
;   IX - читаемая FInterfaceItem с байтовым Height в станционном банке 0
; Out:
;   HL и BC сохранены, E сохранён, A=(ROL8(Item.Height,3)-E-5) AND #F8
;   D=min(A,(входной D*8) AND #FF), F соответствует CP доступной высоты A и байтового запроса
;   Carry=1 означает уменьшение запроса, Carry=0 означает сохранение переведённого запроса
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
; Corrupt:
;   DE, AF
; Note:
;   для штатных высот до 31 вращение Height эквивалентно умножению на восемь, у больших байтов старшие биты возвращаются в младшую тройку
;   у запроса D применяются SLA, старшие три разряда теряются, значение 32 превращается в нулевой запрос
;   вычитания E и 5 выполняются по модулю 256, недостаточная высота может обернуться большой доступной величиной
;   A всегда содержит доступную величину, даже когда возвращённый D меньше неё
;   память не меняется, минимальная допустимая геометрия проверяется не этим входом
; -----------------------------------------
                ; чтение физической высоты элемента перед вычислением доступной области
Entry:          LD A, (IX + FInterfaceItem.Height)
                ; расчёт вращения Height на три бита, у высоты более 31 это не обычный сдвиг
                RLCA
                RLCA
                RLCA
                ; расчёт доступной высоты за вычетом верхнего отступа E
                SUB E
                ; вычет нижнего отступа перед округлением доступной высоты
                SUB @RowSelectConst.BottomInset
                ; округление доступной байтовой высоты вниз к целому числу восьмипиксельных строк
                AND @RowSelectConst.CellMask
                ; расчёт байтового пиксельного запроса из числа строк тремя SLA
                SLA D
                SLA D
                SLA D
                ; проверка запроса относительно доступной высоты
                CP D
                RET NC                                                          ; выход, если доступная высота не меньше запроса, сохранить переведённый D

                ; ограничение возвращаемой высоты доступным числом пикселей
                LD D, A
                RET

                endmodule
                endmodule
