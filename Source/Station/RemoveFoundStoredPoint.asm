                module Station
                module RemoveFoundStoredPoint
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [физические пятибайтовые записи, точные диапазоны сдвигов и общие хвосты](../../Docs/StoredPointEdits.md)
; -----------------------------------------
; Освобождение первой записи по результату поиска без стирания остальных четырёх байтов
; исходная запись 4, файловые смещения #1E5A..#1E61
; In:
;   DE - адрес старшего байта SecondWord совпавшей записи A, как от Map.FindStoredMapPoint, действуют условия общего рисунка
;   действуют договоры BeginScreenUpdate, TryDrawSystemInfo, DrawMapPanel и EndScreenUpdate, две записи панелей и данные карты готовы
;   paging доступен, указатель согласован с фоном, адресные и индексные таблицы готовы, все фактические HALT пробуждаются окружением
;   стек вне экранных областей и переключаемого окна, банк станции 0 доступен
; Out:
;   DE уменьшается на три к началу записи, только её первый байт заменён FF, остальные четыре байта сохранены
;   далее выполнен хвостовой переход в RefreshStoredMapPanels, конечные результаты соответствуют общему рисунку
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, bitmap и рабочие данные общего рисунка, первый байт удалённой записи A
; Note:
;   при прямом входе Pending не устанавливается, обычный ToggleStoredMapPoint уже поставил его до поиска
; -----------------------------------------
                ; расчёт начала найденной записи из адреса старшего байта SecondWord
Entry:          DEC DE
                DEC DE
                DEC DE
                ; освобождение только первого байта записи, остальные поля остаются прежними
                LD A, @StoredPointConst.Empty
                LD (DE), A
                JR @Station.RefreshStoredMapPanels.Entry

                endmodule
                endmodule
