                module Station
                module ConfigureMouseButtons
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [настройка кнопок и аппаратные счётчики](../../Docs/MouseInput.md)
; -----------------------------------------
; Одноразовый выбор соответствия двух кнопок и замена настроечного JR двумя NOP
; исходная запись 4, файловые смещения #083A..#0852
; In:
;   IX - база MouseInput.State, на стеке FMousePollFrame.SavedIX и ReturnAddress
;   байты PreviousX,PreviousY содержат прежние показания, PointerXY содержит исходные пиксельные координаты
;   AF - A инвертированный байт первого чтения кнопок, семь флагов уже обнулены
; Out:
;   HL - итоговые пиксельные X в L и Y в H, DE - прежние аппаратные счётчики X в E и Y в D, BC=#FFDF
;   AF - рабочий результат последней ветви Y, единого флага наличия движения нет
;   StationState.PointerXY и PreviousX,PreviousY обновлены, ненулевые разности устанавливают соответствующий байт направления в 1
;   IX восстановлен из FMousePollFrame, IY, альтернативные регистры, I и IFF сохраняются, SP возвращается за адрес вызова
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   A AND 3 равный нулю передаёт управление непосредственно ReadMouseMotion
;   код 1 сохраняет исходные смещения 0,5, коды 2 и 3 записывают 5,0
;   FinishSetup пишет исходное слово 0 поверх JR, снимает SavedIX и продолжает PollMouse для повторного чтения
;   разность X равна signed8(newX-oldX), разность Y равна signed8(-(newY-oldY)), каждая умножается на два
;   при отрицательной разности применяется max(0,old+2*delta), при положительной min(limit,old+2*delta)
;   limit равен 254 для X и 191 для Y, нулевая разность не нормализует исходную координату
;   отрицательная ветвь не ограничивает сверху, при исходном Y>191 результат может остаться вне экрана
;   байты направлений не очищаются этим продолжением, полный PollMouse очищает семь флагов до чтения портов
;   чтение Y выполняется даже при нулевой разности X, старые оба счётчика загружаются до первого чтения
;   модель задаёт байты трёх портов, реальное устройство и вызов из ISR не проверены
; -----------------------------------------
                ; проверка двух младших инвертированных разрядов первой выборки кнопок
Entry:          AND #03
                JR Z, @Station.ReadMouseMotion.Entry                            ; переход, если обе младшие кнопки отпущены, читать только движение без завершения настройки

                ; проверка одиночной первой кнопки для сохранения исходного соответствия действий
                CP #01
                JR Z, @Station.ConfigureMouseButtons.FinishSetup                ; переход, если код кнопок равен 1, оставить исходное соответствие двух действий

                ; выбор противоположного соответствия при коде 2 либо 3
                XOR A
                LD (@MousePollState.SecondOffset), A
                LD A, #05
                LD (@MousePollState.FirstOffset), A
                ; выбор двух исходных NOP для одноразового отключения настроечного перехода
FinishSetup:    LD HL, #0000
                ; замена JR ConfigureMouseButtons двумя NOP, последующий опрос попадёт в декодирование кнопок
                LD (@MousePollState.SetupJump), HL
                ; снятие сохранённого IX перед повторным входом PollMouse
                POP IX
                ; JP @Station.PollMouse.Entry, продолжение в PollMouse.asm

                endmodule
                endmodule
