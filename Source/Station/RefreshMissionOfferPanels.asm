                module Station
                module RefreshMissionOfferPanels
                ; Документация [порядок генерации и рисунка, селектор 1, строка закрытия и периодическая цель](../../Docs/MissionPanelActions.md)
                ; -----------------------------------------
                ; Генерация нового предложения и последовательное обновление цели, условий миссии и статуса
                ; исходная запись 4, файловые смещения #4A3D..#4A4E
                ; In:
                ;   HL, DE, BC и AF исходный контекст генератора, числового селектора собственной обёртки нет
                ;   выполнен договор GenerateMissionOffer, текущий ключ и RNG подготовлены, чтение ROM достигает ненулевого тоннажа
                ;   станционный банк 0 и KARTA 1 доступны, для возможного завершения DrawItem32 также LANG 6
                ;   действуют договоры BeginScreenUpdate, DrawItem31, DrawItem32, DrawItem00 и EndScreenUpdate
                ;   рисователи имеют подготовленные индексы, видимую геометрию, шрифт и таблицы, IRQ сохраняет контекст в HALT
                ; Out:
                ;   сначала выполнен GenerateMissionOffer, перед рисованием подготовлены новый ключ, требуемый тоннаж, награда и MessageIndex=0
                ;   затем строго последовательно исполнены BeginScreenUpdate, DrawItem31, DrawItem32 и DrawItem00
                ;   хвостовой JP EndScreenUpdate показывает базовый экран, возобновляет указатель, возвращает A=10 с F последнего DrawItem00
                ;   HL, DE, BC, альтернативные пары и рабочие данные соответствуют окончательному DrawItem00 и предшествующим рисователям
                ;   DrawItem32 может завершить активную миссию по собственному договору, включая награду, LANG и дополнительную генерацию
                ;   после нормального возврата страница 10 и UpdateBlocked=0, IY, I, IFF и IM сохранены при договорах IRQ и помощников
                ;   IX сохранён без пути LANG, при его выполнении соответствует интерпретатору, SP после общего возврата входному+2
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX по возможному LANG, предложение, RNG, экран, список и рабочие данные рисователей
                ; Note:
                ;   собственного сброса ActiveCode нет, обновление предложения нельзя автоматически объявлять отменой активной миссии
                ;   чтение ROM генератором используется как данные, ROM исследовательской модели не объявляется ROM Unreal
                ;   последний JP не создаёт дополнительную стековую рамку, возврат EndScreenUpdate использует исходный адрес вызывающего
                ;   модель связки проверяет 128 случаев без завершения миссии, отдельный путь завершения описан и проверен в MissionCompletion
                ; -----------------------------------------
                ; создание нового предложения исходным генератором, собственный ActiveCode здесь не сбрасывается
Entry:          CALL @Station.GenerateMissionOffer.Entry
                ; создание снимка перед последовательным обновлением панелей
                CALL @Station.BeginScreenUpdate.Entry
                ; обновление названия предлагаемого пункта
                CALL @Station.DrawItem31.Entry
                ; обновление условий миссии с её собственным возможным завершением
                CALL @Station.DrawItem32.Entry
                ; обновление статуса после возможных изменений награды и груза
                CALL @Station.DrawItem00.Entry
                ; показ результата и возврат напрямую вызывающему
                JP @Station.EndScreenUpdate.Entry

                endmodule
                endmodule
