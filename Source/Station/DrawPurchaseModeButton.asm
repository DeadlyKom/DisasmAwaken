                module Station
                module DrawPurchaseModeButton
                ; Документация [исходные кнопки продажи и покупки, FF собственного типа, банк 4 и общий вход](../../Docs/ModelTradeMode.md)
                ; -----------------------------------------
                ; Центрируемая кнопка покупки с изменяемым индексом FInterfaceItem 29
                ; исходная запись 4, файловые смещения #1D2E..#1D33
                ; In:
                ;   активный Entry содержит LD HL с подготовленным DrawItemState.Index29, либо временный C9
                ;   при активном коде запись FInterfaceItem и шрифт удовлетворяют DrawCenteredItem, индекс штатно 29
                ; Out:
                ;   при активном коде HL содержит загруженный индекс, DE и BC сохранены, AF содержит A=C3 и F последнего текста DrawCenteredItem
                ;   H', DE', BC', IX, IY, I, IFF и IM сохранены, L' и AF' рабочие по центрируемому рисователю
                ;   зарегистрированы рамка и bitmap кнопки покупки, окно и курсор согласно DrawCenteredItem, отдельного кадра CALL нет
                ;   при временном C9 сохранены все регистры, флаги и память, SP после обычного RET входному+2
                ; Corrupt:
                ;   HL, AF, L', AF', bitmap, окно, курсор и карта владельцев при активном коде
                ; Note:
                ;   исходная подпись взята из CenterTextBase E4AA, её нельзя отождествлять с CaptionTextBase E399
                ;   рисователь не выбирает режим, отдельный вход действия кнопки меняет режим и подготовку просмотра
                ; -----------------------------------------
                ; чтение изменяемого индекса кнопки Покупка перед хвостовым рисованием
Entry:          LD HL, #0000
                JP @Station.DrawCenteredItem.Entry

                endmodule
