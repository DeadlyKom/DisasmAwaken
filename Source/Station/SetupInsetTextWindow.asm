                module Station
                module SetupInsetTextWindow
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [TextWindow.md](../../Docs/TextWindow.md)
; -----------------------------------------
; Настройка внутреннего текстового окна с пиксельными отступами и начальным курсором X=1
; исходная запись 4, файловые смещения #6233..#6286
; In:
;   DE - D высота и E ширина в знакоместах, BC - B знаковая строка и C знаковая колонка начала окна
; Out:
;   HL, DE и BC сохранены, CursorX=1, CursorY=0
;   начала X и Y формируются как в SetupTextWindow, затем к каждому младшему байту прибавляется 3 без переноса в старший
;   Width=(T(E)-4) по модулю 256, Height=(T(D)-11) по модулю 256, T определена в SetupTextWindow
;   AF - A равен записанной Height, F полностью соответствует восьмибитному вычитанию 11 из T(D)
; Corrupt:
;   AF
; Note:
;   нет проверки достаточного размера, малые размеры могут дать байтовое переполнение и не исправляются
;   при обычных координатах младшая добавка 3 задаёт внутренний отступ, для произвольных байтов сохраняется исходная формула без исправления переноса
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   меняются операнды текстового обработчика, Style сохраняется, пиксели и глифы не выводятся
; -----------------------------------------
Entry:          PUSH HL
                ; начальная позиция внутреннего окна, CursorX равен единице и CursorY равен нулю
                LD HL, #0001
                LD (@TextWindow.CursorX), HL
                ; подготовка нулевого знакового расширения координаты X
                DEC L
                ; проверка исходного знака горизонтальной координаты знакомест
                LD A, C
                AND A
                JP P, @Station.SetupInsetTextWindow.ScaleX                      ; переход, если X неотрицателен, модуль уже находится в A

                ; получение модуля отрицательной горизонтальной координаты
                NEG
                ; расчёт пиксельного начала X по исходному преобразованию T
ScaleX:         RLCA
                RLCA
                RLA
                ; проверка исходного знака X для восстановления знакового начала
                BIT 7, C
                JP Z, @Station.SetupInsetTextWindow.InsetX                      ; переход, если X неотрицателен, старший байт начала остаётся нулевым

                ; восстановление отрицательного X и его знакового расширения
                NEG
                DEC L
                ; расчёт младшего байта начала X с внутренним отступом, перенос в старший байт не добавляется
InsetX:         ADD A, @TextWindowConst.OriginInset
                LD (@TextWindow.OriginXLow), A
                LD A, L
                LD (@TextWindow.OriginXHigh), A
                ; подготовка нулевого знакового расширения координаты Y
                LD L, #00
                ; проверка исходного знака вертикальной координаты знакомест
                LD A, B
                AND A
                JP P, @Station.SetupInsetTextWindow.ScaleY                      ; переход, если Y неотрицателен, модуль уже находится в A

                ; получение модуля отрицательной вертикальной координаты
                NEG
                ; расчёт пиксельного начала Y по исходному преобразованию T
ScaleY:         RLCA
                RLCA
                RLA
                ; проверка исходного знака Y для восстановления знакового начала
                BIT 7, B
                JP Z, @Station.SetupInsetTextWindow.InsetY                      ; переход, если Y неотрицателен, старший байт начала остаётся нулевым

                ; восстановление отрицательного Y и его знакового расширения
                NEG
                DEC L
                ; расчёт младшего байта начала Y с внутренним отступом без исправления переноса
InsetY:         ADD A, @TextWindowConst.OriginInset
                LD (@TextWindow.OriginYLow), A
                LD A, L
                LD (@TextWindow.OriginYHigh), A
                ; расчёт пиксельной ширины по T с последующим уменьшением на четыре
                LD A, E
                RLCA
                RLCA
                RLA
                SUB @TextWindowConst.WidthInset
                LD (@TextWindow.Width), A
                ; расчёт пиксельной высоты по T с последующим уменьшением на одиннадцать
                LD A, D
                RLCA
                RLCA
                RLA
                SUB @TextWindowConst.HeightInset
                LD (@TextWindow.Height), A
                POP HL
                RET

                endmodule
                endmodule
