                module Station
                module RefreshStoredMapPanels
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [физические пятибайтовые записи, точные диапазоны сдвигов и общие хвосты](../../Docs/StoredPointEdits.md)
; -----------------------------------------
; Общий рисунок сведений и основной карты после изменения сохранённых точек
; исходная запись 4, файловые смещения #1E47..#1E53
; In:
;   действуют договоры BeginScreenUpdate, TryDrawSystemInfo, DrawMapPanel и EndScreenUpdate, две записи панелей и данные карты готовы
;   paging доступен, указатель согласован с фоном, адресные и индексные таблицы готовы, все фактические HALT пробуждаются окружением
;   стек вне экранных областей и переключаемого окна, банк станции 0 доступен
; Out:
;   старый экран скопирован в банк 7, условно нарисованы сведения, затем безусловно рамка и содержимое основной карты
;   TextWindow в конце относится к основной карте, прежнее окно и стиль не восстанавливаются
;   при обычном успешном рисунке A=10, F=44, ScreenRequest=0, ClipRequest=0, SectorRequest=1, CurrentPage=10
;   HL, DE, BC и альтернативные пары соответствуют DrawMapPanel, AF' рабочий от указателя, IX рабочий по договору карты
;   IY, I и IFF сохраняются инструкциями при договоре HALT, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, bitmap и рабочие данные общего рисунка
; Note:
;   этот общий хвост не ставит Pending и не меняет сохранённые записи сам по себе
;   у TryDrawSystemInfo нет сохранения TextWindow, следом DrawMapPanel заново задаёт собственное окно
;   на обычном пути достигнуты HALT заголовка карты и C000, присутствующая панель сведений добавляет свой HALT
;   модель общих хвостов исполняет обе панели, сравнивает снимок, запросы и состояние, независимый oracle всего bitmap не заявлен
; -----------------------------------------
                ; снимок прежнего экрана перед рисунком зависимых сведений и карты
Entry:          CALL @Station.BeginScreenUpdate.Entry
                ; условный рисунок информационной панели без отдельного сохранения её текстового окна
                CALL @Station.TryDrawSystemInfo.Entry
                ; рисунок основной карты заново устанавливает её окно и все три запроса таблиц
                CALL @Station.DrawMapPanel.Entry
                ; возобновление указателя и показ базового экрана
                CALL @Station.EndScreenUpdate.Entry
                RET

                endmodule
                endmodule
