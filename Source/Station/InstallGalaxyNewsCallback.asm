                module Station
                module InstallGalaxyNewsCallback
                ; Документация [исходная цель открытия, геометрический путь и отложенный вызов](../../Docs/DeferredActionAdapters.md)
                ; -----------------------------------------
                ; Установка отложенного открытия через OpenGalaxyNewsPanel
                ; исходная запись 4, файловые смещения #1D50..#1D59
                ; In:
                ;   HL входа не является параметром, DE индекс выбранного элемента, BC сохраняемый контекст, AF селектор общего действия
                ;   AF - A=0 выбирает попытку интерактивной геометрии, любой ненулевой A приводит к ActivateItem
                ;   для штатного пути выбранный индекс уже присутствует в списке, иначе действует исходный запасной путь MoveItemToTail с HL
                ;   выполняются предусловия TrackItemGeometry, ToggleItemBounds либо ActivateItem на выбранной ветви
                ;   код банкового окна станции доступен для записи, FlagsCache подготовлен вызывающим кодом
                ;   выбранный DE-индекс присутствует в списке, устанавливаемая цель Station.OpenGalaxyNewsPanel.Entry доступна в своём банковом контексте при последующем вызове
                ; Out:
                ;   NextCallback всегда получает Station.OpenGalaxyNewsPanel.Entry до проверки селектора, сама эта цель здесь не исполняется
                ;   при A=0 и выполненной геометрии HL=Station.OpenGalaxyNewsPanel.Entry, DE, BC и IX сохранены, AF=#0045, результат соответствует TrackItemGeometry
                ;   при A=0 и отсутствии интерактивного действия результат соответствует ToggleItemBounds, HL=DE-индекс,IX=адрес записи,Carry=1
                ;   при ненулевом A результат соответствует ActivateItem, HL=Station.OpenGalaxyNewsPanel.Entry,DE и BC сохранены
                ;   IY сохраняется, HL' и AF' рабочие только на пути перерисовок ActivateItem
                ;   после CALL общего обработчика выполняется собственный RET, SP обычного возврата входному+2
                ; Corrupt:
                ;   HL, AF, HL', AF', IX согласно выбранной ветви
                ; Note:
                ;   бит 7 ненулевого A обходит пробу TrackItemGeometry сразу, остальные ненулевые значения проходят ту же активацию через FinishItemAction
                ;   OR A перед условным CALL обеспечивает Z=1 для A=0, поэтому интерактивный вход использует удерживаемый код 1
                ;   входной Carry не задаёт результат, нулевой A всегда заканчивает с Carry=1 через один из двух геометрических путей
                ;   новый callback не вызывается этой обёрткой, при выполненной геометрии сохраняется только NextCallback для возможного последующего использования
                ;   сохранённая геометрия, указатель и EventEnabled меняются только выбранными подпрограммами
                ;   H', DE', BC', I и IFF сохраняются собственным кодом, поведение ISR ограничено договорами HALT, SP восстанавливается
                ;   контракт составлен статическим разбором 11 исходных байтов и договоров всех трёх проверенных хвостов
                ;   Entry сначала делает исходный JP BindCallback, отдельный внутренний вход принимает тот же контекст
                ;   новый callback не подменяет немедленную ветвь A=0, она по-прежнему меняет геометрию и возвращает Carry
                ; -----------------------------------------
                ; переход к установщику открытия через OpenGalaxyNewsPanel без нового CPU-кадра
Entry:          JP @Station.InstallGalaxyNewsCallback.BindCallback

                ; выбор отложенной цели OpenGalaxyNewsPanel вместо входного HL
BindCallback:   LD HL, @Station.OpenGalaxyNewsPanel.Entry
                ; сохранение цели и общая развилка геометрии либо активации, открытие здесь не исполняется
                CALL @Station.ActivateInterfaceCallback.Entry
                RET

                endmodule
                endmodule
