                module Station
                module RefreshVariantPanel
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [установка callback, тактовая маска, геометрия указателя и два банковых контекста](../../Docs/PeriodicVariants.md)
; -----------------------------------------
; Отложенный перенос панели в конец списка и перерисовка через теневой экран
; исходная запись 4, файловые смещения #1B69..#1B81
; In:
;   ActiveItemState.Active задаёт наличие активного элемента, VariantPanelState.RefreshPending является общим кодом отложенного обновления
;   при отсутствии активного элемента обработчик панели уже присутствует в DrawListState, его индекс читается из VariantPanelState.ItemIndex
;   действуют договоры MoveItemToTail, BeginScreenUpdate, TryDrawVariantPanel и EndScreenUpdate, paging доступен
; Out:
;   при ненулевом Active обновления нет, A=Active, F логического OR Active, остальные основные и альтернативные регистры сохранены, RefreshPending не сброшен
;   иначе RefreshPending=0, обработчик панели перенесён в конец списка с исходным сдвигом 128 байтов
;   прежний базовый экран скопирован в банк 7, панель перерисована в базовом экране, конечный EndScreenUpdate показывает банк 5 и возобновляет указатель
;   при завершённой перерисовке CurrentPage=10, A=10, F сохранён от конца DrawVariantPanel, HL, DE, BC и IX соответствуют его результату
;   HL', DE', BC', IY, I и IFF сохраняются инструкциями при договорах вложенных HALT и указателя, AF' рабочий, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF, AF', IX, список, оба экрана, состояние указателя, callback и ресурсы панели на рисующей ветви
; Note:
;   проверка Active относится только к этой отложенной ветви, обычная анимация при нулевом RefreshPending не проверяет Active
;   если обработчика нет в списке, MoveItemToTail использует входной HL как нового кандидата, такой случай не входит в договор этого входа
;   RefreshPending сброшен до перемещения и рисования, отката при дальнейшей проблеме нет
; -----------------------------------------
                ; проверка активного элемента перед отложенной перерисовкой панели
Entry:          LD A, (@ActiveItemState.Active)
                OR A
                RET NZ                                                          ; выход, если активный элемент ещё не закрыт, запрос обновления сохранить

                ; сброс запроса перед переносом и перерисовкой панели
                XOR A
                LD (@VariantPanelState.RefreshPending), A
                ; чтение индекса панели для переноса её существующей обёртки в конец списка
                LD DE, (@VariantPanelState.ItemIndex)
                CALL @Station.MoveItemToTail.Entry
                ; сохранение прежнего экрана в банке 7 и начало обновления базового экрана
                CALL @Station.BeginScreenUpdate.Entry
                ; рисование только при наличии обработчика панели в текущем списке
                CALL @Station.TryDrawVariantPanel.Entry
                ; передача в общий завершающий показ базового экрана с исходным адресом возврата
                JP @Station.EndScreenUpdate.Entry

                endmodule
                endmodule
