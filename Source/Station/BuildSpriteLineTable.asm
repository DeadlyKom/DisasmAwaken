                module Station
                module BuildSpriteLineTable
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [формула трёх страниц, выход за экран и оба комплекта AF](../../Docs/SpriteLineTable.md)
                ; -----------------------------------------
                ; Построение 256 адресов строк и 256 байтовых колонок просмотра без экранного отсечения
                ; исходная запись 4, файловые смещения #05CE..#060F
                ; In:
                ;   DE - D байтовое начало Y, E байтовое начало X, исходные таблицы 8200, 8300 и 8400 соответствуют адресации ULA
                ;   три страницы PreviewLineTable доступны для записи в текущем банке, CPU-стек не пересекает их
                ; Out:
                ;   HL - CB00, DE - адрес строки y0+256 с нулевой колонкой по расширенной адресации, y0=(входной D+16) AND FF
                ;   BC - B=0, C сохранён, AF - A=32+(((входной E+8) AND FF) SHR 3), F=42
                ;   HL', DE', BC' сохранены
                ;   AF' - A' равен y0 AND 7 при ненулевом остатке, иначе нулю при y0 кратном 64, иначе старшему байту выходного DE
                ;   F'=88 OR (1, если y0 кратен 64, иначе 0), IX, IY, I, IFF и IM сохранены
                ;   C900 и CA00 содержат старшие и младшие байты 256 последовательных строк от y0, младшие адреса не включают начальную колонку
                ;   CB00+i содержит (((входной E+8) AND FF) SHR 3)+(i SHR 3), i=0..255, SP обычного возврата равен входному SP+2
                ; Corrupt:
                ;   HL, DE, BC, AF, AF'
                ; Note:
                ;   прибавления 8 к X и 16 к Y байтовые, дальнейший обход 256 строк не оборачивает Y в границах 0..255
                ;   продолжение после строки 191 даёт адреса вне bitmap, после 255 продолжается через 6000, отсечения здесь нет
                ;   таблица колонок также не ограничивается 31, её значения могут достигать 62
                ;   все 768 байтов выходных таблиц перезаписываются, иная память, порт страниц и CPU-стек не записываются
                ;   флаги альтернативного AF соответствуют последним INC H перед EX AF, AF', Carry унаследован от продвижения строки
                ; -----------------------------------------
                ; -----------------------------------------
                ; Начало строк и отделение колонки
                ; -----------------------------------------
                ; расчёт байтового начала X с внутренним отступом 8 пикселей
Entry:          LD A, E
                ADD A, @SpriteLineConst.XInset
                LD E, A
                ; расчёт байтового начала Y с внутренним отступом 16 пикселей
                LD A, D
                ADD A, @SpriteLineConst.YInset
                LD L, A
                LD H, @StationScreenPage.RowHigh
                LD D, (HL)
                INC H
                LD A, (HL)
                INC H
                ; расчёт младшего адреса из таблицы строк и байтовой колонки
                LD L, E
                ADD A, (HL)
                LD E, A
                AND @ScreenConst.ColumnMask
                ; сохранение начальной байтовой колонки в альтернативном AF
                EX AF, AF'
                LD A, E
                ; выделение только строковых разрядов младшего адреса
                AND @SpriteLineConst.RowLowMask
                LD E, A
                LD HL, @PreviewLineTable.RowHigh
                ; -----------------------------------------
                ; Две таблицы для 256 строк
                ; -----------------------------------------
                ; сохранение старшего и младшего адресов одной строки в разных страницах
StoreRow:       LD (HL), D
                INC H
                LD (HL), E
                DEC H
                ; расчёт следующего пиксельного адреса увеличением старшего байта
                INC D
                LD A, D
                ; проверка перехода через восьмую пиксельную строку знакоместа
                AND @ScreenConst.PixelOffsetMask
                JP NZ, @Station.BuildSpriteLineTable.NextRow                    ; переход, если строка внутри восьмёрки ещё не закончилась

                ; расчёт следующего строкового блока в младшем адресе
                LD A, E
                ADD A, @ScreenConst.ByteColumns
                LD E, A
                JR C, @Station.BuildSpriteLineTable.NextRow                     ; переход, если младший адрес переполнился, сохранить новый старший адрес

                LD A, D
                ; возврат старшего адреса к началу восьмистрочного блока без оборачивания всей области
                SUB @ScreenConst.PixelsPerChar
                LD D, A
                ; проверка завершения всех 256 записей по оборачиванию L
NextRow:        INC L
                JR NZ, @Station.BuildSpriteLineTable.StoreRow                   ; переход, если записаны ещё не все 256 адресов строк

                ; выбор страницы колонок, два INC H также определяют будущие F'
                INC H
                INC H
                EX AF, AF'
                ; -----------------------------------------
                ; Таблица 256 байтовых колонок
                ; -----------------------------------------
                ; заполнение одной восьмёрки одинаковой байтовой колонкой
ColumnGroup:    LD B, @ScreenConst.PixelsPerChar
StoreColumn:    LD (HL), A
                INC L
                DJNZ @Station.BuildSpriteLineTable.StoreColumn

                ; расчёт следующей байтовой колонки после восьми одинаковых значений
                INC A
                ; проверка завершения страницы после группы из восьми значений
                INC L
                DEC L
                JR NZ, @Station.BuildSpriteLineTable.ColumnGroup                ; переход, если таблица 256 колонок ещё не заполнена

                RET

                ; -----------------------------------------
                endmodule
                endmodule
