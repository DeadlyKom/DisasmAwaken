                module Station
                module RemoveOtherPopups
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [исключение выбранного элемента и позиция контекстного меню](../../Docs/PopupItems.md)
; -----------------------------------------
; Удаление обработчиков группы #20 с сохранением исключённого индекса и перезапуском поиска
; исходная запись 4, файловые смещения #3E1F..#3E4D
; In:
;   DrawListState.HeadOperand содержит список указателей с ограничителем старшего байта 1
;   PopupState.SkippedIndex содержит исключаемый индекс, штатный Dispatcher записывает выбранный индекс либо #FFF0
;   обычный договор завершения ограничен списком не более 64 указателей и допустимыми читаемыми индексами остальных записей
;   в окне #C000 выбран станционный банк 0 с таблицей FInterfaceItem
;   выполняются договоры GetItemFlags и DropItemDraw, доступно 128 байтов чтения после удаляемого указателя
;   AF - входной A и Carry влияют только на результат исходно пустого списка, BC и DE рабочие
; Out:
;   HL - адрес старшего байта итогового ограничителя, B=0
;   при исходно пустом списке C, DE и A сохранены, F=#42 OR входной Carry
;   иначе C - младший байт последнего прочитанного обработчика плюс два, DE его индекс
;   A - последняя проверенная группа либо ноль после удаления, F=#42 OR последний Carry сравнения, Z всегда установлен
;   все найденные индексы с Flags AND #E0 равным #20 удалены кроме SkippedIndex
;   EventEnabled обнуляется при любом выполненном удалении, без удалений прежнее значение сохраняется
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается на завершающемся пути
;   код обёртки не исполняется, индекс читается из Handler+1 даже при первом байте RET
;   после каждого DropItemDraw поиск снова начинается от головы списка через JP без увеличения глубины CPU-стека
;   исключённый индекс не передаётся GetItemFlags, его группа для проверки принудительно считается нулевой
;   начальное #FFF0 является изменяемым операндом SkippedIndex, а не постоянным специальным индексом всех вызовов
;   в исходном файле к группе #20 относятся элементы 10, 40, 43, 44, их игровые роли по отдельности продолжают разбираться
;   физический сдвиг равен 128 байтам, на искусственном списке из 65 записей может возникать повтор состояния и бесконечный цикл
;   удаление не рисует фон и не закрывает ActiveItemState.Callback, оно только меняет список и запрос перестроения
; -----------------------------------------
                ; выбор головы списка для первого прохода и для каждого повторного поиска после удаления
Entry:          LD HL, (@DrawListState.HeadOperand)
                ; проверка старшего байта очередного указателя на ограничитель 1
NextEntry:      INC HL
                LD B, (HL)
                DEC B
                RET Z                                                           ; выход, если старший байт равен 1, больше нет проверяемых обработчиков

                ; восстановление старшего байта указателя перед чтением изменяемого индекса
                INC B
                DEC HL
                LD C, (HL)
                ; чтение двухбайтового индекса из Handler+1 без исполнения самой обёртки
                INC BC
                LD A, (BC)
                INC BC
                LD E, A
                LD A, (BC)
                LD D, A
                ; сохранение адреса записи списка на время сравнения индекса и чтения Flags
                PUSH HL
                ; чтение изменяемого SkippedIndex, Dispatcher записывает выбранный индекс вместо исходного #FFF0
                LD HL, @PopupConst.NoSelection
                ; очистка Carry перед точным сравнением двух шестнадцатибитных индексов
                XOR A
                ; расчёт разности SkippedIndex и индекса текущего обработчика
                SBC HL, DE
                JR Z, @Station.RemoveOtherPopups.CheckGroup                     ; переход, если текущий индекс исключён, проверить принудительную нулевую группу без чтения Flags

                ; выбор поля Flags по текущему индексу через общий адресный помощник
                LD L, E
                LD H, D
                CALL @Station.GetItemFlags.Entry
                LD A, (HL)
                ; выделение трёхбитового поля группы из Flags
                AND @InterfaceFlags.GroupMask
                ; проверка точного кода группы #20, другие группы сохраняются
CheckGroup:     CP @PopupConst.GroupCode
                ; возврат адреса записи и переход к следующему указателю
                POP HL
                INC HL
                INC HL
                JP NZ, @Station.RemoveOtherPopups.NextEntry                     ; переход, если группа не равна #20, продолжить просмотр без удаления

                ; удаление найденного индекса фиксированным сдвигом с обнулением EventEnabled
                CALL #C873
                ; перезапуск поиска от головы, прежние адреса указателей после сдвига уже не используются
                JP @Station.RemoveOtherPopups.Entry

                endmodule
                endmodule
