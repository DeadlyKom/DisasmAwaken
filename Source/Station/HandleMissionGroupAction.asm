                module Station
                module HandleMissionGroupAction
                ; Документация [порядок генерации и рисунка, селектор 1, строка закрытия и периодическая цель](../../Docs/MissionPanelActions.md)
                ; -----------------------------------------
                ; Общее действие панели миссии и условное закрытие трёх связанных панелей
                ; исходная запись 4, файловые смещения #4A58..#4A81
                ; In:
                ;   HL запасной рисователь текущей панели, DE её индекс, BC контекст, AF полный селектор, IX FInterfaceItem
                ;   действуют договоры RepaintAndTrack.KeepSelector и CloseMenuOnRow, станционный банк выбран
                ;   DrawItemState.Index31, Index32 и Index33 доступны, список и физические хвосты допускают удаления по DropItemDraw
                ; Out:
                ;   при Carry общего обработчика возвращён его результат без последующего закрытия
                ;   при селекторе 1 после разрешённого общего пути A=0 и F от DEC, нет собственной записи callback и удаления группы
                ;   при селекторе не 1 исполняется CloseMenuOnRow, если его Z=0 возвращён его контекст без изменения PeriodicCall
                ;   при Z=1 текущая панель уже удалена, затем HL=EmptyCallback и PeriodicCall обновлён этим адресом
                ;   последовательно удаляются первые совпадения Index31, Index32 и Index33, последний вызов является хвостовым JP
                ;   на закрытии HL=EmptyCallback, DE последний Index33, BC сохранён от CloseMenuOnRow, AF по последнему DropItemDraw
                ;   альтернативные и индексные пары соответствуют общему префиксу и его callback, собственная ветвь закрытия их сохраняет
                ;   I, IFF и IM сохранены при договорах помощников, SP после RET либо хвостового удаления входному+2
                ; Corrupt:
                ;   HL, DE, AF на закрытии, прочие пары только по общему префиксу, PeriodicCall, список и EventEnabled
                ; Note:
                ;   селектор 1 этой процедуры не запускает миссионный сценарий, назначение отдельного действия принятия разобрано в MissionActions
                ;   если текущая панель уже имела один из трёх индексов, последующее повторное удаление может ничего не найти
                ;   поиск и сдвиг каждого совпадения сохраняют исходные 128 физических байтов, а не логическую длину списка
                ;   периодическая цель отключается только после разрешённого закрытия, несовпадение строк и селектор 1 её самостоятельно не меняют
                ; -----------------------------------------
                ; выполнение общего действия с сохранением полного селектора
Entry:          CALL @Station.RepaintAndTrack.KeepSelector
                RET C                                                           ; выход, если общий обработчик вернул Carry, не закрывать группу

                ; проверка селектора 1, не выполняющего собственного действия этой панели
                DEC A
                JP Z, @Station.HandleMissionGroupAction.ReturnUnchanged         ; переход, если селектор равен 1, вернуть результат DEC без закрытия

                ; проверка закрытия по совпадению символьных строк указателя и окна
                CALL @Station.CloseMenuOnRow.Entry
                JP NZ, @Station.HandleMissionGroupAction.ReturnUnchanged        ; переход, если строки различаются, сохранить результат CloseMenuOnRow

                ; выбор пустой периодической цели только после разрешённого закрытия
                LD HL, @Station.EmptyCallback.Entry
                ; обновление PeriodicCall адресом EmptyCallback
                LD (@MenuCommandState.PeriodicCall), HL
                ; чтение индекса панели названия цели
                LD DE, (@DrawItemState.Index31)
                ; удаление первого совпадения панели названия
                CALL @Station.DropItemDraw.Entry
                ; чтение индекса панели условий
                LD DE, (@DrawItemState.Index32)
                ; удаление первого совпадения панели условий
                CALL @Station.DropItemDraw.Entry
                ; чтение индекса панели действия миссии
                LD DE, (@DrawItemState.Index33)
                ; удаление последней панели с исходным возвратом вызывающего
                JP @Station.DropItemDraw.Entry

ReturnUnchanged:RET

                endmodule
                endmodule
