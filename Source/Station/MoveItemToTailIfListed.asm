                module Station
                module MoveItemToTailIfListed
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [два различных ключа поиска, сохранённые аргументы и физический хвост списка](../../Docs/ItemMoveGuard.md)
; -----------------------------------------
; Проверка присутствия DrawHandler в списке перед переносом элемента по его индексу
; исходная запись 4, файловые смещения #5E27..#5E37
; In:
;   HL - кандидат новой обёртки для возможного добавления помощником MoveItemToTail, DE - индекс FInterfaceItem
;   поле DrawHandler записи читаемо, DrawListState.HeadOperand задаёт список до указателя со старшим байтом 1
;   если DrawHandler присутствует, действуют договоры MoveItemToTail, включая доступный хвост 128 байтов и место для записи с ограничителем
;   стек вмещает FListedItemMoveFrame и вложенные кадры, банк станции 0 доступен
; Out:
;   при отсутствии полного указателя DrawHandler HL, DE и BC сохранены, список не меняется, AF=0100 либо 0101
;   у такого выхода Carry относится к последнему сравнению указателя, при пустом списке Carry=0 после GetItemField
;   при присутствии указателя исходные HL и DE восстановлены, затем последовательно выполняется MoveItemToTail с теми же аргументами
;   HL, AF и физические изменения списка на выполняющей ветви соответствуют MoveItemToTail, DE и BC сохранены
;   все альтернативные и индексные регистры, I и IFF сохраняются инструкциями и помощниками, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, AF, список и его физический хвост только на ветви присутствующего DrawHandler
; Note:
;   первый поиск сравнивает указатели, второй читает индекс Handler+1, совпадение этих двух критериев требует согласованных данных
;   если указатель есть, но искомого индекса нет, помощник всё равно добавляет входной HL, такое поведение сохранено
;   если индекс принадлежит другой обёртке, перемещается она, а не обязательно указатель, прошедший первую проверку
;   первый байт обёртки не исполняется и не проверяется, временно отключённый RET не скрывает её индекс
;   фиксированный сдвиг 128 байтов не заменён логическим удалением, поведение длинных списков остаётся частью MoveItemToTail
; -----------------------------------------
                ; сохранение исходного индекса в FListedItemMoveFrame.SavedDE
Entry:          PUSH DE
                ; сохранение кандидата новой обёртки в FListedItemMoveFrame.SavedHL
                PUSH HL
                ; передача индекса в HL для адресации его физического поля DrawHandler
                EX DE, HL
                ; выбор поля указателя рисования, геометрия и Flags этой записи не читаются
                LD A, FInterfaceItem.DrawHandler
                CALL @Station.GetItemField.Entry
                ; чтение полного DrawHandler в DE для первого поиска по указателю
                LD E, (HL)
                INC HL
                LD D, (HL)
                ; проверка присутствия самого указателя, индекс его операнда здесь ещё не сравнивается
                CALL @Station.TestDrawPointer.Entry
                ; восстановление исходных HL и DE до условного выхода либо переноса по индексу
                POP HL
                POP DE
                RET NZ                                                          ; выход, если DrawHandler отсутствует в списке, новую обёртку не добавлять

                ; JP @Station.MoveItemToTail.Entry, продолжение в MoveItemToTail.asm

                endmodule
                endmodule
