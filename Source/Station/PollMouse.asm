                module Station
                module PollMouse
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [настройка кнопок и аппаратные счётчики](../../Docs/MouseInput.md)
; -----------------------------------------
; Опрос кнопок и счётчиков мыши, очистка её входных флагов и обновление координат
; исходная запись 4, файловые смещения #0853..#0874
; In:
;   MousePollState.Disabled ненулевой запрещает опрос, ноль разрешает аппаратные чтения
;   при разрешённом опросе доступны MouseInput.State, PointerXY и изменяемый код настройки
;   SetupJump равен исходному JR ConfigureMouseButtons либо двум NOP, смещения кнопок равны 0,5 либо 5,0
; Out:
;   при запрете AF соответствует AND Disabled, прочие регистры и входное состояние сохранены, порты не читаются
;   HL - итоговые пиксельные X в L и Y в H, DE - прежние аппаратные счётчики X в E и Y в D, BC=#FFDF
;   AF - рабочий результат последней ветви Y, единого флага наличия движения нет
;   StationState.PointerXY и PreviousX,PreviousY обновлены, ненулевые разности устанавливают соответствующий байт направления в 1
;   IX восстановлен из FMousePollFrame, IY, альтернативные регистры, I и IFF сохраняются, SP возвращается за адрес вызова
; Corrupt:
;   при разрешённом опросе HL, DE, BC, AF, при запрете только AF
; Note:
;   описание чтения движения относится только к разрешённому опросу
;   FMousePollFrame сохраняет IX и адрес возврата, временный PUSH HL,POP IX не создаёт постоянного дополнительного слова
;   семь флагов перед опросом обнуляются, затем кнопки дают отдельные байты 0 или 1
;   при первой кнопке нижние два разряда выбирают настройку, затем опрос повторяется уже с двумя NOP
;   пока оба младших разряда равны нулю, настройка остаётся активной, третья кнопка отдельно не декодируется
;   разность X равна signed8(newX-oldX), разность Y равна signed8(-(newY-oldY)), каждая умножается на два
;   при отрицательной разности применяется max(0,old+2*delta), при положительной min(limit,old+2*delta)
;   limit равен 254 для X и 191 для Y, нулевая разность не нормализует исходную координату
;   отрицательная ветвь не ограничивает сверху, при исходном Y>191 результат может остаться вне экрана
;   байты направлений не очищаются этим продолжением, полный PollMouse очищает семь флагов до чтения портов
;   чтение Y выполняется даже при нулевой разности X, старые оба счётчика загружаются до первого чтения
;   модель задаёт байты трёх портов, реальное устройство и вызов из ISR не проверены
; -----------------------------------------
                ; чтение программного запрета опроса из изменяемого операнда
Entry:          LD A, #00
                ; проверка запрета до очистки флагов и аппаратных чтений
                AND A
                RET NZ                                                          ; выход, если опрос запрещён, сохранить входные байты мыши и координаты

                ; создание FMousePollFrame.SavedIX перед выбором базы состояния
                PUSH IX
                LD HL, @MouseInput.State
                PUSH HL
                POP IX
                ; очистка семи независимых байтов действий и направлений перед новой выборкой
                XOR A
                LD (HL), A
                INC HL
                LD (HL), A
                INC HL
                LD (HL), A
                INC HL
                LD (HL), A
                INC HL
                LD (HL), A
                INC HL
                LD (HL), A
                INC HL
                LD (HL), A
                ; выбор порта кнопок, активные низкие уровни затем инвертируются CPL
                LD BC, @MouseConst.ButtonPort
                IN A, (C)
                CPL
                ; исходный JR одноразовой настройки, после первого выбора здесь исполняются два NOP
                JR @Station.ConfigureMouseButtons.Entry

                endmodule
                endmodule
