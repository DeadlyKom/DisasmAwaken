                module Station
                module SumBank4Index
; Подробный разбор [индекс банка 4](../../Docs/Bank4Index.md)
; Сумма двух байтов банка 4 с возвратом банка языка 6
; In:
;   банк 4 загружен и содержит читаемые байты #E146 и #E148, #E147 также читается командой LD BC
;   аппаратный порт и CurrentPage согласованы, bit5 снят, CPU-стек вне сменяемого окна
;   продолжение после возврата находится в фиксированной памяти либо в банке 6
; Out:
;   HL, DE сохранены, BC - B=0, C=(банк4.E146 + банк4.E148) AND #FF
;   AF - A=(входная CurrentPage AND #F8) OR #16, F от финального OR страницы, не от суммы индекса
;   альтернативные и индексные регистры, I и IFF сохранены, SP восстановлен
;   аппаратный порт и тень выбирают сначала (старое AND #F8) OR #14, затем (старое AND #F8) OR #16
; Corrupt:
;   BC, AF
; Note:
;   старший байт E147 загружается в B, затем явно отбрасывается, перенос суммы также не расширяет индекс
;   старшие управляющие биты страницы сохраняются, исходный номер банка не восстанавливается
;   назначение двух компонентов индекса в игровом состоянии ещё не доказано
                ; выбор банка 4 с ROM 1 для чтения двух компонентов индекса
Entry:          LD A, #14
                CALL @Station.SelectRamBank.Entry
                ; чтение первого компонента в C, старший прочитанный байт B затем отбрасывается
                LD BC, (#E146)
                ; чтение второго байтового компонента индекса
                LD A, (#E148)
                ; расчёт суммы компонентов по модулю 256
                ADD A, C
                ; передача суммы в C и обнуление B без добавления переноса
                LD C, A
                LD B, #00
                ; возврат банка LANG 6, сумма BC сохраняется вызовом выбора страницы
                LD A, #16
                CALL @Station.SelectRamBank.Entry
                RET

                endmodule
                endmodule
