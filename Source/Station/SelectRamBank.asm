                module Station
                module SelectRamBank
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [StationCore.md](../../Docs/StationCore.md)
; -----------------------------------------
; Объединение старших пяти битов теневого #7FFD со всем входным A и запись результата в порт
; исходная запись 4, файловые смещения #0642..#064A
; In:
;   AF - A байт, объединяемый со старшими пятью битами StationState.CurrentPage
; Out:
;   AF - A=(прежний StationState.CurrentPage AND #F8) OR исходный A, F соответствует логическому OR результата
;   объединённый байт записан в StationState.CurrentPage и выведен в порт #7FFD
; Corrupt:
;   AF
; Note:
;   при A=0..7 меняется только номер банка, старшие биты входного A не маскируются и могут дополнительно установить старшие биты результата
;   HL, DE, BC, альтернативные и индексные регистры, I и IFF сохраняются
;   исполнение последовательно переходит в SelectMemoryPage, SP восстанавливается его RET
;   фактический аппаратный эффект OUT зависит от состояния устройства, модель сверяет байт порта без эмуляции блокировки переключения
; -----------------------------------------
Entry:          PUSH BC
                ; сохранение полного входного байта, его старшие биты также участвуют в последующем OR
                LD C, A
                ; чтение старших управляющих битов из текущей тени порта
                LD A, (@StationState.CurrentPage)
                AND @Hardware.PageUpperMask
                ; расчёт нового байта страницы объединением сохранённых старших битов со всем входным A
                OR C
                POP BC

                ; JP @Station.SelectMemoryPage.Entry, продолжение в SelectMemoryPage.asm

                endmodule
                endmodule
