                module Station
                module ActivateInterfaceCallback
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [развилка действия элемента](../../Docs/InterfaceAction.md)
                ; -----------------------------------------
                ; Сохранение callback и выбор интерактивной геометрии, переключения границ либо активации
                ; исходная запись 4, файловые смещения #6C21..#6C2B
                ; In:
                ;   HL - новый callback и запасная обёртка для MoveItemToTail, DE - выбранный индекс записи, BC сохраняется
                ;   AF - A=0 выбирает попытку интерактивной геометрии, любой ненулевой A приводит к ActivateItem
                ;   для штатного пути выбранный индекс уже присутствует в списке, иначе действует исходный запасной путь MoveItemToTail с HL
                ;   выполняются предусловия TrackItemGeometry, ToggleItemBounds либо ActivateItem на выбранной ветви
                ;   код банкового окна станции доступен для записи, FlagsCache подготовлен вызывающим кодом
                ; Out:
                ;   NextCallback всегда получает входной HL до проверки A
                ;   при A=0 и выполненной геометрии HL, DE и BC сохранены, AF=#0045, IX сохранён, результат соответствует TrackItemGeometry
                ;   при A=0 и отсутствии интерактивного действия результат соответствует ToggleItemBounds, HL=DE-индекс, Carry=1, IX=адрес записи
                ;   при ненулевом A результат соответствует ActivateItem, HL=входной callback, DE и BC сохранены
                ;   HL' - H' сохраняется и L' рабочий только при перерисовке ActivateItem, AF' рабочий на том же пути, IY сохраняется
                ; Corrupt:
                ;   HL, AF, L', AF', IX, R, NextCallback и побочные записи выбранных TrackItemGeometry/ToggleItemBounds/ActivateItem, включая RAM стека
                ; Note:
                ;   бит 7 ненулевого A обходит пробу TrackItemGeometry сразу, остальные ненулевые значения проходят ту же активацию через FinishItemAction
                ;   OR A перед условным CALL обеспечивает Z=1 для A=0, поэтому интерактивный вход использует удерживаемый код 1
                ;   входной Carry не задаёт результат, нулевой A всегда заканчивает с Carry=1 через один из двух геометрических путей
                ;   новый callback не вызывается этой обёрткой, при выполненной геометрии сохраняется только NextCallback для возможного последующего использования
                ;   сохранённая геометрия, указатель и EventEnabled меняются только выбранными подпрограммами
                ;   H', DE', BC', I и IFF сохраняются собственным кодом, поведение ISR ограничено договорами HALT, SP восстанавливается
                ;   контракт составлен статическим разбором 11 исходных байтов и договоров всех трёх проверенных хвостов
                ; -----------------------------------------
                ; сохранение входного callback в изменяемом операнде ActivateItem до любого выбора действия
Entry:          LD (@ActiveItemState.NextCallback), HL
                ; проверка старшего бита селектора для немедленного пути активации
                BIT 7, A
                JR NZ, @Station.ActivateItem.Entry                              ; переход, если бит 7 селектора установлен, активировать выбранный элемент

                ; проверка нулевого селектора с очисткой Carry и подготовкой Z для интерактивного входа
                OR A
                CALL Z, @Station.TrackItemGeometry.Entry                        ; вызов, если A нулевой, попытаться переместить либо изменить размер элемента
                ; JP @Station.FinishItemAction.Entry, продолжение в FinishItemAction.asm

                endmodule
                endmodule
