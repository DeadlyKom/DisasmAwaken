                module Station
                module PrintFromRow
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [подсчёт и пропуск строк](../../Docs/TextPagination.md)
; -----------------------------------------
; Пропуск E выровненных строк и печать остатка из заданной позиции курсора
; исходная запись 4, файловые смещения #4843..#485E
; In:
;   HL - начало текста с читаемым запасом для выравнивателя
;   DE - E число строк для пропуска 0..255, D сохраняется во время пропуска
;   BC - B исходный CursorY, C исходный CursorX, TextWindow задаёт размеры
; Out:
;   HL - позиция после пропуска и последующего PrintJustified либо раннего конца текста
;   DE и BC при раннем Carry пропуска восстановлены, E содержит остаток включая текущий завершающий проход
;   после перехода к PrintJustified HL, DE, BC, AF соответствуют его полному контракту
;   при раннем возврате AF от SkipJustifyRow, курсор всегда восстановлен из входного BC
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   альтернативные и индексные регистры, I и IFF сохраняются, стек сбалансирован
;   сначала CursorX=C и CursorY=B, после каждого сухого прохода эти координаты задаются заново
;   при E=0 сухого прохода нет, сразу выполняется хвостовой переход в PrintJustified
;   E уменьшается только после прохода без Carry, максимум 255 пропусков
;   переносы, ранняя малая высота и возможное незавершение PrintJustified сохраняются
; -----------------------------------------
                ; задание исходного курсора, младший байт BC содержит X, старший Y
Entry:          LD (@TextWindow.CursorX), BC
                LD A, E
                ; проверка числа пропускаемых строк перед сухим проходом
                AND A
                JP Z, @Station.PrintJustified.Entry                             ; переход, если E равен нулю, сразу вывести оставшийся текст с выравниванием

                ; сохранение остатка строк и исходного курсора вокруг сухого прохода
SkipRow:        PUSH DE
                PUSH BC
                CALL @Station.SkipJustifyRow.Entry
                POP BC
                POP DE
                ; восстановление исходного курсора после каждого пропуска, положение текста HL сохраняется новым
                LD (@TextWindow.CursorX), BC
                RET C                                                           ; выход, если сухой проход установил Carry, остаток текста уже не выводится

                ; уменьшение остатка пропуска только после принятого сухого прохода
                DEC E
                JP NZ, @Station.PrintFromRow.SkipRow                            ; переход, если остались строки для пропуска, повторить сухой проход

                JP @Station.PrintJustified.Entry

                endmodule
                endmodule
