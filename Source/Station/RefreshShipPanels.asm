                module Station
                module RefreshShipPanels
                ; Документация [станционная цепочка, геометрия и настоящее IM2-пробуждение](../../Docs/ShipPreviewCallbacks.md)
                ; -----------------------------------------
                ; Отложенное обновление списка моделей, описания и перенесённого в конец корабельного просмотра
                ; исходная запись 4, файловые смещения #0B78..#0B95
                ; In:
                ;   HL, DE, BC сохраняются быстрым отказом, AF не является параметром, ActiveItemState.Active задаёт занятость
                ;   при Active=0 корректны список рисования, индексы панелей, их геометрия, указатель и договоры экранного обновления
                ;   в списке есть ключ PreviewIndex для MoveItemToTail, фактический адрес с этим ключом может отличаться от DrawShipPreview
                ;   действуют договоры DrawModelListPanel, TryDrawModelDescription, TryDrawShipPreview и HALT зависимых рисователей
                ; Out:
                ;   при Active!=0 HL, DE, BC сохранены, AF содержит Active и флаги OR, PendingRedraw и память сохраняются
                ;   быстрый отказ сохраняет HL', DE', BC', AF', IX, IY, I и IFF
                ;   при Active=0 PendingRedraw=0, сначала рисуются список и условное описание, затем ключ просмотра переносится в конец
                ;   последнее условное рисование требует точный DrawShipPreview, алиас с равным ключом не рисует его
                ;   HL, DE и BC рабочего выхода принадлежат последнему TryDrawShipPreview, EndScreenUpdate их сохраняет
                ;   A=10, F рабочего выхода сохранён от TryDrawShipPreview, для активного просмотра 0C, для найденного C9 50
                ;   HL', DE', BC', AF', IX и IY рабочего выхода определяются последовательной композицией перечисленных помощников
                ;   рабочий выход показывает банк 5 и выбирает окно банка 0, CurrentPage=10, UpdateBlocked=0, SP входному+2
                ; Corrupt:
                ;   AF при быстром отказе, HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, IFF, список, PendingRedraw, панели, D3D и экран при обновлении
                ; Note:
                ;   запрос остаётся ненулевым, пока активный элемент не разрешает обновление, при допуске он сбрасывается перед первым рисователем
                ;   описание может отсутствовать, его пропуск не запрещает перенос и перерисовку просмотра
                ;   проверены активный адрес, временный C9 и чужой адрес с тем же индексом, старый периодический callback в двух последних случаях сохраняется
                ;   полные обновления проверены для OwnedMode=1, рыночный помощник имеет отдельный договор, единый рыночный проход этой моделью не проверен
                ; -----------------------------------------
                ; проверка занятости активного элемента до сброса запроса обновления
Entry:          LD A, (@ActiveItemState.Active)
                OR A
                RET NZ                                                          ; выход, если ActiveItemState.Active ненулевой, сохранить отложенный запрос

                ; сброс обработанного запроса до начала перерисовки панелей
                LD (@ShipPanelState.PendingRedraw), A
                ; сохранение видимого экрана в банке 7 и начало скрытого обновления
                CALL @Station.BeginScreenUpdate.Entry
                ; рисование списка моделей и цен выбранной категории
                CALL @Station.DrawModelListPanel.Entry
                ; условное рисование описания, отсутствие точного адреса панели допустимо
                CALL @Station.TryDrawModelDescription.Entry
                ; чтение индекса просмотра для переноса его ключа в конец списка
                LD DE, (@ShipPanelState.PreviewIndex)
                ; перенос фактического адреса с найденным ключом, адрес-алиас сохраняется
                CALL @Station.MoveItemToTail.Entry
                ; условное рисование только точного адреса корабельного просмотра
                CALL @Station.TryDrawShipPreview.Entry
                ; завершение экранного обновления без дополнительного CPU-возврата
                JP @Station.EndScreenUpdate.Entry

                endmodule
                endmodule
