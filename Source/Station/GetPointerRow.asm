                module Station
                module GetPointerRow
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [байтовые координаты, доступная высота и строка указателя](../../Docs/RowSelection.md)
; -----------------------------------------
; Проверка вертикального попадания и получение восьмипиксельной строки указателя
; исходная запись 4, файловые смещения #42A4..#42B3
; In:
;   DE - D высота проверяемой области в пикселях, E её пиксельный отступ от Item.Y*8
;   IX - читаемая FInterfaceItem, PointerXY.Y доступен, действует договор GetRowHitData
; Out:
;   HL и DE сохранены, B байтовое начало области от GetRowHitData
;   при PointerY<B Carry=1, A=(PointerY-B) AND #FF, C остаётся PointerY, F от байтового SUB
;   при PointerY>=B и PointerY-B>=D Carry=1, A разность, C остаётся PointerY, F от CP и последующего CCF
;   иначе Carry=0, A=C=(PointerY-B)>>3, F от AND #1F, допустимая строка 0..31
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
; Corrupt:
;   BC, AF
; Note:
;   высота здесь уже пиксельная, дополнительного перевода D в восемь пикселей нет
;   нулевая высота всегда запрещает выбор, даже при PointerY равном B
;   номер строки 0 является успешным результатом с Carry=0, нулевой A сам по себе не означает отказ
;   первое сравнение unsigned не поддерживает видимую часть области с обёрнутым отрицательным началом
;   проверяется только вертикальная координата, PointerX не участвует
;   три RRCA и AND #1F вычисляют целую часть деления положительной разности на восемь
; -----------------------------------------
                ; получение пиксельной координаты указателя и байтового начала области
Entry:          CALL @Station.GetRowHitData.Entry
                LD A, C
                ; расчёт смещения PointerY относительно начала области B
                SUB B
                RET C                                                           ; выход, если PointerY меньше B, указатель расположен выше области

                ; проверка смещения относительно пиксельной высоты D
                CP D
                ; инверсия Carry, теперь он означает достижение либо превышение высоты
                CCF
                RET C                                                           ; выход, если смещение не меньше высоты D, указатель расположен за нижней границей

                ; расчёт номера восьмипиксельной строки из принятого смещения
                RRCA
                RRCA
                RRCA
                ; выделение пяти младших битов частного после трёх вращений
                AND @RowSelectConst.RowMask
                LD C, A
                RET

                endmodule
                endmodule
