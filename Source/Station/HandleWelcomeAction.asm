                module Station
                module HandleWelcomeAction
                ; Документация [точный селектор, Carry перерисовки, символьная строка закрытия и выходной HL рисователя](../../Docs/PassivePanelActions.md)
                ; -----------------------------------------
                ; Общая перерисовка и закрытие приветствия, селектор 1 не меняет содержимое
                ; исходная запись 4, файловые смещения #1BF7..#1BFF
                ; In:
                ;   HL запасной рисователь DrawWelcomePanel, DE индекс элемента, штатно 45, BC сохраняемый контекст помощников
                ;   AF содержит полный селектор, его старший бит запрещает общий путь, IX контекст выбранного элемента
                ;   действуют договоры RepaintAndFlag, CloseActiveItem, MoveItemToTail и TrackItemGeometry, повторный вход в общую перерисовку исключён
                ;   при необходимости рисования действуют договоры DrawWelcomePanel, BeginScreenUpdate, EndScreenUpdate и пробуждения HALT
                ;   список с исходным ограничителем и хвостами 128-байтовых сдвигов доступен, PointerY и OriginYLow подготовлены для CloseMenuOnRow
                ; Out:
                ;   сначала выполнен RepaintAndFlag, при его Carry=1 немедленно возвращаются его результаты, DEC A и закрытие не исполняются
                ;   при установленном входном бите 7 A исходный, F=(A AND A8) OR 1, прочие основные и индексные регистры сохранены
                ;   после настоящей перерисовки DE и IX восстановлены, HL результат рисователя, BC и альтернативные пары по callback и рисователю
                ;   после обычного экранного цикла страница 10 по EndScreenUpdate, прежний экранный бит 18 не восстанавливается
                ;   без Carry при A=1 возвращаются A=0, F=42, содержимое не выбирается и CloseMenuOnRow не вызывается
                ;   без Carry при любом ином A вызван CloseMenuOnRow с исходным DE, закрытие зависит только от равенства PointerY SHR 3 и OriginYLow SHR 3
                ;   после CloseMenuOnRow HL и DE сохранены от входа помощника, C=PointerY SHR 3, B сохранён, AF по помощнику
                ;   обычный RET даёт SP входному+2, дополнительные изменения памяти и регистров соответствуют реально выполненным помощникам
                ; Corrupt:
                ;   HL, BC, AF, HL', DE', BC', AF', IY по callback и рисователю, список, экран, карта владельцев, текстовые операнды и состояние интерфейса
                ; Note:
                ;   пустое действие содержимого не означает отсутствие общих эффектов, перед DEC уже выполнены закрытие активного callback и перенос списка
                ;   MoveItemToTail сдвигает 128 байтов даже для уже последней записи, повторное закрытие добавляет самостоятельный сдвиг
                ;   после рисования HL не восстанавливается общей цепочкой, полный DrawWelcomePanel возвращает CE19
                ;   наведение отделено от этого входа, его пустой JP и RET описаны в PassivePanelHovers
                ;   модель ограничивает произвольный callback его договором, использует настоящий пустой активный callback и проверенные реальные рисователи
                ; -----------------------------------------
                ; обновление общей геометрии и порядка приветственного окна
Entry:          CALL @Station.RepaintAndFlag.Entry
                RET C                                                           ; выход, если общая перерисовка или геометрия вернула Carry, дальнейшее действие запрещено

                ; проверка селектора 1 после разрешённого общего пути
                DEC A
                RET Z                                                           ; выход, если селектор равен 1, у приветствия нет действия над содержимым

                ; удаление приветствия по символьной строке с прямым возвратом вызывающей стороне
                JP @Station.CloseMenuOnRow.Entry

                endmodule
                endmodule
