                module Station
                module PrintEnvironmentRows
                ; Документация [два CR-списка, общий хвост значений, полный индекс и счётчик обработанных полей](../../Docs/SettingsRowPanels.md)
                ; -----------------------------------------
                ; CR-подписи установок среды и общий цикл текущих значений со счётчиком в A'
                ; исходная запись 4, файловые смещения #0E6A..#0EAB
                ; In:
                ;   HL содержит полное слово начальной позиции, младший байт выбирает CR-подпись, полное слово смещает указатель значений
                ;   BC сохраняемый контекст поиска подписи, остальные регистры не задают отдельного параметра
                ;   окно, Column2X, глифы, стек и нультерминированные значения подготовлены, Style=0 соответствует штатному выводу
                ;   от DECB существуют L+1 разделителей CR и завершающийся поток подписи, от SettingsText.Interface+HL читается конечный массив
                ; Out:
                ;   HL указывает за фактически обработанными значениями либо на исходный нуль, DE равен входному HL
                ;   BC первоначально 9728, после попытки нового Y B=97, C=Height
                ;   AF=0044 при нулевом значении, AF=0042 при последнем статусе глифа 1 либо 2, иначе A новый байтовый Y и F от CP Height на отказе строки
                ;   HL', DE', BC', IX, IY, I, IFF и IM сохранены, A' содержит число обработанных ненулевых значений по модулю 256
                ;   F' принадлежит последнему INC счётчика, при нуле обработанных значений A'F'=0044, SP после RET входному+2
                ;   первый курсор подписи X=0,Y=8, перед значениями Y=8, перед каждым значением X=Column2X, bitmap содержит принятую часть вывода
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', курсор, bitmap и изменяемые операнды PrintAfterCR и DrawKeyLabel
                ; Note:
                ;   исходная подпись содержит 13 значений, границы и допустимость индекса обёртка не проверяет
                ;   счётчик увеличивается до проверки результата DrawKeyLabel, последний отказ тоже учитывается
                ;   общий вход PrintEnvironmentRows.ResetCount принимает HL непосредственно на первом значении, DE и B сохраняемый контекст, C меняется только при попытке нового Y
                ;   общий вход не печатает подписи и не сбрасывает Y, он обнуляет альтернативный счётчик и переходит к тем же правилам значений
                ; -----------------------------------------
                ; сохранение полного исходного индекса в DE и подготовка курсора подписей
Entry:          EX DE, HL
                LD HL, #0800
                LD (@TextWindow.CursorX), HL
                ; поиск CR-подписи, только E задаёт число пропускаемых разделителей
                LD HL, @SettingsRowConst.EnvLabels
                PUSH DE
                LD A, E
                CALL @Station.PrintAfterCR.Entry
                ; сброс Y перед значениями независимо от результата подписей
                LD A, #08
                LD (@TextWindow.CursorY), A
                ; расчёт полного адреса начального значения, старший байт индекса не отбрасывается
                POP HL
                LD BC, @SettingsText.Interface
                ADD HL, BC
                ; ResetCount принимает HL значений, DE и B сохраняются, исходный Y подготовлен вызывающим кодом
ResetCount:     XOR A
                EX AF, AF'
                ; обновление X колонки перед каждым значением, включая нулевой ограничитель
DrawValue:      LD A, (@TextStreamState.Column2X)
                LD (@TextWindow.CursorX), A
                ; проверка нуля, ограничивающего массив значений
                LD A, (HL)
                OR A
                RET Z                                                           ; выход, если текущее значение равно нулю, оно не учитывается в счётчике

                ; вывод одного значения, специальные клавиши дают четыре глифа
                CALL @Station.DrawKeyLabel.Entry
                ; переход к следующему значению и обновление альтернативного байтового счётчика до проверки статуса
                INC HL
                EX AF, AF'
                INC A
                EX AF, AF'
                JR C, @Station.PrintEnvironmentRows.NextRow                     ; переход, если последний глиф принят, проверить следующую строку

                ; проверка вертикального отказа глифа с кодом 1
                DEC A
                RET Z                                                           ; выход, если последний статус глифа равен 1, значение уже учтено

                ; проверка отказа относительной высоты с кодом 2
                DEC A
                RET Z                                                           ; выход, если последний статус глифа равен 2, значение уже учтено

                ; расчёт следующего байтового Y с шагом 8 и проверка высоты окна
NextRow:        LD A, (@TextWindow.Height)
                LD C, A
                LD A, (@TextWindow.CursorY)
                ADD A, #08
                CP C
                RET NC                                                          ; выход, если новый Y не меньше высоты, последняя обработанная строка уже учтена

                ; обновление принятого Y перед следующим значением
                LD (@TextWindow.CursorY), A
                JP @Station.PrintEnvironmentRows.DrawValue

                endmodule
                endmodule
