                module Station
                module PrepareContextMenu
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [исключение выбранного элемента и позиция контекстного меню](../../Docs/PopupItems.md)
; -----------------------------------------
; Привязка сохранённой позиции контекстного элемента 40 к указателю и запрос перестроения
; исходная запись 4, файловые смещения #3E4E..#3E76
; In:
;   AF - A записываемый код события, штатный вход из Dispatcher передаёт ноль
;   PointerXY содержит два пиксельных байта, изменяемый индекс DrawItem40 подготовлен загрузчиком и равен 40
;   выполняется договор RestoreItemBounds, исходная запись Item40 имеет SavedWidth=9, SavedHeight=9
; Out:
;   SavedX элемента 40=min(PointerX>>3, 23), SavedY=min(PointerY>>3, 15)
;   текущая геометрия восстановлена из SavedX..SavedHeight, исходные размеры дают видимый прямоугольник 9x9 знакомест
;   EventCode получает входной A, EventEnabled=0 запрашивает последующее перестроение
;   HL - выбранная обёртка того же индекса после переноса списка, DE=40, BC сохранён, AF=#09A4
;   IX, IY и альтернативные регистры сохраняются, SP восстанавливается
; Corrupt:
;   HL, DE, AF
; Note:
;   при уже существующей обёртке того же индекса MoveItemToTail может вернуть её вместо переданного DrawItem40
;   HL=#7583 передаётся как указатель обёртки RestoreItemBounds, сама отрисовка DrawItem40 здесь не вызывается
;   SavedX и SavedY записываются до восстановления текущей геометрии, SavedWidth и SavedHeight не меняются
;   ограничения 23 и 15 фиксированные, при изменении сохранённых размеров общая видимость не гарантируется
;   название меню подтверждено указателем DrawItem40 на восемь команд ContextMenuText банка станции
;   I и IFF собственным кодом сохраняются, модель не исполняет IRQ и последующее рисование
; -----------------------------------------
                ; сохранение входного кода события перед вычислением позиции меню
Entry:          LD (@InterfaceState.EventCode), A
                ; чтение двух пиксельных координат указателя
                LD HL, (#6307)
                ; расчёт двух координат знакоместа тремя независимыми сдвигами каждого байта
                SRL H
                SRL L
                SRL H
                SRL L
                SRL H
                SRL L
                ; проверка верхней строки меню, максимальный Y=15 оставляет место исходным девяти строкам
                LD A, H
                CP @PopupConst.MaxY
                JR C, @Station.PrepareContextMenu.ClampX                        ; переход, если строка указателя меньше 15, сохранить вычисленный Y

                LD H, @PopupConst.MaxY
                ; проверка правой позиции меню, максимальный X=23 оставляет место исходным девяти колонкам
ClampX:         LD A, L
                CP @PopupConst.MaxX
                JR C, @Station.PrepareContextMenu.StorePosition                 ; переход, если колонка указателя меньше 23, сохранить вычисленный X

                LD L, @PopupConst.MaxX
                ; обновление физической пары Item40.SavedX, Item40.SavedY до восстановления геометрии
StorePosition:  LD (@InterfaceItems.Item40 + FInterfaceItem.SavedX), HL
                ; выбор исходной обёртки рисования элемента 40 как ключа переноса и восстановления
                LD HL, @Station.DrawItem40.Entry
                ; передача управления восстановлению геометрии без дополнительного возврата на CPU-стеке
                JP @Station.RestoreItemBounds.Entry

                endmodule
                endmodule
