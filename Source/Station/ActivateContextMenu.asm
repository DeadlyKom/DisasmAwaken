                module Station
                module ActivateContextMenu
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [выбор команды, фильтр закрытия и сохранение геометрии](../../Docs/MenuCommands.md)
; -----------------------------------------
; Развилка действия меню после перерисовки и выполнение команды выбранной строки
; исходная запись 4, файловые смещения #17E8..#181E
; In:
;   HL - запасная обёртка, DE=40, IX=Item40, AF селектор действия для RepaintAndFlag
;   выполнены договоры RepaintAndFlag, CloseMenuOnRow, DropItemDraw и выбранной команды
;   операнды индексов окон установлены загрузчиком, PreviousRow содержит сохранённый байт наведения
; Out:
;   при Carry после RepaintAndFlag возврат немедленный с договором этой процедуры
;   при отсутствии Carry и возвращённом A, отличном от 1, результат CloseMenuOnRow после DEC A
;   при A=1 меню удаляется из списка, затем PreviousRow=#FF даёт выход без команды
;   номера 0..6 выбирают отдельные команды, любой другой байт выбирает окно сохранения DrawItem43
;   регистры и память после выбранного хвостового перехода соответствуют договору целевой команды
;   у обычного пути DE и IX восстановлены RepaintAndFlag до команды, затем возможны изменения выбранной команды
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY согласно RepaintAndFlag и выбранной команде
; Note:
;   вход расположен на три байта после HandleItem40, это подтверждено INC HL трижды в DispatchInterfaceEvent
;   нет проверки номера на верхнюю границу 7, поздно сохранённая высота 64 также выбирает сохранение
;   собственная развилка не меняет I и IFF, внешние callbacks перерисовки обязаны выполнять свои договоры
;   модель отдельных команд не доказывает всю композицию перерисовки и содержимого открываемых окон
; -----------------------------------------
                ; подготовка элемента через перерисовку с принудительным Carry после фактического рисования
Entry:          CALL @Station.RepaintAndFlag.Entry
                RET C                                                           ; выход, если перерисовка вернула Carry, команду меню не выполнять

                ; проверка возвращённого селектора на значение 1
                DEC A
                JP Z, @Station.ActivateContextMenu.DispatchRow                  ; переход, если селектор равен 1, удалить меню и выполнить выбранную строку

                ; проверка строки указателя для закрытия меню при другом селекторе
                CALL #C85E
                RET Z                                                           ; выход, если совпала строка закрытия, удаление уже выполнено

                RET

                ; удаление самого меню из списка перед действием выбранной строки
DispatchRow:    CALL #C873
                ; чтение сохранённого номера, он может содержать высоту после позднего отказа наведения
                LD A, (@PopupState.PreviousRow)
                ; проверка маркера отсутствующего выделения через увеличение #FF
                INC A
                RET Z                                                           ; выход, если сохранённый номер равен #FF, команды нет

                ; восстановление номера после проверки маркера
                DEC A
                JP Z, @Station.HideAllItems.Entry                               ; переход, если номер равен 0, скрыть элементы

                ; проверка следующего номера последовательным вычитанием единицы
                DEC A
                JP Z, @Station.CloseAllItems.Entry                              ; переход, если номер равен 1, закрыть разрешённые элементы

                ; проверка команды сохранения текущей геометрии
                DEC A
                JP Z, @Station.RememberItemBounds.Entry                         ; переход, если номер равен 2, запомнить геометрию

                ; проверка команды восстановления сохранённой геометрии
                DEC A
                JP Z, @Station.ArrangeAllItems.Entry                            ; переход, если номер равен 3, расставить элементы

                ; проверка команды открытия установок среды
                DEC A
                JP Z, @Station.OpenEnvOptions.Entry                             ; переход, если номер равен 4, открыть установки среды

                ; проверка команды открытия установок игры
                DEC A
                JP Z, @Station.OpenGameOptions.Entry                            ; переход, если номер равен 5, открыть установки игры

                ; проверка команды открытия восстановления
                DEC A
                JP Z, @Station.OpenRestoreDialog.Entry                          ; переход, если номер равен 6, открыть восстановление

                ; выбор окна сохранения для номера 7 и всех остальных немаркерных байтов
                LD HL, @Station.DrawItem43.Entry
                ; перенос окна сохранения в конец списка и восстановление его границ
                JP #CBA9

                endmodule
                endmodule
