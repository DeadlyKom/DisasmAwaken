                module Station
                module FillItemBitmap
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [Interface.md](../../Docs/Interface.md)
; -----------------------------------------
; Чтение геометрии интерфейсного элемента, настройка текстового окна и заполнение видимой части bitmap
; исходная запись 4, файловые смещения #5FF5..#5FFF
; In:
;   HL - индекс существующей записи FInterfaceItem, первые четыре байта содержат X, Y, Width, Height
;   ширина 1..32 и высота 1..24, прямоугольник имеет ненулевое пересечение с экраном по обеим координатам
;   StationRaster.FillMode - бит 0 выбирает нулевое заполнение при единице, иначе #FF
;   в окне #C000 выбрана страница станционного кода, таблицы #82..#84 подготовлены
; Out:
;   HL - исходный индекс сохранён, DE - D равен нулю, E ширина видимой части, BC - координаты видимого левого верхнего знакоместа
;   AF - если нижняя исключённая строка видимого прямоугольника кратна восьми, A равен видимой колонке и F=#43, иначе A старший байт следующей строки знакомест и F=#42
;   видимая часть bitmap заполнена, текстовое окно настроено по исходной геометрии элемента, относительный текстовый курсор обнулён
; Corrupt:
;   DE, BC, AF
; Note:
;   вход не читает Flags или обработчики записи, исходная геометрия в таблице не изменяется
;   исполнение последовательно продолжается в FinishItemFill, отдельного вызова между файлами нет
;   полностью невидимые элементы и нулевые размеры не проверяются на пустоту, они исключены из подтверждённого контракта
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   меняются операнды TextWindow и FillRectangle, атрибуты экрана не записываются
; -----------------------------------------
                ; сохранение индекса элемента до получения указателя его геометрии
Entry:          PUSH HL
                ; выбор первого физического поля записи, координаты X
                XOR A
                CALL @Station.GetItemField.Entry
                ; чтение исходных X, Y и ширины в C, B и E
                LD C, (HL)
                INC HL
                LD B, (HL)
                INC HL
                LD E, (HL)
                INC HL

                ; JP @Station.FinishItemFill.Entry, продолжение в FinishItemFill.asm

                endmodule
                endmodule
