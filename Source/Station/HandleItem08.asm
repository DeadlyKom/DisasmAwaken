                module Station
                module HandleItem08
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [проверка выбора, две страницы экрана и копирование перехода](../../Docs/StationTransition.md)
; -----------------------------------------
; Активация элемента 8 и подготовка перенесённого перехода из станции
; исходная запись 4, файловые смещения #20FF..#216B
; In:
;   на Entry выполнен договор ActivateInterfaceCallback, HL callback, DE индекс элемента, AF селектор действия
;   на BeginTransition доступен байт выбора 9849, стек вне изменяемых экранных и банковых областей
;   при выборе не FF физический #7FFD допускает смену страницы, фиксированный код 7EC0..7FBF доступен
;   исходный контекст 983B..9A3A доступен, область 4000..42FF допускает замену
; Out:
;   Entry передаёт ActivateInterfaceCallback входной контекст, затем возвращается при его Carry=1
;   иначе либо через прямой BeginTransition проверяется 9849, FF возвращает с A=FF, F=6A
;   на FF HL, DE, BC и остальные пары, I и IFF сохранены относительно BeginTransition, SP обычного возврата
;   при выборе не FF хвостовой переход 4200, SP сохранён относительно BeginTransition
;   выбран #7FFD=1F напрямую, тень CurrentPage не обновлена, IFF=0, IM=1, I=3F
;   очищены 768 байтов D800..DAFF банка 7 и 5800..5AFF фиксированного экрана
;   если 98AA не FF, байт 9906 увеличен на 30 по модулю 256, иначе сохранён
;   байты 983D и 983E переставлены, 512 байтов 983B..9A3A скопированы в 4000..41FF
;   256 байтов 7EC0..7FBF скопированы в 4200..42FF, HL=7FC0, DE=4300, BC=0
;   A равен исходному 983D, F сохраняет S,Z,C от проверки 98AA либо ADD счётчика, P/V=H=N=0
;   X/Y финального F от суммы A с последним перенесённым байтом по правилу LDIR
;   альтернативные и индексные регистры на Prepare сохранены, на Entry сначала действуют эффекты ActivateInterfaceCallback
; Corrupt:
;   HL, DE, BC, AF, I, IM, IFF на Prepare, HL', AF', IX дополнительно по ActivateInterfaceCallback
; Note:
;   BeginTransition обходит активацию элемента, этим входом пользуется команда W
;   новых адресов или буферов не выделяется, копируются исходные области игры
;   описанный выход ограничен входом 4200, дальнейший перенесённый загрузчик имеет отдельный контракт
;   часть копии 4200..42FF является кодом и именем ACTION, часть содержит последующие исходные байты
;   модель проверяет BeginTransition и W, вызов активации разобран композиционно по его договору
; -----------------------------------------
Entry:          JP @Station.HandleItem08.Activate

                ; активация элемента по общему договору интерфейса до проверки возможности перехода
Activate:       CALL @Station.ActivateInterfaceCallback.Entry
                RET C                                                           ; выход, если активация вернула Carry, переход из станции не выполняется

                ; проверка отсутствующего выбора по специальному коду FF
BeginTransition:LD A, (#9849)
                CP #FF
                JP NZ, @Station.HandleItem08.Prepare                            ; переход, если выбор не FF, подготовить копируемый переход

                RET

                ; запрет прерываний перед непосредственной заменой страницы и экранной памяти
Prepare:        DI
                ; выбор банка 7, теневого экрана и ROM 1 без обновления программной тени страницы
                LD A, #1F
                LD BC, #7FFD
                OUT (C), A
                ; очистка атрибутов теневого экрана банка 7 копированием нулевого байта
                LD HL, #D800
                LD DE, #D801
                LD BC, #02FF
                LD (HL), L
                LDIR
                ; проверка кода FF, запрещающего прибавление к счётчику 9906
                LD A, (#98AA)
                INC A
                JP Z, @Station.HandleItem08.ClearAttributes                     ; переход, если исходный байт 98AA равен FF, не увеличивать счётчик

                ; расчёт увеличенного на 30 счётчика с байтовым оборачиванием
                LD A, (#9906)
                ADD A, #1E
                LD (#9906), A
                ; очистка атрибутов фиксированного экрана перед заменой его начала
ClearAttributes:LD HL, #5800
                LD DE, #5801
                LD BC, #02FF
                LD (HL), L
                LDIR
                ; фиксация запрета прерываний и режима IM 1 для передаваемого состояния
                DI
                IM 1
                LD A, #3F
                LD I, A
                ; перестановка двух байтов контекста перед сохранением его экранной копии
                LD A, (#983D)
                LD B, A
                LD A, (#983E)
                LD (#983D), A
                LD A, B
                LD (#983E), A
                ; копирование 512 байтов контекста в начало фиксированного экрана
                LD HL, #983B
                LD DE, #4000
                LD BC, #0200
                LDIR
                ; копирование исходных 256 байтов перехода на исполняемый адрес 4200
                LD HL, #7EC0
                LD DE, #4200
                LD BC, #0100
                LDIR
                ; передача управления скопированной версии кода, продолжение в банк LANG не предусматривается
                JP #4200

                endmodule
                endmodule
