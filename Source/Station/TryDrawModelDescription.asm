                module Station
                module TryDrawModelDescription
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [пустое наведение, условный RET с продолжением и полный рисователь описания](../../Docs/DescriptionPanel.md)
                ; -----------------------------------------
                ; Условное последовательное рисование описания только при наличии точного обработчика в списке
                ; исходная запись 4, файловые смещения #0BEA..#0BF0
                ; In:
                ;   текущий список рисования с ограничителем старшего байта 1 доступен по договору TestDrawPointer, выбран банк станции 0
                ;   при наличии активного рисователя действуют полные требования DrawModelDescriptionPanel
                ; Out:
                ;   при отсутствии HL и BC сохранены, DE=6945, AF соответствует отсутствию указателя в TestDrawPointer, Z=0
                ;   при наличии Z=1 не выполняется RET NZ, поток последовательно входит в DrawModelDescriptionPanel без новой инструкции JP
                ;   на рисующем пути выходы и память принадлежат DrawModelDescriptionPanel, обычный SP равен входному SP+2
                ; Corrupt:
                ;   HL, DE, BC, AF, AF' на реально рисующем пути, при отсутствии только DE и AF
                ; Note:
                ;   сравнивается точный адрес 6945, другой рисователь с тем же индексом элемента не считается совпадением
                ;   операнд ItemIndex и первый байт Opcode перед проверкой не читаются, C9 отключает рисунок уже после успешного поиска
                ;   жёсткий порядок включений 0,1 обязателен, условный RET не исключает продолжения в соседний файл
                ; -----------------------------------------
                ; выбор точного адреса рисователя для поиска в текущем списке
Entry:          LD DE, @Station.DrawModelDescriptionPanel.Entry
                ; проверка наличия указателя, индекс элемента не сравнивается
                CALL @Station.TestDrawPointer.Entry
                RET NZ                                                          ; выход, если точного рисователя описания нет в текущем списке

                ; JP @Station.DrawModelDescriptionPanel.Entry, продолжение в DrawModelDescriptionPanel.asm

                endmodule
                endmodule
