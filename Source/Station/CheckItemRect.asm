                module Station
                module CheckItemRect
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [проверка геометрии и байтовое переполнение](../../Docs/ItemRect.md)
; -----------------------------------------
; Проверка неотрицательного начала, экранных границ и минимального размера элемента
; исходная запись 4, файловые смещения #46C4..#46E9
; In:
;   HL - индекс читаемой записи FInterfaceItem, первые четыре байта содержат X, Y, Width и Height
; Out:
;   HL - при отрицательном X указатель Y, при отрицательном Y указатель Width, иначе H=Height, L=Width
;   DE - E=X, D=Y после принятого X, при отрицательном X исходный D сохранён
;   BC сохранён, AF - Carry=1 только при X, Y<128, Width, Height>=4 и байтовых суммах X+Width<=32, Y+Height<=24
;   при отрицательной координате A=#F0, F=#90 OR (эта координата AND #28)
;   при выходе по правой либо нижней границе A равен соответствующей байтовой сумме, F от сравнения с 33 либо 25
;   при выходе по минимальной ширине A=Width, F от CP Width, 4 и CCF, иначе A=Height, F от CP Height, 4 и CCF
; Corrupt:
;   HL, DE, AF
; Note:
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   суммы координаты и размера вычисляются по модулю 256, Carry ADD перед CP не проверяется
;   поэтому некоторые размеры за пределами экранной области получают Carry=1, исходная особенность сохранена
;   Z не является признаком пригодности, например Height=4 при полном успехе оставляет Z=1
;   при CCF S, Z, PV остаются от CP, биты 5,3 берутся из A, H получает старый Carry, N сбрасывается
;   читаются поля записи без изменения таблицы, bitmap, карты владельцев и текстового окна
; -----------------------------------------
                ; выбор начала FInterfaceItem по нулевому смещению
Entry:          XOR A
                CALL @Station.GetItemField.Entry
                ; чтение исходного X в E перед проверкой знака
                LD E, (HL)
                INC HL
                ; проверка знака байтовой колонки элемента
                BIT 7, E
                RET NZ                                                          ; выход, если X отрицателен, Carry сброшен, HL уже указывает на Y

                ; чтение Y в D только после принятого X
                LD D, (HL)
                INC HL
                ; проверка знака байтовой строки элемента
                BIT 7, D
                RET NZ                                                          ; выход, если Y отрицателен, Carry сброшен, HL указывает на Width

                ; чтение Width и Height в младший и старший байты HL
                LD A, (HL)
                INC HL
                LD H, (HL)
                LD L, A
                ; расчёт правой границы по модулю 256, переполнение ADD не обрабатывается
                LD A, L
                ADD A, E
                ; проверка байтовой правой границы относительно 33
                CP @ItemRectLimit.EndColumn
                RET NC                                                          ; выход, если байтовая правая граница больше 32, Carry сброшен

                ; расчёт нижней границы по модулю 256 без проверки переполнения
                LD A, H
                ADD A, D
                ; проверка байтовой нижней границы относительно 25
                CP @ItemRectLimit.EndRow
                RET NC                                                          ; выход, если байтовая нижняя граница больше 24, Carry сброшен

                ; проверка минимальной ширины четыре знакоместа с инверсией Carry
                LD A, L
                CP @ItemRectLimit.MinSize
                CCF
                RET NC                                                          ; выход, если Width меньше четырёх, Carry после CCF сброшен

                ; проверка минимальной высоты четыре знакоместа, итоговый Carry сообщает о принятии
                LD A, H
                CP @ItemRectLimit.MinSize
                CCF
                RET

                endmodule
                endmodule
