; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [опрос, накопление и таблица направлений](../../Docs/PointerInputs.md)
; -----------------------------------------
; Условный опрос порта #001F с общим накоплением флагов и шагом указателя
; исходная запись 4, файловые смещения #08E4..#08EC
; In:
;   PointerXY содержит X=0..255,Y=0..191, шесть InputFlags доступны для чтения и записи
;   PointerInputState.Step=2, MaxY=191 и MaxX=255 подготовлены StartStation
;   таблица PointerDirections содержит исходные 16 указателей, код и CPU-стек доступны
;   JoyDisabled ненулевой запрещает опрос, ноль разрешает, порт #001F возвращает байт с нулевыми битами 6 и 7
; Out:
;   при запрете AF соответствует AND JoyDisabled, прочие регистры и память сохранены, порт не читается
;   BC - итоговые пиксельные X в C,Y в B, DE=#BF02, HL и AF рабочие
;   PointerXY обновлён выбранным шагом либо прежним BC при отсутствии движения
;   каждый из шести InputFlags получает старое значение OR соответствующий разряд текущей выборки
;   индексные и альтернативные регистры, I и IFF сохраняются, SP восстанавливается
; Corrupt:
;   при разрешённом опросе HL, DE, BC, AF, при запрете только AF
; Note:
;   общий договор накопления относится только к разрешённому опросу, IN A,(#1F) получает старший адрес 0 от A=0
;   байты действий участвуют в накоплении, но не в выборе одного из 16 направлений
;   противоположные направления по любой оси внутри текущей выборки выбирают NoPointerMotion и отменяют обе оси
;   выбор движения использует текущий A, ранее накопленные флаги не отменяют и не усиливают этот шаг
;   ApplyPointerInput кладёт CommitPointerInput поверх исходного адреса возврата и передаёт управление JP (HL)
;   RET обработчика направления выполняет CommitPointerInput, его RET возвращает исходному вызывающему коду
;   ClearInputFlags выполняется до обоих опросов в Interrupt, сами опросы накопленные флаги не очищают
;   последовательные опросы джойстика и клавиатуры каждый отдельно двигают указатель, одинаковое направление даёт два шага
;   модель задаёт показания портов, не исполняет IRQ и не проверяет реальное устройство
; -----------------------------------------
                ; чтение программного запрета джойстика до обращения к порту
Entry:          LD A, #00
                ; проверка запрета с сохранением остальных регистров на раннем выходе
                AND A
                RET NZ                                                          ; выход, если джойстик запрещён, не читать порт и не менять флаги ввода

                ; чтение текущей выборки с полного адреса #001F, A до IN равен нулю
                IN A, (#1F)
                JP @Station.ApplyPointerInput.Entry

                endmodule
                endmodule
