                module Station
                module PrintHelpLine
                ; Документация [банк 7, сохранение экранной страницы, счётчик строк и отключение переноса](../../Docs/StationHelpCalls.md)
                ; -----------------------------------------
                ; Межбанковая печать по индексу таблицы HELP с возвратом банка станции
                ; исходная запись 4, файловые смещения #0C7B..#0C88
                ; In:
                ;   HL содержит индекс 0..1023, таблица HELP подготовлена и выполняется договор Help.PrintIndexedLine
                ;   HELP находится в банке 7, Station доступна, CurrentPage соответствует порту и равен 10 либо 18
                ;   переключение банка не заблокировано, окно, глифы и стек удовлетворяют договору печатателя
                ; Out:
                ;   HL, DE, BC содержат результат Help.PrintIndexedLine, AF содержит A=исходная страница, F результата OR этого байта
                ;   HL', DE', BC', AF', IX, IY, I, IFF и IM сохранены, SP после RET равен входному+2
                ;   выбран банк 0, экранный бит сохранён, курсор и экран согласно печатателю, таблица не меняется
                ; Corrupt:
                ;   HL, DE, BC, AF, курсор, bitmap и изменяемые операнды фактически исполненного печатателя
                ; Note:
                ;   AF статуса печати заменён результатом последнего SelectRamBank, нулевой указатель также проходит два переключения
                ;   окно не настраивается здесь, входной Style остаётся ответственностью вызывающего кода
                ; -----------------------------------------
                ; выбор банка 7 перед чтением таблицы строк HELP
Entry:          LD A, #17
                CALL @Station.SelectRamBank.Entry
                ; печать строки по индексу HL, нулевой указатель возвращается без вывода
                CALL @Help.PrintIndexedLine.Entry
                ; возврат банка 0, статус AF печатателя заменяется флагами переключения
                LD A, #10
                CALL @Station.SelectRamBank.Entry
                RET

                endmodule
                endmodule
