;   HL, AF, HL', AF', bitmap, регистрация и текстовое окно по DrawCenteredItem
; Note:
;   обёртка содержит только исходные LD HL и JP, соседний вход удаления не является её продолжением
; -----------------------------------------
                ; чтение индекса элемента переключения второго списка перед общим центрированным рисунком
