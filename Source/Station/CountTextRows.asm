                module Station
                module CountTextRows
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [подсчёт и пропуск строк](../../Docs/TextPagination.md)
; -----------------------------------------
; Подсчёт сухих проходов выровненной строки до установленного Carry
; исходная запись 4, файловые смещения #482D..#4842
; In:
;   HL - текст с читаемым запасом просмотра слов, TextWindow задаёт ширину и высоту
;   для завершения каждый сухой проход должен продвигать текст до конечного LF либо иного Carry
; Out:
;   HL - позиция последнего SkipJustifyRow
;   DE - число вызовов SkipJustifyRow по модулю 65536, включая завершающий проход
;   BC - выходное состояние последнего SkipJustifyRow
;   AF - результат последнего SkipJustifyRow с установленным Carry
;   CursorX обнулён перед первым проходом, CursorY=8 задаётся перед каждым вызовом
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   D и E сухого прохода не влияют на счётчик, DE сохраняется вокруг каждого вызова
;   при Height<14 получается один проход и DE=1, текст не потребляется
;   после отказа ширины без принятого переноса HL и X могут перестать меняться, функция повторяет подсчёт без завершения
;   при Width=0 и Height>=14, либо слишком узкой строке и Height=14..16 возможен такой повтор
;   код не ограничивает число проходов и не проверяет переполнение DE
; -----------------------------------------
                ; создание нулевого счётчика сухих строк, исходный DE не используется
Entry:          LD DE, #0000
                ; сброс X только перед первым проходом подсчёта
                XOR A
                LD (@TextWindow.CursorX), A
                ; выбор одного и того же Y=8 для каждого сухого прохода
NextRow:        LD A, @ScreenConst.PixelsPerChar
                LD (@TextWindow.CursorY), A
                ; сохранение счётчика строк вокруг рабочего DE выравнивателя
                PUSH DE
                CALL @Station.SkipJustifyRow.Entry
                POP DE
                ; подсчёт очередного прохода, INC DE сохраняет Carry результата выравнивателя
                INC DE
                JP NC, @Station.CountTextRows.NextRow                           ; переход, если сухой проход не установил Carry, обработать следующую строку

                RET

                endmodule
                endmodule
