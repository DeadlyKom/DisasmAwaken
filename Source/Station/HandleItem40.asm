; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [обёртка наведения и отдельный вход действия меню](../../Docs/RowHover.md)
; -----------------------------------------
; Вход наведения контекстного меню с хвостовым переходом в HoverContextMenu
; исходная запись 4, файловые смещения #17E5..#17E7
; In:
;   IX - запись контекстного меню Item40, действуют договоры UpdatePixelHover и его графических вызовов
;   операнд PreviousRow по #757A доступен для записи, после DrawItem40 он равен #FF
;   PointerY=0..191, таблицы экрана и владельцев подготовлены, банк 0 выбран и не заблокирован
; Out:
;   HL, DE, BC, AF и AF' соответствуют UpdatePixelHover с HL=DrawItem40, D=64, E=3
;   при Z=0 A записан в операнд PreviousRow, при Z=1 прежний операнд сохранён
;   HL', DE', BC', IX, IY, I и IFF сохранены, SP восстановлен
; Corrupt:
;   HL, DE, BC, AF, AF'
; Note:
;   пиксельная область высотой 64 задаёт восемь строк с верхним отступом 3
;   самомодификация меняет только непосредственный байт LD A, код операции сохраняется
;   если повторная проверка попадания отвергнута, записывается высота 64, следующий вызов вращает её в смещение 2
;   подтверждённый моделью остаток полосы не является исправлением исходного алгоритма
;   Z=1 означает отсутствие обновления, нулевой номер строки при обновлении возвращается с Z=0
;   равенство проверяется по полному указателю обработчика, а не по номеру или флагам элемента
;   при прежнем A=#FF снятие старой полосы пропускается, иначе выполняется XorItemRow без проверки старого номера
;   после снятия указателя XorPointerRow заново читает PointerY, первое попадание и второе не атомарны
;   UpdateBlocked запрещает периодическое рисование указателя, но не опрос ввода обработчиком прерывания
;   при отказе второго попадания D сохраняет высоту, она возвращается как A с F=0, новый номер не получен
;   при втором попадании в другую строку выбирается именно вторая строка, хотя сравнение с прежней сделано по первой
;   ветви отсутствия обновления не снимают указатель и не меняют порт, фон либо UpdateBlocked
;   вызов ResumePointer допускает изменение AF' даже при сохранении всех прочих альтернативных регистров
; -----------------------------------------
                ; передача наведения исходной обёрткой, вход действия расположен по Entry+3
Entry:          JP @Station.HoverContextMenu.Entry

