                module Station
                module RestoreScrollPointer
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [обратное преобразование значений и самостоятельный стековый выход прокрутки](../../Docs/SettingsParser.md)
                ; -----------------------------------------
                ; Общий выход прокрутки со снятием сохранённых координат и восстановлением указателя
                ; исходная запись 4, файловые смещения #41CD..#41D5
                ; In:
                ;   HL, BC и AF - контекст, стек у FScrollExitFrame.SavedPointerXY, за ним расположен исходный ReturnAddress
                ;   SavedPointerXY содержит X в младшем байте, Y в старшем, Y=0..191, выполнен договор ResumePointer
                ;   указатель и таблицы владельцев допустимы, координаты могут временно отличаться от сохранённых
                ; Out:
                ;   HL, BC и AF сохранены, DE получает SavedPointerXY, PointerXY восстановлен этим словом
                ;   ResumePointer рисует указатель при восстановленном фоне и снимает UpdateBlocked, его эффекты и callback действуют по отдельному договору
                ;   HL', DE', BC', IX, IY сохраняются, AF' рабочий от указателя, I, IFF, IM и страницы собственный код не меняет
                ;   возврат использует следующее за SavedPointerXY слово, SP равен входному SP+4
                ; Corrupt:
                ;   DE, AF', состояние и рисунок указателя
                ; Note:
                ;   это не обычный вход CALL без подготовленного кадра, первое POP снимает координаты, а не адрес возврата
                ;   внешний переход из цикла прокрутки приходит сюда по исходному адресу A1CD
                ;   участок отделён от преобразователя настроек по существующей границе, все девять байтов сохранены
                ;   модель проверяет 1536 вариантов координат и страниц, неизвестные ветви самой прокрутки этим не объявляются разобранными
                ; -----------------------------------------
                ; снятие FScrollExitFrame.SavedPointerXY перед исходным адресом возврата
Entry:          POP DE
                ; восстановление исходной пары координат указателя из кадра прокрутки
                LD (@StationState.PointerXY), DE
                ; рисование указателя после возврата исходных координат и разрешение его обновления
                CALL @Station.ResumePointer.Entry
                RET

                endmodule
                endmodule
