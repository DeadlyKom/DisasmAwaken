; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [CellMap.md](../../Docs/CellMap.md)
; -----------------------------------------
; Получение адреса и байта владельца знакоместа по координатам строки и колонки
; исходная запись 4, файловые смещения #3DA6..#3DB9
; In:
;   BC - B строка знакомест, C байтовая колонка, для видимого экрана B=0..23 и C=0..31
; Out:
;   HL - адрес байта карты, A его содержимое, F соответствует ADD ((B AND 7)*32), C до чтения содержимого
;   для видимого экрана HL=StationState.DirtyCells+32*B+C
;   для произвольных байтов H=#86+((B SHR 3) AND 3), L=((B AND 7)*32+C) по модулю 256
; Corrupt:
;   HL, AF
; Note:
;   перенос сложения младшего байта не добавляется к H, старшие три бита B не участвуют в адресе
;   строки 24..31 обращаются к #8900..#89FF вне 768 видимых знакомест
;   LD A,(HL) не меняет флаги, поэтому выходной Z не является проверкой нулевого владельца
;   DE, BC, альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   байт владельца является кодом ссылки на индексную пару, не набором независимых флагов
; -----------------------------------------
                ; расчёт старшей страницы карты по битам 4 и 3 строки знакомест
Entry:          LD A, B
                AND #18
                RRA
                RRA
                RRA
                ADD A, @StationTables.CellMapPage
                LD H, A
                ; расчёт младшего строкового вклада, три младших бита строки задают группы по 32 байта
                LD A, B
                AND #07
                RRA
                RRA
                RRA
                RRA
                ; расчёт младшего байта адреса с колонкой без переноса в H
                ADD A, C
                LD L, A
                ; чтение кода владельца, выходные флаги остаются от адресного сложения
                LD A, (HL)
                RET

                endmodule
                endmodule
