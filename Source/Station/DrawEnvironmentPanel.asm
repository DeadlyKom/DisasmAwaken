                module Station
                module DrawEnvironmentPanel
                ; Документация [два CR-списка, общий хвост значений, полный индекс и счётчик обработанных полей](../../Docs/SettingsRowPanels.md)
                ; -----------------------------------------
                ; Рамка установок среды, сброс подсветки и сохранение числа обработанных значений
                ; исходная запись 4, файловые смещения #0E51..#0E69
                ; In:
                ;   EnvironmentPanelState.ItemIndex содержит индекс FInterfaceItem, штатно 41, либо Entry временно содержит C9
                ;   геометрия, шрифт, таблицы, стек и IRQ удовлетворяют DrawCaptionItem, TopRow и значения подготовлены
                ;   для обычного Entry выполняются договоры SetupEnvironmentText и PrintEnvironmentRows
                ; Out:
                ;   после рамки PanelHoverState.EnvironmentRow=FF, окно и колонка значений настроены, TopRow передан печатателю
                ;   HL, DE и BC принадлежат печатателю, основной AF содержит его альтернативный счётчик и флаги
                ;   AF' содержит основной результат печатателя, HL', DE', BC', IX и IY сохранены
                ;   EnvironmentPanelState.RowCount получает полный байт обработанных значений, включая последний отказ, TopRow не меняется
                ;   страница не переключается собственным кодом, I, IFF и IM сохраняются при договоре IRQ, SP после RET входному+2
                ;   RenderRows принимает HL от прокрутки, пропускает рамку, сброс подсветки, настройку и чтение TopRow, затем выполняет печать и запись RowCount
                ;   при временном C9 в Entry сохраняются регистры, флаги и память, SP после RET входному+2
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', окно, курсор, bitmap, номер подсветки, RowCount и изменяемые операнды помощников
                ; Note:
                ;   RowCount задаёт D обработчика наведения, число начатых значений не является числом успешно нарисованных строк
                ;   пробуждение HALT рамки требуется только для Entry, внутренний RenderRows нового HALT не выполняет
                ; -----------------------------------------
                ; чтение изменяемого индекса панели среды перед рисованием рамки
Entry:          LD HL, #0000
                ; рисование рамки и заголовка с подготовкой окна
                CALL @Station.DrawCaptionItem.Entry
                ; сброс прежней XOR-полосы, фон панели заменяется
                LD A, #FF
                LD (@PanelHoverState.EnvironmentRow), A
                ; выбор политики без переноса и колонки значений среды
                CALL @Station.SetupEnvironmentText.Entry
                ; чтение полного слова прокрутки панели среды
                LD HL, (@EnvironmentPanelState.TopRow)
                ; RenderRows принимает HL от прокрутки, рамка и настройка уже подготовлены
RenderRows:     CALL @Station.PrintEnvironmentRows.Entry
                ; получение альтернативного счётчика обработанных значений
                EX AF, AF'
                ; обновление байтового ограничения строк обработчика наведения
                LD (@EnvironmentPanelState.RowCount), A
                RET

                endmodule
                endmodule
