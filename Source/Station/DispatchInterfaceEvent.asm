                module Station
                module DispatchInterfaceEvent
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [новый и повторный ввод, выбранный индекс, подавление вызова и фоновые действия](../../Docs/EventDispatch.md)
; -----------------------------------------
; Выбор владельца события, удаление других всплывающих элементов и переход во вход действия обработчика
; исходная запись 4, файловые смещения #3DBA..#3E1E
; In:
;   AF - A входной байт события, Z=1 означает повтор прежнего кода, Z=0 новый код, Carry сохраняется в кодируемом контексте
;   PointerXY, карта владельцев и индексная страница доступны, станционный банк 0 выбран
;   штатный ненулевой владелец задаёт пару индекса 1..128, действительный индекс принадлежит FInterfaceItem
;   действуют договоры RemoveOtherPopups и PrepareContextMenu, список и обёртки имеют допустимые индексы
;   EventHandler записи содержит отдельный вход действия по адресу Handler+3, конечный обработчик соблюдает собственный договор
; Out:
;   при входном Z=1 к A добавляется бит #80 через OR, иначе A и F до сохранения не меняются
;   до каждого поиска PopupState.SkippedIndex=#FFF0, при действительном владельце он заменяется выбранным индексом
;   если EventEnabled после очистки равен нулю, HL=DE=выбранный индекс, IX и IY сохранены, AF восстановлен до DEC
;   при передаче событию HL=EventHandler+3, DE=выбранный индекс, IX адрес его FInterfaceItem, FlagsCache=Flags
;   при передаче A=кодированный байт-1 по модулю 256, F от DEC с сохранением Carry сохранённого AF, EventCode=A
;   BC перед конечным переходом соответствует RemoveOtherPopups, альтернативные регистры и IY до обработчика сохранены
;   после JP результат и память зависят от выбранного обработчика, собственного завершающего RET здесь нет
;   без владельца ненулевой Hidden снимается вместе с EventEnabled, код 1 открывает меню, код 2 очищает группу всплывающих элементов
;   прочий код без владельца возвращает A=кодированный байт-2, F от второго DEC, EventCode не меняется
;   SP восстановлен при прямом возврате либо сохранён для хвостового обработчика, I и IFF собственным кодом не меняются
; Corrupt:
;   HL, DE, BC, AF, IX до передачи, затем согласно договору выбранного обработчика
; Note:
;   сохранённый AF зависит от входного Z, после OR #80 Carry=0, при новом коде исходный Carry возвращается через DEC
;   исключение выбранного индекса запрещает RemoveOtherPopups удалить сам выбранный элемент даже при группе #20
;   удаление любого другого всплывающего элемента сбрасывает EventEnabled, поэтому текущий обработчик тогда не вызывается
;   нулевой владелец и пара с высоким байтом #FF используют один фоновый путь, ранней ошибки стека здесь нет
;   индексная адресация через RLCA при владельцах выше 128 меняет чётность смещения, такие коды не являются штатным договором
;   для фонового кода 1 PrepareContextMenu вызывается без предварительной RemoveOtherPopups
;   для фонового кода 2 после условного RET исполнение продолжается в RemoveOtherPopups.asm, нового CALL нет
;   повторные штатные коды 1..3 после OR #80 не совпадают с фоновыми командами 1 и 2
;   три INC HL при вычислении цели сохраняют оригинальный вход Handler+3, JP наведения по Handler не исполняется
;   FDispatchSelectedFrame описывает десять байтов на входе RemoveOtherPopups, включая его аппаратный возврат
;   модель останавливается перед конечным обработчиком, его игровой алгоритм ею не подтверждается
; -----------------------------------------
Entry:          JR NZ, @Station.DispatchInterfaceEvent.SaveEvent                ; переход, если входной код отличается от прежнего, сохранить новый код без бита повтора

                ; установка старшего бита повторного кода при равенстве входов
                OR @InterfaceEventConst.HeldMask
                ; выбор исходного исключения, пока действительный индекс владельца не найден
SaveEvent:      LD HL, @PopupConst.NoSelection
                ; обновление исключённого индекса для последующей очистки всплывающих элементов
                LD (@PopupState.SkippedIndex), HL
                ; сохранение кодированного события и флагов до поиска владельца
                PUSH AF
                ; поиск владельца ячейки по текущим пиксельным координатам указателя
                CALL @Station.GetPointerOwner.Entry
                ; проверка отсутствующего владельца по нулевому коду карты
                AND A
                JP Z, @Station.DispatchInterfaceEvent.NoOwner                   ; переход, если владелец равен нулю, обработать фоновое событие

                ; расчёт смещения индексной пары по коду владельца минус один
                DEC A
                ; удвоение вращением, штатный диапазон владельца не больше 128
                RLCA
                LD L, A
                ; выбор страницы индексных пар для чтения полного индекса
                LD H, #85
                LD A, (HL)
                INC L
                LD H, (HL)
                LD L, A
                ; проверка старшего байта индекса на #FF через увеличение
                INC H
                JP Z, @Station.DispatchInterfaceEvent.NoOwner                   ; переход, если индекс владельца недействителен, обработать фоновое событие

                ; восстановление старшего байта действительного индекса
                DEC H
                ; копирование выбранного индекса в сохраняемую пару DE
                LD D, H
                LD E, L
                ; исключение самого выбранного элемента из удаления всплывающей группы
                LD (@PopupState.SkippedIndex), HL
                ; создание SavedIndexHL в FDispatchSelectedFrame
                PUSH HL
                ; создание SavedIndexDE перед аппаратным ReturnCleanup
                PUSH DE
                ; удаление других элементов группы #20, оно может запретить текущее событие
                CALL @Station.RemoveOtherPopups.Entry
                ; восстановление обеих копий выбранного индекса после очистки
                POP DE
                POP HL
                ; чтение разрешения событий после возможного запроса перестроения
                LD A, (@InterfaceState.EventEnabled)
                ; проверка ненулевого EventEnabled до чтения обработчика
                OR A
                JR Z, @Station.DispatchInterfaceEvent.Suppressed                ; переход, если очистка либо прежнее состояние запрещает события, вернуть сохранённый AF

                ; выбор нулевого физического поля перед поиском начала FInterfaceItem
                XOR A
                ; поиск физической записи выбранного индекса
                CALL @Station.GetItemField.Entry
                ; передача физического начала записи в IX для обработчика действия
                PUSH HL
                POP IX
                ; переход к физическому Flags выбранной записи
                INC HL
                INC HL
                INC HL
                INC HL
                ; чтение исходных Flags для интерактивной геометрии
                LD A, (HL)
                ; обновление FlagsCache перед передачей события обработчику
                LD (@TrackState.FlagsCache), A
                ; переход от Flags к младшему байту EventHandler
                INC HL
                INC HL
                ; чтение полного адреса обработчика события из FInterfaceItem
                LD A, (HL)
                INC HL
                LD H, (HL)
                LD L, A
                ; расчёт отдельного входа действия Handler+3 после трёхбайтовой обёртки
                INC HL
                INC HL
                INC HL
                ; восстановление кодированного события и сохранённого Carry
                POP AF
                ; расчёт передаваемого селектора события вычитанием единицы по модулю 256
                DEC A
                ; обновление EventCode тем же байтом, который передаётся в A
                LD (@InterfaceState.EventCode), A
                JP (HL)

                ; восстановление сохранённого события без DEC на пути подавленного вызова
Suppressed:     POP AF
                RET

                ; чтение состояния скрытого интерфейса при фоновом событии
NoOwner:        LD A, (@MenuCommandState.Hidden)
                ; проверка необходимости снова разрешить рисователи на перестроении
                AND A
                JR Z, @Station.DispatchInterfaceEvent.BackgroundEvent           ; переход, если Hidden уже равен нулю, не менять запрос перестроения

                ; подготовка снятого Hidden и запроса полного перестроения
                XOR A
                ; снятие запрета EnableDrawList после события вне владельца
                LD (@MenuCommandState.Hidden), A
                ; запрос перестроения интерфейса после снятия Hidden
                LD (@InterfaceState.EventEnabled), A
                ; восстановление кодированного события для фоновых команд
BackgroundEvent:POP AF
                ; проверка исходного кодированного значения 1 через DEC
                DEC A
                JR Z, @Station.PrepareContextMenu.Entry                         ; переход, если код равен 1, подготовить меню с передаваемым A=0

                ; проверка исходного кодированного значения 2 вторым DEC
                DEC A
                RET NZ                                                          ; выход, если код отличается от 2, иначе продолжить очистку всплывающих элементов

                ; JP @Station.RemoveOtherPopups.Entry, продолжение в RemoveOtherPopups.asm

                endmodule
                endmodule
