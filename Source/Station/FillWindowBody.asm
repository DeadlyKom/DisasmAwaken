                module Station
                module FillWindowBody
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [иконка, внутреннее тело и заимствованный стек](../../Docs/WindowGraphics.md)
; -----------------------------------------
; Заливка внутреннего тела окна группами восьми строк через таблицу CPU-возвратов
; исходная запись 4, файловые смещения #405B..#40C3
; In:
;   TextWindow настроено SetupInsetTextWindow для элемента X>=0,Y>=0,Width=2..32,Height=4..24
;   элемент полностью помещается в 32x24 знакоместа, таблицы адресации подготовлены
;   WindowFillChain содержит исходные слова, обычный CPU-стек и код доступны для записи
;   прерывания запрещены либо обслуживаются станционным Interrupt с ремонтом таблицы возвратов
; Out:
;   заполнены Width-2 байта по горизонтали и 8*(Height-3) строк от знакоместа X+1,Y+2
;   бит 0 FillMode выбирает нулевой байт при 1 и #FF при 0, остальные разряды здесь не влияют
;   HL - вход выбранной длины FillBodyRow, DE - начало следующего знакоместа Y+Height-1,X+1
;   B=0, C - младший экранный адрес начала последнего обработанного знакоместа Y+Height-2,X+1
;   AF - результат последнего перехода знакоместа через E+32 либо D-8, AF' и остальные альтернативные регистры сохранены
;   SavedSP содержит адрес исходного возврата, FillByte выбранный байт, исходный SP восстанавливается перед RET
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   исходные размеры внутреннего окна равны 8*Width-4 и 8*Height-11, из них получаются Width-2 байта и Height-3 группы
;   HL=#A102-2*(TextWindow.Width>>3), допускает нулевую запись при ширине элемента 2
;   каждая группа устанавливает SP=#A104, выполняет восемь участков FillBodyRow через семь повторных LD C,E,JP (HL) и выход AfterGroup
;   каждый RET потребляет слово таблицы, обычный стек вызова сохранён в операнде SavedSP
;   IRQ может затереть одно слово аппаратным PUSH PC, Interrupt извлекает PC до ремонта таблицы и продолжает через JP
;   дополнительное девятое слово #A0B6 сохраняется и ремонтируется, обычный цикл восьми возвратов его не читает
;   нулевой байтовый счётчик групп в DJNZ означает 256 групп, входные размеры вне договора не исправляются
;   ширина с (Width>>3)=0 направила бы выполнение в область данных, такой вход договором исключён
;   индексные регистры, I и IFF собственным кодом сохраняются, повторный вход недопустим из-за общих операндов и таблицы
; -----------------------------------------
                ; расчёт начала тела окна, отступ Y=13 от внутреннего начала
Entry:          LD A, (@TextWindow.OriginYLow)
                ADD A, #0D
                LD L, A
                ; расчёт колонки тела окна, отступ X=5 от внутреннего начала
                LD A, (@TextWindow.OriginXLow)
                ADD A, #05
                LD E, A
                ; поиск экранного адреса начала тела по трём исходным таблицам
                LD H, #82
                LD D, (HL)
                INC H
                LD A, (HL)
                INC H
                LD L, E
                ADD A, (HL)
                LD E, A
                ; расчёт числа полных байтов внутренней ширины через три сдвига и маску
                LD A, (@TextWindow.Width)
                RRA
                RRA
                RRA
                AND #1F
                ; расчёт смещения входа развёрнутого ядра как 2*(31-(TextWindow.Width>>3))
                SUB #1F
                NEG
                ADD A, A
                LD C, A
                LD B, #00
                ; выбор входа записи строки по рассчитанному числу пропущенных пар
                LD HL, @Station.FillBodyRow.Entry
                ADD HL, BC
                ; расчёт числа восьмистрочных групп из внутренней высоты за вычетом 13 пикселей
                LD A, (@TextWindow.Height)
                SUB #0D
                RRA
                RRA
                RRA
                AND #1F
                LD B, A
                ; проверка разряда 0 FillMode для выбора нулевого либо сплошного заполнения
                LD A, (@StationRaster.FillMode)
                RRA
                LD A, #FF
                JR NC, @Station.FillWindowBody.SetFill                          ; переход, если бит 0 FillMode сброшен, сохранить байт заполнения #FF

                INC A
                ; обновление изменяемого байта заполнения перед заимствованием CPU-стека
SetFill:        LD (@WindowFillState.FillByte), A
                ; сохранение исходного адреса возврата в операнде LD SP
                LD (@WindowFillState.SavedSP), SP
                ; выбор начала исходной цепочки восьми возвратов для очередного знакоместа
CellRow:        LD SP, @WindowFillChain.State + FWindowReturnChain.Row1
                ; чтение выбранного байта заполнения из изменяемого операнда
                LD A, #FF
                ; сохранение младшего адреса строки перед косвенным входом выбранной длины
                LD C, E
                JP (HL)

                ; повторное сохранение младшего адреса для пиксельной строки 2 группы
Scan1:          LD C, E
                JP (HL)

                ; повторное сохранение младшего адреса для пиксельной строки 3 группы
Scan2:          LD C, E
                JP (HL)

                ; повторное сохранение младшего адреса для пиксельной строки 4 группы
Scan3:          LD C, E
                JP (HL)

                ; повторное сохранение младшего адреса для пиксельной строки 5 группы
Scan4:          LD C, E
                JP (HL)

                ; повторное сохранение младшего адреса для пиксельной строки 6 группы
Scan5:          LD C, E
                JP (HL)

                ; повторное сохранение младшего адреса для пиксельной строки 7 группы
Scan6:          LD C, E
                JP (HL)

                ; повторное сохранение младшего адреса для пиксельной строки 8 группы
Scan7:          LD C, E
                JP (HL)

                ; расчёт перехода к следующей строке знакомест после восьми RET ядра
AfterGroup:     LD A, E
                ADD A, #20
                LD E, A
                JR C, @Station.FillWindowBody.CountGroup                        ; переход, если E+32 дало перенос, не вычитать восемь из D

                ; расчёт коррекции D на минус восемь при переходе знакоместа без переноса E
                LD A, D
                SUB #08
                LD D, A
                ; расчёт оставшегося числа групп из восьми строк, начальный ноль означает 256 проходов
CountGroup:     DJNZ @Station.FillWindowBody.CellRow

                ; восстановление обычного CPU-стека после использования таблицы возвратов
RestoreSP:      LD SP, #0000
                RET

                endmodule
                endmodule
