                module Station
                module PrintDecodedMessage
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [два числовых селектора, точные строки, переносы и ранние выходы текста](../../Docs/DecodedMessage.md)
                ; -----------------------------------------
                ; Выбор и печать сообщения расшифровки по числовому полю MessageIndex предложения
                ; исходная запись 4, файловые смещения #1122..#112A
                ; In:
                ;   DE - сохраняемый контекст, BC - сохраняемый контекст, банк станции 0 и исходный LF-блок DecodedMessageText.Entry доступны
                ;   MissionOffer.Entry.MessageIndex=0 либо 1 задаёт одну из двух установленных строк, остальные значения не ограничиваются собственным кодом
                ;   действуют договоры PrintAfterLF и PrintText, TextWindow и шрифт подготовлены, поисковые и текстовые проходы завершаются по их условиям
                ; Out:
                ;   MessageIndex=0 печатает строку Расшифрована система:Дзета-43/78-Д, MessageIndex=1 предупреждение об иносигнале прошлых поколений
                ;   HL получает позицию продолжения текста по договору PrintAfterLF, DE и BC сохранены
                ;   AF соответствует PrintText, при потреблённом LF AF=0A4A, ранние отказы высоты и переноса сохраняют отдельные статусы
                ;   TextWindow.CursorX и CursorY соответствуют реально выполненной части текста, Style не меняется
                ;   MessageIndex и остальные поля FMissionOfferState не изменяются, paging не переключается
                ;   все альтернативные и индексные регистры, I и IFF сохраняются инструкциями печатателей, SP обычного возврата равен входному SP+2
                ; Corrupt:
                ;   HL, AF, курсор, bitmap и изменяемые операнды текстового и глифового рисователей
                ; Note:
                ;   MessageIndex является целым числовым индексом LF-строки, независимые флаги по разрядам здесь не установлены
                ;   генератор предложения записывает 0, исходный экземпляр имеет 1, CenterContractMap пишет 1 до проверки ROM
                ;   код не проверяет диапазон и не ограничивает значения 2..255, дополнительные сообщения им не приписываются
                ;   девять байтов содержат LD A, LD HL и хвостовой JP, самостоятельного адреса возврата для PrintAfterLF не создаётся
                ;   модель проверила 864 варианта окна и переноса с настоящими печатателями и независимой композицией bitmap, аппаратная игра не проверена
                ; -----------------------------------------
                ; чтение целого числового селектора, исходный ноль выбирает сообщение о системе, единица предупреждение об иносигнале
Entry:          LD A, (@MissionOffer.Entry.MessageIndex)
                ; выбор исходного блока с начальным LF перед двумя сообщениями
                LD HL, @DecodedMessageText.Entry
                ; передача селектора и таблицы в общий поиск LF с последующей печатью и тем же адресом возврата
                JP @Station.PrintAfterLF.Entry

                endmodule
                endmodule
