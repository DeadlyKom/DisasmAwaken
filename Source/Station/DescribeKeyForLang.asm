                module Station
                module DescribeKeyForLang
; Подробный разбор [возврат в банк языка](../../Docs/SignatureReturn.md)
; -----------------------------------------
; Характеристика входного ключа с возвратом банка языка 6
; In:
;   HL - FirstWord, DE - SecondWord, AF - A Variant=0..255, BC сохраняемый контекст
;   MAP загружен в банк 1, фиксированный станционный код и рабочий ключ доступны
;   тень CurrentPage согласована с аппаратным #7FFD, bit5 снят, стек вне сменяемого окна
;   возврат должен находиться в фиксированной памяти либо в банке LANG 6
; Out:
;   HL, DE, BC и основной AF имеют результат соответствующего DescribeCurrentKey либо DescribeKeyBanked
;   HL', DE', BC', IX, IY, I и IFF сохранены, SP восстановлен
;   AF' содержит страницу (входная CurrentPage AND #F8) OR #16 и флаги её OR
;   порт #7FFD и тень последовательно получают страницы с младшими битами 1, 0, 6 и принудительным ROM 1
; Corrupt:
;   HL, DE, AF, AF'
; Note:
;   входные старшие биты страницы сохраняются, исходный номер RAM-банка не восстанавливается
;   итоговый основной AF сохраняется через два EX AF вокруг третьего выбора страницы
;   точные признаки и формулы результата описаны в WorldSignature.md, алгоритм ядра не меняется
; -----------------------------------------
                ; получение исходной характеристики через DescribeKeyBanked, временный возврат в банк 0
Entry:          CALL @Station.DescribeKeyBanked.Entry
                ; сохранение основного AF результата перед выбором банка языка
                EX AF, AF'
                ; выбор банка LANG 6 с установленным ROM 1
                LD A, #16
                CALL @Station.SelectRamBank.Entry
                ; восстановление AF характеристики, результат выбора страницы остаётся в альтернативном AF
                EX AF, AF'
                RET

                endmodule
                endmodule
