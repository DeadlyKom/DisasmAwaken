                ; -----------------------------------------
                ; Передача события наведения пустому обработчику панели расшифровки
                ; исходная запись 4, файловые смещения #106E..#1070
                ; In:
                ;   SP у обычного двухбайтового адреса возврата, прочие регистры и флаги произвольны
                ; Out:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY сохранены без изменения флагов
                ;   PC получает слово со стека, SP равен входному SP+2, I, IFF, IM и страницы не меняются
                ; Corrupt:
                ;   нет изменений регистров общего назначения и памяти
                ; Note:
                ;   это именно вход наведения по адресу Event, соседний вход действия Event+3 имеет отдельный алгоритм
                ;   обёртка JP не создаёт дополнительного возврата, пустой RET не является продолжением действия
                ;   регистр R изменяется при выборке инструкций, равенство R не обещается
                ; -----------------------------------------
                ; передача наведения без нового адреса возврата, действие начинается отдельно по Entry+3
Entry:          JP @Station.ReturnDecodedMessageHover.Entry

