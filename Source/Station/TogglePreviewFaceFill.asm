                module Station
                module TogglePreviewFaceFill
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [доказанная связь заголовков граней с парой шаблонов и широковещательная запись](../../Docs/PreviewFaceFill.md)
                ; -----------------------------------------
                ; Переключение шаблона заполнения семи четырёхугольных и шести треугольных граней по двум опорным заголовкам
                ; исходная запись 4, файловые смещения #0610..#0641
                ; In:
                ;   подключён D3D в банке 4, заголовки граней PreviewFaceHeaders доступны для чтения и записи
                ;   Quad0 и Triangle0 являются двумя опорными байтами, допустимые игровые заголовки имеют ненулевой счётчик в младшей тетраде
                ; Out:
                ;   HL, DE и BC сохранены, AF - A исходный Triangle0 XOR 60, F от логического XOR этого значения
                ;   все семь Quad получают исходный Quad0 XOR 60, все шесть Triangle получают исходный Triangle0 XOR 60
                ;   альтернативные и индексные регистры, I, IFF и IM сохранены, SP обычного возврата равен входному SP+2
                ; Corrupt:
                ;   AF
                ; Note:
                ;   это широковещательная запись двух вычисленных значений, а не индивидуальный XOR каждого заголовка
                ;   в исходных опорных байтах 24 и 23 маска 60 переключает индекс заполнения 2 и 4, число вершин остаётся 4 и 3
                ;   исходные Quad6=14, Triangle1=13 и Triangle2=13 имеют другой индекс, первый вызов заменяет их значением своей опорной группы
                ;   грани читаются DBE9 и DD4F, положительный заголовок даёт счётчик AND 0F и индекс шаблона через четыре RRCA и AND 07
                ;   индекс из C23B выбирает пару байтов D100+2*индекс, общий смысл прочих типов записей с bit7=1 ещё не установлен
                ;   в этом входе нет экранного рисования, переключения банка или EI, включение IFF в вызывающем E07F является отдельным действием
                ; -----------------------------------------
                ; -----------------------------------------
                ; Общий шаблон четырёхугольных граней
                ; -----------------------------------------
                ; чтение опорного заголовка, его младшая тетрада в исходнике равна четырём
Entry:          LD A, (@PreviewFaceHeaders.Quad0)
                ; переключение двух разрядов индекса заполнения между исходными вариантами 2 и 4
                XOR @PreviewFaceConst.FillToggleMask
                ; распространение вычисленного заголовка на все семь выбранных четырёхугольников
                LD (@PreviewFaceHeaders.Quad1), A
                LD (@PreviewFaceHeaders.Quad2), A
                LD (@PreviewFaceHeaders.Quad3), A
                LD (@PreviewFaceHeaders.Quad0), A
                LD (@PreviewFaceHeaders.Quad4), A
                LD (@PreviewFaceHeaders.Quad5), A
                LD (@PreviewFaceHeaders.Quad6), A
                ; -----------------------------------------
                ; Общий шаблон треугольных граней
                ; -----------------------------------------
                ; чтение второго опорного заголовка, его младшая тетрада равна трём
                LD A, (@PreviewFaceHeaders.Triangle0)
                ; переключение индекса заполнения треугольников той же маской
                XOR @PreviewFaceConst.FillToggleMask
                ; распространение одного вычисленного заголовка на шесть треугольников
                LD (@PreviewFaceHeaders.Triangle1), A
                LD (@PreviewFaceHeaders.Triangle2), A
                LD (@PreviewFaceHeaders.Triangle0), A
                LD (@PreviewFaceHeaders.Triangle3), A
                LD (@PreviewFaceHeaders.Triangle4), A
                LD (@PreviewFaceHeaders.Triangle5), A
                RET

                ; -----------------------------------------
                endmodule
                endmodule
