                module Station
                module SelectSaleMode
                ; Документация [исходные кнопки продажи и покупки, FF собственного типа, банк 4 и общий вход](../../Docs/ModelTradeMode.md)
                ; -----------------------------------------
                ; Выбор продажи собственного корабля либо скимера с возвратом к покупке при типе FF
                ; исходная запись 4, файловые смещения #1CD0..#1D00
                ; In:
                ;   DE содержит индекс выбранной новой кнопки, штатно 28, HL входа отдельного параметра не задаёт
                ;   BC сохраняемый контекст, AF содержит Carry запрета действия, при Carry=1 других условий не требуется
                ;   при Carry=0 банк станции 0 выбран, CurrentPage=10 либо 18, реальные переключения банка не заблокированы
                ;   D3D загружен в банк 4, RowOperand доступен, обе записи кнопок удовлетворяют SwitchItemContour и DrawCenteredItem
                ;   Selector и текущие собственные типы доступны, допустимость последующего 3D-показа обеспечивает вызывающий код
                ; Out:
                ;   при входном Carry=1 сохранены все регистры, флаги, память, страницы и порты, SP после RET входному+2
                ;   при Carry=0 RowOperand банка 4=0, PendingRedraw=1, банк возвращён в 0 с сохранением экранного бита
                ;   Selector=0 читает CurrentModels.ShipIndex, любое ненулевое значение читает SkimmerIndex, FF принудительно выбирает покупку
                ;   при типе не FF OwnedMode=1, старый индекс берётся из DrawItemState.Index29, новый из входного DE, при FF старый Index28 и новый Index29
                ;   HL и DE содержат индекс новой кнопки, BC сохранён, AF содержит A=C3 и F последнего текстового прохода SwitchItemContour
                ;   H', DE', BC', IX, IY, I, IFF и IM сохранены, L' и AF' рабочие по SwitchItemContour
                ;   у старой кнопки сброшен только Flags.bit0, у новой установлен, обе рамки перерисованы, UpdateBlocked=0
                ;   SP обычного возврата входному+2, собственного немедленного 3D-кадра нет, запрос обслужит последующий периодический проход
                ; Corrupt:
                ;   HL, DE, AF, L', AF', RowOperand банка 4, PendingRedraw, OwnedMode, Flags двух кнопок, bitmap, курсор и карта владельцев
                ; Note:
                ;   OwnedMode является целым режимом, здесь записываются только 0 покупки либо 1 продажи, независимые флаговые биты не вводятся
                ;   SelectRamBank объединяет весь аргумент со старшими битами тени, страницы 10/18 переходят в 14/1C и обратно
                ;   договоры указателя и центрируемых элементов сохраняются, модель не объявляет независимый oracle всего итогового bitmap
                ; -----------------------------------------
                ; проверка Carry общего обработчика кнопки до любых изменений режима
Entry:          RET C                                                           ; выход, если входной Carry установлен, действие запрещено

                ; выбор реального банка 4 перед сбросом существующего операнда номера модели
                LD A, @ShipPreviewConst.PreviewPage
                CALL @Station.SelectRamBank.Entry
                ; обновление строки будущего просмотра нулём, это байт кода D3D банка 4
                XOR A
                LD (@D3DPreviewState.RowOperand), A
                ; возврат банка станции 0 с сохранением бита экранной страницы
                LD A, @StationIrqConst.StationPage
                CALL @Station.SelectRamBank.Entry
                ; установка отложенного запроса, 3D-кадр здесь не исполняется
                LD A, #01
                LD (@ShipPanelState.PendingRedraw), A
                ; проверка полного селектора, ноль относится к собственному кораблю, прочие байты к скимеру
                LD A, (@ShipPanelState.Selector)
                OR A
                LD A, (@CurrentModels.ShipIndex)
                JR Z, @Station.SelectSaleMode.CheckOwnedType                    ; переход, если Selector равен нулю, проверить прочитанный ShipIndex

                ; чтение собственного скимера для любого ненулевого Selector
                LD A, (@CurrentModels.SkimmerIndex)
                ; проверка FF собственного типа через исходный байтовый INC
CheckOwnedType: INC A
                ; сохранение входного нового индекса и чтение ключа кнопки покупки
                EX DE, HL
                LD DE, (@DrawItemState.Index29)
                JR Z, @Station.SelectPurchaseMode.ApplyMode                     ; переход, если собственный тип равен FF, выбрать покупку через общий хвост

                ; обновление полного байта режима, единица выбирает продажу собственного объекта
                LD A, #01
                LD (@ShipPanelState.OwnedMode), A
                ; подготовка старой кнопки покупки и входного нового индекса продажи
                EX DE, HL
                JP @Station.SwitchItemContour.Entry

                endmodule
                endmodule
