                module Station
                module HandleSaveSlotAction
                ; Документация [точный протокол DOS, два разных кадра, I, IM, IFF, отсутствие проверки ошибки и физический ключ](../../Docs/SaveSlots.md)
                ; -----------------------------------------
                ; Выбор позиции и запись двух секторов блока состояния в существующий SAVE-файл
                ; исходная запись 4, файловые смещения #16CD..#172D
                ; In:
                ;   HL запасной рисователь позиции, DE индекс элемента 43 записи либо 44 чтения, BC контекст, AF полный селектор
                ;   действуют договоры RepaintAndFlag, CloseMenuOnRow и DropItemDraw, исходный список и хвосты сдвига доступны
                ;   для селектора 1 PanelHoverState.ToPositionRow содержит выбранный байт, существующий ключ SAVE и системная область DOS доступны
                ;   TR-DOS возвращается штатным CPU-возвратом, не меняет кадр, его договоры сохраняют доступность кода, стека и выбранного банка
                ;   системная длина ключа поиска DOS подготовлена на девять байтов, после поиска допустимого файла C задаёт индекс записи
                ;   команда 08 выдаёт FTrDosEntry в Descriptor, первые два сектора существуют
                ;   блок 983B..9A3A и изменяемый операнд восстановления I доступны, IY во время DOS указывает на системные переменные 5C3A
                ; Out:
                ;   при Carry от RepaintAndFlag немедленно возвращён его результат, при селекторе не 1 вызван только CloseMenuOnRow
                ;   при выборе FileDigit=(выбранный байт+30) AND FF, имя и тип скопированы девятью байтами в TrDosState.Descriptor
                ;   последовательно вызваны команды 0A поиска, 08 дескриптора и 06 записи, последний вызов получает HL=983B, B=2, DE=FirstTrack:FirstSector
                ;   при штатной записи два сектора получают прежние 512 байтов блока, создание нового файла не выполняется
                ;   DE и IY восстановлены из кадра TransferState, HL сохранён от входа TransferState
                ;   BC, IX и альтернативные пары имеют результаты DOS и сохраняются DropItemDraw, отдельного сохранения этих регистров нет
                ;   I восстановлен до значения в начале TransferState, IM принудительно равен 2, IFF не восстанавливается и зависит от DOS
                ;   текущий элемент удалён по сохранённому DE, при найденном ключе EventEnabled=0, A содержит выбранный байт, F соответствует DropItemDraw
                ;   при найденном удалении F=44, SP обычного возврата входному+2, явных OUT и самостоятельного нового рисунка после переноса нет
                ; Corrupt:
                ;   HL, BC, AF, HL', DE', BC', AF', IX по DOS, IFF, IM, имя, дескриптор DOS, сохранённый I, список и EventEnabled, содержимое существующих секторов при настоящем DOS
                ; Note:
                ;   TransferState является внутренним входом без RepaintAndFlag и проверки селектора, DE и IY задают сохраняемый контекст
                ;   до DOS исполняются DI, I=3F и IM 1, исходный режим IM не сохраняется, EI после возврата отсутствует
                ;   сохранённый AF содержит A=3F и флаги LD A,I, это не сохранение исходного AF и не восстановление IFF
                ;   код не проверяет FF поиска, передаёт его в A команды 08, ошибки дескриптора и переноса тоже не проверяются
                ;   выбранный FF не отвергается, арифметика даёт символ 2F вместо цифры, допустимость позиции задаёт вызывающее окружение
                ;   модель подменяет 3D13 явными договорами и переносит сектора только в памяти, настоящая ROM, контроллер и дисковая запись не исполнялись
                ; -----------------------------------------
                ; обновление общей геометрии и порядка списка до обработки выбора позиции
Entry:          CALL @Station.RepaintAndFlag.Entry
                RET C                                                           ; выход, если общий обработчик вернул Carry, запись позиции не разрешена

                ; проверка селектора 1 для записи состояния
                DEC A
                JP Z, @Station.HandleSaveSlotAction.TransferState               ; переход, если селектор равен 1, выполнить протокол записи

                ; удаление панели только при совпадении символьных строк указателя и окна
                CALL @Station.CloseMenuOnRow.Entry
                RET Z                                                           ; выход, если символьные строки совпали, помощник закрытия уже завершён

                RET

                ; сохранение текущего I в существующий операнд восстановления записи
TransferState:  LD A, I
                LD (@SaveSlotState.SaveI), A
                ; выбор ROM-совместимого режима, IFF запрещается, I=3F, IM 1
                DI
                LD A, @SaveSlotConst.RomI
                LD I, A
                IM 1
                ; создание FSaveSlotFrame, порядок IY, HL, AF, DE оставляет SavedDE на вершине
                PUSH IY
                PUSH HL
                PUSH AF
                PUSH DE
                ; выбор системных переменных Spectrum для вызовов TR-DOS
                LD IY, @LoaderConst.SystemIY
                ; расчёт символа номера файла по полному байту наведения без проверки FF
                LD A, (@PanelHoverState.ToPositionRow)
                ADD A, @NumberConst.DigitZero
                ; обновление пятого символа физического имени SAVE
                LD HL, @SaveSlotState.FileDigit
                LD (HL), A
                ; копирование реального FTrDosFileKey в буфер запроса DOS без терминатора
                LD HL, @SaveSlotFileName.Entry
                LD DE, @TrDosState.Descriptor
                LD BC, FTrDosFileKey
                LDIR
                ; поиск существующей записи по имени и типу, результат C далее не проверяется
                LD C, @TrDos.FindFile
                CALL @TrDos.Dispatch
                ; чтение дескриптора по возвращённому C, исходник передаёт также ошибочный FF
                LD A, C
                LD C, @TrDos.ReadCatalog
                CALL @TrDos.Dispatch
                ; подготовка 512-байтового блока, адрес первых секторов берётся из дескриптора
                LD HL, @SaveSlotState.Buffer
                LD DE, (@TrDosState.Descriptor + FTrDosEntry.FirstSector)
                ; выбор ровно двух секторов для записи, длина записи не читается из каталога
                LD B, @SaveSlotConst.SectorCount
                LD C, @TrDos.WriteSectors
                CALL @TrDos.Dispatch
                ; восстановление исходного I и принудительный IM 2 до снятия кадра
RestoreContext: LD A, #00
                LD I, A
                IM 2
                ; снятие FSaveSlotFrame в порядке DE, AF, HL, IY
                POP DE
                POP AF
                POP HL
                POP IY
                ; удаление текущей панели после возврата DOS, статус записи не проверяется
                CALL @Station.DropItemDraw.Entry
                ; возврат исходного выбранного байта с флагами удаления панели
                LD A, (@PanelHoverState.ToPositionRow)
                RET

                endmodule
                endmodule
