                module Station
                module ReadMouseMotion
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [настройка кнопок и аппаратные счётчики](../../Docs/MouseInput.md)
; -----------------------------------------
; Разности двух аппаратных счётчиков, удвоение шага и одностороннее насыщение координат
; исходная запись 4, файловые смещения #0884..#08E3
; In:
;   IX - база MouseInput.State, на стеке FMousePollFrame.SavedIX и ReturnAddress
;   байты PreviousX,PreviousY содержат прежние показания, PointerXY содержит исходные пиксельные координаты
; Out:
;   HL - итоговые пиксельные X в L и Y в H, DE - прежние аппаратные счётчики X в E и Y в D, BC=#FFDF
;   AF - рабочий результат последней ветви Y, единого флага наличия движения нет
;   StationState.PointerXY и PreviousX,PreviousY обновлены, ненулевые разности устанавливают соответствующий байт направления в 1
;   IX восстановлен из FMousePollFrame, IY, альтернативные регистры, I и IFF сохраняются, SP возвращается за адрес вызова
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   разность X равна signed8(newX-oldX), разность Y равна signed8(-(newY-oldY)), каждая умножается на два
;   при отрицательной разности применяется max(0,old+2*delta), при положительной min(limit,old+2*delta)
;   limit равен 254 для X и 191 для Y, нулевая разность не нормализует исходную координату
;   отрицательная ветвь не ограничивает сверху, при исходном Y>191 результат может остаться вне экрана
;   байты направлений не очищаются этим продолжением, полный PollMouse очищает семь флагов до чтения портов
;   чтение Y выполняется даже при нулевой разности X, старые оба счётчика загружаются до первого чтения
;   модель задаёт байты трёх портов, реальное устройство и вызов из ISR не проверены
; -----------------------------------------
                ; чтение исходных пиксельных координат и двух прежних аппаратных счётчиков
Entry:          LD HL, (#6307)
                LD DE, (@MouseInput.State + FMouseInput.PreviousX)
                LD BC, @MouseConst.XPort
                IN A, (C)
                LD (@MouseInput.State + FMouseInput.PreviousX), A
                ; расчёт байтовой разности нового и прежнего X, знак определяет направление
                SUB E
                JR Z, @Station.ReadMouseMotion.ReadY                            ; переход, если счётчик X не изменился, оставить X и читать Y

                JP P, @Station.ReadMouseMotion.PositiveX                        ; переход, если знаковая разность X неотрицательная, выполнить положительный шаг

                ; установка направления влево независимо от достижения границы
                LD (IX + FMouseInput.Left), #01
                ; расчёт удвоенного отрицательного шага X и его суммы с исходной координатой
                ADD A, A
                ADD A, L
                JR C, @Station.ReadMouseMotion.StoreX                           ; переход, если сложение дало перенос, сохранить ненулевой остаток X после отрицательного шага

                XOR A
StoreX:         LD L, A
                JR @Station.ReadMouseMotion.ReadY

                ; расчёт удвоенного положительного шага X и суммы с исходной координатой
PositiveX:      ADD A, A
                ADD A, L
                ; установка направления вправо независимо от насыщения X
                LD (IX + FMouseInput.Right), #01
                JR C, @Station.ReadMouseMotion.MaxX                             ; переход, если положительный шаг X переполнил байт, ограничить X значением 254

                ; проверка верхнего предела X после сложения без переполнения
                CP @MouseConst.MaxX
                JR C, @Station.ReadMouseMotion.SetX                             ; переход, если новый X меньше 254, сохранить вычисленный X

MaxX:           LD A, @MouseConst.MaxX
SetX:           LD L, A
                ; выбор порта счётчика Y с сохранением младшего номера порта DF
ReadY:          LD B, #FF
                IN A, (C)
                LD (#658D), A
                ; расчёт разности счётчика Y перед инверсией направления
                SUB D
                JR Z, @Station.ReadMouseMotion.StoreXY                          ; переход, если счётчик Y не изменился, сохранить координаты без нормализации

                ; инверсия байтовой разности Y, движение счётчика и экранная ось направлены противоположно
                NEG
                JP P, @Station.ReadMouseMotion.PositiveY                        ; переход, если инвертированная разность Y неотрицательная, выполнить положительный шаг

                ; установка направления вверх независимо от достижения нуля
                LD (IX + FMouseInput.Up), #01
                ; расчёт удвоенного отрицательного шага Y и суммы с исходным Y
                ADD A, A
                ADD A, H
                JR C, @Station.ReadMouseMotion.StoreY                           ; переход, если сумма дала перенос, сохранить остаток Y после отрицательного шага

                XOR A
StoreY:         LD H, A
                JR @Station.ReadMouseMotion.StoreXY

                ; расчёт удвоенного положительного шага Y и суммы с исходным Y
PositiveY:      ADD A, A
                ADD A, H
                ; установка направления вниз независимо от насыщения Y
                LD (IX + FMouseInput.Down), #01
                JR C, @Station.ReadMouseMotion.MaxY                             ; переход, если положительный шаг Y переполнил байт, ограничить Y значением 191

                ; проверка последней экранной строки после положительного шага Y
                CP @MouseConst.MaxY
                JR C, @Station.ReadMouseMotion.SetY                             ; переход, если новый Y меньше 191, сохранить вычисленный Y

MaxY:           LD A, @MouseConst.MaxY
SetY:           LD H, A
                ; обновление пары пиксельных координат после обоих аппаратных чтений
StoreXY:        LD (#6307), HL
                ; снятие FMousePollFrame.SavedIX перед возвратом исходному вызывающему коду
                POP IX
                RET

                endmodule
                endmodule
