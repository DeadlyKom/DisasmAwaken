                module Station
                module DescribeKeyBanked
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [точная формула ключа и банковый договор](../../Docs/WorldSignature.md)
; -----------------------------------------
; Характеристика числового ключа через банк 1 с сохранением AF результата
; исходная запись 4, файловые смещения #446E..#447F
; In:
;   HL - FirstWord, DE - SecondWord, AF - A Variant=0..255, BC сохраняемый контекст
;   MAP загружен в банк 1, фиксированный станционный код и рабочий ключ доступны
;   тень CurrentPage согласована с аппаратным #7FFD, bit5 снят, стек вне сменяемого окна
;   возврат исполняется в фиксированной памяти либо в возвращаемом станционном банке 0
; Out:
;   HL - H код 0..3 внутри трёх областей либо 4 вне них, L числовой признак 1..16
;   DE - D код геометрической области 0..3, E младший двухбитовый признак 0..3, BC сохранён
;   AF - A=max((((FirstWord.high XOR FirstWord.low XOR SecondWord.high XOR SecondWord.low) AND 7)-1),0)
;   если XOR AND 7 равен 0, F=#44, если 1, F=#42, иначе F=#02, Z означает A=0
;   рабочий FSignatureKey по #631C содержит состояние после Variant+1 шагов
;   HL', DE', BC', IX, IY, I и IFF сохранены, SP восстановлен
;   AF' - страница (входная CurrentPage AND #F8) OR #10 и F от её OR, AF результата сохранён
;   порт и тень выбирают сначала (старое AND #F8) OR #11, затем (старое AND #F8) OR #10
; Corrupt:
;   HL, DE, AF, AF'
; Note:
;   старшие биты дисплея сохраняются, ROM 1 устанавливается принудительно, исходный номер банка не восстанавливается
;   результат AF ядра сохраняется в AF' вокруг второго переключения, затем возвращается основным AF
; -----------------------------------------
                ; сохранение входных A и F в альтернативном AF перед переключением
Entry:          EX AF, AF'
                ; выбор банка 1 с MAP и принудительного ROM 1
                LD A, #11
                CALL @Station.SelectRamBank.Entry
                ; восстановление входного Variant после записи порта
                EX AF, AF'
                ; получение числовой характеристики настоящим кодом MAP в банке 1
                CALL @Map.DescribeKey.Entry
                ; сохранение итоговых A и F вокруг возврата станционного банка
                EX AF, AF'
                ; возврат банка 0 без восстановления произвольного исходного номера
                LD A, #10
                CALL @Station.SelectRamBank.Entry
                ; возврат AF характеристики, результат выбора страницы остаётся в AF'
                EX AF, AF'
                RET

                endmodule
                endmodule
