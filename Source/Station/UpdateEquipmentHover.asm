                module Station
                module UpdateEquipmentHover
                ; Документация [Station](../../Docs/FunctionDetails/Station.md)
                ; Подробный разбор [точные ограничения, изменяемые строки и различие пиксельного и строчного входов](../../Docs/PanelHover.md)
                ; -----------------------------------------
                ; Обновление XOR-полосы оснащения корабля с сохранением номера только по Z=0
                ; исходная запись 4, файловые смещения #14BC..#14CB
                ; In:
                ;   IX - допустимая FInterfaceItem оснащения корабля, подготовлены указатель, шрифт, таблицы адресации и банковое XOR-ядро
                ;   список рисования непуст и завершается исходным маркером, PointerY=0..191, выбран станционный банк 0
                ;   ScriptSelection.EquipmentRow содержит прежний номер либо FF, его операнд доступен для записи
                ;   действуют договоры UpdateRowHover, XorItemRow, XorPointerRow, SuspendPointer и ResumePointer
                ; Out:
                ;   перед UpdateRowHover установлены HL=DrawEquipmentList.Entry, DE с младшим отступом 1B и старшим EquipmentListState.RowCount, A прежний номер
                ;   D равен текущему EquipmentListState.RowCount, исходно 30, E=27 пикселей, фактическую байтовую высоту рассчитывает ClampRowHeight
                ;   при Z=1 возвращённого UpdateRowHover сохранённый номер не меняется, выходные регистры принадлежат соответствующей ветви отказа или совпадения
                ;   при Z=0 весь возвращённый A записан в ScriptSelection.EquipmentRow, даже если A=0 либо повторная проверка вернула высоту
                ;   HL, DE, BC и AF принадлежат UpdateRowHover, HL', DE', BC', IX, IY сохраняются, AF' рабочий только на обновлении указателя
                ;   при соблюдении договоров SP обычного возврата равен входному SP+2, I, IFF и IM не меняются
                ; Corrupt:
                ;   HL, DE, BC, AF, AF' на изменении полосы и указателя
                ; Note:
                ;   обновление допускается лишь для точного адреса рисователя в последнем слове списка
                ;   Z показывает отсутствие обновления, он не равнозначен нулю A
                ;   две проверки PointerY не атомарны, обёртка не исправляет служебный результат позднего отказа
                ;   рисователь сбрасывает свой операнд строки в FF после замены фона, эта обёртка сама фон панели не рисует
                ;   названия списков взяты из исходных заголовков и текстов, назначение действий их строк этим контрактом не устанавливается
                ;   DrawEquipmentList записывает счётчик попыток с маркером 80 в старший операнд 7212, после отказа заголовка он равен нулю
                ; -----------------------------------------
                ; выбор отступа 27 пикселей и текущего EquipmentListState.RowCount, исходно 30
Entry:          LD DE, @PanelHoverConst.IndentedRows
                ; выбор точного рисователя, который должен быть последним в списке
                LD HL, @Station.DrawEquipmentList.Entry
                ; чтение изменяемого номера прежней XOR-полосы, FF означает её отсутствие
                LD A, #FF
                ; проверка положения указателя и обновление полосы через UpdateRowHover
                CALL @Station.UpdateRowHover.Entry
                RET Z                                                           ; выход, если UpdateRowHover вернул Z=1, сохранить прежний номер

                ; сохранение полного результата A только по Z=0, нулевая строка тоже допустима
                LD (@ScriptSelection.EquipmentRow), A
                RET

                endmodule
                endmodule
