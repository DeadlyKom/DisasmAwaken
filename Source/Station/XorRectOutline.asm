                module Station
                module XorRectOutline
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [временный XOR-контур](../../Docs/XorOutline.md)
; -----------------------------------------
; Обратимое рисование четырёх граней временного прямоугольника с отсечением
; исходная запись 4, файловые смещения #64BE..#6565
; In:
;   DE - D высота 1..24, E ширина 1..32 в знакоместах, BC - знаковые B строка и C колонка
;   прямоугольник имеет непустое пересечение с экраном, таблицы #82,#83,#84 построены
;   основной экран и собственные изменяемые операнды доступны для записи
; Out:
;   HL - адрес нижней видимой пиксельной строки в первой видимой колонке, DE и BC сохранены
;   при исходной нижней грани за экраном AF=#0042
;   иначе A - последний инвертированный байт нижней грани, F=#12 OR (A AND #28), дополнительно S=бит 7 его младшего адреса при видимой ширине больше одного
;   четыре видимые исходные грани инвертированы, отсекаемые стороны не рисуются
; Corrupt:
;   HL, AF
; Note:
;   все альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
;   верхняя и нижняя грани инвертируют байт целиком, левая использует #80, правая #01
;   в углах операции накладываются, крайний угловой пиксель инвертирован дважды и сохраняется
;   повторный вызов с той же геометрией восстанавливает исходные пиксели без буфера фона
;   FOutlineFrame хранит SavedDEAlt, SavedDE, SavedBC, ReturnAddress, временные DE' описывают отсечение
;   отсечение не создаёт новых границ на краю экрана, рисуются только попавшие в экран части исходных граней
;   пустые пересечения, нулевые размеры и размеры больше экрана не входят в подтверждённый договор
;   HorizontalSkip и VerticalMask самоподменяются, итоговая VerticalMask равна #01
; -----------------------------------------
                ; сохранение BC, DE и альтернативного DE в динамическом FOutlineFrame
Entry:          PUSH BC
                PUSH DE
                EXX
                PUSH DE
                ; обнуление временных признаков отсечения, DE' хранит -1 для левой или верхней и +1 для правой или нижней грани
                LD DE, #0000
                EXX
                ; проверка знаковой колонки исходного прямоугольника
                LD A, C
                AND A
                JP P, @Station.XorRectOutline.ClipTop                           ; переход, если колонка неотрицательна, левую границу отсекать не нужно

                ; расчёт видимой ширины при отрицательной колонке, левая грань отмечается скрытой
                ADD A, E
                LD E, A
                EXX
                LD E, #FF
                EXX
                LD C, #00
                ; проверка знаковой строки исходного прямоугольника
ClipTop:        LD A, B
                AND A
                JP P, @Station.XorRectOutline.ClipRight                         ; переход, если строка неотрицательна, верхнюю границу отсекать не нужно

                ; расчёт видимой высоты при отрицательной строке, верхняя грань отмечается скрытой
                ADD A, D
                LD D, A
                EXX
                LD D, #FF
                EXX
                LD B, #00
                ; расчёт колонки за прямоугольником для проверки правого края
ClipRight:      LD A, C
                ADD A, E
                ; проверка выхода правой границы за колонку 32
                CP #21
                JP C, @Station.XorRectOutline.ClipBottom                        ; переход, если правая граница не выходит за экран, ширину сохранить

                ; вычитание правого избытка из ширины и пометка скрытой правой грани
                SUB #20
                NEG
                ADD A, E
                LD E, A
                EXX
                LD E, #01
                EXX
                ; расчёт строки за прямоугольником для проверки нижнего края
ClipBottom:     LD A, B
                ADD A, D
                ; проверка выхода нижней границы за строку 24
                CP #19
                JP C, @Station.XorRectOutline.ScreenAddress                     ; переход, если нижняя граница не выходит за экран, высоту сохранить

                ; вычитание нижнего избытка из высоты и пометка скрытой нижней грани
                SUB #18
                NEG
                ADD A, D
                LD D, A
                EXX
                LD D, #01
                EXX
                ; расчёт экранного адреса верхней видимой пиксельной строки через исходные таблицы
ScreenAddress:  LD L, B
                RLC L
                RLC L
                RLC L
                LD H, #82
                LD B, (HL)
                INC H
                LD A, (HL)
                INC H
                LD L, C
                RLC L
                RLC L
                RLC L
                OR (HL)
                LD L, A
                LD H, B
                ; чтение признака отсечения верхней грани из временного D'
                EXX
                LD A, D
                EXX
                ; проверка скрытой верхней грани по отрицательному признаку
                AND A
                CALL P, @Station.XorOutlineRow.Entry                            ; вызов, если верхняя грань не отсечена сверху, инвертировать её строку
                ; чтение признака отсечения левой грани
                EXX
                LD A, E
                EXX
                ; проверка скрытой левой грани с сохранением результата до условного CALL
                AND A
                ; установка XOR-маски старшего пикселя байта для левой грани
                LD A, #80
                LD (@XorOutlineState.VerticalMask), A
                CALL P, @Station.XorOutlineColumn.Entry                         ; вызов, если левая грань не отсечена, инвертировать старший пиксель каждой строки
                ; расчёт адреса правой видимой колонки добавлением ширины минус один
                LD A, E
                DEC A
                ADD A, L
                LD L, A
                ; чтение признака правого отсечения, единица означает скрытую правую грань
                EXX
                LD A, E
                EXX
                ; проверка скрытой правой грани через вычитание единицы
                DEC A
                ; установка XOR-маски младшего пикселя байта для правой грани
                LD A, #01
                LD (@XorOutlineState.VerticalMask), A
                CALL NZ, @Station.XorOutlineColumn.Entry                        ; вызов, если правая грань не отсечена, инвертировать младший пиксель каждой строки
                ; возврат HL к первой видимой колонке
                LD A, E
                DEC A
                NEG
                ADD A, L
                LD L, A
                ; расчёт адреса последней пиксельной строки видимой высоты с чередованием адресов Spectrum
                LD A, D
                DEC A
                AND #07
                RRCA
                RRCA
                RRCA
                ADD A, L
                LD L, A
                ; сохранение переноса младшего адреса для расчёта старшего байта нижней строки
                PUSH AF
                LD A, D
                DEC A
                OR #07
                LD B, A
                POP AF
                LD A, B
                ADC A, #00
                OR #07
                ADD A, H
                LD H, A
                ; чтение признака нижнего отсечения, единица означает скрытую нижнюю грань
                EXX
                LD A, D
                EXX
                ; проверка скрытой нижней грани через вычитание единицы
                DEC A
                CALL NZ, @Station.XorOutlineRow.Entry                           ; вызов, если нижняя грань не отсечена, инвертировать её строку
                ; снятие FOutlineFrame с восстановлением альтернативного DE и входных размеров с координатами
                EXX
                POP DE
                EXX
                POP DE
                POP BC
                RET

                endmodule
                endmodule
