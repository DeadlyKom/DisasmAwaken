                module Station
                module ApplyPointerInput
; Документация [Station](../../Docs/FunctionDetails/Station.md)
; Подробный разбор [опрос, накопление и таблица направлений](../../Docs/PointerInputs.md)
; -----------------------------------------
; Накопление шести независимых флагов и выбор шага по младшим четырём направлениям
; исходная запись 4, файловые смещения #0934..#097E
; In:
;   PointerXY содержит X=0..255,Y=0..191, шесть InputFlags доступны для чтения и записи
;   PointerInputState.Step=2, MaxY=191 и MaxX=255 подготовлены StartStation
;   таблица PointerDirections содержит исходные 16 указателей, код и CPU-стек доступны
;   AF - A содержит текущие шесть разрядов ввода, биты 6 и 7 нулевые
; Out:
;   BC - итоговые пиксельные X в C,Y в B, DE=#BF02, HL и AF рабочие
;   PointerXY обновлён выбранным шагом либо прежним BC при отсутствии движения
;   каждый из шести InputFlags получает старое значение OR соответствующий разряд текущей выборки
;   индексные и альтернативные регистры, I и IFF сохраняются, SP восстанавливается
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   байты действий участвуют в накоплении, но не в выборе одного из 16 направлений
;   противоположные направления по любой оси внутри текущей выборки выбирают NoPointerMotion и отменяют обе оси
;   выбор движения использует текущий A, ранее накопленные флаги не отменяют и не усиливают этот шаг
;   ApplyPointerInput кладёт CommitPointerInput поверх исходного адреса возврата и передаёт управление JP (HL)
;   RET обработчика направления выполняет CommitPointerInput, его RET возвращает исходному вызывающему коду
;   ClearInputFlags выполняется до обоих опросов в Interrupt, сами опросы накопленные флаги не очищают
;   последовательные опросы джойстика и клавиатуры каждый отдельно двигают указатель, одинаковое направление даёт два шага
;   модель задаёт показания портов, не исполняет IRQ и не проверяет реальное устройство
;   после семи RRC и сброса разрядов 5,6 смещение равно 2*(A AND 15) только при нулевых исходных битах 6,7
;   ненулевые исходные биты 6,7 могут дать нечётное либо выходящее за таблицу смещение, код это не проверяет
; -----------------------------------------
                ; сохранение текущего байта выбора в E перед разбором шести битов
Entry:          LD E, A
                ; выбор начала шести независимых накопленных байтов ввода
                LD HL, @InputFlags.State
                XOR A
                LD D, A
                ; выделение текущего бита Right перед объединением с накопленным байтом
                RRC E
                ; расчёт байтового значения 0 либо 1 из Carry для Right
                ADC A, A
                ; объединение текущего Right с накопленным байтом без очистки прежних разрядов
                OR (HL)
                LD (HL), A
                INC HL
                XOR A
                ; выделение текущего бита Left перед объединением с накопленным байтом
                RRC E
                ; расчёт байтового значения 0 либо 1 из Carry для Left
                ADC A, A
                ; объединение текущего Left с накопленным байтом без очистки прежних разрядов
                OR (HL)
                LD (HL), A
                INC HL
                XOR A
                ; выделение текущего бита Down перед объединением с накопленным байтом
                RRC E
                ; расчёт байтового значения 0 либо 1 из Carry для Down
                ADC A, A
                ; объединение текущего Down с накопленным байтом без очистки прежних разрядов
                OR (HL)
                LD (HL), A
                INC HL
                XOR A
                ; выделение текущего бита Up перед объединением с накопленным байтом
                RRC E
                ; расчёт байтового значения 0 либо 1 из Carry для Up
                ADC A, A
                ; объединение текущего Up с накопленным байтом без очистки прежних разрядов
                OR (HL)
                LD (HL), A
                INC HL
                XOR A
                ; выделение текущего бита Action2 перед объединением с накопленным байтом
                RRC E
                ; расчёт байтового значения 0 либо 1 из Carry для Action2
                ADC A, A
                ; объединение текущего Action2 с накопленным байтом без очистки прежних разрядов
                OR (HL)
                LD (HL), A
                INC HL
                XOR A
                ; выделение текущего бита Action1 перед объединением с накопленным байтом
                RRC E
                ; расчёт байтового значения 0 либо 1 из Carry для Action1
                ADC A, A
                ; объединение текущего Action1 с накопленным байтом без очистки прежних разрядов
                OR (HL)
                LD (HL), A
                RRC E
                ; удаление двух битов действий из смещения после переноса шести флагов
                RES 5, E
                RES 6, E
                ; расчёт адреса двухбайтового указателя направления по смещению текущей выборки
                LD HL, @PointerDirections.None
                ADD HL, DE
                LD A, (HL)
                INC HL
                LD H, (HL)
                LD L, A
                LD DE, #66D3
                ; создание возврата CommitPointerInput поверх исходного адреса вызова
                PUSH DE
                ; чтение текущих координат перед выбранным обработчиком шага
                LD BC, (#6307)
                ; чтение изменяемого шага, StartStation записывает 2
                LD E, #01
                ; чтение изменяемого предела Y, StartStation записывает 191
                LD D, #00
                ; чтение изменяемого предела X, StartStation записывает 255
                LD A, #00
                JP (HL)

                endmodule
                endmodule
