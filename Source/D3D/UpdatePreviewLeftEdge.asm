                module D3D
                module UpdatePreviewLeftEdge
                ; Документация [кольцевые цепочки, все знаки и длины наклона, точные шаги, флаги и временный стек](../../Docs/PreviewPolygonFill.md)
                ; -----------------------------------------
                ; Выбор восходящего левого ребра, деление наклона и подготовка шага и ошибки
                ; исходная запись 6, банк 4, файловые смещения #128C..#134A
                ; In:
                ;   HL - H текущая страница масок C0 либо C1, входной L не используется
                ;   DE - D=D1 для развёрнутой записи, входной E будет заменён начальной колонкой
                ;   BC - текущий экранный указатель, AF - A текущая строка Y, F сохраняется
                ;   HL' - H' ошибка правого ребра, DE' его шаг, BC' и L' заменяются, AF' сохраняется
                ;   IX и IY содержат текущие границы, LeftVertex указывает строковый байт начала в C8
                ;   LastIndex задаёт конец кольца, найденное следующее ребро имеет положительную высоту h
                ;   SP=FFE0, под ним доступны шесть байтов временного CPU-стека, повторный вход исключён
                ; Out:
                ;   HL - H сохранён, L равен входному D, временная маска заменена до DrawRow
                ;   DE - D сохранён, E содержит старую колонку при abs(dx)<h, иначе (abs(dx) DIV h) XOR 255
                ;   BC и AF полностью сохранены, включая точный входной F
                ;   HL' - H' сохранён, L'=floor(h/2), DE' сохранён, BC'=(2000+32*s) AND FFFF
                ;   AF', IX, IY, SP, I, IFF и IM сохранены, продолжение StepPreviewPolygonRow.CheckRightEnd
                ;   s=ceil(dx/h) для dx не равного нулю, при dx=0 s=1 с дробной компенсацией
                ;   LeftVertex указывает строковый байт конца, LeftHeight=h, LeftEndRow=Y+h
                ;   при dx<0 LeftSubtract=abs(dx) MOD h, при dx>=0 и точном длинном наклоне нуль, иначе h-(dx MOD h)
                ; Corrupt:
                ;   HL - только L, DE - только E, HL' - только L', BC', операнды левой цепочки и шесть байтов под SP
                ; Note:
                ;   перебор идёт назад по строковым байтам страницы C8, строки не выше Y пропускаются
                ;   начальная колонка читается один раз до пропуска равных и меньших строк, пропущенная точка её не заменяет
                ;   четыре ветви сохраняют знаковые RRA и SRA оригинала, результат делителя хранится в дополненном виде
                ;   CALL делителя использует ещё два байта под двумя PUSH, перед продолжением исходный SP восстановлен
                ;   контракт относится к корректной восходящей цепочке, бесконечный поиск повреждённого кольца не исправляется
                ; -----------------------------------------
                ; -----------------------------------------
                ; Контекст левой цепочки
                ; -----------------------------------------
                ; сохранение страницы масок и D=D1 в HL, входной L дальше не нужен
Entry:          LD L, D
                ; сохранение текущей строки и флагов перед делением наклона
                PUSH AF
                ; сохранение временного HL в заимствованном стеке под FFE0
                PUSH HL
                ; чтение изменяемого указателя начала текущего левого ребра
                LD HL, #0000
                ; выбор байта колонки перед строкой начальной точки
                DEC L
                ; чтение начальной колонки, дальнейший пропуск плоских участков E не обновляет
                LD E, (HL)
                INC L
                ; сохранение текущей строки Y для поиска более высокой конечной точки
                LD D, A
                ; -----------------------------------------
                ; Обратный поиск конца ребра
                ; -----------------------------------------
                ; переход к предыдущему строковому байту в кольце страницы C8
Previous:       DEC L
                JR Z, @D3D.WrapPreviewLeftEdge.Entry                            ; переход, если после уменьшения L получен нуль, выбрать последнюю строку кольца

                DEC L
                ; чтение строки кандидата конца левого ребра
ReadRow:        LD A, (HL)
                ; расчёт высоты кандидата относительно текущей строки Y
                SUB D
                JR Z, @D3D.UpdatePreviewLeftEdge.Previous                       ; переход, если высота нулевая, продолжить поиск без перечитывания начальной колонки

                JR C, @D3D.UpdatePreviewLeftEdge.Previous                       ; переход, если строка кандидата ниже текущей Y по байтовому сравнению, продолжить обратный поиск

                ; сохранение указателя выбранного конца для следующего обновления цепочки
                LD (@PreviewPolygonEdgeState.LeftVertex), HL
                ; сохранение высоты h и периода восстановления левой ошибки
                LD D, A
                LD (@PreviewPolygonState.LeftHeight), A
                ; расчёт начальной половины высоты с округлением вниз
                SRL A
                ; сохранение начальной ошибки в L', правый накопитель H' не меняется
                EXX
                LD L, A
                EXX
                ; чтение и сохранение строки окончания выбранного левого ребра
                LD A, (HL)
                LD (@PreviewPolygonState.LeftEndRow), A
                ; выбор колонки конечной точки перед её строковым байтом
                DEC L
                LD A, (HL)
                ; расчёт знакового горизонтального смещения относительно начальной колонки E
Slope:          SUB E
                JP C, @D3D.UpdatePreviewLeftEdge.Negative                       ; переход, если конечная колонка меньше начальной, подготовить отрицательный наклон

                ; проверка длинного неотрицательного наклона по сравнению с высотой h
                CP D
                JP C, @D3D.UpdatePreviewLeftEdge.ShortPositive                  ; переход, если горизонтальная длина меньше высоты h, выбрать целый шаг плюс один

                ; -----------------------------------------
                ; Неотрицательный длинный наклон
                ; -----------------------------------------
                ; подготовка байтового делимого с нулевым старшим остатком и Carry
                LD E, A
                XOR A
                CALL @D3D.DividePreviewSlopeByte.Entry
                ; объединение восьми битов дополненного частного из E и Carry
                RL E
                ; проверка остатка деления для выбора точного целого шага
                AND A
                JR Z, @D3D.UpdatePreviewLeftEdge.ExactPositive                  ; переход, если остаток равен нулю, дробная поправка не нужна

                ; расчёт вычитаемой ошибки h-r при целом шаге q+1
                SUB D
                NEG
                ; обновление операнда дробной части левой границы
                LD (@PreviewPolygonState.LeftSubtract), A
                ; расчёт q+1 отрицанием дополненного частного
                LD A, E
                NEG
                ; перепаковка целого пиксельного шага в BC' со сдвигом на пять разрядов
                SRL A
                EXX
                LD C, #00
                RR C
                RRA
                RR C
                RRA
                RR C
                ; добавление строкового шага 2000 в старшую часть BC'
                ADD A, @PreviewPolygonConst.RowStepHigh
                LD B, A
                EXX
                ; восстановление масок, текущей строки, исходных флагов и D=D1
                POP HL
                POP AF
                LD D, L
                JP @D3D.StepPreviewPolygonRow.CheckRightEnd

                ; -----------------------------------------
                ; Точный неотрицательный наклон
                ; -----------------------------------------
                ; обнуление вычитаемой ошибки при нулевом остатке
ExactPositive:  LD (@PreviewPolygonState.LeftSubtract), A
                ; восстановление q инверсией дополненного частного
                LD A, E
                CPL
                ; перепаковка точного шага, Carry после AND A нулевой
                RRA
                EXX
                LD C, #00
                RR C
                SRA A
                RR C
                SRA A
                RR C
                ; добавление строкового шага к целой пиксельной части BC'
                ADD A, @PreviewPolygonConst.RowStepHigh
                LD B, A
                EXX
                ; восстановление сохранённого основного контекста левого обновления
                POP HL
                POP AF
                LD D, L
                JP @D3D.StepPreviewPolygonRow.CheckRightEnd

                ; -----------------------------------------
                ; Короткий неотрицательный наклон
                ; -----------------------------------------
                ; расчёт ошибки h-dx, целый шаг один пиксель компенсируется при заёме
ShortPositive:  SUB D
                NEG
                ; обновление вычитаемой левой ошибки без вызова делителя
                LD (@PreviewPolygonState.LeftSubtract), A
                ; подготовка BC'=2020, следующая строка и один пиксель вправо
                EXX
                LD C, @PreviewPolygonConst.PixelStepLo
                LD B, C
                EXX
                ; восстановление основного контекста перед проверкой правого ребра
                POP HL
                POP AF
                LD D, L
                JP @D3D.StepPreviewPolygonRow.CheckRightEnd

                ; -----------------------------------------
                ; Отрицательный наклон
                ; -----------------------------------------
                ; расчёт модуля отрицательной горизонтальной разности
Negative:       NEG
                ; проверка, требуется ли деление отрицательного наклона
                CP D
                JR C, @D3D.UpdatePreviewLeftEdge.ShortNegative                  ; переход, если модуль смещения меньше высоты h, целый пиксельный шаг нулевой

                ; подготовка модуля делимого, нулевого A и Carry
                LD E, A
                XOR A
                CALL @D3D.DividePreviewSlopeByte.Entry
                ; объединение дополненного частного, остаток A задаёт дробную ошибку
                RL E
                ; обновление левой ошибки остатком отрицательного наклона
                LD (@PreviewPolygonState.LeftSubtract), A
                ; расчёт отрицательной целой части -q через дополненное частное плюс один
                LD A, E
                INC A
                ; расширение знака отрицательного шага при первом RRA
                SCF
                RRA
                ; перепаковка отрицательной части в BC', SRA сохраняет её знак
                EXX
                LD C, #00
                RR C
                SRA A
                RR C
                SRA A
                RR C
                ; добавление строкового шага к знаковому целому смещению
                ADD A, @PreviewPolygonConst.RowStepHigh
                LD B, A
                EXX
                ; восстановление основного контекста, AF возвращается без изменения
                POP HL
                POP AF
                LD D, L
                JP @D3D.StepPreviewPolygonRow.CheckRightEnd

                ; -----------------------------------------
                ; Короткий отрицательный наклон
                ; -----------------------------------------
                ; сохранение всего модуля смещения как дробной ошибки
ShortNegative:  LD (@PreviewPolygonState.LeftSubtract), A
                ; подготовка BC'=2000 без целого пиксельного смещения
                EXX
                LD C, #00
                LD B, @PreviewPolygonConst.RowStepHigh
                EXX
                ; восстановление исходных HL, AF и D перед общим продолжением
                POP HL
                POP AF
                LD D, L
                JP @D3D.StepPreviewPolygonRow.CheckRightEnd

                ; -----------------------------------------
                endmodule
                endmodule
