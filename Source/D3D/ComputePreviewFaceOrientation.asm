                module D3D
                module ComputePreviewFaceOrientation
                ; Документация [32-битные результаты, размерные ветви, край 8000, выбор вершин, Carry и точные контракты](../../Docs/PreviewFaceMath.md)
                ; -----------------------------------------
                ; Ориентация по трём вершинам с выбором индексов, цепочкой заёмов и двумя настоящими произведениями
                ; исходная запись 6, банк 4, файловые смещения #1FA6..#2010
                ; In:
                ;   HL - адрес заголовка грани, DE не является входом, BC сохраняемый контекст вызывающего прохода
                ;   AF - A определяет выбор тройки, при A<5 читаются индексы 0,1,2, иначе 0,2,4 после заголовка
                ;   выбранные индексы задают младшие адреса записей страницы C6, читаются оба координатных слова
                ;   AF' - только Carry участвует в сохраняемом служебном AF', прочие альтернативные входы перезаписываются
                ;   IX сохраняется лишь если оба внутренних произведения выбрали короткие ветви, IY сохраняется
                ;   SP указывает на CPU-возврат, под ним доступны двенадцать байтов для указателей, произведений и двух вложенных CALL
                ; Out:
                ;   HL и BC сохраняются, DE содержит младшее слово итоговой 32-битной разности, старшее слово восстанавливаемый HL не возвращает
                ;   AF - A знаковый XOR аргументов второго произведения, F от старшего SBC окончательной разности
                ;   HL' и DE' содержат старшее и младшее слова первого произведения, BC' его точный размерный рабочий результат
                ;   AF' - A старший байт первой координаты второй выбранной вершины, F от INC её младшего адреса с входным Carry AF'
                ;   IX принадлежит последней длинной ветви внутреннего умножения либо сохраняется, IY, I, IFF и IM сохраняются
                ;   SP после RET равен входному+2, двенадцать байтов под ним имеют точный состав из PreviewFaceMath.md
                ; Corrupt:
                ;   DE, AF, HL', DE', BC', AF', IX при длинных произведениях, двенадцать байтов под CPU-SP
                ; Note:
                ;   первая разность первой оси получает Carry от CP A,5, следующие три SBC продолжают цепочку unsigned-заёмов
                ;   первое произведение получает dY1 и dX2, второе dX1 и dY2, каждое сохраняет особенность второго 8000
                ;   итог равен второе произведение минус первое и дополнительно Carry, оставшийся после второго умножителя
                ;   S финального старшего SBC используется вызывающим кодом непосредственно, P/V его не корректирует
                ;   индексы читаются через INC HL, координаты через INC L с оборачиванием внутри C6, пятый байт кода сторон не проверяется
                ;   геометрический идеальный определитель без этих заёмов не является побайтово эквивалентной заменой
                ; -----------------------------------------
                ; -----------------------------------------
                ; Выбор трёх индексов грани
                ; -----------------------------------------
                ; сохранение контекста вызывающего кода и адреса заголовка
Entry:          PUSH BC
                PUSH HL
                INC HL
                ; проверка входного A для выбора шага индексов, её Carry затем участвует в первой разности
                CP @PreviewFaceMathConst.SparseAt
                JR NC, @D3D.ComputePreviewFaceOrientation.Sparse                ; переход, если A не меньше 5, читать индексы 0,2,4

                ; чтение трёх последовательных индексных байтов
                LD D, (HL)
                INC HL
                LD E, (HL)
                INC HL
                LD A, (HL)
                JP @D3D.ComputePreviewFaceOrientation.ReadVertices

                ; чтение трёх индексных байтов через один
Sparse:         LD D, (HL)
                INC HL
                INC HL
                LD E, (HL)
                INC HL
                INC HL
                LD A, (HL)
                ; -----------------------------------------
                ; Координаты страницы C6
                ; -----------------------------------------
                ; выбор физической страницы проекции без проверки кодов сторон
ReadVertices:   LD H, @PreviewFaceMathConst.VertexPage
                LD L, D
                ; сохранение третьего индекса и Carry выбора шага, основной AF получает входной альтернативный контекст
                EX AF, AF'
                ; чтение второй координаты нулевой выбранной вершины в BC
                LD C, (HL)
                INC L
                LD B, (HL)
                INC L
                ; чтение первой координаты нулевой вершины в альтернативный BC
                LD A, (HL)
                INC L
                EXX
                LD C, A
                EXX
                LD A, (HL)
                EXX
                LD B, A
                EXX
                ; поиск второй выбранной вершины по младшему адресу E
                LD L, E
                ; чтение её второй координаты в DE
                LD E, (HL)
                INC L
                LD D, (HL)
                INC L
                ; чтение её первой координаты в альтернативный DE, INC L сохраняет входной Carry AF'
                LD A, (HL)
                INC L
                EXX
                LD E, A
                EXX
                LD A, (HL)
                EXX
                LD D, A
                EXX
                ; восстановление третьего индекса и Carry от CP A,5
                EX AF, AF'
                LD L, A
                ; временное сохранение второй координаты второй вершины перед чтением третьей
                PUSH DE
                ; чтение второй координаты третьей выбранной вершины
                LD E, (HL)
                INC L
                LD D, (HL)
                INC L
                ; чтение её первой координаты в альтернативный HL
                LD A, (HL)
                INC L
                EXX
                LD L, A
                EXX
                LD A, (HL)
                EXX
                LD H, A
                EXX
                ; подготовка второй оси трёх вершин в HL, DE, BC с восстановлением сохранённого слова
                EX DE, HL
                POP DE
                ; -----------------------------------------
                ; Четыре разности с общей цепочкой заёмов
                ; -----------------------------------------
                ; выбор первой координатной оси через обмен наборами
                EXX
                ; расчёт dX2=X2-X0-Carry выбора шага
                SBC HL, BC
                EX DE, HL
                ; расчёт dX1=X1-X0 с заёмом предыдущей разности
                SBC HL, BC
                ; сохранение dX1 для дальнейшей перекрёстной перестановки
                PUSH HL
                EXX
                ; расчёт dY2=Y2-Y0 с текущим заёмом первой оси
                SBC HL, BC
                EX DE, HL
                ; расчёт dY1=Y1-Y0 с заёмом предыдущей разности
                SBC HL, BC
                ; перестановка dY1 и сохранённого dX1 через обычный стек
                EX (SP), HL
                EXX
                POP HL
                ; -----------------------------------------
                ; Два произведения и окончательная разность
                ; -----------------------------------------
                ; расчёт первого произведения P1=dY1*dX2 с точным исходным умножителем
                CALL @D3D.MultiplyPreviewSignedWords.Entry
                ; сохранение старшего и младшего слов P1 для вычитания после второго умножения
                PUSH HL
                PUSH DE
                EXX
                ; расчёт второго произведения P2=dX1*dY2
                CALL @D3D.MultiplyPreviewSignedWords.Entry
                EX DE, HL
                POP BC
                ; расчёт младшего слова P2-P1 с Carry, оставшимся от второго произведения
                SBC HL, BC
                EX DE, HL
                POP BC
                ; расчёт старшего слова P2-P1 с заёмом младшего, его S выбирает ориентацию
                SBC HL, BC
                ; восстановление исходных HL и BC без изменения флагов ориентации
                POP HL
                POP BC
                RET

                ; -----------------------------------------
                endmodule
                endmodule
