                module D3D
                module CollectPreviewFaceCodes
                ; Документация [индексы кодов сторон, ранний нуль, B=0, точные флаги, указатели и стек](../../Docs/PreviewFaceCodes.md)
                ; -----------------------------------------
                ; Общий OR кодов вершин грани с ранним Carry по нулевому коду и восстановлением счётчика
                ; исходная запись 6, банк 4, файловые смещения #1DFD..#1E1B
                ; In:
                ;   HL - указатель заголовка грани, следующие B байтов содержат индексы вершин, при B=0 доступны 256 байтов
                ;   BC - B исходный счётчик, входной C не используется, DE и AF не являются параметрами
                ;   индекс плюс FPreviewProjectedVertex.Outcode по модулю 256 выбирает байт страницы C6
                ;   IXH сохраняемый контекст, IXL используется для сохранения исходного B
                ;   SP указывает на CPU-возврат, под ним доступны два байта для сохранения HL
                ; Out:
                ;   HL сохранён, DE указывает сразу после последнего прочитанного индексного байта
                ;   BC - B восстановлен входным значением, C содержит OR всех ненулевых кодов до конца либо первого нуля
                ;   AF при завершении содержит A=C и флаги OR с Carry=0, при нулевом коде A=0,F=45 с Carry=1
                ;   HL', DE', BC', AF', IXH и IY сохраняются, IXL содержит входной B
                ;   I, IFF и IM сохраняются, SP после RET равен входному+2, сохранённые байты HL остаются под входным SP
                ;   страница проекции и перечисление индексов не записываются
                ; Corrupt:
                ;   DE, BC, AF, IXL, два байта под CPU-SP
                ; Note:
                ;   нулевой код проверяется до объединения, C при отказе не обнуляется и сохраняет уже накопленные коды
                ;   исходный B=0 не означает пустой список, DJNZ читает 256 индексов, если раньше не встретится нулевой код
                ;   индексы читаются полным INC DE, адрес кода оборачивается по байту внутри C6
                ;   кратность индексов пяти не проверяется, для нештатного индекса читается фактический байт по обёрнутому адресу
                ;   после успешного OR старшая тетрада накопителя позволяет вызывающему коду проверить общую внешнюю сторону
                ;   процедура не проверяет ориентацию и не рисует грани
                ; -----------------------------------------
                ; сохранение исходного счётчика в IXL перед использованием DJNZ
Entry:          LD IXL, B
                ; сохранение указателя заголовка грани в обычном CPU-стеке
                PUSH HL
                ; перенос указателя перечисления в DE и пропуск заголовочного байта
                EX DE, HL
                INC DE
                ; выбор исходной страницы кодов проекции
                LD H, @PreviewFaceMathConst.VertexPage
                ; обнуление общего OR кодов выбранных вершин
                LD C, #00
                ; чтение следующего индексного байта с полным увеличением указателя перечисления
NextIndex:      LD A, (DE)
                INC DE
                ; расчёт младшего адреса пятого байта записи, сумма оборачивается в пределах страницы C6
                ADD A, @FPreviewProjectedVertex.Outcode
                LD L, A
                ; чтение фактического кода сторон по полученному адресу
                LD A, (HL)
                ; проверка нулевого кода до добавления в накопитель
                AND A
                JR Z, @D3D.CollectPreviewFaceCodes.ZeroCode                     ; переход, если код равен нулю, вернуть Carry без изменения накопителя

                ; обновление общего OR ненулевых кодов выбранных вершин
                OR C
                LD C, A
                ; продолжение по исходному счётчику, нулевой входной B соответствует 256 итерациям
                DJNZ @D3D.CollectPreviewFaceCodes.NextIndex

                ; восстановление указателя грани и исходного B с сохранением флагов OR
                POP HL
                LD B, IXL
                RET

                ; установка Carry для нулевого кода, Z/PV остаются от AND 0
ZeroCode:       SCF
                ; восстановление указателя и счётчика без изменения признака отказа
                POP HL
                LD B, IXL
                RET

                endmodule
                endmodule
