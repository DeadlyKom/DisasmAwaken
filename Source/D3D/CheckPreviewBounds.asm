                module D3D
                module CheckPreviewBounds
                ; Документация [четыре знаковые границы](../../Docs/PreviewBounds.md)
                ; -----------------------------------------
                ; Проверка четырёх обёрнутых знаковых границ с табличными размерами и продолжением во вставку очереди
                ; исходная запись 6, банк 4, файловые смещения #2DB0..#2E23
                ; In:
                ;   BC - C исходный байтовый размер модели, IX - IXL копия этого размера
                ;   FirstSkip и SecondSkip содержат одинаковое смещение 6-b при b=1..6, их исходное FE должно быть заменено до входа
                ;   ResultFirst, ResultSecond, ResultThird доступны по договору TransformPreviewCoords, исходная FoldedSquare127 находится в странице C3
                ;   на принятом пути действуют требования InsertPreviewQueue к подготовленному объекту и активной цепочке
                ;   банк 4 выбран и доступен для записи, маскируемые прерывания отключены, NMI и повторный вход исключены
                ; Out:
                ;   на первом отрицательном результате выполняется JP ECAE без вставки и без записи памяти, SP остаётся входным
                ;   на отказе HL последнее проверенное слово, DE табличный размер текущей компоненты, BC её исходное координатное слово
                ;   AF на отказе содержит A разность табличных значений текущей компоненты, F от её ADC либо SBC
                ;   если четыре знаковых теста приняты, выполнение последовательно входит в InsertPreviewQueue без новой инструкции JP
                ;   на принятом пути конечные регистры, SP, ссылки и память принадлежат InsertPreviewQueue, заполнение может завершить обход по EEEE
                ;   собственный участок сохраняет HL', DE', BC', AF', IX, IY, I, IFF и IM, очередь затем может изменить IX и IY
                ; Corrupt:
                ;   HL, DE, BC, AF, на принятом пути также IX, IY, SP и память по договору очереди
                ; Note:
                ;   половины знаковых слов получаются арифметическим сдвигом с округлением вниз, промежуточные сложения оборачиваются до следующего деления
                ;   все четыре условия используют только S, переполнение P/V не корректирует сравнение
                ;   размеры вычисляются разностью FoldedSquare127 с исходными затравками 72 и 66 и масштабируются на 2^(b-1)
                ;   JR по EDC3 и EDFC исходно направлены в себя, писатели ED52 и ED55 заранее меняют их операнды
                ;   жёсткий порядок включений 1, 2 обязателен, последнее JP M допускает последовательное продолжение в файл очереди
                ; -----------------------------------------
                ; выбор исходной затравки первой пары граничных тестов
Entry:          LD A, @PreviewBoundsConst.FirstSeed
                ; выбор исходной страницы свёрнутых квадратов
                LD H, @PreviewBoundsConst.TablePage
                ; расчёт половины первой затравки
                SRA A
                ; чтение байтового размера перед вычислением его знаковой половины
                LD L, C
                ; расчёт половины размера с округлением отрицательных нечётных вниз
                SRA L
                ; расчёт индекса разности половин для первого табличного значения
                SUB L
                LD L, A
                ; расчёт индекса суммы через прибавление полного размера
                ADD A, C
                ; поиск первого свёрнутого квадрата
                LD E, (HL)
                LD L, A
                ; поиск второго свёрнутого квадрата
                LD A, (HL)
                ; расчёт байтовой разности квадратов первой компоненты
                SUB E
                ; создание беззнакового слова из табличной разности
                LD L, A
                LD H, #00
                ; масштабирование первым изменяемым JR, подготовленное смещение пропускает часть пяти удвоений
ScaleFirst:     JR @D3D.CheckPreviewBounds.ScaleFirst

                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ; сохранение масштабированного первого размера в DE
                EX DE, HL
                ; чтение третьего результата преобразования для первой пары тестов
                LD HL, (@PreviewTransformState.ResultThird)
                ; расчёт арифметической половины третьего результата
                SRA H
                RR L
                ; чтение первой компоненты преобразования
                LD BC, (@PreviewTransformState.ResultFirst)
                ; расчёт обёрнутой суммы половины третьего результата и первой компоненты
                ADD HL, BC
                ; расчёт арифметической половины полученной суммы
                SRA H
                RR L
                ; очистка Carry перед прибавлением первого табличного размера
                AND A
                ; расчёт первой граничной суммы с исходным шестнадцатибитным оборачиванием
                ADC HL, DE
                JP M, @D3D.BuildPreviewQueue.NextRecord                         ; переход, если первая граничная сумма имеет знак минус, пропустить объект

                ; очистка Carry перед вычитанием исходной первой компоненты
                OR A
                ; расчёт второй границы из первой граничной суммы и первой компоненты
                SBC HL, BC
                JP M, @D3D.BuildPreviewQueue.NextRecord                         ; переход, если вторая граничная разность имеет знак минус, пропустить объект

                ; восстановление исходного размера из IXL после использования BC как координаты
                LD C, IXL
                ; выбор затравки второй пары граничных тестов
                LD A, @PreviewBoundsConst.SecondSeed
                ; выбор той же исходной страницы квадратов
                LD H, @PreviewBoundsConst.TablePage
                ; расчёт половины второй затравки
                SRA A
                ; чтение восстановленного размера для второй табличной разности
                LD L, C
                ; расчёт арифметической половины размера
                SRA L
                ; расчёт индекса разности для второй компоненты
                SUB L
                LD L, A
                ; расчёт индекса суммы прибавлением полного размера
                ADD A, C
                ; поиск первого квадрата второй компоненты
                LD E, (HL)
                LD L, A
                ; поиск второго квадрата второй компоненты
                LD A, (HL)
                ; расчёт байтовой разности квадратов второй компоненты
                SUB E
                ; создание беззнакового слова из второй табличной разности
                LD L, A
                LD H, #00
                ; масштабирование вторым подготовленным JR, исходное FE не является рабочим смещением
ScaleSecond:    JR @D3D.CheckPreviewBounds.ScaleSecond

                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ; сохранение масштабированного второго размера в DE
                EX DE, HL
                ; повторное чтение третьего результата преобразования
                LD HL, (@PreviewTransformState.ResultThird)
                ; расчёт первой арифметической половины третьего результата
                SRA H
                RR L
                ; расчёт второй арифметической половины, деление знакового слова на четыре
                SRA H
                RR L
                ; чтение второй компоненты преобразования
                LD BC, (@PreviewTransformState.ResultSecond)
                ; расчёт обёрнутой суммы четверти третьего результата и второй компоненты
                ADD HL, BC
                ; расчёт арифметической половины полученной суммы
                SRA H
                RR L
                ; очистка Carry перед прибавлением второго табличного размера
                AND A
                ; расчёт третьей граничной суммы
                ADC HL, DE
                JP M, @D3D.BuildPreviewQueue.NextRecord                         ; переход, если третья граничная сумма имеет знак минус, пропустить объект

                ; очистка Carry перед последним вычитанием координаты
                OR A
                ; расчёт четвёртой граничной разности
                SBC HL, BC
                JP M, @D3D.BuildPreviewQueue.NextRecord                         ; переход, если четвёртая граничная разность имеет знак минус, иначе продолжить вставку

                ; JP @D3D.InsertPreviewQueue.Entry, продолжение в InsertPreviewQueue.asm

                endmodule
                endmodule
