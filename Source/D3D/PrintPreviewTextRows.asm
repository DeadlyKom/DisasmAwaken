                module D3D
                module PrintPreviewTextRows
                ; Документация [описания моделей](../../Docs/PreviewDescriptions.md)
                ; -----------------------------------------
                ; Печать выбранного описания корабля либо скимера с байтовым пропуском строк
                ; исходная запись 6, банк 4, файловые смещения #2154..#2170
                ; In:
                ;   HL - слово прокрутки, только L определяет число пропускаемых строк, H передаётся как D в PrintFromRow
                ;   AF - A селектор таблицы, ровно 1 выбирает скимеры, остальные значения корабли
                ;   действуют требования выбора текста, поиска LF и запасов чтения CountPreviewTextRows, подготовлены окно и реальный глиф
                ; Out:
                ;   HL, DE, BC, AF - полный результат PrintFromRow после выбора описания, начальные координаты CursorX=0 и CursorY=8
                ;   при раннем Carry пропуска дальнейшая печать не выполняется, действуют точные выходы PrintFromRow
                ;   bitmap и курсор изменены настоящим выравнивателем и DrawGlyph, альтернативные и индексные регистры, I, IFF и IM сохранены
                ;   SP обычного возврата равен входному SP+2
                ; Corrupt:
                ;   HL, DE, BC, AF
                ; Note:
                ;   исходный HL сохраняется до поиска записи на стеке, затем извлекается в DE, пропуск использует только E
                ;   слова 0000 и 0100 оба задают ноль пропускаемых строк, их D различается на ранних выходах
                ;   проверки границ таблиц, предельного числа строк и исправления неподходящей геометрии в этой обёртке нет
                ; -----------------------------------------
                ; сохранение полного слова прокрутки на время выбора текста
Entry:          PUSH HL
                ; выбор основного потока описаний кораблей
                LD HL, @PreviewShipText.Dominion
                ; проверка селектора потока скимеров
                DEC A
                JR NZ, @D3D.PrintPreviewTextRows.SelectedText                   ; переход, если исходный селектор не равен 1, сохранить основной поток

                ; выбор потока описаний скимеров
                LD HL, @PreviewSkimText.Fervest
                ; чтение компонента строки с передачей его в C поиска
SelectedText:   LD A, (@D3DPreviewState.RowOperand)
                LD C, A
                LD A, (@D3DPreviewState.BaseOperand)
                ; расчёт байтового номера описания без расширения переносом
                ADD A, C
                ; поиск записи по исходным LF без проверки допустимого номера
                CALL @Station.SkipLfRecords.Entry
                ; извлечение прокрутки в DE, только младший E задаёт число пропускаемых строк
                POP DE
                ; задание курсора X=0, Y=8 перед пропуском и печатью
                LD BC, #0800
                ; печать выбранного текста с реальным пропуском выровненных строк
                CALL @Station.PrintFromRow.Entry
                RET

                endmodule
                endmodule
