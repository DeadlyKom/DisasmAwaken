                module D3D
                module ConfigurePreviewClip
                ; Документация [границы просмотра](../../Docs/PreviewClipBounds.md)
                ; -----------------------------------------
                ; Настройка четырёх углов и повторённых операндов границ корабельного просмотра
                ; исходная запись 6, банк 4, файловые смещения #2011..#207E
                ; In:
                ;   HL - H верхний предел X, L верхний предел Y, DE - D нижний предел X, E нижний предел Y, все компоненты байтовые
                ;   подключён исходный D3D в банке 4, существующие операнды графического ядра доступны для записи
                ; Out:
                ;   HL - H исходный верхний X, L исходный нижний Y, DE - D исходный нижний X, E исходный верхний Y, BC сохранён
                ;   AF - A исходный нижний Y, F от INC исходного верхнего Y, Carry равен биту 0 суммы верхний Y+1 по модулю 256
                ;   четыре упакованных угла и повторённые граничные операнды настроены, полупределы равны ((верхняя компонента+1) AND FF) SHR 1
                ;   альтернативные и индексные регистры, I, IFF и IM сохранены, SP обычного возврата равен входному SP+2
                ; Corrupt:
                ;   HL, DE, AF
                ; Note:
                ;   верхний X берётся из ширины текстового окна минус 14, верхний Y из высоты минус 13 в исходном DrawItem26, нижние пределы там нулевые
                ;   процедура не проверяет порядок границ и не включает нижние пределы в расчёт полупределов
                ;   при верхнем пределе FF прибавление единицы оборачивается в ноль до деления, это исходное поведение
                ;   полупределы и первые копии X и Y меняют младшие байты слов, остальные копии меняют байтовые операнды LD (HL),n или LD L,n
                ;   всего меняются 34 байта существующих операндов в банке 4, экран, порт страниц и стековая память не записываются
                ; -----------------------------------------
                ; -----------------------------------------
                ; Полупределы и четыре угла
                ; -----------------------------------------
                ; расчёт байтового полупредела X с исходным оборачиванием FF в ноль
Entry:          LD A, H
                INC A
                SRL A
                LD (@D3DClipState.HalfXLow), A
                ; расчёт байтового полупредела Y, младший бит суммы останется в Carry до возврата
                LD A, L
                INC A
                SRL A
                LD (@D3DClipState.HalfYLow), A
                ; сохранение углов с одновременно верхними и одновременно нижними компонентами
                LD (@D3DClipState.MaxCorner), HL
                LD (@D3DClipState.MinCorner), DE
                ; перестановка только младших компонент для двух остальных углов
                LD A, L
                LD L, E
                LD E, A
                LD (@D3DClipState.MaxXMinY), HL
                LD (@D3DClipState.MinXMaxY), DE
                ; -----------------------------------------
                ; Повторённые операнды пределов
                ; -----------------------------------------
                ; обновление копий верхнего X и исключённого предела X+1
                LD A, H
                LD (@D3DClipState.MaxX0), A
                LD (@D3DClipState.MaxX1), A
                LD (@D3DClipState.MaxX2), A
                LD (@D3DClipState.MaxX3), A
                LD (@D3DClipState.MaxX4), A
                INC A
                LD (@D3DClipState.AfterMaxX), A
                ; обновление копий нижнего X, меняются только указанные байтовые операнды
                LD A, D
                LD (@D3DClipState.MinX0), A
                LD (@D3DClipState.MinX1), A
                LD (@D3DClipState.MinX2), A
                LD (@D3DClipState.MinX3), A
                LD (@D3DClipState.MinX4), A
                ; обновление копий верхнего Y и исключённого предела Y+1
                LD A, E
                LD (@D3DClipState.MaxY0), A
                LD (@D3DClipState.MaxY1), A
                LD (@D3DClipState.MaxY2), A
                LD (@D3DClipState.MaxY3), A
                LD (@D3DClipState.MaxY4), A
                LD (@D3DClipState.MaxY5), A
                INC A
                LD (@D3DClipState.AfterMaxY), A
                ; обновление копий нижнего Y без изменения флагов последнего INC верхнего Y
                LD A, L
                LD (@D3DClipState.MinY0), A
                LD (@D3DClipState.MinY1), A
                LD (@D3DClipState.MinY2), A
                LD (@D3DClipState.MinY3), A
                LD (@D3DClipState.MinY4), A
                LD (@D3DClipState.MinY5), A
                RET

                ; -----------------------------------------
                endmodule
                endmodule
