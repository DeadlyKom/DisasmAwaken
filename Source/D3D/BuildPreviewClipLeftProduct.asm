                module D3D
                module BuildPreviewClipLeftProduct
                ; Документация [производители четырёх кэшей, внутренние входы, разности слов, точные регистры и второй множитель 8000](../../Docs/PreviewClipProducts.md)
                ; -----------------------------------------
                ; Формирование кэша Left относительно границы с исходным порядком аргументов умножения
                ; исходная запись 6, банк 4, файловые смещения #2626..#2644
                ; In:
                ;   HL, DE, BC и AF не являются параметрами полного Entry, два физических конца содержат координатные слова
                ;   граница подготовлена ConfigurePreviewClip, старший байт слова LD BC сохраняет исходный нуль
                ;   HL', DE', BC', AF' сохраняются, IX контекст коротких ветвей умножителя, IY сохраняется
                ;   SP указывает на CPU-возврат, под ним доступны четыре байта вложенного CALL и сохранённого AF
                ; Out:
                ;   HL и DE содержат старшее и младшее слова результата MultiplyPreviewSignedWords и записаны в кэш Left
                ;   BC определяется размерной ветвью и знаком умножителя, исходный BC его входа равен FirstAxis второго конца
                ;   AF - A равен XOR старших байтов двух аргументов, F от знакового XOR либо старшего SBC при отрицании результата
                ;   HL', DE', BC', AF' сохранены, IX сохранён короткими ветвями, длинной заменён младшим словом модуля, IY сохранён
                ;   I, IFF и IM сохранены, SP после RET равен входному+2, координатные записи не меняются
                ;   записаны четыре байта выбранного кэша и четыре байта под входным SP, другие кэши и промежутки не записываются
                ; Corrupt:
                ;   HL, DE, BC, AF, IX в длинной ветви, четыре байта кэша и четыре байта под CPU-SP
                ; Note:
                ;   первый аргумент HL равен FirstAxis первого конца минус FirstAxis второго, второй DE равен SecondAxis первого конца минус MinY0
                ;   каждая разность формируется отдельно по модулю 65536 с предварительным сбросом Carry
                ;   порядок аргументов менять нельзя, для двух длинных модулей и второго 8000 умножитель использует эффективный множитель 256
                ;   сам производитель не проверяет коды сторон или геометрическую допустимость, готовность кэша для следующего обработчика проверяется отдельно
                ; -----------------------------------------
                ; чтение изменяемого слова граничной колонки
Entry:          LD BC, #0000
                ; чтение колонки первого конца
                LD HL, (@PreviewClipFirst.Value.SecondAxis)
                ; сброс Carry перед смещением колонки относительно границы
                OR A
                ; расчёт смещения колонки, этот аргумент должен остаться вторым
                SBC HL, BC
                ; сохранение смещения колонки в DE
                EX DE, HL
                ; чтение строк второго и первого конца для первого аргумента HL
                LD BC, (@PreviewClipSecond.Value.FirstAxis)
                LD HL, (@PreviewClipFirst.Value.FirstAxis)
                ; сброс Carry перед первой строковой разностью, заём колонки сюда не переносится
                OR A
                ; расчёт строкового аргумента HL по модулю 65536
                SBC HL, BC
                ; вызов настоящего знакового умножителя с сохранением его особенности второго 8000
                CALL @D3D.MultiplyPreviewSignedWords.Entry
                ; запись младшего слова результата в физический кэш Left
                LD (@PreviewClipLeftLow.Value.Word), DE
                ; запись старшего слова без изменения флагов умножителя
                LD (@PreviewClipLeftHigh.Value.Word), HL
                RET

                endmodule
                endmodule
