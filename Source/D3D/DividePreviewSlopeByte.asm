                SUB D
                JR NC, @D3D.DividePreviewSlopeByte.Step2                        ; переход, если пробный остаток не меньше делителя, оставить результат вычитания

                ; восстановление байтового остатка после заёма, Carry задаёт единицу дополненного частного
                ADD A, D
                ; -----------------------------------------
