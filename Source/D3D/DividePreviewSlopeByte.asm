                ; Восемь шагов деления горизонтальной длины ребра с дополненным частным и остатком
                ; исходная запись 6, банк 4, файловые смещения #14DF..#1517
                ; In:
                ;   HL сохраняется, DE содержит D как делитель и E как делимое
                ;   BC сохраняется, AF содержит A как начальный старший остаток и Carry как начальный бит регистра E
                ;   в четырёх найденных вызовах A=0 и Carry=0, выбран банк 4, IRQ и NMI не вмешиваются
                ;   SP указывает на адрес CPU-возврата, дополнительных байтов под ним не требуется
                ; Out:
                ;   HL сохраняется, D сохраняется, E=(входной Carry*128) OR ((частное XOR 255)>>1), BC сохраняется
                ;   A содержит байтовый остаток, Carry младший бит дополненного частного
                ;   при входном A=0 и D>0 частное равно входному E DIV D, остаток входному E MOD D
                ;   F соответствует последнему SUB D либо восстанавливающему ADD A, D, при D=0 F=(входной E AND A8) OR (40 при E=0) OR 02
                ;   HL', DE', BC', AF', IX, IY, I, IM и IFF сохраняются
                ;   последующий RL E объединяет возвращённые E и Carry в полное дополненное частное
                ;   SP после RET равен входному+2, записей в память нет
                ;   полный M1 равен 41 плюс число единиц дополненного частного, от 41 до 49, бит 7 R сохраняется
                ; Corrupt:
                ;   E, AF, R
                ; Note:
                ;   восемь шагов развёрнуты, счётчик и обращения к таблицам не требуются
                ;   каждый шаг переносит следующий старший бит исходного E в байтовый остаток A
                ;   при заёме остаток восстанавливается, Carry становится следующим битом дополненного частного
                ;   старший девятый разряд после RLA теряется перед SUB, для произвольного A это не полное деление слова A:E
                ;   при D=0 проверки нет, возвращается A равный исходному E, E равный входному Carry*128 и Carry=0
                ;   входной Carry влияет только на старший бит возвращённого E, при объединении полного частного он теряется
                ;   четыре найденных вызова находятся в D2BC, D319, D386 и D3E0, профиль вызывающих проходов рассмотрен в PreviewPolygonFill.md и не подменяется локальным договором делителя
