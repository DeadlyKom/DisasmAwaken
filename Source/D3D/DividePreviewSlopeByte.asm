                ;   HL и BC не используются, SP указывает на адрес CPU-возврата
                ; Out:
                ;   DE - D сохранён, E=(входной Carry*128) OR ((частное XOR 255)>>1)
                ;   AF - A байтовый остаток, Carry содержит младший бит дополненного частного
