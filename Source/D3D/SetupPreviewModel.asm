                module D3D
                module SetupPreviewModel
                ; Документация [подготовка просмотра](../../Docs/PreviewSetup.md)
                ; -----------------------------------------
                ; Настройка границ и трёх таблиц просмотра с выбором байтового смещения модели
                ; исходная запись 6, банк 4, файловые смещения #213C..#2153
                ; In:
                ;   HL и DE - верхние и нижние пределы по договору ConfigurePreviewClip, AF - A селектор, F произвольный сохраняемый байт
                ;   DE' - D' начало Y и E' начало X для BuildSpriteLineTable после EXX
                ;   исходные таблицы ULA подготовлены, подключён банк 4, действуют договоры обоих помощников, стек вне изменяемых областей
                ;   RowOperand и BaseOperand содержат два байтовых компонента выбора, читаемых непосредственно исполняемыми инструкциями
                ; Out:
                ;   HL - CB00, DE - выходной адрес строки от BuildSpriteLineTable, BC - B=(исходный A-1) AND FF, C=исходный F
                ;   AF - A байтовое смещение модели, F от последнего ADD при исходном A=1, иначе от DEC B с Carry второго удвоения
                ;   HL' и DE' - верхние и нижние пределы после обмена младших компонент в ConfigurePreviewClip, BC' - исходный BC
                ;   AF' - выходное альтернативное состояние BuildSpriteLineTable, IX, IY, I, IFF и IM сохранены
                ;   операнды границ и три страницы таблиц настроены, ModelOffset получает вычисленное смещение, SP обычного возврата равен входному SP+2
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF'
                ; Note:
                ;   первые два помощника вызываются реально, EXX выполняется между ними, исходный AF после этого извлекается в BC
                ;   смещение равно (4*((RowOperand+BaseOperand) AND FF) + (28, если исходный A=1, иначе 0)) AND FF
                ;   первое сложение индексов и оба удвоения байтовые, никакое переполнение здесь не расширяет индекс и не вызывает отказа
                ;   DE' является началом экрана, а DE является нижними границами, это разные входные пары
                ;   под входным SP остаются четыре служебных байта, последняя пара возврата E144 и исходные F,A, их память не очищается
                ;   процедура не меняет аппаратную страницу, реальный вывод модели и EI последующего E07F сюда не входят
                ; -----------------------------------------
                ; сохранение полного селектора и входных флагов для последующего POP BC
Entry:          PUSH AF
                ; настройка операндов границ по исходным HL и DE
                CALL @D3D.ConfigurePreviewClip.Entry
                ; выбор альтернативного DE с началом экрана для построения трёх таблиц
                EXX
                ; создание реальных таблиц строк и колонок в банке 4
                CALL @Station.BuildSpriteLineTable.Entry
                ; восстановление исходного AF как B селектор и C прежние флаги
                POP BC
                ; чтение изменяемого компонента строки и сложение со смещением списка
                LD A, #00
                ADD A, #00
                ; расчёт байтового смещения четырёхбайтовой записи двумя удвоениями
                ADD A, A
                ADD A, A
                ; проверка особого селектора 1 после декремента восстановленного B
                DEC B
                JR NZ, @D3D.SetupPreviewModel.StoreOffset                       ; переход, если исходный селектор не равен 1, общую базу 28 не добавлять

                ; добавление исходной базы 28 только для селектора 1
                ADD A, @D3DPreviewConst.SpecialBase
                ; сохранение байтового смещения модели в существующем поле исходной записи
StoreOffset:    LD (@D3DPreviewState.ModelOffset), A
                RET

                endmodule
                endmodule
