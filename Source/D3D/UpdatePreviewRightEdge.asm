                module D3D
                module UpdatePreviewRightEdge
                ; Документация [кольцевые цепочки, все знаки и длины наклона, точные шаги, флаги и временный стек](../../Docs/PreviewPolygonFill.md)
                ; -----------------------------------------
                ; Выбор восходящего правого ребра и подготовка его шага, ошибки и следующей строки
                ; исходная запись 6, банк 4, файловые смещения #1350..#140E
                ; In:
                ;   HL - H страница масок C0 либо C1, входной L не используется
                ;   DE - D=D1, входной E будет заменён начальной колонкой
                ;   BC - текущий экранный указатель, AF - A текущая строка Y
                ;   HL' - L' ошибка левого ребра, BC' его шаг, DE' и H' заменяются, AF' сохраняется
                ;   IX и IY текущие границы, RightVertex и LastIndex задают прямую цепочку в странице C8
                ;   следующее ребро имеет h>0, SP=FFE0, под ним доступны четыре байта временного стека
                ; Out:
                ;   HL - H сохранён, L равен входному D
                ;   DE - D сохранён, при abs(dx)<h E старая колонка, при длинном dx>=0 E=(q XOR 255), при длинном dx<0 E=(q XOR 255)>>1
                ;   q=abs(dx) DIV h, BC полностью сохранён
                ;   AF длинной ветви от последнего ADD A, 20, A старший байт упакованного шага
                ;   AF короткой dx>=0 ветви от NEG разности dx-h, A=h-dx
                ;   AF короткой dx<0 ветви от CP abs(dx), h, A=abs(dx), биты 3 и 5 берутся из h
                ;   HL' - H'=floor(h/2), L' сохранён, DE'=(2000+32*s) AND FFFF, BC' сохранён
                ;   AF', IX, IY, SP, I, IFF и IM сохранены, продолжение StepPreviewPolygonRow.DrawRow
                ;   s=ceil(dx/h) при ненулевом dx, для dx=0 s=1 с дробной компенсацией
                ;   RightVertex указывает конец, RightHeight=h, RightEndRow=Y+h, CurrentRow=Y+1
                ;   RightSubtract для отрицательного dx равен abs(dx) MOD h, для неотрицательного точного длинного нуль, иначе h-(dx MOD h)
                ; Corrupt:
                ;   HL - только L, DE - только E, AF, HL' - только H', DE', операнды правой цепочки и четыре байта под SP
                ; Note:
                ;   в отличие от левой цепочки AF не сохраняется в стеке, его точные три выходных случая проверены отдельно
                ;   при отрицательном длинном наклоне заключительный бит частного объединяется в A через RLA, E остаётся половинным
                ;   прямой обход пропускает строки не выше Y, но начальная колонка не перечитывается при каждом пропуске
                ;   CurrentRow обновляется здесь, поэтому возврат минует общий INC A и сразу продолжает DrawRow
                ; -----------------------------------------
                ; -----------------------------------------
                ; Контекст правой цепочки
                ; -----------------------------------------
                ; сохранение страницы масок и D=D1 во временном HL
Entry:          LD L, D
                ; сохранение HL под временным SP, AF в правой цепочке не сохраняется
                PUSH HL
                ; сохранение текущей строки Y для поиска положительной высоты
                LD D, A
                ; расчёт и сохранение следующей строки Y+1 до выбора нового правого ребра
                INC A
                LD (@PreviewPolygonState.CurrentRow), A
                ; чтение изменяемого указателя начала правой цепочки
                LD HL, #0000
                ; выбор и чтение начальной колонки правого ребра
                DEC L
                LD E, (HL)
                INC L
                ; -----------------------------------------
                ; Прямой поиск конца ребра
                ; -----------------------------------------
                ; проверка последнего строкового индекса перед продвижением пары
Next:           LD A, L
                CP #00
                JR Z, @D3D.WrapPreviewRightEdge.Entry                           ; переход, если текущий индекс равен последнему, выбрать первую строку кольца

                ; переход к строковому байту следующей точки в странице C8
                INC L
                INC L
                ; чтение строки кандидата конца правого ребра
ReadRow:        LD A, (HL)
                ; расчёт высоты кандидата относительно текущей строки Y
                SUB D
                JR Z, @D3D.UpdatePreviewRightEdge.Next                          ; переход, если высота нулевая, продолжить прямой поиск

                JR C, @D3D.UpdatePreviewRightEdge.Next                          ; переход, если строка кандидата ниже Y по байтовому сравнению, продолжить прямой поиск

                ; сохранение выбранного конца правого ребра в изменяемом указателе
                LD (@PreviewPolygonEdgeState.RightVertex), HL
                ; сохранение высоты и периода правой ошибки
                LD D, A
                LD (@PreviewPolygonState.RightHeight), A
                ; расчёт начальной половины высоты правого ребра
                SRL A
                ; сохранение ошибки в H', левый накопитель L' остаётся прежним
                EXX
                LD H, A
                EXX
                ; чтение и сохранение строки окончания правого ребра
                LD A, (HL)
                LD (@PreviewPolygonState.RightEndRow), A
                ; выбор колонки конечной точки перед её строкой
                DEC L
                LD A, (HL)
                ; расчёт горизонтального смещения конца относительно начальной колонки
Slope:          SUB E
                JP C, @D3D.UpdatePreviewRightEdge.Negative                      ; переход, если конечная колонка меньше начальной, подготовить отрицательный правый наклон

                ; проверка длинного неотрицательного правого наклона
                CP D
                JP C, @D3D.UpdatePreviewRightEdge.ShortPositive                 ; переход, если длина по колонкам меньше высоты, выбрать короткий положительный шаг

                ; -----------------------------------------
                ; Неотрицательный длинный правый наклон
                ; -----------------------------------------
                ; подготовка делимого и нулевого старшего остатка
                LD E, A
                XOR A
                CALL @D3D.DividePreviewSlopeByte.Entry
                ; объединение дополненного частного, остаток остаётся в A
                RL E
                ; проверка точности целого правого шага
                AND A
                JR Z, @D3D.UpdatePreviewRightEdge.ExactPositive                 ; переход, если остаток нулевой, использовать точный правый шаг

                ; расчёт дробной ошибки h-r для целого шага q+1
                SUB D
                NEG
                ; обновление вычитаемой правой ошибки
                LD (@PreviewPolygonState.RightSubtract), A
                ; расчёт q+1 и его перепаковка в DE' со сдвигом на пять разрядов
                LD A, E
                NEG
                SRL A
                EXX
                LD E, #00
                RR E
                RRA
                RR E
                RRA
                RR E
                ; добавление строкового шага в старший байт DE', флаги этого ADD возвращаются
                ADD A, @PreviewPolygonConst.RowStepHigh
                LD D, A
                EXX
                ; восстановление H страницы масок и D=D1 без восстановления AF
                POP HL
                LD D, L
                JP @D3D.StepPreviewPolygonRow.DrawRow

                ; -----------------------------------------
                ; Точный неотрицательный правый наклон
                ; -----------------------------------------
                ; обнуление правой ошибки при нулевом остатке
ExactPositive:  LD (@PreviewPolygonState.RightSubtract), A
                ; восстановление q инверсией и перепаковка в DE'
                LD A, E
                CPL
                RRA
                EXX
                LD E, #00
                RR E
                SRA A
                RR E
                SRA A
                RR E
                ; добавление строкового шага к точной целой части, A и F остаются от ADD
                ADD A, @PreviewPolygonConst.RowStepHigh
                LD D, A
                EXX
                ; восстановление масок и страницы развёрнутой записи
                POP HL
                LD D, L
                JP @D3D.StepPreviewPolygonRow.DrawRow

                ; -----------------------------------------
                ; Короткий неотрицательный правый наклон
                ; -----------------------------------------
                ; расчёт h-dx, NEG задаёт возвращаемые A и F этой ветви
ShortPositive:  SUB D
                NEG
                ; обновление вычитаемой правой ошибки без деления
                LD (@PreviewPolygonState.RightSubtract), A
                ; подготовка DE'=2020, целый шаг один пиксель с последующей дробной компенсацией
                EXX
                LD E, @PreviewPolygonConst.PixelStepLo
                LD D, E
                EXX
                ; восстановление масок и D, флаги NEG сохраняются
                POP HL
                LD D, L
                JP @D3D.StepPreviewPolygonRow.DrawRow

                ; -----------------------------------------
                ; Отрицательный правый наклон
                ; -----------------------------------------
                ; расчёт модуля отрицательного смещения
Negative:       NEG
                ; проверка необходимости деления модуля на высоту
                CP D
                JR C, @D3D.UpdatePreviewRightEdge.ShortNegative                 ; переход, если модуль меньше высоты, подготовить нулевую целую пиксельную часть

                ; подготовка модуля делимого и нулевого старшего остатка
                LD E, A
                XOR A
                CALL @D3D.DividePreviewSlopeByte.Entry
                ; сохранение остатка деления как вычитаемой правой ошибки
                LD (@PreviewPolygonState.RightSubtract), A
                ; объединение последнего бита дополненного частного в A, E намеренно остаётся половинным
                LD A, E
                RLA
                ; расчёт отрицательной целой части -q и её знаковое расширение
                INC A
                SCF
                RRA
                ; перепаковка отрицательного целого шага в DE', SRA сохраняет знак
                EXX
                LD E, #00
                RR E
                SRA A
                RR E
                SRA A
                RR E
                ; добавление строковой части к знаковому шагу, возвращаются A и F этого ADD
                ADD A, @PreviewPolygonConst.RowStepHigh
                LD D, A
                EXX
                ; восстановление H страницы масок и D перед рисунком текущей строки
                POP HL
                LD D, L
                JP @D3D.StepPreviewPolygonRow.DrawRow

                ; -----------------------------------------
                ; Короткий отрицательный правый наклон
                ; -----------------------------------------
                ; сохранение модуля целиком как дробной ошибки, F остаётся от CP с высотой
ShortNegative:  LD (@PreviewPolygonState.RightSubtract), A
                ; подготовка DE'=2000 без целой пиксельной части
                EXX
                LD E, #00
                LD D, @PreviewPolygonConst.RowStepHigh
                EXX
                ; восстановление масок и D с сохранением точных A и F короткой отрицательной ветви
                POP HL
                LD D, L
                JP @D3D.StepPreviewPolygonRow.DrawRow

                ; -----------------------------------------
                endmodule
                endmodule
