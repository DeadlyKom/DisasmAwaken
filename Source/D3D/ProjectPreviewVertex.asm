                ; расчёт обёрнутой глубины вершины
                ADC HL, DE
                JP M, @D3D.ProjectPreviewVertex.RejectFirst                     ; переход, если глубина отрицательна, записать отказ с ещё исходной базой глубины

                ; сохранение принятой глубины в DE как знаменателя обоих делений
                EX DE, HL
                ; -----------------------------------------
                ; Первая ось и первое деление
                ; -----------------------------------------
                ; чтение первой локальной координаты из сохраняемого набора
                EXX
                LD A, E
                EXX
                ; расчёт знакового слова первой локальной координаты
                LD L, A
                RLCA
                AND @PreviewPerspectiveConst.SignBitMask
                NEG
                LD H, A
                ; чтение базы первой оси ResultSecond из изменяемого операнда
                LD BC, #0000
                ; масштаб первой оси, смещение заранее получает 6-b
