                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ; очистка Carry перед сложением первой оси с её базой
                AND A
                ; расчёт обёрнутой первой координаты вершины
