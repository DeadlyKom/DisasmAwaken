                ; Документация [перспектива одной вершины](../../Docs/PreviewPerspective.md)
                ; -----------------------------------------
                ; Перспектива одной вершины с двумя знаковыми делениями, маркерами отказа и пятибайтовым шагом рабочего SP
                ; исходная запись 6, банк 4, файловые смещения #1A14..#1BD8
                ; In:
                ;   HL - адрес непрямого продолжения, обычный CALL/RET для этой фазы не используется
                ;   DE - E первая локальная координата, D вторая, обе знаковые байтовые
                ;   BC - сохраняемый контекст группы, AF - A третья локальная координата
                ;   ResultThird, ResultSecond, ResultFirst содержат базы глубины, первой и второй осей
                ;   три JR заранее подготовлены ConfigurePreviewProjectionScale для показателя b=1..6
                ;   D3DClipState.HalfXLow и HalfYLow являются младшими байтами слов центров, старшие байты сохраняются
                ;   SP=p указывает на рабочий буфер, доступны p-6..p-1, во время штатного прохода p начинается с C604
                ;   банк 4 доступен для записи, прерывания отключены, NMI и повторный вход исключены
                ; Out:
                ;   HL, DE и BC сохранены, управление передано через JP (HL), IX и IY сохранены
                ;   AF содержит точный результат выбранного пути, флаги последнего ADD HL,SP сохраняют S/Z/PV предшествующей арифметики
                ;   HL' равен p+5, DE' при успехе содержит центр второй оси, при отказе маркер 8000 с младшим байтом глубины либо её базы
                ;   BC' при успехе содержит прежнее слово по p-6, при отказе оси её базу, при отрицательной глубине сохранён
                ;   AF' при успехе содержит старший байт модуля частного второй оси и флаги делителя, при отказе оси её сохранённый знаковый контекст
                ;   при отрицательной глубине AF' сохраняется, точные формулы всех AF и AF' приведены в PreviewPerspective.md и числовой модели
                ;   I, IFF и IM сохраняются, SP=p+5, CPU-адрес возврата с памяти стека не читается
                ;   по p-2 и p-4 записаны два слова результата либо маркеры отказа, байт p не записывается
                ;   успех дополнительно обновляет SecondOutput и PreserveTarget, затем переписывает прежнее слово по p-6 тем же значением
                ; Corrupt:
                ;   AF, HL', DE', BC', AF', SP, четыре байта рабочего результата, при успехе также два операнда и повторная запись по p-6
                ; Note:
                ;   после знакового расширения и масштаба каждая сумма с базой оборачивается до слова, P/V не является условием отказа
                ;   отрицательная глубина отклоняется до EX DE,HL, её маркер использует ещё исходную базу глубины
                ;   при z=0 или модуле оси не меньше 128*z выполняется отказ, иначе результат равен знаковому trunc(256*n/z) плюс центр
                ;   первый и второй результаты лежат по p-2 и p-4, после двух PUSH прибавляется 9, общий шаг равен 5
                ;   модель проверяет локальный контракт, генерация группы вершин и весь игровой кадр проверяются отдельно
                ; -----------------------------------------
                ; -----------------------------------------
                ; Глубина и сохранение контекста продолжения
                ; -----------------------------------------
                ; сохранение BC, DE и адреса продолжения HL через обмен наборами
Entry:          EXX
                ; чтение базы глубины ResultThird из заранее обновлённого операнда
                LD DE, #0000
                ; расчёт знакового слова третьей локальной координаты, H получает 00 или FF
                LD L, A
                RLCA
                AND @PreviewPerspectiveConst.SignBitMask
                NEG
                LD H, A
                ; масштаб глубины, исходный JR FE должен быть заранее подготовлен как пропуск 6-b
