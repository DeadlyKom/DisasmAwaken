                module D3D
                module LookupPreviewProductC
                ; Документация [табличные приближения произведения](../../Docs/PreviewLookupProducts.md)
                ; -----------------------------------------
                ; Табличная аппроксимация произведения байтов A и C через разность свёрнутых квадратов
                ; исходная запись 6, банк 4, файловые смещения #1532..#153E
                ; In:
                ;   HL - H=C3, страница исходной FoldedSquare127, младший L произвольный
                ;   DE - E рабочий выход таблицы, D сохраняемый контекст
                ;   BC - входной множитель находится в C, оба регистра сохраняются
                ;   AF - A первый знаковый байтовый множитель, входной F не является параметром
                ; Out:
                ;   HL - H=C3, L индекс суммы половин по точной формуле алгоритма
                ;   DE - D сохранён, E содержит значение таблицы по индексу разности половин, BC сохранён
                ;   AF - A разность двух табличных значений по модулю 256, F от последнего SUB, P/V=0 для исходной страницы C3
                ;   HL', DE', BC', AF', IX, IY, I, IFF и IM сохраняются, SP обычного возврата равен входному SP+2
                ;   память и порты не записываются, входной множитель C сохранён
                ; Corrupt:
                ;   HL, DE, AF
                ; Note:
                ;   обе арифметические половины округляются вниз, включая отрицательные нечётные значения
                ;   индекс разности равен SRA(A)-SRA(C) по модулю 256, индекс суммы получается добавлением полного исходного C
                ;   точная таблица T(i)=floor(min(i,255-i)^2/127), отрицательные индексы сворачиваются дополнением, а не модулем знакового числа
                ;   это аппроксимация произведения через разность квадратов, она не равна точному умножению с делением на 128
                ;   входной 80 обрабатывается исходными сдвигами и таблицей без отдельного исправления
                ;   договор доказан для исходной страницы C3, произвольная другая страница в H не подтверждается
                ; -----------------------------------------
                ; расчёт арифметической половины первого множителя с округлением вниз
Entry:          SRA A
                ; чтение второго множителя C перед вычислением его половины
                LD L, C
                ; расчёт арифметической половины второго множителя, отрицательные нечётные округляются вниз
                SRA L
                ; расчёт байтового индекса разности половин с исходным оборачиванием
                SUB L
                LD L, A
                ; расчёт индекса суммы добавлением полного исходного второго множителя
                ADD A, C
                ; поиск первого значения свёрнутого квадрата по индексу разности
                LD E, (HL)
                LD L, A
                ; поиск второго значения по индексу суммы
                LD A, (HL)
                ; расчёт разности квадратов, возвращаемой как байтовое приближение произведения
                SUB E
                RET

