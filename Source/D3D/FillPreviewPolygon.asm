                module D3D
                module FillPreviewPolygon
                ; Документация [подготовка контура, верхние цепочки, полный локальный контракт и точные пределы проверки](../../Docs/PreviewPolygonFill.md)
                ; -----------------------------------------
                ; Подготовка двух границ и шаблона, временного стека и полный проход заливки многоугольника
                ; исходная запись 6, банк 4, файловые смещения #141B..#14DE
                ; In:
                ;   HL - контекст вызывающего, сохраняется через CPU-стек
                ;   DE и BC не задают геометрию, AF не задаёт координаты, входной Carry сохраняется только в раннем AF'
                ;   HL', DE', BC', AF', IX и IY входной контекст, при непустой высоте используются как рабочие
                ;   PreviewContourSize.Value.ByteCount содержит чётную длину 6..254, C800 пары колонка и строка
                ;   PreviewFillMode.Value.Index выбирает шаблон, полный профиль заливки доказан для 0..4
                ;   контур выпуклый с верхним обходом вправо, координаты внутри 256 на 192, таблицы от начала bitmap подготовлены BuildSpriteLineTable
                ;   SP указывает на CPU-возврат, под ним два байта для HL, под FFE0 шесть свободных рабочих байтов
                ;   во время временного SP нет аппаратных IRQ и повторного входа в общие операнды
                ; Out:
                ;   HL сохранён, SP после обычного RET равен входному+2
                ;   DE при непустой высоте содержит D=D1 и точный остаток последнего края, при горизонтальном контуре DE=Y*257
                ;   BC при непустой высоте фактический указатель после последней строки, при горизонтальном контуре BC=1
                ;   AF содержит A нижнюю исключённую строку Y, F=42 OR (Y AND 28)
                ;   HL', DE', BC', AF', IX и IY при непустой высоте имеют точные конечные значения по формулам документации
                ;   при горизонтальном контуре HL', DE', BC', IX и IY сохранены, AF' содержит 2*n-1 и F от DEC с входным Carry
                ;   I, IFF и IM сохранены, банк не переключается, bitmap меняется только внутри геометрического полуинтервала
                ;   сохранены исходные попытки записи неизменённого значения в ROM у схлопнувшегося правого края
                ; Corrupt:
                ;   DE, BC, AF, HL', DE', BC', AF', IX, IY, CPU-стек, временный стек, bitmap и рабочие операнды
                ; Note:
                ;   первый минимум выбирается строго, одинаковая высота всех точек возвращает управление до смены SP
                ;   весь верхний плоский участок обходится раздельно назад и вперёд, выбранные начала сохраняются в двух операндах
                ;   парность длины и допустимость индекса исходный код не проверяет, нулевой счётчик не означает пустой контур
                ;   индексы 5..7 проверены только до цикла, их крайние маски не объявляются обычной очисткой
                ;   подготовка завершается настоящим JP в StepPreviewPolygonRow.CheckLastRow, а не RET
                ;   точное конечное состояние двух цепочек и Carry экранной строки проверено полной независимой моделью 10728 контуров
                ; -----------------------------------------
                ; -----------------------------------------
                ; Размер контура и диапазон строк
                ; -----------------------------------------
                ; сохранение HL вызывающего в обычном CPU-стеке до временной подмены SP
Entry:          PUSH HL
                ; чтение байтовой длины пар колонка и строка
                LD A, (@PreviewContourSize.Value.ByteCount)
                LD B, A
                ; расчёт последнего нечётного индекса строковой координаты
                DEC A
                ; обновление операнда границы кольца прямой цепочки
                LD (@PreviewPolygonEdgeState.LastIndex), A
                ; сохранение последнего индекса в AF' для двух верхних обходов
                EX AF, AF'
                ; расчёт числа точек делением байтовой длины на два без проверки парности
                SRL B
                ; выбор первого строкового байта страницы C8
                LD HL, @PreviewPolygonPrepConst.FirstPointRow
                ; начальные значения минимума FF и максимума 00 для экранных строк
                LD DE, #FF00
                ; чтение очередной строки контура
FindRowRange:   LD A, (HL)
                ; проверка строгого обновления минимума, первая равная точка остаётся выбранной
                CP D
                JP NC, @D3D.FillPreviewPolygon.CheckMaximum                     ; переход, если строка не меньше текущего минимума, сохранить ранее выбранный индекс

                ; сохранение новой минимальной строки и её нечётного индекса
                LD D, A
                LD C, L
                ; проверка верхнего числового предела строк для общего завершения
CheckMaximum:   CP E
                JP C, @D3D.FillPreviewPolygon.NextRow                           ; переход, если строка меньше текущего максимума, не менять нижний предел рисунка

                ; сохранение максимальной строки контура
                LD E, A
                ; продвижение на следующую пару внутри страницы C8
NextRow:        INC L
                INC L
                DJNZ @D3D.FillPreviewPolygon.FindRowRange

                ; проверка совпадения минимальной и максимальной строки
                LD A, E
                CP D
                JP Z, @D3D.StepPreviewPolygonRow.RestoreHL                      ; переход, если все строки равны, восстановить HL и выйти до подмены SP

                ; обновление исключённой нижней строки всего рисунка
                LD (@PreviewPolygonState.LastRow), A
                ; обновление начальных пределов обеих цепочек минимальной строкой
                LD A, D
                LD (@PreviewPolygonState.LeftEndRow), A
                LD (@PreviewPolygonState.RightEndRow), A
                ; сохранение минимальной строки в B и выбор первого минимального индекса
                LD B, D
                LD L, C
                ; -----------------------------------------
                ; Последняя верхняя точка обратной цепочки
                ; -----------------------------------------
                ; сохранение текущего верхнего индекса перед проверкой предыдущего
PreviousTop:    LD E, L
                ; переход к колонке перед предыдущим строковым байтом
                DEC L
                JR Z, @D3D.WrapPreviewTopLeft.Entry                             ; переход, если достигнута нулевая колонка, обернуть обратный поиск через конец кольца

                ; выбор и проверка предыдущей строки относительно минимального Y
ReadLeftTop:    DEC L
                CP (HL)
                JR Z, @D3D.FillPreviewPolygon.PreviousTop                       ; переход, если предыдущая строка также минимальная, продолжить верхний обратный обход

                ; восстановление последней верхней точки обратного обхода
                LD L, E
                ; обновление исходного указателя левого ребра
                LD (@PreviewPolygonEdgeState.LeftVertex), HL
                ; возврат к первому минимуму перед независимым прямым обходом
                LD L, C
                ; -----------------------------------------
                ; Последняя верхняя точка прямой цепочки
                ; -----------------------------------------
                ; сохранение текущего индекса и выбор последнего индекса из AF'
NextTop:        LD E, L
                EX AF, AF'
                ; проверка конца кольца перед продвижением к следующей верхней точке
                CP L
                JR Z, @D3D.WrapPreviewTopRight.Entry                            ; переход, если текущий индекс последний, выбрать первую строку кольца

                ; продвижение к строковому байту следующей пары
                INC L
                INC L
                ; восстановление минимального Y и проверка строки следующей точки
ReadRightTop:   EX AF, AF'
                CP (HL)
                JR Z, @D3D.FillPreviewPolygon.NextTop                           ; переход, если следующая строка тоже минимальная, продолжить прямой верхний обход

                ; восстановление последнего верхнего индекса прямого обхода
                LD L, E
                ; обновление исходного указателя правого ребра
                LD (@PreviewPolygonEdgeState.RightVertex), HL
                ; -----------------------------------------
                ; Шаблон внутренних байтов
                ; -----------------------------------------
                ; чтение индекса пары заполнения
                LD A, (@PreviewFillMode.Value.Index)
                ; расчёт байтового смещения пары Pattern и RowXor
                ADD A, A
                LD C, A
                ; выбор исходной пары на странице D1
                LD H, @PreviewPolygonPrepConst.PatternPage
                LD L, A
                ; чтение первого шаблона строки в A', F' остаётся от удвоения индекса
                LD A, (HL)
                EX AF, AF'
                ; выбор второго поля пары, XOR для следующей строки
                INC L
                LD A, (HL)
                ; обновление операнда смены шаблона общего цикла
                LD (@PreviewPolygonState.PatternDelta), A
                ; -----------------------------------------
                ; Упакованная левая граница и экранная строка
                ; -----------------------------------------
                ; чтение колонки выбранного начала обратной цепочки
                LD HL, (@PreviewPolygonEdgeState.LeftVertex)
                DEC L
                LD E, (HL)
                ; чтение горизонтального начала из первого байта таблицы колонок
                LD H, @PreviewPolygonPrepConst.ColumnPage
                LD L, #00
                LD A, (HL)
                ; выбор строки адресных таблиц по минимальному Y
                LD L, B
                ; обновление горизонтального начала экранного адреса
                LD (@PreviewPolygonState.ColumnBase), A
                ; выбор страницы старших адресов экранных строк
                LD H, @PreviewEdgeRasterConst.RowHighPage
                ; расчёт упаковки Y и X, три младших бита строки занимают старшие разряды границы
                XOR A
                SRL B
                RR E
                RRA
                SRL B
                RR E
                RRA
                ; введение старшего бита временного B перед последним циклом упаковки
                SCF
                RR B
                RR E
                RRA
                ; добавление индекса шаблона к младшей части упакованной левой границы
                ADD A, C
                ; сохранение двух частей границы в IX
                LD IXL, A
                LD IXH, E
                ; чтение старшего и младшего экранных адресов начальной строки
                LD B, (HL)
                INC H
                LD A, (HL)
                ; обновление временного операнда младшего адреса строки
                LD (@PreviewPolygonPrepState.FirstRowLow), A
                ; -----------------------------------------
                ; Упакованная правая граница
                ; -----------------------------------------
                ; чтение колонки выбранного начала прямой цепочки
                LD HL, (@PreviewPolygonEdgeState.RightVertex)
                DEC L
                LD E, (HL)
                ; расчёт той же упаковки начальной строки и правой колонки
                XOR A
                SRL D
                RR E
                RRA
                SRL D
                RR E
                RRA
                ; введение старшего бита временного D перед последним циклом упаковки
                SCF
                RR D
                RR E
                RRA
                ; добавление индекса шаблона и смещения правых масок 10
                ADD A, C
                ADD A, @PreviewPolygonPrepConst.RightMaskOffset
                ; сохранение двух частей правой границы в IY
                LD IYL, A
                LD IYH, E
                ; -----------------------------------------
                ; Первый экранный адрес и запуск цикла
                ; -----------------------------------------
                ; расчёт левой байтовой колонки без строковых разрядов IXH
                LD A, IXH
                AND @ScreenConst.ColumnMask
                ; объединение колонки с сохранённым младшим адресом начальной строки
                OR #00
                LD C, A
                ; добавление подготовленного горизонтального начала
                LD A, (@PreviewPolygonState.ColumnBase)
                ADD A, C
                LD C, A
                ; выбор страницы развёрнутой записи и первой страницы масок
                LD D, @PreviewPolygonConst.SpanPage
                LD H, @PreviewPolygonPrepConst.FirstMaskPage
                ; чтение минимальной строки для первичной проверки общего цикла
                LD A, (@PreviewPolygonState.LeftEndRow)
                ; сохранение CPU-SP, который уже указывает на сохранённый HL
                LD (@PreviewPolygonState.SavedStack), SP
                ; подмена SP для дробной поправки границ на минус один пиксель
                LD SP, @PreviewPolygonConst.ErrorStep
                ; первичный вход в проверку строки без предварительного продвижения
                JP @D3D.StepPreviewPolygonRow.CheckLastRow

                ; -----------------------------------------
                endmodule
                endmodule
