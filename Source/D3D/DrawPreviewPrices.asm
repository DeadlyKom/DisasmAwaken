                module D3D
                module DrawPreviewPrices
                ; Документация [описания моделей](../../Docs/PreviewPrices.md)
                ; -----------------------------------------
                ; Вывод цен доступных моделей либо одной собственной модели с временным ограничителем текста
                ; исходная запись 6, банк 4, файловые смещения #20C5..#2123
                ; In:
                ;   HL - H=0 для рыночного суффикса списка, любой ненулевой H для одной собственной модели, L не используется как индекс
                ;   BC - сохраняемый контекст, кроме C выбранного индекса на собственном пути, AF - A селектор, ровно 1 выбирает скимеры
                ;   AF' - A' начальный индекс, для исходного рынка кораблей 0..5, скимеров 0..3, собственных кораблей 0..6
                ;   подключён банк 4, ценовые потоки доступны для временной записи, окно, колонки и реальный глиф подготовлены по договорам PrintText и PrintAfterCR, LineEndCode=C3 продолжает поток после CR
                ; Out:
                ;   HL - позиция завершения тела PrintAfterCR, DE - сохранён при H=0, иначе адрес временно изменённого конца записи
                ;   BC - сохранён при H=0, иначе B сохранён и C равен входному индексу A'
                ;   AF - 0044 при H=0 независимо от успеха печати, иначе настоящий статус PrintAfterCR
                ;   HL', DE', BC' сохранены, AF' - A'=1+(((CursorY-24) AND FF) SHR 3), F' от INC этого частного после AND 1F
                ;   IX, IY, I, IFF и IM сохранены, SP обычного возврата равен входному SP+2
                ;   BaseOperand получает входной A', курсор, bitmap и рабочее состояние печати соответствуют двум реальным текстовым проходам
                ; Corrupt:
                ;   HL, DE, BC, AF, AF'
                ; Note:
                ;   заголовок всегда запускается с курсора 0,8, тело с 0,24, отказ заголовка не отменяет тело
                ;   начальный разделитель Karen всегда устанавливается в LF, затем только на собственном индексе 6 становится CR и остаётся CR до следующего вызова
                ;   собственный путь временно заменяет один найденный CR на LF, после печати возвращает именно прочитанный исходный байт
                ;   временный конец ищется по index+2 разделителям CR, тело выбирается по index+1, LF при поиске CR не завершает поиск
                ;   код не проверяет допустимый индекс, для произвольного A' действуют ограничения и оборачивание SkipCrRecords
                ;   возвращаемое A' вычисляется из конечного CursorY, не доказывает число полностью напечатанных строк
                ;   рыночный путь возвращает прежний 0044 через EX AF,AF', поэтому AF не является общим статусом последней печати
                ; -----------------------------------------
                ; сохранение режима из H и селектора A на время вывода заголовка
Entry:          PUSH HL
                PUSH AF
                ; восстановление исходной границы рыночного списка перед Карэном в LF
                LD A, @TextConst.LineFeed
                LD (@PreviewPrices.Karen), A
                ; задание начального курсора заголовка X=0, Y=8
                LD HL, @PreviewPriceConst.HeadingCursor
                LD (@TextWindow.CursorX), HL
                ; вывод настоящего заголовка Модель и Цена, его отказ не отменяет тело
                LD HL, @PreviewPrices.Heading
                CALL @Station.PrintText.Entry
                ; задание начального курсора тела X=0, Y=24
                LD HL, @PreviewPriceConst.BodyCursor
                LD (@TextWindow.CursorX), HL
                ; восстановление селектора и проверка особого значения 1
                POP AF
                DEC A
                LD HL, @PreviewPrices.Dominion
                JR NZ, @D3D.DrawPreviewPrices.SelectMode                        ; переход, если исходный селектор не равен 1, сохранить ценовой поток кораблей

                LD HL, @PreviewPrices.Fervest
                ; извлечение прежнего H в A для выбора рыночного либо собственного режима
SelectMode:     POP AF
                ; проверка нулевого режима рыночного списка
                OR A
                JR Z, @D3D.DrawPreviewPrices.MarketList                         ; переход, если исходный H равен нулю, вывести суффикс рыночного списка

                ; сохранение начала потока и извлечение выбранного индекса из альтернативного A
                PUSH HL
                EX AF, AF'
                LD C, A
                EX AF, AF'
                LD A, C
                ; проверка особого индекса 6, описывающего Карэн
                CP @PreviewPriceConst.KarenIndex
                JR NZ, @D3D.DrawPreviewPrices.BoundRecord                       ; переход, если индекс не равен 6, границу перед Карэном не открывать

                ; замена LF перед Карэном на CR для поиска собственного корабля с индексом 6
                LD A, @TextConst.CarriageReturn
                LD (@PreviewPrices.Karen), A
                ; расчёт числа CR для нахождения конца выбранной записи
BoundRecord:    LD A, C
                INC A
                ; поиск index+2 ограничителей CR через общий помощник
                CALL @Station.SkipCrRecords.Entry
                ; возврат к найденному разделителю для временного ограничения одной записи
                DEC HL
                ; сохранение исходного разделителя и его временная замена на LF
                LD A, (HL)
                LD (HL), @TextConst.LineFeed
                ; сохранение адреса разделителя в DE и восстановление начала таблицы
                EX DE, HL
                POP HL
                ; выбор индекса для печати и сохранение исходного разделителя в альтернативном A
                EX AF, AF'
                ; сохранение начального индекса для выбора модели и описаний
                LD (@D3DPreviewState.BaseOperand), A
                ; вывод одной записи с реальной обработкой управляющих кодов
                CALL @Station.PrintAfterCR.Entry
                ; восстановление разделителя, результат печати остаётся в альтернативном AF
                EX AF, AF'
                LD (DE), A
                JR @D3D.DrawPreviewPrices.CountRows

                ; выбор начального индекса рынка, прежний 0044 сохраняется в альтернативном AF
MarketList:     EX AF, AF'
                ; сохранение базы для последующей суммы с номером строки
                LD (@D3DPreviewState.BaseOperand), A
                ; вывод доступного суффикса до исходного LF без временного ограничения
                CALL @Station.PrintAfterCR.Entry
                ; расчёт количества строк из байтовой разности конечного Y и начального 24
CountRows:      LD A, (@TextWindow.CursorY)
                SUB @PreviewPriceConst.BodyY
                ; деление байтовой разности на восемь с удалением обёрнутых старших разрядов
                RRCA
                RRCA
                RRCA
                AND @RowSelectConst.RowMask
                ; переход от номера последней строки к количеству и возврат через альтернативный AF
                INC A
                EX AF, AF'
                RET

                endmodule
                endmodule
