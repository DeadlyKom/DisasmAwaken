                module D3D
                module CountPreviewTextRows
                ; Документация [описания моделей](../../Docs/PreviewDescriptions.md)
                ; -----------------------------------------
                ; Подсчёт выровненных строк выбранного описания корабля либо скимера
                ; исходная запись 6, банк 4, файловые смещения #2124..#213B
                ; In:
                ;   HL и DE входных аргументов не задают, BC содержит сохраняемый до подсчёта B, C заменяется RowOperand
                ;   AF содержит A как селектор, ровно 1 выбирает скимеры, остальные значения выбирают корабли
                ;   RowOperand и BaseOperand содержат байтовые компоненты выбора, выбранный текст имеет читаемый запас и достигает конечного LF
                ;   подключён банк 4, действуют договоры SkipLfRecords и CountTextRows, окно и исходный префикс сухого глифа подготовлены
                ; Out:
                ;   HL, DE, BC и AF возвращаются от настоящего CountTextRows, DE число сухих проходов по модулю 65536, включая завершающий
                ;   Carry всегда установлен на возвращающемся пути, он принадлежит последнему сухому проходу, не переносу суммы индексов
                ;   при Height<14 HL сохраняет позицию после SkipLfRecords, DE=1, BC содержит входной B и RowOperand
                ;   HL', DE', BC', AF', IX, IY, I, IM и IFF сохраняются, SP после RET равен входному SP+2
                ;   начало подсчёта выбрано после ((RowOperand+BaseOperand) AND FF)+1 ограничителей LF
                ;   курсор и рабочий префикс глифа меняются по договору подсчёта, экран не рисуется, R не сверялся
                ; Corrupt:
                ;   HL, DE, BC, AF, R
                ; Note:
                ;   сумма компонентов байтовая, перенос не расширяет индекс, ноль в сумме выбирает первую запись
                ;   проверки 7 кораблей или 4 скимеров в коде нет, выход за таблицу использует общий поиск LF и может обойти память
                ;   первый лимит поиска FF00 OR RowOperand, последующие ограничения и возможное незавершение принадлежат SkipLfRecords
                ;   CountTextRows также может не завершиться при неподходящей ширине, это исходная особенность, не исправление
                ; -----------------------------------------
                ; выбор основного потока описаний кораблей по умолчанию
Entry:          LD HL, @PreviewShipText.Dominion
                ; проверка особого селектора 1 для потока описаний скимеров
                DEC A
                JR NZ, @D3D.CountPreviewTextRows.SelectedText                   ; переход, если исходный селектор не равен 1, сохранить основной поток

                ; выбор исходного потока описаний скимеров
                LD HL, @PreviewSkimText.Fervest
                ; чтение компонента строки, его значение станет C первого лимита поиска
SelectedText:   LD A, (@D3DPreviewState.RowOperand)
                LD C, A
                ; чтение компонента смещения списка
                LD A, (@D3DPreviewState.BaseOperand)
                ; расчёт номера описания по модулю 256
                ADD A, C
                ; поиск начала записи через A+1 исходных разделителей LF
                CALL @Station.SkipLfRecords.Entry
                ; подсчёт реальных выровненных строк выбранного текста без рисования
                CALL @Station.CountTextRows.Entry
                RET

                endmodule
                endmodule
