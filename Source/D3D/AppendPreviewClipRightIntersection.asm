                module D3D
                module AppendPreviewClipRightIntersection
                ; Документация [полный и кэшированный входы, однокомплементное деление, насыщение, сохранение младшего байта и точные регистры](../../Docs/PreviewClipIntersections.md)
                ; -----------------------------------------
                ; Пересечение с границей Right и запись исходной байтовой проекции в контур C8
                ; исходная запись 6, банк 4, файловые смещения #2757..#27B3
                ; In:
                ;   HL и DE не являются входами, BC сохраняемый контекст соответствующих ветвей вложенной арифметики
                ;   AF полного Entry не задаёт результат, внутренний FromProduct использует входной Carry как будущий Carry альтернативного AF делителя
                ;   HL', DE', BC' сохраняются, AF' перезаписывается числителем и делением, IX контекст короткого умножения, IY сохраняется
                ;   PreviewClipFirst и PreviewClipSecond содержат слова координат, все граничные операнды подготовлены ConfigurePreviewClip
                ;   FromProduct принимает готовый кэш Right, полный Entry предварительно вызывает его настоящий производитель
                ;   знаковое слово второго минус первого для колонок ненулевое, U<abs(d)*65536 для фактического результата умножителя
                ;   ByteCount=N задаёт байтовый курсор C8, под CPU-SP доступны шесть байтов полного Entry либо два кэшированного
                ; Out:
                ;   HL=C800+((N+2) AND FF), DE зависит от ветви проекции, точные формулы в документации
                ;   BC от делителя, если числитель отрицателен это его исходное старшее слово, иначе при отрицательном d исходный d
                ;   при неотрицательных входах деления BC сохраняется от внешнего FromProduct либо возвращается производителем полного Entry
                ;   AF - A новый ByteCount, F от второго INC L, Carry установлен только при сохранении младшего байта строки
                ;   HL', DE', BC' сохранены, AF' содержит младший байт слова частного и точный F' делителя
                ;   IXH от производителя либо входного FromProduct, IXL число отрицательных входов деления минус один по модулю 256, IY сохранён
                ;   SP после RET равен входному+2, I, IFF и IM сохранены, координатные записи не меняются
                ;   два байта проекции и новый ByteCount записаны, полный Entry также обновляет четыре байта кэша Right
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', IX, два байта C8, ByteCount, кэш полного Entry и вложенный CPU-стек
                ; Note:
                ;   выбранная фиксированная граница максимальная колонка, вычисляемая координата строка
                ;   при отрицательном H строка насыщается минимумом, иначе L<192 сохраняется даже при ненулевом положительном H
                ;   угловые границы не нормализуются, начальный ByteCount может оборачиваться только внутри C8
                ;   нулевой знаменатель и переполнение слова частного исключены договором, исходный код проверки не добавляет
                ;   возвращаемый Carry характеризует ветвь проекции, окончательный приём контура проверяет внешний диспетчер
                ; -----------------------------------------
                ; полная подготовка кэша Right настоящим производителем перед пересечением
Entry:          CALL @D3D.BuildPreviewClipRightProduct.Entry
                ; внутренний вход с готовым кэшем, чтение младшего байта 32-битного числителя
FromProduct:    LD A, (@PreviewClipRightProduct.Value.LowWord)
                ; сохранение младшего байта числителя в A' вместе с текущим Carry
                EX AF, AF'
                ; чтение следующего байта числителя в основной A
                LD A, (@PreviewClipRightProduct.Value.LowWord + 1)
                ; чтение координат второго и первого конца для знаменателя по оси колонок
                LD HL, (@PreviewClipSecond.Value.SecondAxis)
                LD DE, (@PreviewClipFirst.Value.SecondAxis)
                ; сброс Carry перед обёрнутой разностью знаменателя
                OR A
                ; расчёт знаменателя, его S передаётся делителю как знак
                SBC HL, DE
                ; перенос знаменателя в DE без изменения флагов
                EX DE, HL
                ; чтение старшей половины числителя с сохранением S знаменателя
                LD HL, (@PreviewClipRightProduct.Value.HighWord)
                ; деление настоящим EA01, однокомплементный результат не заменяется обычным частным
                CALL @D3D.DividePreviewClip32To16.Entry
                ; чтение исходного начала вычисляемой координаты
                LD DE, (@PreviewClipFirst.Value.FirstAxis)
                ; расчёт итогового слова координаты прибавлением начала по модулю 65536
                ADD HL, DE
                ; проверка старшего байта результата для исходного преобразования в байтовый контур
                LD A, H
                AND A
                JP M, @D3D.AppendPreviewClipRightIntersection.MinRow            ; переход, если старший байт координаты отрицателен, записать минимальную строку

                ; чтение младшего байта строки, положительный старший байт отдельно не отвергается
                LD A, L
                ; проверка младшего байта относительно постоянного порога 192
                CP @PreviewClipIntersectionConst.LowRowLimit
                JR C, @D3D.AppendPreviewClipRightIntersection.StoreLowRow       ; переход, если младший байт строки меньше 192, сохранить его без насыщения

                ; чтение курсора для строки, насыщенной максимумом
                LD A, (@PreviewContourSize.Value.ByteCount)
                LD L, A
                LD H, @PreviewPolygonConst.PointPage
                ; запись выбранной граничной колонки
                LD (HL), #FF
                ; продвижение к строковому байту пары
                INC L
                ; запись максимальной строки из настроенного операнда
                LD (HL), #00
                ; расчёт следующего курсора после насыщения максимумом, Carry=0
                INC L
                ; обновление размера с сохранением флагов второго INC
                LD A, L
                LD (@PreviewContourSize.Value.ByteCount), A
                RET

                ; чтение курсора для отрицательной строки
MinRow:         LD A, (@PreviewContourSize.Value.ByteCount)
                LD L, A
                LD H, @PreviewPolygonConst.PointPage
                ; запись выбранной граничной колонки для отрицательного результата
                LD (HL), #FF
                ; продвижение к строковому байту без переноса страницы
                INC L
                ; запись минимальной строки
                LD (HL), #00
                ; расчёт следующего курсора отрицательной ветви, Carry=0
                INC L
                ; обновление ByteCount без изменения F второго INC
                LD A, L
                LD (@PreviewContourSize.Value.ByteCount), A
                RET

                ; сохранение младшей строки в D, E остаётся младшим байтом исходного начала
StoreLowRow:    LD D, L
                ; чтение курсора для сохранённого младшего байта строки
                LD A, (@PreviewContourSize.Value.ByteCount)
                LD L, A
                LD H, @PreviewPolygonConst.PointPage
                ; запись выбранной граничной колонки
                LD (HL), #FF
                ; продвижение к сохранённой строке, Carry=1 от успешного CP 192
                INC L
                ; запись D без повторной проверки положительного старшего байта
                LD (HL), D
                ; расчёт нового курсора с сохранением Carry=1
                INC L
                ; обновление ByteCount и возврат точных F сохранённого младшего байта
                LD A, L
                LD (@PreviewContourSize.Value.ByteCount), A
                RET

                endmodule
                endmodule
