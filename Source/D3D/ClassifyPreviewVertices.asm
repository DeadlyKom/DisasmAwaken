                module D3D
                module ClassifyPreviewVertices
                ; Документация [схема двух тетрад, точные пороги, ранний маркер, модульный счётчик и регистры](../../Docs/PreviewVertexClass.md)
                ; -----------------------------------------
                ; Коды сторон окна для спроецированных вершин, инверсная старшая тетрада и ранний отказ по маркеру 80
                ; исходная запись 6, банк 4, файловые смещения #1F46..#1FA5
                ; In:
                ;   HL, DE, BC, AF - входной контекст, HL и DE сохраняются
                ;   NextOffset содержит младший байт рабочего адреса после проекции, штатный формат 4+5*n при n=1..50
                ;   страница C6 содержит пятибайтовые записи, два слова координат и байт кода сторон
                ;   D3DClipState.AfterMaxX и AfterMaxY содержат байтовые исключённые верхние пределы, нижняя граница здесь всегда нулевая
                ;   банк 4 доступен для записи, SP указывает на CPU-возврат, под ним доступны два байта для PUSH HL
                ; Out:
                ;   HL и DE сохранены, B=(NextOffset-4) по модулю 256, C последний младший код сторон либо ноль при отказе
                ;   AF при полном проходе содержит OR всех кодов, F от OR, при маркере второй координаты 80 возвращается A=0,F=44
                ;   HL', DE', BC', IX и IY сохраняются, AF' при полном проходе равен B и 42 OR (B AND 28)
                ;   AF' при раннем отказе содержит предыдущую накопленную маску и флаги её OR, до первой вершины 0044
                ;   в пятые байты пройденных записей записаны коды с инверсной старшей тетрадой, после отказа остальные записи сохранены
                ;   I, IFF и IM сохраняются, SP после RET равен входному SP+2, под входным SP остаются сохранённые байты HL
                ; Corrupt:
                ;   BC, AF, AF', пятые байты обработанных записей и два байта под CPU-SP
                ; Note:
                ;   старший байт 80 второй координаты проверяется до знака и отвергает всю дальнейшую обработку без нового кода
                ;   для первой координаты старший байт 80 является обычной отрицательной координатой, не маркером
                ;   при нулевом старшем байте сравнивается младший, любой положительный ненулевой старший байт выходит за байтовый верхний предел
                ;   код равен ((C XOR 0F) SHL 4) OR C, накопление выполняется по OR, входной AF' не сохраняется
                ;   при NextOffset=4 штатного пропуска нет, без маркера выполняются 256 шагов с оборачиванием L
                ;   число шагов для произвольного B равно (205*B) mod 256, нулевое значение означает 256, модель проверяет все байтовые счётчики
                ;   эта фаза не учитывает ненулевые нижние пределы ConfigurePreviewClip и не рисует грани
                ; -----------------------------------------
                ; сохранение указателя вызывающего прохода на время обхода страницы C6
Entry:          PUSH HL
                ; обнуление накопленной маски и перенос её в альтернативный AF
                XOR A
                EX AF, AF'
                ; поиск старшего байта второй координаты первой записи
                LD HL, @PreviewProjectedVertices.Vertex00.SecondAxis+#01
                ; чтение следующего свободного смещения после проекции
                LD A, (@PreviewVertexGroupState.NextOffset)
                ; расчёт байтового смещения конца, из NextOffset исключается исходный сдвиг 4
                SUB @FPreviewProjectedVertex.Outcode
                LD B, A
                ; -----------------------------------------
                ; Вторая координата и маркер отказа
                ; -----------------------------------------
                ; обнуление младшего кода сторон текущей вершины
NextVertex:     LD C, #00
                ; чтение старшего байта второй координаты
                LD A, (HL)
                ; проверка маркера 80 до обычной проверки знака
                CP @PreviewVertexClassConst.InvalidHigh
                JR Z, @D3D.ClassifyPreviewVertices.Invalid                      ; переход, если старший байт второй координаты равен 80, прекратить обработку без нового кода

                ; проверка знака и нулевого старшего байта второй координаты
                AND A
                JP M, @D3D.ClassifyPreviewVertices.YBelow                       ; переход, если вторая координата отрицательна, установить YBelow

                JP NZ, @D3D.ClassifyPreviewVertices.YAbove                      ; переход, если положительный старший байт ненулевой, установить YAbove

                ; чтение младшего байта второй координаты при нулевом старшем
                DEC L
                LD A, (HL)
                INC L
                ; проверка исключённого байтового предела AfterMaxY
                CP #FF
                JR NC, @D3D.ClassifyPreviewVertices.YAbove                      ; переход, если вторая координата не меньше AfterMaxY, установить YAbove

                JP @D3D.ClassifyPreviewVertices.CheckX

                ; установка признака второй координаты меньше нуля
YBelow:         SET @PreviewVertexClassConst.YBelowBit, C
                JP @D3D.ClassifyPreviewVertices.CheckX

                ; установка признака второй координаты не меньше верхнего предела
YAbove:         SET @PreviewVertexClassConst.YAboveBit, C
                ; -----------------------------------------
                ; Первая координата
                ; -----------------------------------------
                ; переход по записи к старшему байту первой координаты
CheckX:         INC L
                INC L
                LD A, (HL)
                ; проверка знака и нулевого старшего байта первой координаты
                AND A
                JP M, @D3D.ClassifyPreviewVertices.XBelow                       ; переход, если первая координата отрицательна, установить XBelow

                JP NZ, @D3D.ClassifyPreviewVertices.XAbove                      ; переход, если положительный старший байт ненулевой, установить XAbove

                ; чтение младшего байта первой координаты при нулевом старшем
                DEC L
                LD A, (HL)
                INC L
                ; проверка исключённого байтового предела AfterMaxX
                CP #FF
                JR NC, @D3D.ClassifyPreviewVertices.XAbove                      ; переход, если первая координата не меньше AfterMaxX, установить XAbove

                JP @D3D.ClassifyPreviewVertices.StoreCode

                ; установка признака первой координаты меньше нуля
XBelow:         SET @PreviewVertexClassConst.XBelowBit, C
                JP @D3D.ClassifyPreviewVertices.StoreCode

                ; установка признака первой координаты не меньше верхнего предела
XAbove:         SET @PreviewVertexClassConst.XAboveBit, C
                ; -----------------------------------------
                ; Две тетрады и накопление
                ; -----------------------------------------
                ; переход к пятому байту записи для кода сторон
StoreCode:      INC L
                ; расчёт старшей тетрады поворотом четырёхбитного кода на четыре разряда
                LD A, C
                RLCA
                RLCA
                RLCA
                RLCA
                ; инверсия старшей тетрады для последующей общей проверки сторон
                XOR @PreviewVertexClassConst.CodeInvert
                ; объединение инверсной старшей и прямой младшей тетрад
                OR C
                ; запись кода сторон в пятый байт текущей записи
                LD (HL), A
                ; обновление накопленного OR кодов в альтернативном AF
                EX AF, AF'
                OR (HL)
                EX AF, AF'
                ; расчёт байтового смещения следующей записи, INC L намеренно не переносит страницу
                INC L
                LD A, L
                INC L
                ; проверка совпадения пройденного смещения с байтовым концом
                CP B
                JP NZ, @D3D.ClassifyPreviewVertices.NextVertex                  ; переход, если смещение не равно концу, обработать следующую вершину

                ; восстановление указателя вызывающего кода и возврат накопленного OR в основной AF
                POP HL
                EX AF, AF'
                RET

                ; восстановление указателя и возврат нулевого результата после маркера, старые коды не очищаются
Invalid:        POP HL
                XOR A
                RET

                ; -----------------------------------------
                endmodule
                endmodule
