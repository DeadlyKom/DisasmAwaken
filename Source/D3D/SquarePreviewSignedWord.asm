                module D3D
                module SquarePreviewSignedWord
                ; Документация [условный вход и проверка всех исходных слов](../../Docs/PreviewSquareEntry.md)
                ; -----------------------------------------
                ; Подготовка двух одинаковых знаковых сомножителей для общего умножения
                ; исходная запись 6, банк 4, файловые смещения #2867..#2868
                ; In:
                ;   HL содержит знаковое слово, DE может содержать любое значение
                ;   BC и IX сохраняются байтовой ветвью, SP указывает на внешнее слово возврата
                ;   под SP доступны два байта для знакового контекста общего умножения
                ; Out:
                ;   HL и DE возвращают старшее и младшее слова квадрата, для входа 8000 результат равен 00800000
                ;   BC сохраняется при модуле меньше 256, иначе равен нулю, AF=0044
                ;   HL', DE', BC', AF', IY, I, IM и IFF сохраняются
                ;   IX сохраняется при модуле меньше 256, иначе получает младшее слово результата
                ;   SP увеличен на два, под входным SP остаётся слово 0044
                ; Corrupt:
                ;   HL, DE, BC и IX в длинной ветви, AF, R, два байта под CPU-стеком
                ; Note:
                ;   LD D,H и LD E,L оставляют флаги и SP неизменными и продолжают выполнение с E869
                ;   проверены все 65536 входных слов HL, прямой штатный вызывающий путь по E867 не установлен
                ; -----------------------------------------
                ; Подготовка второго знакового множителя из обоих байтов первого.
Entry:          LD D, H
                LD E, L
                ; JP @D3D.MultiplyPreviewSignedWords.Entry, продолжение в MultiplyPreviewSignedWords.asm

                endmodule
                endmodule
