                module D3D
                module AdjustPreviewThird
                ; Документация [третья координата просмотра](../../Docs/PreviewThird.md)
                ; -----------------------------------------
                ; Изменение третьей координаты записи просмотра с принятием обёрнутой суммы только в 512..4095
                ; исходная запись 6, банк 4, файловые смещения #20B5..#20C4
                ; In:
                ;   HL - прибавляемое слово по модулю 65536, D3DPreviewState.ThirdCoordinate - прежняя третья координата записи
                ;   подключён исходный банк 4, слово координаты доступно для чтения и записи
                ; Out:
                ;   HL - сумма входного HL и прежней координаты по модулю 65536, DE - прежняя координата, BC сохранён
                ;   AF - A старший байт суммы, F от CP A,2 при A<2, иначе от CP A,16
                ;   в память записана сумма, только если 512<=HL<=4095, иначе прежняя координата сохранена
                ;   альтернативные и индексные регистры, I, IFF и IM сохранены, SP обычного возврата равен входному SP+2
                ; Corrupt:
                ;   HL, DE, AF
                ; Note:
                ;   сначала выполняется оборачивание ADD HL,DE, перенос этого сложения не используется проверкой
                ;   даже при отказе HL возвращает вычисленную сумму, а не прежнее значение
                ;   признак принятия не сводится к Carry или Z, проверяется числовой интервал либо оба сравнения
                ;   исходные станционные входы передают шаги 0020 и FFE0, единицы и полный смысл третьей координаты ещё неизвестны
                ;   ядро EC28 читает запись CDC0 через POP, третье прочитанное слово CDC4 передаётся в рабочие CF00 и EBA0
                ;   экран, порт страниц и память CPU-стека процедура не записывает
                ; -----------------------------------------
                ; чтение прежней третьей координаты записи просмотра в DE
Entry:          LD DE, (@D3DPreviewState.ThirdCoordinate)
                ; расчёт новой координаты по модулю 65536 без насыщения
                ADD HL, DE
                ; проверка нижней границы 512 по старшему байту суммы
                LD A, H
                CP @D3DPreviewConst.ThirdMinHigh
                RET C                                                           ; выход, если сумма меньше 512, прежнюю координату сохранить

                ; проверка исключённой верхней границы 4096
                CP @D3DPreviewConst.ThirdEndHigh
                RET NC                                                          ; выход, если сумма не меньше 4096, прежнюю координату сохранить

                ; сохранение принятой суммы в третьей координате исходной записи
                LD (@D3DPreviewState.ThirdCoordinate), HL
                RET

                endmodule
                endmodule
