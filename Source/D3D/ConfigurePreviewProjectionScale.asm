                module D3D
                module ConfigurePreviewProjectionScale
                ; Документация [масштаб перспективы](../../Docs/PreviewProjectionScale.md)
                ; -----------------------------------------
                ; Настройка трёх последовательностей масштаба проекции по показателю заголовка модели
                ; исходная запись 6, банк 4, файловые смещения #1BD9..#1BE8
                ; In:
                ;   HL - адрес второго байта заголовка выбранной модели, младшие семь битов содержат показатель b
                ;   DE, BC, AF - входной контекст, младший C сохраняется
                ;   банк 4 доступен для записи, для безопасного исполнения потребителей b должен находиться в 1..6
                ;   SP указывает на обычный адрес возврата, повторный вход с изменением тех же операндов исключён
                ; Out:
                ;   HL и DE сохранены, B содержит исходный байт заголовка без бита 7, C сохранён
                ;   AF - A=(6-b) по модулю 256, F точного SUB 6,b
                ;   DepthSkip, FirstAxisSkip и SecondAxisSkip получают одинаковый байт 6-b
                ;   HL', DE', BC', AF', IX, IY, I, IFF и IM сохранены, SP после RET равен входному SP+2
                ;   помимо трёх изменяемых байтов память и порты не записываются
                ; Corrupt:
                ;   BC, AF, три операнда JR масштаба перспективы
                ; Note:
                ;   бит 7 заголовка не участвует в показателе, его роль передаётся отдельно через Flags очереди
                ;   при b=1..6 смещение равно 5..0 и пропускает часть пяти ADD HL,HL, масштаб равен 2^(b-1)
                ;   исходные JR содержат FE и до подготовки образуют самопереход, подготовка обязательна перед исполнением
                ;   процедура не проверяет допустимость b, при других значениях записывает обёрнутый байт без исправления
                ;   у всех 11 исходных моделей показатели равны 2 либо 3, безопасные 1..6 дополнительно проверены как допустимый формат
                ;   само деление перспективы и обход вершин локальной проверкой не подтверждены
                ; -----------------------------------------
                ; чтение показателя и старшего признака из заголовка выбранной модели
Entry:          LD B, (HL)
                ; исключение старшего признака из числового показателя масштаба
                RES @PreviewQueueConst.SecondKeyBit, B
                ; расчёт пропуска 6-b для трёх одинаковых последовательностей из пяти удвоений
                LD A, @PreviewQueueBuildConst.ScaleStart
                SUB B
                ; обновление JR масштаба глубины перед её сложением с координатой объекта
                LD (@PreviewProjectionScaleState.DepthSkip), A
                ; обновление JR масштаба первой проектируемой координаты
                LD (@PreviewProjectionScaleState.FirstAxisSkip), A
                ; обновление JR масштаба второй проектируемой координаты
                LD (@PreviewProjectionScaleState.SecondAxisSkip), A
                RET

                endmodule
                endmodule
