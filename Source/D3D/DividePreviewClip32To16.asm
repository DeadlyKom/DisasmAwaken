                OR A
                SBC HL, BC
                ; возврат модуля в DE, исходное старшее слово числителя снова в HL
                EX DE, HL
                ; увеличение числа отрицательных входов за отрицательный делитель
                INC IXL
                ; -----------------------------------------
                ; Однокомплементный модуль числителя
                ; -----------------------------------------
                ; проверка старшего знакового бита всего 32-битного N
