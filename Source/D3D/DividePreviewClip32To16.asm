                ; -----------------------------------------
                ; Деление HL:A:A' на DE с входным знаком делителя и однокомплементными отрицательными значениями
                ; исходная запись 6, банк 4, файловые смещения #2A01..#2AB5
                ; In:
                ;   HL старшие 16 бит знакового числителя N, DE ненулевой знаковый делитель d
                ;   BC сохраняется, только если оба входа неотрицательны, иначе заменяется при подготовке модулей
                ;   AF - A следующие восемь бит N, входной S обязан отражать знак d, Carry входит в точный выходной F
                ;   HL', DE', BC' сохраняются, AF' - A' младшие восемь бит N, входной Carry F' участвует в выходном F'
                ;   IXH сохраняется, IXL рабочий счётчик знаков, IY сохраняется, SP указывает на CPU-возврат
                ;   U=N при N>=0, иначе U=-N-1, для числового договора U<abs(d)*65536
                ; Out:
                ;   HL содержит слово q=floor(U/abs(d)) при чётном числе отрицательных входов, иначе q XOR FFFF
                ;   DE=abs(d), BC исходный старший N при N<0, иначе исходный d при d<0, иначе входной BC
                ;   AF - A равен выходному H, S/Z/PV от восьмой пробы старшего байта, остальные биты по формуле документации
                ;   HL', DE', BC' сохранены, AF' - A' равен выходному L, F' от DEC IXL и возможного CPL
                ;   IXH сохранён, IXL=(число отрицательных входов-1) AND FF, IY, I, IFF и IM сохранены
                ;   SP после RET равен входному+2, память не записывается, остаток не возвращается
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', IXL
                ; Note:
                ;   знак делителя берётся из входного S без проверки D, противоречивый S не входит в числовой договор
                ;   отрицательный N дополняется побитово без прибавления единицы, отрицательный результат тоже однокомплементный
                ;   Carry не является сообщением об ошибке или ненулевом остатке, Z не проверяет конечное частное
                ;   q допускается до FFFF как слово, знаковая представимость результата отдельной проверкой не обеспечивается
                ;   делитель нуль и переполнение частного код не проверяет, их числовая эквивалентность данной моделью не заявляется
                ; -----------------------------------------
                ; -----------------------------------------
                ; Модуль делителя и число отрицательных входов
                ; -----------------------------------------
                ; обнуление счётчика знаков в IXL, старший IX сохраняется
Entry:          LD IXL, #00
                ; проверка именно входного S, знак старшего D самостоятельно не читается
                JP P, @D3D.DividePreviewClip32To16.CheckNumerator               ; переход, если входной S сброшен, не отрицать делитель

                ; выбор исходного делителя в HL для дополнительного отрицания
                EX DE, HL
                ; сохранение исходного делителя в BC перед вычислением модуля
                LD B, H
                LD C, L
                ; расчёт обычного модуля делителя через нуль минус исходное слово
