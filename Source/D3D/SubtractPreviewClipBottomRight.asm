                module D3D
                module SubtractPreviewClipBottomRight
                ; Документация [физический разрыв левого кэша, перенос низкой половины, точные регистры и ограниченный смысл Z](../../Docs/PreviewClipProducts.md)
                ; -----------------------------------------
                ; Разность кэшей Bottom и Right с заёмом младшего слова и возвратом старшего
                ; исходная запись 6, банк 4, файловые смещения #281C..#282F
                ; In:
                ;   HL не является входом, DE сохраняется, BC не является входом, AF - A сохраняется, входной Carry сбрасывается
                ;   кэши Bottom и Right содержат готовые 32-битные значения, низкая и высокая половины имеют исходные физические адреса
                ;   для Left младшее слово C2EE и старшее C2FA разнесены, промежуточные байты не входят в кэш
                ; Out:
                ;   HL содержит старшее слово (Bottom-Right) по модулю 2^32, младшая разность не возвращается
                ;   DE сохранён, BC содержит старшее слово второго кэша Right
                ;   AF - A сохранён, F от старшего SBC HL, BC с заёмом младшей половины
                ;   Z=1 означает нулевую старшую половину разности, младшая при этом может быть ненулевой
                ;   HL', DE', BC', AF', IX, IY, I, IFF и IM сохранены, SP после RET равен входному+2, память не записывается
                ; Corrupt:
                ;   HL, BC, AF - только F
                ; Note:
                ;   сброс Carry выполняется только перед младшей половиной, загрузки двух старших слов его не меняют
                ;   это не проверка равенства полных кэшей через Z, знак S принадлежит обёрнутой 32-битной разности
                ;   условия предварительной подготовки кэшей задают обработчики, полный разбор их путей ещё не завершён
                ; -----------------------------------------
                ; чтение младших слов кэшей Bottom и Right из фактических полей
Entry:          LD HL, (@PreviewClipBottomProduct.Value.LowWord)
                LD BC, (@PreviewClipRightProduct.Value.LowWord)
                ; сброс входного Carry перед младшей разностью с сохранением A
                OR A
                ; расчёт младшей половины и её заёма, сам младший результат дальше теряется
                SBC HL, BC
                ; чтение старших слов без изменения Carry младшей разности
                LD HL, (@PreviewClipBottomProduct.Value.HighWord)
                LD BC, (@PreviewClipRightProduct.Value.HighWord)
                ; расчёт старшей половины с унаследованным заёмом, Z относится только к этой половине
                SBC HL, BC
                RET

                endmodule
                endmodule
