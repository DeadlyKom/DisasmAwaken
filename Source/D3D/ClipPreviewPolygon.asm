                module D3D
                module ClipPreviewPolygon
                ; Документация [замыкание, индексная страница C6, B=0, два возврата, оборачивание C8 и общий RET](../../Docs/PreviewClipPolygon.md)
                ; -----------------------------------------
                ; Замкнутый обход индексов проекции, отсечение каждого ребра и приём контура по размеру
                ; исходная запись 6, банк 4, файловые смещения #2171..#21EA
                ; In:
                ;   HL адрес списка байтовых смещений записей проекции, DE не является параметром
                ;   BC содержит B число индексов, B=0 означает 256 проходов, C сохраняется обычным завершением, AF не является параметром
                ;   HL', DE', BC' сохраняются, AF' и IX рабочий контекст арифметики, IY сохраняется
                ;   каждый индекс выбирает пятибайтовую запись на странице C6, чтение её полей продвигает только L
                ;   коды сторон записей согласованы с координатами и текущим E011, страницы CC/CD содержат исходные цели
                ;   страница C8, физические концы, состояние углов, кэши и CPU-стек доступны, деления имеют допустимую область
                ; Out:
                ;   HL указывает за всеми n входными индексами и при обычном, и при специальном завершении
                ;   DE контекст последнего обработчика, обычный BC имеет B=0 и сохранённый C, AF содержит A=ByteCount и F от CP 6
                ;   специальный BC равен числу оставшихся индексов, AF содержит A=E1 и Carry=1, S/Z/PV от DEC этого числа
                ;   HL', DE', BC' сохранены, AF' и IX определяются фактическим путём арифметики, IY сохранён
                ;   BlockCode=0, SeenFlags содержит отметки после последнего исполненного ребра, ByteCount размер по модулю 256
                ;   два физических конца содержат последнее исполненное ребро, полный вывод расположен в странице C8 с возможным оборачиванием
                ;   SP после окончательного возврата равен входному+2, I, IFF и IM сохраняются
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', IX, оба конца, SeenFlags, BlockCode, ByteCount, кэши, страница C8 и CPU-стек
                ; Note:
                ;   сначала второй конец берётся из последнего индекса, затем каждое ребро соединяет предыдущую вершину с очередной
                ;   перед обработчиком на стеке E1E2, сохранённый BC и адрес следующего индекса, затем настоящий CPU-возврат
                ;   обычный RET возвращает к POP BC и DJNZ, специальный UnwindPreviewClipFrame пропускает ещё B-1 индексов
                ;   обычный CP 6 сбрасывает Carry только при текущем размере не меньше шести, оборачивание размера не предотвращается
                ;   конечный RET физически общий с пустым Entry PreviewClipCases, сохраняется жёсткий порядок include
                ;   проверены 1980 контуров и 37390 рёбер, длины 1..256, переход входного списка между страницами и оборачивание C8
                ;   ненулевые минимумы всей группы, все конечные DE, AF' и IX, IRQ и игровой запуск остаются непроверенными
                ; -----------------------------------------
                ; обнуление режима запрета углов, размера и прежних отметок для нового контура
Entry:          XOR A
                LD (@PreviewClipCorners.Value.BlockCode), A
                LD (@PreviewContourSize.Value.ByteCount), A
                LD (@PreviewClipCorners.Value.SeenFlags), A
                ; -----------------------------------------
                ; Последняя вершина как начало замыкающего ребра
                ; -----------------------------------------
                ; сохранение начала списка перед поиском последнего индекса
                PUSH HL
                ; расчёт смещения последнего индекса n-1, входной B=0 даёт байтовое FF
                LD A, B
                DEC A
                ADD A, L
                LD L, A
                ; расчёт старшего байта адреса последнего индекса с переносом от младшего
                LD A, H
                ADC A, #00
                LD H, A
                ; поиск пятибайтовой записи на странице проекции по байтовому индексу
                LD L, (HL)
                LD H, @PreviewFaceMathConst.VertexPage
                ; чтение слова колонки последней вершины с продвижением только младшего адреса
                LD E, (HL)
                INC L
                LD D, (HL)
                INC L
                ; сохранение колонки второго конца будущего ребра
                LD (@PreviewClipSecond.Value.SecondAxis), DE
                ; чтение и сохранение слова строки последней вершины
                LD E, (HL)
                INC L
                LD D, (HL)
                INC L
                LD (@PreviewClipSecond.Value.FirstAxis), DE
                ; сохранение полного кода сторон последней вершины
                LD A, (HL)
                LD (@PreviewClipSecond.Value.Outcode), A
                ; -----------------------------------------
                ; Очередное замкнутое ребро
                ; -----------------------------------------
                ; перенос предыдущего второго конца в первый, начиная со слова колонки
NextEdge:       LD HL, (@PreviewClipSecond.Value.SecondAxis)
                LD (@PreviewClipFirst.Value.SecondAxis), HL
                ; перенос слова строки предыдущего конца
                LD HL, (@PreviewClipSecond.Value.FirstAxis)
                LD (@PreviewClipFirst.Value.FirstAxis), HL
                ; перенос кода сторон, запись первого конца теперь полна
                LD A, (@PreviewClipSecond.Value.Outcode)
                LD (@PreviewClipFirst.Value.Outcode), A
                ; восстановление адреса очередного индекса и сохранение адреса следующего
                POP HL
                LD A, (HL)
                INC HL
                PUSH HL
                ; сохранение числа оставшихся индексов и входного C в служебном кадре
                PUSH BC
                ; поиск очередной проекции по байтовому смещению на странице C6
                LD L, A
                LD H, @PreviewFaceMathConst.VertexPage
                ; чтение и сохранение колонки нового второго конца
                LD E, (HL)
                INC L
                LD D, (HL)
                INC L
                LD (@PreviewClipSecond.Value.SecondAxis), DE
                ; чтение и сохранение строки нового второго конца
                LD E, (HL)
                INC L
                LD D, (HL)
                INC L
                LD (@PreviewClipSecond.Value.FirstAxis), DE
                ; чтение и сохранение полного кода сторон второго конца
                LD A, (HL)
                LD (@PreviewClipSecond.Value.Outcode), A
                ; расчёт старшей тетрады индекса из дополнения к коду первого конца, перестановки здесь нет
                LD A, (@PreviewClipFirst.Value.Outcode)
                CPL
                AND @PreviewClipDispatchConst.ComplementMask
                LD L, A
                ; расчёт младшей тетрады по прямому коду второго конца
                LD A, (@PreviewClipSecond.Value.Outcode)
                AND @PreviewClipDispatchConst.SideMask
                OR L
                LD L, A
                ; поиск младшего и старшего байтов цели на разнесённых страницах CC и CD
                LD H, @PreviewClipDispatchConst.LowTablePage
                LD E, (HL)
                INC H
                LD D, (HL)
                EX DE, HL
                ; создание одного подставного возврата E1E2 над сохранёнными BC и адресом следующего индекса
                LD DE, @D3D.ClipPreviewPolygon.ResumeEdge
                PUSH DE
                ; передача управления обработчику без дополнительного CALL
                JP (HL)

                ; обычный возврат обработчика, восстановление счётчика и контекста C
ResumeEdge:     POP BC
                ; уменьшение числа оставшихся индексов, при B!=0 следующий обход начинается с переноса концов
                DJNZ @D3D.ClipPreviewPolygon.NextEdge

                ; восстановление адреса за входным списком после последнего ребра
                POP HL
                ; чтение текущего байтового размера после всех добавлений
                LD A, (@PreviewContourSize.Value.ByteCount)
                ; проверка минимального размера трёх точек перед общим физическим RET следующего файла
                CP @PreviewClipPolygonConst.MinimumBytes
                ; JP @D3D.PreviewClipCases.Entry, продолжение в PreviewClipCases.asm

                ; -----------------------------------------
                endmodule
                endmodule
