                CPL
                LD L, A
                LD A, H
                CPL
                LD H, A
                INC HL
                ; проверка знака второго слова
AbsSecond:      BIT @PreviewFaceMathConst.SignBit, D
                JR Z, @D3D.MultiplyPreviewSignedWords.SelectSize                ; переход, если второе слово неотрицательно, его модуль уже готов

                ; расчёт модуля второго отрицательного слова
