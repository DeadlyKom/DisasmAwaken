                ; Знаковое произведение слов с тремя размерными ветвями и особым длинным случаем второго слова 8000
                ; исходная запись 6, банк 4, файловые смещения #2869..#2A00
                ; In:
                ;   HL - первое знаковое слово, DE - второе знаковое слово
                ;   BC - сохраняемый контекст короткой ветви, в смешанной ветви сохраняется только входной B
                ;   AF - исходный контекст не используется, IX сохраняется только двумя короткими ветвями
                ;   SP указывает на CPU-возврат, под ним доступны два байта для сохранения знакового контекста
                ; Out:
                ;   HL и DE содержат старшее и младшее слова 32-битного результата по точному алгоритму
                ;   при обычном случае результат равен произведению знаковых входов, исключение длинного второго 8000 описано отдельно
                ;   BC при отрицании содержит старшее слово модуля произведения, без отрицания длинная ветвь даёт 0
                ;   без отрицания смешанная ветвь сохраняет B и обнуляет C, байтовая сохраняет весь входной BC
                ;   AF - A равно исходный H XOR исходный D, при совпадении знаков F от этого XOR
                ;   при разных знаках F принадлежит старшему SBC при отрицании 32-битного результата с переносом младшего слова
                ;   HL', DE', BC', AF', IY, I, IFF и IM сохраняются, IX в длинной ветви содержит младшее слово модуля, в коротких сохранён
                ;   SP после RET равен входному+2, под входным SP остаются A знакового XOR и его исходные логические флаги
                ; Corrupt:
                ;   HL, DE, BC, AF, IX в длинной ветви, два байта под CPU-SP
                ; Note:
                ;   модули обоих входов вычисляются до выбора ветви, формат 8000 остаётся модулем 32768
                ;   если оба модуля не меньше 256 и модуль второго входа равен 32768, эффективный множитель равен 256
                ;   это следствие потери разряда 15 и безусловного принятия разряда 8, исходная особенность не исправляется
                ;   в таком случае модуль результата равен модуль первого входа умножить на 256, знак выбирается по исходным словам
                ;   перестановка входов не разрешена как оптимизация, в крайнем случае они несимметричны
                ;   RET P проверяет исходное совпадение знаков из сохранённого XOR, а не знак уже получившегося результата
                ; -----------------------------------------
                ; -----------------------------------------
                ; Исходные знаки и модули
                ; -----------------------------------------
                ; расчёт XOR исходных старших байтов, его S выбирает последующее отрицание
Entry:          LD A, H
                XOR D
                ; сохранение исходного знакового контекста до любой арифметики модуля
                PUSH AF
                ; проверка знака первого слова
                BIT @PreviewFaceMathConst.SignBit, H
                JR Z, @D3D.MultiplyPreviewSignedWords.AbsSecond                 ; переход, если первое слово неотрицательно, его модуль уже готов

                ; расчёт модуля первого отрицательного слова через дополнение и единицу
