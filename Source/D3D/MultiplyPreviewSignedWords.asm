                CPL
                LD E, A
                LD A, D
                CPL
                LD D, A
                INC DE
                ; -----------------------------------------
                ; Выбор размерной ветви
                ; -----------------------------------------
                ; перестановка модулей, первое слово становится множимым DE, второе множителем HL
