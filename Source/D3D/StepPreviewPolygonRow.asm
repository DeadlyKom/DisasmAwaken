                module D3D
                module StepPreviewPolygonRow
                ; Документация [две цепочки, точные шаги и регистры, маски, перенос строки, SP и внутренние входы](../../Docs/PreviewPolygonFill.md)
                ; -----------------------------------------
                ; Продвижение двух рёбер, экранной строки и шаблона, вывод полосы и общий возврат
                ; исходная запись 6, банк 4, файловые смещения #1207..#1281
                ; In:
                ;   HL - H страница масок завершённой строки C0 либо C1, L временная часть последней маски
                ;   DE - D=D1, E временная часть последнего экранного действия
                ;   BC - адрес последнего затронутого байта строки, текущая строка уже обработана
                ;   HL' содержит ошибки правого и левого ребра, DE' и BC' их целые шаги, AF' содержит A' шаблон завершённой строки
                ;   IX, IY содержат упакованные границы завершённой строки, исходные операнды ошибок и пределов подготовлены
                ;   SP=FFE0, SavedStack содержит адрес сохранённого HL, над ним адрес CPU-возврата вызывающего
                ;   внутренний CheckLastRow принимает A текущую строку до вывода, без первого продвижения
                ;   рабочий профиль выпуклый экранный контур с подготовленными таблицами от начала bitmap и индексом 0..4
                ; Out:
                ;   HL восстановлен из сохранённого CPU-стека, для обычного входа это HL вызывающего FillPreviewPolygon
                ;   DE содержит D=D1 и точный остаток правого края либо смещение входа развёрнутой строки
                ;   BC содержит фактическое последнее продвижение экранного адреса, не обязательно адрес нижней строки
                ;   AF содержит A исключённую нижнюю строку Y, F=42 OR (Y AND 28)
                ;   HL', DE', BC', AF', IX, IY содержат конечные ошибки, шаги, следующий шаблон и нижние концы, точные формулы в документации
                ;   SP=SavedStack+4 после POP HL и RET, I, IFF и IM сохранены, содержимое банка не переключается
                ;   обработаны остальные строки, операнды текущей строки и сменяемых рёбер содержат конечное состояние
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, экран, рабочие операнды и временный стек под FFE0
                ; Note:
                ;   это общий внутренний цикл, его первый Entry продвигает строку, первичная подготовка прыгает сразу в CheckLastRow
                ;   ветви к UpdatePreviewLeftEdge и SelectPreviewRightEdge продолжаются в отдельных ASM без CPU-вызова
                ;   CheckRightEnd после обновления левой цепочки повторяет проверку правой, DrawRow после правой сразу рисует
                ;   RestoreHL также принимает ранний выход горизонтального контура с обычным SP, не читая SavedStack
                ;   Carry экранного продвижения берётся до дробной коррекции IX, исходное отклонение у колонки 255 сохранено
                ;   строка с левой байтовой границей правее правой пропускается, равная колонка использует общий крайний байт
                ; -----------------------------------------
                ; -----------------------------------------
                ; Следующая строка, маски и целый левый шаг
                ; -----------------------------------------
                ; чередование страниц C0 и C1, номер строки в контуре выбирает маски шаблона
Entry:          INC H
                RES @PreviewPolygonConst.MaskCycleBit, H
                ; выбор шаблона из альтернативного AF
                EX AF, AF'
                ; расчёт шаблона следующей строки, исходный нулевой операнд меняется подготовкой FillPreviewPolygon
                XOR #00
                EX AF, AF'
                ; выбор целого левого шага из BC' без изменения основного экранного адреса
                EXX
                ; расчёт следующего упакованного IX до дробной коррекции, Carry используется экранным переходом
                ADD IX, BC
                EXX
                ; продвижение экранной строки внутри восьмистрочного блока, INC сохраняет Carry от ADD IX
                INC B
                JP NC, @D3D.StepPreviewPolygonRow.LeftError                     ; переход, если целый левый шаг не дал Carry, младший экранный адрес не сдвигается

                ; расчёт следующей строки знакомест после переноса упакованной координаты
                LD A, C
                ADD A, @ScreenConst.ByteColumns
                LD C, A
                JR C, @D3D.StepPreviewPolygonRow.LeftError                      ; переход, если прибавление строки знакомест дало Carry, новый экранный блок уже выбран

                ; возврат старшего экранного адреса в начало восьмистрочного блока без смены трети экрана
                LD A, B
                SUB @ScreenConst.PixelsPerChar
                LD B, A
                ; -----------------------------------------
                ; Дробные поправки двух рёбер
                ; -----------------------------------------
                ; выбор накопителей ошибок L' и H'
LeftError:      EXX
                LD A, L
                ; расчёт левой ошибки вычитанием подготовленной дробной части
                SUB #00
                JR NC, @D3D.StepPreviewPolygonRow.LeftReady                     ; переход, если левая ошибка не дала заёма, поправка колонки не требуется

                ; восстановление левой ошибки её периодом после заёма
                ADD A, #00
                ; поправка упакованной левой колонки на минус один пиксель через SP=FFE0
                ADD IX, SP
                ; сохранение левой ошибки для следующей строки
LeftReady:      LD L, A
                ; расчёт следующего упакованного IY по целому правому шагу
                ADD IY, DE
                LD A, H
                ; расчёт правой ошибки вычитанием её дробной части
                SUB #00
                JR NC, @D3D.StepPreviewPolygonRow.RightReady                    ; переход, если правая ошибка не дала заёма, поправка колонки не требуется

                ; восстановление правой ошибки её периодом после заёма
                ADD A, #00
                ; поправка правой колонки на минус один пиксель через тот же временный SP
                ADD IY, SP
                ; сохранение правой ошибки и возврат основных экранных регистров
RightReady:     LD H, A
                EXX
                ; -----------------------------------------
                ; Предел контура и смена рёбер
                ; -----------------------------------------
                ; чтение операнда текущей строки, обновлённого перед предыдущим рисунком
CurrentRow:     LD A, #00
                ; проверка исключённой нижней строки всего многоугольника
CheckLastRow:   CP #00
                JR NC, @D3D.StepPreviewPolygonRow.RestoreStack                  ; переход, если текущая строка достигла нижнего предела, восстановить CPU-стек и выйти

                ; проверка нижней строки текущего левого ребра
CheckLeftEnd:   CP #00
                JR NC, @D3D.UpdatePreviewLeftEdge.Entry                         ; переход, если левое ребро закончилось, выбрать следующее ребро обратной цепочки

                ; проверка нижней строки текущего правого ребра
CheckRightEnd:  CP #00
                JR NC, @D3D.SelectPreviewRightEdge.Entry                        ; переход, если правое ребро закончилось, выбрать следующее ребро прямой цепочки

                ; расчёт и сохранение номера строки, которую нужно проверить после текущего рисунка
                INC A
                LD (@PreviewPolygonState.CurrentRow), A
                ; -----------------------------------------
                ; Экранная колонка и ширина строки
                ; -----------------------------------------
                ; выбор пары левых масок по младшей части упакованного IX
DrawRow:        LD A, IXL
                LD L, A
                ; расчёт левой байтовой колонки из IXH без трёх строковых разрядов
                LD A, IXH
                AND @ScreenConst.ColumnMask
                LD E, A
                ; сохранение строковой части младшего экранного адреса
                LD A, C
                AND @SpriteLineConst.RowLowMask
                ; объединение строковой части с левой колонкой и добавление подготовленного горизонтального начала
                OR E
                ADD A, #00
                LD C, A
                ; расчёт знаковой разности байтовых границ, строковые разряды обеих координат совпадают
                LD A, IXH
                SUB IYH
                JR NC, @D3D.StepPreviewPolygonRow.SameOrInverted                ; переход, если левая байтовая граница не меньше правой, проверить общий байт или пустую строку

                ; расчёт отрицательного удвоенного числа байтов до правого края, выбор входа D1C0..D1FE
                ADD A, A
                LD E, A
                ; чтение левого экранного края
                LD A, (BC)
                ; сохранение внешних пикселей слева от контура
                AND (HL)
                ; выбор заполнения внутренней части левого края
                INC L
                ; объединение левой сохранённой части с шаблоном контура
                OR (HL)
                ; запись левого края, следующий C выбирает первый полный байт
                LD (BC), A
                INC C
                ; выбор адреса развёрнутой записи из D1 и отрицательного удвоенного смещения
                EX DE, HL
                ; выбор полного шаблона строки из AF' перед косвенным переходом
                EX AF, AF'
                ; переход на один из проверенных чётных входов развёрнутой записи, CPU-возврат не создаётся
                JP (HL)

SameOrInverted: JR NZ, @D3D.StepPreviewPolygonRow.Entry                         ; переход, если левая байтовая колонка правее правой, пропустить запись этой строки

                ; -----------------------------------------
                ; Обе границы в одном экранном байте
                ; -----------------------------------------
                ; чтение левой сохраняющей маски и выбор правой пары
                LD A, (HL)
                LD E, IYL
                LD L, E
                ; объединение двух сохраняющих масок, внешние пиксели остаются с обеих сторон
                OR (HL)
                ; выбор байта шаблона правой пары
                INC L
                LD E, A
                ; расчёт маски внутреннего полуинтервала инверсией общего сохранения
                CPL
                ; ограничение шаблона пикселями между обеими границами
                AND (HL)
                LD L, A
                ; чтение исходного общего экранного байта
                LD A, (BC)
                ; сохранение внешних пикселей и добавление внутреннего шаблона
                AND E
                OR L
                ; запись общего края, при совпавших пиксельных границах значение не меняется
                LD (BC), A
                JP @D3D.StepPreviewPolygonRow.Entry

                ; -----------------------------------------
                ; Общий возврат после временного SP
                ; -----------------------------------------
                ; восстановление CPU-SP, сохранённого первичной подготовкой контура
RestoreStack:   LD SP, #0000
                ; восстановление HL вызывающего, ранний горизонтальный выход входит прямо сюда
RestoreHL:      POP HL
                RET

                ; -----------------------------------------
                endmodule
                endmodule
