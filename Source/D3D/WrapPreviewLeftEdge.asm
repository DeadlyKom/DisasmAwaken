                module D3D
                module WrapPreviewLeftEdge
                ; Документация [кольцевые цепочки, все знаки и длины наклона, точные шаги, флаги и временный стек](../../Docs/PreviewPolygonFill.md)
                ; -----------------------------------------
                ; Переход обратной цепочки к последней строковой координате контура
                ; исходная запись 6, банк 4, файловые смещения #1285..#128B
                ; In:
                ;   HL - H страница контура C8, L достиг нулевой колонки первой точки
                ;   DE - D текущая строка, E начальная колонка сканируемого ребра
                ;   LastIndex содержит нечётный индекс последней строковой координаты, контекст UpdatePreviewLeftEdge сохранён в стеке
                ; Out:
                ;   HL - H сохранён, L равен LastIndex, выбран строковый байт последней точки
                ;   DE и BC сохранены, AF - A равен LastIndex, F сохранён
                ;   HL', DE', BC', AF', IX, IY и SP сохранены, продолжение UpdatePreviewLeftEdge.ReadRow
                ; Corrupt:
                ;   HL - только L, AF - только A
                ; Note:
                ;   это ветвь сканирования кольца, чтение строки выполнит следующий файл, CPU-возврат не создаётся
                ; -----------------------------------------
                ; чтение последнего строкового индекса при переходе обратной цепочки через начало
Entry:          LD A, (@PreviewPolygonEdgeState.LastIndex)
                ; выбор последней строковой координаты без изменения страницы C8
                LD L, A
                JP @D3D.UpdatePreviewLeftEdge.ReadRow

                endmodule
                endmodule
