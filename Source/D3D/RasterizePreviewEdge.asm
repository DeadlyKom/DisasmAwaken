                module D3D
                module RasterizePreviewEdge
                ; Документация [формула точек, физические параметры, четыре ветви, режимы, точные регистры и проверка bitmap](../../Docs/PreviewEdgeRaster.md)
                ; -----------------------------------------
                ; Растровое ребро с исключённым концом, четырьмя ветвями, режимами XOR/OR/AND и точными флагами
                ; исходная запись 6, банк 4, файловые смещения #1E1C..#1F45
                ; In:
                ;   PreviewEdgeEndpoints.Value.StartPoint и EndPoint содержат слова, младший байт колонка, старший строка
                ;   PreviewEdgeMode.Value содержит согласованную пару A9/38 для XOR, B1/38 для OR либо A1/30 для AND
                ;   MaskOffset содержит B0 для XOR и OR, B8 для AND, исходные таблицы масок сохранены
                ;   PreviewLineTable.RowHigh, RowLow и Column подготовлены BuildSpriteLineTable в текущем банке 4
                ;   профиль требует попадания обоих концов и всех точек в bitmap 256 на 192 после добавления начала таблиц
                ;   CPU-стек не пересекает экран и изменяемый код, повторный вход в общий код opcode исключён
                ;   HL, DE, BC, AF не задают координаты, их входной контекст сохраняется только в указанных случаях раннего выхода
                ; Out:
                ;   для разных концов HL содержит адрес исключённого конца, DE содержит D=max(dx,dy), E=min(dx,dy), BC содержит B=0 и C маску конца
                ;   C является одноразрядной маской для XOR и OR либо её инверсией для AND
                ;   AF пологой ветви содержит A равный конечному экранному байту, F от последнего поворота маски, смены колонки либо строки
                ;   AF крутой ветви принадлежит расчёту последнего перехода строки, A не является возвращаемым пикселем
                ;   AF' содержит A'=floor(max(dx,dy)/2), F' точного последнего действия накопителя ошибки, маски либо колонки
                ;   полные формулы AF и AF' приведены в registers, row_context, column_context независимой модели
                ;   HL', DE', BC', IX, IY, I, IFF и IM сохраняются, SP после RET равен входному+2, CPU-стек не записывается
                ;   при совпавших словах концов HL=0, DE равен слову конца, BC, A и весь альтернативный набор сохранены, F=42
                ;   при непустом ребре меняются два opcode выбранной ветви и экранные байты, при совпавших концах записей нет
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', два opcode выбранной ветви, затронутые экранные байты
                ; Note:
                ;   при разных строках начало выбирается по меньшей строке, при равных строках исходный порядок концов сохраняется
                ;   начальная точка включена, конечная исключена, равенство dx и dy выбирает пологую ветвь
                ;   пологая ветвь накапливает несколько пикселей байта в A и может повторно записывать неизменённый соседний байт
                ;   AND использует инверсную маску и заменяет исходный JR C на JR NC, оба изменяемых байта необходимы
                ;   не выровненное горизонтальное начало таблиц округляется вниз до байтовой колонки, остаток не добавляется в маску
                ;   сам код отсечения не выполняет, внеэкранные таблицы и неподготовленные opcode не входят в проверенный профиль
                ;   проверка включает настоящую подготовку таблиц, весь bitmap и точные основные и альтернативные AF, не аппаратные IRQ
                ; -----------------------------------------
                ; -----------------------------------------
                ; Концы и нормализация строк
                ; -----------------------------------------
                ; чтение двух физических слов концов отрезка
Entry:          LD HL, (@PreviewEdgeEndpoints.Value.StartPoint)
                LD DE, (@PreviewEdgeEndpoints.Value.EndPoint)
                ; очистка Carry перед сравнением полных координатных слов
                OR A
                ; проверка полного совпадения концов без рисования одной точки
                SBC HL, DE
                RET Z                                                           ; выход, если координатные слова совпадают, отрезок не рисуется

                ; восстановление первого слова после сравнения
                ADD HL, DE
                ; расчёт разности строк для выбора начала с меньшей строкой
                LD A, D
                SUB H
                JR NC, @D3D.RasterizePreviewEdge.RowsReady                      ; переход, если строка второго конца не меньше первой, перестановка не нужна

                ; перестановка концов и расчёт модуля разности строк
                EX DE, HL
                NEG
                ; сохранение длины по строкам, колонка конца остаётся в E
RowsReady:      LD D, A
                ; расчёт индекса пиксельного бита начала внутри экранного байта
                LD A, L
                AND @ScreenConst.PixelOffsetMask
                ; добавление подготовленного B0 либо B8 к индексу маски
MaskIndex:      ADD A, #00
                LD C, A
                ; расчёт полного адреса исходной маски с переносом младшей суммы
                LD A, @PreviewEdgeRasterConst.MaskPage
                ADC A, #00
                LD B, A
                ; чтение выбранной маски и временное сохранение её в AF'
                LD A, (BC)
                EX AF, AF'
                ; -----------------------------------------
                ; Экранный адрес начала
                ; -----------------------------------------
                ; сохранение относительной колонки и выбор строки таблиц
                LD C, L
                LD L, H
                LD H, @PreviewEdgeRasterConst.RowHighPage
                ; чтение старшего и младшего байтов адреса строки
                LD B, (HL)
                INC H
                LD A, (HL)
                INC H
                LD L, C
                ; расчёт младшего экранного адреса добавлением байтовой колонки
                ADD A, (HL)
                LD L, A
                LD H, B
                ; перенос маски в C с восстановлением относительной начальной колонки в A
                LD A, C
                EX AF, AF'
                LD C, A
                EX AF, AF'
                ; расчёт разности начальной и конечной колонок
                SUB E
                JR C, @D3D.RasterizePreviewEdge.Right                           ; переход, если начальная колонка меньше конечной, рисовать вправо

                ; проверка выбора главной оси для движения влево
                CP D
                JR C, @D3D.RasterizePreviewEdge.LeftSteep                       ; переход, если длина по колонкам меньше длины по строкам, выбрать крутую ветвь

                ; -----------------------------------------
                ; Пологая ветвь влево
                ; -----------------------------------------
                ; сохранение главной длины в D и B, малой длины в E
                LD E, D
                LD D, A
                LD B, A
                ; расчёт начальной ошибки как половины главной длины с округлением вниз
                SRL A
                ; сохранение накопителя ошибки в альтернативном AF
                EX AF, AF'
                ; чтение байта пиксельной операции из физического экземпляра режима
                LD A, (@PreviewEdgeMode.Value.PixelOpcode)
                ; обновление opcode NOP выбранной ветви на подготовленный AND, XOR либо OR
                LD (@PreviewEdgeRasterState.LeftFlatOp), A
                ; чтение opcode перехода по границе байта, C для прямой маски, NC для инверсной
                LD A, (@PreviewEdgeMode.Value.BoundaryOpcode)
                ; обновление opcode условного перехода без изменения его смещения
                LD (@PreviewEdgeRasterState.LeftFlatJump), A
LeftFlatLoop:   LD A, (HL)
                ; пиксельная операция над накопленным байтом, исходный NOP заменяется выбранной ветвью
LeftFlatOp:     NOP
                ; циклическое продвижение маски на одну колонку в выбранном направлении
                RLC C
                ; исходный JR C в режиме AND меняется на JR NC, направление границы связано с инверсией маски
LeftFlatJump:   JR C, @D3D.RasterizePreviewEdge.LeftFlatByte                    ; переход, если Carry установлен, перейти к соседнему экранному байту

                ; выбор накопителя ошибки вместо текущего экранного байта
LeftFlatError:  EX AF, AF'
                ; вычитание малой длины из ошибки пологой ветви
                SUB E
                JR C, @D3D.RasterizePreviewEdge.LeftFlatRow                     ; переход, если ошибка дала заём, продвинуть строку

                ; восстановление экранного байта после шага без смены строки
                EX AF, AF'
                DJNZ @D3D.RasterizePreviewEdge.LeftFlatOp

                LD (HL), A
                RET

                ; запись накопленного байта перед переходом границы колонки
LeftFlatByte:   LD (HL), A
                ; переход к соседнему байту без переноса младшего адреса в H
                DEC L
                ; чтение нового байта для последующего накопления пикселей
                LD A, (HL)
                JP @D3D.RasterizePreviewEdge.LeftFlatError

                ; восстановление ошибки добавлением главной длины после заёма
LeftFlatRow:    ADD A, D
                EX AF, AF'
                LD (HL), A
                ; продвижение старшего адресного байта на следующую пиксельную строку ULA
                INC H
                LD A, H
                ; проверка остатка строки внутри восьмистрочного знакоместа
                AND @ScreenConst.PixelOffsetMask
                JP NZ, @D3D.RasterizePreviewEdge.LeftFlatRead                   ; переход, если граница восьми строк не достигнута, адрес строки готов

                ; расчёт следующей строки знакомест через младший адрес
                LD A, L
                ; добавление 32 байтов к младшему экранному адресу
                ADD A, @ScreenConst.ByteColumns
                LD L, A
                JR C, @D3D.RasterizePreviewEdge.LeftFlatRead                    ; переход, если младший адрес переполнился, переход в следующую часть экрана уже готов

                ; коррекция старшего адреса внутри текущей части экрана
                LD A, H
                ; вычитание восьми старших адресных шагов после границы знакоместа
                SUB @ScreenConst.PixelsPerChar
                LD H, A
LeftFlatRead:   LD A, (HL)
                DJNZ @D3D.RasterizePreviewEdge.LeftFlatOp

                RET

                ; -----------------------------------------
                ; Крутая ветвь влево
                ; -----------------------------------------
                ; сохранение малой длины по колонкам и главной длины по строкам
LeftSteep:      LD E, A
                LD A, D
                LD B, D
                ; расчёт начальной половины главной длины для ошибки
                SRL A
                EX AF, AF'
                ; чтение байта пиксельной операции из физического экземпляра режима
                LD A, (@PreviewEdgeMode.Value.PixelOpcode)
                ; обновление opcode NOP выбранной ветви на подготовленный AND, XOR либо OR
                LD (@PreviewEdgeRasterState.LeftSteepOp), A
                ; чтение opcode перехода по границе байта, C для прямой маски, NC для инверсной
                LD A, (@PreviewEdgeMode.Value.BoundaryOpcode)
                ; обновление opcode условного перехода без изменения его смещения
                LD (@PreviewEdgeRasterState.LeftSteepJump), A
LeftSteepLoop:  LD A, (HL)
                ; пиксельная операция текущей строки, исходный NOP заранее заменён рабочим opcode
LeftSteepOp:    NOP
                ; запись изменённого байта перед обязательным продвижением строки
                LD (HL), A
                ; продвижение старшего адресного байта на следующую пиксельную строку ULA
                INC H
                LD A, H
                ; проверка остатка строки внутри восьмистрочного знакоместа
                AND @ScreenConst.PixelOffsetMask
                JP NZ, @D3D.RasterizePreviewEdge.LeftSteepError                 ; переход, если граница восьми строк не достигнута, адрес строки готов

                ; расчёт следующей строки знакомест через младший адрес
                LD A, L
                ; добавление 32 байтов к младшему экранному адресу
                ADD A, @ScreenConst.ByteColumns
                LD L, A
                JR C, @D3D.RasterizePreviewEdge.LeftSteepError                  ; переход, если младший адрес переполнился, переход в следующую часть экрана уже готов

                ; коррекция старшего адреса внутри текущей части экрана
                LD A, H
                ; вычитание восьми старших адресных шагов после границы знакоместа
                SUB @ScreenConst.PixelsPerChar
                LD H, A
                ; выбор накопителя ошибки после продвижения экранной строки
LeftSteepError: EX AF, AF'
                ; вычитание малой длины для решения о сдвиге колонки
                SUB E
                JR NC, @D3D.RasterizePreviewEdge.LeftSteepNext                  ; переход, если ошибка не дала заёма, колонку не менять

                ; восстановление ошибки добавлением главной длины
                ADD A, D
                ; сдвиг маски на следующую колонку после заёма ошибки
                RLC C
                ; режим AND заменяет исходный JR C на JR NC
LeftSteepJump:  JR C, @D3D.RasterizePreviewEdge.LeftSteepByte                   ; переход, если Carry установлен, изменить байтовую колонку

                ; восстановление рабочего AF после решения по колонке
LeftSteepNext:  EX AF, AF'
                DJNZ @D3D.RasterizePreviewEdge.LeftSteepLoop

                RET

                ; изменение байтовой колонки на единицу при переходе пиксельного бита через край
LeftSteepByte:  DEC L
                EX AF, AF'
                DJNZ @D3D.RasterizePreviewEdge.LeftSteepLoop

                RET

                ; -----------------------------------------
                ; Выбор ветви вправо
                ; -----------------------------------------
                ; расчёт модуля отрицательной разности колонок
Right:          NEG
                ; проверка главной оси для движения вправо
                CP D
                JR C, @D3D.RasterizePreviewEdge.RightSteep                      ; переход, если длина по колонкам меньше длины по строкам, выбрать крутую ветвь

                ; сохранение главной и малой длин пологого ребра вправо
                LD E, D
                LD D, A
                LD B, A
                ; расчёт начальной половины главной длины
                SRL A
                EX AF, AF'
                ; чтение байта пиксельной операции из физического экземпляра режима
                LD A, (@PreviewEdgeMode.Value.PixelOpcode)
                ; обновление opcode NOP выбранной ветви на подготовленный AND, XOR либо OR
                LD (@PreviewEdgeRasterState.RightFlatOp), A
                ; чтение opcode перехода по границе байта, C для прямой маски, NC для инверсной
                LD A, (@PreviewEdgeMode.Value.BoundaryOpcode)
                ; обновление opcode условного перехода без изменения его смещения
                LD (@PreviewEdgeRasterState.RightFlatJump), A
RightFlatLoop:  LD A, (HL)
                ; пиксельная операция над накопленным байтом, исходный NOP заменяется выбранной ветвью
RightFlatOp:    NOP
                ; циклическое продвижение маски на одну колонку в выбранном направлении
                RRC C
                ; исходный JR C в режиме AND меняется на JR NC, направление границы связано с инверсией маски
RightFlatJump:  JR C, @D3D.RasterizePreviewEdge.RightFlatByte                   ; переход, если Carry установлен, перейти к соседнему экранному байту

                ; выбор накопителя ошибки вместо текущего экранного байта
RightFlatError: EX AF, AF'
                ; вычитание малой длины из ошибки пологой ветви
                SUB E
                JR C, @D3D.RasterizePreviewEdge.RightFlatRow                    ; переход, если ошибка дала заём, продвинуть строку

                ; восстановление экранного байта после шага без смены строки
                EX AF, AF'
                DJNZ @D3D.RasterizePreviewEdge.RightFlatOp

                LD (HL), A
                RET

                ; запись накопленного байта перед переходом границы колонки
RightFlatByte:  LD (HL), A
                ; переход к соседнему байту без переноса младшего адреса в H
                INC L
                ; чтение нового байта для последующего накопления пикселей
                LD A, (HL)
                JP @D3D.RasterizePreviewEdge.RightFlatError

                ; восстановление ошибки добавлением главной длины после заёма
RightFlatRow:   ADD A, D
                EX AF, AF'
                LD (HL), A
                ; продвижение старшего адресного байта на следующую пиксельную строку ULA
                INC H
                LD A, H
                ; проверка остатка строки внутри восьмистрочного знакоместа
                AND @ScreenConst.PixelOffsetMask
                JP NZ, @D3D.RasterizePreviewEdge.RightFlatRead                  ; переход, если граница восьми строк не достигнута, адрес строки готов

                ; расчёт следующей строки знакомест через младший адрес
                LD A, L
                ; добавление 32 байтов к младшему экранному адресу
                ADD A, @ScreenConst.ByteColumns
                LD L, A
                JR C, @D3D.RasterizePreviewEdge.RightFlatRead                   ; переход, если младший адрес переполнился, переход в следующую часть экрана уже готов

                ; коррекция старшего адреса внутри текущей части экрана
                LD A, H
                ; вычитание восьми старших адресных шагов после границы знакоместа
                SUB @ScreenConst.PixelsPerChar
                LD H, A
RightFlatRead:  LD A, (HL)
                DJNZ @D3D.RasterizePreviewEdge.RightFlatOp

                RET

                ; -----------------------------------------
                ; Крутая ветвь вправо
                ; -----------------------------------------
                ; сохранение главной и малой длин крутого ребра вправо
RightSteep:     LD E, A
                LD A, D
                LD B, D
                ; расчёт начальной половины главной длины
                SRL A
                EX AF, AF'
                ; чтение байта пиксельной операции из физического экземпляра режима
                LD A, (@PreviewEdgeMode.Value.PixelOpcode)
                ; обновление opcode NOP выбранной ветви на подготовленный AND, XOR либо OR
                LD (@PreviewEdgeRasterState.RightSteepOp), A
                ; чтение opcode перехода по границе байта, C для прямой маски, NC для инверсной
                LD A, (@PreviewEdgeMode.Value.BoundaryOpcode)
                ; обновление opcode условного перехода без изменения его смещения
                LD (@PreviewEdgeRasterState.RightSteepJump), A
RightSteepLoop: LD A, (HL)
                ; пиксельная операция текущей строки, исходный NOP заранее заменён рабочим opcode
RightSteepOp:   NOP
                ; запись изменённого байта перед обязательным продвижением строки
                LD (HL), A
                ; продвижение старшего адресного байта на следующую пиксельную строку ULA
                INC H
                LD A, H
                ; проверка остатка строки внутри восьмистрочного знакоместа
                AND @ScreenConst.PixelOffsetMask
                JP NZ, @D3D.RasterizePreviewEdge.RightSteepError                ; переход, если граница восьми строк не достигнута, адрес строки готов

                ; расчёт следующей строки знакомест через младший адрес
                LD A, L
                ; добавление 32 байтов к младшему экранному адресу
                ADD A, @ScreenConst.ByteColumns
                LD L, A
                JR C, @D3D.RasterizePreviewEdge.RightSteepError                 ; переход, если младший адрес переполнился, переход в следующую часть экрана уже готов

                ; коррекция старшего адреса внутри текущей части экрана
                LD A, H
                ; вычитание восьми старших адресных шагов после границы знакоместа
                SUB @ScreenConst.PixelsPerChar
                LD H, A
                ; выбор накопителя ошибки после продвижения экранной строки
RightSteepError:EX AF, AF'
                ; вычитание малой длины для решения о сдвиге колонки
                SUB E
                JR NC, @D3D.RasterizePreviewEdge.RightSteepNext                 ; переход, если ошибка не дала заёма, колонку не менять

                ; восстановление ошибки добавлением главной длины
                ADD A, D
                ; сдвиг маски на следующую колонку после заёма ошибки
                RRC C
                ; режим AND заменяет исходный JR C на JR NC
RightSteepJump: JR C, @D3D.RasterizePreviewEdge.RightSteepByte                  ; переход, если Carry установлен, изменить байтовую колонку

                ; восстановление рабочего AF после решения по колонке
RightSteepNext: EX AF, AF'
                DJNZ @D3D.RasterizePreviewEdge.RightSteepLoop

                RET

                ; изменение байтовой колонки на единицу при переходе пиксельного бита через край
RightSteepByte: INC L
                EX AF, AF'
                DJNZ @D3D.RasterizePreviewEdge.RightSteepLoop

                RET

                ; -----------------------------------------
                endmodule
                endmodule
