                module D3D
                module ProjectPreviewVertexGroup
                ; Документация [генератор группы вершин](../../Docs/PreviewVertexGroup.md)
                ; -----------------------------------------
                ; Генерация комбинаций вершин по маске с настоящей перспективой, рабочим стеком и восстановлением CPU-возврата
                ; исходная запись 6, банк 4, файловые смещения #1908..#1A13
                ; In:
                ;   девять произведений заданы шестью операндами PackedFirst..PackedThird и DepthFirst..DepthThird, каждое упакованное слово содержит две байтовые компоненты
                ;   IX - IXL восьмибитная маска вершин, бит i относится к комбинации i
                ;   NextOffset является младшим байтом существующего LD SP,C600, штатное начальное значение 4
                ;   базы, центры и три показателя масштаба настроены для ProjectPreviewVertex, b=1..6
                ;   SP указывает на обычный CPU-возврат, рабочий буфер C600 доступен для записи без пересечения с исходниками и CPU-стеком
                ;   входной рабочий SP p=C600+NextOffset и все p+5*k остаются в допустимой части страницы C6
                ;   банк 4 доступен для записи, прерывания отключены, NMI и повторный вход исключены
                ; Out:
                ;   HL - следующий рабочий SP p+5*n, DE - последняя загруженная упакованная комбинация, BC - B маска, C побайтово циклически удвоенный младший PackedFirst
                ;   AF - A младший байт следующего рабочего SP, S/Z/PV относятся к последнему пути, точные случаи описаны в PreviewVertexGroup.md
                ;   IX - IXH третья компонента комбинации 0 либо её отрицание при маске 81, IXL третья компонента комбинации 2
                ;   IY - IYH третья компонента комбинации 1, IYL третья компонента комбинации 3
                ;   HL', DE', BC', AF' принадлежат последней проекции, при нулевой маске полностью сохраняются
                ;   подготовлены восемь упакованных комбинаций в операндах и четыре третьих компоненты, NextOffset обновлён
                ;   SavedSP содержит входной CPU-SP, SP после обычного RET равен входному SP+2, I, IFF и IM сохраняются
                ;   в рабочий буфер записаны n результатов проекции с шагом пять, правила отказа и сохранения соседнего слова относятся к ProjectPreviewVertex
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, операнды комбинаций и возврата SP, рабочий буфер проекции
                ; Note:
                ;   обычный порядок маски равен 0,1,3,2,6,7,5,4, нулевая маска не вызывает проекцию
                ;   маска 01 проектирует только комбинацию 0, маска 81 проектирует её и побайтово отрицательную комбинацию 0
                ;   арифметика упакованных слов допускает межбайтовые переносы, отрицание каждой компоненты выполняется отдельно
                ;   удвоения отдельных компонент являются циклическими RLC, не заменяются обычным умножением на два
                ;   после каждой вершины проекция передаёт управление через HL, CPU-стек восстанавливается только в Finish
                ;   это самостоятельный генератор группы, физический обход групп и формат всей модели проверяются отдельно
                ; -----------------------------------------
                ; -----------------------------------------
                ; CPU-стек и первые комбинации
                ; -----------------------------------------
                ; сохранение обычного CPU-SP до переключения на выходной буфер
Entry:          LD (@PreviewVertexGroupState.SavedSP), SP
                ; выбор рабочего SP из страницы C6 и подготовленного NextOffset
                LD SP, #C600
                ; чтение первой пары произведений, две байтовые оси упакованы в BC
                LD BC, #0000
                ; чтение второй пары произведений в DE
                LD DE, #0000
                ; чтение третьей пары произведений в HL
                LD HL, #0000
                ; расчёт упакованной комбинации 0 через два сложения слов с исходными межбайтовыми переносами
                ADD HL, BC
                ADD HL, DE
                ; обновление упакованной комбинации 0 для диспетчера
                LD (@PreviewVertexGroupState.PackedVertex0), HL
                ; расчёт циклически удвоенных байтов первых двух пар, исходный RLC сохраняет перенос старшего бита в младший
                RLC B
                RLC C
                RLC D
                RLC E
                ; очистка Carry перед вычитанием первой пары
                OR A
                ; расчёт комбинации 1 вычитанием циклически удвоенной первой пары
                SBC HL, BC
                LD (@PreviewVertexGroupState.PackedVertex1), HL
                ; очистка Carry перед вычитанием второй пары
                OR A
                ; расчёт комбинации 3 вычитанием циклически удвоенной второй пары
                SBC HL, DE
                LD (@PreviewVertexGroupState.PackedVertex3), HL
                ; расчёт комбинации 2 добавлением циклически удвоенной первой пары
                ADD HL, BC
                LD (@PreviewVertexGroupState.PackedVertex2), HL
                ; расчёт комбинации 5 отдельным отрицанием младшего и старшего байтов комбинации 2
                LD A, L
                NEG
                LD L, A
                LD A, H
                NEG
                LD H, A
                LD (@PreviewVertexGroupState.PackedVertex5), HL
                ; расчёт комбинации 4 добавлением циклически удвоенной первой пары
                ADD HL, BC
                LD (@PreviewVertexGroupState.PackedVertex4), HL
                ; очистка Carry перед расчётом комбинации 6
                OR A
                ; расчёт комбинации 6 вычитанием циклически удвоенной второй пары
                SBC HL, DE
                LD (@PreviewVertexGroupState.PackedVertex6), HL
                ; очистка Carry перед расчётом комбинации 7
                OR A
                ; расчёт комбинации 7 вычитанием циклически удвоенной первой пары
                SBC HL, BC
                LD (@PreviewVertexGroupState.PackedVertex7), HL
                ; -----------------------------------------
                ; Третьи компоненты и сохранение маски
                ; -----------------------------------------
                ; сохранение входной маски из IXL до использования индексного регистра для координат
                LD B, IXL
                ; чтение третьего произведения третьей компоненты
                LD A, #00
                ; чтение первых двух произведений третьей компоненты в D и E
                LD DE, #0000
                ; расчёт третьей компоненты комбинации 0 с байтовым оборачиванием
                ADD A, D
                ADD A, E
                LD IXH, A
                ; расчёт циклически удвоенных первых двух произведений
                RLC D
                RLC E
                ; расчёт третьей компоненты комбинации 1
                SUB D
                LD IYH, A
                ; расчёт третьей компоненты комбинации 3
                SUB E
                LD IYL, A
                ; расчёт третьей компоненты комбинации 2
                ADD A, D
                LD IXL, A
                ; расчёт отрицательной третьей компоненты комбинации 5
                NEG
                LD (@PreviewVertexGroupState.DepthVertex5), A
                ; расчёт третьей компоненты комбинации 4
                ADD A, D
                LD (@PreviewVertexGroupState.DepthVertex4), A
                ; расчёт третьей компоненты комбинации 6
                SUB E
                LD (@PreviewVertexGroupState.DepthVertex6), A
                ; расчёт третьей компоненты комбинации 7
                SUB D
                LD (@PreviewVertexGroupState.DepthVertex7), A
                ; -----------------------------------------
                ; Особые маски одной и двух противоположных вершин
                ; -----------------------------------------
                ; чтение упакованной комбинации 0 перед выбором диспетчеризации
                LD DE, #0000
                LD A, B
                ; проверка особой маски единственной вершины
                CP @PreviewVertexGroupConst.SingleMask
                JR Z, @D3D.ProjectPreviewVertexGroup.SingleOrLast               ; переход, если маска равна 01, спроектировать только комбинацию 0

                ; проверка особой маски пары противоположных вершин
                CP @PreviewVertexGroupConst.OppositeMask
                JR NZ, @D3D.ProjectPreviewVertexGroup.Masked                    ; переход, если маска не равна 81, обойти обычные восемь битов

                ; подготовка первой вершины пары и продолжения для построения её противоположности
                LD A, IXH
                LD HL, @D3D.ProjectPreviewVertexGroup.Opposite
                JP @D3D.ProjectPreviewVertex.Entry

                ; расчёт противоположной вершины отдельным отрицанием третьего байта и обоих байтов упакованного слова
Opposite:       LD A, IXH
                NEG
                LD IXH, A
                LD A, D
                NEG
                LD D, A
                LD A, E
                NEG
                LD E, A
                ; подготовка единственной либо последней вершины и прямого продолжения к восстановлению CPU-SP
SingleOrLast:   LD A, IXH
                LD HL, @D3D.ProjectPreviewVertexGroup.Finish
                JP @D3D.ProjectPreviewVertex.Entry

                ; -----------------------------------------
                ; Обычный масочный обход
                ; -----------------------------------------
                ; подготовка третьей компоненты комбинации 0
Masked:         LD A, IXH
                ; проверка бита 0, выбирающего комбинацию 0
                BIT @PreviewVertexGroupConst.Vertex0Bit, B
                LD HL, @D3D.ProjectPreviewVertexGroup.Vertex1
                JP NZ, @D3D.ProjectPreviewVertex.Entry                          ; переход, если бит 0 установлен, спроектировать комбинацию 0

                ; чтение упакованной комбинации 1 для текущего бита маски
Vertex1:        LD DE, #0000
                LD A, IYH
                ; проверка бита 1, выбирающего комбинацию 1
                BIT @PreviewVertexGroupConst.Vertex1Bit, B
                LD HL, @D3D.ProjectPreviewVertexGroup.Vertex3
                JP NZ, @D3D.ProjectPreviewVertex.Entry                          ; переход, если бит 1 установлен, спроектировать комбинацию 1

                ; чтение упакованной комбинации 3 для текущего бита маски
Vertex3:        LD DE, #0000
                LD A, IYL
                ; проверка бита 3, выбирающего комбинацию 3
                BIT @PreviewVertexGroupConst.Vertex3Bit, B
                LD HL, @D3D.ProjectPreviewVertexGroup.Vertex2
                JP NZ, @D3D.ProjectPreviewVertex.Entry                          ; переход, если бит 3 установлен, спроектировать комбинацию 3

                ; проверка бита 2, выбирающего комбинацию 2
Vertex2:        BIT @PreviewVertexGroupConst.Vertex2Bit, B
                ; чтение упакованной комбинации 2 для текущего бита маски
                LD DE, #0000
                LD A, IXL
                LD HL, @D3D.ProjectPreviewVertexGroup.Vertex6
                JP NZ, @D3D.ProjectPreviewVertex.Entry                          ; переход, если бит 2 установлен, спроектировать комбинацию 2

                ; чтение упакованной комбинации 6 для текущего бита маски
Vertex6:        LD DE, #0000
                LD A, #00
                ; проверка бита 6, выбирающего комбинацию 6
                BIT @PreviewVertexGroupConst.Vertex6Bit, B
                LD HL, @D3D.ProjectPreviewVertexGroup.Vertex7
                JP NZ, @D3D.ProjectPreviewVertex.Entry                          ; переход, если бит 6 установлен, спроектировать комбинацию 6

                ; чтение упакованной комбинации 7 для текущего бита маски
Vertex7:        LD DE, #0000
                LD A, #00
                ; проверка бита 7, выбирающего комбинацию 7
                BIT @PreviewVertexGroupConst.Vertex7Bit, B
                LD HL, @D3D.ProjectPreviewVertexGroup.Vertex5
                JP NZ, @D3D.ProjectPreviewVertex.Entry                          ; переход, если бит 7 установлен, спроектировать комбинацию 7

                ; чтение упакованной комбинации 5 для текущего бита маски
Vertex5:        LD DE, #0000
                LD A, #00
                ; проверка бита 5, выбирающего комбинацию 5
                BIT @PreviewVertexGroupConst.Vertex5Bit, B
                LD HL, @D3D.ProjectPreviewVertexGroup.Vertex4
                JP NZ, @D3D.ProjectPreviewVertex.Entry                          ; переход, если бит 5 установлен, спроектировать комбинацию 5

                ; чтение упакованной комбинации 4 для текущего бита маски
Vertex4:        LD DE, #0000
                LD A, #00
                ; проверка бита 4, выбирающего комбинацию 4
                BIT @PreviewVertexGroupConst.Vertex4Bit, B
                LD HL, @D3D.ProjectPreviewVertexGroup.Finish
                JP NZ, @D3D.ProjectPreviewVertex.Entry                          ; переход, если бит 4 установлен, спроектировать комбинацию 4

                ; -----------------------------------------
                ; Свободный индекс и восстановление CPU-возврата
                ; -----------------------------------------
                ; расчёт следующего рабочего адреса без изменения текущего SP
Finish:         LD HL, #0000
                ADD HL, SP
                ; чтение младшего байта следующего рабочего адреса для последующей группы
                LD A, L
                ; обновление NextOffset перед восстановлением CPU-стека
                LD (@PreviewVertexGroupState.NextOffset), A
                ; восстановление исходного CPU-SP из сохранённого операнда
                LD SP, #0000
                RET

                ; -----------------------------------------
                endmodule
                endmodule
