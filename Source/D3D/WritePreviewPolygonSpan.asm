                ; -----------------------------------------
                ; Развёрнутая запись 0..31 полного байта и маскированный правый край с продолжением в цикл строк
                ; исходная запись 6, банк 4, файловые смещения #11C0..#1206
                ; In:
                ;   HL - адрес выбранного входа Entry, Fill30..Fill1 либо RightEdge, исходный Entry пишет 31 полный байт
                ;   DE - D страница C0 либо C1 пары правых масок, входной E не используется
                ;   BC - B старший экранный адрес, C первая внутренняя байтовая колонка, INC C не переносится в B
                ;   AF - A шаблон полного байта текущей строки, Carry сохраняется в F следующими INC C
                ;   HL', DE', BC', AF', IX задают сохраняемый контекст, IY содержит IYL индекса пары правых масок
                ;   IYL=(колонка правого пикселя AND 7)*32+2*индекс заполнения+16, профиль индексов 0..4
                ;   SP и все параметры общего цикла подготовлены, в памяти CPU-возврат не создаётся
                ; Out:
                ;   HL - H исходный D, L исходный IYL+1, указатель правого байта заполнения
                ;   DE - исходный HL, выбранный адрес развёрнутой записи
                ;   BC - B сохранён, C увеличен на число полных байтов по модулю 256
                ;   AF - A новый правый экранный байт, F от OR сохраняемой и заполняемой частей
                ;   HL', DE', BC' сохранены, AF' содержит входной A и F последнего INC C либо входной F при нуле полных байтов
                ;   IX, IY, SP, I, IFF и IM сохранены, следующий исполняемый адрес StepPreviewPolygonRow.Entry
                ;   записаны все полные байты и правый край, запись края выполняется и при нулевой ширине его маски
                ; Corrupt:
                ;   HL, DE, BC - только C, AF, AF', полные экранные байты и правый край
                ; Note:
                ;   входы разделены двумя байтами, Entry пишет 31 байт, Fill30..Fill1 соответствующее число, RightEdge ни одного полного
                ;   переход JP (HL) вызывающего цикла уже обменял AF с альтернативным, повторного обмена до полных байтов нет
                ;   31-й полный байт не достигается контуром с обеими колонками 0..255, его исходные инструкции отдельно проверены
                ;   самостоятельного RET нет, физический порядок двух ASM обязателен, схема рассчитана на отсутствие аппаратных IRQ
                ; -----------------------------------------
                ; -----------------------------------------
                ; Полные внутренние байты строки
