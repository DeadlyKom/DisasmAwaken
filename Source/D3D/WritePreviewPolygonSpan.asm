                ; -----------------------------------------
                ; Правый край и последовательное продолжение
                ; -----------------------------------------
                ; возврат основного AF после вывода полных байтов, шаблон остаётся в AF'
RightEdge:      EX AF, AF'
                ; выбор пары масок правого пиксельного края из упакованного IY
                LD E, IYL
                EX DE, HL
                ; чтение байта правого края, в том числе при нулевом числе затронутых пикселей
                LD A, (BC)
                ; сохранение пикселей справа от исключённой границы
                AND (HL)
                ; выбор следующего байта пары, содержащего заполнение левой части края
                INC L
                ; объединение сохранённых внешних пикселей с шаблоном внутри контура
                OR (HL)
                ; запись правого края перед общим продвижением строки
                LD (BC), A
                ; JP @D3D.StepPreviewPolygonRow.Entry, продолжение в StepPreviewPolygonRow.asm

