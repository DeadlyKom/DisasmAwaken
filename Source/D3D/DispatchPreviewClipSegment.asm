                module D3D
                module DispatchPreviewClipSegment
                ; Документация [перестановка двух полных записей, точный вход обработчика и общий эпилог CP 4](../../Docs/PreviewClipSegment.md)
                ; -----------------------------------------
                ; Перестановка внутреннего первого конца и табличное отсечение отдельного сегмента
                ; исходная запись 6, банк 4, файловые смещения #2AB6..#2B0F
                ; In:
                ;   HL, DE, BC и AF произвольный исходный контекст, параметры читаются из PreviewClipFirst и PreviewClipSecond
                ;   HL', DE', BC' сохраняются, AF' и IX рабочий контекст арифметики, IY сохраняется
                ;   два физических конца содержат слова координат и согласованные полные коды сторон
                ;   D3D подключён в банке 4, E011 настроил операнды границ, страницы CC/CD содержат исходные цели
                ;   под CPU-SP доступны байты трёх подставных возвратов и вложенных вызовов, обычный адрес возврата доступен
                ;   все фактически исполненные деления имеют ненулевой знаменатель и допустимое слово частного
                ; Out:
                ;   HL и BC обычного выхода равны контексту последнего действия обработчика, DE=Return, A=ByteCount, F от CP 4
                ;   специальный выход даёт HL=EBF2, DE рабочий, BC=00EA, AF=EBA9, A=EB не является размером
                ;   HL', DE', BC' сохранены, AF' и IX определяются исполненным путём, IY сохранён
                ;   при полном коде первого конца F0 две пятибайтовые записи меняются местами, иначе остаются на своих местах
                ;   BlockCode=1, ByteCount содержит размер результата 0, 2 или 4 в проверенной геометрической области
                ;   младшая тетрада SeenFlags может получать отметки углов, старшая сохраняется, выбранные кэши обновляются
                ;   SP после окончательного возврата равен входному+2, I, IFF и IM сохраняются
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', IX по выбранному пути, оба конца при обмене, BlockCode, SeenFlags, ByteCount, кэши, страница C8 и CPU-стек
                ; Note:
                ;   непосредственно перед JP HL равен цели, DE=EB08, BC имеет входной C, B равен F0 при обмене либо входному B
                ;   входной AF обработчика содержит A=индекс таблицы, F=88 от INC H страницы CC в CD
                ;   индекс равен ((NOT код первого) AND F0) OR (код второго AND 0F) после возможной перестановки
                ;   три слова EB08 расположены под входным SP, обычный эпилог снимает два оставшихся слова, специальный снимает все три
                ;   CP 4 устанавливает Z только для двух точек, Carry устанавливается для размера 0 или 2
                ;   два внутренних конца дают одну выходную точку, размер 2 и Carry=1, полноценным отрезком такой результат не считается
                ;   состояние SeenFlags перед обработчиком сохраняется, оно здесь не обнуляется
                ;   префикс проверен в 20736 контекстах, геометрия в 534160 случаях, все конечные регистры всех путей не заявлены
                ; -----------------------------------------
                ; установка ненулевого режима, отдельные угловые точки сегменту не добавляются
Entry:          LD A, @PreviewClipDispatchConst.BlockCorners
                LD (@PreviewClipCorners.Value.BlockCode), A
                ; проверка полного кода первого конца на точное внутреннее значение F0
                LD A, (@PreviewClipFirst.Value.Outcode)
                CP @PreviewClipDispatchConst.InsideCode
                JR NZ, @D3D.DispatchPreviewClipSegment.PickCase                 ; переход, если полный код первого конца не равен F0, сохранить порядок концов

                ; -----------------------------------------
                ; Обмен двух полных пятибайтовых записей
                ; -----------------------------------------
                ; сохранение внутреннего кода и перестановка кодов сторон
                LD B, A
                LD A, (@PreviewClipSecond.Value.Outcode)
                LD (@PreviewClipFirst.Value.Outcode), A
                LD A, B
                LD (@PreviewClipSecond.Value.Outcode), A
                ; обмен координатными словами колонок, флаги сравнения сохраняются
                LD HL, (@PreviewClipFirst.Value.SecondAxis)
                LD DE, (@PreviewClipSecond.Value.SecondAxis)
                LD (@PreviewClipSecond.Value.SecondAxis), HL
                LD (@PreviewClipFirst.Value.SecondAxis), DE
                ; обмен координатными словами строк без изменения флагов
                LD HL, (@PreviewClipFirst.Value.FirstAxis)
                LD DE, (@PreviewClipSecond.Value.FirstAxis)
                LD (@PreviewClipSecond.Value.FirstAxis), HL
                LD (@PreviewClipFirst.Value.FirstAxis), DE
                ; -----------------------------------------
                ; Индекс таблицы и CPU-кадр
                ; -----------------------------------------
                ; обнуление байтового размера нового результата
PickCase:       XOR A
                LD (@PreviewContourSize.Value.ByteCount), A
                ; расчёт старшей тетрады индекса из дополнения к коду первого конца
                LD A, (@PreviewClipFirst.Value.Outcode)
                CPL
                AND @PreviewClipDispatchConst.ComplementMask
                LD L, A
                ; расчёт младшей тетрады по коду сторон второго конца
                LD A, (@PreviewClipSecond.Value.Outcode)
                AND @PreviewClipDispatchConst.SideMask
                OR L
                LD L, A
                ; поиск двух байтов цели на страницах CC и CD
                LD H, @PreviewClipDispatchConst.LowTablePage
                LD E, (HL)
                ; переход к странице старших байтов, итоговый F=88 от INC H при Carry=0
                INC H
                LD D, (HL)
                EX DE, HL
                ; создание трёх одинаковых подставных CPU-возвратов для общего и специального выходов
                LD DE, @D3D.DispatchPreviewClipSegment.Return
                PUSH DE
                PUSH DE
                PUSH DE
                ; передача управления фактической цели таблицы без четвёртого слова возврата
                JP (HL)

                ; -----------------------------------------
                ; Обычный эпилог сегмента
                ; -----------------------------------------
                ; чтение результата и снятие двух оставшихся подставных возвратов
Return:         LD A, (@PreviewContourSize.Value.ByteCount)
                POP DE
                POP DE
                ; проверка размера ровно из двух точек, флаги возвращаются внешнему конвейеру
                CP @PreviewClipDispatchConst.TwoPointBytes
                RET

                ; -----------------------------------------
                endmodule
                endmodule
