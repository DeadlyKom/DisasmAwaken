                module PreviewPrices
                ; Документация [ценовые списки и временные разделители](../../../Docs/PreviewPrices.md)
                ; исходная кодировка CP866, код 02 задаёт колонку цены, CR и LF сохраняются
                assert $ == #CE40
                ; -----------------------------------------
                ; Доминион, исходные байты ценового потока
Dominion:       DB #0D, #84, #AE, #AC, #A8, #AD, #A8, #AE, #AD, #02, #36, #34, #30, #30, #30
                ; -----------------------------------------
                ; Софист, исходные байты ценового потока
Sofist:         DB #0D, #91, #AE, #E4, #A8, #E1, #E2, #02, #34, #34, #30, #30, #30
                ; -----------------------------------------
                ; Мемфис, исходные байты ценового потока
Memfis:         DB #0D, #8C, #A5, #AC, #E4, #A8, #E1, #02, #34, #30, #30, #30, #30
                ; -----------------------------------------
                ; Фирс, исходные байты ценового потока
Firs:           DB #0D, #94, #A8, #E0, #E1, #02, #33, #35, #30, #30, #30
                ; -----------------------------------------
                ; Орсан, исходные байты ценового потока
Orsan:          DB #0D, #8E, #E0, #E1, #A0, #AD, #02, #33, #34, #30, #30, #30
                ; -----------------------------------------
                ; Барос, исходные байты ценового потока
Baros:          DB #0D, #81, #A0, #E0, #AE, #E1, #02, #32, #37, #30, #30, #30
                ; -----------------------------------------
                ; Карэн, исходные байты ценового потока
                ; начальный LF отделяет Карэна от обычного рыночного списка, для собственного индекса 6 меняется на CR
Karen:          DB #0A, #8A, #A0, #E0, #ED, #AD, #02, #31, #33, #30, #30, #30, #0A
                ; -----------------------------------------
                ; Фервест, исходные байты ценового потока
Fervest:        DB #0D, #94, #A5, #E0, #A2, #A5, #E1, #E2, #02, #33, #30, #30, #30, #30
                ; -----------------------------------------
                ; Кридан, исходные байты ценового потока
                ; исходное имя Кридан сохранено, в описательном потоке исходник использует Кридон
Kridan:         DB #0D, #8A, #E0, #A8, #A4, #A0, #AD, #02, #32, #37, #30, #30, #30
                ; -----------------------------------------
                ; Протос, исходные байты ценового потока
Protos:         DB #0D, #8F, #E0, #AE, #E2, #AE, #E1, #02, #32, #34, #30, #30, #30
                ; -----------------------------------------
                ; Алгол, исходные байты ценового потока
Algol:          DB #0D, #80, #AB, #A3, #AE, #AB, #02, #31, #38, #30, #30, #30, #0A
                ; -----------------------------------------
                ; Модель, исходные байты ценового потока
                ; 31 исходный байт FF после CR сохранены, они не заменяются пробелами ASCII
Heading:        DB #8C, #AE, #A4, #A5, #AB, #EC, #02, #96, #A5, #AD, #A0, #0D, #FF, #FF, #FF, #FF
                DB #FF, #FF, #FF, #FF, #FF, #FF, #FF, #FF, #FF, #FF, #FF, #FF, #FF, #FF, #FF, #FF
                DB #FF, #FF, #FF, #FF, #FF, #FF, #FF, #FF, #FF, #FF, #FF, #0A
                endmodule
