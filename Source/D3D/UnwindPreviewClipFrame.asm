                module D3D
                module UnwindPreviewClipFrame
                ; Документация [три служебных возврата, все поля кадра, точные флаги и геометрическая проверка EAB6](../../Docs/PreviewClipSegment.md)
                ; -----------------------------------------
                ; Снятие трёх служебных слов отсечения и возврат по настоящему CPU-адресу с Carry
                ; исходная запись 6, банк 4, файловые смещения #285D..#2866
                ; In:
                ;   SP указывает на существующий FClipUnwindFrame, три служебных слова и настоящий ReturnAddress
                ;   FirstWord задаёт A старшим байтом, SecondWord задаёт старший байт смещения, ThirdWord базовое слово HL
                ;   это не самостоятельный CALL с одним словом возврата, в EAB6 три поля равны EB08
                ; Out:
                ;   HL=(ThirdWord+((high(SecondWord)-1) AND FF)) AND FFFF, DE сохранён
                ;   BC=(high(SecondWord)-1) AND FF, старший B нулевой
                ;   AF - A=high(FirstWord), Carry=1, S/Z/PV от DEC high(SecondWord), H=N=0, биты 5 и 3 из A
                ;   HL', DE', BC', AF', IX, IY, I, IFF и IM сохранены
                ;   SP равен входному+8, управление передано ReturnAddress, память не записывается
                ;   для трёх EB08 возвращаются HL=EBF2, DE сохранён, BC=00EA, AF=EBA9
                ; Corrupt:
                ;   HL, BC, AF, SP
                ; Note:
                ;   снятые слова намеренно не исполняются как обычные возвраты, весь кадр удаляется за один выход
                ;   флаги не равны флагам сравнения OutputSize, Z не является проверкой четырёх выходных байтов
                ;   вход EAB6 различает обычный EB08 и этот выход, графическая причина выхода задаётся обработчиками таблицы
                ; -----------------------------------------
                ; чтение FirstWord кадра, старший байт становится выходным A
Entry:          POP AF
                ; чтение SecondWord, его старший байт задаёт оборачиваемое смещение
                POP BC
                ; чтение ThirdWord как базы возвращаемого HL
                POP HL
                ; выбор старшего байта второго слова для байтового смещения
                LD C, B
                ; расчёт смещения минус один, S/Z/PV этого DEC сохраняются до возврата
                DEC C
                ; обнуление старшей части смещения перед прибавлением к HL
                LD B, #00
                ; расчёт окончательного HL по модулю 65536 без изменения S/Z/PV
                ADD HL, BC
                ; установка Carry, сброс H и N, недокументированные биты берутся из A
                SCF
                ; возврат по четвёртому слову кадра, три служебных адреса уже сняты
                RET

                endmodule
                endmodule
