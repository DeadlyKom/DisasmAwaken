                module D3D
                module MultiplyPreviewCoordinate
                ; Документация [переходный умножитель координаты](../../Docs/PreviewCoordinateMultiply.md)
                ; -----------------------------------------
                ; Знаковое произведение 16-битной координаты и 7-битного коэффициента с усечением после деления на 128 и переходным возвратом
                ; исходная запись 6, банк 4, файловые смещения #2B10..#2B7D
                ; In:
                ;   HL - сохраняемый контекст будущего HL', DE - адрес продолжения, BC - сохраняемый контекст будущего BC'
                ;   AF - A знаковый коэффициент -127..127, исходные флаги параметром не являются
                ;   DE' - знаковая 16-битная координата, BC' - B' сохраняется как основной B, остальные несохранённые альтернативные регистры рабочие
                ;   банк 4 выбран, ReturnTarget доступен для записи, продолжение не требует обычного снятия адреса со стека
                ;   повторный вход и прерывающий вызов этого умножителя не допускаются до исполнения завершающего JP
                ; Out:
                ;   HL - знаковое произведение координаты и коэффициента, делённое на 128 с усечением к нулю
                ;   DE - модуль исходной координаты при неотрицательном знаке, модуль усечённого произведения при отрицательном
                ;   BC - B равен входному B', C=0, AF - A равен входному коэффициенту XOR старший байт исходного DE'
                ;   при неотрицательном знаке F соответствует XOR знакового байта, при отрицательном F от SBC 0, модуль, Carry равен ненулевому модулю
                ;   HL', DE', BC' получают входные основные HL, DE, BC после одного EXX, DE' поэтому содержит адрес продолжения
                ;   AF' - A' старший байт модуля результата, F' от последнего ADC аккумулятора либо последнего ADD для нулевого коэффициента
                ;   IX, IY, I, IFF и IM сохраняются, SP не меняется, финальный JP передаёт управление входному DE
                ;   единственная запись памяти самой процедуры - два байта ReturnTarget по EB7C и EB7D
                ;   для нештатного коэффициента 80 исходный алгоритм возвращает нулевой модуль, знак и перестановка регистров сохраняются
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', операнд ReturnTarget
                ; Note:
                ;   это не CALL/RET-функция, адрес продолжения передаётся в основном DE до EXX, координата находится в альтернативном DE'
                ;   развёрнутый цикл обрабатывает семь значащих разрядов модуля коэффициента, младшие семь разрядов произведения отбрасываются до применения знака
                ;   при малом отрицательном произведении результат ноль, математический floor для отрицательных чисел здесь неверен
                ;   коэффициенты 80 в матричном входе EC28 заранее заменяются на 81, локальный умножитель этой защиты не делает
                ;   договор относится к локальному алгоритму, полный кадр D3D и аппаратный IRQ не объявляются доказанными
                ; -----------------------------------------
                ; сохранение адреса продолжения в исходном операнде JP, CPU-стек не используется
Entry:          LD (@PreviewMultiplyState.ReturnTarget), DE
                ; выбор координаты из DE' и перенос основного контекста в альтернативные регистры
                EXX
                ; сохранение коэффициента перед вычислением знака произведения
                LD L, A
                ; расчёт знака через XOR коэффициента и старшего байта исходной координаты
                XOR D
                ; сохранение знакового байта и его логических флагов в AF'
                EX AF, AF'
                ; проверка отрицательной координаты перед вычислением её модуля
                BIT 7, D
                JR Z, @D3D.MultiplyPreviewCoordinate.AbsoluteCoeff              ; переход, если координата неотрицательна, её модуль уже находится в DE

                ; расчёт 16-битного модуля отрицательной координаты, 8000 остаётся допустимым беззнаковым модулем
                LD A, E
                CPL
                LD E, A
                LD A, D
                CPL
                LD D, A
                INC DE
                ; чтение сохранённого коэффициента для перехода к его модулю
AbsoluteCoeff:  LD A, L
                ; проверка знака коэффициента, флаги исходного вызова не используются
                AND A
                JP P, @D3D.MultiplyPreviewCoordinate.StartProduct               ; переход, если коэффициент неотрицателен, отрицание не требуется

                ; расчёт модуля отрицательного коэффициента, особый 80 остаётся 80
                NEG
                ; обнуление переноса для ADC верхнего аккумулятора и 16-битной части произведения
StartProduct:   LD C, #00
                LD H, C
                LD L, C
                ; выделение старшего из семи значащих разрядов коэффициента
                ADD A, A
                ADD A, A
                JR C, @D3D.MultiplyPreviewCoordinate.AddBit6                    ; переход, если очередной разряд 6 модуля коэффициента равен 1, начать накопление

                ADD A, A
                JR C, @D3D.MultiplyPreviewCoordinate.AddBit5                    ; переход, если очередной разряд 5 модуля коэффициента равен 1, начать накопление

                ADD A, A
                JR C, @D3D.MultiplyPreviewCoordinate.AddBit4                    ; переход, если очередной разряд 4 модуля коэффициента равен 1, начать накопление

                ADD A, A
                JR C, @D3D.MultiplyPreviewCoordinate.AddBit3                    ; переход, если очередной разряд 3 модуля коэффициента равен 1, начать накопление

                ADD A, A
                JR C, @D3D.MultiplyPreviewCoordinate.AddBit2                    ; переход, если очередной разряд 2 модуля коэффициента равен 1, начать накопление

                ADD A, A
                JR C, @D3D.MultiplyPreviewCoordinate.AddBit1                    ; переход, если очередной разряд 1 модуля коэффициента равен 1, начать накопление

                ADD A, A
                JR C, @D3D.MultiplyPreviewCoordinate.AddBit0                    ; переход, если очередной разряд 0 модуля коэффициента равен 1, начать накопление

                ; нулевой коэффициент пропускает все сложения и перенос результата
                JP @D3D.MultiplyPreviewCoordinate.ApplySign

                ; накопление вклада разряда 6 с переносом в верхний аккумулятор
AddBit6:        ADD HL, DE
                ADC A, C
                ADD HL, HL
                ADC A, A
                JR NC, @D3D.MultiplyPreviewCoordinate.ShiftBit5                 ; переход, если следующий разряд 5 равен 0, пропустить прибавление координаты

                ; накопление вклада разряда 5 с переносом в верхний аккумулятор
AddBit5:        ADD HL, DE
                ADC A, C
ShiftBit5:      ADD HL, HL
                ADC A, A
                JR NC, @D3D.MultiplyPreviewCoordinate.ShiftBit4                 ; переход, если следующий разряд 4 равен 0, пропустить прибавление координаты

                ; накопление вклада разряда 4 с переносом в верхний аккумулятор
AddBit4:        ADD HL, DE
                ADC A, C
ShiftBit4:      ADD HL, HL
                ADC A, A
                JR NC, @D3D.MultiplyPreviewCoordinate.ShiftBit3                 ; переход, если следующий разряд 3 равен 0, пропустить прибавление координаты

                ; накопление вклада разряда 3 с переносом в верхний аккумулятор
AddBit3:        ADD HL, DE
                ADC A, C
ShiftBit3:      ADD HL, HL
                ADC A, A
                JR NC, @D3D.MultiplyPreviewCoordinate.ShiftBit2                 ; переход, если следующий разряд 2 равен 0, пропустить прибавление координаты

                ; накопление вклада разряда 2 с переносом в верхний аккумулятор
AddBit2:        ADD HL, DE
                ADC A, C
ShiftBit2:      ADD HL, HL
                ADC A, A
                JR NC, @D3D.MultiplyPreviewCoordinate.ShiftBit1                 ; переход, если следующий разряд 1 равен 0, пропустить прибавление координаты

                ; накопление вклада разряда 1 с переносом в верхний аккумулятор
AddBit1:        ADD HL, DE
                ADC A, C
ShiftBit1:      ADD HL, HL
                ADC A, A
                JR NC, @D3D.MultiplyPreviewCoordinate.ShiftBit0                 ; переход, если следующий разряд 0 равен 0, пропустить прибавление координаты

                ; накопление вклада разряда 0 с переносом в верхний аккумулятор
AddBit0:        ADD HL, DE
                ADC A, C
ShiftBit0:      ADD HL, HL
                ADC A, A
                ; усечение модуля после семи разрядов, средний и старший байты становятся результатом деления на 128
                LD L, H
                LD H, A
                ; возврат знакового байта и его флагов, рабочий аккумулятор переходит в AF'
ApplySign:      EX AF, AF'
                JP P, @D3D.MultiplyPreviewCoordinate.Continue                   ; переход, если знак произведения неотрицателен, оставить вычисленный модуль

                ; расчёт отрицательного результата из уже усечённого модуля с исходным Carry=0
                EX DE, HL
                LD HL, #0000
                SBC HL, DE
                ; переход по адресу, записанному при входе, SP остаётся прежним
Continue:       JP #0000

                endmodule
                endmodule
