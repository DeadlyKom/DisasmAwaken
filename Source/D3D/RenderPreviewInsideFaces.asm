                module D3D
                module RenderPreviewInsideFaces
                ; Документация [формат 0FFFNNNN и 1GMMNNNN, условные полилинии и точная композиция выходных регистров](../../Docs/PreviewFaceStream.md)
                ; -----------------------------------------
                ; Обход граней и полилиний без отсечения с сохранённым кодом ориентации и тремя режимами рёбер
                ; исходная запись 6, банк 4, файловые смещения #1D4F..#1DFC
                ; In:
                ;   HL - поток заголовков и индексных байтов с завершающим нулём, значения индексов адресуют страницу C6
                ;   DE не задаёт геометрию, BC содержит сохраняемый C для первой полилинии, AF не является входом
                ;   HL', DE', BC', AF', IX, IY начальный контекст, точная композиция сохранений указана в документации
                ;   FPreviewProjectedVertex содержит слова координат, для рисунка используются младшие байты SecondAxis и FirstAxis
                ;   положительная грань имеет 3..15 точек и индекс заливки 0..4, полилиния 2..15 точек, контуры выпуклые и экранные
                ;   RejectCode задаёт разрешение условной полилинии до первой грани, нуль разрешает, любой ненуль запрещает
                ;   таблицы от начала bitmap подготовлены BuildSpriteLineTable, под CPU-SP доступны 14 байтов и шесть под FFE0
                ;   сам код не проверяет Outcode, ограничения координат должны обеспечить вызывающий проход и классификатор
                ; Out:
                ;   HL указывает на завершающий нуль без его пропуска, DE принадлежит последней ориентации, заливке или ребру
                ;   BC после принятой грани принадлежит заливке, после пропуска записи B=0, C=N+1, после полилинии B=0, C её входной
                ;   AF содержит A=0, F=54 от завершающего AND A
                ;   HL', DE', BC', AF', IX и IY вычисляются последовательной композицией договоров, точная модель render возвращает все
                ;   после полилинии HL', DE', BC' сохраняются, AF' принадлежит последнему ребру, IX и IY сохраняются
                ;   при пустом потоке DE, BC, альтернативные и индексные регистры сохранены
                ;   RejectCode изменяется только положительной гранью, нуль после отрицательного S, один после неотрицательного
                ;   SP после RET равен входному+2, I, IFF и IM сохранены, банк не переключается
                ;   в C800 остаётся последний скопированный контур, индекс и длина принадлежат последней принятой грани
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, экран, контур C8, параметры заливки и ребра, рабочие операнды и CPU-стек
                ; Note:
                ;   положительная запись использует первое либо разреженное тройное индексирование ориентации, исходные заёмы не исправлены
                ;   bit6 отрицательной записи проверяет предыдущую ориентацию целым байтом, не код сторон и не текущую видимость
                ;   MM=00 означает AND, 01 OR, 10 и 11 XOR, пара opcode и смещение масок задаются совместно
                ;   полилиния не замыкается автоматически, для замыкания последний индекс должен повторить первый
                ;   нулевой счётчик ненулевого заголовка не является пустой записью, повреждённые потоки не входят в договор
                ;   вход DBE9 с отсекателями является другим алгоритмом и ещё требует отдельного разбора
                ; -----------------------------------------
                ; -----------------------------------------
                ; Заголовок и положительная грань
                ; -----------------------------------------
                ; чтение заголовка без продвижения, нуль остаётся адресом возврата HL
Entry:          LD A, (HL)
                ; проверка полного нуля до разделения числовых полей заголовка
                AND A
                RET Z                                                           ; выход, если полный заголовок равен нулю, поток завершён

                JP M, @D3D.RenderPreviewInsideFaces.Polyline                    ; переход, если bit7 установлен, обработать полилинию

                ; извлечение числа индексных байтов положительной грани
                AND @PreviewFaceStreamConst.CountMask
                LD B, A
                ; расчёт ориентации исходным определителем с выбором тройки по числу точек
                CALL @D3D.ComputePreviewFaceOrientation.Entry
                JP P, @D3D.RenderPreviewInsideFaces.RejectFace                  ; переход, если S ориентации сброшен, сохранить код отказа и пропустить грань

                ; обновление кода принятой ориентации нулём до рисования
                XOR A
                LD (@PreviewFaceGateState.Value.RejectCode), A
                ; -----------------------------------------
                ; Копирование контура принятой грани
                ; -----------------------------------------
                ; повторное чтение заголовка и переход к первому индексному байту
CopyPolygon:    LD A, (HL)
                INC HL
                ; расчёт индекса заполнения из поля 6..4 четырьмя циклическими поворотами
                RRCA
                RRCA
                RRCA
                RRCA
                AND @PreviewFaceStreamConst.FillMask
                ; обновление физического индекса заполнения
                LD (@PreviewFillMode.Value.Index), A
                ; выбор начала страницы пар колонка и строка
                LD DE, @PreviewPolygonPrepConst.FirstPointRow - 1
                ; расчёт и сохранение байтовой длины контура 2*N
                LD A, B
                ADD A, A
                LD (@PreviewContourSize.Value.ByteCount), A
                ; выбор страницы записей FPreviewProjectedVertex
                LD B, @PreviewFaceMathConst.VertexPage
                ; возврат от байтовой длины к числу точек, чётное 2*N даёт Carry=0
                RRCA
                ; сохранение оставшегося числа точек в AF' перед чтением координат
CopyVertex:     EX AF, AF'
                ; чтение младшего адреса записи вершины без умножения индекса на пять
                LD C, (HL)
                INC HL
                ; чтение младшего байта SecondAxis как колонки
                LD A, (BC)
                ; запись колонки в следующую пару контура
                LD (DE), A
                ; продвижение внутри страницы C8 и выбор FirstAxis через два INC C
                INC E
                INC C
                INC C
                ; чтение младшего байта FirstAxis как строки
                LD A, (BC)
                ; запись строки после колонки
                LD (DE), A
                ; продвижение адреса следующей пары контура
                INC E
                ; возврат оставшегося счётчика из AF'
                EX AF, AF'
                ; расчёт оставшегося числа копируемых вершин
                DEC A
                JP NZ, @D3D.RenderPreviewInsideFaces.CopyVertex                 ; переход, если остались вершины, продолжить копирование координат

                ; рисование настоящей заливки, HL указателя потока она сохраняет
                CALL @D3D.FillPreviewPolygon.Entry
                JP @D3D.RenderPreviewInsideFaces.Entry

                ; обновление кода отказа по неотрицательному S, это не общий результат отсечения
RejectFace:     LD A, #01
                LD (@PreviewFaceGateState.Value.RejectCode), A
                ; -----------------------------------------
                ; Пропуск записи
                ; -----------------------------------------
                ; расчёт размера заголовка и N индексных байтов
SkipRecord:     INC B
                ; подготовка BC=N+1 без старшей части перед продвижением потока
                LD C, B
                LD B, #00
                ; продвижение к следующему заголовку записи
                ADD HL, BC
                JP @D3D.RenderPreviewInsideFaces.Entry

                ; -----------------------------------------
                ; Условная полилиния
                ; -----------------------------------------
                ; извлечение числа точек отрицательной записи
Polyline:       AND @PreviewFaceStreamConst.CountMask
                LD B, A
                ; проверка bit6 заголовка для условного пропуска по предыдущей ориентации
                BIT @PreviewFaceStreamConst.GateBit, (HL)
                JR Z, @D3D.RenderPreviewInsideFaces.LineMode                    ; переход, если bit6 сброшен, рисовать полилинию независимо от предыдущей грани

                ; чтение и проверка всего байта RejectCode, отдельные разряды не маскируются
                LD A, (@PreviewFaceGateState.Value.RejectCode)
                AND A
                JR NZ, @D3D.RenderPreviewInsideFaces.SkipRecord                 ; переход, если предыдущая ориентация отвергнута ненулевым кодом, пропустить полилинию

                ; расчёт числа сегментов N-1, автоматического замыкания нет
LineMode:       DEC B
                ; чтение заголовка и продвижение к первому индексу полилинии
                LD A, (HL)
                INC HL
                ; извлечение двухбитового поля операции MM
                AND @PreviewFaceStreamConst.LineModeMask
                JR Z, @D3D.RenderPreviewInsideFaces.SelectAnd                   ; переход, если поле MM нулевое, выбрать AND и инверсные маски

                ; проверка отдельного кода OR, оставшиеся 20 и 30 обозначают XOR
                CP @PreviewFaceStreamConst.OrMode
                JR Z, @D3D.RenderPreviewInsideFaces.SelectOr                    ; переход, если маскированный код режима равен #10, выбрать OR и прямые маски

                ; подготовка согласованной пары XOR C и JR C с прямыми масками
                LD DE, @PreviewFaceStreamConst.XorPair
                LD A, @PreviewFaceStreamConst.SetMaskLow
                JP @D3D.RenderPreviewInsideFaces.StoreLineMode

                ; подготовка пары AND C и JR NC с инверсными масками
SelectAnd:      LD DE, @PreviewFaceStreamConst.AndPair
                LD A, @PreviewFaceStreamConst.ClearMaskLow
                JP @D3D.RenderPreviewInsideFaces.StoreLineMode

                ; подготовка пары OR C и JR C с прямыми масками
SelectOr:       LD DE, @PreviewFaceStreamConst.OrPair
                LD A, @PreviewFaceStreamConst.SetMaskLow
                ; обновление физического экземпляра режима ребра
StoreLineMode:  LD (@PreviewEdgeMode.Value.PixelOpcode), DE
                ; обновление операнда выбора таблицы масок рисователя ребра
                LD (@PreviewEdgeRasterState.MaskOffset), A
                ; выбор страницы вершины, Outcode быстрым путём не читается
                LD D, @PreviewFaceMathConst.VertexPage
                ; чтение первого индекса полилинии
                LD E, (HL)
                INC HL
                ; чтение и сохранение колонки первого конца
                LD A, (DE)
                LD (@PreviewEdgeEndpoints.Value.EndPoint), A
                ; выбор младшего байта FirstAxis внутри той же страницы C6
                INC E
                INC E
                ; чтение и сохранение строки первого конца
                LD A, (DE)
                LD (@PreviewEdgeEndpoints.Value.EndPoint + 1), A
                ; -----------------------------------------
                ; Следующий сегмент полилинии
                ; -----------------------------------------
                ; выбор страницы и чтение следующего индексного байта
NextLinePoint:  LD D, @PreviewFaceMathConst.VertexPage
                LD E, (HL)
                INC HL
                ; сохранение счётчика оставшихся сегментов и C контекста
                PUSH BC
                ; сохранение указателя следующего элемента потока
                PUSH HL
                ; чтение предыдущего конечного слова и перенос его в начальный конец
                LD HL, (@PreviewEdgeEndpoints.Value.EndPoint)
                LD (@PreviewEdgeEndpoints.Value.StartPoint), HL
                ; чтение и сохранение колонки нового конечного слова
                LD A, (DE)
                LD (@PreviewEdgeEndpoints.Value.EndPoint), A
                ; выбор младшего FirstAxis для новой конечной строки
                INC E
                INC E
                ; чтение и сохранение новой конечной строки
                LD A, (DE)
                LD (@PreviewEdgeEndpoints.Value.EndPoint + 1), A
                ; вызов настоящего рисователя с исключённым конечным пикселем
                CALL @D3D.RasterizePreviewEdge.Entry
                ; восстановление потока и счётчика сегментов после рисования
                POP HL
                POP BC
                ; продолжение N-1 сегментов, отдельного замыкающего ребра нет
                DJNZ @D3D.RenderPreviewInsideFaces.NextLinePoint

                JP @D3D.RenderPreviewInsideFaces.Entry

                ; -----------------------------------------
                endmodule
                endmodule
