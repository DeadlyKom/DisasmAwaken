                module D3D
                module WrapPreviewTopLeft
                ; Документация [подготовка контура, верхние цепочки, полный локальный контракт и точные пределы проверки](../../Docs/PreviewPolygonFill.md)
                ; -----------------------------------------
                ; Переход верхнего обратного поиска к последней строке контура через AF'
                ; исходная запись 6, банк 4, файловые смещения #140F..#1415
                ; In:
                ;   HL - H=C8, L=0 после перехода обратного верхнего поиска через первую колонку
                ;   AF - A минимальная строка, AF' содержит A' последний нечётный индекс контура
                ; Out:
                ;   HL - H сохранён, L=(входной A'+1) AND FF
                ;   DE и BC сохранены, AF - A сохранён, F от INC L с сохранённым входным Carry
                ;   HL', DE', BC', AF', IX, IY, SP, I, IFF и IM сохранены, продолжение FillPreviewPolygon.ReadLeftTop
                ; Corrupt:
                ;   HL - только L, AF - только F
                ; Note:
                ;   следующий DEC L в подготовке выбирает последнюю строку кольца, CPU-возврат не создаётся
                ; -----------------------------------------
                ; выбор последнего индекса из A' с сохранением основного минимального Y
Entry:          EX AF, AF'
                LD L, A
                EX AF, AF'
                ; расчёт промежуточного индекса перед следующим DEC L в основном поиске
                INC L
                JP @D3D.FillPreviewPolygon.ReadLeftTop

                endmodule
                endmodule
