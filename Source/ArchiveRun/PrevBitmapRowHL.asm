                module ArchiveRun
                module PrevBitmapRowHL
                ; Документация [архивное меню](../../Docs/StartArchiveMenu.md)
                ; -----------------------------------------
                ; переход HL к предыдущей строке экрана в том же столбце
                ; In:
                ;   HL - адрес байта в раскладке ULA
                ; Out:
                ;   HL - адрес строки выше, проверка верхнего предела отсутствует
                ; Corrupt:
                ;   HL, AF
                ; Note:
                ;   штатный вызывающий путь пока не установлен
                ; -----------------------------------------
                ; проверка первой строки знакоместного ряда
Entry:          LD A, H
                AND #07
                JR Z, @ArchiveRun.PrevBitmapRowHL.PrevGroup                     ; переход, если достигнута первая строка ряда

                DEC H
                RET

                ; переход к последней строке предыдущего знакоместного ряда
PrevGroup:      LD A, H
                OR #07
                LD H, A
                LD A, L
                SUB #20
                LD L, A
                RET NC                                                          ; выход, если заём из старшего байта не потребовался

                ; переход в предыдущую треть после заёма
                LD A, H
                SUB #08
                LD H, A
                RET

                endmodule
                endmodule
