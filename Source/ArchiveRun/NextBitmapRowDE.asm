                module NextBitmapRowDE
                ; Документация [архивное меню](../../Docs/StartArchiveMenu.md)
                ; -----------------------------------------
                ; переход DE к следующей строке экрана в том же столбце
                ; In:
                ;   DE - адрес байта в раскладке ULA
                ; Out:
                ;   DE - адрес строки ниже, проверка нижнего предела отсутствует
                ; Corrupt:
                ;   DE, AF
                ; Note:
                ;   штатный вызывающий путь пока не установлен
                ; -----------------------------------------
                ; проверка границы восьми строк после продвижения старшего байта
Entry:          INC D
                LD A, D
                AND #07
                RET NZ                                                          ; выход, если следующая строка в той же группе

                ; переход к следующему знакоместному ряду
                LD A, E
                ADD A, #20
                LD E, A
                RET C                                                           ; выход, если перенос уже учтён в старшем байте

                ; компенсация старшего байта при отсутствии переноса в следующую треть
                LD A, D
                SUB #08
                LD D, A
                RET

                endmodule
                endmodule
