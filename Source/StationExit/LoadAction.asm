                module StationExit
                module LoadAction
; Документация [StationExit](../../Docs/FunctionDetails/StationExit.md)
; Подробный разбор [адресный контекст 4200 и границы TR-DOS](../../Docs/StationExit.md)
; -----------------------------------------
; Повторная инициализация музыки, запрос ACTION и передача сохранённого контекста
; исходная запись 4, файловые смещения #216C..#21B3
; In:
;   исходные 256 байтов 7EC0..7FBF уже скопированы в 4200..42FF, выполняется фиксированная копия
;   банк 3 содержит загруженный MUZ1 с модулем E700, действует Music.Initialize
;   512 байтов сохранённого контекста находятся в 4000..41FF, стек не пересекается с ними либо с копией кода
;   CurrentPage допускает переключение, TR-DOS доступен и принимает имя/тип по 5CDD
; Out:
;   банк 3 и ROM 1 выбраны перед полной инициализацией музыки, AY 13..0 обнулены
;   затем банк 0 выбран через SelectRamBank, прямой OUT 18 включает теневой экран
;   перед TR-DOS аппаратная страница 18, CurrentPage=10, нулевой байт записан только по 5000
;   перед CALL TrDos.Dispatch A=0, BC=000E, HL=4251, DE=5CE6, IY=5C3A, 5CF9=0
;   по 5CDD..5CE5 находятся девять байтов ACTION и типа C, на CPU-стеке возврат AfterLoad
;   если TR-DOS успешно вернулся в AfterLoad и сохранил копию кода и контекст, IFF сбрасывается
;   AfterLoad копирует 4000..41FF в 9BBD..9DBC загруженного ACTION, HL=4200, DE=9DBD, BC=0
;   затем SP=6000 и хвостовой вход ActionBoot.RelocateBootstrap.Entry, A сохраняет выход TR-DOS
;   F после копирования сохраняет S,Z,C от TR-DOS, сбрасывает H,N,P/V и задаёт X/Y по последнему LDIR
;   после TR-DOS IX, IY и альтернативные регистры сохраняют его выход, ошибочные пути определяет TR-DOS
; Corrupt:
;   HL, DE, BC, AF, SP, IFF, IY, дополнительные эффекты внешнего TR-DOS
; Note:
;   новый регион отражает доказанный адрес исполнения, это не новое размещение кода
;   LD DE,5001 и LD BC,02FF не сопровождаются LDIR, область 5001..52FF здесь не очищается
;   вызов DB00 именно повторно инициализирует проигрыватель, он не является кадровым тиком
;   AfterLoad не проверяет флаг ошибки, исполнение продолжения обусловлено фактическим возвратом TR-DOS
;   модель исполняет настоящий музыкальный и банковый код до TR-DOS, далее задаёт постусловие успешной загрузки
;   загрузка DOS, обработка дисковой ошибки и вход ACTION моделью не исполняются
; -----------------------------------------
                ; выбор банка 3 с уже загруженным проигрывателем MUZ1
Entry:          LD A, #13
                CALL @Station.SelectRamBank.Entry
                ; повторная полная инициализация музыки и обнуление AY, это не кадровый вход
                CALL @Music.Initialize.Entry
                ; возврат банка 0 перед обращением к диску
                LD A, #10
                CALL @Station.SelectRamBank.Entry
                ; выбор теневого экрана прямым OUT, программная тень останется равной 10
                LD A, #18
                LD BC, #7FFD
                OUT (C), A
                ; подготовка адресов и длины, исходник не выполняет по ним LDIR
                LD HL, #5000
                LD DE, #5001
                LD BC, #02FF
                ; запись только одного нулевого байта по 5000, остальная область не очищается
                LD (HL), L
                ; восстановление указателя системных переменных ROM для вызова TR-DOS
                LD IY, #5C3A
                ; копирование девяти байтов имени и типа ACTION из перенесённой записи
                LD HL, @ActionFileName.Entry
                LD DE, #5CDD
                LD BC, FTrDosFileKey
                LDIR
                ; выбор исходного режима A=0 для файлового запроса
                XOR A
                ; обнуление системного байта TR-DOS 5CF9 перед запросом
                LD (#5CF9), A
                ; выбор файловой функции 0E, адрес загрузки задаёт фактический договор TR-DOS
                LD C, #0E
                CALL @TrDos.Dispatch
                ; запрет прерываний после возврата DOS, явной проверки ошибки нет
AfterLoad:      DI
                ; копирование сохранённых 512 байтов контекста в состояние загруженного ACTION
                LD HL, #4000
                LD DE, #9BBD
                LD BC, #0200
                LDIR
                ; замена стека исходным значением для входа загрузчика ACTION
                LD SP, #6000
                JP @ActionBoot.RelocateBootstrap.Entry

                endmodule
                endmodule
