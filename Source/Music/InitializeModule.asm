                module Music
                module InitializeModule
; Документация [Music](../../Docs/FunctionDetails/Music.md)
; -----------------------------------------
; Чтение заголовка и относительных указателей PT3, сброс внутренних состояний и регистров AY
; исходная запись 10, файловые смещения #000A..#007B
; In:
;   HL - начало PT3-модуля, заголовок и таблицы указателей должны помещаться в доступной памяти
; Out:
;   состояния проигрывателя подготовлены, аппаратные регистры AY обнулены, SP восстановлен
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   временный SP читает заголовок со смещения 101, 48 указателей сэмплов и орнаментов переводятся в абсолютные
;   начальная задержка берётся из смещения 100, список позиций начинается со смещения 201
;   прерывания запрещаются в начале и не разрешаются на выходе
; -----------------------------------------
Entry:          DI
                ; сохранение исходного SP до чтения заголовка через POP
                LD (#DB4D), SP
                ; сохранение базы PT3-модуля для перевода относительных указателей
                LD (#DFAE), HL
                LD B, H
                LD C, L
                ; поиск поля задержки со смещением 100 от начала модуля
                LD DE, #0064
                ADD HL, DE
                LD A, (HL)
                INC HL
                LD (#DF62), A
                LD SP, HL
                ; расчёт начала списка позиций со смещением 201
                ADD HL, DE
                LD (#DF98), HL
                ; чтение количества позиций в F и номера петли в A, POP AF используется как чтение двух байтов
                POP AF
                ; расчёт указателя позиции петли по байту со смещением 102
                LD E, A
                ADD HL, DE
                LD (#DF9F), HL
                ; перевод указателя таблицы паттернов из относительного формата в абсолютный
                POP HL
                ADD HL, BC
                LD (#DFA7), HL
                LD HL, #DBA0
                ; преобразование 48 указателей сэмплов и орнаментов с добавлением базы модуля
PointDB30:      EX DE, HL
                POP HL
                ADD HL, BC
                EX DE, HL
                LD (HL), E
                INC L
                LD (HL), D
                INC L
                JR NZ, @Music.InitializeModule.PointDB30                        ; переход, если ещё не заполнены все 96 байтов таблицы #DBA0..#DBFF


                ; установка начальных счётчиков длительности трёх каналов в единицу
                INC L
                LD H, L
                LD (#DE1E), HL
                LD (#DC0E), HL
                XOR A
                LD (#E037), A
                LD (#E136), A
                LD (#E235), A
                ; восстановление настоящего SP после чтения заголовка и указателей
                LD SP, #0000
                ; назначение пустого сэмпла и орнамента каналам до чтения первого паттерна
                LD HL, #DC10
                LD (#E078), HL
                LD (#E178), HL
                LD (#E276), HL
                LD (#DE52), HL
                LD (#DEE0), HL
                LD (#E1F5), HL
                LD (#DF89), HL
                SUB #10
                LD (#DE5D), A
                LD (#DEEB), A
                LD (#E22B), A
                SBC A, A
                LD (#DFEF), A
                LD (#E1EE), A
                LD (#E0EE), A
                ; JP @Music.ClearAyRegisters.Entry, продолжение в ClearAyRegisters.asm

                endmodule
                endmodule
