                module Music
                module SetOrnamentPositionC
                ; Документация [музыкальные эффекты](../../Docs/MusicEffects.md)
                ; -----------------------------------------
                ; Чтение позиции орнамента канала C
                ; исходная запись 10, файловые смещения #0BF4..#0BF9
                ; In:
                ;   DE указывает на байт позиции, входной F сохраняется
                ; Out:
                ;   HL сохранён, DE=входной DE+1, BC сохранён
                ;   AF содержит входной байт позиции в A и входной F
                ;   HL', DE', BC', AF' сохранены
                ;   текущий курсор обновлён немедленно
                ;   R получает 4 M1, внешний CALL не включён
                ; Corrupt:
                ;   DE, AF только A, позиция текущая, R
                ; Note:
                ;   байт позиции копируется без проверки длины сэмпла либо орнамента
                ;   индексные регистры, I, IM и IFF сохранены, SP увеличен на два обычным RET
                ; -----------------------------------------
                ; Чтение позиции орнамента канала C
Entry:          LD A, (DE)
                INC DE
                LD (@MusicEffectState.OrnamentCursorC), A
                RET

                endmodule
                endmodule
