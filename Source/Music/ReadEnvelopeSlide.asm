                module Music
                module ReadEnvelopeSlide
                ; Документация [команда скольжения огибающей](../../Docs/MusicEnvelopeStaging.md)
                ; -----------------------------------------
                ; Чтение задержки и знакового слова шага, включение отложенного скольжения огибающей
                ; исходная запись 10, файловые смещения #008C..#009F
                ; In:
                ;   DE указывает на три доступных байта потока, задержка и младший, старший байты шага
                ;   HL, BC и AF не задают дополнительных аргументов, банк MUZ1 доступен для записи
                ; Out:
                ;   HL=слово шага, DE=входной DE+3, BC сохранён, A=06, F сохранён
                ;   альтернативные пары, IX, IY, I, IM и IFF сохранены, SP увеличен на два обычным RET
                ;   Delay получает первый байт, Step получает два следующих, SlideGate=06 включает отложенную команду
                ; Corrupt:
                ;   HL, DE, AF только A, Delay, Step, SlideGate, R и обычный адрес возврата со стека
                ; Note:
                ;   указатель DB8C физически записан в таблицах каналов A, B и C по DDCE, DDEE, DE0E
                ;   задержка и шаг копируются без нормализации, нулевые и отрицательные значения сохраняются
                ;   сам обработчик не меняет текущий SlideOffset, он применяет команду позже в StageEnvelopeAndNoise
                ; -----------------------------------------
                ; чтение байта задержки отложенного скольжения огибающей
Entry:          LD A, (DE)
                INC DE
                ; сохранение задержки в изменяемом операнде Delay
                LD (@MusicEnvelopeState.Delay), A
                ; чтение младшего и старшего байтов шага с продвижением полного указателя потока
                EX DE, HL
                LD E, (HL)
                INC HL
                LD D, (HL)
                INC HL
                EX DE, HL
                ; сохранение слова шага в операнде PendingStep
                LD (@MusicEnvelopeState.Step), HL
                ; включение однократной команды, JR по SlideGate становится LD B,n той же длины
                LD A, #06
                LD (@MusicEnvelopeState.SlideGate), A
                RET

                endmodule
                endmodule
