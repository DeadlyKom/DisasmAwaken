                module Music
                module SetGateTimingC
                ; Документация [длительности C и регистр R](../../Docs/MusicEffects.md#длительности-c-и-регистр-r)
                ; -----------------------------------------
                ; Установка текущего счётчика и двух длительностей канала C
                ; исходная запись 10, файловые смещения #0312..#031D
                ; In:
                ;   DE указывает на второй байт длительности, A содержит первую длительность, входной F сохраняется
                ;   байт потока и два байта внешнего возврата не перекрывают изменяемые байты E2E7, E2D5 и E2E3
                ;   исходные команды сохранены, IRQ и NMI не вмешиваются
                ; Out:
                ;   HL сохранён, DE=входной DE+1, BC сохранён, AF содержит вторую длительность в A и входной F
                ;   HL', DE', BC', AF', IX, IY, I, IM и IFF сохранены, SP=входной SP+2
                ;   E2E7 и GateCounterC по E2D5 получают входную A, E2E3 получает байт потока
                ;   R сохраняет бит 7, младшие семь бит увеличены на 6 M1 по модулю 128, внешний CALL не включён
                ; Corrupt:
                ;   DE, AF только A, SP, R, изменяемые байты E2E7, E2D5 и E2E3
                ; Note:
                ;   счётчик далее переключает байт разрешения канала E1EE между нулём и FF
                ;   нулевые длительности сохраняются без нормализации, достаточные условия неперекрытия не доказывают все варианты наложений
                ; -----------------------------------------
                ; Обновление текущего счётчика и значений перезагрузки
Entry:          LD (#E2E7), A
                LD (@MusicState.GateCounterC), A
                LD A, (DE)
                INC DE
                LD (#E2E3), A
                RET


                endmodule
                endmodule
