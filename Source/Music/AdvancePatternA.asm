                module Music
                module AdvancePatternA
                ; Документация [отложенные состояния каналов](../../Docs/MusicPattern.md)
                ; -----------------------------------------
                ; Счётчик строки A, переход позиции, чтение трёх указателей через SP и подготовка маркеров строки A
                ; исходная запись 10, файловые смещения #047F..#04E2
                ; In:
                ;   HL входного указателя не задаёт, DE несёт подготовительные маркеры, E=18 либо 06 задаёт начальные B и H подготовительного комплекта
                ;   BC задаёт сохраняемый C подготовительного комплекта, HL', DE' и BC' становятся рабочими после EXX
                ;   AF задаёт только Carry на пути без декодера, RowCounterA и RowDelayA являются байтами без нормализации
                ;   PatternA указывает следующую команду, нулевой байт вне декодера означает переход позиции
                ;   PositionCursor и LoopPosition указывают список позиций, PatternTable и ModuleBase подготовлены инициализатором
                ;   после выбора позиции читаются три доступных слова, полученный поток конечен и использует эффекты 1..5, 8, 9
                ;   SP указывает стек вызывающего кадрового пути, код MUZ1 доступен для записи, прерывания запрещены
                ; Out:
                ;   граница договора находится перед RenderChannelA по DFE3, собственного RET нет, исходный SP восстановлен
                ;   RowCounterA уменьшается, нулевой счётчик становится FF, при ненулевом результате декодер не вызывается
                ;   при истечении и ненулевой следующей команде выполнен DecodePatternA, сохранён новый PatternA и перезагружен RowCounterA
                ;   если следующая команда нулевая, базовый шум сброшен, SavedStack получает SP, FF в списке заменяет PositionCursor адресом LoopPosition для чтения
                ;   новый PositionCursor равен адресу выбранного байта плюс один, перенос указателей по шестнадцатибитной границе сохраняется
                ;   адрес чтения равен (PatternTable+2*байт_позиции)&FFFF, из него три POP читают относительные A, B и C
                ;   к каждому слову прибавлен ModuleBase по модулю 65536, PatternB и PatternC сохранены, A передан декодеру
                ;   ResetOpcodeA=22 только если рабочий B перед DJNZ равен 1, иначе 01, рабочий B уменьшается и на пути без декодера
                ;   после EXX OrnamentBlockA, NoteBlockA и SlideBlockA получают B, H и E подготовительного комплекта, A в конце равен этому E
                ;   F сохраняется от DEC RowCounterA на пути без декодера, иначе равен F результата декодера и его эффектов
                ;   альтернативные HL', DE' и BC' содержат рабочий результат с уменьшенным B, AF', IX, IY, I, IM и IFF сохраняются
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC' согласно выбранной ветви
                ;   счётчики, указатели потоков и позиции, код сброса, подготовительные маркеры, параметры декодера, SavedStack, память CALL и эффектов, R
                ; Note:
                ;   байт позиции является исходным смещением в единицах двух байтов, умножение на шесть здесь отсутствует
                ;   SP временно указывает таблицу, запрет IRQ существенен, POP читает данные, а не снимает возвраты обычного стека
                ;   CALL DecodePatternA записывает на обычный восстановленный стек возврат DFC4
                ;   при нулевом байте по LoopPosition он также читается как позиция, повторной проверки FF выбранной петли нет
                ;   точные комплекты и ветви описаны в MusicPattern.md, последующий синтез не входит в локальный договор
                ; -----------------------------------------
                ; чтение текущей длительности строки A
Entry:          LD HL, @MusicPatternState.RowCounterA
                ; расчёт оставшейся длительности с байтовым оборачиванием
                DEC (HL)
                ; подготовка отключённых маркеров H и B из E перед переключением комплекта
                LD H, E
                LD B, E
                EXX
                JR NZ, @Music.AdvancePatternA.SelectReset                       ; переход, если уменьшенная длительность A ненулевая, пропустить декодер и сохранить рабочий поток

                ; проверка следующей команды A, ноль вне декодера завершает текущую позицию
                LD DE, #DC10
                LD A, (DE)
                OR A
                JR NZ, @Music.AdvancePatternA.DecodeRow                         ; переход, если следующая команда A ненулевая, декодировать прежний поток без смены позиции

                ; сброс базового шума при переходе позиции и сохранение обычного стека
                LD (@MusicEnvelopeState.Noise), A
                LD D, A
                LD (@MusicAdvanceAState.SavedStack), SP
                ; проверка следующего байта списка позиций на маркер FF
                LD HL, #E7C9
                LD A, (HL)
                INC A
                JR NZ, @Music.AdvancePatternA.ReadPosition                      ; переход, если байт позиции не равен FF, использовать текущий курсор списка

                ; выбор адреса петли вместо достигнутого маркера FF
                LD HL, #E7C9
                ; чтение байта выбранной позиции и сохранение адреса следующей позиции
ReadPosition:   LD E, (HL)
                INC HL
                LD (@MusicAdvanceAState.PositionCursor), HL
                ; расчёт адреса трёх относительных указателей, к базе прибавляется дважды байт позиции
                LD HL, #0000
                ADD HL, DE
                ADD HL, DE
                ; временное переключение SP на таблицу указателей, аппаратные IRQ должны быть запрещены
                LD SP, HL
                ; чтение относительного указателя A и прибавление базы модуля
                POP HL
                LD BC, #0000
                ADD HL, BC
                EX DE, HL
                ; чтение относительного указателя B, прибавление базы и сохранение абсолютного потока
                POP HL
                ADD HL, BC
                LD (@MusicPatternState.PatternB), HL
                ; чтение относительного указателя C, прибавление базы и сохранение абсолютного потока
                POP HL
                ADD HL, BC
                LD (@MusicPatternState.PatternC), HL
                ; восстановление обычного SP перед CALL декодера и его отложенными эффектами
                LD SP, #0000
                ; выбор страницы DB таблиц перед декодированием новой строки A
DecodeRow:      LD H, #DB
                CALL @Music.DecodePatternA.Entry
                ; сохранение следующей команды после терминатора и всех параметров эффектов
                LD (@MusicAdvanceAState.PatternA), DE
                ; перезагрузка длительности строки A из изменяемого операнда
                LD A, #00
                LD (@MusicPatternState.RowCounterA), A
                ; выбор кода сохранения скольжения, рабочий B=1 заменяет его кодом сброса 22
SelectReset:    LD A, #01
                DJNZ @Music.AdvancePatternA.StoreReset

                LD A, #22
                ; перенос кода сброса и возврат к подготовительному комплекту через EXX
StoreReset:     LD (@MusicChannelARow.ResetOpcode), A
                EXX
                ; перенос маркеров орнамента, ноты и скольжения в изменяемые блоки строки A
                LD A, B
                LD (@MusicChannelARow.OrnamentBlock), A
                LD A, H
                LD (@MusicChannelARow.NoteBlock), A
                LD A, E
                LD (@MusicChannelARow.SlideBlock), A
                ; JP @Music.RenderChannelA.Entry, продолжение в RenderChannelA.asm

                endmodule
                endmodule
