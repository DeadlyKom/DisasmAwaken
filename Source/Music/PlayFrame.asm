                ; Кадровый вход проигрывателя, переход к изменяемому диспетчеру #DE1F
                ; исходная запись 10, файловые смещения #0005..#0007
                ; In:
                ;   Initialize выполнен, выбран банк музыкального модуля, прерывания во время тика запрещены
                ; Out:
                ;   обновлён синтез и аппаратные регистры AY, очередная стадия разбора паттернов определяется состоянием проигрывателя
                ;   IY сохраняется, настоящий SP восстановлен до завершения тика, обычный RET снимает внешний адрес возврата
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, R
                ;   MusicAyState.Registers и параметры синтеза каналов, изменяемые операнды и указатели разбора паттернов
                ;   MusicAyState.SavedSP, временные слова CPU-стека и аппаратные регистры AY через FFFD, BFFD и зеркало BEFD
                ; Note:
                ;   IY кодом проигрывателя не используется, сохранение регистров выполняет станционный Interrupt
                ;   вход сам DI не выполняет, SP используется как указатель данных и восстанавливается перед выводом AY
                ;   изменяемая команда #DE1F задаёт обход либо выполнение предварительного разбора паттерна
                ;   Station.Interrupt выбирает банк 3 и вызывает этот вход из #9B7A
                ; -----------------------------------------
