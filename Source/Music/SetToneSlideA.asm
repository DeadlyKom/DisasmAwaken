                module Music
                module SetToneSlideA
                ; Документация [музыкальные эффекты](../../Docs/MusicEffects.md)
                ; -----------------------------------------
                ; Чтение задержки и шага неограниченного скольжения тона A
                ; исходная запись 10, файловые смещения #0B0C..#0B22
                ; In:
                ;   DE указывает на задержку и младший, старший байты шага, F сохраняется
                ;   D' задаёт код включения отложенного блока, штатное значение 06
                ; Out:
                ;   HL=слово шага, DE=входной DE+3, BC сохранён, A=1D, F сохранён
                ;   E' получает D', остальные альтернативные байты сохранены
                ;   ожидающие задержка и шаг обновлены, смещение JR получает 1D для обхода ограничения целевой нотой
                ; Corrupt:
                ;   HL, DE, AF только A, DE' только E', ожидающие задержка, шаг и смещение JR, R
                ; Note:
                ;   параметры применяются последующим блоком подготовки строки, текущий синтез этой командой не выполняется
                ;   индексные регистры, I, IM и IFF сохранены, SP увеличен на два обычным RET
                ; -----------------------------------------
                ; Чтение задержки и шага неограниченного скольжения тона A
Entry:          LD A, (DE)
                INC DE
                LD (@MusicEffectState.PendingDelayA), A
                ; чтение младшего и старшего байтов шага с продвижением полного указателя потока
                EX DE, HL
                LD E, (HL)
                INC HL
                LD D, (HL)
                INC HL
                EX DE, HL
                LD (@MusicEffectState.PendingStepA), HL
                ; выбор ветви без ограничения целевой нотой для последующего применения шага
                LD A, @MusicCommandConst.SkipToneLimit
                LD (@MusicEffectState.PendingBranchA), A
                ; включение отложенного блока скольжения через E' по коду из D'
                EXX
                LD E, D
                EXX
                RET

                endmodule
                endmodule
