; -----------------------------------------
; Остановка звука обнулением регистров AY с номерами 13..0
; исходная запись 10, файловые смещения #0008..#0009
; In:
;   выбран банк 3, содержащий MUZ1.C
; Out:
;   DE - 0, BC - #BFFD, AY-регистры 13..0 содержат ноль
; Corrupt:
;   DE, BC, AF
; Note:
;   вход ведёт прямо к ClearAyRegisters, HL, A, индексные и альтернативные регистры сохраняются
;   A сохраняется, F меняется при DEC D, состояние IFF не меняется
;   обнуление портов не запрещает следующий PlayFrame, остановкой кадров управляет вызывающий код
;   Station.StopMusic вызывает #DB08 до восстановления IM 1, это глушение AY, не кадровый синтез
; -----------------------------------------
Entry:          JR @Music.ClearAyRegisters.Entry


