                module Music
                module Stop
                ; Документация [инициализация и глушение AY](../../Docs/MusicInitialization.md)
                ; -----------------------------------------
                ; Глушение аппаратных регистров AY без изменения RAM и запрета последующих кадров
                ; исходная запись 10, файловые смещения #0008..#0009
                ; In:
                ;   HL сохраняется, DE и BC аргументов не задают, AF задаёт сохраняемые A и входной Carry
                ;   выбран банк MUZ1, на CPU-стеке внешний возврат, портовая трасса рассматривается без вмешательства ISR
                ; Out:
                ;   HL сохранён, DE=0000, BC=BFFD, A сохранён, F=42 OR входной Carry
                ;   аппаратные регистры AY 13..0 получают ноль, каждому предшествует выбор номера через FFFD, данные идут через BFFD
                ;   ни один байт RAM не записывается, в том числе буфер AY, разрешения каналов и данные стека сохраняются
                ;   HL', DE', BC', AF', IX, IY, I, IM и IFF сохраняются, SP после RET равен входному SP+2
                ; Corrupt:
                ;   DE, BC, AF только по F, аппаратные AY, R
                ; Note:
                ;   это глушение портов, следующий PlayFrame может снова вывести звук из сохранённого состояния
                ;   DI здесь нет, остановкой кадров и режимом прерываний управляет вызывающий код
                ;   F создаётся последним DEC D от 1 к 0, Carry сохраняется от входа
                ;   вход Stop содержит только JR к ClearAyRegisters, отдельного вызова или рамки стека нет
                ; -----------------------------------------
Entry:          JR @Music.ClearAyRegisters.Entry

                endmodule
                endmodule
