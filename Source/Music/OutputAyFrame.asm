                module Music
                module OutputAyFrame
                ; Документация [огибающая и вывод AY](../../Docs/MusicAyOutput.md)
                ; -----------------------------------------
                ; Расчёт общей огибающей, восстановление стека и вывод регистров AY
                ; исходная запись 10, файловые смещения #07EB..#087B
                ; In:
                ;   HL, DE и BC будут перенесены в альтернативные пары начальным EXX
                ;   L' содержит восьмибитовый суммарный вклад каналов в огибающую, остальные альтернативные байты отдельно не используются
                ;   IXH содержит вклад шума, IXL содержит готовый микшер, буфер AY0..13 и параметры огибающей подготовлены
                ;   SavedSP содержит настоящий доступный стек, банк MUZ1 доступен для записи, прерывания запрещены до восстановления SP
                ; Out:
                ;   HL=DC0D, DE=FFBF, BC=BFFD при ненулевой входной форме, иначе BEFD, A=входная форма
                ;   F соответствует OR входной формы, Sign, Zero, XY и Parity по байту формы, Carry, HalfCarry и N равны нулю
                ;   HL', DE', BC' равны входным основным парам, AF' сохранён, IX и IY сохранены, I, IM и IFF сохранены
                ;   SP восстановлен из SavedSP, буфер AY11..12 содержит текущий период огибающей
                ;   период равен SlideOffset плюс Base со сложением L' только к младшему байту Base, перенос этого сложения отброшен
                ;   при счётчике огибающей 1 к SlideOffset добавлен SlideStep для следующего кадра, счётчик получает SlideReload
                ;   при счётчике 2..128 он уменьшен, при 0 и 129..255 сохранён
                ;   выведены регистры AY0..12, AY6 получает сумму шума и IXH по модулю 256, AY7 получает IXL
                ;   ненулевая форма дополнительно выведена в AY13 и очищена в буфере, нулевая не выводится
                ;   IXH сохранён в NoiseSeed, собственного RET нет, продолжение UnknownE37C
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', SP, буфер периода и формы, SlideOffset и SlideCounter по условию, NoiseSeed, порты AY, R
                ; Note:
                ;   записи OUTI идут через зеркало BEFD, отдельные записи шума, микшера и формы через BFFD, выбор регистра через FFFD
                ;   вывод сравнивает сырые байты портов, аппаратная маска разрядности регистров и слышимое аудио не моделируются
                ;   счётчик и смещение обновляются после записи текущего периода, шаг скольжения влияет на следующий кадр
                ;   последующий разбор паттернов, IRQ и нативный звук не входят в эту проверку
                ; -----------------------------------------
                ; переход к альтернативным рабочим парам с суммарным восьмибитовым вкладом огибающей в L
Entry:          EXX
                ; чтение суммарного вклада каналов перед загрузкой текущего смещения и базового периода
                LD A, L
                LD DE, #0000
                LD HL, #0000
                ; расчёт младшего байта базового периода с вкладом каналов, перенос в старший байт не учитывается
                ADD A, L
                LD L, A
                ; добавление текущего шестнадцатибитового смещения огибающей
                ADD HL, DE
                ; запись периода текущего кадра до обновления шага скольжения
                LD (@MusicAyState.EnvelopePeriod), HL
                ; чтение счётчика до очередного шага скольжения огибающей
                LD A, #00
                ; расчёт уменьшенного байтового счётчика огибающей
                DEC A
                JP M, @Music.OutputAyFrame.FlushAy                              ; переход, если результат DEC отрицателен, сохранить счётчик и смещение огибающей

                JR NZ, @Music.OutputAyFrame.StoreEnvDelay                       ; переход, если уменьшенный счётчик ненулевой, сохранить его без применения шага

                ; чтение шага и прибавление к прежнему смещению для следующего кадра
                LD HL, #0000
                ADD HL, DE
                ; сохранение нового смещения, текущий период уже записан в буфер AY
                LD (@MusicEnvelopeState.SlideOffset), HL
                ; чтение задержки перезагрузки после применения шага
                LD A, #00
                ; сохранение уменьшенного либо перезагруженного счётчика огибающей
StoreEnvDelay:  LD (@MusicEnvelopeState.SlideCounter), A
                ; восстановление настоящего стека после использования SP для данных синтеза
FlushAy:        LD SP, #0000
                ; подготовка старших байтов портов выбора и данных AY
                LD DE, #FFBF
                ; выбор порта FFFD и начала четырнадцатибайтового буфера AY
                LD BC, #FFFD
                LD HL, @MusicAyState.Registers
                ; последовательный вывод тональных регистров AY0..5, OUTI использует зеркало BEFD
                OUT (C), L
                LD B, E
                OUTI
                LD B, D
                OUT (C), L
                LD B, E
                OUTI
                LD B, D
                OUT (C), L
                LD B, E
                OUTI
                LD B, D
                OUT (C), L
                LD B, E
                OUTI
                LD B, D
                OUT (C), L
                LD B, E
                OUTI
                LD B, D
                OUT (C), L
                LD B, E
                OUTI
                LD B, D
                OUT (C), L
                ; чтение вклада шума из IXH перед прибавлением базового шума
                LD A, IXH
                ; сохранение вклада шума для исходного операнда следующего кадра
                LD (@MusicAyState.NoiseSeed), A
                ; расчёт шума как байтовой суммы вклада сэмплов и базового значения
                ADD A, (HL)
                LD B, E
                OUT (C), A
                INC L
                LD B, D
                OUT (C), L
                ; вывод готового микшера IXL в AY7
                LD A, IXL
                LD B, E
                OUT (C), A
                INC L
                LD B, D
                OUT (C), L
                LD B, E
                OUTI
                LD B, D
                OUT (C), L
                LD B, E
                OUTI
                LD B, D
                OUT (C), L
                LD B, E
                OUTI
                LD B, D
                OUT (C), L
                LD B, E
                OUTI
                LD B, D
                OUT (C), L
                LD B, E
                OUTI
                ; чтение однократного запроса формы огибающей из буфера AY13
                LD A, (HL)
                ; проверка наличия новой формы огибающей
                OR A
                JR Z, @Music.AdvancePatternBC.Entry                             ; переход, если форма равна нулю, пропустить аппаратную запись AY13

                ; вывод ненулевой формы и очистка её однократного буфера
                LD B, D
                OUT (C), L
                LD B, E
                OUT (C), A
                LD (HL), #00
                ; JP @Music.AdvancePatternBC.Entry, продолжение в UnknownE37C.asm

                endmodule
                endmodule
