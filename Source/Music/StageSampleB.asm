                module Music
                module StageSampleB
                ; Документация [отложенные состояния каналов](../../Docs/MusicChannelStaging.md)
                ; -----------------------------------------
                ; Применение отложенной позиции сэмпла канала B
                ; исходная запись 10, файловые смещения #0431..#043B
                ; In:
                ;   HL, DE и C сохраняются, E=18 требуется для восстановления JR после отложенной команды
                ;   B и AF сохраняются при выключенной команде, переключатель содержит 18 либо 06
                ;   параметр команды подготовлен в доступном для записи банке MUZ1, прерывания запрещены согласно кадровому входу
                ; Out:
                ;   граница блока находится в StageOrnamentB по DF3C, собственного RET нет
                ;   при SampleCommand=06 SamplePosition записан в SampleCursor, SampleCommand получает E, A=E, B=09
                ;   HL, DE, C и F сохранены, альтернативные пары, IX, IY, SP, I, IM и IFF сохранены до следующего блока
                ;   при выключенной команде A и B сохранены, штатный E=18 выключает применённую команду восстановлением JR
                ; Corrupt:
                ;   BC только B, AF только A, SampleCommand, SampleCursor, R
                ; Note:
                ;   позиция сэмпла копируется без проверки его заголовка, последующий синтез не входит в локальный договор
                ; -----------------------------------------
                ; изменяемый JR пропускает команду позиции сэмпла B, код 06 открывает её тело
Entry:          JR @Music.StageOrnamentB.Entry

                ; перенос ожидающей позиции сэмпла в курсор синтеза канала B
                LD A, #00
                LD (@MusicChannelBState.SampleCursor), A
                ; выключение однократной команды позиции сэмпла кодом JR из E
                LD A, E
                LD (@MusicChannelBState.SampleCommand), A
                ; JP @Music.StageOrnamentB.Entry, продолжение в StageOrnamentB.asm

                endmodule
                endmodule
