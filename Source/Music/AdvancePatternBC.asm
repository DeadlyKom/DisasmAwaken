                module Music
                module AdvancePatternBC
                ; Документация [декодирование паттернов](../../Docs/MusicPattern.md)
                ; -----------------------------------------
                ; Распределение фаз разбора B и C, счётчиков строк и кодов подготовки следующего кадра
                ; исходная запись 10, файловые смещения #087C..#08DB
                ; In:
                ;   HL, DE и BC вместе с HL', DE' и BC' несут завершённый контекст синтеза, B′ существенен даже при пропуске разбора B
                ;   AF задаёт только сохраняемый Carry для ветвей без декодирования, Phase и счётчики являются байтами без нормализации
                ;   PatternB и PatternC указывают конечные строки, RowDelayB/C задают перезагрузки, поддерживаемые эффекты имеют коды 1..5, 8, 9
                ;   на стеке внешний возврат, банк MUZ1 доступен для записи, прерывания запрещены
                ; Out:
                ;   Phase всегда уменьшается на один и сохраняется, только прежнее 2 выбирает B, прежнее 1 выбирает C
                ;   при иной фазе HL, DE, BC и альтернативные пары сохранены, A=(Phase−2)&FF, F соответствует второму DEC с входным Carry
                ;   фаза C задаёт EntryOpcode=01, уменьшает RowCounterC, при ненулевом результате возвращается с HL=DC0F и A=1
                ;   при истечении C выполнен DecodePatternC, сохранён новый PatternC и перезагружен RowCounterC, B уменьшается
                ;   если декодер C вернул B=1, после DEC B=0 также HL=0 и SlideOffsetC=0, иначе его накопитель сохраняется
                ;   фаза B уменьшает RowCounterB и переключает пары через EXX, при истечении выполняет DecodePatternB и сохраняет PatternB и RowDelayB
                ;   ResetOpcodeB получает 22 только если рабочий B перед DJNZ равен 1, иначе 01, DJNZ уменьшает этот B и без вызова декодера
                ;   после обратного EXX OrnamentBlockB, NoteBlockB и SlideBlockB получают соответственно B, H и E подготовительного комплекта
                ;   AF', IX, IY, I, IM и IFF сохраняются, SP после внешнего RET равен входному SP+2
                ;   точные пары и F для всех ветвей заданы формулами и таблицами MusicPattern.md
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC' согласно выбранной фазе
                ;   Phase, счётчики, указатели потоков, коды подготовки B и входа A, параметры декодеров, память стека, R
                ; Note:
                ;   RET происходит до PatternCommandsA, физическое соседство не задаёт последовательного продолжения
                ;   нулевые счётчики переходят в FF, фаза 0 переходит в FF, эти случаи не исправляются
                ;   модель включает настоящие CALL декодеров и точные рамки возврата, аппаратные IRQ и нативный звук не проверены
                ; -----------------------------------------
                ; чтение числовой фазы распределённого разбора B и C
Entry:          LD A, #03
                ; расчёт следующей фазы с байтовым оборачиванием
                DEC A
                LD (@MusicEnvelopeState.Phase), A
                JR Z, @Music.AdvancePatternBC.AdvanceC                          ; переход, если прежняя фаза равна 1, обработать счётчик C

                ; проверка прежней фазы 2 вторым уменьшением рабочего A
                DEC A
                RET NZ                                                          ; выход, если прежняя фаза не равна ни 1, ни 2, пропустить разбор каналов

                LD HL, @MusicPatternState.RowCounterB
                ; расчёт оставшейся длительности строки B
                DEC (HL)
                ; подготовка отключённых маркеров B/H/E=18 для последующего EXX
                LD DE, #0618
                LD H, E
                LD B, E
                EXX
                JR NZ, @Music.AdvancePatternBC.SelectReset                      ; переход, если уменьшенный счётчик B ненулевой, пропустить декодер и сохранить рабочий комплект

                ; чтение строки B и сохранение её следующего указателя
                LD DE, #0000
                LD H, #DB
                CALL @Music.DecodePatternB.Entry
                LD (@MusicPatternState.PatternB), DE
                ; перезагрузка длительности строки B после декодирования
                LD A, #00
                LD (@MusicPatternState.RowCounterB), A
                ; выбор команды сохранения скольжения B, рабочий B=1 заменяет её кодом сброса 22
SelectReset:    LD A, #01
                DJNZ @Music.AdvancePatternBC.StoreReset

                LD A, #22
                ; перенос кода сброса и возврат к подготовленному комплекту через EXX
StoreReset:     LD (@MusicChannelBRow.ResetOpcode), A
                EXX
                ; перенос маркеров орнамента, ноты и скольжения B в изменяемые команды подготовки
                LD A, B
                LD (@MusicChannelBRow.OrnamentBlock), A
                LD A, H
                LD (@MusicChannelBRow.NoteBlock), A
                LD A, E
                LD (@MusicChannelBRow.SlideBlock), A
                RET

                ; подготовка кода 01 для применения строки A в следующем тике
AdvanceC:       INC A
                LD (@MusicChannelARow.EntryOpcode), A
                ; уменьшение текущего счётчика строки паттерна C
                LD HL, @MusicPatternState.RowCounterC
                ; расчёт оставшейся длительности строки C
                DEC (HL)
                RET NZ                                                          ; выход, если уменьшенный счётчик C ненулевой, сохранить прежние параметры канала

                ; чтение строки C и сохранение её следующего указателя
                LD DE, #0000
                LD H, #DB
                CALL @Music.DecodePatternC.Entry
                LD (@MusicPatternState.PatternC), DE
                ; перезагрузка длительности строки C после декодирования
                LD A, #00
                LD (@MusicPatternState.RowCounterC), A
                ; проверка признака новой ноты C уменьшением возвращённого B
                DEC B
                RET NZ                                                          ; выход, если декодер вернул B, отличный от 1, сохранить накопленное скольжение C

                ; сброс накопленного скольжения C только при признаке новой ноты B=1
                LD H, B
                LD L, B
                LD (@MusicSynthesisC.SlideOffset), HL
                RET

                endmodule
                endmodule
