                module Music
                module FinishChannelA
                ; Документация [синтез трёх каналов](../../Docs/MusicSynthesis.md)
                ; -----------------------------------------
                ; Завершение счётчика скольжения A, восстановление амплитуды и обновление чередования
                ; исходная запись 10, файловые смещения #05CD..#05EC
                ; In:
                ;   HL, DE и BC сохраняются, AF' содержит амплитуду и её флаги, AF содержит рабочий контекст скольжения
                ;   Entry читает перезагрузку, StoreSlideDelay принимает текущую A, RestoreLevel пропускает запись счётчика
                ;   банк MUZ1 доступен для записи, SP может указывать на данные, прерывания запрещены
                ; Out:
                ;   Entry пишет перезагрузку в счётчик по E09F, StoreSlideDelay пишет входную A, RestoreLevel не меняет его
                ;   AF восстановлен обменом с альтернативным AF, рабочая пара сохраняется в AF'
                ;   амплитуда записана в буфер AY, счётчик и состояние чередования обновлены по MusicGateTicks
                ;   HL сохранён, кроме истечения счётчика, тогда HL=DFEF, DE и BC сохранены
                ;   HL', DE', BC', IX, IY, SP, I, IM и IFF сохранены, собственного RET нет, продолжение следующего канала
                ; Corrupt:
                ;   HL по условию, AF, AF', счётчик скольжения по выбранному входу, буфер амплитуды, счётчик и состояние чередования, R
                ; Note:
                ;   различие трёх входов и все байты состояния проверены отдельной моделью, SP здесь не восстанавливается
                ;   подробный [разбор счётчика чередования](../../Docs/MusicGateTicks.md)
                ; -----------------------------------------
                ; чтение перезагрузки счётчика тонального скольжения
Entry:          LD A, #00
                ; сохранение перезагрузки либо уже уменьшенного счётчика скольжения
StoreSlideDelay:LD (@MusicSynthesisA.SlideCounter), A
                ; восстановление амплитуды и её флагов обменом с альтернативным AF
RestoreLevel:   EX AF, AF'
                ; запись рассчитанной амплитуды в буфер AY канала A
UpdateGate:     LD (@MusicGateState.AmplitudeA), A
                ; чтение текущего счётчика чередования канала A
                LD A, #00
                ; расчёт уменьшенного счётчика с байтовым оборачиванием
                DEC A
                JP M, @Music.RenderChannelB.Entry                               ; переход, если результат DEC отрицателен, сохранить счётчик и продолжить синтез

                JR NZ, @Music.FinishChannelA.StoreGateDelay                     ; переход, если счётчик после DEC ненулевой, записать уменьшенное значение

                ; формирование FF для переключения всего байта состояния
                DEC A
                LD HL, @MusicGateState.StateA
                ; инверсия полного байта состояния после истечения счётчика
                XOR (HL)
                LD (HL), A
                ; выбор перезагрузки для нового ненулевого состояния
                LD A, #00
                JR NZ, @Music.FinishChannelA.StoreGateDelay                     ; переход, если новое состояние ненулевое, использовать длительность выключенного состояния

                ; выбор перезагрузки для нового нулевого состояния
                LD A, #00
                ; сохранение уменьшенного либо перезагруженного счётчика
StoreGateDelay: LD (@MusicChannelAState.GateCounter), A
                ; JP @Music.RenderChannelB.Entry, продолжение в RenderChannelB.asm

                endmodule
                endmodule
