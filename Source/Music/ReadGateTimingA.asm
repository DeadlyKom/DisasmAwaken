                module Music
                module ReadGateTimingA
                ; Документация [длительности A и регистр R](../../Docs/MusicEffects.md#длительности-a-и-регистр-r)
                ; -----------------------------------------
                ; Чтение двух длительностей переключения канала A из потока паттерна
                ; исходная запись 10, файловые смещения #02CA..#02CD
                ; In:
                ;   DE указывает на две длительности, входной F сохраняется
                ;   поток и два байта внешнего возврата не перекрывают изменяемые байты DE90, DE97 и DE9F
                ;   исходные команды сохранены, IRQ и NMI не вмешиваются
                ; Out:
                ;   HL сохранён, DE=входной DE+2, BC сохранён, AF содержит A=06 и входной F
                ;   HL', DE', BC', AF', IX, IY, I, IM и IFF сохранены, SP=входной SP+2
                ;   DE97 получает первую длительность, DE9F получает вторую, DE90 получает код 06
                ;   R сохраняет бит 7, младшие семь бит увеличены на 10 M1 по модулю 128, внешний CALL не включён
                ; Corrupt:
                ;   DE, AF только A, SP, R, изменяемые байты DE90, DE97 и DE9F
                ; Note:
                ;   JR передаёт управление в SetGateTimingA, дополнительной рамки возврата нет
                ;   DE90 получает 06 и при следующем исполнении означает LD B,n вместо JR
                ;   длительности далее копируются в счётчик и перезагрузочные значения по E0D7, E0E9 и E0E5
                ;   нулевые длительности сохраняются без нормализации, достаточные условия неперекрытия не доказывают все варианты наложений
                ; -----------------------------------------
                ; Чтение первой длительности и переход к общему установщику
Entry:          LD A, (DE)
                INC DE
                JR @Music.SetGateTimingA.Entry


                endmodule
                endmodule
