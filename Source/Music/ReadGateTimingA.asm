                module Music
                module ReadGateTimingA
; Документация [Music](../../Docs/FunctionDetails/Music.md)
; -----------------------------------------
; Чтение двух длительностей переключения канала A из потока паттерна
; исходная запись 10, файловые смещения #02CA..#02CD
; In:
;   DE - адрес двух последовательных байтов длительностей канала A
; Out:
;   DE увеличен на два, A равен #06, длительности записаны в операнды #DE97 и #DE9F
; Corrupt:
;   DE, AF
; Note:
;   флаги сохраняются, #DE90 получает #06 и при следующем исполнении означает LD B,n вместо JR
;   длительности далее копируются в счётчик и перезагрузочные значения по #E0D7, #E0E9 и #E0E5
; -----------------------------------------
                ; чтение первой длительности канала A и переход к общей установке двух байтов
Entry:          LD A, (DE)
                INC DE
                JR @Music.SetGateTimingA.Entry


                endmodule
                endmodule
