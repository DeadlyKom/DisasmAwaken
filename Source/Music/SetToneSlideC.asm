                module Music
                module SetToneSlideC
                ; Документация [эффект скольжения C и R](../../Docs/MusicEffects.md#скольжение-01)
; Документация [скольжение тона C](../../Docs/Music.md)
; Подробный разбор [Music.md](../../Docs/Music.md)
; -----------------------------------------
; Чтение задержки и шага скольжения тона C, настройка изменяемых операндов и отключение счётчика чередования
; исходная запись 10, файловые смещения #0BAE..#0BC8
                ; In:
                ;   DE указывает на три байта команды, задержку и младший, старший байты шага
                ;   поток и два байта внешнего возврата не перекрывают изменяемые параметры C
                ;   исходные команды сохранены, IRQ и NMI не вмешиваются
                ; Out:
                ;   HL содержит слово шага, DE=входной DE+3, BC сохранён, AF содержит A=0 и F=44 после XOR A
                ;   HL', DE', BC', AF', IX, IY, I, IM и IFF сохранены, SP=входной SP+2
                ;   SlideCounterC и SlideReloadC получают задержку, SlideStepC получает слово шага
                ;   SlideBranchC получает 1D, GateCounterC получает ноль
                ;   R сохраняет бит 7, младшие семь бит увеличены на 16 M1 по модулю 128, внешний CALL не включён
                ; Corrupt:
                ;   HL, DE, AF, SP, R, SlideCounterC, SlideReloadC, SlideStepC, SlideBranchC и GateCounterC
                ; Note:
                ;   SlideBranchC направляет последующий переход к перезагрузке счётчика, обходя дополнительную обработку между E2AE и E2CA
                ;   команда скольжения сама не меняет байт разрешения канала
                ;   модель охватывает все байты задержки и шесть граничных слов шага, полного совместного перебора параметров нет
; -----------------------------------------
                ; чтение задержки скольжения и установка текущего счётчика вместе с перезагрузкой
Entry:          LD A, (DE)
                INC DE
                LD (@MusicState.SlideCounterC), A
                LD (@MusicState.SlideReloadC), A
                ; чтение двухбайтового шага через HL с возвратом следующей позиции потока в DE
                EX DE, HL
                LD E, (HL)
                INC HL
                LD D, (HL)
                INC HL
                EX DE, HL
                ; сохранение шага и выбор прямой перезагрузки счётчика после его применения
                LD (@MusicState.SlideStepC), HL
                LD A, #1D
                LD (@MusicState.SlideBranchC), A
                ; отключение чередования канала, его текущий байт разрешения сохраняется
                XOR A
                LD (@MusicState.GateCounterC), A
                RET

                endmodule
                endmodule
