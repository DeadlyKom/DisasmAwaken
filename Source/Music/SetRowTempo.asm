                module Music
                module SetRowTempo
                ; Документация [музыкальные эффекты](../../Docs/MusicEffects.md)
                ; -----------------------------------------
                ; Чтение и установка изменяемого темпа музыкальной строки
                ; исходная запись 10, файловые смещения #0BFA..#0BFF
                ; In:
                ;   DE указывает на байт темпа, входной F сохраняется
                ; Out:
                ;   HL и BC сохранены, DE=входной DE+1, A=байт темпа, F сохранён, альтернативные пары сохранены
                ;   RowTempo по DF62 обновлён, текущая Phase по E37D не меняется
                ; Corrupt:
                ;   DE, AF только A, RowTempo, R
                ; Note:
                ;   новый темп переносится в Phase при следующем проходе StageEnvelopeAndNoise, нулевой темп не исправляется
                ;   индексные регистры, I, IM и IFF сохранены, SP увеличен на два обычным RET
                ; -----------------------------------------
                ; Чтение и установка изменяемого темпа музыкальной строки
Entry:          LD A, (DE)
                INC DE
                LD (@MusicEnvelopeState.RowTempo), A
                RET

                endmodule
                endmodule
