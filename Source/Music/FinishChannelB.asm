                module Music
                module FinishChannelB
                ; Документация [синтез трёх каналов](../../Docs/MusicSynthesis.md)
                ; -----------------------------------------
                ; Завершение счётчика скольжения B, восстановление амплитуды и обновление чередования
                ; исходная запись 10, файловые смещения #06CD..#06EC
                ; In:
                ;   HL, DE, BC задают сохраняемый контекст, HL может измениться при исходном счётчике чередования 1
                ;   AF содержит рабочую пару скольжения, AF' содержит амплитуду в A' и Carry в F' для DEC счётчика
                ;   Entry читает перезагрузку, StoreSlideDelay принимает текущую A, RestoreLevel пропускает запись счётчика
                ;   банк MUZ1 доступен для записи, SP может указывать на данные, прерывания запрещены
                ; Out:
                ;   HL сохранён при исходном MusicGateState.CounterB!=1, при единице HL=E0EE, DE и BC сохранены
                ;   AF при исходном MusicGateState.CounterB!=1 содержит A=(старый счётчик-1)&FF, F от DEC с Carry из входного F'
                ;   AF при исходном счётчике 1 содержит A=MusicGateState.DisabledTicksB при новом ненулевом StateB, иначе EnabledTicksB, F от XOR FF прежнего состояния
                ;   HL', DE', BC' сохранены
                ;   AF' содержит в A' перезагрузку Entry либо входную A двух других входов, F' равен входному основному F
                ;   IX, IY, SP, I, IM и IFF сохранены, собственного RET нет, продолжение RenderChannelC
                ;   Entry пишет перезагрузку в счётчик по E19F, StoreSlideDelay пишет входную A, RestoreLevel не меняет его
                ;   MusicGateState.AmplitudeB получает входной A' до обработки счётчика, амплитуда не является конечной основной A
                ;   исходные счётчики 0 и 129..255 не меняются, 2..128 уменьшаются, 1 инвертирует весь байт состояния и выбирает его перезагрузку
                ;   R получает p+4, p+6 либо p+12+(старое состояние=FF) M1, p=3/2/1 для Entry/StoreSlideDelay/RestoreLevel, условия в MusicGateTicks.md
                ; Corrupt:
                ;   HL по условию, AF, AF', счётчик скольжения по выбранному входу, буфер амплитуды, счётчик и состояние чередования, R
                ; Note:
                ;   различие трёх входов и все байты состояния проверены отдельной моделью, SP здесь не восстанавливается
                ;   подробный [разбор счётчика чередования](../../Docs/MusicGateTicks.md)
                ; -----------------------------------------
                ; чтение перезагрузки счётчика тонального скольжения
Entry:          LD A, #00
                ; сохранение перезагрузки либо уже уменьшенного счётчика скольжения
StoreSlideDelay:LD (@MusicChannelBRow.SlideCounter), A
                ; восстановление амплитуды и её флагов обменом с альтернативным AF
RestoreLevel:   EX AF, AF'
                ; запись рассчитанной амплитуды в буфер AY канала B
UpdateGate:     LD (@MusicGateState.AmplitudeB), A
                ; чтение текущего счётчика чередования канала B
                LD A, #00
                ; расчёт уменьшенного счётчика с байтовым оборачиванием
                DEC A
                JP M, @Music.RenderChannelC.Entry                               ; переход, если результат DEC отрицателен, сохранить счётчик и продолжить синтез

                JR NZ, @Music.FinishChannelB.StoreGateDelay                     ; переход, если счётчик после DEC ненулевой, записать уменьшенное значение

                ; формирование FF для переключения всего байта состояния
                DEC A
                LD HL, @MusicChannelBRow.Disabled
                ; инверсия полного байта состояния после истечения счётчика
                XOR (HL)
                LD (HL), A
                ; выбор перезагрузки для нового ненулевого состояния
                LD A, #00
                JR NZ, @Music.FinishChannelB.StoreGateDelay                     ; переход, если новое состояние ненулевое, использовать длительность выключенного состояния

                ; выбор перезагрузки для нового нулевого состояния
                LD A, #00
                ; сохранение уменьшенного либо перезагруженного счётчика
StoreGateDelay: LD (@MusicChannelBState.GateCounter), A
                ; JP @Music.RenderChannelC.Entry, продолжение в RenderChannelC.asm

                endmodule
                endmodule
