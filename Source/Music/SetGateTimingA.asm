                module Music
                module SetGateTimingA
                ; Документация [длительности A и регистр R](../../Docs/MusicEffects.md#длительности-a-и-регистр-r)
                ; -----------------------------------------
                ; Настройка двух длительностей канала A и замена JR в DE90 на LD B,n
                ; исходная запись 10, файловые смещения #02D2..#02DF
                ; In:
                ;   DE указывает на второй байт длительности, A содержит первую длительность, входной F сохраняется
                ;   байт потока и два байта внешнего возврата не перекрывают изменяемые байты DE90, DE97 и DE9F
                ;   исходные команды сохранены, IRQ и NMI не вмешиваются
                ; Out:
                ;   HL сохранён, DE=входной DE+1, BC сохранён, AF содержит A=06 и входной F
                ;   HL', DE', BC', AF', IX, IY, I, IM и IFF сохранены, SP=входной SP+2
                ;   DE97 получает входную A, DE9F получает байт потока, DE90 получает код 06
                ;   R сохраняет бит 7, младшие семь бит увеличены на 7 M1 по модулю 128, внешний CALL не включён
                ; Corrupt:
                ;   DE, AF только A, SP, R, изменяемые байты DE90, DE97 и DE9F
                ; Note:
                ;   изменяемый вход DE90 переключается на инструкцию LD B,n
                ;   нулевые длительности сохраняются без нормализации, достаточные условия неперекрытия не доказывают все варианты наложений
                ; -----------------------------------------
                ; Обновление двух длительностей и включение отложенной команды
Entry:          LD (#DE97), A
                LD A, (DE)
                INC DE
                LD (#DE9F), A
                LD A, #06
                LD (#DE90), A
                RET


                endmodule
                endmodule
