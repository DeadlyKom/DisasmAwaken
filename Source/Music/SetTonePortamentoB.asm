                module Music
                module SetTonePortamentoB
                ; Документация [музыкальные эффекты](../../Docs/MusicEffects.md)
                ; -----------------------------------------
                ; Настройка ограниченного скольжения от прежней ноты к новой цели B
                ; исходная запись 10, файловые смещения #0B74..#0B97
                ; In:
                ;   DE указывает на пять байтов, задержка, два пропускаемых байта, младший и старший байты шага
                ;   ожидающая нота содержит новую цель, текущая либо сохранённая прежняя нота содержит начало скольжения
                ;   D' задаёт код включения отложенного блока, штатное значение 06
                ; Out:
                ;   HL=адрес ожидающей ноты DEDB, DE=входной DE+5, B=0, C сохранён, F=44
                ;   целевая нота получает новую ожидающую ноту, ожидающая нота заменяется прежней, слово шага обновлено, смещение JR=0
                ;   A=прежняя текущая нота, E' получает D', остальные альтернативные байты сохранены
                ;   задержка и шаг записаны в ожидающие операнды, применяются при подготовке следующей строки
                ; Corrupt:
                ;   HL, DE, BC только B, AF, DE' только E', параметры скольжения, ожидающая и целевая нота, R
                ; Note:
                ;   два промежуточных байта только пропускаются, их значения не участвуют в расчёте
                ;   A и B сохраняют прежнюю ноту из текущего состояния до применения отложенного блока
                ;   индексные регистры, I, IM и IFF сохранены, SP увеличен на два обычным RET
                ; -----------------------------------------
                ; Настройка ограниченного скольжения от прежней ноты к новой цели B
Entry:          LD A, (DE)
                INC DE
                LD (@MusicChannelBRow.PendingDelay), A
                ; пропуск двух промежуточных байтов перед чтением знакового слова шага B
                EX DE, HL
                INC HL
                INC HL
                LD E, (HL)
                INC HL
                LD D, (HL)
                INC HL
                EX DE, HL
                LD (@MusicChannelBRow.PendingStep), HL
                ; выбор ограничения целевой нотой B и сохранения прежней основы
                XOR A
                LD B, A
                LD (@MusicChannelBRow.PendingBranch), A
                ; сохранение новой целевой ноты и возврат прежней ноты в ожидающий операнд B
                LD HL, @MusicChannelBRow.PendingNote
                LD A, (HL)
                LD (@MusicChannelBRow.PendingTarget), A
                LD A, (@MusicChannelBRow.CurrentNote)
                LD (HL), A
                EXX
                LD E, D
                EXX
                RET

                endmodule
                endmodule
