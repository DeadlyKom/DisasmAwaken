                module Music
                module FinishChannelC
                ; Документация [огибающая и вывод AY](../../Docs/MusicAyOutput.md)
                ; -----------------------------------------
                ; Завершение счётчика скольжения C, восстановление амплитуды и обновление чередования
                ; исходная запись 10, файловые смещения #07CB..#07EA
                ; In:
                ;   HL, DE, BC задают сохраняемый контекст, HL может измениться при исходном счётчике чередования 1
                ;   AF содержит рабочую пару скольжения, AF' содержит амплитуду в A' и Carry в F' для DEC счётчика
                ;   Entry читает перезагрузку, StoreSlideDelay принимает текущую A, RestoreLevel пропускает запись счётчика
                ;   банк MUZ1 доступен для записи, SP может указывать на данные, прерывания запрещены
                ; Out:
                ;   HL сохранён при исходном MusicGateState.CounterC!=1, при единице HL=E1EE, DE и BC сохранены
                ;   AF при исходном MusicGateState.CounterC!=1 содержит A=(старый счётчик-1)&FF, F от DEC с Carry из входного F'
                ;   AF при исходном счётчике 1 содержит A=MusicGateState.DisabledTicksC при новом ненулевом StateC, иначе EnabledTicksC, F от XOR FF прежнего состояния
                ;   HL', DE', BC' сохранены
                ;   AF' содержит в A' перезагрузку Entry либо входную A двух других входов, F' равен входному основному F
                ;   IX, IY, SP, I, IM и IFF сохранены, собственного RET нет, продолжение OutputAyFrame
                ;   основной вход пишет SlideReloadC в SlideCounterC, StoreSlideDelay пишет входную A, RestoreLevel не меняет это поле
                ;   MusicGateState.AmplitudeC получает входной A' до обработки счётчика, амплитуда не является конечной основной A
                ;   исходные счётчики 0 и 129..255 не меняются, 2..128 уменьшаются, 1 инвертирует весь байт состояния и выбирает его перезагрузку
                ;   R получает p+4, p+6 либо p+12+(старое состояние=FF) M1, p=3/2/1 для Entry/StoreSlideDelay/RestoreLevel, условия в MusicGateTicks.md
                ; Corrupt:
                ;   HL при истечении счётчика, AF, AF', SlideCounterC по выбранному входу, буфер AY10, счётчик и состояние чередования C, R
                ; Note:
                ;   три входа имеют разные действия над счётчиком скольжения, общий хвост восстанавливает AF одинаково
                ;   SP может ещё указывать на данные синтеза, восстановление настоящего стека выполняется следующим OutputAyFrame
                ;   393216 случаев проверены на исходных байтах до границы E2EB
                ; -----------------------------------------
                ; чтение перезагрузки счётчика тонального скольжения C
Entry:          LD A, #00
                ; сохранение перезагрузки либо уже уменьшенного счётчика тонального скольжения C
StoreSlideDelay:LD (@MusicState.SlideCounterC), A
                ; восстановление рассчитанной амплитуды и её флагов из альтернативного AF
RestoreLevel:   EX AF, AF'
                ; запись рассчитанной амплитуды в буфер AY канала C
UpdateGate:     LD (@MusicGateState.AmplitudeC), A
                ; чтение текущего счётчика чередования канала C
                LD A, #00
                ; расчёт уменьшенного счётчика с байтовым оборачиванием
                DEC A
                JP M, @Music.OutputAyFrame.Entry                                ; переход, если результат DEC отрицателен, сохранить счётчик и продолжить синтез

                JR NZ, @Music.FinishChannelC.StoreGateDelay                     ; переход, если счётчик после DEC ненулевой, записать уменьшенное значение

                ; формирование FF для переключения всего байта состояния
                DEC A
                LD HL, @MusicGateState.StateC
                ; инверсия полного байта состояния после истечения счётчика
                XOR (HL)
                LD (HL), A
                ; выбор перезагрузки для нового ненулевого состояния
                LD A, #00
                JR NZ, @Music.FinishChannelC.StoreGateDelay                     ; переход, если новое состояние ненулевое, использовать длительность выключенного состояния

                ; выбор перезагрузки для нового нулевого состояния
                LD A, #00
                ; сохранение уменьшенного либо перезагруженного счётчика
StoreGateDelay: LD (@MusicGateState.CounterC), A
                ; JP @Music.OutputAyFrame.Entry, продолжение в OutputAyFrame.asm

                endmodule
                endmodule
