                module Music
                module SetTonePortamentoC
                ; Документация [музыкальные эффекты](../../Docs/MusicEffects.md)
                ; -----------------------------------------
                ; Настройка ограниченного скольжения от прежней ноты к новой цели C
                ; исходная запись 10, файловые смещения #0BC9..#0BED
                ; In:
                ;   DE указывает на пять байтов, задержка, два пропускаемых байта, младший и старший байты шага
                ;   ожидающая нота содержит новую цель, текущая либо сохранённая прежняя нота содержит начало скольжения
                ; Out:
                ;   HL=адрес ожидающей ноты E2B9, DE=входной DE+5, B=0, C сохранён, F=44
                ;   целевая нота получает новую ожидающую ноту, ожидающая нота заменяется прежней, слово шага обновлено, смещение JR=0
                ;   A=новая целевая нота, задержка записана в текущий счётчик и перезагрузку, счётчик чередования обнулён
                ;   альтернативные пары сохранены
                ; Corrupt:
                ;   HL, DE, BC только B, AF, параметры скольжения, ожидающая и целевая нота, R
                ; Note:
                ;   два промежуточных байта только пропускаются, их значения не участвуют в расчёте
                ;   C восстанавливает прежнюю ноту из изменяемого операнда E6EC, заполненного декодером при постановке эффекта в стек
                ;   индексные регистры, I, IM и IFF сохранены, SP увеличен на два обычным RET
                ; -----------------------------------------
                ; Настройка ограниченного скольжения от прежней ноты к новой цели C
Entry:          LD A, (DE)
                INC DE
                LD (@MusicState.SlideCounterC), A
                LD (@MusicState.SlideReloadC), A
                ; пропуск двух промежуточных байтов перед чтением знакового слова шага C
                EX DE, HL
                INC HL
                INC HL
                LD E, (HL)
                INC HL
                LD D, (HL)
                INC HL
                EX DE, HL
                LD (@MusicState.SlideStepC), HL
                ; отключение чередования C и выбор пути ограничения целевой нотой
                XOR A
                LD B, A
                LD (@MusicGateState.CounterC), A
                LD (@MusicState.SlideBranchC), A
                ; сохранение новой цели C перед восстановлением ноты, захваченной декодером
                LD HL, @MusicEffectState.CurrentNoteC
                LD A, (HL)
                LD (@MusicEffectState.TargetNoteC), A
                ; восстановление прежней ноты C из изменяемого операнда, подготовленного декодером
                LD (HL), #00
                RET

                endmodule
                endmodule
