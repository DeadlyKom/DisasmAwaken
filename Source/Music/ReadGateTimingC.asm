                module Music
                module ReadGateTimingC
; Документация [Music](../../Docs/FunctionDetails/Music.md)
; -----------------------------------------
; Чтение двух длительностей переключения канала C из потока паттерна
; исходная запись 10, файловые смещения #030A..#030D
; In:
;   DE - адрес двух последовательных длительностей канала C
; Out:
;   DE увеличен на два, A содержит второй байт длительности, счётчик и перезагрузка настроены
; Corrupt:
;   DE, AF
; Note:
;   флаги сохраняются, первый байт записывается в #E2E7 и #E2D5, второй в #E2E3
; -----------------------------------------
                ; чтение первой длительности канала C, второй байт читает общий установщик
Entry:          LD A, (DE)
                INC DE
                JR @Music.SetGateTimingC.Entry


                endmodule
                endmodule
