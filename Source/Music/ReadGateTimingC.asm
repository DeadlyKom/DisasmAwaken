                module Music
                module ReadGateTimingC
                ; Документация [длительности C и регистр R](../../Docs/MusicEffects.md#длительности-c-и-регистр-r)
                ; -----------------------------------------
                ; Чтение двух длительностей переключения канала C из потока паттерна
                ; исходная запись 10, файловые смещения #030A..#030D
                ; In:
                ;   DE указывает на две длительности, входной F сохраняется
                ;   поток и два байта внешнего возврата не перекрывают изменяемые байты E2E7, E2D5 и E2E3
                ;   исходные команды сохранены, IRQ и NMI не вмешиваются
                ; Out:
                ;   HL сохранён, DE=входной DE+2, BC сохранён, AF содержит вторую длительность в A и входной F
                ;   HL', DE', BC', AF', IX, IY, I, IM и IFF сохранены, SP=входной SP+2
                ;   E2E7 и GateCounterC по E2D5 получают первую длительность, E2E3 получает вторую
                ;   R сохраняет бит 7, младшие семь бит увеличены на 9 M1 по модулю 128, внешний CALL не включён
                ; Corrupt:
                ;   DE, AF только A, SP, R, изменяемые байты E2E7, E2D5 и E2E3
                ; Note:
                ;   JR передаёт управление в SetGateTimingC, дополнительной рамки возврата нет
                ;   параметры C обновляются непосредственно, отложенный код 06 как у A и B не записывается
                ;   нулевые длительности сохраняются без нормализации, достаточные условия неперекрытия не доказывают все варианты наложений
                ; -----------------------------------------
                ; Чтение первой длительности и переход к общему установщику
Entry:          LD A, (DE)
                INC DE
                JR @Music.SetGateTimingC.Entry


                endmodule
                endmodule
