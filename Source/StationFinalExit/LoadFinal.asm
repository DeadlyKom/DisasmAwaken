                module StationFinalExit
                module LoadFinal
                ; Документация [StationFinalExit](../../Docs/FunctionDetails/StationFinalExit.md)
                ; Подробный разбор [физическое хранение 6E11, исполнение 4000, экран банка 7 и граница TR-DOS](../../Docs/FinalExit.md)
                ; -----------------------------------------
                ; Перенесённый загрузчик FINALF с повторной инициализацией музыки и ожиданием точного байта клавиатуры
                ; исходная запись 4, физическое хранение 6E11, исполнение 4000, файловые смещения #10BD..#1118
                ; In:
                ;   512 исходных байтов 6E11..7010 уже скопированы в 4000..41FF, выполняется фиксированная копия, её первые 92 байта являются этим загрузчиком
                ;   MUZ1 загружен в банк 3 по DB00 с модулем E700, действуют договоры Music.Initialize и SelectRamBank, paging не заблокирован
                ;   клавиатурное чтение порта 7FFE когда-либо возвращает ровно BE, иначе исходная петля ожидания не завершится
                ;   ROM и TR-DOS доступны, системные переменные и экран банка 7 доступны для записи, стек до первой замены пригоден для инициализации музыки
                ; Out:
                ;   IFF сброшен до инициализации музыки, затем SP=5FFF, аппаратный порт 7FFD получает 1F и показывает экран банка 7
                ;   перед ожиданием 768 атрибутов D800..DAFF в банке 7 заполнены 01, OUT по 01FE получает 01
                ;   после принятого BE те же атрибуты заполнены нулём, IM=1, IY=5C3A, I=3F
                ;   имя и тип FINALF  C скопированы девятью байтами в 5CDD..5CE5, 5CF9=0
                ;   перед хвостовым JP TrDos.Dispatch HL=4065, DE=6000, BC=000E, AF=0044, SP=5FFD, на стеке слово 6000
                ;   CurrentPage остаётся (входной CurrentPage AND F8) OR 13 от первого выбора банка, фактическая аппаратная страница уже 1F
                ;   IX и альтернативные регистры сохранены до границы DOS, 512 байтов фиксированной копии не меняются
                ;   после передачи TR-DOS собственный возврат загрузчика не предусмотрен, успешный внешний возврат должен использовать слово 6000, результат DOS этим кодом не проверяется
                ; Corrupt:
                ;   HL, DE, BC, AF, SP, I, IFF, IM, IY, AY, экран банка 7, порт FE и системные данные TR-DOS
                ; Note:
                ;   имя из девяти байтов не является исполняемым кодом, расположено в копии по 405C..4064
                ;   512-байтовый исходный перенос включает ещё соседние станционные байты после имени, они сохраняются, но не объявляются частью алгоритма этого загрузчика
                ;   условие IN/CP сравнивает полный байт с BE, смысл остальных клавиатурных сочетаний не заменяет фактическое сравнение
                ;   прямой OUT 1F не обновляет программную тень CurrentPage, эта исходная рассогласованность сохранена
                ;   модель проверила 512 путей для всех первых клавиатурных байтов и двух начальных страниц с настоящим MUZ1, остановка строго до TR-DOS
                ;   фактическая дисковая загрузка, выполнение FINALF, аппаратные IRQ и нативная игра этим договором модели не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Подготовка проигрывателя и временного экрана
                ; -----------------------------------------
                ; запрет прерываний до первого банкового вызова
Entry:          DI
                ; выбор банка 3 с MUZ1 через станционный интерфейс paging
                LD A, #13
                CALL @Station.SelectRamBank.Entry
                ; повторная полная инициализация музыки и сброс AY 13..0
                CALL @Music.Initialize.Entry
                ; замена SP после возврата инициализатора, дальнейшего возврата в исходного вызывающего нет
                LD SP, #5FFF
                ; прямой выбор банка 7 и теневого экрана, CurrentPage не обновляется
                LD A, #1F
                LD BC, #7FFD
                OUT (C), A
                ; подготовка перекрывающегося заполнения всех 768 атрибутов теневого экрана единицей
                LD HL, #D800
                LD DE, #D801
                LD BC, #02FF
                ; запись первого атрибута и распространение его остальными 767 байтами LDIR
                LD (HL), #01
                LDIR
                ; выбор полного байта для OUT FE, старший байт порта будет равен 01
                LD A, #01
                OUT (#FE), A
                ; -----------------------------------------
                ; Ожидание точного клавиатурного байта
                ; -----------------------------------------
                ; выбор порта 7FFE для повторного чтения
                LD BC, #7FFE
                ; проверка полного входного байта, принимается только BE
WaitKey:        IN A, (C)
                CP #BE
                JP NZ, @StationFinalExit.LoadFinal.WaitKey                      ; переход, если прочитанный байт отличается от BE, продолжить ожидание

                ; -----------------------------------------
                ; Подготовка системных переменных и передача TR-DOS
                ; -----------------------------------------
                ; подготовка обнуления тех же 768 атрибутов банка 7
                LD HL, #D800
                LD DE, #D801
                LD BC, #02FF
                ; запись нулевого L в первый атрибут и распространение нуля по области
                LD (HL), L
                LDIR
                ; выбор исходного режима прерываний IM 1, разрешение IFF не выполняется
                IM 1
                ; восстановление адреса системных переменных ROM в IY и исходного I=3F
                LD IY, #5C3A
                LD A, #3F
                LD I, A
                ; подготовка переноса имени и типа из девяти физических байтов фиксированной копии
                LD HL, @FinalFileName.Entry
                LD DE, #5CDD
                LD BC, FTrDosFileKey
                ; копирование FTrDosFileKey в системное поле TR-DOS без нулевого терминатора
                LDIR
                ; подготовка режима A=0 и обнуление системного байта 5CF9
                XOR A
                LD (#5CF9), A
                ; выбор файловой функции 0E и исходного адреса 6000
                LD C, #0E
                LD DE, #6000
                ; помещение 6000 на CPU-стек как внешнего адреса продолжения после DOS
                PUSH DE
                ; хвостовая передача диспетчеру TR-DOS, ошибки и дисковая загрузка не проверяются здесь
                JP @TrDos.Dispatch

                ; -----------------------------------------
                endmodule
                endmodule
