                module Action
                module RecordIXToIndex
                ; Документация [коды и адреса записей](../../Docs/ActionRecordIndex.md)
                ; -----------------------------------------
                ; Расчёт байтового кода записи по IX с сохранением HL
                ; исходная запись 17, код ACTION банка 0, адреса E6B5..E6BD
                ; In:
                ;   HL сохраняется, DE, BC и AF числовых аргументов не задают, IX входной адрес записи
                ;   действует договор RecordAddressToIndex, CPU-стек имеет четыре дополнительных байта, IRQ не вмешиваются
                ; Out:
                ;   HL, DE и BC сохраняются, A и F соответствуют RecordAddressToIndex с входным HL=IX
                ;   HL', DE', BC', AF', IX, IY, I, IM и IFF сохраняются, SP=входной SP+2
                ;   R увеличивается на 16 M1, записываются четыре байта CPU-стека, иной RAM не меняется
                ; Corrupt:
                ;   AF, R, четыре байта CPU-стека
                ; Note:
                ;   перед расчётом исходный HL сохраняется, временный PUSH IX используется только для переноса адреса в HL
                ;   адрес записи не разыменовывается, произвольные значения IX не вызывают отказа
                ; -----------------------------------------
                ; Сохранение исходного HL и перенос IX в HL через CPU-стек.
Entry:          PUSH HL
                PUSH IX
                POP HL
                ; Расчёт кода по адресу IX без чтения содержимого записи.
                CALL @Action.RecordAddressToIndex.Entry
                ; Восстановление исходного HL после получения кода в A.
                POP HL
                RET

                endmodule
                endmodule
