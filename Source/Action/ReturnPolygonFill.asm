                module ReturnPolygonFill
                ; Документация [алгоритм и проверка](../../Docs/ActionPolygonReturn.md)
                ; -----------------------------------------
                ; Восстановление сохранённого HL и внешний возврат плоского контура
                ; исходная запись 17, адреса D50F..D510
                ; In:
                ;   SP указывает на ранее сохранённый HL, следующее слово содержит внешний адрес возврата
                ;   остальные регистры содержат результат раннего пути PreparePolygonFill
                ; Out:
                ;   HL снят с CPU-стека
                ;   DE, BC, AF сохраняются
                ;   HL', DE', BC', AF' сохраняются
                ;   IX и IY сохраняются, I, IM, IFF и paging сохраняются
                ;   SP увеличен на четыре, выполнен RET по слову после сохранённого HL, память и порты не записываются
                ;   R добавляет 2 M1, бит 7 R сохраняется
                ; Corrupt:
                ;   HL, SP при снятии двух слов, R
                ; Note:
                ;   возврат снимает два существующих слова, дополнительная память не выделяется
                ;   проверены точные регистры включая R и отсутствие записей RAM, полное игровое исполнение этим не доказывается
                ;   точные T, IRQ, сборка и нативный запуск не проверены
                ; -----------------------------------------
                ; Восстановление HL вызывающего и внешнего возврата без смены временного SP.
Entry:          POP HL
                RET

                endmodule
                endmodule
