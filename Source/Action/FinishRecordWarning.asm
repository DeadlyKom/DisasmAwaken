                module Action
                module FinishRecordWarning
                ; Документация [алгоритм и проверка](../../Docs/ActionRecordWarningReturn.md)
                ; -----------------------------------------
                ; Восстановление DE после запроса предупреждения и завершение через восстановитель смещений
                ; исходная запись 17, адреса E655..E657
                ; In:
                ;   HL и BC задают сохраняемый контекст, DE и AF будут заменены
                ;   IX - читаемая FActionRecord, действует договор RestoreHalvedOffsets
                ;   входной SP указывает на сохранённое слово DE, сразу за ним лежит внешний возврат, это внутренний вход после CALL очереди
                ;   выбран банк 0, IRQ не вмешивается
                ; Out:
                ;   HL и AF определены RestoreHalvedOffsets, DE восстановлен из слова входного стека, BC сохранён
                ;   HL', DE', BC', AF', IX и IY, I/IM/IFF и paging сохраняются
                ;   SP после внешнего RET равен входному SP+4, CPU-стек только читается
                ;   R получает 13 M1 для класса 14 и 6 M1 для другого класса, старший разряд сохраняется
                ; Corrupt:
                ;   HL только для класса 14, DE, AF, R и шесть байтов Active0..2 только для класса 14
                ; Note:
                ;   (1) жёсткий порядок, сюда продолжается UpdateRecordComponents.asm, часть (0), после возврата из очереди
                ;   POP DE соответствует PUSH DE перед загрузкой адреса сообщения, добавлять внешний CALL к этому входу нельзя без такой рамки
                ;   65536 сценариев проверили все сохранённые слова DE и все коды класса, регистры включая R, RAM и записи восстановителя
                ;   код класса связан со старшим байтом тестового DE, полное произведение DE и ClassCode не перебиралось
                ;   IRQ, точные T, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Возврат после запроса предупреждения
                ; Восстановление DE, сохранённого перед установкой адреса текста, внешний возврат находится следующим словом стека.
Entry:          POP DE
                JR @Action.RestoreHalvedOffsets.Entry

                endmodule
                endmodule
