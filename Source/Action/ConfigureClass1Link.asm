                module Action
                module ConfigureClass1Link
                ; Документация [алгоритм и проверка](../../Docs/ActionClass1Link.md)
                ; -----------------------------------------
                ; Подстановка и условный общий выбор связи со сменой класса на 0 после успеха
                ; исходная запись 17, адреса 6594..65AC
                ; In:
                ;   HL, DE, BC числовых аргументов не задают, AF задаёт входной Carry ранней подстановки, IX указывает доступную FActionRecord
                ;   LinkOverride, StateCode и LinkedIndex доступны по договору CopyRecordLinkOverride, он вызывается до иных проверок
                ;   действуют договоры вызываемых потоков и фильтров, достижима подходящая активная запись либо маркер
                ;   выбран ACTION банка 0, CPU-стек не пересекает запись, код и потоки, доступны 10 дополнительных байтов, IRQ не вмешиваются
                ; Out:
                ;   при LinkOverride=1..FE возвращается результат подстановки, LinkedIndex=LinkOverride и StateCode=02
                ;   при LinkOverride=0 либо FF обработка продолжается, разрешённый ноль сначала записывает LinkedIndex=0 и StateCode=02
                ;   после незавершившей подстановки StateCode=01, обновляется Stream0 и вычисляется p=(прочитанный R AND H) OR L
                ;   при p!=0 возврат сохраняет StateCode=01, при p=0 вызывается общий SelectLink
                ;   после NZ общего выбора ClassCode становится 00, после Z прежний ClassCode сохраняется
                ;   HL сохраняется без генератора, иначе содержит новый LowWord последнего вызванного потока, последующий поиск его не меняет
                ;   DE - D сохраняется, E без фильтра сохраняется, при находке равен (ClassCode+1) AND FF
                ;   при маркере E содержит последний проверенный ClassCode либо входной E, если активных записей не было
                ;   BC при фильтре равен FActionRecord, без фильтра сохраняется
                ;   AF при разрешённой ненулевой подстановке содержит A=LinkOverride и флаги DEC байта LinkOverride+1 с сохранённым входным Carry
                ;   AF при ненулевом предикате Stream0 содержит предикат в A и его логические флаги OR, поиск не вызывается
                ;   AF при отдельном коде 26 общего SelectLink содержит A=1A и F=0A, это не найденный индекс
                ;   AF после фактического фильтра содержит индекс в A и флаги INC E с Carry=0 для проверенной области списка, при маркере A=80 и F=42
                ;   HL', DE', BC' сохраняются без генератора, иначе HL' указывает последний Stream, DE' содержит его новое слово, B'=0 и C' младший байт промежуточного n
                ;   AF' сохраняется на всех путях
                ;   IX сохраняется, IY при фильтре указывает найденную запись либо маркер, без фильтра сохраняется
                ;   I, IM, IFF и paging сохраняются, SP после внешнего RET равен входному SP+2
                ;   R и все флаги проверены точной числовой моделью каждого пути, бит 7 R сохраняется
                ; Corrupt:
                ;   HL, E, BC, AF, HL', DE', BC', IY, R, StateCode, LinkedIndex, вызываемые состояния потоков и временные слова CPU-стека
                ;   ClassCode только после принятого общего выбора
                ; Note:
                ;   коды состояний и пороги в этой записи шестнадцатеричные, номера классов в названии десятичные
                ;   общий SelectLink может вернуть отдельный код 26, он не объявляется индексом найденной записи
                ;   совместная проверка восьми обработчиков исполнила 405456 сценариев с настоящими детьми, точными регистрами, R, восемью банками и кратностью записей
                ;   охват конкретного входа и списков приведён в его отчёте, произведение всех состояний и списков не исчерпано
                ;   распределение аппаратного R, период генераторов, аппаратные IRQ, точные T, сборка и нативная игра не доказаны
                ;   чтение R после обновления Stream0 происходит через 77 M1 для подстановки FF либо 83 M1 для нуля
                ;   при продолжении после подстановки последний генератор равен Stream0 до общего SelectLink, после его вызова Stream10, поиск и возврат сохраняют результаты этого потока
                ; -----------------------------------------
                ; Применение исходной подстановки до выбора состояния, ноль разрешён и продолжает обработку.
Entry:          CALL @Action.CopyRecordLinkOverride.Entry
                RET NZ                                                          ; выход, если LinkOverride находится в 1..FE, сохранить результат подстановки

                ; Подготовка StateCode=01 перед условным выбором и возможной сменой самого класса.
                LD (IX + @FActionRecord.StateCode), @ActionClass9Const.DefaultCode
                ; Обновление Stream0, исходное состояние других потоков сохраняется до общего поиска.
                CALL @Action.NextRandomWord0.Entry
                ; Расчёт аппаратно зависимого предиката по новому слову Stream0.
                LD A, R
                AND H
                OR L
                RET NZ                                                          ; выход, если выражение прочитанный R AND H OR L ненулевое, сохранить StateCode=01

                ; Вызов общего выбора с отдельным возвратом, поэтому рамка здесь глубже хвостовых переходов.
                CALL @Action.ConfigureClass0Link.SelectLink
                RET Z                                                           ; выход, если общий выбор вернул Z, сохранить прежний ClassCode

                ; Обновление полного ClassCode до 00 после успешного общего выбора.
                LD (IX + @FActionRecord.ClassCode), @ActionRandomRecordConst.ClassZero
                RET

                endmodule
                endmodule
