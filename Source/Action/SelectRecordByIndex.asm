                module Action
                module SelectRecordByIndex
                ; Документация [алгоритм и проверка](../../Docs/ActionRecordSelection.md)
                ; -----------------------------------------
                ; Расчёт адреса записи в IY по коду A с сохранением HL
                ; исходная запись 17, адреса E69E..E6A6
                ; In:
                ;   HL, DE и BC содержат сохраняемый контекст, A - байтовый код записи 00..FF, входные флаги на адрес не влияют
                ;   в окне C000 выбран банк 0, код E69E..E6B4 доступен, IRQ не вмешивается
                ;   CPU-стек содержит внешний возврат и допускает четыре дополнительных байта без пересечения с кодом
                ; Out:
                ;   HL, DE и BC сохраняются, A - старший байт адреса A100+64*входной A
                ;   F - результат ADD A1 к входному коду, сдвинутому вправо на два разряда
                ;   HL', DE', BC', AF' и IX сохраняются, IY=A100+64*входной A, I/IM/IFF и paging сохраняются
                ;   R получает 19 M1 с сохранением старшего разряда, SP после RET равен входному SP+2
                ;   временные четыре байта под CPU-стеком остаются изменёнными, выполнено шесть байтовых записей
                ; Corrupt:
                ;   AF, IY, R и четыре байта временного CPU-стека
                ; Note:
                ;   адрес вычисляет настоящий RecordIndexToAddress, сама запись не читается и не проверяется
                ;   диапазон результата A100..E0C0 включает банковое окно, это числовое преобразование без проверки границ списка
                ;   PUSH HL сохраняет исходный HL, после CALL вычисленный адрес переносится в IY через стек, затем HL восстанавливается
                ;   65536 сценариев проверили все входные AF, регистры включая R, все физические банки RAM и шесть записей в порядке модели
                ;   три варианта SP распределены между случаями, два пересекают границы банков, полное произведение AF и SP не перебиралось
                ;   порядок шинных циклов записи двух байтов PUSH и CALL моделью не доказывается
                ;   содержимое и игровая допустимость записи, IRQ, точные T и нативный запуск не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Сохранение контекста и расчёт адреса
                ; Сохранение входного HL, чтобы выбор IY не разрушил данные вызывающего кода.
Entry:          PUSH HL
                ; Расчёт адреса по коду A, результат HL=A100+64*A, сама запись не просматривается.
                CALL @Action.RecordIndexToAddress.Entry
                ; -----------------------------------------
                ; Выбор IY и восстановление HL
                ; Перенос вычисленного адреса в IY через временное слово CPU-стека.
                PUSH HL
                POP IY
                ; Восстановление исходного HL перед возвратом, арифметические флаги преобразователя сохраняются.
                POP HL
                RET

                ; -----------------------------------------
                endmodule
                endmodule
