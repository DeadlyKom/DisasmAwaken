                module Action
                module UnknownE9A1
; Документация [Action](../../Docs/FunctionDetails/Action.md)
; -----------------------------------------
; Unknown, назначение этого фрагмента ещё не установлено
; исходная запись 17, файловые смещения #89A1..#89C1
; In:
;   Unknown, регистровый контракт ещё не доказан
; Out:
;   исходный поток управления, включая переходы в соседние фрагменты
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, консервативная верхняя граница
; Note:
;   граница файла не доказывает границу логической процедуры
;   состояние самомодификации и активной страницы учитывается отдельно
; -----------------------------------------
Entry:          LD IY, #A0C0
                LD DE, #0040
PointE9A8:      ADD IY, DE
                LD A, (IY + #01)
                CP #80
                JR NZ, @Action.UnknownE9A1.PointE9A8                            ; переход, если флаг Z сброшен


                LD A, (IY + #00)
                CP #80
                RET Z                                                           ; выход, если флаг Z установлен

                LD A, (IY + #18)
                LD (IY + #18), #00
                INC A
                JR Z, @Action.UnknownE9A1.PointE9A8                             ; переход, если флаг Z установлен


                RET


                endmodule
                endmodule
