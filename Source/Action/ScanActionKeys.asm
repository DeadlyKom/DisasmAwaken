                module Action
                module ScanActionKeys
                ; Документация [алгоритм и проверка](../../Docs/ActionMotionVectorTail.md)
                ; -----------------------------------------
                ; Обход 27 клавиатурных условий и программные вызовы обработчиков
                ; исходная запись 17, перенесённое ядро 6000..7F8E, смещения #115A..#118A
                ; In:
                ;   доступны 27 входных условий и соответствующие слова целей, на стеке внешний возврат
                ;   B задаётся строкой порта, младший байт порта равен #FE, доступен байт режима по #A85F
                ;   при допуске обработчик должен вернуть управление на RestoreKeyScanFrame либо выполнить свой явный переход
                ; Out:
                ;   при ненулевом результате AND сканирование продолжается, при нулевом вызывается выбранный обработчик
                ;   программный вызов сохраняет HL, DE, BC и IX, возвратная рамка восстанавливается в RestoreKeyScanFrame
                ;   после последнего условия хвост LatchControlsAndDecay завершает обработку
                ; Corrupt:
                ;   HL, DE, BC, AF, IX, R и стек, далее изменения зависят от обработчика и хвоста затухания
                ; Note:
                ;   27-е слово цели физически пересекается с кодом, отдельная запись не добавлена
                ;   локальные границы и возврат пустого обработчика доказаны, игровые действия остальных целей требуют отдельных договоров
                ; -----------------------------------------
                ; Подготовка указателей условий и целей, первый шаг сдвигает адрес цели на два.
Entry:          LD IX, @ActionKeyScanInputs.Index00.RowSelect
                LD DE, @ActionKeyHandlerPointers.Index00 - 2
                LD L, #1C
                LD C, #FE
                ; Проверка окончания 27 входных условий.
ScanNext:       DEC L
                JR Z, @Action.LatchControlsAndDecay.Entry                       ; переход, если все условия просмотрены, завершить затуханием

                ; Чтение порта выбранной строки и проверка маски допуска.
                LD B, (IX + #00)
                INC IX
                INC IX
                INC DE
                INC DE
                IN A, (C)
                AND (IX - #01)
                JR NZ, @Action.ScanActionKeys.ScanNext                          ; переход, если маскированный результат ненулевой, пропустить обработчик

                ; Создание рамки и программного возврата перед JP (HL).
                PUSH HL
                PUSH DE
                PUSH BC
                PUSH IX
                LD A, (DE)
                LD L, A
                INC DE
                LD A, (DE)
                LD H, A
                LD A, (#A85F)
                AND A
                LD DE, @Action.RestoreKeyScanFrame.Entry
                PUSH DE
                JP (HL)

                endmodule
                endmodule
