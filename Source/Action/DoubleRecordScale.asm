                ; Документация [алгоритм и проверка](../../Docs/ActionRecordScaleExtraEntry.md)
                ; -----------------------------------------
                ; Дополнительное удвоение масштаба перед обновлением компонент
                ; исходная запись 17, адреса E59F..E59F
                ; In:
                ;   HL содержит исходное слово масштаба, остальные регистры сохраняются, кроме части F и R
                ;   в исходном PrepareRecordScale этот адрес возможен, если старший байт заголовка равен 6
                ; Out:
                ;   HL удваивается по модулю 65536, управление продолжает UpdateRecordComponents.Entry
                ;   AF сохраняет A, S, Z и P/V, N сброшен, H и Carry отражают переносы из битов 11 и 15
                ;   биты 5 и 3 в F берутся из старшего байта результата, R увеличивается на один M1
                ;   SP и память сохраняются, физического JP или CALL между файлами нет
                ; Corrupt:
                ;   HL, F и R
                ; Note:
                ;   в штатной таблице старший байт заголовка лежит в диапазоне 1..5, эти профили пропускают E59F
                ;   65536 значений HL проверены непосредственно, два входа через исходный JR используют заголовок 6 в тестовой памяти
                ; -----------------------------------------
                ; Расчёт дополнительного удвоения перед четырьмя удвоениями общего входа.
Entry:          ADD HL, HL
                ; JP @Action.UpdateRecordComponents.Entry, продолжение в UpdateRecordComponents.asm

