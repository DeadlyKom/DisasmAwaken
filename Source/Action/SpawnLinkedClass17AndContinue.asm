                module Action
                module SpawnLinkedClass17AndContinue
                ; Документация [алгоритм и проверка](../../Docs/ActionSpawnContinue.md)
                ; -----------------------------------------
                ; Создание класса 17 по текущей связи и продолжение общего расчёта смещений
                ; исходная запись 17, адреса F24F..F254
                ; In:
                ;   HL, DE, BC, AF и альтернативные пары соответствуют SpawnClass17FromCurrentLink
                ;   IX указывает текущую запись, действует полный договор создателя и доступны восемь дополнительных байтов CPU-стека
                ;   ACTION банка 0 и перенесённый код банка 5 доступны, IRQ исключены
                ; Out:
                ;   выполняется полный SpawnClass17FromCurrentLink, включая отказ выделения и обратную связь
                ;   регистры и поля соответствуют результату ребёнка, PC=F0F8, внешний SP сохраняется
                ;   собственные CALL и JP добавляют два M1 к дочерней стоимости, Carry не влияет на продолжение
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IY, R и побочные эффекты создателя, временная возвратная рамка CPU-стека
                ; Note:
                ;   44656 композиционных сценариев State02 включили 5700 фактических вызовов этой обёртки по истечению Unknown14
                ;   на этих путях исполнены настоящие инструкции до F0F8, сверены точные регистры, R, все банки и кратность записей
                ;   общий F0F8, полное произведение входов, аппаратные IRQ, время, сборка и нативная игра не проверялись
                ; -----------------------------------------
                ; Создание связанной записи класса 17 без проверки Carry перед общим продолжением.
Entry:          CALL @Action.SpawnClass17FromCurrentLink.Entry
                JP @Action.PrepareObjectOffsetTransform.Entry

                endmodule
                endmodule
