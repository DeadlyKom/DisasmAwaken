                module Action
                module QueueTextItemBank1
                ; Документация [межбанковые вызовы очереди](../../Docs/ActionTextQueueCalls.md)
                ; -----------------------------------------
                ; Передача записи DE в очередь Controls банка 1 с сохранением регистров и возвратом страницы 10
                ; исходная запись 17, файловые смещения #027D..#0290
                ; In:
                ;   HL сохраняется, DE задаёт HighKind и LowValue записи, BC и AF сохраняются
                ;   paging не заблокирован, банк 1 содержит Controls, его очередь и курсор удовлетворяют договору QueueTextItem
                ;   код обёртки и SelectMemoryPage находятся ниже C000 и доступны при обоих значениях страницы
                ;   на стеке внешний возврат, доступны четырнадцать дополнительных байтов ниже входного SP, вмешательство ISR не входит в договор
                ; Out:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, I, IM и IFF сохраняются
                ;   OUT 7FFD получает 11, реальный Controls.QueueTextItem исполняется в банке 1, затем OUT 7FFD получает 10
                ;   на выходе выбрана полная страница 10, прежнее значение paging не восстанавливается
                ;   очередь обновлена либо молча отклонила запись, регистры не являются признаком приёма
                ;   SP после внешнего RET равен входному SP+2, собственная рамка описана FActionTextQueueFrame
                ; Corrupt:
                ;   paging, очередь и курсор банка 1 при успехе, четырнадцать байтов временного стека, R
                ; Note:
                ;   собственный PUSH AF, PUSH BC, PUSH HL отличается по порядку от внутренней рамки QueueTextItem
                ;   RET по 6053 завершает обёртку, соседний блок Unknown6054 не является её продолжением
                ;   D=02 означает число, D>=03 старший байт адреса строки, D=00 и D=01 производитель не проверяет
                ; -----------------------------------------
                ; сохранение собственных AF, BC и HL до переключения банка
Entry:          PUSH AF
                PUSH BC
                PUSH HL
                ; выбор Controls в банке 1 без изменения передаваемого DE
                LD A, @ActionBankPage.Controls
                CALL @Action.SelectMemoryPage.Entry
                ; передача DE в настоящий производитель очереди выбранного банка 1
                CALL @Controls.QueueTextItem.Entry
                ; фиксированный возврат полной страницы 10 до восстановления сохранённых регистров
                LD A, @ActionBankPage.Runtime
                CALL @Action.SelectMemoryPage.Entry
                ; восстановление HL, BC и AF из собственной рамки обёртки
                POP HL
                POP BC
                POP AF
                RET

                endmodule
                endmodule
