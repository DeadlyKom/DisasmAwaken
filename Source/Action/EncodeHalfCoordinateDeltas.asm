                module Action
                module EncodeHalfCoordinateDeltas
                ; Документация [алгоритм и проверка](../../Docs/ActionHalfDeltaCodes.md)
                ; -----------------------------------------
                ; Два кода по трём разностям половинных координат и корню усечённых квадратов
                ; исходная запись 17, фиксированное окно 8000..BFFF, физический банк 2, смещения #4D5A..#4DB6
                ; In:
                ;   HL=Left0, DE=Right0, BC=Right1, AF аргументов не задаёт
                ;   HL'=Left1, DE'=Left2, BC'=Right2, AF' аргументов не задаёт, все шесть координат являются signed16
                ;   ACTION и MultiplySigned16 загружены в банк 0, полное входное значение 7FFD равно 00, 08, 10 либо 18
                ;   таблицы логарифмов, обратная таблица и исходные коды отношения подготовлены, кэш корня находится в банке 1
                ;   CPU-стек расположен в общей RAM, не пересекает код, таблицы и рабочие поля, 14 байтов ниже внешнего возврата доступны
                ;   повторный вход и вмешательство IRQ исключены, действуют договоры дочерних процедур
                ; Out:
                ;   HL и DE возвращаются от второго EncodeSignedRatio с аргументами d1 и d0, формулы d приведены в документации
                ;   BC - B=(abs(signed8(первый код))+80) AND FF, C=второй код, первый код вычисляется от слова root*256 и d2
                ;   AF возвращается от второго EncodeSignedRatio с аргументами d1 и d0
                ;   HL'=d2 по модулю слова, DE'=входной HL', BC'=арифметическая половина входного BC'
                ;   AF' возвращается от второго кодировщика
                ;   IX, IY, I, IM и IFF сохраняются, SP=входной SP+2
                ;   в порт 7FFD выданы 11 и 10, итоговая конфигурация равна 10, входная конфигурация полностью не восстанавливается
                ;   R получает 99+2*negCode+Sq0+Sq1+Root+Code0+Code1 M1, бит 7 R сохраняется
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', R, до 14 байтов CPU-стека и изменяемые сдвиги делителя, 7FFD
                ; Note:
                ;   полные M1 всех 613638 исполнений сверены без потери кратных 128 в R, охвачены все 256 начальных R
                ;   наблюдавшиеся 332..876 M1 относятся к проверенной серии, не объявляются общими минимумом и максимумом всех шести слов
                ;   каждый операнд сначала арифметически делится на два, затем вычитается, это не арифметическая половина полной разности
                ;   negCode равен 1 при отрицательном первом signed8 коде до его модуля, иначе 0, Sq0/Sq1 обозначают M1 квадратов d0/d1 в MultiplySigned16
                ;   Root обозначает M1 SqrtWordCached без банковой обёртки, Code0/Code1 обозначают M1 двух EncodeSignedRatio, все стоимости включают собственный RET
                ;   постоянные 99 M1 уже включают 22 M1 обёртки SqrtWordBank1, повторно прибавлять переключения страниц не нужно
                ;   d0=half(Left0)-half(Right0), d1=half(Left1)-half(Right1), d2=half(Left2)-half(Right2), каждый лежит в -32767..32767
                ;   в корень поступает floor(d0*d0/65536)+floor(d1*d1/65536), не больше 7FFE, верхние ошибочные строки кэша недостижимы
                ;   исключение второго операнда MultiplySigned16=8000 здесь недостижимо, обе копии каждой разности строго больше -32768
                ;   слово root*256 может быть отрицательным signed16 при root>=128, исходная интерпретация кодировщика сохранена
                ;   613638 сценариев исполнили настоящие произведения, банковый корень и оба кодировщика, сопоставлены все регистры включая R, восемь банков RAM, OUT и кратность записей
                ;   полное произведение шести слов, аппаратный порядок записи слов, IRQ, точные T, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; Сохранение исходного IX, полное ядро произведения может менять IX до его восстановления в конце.
Entry:          PUSH IX
                ; Расчёт арифметических половин Left0 и Right0 до вычитания.
                SRA H
                RR L
                SRA D
                RR E
                ; Расчёт d0 с очищенным Carry, разность двух половин не выходит за signed16.
                OR A
                SBC HL, DE
                ; Сохранение d0 и исходного Right1 на динамическом CPU-стеке.
                PUSH HL
                PUSH BC
                ; Расчёт первого квадрата через настоящий MultiplySigned16, оба аргумента равны d0.
                LD D, H
                LD E, L
                CALL @Action.MultiplySigned16.Entry
                ; Сохранение старшего слова первого квадрата в DE, его младшее слово больше не используется.
                EX DE, HL
                POP BC
                ; Перенос исходного Left1 из альтернативного HL через временный PUSH и POP.
                EXX
                PUSH HL
                EXX
                POP HL
                ; Расчёт половин Left1 и Right1, BC после этого содержит половину Right1.
                SRA H
                RR L
                SRA B
                RR C
                ; Расчёт d1 с независимым очищенным Carry.
                OR A
                SBC HL, BC
                ; Сохранение d1 и старшего слова первого квадрата перед вторым произведением.
                PUSH HL
                PUSH DE
                ; Расчёт второго квадрата из двух равных d1, исключение операнда 8000 недостижимо.
                LD D, H
                LD E, L
                CALL @Action.MultiplySigned16.Entry
                POP DE
                ; Расчёт суммы только двух старших слов квадратов, переносы отброшенных младших слов не добавляются.
                ADD HL, DE
                EX DE, HL
                ; Расчёт банкового корня, в SelectMemoryPage физическая вершина рамки соответствует FDeltaCodeRootFrame.
                CALL @Action.SqrtWordBank1.Entry
                ; Преобразование корня в слово с нулевым младшим байтом, при root>=128 это отрицательное signed16.
                LD H, A
                LD L, #00
                ; Сохранение слова корня и выбор альтернативных Left2 и Right2.
                PUSH HL
                EXX
                EX DE, HL
                ; Расчёт арифметических половин Left2 и Right2.
                SRA H
                RR L
                SRA B
                RR C
                ; Расчёт d2 с очищенным Carry и сохранение его для первого кодировщика.
                OR A
                SBC HL, BC
                PUSH HL
                EXX
                ; Восстановление аргументов первого кодировщика, HL=root*256, DE=d2.
                POP DE
                POP HL
                ; Расчёт первого исходного кода, внутри делителя его рамка соответствует FDeltaCodeFirstFrame.
                CALL @Action.EncodeSignedRatio.Entry
                ; Проверка знака самого байта кода через OR A, флаги кодировщика для этого не используются.
                OR A
                JP P, @Action.EncodeHalfCoordinateDeltas.SaveFirstCode          ; переход, если первый код неотрицателен как signed8, сохранить его без NEG

                ; Расчёт модуля отрицательного первого кода по исходной байтовой инструкции NEG.
                NEG
                ; Восстановление d1 и d0 для второго кодировщика, исходный IX пока остаётся на стеке.
SaveFirstCode:  POP HL
                POP DE
                ; Расчёт первого выходного байта B, прибавление 80 к модулю первого кода.
                ADD A, @ActionRatioCodeConst.HalfCode
                ; Сохранение будущего B и флагов сложения на время второго кодировщика.
                PUSH AF
                ; Расчёт второго исходного кода из d1 и d0, внутри делителя действует FDeltaCodeSecondFrame.
                CALL @Action.EncodeSignedRatio.Entry
                ; Восстановление B из сохранённого AF и замена C вторым кодом A.
                POP BC
                LD C, A
                ; Восстановление исходного IX после обоих произведений и кодировщиков.
                POP IX
                RET

                endmodule
                endmodule
