                module Action
                module WrapPolygonLeftTop
                ; Документация [алгоритм и проверка](../../Docs/ActionPolygonWrapLeftTop.md)
                ; -----------------------------------------
                ; Оборачивание поиска левого конца верхней горизонтали
                ; исходная запись 17, адреса D503..D509
                ; In:
                ;   HL содержит страницу 90, обратный верхний поиск достиг нулевого младшего индекса
                ;   AF содержит минимальную First, альтернативный A содержит последний нечётный индекс списка
                ; Out:
                ;   HL сохраняет H, L=(входной альтернативный A+1) AND #FF
                ;   DE и BC сохраняются
                ;   AF сохраняет A и входной Carry, остальные биты F равны результату INC L, N=0
                ;   HL', DE', BC', AF' сохраняются
                ;   IX и IY сохраняются, SP, I, IM, IFF и paging сохраняются
                ;   управление передано PreparePolygonFill.ReadLeftTop, память и порты не записываются
                ;   R добавляет 5 M1, бит 7 R сохраняется
                ; Corrupt:
                ;   HL, только L, AF, только F, R
                ; Note:
                ;   короткий переходник сохраняет исходные адреса и инструкции, новый адрес возврата не создаётся
                ;   проверены точные регистры включая R и отсутствие записей RAM, полное игровое исполнение этим не доказывается
                ;   точные T, IRQ, сборка и нативный запуск не проверены
                ; -----------------------------------------
                ; Выбор последнего нечётного индекса из альтернативного A с восстановлением обоих AF.
Entry:          EX AF, AF'
                LD L, A
                EX AF, AF'
                ; Расчёт промежуточного индекса LastIndex+1 перед следующим DEC L основного поиска.
                INC L
                JP @Action.PreparePolygonFill.ReadLeftTop

                endmodule
                endmodule
