                module Action
                module CheckLinkedTargetTransition
                ; Документация [алгоритм и проверка](../../Docs/ActionTargetTransition.md)
                ; -----------------------------------------
                ; Проверка допуска к выбору связанной записи либо перехода к фазовому ожиданию
                ; исходная запись 17, адреса E91E..E934
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, IX указывает доступную FActionRecord
                ;   действуют договоры CheckCandidateListReady, FindNearestListedRecord и CheckObjectPhaseTransition
                ;   из R читается реальное значение после двух M1 инструкции LD A,R, от этого значения зависит допуск
                ;   ACTION банка 0 выбран, восемь дополнительных байтов CPU-стека доступны, IRQ и повторный вход исключены
                ; Out:
                ;   DE и BC сохраняются на всех путях
                ;   если прочитанный R меньше 64, хвостом выполняется CheckObjectPhaseTransition с исходным внешним возвратом
                ;   при R>=64 вызывается CheckCandidateListReady, Z также передаёт исполнение хвостом CheckObjectPhaseTransition
                ;   при NZ допуска исполняется FindNearestListedRecord, затем StateCode=0E, LinkedIndex=A результата выбора и Carry=1
                ;   на пути StateCode=0E HL указывает FE, DE и BC сохраняются, A равен записанному LinkedIndex, F=41 OR (A AND 28)
                ;   на пути фазовой проверки регистры, состояние потока 5 и условные поля определяются CheckObjectPhaseTransition
                ;   Carry установлен также при успешном фазовом переходе 14, его нельзя трактовать как признак найденного кандидата
                ;   при списке только недоступных записей LinkedIndex получает прежний ChosenIndex, путь StateCode=0E всё равно выполнен
                ;   AF', IX, I/IM/IFF и paging сохраняются, BC' сохраняется на пути выбора цели, прочие альтернативные регистры зависят от вызванных детей
                ;   SP после внешнего RET увеличен на два, внешний возврат сохраняется, максимальная дополнительная рамка равна восьми байтам
                ;   R на фазовом пути добавляет к стоимости хвоста 4 M1 для раннего допуска либо 6 плюс стоимость CheckCandidateListReady
                ;   R на пути выбора добавляет 13 M1 к сумме стоимостей CheckCandidateListReady и FindNearestListedRecord
                ; Corrupt:
                ;   HL, AF, HL', DE', BC', IY, R, условные поля текущей записи, список, операнды выбора и поток 5 по договорам детей, до восьми байтов CPU-стека, SP внешним RET
                ; Note:
                ;   R зависит от M1 и его бит 7 сохраняется, значение не заменяется равномерной случайной величиной
                ;   успех допуска списка не доказывает доступность его индексов, старый результат выбора на этом пути исходно сохраняется
                ;   67072 сценария охватили все пары начального R и полного класса и все прежние результаты для шести допущенных классов при недоступном кандидате
                ;   проверены реальные дети, точные регистры, флаги, R, восемь банков и все записи, полный игровой кадр не исполнялся
                ;   полное произведение входов, аппаратные IRQ, точные T, сборка и нативный запуск не выполнялись
                ; -----------------------------------------
                ; Проверка реального R после двух M1 инструкции LD A,R, без предположения равномерного распределения.
Entry:          LD A, R
                CP @ActionTargetTransitionConst.RefreshMin
                JR C, @Action.CheckObjectPhaseTransition.Entry                  ; переход, если прочитанный R меньше 64, выполнить хвостовую проверку фазового перехода

                ; Проверка разрешённого класса и наличия непропущенного байта в списке кандидатов.
                CALL @Action.CheckCandidateListReady.Entry
                JR Z, @Action.CheckObjectPhaseTransition.Entry                  ; переход, если класс запрещён либо достигнут FE, выполнить хвостовую проверку фазового перехода

                ; Поиск минимального расстояния, без доступного кандидата возвращается прежний ChosenIndex.
                CALL @Action.FindNearestListedRecord.Entry
                ; Обновление состояния и связанного индекса независимо от наличия нового улучшения в выборе.
                LD (IX + @FActionRecord.StateCode), @ActionTargetTransitionConst.LinkedState
                LD (IX + @FActionRecord.LinkedIndex), A
                ; Установка Carry для этого пути, успешный фазовый переход в другом хвосте также возвращает Carry.
                SCF
                RET

                endmodule
                endmodule
