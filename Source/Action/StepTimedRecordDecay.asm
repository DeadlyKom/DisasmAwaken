                module Action
                module StepTimedRecordDecay
                ; Документация [алгоритм и проверка](../../Docs/ActionTimedDecayState.md)
                ; -----------------------------------------
                ; Декремент времени состояния, освобождение при истечении и деление управляющего байта на два
                ; исходная запись 17, адреса F66A..F67E
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, IX указывает доступную FActionRecord
                ;   Unknown11 счётчик этого состояния, Unknown10 управляющий байт затухания, доступные поля освобождения имеют договор MarkRecordForReuse
                ;   ACTION банка 0 доступен, внешний возврат сохранён в CPU-стеке, IRQ не вмешиваются
                ; Out:
                ;   Unknown11 уменьшается на один по модулю 256, начальный ноль становится FF и не освобождает запись
                ;   только при начальном Unknown11=1 выполняется MarkRecordForReuse с внешним RET, A сохраняется, F от DEC счётчика с входным Carry
                ;   при новом ненулевом счётчике и Unknown10=0 поле сохраняется, AF=0054 и достигнут F0F8
                ;   при новом ненулевом счётчике и Unknown10!=0 поле получает его беззнаковую половину, A равен половине, F от SRL исходного байта
                ;   HL, DE, BC, HL', DE', BC', AF', IX, IY, I/IM/IFF и paging сохраняются
                ;   SP увеличен на два только при освобождении, на остальных путях SP сохранён и PC=F0F8
                ;   R добавляет 10 M1 при освобождении, 7 при сохранённом нулевом Unknown10 и 12 при делении, временных записей CPU-стека нет
                ; Corrupt:
                ;   AF, R, Unknown11, условно Unknown10 либо Component0 и ReuseByte текущей записи, SP только внешним RET при освобождении
                ; Note:
                ;   это исходная цель State07, значения 10 и 11 не объявляются универсальными полями времени для других состояний
                ;   131072 сценария исчерпывают произведение обоих входных байтов и Carry, точные регистры, флаги, R, восемь банков и записи проверены
                ;   MarkRecordForReuse исполнен реально, общий F0F8 не исполнялся, аппаратные IRQ, сборка и нативный запуск не выполнялись
                ; -----------------------------------------
                ; Обновление счётчика состояния по модулю 256, истечение наступает только при исходной единице.
Entry:          DEC (IX + @FActionRecord.Unknown11)
                JP Z, @Action.MarkRecordForReuse.Entry                          ; переход, если после декремента Unknown11 равен нулю, освободить текущую запись с внешним RET

                ; Проверка управляющего байта перед беззнаковым затуханием.
                LD A, (IX + @FActionRecord.Unknown10)
                AND A
                JP Z, @Action.PrepareObjectOffsetTransform.Entry                ; переход, если Unknown10 равен нулю, сохранить его и продолжить общий хвост

                ; Расчёт целой половины Unknown10, его прежний младший бит становится Carry.
                SRL A
                ; Обновление управляющего байта рассчитанной половиной.
                LD (IX + @FActionRecord.Unknown10), A
                JP @Action.PrepareObjectOffsetTransform.Entry

                endmodule
                endmodule
