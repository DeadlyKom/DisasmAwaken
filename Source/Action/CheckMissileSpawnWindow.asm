                module Action
                module CheckMissileSpawnWindow
                ; Документация [алгоритм и проверка](../../Docs/ActionSpawnWindow.md)
                ; -----------------------------------------
                ; Проверка случайного окна создания ракеты и загрузка байта допуска по полному классу
                ; исходная запись 17, адреса F222..F24E
                ; In:
                ;   H задаёт старший байт случайного слова, DE и BC числовых аргументов не задают, A задаёт проверяемый младший байт
                ;   IX указывает текущую FActionRecord с ClassCode, MissileRepeatDelay и входами CreateMissileFromCurrentLink
                ;   действуют договоры общего создателя, доступны реальные байты F280+ClassCode, таблица индексируется без проверки верхней границы
                ;   ACTION банка 0 и перенесённый общий код банка 5 доступны, восемь дополнительных байтов CPU-стека доступны, IRQ исключены
                ;   читается Component0.High, для активной записи доступны остальные фазовые поля, класс, состояние и порог
                ;   OffsetScaleLow и OffsetScaleHigh активной записи доступны для записи, ACTION банка 0 и общая RAM доступны
                ;   действует договор ApplyObjectOffsetVector, шесть байтов под SP и внешний возврат не перекрывают его код, таблицы, операнды и результаты
                ;   IRQ и повторный вход исключены
                ;   для исходных числовых постусловий записи обратной связи создателя не должны менять исполняемый вычислитель, таблицы и внешний возврат
                ; Out:
                ;   если A не равен F0, H меньше 5F, ClassCode равен 9 либо MissileRepeatDelay ненулевой, создание пропускается
                ;   после всех допусков выполняется CreateMissileFromCurrentLink независимо от наличия свободного слота
                ;   после попытки создания MissileRepeatDelay получает байт по F280+текущий полный ClassCode, даже при отказе выделения
                ;   перед F0F8 на пути попытки HL указывает выбранный байт, DE определён результатом создателя, BC равен полному классу, A прочитанный байт
                ;   перед F0F8 F после попытки определяется ADD HL,BC с сохранением S/Z/PV от создателя, ранние F соответствуют последней проверке
                ;   перед F0F8 альтернативные пары и IY определяются достигнутым создателем, IX, I/IM/IFF и paging сохраняются
                ;   общий хвост исполняется на всех путях, после попытки создания он читает уже обновлённую запись
                ;   при итоговом Component0.High=80 общий хвост даёт AF=8042, остальные регистры сохраняют результаты префикса, его записи не откатываются, R добавляет четыре M1
                ;   на активной ветви нижеследующие результаты вычислителя относятся к V из прежнего OffsetScaleLow и выбранного старшего байта
                ;   HL=(-Q) AND FFFF при бите 7 S=1, иначе HL=Q, DE=Q при бите 7 S=1, иначе DE=abs(V)
                ;   BC - B=W[Offset0], C=0
                ;   AF - A=S, F от 16-разрядного 0-Q при бите 7 S=1, иначе флаги логического XOR с результатом S
                ;   HL', DE', BC' сохраняют результат создателя, без его вызова исходные значения
                ;   AF' - A'=U, F'=(U AND 28) OR (40 при U=0) OR (10 при 2*((P SHR 16) AND 0F)+(U AND 1)>0F), остальные биты F' нулевые
                ;   IX восстановлен, IYH сохраняет результат создателя либо исходное значение без вызова, IYL=W[(Offset1+64) AND FF]
                ;   Coefficient0..2 содержат результат построителя, Base0..2 содержат три произведения с одним входным V
                ;   SP=входной SP+2, I, IM, IFF и paging сохраняются, порты не используются
                ;   Offset0..2 получают OffsetPhase0, wrap8(OffsetPhase1+80) и OffsetPhase2
                ;   OffsetScaleLow получает wrap8(старое+1), если этот кандидат ниже Phase2OrTarget, иначе сохраняется прежний байт
                ;   OffsetScaleHigh обнулён при ClassCode<10 и StateCode не равном 13, иначе сохранён
                ;   на активной ветви R учитывает 30+Hold+4*Small+2*Small*Different M1 подготовки плюс полный вычислитель, старший бит R сохраняется
                ;   на всех путях SP=входной SP+2, IX, I/IM/IFF и paging сохраняются, OUT отсутствует
                ;   на пути попытки собственный префикс добавляет 23 M1 плюс полный создатель, затем учитывается полный общий хвост, ранние пути учитывают только достигнутые проверки
                ;   максимальная временная рамка до восьми байтов, после возврата создателя общий вычислитель последовательно использует шесть байтов
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IY, R, эффекты создателя, MissileRepeatDelay, три фазовых операнда, Coefficient0..2, Base0..2, условно масштабы и до восьми временных байтов CPU-стека
                ; Note:
                ;   девять исходных табличных значений предназначены физическим индексам 0..8, но исходный код принимает все классы кроме 9
                ;   классы 0A..FF читают последующие физические байты, их ограничение либо расширение таблицы изменило бы игру
                ;   131072 сценария покрыли все пары A/H и все пары полного класса/MissileRepeatDelay, настоящий создатель исполнен до общего продолжения
                ;   прежняя серия заканчивается перед F0F8, новая серия 262144 случая исполняет весь путь до внешнего RET, каждый профиль проверен с активной и маркерной текущей записью
                ;   начальный LinkedIndex=2, фазы, масштабы и пределы связаны с A/H/классом, остальные индексы и все сочетания полей этой серией не проверены
                ;   сверены регистры кроме T, точный R, восемь банков, кратность присваиваний и отсутствие OUT
                ;   при выделении текущая запись сама может стать ребёнком, общий хвост проверяет её итоговые Components после копирования создателем
                ;   наложения обратной связи на код для произвольных индексов описаны в ActionSpawnContinue.md, их исходные числовые формулы требуют отдельного разбора
                ;   полное произведение входов, T, IRQ, сборка и нативная игра не доказаны
                ;   эффективное слово V перед 6D06 содержит прежний OffsetScaleLow в E и итоговый OffsetScaleHigh в D, это не входное DE всей процедуры
                ;   Hold=1 при сохранении прежнего младшего масштаба, иначе 0, Small=1 при ClassCode<10, Different=1 при StateCode не равном 13, иначе соответствующий признак нулевой
                ;   10, 13 и 80 в условиях полей обозначают шестнадцатеричные коды, числа M1 десятичные
                ;   c2 обозначает третий байтовый коэффициент, m=abs(s8(c2)) AND 7F, P=m*abs(V), Q=floor(P/128), U=P SHR 15, S=c2 XOR HIGH слова V
                ;   нулевой фактор для коэффициента 80 сохранён, знак определяется исходным байтом коэффициента и старшим байтом V
                ;   каждое Base равно -floor((abs(s8(c_i)) AND 7F)*abs(V)/128) при бите 7 c_i XOR HIGH V, иначе положительному частному, всё по модулю 65536
                ;   шесть временных байтов после возврата содержат исходный IX по SP-2, слово V по SP-4 и внутренний возврат 6D0C по SP-6, POP не очищает RAM
                ;   для фактора m>0 умножение даёт 35+floor(log2(m))+2*popcount(m) M1, при m=0 даёт 32 M1
                ;   к каждому умножению добавляются семь M1 при V<0, две при бите 7 коэффициента и четыре при бите 7 его XOR HIGH V
                ; -----------------------------------------
                ; Проверка точного младшего байта случайного слова перед остальными допусками создания.
Entry:          CP #F0
                JP NZ, @Action.PrepareObjectOffsetTransform.Entry               ; переход, если A не равен F0, сохранить MissileRepeatDelay и продолжить общий расчёт

                ; Проверка нижней границы старшего байта случайного слова.
                LD A, H
                CP #5F
                JP C, @Action.PrepareObjectOffsetTransform.Entry                ; переход, если H меньше 5F, сохранить MissileRepeatDelay и продолжить общий расчёт

                ; Проверка исключённого полного класса 9 без маскирования старшего бита.
                LD A, (IX + @FActionRecord.ClassCode)
                CP #09
                JP Z, @Action.PrepareObjectOffsetTransform.Entry                ; переход, если ClassCode равен 9, пропустить создание

                ; Проверка нулевого MissileRepeatDelay перед попыткой выделения связанного ребёнка.
                LD A, (IX + @FActionRecord.MissileRepeatDelay)
                AND A
                JP NZ, @Action.PrepareObjectOffsetTransform.Entry               ; переход, если MissileRepeatDelay ненулевой, пропустить создание

                ; Создание класса 17 из Components и LinkedIndex текущей записи, отказ по слотам не отменяет следующий шаг.
                CALL @Action.CreateMissileFromCurrentLink.Entry
                ; Расчёт адреса исходного байта допуска по полному классу без ограничения девятью табличными элементами.
                LD C, (IX + @FActionRecord.ClassCode)
                LD B, #00
                LD HL, @ActionClassSpawnValues.Class0.Counter
                ADD HL, BC
                ; Обновление MissileRepeatDelay прочитанным физическим байтом даже после неудачного выделения.
                LD A, (HL)
                LD (IX + @FActionRecord.MissileRepeatDelay), A
                JP @Action.PrepareObjectOffsetTransform.Entry

                endmodule
                endmodule
