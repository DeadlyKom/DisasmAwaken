                module Action
                module MaxFoldedVectorHigh
                ; Документация [алгоритм и проверка](../../Docs/ActionVectorHighMaximum.md)
                ; -----------------------------------------
                ; Максимум трёх старших байтов с дополнением отрицательных кодов через CPL
                ; исходная запись 17, перенесённое ядро 6000..7F8E, смещения #0BD9..#0BFA
                ; In:
                ;   HL задаёт сохраняемый H, входной L не используется, DE и BC сохраняются, AF аргументов не задаёт
                ;   High0, High1 и High2 доступны для чтения в общей RAM ACTION, каждый является полным байтом 0..FF
                ;   на CPU-стеке внешний возврат, прерывания не вмешиваются
                ; Out:
                ;   H сохраняется, L=max(f(High0), f(High1), f(High2)), где f(b)=b при b<80, иначе b XOR FF
                ;   DE и BC сохраняются, A=f(High2), F от сравнения A с max(f(High0), f(High1)) до возможной записи нового L
                ;   HL', DE', BC', AF', IX, IY сохраняются, I, IM, IFF и страница сохраняются
                ;   SP=входной SP+2, RAM и CPU-стек не записываются, точная формула 15..20 M1 приведена в документации, бит 7 R сохранён
                ; Corrupt:
                ;   L, AF, R
                ; Note:
                ;   отрицательный код сворачивается через CPL, не NEG, FF даёт 0, 80 даёт 7F
                ;   нижние шестнадцать разрядов трёх рабочих компонент не читаются, точный модуль полного числа этим не вычисляется
                ;   все 16777216 сочетаний трёх байтов проверены независимо через математический максимум и отдельные формулы флагов
                ;   сопоставлены все регистры включая R, записи памяти отсутствовали в каждом сценарии, итоговые восемь банков совпали с входной фикстурой
                ;   глобальные игровые единицы и роль результата, IRQ, точные T, сборка и нативное исполнение не доказаны
                ; -----------------------------------------
                ; Чтение первого старшего байта, его свёрнутый код задаёт начальный максимум.
Entry:          LD A, (@ActionVectorHighMaximumState.High0)
                ; Проверка знака первого полного байта перед дополнением.
                OR A
                JP P, @Action.MaxFoldedVectorHigh.StoreFirst                    ; переход, если High0 неотрицателен, сохранить его без CPL

                ; Преобразование отрицательного кода через CPL без прибавления единицы.
                CPL
StoreFirst:     LD L, A
                LD A, (@ActionVectorHighMaximumState.High1)
                ; Проверка знака второго старшего байта.
                OR A
                JP P, @Action.MaxFoldedVectorHigh.CompareSecond                 ; переход, если High1 неотрицателен, сравнить его без CPL

                CPL
                ; Проверка обновления максимума по второму свёрнутому коду.
CompareSecond:  CP L
                JR C, @Action.MaxFoldedVectorHigh.ReadThird                     ; переход, если свёрнутый High1 меньше текущего максимума, сохранить L и читать High2

                LD L, A
ReadThird:      LD A, (@ActionVectorHighMaximumState.High2)
                ; Проверка знака третьего старшего байта.
                OR A
                JP P, @Action.MaxFoldedVectorHigh.CompareThird                  ; переход, если High2 неотрицателен, сравнить его без CPL

                CPL
                ; Проверка последнего обновления максимума, флаги этого сравнения остаются выходными.
CompareThird:   CP L
                JR C, @Action.MaxFoldedVectorHigh.ReturnMaximum                 ; переход, если свёрнутый High2 меньше текущего максимума, вернуть прежний L

                LD L, A
ReturnMaximum:  RET

                endmodule
                endmodule
