                module AbortProjectedVertexScan
                ; Документация [алгоритм и проверка](../../Docs/ActionVertexAbort.md)
                ; -----------------------------------------
                ; Завершение сканирования точек по маркеру отказа перспективы без отката предыдущих кодов
                ; исходная запись 17, адреса DEF0..DEF2
                ; In:
                ;   SP указывает на сохранённое слово HL сканера, сразу за ним находится внешний адрес возврата
                ;   вход является общим хвостом ClassifyProjectedVertices, прямой CALL с обычной рамкой не соответствует договору
                ; Out:
                ;   HL восстановлен из служебного слова, DE, BC и альтернативный набор сохранены
                ;   A=0, F=44, Z установлен, IX и IY сохраняются, SP после RET равен входному SP+4
                ;   I, IM, IFF и paging сохраняются, R меняется, ранее записанные коды точек остаются в RAM
                ; Corrupt:
                ;   HL, AF, SP и R
                ; Note:
                ;   RAM не записывается, POP HL снимает служебное слово, RET снимает внешний возврат
                ;   хвост реально достигнут в 2228 из 525288 сценариев общего сканера, отдельная независимая серия для произвольной рамки не заявляется
                ;   возврат нуля означает найденный маркер перспективы 80xx, а не очистку накопленных данных
                ; -----------------------------------------
                ; -----------------------------------------
                ; Отказ всего прохода
                ; Восстановление HL со служебного CPU-стека, коды предыдущих точек не откатываются.
Entry:          POP HL
                ; Возврат нуля и Z как признака маркера 80xx, альтернативный накопитель остаётся неизменным.
                XOR A
                RET

                endmodule
