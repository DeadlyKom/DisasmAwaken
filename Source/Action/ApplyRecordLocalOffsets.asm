                module Action
                module ApplyRecordLocalOffsets
                ; Документация [алгоритм и проверка](../../Docs/ActionLocalOffsets.md)
                ; -----------------------------------------
                ; Увеличение фазового индекса и расчёт баз по отдельным фазам из байтов 0D..0F записи
                ; исходная запись 17, адреса F6CD..F6EB
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, IX указывает доступную FActionRecord
                ;   Phase0OrLink, LocalPhase1, Phase2OrTarget и OffsetScaleLow читаемы, OffsetPhase0 доступен для записи
                ;   действует договор ApplyObjectOffsetVector, ACTION банка 0 выбран, исходные фазовые таблицы доступны
                ;   шесть байтов под SP и внешний возврат не перекрывают код, поля записи, таблицы, операнды и результаты, IRQ и повторный вход исключены
                ; Out:
                ;   нижеследующие результаты вычислителя относятся к V=zero_extend(OffsetScaleLow), исходные HL/DE/BC/AF входа числовых аргументов не задают
                ;   HL=(-Q) AND FFFF при бите 7 S=1, иначе HL=Q, DE=Q при бите 7 S=1, иначе DE=abs(V)
                ;   BC - B=W[Offset0], C=0
                ;   AF - A=S, F от 16-разрядного 0-Q при бите 7 S=1, иначе флаги логического XOR с результатом S
                ;   HL', DE', BC' сохраняются
                ;   AF' - A'=U, F'=(U AND 28) OR (40 при U=0) OR (10 при 2*((P SHR 16) AND 0F)+(U AND 1)>0F), остальные биты F' нулевые
                ;   IX восстановлен, IYH сохраняется, IYL=W[(Offset1+64) AND FF]
                ;   Coefficient0..2 содержат результат построителя, Base0..2 содержат три произведения с одним входным V
                ;   SP=входной SP+2, I, IM, IFF и paging сохраняются, порты не используются
                ;   OffsetPhase0 увеличен на один по модулю 256, это значение не является первой фазой текущего вызова
                ;   Offset0..2 получают Phase0OrLink, wrap8(LocalPhase1+80) и Phase2OrTarget
                ;   OffsetScaleLow и OffsetScaleHigh сохраняются, Component0.High не проверяется
                ;   R добавляет 16 M1 к полному ApplyObjectOffsetVector, максимальная дополнительная рамка равна шести байтам
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', IYL, R, Coefficient0..2, Base0..2 и шесть временных байтов CPU-стека, OffsetPhase0 и три фазовых операнда
                ; Note:
                ;   эффективное слово V перед вычислителем имеет D=00 и E=OffsetScaleLow, поэтому оно беззнаковое 0..255
                ;   Phase2OrTarget здесь используется как фазовый индекс, его роли цели и предела других обработчиков не переопределяются
                ;   80 в поправке второй фазы шестнадцатеричное, это десятичный полупериод 128
                ;   c2 обозначает третий байтовый коэффициент, m=abs(s8(c2)) AND 7F, P=m*abs(V), Q=floor(P/128), U=P SHR 15, S=c2 XOR HIGH слова V
                ;   нулевой фактор для коэффициента 80 сохранён, знак определяется исходным байтом коэффициента и старшим байтом V
                ;   каждое Base равно -floor((abs(s8(c_i)) AND 7F)*abs(V)/128) при бите 7 c_i XOR HIGH V, иначе положительному частному, всё по модулю 65536
                ;   шесть временных байтов после возврата содержат исходный IX по SP-2, слово V по SP-4 и внутренний возврат 6D0C по SP-6, POP не очищает RAM
                ;   для фактора m>0 умножение даёт 35+floor(log2(m))+2*popcount(m) M1, при m=0 даёт 32 M1
                ;   к каждому умножению добавляются семь M1 при V<0, две при бите 7 коэффициента и четыре при бите 7 его XOR HIGH V
                ;   65536 сценариев этого входа входят в существующие 131072, реальные коэффициенты и три умножителя исполняются до полного RET
                ;   точные регистры, R, восемь банков и записи ранее проверены, новый числовой прогон ради уточнения договора не объявляется
                ;   полное произведение входов, точные T, IRQ и нативная игра не доказаны
                ; -----------------------------------------
                ; Обновление OffsetPhase0 по модулю 256, фазы текущего расчёта читаются отдельно из 0D..0F.
Entry:          INC (IX + @FActionRecord.OffsetPhase0)
                ; Подготовка первой фазы из Phase0OrLink, увеличенный OffsetPhase0 здесь не читается.
                LD A, (IX + @FActionRecord.Phase0OrLink)
                LD (@ActionObjectOffsetTransferState.Offset0), A
                ; Расчёт второй фазы из LocalPhase1 с полупериодом 128 по модулю байта.
                LD A, (IX + @FActionRecord.LocalPhase1)
                ADD A, #80
                LD (@ActionObjectOffsetTransferState.Offset1), A
                ; Подготовка третьей фазы из физического байта Phase2OrTarget, в этом состоянии он не разыменовывается как индекс записи.
                LD A, (IX + @FActionRecord.Phase2OrTarget)
                LD (@ActionObjectOffsetTransferState.Offset2), A
                ; Подготовка неотрицательного масштаба с D=00 и E=OffsetScaleLow без изменения исходного байта.
                LD E, (IX + @FActionRecord.OffsetScaleLow)
                LD D, #00
                ; Расчёт коэффициентов и трёх базовых слов с исходным внешним возвратом.
                JP @Action.ApplyObjectOffsetVector.Entry

                endmodule
                endmodule
