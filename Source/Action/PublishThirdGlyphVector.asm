                module Action
                module PublishThirdGlyphVector
                ; Документация [алгоритм и проверка](../../Docs/ActionThirdGlyphPublish.md)
                ; -----------------------------------------
                ; Перенос четвертей двух выходных слов и знакового байта третьего слова во вход третьего экранного знака
                ; исходная запись 17, перенесённый ACTION фиксированного банка 5, смещения #0EF1..#0F12
                ; In:
                ;   HL, DE и BC числовых аргументов не задают, DE и BC сохраняются
                ;   при входном P/V=0 Output0, Output1 и Output2 содержат выходные слова ComputePatchedVector в выбранном банке 0
                ;   входной P/V=1 означает отказ вычислителя по переполнению и запрещает публикацию, остальные входные флаги на расчёт не влияют
                ;   ActionGlyphIndicatorState.Third доступен для записи, CPU SP восстановлен и содержит внешний возврат, IRQ не вмешивается
                ; Out:
                ;   при входном P/V=1 HL, DE, BC и AF сохранены, три поля Third не меняются
                ;   при входном P/V=0 Third.X=LOW(signed16(Output0)//4), Third.Y=LOW(signed16(Output1)//4), Third.SignSource=HIGH(Output2)
                ;   при публикации H=LOW(signed8(HIGH(Output1))//4), L=LOW(Output1), DE и BC сохранены, A=HIGH(Output2)
                ;   F после публикации содержит S/Z/P от сдвинутого H, биты 5/3 от нового Third.Y, Carry от бита 1 LOW(Output1), H/N сброшены
                ;   HL', DE', BC', AF', IX и IY, I/IM/IFF и paging сохраняются, SP после RET равен входному SP+2
                ;   R получает один M1 при отказе и 22 M1 при публикации, бит 7 сохраняется, CPU-стек не записывается
                ; Corrupt:
                ;   HL и AF только при публикации, R и три байта Third только при публикации
                ; Note:
                ;   (1) жёсткий порядок, сюда продолжается часть (0) RestoreThirdGlyphStack.asm после восстановления CPU SP
                ;   деление знаковое с округлением вниз, затем сохраняется только младший байт, насыщения и ограничения экранного диапазона здесь нет
                ;   реальный потребитель Controls.UpdateGlyphIndicators ограничивает координаты и выбирает заполненную либо полую форму по SignSource
                ;   порядок публикации X, затем Y, затем SignSource, входное переполнение оставляет весь старый Third без изменения
                ;   после успешной публикации P/V отражает чётность сдвинутого H и не является итоговым флагом переполнения исходного вычислителя
                ;   65792 сценария проверили все слова каждого делимого поля и все входные F, регистры включая R, восемь банков RAM и точный порядок трёх записей
                ;   полное произведение трёх выходных слов, IRQ, точные T, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Допуск публикации результата
                ; Проверка входного P/V от арифметического вычислителя, старое состояние знака сохраняется при отказе.
Entry:          RET PE                                                          ; выход, если вычислитель сообщил знаковое переполнение, оставить прежние X, Y и SignSource

                ; -----------------------------------------
                ; Горизонтальный байт третьего знака
                ; Чтение Output0 и расчёт знаковой четверти, отрицательные нечётные слова округляются вниз.
                LD HL, (@ActionPatchedVectorState.Output0)
                LD A, L
                SRA H
                RRA
                SRA H
                RRA
                ; Обновление Third.X младшим байтом четверти, экранное ограничение выполняется позже потребителем.
                LD (@ActionGlyphIndicatorState.Third.X), A
                ; -----------------------------------------
                ; Вертикальный байт третьего знака
                ; Чтение Output1 и расчёт его знаковой четверти с тем же правилом округления.
                LD HL, (@ActionPatchedVectorState.Output1)
                LD A, L
                SRA H
                RRA
                SRA H
                RRA
                ; Обновление Third.Y, итоговый F описывает последнюю пару сдвигов, не окончательное значение A.
                LD (@ActionGlyphIndicatorState.Third.Y), A
                ; Чтение старшего байта Output2 для выбора формы третьего знака по его знаку.
                LD A, (@ActionPatchedVectorState.Output2+1)
                ; Обновление Third.SignSource, младший байт Output2 здесь не используется.
                LD (@ActionGlyphIndicatorState.Third.SignSource), A
                RET

                ; -----------------------------------------
                endmodule
                endmodule
