                module Action
                module SelectMemoryPage
                ; Документация [выбор страницы и активация параметров](../../Docs/ActionParameterActivation.md)
                ; -----------------------------------------
                ; Запись полного A в 7FFD с сохранением регистров и учётом блокировки
                ; исходная запись 17, общий код фиксированного банка 2, смещения #4B1B..#4B22
                ; In:
                ;   HL, DE и BC сохраняются, AF задаёт A как полный записываемый байт 7FFD, весь F сохраняется
                ;   сохранённый BC и внешний возврат находятся в сохраняющемся RAM-окне, рамка не перекрывает исполняемый код
                ;   на стеке внешний возврат, ещё два байта нужны для PUSH BC, IRQ не вмешиваются
                ; Out:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, I, IM и IFF сохраняются
                ;   в порт 7FFD выдан ровно один байт A, при исходной блокировке записи выбранное отображение не меняется
                ;   SP=входной SP+2, R получает 6 M1, два байта перед входным SP содержат исходные C и B
                ; Corrupt:
                ;   два байта CPU-стека, управление 7FFD при разрешённой записи, R
                ; Note:
                ;   теневая программная копия 7FFD не записывается, BC восстанавливается после настоящего OUT
                ;   значение на шине порта и результат аппаратного переключения различаются при установленном бите блокировки
                ;   поведение исходной блокировки проверено моделью банка, нативный запуск и IRQ этим не доказываются
                ; -----------------------------------------
                ; сохранение BC в общей RAM до изменения выбранного верхнего окна
Entry:          PUSH BC
                ; подготовка полного адреса порта 7FFD без изменения F
                LD BC, #7FFD
                ; выдача A на шину 7FFD, исходная аппаратная блокировка может сохранить прежнее отображение
                OUT (C), A
                ; восстановление BC из общей RAM без изменения AF
                POP BC
                RET

                endmodule
                endmodule
