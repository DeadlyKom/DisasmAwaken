                module Action
                module HandleClass18Proximity
                ; Документация [алгоритм и проверка](../../Docs/ActionClass18Proximity.md)
                ; -----------------------------------------
                ; Поиск записи класса 18, освобождение текущей при близости либо подвод фазовых кодов
                ; исходная запись 17, адреса F356..F36A
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, IX указывает текущую FActionRecord
                ;   для FindRecordByCode от A100 достижимы первая активная запись полного класса 12 либо маркер конца
                ;   Components, OffsetPhase1, OffsetPhase2, ReuseByte и TargetCodeStep текущей записи доступны по договорам детей
                ;   исходный ACTION банка 0 и числовые таблицы подготовлены, 7FFD разблокирован, доступны 18 дополнительных байтов стека, IRQ не вмешиваются
                ; Out:
                ;   при отсутствии класса HL сохраняется, DE содержит D=12 и входной E, BC=0040, AF=8042, IY указывает маркер, PC=F0F8, SP сохранён
                ;   при найденной записи IY указывает её, расстояние A=max старших байтов трёх модулей обёрнутых разностей IY минус IX
                ;   при A<2 текущая Component0 становится 8000, ReuseByte=FF, HL=модуль третьей разности, DE первой, BC=0040, F от CP A,2
                ;   ближний путь выполняет внешний RET с SP=входной SP+2, кроме трёх байтов текущей записи изменён только временный стек
                ;   при A>=2 выполнен StepCodesTowardRecord с найденным IY, регистры и записи соответствуют его договору, PC=F0F8 и SP сохранён
                ;   IX, I/IM/IFF сохраняются, на ближнем пути и при отсутствии цели альтернативные регистры сохраняются
                ;   без подвода кодов paging сохраняется, при подводе OUT 7FFD получает 11 и 10, итоговая конфигурация 10
                ; Corrupt:
                ;   HL, DE, BC, AF, IY, R, три байта освобождения либо фазовые поля и операнды дочерней геометрии, до 18 байтов CPU-стека
                ;   HL', DE', BC', AF' и 7FFD только при подводе кодов, дальнейший общий хвост имеет отдельный договор
                ; Note:
                ;   это настоящий адрес State0C исходной таблицы EF50, ClassCode=12 здесь является числом 18, игровое имя класса не назначается
                ;   близость требует каждого из трёх модулей меньше 512, это не проверка евклидовой длины
                ;   поиск может вернуть текущую запись, в таком случае нулевое расстояние приводит к её освобождению
                ;   в F0F8 начинается отдельный PrepareObjectOffsetTransform, его эффекты описаны отдельно и не выдаются за исполненные этой моделью
                ;   958 сценариев проверили все 25 позиций, активные отвлекающие классы, самовыбор, границу 511/512 и отсутствие цели
                ;   реальные поиск, вычислитель расстояния, геометрия, шаг и освобождение исполнены, модели детей составлены с рамками вызовов
                ;   сверены все регистры с R, все восемь банков, значения и кратность записей и реальные OUT, IRQ, точные T, сборка и нативная игра не проверены
                ; -----------------------------------------
                ; Поиск первой активной записи полного класса 12, это десятичный код 18.
Entry:          LD D, @ActionClass18ProximityConst.ClassCode
                CALL @Action.FindRecordByCode.Entry
                JP Z, @Action.PrepareObjectOffsetTransform.Entry                ; переход, если поиск достиг маркера без класса 18, продолжить общий расчёт смещений

                ; Расчёт максимального старшего байта трёх модулей разностей выбранной и текущей записей.
                CALL @Action.MaxRecordDeltaHigh.Entry
                ; Проверка близости, каждый модуль должен быть строго меньше 512.
                CP @ActionClass18ProximityConst.NearLimit
                JR C, @Action.MarkRecordForReuse.Entry                          ; переход, если максимальный старший байт меньше двух, отметить текущую запись для повторного использования

                ; Подвод двух фазовых кодов текущей записи к выбранной записи через настоящую геометрию.
                ; -----------------------------------------
                ; Дополнительный вход StepFar, поиск и проверка расстояния пропускаются
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, IX указывает текущую запись, IY выбранную цель
                ;   действуют условия StepCodesTowardRecord, доступны 18 байтов дополнительного CPU-стека, IRQ не вмешиваются
                ; Out:
                ;   регистры, поля и порты определяются StepCodesTowardRecord, затем PC=F0F8 и SP сохранён
                ; Corrupt:
                ;   регистры, фазы, операнды и CPU-стек по договору StepCodesTowardRecord
                ; Note:
                ;   R добавляет 2 M1 к стоимости ребёнка, точный R композиции проверен моделью State0E
                ; -----------------------------------------
StepFar:        CALL @Action.StepCodesTowardRecord.Entry
                ; Передача общему подготовителю смещений с исходным внешним CPU-стеком.
                JP @Action.PrepareObjectOffsetTransform.Entry

                ; -----------------------------------------
                endmodule
                endmodule
