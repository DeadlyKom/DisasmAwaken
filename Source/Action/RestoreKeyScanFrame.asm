                module Action
                module RestoreKeyScanFrame
                ; Документация [рамка клавиатурного сканирования](../../Docs/ActionKeyDispatchPrefix.md)
                ; -----------------------------------------
                ; Восстановление IX, BC, DE и HL после обработчика клавиши и продолжение сканирования
                ; исходная запись 17, банк 5, перенесённые 6F4E..6F54, смещения 118B..1191
                ; In:
                ;   HL, DE и BC входных числовых аргументов не задают, AF сохраняется
                ;   на CPU-стеке восемь доступных байтов, четыре слова IX, BC, DE и HL по возрастанию адресов
                ;   адрес 6F4E уже снят RET обработчика, внешний адрес возврата остаётся за сохранёнными словами
                ;   исполняется перенесённое ядро ACTION, IRQ не вмешиваются
                ; Out:
                ;   HL, DE и BC восстановлены из четвёртого, третьего и второго слов рамки, AF сохраняется
                ;   HL', DE', BC', AF' сохраняются, IX восстановлен из первого слова, IY, I, IM и IFF сохраняются
                ;   SP=входной SP+8, R увеличивается на 6 M1, управление передано на 6F28 до команды DEC L
                ;   RAM и CPU-стек не записываются
                ; Corrupt:
                ;   HL, DE, BC, IX, SP, R
                ; Note:
                ;   это хвост восстановления после косвенного вызова, внешний RET здесь не выполняется
                ;   полный контракт обработчиков и диспетчера 6F1D остаётся недоказанным
                ;   65536 профилей рамки проверяют все значения каждого сохраняемого слова и AF, совместное пространство четырёх слов не перебиралось
                ; -----------------------------------------
                ; Восстановление сохранённых слов после RET динамического обработчика клавиши.
Entry:          POP IX
                POP BC
                POP DE
                POP HL
                ; Продолжение следующего шага исходного сканирования, адрес и относительное смещение не меняются.
                JR @Action.ScanActionKeys.ScanNext

                endmodule
                endmodule
