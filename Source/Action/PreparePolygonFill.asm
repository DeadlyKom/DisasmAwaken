                module Action
                module PreparePolygonFill
                ; Документация [чтения дополнительных пар и наложение рабочих полей](../../Docs/ActionPolygonExtraMaskPairs.md)
                ; Физические таблицы [адресные строки, шаблоны и крайние маски](../../Docs/PolygonFillPhysicalData.md)
                ; Документация [алгоритм и проверка](../../Docs/ActionPolygonPreparation.md)
                ; -----------------------------------------
                ; Подготовка диапазона строк, верхних вершин двух цепочек, масок и временного стека заливки
                ; исходная запись 17, адреса D511..D5C8
                ; In:
                ;   HL содержит контекст вызывающего, сохраняется в двух свободных байтах под входным CPU SP
                ;   DE, BC и AF координаты не задают, входной Carry существенен для альтернативного AF раннего выхода
                ;   HL', DE', BC', AF', IX и IY содержат сохраняемый либо рабочий контекст по выбранному пути
                ;   Vertices содержит от 3 до 60 пар Second, First, OutputSize равен удвоенному числу точек
                ;   контур выпуклый положительного обхода, Second от 0 до 255, First от 0 до 95, допускается горизонтальное вырождение
                ;   Mode от 0 до 4, пять пар Patterns и исходные маски страниц 8C/8D сохранены
                ;   ACTION находится в банке 0 и доступен для самомодификации, внешний возврат на CPU-стеке, IRQ не вмешиваются
                ; Out:
                ;   HL при горизонтальном контуре восстанавливается из входного CPU-стека, иначе H=8C и L чётный индекс правой верхней вершины
                ;   DE при горизонтальном контуре содержит одинаковую First в обоих байтах, иначе D=minFirst и E=maxFirst
                ;   BC при горизонтальном контуре равен #0001, иначе B=#80+minFirst DIV 8 и C=2*Mode
                ;   AF при горизонтальном контуре содержит A=First и F=#42 OR (First AND #28)
                ;   при непустой высоте A=minFirst и F=#83 OR (maxFirst AND #28) OR Hborrow, где Hborrow=#10 только при (minFirst AND #0F)<(maxFirst AND #0F)
                ;   HL', DE', BC' сохраняются в обоих случаях
                ;   AF' при горизонтальном контуре содержит A'=OutputSize-1 и F'=#02 OR (A' AND #28) OR Hdec OR входной Carry, Hdec=#10 только при (OutputSize AND #0F)=0
                ;   при непустой высоте A' содержит первый шаблон, F'=#40 при Mode=0, #08 при Mode=4, #00 при Mode=1..3
                ;   IX и IY сохраняются при горизонтальном контуре, иначе IX=(minFirst AND 7)*8192+левая Second*32+2*Mode, IY=(minFirst AND 7)*8192+правая Second*32+2*Mode+16
                ;   при горизонтальном контуре общий POP HL и RET по D50F даёт SP=входной SP+2, пиксели не записываются
                ;   при непустой высоте управление передаётся D229 с SP=FFE0, сохранённые HL и внешний возврат остаются на исходном CPU-стеке
                ;   обновлены 11 именованных операндов, LastIndex записывается также на раннем пути, CPU-стек получает исходный HL
                ;   I, IM, IFF и paging сохраняются, порты и пиксельный буфер не используются, R меняется и отдельно не доказан
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', IX, IY, R, два байта CPU-стека и 11 именованных операндов, HL восстанавливается при раннем RET
                ; Note:
                ;   minFirst и maxFirst обозначают минимум и максимум First всех вершин, Size=OutputSize=2*число вершин, Mode=0..4
                ;   контракт непустого случая относится к границе JP D229, а не к конечному RET всего заполнителя
                ;   минимум выбирается строго, одинаковая First сохраняет первый найденный индекс, максимум допускает равенство
                ;   верхняя горизонталь обходится раздельно назад и вперёд с оборачиванием индексов внутри страницы 90
                ;   IX/IY упаковывают адресную фазу и номер маски, это не два обычных адреса пиксельного буфера
                ;   нулевая и нечётная длина, невыпуклые контуры и режимы 5..7 в доказанный профиль не входят
                ;   3978 сценариев проверяют регистры кроме R, все физические банки и кратность записей без подмены инструкций
                ;   1060 горизонтальных профилей включают все длины 3..60 с обоими входными Carry, прежние 480 проверяли только три вершины
                ;   весь строковый заполнитель, все совместные входы, точное R/T, IRQ, сборка и нативный запуск отдельно не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; CPU-стек и размер кольца
                ; Сохранение HL вызывающего до подмены SP в непустом случае.
Entry:          PUSH HL
                ; Чтение байтовой длины контура, исходный код не проверяет её парность.
                LD A, (@ActionClipIntersectionsState.OutputSize)
                LD B, A
                ; Расчёт последнего нечётного индекса для оборачивания правой цепочки.
                DEC A
                ; Обновление границы списка в операнде сравнения.
                LD (@ActionPolygonPreparationState.LastIndex), A
                EX AF, AF'
                ; Расчёт числа вершин из байтовой длины и начальных пределов FF/00.
                SRL B
                LD HL, @ActionPolygonPreparationState.Vertices+1
                LD DE, #FF00
                ; -----------------------------------------
                ; Минимальная и максимальная строка
                ; Проверка очередной First относительно ранее найденного минимума.
ScanRows:       LD A, (HL)
                CP D
                JP NC, @Action.PreparePolygonFill.CheckMaximum                  ; переход, если First не меньше минимума, сохранить первый минимальный индекс

                ; Обновление строгого минимума и его нечётного индекса.
                LD D, A
                LD C, L
                ; Проверка очередной First относительно максимальной строки.
CheckMaximum:   CP E
                JP C, @Action.PreparePolygonFill.NextVertex                     ; переход, если First меньше максимума, сохранить прежний максимум

                LD E, A
                ; Продвижение к First следующей пары без переноса в старший байт адреса.
NextVertex:     INC L
                INC L
                DJNZ @Action.PreparePolygonFill.ScanRows

                ; Проверка нулевой высоты всего контура.
                LD A, E
                CP D
                JR Z, @Action.ReturnPolygonFill.Entry                           ; переход, если минимум равен максимуму, восстановить HL и вернуть управление без пикселей

                ; Обновление общего нижнего предела и начальных пределов двух рёбер.
                LD (@ActionPolygonPreparationState.MaximumRow), A
                LD A, D
                LD (@ActionPolygonPreparationState.LeftEndRow), A
                LD (@ActionPolygonPreparationState.RightEndRow), A
                ; Выбор первого минимума как исходной вершины обоих верхних обходов.
                LD B, D
                LD L, C
                ; -----------------------------------------
                ; Левый конец верхней горизонтали
                ; Поиск предыдущей верхней вершины с сохранением последнего подходящего индекса.
ScanLeftTop:    LD E, L
                DEC L
                JR Z, @Action.WrapPolygonLeftTop.Entry                          ; переход, если достигнут нулевой байт страницы, продолжить обратный обход с конца списка

ReadLeftTop:    DEC L
                ; Проверка First предыдущей вершины относительно верхней горизонтали.
                CP (HL)
                JR Z, @Action.PreparePolygonFill.ScanLeftTop                    ; переход, если предыдущая вершина имеет минимальную First, продолжить обратный обход

                ; Обновление левого курсора выбранным верхним строковым байтом.
KeepLeftTop:    LD L, E
                LD (@ActionPolygonPreparationState.LeftCursor), HL
                ; -----------------------------------------
                ; Правый конец верхней горизонтали
                ; Поиск следующей верхней вершины, последний индекс берётся из альтернативного A.
                LD L, C
ScanRightTop:   LD E, L
                EX AF, AF'
                ; Проверка достижения последнего нечётного индекса перед продвижением.
                CP L
                JR Z, @Action.WrapPolygonRightTop.Entry                         ; переход, если достигнут конец списка, продолжить прямой обход с первого строкового байта

NextRightTop:   INC L
                INC L
ReadRightTop:   EX AF, AF'
                ; Проверка First следующей вершины относительно верхней горизонтали.
                CP (HL)
                JR Z, @Action.PreparePolygonFill.ScanRightTop                   ; переход, если следующая вершина имеет минимальную First, продолжить прямой обход

                ; Обновление правого курсора выбранным верхним строковым байтом.
KeepRightTop:   LD L, E
                LD (@ActionPolygonPreparationState.RightCursor), HL
                ; -----------------------------------------
                ; Шаблон и XOR соседних строк
                ; Чтение номера режима из изменяемого операнда.
                LD A, #00
                ; Расчёт смещения пары шаблонов как удвоенного номера режима.
                ADD A, A
                LD C, A
                LD H, #D1
                LD L, A
                ; Чтение первого шаблона и сохранение его в альтернативном A до строкового цикла.
                LD A, (HL)
                EX AF, AF'
                ; Чтение XOR разности соседних строк и обновление обоих строковых путей.
                INC L
                LD A, (HL)
                LD (@ActionPolygonPreparationState.WideDelta), A
                LD (@ActionPolygonPreparationState.NarrowDelta), A
                ; -----------------------------------------
                ; Начальные IX и IY
                ; Расчёт левой адресной фазы из First и Second верхней вершины.
                LD HL, (@ActionPolygonPreparationState.LeftCursor)
                DEC L
                LD E, (HL)
                XOR A
                SRL B
                RR E
                RRA
                SRL B
                RR E
                RRA
                SCF
                RR B
                RR E
                RRA
                ; Добавление номера пары масок к фазе левой границы.
                ADD A, C
                LD IXL, A
                LD IXH, E
                ; Расчёт правой адресной фазы из First и Second правой верхней вершины.
                LD HL, (@ActionPolygonPreparationState.RightCursor)
                DEC L
                LD E, (HL)
                XOR A
                SRL D
                RR E
                RRA
                SRL D
                RR E
                RRA
                SCF
                RR D
                RR E
                RRA
                ; Добавление номера режима и смещения правых масок 16.
                ADD A, C
                ADD A, #10
                LD IYL, A
                LD IYH, E
                ; -----------------------------------------
                ; Передача управления строковому циклу
                ; Выбор первой страницы масок и сохранение CPU SP после PUSH HL.
                LD H, #8C
                LD (@ActionPolygonPreparationState.SavedSP), SP
                ; Чтение общего максимума и текущей минимальной строки перед входом в ядро.
                LD A, (@ActionPolygonPreparationState.MaximumRow)
                LD E, A
                LD A, (@ActionPolygonPreparationState.LeftEndRow)
                LD D, A
                ; Повторная проверка непустой высоты перед подменой SP.
                CP E
                JP NC, @Action.PolygonFillRows.RestoreStack                     ; переход, если текущая строка достигла максимума, восстановить CPU-стек и выйти

                ; Обновление ближайшего предела минимальной строкой, первый переход подготовит левое ребро.
                LD (@ActionPolygonPreparationState.RowLimit), A
                ; Обновление смещения JR NC, значение 45 ведёт из строкового ядра на D272.
                LD A, #45
                LD (@ActionPolygonPreparationState.RowBranch), A
                LD A, D
                ; Установка существующего временного SP=FFE0 для поправки границы на минус 32.
                LD SP, @ActionPolygonScratch.Value + 2
                ; Продолжение по D229, сохранённый HL и внешний адрес возврата остаются на CPU-стеке.
                JP @Action.PolygonFillRows.CheckRow

                ; -----------------------------------------
                endmodule
                endmodule
