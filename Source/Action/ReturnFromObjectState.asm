                ; -----------------------------------------
                ; Пустой вход с немедленным возвратом
                ; исходная запись 17, банк 0, адрес #EF7C
                ; In:
                ;   на CPU-стеке лежит двухбайтовый адрес продолжения, выбран банк 0
                ; Out:
                ;   PC получает слово с CPU-стека, SP увеличивается на два по модулю 65536
                ;   HL, DE, BC, AF, HL′, DE′, BC′, AF′, IX, IY, I и IFF сохраняются, R получает один M1
                ; Corrupt:
                ;   SP и R, записи в память отсутствуют
                ; Note:
                ;   авторская метка NTH у отдельного RET после 22 слов ITAB, активный вызывающий вход не установлен
                ;   при коде #16 или #96 диспетчер читает #C9 как младший байт адреса и переходит на #DDC9
                ; -----------------------------------------
                ; Возврат по готовой рамке без обновления записи объекта.
Entry:          RET

