                module Action
                module CopyObjectData
                ; Документация [алгоритм и проверка](../../Docs/ActionObjectCopy.md)
                ; -----------------------------------------
                ; Копирование двухчастного потока OBJECT3D в исходный рабочий буфер с возвратом банка 0
                ; исходная запись 17, адреса AAE2..AB1A
                ; In:
                ;   L задаёт байтовое смещение таблицы указателей 9E00, входной H игнорируется, DE и AF аргументов не задают
                ;   BC задаёт начальный счётчик LDI, допустимо любое слово, это не ограничитель общей длины копии
                ;   по указателю находится конечный поток, два байта заголовка, четырёхбайтовые записи до нулевого первого байта, затем переменные записи
                ;   длина переменной записи равна 1 плюс младшая тетрада первого байта, нулевая тетрада завершает поток
                ;   банк 4 содержит поток OBJECT3D, paging не заблокирован, код и CPU-стек находятся в фиксированной RAM, IRQ не вмешиваются
                ;   копия в Buffer не должна разрушать исполняемый код, исходный поток и стек, сама процедура ёмкость назначения не проверяет
                ;   на CPU-стеке внешний возврат, нужны четыре дополнительных байта для CALL и PUSH BC настоящего селектора
                ; Out:
                ;   HL указывает за последним скопированным маркером источника, DE указывает за копией в Buffer
                ;   все байты потока скопированы в исходном порядке, включая оба маркера и старшие тетрады переменных заголовков
                ;   если была хотя бы одна переменная запись, BC=FFFF, иначе BC=входной BC минус полный размер копии по модулю 65536
                ;   A=10, F=40 при конечном BC=0 либо F=44 при ненулевом BC, Z установлен независимо от содержимого копии
                ;   HL', DE', BC', AF', IX, IY, I, IM и IFF сохраняются, SP после RET равен входному SP+2
                ;   OUT 7FFD получает 14, затем 10, прежняя полная конфигурация paging не восстанавливается
                ;   R увеличивается на 37 плюс 12 на каждую четырёхбайтовую запись, затем 7 плюс удвоенная длина на каждую переменную запись
                ; Corrupt:
                ;   HL, DE, BC, AF, R, Buffer по полной длине потока, четыре байта CPU-стека и управление 7FFD
                ; Note:
                ;   старший байт указателя читается по 9E00 плюс ((L+1) AND FF), индекс FF оборачивается в начало той же страницы
                ;   первый маркер должен быть целым нулевым байтом, второй проверяется только по младшей тетраде и может иметь ненулевую старшую
                ;   первые LDI могут оборачивать BC, но это не останавливает фиксированные записи, перед каждым LDIR задаётся положительная длина 2..16
                ;   все 128 исходных чётных указателей дают 95 конечных потоков, максимальная исходная копия равна 238 байтам и заканчивается по A00A
                ;   искусственные нечётные индексы и более длинные потоки проверены отдельными синтетическими данными, их игровая допустимость не утверждается
                ;   первые два байта и внутренний игровой смысл всех записей этой процедурой не интерпретируются, преобразование вершин проверяется отдельно
                ; -----------------------------------------
                ; -----------------------------------------
                ; Чтение указателя объекта
                ; Подготовка страницы 9E, входной L является байтовым смещением, а не номером слова.
Entry:          LD H, @ActionObjectCopyConst.PointerPage
                ; Чтение little-endian указателя, INC L оборачивает только байтовый индекс внутри страницы 9E.
                LD A, (HL)
                INC L
                LD H, (HL)
                LD L, A
                ; Выбор OBJECT3D в банке 4 с сохранением указателя в HL.
                LD A, @ActionObjectCopyConst.DataPage
                CALL @Action.SelectMemoryPage.Entry
                ; -----------------------------------------
                ; Копирование заголовка и фиксированных записей
                ; Подготовка существующего Buffer и копирование двух байтов заголовка без проверки BC.
                LD DE, @ActionObjectCopyState.Buffer
                LDI
                LDI
                ; Проверка первого байта следующей четырёхбайтовой записи на полный нуль.
NextFixed:      LD A, (HL)
                OR A
                JR Z, @Action.CopyObjectData.FixedEnd                           ; переход, если первый байт записи равен нулю, скопировать маркер конца фиксированной части

                ; Копирование всех четырёх байтов текущей записи, BC не является пределом этого цикла.
                LDI
                LDI
                LDI
                LDI
                JP @Action.CopyObjectData.NextFixed

                ; Сохранение полного нулевого маркера между двумя частями потока.
FixedEnd:       LDI
                ; -----------------------------------------
                ; Копирование записей переменной длины
                ; Проверка младшей тетрады заголовка, старшая тетрада не меняет длину и сохраняется в копии.
NextVariable:   LD A, (HL)
                AND @ActionObjectCopyConst.LengthMask
                JR Z, @Action.CopyObjectData.VariableEnd                        ; переход, если младшая тетрада заголовка равна нулю, скопировать последний маркер

                ; Расчёт длины записи вместе с заголовком, положительный BC получает значение от 2 до 16.
                INC A
                LD C, A
                LD B, #00
                ; Копирование заголовка и указанного числа последующих байтов, LDIR заканчивается при BC=0.
                LDIR
                JP @Action.CopyObjectData.NextVariable

                ; -----------------------------------------
                ; Сохранение маркера и возврат банка 0
                ; Копирование последнего байта целиком, ненулевая старшая тетрада не отбрасывается.
VariableEnd:    LDI
                ; Возврат полной конфигурации 10, исходное значение paging не восстанавливается.
                LD A, @ActionBankPage.Runtime
                CALL @Action.SelectMemoryPage.Entry
                RET

                ; -----------------------------------------
                endmodule
                endmodule
