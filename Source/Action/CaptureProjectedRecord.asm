                module Action
                module CaptureProjectedRecord
                ; Документация [локальный выбор и неизвестный обход](../../Docs/ActionProjectedCapture.md)
                ; -----------------------------------------
                ; Условная запись альтернативного HL в PendingRecord после двух проверок координатного допуска
                ; исходная запись 17, код ACTION банка 0, адреса E30F..E369
                ; In:
                ;   HL и BC сохраняются только при ненулевом Gate, DE входная координата Y в слове, AF числовых аргументов не задаёт
                ;   HL' значение для PendingRecord при попадании, DE', BC', AF', IX и IY сохраняются
                ;   Gate по E310 блокирует проверку при любом ненулевом байте, Limit по E331 задаёт беззнаковый допуск, ProjectedX по E33A задаёт слово X
                ;   байты 9B19 и 9B1A задают две исходные точки отсчёта, поправки равны signed8(77 - байт X) и signed8(2B - байт Y)
                ;   код ACTION доступен в банке 0, SP сохраняется, это последовательный фрагмент без RET, IRQ не вмешиваются
                ; Out:
                ;   при Gate не равном нулю HL, DE и BC сохраняются, A=Gate, F соответствует AND Gate, записей RAM нет
                ;   при Gate=0 сначала вычисляется Y с signed8-поправкой по модулю 65536, затем абсолютное слово сравнивается с Limit без знака
                ;   после отказа по Y HL=Limit - abs16(Y) по модулю 65536, DE=abs16(Y), F соответствует этому SBC без входного переноса
                ;   после допуска Y аналогично проверяется X, при отказе по X возвращаются разность HL и расстояние DE для X
                ;   при попадании обеих осей Gate получает 1, PendingRecord получает HL', A=1, HL и DE содержат результат сравнения X, F сохраняет флаги SBC для X
                ;   при отказе A содержит байт поправки выбранной оси для неотрицательного переведённого слова либо инвертированный старший байт этого слова для отрицательного
                ;   BC, HL', DE', BC', AF', IX, IY, SP, I, IM и IFF сохраняются, следующее исполнение начинается по E36A
                ;   дополнительных рамок CPU-стека, чтений и записей портов нет, равенство расстояния допуску разрешает захват
                ; Corrupt:
                ;   HL, DE и AF при обработке, AF при ненулевом Gate, R, Gate и PendingRecord при попадании
                ; Note:
                ;   абсолютное слово 8000 остаётся 8000, сравнение с Limit беззнаковое, переполнение перевода координаты не исправляется
                ;   между двумя проверками нет записи результата, отказ по любой оси сохраняет прежний PendingRecord
                ;   сам фрагмент не доказывает, что альтернативный HL всегда является допустимой записью, это должен обеспечить окружающий обход
                ;   подготовка Limit и ProjectedX, полный цикл обхода и игровой смысл события ещё не доказаны
                ;   локальная модель завершается перед E36A, окружающий неизвестный код не включён в доказанный договор
                ; -----------------------------------------
                ; Проверка изменяемого Gate, ненулевое значение запрещает новый выбор в этом фрагменте.
Entry:          LD A, #01
                AND A
                JP NZ, @Action.FollowProjectedTarget.Entry                      ; переход, если Gate ненулевой, координаты не проверять и PendingRecord сохранить

                ; -----------------------------------------
                ; Проверка допуска по Y
                ; Расчёт signed8-поправки от байта 9B1A к исходному центру 2B, затем расширение знака до слова.
                LD A, (#9B1A)
                SUB #2B
                NEG
                LD L, A
                LD H, #00
                JP P, @Action.CaptureProjectedRecord.TranslateY                 ; переход, если signed8-поправка Y неотрицательна, оставить H равным нулю

                DEC H
                ; Перевод слова Y с оборачиванием по модулю 65536 и проверка знака результата.
TranslateY:     ADD HL, DE
                EX DE, HL
                BIT 7, D
                JR Z, @Action.CaptureProjectedRecord.CheckY                     ; переход, если переведённое слово Y неотрицательно, модуль уже получен

                ; Расчёт модуля отрицательного слова Y, исходное 8000 остаётся 8000.
                LD A, E
                CPL
                LD E, A
                LD A, D
                CPL
                LD D, A
                INC DE
                ; Проверка беззнакового расстояния Y относительно Limit, равенство допускается.
CheckY:         LD HL, #0000
                OR A
                SBC HL, DE
                JP C, @Action.FollowProjectedTarget.Entry                       ; переход, если расстояние Y больше Limit, PendingRecord сохранить

                ; -----------------------------------------
                ; Проверка допуска по X
                ; Чтение изменяемого ProjectedX и расчёт signed8-поправки от байта 9B19 к центру 77.
                LD DE, #0000
                LD A, (#9B19)
                SUB #77
                NEG
                LD L, A
                LD H, #00
                JP P, @Action.CaptureProjectedRecord.TranslateX                 ; переход, если signed8-поправка X неотрицательна, оставить H равным нулю

                DEC H
                ; Перевод слова X и проверка знака результата перед вычислением расстояния.
TranslateX:     ADD HL, DE
                EX DE, HL
                BIT 7, D
                JR Z, @Action.CaptureProjectedRecord.CheckX                     ; переход, если переведённое слово X неотрицательно, модуль уже получен

                ; Расчёт модуля отрицательного слова X, без исправления случая 8000.
                LD A, E
                CPL
                LD E, A
                LD A, D
                CPL
                LD D, A
                INC DE
                ; Проверка беззнакового расстояния X относительно того же Limit.
CheckX:         LD HL, (@ActionProjectedCaptureState.Limit)
                OR A
                SBC HL, DE
                JP C, @Action.FollowProjectedTarget.Entry                       ; переход, если расстояние X больше Limit, PendingRecord сохранить

                ; -----------------------------------------
                ; Сохранение результата выбора
                ; Установка Gate перед записью альтернативного HL в PendingRecord, альтернативный набор затем восстанавливается.
                LD A, #01
                LD (@ActionProjectedCaptureState.Gate), A
                EXX
                LD (@ActionRecordLinkEventState.PendingRecord), HL
                EXX
                ; JP @Action.FollowProjectedTarget.Entry, продолжение в UnknownE36A.asm

                ; -----------------------------------------
                endmodule
                endmodule
