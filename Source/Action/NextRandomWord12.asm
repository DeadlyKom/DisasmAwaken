                module Action
                module NextRandomWord12
                ; Документация [генератор и все потоки](../../Docs/ActionFoldedRandom.md)
                ; -----------------------------------------
                ; Следующее слово независимого потока 12 с физическим состоянием Stream12
                ; исходная запись 17, банк 0, смещения #8BC6..#8BCC
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, DE и BC являются сохраняемым контекстом вызывающего
                ;   ActionRandomStreams.Stream12 - физический FFoldedRandomState, LowWord и FoldByte доступны для записи
                ;   в окне C000 выбран банк 0, SP указывает внешний возврат и имеет два доступных байта ниже него, IRQ не вмешивается
                ; Out:
                ;   HL - новый LowWord выбранного потока, DE и BC сохранены, A - новый FoldByte, F соответствует StepFoldedRandom
                ;   HL' - адрес выбранного Stream12, DE' - новое слово, B'=0, C' - младший байт n, AF' сохранён
                ;   IX и IY, I/IM/IFF и paging сохраняются, R увеличен на 66 M1, SP после RET равен входному SP+2
                ;   обновлены только LowWord и FoldByte выбранного потока и два временных байта ниже SP
                ; Corrupt:
                ;   HL, AF, HL', DE', BC', R, три байта состояния и два временных байта CPU-стека
                ; Note:
                ;   EXX перед выбором состояния обеспечивает обратное восстановление основных DE и BC общим ядром
                ;   JP в StepFoldedRandom не создаёт нового возврата, итоговый RET снимает внешний адрес данного входа
                ;   формула, точные флаги, пятнадцать исходных состояний и все внешние входы проверены вместе с реальным общим ядром
                ;   игровая роль потока 12 отдельно не установлена, распределение и период результата не доказаны
                ; -----------------------------------------
                ; Выбор рабочего альтернативного набора, основное DE и BC вызывающего вернутся после EXX общего ядра.
Entry:          EXX
                ; Выбор физического состояния Stream12, другие потоки этим вызовом не обновляются.
                LD HL, @ActionRandomStreams.Stream12
                JP @Action.StepFoldedRandom.Entry

                endmodule
                endmodule
