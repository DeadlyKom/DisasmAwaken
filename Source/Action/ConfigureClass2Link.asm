                module Action
                module ConfigureClass2Link
                ; Документация [алгоритм и проверка](../../Docs/ActionClass2Link.md)
                ; -----------------------------------------
                ; Подстановка и выбор связи среди классов 6 и 7 после аппаратного порога
                ; исходная запись 17, адреса 6549..6565
                ; In:
                ;   HL, DE, BC числовых аргументов не задают, AF задаёт входной Carry ранней подстановки, IX указывает доступную FActionRecord
                ;   LinkOverride, StateCode и LinkedIndex доступны по договору CopyRecordLinkOverride, он вызывается до иных проверок
                ;   действует договор соответствующего фильтра, достижима подходящая активная запись либо маркер
                ;   выбран ACTION банка 0, CPU-стек не пересекает запись, код и список, доступны 8 дополнительных байтов, IRQ не вмешиваются
                ;   дополнительный SelectSixSeven по 655A не задаёт StateCode и не проверяет R, он начинает с повторной подстановки
                ; Out:
                ;   при LinkOverride=1..FE возвращается результат подстановки, LinkedIndex=LinkOverride и StateCode=02
                ;   при LinkOverride=0 либо FF обработка продолжается, разрешённый ноль сначала записывает LinkedIndex=0 и StateCode=02
                ;   после незавершившей подстановки читается R, StateCode=02 и LinkedIndex=FF записываются до проверки порога
                ;   при R<70 поиск пропускается, иначе дополнительный вход SelectSixSeven повторяет подстановку и ищет класс 6 либо 7
                ;   при NZ фильтра LinkedIndex получает его A, при Z сохраняется результат повторной подстановки, в том числе разрешённый ноль
                ;   HL сохраняется на всех путях, генераторы здесь не вызываются
                ;   DE - D сохраняется, E без фильтра сохраняется, при находке равен (ClassCode+1) AND FF
                ;   при маркере E содержит последний проверенный ClassCode либо входной E, если активных записей не было
                ;   BC при фильтре равен FActionRecord, без фильтра сохраняется
                ;   AF при разрешённой ненулевой подстановке содержит A=LinkOverride и флаги DEC байта LinkOverride+1 с сохранённым входным Carry
                ;   AF при выходе по порогу содержит прочитанный R в A и флаги его CP с 70
                ;   AF при находке содержит индекс в A и флаги INC E с Carry=0 для проверенной области списка, при маркере A=80 и F=42
                ;   HL', DE', BC', AF' сохраняются
                ;   IX сохраняется, IY при фильтре указывает найденную запись либо маркер, без фильтра сохраняется
                ;   I, IM, IFF и paging сохраняются, SP после внешнего RET равен входному SP+2
                ;   R и все флаги проверены точной числовой моделью каждого пути, бит 7 R сохраняется
                ; Corrupt:
                ;   E, BC, AF, IY, R, StateCode, LinkedIndex и временные слова CPU-стека
                ; Note:
                ;   коды состояний и пороги в этой записи шестнадцатеричные, номера классов в названии десятичные
                ;   совместная проверка восьми обработчиков исполнила 405456 сценариев с настоящими детьми, точными регистрами, R, восемью банками и кратностью записей
                ;   охват конкретного входа и списков приведён в его отчёте, произведение всех состояний и списков не исчерпано
                ;   распределение аппаратного R, аппаратные IRQ, точные T, сборка и нативная игра не доказаны
                ;   после подстановки FF чтение R перед непосредственным CP происходит через 8 M1, после нуля через 14 M1
                ;   при стабильном LinkOverride второй RET NZ недостижим из обычного Entry, но сохранён для самостоятельного SelectSixSeven
                ;   1024 дополнительных сценария этого входа проверяют все ClassCode первой активной записи, подстановки 0 и FF, выход по порогу и достижение фильтра
                ; -----------------------------------------
                ; Применение исходной подстановки до выбора состояния, ноль разрешён и продолжает обработку.
Entry:          CALL @Action.CopyRecordLinkOverride.Entry
                RET NZ                                                          ; выход, если LinkOverride находится в 1..FE, сохранить результат подстановки

                ; Проверка аппаратного R перед поиском классов 6 и 7.
                LD A, R
                CP @ActionClass9Const.FlagThreshold
                ; Обновление StateCode и LinkedIndex до решения о выполнении поиска, флаги CP сохраняются.
                LD (IX + @FActionRecord.StateCode), @ActionClass0Const.RecordCode
                LD (IX + @FActionRecord.LinkedIndex), @ActionClass9Const.DefaultIndex
                RET C                                                           ; выход, если прочитанный R меньше 70, оставить StateCode=02 и LinkedIndex=FF

                ; Повторное применение подстановки, этот вход также используется классом 6 без новой проверки R.
SelectSixSeven: CALL @Action.CopyRecordLinkOverride.Entry
                RET NZ                                                          ; выход, если повторная подстановка LinkOverride находится в 1..FE, сохранить её результат

                ; Поиск первой допустимой записи полного класса 6 либо 7.
                CALL @Action.FindRecordClass6Or7.Entry
                RET Z                                                           ; выход, если фильтр классов 6 и 7 вернул Z, сохранить текущий LinkedIndex

                ; Сохранение выбранного индекса, фильтр принимает также нулевой индекс при NZ.
                LD (IX + @FActionRecord.LinkedIndex), A
                RET

                endmodule
                endmodule
