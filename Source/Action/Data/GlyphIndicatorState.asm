Control:        FGlyphIndicatorControl {
                    #00,                                                        ; FirstMode, код 01 пропускает первый знак, остальные значения допускают его
                    #00,                                                        ; ThirdGate, ноль допускает третий знак после проверки второго, ненулевое значение запрещает
                    #00                                                         ; Unknown83, E021 этот байт не читает, полный игровой смысл не установлен
                }
                ; -----------------------------------------
                ; исходная физическая запись Third
