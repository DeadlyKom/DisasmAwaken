                    #00                                                         ; SignSource, знаковый байт выбора заполненного или полого квадрата, глобальный смысл не установлен
                }
                ; -----------------------------------------
                ; исходная физическая запись Second
Second:         FGlyphIndicatorXY {
                    #00,                                                        ; X, байт горизонтального смещения в формуле экрана
                    #00,                                                        ; Y, байт вертикального смещения в формуле экрана
                    #00                                                         ; SignSource, знаковый байт выбора формы, у Second весь байт также входит в OR-маркер отсутствия
                }
                ; -----------------------------------------
                ; исходная физическая запись First
First:          FGlyphIndicatorXY {
                    #00,                                                        ; X, байт горизонтального смещения в формуле экрана
