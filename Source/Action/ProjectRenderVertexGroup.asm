                module Action
                module ProjectRenderVertexGroup
                ; Физические результаты [поля, порядок заполнения и предел исходных моделей](../../Docs/ActionProjectedPointsData.md)
                ; Документация [алгоритм и проверка](../../Docs/ActionVertexGroup.md)
                ; -----------------------------------------
                ; Построение комбинаций координат и перспективная запись выбранной группы вершин
                ; исходная запись 17, адреса D694..D79F
                ; In:
                ;   IXL задаёт код группы, 01 означает одну вершину, 81 означает вершину и её покомпонентное отрицание
                ;   для остальных кодов биты 7..0 независимо выбирают комбинации 7..0, нулевой код здесь допустим и не пишет точек
                ;   PackedFirst, PackedSecond, PackedThird содержат три слова упакованных локальных осей, DepthFirst/Second/Third содержат третьи координаты
                ;   NextOffset задаёт младший байт рабочего SP в существующей странице 8E, параметры ProjectRenderVertex уже подготовлены
                ;   ACTION находится в банке 0, CPU-стек содержит внешний возврат, IRQ не вмешиваются в рабочий стек
                ;   все записи выходных точек должны оставаться вне исполняемого кода, операндов и CPU-стека
                ; Out:
                ;   HL равен конечному рабочему SP, за каждую выбранную вершину прибавлено пять байтов
                ;   DE содержит последнюю пару для кодов 01/81, для остальных всегда комбинацию 4 независимо от её выбора
                ;   B содержит исходный код группы, C содержит RLC младшего байта входного PackedFirst
                ;   A равен младшему байту HL, F сохраняет S/Z/PV последнего достигнутого пути и получает H/N/C=0, X/Y от старшего байта HL
                ;   для обычной маски с нулевым битом 4 последние S/Z/PV равны 0/1/1 от BIT 4,B, даже если до этого проектировались вершины
                ;   HL', DE', BC', AF' равны результату последней перспективы, если точек нет, альтернативный набор сохраняется
                ;   IXH содержит глубину комбинации 0, для кода 81 её отрицание, IXL содержит глубину 2, IYH и IYL содержат глубины 1 и 3
                ;   NextOffset получает только младший байт конечного рабочего SP, SavedSP содержит входной CPU SP, SP после RET равен входному SP+2
                ;   I, IM, IFF и paging сохраняются, R изменяется, портов нет
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, R, рабочие записи точек, SavedDepth перспективы и 14 изменяемых операндов
                ; Note:
                ;   повороты RLC и отрицание пары выполняются отдельно для её двух байтов, ADD/SBC над парой остаются 16-разрядными с переносом между байтами
                ;   порядок обычной маски строго 0, 1, 3, 2, 6, 7, 5, 4, коды 01 и 81 проверяются до битовой маски
                ;   пятый байт каждого FRenderProjectedPoint не записывается, отказ перспективы всё равно занимает полную запись
                ;   после перехода через границу страницы сохраняется только младший байт, следующий вызов вновь начнёт со страницы 8E
                ;   CPU-стек внутри тела не записывается, CALL отсутствует, JP в перспективу использует рабочий SP и продолжение через HL
                ;   206592 сценария проверяют регистры, флаги, всю RAM и кратность записей с настоящей перспективой, R и время отдельно не доказаны
                ;   вся декартова область входных данных и полный проход объекта этой проверкой не исчерпаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Разделение CPU-стека и рабочего стека точек
                ; Сохранение внешнего возврата, последующие PUSH выполняет перспектива в странице 8E.
Entry:          LD (@ActionVertexGroupState.SavedSP), SP
                LD SP, @ActionVertexGroupConst.WorkPage
                ; Чтение трёх подготовленных пар локальных координат из изменяемых операндов.
                LD BC, #0000
                LD DE, #0000
                LD HL, #0000
                ; -----------------------------------------
                ; Расчёт восьми пар координат
                ; Комбинация 0 равна сумме трёх упакованных слов, перенос между байтами сохраняется.
                ADD HL, BC
                ADD HL, DE
                LD (@ActionVertexGroupState.Corner0), HL
                ; Расчёт побайтового RLC первых двух пар, это не удвоение 16-разрядного слова.
                RLC B
                RLC C
                RLC D
                RLC E
                ; Расчёт комбинации 1 вычитанием первой повёрнутой пары без входного Carry.
                OR A
                SBC HL, BC
                LD (@ActionVertexGroupState.Corner1), HL
                ; Расчёт комбинации 3 вычитанием второй повёрнутой пары.
                OR A
                SBC HL, DE
                LD (@ActionVertexGroupState.Corner3), HL
                ; Расчёт комбинации 2 возвратом первой повёрнутой пары.
                ADD HL, BC
                LD (@ActionVertexGroupState.Corner2), HL
                ; Расчёт комбинации 5 отдельным отрицанием двух байтов комбинации 2.
                LD A, L
                NEG
                LD L, A
                LD A, H
                NEG
                LD H, A
                LD (@ActionVertexGroupState.Corner5), HL
                ; Расчёт комбинации 4 прибавлением первой повёрнутой пары.
                ADD HL, BC
                LD (@ActionVertexGroupState.Corner4), HL
                ; Расчёт комбинации 6 вычитанием второй повёрнутой пары.
                OR A
                SBC HL, DE
                LD (@ActionVertexGroupState.Corner6), HL
                ; Расчёт комбинации 7 вычитанием первой повёрнутой пары.
                OR A
                SBC HL, BC
                LD (@ActionVertexGroupState.Corner7), HL
                ; -----------------------------------------
                ; Расчёт восьми глубин
                ; Сохранение кода в B до замены IXL, глубины оборачиваются отдельно до восьми бит.
                LD B, IXL
                LD A, #00
                LD DE, #0000
                ; Расчёт глубины 0 суммой трёх входных байтов.
                ADD A, D
                ADD A, E
                LD IXH, A
                ; Расчёт повёрнутых первых двух глубин.
                RLC D
                RLC E
                ; Расчёт глубин 1 и 3 последовательным вычитанием повёрнутых байтов.
                SUB D
                LD IYH, A
                SUB E
                LD IYL, A
                ; Расчёт глубины 2, затем её отрицания для глубины 5.
                ADD A, D
                LD IXL, A
                NEG
                LD (@ActionVertexGroupState.Depth5), A
                ; Расчёт глубин 4, 6 и 7 с сохранением каждого байта в его операнде.
                ADD A, D
                LD (@ActionVertexGroupState.Depth4), A
                SUB E
                LD (@ActionVertexGroupState.Depth6), A
                SUB D
                LD (@ActionVertexGroupState.Depth7), A
                ; -----------------------------------------
                ; Особые числовые коды группы
                ; Проверка полного кода 01 раньше битовой маски.
                LD DE, #0000
                LD A, B
                CP @ActionVertexGroupConst.SingleCode
                JR Z, @Action.ProjectRenderVertexGroup.Single                   ; переход, если код равен 01, спроектировать только комбинацию 0

                ; Проверка полного кода 81, для него вторая точка является отрицанием первой.
                CP @ActionVertexGroupConst.AntipodeCode
                JR NZ, @Action.ProjectRenderVertexGroup.Masked                  ; переход, если код не равен 81, обработать обычную маску

                ; Передача первой точки кода 81, продолжение NegatePair передаётся через HL.
                LD A, IXH
                LD HL, @Action.ProjectRenderVertexGroup.NegatePair
                JP @Action.ProjectRenderVertex.Entry

                ; Расчёт противоположной точки отдельным отрицанием глубины и двух байтов DE.
NegatePair:     LD A, IXH
                NEG
                LD IXH, A
                LD A, D
                NEG
                LD D, A
                LD A, E
                NEG
                LD E, A
                ; Передача последней точки особого кода, перспектива вернёт управление в Finish.
Single:         LD A, IXH
                LD HL, @Action.ProjectRenderVertexGroup.Finish
                JP @Action.ProjectRenderVertex.Entry

                ; -----------------------------------------
                ; Обход обычной маски
                ; Разряды 7..0 выбирают комбинации 7..0, порядок посещения отличается от порядка разрядов.
Masked:         LD A, IXH
                ; Проверка выбора комбинации 0 в исходном коде группы.
                BIT 0, B
                LD HL, @Action.ProjectRenderVertexGroup.Next1
                JP NZ, @Action.ProjectRenderVertex.Entry                        ; переход, если выбран разряд 0, спроектировать соответствующую комбинацию

Next1:          LD DE, #0000
                LD A, IYH
                ; Проверка выбора комбинации 1 в исходном коде группы.
                BIT 1, B
                LD HL, @Action.ProjectRenderVertexGroup.Next3
                JP NZ, @Action.ProjectRenderVertex.Entry                        ; переход, если выбран разряд 1, спроектировать соответствующую комбинацию

Next3:          LD DE, #0000
                LD A, IYL
                ; Проверка выбора комбинации 3 в исходном коде группы.
                BIT 3, B
                LD HL, @Action.ProjectRenderVertexGroup.Next2
                JP NZ, @Action.ProjectRenderVertex.Entry                        ; переход, если выбран разряд 3, спроектировать соответствующую комбинацию

                ; Проверка выбора комбинации 2 в исходном коде группы.
Next2:          BIT 2, B
                LD DE, #0000
                LD A, IXL
                LD HL, @Action.ProjectRenderVertexGroup.Next6
                JP NZ, @Action.ProjectRenderVertex.Entry                        ; переход, если выбран разряд 2, спроектировать соответствующую комбинацию

Next6:          LD DE, #0000
                LD A, #00
                ; Проверка выбора комбинации 6 в исходном коде группы.
                BIT 6, B
                LD HL, @Action.ProjectRenderVertexGroup.Next7
                JP NZ, @Action.ProjectRenderVertex.Entry                        ; переход, если выбран разряд 6, спроектировать соответствующую комбинацию

Next7:          LD DE, #0000
                LD A, #00
                ; Проверка выбора комбинации 7 в исходном коде группы.
                BIT 7, B
                LD HL, @Action.ProjectRenderVertexGroup.Next5
                JP NZ, @Action.ProjectRenderVertex.Entry                        ; переход, если выбран разряд 7, спроектировать соответствующую комбинацию

Next5:          LD DE, #0000
                LD A, #00
                ; Проверка выбора комбинации 5 в исходном коде группы.
                BIT 5, B
                LD HL, @Action.ProjectRenderVertexGroup.Next4
                JP NZ, @Action.ProjectRenderVertex.Entry                        ; переход, если выбран разряд 5, спроектировать соответствующую комбинацию

Next4:          LD DE, #0000
                LD A, #00
                ; Проверка выбора комбинации 4 в исходном коде группы.
                BIT 4, B
                LD HL, @Action.ProjectRenderVertexGroup.Finish
                JP NZ, @Action.ProjectRenderVertex.Entry                        ; переход, если выбран разряд 4, спроектировать соответствующую комбинацию

                ; -----------------------------------------
                ; Возврат к CPU-стеку
                ; Расчёт конечного рабочего адреса, сохранение его младшего байта и восстановление внешнего SP.
Finish:         LD HL, #0000
                ADD HL, SP
                LD A, L
                LD (@ActionVertexGroupState.NextOffset), A
                LD SP, #0000
                RET

                ; -----------------------------------------
                endmodule
                endmodule
