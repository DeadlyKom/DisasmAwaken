                module Action
                module CheckCandidateListReady
                ; Документация [алгоритм и проверка](../../Docs/ActionCandidateGate.md)
                ; -----------------------------------------
                ; Проверка допуска класса и наличия непропущенного кандидата в списке
                ; исходная запись 17, адреса EA15..EA28
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, IX указывает запись с доступным ClassCode
                ;   действует договор CheckCandidateListClass, после A01B достижим первый байт не FF либо маркер FE
                ;   исходный ACTION банка 0 доступен, два дополнительных байта CPU-стека доступны, IRQ не вмешиваются
                ; Out:
                ;   для класса вне 0, 4, 5, 8, 1 и 9 возвращается AF=0044 и исходный HL
                ;   для допущенного класса HL указывает первый байт списка не FF, при FE возвращается A=FE и Z установлен
                ;   для байта 00..FD возвращается A=байт+1, Z сброшен, Carry установлен, F соответствует INC байта после CP с FE
                ;   DE и BC сохраняются, ни индекс кандидата, ни доступность его записи этой процедурой не проверяются
                ;   HL', DE', BC', AF', IX, IY, I/IM/IFF и paging сохраняются, SP после RET увеличен на 2
                ;   кроме двух байтов временного CPU-стека RAM сохраняется, R добавляет стоимость CheckCandidateListClass и 4 M1 при отказе класса
                ;   при допуске R добавляет к стоимости CheckCandidateListClass 7 M1 для FE либо 10 для кандидата, плюс 6 на каждый пропуск FF
                ; Corrupt:
                ;   HL при допуске класса, AF, R, два временных байта CPU-стека, SP внешним RET
                ; Note:
                ;   00 является разрешённым байтом кандидата и даёт A=1, FF пропускается, FE завершает список
                ;   4096 сценариев охватывают все классы с десятью списками и все первые байты списка для шести разрешённых классов
                ;   граница и число элементов списка не задаются по одному потребителю, полные игровые писатели ещё исследуются
                ;   все возможные длины списков, IRQ, сборка и нативный запуск не проверялись
                ; -----------------------------------------
                ; Проверка допуска полного класса к просмотру списка кандидатов.
Entry:          CALL @Action.CheckCandidateListClass.Entry
                JR Z, @Action.CheckCandidateListReady.StartList                 ; переход, если класс допущен и установлен Z, просмотреть список кандидатов

                ; Возврат Z для запрещённого класса без чтения списка и изменения HL.
                XOR A
                RET

                ; Подготовка курсора перед первым байтом списка, первый INC HL переходит к A01C.
StartList:      LD HL, @ActionCandidateListData.Slot00.Code - 1
                ; Поиск первого непропущенного байта, FF означает пропуск, FE завершает список.
NextItem:       INC HL
                LD A, (HL)
                CP @ActionCandidateListConst.ListEnd
                RET Z                                                           ; выход, если прочитан маркер FE, кандидаты отсутствуют

                ; Проверка пропуска FF, обычный байт 00..FD после INC даёт ненулевой результат.
                INC A
                JP Z, @Action.CheckCandidateListReady.NextItem                  ; переход, если прочитан FF и INC дал ноль, проверить следующий байт списка

                RET

                endmodule
                endmodule
