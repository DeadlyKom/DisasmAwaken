                module RefreshRecordClassAndOffsets
                ; Документация [алгоритм и проверка](../../Docs/ActionClassRefresh.md)
                ; -----------------------------------------
                ; Повторный выбор поведения записи по классу и передача общему подготовителю смещений
                ; исходная запись 17, адреса F003..F008
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, IX указывает доступную текущую FActionRecord
                ;   ClassCode AND 7F меньше 26, исходная таблица классов и договоры её целевых обработчиков действуют
                ;   потоки 0, 8 и 10 и списки поиска доступны при достигнутых вызовах, ACTION банка 0 выбран
                ;   двенадцать дополнительных байтов CPU-стека доступны, IRQ и повторный вход исключены
                ; Out:
                ;   реальный DispatchRecordClass исполняет выбранный обработчик с возвратом по F006
                ;   результаты полей и регистров определяются полным выбранным классом, старший бит индексирования диспетчера отбрасывается, отдельные фильтры детей его не маскируют
                ;   после возвращения ребёнка PC=F0F8 и SP равен входному SP, общий подготовитель ещё не исполнен этим договором границы
                ;   D, AF', IX, I/IM/IFF и paging сохраняются до F0F8, прочие регистры уточнены договорами выбранного ребёнка
                ;   R добавляет 15 M1 к стоимости выбранного обработчика, 13 диспетчера, один CALL и один JP
                ;   максимальная дополнительная рамка равна двенадцати байтам, внешнее слово возврата сохраняется
                ; Corrupt:
                ;   HL, E, BC, AF, HL', DE', BC', IY, R, условные поля записи, потоки и до двенадцати байтов CPU-стека по выбранному ребёнку
                ; Note:
                ;   это общий хвост отказа связанной записи по F003, искусственного RET вместо конечного JP не добавлено
                ;   39936 сценариев исполнили все 26 табличных записей и оба алиаса бита 7 при всех начальных R и трёх вариантах подстановки
                ;   все одиннадцать различных дочерних целей исполняются реально, сверены регистры, флаги, R, восемь банков и все записи
                ;   проверка заканчивается перед F0F8, полное произведение входов, IRQ, сборка и нативный запуск не выполнялись
                ; -----------------------------------------
                ; Повторный выбор поведения текущей записи по исходной таблице класса, настоящий CALL создаёт возврат F006.
Entry:          CALL @Action.DispatchRecordClass.Entry
                ; Передача исходного внешнего возврата общему подготовителю смещений после завершения выбранного класса.
                JP @Action.PrepareObjectOffsetTransform.Entry

