                module Action
                module AcquireLinkAndApplyOffsets
                ; Документация [алгоритм и проверка](../../Docs/ActionAcquireLocalState.md)
                ; -----------------------------------------
                ; Выбор связи и попытка создания дочерних записей перед обязательным расчётом локальных смещений
                ; исходная запись 17, адреса F6BD..F6CC
                ; In:
                ;   IX указывает активную FActionRecord, доступны поля связи, запроса детей и локальных фаз
                ;   действуют договоры CheckCandidateListReady, FindNearestListedRecord, SpawnLinkedClass9Records и ApplyRecordLocalOffsets
                ;   ACTION банка 0 и фазовые таблицы доступны, восемь дополнительных байтов CPU-стека доступны, IRQ и повторный вход исключены
                ; Out:
                ;   при Z допуска списка связь и создание детей пропускаются, общий хвост локальных фаз исполняется всегда
                ;   при NZ допуска результат FindNearestListedRecord записывается в LinkedIndex, в том числе старый ChosenIndex при отсутствии доступных кандидатов
                ;   после записи связи SpawnLinkedClass9Records вызывается с A=0E, родительский StateCode этой инструкцией не меняется
                ;   создатель может записать до двух детей класса 9 с начальным StateCode=0E, отказ не отменяет новую связь и бит запроса
                ;   затем физическим продолжением по F6CD выполняется ApplyRecordLocalOffsets до полного внешнего RET
                ;   HL, DE, BC, AF, AF' и IYL определяются вычислителем локальных фаз, IYH остаётся от выбора связи и попытки создания детей, при Z допуска сохраняется исходный
                ;   IX, I/IM/IFF и paging сохраняются на всех путях
                ;   альтернативные пары сохраняют результат создателя детей, включая обмен через EXX при раннем отказе выделения
                ;   SP после внешнего RET увеличен на два, дополнительная рамка до восьми байтов, внешнее слово возврата сохраняется
                ;   R добавляет 2 M1 к стоимости допуска и хвоста при Z либо 7 M1 к сумме всех четырёх детей при NZ
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IY, R, связь родителя, бит запроса, дети, фазовые операнды, коэффициенты и базы по договорам детей, до восьми байтов CPU-стека, SP внешним RET
                ; Note:
                ;   это исходная цель State12, A=0E является начальным состоянием детей, а не присваиванием состояния родителя
                ;   жёсткий порядок include, (0) AcquireLinkAndApplyOffsets.asm, (1) ApplyRecordLocalOffsets.asm
                ;   73984 сценария проверили реальные допуск, выбор, создание детей, коэффициенты и три умножителя до полного внешнего RET
                ;   точные регистры, флаги, R, восемь банков и все записи сверены, полное произведение входов, IRQ, сборка и нативный запуск не выполнялись
                ; -----------------------------------------
                ; Проверка разрешённого класса и наличия непропущенного байта в списке перед выбором связи.
Entry:          CALL @Action.CheckCandidateListReady.Entry
                JR Z, @Action.ApplyRecordLocalOffsets.Entry                     ; переход, если допуск вернул Z, пропустить выбор связи и детей, выполнить общий хвост локальных фаз

                ; Выбор ближайшей доступной записи, при отсутствии доступных записей возвращается прежний ChosenIndex.
                CALL @Action.FindNearestListedRecord.Entry
                ; Обновление связи родителя фактическим результатом выбора, отдельной проверки нового кандидата нет.
                LD (IX + @FActionRecord.LinkedIndex), A
                ; Подготовка начального состояния 0E для детей, состояние родителя этой загрузкой не изменяется.
                LD A, @ActionTargetTransitionConst.LinkedState
                ; Попытка создания дочерних записей, после возврата всегда продолжается общий хвост по F6CD.
                CALL @Action.SpawnLinkedClass9Records.Entry
                ; JP @Action.ApplyRecordLocalOffsets.Entry, продолжение в ApplyRecordLocalOffsets.asm

                endmodule
                endmodule
