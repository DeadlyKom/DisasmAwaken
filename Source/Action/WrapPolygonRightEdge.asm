                module WrapPolygonRightEdge
                ; Документация [алгоритм и проверка](../../Docs/ActionPolygonWrapRight.md)
                ; -----------------------------------------
                ; Оборачивание прямого поиска к первой First кольца
                ; исходная запись 17, адреса D3A8..D3AC
                ; In:
                ;   HL содержит страницу 90, прямой поиск достиг последнего нечётного индекса
                ;   DE содержит D текущей строки и E первоначальной Second, временный контекст сохранён UpdatePolygonRightEdge
                ; Out:
                ;   HL сохраняет H, L=1
                ;   DE, BC, AF сохраняются
                ;   HL', DE', BC', AF' сохраняются
                ;   IX и IY сохраняются, SP, I, IM, IFF и paging сохраняются
                ;   управление передано UpdatePolygonRightEdge.ReadNextRow, память и порты не записываются
                ;   R добавляет 2 M1, бит 7 R сохраняется
                ; Corrupt:
                ;   HL, только L, R
                ; Note:
                ;   короткий переходник сохраняет исходные адреса и инструкции, новый адрес возврата не создаётся
                ;   проверены точные регистры включая R и отсутствие записей RAM, полное игровое исполнение этим не доказывается
                ;   точные T, IRQ, сборка и нативный запуск не проверены
                ; -----------------------------------------
                ; Выбор первой First по нечётному индексу 1 без изменения страницы контура.
Entry:          LD L, #01
                JP @Action.UpdatePolygonRightEdge.ReadNextRow

