                module Action
                module AdvanceObjectOffsetFall
                ; Документация [алгоритм и проверка](../../Docs/ActionObjectOffsetFall.md)
                ; -----------------------------------------
                ; Уменьшение байта смещения и возврат сохранённого состояния по таймеру
                ; исходная запись 17, адреса EF9A..EFB4
                ; In:
                ;   IX указывает FActionRecord, байты 07, 17 и 16 доступны, банк 0 выбран
                ; Out:
                ;   байт 07 изменён на −2 по модулю 256, таймер 17 уменьшен по модулю 256
                ;   при нулевом результате таймера состояние восстановлено из байта 16
                ;   F соответствует DEC таймера с Carry изменения смещения, PC=F0F8, SP сохраняется
                ; Corrupt:
                ;   AF, R и поля смещения, таймера и состояния
                ; Note:
                ;   таймер 0 оборачивается в FF, изменение состояния выполняется при исходном таймере 1
                ;   11 M1 на обычном пути и 16 при переходе состояния, регистры и записи сверены во всех 65536 парах смещения и таймера
                ; -----------------------------------------
                ; Изменение байта смещения на два с сохранением байтового оборачивания.
Entry:          LD A, (IX + @FActionRecord.Unknown07)
                SUB #02
                LD (IX + @FActionRecord.Unknown07), A
                ; Уменьшение таймера хода, нулевой результат завершает фазу.
                LD A, (IX + @FActionRecord.Unknown17)
                DEC A
                LD (IX + @FActionRecord.Unknown17), A
                JP NZ, @Action.PrepareObjectOffsetTransform.Entry               ; переход, если таймер после уменьшения ненулевой, продолжить общий обработчик

                ; Смена состояния после истечения таймера.
                LD A, (IX + @FActionRecord.Unknown16)
                LD (IX + @FActionRecord.Unknown0A), A
                JP @Action.PrepareObjectOffsetTransform.Entry

                endmodule
                endmodule
