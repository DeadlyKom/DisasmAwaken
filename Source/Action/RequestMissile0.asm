                module Action
                module RequestMissile0
                ; Документация [запросы запуска ракет](../../Docs/ActionMissileRequests.md)
                ; -----------------------------------------
                ; Условный запрос запуска по Target0 с продолжением в общий хвост
                ; исходная запись 17, перенесённое ядро банка 5, адреса 704C..705C
                ; In:
                ;   HL, DE и BC числовых аргументов не задают, входной Z допускает обработку только при Z=1
                ;   выбранный Target задаёт код цели, FF означает отсутствие захвата, иной код относится к допустимой записи массива
                ;   действуют договоры CheckMissileLaunch и CompleteMissileLaunch, банк 0 выбран, 7FFD не заблокирован
                ;   общий CPU-стек допускает двадцать дополнительных байтов, IRQ не вмешиваются
                ; Out:
                ;   при входном Z=0 HL, DE, BC, AF, альтернативные регистры и IX/IY сохраняются, запись памяти и OUT отсутствуют
                ;   при Target=FF HL, DE и BC сохраняются, A=00, F=50 OR входной Carry, передано сообщение F2C5
                ;   при имеющемся коде и пустом запасе HL=9C12, DE и BC сохраняются, AF=0044, все три Target получают FF, передано сообщение F280
                ;   CommandDelay получает 5 при любом коде не FF, даже при последующем отказе по запасу
                ;   при допуске выбранный Target получает FF до попытки создания, C содержит его прежний код, результат соответствует CompleteMissileLaunch
                ;   IX, I, IM и IFF сохраняются, SP=входной SP+2, отказ очереди не меняет решение о пуске
                ; Corrupt:
                ;   HL, DE, BC и AF по пути, HL', DE', BC', AF' и IY после создания, R, рамка до двадцати байтов, CommandDelay, захваты, состояние общего хвоста, очередь и 7FFD
                ; Note:
                ;   это клавиатурный вход по таблице, соответствие физической клавише здесь ещё не установлено
                ;   первый код C0 также читается как старший байт перекрытого слова C0C9 последнего шага диспетчера
                ;   [Перекрытие кода и указателя](../../Docs/ActionKeyDispatchPrefix.md)
                ;   после позднего отказа потерянной цели или отсутствия слота выбранный захват остаётся снятым, боезапас сохраняется
                ;   при обоих предварительных отказах 7FFD получает 11 и 10, очередь может молча отклонить сообщение
                ;   точная стоимость R и содержимое временных рамок стека в родительской модели отдельно не проверяются
                ; -----------------------------------------
                ; Проверка допуска клавиатурного диспетчера по входному Z.
Entry:          RET NZ                                                          ; выход, если Z сброшен, запрос Target0 не обрабатывать

                ; Проверка захвата Target0 и наличия запаса через общий предварительный допуск.
                LD A, (@ActionMissileTargets.Value.Target0)
                CALL @Action.CheckMissileLaunch.Entry
                RET Z                                                           ; выход, если код цели отсутствует или выбранный запас равен нулю

                ; Сохранение кода цели в C и снятие выбранного захвата до попытки выделения слота.
                LD A, (@ActionMissileTargets.Value.Target0)
                LD C, A
                LD A, #FF
                LD (@ActionMissileTargets.Value.Target0), A
                ; JP @Action.CompleteMissileLaunch.Entry, продолжение в CompleteMissileLaunch.asm

                endmodule
                endmodule
