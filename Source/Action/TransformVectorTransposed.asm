                module Action
                module TransformVectorTransposed
                ; Документация [транспонированная матрица и CPU-стек](../../Docs/ActionVectorWrapper.md)
                ; -----------------------------------------
                ; Вычисление трёх выходных слов с временно транспонированной матрицей, сохранением IX/IY и восстановлением CPU-стека
                ; исходная запись 17, общая RAM банка 2, адреса ACEA..AD1C
                ; In:
                ;   HL, DE и BC три исходных знаковых слова, AF числового аргумента не задаёт
                ;   девять коэффициентов и выходы ActionPatchedVectorState доступны, исполняется ACTION банка 0
                ;   действуют договоры SwapCodePatchWords и ComputePatchedVector, IX и IY сохраняются
                ;   CPU-стек допускает шесть дополнительных байтов, повторный вход и IRQ при арифметическом SP запрещены
                ; Out:
                ;   HL=Output0, DE=Output1, BC=Output2 после завершения либо частичного выхода ComputePatchedVector
                ;   AF и альтернативный AF соответствуют последнему ADC и умножителю вычислителя, P/V установлен при переполнении
                ;   HL', DE' и BC' сохраняются, IX и IY восстановлены со стека, SP=входной SP+2
                ;   Input0..Input2 получают входные HL, DE и BC, SavedSP получает входной SP-4, SavedIX получает входной IX
                ;   все шесть обмениваемых слов, включая старшие байты, восстановлены вторым обменом даже после переполнения
                ;   I, IM и IFF сохраняются, портовых записей нет, максимальная дополнительная рамка шесть байтов
                ;   R равен стоимости ComputePatchedVector на транспонированной матрице плюс 65 M1 обоих обменов и обёртки
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', R, три входных операнда, SavedSP, SavedIX, выходы вычислителя, шесть байтов CPU-стека
                ; Note:
                ;   при переполнении загружаются все три выходных слова, невычисленные компоненты сохраняют старые значения
                ;   SP сохраняется после PUSH IX и PUSH IY, восстанавливается в Resume до второго CALL
                ;   матрица транспонируется обменом трёх пар полных слов, префиксы после операндов также временно переставляются
                ;   временное изменение матрицы и самомодификация SavedSP и SavedIX исключают повторный вход до завершения
                ; -----------------------------------------
                ; Сохранение IX и IY на настоящем CPU-стеке до перехода на арифметический SP.
Entry:          PUSH IX
                PUSH IY
                ; Сохранение трёх исходных компонентов в разнесённых операндах первой строки вычислителя.
                LD (@ActionPatchedVectorState.Input0), HL
                LD (@ActionPatchedVectorState.Input1), DE
                LD (@ActionPatchedVectorState.Input2), BC
                ; Транспонирование матрицы перестановкой внедиагональных элементов, обмениваются полные слова с префиксами.
                CALL @Action.SwapCodePatchWords.Entry
                ; Сохранение настоящего SP после двух PUSH, значение указывает на сохранённый IY.
                LD (@ActionVectorWrapperState.SavedSP), SP
                ; Подготовка переходного продолжения, вычислитель вернёт управление через JP (IY).
                LD IY, @Action.TransformVectorTransposed.Resume
                ; Расчёт выходов с арифметическим SP, обычного CALL здесь нет.
                JP @Action.ComputePatchedVector.Entry

                ; -----------------------------------------
                ; Восстановление CPU-стека и исходной матрицы
                ; Этот LD SP,nn исполнится и после переполнения, его операнд записан перед переходом.
Resume:         LD SP, #0000
                ; Восстановление всех шести исходных слов вторым обменом, флаги вычислителя сохраняются.
                CALL @Action.SwapCodePatchWords.Entry
                ; Чтение трёх выходных слов, при переполнении часть из них может сохранять старые значения.
                LD HL, (@ActionPatchedVectorState.Output0)
                LD DE, (@ActionPatchedVectorState.Output1)
                LD BC, (@ActionPatchedVectorState.Output2)
                ; Восстановление IY и IX из исходной рамки перед обычным RET.
                POP IY
                POP IX
                RET

                ; -----------------------------------------
                endmodule
                endmodule
