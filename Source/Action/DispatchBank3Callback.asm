                module Action
                module DispatchBank3Callback
                ; Документация [алгоритм и проверка](../../Docs/ActionBankedCallback.md)
                ; -----------------------------------------
                ; Передача управления HL с конфигурацией банка 3, обменом AF и возвратным хвостом Runtime
                ; исходная запись 17, перенесённое ядро 6000..7F8E, смещения #0F2C..#0F3C
                ; In:
                ;   HL содержит адрес целевого обработчика, DE числового аргумента не задаёт, BC сохраняется
                ;   AF и AF' обмениваются, обработчику передаётся прежний альтернативный AF
                ;   код фиксированных банков 5 и 2 доступен, на CPU-стеке внешний возврат и место для четырёх временных байтов
                ;   IRQ не вмешиваются, выполнение цели и её договор исследуются отдельно
                ; Out:
                ;   непосредственно после JP управление передано по исходному HL, сам обработчик ещё не исполнен
                ;   HL и BC сохранены, DE=6D00, AF=входной AF', AF'=входной AF, остальные альтернативные пары и IX сохранены
                ;   IY=ContextBase по A783, SP=входной SP-2, на вершине 6D00, за ним исходный внешний возврат
                ;   в 7FFD выдан 13, при блокировке аппаратная страница остаётся прежней, I, IM и IFF сохраняются
                ;   R получает 16 M1 с сохранением бита 7, четыре временных байта стека описаны в документации
                ; Corrupt:
                ;   DE, AF, AF', IY, SP, R, четыре временных байта CPU-стека, 7FFD при разрешённой записи
                ; Note:
                ;   это точный договор передачи управления, окончательный игровой результат цели не объявляется доказанным
                ;   при штатном RET цели управление попадает в RestoreRuntimePage, который выдаёт 10 и возвращается внешнему вызывающему
                ;   блокировка 7FFD может оставить другой банк на входе в цель либо банк 3 на возврате, нового обхода блокировки нет
                ;   393216 сценариев проверили все адреса HL, AF, AFprime и BC при шести исходных страницах
                ;   сопоставлены регистры включая R, RAM, записи стека и настоящий OUT, произвольная цель не исполнялась
                ;   полное произведение AF и AFprime, договоры целей, IRQ, точные T, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; Преобразование регистрового контекста, в основной AF передаётся прежний альтернативный AF.
Entry:          EX AF, AF'
                ; Сохранение передаваемого A в E на время выбора страницы.
                LD E, A
                ; Выбор полной конфигурации 13, при заблокированном 7FFD запись не меняет аппаратный банк.
                LD A, @ActionBankCallbackConst.CallbackPage
                CALL @Action.SelectMemoryPage.Entry
                ; Восстановление передаваемого A после SelectMemoryPage без изменения передаваемого F.
                LD A, E
                ; Создание исходного IY-контекста обработчика, формат данных по A783 устанавливается отдельно.
                LD IY, @ActionBankedCallbackState.ContextBase
                ; Создание возврата банкового обработчика через отдельный хвост RestoreRuntimePage.
                LD DE, @Action.RestoreRuntimePage.Entry
                PUSH DE
                ; Передача управления исходному HL, новая инструкция CALL вместо JP не добавляется.
                JP (HL)

                endmodule
                endmodule
