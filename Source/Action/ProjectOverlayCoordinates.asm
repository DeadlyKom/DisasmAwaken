                module Action
                module ProjectOverlayCoordinates
                ; Документация [алгоритм и проверка](../../Docs/ActionOverlayProjection.md)
                ; -----------------------------------------
                ; Проекция двух координат относительно общей глубины с центром 128, 48
                ; исходная запись 17, адреса ADC5..AE14
                ; In:
                ;   HL задаёт вертикальную координату signed16, DE глубину signed16, BC горизонтальную координату signed16
                ;   подготовлены таблицы DivideScaledLogarithmic по 9100..93FF, её операнды доступны для записи
                ;   код находится в общей RAM, на стеке внешний возврат и шесть доступных байтов ниже него, IRQ не вмешиваются
                ; Out:
                ;   HL при успехе равен экранному X, при отказе частичному результату отказавшего DivideScaledLogarithmic
                ;   DE при успехе равен экранному Y, при отказе содержит исходную глубину
                ;   BC содержит результат последнего достигнутого делителя, при успехе это горизонтальный вызов
                ;   AF при успехе равен #0044, при отказе любой оси #0100, Z означает успех, Carry сброшен в обоих случаях
                ;   HL', DE', BC' сохраняются
                ;   AF' содержит результат последнего достигнутого делителя, при успехе это горизонтальный вызов
                ;   IX и IY сохраняются, I, IM, IFF и paging сохраняются
                ;   SP после внешнего RET равен входному SP+2, шесть байтов под исходным SP содержат временный кадр последнего достигнутого CALL
                ;   R добавляет 12+7*N+Kv M1 при отказе вертикали, 28+21*N+Kv+Kh при отказе горизонтали, 32+28*N+Kv+Kh при успехе, бит 7 R сохраняется
                ;   Y=wrap16(signedRatio(вертикаль, глубина)+48), X=wrap16(signedRatio(горизонталь, глубина)+128)
                ;   signedRatio вызывает DivideScaledLogarithmic со знаменателем abs16 глубины, при отрицательной глубине отрицает его результат
                ;   сначала проверяется вертикаль, Carry делителя немедленно выбирает отказ без горизонтального деления
                ;   изменяется ShiftFraction либо ShiftInteger по достигнутым ветвям делителя
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', R, операнды делителя и шесть временных байтов CPU-стека
                ; Note:
                ;   N равен 1 только при отрицательной исходной глубине, Kv и Kh полные стоимости достигнутых делителей с их RET
                ;   signedRatio обозначает исходную табличную аппроксимацию, точное арифметическое деление не подставляется
                ;   abs16(8000)=8000, нулевая глубина передаётся делителю без отдельного запрета, исключительные результаты сохранены
                ;   проверки границ экрана здесь нет, её выполняет вызывающий ToggleTargetOverlay
                ;   первый кадр содержит исходную горизонталь, второй использует то же место для уже рассчитанного экранного Y
                ;   8192 сценария сверили все регистры включая R, полное число M1, точную последовательность записей модели, оба отказа и успех
                ;   Controls.ToggleTargetOverlay использует JR NZ, Action.ToggleTargetOverlay использует RET NZ после каждого вызова, внешний Carry делителя не передаётся
                ;   время шинных циклов, IRQ, все совместные входы и нативный запуск не проверены
                ; -----------------------------------------
                ; Сохранение горизонтали и исходной глубины для первой оси.
Entry:          PUSH BC
                PUSH DE
                ; Проверка знака общей глубины перед делением вертикали.
                BIT 7, D
                JR Z, @Action.ProjectOverlayCoordinates.DivideVertical          ; переход, если глубина неотрицательна, её модуль уже готов

                ; Расчёт модуля глубины в дополнительном коде, 8000 остаётся 8000.
                LD A, E
                CPL
                LD E, A
                LD A, D
                CPL
                LD D, A
                INC DE
                ; Расчёт приближённого вертикального отношения исходным табличным делителем.
DivideVertical: CALL @Action.DivideScaledLogarithmic.Entry
                POP DE
                JP C, @Action.ProjectOverlayCoordinates.Reject                  ; переход, если вертикальное отношение дало отказ, снять сохранённую горизонталь

                ; Проверка исходного знака глубины после восстановления DE.
                BIT 7, D
                JR Z, @Action.ProjectOverlayCoordinates.CenterVertical          ; переход, если исходная глубина неотрицательна, знак вертикали уже правильный

                ; Отрицание отношения для отрицательной глубины.
                LD A, L
                CPL
                LD L, A
                LD A, H
                CPL
                LD H, A
                INC HL
                ; Перенос вертикального отношения к центру Y=48 и сохранение экранного Y вместо исходной горизонтали.
CenterVertical: LD BC, #0030
                ADD HL, BC
                LD B, H
                LD C, L
                POP HL
                PUSH BC
                ; Сохранение исходной глубины и повторная проверка её знака для горизонтали.
                PUSH DE
                BIT 7, D
                JR Z, @Action.ProjectOverlayCoordinates.DivideHoriz             ; переход, если глубина неотрицательна, её модуль для горизонтали уже готов

                ; Расчёт того же модуля глубины, исходное слово остаётся в кадре.
                LD A, E
                CPL
                LD E, A
                LD A, D
                CPL
                LD D, A
                INC DE
                ; Расчёт горизонтального отношения после переноса сохранённой горизонтали в HL.
DivideHoriz:    CALL @Action.DivideScaledLogarithmic.Entry
                POP DE
                JP C, @Action.ProjectOverlayCoordinates.Reject                  ; переход, если горизонтальное отношение дало отказ, снять сохранённый экранный Y

                ; Проверка исходного знака глубины после второго деления.
                BIT 7, D
                JR Z, @Action.ProjectOverlayCoordinates.CenterHoriz             ; переход, если исходная глубина неотрицательна, знак горизонтали уже правильный

                ; Отрицание горизонтального отношения для отрицательной глубины.
                LD A, L
                CPL
                LD L, A
                LD A, H
                CPL
                LD H, A
                INC HL
                ; Перенос горизонтального отношения к центру X=128 и возврат экранного Y в DE.
CenterHoriz:    LD DE, #0080
                ADD HL, DE
                POP DE
                XOR A
                RET

                ; Снятие оставшегося слова кадра и возврат A=1, Z=0, Carry=0.
Reject:         POP AF
                XOR A
                INC A
                RET

                endmodule
                endmodule
