                module Action
                module ReleaseBoostDebrisRecords
                ; Документация [алгоритм и проверка](../../Docs/ActionClass14Reuse.md)
                ; -----------------------------------------
                ; Освобождение всех активных записей мусора форсажа через повторный поиск
                ; исходная запись 17, перенесённый код ACTION в фиксированном банке 5, смещения #03AF..#03B9
                ; In:
                ;   HL сохраняется, D не задаёт аргумента и заменяется кодом 14, E сохраняется, BC и AF числовых аргументов не задают
                ;   от A100 с шагом FActionRecord достижим маркер 8080, записи доступны для чтения и пометки
                ;   действуют договоры FindRecordByCode, NextActiveRecord и MarkIYRecordForReuse, выбран банк 0
                ;   CPU-стек содержит внешний возврат и допускает четыре временных байта без пересечения с изменяемыми записями, IRQ не вмешивается
                ; Out:
                ;   HL сохранён, D=14, E сохранён, BC=0040, AF=8042
                ;   HL', DE', BC', AF', IX сохраняются, IY указывает на маркер конца, I/IM/IFF и paging сохраняются
                ;   все достигнутые активные записи класса 14 получили Component0=8000 и ReuseByte=FF, другие классы и неактивные записи сохранены
                ;   SP после RET равен входному SP+2, в RAM остаются четыре временных байта вложенных CALL
                ;   R получает сумму M1 всех вызовов FindRecordByCode плюс 12*k+3, k - число помеченных записей, бит 7 R сохраняется
                ; Corrupt:
                ;   DE только D, BC, AF, IY, R, три поля каждой выбранной записи и четыре байта CPU-стека
                ; Note:
                ;   код 14 соответствует авторскому T_TRASH, мусор для форсажа, создатель выбирает модель TRASH через смещение C0
                ;   после каждой пометки поиск снова начинается перед A100, ранее помеченные записи пропускаются как неактивные
                ;   это повторный поиск, а не однократный линейный проход, оптимизация изменила бы исходную последовательность чтений и время
                ;   RET Z здесь означает отсутствие класса 14, неоднозначность найденного FF из общего поиска для фиксированного кода 14 не возникает
                ;   ReuseByte=FF обеспечивает однократный пропуск при следующем достигшем записи поиске доступного места
                ;   1874 сценария проверили все позиции исходного массива в трёх состояниях, 1024 смешанных списка, крайние списки и все входные F
                ;   исполнены настоящие поиск, итератор и IY-пометка, сопоставлены регистры включая R, все восемь банков RAM и кратность записей
                ;   для 26 неактивных записей получены 279 M1, для 26 активных записей класса 14 получены 4283 M1, это не расчёт T
                ;   полное пространство списков, порядок шинных циклов стека, IRQ, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Повторный поиск класса 14
                ; Подготовка полного кода HalvedClass, последующий поиск каждый раз начинает просмотр перед A100.
Entry:          LD D, @ActionOffsetConst.HalvedClass
                ; Поиск первой активной записи указанного класса, ранее помеченные записи пропускаются итератором.
                CALL @Action.FindRecordByCode.Entry
                RET Z                                                           ; выход, если активных записей класса 14 больше не найдено, IY указывает на маркер конца

                ; Пометка найденной записи IY кодом доступности 8000 и ReuseByte=FF, остальные её поля сохраняются.
                CALL @Action.MarkIYRecordForReuse.Entry
                ; Повтор поиска с начала массива после каждой пометки, физическое продолжение от текущего IY не используется.
                JR @Action.ReleaseBoostDebrisRecords.Entry

                endmodule
                endmodule
