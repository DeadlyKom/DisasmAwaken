                module Action
                module SetClass18ObjectState
                ; Документация [алгоритм и проверка](../../Docs/ActionObjectStateDispatch.md)
                ; -----------------------------------------
                ; Установка состояния 0A у записи класса 12h перед диспетчеризацией
                ; исходная запись 17, перенесённое ядро 6000..7F8E, смещения #9075..#907B
                ; In:
                ;   IX указывает запись FActionRecord, ветвь F7C6 передаёт сюда ClassCode=12h
                ; Out:
                ;   в байт состояния записано 0A, PC получает вход диспетчера F843, SP, регистры и флаги сохранены
                ; Corrupt:
                ;   байт состояния и R
                ; Note:
                ;   три M1 до диспетчера, исполнение целевого обработчика проверяется отдельно
                ; -----------------------------------------
                ; Назначение состояния 0A перед общей косвенной передачей.
Entry:          LD (IX+#0A), #0A
                JP @Action.DispatchObjectState.CallHandler

                endmodule
