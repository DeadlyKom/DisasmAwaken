                module Action
                module EjectMine
                ; Документация [выброс груза и мины](../../Docs/ActionEjectCommands.md)
                ; -----------------------------------------
                ; Списание одной мины и попытка создания помеченной записи класса 19
                ; исходная запись 17, перенесённое ядро банка 5, адреса 75CF..7605
                ; In:
                ;   HL, DE, BC и AF входных числовых аргументов не задают, C сохраняемый контекст
                ;   CommandDelay допускает обработку только при нуле, банк 0 выбран, paging разблокирован
                ;   особая запись A780 задаёт родительские поля SpawnPrepared, доступны свободные строки и конечный список A01C
                ;   очередь Controls банка 1 соответствует QueueTextItemBank1, доступны восемнадцать дополнительных байтов CPU-стека, IRQ не вмешиваются
                ; Out:
                ;   при ненулевой задержке HL, DE и BC сохраняются, A содержит задержку, F соответствует AND A, память и paging не меняются
                ;   при нулевой задержке CursorA получает EE1B, CommandDelay получает 20 до проверки наличия груза или мин
                ;   при попытке создания IX получает A780 и не восстанавливается, другие результаты общего тела следуют SpawnPrepared
                ;   при отсутствии свободного места уже списанный исходный байт не восстанавливается, сообщение об успешном выбросе всё равно передаётся
                ;   на каждом пути с нулевой задержкой ставится ровно одно сообщение, OUT 7FFD получает 11 и 10, конечная страница 10
                ;   внешний SP после RET равен входному SP+2, максимальная дополнительная глубина восемнадцать байтов, точные R и такты родительской композиции не сверялись
                ;   MineMx1.Value является полным восьмибитовым счётчиком, ноль даёт отказ, FF означает 255 и также уменьшается
                ;   при нулевом запасе HL=EE1B, DE и BC сохранены, AF=0054, IX/IY и альтернативные регистры сохраняются, передано F412
                ;   при ненулевом запасе он уменьшается на один до создания, SpawnPrepared получает HL=EE80, A=1, IX=A780
                ;   созданный объект получает Unknown11=1, PickupKind=0 и пометку ReuseByte=10, производный код списка равен 36, передано F402
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, R, CommandDelay, CursorA, исходный байт запаса, создаваемая запись, пометки поиска, список, очередь, paging и восемнадцать временных байтов стека по пути
                ; Note:
                ;   на достигнутом участке событий UpdateFrame бит 2 запрашивает списание 40 из уровня защиты SHILD, при нехватке текущего уровня выполняется переход ShowNoiseBeforeReload
                ;   при успешном подборе созданной помеченной записи без промежуточного изменения её полей RequestAimOrCollectTarget добавляет единицу виду 0 и устанавливает бит 2 ActionPanelEvents.Value.Flags
                ;   при успешном создании общий вход задаёт ClassCode=13 и ModelOffset=98 модели CRG1, собственный хвост команды их не заменяет
                ;   сообщение F402 говорит о мине, название запаса совпадает с исходным авторским полем MineMx1
                ;   при отказе поиска мина уже списана, при отказе очереди созданная запись класса 13 не удаляется
                ;   все 256 полных значений запаса проверены с четырьмя вариантами поиска и шестью вариантами списка
                ; -----------------------------------------
                ; Проверка задержки перед списанием мины.
Entry:          LD A, (@ActionMissileLaunchState.CommandDelay)
                AND A
                RET NZ                                                          ; выход, если CommandDelay ненулевой, запас мин и состояние сохранить

                ; Выбор исходного звукового потока до проверки запаса мин.
                LD HL, @ActionEjectConst.Sound
                LD (@ActionAyEffectState.CursorA), HL
                ; Обновление задержки принятой команды даже при отсутствии мин.
                LD A, @ActionEjectConst.Delay
                LD (@ActionMissileLaunchState.CommandDelay), A
                ; Проверка полного восьмибитового счётчика мин, FF не является запретом.
                LD A, (@ActionShipEquipment.MineMx1.Value)
                AND A
                JR Z, @Action.EjectMine.NoMines                                 ; переход, если запас мин равен нулю, передать сообщение об отсутствии

                ; Списание одной мины до попытки выделения объекта.
                DEC A
                LD (@ActionShipEquipment.MineMx1.Value), A
                ; Создание подготовленного вида 80 с единичным значением Unknown11, H сохраняется равным EE.
                LD A, #01
                LD L, #80
                LD IX, @ActionLinkedContextConst.SpecialRecord
                CALL @Action.CreateCargoAndUpdateList.SpawnPrepared
                ; Передача сообщения о сброшенной мине даже при отказе выделения объекта.
                PUSH DE
                LD DE, @ControlsFlightText.MineEjected
                CALL @Action.QueueTextItemBank1.Entry
                POP DE
                RET

                ; Передача сообщения об отсутствии мин с сохранением DE.
NoMines:        PUSH DE
                LD DE, @ControlsFlightText.NoMines
                CALL @Action.QueueTextItemBank1.Entry
                POP DE
                RET

                endmodule
                endmodule
