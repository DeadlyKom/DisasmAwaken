                module Action
                module PrepareRecordScale
                ; Документация [алгоритм и проверка](../../Docs/ActionRecordScale.md)
                ; -----------------------------------------
                ; Сохранение CPU SP, временное деление смещений класса 14 и выбор числа удвоений по заголовку модели
                ; исходная запись 17, окно ACTION банка 0, смещения #855C..#859E
                ; In:
                ;   HL, DE, BC и AF не задают числовых аргументов, DE и BC сохраняются
                ;   IX - адрес FActionRecord, ClassCode доступен для чтения, Unknown06 содержит чётное смещение исходной таблицы моделей 9E00
                ;   таблица 128 указателей и OBJECT3D в банке 4 соответствуют оригиналу, старший байт первого слова модели e лежит в диапазоне 1..5
                ;   Active0..2 доступны для чтения и записи, Original0..2 и SavedCpuSP доступны для записи, при ClassCode=14 нужны все три исходных слова
                ;   7FFD не заблокирован, в окне C000 выбран банк 0, IRQ не вмешивается, CPU-стек допускает шесть дополнительных байтов и не пересекается с записью и операндами
                ; Out:
                ;   HL=00C8, DE и BC сохраняются, A=6-e, F от SUB 6,e
                ;   HL', DE', BC', AF', IX и IY сохраняются, I/IM/IFF сохраняются, SP равен входному SP, RET здесь не выполняется
                ;   SavedCpuSP равен входному SP, ShiftSkip=6-e, PC=E59F+6-e, это один из входов E5A0..E5A4
                ;   при ClassCode=14 Original0..2 получают исходные Active0..2, активные слова заменяются знаковыми половинами с округлением вниз
                ;   при другом классе Active0..2 и Original0..2 сохраняются, запись FActionRecord не меняется
                ;   OUT 7FFD получает 14 и 10, итоговый банк 0 с ROM 1, R получает 62 M1 для класса 14 и 41 M1 для другого класса
                ;   записаны шесть временных байтов под входным SP, после выхода они не восстановлены
                ; Corrupt:
                ;   HL, AF, R, SavedCpuSP, ShiftSkip, шесть байтов CPU-стека, 7FFD
                ;   Active0..2 и Original0..2 только при ClassCode=14
                ; Note:
                ;   значения Active и Original являются существующими операндами исполняемого кода, дополнительная память не выделяется
                ;   исходный JR по E59D содержит FE и возвращается на себя, перед исполнением этот байт обязательно заменяется на 6-e
                ;   после перехода остаётся e-1 инструкций ADD HL,HL, они расположены уже в UpdateRecordComponents и не выполняются внутри этого договора
                ;   последующее значение HL=200*2^(e-1), потребитель вычисляет B=125-H, это не доказательство всего обновления записи
                ;   32768 сценариев выполнили настоящий ReadObjectHeaderWord и селектор страниц для всех 128 исходных указателей и всех кодов класса
                ;   проверены регистры включая R, все восемь банков RAM и кратность записей, порядок аппаратных шинных циклов не доказан
                ;   нечётные индексы, изменённые заголовки, игровые имена классов, IRQ, точные T, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Сохранение CPU-стека
                ; Сохранение исходного SP в операнд восстановления, следующий обработчик использует SP для чтения и записи компонент.
Entry:          LD (@ActionOffsetState.SavedCpuSP), SP
                ; Проверка полного кода ClassCode, только HalvedClass требует временно уменьшенных вычитаемых слов.
                LD A, (IX+FActionRecord.ClassCode)
                CP @ActionOffsetConst.HalvedClass
                JR NZ, @Action.PrepareRecordScale.ReadModelScale                ; переход, если ClassCode отличается от HalvedClass и делить смещения не требуется

                ; -----------------------------------------
                ; Временные смещения класса 14
                ; Чтение Active0 и сохранение исходного значения в Original0 для RestoreHalvedOffsets.
                LD HL, (@ActionOffsetState.Active0)
                LD (@ActionOffsetState.Original0), HL
                ; Расчёт знаковой половины Active0, отрицательное нечётное слово округляется вниз.
                SRA H
                RR L
                ; Обновление Active0 для следующего вычитания из Component0.
                LD (@ActionOffsetState.Active0), HL
                ; Чтение Active1 и сохранение исходного значения в Original1.
                LD HL, (@ActionOffsetState.Active1)
                LD (@ActionOffsetState.Original1), HL
                ; Расчёт знаковой половины Active1 с сохранением знакового разряда.
                SRA H
                RR L
                ; Обновление Active1 для следующего вычитания из Component1.
                LD (@ActionOffsetState.Active1), HL
                ; Чтение Active2 и сохранение исходного значения в Original2.
                LD HL, (@ActionOffsetState.Active2)
                LD (@ActionOffsetState.Original2), HL
                ; Расчёт знаковой половины Active2 с округлением отрицательных нечётных слов вниз.
                SRA H
                RR L
                ; Обновление Active2 для следующего вычитания из Component2.
                LD (@ActionOffsetState.Active2), HL
                ; -----------------------------------------
                ; Выбор числа удвоений
                ; Чтение Unknown06 как байтового смещения таблицы моделей, поле намеренно не переименовано для всех остальных потребителей.
ReadModelScale: LD A, (IX+FActionRecord.Unknown06)
                ; Чтение первого слова исходной модели с настоящим переключением банка 4 и возвратом к банку 0.
                CALL @Action.ReadObjectHeaderWord.Entry
                ; Расчёт числа пропускаемых удвоений, старший байт e исходного заголовка лежит в диапазоне 1..5.
                LD A, @ActionRecordScaleConst.SkipBase
                SUB H
                ; Подготовка начального значения 200, фактические удвоения выполняются после изменяемого JR.
                LD HL, @ActionRecordScaleConst.InitialValue
                ; Обновление смещения ShiftSkip в JR, цель равна адресу следующего байта E59F плюс 6-e.
                LD (@ActionRecordScaleState.ShiftSkip), A
                ; -----------------------------------------
                ; Передача в цепь удвоений
                ; Исходный FE заменён на 6-e, исполнение продолжается по E5A0..E5A4 внутри UnknownE5A0.asm.
DispatchScale:  JR @Action.PrepareRecordScale.DispatchScale                     ; после изменения ShiftSkip продолжение в выбранной точке цепи удвоений

                ; -----------------------------------------
                endmodule
                endmodule
