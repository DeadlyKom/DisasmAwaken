                module Action
                module DivideScaledLogarithmic
                ; Документация [алгоритм и проверка](../../Docs/ActionLogRatio.md)
                ; -----------------------------------------
                ; Приближённое отношение с масштабом 256 через нормализацию, разность логарифмов и обратную таблицу
                ; исходная запись 17, код ACTION банка 2, адреса AE73..AF42, таблицы 9100..93FF подготовлены загрузчиком, смещения #4E73..#4F42
                ; In:
                ;   HL числитель signed16, DE знаменатель, обычный числовой смысл отношения доказан для положительного DE от 1 до 7FFF
                ;   BC и AF числовых аргументов не задают, входной AF' перезаписывается
                ;   страницы 9100 и 9200 построены BuildLogarithmTable, страница 9300 построена BuildExponentialTable
                ;   на CPU-стеке внешний возврат, два операнда относительных переходов допускают запись, IRQ не вмешиваются
                ; Out:
                ;   при обычном выходе HL приближает 256*числитель/знаменатель с восстановлением знака, Carry=0
                ;   при отрицательной знаковой разности логарифмов HL=0, A младший байт табличного логарифма числителя, F соответствует AND A, Carry=0
                ;   при неотрицательной разности с показателем больше 15 Carry=1, HL остаётся 0100 OR байт обратной таблицы, это не насыщенный результат
                ;   при переполнении A=15-показатель по модулю байта, F соответствует SUB этого показателя из 15, отрицательный знак числителя не восстанавливается
                ;   DE содержит нормализованный табличный логарифм знаменателя, C=0, B показатель разности либо 8+число сдвигов числителя при отрицательной разности
                ;   при обычном положительном результате A содержит удвоенный входной H по модулю байта, при отрицательном A равен инверсии старшего байта модуля результата, F соответствует AND A
                ;   при обычном выходе AF' хранит байт смещения изменённого JR и флаги последнего расчёта сдвига, при ранних выходах AF' хранит промежуточный признак знака
                ;   HL', DE', BC', IX, IY, I, IM и IFF сохраняются, SP=входной SP+2, дополнительных стековых записей и OUT нет
                ;   при обычном показателе 0..7 ShiftFraction получает 7-показатель, при показателе 8..15 ShiftInteger получает 15-показатель, остальные пути операнды не пишут
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', R, ShiftFraction либо ShiftInteger при обычном выходе
                ; Note:
                ;   таблицы задают приближение, обычное деление Z80 или исправление нулей вместо исходного алгоритма не подставляется
                ;   нормализация использует не больше семи SRA H, для отрицательного знаменателя сохраняется исходная арифметическая нормализация
                ;   модуль числителя 8000 остаётся 8000, его последующая нормализация имеет особый исходный результат
                ;   при HL=0 и DE=0 возвращается HL=0100 и Carry=0, при HL=1 и DE=0 Carry=1 и HL=0100
                ;   показатель сравнивается по старшему байту разности таблиц, Carry не является проверкой точного математического переполнения 256*HL/DE
                ;   полный покадровый потребитель и проекция этим локальным договором не подтверждены
                ; -----------------------------------------
                ; -----------------------------------------
                ; Нормализация знаменателя
                ; Перенос знаменателя в HL и очистка счётчика сдвигов B.
Entry:          LD BC, #0000
                EX DE, HL
                INC H
                DEC H
                JR Z, @Action.DivideScaledLogarithmic.ReadDenLog                ; переход, если старший байт знаменателя нулевой, сдвиги не требуются

                INC B
                SRA H
                JR Z, @Action.DivideScaledLogarithmic.LastDenShift              ; переход, если старший байт знаменателя после SRA нулевой, выполнить последний RR L

                RR L
                INC B
                SRA H
                JR Z, @Action.DivideScaledLogarithmic.LastDenShift              ; переход, если старший байт знаменателя после SRA нулевой, выполнить последний RR L

                RR L
                INC B
                SRA H
                JR Z, @Action.DivideScaledLogarithmic.LastDenShift              ; переход, если старший байт знаменателя после SRA нулевой, выполнить последний RR L

                RR L
                INC B
                SRA H
                JR Z, @Action.DivideScaledLogarithmic.LastDenShift              ; переход, если старший байт знаменателя после SRA нулевой, выполнить последний RR L

                RR L
                INC B
                SRA H
                JR Z, @Action.DivideScaledLogarithmic.LastDenShift              ; переход, если старший байт знаменателя после SRA нулевой, выполнить последний RR L

                RR L
                INC B
                SRA H
                JR Z, @Action.DivideScaledLogarithmic.LastDenShift              ; переход, если старший байт знаменателя после SRA нулевой, выполнить последний RR L

                RR L
                INC B
                SRA H
LastDenShift:   RR L
                ; Поиск младшего и старшего байтов логарифма по нормализованному L, добавление 256 за каждый сдвиг.
ReadDenLog:     LD H, #91
                LD A, (HL)
                INC H
                LD H, (HL)
                LD L, A
                ADD HL, BC
                ; Проверка знака исходного числителя перед вычислением его модуля.
                EX DE, HL
                LD A, H
                RLA
                JR NC, @Action.DivideScaledLogarithmic.NormalizeNum             ; переход, если числитель неотрицателен, модуль уже получен

                ; Расчёт модуля отрицательного числителя и сохранение Carry=1 признака знака, случай 8000 не исправляется.
                LD A, L
                CPL
                LD L, A
                LD A, H
                CPL
                LD H, A
                INC HL
                SCF
                ; -----------------------------------------
                ; Нормализация числителя
                ; Сохранение признака знака в альтернативном AF и начального масштаба 8*256 в BC.
NormalizeNum:   EX AF, AF'
                LD BC, #0800
                INC H
                DEC H
                JR Z, @Action.DivideScaledLogarithmic.ReadNumLog                ; переход, если старший байт модуля числителя нулевой, сдвиги не требуются

                INC B
                SRA H
                JR Z, @Action.DivideScaledLogarithmic.LastNumShift              ; переход, если старший байт модуля числителя после SRA нулевой, выполнить последний RR L

                RR L
                INC B
                SRA H
                JR Z, @Action.DivideScaledLogarithmic.LastNumShift              ; переход, если старший байт модуля числителя после SRA нулевой, выполнить последний RR L

                RR L
                INC B
                SRA H
                JR Z, @Action.DivideScaledLogarithmic.LastNumShift              ; переход, если старший байт модуля числителя после SRA нулевой, выполнить последний RR L

                RR L
                INC B
                SRA H
                JR Z, @Action.DivideScaledLogarithmic.LastNumShift              ; переход, если старший байт модуля числителя после SRA нулевой, выполнить последний RR L

                RR L
                INC B
                SRA H
                JR Z, @Action.DivideScaledLogarithmic.LastNumShift              ; переход, если старший байт модуля числителя после SRA нулевой, выполнить последний RR L

                RR L
                INC B
                SRA H
                JR Z, @Action.DivideScaledLogarithmic.LastNumShift              ; переход, если старший байт модуля числителя после SRA нулевой, выполнить последний RR L

                RR L
                INC B
                SRA H
LastNumShift:   RR L
                ; Поиск логарифма модуля числителя и расчёт разности с логарифмом знаменателя и масштабом 8*256.
ReadNumLog:     LD H, #91
                LD A, (HL)
                INC H
                LD H, (HL)
                LD L, A
                ADD HL, BC
                OR A
                SBC HL, DE
                JP M, @Action.DivideScaledLogarithmic.Underflow                 ; переход, если знаковая разность логарифмов отрицательна, вернуть нулевой результат

                ; -----------------------------------------
                ; Обратное преобразование разности
                ; Поиск дробной мантиссы в странице 9300 и сохранение целого показателя в B.
                LD A, H
                LD B, A
                LD H, #93
                LD L, (HL)
                LD H, #01
                ; Проверка показателя относительно 8, ниже него результат требует деления мантиссы на степень двух.
                SUB #08
                JR NC, @Action.DivideScaledLogarithmic.CheckOverflow            ; переход, если показатель не меньше 8, использовать целый результат без выделения старшего байта

                ; Расчёт смещения JR для пропуска ненужных удвоений мантиссы, последующее выделение H реализует дробный масштаб.
                LD A, #07
                SUB B
                LD (@ActionLogRatioState.ShiftFraction), A
ShiftFraction:  JR NZ, @Action.DivideScaledLogarithmic.ShiftFraction            ; переход, если показатель меньше 7, пропустить 7-показатель следующих удвоений

                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ; Расчёт восьмибитового результата дробного масштаба из старшего байта после оставшихся удвоений.
                LD L, H
                LD H, #00
                JP @Action.DivideScaledLogarithmic.RestoreSign

                ; Возврат нуля при отрицательной разности логарифмов без восстановления знака и без изменения JR.
Underflow:      LD HL, #0000
                AND A
                RET

                ; -----------------------------------------
                ; Проверка представимости целого масштаба
                ; Расчёт 15-показатель, отрицательный результат означает ранний выход с Carry=1.
CheckOverflow:  LD A, #0F
                SUB B
                RET C                                                           ; выход, если показатель больше 15, мантисса не является итоговым отношением

                ; Обновление смещения JR для выбора числа удвоений, показатель 8 пропускает все семь.
                LD (@ActionLogRatioState.ShiftInteger), A
ShiftInteger:   JR NZ, @Action.DivideScaledLogarithmic.ShiftInteger             ; переход, если показатель меньше 15, пропустить 15-показатель следующих удвоений

                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ; -----------------------------------------
                ; Восстановление знака
                ; Возврат сохранённого признака знака, флаги вычисления сдвигов остаются в альтернативном AF.
RestoreSign:    EX AF, AF'
                JR NC, @Action.DivideScaledLogarithmic.ReturnRatio              ; переход, если входной числитель неотрицателен, модуль результата не отрицать

                ; Расчёт отрицательного слова результата по модулю 65536.
                LD A, L
                CPL
                LD L, A
                LD A, H
                CPL
                LD H, A
                INC HL
                ; Формирование Carry=0 обычного выхода, остальные флаги описывают промежуточный A, а не HL.
ReturnRatio:    AND A
                RET

                ; -----------------------------------------
                endmodule
                endmodule
