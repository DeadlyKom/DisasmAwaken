                module Action
                module CheckCandidateListClass
                ; Документация [алгоритм и проверка](../../Docs/ActionCandidateClass.md)
                ; -----------------------------------------
                ; Проверка принадлежности полного класса списку допуска выбора цели
                ; исходная запись 17, адреса EA00..EA14
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, IX указывает запись с доступным ClassCode
                ;   исходный ACTION банка 0 доступен, внешний возврат лежит в CPU-стеке, IRQ не вмешиваются
                ; Out:
                ;   HL, DE и BC сохраняются, A равен полному ClassCode
                ;   Z установлен только для полных кодов 0, 4, 5, 8, 1 и 9, совпадение проверяется именно в этом порядке
                ;   F соответствует CP с первым совпавшим кодом либо с последним кодом 9 при отсутствии совпадений
                ;   HL', DE', BC', AF', IX, IY, I/IM/IFF и paging сохраняются, SP после RET увеличен на 2
                ;   R увеличен на 2+2*k M1, k равен числу выполненных сравнений, от 1 до 6
                ; Corrupt:
                ;   AF, R, SP внешним RET
                ; Note:
                ;   это числовые коды классов, а не независимые биты, игровые названия классов не установлены
                ;   проверены все 65536 сочетаний полного класса и исходных флагов, записи RAM отсутствуют
                ;   входные флаги не влияют на результат, сборка, IRQ и нативный запуск не выполнялись
                ; -----------------------------------------
                ; Проверка полного класса для допуска к списку кандидатов, порядок сравнений исходный.
Entry:          LD A, (IX + @FActionRecord.ClassCode)
                CP @ActionCandidateListConst.AllowedClass0
                RET Z                                                           ; выход, если ClassCode равен 0, установить Z для допуска к просмотру списка

                CP @ActionCandidateListConst.AllowedClass4
                RET Z                                                           ; выход, если ClassCode равен 4, установить Z для допуска к просмотру списка

                CP @ActionCandidateListConst.AllowedClass5
                RET Z                                                           ; выход, если ClassCode равен 5, установить Z для допуска к просмотру списка

                CP @ActionCandidateListConst.AllowedClass8
                RET Z                                                           ; выход, если ClassCode равен 8, установить Z для допуска к просмотру списка

                CP @ActionCandidateListConst.AllowedClass1
                RET Z                                                           ; выход, если ClassCode равен 1, установить Z для допуска к просмотру списка

                ; Проверка последнего допустимого кода 9, NZ означает отказ для остальных полных кодов.
                CP @ActionCandidateListConst.AllowedClass9
                RET

                endmodule
                endmodule
