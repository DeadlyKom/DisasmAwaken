                module Action
                module SqrtWordBank1
                ; Документация [алгоритм и проверка](../../Docs/ActionCachedRoot.md)
                ; -----------------------------------------
                ; Вызов табличного корня с выбором Controls банка 1 и сохранением BC
                ; исходная запись 17, общая RAM ACTION фиксированного банка 2, смещения #4D48..#4D59
                ; In:
                ;   HL передаётся ребёнку и будет скопирован в DE только при входном D=0, DE задаёт беззнаковое число n от #0000 до #FFFF
                ;   BC является сохраняемым контекстом, AF числовых аргументов не задаёт
                ;   Controls с исходными таблицами загружен в банк 1, 7FFD не заблокирован, код обёртки и помощников вне окна C000
                ;   CPU-стек содержит внешний возврат и допускает шесть дополнительных байтов без пересечения с кодом и таблицами, IRQ не вмешивается
                ; Out:
                ;   HL содержит последний пробный остаток SqrtWordCached по модулю 65536
                ;   DE получает входной HL при входном D=0, иначе сохраняется
                ;   BC сохраняется
                ;   AF содержит A=floor(sqrt(n)) для n=#0000..#E8FF, для n=#E900..#FFFF A=261-floor(sqrt(n AND #FF00))
                ;   F относится к последнему внутреннему ADD HL,BC ребёнка при выходе по заёму либо к последнему INC A при исчерпании проб
                ;   HL', DE', BC' сохраняются
                ;   AF' содержит A'=#10, при входном D=0 F' сохраняется, иначе F'=#80 либо #81 от подготовки нечётной разности ребёнком
                ;   IX и IY сохраняются, I, IM и IFF сохраняются
                ;   OUT 7FFD получает #11 и #10, конечная полная конфигурация #10, прежняя не восстанавливается
                ;   SP после RET равен входному SP+2, R получает полные M1 ребёнка плюс 22 с сохранением бита 7
                ;   в RAM изменены только шесть временных байтов CPU-стека, выполнено двенадцать байтовых записей
                ; Corrupt:
                ;   HL, DE только при входном D=0, AF, AF', R, шесть байтов CPU-стека и 7FFD
                ; Note:
                ;   EX AF,AF' сохраняет основной результат корня на время второго выбора страницы, альтернативный A после него равен 10, прежний AF' не восстанавливается
                ;   предел математического корня 0000..E8FF и особые результаты старшего диапазона полностью наследуются от ребёнка
                ;   все 65536 слов проверены с реальными OUT и ребёнком, полные входные страницы 00..1F и два SP распределены между случаями
                ;   сопоставлены регистры включая R, восемь банков RAM и кратность двенадцати записей, полное произведение входов не перебиралось
                ;   аппаратный порядок шинных циклов стека, точные T, IRQ, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Сохранение BC и контекст таблиц
                ; Сохранение BC вызывающего кода перед реальным переключением банка.
Entry:          PUSH BC
                ; Выбор Controls банка 1, исходные таблицы C000..C2FF читаются именно из этого контекста.
                LD A, @ActionBankPage.Controls
                CALL @Action.SelectMemoryPage.Entry
                ; Расчёт на настоящих исходных таблицах, верхние 5888 входов сохраняют особое поведение оригинала.
                CALL @Action.SqrtWordCached.Entry
                ; Сохранение результата AF в альтернативной паре на время возврата к полной конфигурации Runtime.
                EX AF, AF'
                LD A, @ActionBankPage.Runtime
                CALL @Action.SelectMemoryPage.Entry
                ; Восстановление результата AF и исходного BC, альтернативный A остаётся равным Runtime.
                EX AF, AF'
                POP BC
                RET

                endmodule
                endmodule
