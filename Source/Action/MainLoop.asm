                ; In:
                ;   состояния регистров и банков задаются StartFlight и последующими кадрами
                ;   SP указывает в общую RAM, доступны два байта для CALL и рабочая рамка UpdateFrame
                ; Out:
                ;   UpdateFrame получает возврат #A85C, после штатного RET восстанавливается входной SP
                ;   JR начинает следующий кадр, прямого RET из MainLoop нет
                ; Corrupt:
                ;   R и два байта под SP, остальные изменения определяются UpdateFrame
                ; Note:
                ;   на 64 обычных кадрах проверены страница #10 и одинаковый SP при каждом входе
                ;   переход кадра к загрузке станции не возвращается по #A85C
; -----------------------------------------
