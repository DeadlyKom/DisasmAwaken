                module Action
                module NextActiveRecord
                ; Документация [алгоритм и проверка](../../Docs/ActionRecordIterator.md)
                ; -----------------------------------------
                ; Переход по шагу BC к следующей записи с байтом 1 не равным 80 либо к маркеру конца
                ; исходная запись 17, код ACTION банка 0, адрес E6D1, смещения #86D1..#86E1
                ; In:
                ;   HL и DE сохраняются, BC шаг между проверяемыми адресами, AF числовых аргументов не задаёт
                ;   IY адрес перед первой проверяемой записью, первое действие прибавляет BC по модулю 65536
                ;   достижимы запись с байтом 1 не равным 80 либо запись-маркер с байтами 0 и 1 равными 80
                ;   код ACTION доступен в банке 0, чтения записей допустимы, на CPU-стеке внешний возврат, IRQ не вмешиваются
                ; Out:
                ;   HL, DE и BC сохраняются, IY адрес возвращаемой записи либо маркера
                ;   для активной записи A равен её байту 1, F соответствует CP этого байта с 80, Z сброшен
                ;   для маркера A=80, F=42, Z установлен, записи с байтом 1 равным 80 и байтом 0 не равным 80 пропущены
                ;   HL', DE', BC', AF', IX, I, IM и IFF сохраняются, SP=входной SP+2
                ;   R получает 10 M1 за каждую пропущенную запись плюс 6 M1 при активном выходе либо 11 M1 при маркере
                ; Corrupt:
                ;   AF, IY, R
                ; Note:
                ;   RAM, CPU-стек и порты не записываются, доступность означает только проверенное условие байта 1
                ;   шага 64 здесь не зашито, BC=0 при пропускаемой записи не завершает поиск
                ;   предел массива и полный игровой смысл полей не установлены
                ; -----------------------------------------
                ; -----------------------------------------
                ; Поиск следующей активной записи по входному шагу BC
                ; Начальный IY не проверяется, прибавление шага выполняется перед первым чтением.
Entry:          ADD IY, BC
                ; Проверка кода состояния по байту 1, полное значение 80 означает пропуск либо маркер.
                LD A, (IY + FActionRecord.Components.Component0.High)
                CP #80
                RET NZ                                                          ; выход, если байт 1 не равен 80, вернуть активную запись с Z сброшенным

                ; Проверка маркера конца по байту 0 записи с байтом 1 равным 80.
                LD A, (IY + FActionRecord.Components.Component0.Low)
                CP #80
                JP NZ, @Action.NextActiveRecord.Entry                           ; переход, если байт 0 не равен 80, продолжить поиск через следующий шаг BC

                RET

                endmodule
                endmodule
