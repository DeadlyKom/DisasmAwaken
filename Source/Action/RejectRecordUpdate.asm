                module RejectRecordUpdate
                ; Документация [алгоритм и проверка](../../Docs/ActionRejectRecord.md)
                ; -----------------------------------------
                ; Восстановление CPU-стека, пометка записи IX для повторного использования и продолжение очистки класса 12
                ; исходная запись 17, окно ACTION банка 0, смещения #8658..#865E
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, IX - изменяемая FActionRecord
                ;   входной SP может указывать внутрь компонент записи, SavedCpuSP содержит действительный CPU SP с внешним возвратом
                ;   по восстановленному CPU SP допустимы два дополнительных временных байта, они не пересекаются с кодом и изменяемыми полями
                ;   действуют договоры MarkRecordForReuse и ReleaseClass12Records, при классе 14 сохранены Original0..2
                ;   код ACTION доступен в банке 0, IRQ не вмешивается
                ; Out:
                ;   по IX записаны Component0=8000 и ReuseByte=FF, ClassCode сохранён
                ;   дальнейшие HL, DE, BC, AF и IY определены ReleaseClass12Records, при классе 12 сама IX-запись уже неактивна и пропускается итератором
                ;   HL', DE', BC', AF' и IX сохраняются, I/IM/IFF и paging сохраняются
                ;   SP после внешнего RET равен SavedCpuSP+2, входной временный SP не восстанавливается
                ;   R получает десять M1 этого входа и M1 общего хвоста, для классов 14 и вне 12/14 всего 25 и 18 M1 соответственно
                ;   CALL пометки оставляет E65F в двух байтах под SavedCpuSP, класс 12 затем использует те же байты для обхода списка
                ; Corrupt:
                ;   HL только для класса 14, BC только для класса 12, AF, IY только для класса 12, R, SP
                ;   три поля записи IX, два байта CPU-стека под SavedCpuSP и данные согласно договору ReleaseClass12Records
                ; Note:
                ;   (0) жёсткий порядок, после CALL исполнение без машинного JP продолжается в ReleaseClass12Records.asm, часть (1)
                ;   LD SP,(SavedCpuSP) выполняется до первого CALL, временный стек компонент не получает адреса возврата
                ;   пометка сначала записывает High=80, затем Low=00 и ReuseByte=FF, не исправляя другие поля записи
                ;   2129 сценариев выполнили весь путь E658 через настоящие пометку, общий хвост, итератор и восстановитель
                ;   IX выбирался среди всех 26 физических записей, входной SP указывал на одну из трёх пар компонент, проверены все коды класса и входные F
                ;   сопоставлены регистры включая R, все восемь банков RAM и кратность записей, полный перебор всех списков не выполнен
                ;   аппаратные IRQ, точные T, порядок шинных циклов стека, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Отказ обновления записи
                ; Восстановление CPU SP из существующего операнда до CALL, входной SP мог использоваться для компонент.
Entry:          LD SP, (@ActionOffsetState.SavedCpuSP)
                ; Пометка записи IX кодом доступности 8000 и ReuseByte=FF, затем физически следует общий хвост класса 12.
                CALL @Action.MarkRecordForReuse.Entry
                ; JP @Action.ReleaseClass12Records.Entry, продолжение в ReleaseClass12Records.asm

                endmodule
