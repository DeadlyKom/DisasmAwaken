                module Action
                module HandleLinkedRecordProximity
                ; Документация [алгоритм и проверка](../../Docs/ActionLinkedProximity.md)
                ; -----------------------------------------
                ; Проверка связи с записью полного класса 13, обработка близости и запуск эффекта по исходному биту 4
                ; исходная запись 17, адреса F009..F03C
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, IX указывает доступную текущую FActionRecord
                ;   LinkedIndex задаёт обычный байтовый индекс 00..FF, выбранная запись читается по Components, ClassCode и ReuseByte
                ;   для повторного выбора класса требуется текущий ClassCode AND 7F < 26 и условия RefreshRecordClassAndOffsets
                ;   действуют договоры RecordIndexToAddress, MaxRecordDeltaHigh, MarkIYRecordForReuse и StepCodesTowardRecord
                ;   при запуске большого эффекта действуют все дополнительные условия PrepareLargeEffect и AllocateLargeEffect, включая доступные банки OBJECT3D и VOXAL
                ;   для путей модели доступны восемнадцать дополнительных байтов CPU-стека и числовые таблицы, 7FFD разблокирован, IRQ не вмешиваются
                ; Out:
                ;   обычный индекс выбирает адрес A100+64*LinkedIndex, FF здесь не подменяется A780
                ;   Component0.High=80 либо полный ClassCode выбранной записи не равный 13 передаёт исполнение RefreshRecordClassAndOffsets
                ;   для подходящей записи IY установлен в её адрес, максимум старших байтов модулей разностей A>=1 передаёт исполнение дальнему StepFar по F365
                ;   дальний путь реально подводит коды через StepCodesTowardRecord и передаёт управление F0F8, исходные координаты выбранной записи не копируются в текущую
                ;   при A=0 все три модуля разностей меньше 256, исходный бит 4 выбранного ReuseByte проверяется до вызова MarkIYRecordForReuse
                ;   ближняя выбранная запись получает Component0=8000 и ReuseByte=FF на обоих путях, решение использует сохранённые флаги BIT, а не новое FF
                ;   при исходном бите 4=0 исполняется RefreshRecordClassAndOffsets, при бите 4=1 вызывается PrepareLargeEffect с возвратом F03A, затем выполняется общий хвост F0F8
                ;   на границе запуска EA29 A=0, HL равен модулю третьей разности, DE первой, B сохраняется и C=13, SP=входной SP−2 со словом F03A
                ;   дальнейшие эффекты большого пути определяются PrepareLargeEffect, AllocateLargeEffect и общим подготовителем, граница модели не заменяет их договора
                ;   IX и I/IM/IFF сохраняются по вызываемым детям, paging сохраняется до большого эффекта, дальний подвод выдаёт 11 и 10 в 7FFD
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IY, R, условные поля записи и операнды по выбранным детям, CPU-стек и страницы по договорам соответствующего пути
                ; Note:
                ;   это исходная цель State0E, класс 13 дан шестнадцатерично и равен 19 десятично, имя игрового типа не выдумывается
                ;   при IY=IX ближняя пометка меняет текущую запись до повторного выбора класса либо эффекта, порядок исходных записей сохранён
                ;   106496 сценариев проверили все 256 индексов с четырьмя профилями, классами и старшими алиасами, самовыбор использует одно физическое поле класса
                ;   точные регистры с R, восемь банков, кратность записей и реальные порты проверены во всех 106496 сценариях, включая дальний вычислитель
                ;   модель останавливается перед F0F8 либо EA29, тело большого эффекта и общий хвост ею не исполняются, полный игровой запуск не заявляется
                ;   полное произведение входов, аппаратные IRQ, точные T, сборка и нативный запуск не проверялись
                ; -----------------------------------------
                ; Выбор адреса по обычному полному LinkedIndex, специальный случай FF подготовителя E761 здесь не применяется.
Entry:          LD A, (IX + @FActionRecord.LinkedIndex)
                CALL @Action.RecordIndexToAddress.Entry
                ; Проверка старшего байта первой компоненты выбранной записи, младший байт маркера не читается.
                INC L
                LD A, (HL)
                CP @ActionReuseConst.ReusableHigh
                JR Z, @Action.RefreshRecordClassAndOffsets.Entry                ; переход, если Component0.High выбранной записи равен 80, повторно выбрать поведение текущего класса

                ; Поиск физического ClassCode выбранной записи через младший байт адреса и возврат указателя к началу записи.
                LD A, L
                ADD A, #11
                LD L, A
                LD C, (HL)
                SUB #12
                LD L, A
                LD A, C
                ; Проверка точного полного класса 13 выбранной записи, старший бит класса не маскируется.
                CP @ActionLinkedProximityConst.RequiredClass
                JR NZ, @Action.RefreshRecordClassAndOffsets.Entry               ; переход, если полный ClassCode выбранной записи отличается от 13, повторно выбрать поведение текущего класса

                ; Подготовка IY выбранной записи и расчёт максимума старших байтов модулей трёх разностей.
                PUSH HL
                POP IY
                CALL @Action.MaxRecordDeltaHigh.Entry
                ; Проверка более строгой близости, для ближнего пути каждый модуль должен быть меньше 256.
                CP @ActionLinkedProximityConst.NearLimit
                JP NC, @Action.HandleClass18Proximity.StepFar                   ; переход, если максимум старших байтов не меньше 1, подвести фазовые коды через общий дальний вход

                ; Проверка исходного бита 4 перед пометкой выбранной записи, флаги BIT переживают последующий вызов.
                BIT @ActionLinkedProximityConst.EffectBit, (IY + @FActionRecord.ReuseByte)
                ; Пометка выбранной записи Component0=8000 и ReuseByte=FF без изменения флагов проверки исходного бита 4.
                CALL @Action.MarkIYRecordForReuse.Entry
                JP Z, @Action.RefreshRecordClassAndOffsets.Entry                ; переход, если исходный бит 4 выбранного ReuseByte был сброшен, повторно выбрать поведение текущего класса

                ; Запуск большого эффекта текущей записи по исходно установленному биту 4 выбранной записи.
                CALL @Action.PrepareLargeEffect.Entry
                ; Продолжение после возврата большого эффекта в общем подготовителе текущей записи.
                JP @Action.PrepareObjectOffsetTransform.Entry

                endmodule
                endmodule
