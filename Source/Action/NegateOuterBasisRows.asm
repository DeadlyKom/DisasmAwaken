                module Action
                module NegateOuterBasisRows
                ; Документация [отрицание внешних строк базиса](../../Docs/ActionReverseViewBasis.md)
                ; -----------------------------------------
                ; Изменение знака слов строк 2 и 0 базиса с сохранением средней строки
                ; исходная запись 17, фиксированный ACTION банка 2, адреса AFF5..B043
                ; In:
                ;   HL и DE входных аргументов не задают, BC и A сохраняемый контекст, входные F не задают Carry для отрицания
                ;   физические слова ActionRenderBasis C00..C22 доступны для записи, используется исходный столбцовый порядок
                ;   на CPU-стеке читаемое слово внешнего возврата, IRQ не вмешиваются
                ; Out:
                ;   C20, C21, C22, C00, C01 и C02 заменяются на свои отрицания по модулю 65536 именно в таком порядке
                ;   C10, C11 и C12 сохраняются, слова не переставляются, нормализация не выполняется
                ;   HL равен отрицанию исходного C02 по модулю 65536, DE содержит исходный C02, BC и A сохраняются
                ;   F соответствует SBC 0,исходный C02 с нулевым входным Carry, PV установлен при исходном C02=8000
                ;   HL', DE', BC', AF', IX, IY, I, IM, IFF и paging сохраняются, SP после RET равен входному SP+2
                ;   R увеличивается на 43 M1 с сохранением бита 7, временных записей CPU-стека нет, OUT не выполняется
                ; Corrupt:
                ;   HL, DE, AF только F, R и двенадцать байтов шести слов базиса
                ; Note:
                ;   исходное 8000 остаётся 8000, переполнение при отрицании сохраняется, код не исправляется насыщением
                ;   операция соответствует изменению знака строк 0 и 2 матрицы, ось и единицы не выводятся только из этого тела
                ;   66304 сценария проверили весь домен каждого слова, смешанные матрицы, точные регистры, R, всю RAM и порядок записей
                ;   полное произведение шести 16-битовых слов, аппаратные IRQ, точные такты и нативный вид не проверялись
                ; -----------------------------------------
                ; Изменение знака C20, первый элемент строки 2 в физическом столбцовом порядке.
Entry:          LD DE, (@ActionRenderBasis.C20.Low)
                LD HL, #0000
                OR A
                SBC HL, DE
                LD (@ActionRenderBasis.C20.Low), HL
                ; Изменение знака C21, средняя строка C10..C12 не затрагивается.
                LD DE, (@ActionRenderBasis.C21.Low)
                LD HL, #0000
                OR A
                SBC HL, DE
                LD (@ActionRenderBasis.C21.Low), HL
                ; Изменение знака C22, арифметика сохраняет исходное оборачивание слова.
                LD DE, (@ActionRenderBasis.C22.Low)
                LD HL, #0000
                OR A
                SBC HL, DE
                LD (@ActionRenderBasis.C22.Low), HL
                ; Изменение знака C00, начало строки 0 после обработки всех слов строки 2.
                LD DE, (@ActionRenderBasis.C00.Low)
                LD HL, #0000
                OR A
                SBC HL, DE
                LD (@ActionRenderBasis.C00.Low), HL
                ; Изменение знака C01 без перестановки с C10.
                LD DE, (@ActionRenderBasis.C01.Low)
                LD HL, #0000
                OR A
                SBC HL, DE
                LD (@ActionRenderBasis.C01.Low), HL
                ; Изменение знака C02, его исходное значение останется в DE, итоговый SBC задаст F.
                LD DE, (@ActionRenderBasis.C02.Low)
                LD HL, #0000
                OR A
                SBC HL, DE
                LD (@ActionRenderBasis.C02.Low), HL
                RET

                endmodule
                endmodule
