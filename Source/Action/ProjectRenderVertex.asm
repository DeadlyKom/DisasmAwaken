                ;   DepthShiftSkip, FirstShiftSkip и SecondShiftSkip содержат одинаковое 6-exponent, exponent от 1 до 6
                ;   SP указывает на рабочее место записи, начало выходного FRenderProjectedPoint находится по входному SP-4
                ;   записываемые байты и промежуточный SP не должны разрушать код и исходные параметры, обычный CALL/RET здесь не используется
                ;   ACTION находится в банке 0, прерывания не вмешиваются в рабочий стек
                ; Out:
                ;   HL, DE, BC, IX и IY сохраняются, управление заканчивается JP (HL) с исходным адресом продолжения
                ;   SP увеличен на размер FRenderProjectedPoint, два слова записаны по входному SP-2 и SP-4, пятый байт записи сохранён
                ;   глубина равна wrap16(signed8(A)*2^(exponent-1)+Output2), проверяется только её бит Sign
                ;   при отрицательной глубине первое слово равно исходному Output2, второе равно 8000 OR LOW(Output2), SavedDepth не меняется
                ;   при неотрицательной глубине SavedDepth получает полное слово глубины до проверки первой оси
                ;   если depth=0 либо модуль первой переведённой координаты не меньше 128*depth, первое слово равно depth, второе 8000 OR LOW(depth)
                ;   при отказе второй оси первое уже вычисленное экранное слово сохраняется, второе получает 8000 OR LOW(depth)
                ;   при двух принятых осях слова получают точную формулу дополненного частного и центров 48 и 128 из ActionPerspective.md
                ;   AF, HL', DE', BC' и AF' задаются последней достигнутой ветвью по формулам ReferenceActionPerspective.py, а не общим булевым признаком
                ;   HL' всегда содержит конечный SP, DE' при успехе содержит depth, при отказе второе слово маркера
                ;   BC' при успехе содержит сырой дополненный результат второй оси, при отказе исходную базу оси с отдельно описанным случаем 8000/0100
