                module Action
                module MarkRecordForReuse
                ; Документация [алгоритм и проверка](../../Docs/ActionRecordReuse.md)
                ; -----------------------------------------
                ; Пометка записи кодом Component0=8000 и однократным пропуском ReuseByte=FF при поиске доступной записи
                ; исходная запись 17, окно ACTION банка 0, смещения #9394..#93A0
                ; In:
                ;   HL, DE, BC, AF и альтернативные регистры содержат сохраняемый контекст
                ;   IX - адрес FActionRecord, поля Components.Component0.Low, Components.Component0.High и ReuseByte доступны для записи
                ;   код F394..F3A0 и запись не пересекаются, SP содержит внешний возврат и не пересекается с изменяемыми полями
                ;   в окне C000 выбран банк 0, другой код не просматривает запись между тремя последовательными изменениями
                ; Out:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX и IY сохраняются, I/IM/IFF и paging сохраняются
                ;   Components.Component0 равен 8000, ReuseByte равен FF, остальные 61 байт записи не изменены
                ;   R увеличен на семь M1 в младших семи разрядах с сохранением старшего разряда, SP после RET равен входному SP+2
                ;   порядок записей строго High=80, Low=00, ReuseByte=FF, CPU-стек и порты не записываются
                ; Corrupt:
                ;   R и три байта FActionRecord по смещениям 1, 0 и 18 в указанном порядке
                ; Note:
                ;   FindReusableRecord проверяет полный байт High=80, Low=00 не является его маркером конца Low=80
                ;   при первом достижении записи ReuseByte=FF обнуляется и запись пропускается, при следующем достижении нулевой ReuseByte уже допускается
                ;   отсрочка определяется достижением записи поиском, не количеством кадров или общим числом вызовов
                ;   запись координаты Component0 используется как код доступности, новые независимые флаговые биты не вводятся
                ;   первое присваивание при прежнем Low=80 временно даёт слово 8080, поэтому просмотр незавершённой записи исключён входным условием
                ;   7450 сценариев проверили 26 физических записей, три дополнительные границы адреса, все F, регистры включая R, все банки RAM и точный порядок записей
                ;   26 сценариев выполнили настоящий MarkRecordForReuse и два поиска FindReusableRecord, первое достижение пропускает, второе принимает
                ;   индексные обращения не меняют AF, функция сама DI не выполняет, аппаратные IRQ, время и нативное освобождение объектов не проверялись
                ; -----------------------------------------
                ; -----------------------------------------
                ; Код доступности и отложенное повторное использование
                ; Установка старшего байта Component0, это полный байтовый код 80, не самостоятельный флаг занятости.
Entry:          LD (IX+FActionRecord.Components.Component0.High), @ActionReuseConst.ReusableHigh
                ; Завершение слова Component0=8000, младший байт ноль отличает запись от маркера конца Low=80.
                LD (IX+FActionRecord.Components.Component0.Low), @ActionReuseConst.ReusableLow
                ; Установка точного кода FF, первый достигший записи поиск обнулит его и пропустит эту запись.
                LD (IX+FActionRecord.ReuseByte), @ActionReuseConst.SkipOnce
                RET

                endmodule
                endmodule
