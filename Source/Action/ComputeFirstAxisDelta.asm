                module Action
                module ComputeFirstAxisDelta
                ; Документация [алгоритм и проверка](../../Docs/ActionClipComparisons.md)
                ; -----------------------------------------
                ; Разность координат First второй и первой точки с оборачиванием до слова
                ; исходная запись 17, банковое окно ACTION банка 0, смещения #66C8..#66D2
                ; In:
                ;   FirstPoint и SecondPoint содержат две исходные точки, используется поле First
                ;   ACTION доступен в банке 0, на CPU-стеке внешний возврат, IRQ не вмешиваются
                ; Out:
                ;   HL=wrap16(SecondPoint.First-FirstPoint.First)
                ;   DE содержит FirstPoint.First, BC сохраняется
                ;   A сохраняется, F равен точным флагам SBC HL,DE с очищенным входным Carry
                ;   HL', DE', BC', AF', IX и IY сохраняются, I, IM, IFF и paging сохраняются
                ;   SP после RET равен входному SP+2, RAM и порты не записываются, R увеличивается на 7 по модулю младших семи бит
                ; Corrupt:
                ;   HL, DE, F и R
                ; Note:
                ;   разность оборачивается до 16 бит, более широкий знаковый результат отдельно не сохраняется
                ;   Overflow не исправляется, Sign не является универсальным математическим сравнением при переполнении
                ;   803012 сценариев общей серии проверяют регистры, флаги, R, SP и отсутствие записей RAM, все совместные входы не исчерпаны
                ;   IRQ, сборка и нативный запуск не проверены
                ; -----------------------------------------
                ; -----------------------------------------
                ; Чтение исходных значений
                ; Чтение одноимённых полей второй и первой точки без изменения исходных записей.
Entry:          LD HL, (@ActionClipPoints.SecondPoint.First)
                LD DE, (@ActionClipPoints.FirstPoint.First)
                ; Расчёт разности с предварительно очищенным Carry.
                OR A
                SBC HL, DE
                RET

                endmodule
                endmodule
