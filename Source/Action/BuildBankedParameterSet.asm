                module Action
                module BuildBankedParameterSet
                ; Документация [алгоритм и проверка](../../Docs/ActionBankedParameterBuild.md)
                ; -----------------------------------------
                ; Выбор банка Controls и хвостовая подготовка с активацией набора параметров
                ; исходная запись 17, адреса 697E..6985
                ; In:
                ;   HL, DE, BC и AF основных числовых аргументов не задают, зерно и управление читаются BuildParameterTables из исходных полей
                ;   DE' станет основным выходным DE, IY сохраняется, действуют все остальные условия BuildAndActivateParameters
                ;   перенесённый код 697E и общий селектор AB1B доступны, в физическом банке 1 находится Controls
                ;   запись 7FFD не заблокирована, внешний возврат находится в фиксированной RAM и действителен после выбора банка 0
                ;   доступны десять дополнительных байтов CPU-стека вне кода и данных, IRQ не вмешиваются
                ; Out:
                ;   исполнен настоящий Controls.BuildAndActivateParameters после выбора полного байта paging 11
                ;   HL=0000, DE=входной DE', BC=0000 OR C с четырёхбитным индексом зерна, AF=0044
                ;   HL'=7BCD, DE'=DEDC+16*G+9, BC'=0006, AF' последнее поле параметров с флагами сложения, IX=9BB3
                ;   подготовлены пятнадцать параметров и девять строк, выполнены все пятнадцать маршрутов ApplyParameterSet и сбросы ActivateParameterSet
                ;   в порт 7FFD выданы 11 и 10, конечный банк 0, исходная конфигурация paging не восстанавливается
                ;   IY, I/IM/IFF сохраняются, SP после внешнего RET равен входному SP+2
                ;   R получает стоимость BuildAndActivateParameters плюс девять M1 собственного выбора банка и переходов
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, R, данные построителя и активации, десять байтов CPU-стека и paging
                ; Note:
                ;   штатный игровой вызывающий вход пока не установлен, смысл зерна и группы G определяется договором BuildParameterTables
                ;   исходный соседний байт по 697D в процедуру не включён, его назначение не объявляется установленным
                ;   1120 сценариев исполнили настоящий полный дочерний путь, все управляющие байты в четырёх областях и все 32 неблокированных значения paging
                ;   сверены регистры с R, SP, восемь банков, значения и кратность записей, OUT имеют исходный порядок 11 затем 10
                ;   проверка композиционная, дочерний числовой договор ранее проверен отдельно, это не новое независимое доказательство всей математики
                ;   полное произведение зерна, управления и входных регистров, аппаратные IRQ, точные T, сборка и нативный запуск не проверялись
                ; -----------------------------------------
                ; Выбор полного управляющего байта для банка 1, прежний paging не сохраняется.
Entry:          LD A, @ActionBankPage.Controls
                ; Выбор банка Controls через общий селектор с сохранением BC и флагов.
                CALL @Action.SelectMemoryPage.Entry
                ; Хвостовая передача исходного внешнего возврата построителю и активатору параметров банка 1.
Build:          JP @Controls.BuildAndActivateParameters.Entry

                endmodule
                endmodule
