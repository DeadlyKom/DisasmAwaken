                module Action
                module CheckLinkedDistanceAndStepCodes
                ; Документация [алгоритм и проверка](../../Docs/ActionLinkedMotionGate.md)
                ; -----------------------------------------
                ; Проверка расстояния связанной записи перед шагом кодов либо переходом во временное состояние
                ; исходная запись 17, адреса 624B..6264
                ; In:
                ;   HL, DE, BC и альтернативные пары задают исходные аргументы EncodeHalfCoordinateDeltas согласно StepRecordTargetCodes
                ;   IX указывает текущую FActionRecord с LinkedIndex, Components, фазами, TargetCodeStep и полями временного состояния
                ;   LinkedIndex используется как обычный полный индекс для SelectRecordByIndex, включая FF без специальной трактовки
                ;   действуют договоры MaxRecordDeltaHigh, StepRecordTargetCodes и EnterTimedPhaseFromMotion, доступны таблицы геометрии и 16 дополнительных байтов CPU-стека
                ;   перенесённый код банка 5 и ACTION банка 0 доступны, IRQ исключены
                ; Out:
                ;   IY выбирает запись A100+64*LinkedIndex, исходные HL, DE и BC сохраняются рамкой до проверки цели
                ;   если Component0.High цели равен 80, расстояние не вычисляется и после восстановления аргументов выполняется обычная геометрия
                ;   если цель доступна, MaxRecordDeltaHigh возвращает максимум старших байтов обёрнутых модулей трёх разностей
                ;   при этом максимуме меньше 0A выполняется рамочный EnterTimedPhaseFromMotion, StateCode=11, Unknown19 получает прежнее состояние, таймер 5..20
                ;   ближний путь восстанавливает входные HL и DE, задаёт BC=8080 и не меняет фазовые коды
                ;   остальные пути восстанавливают аргументы и физически продолжают StepRecordTargetCodes, его выходные регистры и обновления фаз сохраняются
                ;   AF', альтернативные HL/DE/BC и R определяются достигнутым ребёнком, IX, I/IM/IFF сохраняются, IY остаётся выбранной записью
                ;   SP после внешнего RET равен входному SP+2, обычная геометрия заканчивается 7FFD=10, ближний путь paging не меняет
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IY, R, поля временного состояния либо фазовые коды и операнды геометрии, CPU-стек и условно 7FFD
                ; Note:
                ;   физическое продолжение после POP HL по 6264 требует жёсткого порядка двух include, добавлять настоящий JP нельзя
                ;   8704 сценария покрыли все 256 индексов, ближайшую, дальнюю и недоступную запись внутри исходного массива, границы R и смешанные аргументы
                ;   старшие индексы читают исходную RAM без подмены её кодовых областей тестовыми координатами, это не расширение массива
                ;   все дочерние процедуры исполнены, сверены точные регистры, флаги, R, восемь банков, кратность записей и настоящие OUT
                ;   полное произведение входов, аппаратные IRQ, время, сборка и нативная игра не проверялись
                ; -----------------------------------------
                ; Сохранение трёх основных аргументов геометрии перед выбором и проверкой связанной записи.
Entry:          PUSH HL
                PUSH DE
                PUSH BC
                ; Поиск IY по обычному полному LinkedIndex, FF не является специальным значением этого входа.
                LD A, (IX + @FActionRecord.LinkedIndex)
                CALL @Action.SelectRecordByIndex.Entry
                ; Проверка доступности выбранной записи по полному Component0.High=80.
                LD A, (IY + @FActionRecord.Components.Component0.High)
                CP @ActionReuseConst.ReusableHigh
                JR Z, @Action.CheckLinkedDistanceAndStepCodes.RestoreArgs       ; переход, если Component0.High цели равен 80, восстановить аргументы без расчёта расстояния

                ; Расчёт квантованного максимума расстояния по трём компонентам текущей и выбранной записей.
                CALL @Action.MaxRecordDeltaHigh.Entry
                ; Проверка ближней области по максимуму старших байтов модулей разностей.
                CP #0A
                JR C, @Action.EnterTimedPhaseFromMotion.Entry                   ; переход, если максимум меньше 0A, восстановить рамку и установить временное состояние

                ; Восстановление аргументов перед обязательным последовательным продолжением в StepRecordTargetCodes.
RestoreArgs:    POP BC
                POP DE
                POP HL
                ; JP @Action.StepRecordTargetCodes.Entry, продолжение в StepRecordTargetCodes.asm

                endmodule
                endmodule
