                module Action
                module RequestTurnPositive
                ; Документация [алгоритм и проверка](../../Docs/ActionKeyTurnPositive.md)
                ; -----------------------------------------
                ; Запрос увеличения управления Turn с накопителем повтора и исходной знаковой границей
                ; исходная запись 17, адреса 76EA..770C
                ; In:
                ;   HL, DE, BC, AF входных аргументов не задают
                ;   исходный изменяемый операнд накопителя и TurnControl доступны, код исполняется в фиксированном банке 5
                ;   CPU-стек содержит внешний возврат, IRQ не вмешиваются, прежние операнды не изменяются параллельно
                ; Out:
                ;   HL, DE, BC сохраняются, TurnPrev=1, текущий накопитель увеличен на 94 по модулю 256
                ;   накопитель противоположного направления равен C8 независимо от переноса текущего
                ;   без переполнения накопителя управление не записывается, A=C8 и F соответствует ADD накопителя и шага
                ;   при переполнении проверяется исходный знаковый кандидат увеличения на единицу, точные граничные подстановки описаны в документации
                ;   после проверки A содержит кандидата, F соответствует CP с границей 08, запись зависит от Carry
                ;   HL', DE', BC', AF', IX, IY сохраняются, SP=входной SP+2, I, IM, IFF и 7FFD сохраняются
                ;   R увеличен на 8 M1 без переноса, 13 M1 при отказе по границе, 15 либо 16 M1 при записи
                ; Corrupt:
                ;   AF, R, три исходных изменяемых операнда и при разрешённом шаге соответствующий байт управления
                ; Note:
                ;   полный домен пары накопитель и управление проверен во всех 65536 сочетаниях этого входа
                ;   начальные неподходящие signed8 не нормализуются общим насыщением, исходные переполнения и подстановки сохранены
                ;   сопоставлены регистры включая R, все записи и восемь банков RAM, записей CPU-стека и порта нет
                ;   повтор клавиши зависит от числа вызовов и накопленного остатка, период в игровых кадрах здесь не устанавливается
                ;   совместное пространство остальных входных регистров, IRQ, точные T, сборка и нативный запуск не проверялись
                ; -----------------------------------------
                ; Создание запрета затухания Turn на текущий проход, даже без готовности накопителя.
Entry:          LD A, @ActionControlKeyConst.One
                LD (@ActionControlDecayState.TurnPrev), A
                ; Расчёт накопленного повтора клавиши с сохранением остатка по модулю 256.
                LD A, #00
                ADD A, @ActionControlKeyConst.TurnAdd
                LD (@ActionControlDecayState.TurnStep1), A
                ; Обновление накопителя противоположного направления, флаги текущего ADD сохраняются.
                LD A, @ActionControlKeyConst.OppositeReset
                LD (@ActionControlDecayState.TurnStep0), A
                RET NC                                                          ; выход, если накопитель не переполнился, управление пока не изменяется

                ; Расчёт кандидата увеличения signed8 на единицу.
                LD A, (@ControlsPointMotionState.TurnControl)
                ADD A, @ActionControlKeyConst.One
                JP P, @Action.RequestTurnPositive.CheckLimit                    ; переход, если кандидат неотрицательный, проверить его границу без подстановки

                ; Создание исходного первого значения направления после смены знака либо его переполнения.
                LD A, @ActionControlKeyConst.One
                ; Проверка кандидата на исходную границу направления, прежнее значение при отказе сохраняется.
CheckLimit:     CP @ActionControlKeyConst.TurnPositive
                RET NC                                                          ; выход, если кандидат не меньше исключённой положительной границы, сохранить управление

                ; Обновление управления разрешённым кандидатом без изменения флагов CP.
                LD (@ControlsPointMotionState.TurnControl), A
                RET

                endmodule
                endmodule
