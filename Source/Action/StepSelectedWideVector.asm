                module Action
                module StepSelectedWideVector
                ; Документация [алгоритм и проверка](../../Docs/ActionWideVectorState.md)
                ; -----------------------------------------
                ; Шаг кодов движения к выбранному широкому вектору и проверка следующих состояний
                ; исходная запись 17, адреса F0BE..F0F7
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, альтернативные регистры учитываются договорами дочерних процедур
                ;   IX указывает FActionRecord с Components, OffsetPhase1/2, TargetCodeStep, WideTargetIndex, StateCode и ClassCode
                ;   WideTargetIndex задаёт индекс строки из трёх dword по 9B27+12*индекс, доступны фактические байты выбранной строки
                ;   действуют договоры StepRecordTowardWideVector, CheckLinkedTargetTransition и NextRandomWord2
                ;   ACTION банка 0 и таблицы геометрии доступны, 18 дополнительных байтов CPU-стека доступны, IRQ и повторный вход исключены
                ;   действует договор PrepareObjectOffsetTransform, активной записи доступны фазы, масштабы и предел, результаты и стек не перекрывают код и таблицы
                ; Out:
                ;   перед переходами состояния всегда выполнен StepRecordTowardWideVector с IY выбранной строки
                ;   CheckLinkedTargetTransition может установить связь и State0E либо выполнить переходы State13/14, Carry немедленно ведёт к общему F0F8
                ;   при Carry=0 дополнительный поток 2 вызывается только при ненулевом байте 9B83 и полном ClassCode в диапазоне 1..4
                ;   только H нового слова потока 2=41 и L>=5A устанавливают StateCode=0C, это не маскированная проверка класса
                ;   все дальнейшие эффекты общего хвоста относятся к полям и регистрам после собственного выбора состояния
                ;   при итоговом Component0.High=80 общий хвост возвращает AF=8042 и сохраняет остальные результаты дочерних процедур, R добавляет четыре M1, SP=входной SP+2
                ;   на активной ветви нижеследующие результаты вычислителя относятся к V из прежнего OffsetScaleLow и выбранного старшего байта
                ;   HL=(-Q) AND FFFF при бите 7 S=1, иначе HL=Q, DE=Q при бите 7 S=1, иначе DE=abs(V)
                ;   BC - B=W[Offset0], C=0
                ;   AF - A=S, F от 16-разрядного 0-Q при бите 7 S=1, иначе флаги логического XOR с результатом S
                ;   HL', DE', BC' сохраняют результаты дочерних процедур
                ;   AF' - A'=U, F'=(U AND 28) OR (40 при U=0) OR (10 при 2*((P SHR 16) AND 0F)+(U AND 1)>0F), остальные биты F' нулевые
                ;   IX восстановлен, IYH сохраняет результат дочерних процедур, IYL=W[(Offset1+64) AND FF]
                ;   Coefficient0..2 содержат результат построителя, Base0..2 содержат три произведения с одним входным V
                ;   SP=входной SP+2, I, IM, IFF и paging сохраняются, порты не используются
                ;   Offset0..2 получают OffsetPhase0, wrap8(OffsetPhase1+80) и OffsetPhase2
                ;   OffsetScaleLow получает wrap8(старое+1), если этот кандидат ниже Phase2OrTarget, иначе сохраняется прежний байт
                ;   OffsetScaleHigh обнулён при ClassCode<10 и StateCode не равном 13, иначе сохранён
                ;   на активной ветви общий хвост добавляет к R 30+Hold+4*Small+2*Small*Different M1 подготовки плюс полный вычислитель, старший бит R сохраняется
                ;   на всех путях внешний RET снимает исходный возврат, IX, I/IM/IFF сохраняются, итоговый 7FFD=10
                ;   R учитывает все M1 выбора строки и дочерних путей, выбор требует 6+3*(WideTargetIndex+1) M1 до первого CALL, затем прибавляются полные M1 общего хвоста
                ;   глубина временного стека до 18 байтов достигается в геометрии, общий вычислитель после возврата детей повторно использует до шести байтов ниже исходного SP
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IY, R, коды движения и условно поля состояний, связи и таймера, состояния потоков, изменяемые операнды дочерних процедур, CPU-стек, 7FFD, три фазовых операнда, Coefficient0..2 и Base0..2
                ; Note:
                ;   при WideTargetIndex=FF исходный INC B даёт ноль, DJNZ выполняет 256 сложений, строка находится по A71B, ограничение диапазона не добавлялось
                ;   выбор не проверяет границы логического массива, старшие индексы могут читать другие физические данные, их назначение этим не переопределяется
                ;   прежние 69632 случая проверяют границу F0F8, новая композиция того же количества исполняет общий подготовитель и вычислитель до внешнего RET
                ;   в обеих сериях список кандидатов пуст, другие списки проверены отдельной моделью CheckLinkedTargetTransition до её возврата, полное сочетание этих списков с общим хвостом не проверено
                ;   сверены регистры кроме T, точный R, восемь банков, кратность присваиваний и реальные OUT, поля за пределами изменяемых профилей сохраняют исходную подготовку
                ;   сохранение альтернативных координатных регистров и IYH общим хвостом относится к результатам дочерних процедур
                ;   полное произведение входов, аппаратные IRQ, сборка, точные T и нативный запуск не проверялись
                ;   эффективное слово V перед 6D06 содержит прежний OffsetScaleLow в E и итоговый OffsetScaleHigh в D, это не входное DE всей процедуры
                ;   Hold=1 при сохранении прежнего младшего масштаба, иначе 0, Small=1 при ClassCode<10, Different=1 при StateCode не равном 13, иначе соответствующий признак нулевой
                ;   10, 13 и 80 в условиях полей обозначают шестнадцатеричные коды, числа M1 десятичные
                ;   c2 обозначает третий байтовый коэффициент, m=abs(s8(c2)) AND 7F, P=m*abs(V), Q=floor(P/128), U=P SHR 15, S=c2 XOR HIGH слова V
                ;   нулевой фактор для коэффициента 80 сохранён, знак определяется исходным байтом коэффициента и старшим байтом V
                ;   каждое Base равно -floor((abs(s8(c_i)) AND 7F)*abs(V)/128) при бите 7 c_i XOR HIGH V, иначе положительному частному, всё по модулю 65536
                ;   шесть временных байтов после возврата содержат исходный IX по SP-2, слово V по SP-4 и внутренний возврат 6D0C по SP-6, POP не очищает RAM
                ;   для фактора m>0 умножение даёт 35+floor(log2(m))+2*popcount(m) M1, при m=0 даёт 32 M1
                ;   к каждому умножению добавляются семь M1 при V<0, две при бите 7 коэффициента и четыре при бите 7 его XOR HIGH V
                ; -----------------------------------------
                ; Выбор строки широкого вектора по WideTargetIndex, индекс FF сохраняет исходные 256 итераций DJNZ.
Entry:          LD B, (IX + @FActionRecord.WideTargetIndex)
                INC B
                ; Подготовка адреса перед первой строкой и физического размера трёх dword.
                LD IY, @ActionWideStateConst.BeforeFirst
                LD DE, @ActionWideStateConst.VectorStride
                ; Расчёт адреса очередной строки прибавлением её исходного размера.
SelectVector:   ADD IY, DE
                DJNZ @Action.StepSelectedWideVector.SelectVector

                ; Обновление кодов движения через исходное насыщение, банковый корень и оба кодировщика отношения.
                CALL @Action.StepRecordTowardWideVector.Entry
                ; Проверка случайного выбора связи либо фазовых переходов после изменения кодов движения.
                CALL @Action.CheckLinkedTargetTransition.Entry
                JP C, @Action.PrepareObjectOffsetTransform.Entry                ; переход, если дочерняя проверка вернула Carry, продолжить общий расчёт смещений

                ; Проверка глобального допуска дополнительного перехода State0C.
                LD A, (@ActionWideStateConst.ModeByte)
                AND A
                JR Z, @Action.PrepareObjectOffsetTransform.Entry                ; переход, если байт допуска равен нулю, продолжить общий расчёт смещений

                ; Проверка полного ClassCode, дополнительный переход разрешён только классам от 1 до 4.
                LD A, (IX + @FActionRecord.ClassCode)
                CP #00
                JR Z, @Action.PrepareObjectOffsetTransform.Entry                ; переход, если ClassCode равен нулю, продолжить общий расчёт смещений

                CP @ActionWideStateConst.FirstExcluded
                JR NC, @Action.PrepareObjectOffsetTransform.Entry               ; переход, если ClassCode не меньше пяти, продолжить общий расчёт смещений

                ; Обновление отдельного случайного потока 2 после всех предварительных допусков.
                CALL @Action.NextRandomWord2.Entry
                ; Проверка точного старшего байта нового слова перед проверкой нижнего порога.
                LD A, H
                CP @ActionWideStateConst.RandomHigh
                JR NZ, @Action.PrepareObjectOffsetTransform.Entry               ; переход, если старший байт нового слова не равен 41, продолжить общий расчёт смещений

                ; Проверка нижней границы младшего байта при уже принятом старшем байте 41.
                LD A, L
                CP @ActionWideStateConst.RandomLowMin
                JR C, @Action.PrepareObjectOffsetTransform.Entry                ; переход, если младший байт меньше 5A, сохранить состояние и продолжить общий расчёт смещений

                ; Обновление StateCode до 0C после совпадения обоих случайных условий.
                LD (IX + @FActionRecord.StateCode), @ActionWideStateConst.NextState
                ; JP @Action.PrepareObjectOffsetTransform.Entry, продолжение в PrepareObjectOffsetTransform.asm

                endmodule
                endmodule
