                module Action
                module DispatchClassOnHighRandomWord
                ; Документация [алгоритм и проверка](../../Docs/ActionRandomClassGate.md)
                ; -----------------------------------------
                ; Вызов обработчика класса только при новом слове потока 0 не меньше F000
                ; исходная запись 17, адреса F69E..F6AA
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, IX текущая доступная FActionRecord
                ;   при допуске ClassCode AND 7F меньше 26, действуют условия DispatchRecordClass и соответствующего обработчика
                ;   подготовлен Stream0, выбран ACTION банка 0, доступен внешний возврат и восемь дополнительных байтов CPU-стека, IRQ не вмешиваются
                ; Out:
                ;   Stream0 всегда продвинут один раз, при новом слове меньше F000 обработчик класса не вызывается
                ;   при отказе HL=wrap16(новое слово-F000), DE=F000, BC равен исходному BC', A новый FoldByte, F от вычитания с нулевым входным Carry
                ;   при отказе HL', DE', BC' соответствуют результату потока 0, AF', IX, IY, I/IM/IFF и paging сохраняются
                ;   при новом слове не меньше F000 исполнен DispatchRecordClass с хвостовым JP, все дальнейшие выходы и записи определяются договором выбранного класса
                ;   SP после полного возврата равен входному SP+2, новый промежуточный адрес возврата перед диспетчером не создаётся
                ;   R включает вызов и поток 0, пять M1 проверки, а при допуске ещё один M1 хвостового JP и стоимость диспетчера с обработчиком
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', R, Stream0 и CPU-стек всегда, остальные регистры и поля по допущенному обработчику класса
                ; Note:
                ;   это сравнение полного слова, а не проверка одного случайного байта или битовой маски
                ;   порог F000 допускает последние 4096 из 65536 возможных слов, равномерность и независимость потока этим не доказываются
                ;   65536 сценариев проверили все начальные слова потока на выбранных свёртках, все 26 кодов класса и их старшие алиасы
                ;   исполнены настоящие генератор, диспетчер и классовые обработчики до внешнего RET, сверены регистры с R, восемь банков и кратность записей
                ;   штатный вызывающий путь F69E не установлен, соседний JP по F68E находится после RET другого обработчика
                ;   полное произведение данных, аппаратные IRQ, точные T, сборка и нативный запуск не проверялись
                ; -----------------------------------------
                ; Обновление отдельного потока 0 перед решением о повторной обработке класса.
Entry:          CALL @Action.NextRandomWord0.Entry
                ; Проверка полного нового слова относительно порога F000, OR A очищает входной Carry вычитания.
                LD DE, @ActionRandomClassGateConst.WordThreshold
                OR A
                SBC HL, DE
                RET C                                                           ; выход, если новое слово потока 0 меньше F000, обработчик класса не вызывать

                ; Хвостовая передача в обычный диспетчер класса с исходным внешним возвратом.
                JP @Action.DispatchRecordClass.Entry

                endmodule
                endmodule
