                module Action
                module PrepareProjectionScale
                ; Документация [масштаб заголовка](../../Docs/ActionScaleHeader.md)
                ; -----------------------------------------
                ; Масштабирование мантиссы заголовка на степень двух и настройка трёх относительных переходов
                ; исходная запись 17, код ACTION банка 0, адреса E1B9..E1D0
                ; In:
                ;   HL слово FActionModelHeader, L содержит BoundMantissa 0..255, H содержит ScaleExponent от 1 до 6
                ;   DE, BC и AF числовых аргументов не задают, исходные флаги не влияют на результат
                ;   операнды JR по E1C8, E232 и E26B и слово по E2C5 доступны для записи, IRQ не вмешиваются
                ;   это последовательный фрагмент, SP сохраняется, внешний возврат на CPU-стеке не используется
                ; Out:
                ;   HL=m*2^(h-1), где m входной BoundMantissa и h входной ScaleExponent, ScaledBound получает то же слово
                ;   DE и BC сохраняются
                ;   AF содержит A=6-h, при h=1 F=#02, при h=2..4 F=#00
                ;   при h=5 F=(m >> 4) AND #08, при h=6 F=#40 OR ((m >> 3) AND #18)
                ;   HL', DE', BC', AF' сохраняются
                ;   IX и IY сохраняются, SP, I, IM, IFF и paging сохраняются, следующее исполнение начинается по E1D1
                ;   SizeSkip, FirstAxisSkip и SecondAxisSkip получают 6-h, первый JR исполняет ровно h-1 удвоений
                ;   Z установлен только при h=6, в том числе при ненулевом масштабированном HL, нулевая мантисса при h<6 не устанавливает Z
                ;   R получает 7+h M1, бит 7 R сохраняется, дополнительных записей CPU-стека и OUT нет
                ; Corrupt:
                ;   HL, AF, R, три байта смещений JR и слово ScaledBound
                ; Note:
                ;   при H=1 JR пропускает все пять ADD, при H=6 его нулевое смещение оставляет все пять ADD
                ;   исходный JR безусловный, Z не управляет числом удвоений
                ;   H вне 1..6 не проверяется, такой вход способен передать управление внутрь другой инструкции, допустимым он не объявляется
                ;   все 128 исходных чётных указателей страницы 9E дают заголовки с H от 1 до 5, но полный игровой диапазон индексов ещё не установлен
                ;   физические единицы мантиссы и полный окружающий обход этим локальным договором не доказаны
                ; -----------------------------------------
                ; Расчёт числа пропускаемых удвоений по показателю H заголовка, допустимы только H от 1 до 6.
Entry:          LD A, #06
                SUB H
                ; Обновление трёх смещений JR одним значением 6-H, следующие два перехода используют тот же масштаб осей.
                LD (@ActionScaleHeaderState.SizeSkip), A
                LD (@ActionScaleHeaderState.FirstAxisSkip), A
                LD (@ActionScaleHeaderState.SecondAxisSkip), A
                ; Расчёт масштабированной мантиссы, очистить H перед исходной цепочкой из пяти удвоений.
                LD H, #00
                ; Пропуск 6-H однобайтовых ADD, остаётся H-1 удвоений, исходный FE заменён выше.
SelectShifts:   JR @Action.PrepareProjectionScale.SelectShifts

                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ; Сохранение полученного слова в ScaledBound для последующего вычисления допуска.
                LD (@ActionScaleHeaderState.ScaledBound), HL
                ; JP @Action.CheckCloseRecordBounds.Entry, продолжение в CheckCloseRecordBounds.asm

                endmodule
                endmodule
