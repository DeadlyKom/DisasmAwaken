                module Action
                module ConsumeMissileStock
                ; Документация [списание ракет](../../Docs/ActionMissileConsume.md)
                ; -----------------------------------------
                ; Уменьшение выбранного запаса и отдельного байта 9BD2, передача сообщения о пуске и нового остатка очереди
                ; исходная запись 17, перенесённый код банка 5, адреса 70C6..70EC
                ; In:
                ;   HL адрес выбранного поля FMissileStock, Preferred при ненулевом Preferred, иначе Fallback
                ;   DE и BC числовых аргументов не задают, входной AF не задаёт условия списания
                ;   действуют договоры SelectMissileStock, QueueTextItemBank1 и QueueNumberBank1
                ;   банк 1 содержит Controls, 7FFD не заблокирован, общий стек имеет восемнадцать дополнительных байтов, IRQ не вмешиваются
                ; Out:
                ;   HL адрес поля, выбранного повторно после уменьшения, BC сохраняется
                ;   DE=0200 OR новый выбранный остаток, A=10, F соответствует AND нового Preferred даже при выборе Fallback
                ;   HL', DE', BC' и F' сохраняются, A'=11, IX, IY, I, IM и IFF сохраняются
                ;   SP=входной SP+2, выбранный входным HL байт запаса и байт 9BD2 уменьшены по модулю 256
                ;   последовательно переданы текст пуска, начало фразы остатка, числовая запись и конец фразы, каждый запрос может быть отклонён
                ;   7FFD получает четыре пары 11 и 10, на выходе полная конфигурация 10
                ;   R увеличивается на 113 M1 плюс 4 либо 7 M1 повторного выбора и суммы стоимостей четырёх QueueTextItem
                ; Corrupt:
                ;   HL, DE, AF, A', R, выбранный байт запаса, байт 9BD2, очередь и курсор при приёме записей, восемнадцать байтов CPU-стека, 7FFD
                ; Note:
                ;   при Preferred=1 повторный выбор переходит к Fallback, выводится его значение
                ;   проверка ненулевого запаса отсутствует, прямой вход с нулевым выбранным байтом даёт FF
                ;   9BD2 также читается как часть слова в Unknown6780, его игровой смысл не доказан
                ;   хвост не доказывает создание объекта ракеты, четыре запроса не являются атомарной записью фразы
                ; -----------------------------------------
                ; -----------------------------------------
                ; Списание запаса, выбранного до входа
                ; Предусловие задаёт одно из физических полей FMissileStock, защиты от нуля здесь нет.
Entry:          DEC (HL)
                ; Изменение отдельного исходного байта 9BD2, его игровое назначение ещё неизвестно.
                ; Unknown6780 обращается также ко всему слову 9BD2..9BD3, здесь меняется только младший байт.
                LD A, (#9BD2)
                ; Расчёт нового значения отдельного байта по модулю 256, без переноса в 9BD3.
                DEC A
                LD (#9BD2), A
                ; -----------------------------------------
                ; Передача сообщения о пуске в очередь банка 1
                ; Отказ заполненной очереди не отменяет уже выполненное списание.
                PUSH DE
                LD DE, @ActionMissileConsumeConst.LaunchedText
                CALL @Action.QueueTextItemBank1.Entry
                POP DE
                ; Передача начала фразы остатка отдельным запросом, приём предыдущей записи не проверяется.
                PUSH DE
                LD DE, @ActionMissileConsumeConst.RemainingText
                CALL @Action.QueueTextItemBank1.Entry
                POP DE
                ; -----------------------------------------
                ; Повторный выбор и передача остатка
                ; При исчерпании Preferred число теперь читается из Fallback.
                CALL @Action.SelectMissileStock.Entry
                ; Добавление числовой записи с кодом 02, обёртка оставляет её в DE.
                CALL @Action.QueueNumberBank1.Entry
                ; Передача конца фразы с сохранением числовой записи DE, запрос также может быть отклонён.
                PUSH DE
                LD DE, @ActionMissileConsumeConst.MissilesText
                CALL @Action.QueueTextItemBank1.Entry
                POP DE
                RET

                ; -----------------------------------------
                endmodule
                endmodule
