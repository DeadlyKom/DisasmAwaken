                ; Документация [алгоритм и проверка](../../Docs/ActionIgnoredClasses.md)
                ; -----------------------------------------
                ; Немедленный общий возврат исходных классов 10..25 без изменения записи
                ; исходная запись 17, адреса 6524..6524
                ; In:
                ;   HL, DE, BC, AF и альтернативные регистры являются сохраняемым контекстом
                ;   на CPU-стеке лежит действительный внешний возврат, прерывания не вмешиваются
                ; Out:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY сохраняются
                ;   SP=входной SP+2, PC получает слово внешнего возврата, I, IM, IFF и страница сохраняются
                ;   R получает один M1 с сохранением бита 7, записи RAM и CPU-стека отсутствуют
                ; Corrupt:
                ;   R, SP и PC, регистры данных и флаги не меняются
                ; Note:
                ;   это существующий байт C9 по 6524, искусственная инструкция для упрощения проекта не добавлялась
                ;   832 композиционных сценария исполнили реальный диспетчер и этот RET для классов 10..25 и их алиасов со старшим битом
                ;   проверены все 26 исследовательских позиций, регистры включая R и восемь банков RAM
                ;   назначение других классов, IRQ, точные T, сборка и нативный запуск этим не доказаны
                ; -----------------------------------------
                ; Возврат вызывающему диспетчера, исходная таблица направляет сюда классы 10..25.
Entry:          RET

                endmodule
