                module Action
                module ApproachWordAndAccumulate
                ; Документация [алгоритм и проверка](../../Docs/ActionApproachWord.md)
                ; -----------------------------------------
                ; Приближение HL к BC по обёрнутой разности с накоплением старшего байта остатка в C'
                ; исходная запись 17, адреса 6311..634A
                ; In:
                ;   HL текущее слово, BC базовое слово, оба допускают весь диапазон 0000..FFFF
                ;   BC', C' содержит байтовый накопитель, B' сохраняется, остальные регистры не задают числовых аргументов
                ;   общий код ACTION доступен, SP указывает на внешний возврат, IRQ не вмешиваются
                ; Out:
                ;   HL=wrap16(исходный HL+signedStep), DE=signedStep в дополнительном коде, BC сохраняется
                ;   delta=wrap16(исходный HL−BC), magnitude равен delta при сброшенном бите 15, иначе wrap16(−delta)
                ;   step=floor(magnitude/8) при magnitude<256, иначе 180, signedStep положителен для отрицательной delta и отрицателен для неотрицательной
                ;   residual=wrap16(delta+signedStep), folded равен старшему байту residual либо его инверсии при установленном бите 7 этого байта
                ;   AF - A равен исходному C' OR folded, F содержит логические флаги OR этого результата
                ;   HL', DE' сохраняются
                ;   BC' - B' сохраняется, C' равен исходному C' OR folded
                ;   AF' сохраняется
                ;   IX, IY, I/IM/IFF и paging сохраняются, память не меняется
                ;   SP после RET равен входному SP+2, временных записей CPU-стека нет
                ;   R получает 25 M1 плюс 7 при отрицательной delta, плюс 9 при малом модуле, плюс 7 при неотрицательной delta, плюс 1 при отрицательном residual
                ; Corrupt:
                ;   HL, DE, AF, C', R, SP только внешним RET
                ; Note:
                ;   отрицательность определяется битом 15 обёрнутой разности, исходный JP P не учитывает математическое переполнение
                ;   при magnitude<8 шаг равен нулю и слово не приближается дальше, эта особенность оригинала сохранена
                ;   folded не является точным модулем residual, отрицательный старший байт инвертируется без прибавления единицы
                ;   Z показывает ноль накопителя после OR, а не точное равенство HL и BC
                ;   196608 сценариев проверили все 65536 разностей для BC=0000, 7FFF, FFFF, точные регистры, флаги, R и отсутствие любых записей
                ;   полное произведение двух входных слов и независимого C' не исчерпано
                ;   ApproachTargetRecordAndResolve вызывает процедуру для трёх Components в State08, CreateLinkedMissileRecord задаёт это состояние классу #11
                ;   цепочка создания и выбора State08 установлена по исходникам, её нативное прохождение не подтверждено
                ;   вмешательство IRQ, точные T, сборка и нативный запуск не проверялись
                ; -----------------------------------------
                ; Расчёт обёрнутой разности текущего слова и базы с очищенным Carry.
Entry:          OR A
                SBC HL, BC
                ; Сохранение разности в DE, исходный знак остаётся в старшем байте H.
                LD D, H
                LD E, L
                JP P, @Action.ApproachWordAndAccumulate.SelectStep              ; переход, если бит 15 обёрнутой разности сброшен, её модуль уже находится в DE

                ; Расчёт модуля отрицательной разности по модулю 65536, значение 8000 остаётся 8000.
                LD A, E
                CPL
                LD E, A
                LD A, D
                CPL
                LD D, A
                INC DE
                ; Проверка модуля перед выбором малого шага или фиксированного шага 180.
SelectStep:     LD A, D
                CP #01
                LD A, #B4
                JR NC, @Action.ApproachWordAndAccumulate.SetDirection           ; переход, если модуль не меньше 256, использовать шаг 180

                ; Расчёт целой части модуля, делённого на восемь, оба SRL D перед RRA дают нулевой Carry.
                LD A, E
                SRL D
                RRA
                SRL D
                RRA
                SRL A
                ; Подготовка положительного слова шага и проверка исходного знака delta.
SetDirection:   LD E, A
                LD D, #00
                BIT 7, H
                JR NZ, @Action.ApproachWordAndAccumulate.ApplyStep              ; переход, если delta отрицательна, положительный шаг уже направлен к базе

                ; Расчёт отрицательного шага для неотрицательной обёрнутой разности.
                LD A, E
                CPL
                LD E, A
                LD A, D
                CPL
                LD D, A
                INC DE
                ; Расчёт нового остатка относительно базы, его старший байт сохраняется в A.
ApplyStep:      ADD HL, DE
                LD A, H
                ; Восстановление абсолютного текущего слова добавлением BC, флаги затем задаёт старший байт остатка.
                ADD HL, BC
                OR A
                JP P, @Action.ApproachWordAndAccumulate.Accumulate              ; переход, если старший байт остатка неотрицателен, использовать его без инверсии

                ; Нормализация отрицательного старшего байта через инверсию без прибавления единицы.
                CPL
                ; Накопление нормализованного старшего байта в альтернативном C без изменения других альтернативных пар.
Accumulate:     EXX
                OR C
                LD C, A
                EXX
                RET

                endmodule
                endmodule
