                module Action
                module RecordIndexToAddress
                ; Документация [коды и адреса записей](../../Docs/ActionRecordIndex.md)
                ; -----------------------------------------
                ; Расчёт адреса записи A100 плюс входной код, умноженный на 64
                ; исходная запись 17, код ACTION банка 0, адреса E6A7..E6B4
                ; In:
                ;   HL, DE и BC числовых аргументов не задают, A входной код 00..FF, входные флаги не влияют на результат
                ;   исполняется код ACTION банка 0, на CPU-стеке внешний возврат, IRQ не вмешиваются
                ; Out:
                ;   HL=A100+64*входной A, A старший байт полученного адреса, DE и BC сохраняются
                ;   F соответствует ADD A1 к входному A, сдвинутому вправо на два разряда
                ;   HL', DE', BC', AF', IX, IY, I, IM и IFF сохраняются, SP=входной SP+2
                ;   R увеличивается на 12 M1, записей RAM и CPU-стека нет
                ; Corrupt:
                ;   HL, AF, R
                ; Note:
                ;   диапазон результата A100..E0C0, доступность и содержимое записи не проверяются
                ;   адрес выше BFFF относится к текущему банковому окну, преобразователь только считает число
                ; -----------------------------------------
                ; Расчёт младших разрядов адреса, два младших бита кода становятся битами 7 и 6 L.
Entry:          LD L, #00
                SRL A
                RR L
                SRL A
                RR L
                ; Расчёт старшего байта адреса, к частному от деления кода на четыре добавляется A1.
                ADD A, @ActionRecordIndexConst.BaseHigh
                LD H, A
                RET

                endmodule
                endmodule
