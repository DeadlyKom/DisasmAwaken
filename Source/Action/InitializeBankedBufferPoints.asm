                module Action
                module InitializeBankedBufferPoints
                ; Документация [алгоритм и проверка](../../Docs/ActionBankedBufferInit.md)
                ; -----------------------------------------
                ; Подготовка 35 координат точек в Controls банка 1 с возвратом полной конфигурации 10
                ; исходная запись 17, перенесённый код ACTION фиксированного банка 5, смещения #0F13..#0F20
                ; In:
                ;   HL, DE, BC и AF входных числовых аргументов не задают, DE и BC сохраняются
                ;   Seed и ControlsBufferPoints находятся в загруженном банке 1, действуют договоры InitializeBufferPoints и NextBufferRandom
                ;   7FFD не заблокирован, обёртка и SelectMemoryPage доступны вне банкового окна, IRQ не вмешивается
                ;   CPU-стек содержит внешний возврат и допускает четыре дополнительных байта без пересечения с кодом и данными
                ; Out:
                ;   HL=C546, адрес после 35 записей Y,X, DE и BC сохранены, AF=1042
                ;   подготовлены 35 записей, Y=1..94, X=1..253, Seed обновлён 70 раз
                ;   HL' - новое Seed, DE' - последняя разность HIGH(t)-LOW(t), BC'=LOW(t), t=(7*предыдущее Seed-4) AND FFFF
                ;   A' - Y последней точки, F' содержит только Carry последнего ограничения Y, IX и IY сохраняются
                ;   OUT 7FFD получает 11, затем 10, итоговая полная конфигурация 10 не восстанавливает входную страницу
                ;   I/IM/IFF сохраняются, SP после RET равен входному SP+2, четыре временных байта CPU-стека остаются изменёнными
                ;   R получает 3030 M1 плюс по одному за каждое фактически выполненное дополнительное ограничение X или Y, бит 7 сохраняется
                ; Corrupt:
                ;   HL, AF, HL', DE', BC', AF', R, 70 байтов координат и два байта Seed банка 1, четыре байта CPU-стека и 7FFD
                ; Note:
                ;   перед каждой парой сначала генерируется X, затем Y, физически сохраняются Y и X, исходное неравномерное ограничение не исправляется
                ;   дополнительная операция выполняется для X=0 либо X>=254, для (Y AND 7F)=0 либо >=95, условия внутри каждой координаты взаимоисключающие
                ;   обёртка с двумя селекторами добавляет 18 M1, построитель добавляет 3012 M1 и дополнительные ограничения координат
                ;   65536 сценариев выполняют обёртку для каждого исходного Seed с настоящими 70 вызовами генератора и реальными OUT
                ;   все входные AF связаны с Seed, 32 незаблокированные конфигурации и два SP распределены по случаям, полное произведение аргументов не перебиралось
                ;   проверены регистры включая R, все восемь банков RAM и 360 байтовых записей каждого вызова
                ;   аппаратный порядок шинных циклов стека, точные T, IRQ, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Контекст Controls банка 1
                ; Выбор полной конфигурации Controls, исходные DE и BC сохраняются селектором.
Entry:          LD A, @ActionBankPage.Controls
                CALL @Action.SelectMemoryPage.Entry
                ; Подготовка 35 координат Y,X настоящим построителем с 70 вызовами генератора, Seed хранится в банке 1.
                CALL @Controls.InitializeBufferPoints.Entry
                ; -----------------------------------------
                ; Возврат к контексту ACTION
                ; Выбор полной конфигурации Runtime, предыдущая входная страница не восстанавливается.
                LD A, @ActionBankPage.Runtime
                CALL @Action.SelectMemoryPage.Entry
                RET

                ; -----------------------------------------
                endmodule
                endmodule
