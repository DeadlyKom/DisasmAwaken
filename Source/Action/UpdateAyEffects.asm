                module Action
                module UpdateAyEffects
                ; Документация [алгоритм и проверка](../../Docs/ActionAyEffects.md)
                ; -----------------------------------------
                ; Вывод очередных строк потоков AY-каналов A и B и формирование канала C по R и изменяемому уровню
                ; исходная запись 17, код ACTION банка 0, адреса ECA8..ED8E, один вызов не задаёт длительность строки во времени, смещения #8CA8..#8D8E
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, входной R участвует в формировании шума канала C
                ;   CursorA и CursorB в операндах кода задают строки, нулевой старший байт курсора отключает соответствующий поток
                ;   активная строка содержит ToneLow, ToneHigh, MixerBits и Volume, доступен младший байт тона следующей строки
                ;   ChannelCLevel задаёт байт уровня, банк 0 выбран, чтение FFFD возвращает актуальный регистр 7 смесителя AY
                ;   CPU-стек содержит внешний возврат, IRQ не вмешиваются, других писателей курсоров и AY во время вызова нет
                ; Out:
                ;   HL содержит старший байт CursorB+4 при активном B либо нулевой H при отключённом B, L равен 00 или 20 по порогу R
                ;   DE сохраняется, BC=BFFD, A=max(4, ChannelCLevel >> 1), F соответствует CP значения ChannelCLevel >> 1 с 4
                ;   HL', DE', BC', AF', IX, IY, I, IM и IFF сохраняются, SP=входной SP+2, дополнительных стековых записей нет
                ;   активный поток продвигает курсор на четыре, нулевой ToneLow следующей строки обнуляет старший байт курсора и запрещает тон и шум своего канала
                ;   A выводит регистры 0, 1, 7 и 8, B выводит 2, 3, 7 и 9, каждый активный поток выводит ровно одну строку
                ;   C всегда записывает регистр 5 значением 0C, регистр 6 значением 05 и регистр 10 вычисленным уровнем, регистр 4 не записывается
                ;   смеситель C получает (старый регистр 7 AND DB) OR 20 при R >= 20 в момент LD A,R, иначе тот же результат OR 00
                ;   7FFD не записывается, OUTI использует зеркало BEFD, обычная запись данных использует BFFD
                ; Corrupt:
                ;   HL, BC, AF, R, два операнда Cursor при активных потоках, выбранный AY-регистр и регистры 0..3, 5..10 по пути
                ; Note:
                ;   нулевой младший байт текущей строки сам по себе не останавливает чтение, проверяется только следующая строка после вывода
                ;   MixerBits A применяется целиком после AND F6, MixerBits B циклически сдвигается влево и применяется целиком после AND ED
                ;   поток с произвольными MixerBits способен затронуть чужие каналы, предположение о единственном допустимом бите не вводится
                ;   выходной H не обнуляется при завершении B, обнуляется старший байт сохранённого операнда, это разные значения
                ;   ChannelCLevel не уменьшается этой процедурой, при нуле выводится уровень 4, исходная особенность сохранена
                ;   модель проверяет обмен с восьмибитовым регистром 7, реальный AY, прерывания и акустический результат не запускались
                ; -----------------------------------------
                ; -----------------------------------------
                ; Следующая строка канала A
                ; Чтение изменяемого указателя и проверка нулевого старшего байта как признака отключённого потока.
Entry:          LD HL, #0000
                LD A, H
                OR A
                JR Z, @Action.UpdateAyEffects.ChannelB                          ; переход, если старший байт CursorA равен нулю, канал A не обновлять

                ; Вывод двух байтов периода A в регистры 0 и 1, OUTI продвигает указатель строки.
                LD BC, #FFFD
                XOR A
                OUT (C), A
                LD B, #BF
                OUTI
                LD B, #FF
                LD A, #01
                OUT (C), A
                LD B, #BF
                OUTI
                ; Обновление смесителя, очистить только запреты тона и шума A и применить полный MixerBits строки.
                LD B, #FF
                LD A, #07
                OUT (C), A
                IN A, (C)
                AND #F6
                OR (HL)
                LD B, #BF
                OUT (C), A
                ; Вывод Volume в регистр 8 и продвижение на четыре байта от начала строки.
                INC HL
                LD A, #08
                LD B, #FF
                OUT (C), A
                LD B, #BF
                OUTI
                ; Обновление CursorA и проверка ToneLow следующей строки как маркера завершения.
                LD (@ActionAyEffectState.CursorA), HL
                LD A, (HL)
                OR A
                JR NZ, @Action.UpdateAyEffects.ChannelB                         ; переход, если ToneLow следующей строки ненулевой, оставить поток A активным

                ; Отключение курсора A через его старший байт, затем установка запретов тона и шума A.
                LD (@ActionAyEffectState.CursorA + 1), A
                LD B, #FF
                LD A, #07
                OUT (C), A
                IN A, (C)
                OR #09
                LD B, #BF
                OUT (C), A
                ; -----------------------------------------
                ; Следующая строка канала B
                ; Чтение собственного изменяемого указателя, независимо от состояния потока A.
ChannelB:       LD HL, #0000
                LD A, H
                OR A
                JR Z, @Action.UpdateAyEffects.ChannelC                          ; переход, если старший байт CursorB равен нулю, канал B не обновлять

                ; Вывод двух байтов периода B в регистры 2 и 3.
                LD BC, #FFFD
                LD A, #02
                OUT (C), A
                LD B, #BF
                OUTI
                LD B, #FF
                LD A, #03
                OUT (C), A
                LD B, #BF
                OUTI
                ; Обновление смесителя, очистить запреты B и применить MixerBits строки после циклического сдвига на один разряд.
                LD B, #FF
                LD A, #07
                OUT (C), A
                IN A, (C)
                AND #ED
                LD B, A
                LD A, (HL)
                RLCA
                OR B
                LD B, #BF
                OUT (C), A
                ; Вывод Volume в регистр 9, указатель переходит к следующей четырёхбайтовой строке.
                INC HL
                LD A, #09
                LD B, #FF
                OUT (C), A
                LD B, #BF
                OUTI
                ; Обновление CursorB и проверка ToneLow следующей строки на завершение.
                LD (@ActionAyEffectsState.CursorB), HL
                LD A, (HL)
                OR A
                JR NZ, @Action.UpdateAyEffects.ChannelC                         ; переход, если ToneLow следующей строки ненулевой, оставить поток B активным

                ; Отключение курсора B и установка запретов тона и шума B, остальные биты прочитанного смесителя сохраняются.
                LD (@ActionAyEffectsState.CursorB + 1), A
                LD B, #FF
                LD A, #07
                OUT (C), A
                IN A, (C)
                OR #12
                LD B, #BF
                OUT (C), A
                ; -----------------------------------------
                ; Формирование канала C
                ; Обновление только старшего байта периода C значением 0C, младший байт регистра 4 остаётся прежним.
ChannelC:       LD C, #FD
                LD B, #FF
                LD A, #05
                OUT (C), A
                LD B, #BF
                LD A, #0C
                OUT (C), A
                ; Расчёт двоичного управления шумом по текущему R, сравнение с порогом 20 учитывает весь байт.
                LD B, #FF
                LD A, #07
                OUT (C), A
                LD A, R
                CP #20
                JR C, @Action.UpdateAyEffects.ApplyNoise                        ; переход, если прочитанный R меньше 20, оставить значение ниже порога

                ; Ограничение всех значений от 20 до FF константой 20 до выделения бита.
                LD A, #20
                ; Обновление запретов C, бит 2 очищается, бит 5 получает результат порогового сравнения R.
ApplyNoise:     AND #20
                LD L, A
                IN A, (C)
                AND #DB
                OR L
                LD B, #BF
                OUT (C), A
                ; Установка периода генератора шума равным 5, этот регистр общий для трёх каналов.
                LD A, #06
                LD B, #FF
                OUT (C), A
                LD B, #BF
                LD A, #05
                OUT (C), A
                ; Расчёт уровня C, сдвиг ChannelCLevel вправо и ограничение результата снизу значением 4.
                LD A, #0A
                LD B, #FF
                OUT (C), A
                LD B, #BF
                LD A, #00
                SRL A
                CP #04
                JR NC, @Action.UpdateAyEffects.WriteVolume                      ; переход, если половина ChannelCLevel не меньше 4, использовать вычисленное значение

                ; Выбор минимального уровня 4, флаги остаются от предшествующего CP.
                LD A, #04
                ; Вывод уровня в регистр 10 без изменения исходного ChannelCLevel.
WriteVolume:    OUT (C), A
                RET

                ; -----------------------------------------
                endmodule
                endmodule
