                module Action
                module AdvanceObjectPhaseWait
                ; Документация [алгоритм и проверка](../../Docs/ActionObjectPhaseWait.md)
                ; -----------------------------------------
                ; Обновление фазового счётчика и завершение ожидания по классу и компонентам
                ; исходная запись 17, адреса EFB5..F002
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, IX указывает доступную FActionRecord
                ;   полный ClassCode, SavedStateCode и старшие байты трёх Components читаемы, StateCode и OffsetScaleHigh доступны для записи
                ;   PhaseGate является доступным для записи общим операндом LD A,n, исходное значение в бинарнике 11
                ;   читается Component0.High, для активной записи доступны остальные фазовые поля, класс, состояние и порог
                ;   OffsetScaleLow и OffsetScaleHigh активной записи доступны для записи, ACTION банка 0 и общая RAM доступны
                ;   действует договор ApplyObjectOffsetVector, шесть байтов под SP и внешний возврат не перекрывают его код, таблицы, операнды и результаты
                ;   IRQ и повторный вход исключены
                ; Out:
                ;   при маркере Component0.High=80 выполняется внешний RET после собственного фазового префикса, AF=8042, SP=входной SP+2
                ;   на маркере HL/DE, альтернативные регистры, IX/IY сохраняются, BC сохраняется при ClassCode>=08, иначе B=fold(Yhigh), C=fold(Xhigh)
                ;   маркер не отменяет PhaseGate, OffsetScaleHigh и StateCode, уже записанные собственным префиксом
                ;   на активной ветви нижеследующие результаты вычислителя относятся к V из прежнего OffsetScaleLow и выбранного старшего байта
                ;   HL=(-Q) AND FFFF при бите 7 S=1, иначе HL=Q, DE=Q при бите 7 S=1, иначе DE=abs(V)
                ;   BC - B=W[Offset0], C=0
                ;   AF - A=S, F от 16-разрядного 0-Q при бите 7 S=1, иначе флаги логического XOR с результатом S
                ;   HL', DE', BC' сохраняются
                ;   AF' - A'=U, F'=(U AND 28) OR (40 при U=0) OR (10 при 2*((P SHR 16) AND 0F)+(U AND 1)>0F), остальные биты F' нулевые
                ;   IX восстановлен, IYH сохраняется, IYL=W[(Offset1+64) AND FF]
                ;   Coefficient0..2 содержат результат построителя, Base0..2 содержат три произведения с одним входным V
                ;   SP=входной SP+2, I, IM, IFF и paging сохраняются, порты не используются
                ;   Offset0..2 получают OffsetPhase0, wrap8(OffsetPhase1+80) и OffsetPhase2
                ;   OffsetScaleLow получает wrap8(старое+1), если этот кандидат ниже Phase2OrTarget, иначе сохраняется прежний байт
                ;   на активной ветви общий хвост добавляет к R 30+Hold+4*Small+2*Small*Different M1 подготовки плюс полный вычислитель, старший бит R сохраняется
                ;   при ClassCode>=08 собственный префикс задаёт StateCode=SavedStateCode и OffsetScaleHigh=0, PhaseGate не вращается
                ;   при ClassCode<08 PhaseGate получает RRCA прежнего байта, его исходный бит 0 допускает инкремент OffsetScaleHigh только ниже 0F
                ;   для класса ниже 08 максимум fold трёх старших компонент меньше 14 восстанавливает SavedStateCode и обнуляет OffsetScaleHigh
                ;   общий хвост дополнительно обнуляет OffsetScaleHigh при ClassCode<10 и итоговом StateCode не равном 13, иначе сохраняет результат фазового префикса
                ;   полный R включает собственную стоимость ниже и весь достигнутый F0F8, старший бит R сохраняется
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', IYL, R, Coefficient0..2, Base0..2 и шесть временных байтов CPU-стека, три фазовых операнда и условно OffsetScaleLow/OffsetScaleHigh, PhaseGate и условно StateCode
                ;   на маркере изменяются AF/R и при классе ниже 08 BC, собственные записи фазового префикса сохраняются, вычислитель не вызывается
                ; Note:
                ;   fold(b)=b XOR FF при установленном бите 7, иначе b, это инверсия отрицательного байта, а не точный модуль
                ;   08, 0F, 14, 10, 13 и 11 здесь шестнадцатеричные, соответствующие пороги класса, счётчика и максимума равны 8, 15 и 20 десятичным
                ;   PhaseGate общий для всех записей, при изменении только этим RRCA исходный 11 проходит цикл 11, 88, 44, 22, 11
                ;   единичный бит 0 встречается один раз за четыре допустимых вызова этого цикла, число не означает четыре кадра для каждой записи
                ;   если весь PhaseGate равен нулю, вращение сохраняет ноль и этот префикс не допускает инкремент через бит 0
                ;   класс не меньше 08 даёт 11 M1 собственного префикса, без вращения и свёртки компонент
                ;   для класса ниже 08 собственная стоимость 28+4*Gate+3*Gate*CanIncrement+NegCount+ChooseY+ChooseX+7*Release M1
                ;   Gate исходный бит 0, CanIncrement проверка прежнего OffsetScaleHigh<0F, NegCount число отрицательных старших компонент
                ;   ChooseY=1 при fold(Z)<fold(Y), ChooseX=1 при max(fold(Z),fold(Y))<fold(X), Release=1 при максимуме ниже 14, иначе признаки нулевые
                ;   эффективное слово V перед 6D06 содержит прежний OffsetScaleLow в E и итоговый OffsetScaleHigh в D, это не входное DE всей процедуры
                ;   Hold=1 при сохранении прежнего младшего масштаба, иначе 0, Small=1 при ClassCode<10, Different=1 при StateCode не равном 13, иначе соответствующий признак нулевой
                ;   10, 13 и 80 в условиях полей обозначают шестнадцатеричные коды, числа M1 десятичные
                ;   c2 обозначает третий байтовый коэффициент, m=abs(s8(c2)) AND 7F, P=m*abs(V), Q=floor(P/128), U=P SHR 15, S=c2 XOR HIGH слова V
                ;   нулевой фактор для коэффициента 80 сохранён, знак определяется исходным байтом коэффициента и старшим байтом V
                ;   каждое Base равно -floor((abs(s8(c_i)) AND 7F)*abs(V)/128) при бите 7 c_i XOR HIGH V, иначе положительному частному, всё по модулю 65536
                ;   шесть временных байтов после возврата содержат исходный IX по SP-2, слово V по SP-4 и внутренний возврат 6D0C по SP-6, POP не очищает RAM
                ;   для фактора m>0 умножение даёт 35+floor(log2(m))+2*popcount(m) M1, при m=0 даёт 32 M1
                ;   к каждому умножению добавляются семь M1 при V<0, две при бите 7 коэффициента и четыре при бите 7 его XOR HIGH V
                ;   маркер внутри F0F8 возвращается до записи общих фазовых операндов и не вызывает вычислитель, на активном пути внешний RET выполняет его хвост
                ;   отдельная проверка F0F8, 196608 прежних сценариев останавливаются перед 6D06 либо на раннем RET, новая композиция проверяет 15616 случаев до полного внешнего возврата
                ;   полное произведение всех аргументов, точные T, IRQ и нативная игра не доказаны
                ;   собственный префикс ранее проверен в 69632 случаях, полная композиция добавляет 49152 профиля ожидания и сохраняет 16384 профиля двух фазовых ходов
                ;   в полной композиции проверены регистры включая R, восемь банков, кратность присваиваний, отсутствие OUT и внешний RET
                ;   полное произведение входов, точные T, IRQ и нативная игра не доказаны
                ; -----------------------------------------
                ; Проверка класса перед фазовым ожиданием.
Entry:          LD A, (IX + @FActionRecord.ClassCode)
                CP #08
                JR NC, @Action.AdvanceObjectPhaseWait.ResumeState               ; переход, если класс не меньше 8, восстановить сохранённое состояние

                ; Вращение фазового операнда и проверка его исходного младшего бита.
                LD A, #11
                RRCA
                LD (@ActionObjectPhaseWaitState.PhaseGate), A
                JR NC, @Action.AdvanceObjectPhaseWait.FoldX                     ; переход, если младший бит фазы был нулём, пропустить инкремент

                ; Проверка насыщения счётчика перед инкрементом.
                LD A, (IX + @FActionRecord.OffsetScaleHigh)
                CP #0F
                JR NC, @Action.AdvanceObjectPhaseWait.FoldX                     ; переход, если счётчик не меньше 15, сохранить его

                INC A
                LD (IX + @FActionRecord.OffsetScaleHigh), A
                ; Свёртка старших байтов трёх компонент, отрицательные значения инвертируются.
FoldX:          LD A, (IX + @FActionRecord.Components.Component0.High)
                OR A
                JP P, @Action.AdvanceObjectPhaseWait.SaveX                      ; переход, если старший байт X неотрицателен, сохранить его

                CPL
SaveX:          LD C, A
                LD A, (IX + @FActionRecord.Components.Component1.High)
                OR A
                JP P, @Action.AdvanceObjectPhaseWait.SaveY                      ; переход, если старший байт Y неотрицателен, сохранить его

                CPL
SaveY:          LD B, A
                LD A, (IX + @FActionRecord.Components.Component2.High)
                OR A
                JP P, @Action.AdvanceObjectPhaseWait.CompareY                   ; переход, если старший байт глубины неотрицателен, сравнить его с Y

                CPL
                ; Поиск максимума свёрнутых компонент.
CompareY:       CP B
                JR NC, @Action.AdvanceObjectPhaseWait.CompareX                  ; переход, если глубина не меньше Y, сохранить текущий максимум

                LD A, B
CompareX:       CP C
                JR NC, @Action.AdvanceObjectPhaseWait.CheckLimit                ; переход, если текущий максимум не меньше X, проверить порог ожидания

                LD A, C
                ; Проверка порога удержания состояния.
CheckLimit:     CP #14
                JP NC, @Action.PrepareObjectOffsetTransform.Entry               ; переход, если максимум не меньше 20, сохранить состояние ожидания

                ; Восстановление сохранённого состояния и сброс фазового счётчика записи.
ResumeState:    LD A, (IX + @FActionRecord.SavedStateCode)
                LD (IX + @FActionRecord.StateCode), A
                LD (IX + @FActionRecord.OffsetScaleHigh), #00
                JP @Action.PrepareObjectOffsetTransform.Entry

                endmodule
                endmodule
