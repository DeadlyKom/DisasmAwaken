                module Action
                module StepNearZeroWord
                ; Документация [алгоритм и проверка](../../Docs/ActionNearZeroWord.md)
                ; -----------------------------------------
                ; Изменение слова около нуля, запрос шестой шкалы и выключение обработки при модуле от двух
                ; исходная запись 17, банк 5, перенесённое ядро ACTION #6000..#7F8E, смещения #10E9..#111A
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают
                ;   входной A' возвращается как основной A только на активном пути записи слова, входной F' числового смысла не имеет
                ;   EnabledCode содержит код допуска, ActionPanelGaugesState.SignedWord задаёт исходное знаковое слово
                ;   запрос ActionPanelGaugesState.SixthRequest доступен для записи в существующий операнд кода
                ;   код ACTION доступен для самомодификации, на CPU-стеке внешний адрес возврата, IRQ не вмешиваются
                ; Out:
                ;   при EnabledCode=00 HL, DE, BC и альтернативный AF сохраняются, AF=0054, RAM не меняется
                ;   при ненулевом EnabledCode HL содержит abs(слово)-2 с восстановлением исходного знака по модулю 65536, DE сохраняется, BC=0002
                ;   при исходном модуле от двух AF=0044, EnabledCode обнуляется, исходное слово в RAM не меняется
                ;   при исходном модуле меньше двух HL записывается в SignedWord, A равен входному A', F соответствует SBC HL,0002 без входного займа, EnabledCode сохраняется
                ;   при ненулевом EnabledCode SixthRequest получает его исходное значение независимо от ветви записи слова
                ;   на активном неотрицательном пути A'=EnabledCode, F'=54 OR разряды 5 и 3 исходного старшего байта слова
                ;   на активном отрицательном пути A'=NOT HIGH(abs(слово)-2), F'=92 OR разряды 5 и 3 этого A'
                ;   HL', DE', BC', IX, IY, I, IM и IFF сохраняются, SP=входной SP+2
                ;   R увеличивается на 3 M1 при входном EnabledCode=00, 19 или 20 M1 при активном неотрицательном слове, 33 или 34 M1 при активном отрицательном, меньшее число относится к записи слова
                ; Corrupt:
                ;   HL, BC, AF, AF', R, SixthRequest, EnabledCode либо два байта SignedWord, только на соответствующих активных путях
                ; Note:
                ;   RAM слова изменяется только для исходных 0000, 0001 и FFFF, результаты соответственно FFFE, FFFF и 0001
                ;   исходный JR NC выключает обработку при отсутствии займа, вычисленный HL на этом пути не записывается в слово
                ;   CPU-стек не записывается, игровой смысл слова и причина такого условия пока не установлены
                ;   проверены все знаковые слова, все коды допуска и все альтернативные AF в отдельных профилях, не весь совместный набор входов
                ; -----------------------------------------
                ; -----------------------------------------
                ; Проверка кода допуска обработки
Entry:          LD A, #00
                AND A
                RET Z                                                           ; выход, если EnabledCode равен нулю, состояние не изменяется

                ; Обновление запроса шестой шкалы исходным ненулевым кодом допуска.
                LD (@ActionPanelGaugesState.SixthRequest), A
                ; -----------------------------------------
                ; Расчёт модуля исходного знакового слова
                LD HL, (@ActionPanelGaugesState.SignedWord)
                ; Проверка исходного знака, Z этой проверки определяет последующее восстановление знака.
                BIT 7, H
                JR Z, @Action.StepNearZeroWord.SubtractStep                     ; переход, если исходное слово неотрицательно, модуль уже находится в HL

                ; Расчёт модуля по модулю 65536, исходное 8000 сохраняет беззнаковую величину 32768.
                LD A, L
                CPL
                LD L, A
                LD A, H
                CPL
                LD H, A
                INC HL
                ; -----------------------------------------
                ; Вычитание шага из модуля и восстановление знака
SubtractStep:   EX AF, AF'
                LD BC, @ActionNearZeroWordConst.Step
                ; Сброс входного Carry перед вычитанием, альтернативный A сохраняет своё числовое значение.
                OR A
                SBC HL, BC
                ; Восстановление Z исходного знака из сохранённого AF, флаги вычитания пока находятся в альтернативном F.
                EX AF, AF'
                JR Z, @Action.StepNearZeroWord.CheckBorrow                      ; переход, если исходное слово неотрицательно, знак результата не меняется

                ; Восстановление отрицательного знака вычисленного слова по модулю 65536.
                LD A, L
                CPL
                LD L, A
                LD A, H
                CPL
                LD H, A
                INC HL
                ; -----------------------------------------
                ; Выбор записи по займу исходного вычитания
CheckBorrow:    EX AF, AF'
                JR NC, @Action.StepNearZeroWord.Disable                         ; переход, если исходный модуль не меньше двух, слово не записывается и обработка выключается

                ; Обновление слова только при исходном модуле меньше двух, вычисленный HL уже имеет нужный знак.
                LD (@ActionPanelGaugesState.SignedWord), HL
                RET

                ; Сброс кода допуска без изменения исходного слова в RAM.
Disable:        XOR A
                LD (@ActionNearZeroWordState.EnabledCode), A
                RET

                ; -----------------------------------------
                endmodule
                endmodule
