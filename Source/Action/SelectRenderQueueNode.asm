                module Action
                module SelectRenderQueueNode
                ; Документация [алгоритм и проверка](../../Docs/ActionRenderQueueControl.md)
                ; -----------------------------------------
                ; Проверка конца очереди либо переход к загрузке выбранного узла
                ; исходная запись 17, код ACTION банка 0, адреса E4FF..E505, смещения #84FF..#8505
                ; In:
                ;   H задаёт страницу узлов, в текущем обходе H=8F, L сохраняется до проверки конца
                ;   DE и BC числовых аргументов не задают, A содержит полный байт Head либо Next, входной F не влияет на выбор
                ;   при A=01 на CPU-стеке должен находиться внешний возврат, при ином A исполнение перейдёт в ReadRenderQueue.LoadNode
                ; Out:
                ;   HL при A=#01 сохраняется, иначе сохраняет H и получает L=входной A
                ;   DE и BC сохраняются
                ;   AF сохраняет A и получает F от CP A,#01, Z установлен только при A=#01, Carry только при A=#00, N=1
                ;   HL', DE', BC', AF' сохраняются
                ;   IX и IY сохраняются, I, IM, IFF и paging сохраняются, RAM и порты не изменяются
                ;   при A=#01 выполнен внешний RET, SP=входной SP+2, R увеличен на 2 M1
                ;   при A<>#01 SP сохраняется, R увеличен на 4 M1, управление передано ReadRenderQueue.LoadNode по E4B1 до его исполнения
                ;   бит 7 R сохраняется, остальные семь изменяются по полной стоимости соответствующей ветви
                ; Corrupt:
                ;   L при выборе узла, F, SP при возврате и R
                ; Note:
                ;   селектор не проверяет допустимость смещения или страницы, числовой маркер конца равен ровно 01
                ;   модель проверяет все сочетания A и F, но не исполняет последующую загрузку узла в этом же испытании
                ;   A=00 является допустимым первым смещением узла, Carry сравнения не означает ошибку и не проверяется селектором
                ;   PV сравнения устанавливается при A=80, биты 5/3 F равны нулю из-за второго операнда 01, ветвление использует только Z
                ; -----------------------------------------
                ; -----------------------------------------
                ; Проверка конца цепочки
                ; Сравнение полного Head либо Next с числовым маркером 01.
Entry:          CP @ActionRenderQueueConst.EndLink
                RET Z                                                           ; выход, если смещение равно 01, очередь закончилась

                ; Создание полного адреса следующего узла с сохранением страницы в H.
                LD L, A
                JP @Action.ReadRenderQueue.LoadNode

                endmodule
                endmodule
