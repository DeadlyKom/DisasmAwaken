                module Action
                module RenderQueuedObject
                ; Документация [алгоритм и проверка](../../Docs/ActionQueuedObject.md)
                ; -----------------------------------------
                ; Подготовка и вывод текущего объекта очереди с выбором рисователя и чтением следующего узла
                ; исходная запись 17, банковое окно ACTION банка 0, смещения #84DB..#84FE
                ; In:
                ;   HL, DE, BC и AF содержат контекст после ReadRenderQueue.LoadNode, числовые аргументы подготовки находятся в существующих полях
                ;   HL', DE', BC', AF', IX и IY содержат входной контекст дочерних процедур
                ;   HeaderWord0 выбирает режим ориентации и чётный байтовый ModelByteOffset исходной таблицы, Phase0..Phase2 задают фазы
                ;   ActionPatchedVectorCoeffs.C00..C22 задают матрицу сцены, Output2, Output1 и Output0 базы глубины, First и Second
                ;   OBJECT3D загружен в банк 4, таблицы 98/99, CF/D0, маски и шаблоны сохранены, для исходных моделей показатель масштаба 1..6
                ;   действуют договоры BuildRenderCoefficients, ComposeRenderMatrix, TransformObjectVertices и ClassifyProjectedVertices, после преобразования 1..50 точек одной страницы
                ;   для достигнутого рисователя действуют его договоры геометрии, индексированных записей и временных буферов
                ;   на вершине CPU-стека сохранён указатель FActionRenderNode, под ним находится внешний возврат обхода, место рамок всех детей свободно
                ;   ACTION находится в банке 0, paging не заблокирован, IRQ не вмешиваются в временные SP и общие операнды
                ; Out:
                ;   HL равен снятому указателю FActionRenderNode, A содержит фактический байт Next по этому адресу после работы детей
                ;   SP увеличен на два, внешний возврат обхода не потреблён, исполнение последовательно продолжается в SelectRenderQueueNode.Entry по E4FF
                ;   при маркере отказа перспективы 80xx рисование пропущено, F=44, B=5*n и C=0 по договору классификатора
                ;   при общей внешней стороне рисование пропущено, B содержит общий ClipCode, C стороны последней точки, F от AND F0 инверсии общего кода
                ;   при обычном выводе F=54 после нулевого конца потока, DE, BC, альтернативные и индексные регистры равны результату выбранного рисователя
                ;   нулевая младшая тетрада выбирает RenderInsideRecords, ненулевая RenderClippedRecords, проверка общей внешней стороны предшествует этому выбору
                ;   подготовлены девять коэффициентов и их композиция, скопирован исходный поток, построены и классифицированы точки, выведены разрешённые записи
                ;   в порт 7FFD выданы 14 и 10 настоящим копировщиком, окончательная конфигурация 10, прежняя полная конфигурация не восстанавливается
                ;   I, IM и IFF сохраняются, R меняется, пиксели, операнды и остаточные стековые слова соответствуют композиции детей
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, R, paging, коэффициенты, копия потока, рабочие точки, пиксели, операнды и CPU/временные стековые слова
                ; Note:
                ;   подготовительные вызовы исполняются и в композиционном эталоне, новая независимая математика этих четырёх детей здесь не заявляется
                ;   маршрутизация, итоговые флаги, рамки вызовов, чтение Next и оба рисователя проверяются отдельным управляющим и числовым эталоном
                ;   1920 сценариев используют все 128 исходных чётных индексов, два одноосных и один общий набор фаз, пять наборов баз и единичную матрицу сцены
                ;   подтверждены 466 отказов перспективы, 638 общих внешних сторон, 604 внутренних и 212 отсечённых выводов
                ;   сверены регистры кроме R, все физические банки, кратность записей и оба OUT, селектор следующего узла после E4FF не исполнялся
                ;   все матрицы сцены и игровые состояния, R/T, IRQ, сборка и нативный игровой процесс не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Подготовка текущего объекта
                ; Построение ориентации, композиция со сценой, копирование и преобразование групп, затем коды всех точек.
Entry:          CALL @Action.BuildRenderCoefficients.Entry
                CALL @Action.ComposeRenderMatrix.Entry
                CALL @Action.TransformObjectVertices.Entry
                CALL @Action.ClassifyProjectedVertices.Entry
                JR Z, @Action.RenderQueuedObject.ReadNodeNext                   ; переход, если классификатор обнаружил маркер отказа перспективы 80xx, пропустить рисование объекта

                ; Сохранение общего кода и проверка общей внешней стороны по инверсной старшей тетраде.
                LD B, A
                CPL
                AND @ActionVertexCodeConst.InverseMask
                JR NZ, @Action.RenderQueuedObject.ReadNodeNext                  ; переход, если все точки находятся снаружи одной стороны, пропустить рисование объекта

                ; Проверка наличия внешних точек по младшей тетраде общего кода.
                LD A, B
                AND @ActionPolygonConst.OutsideMask
                JR NZ, @Action.RenderQueuedObject.DrawClipped                   ; переход, если хотя бы одна точка снаружи, выбрать RenderClippedRecords

                ; Вывод полностью внутреннего объекта без повторного отсечения его записей.
                CALL @Action.RenderInsideRecords.Entry
                JP @Action.RenderQueuedObject.ReadNodeNext

                ; Вывод объекта с проверками отдельных граней и отсечением открытых сегментов.
DrawClipped:    CALL @Action.RenderClippedRecords.Entry
                ; -----------------------------------------
                ; Восстановление узла и продолжение обхода
                ; Снятие сохранённого указателя FActionRenderNode и чтение его Next перед последовательным E4FF.
ReadNodeNext:   POP HL
                LD A, (HL)
                ; JP @Action.SelectRenderQueueNode.Entry, продолжение в SelectRenderQueueNode.asm

                ; -----------------------------------------
                endmodule
                endmodule
