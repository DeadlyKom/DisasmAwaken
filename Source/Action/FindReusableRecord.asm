                module Action
                module FindReusableRecord
                ; Документация [алгоритм и проверка](../../Docs/ActionRecordSearch.md)
                ; -----------------------------------------
                ; Поиск первой записи с байтом 1 равным 80, обработка маркера конца и однократного пропуска по байту 18
                ; исходная запись 17, код ACTION банка 0, адреса E9A1..E9C1, смещения #89A1..#89C1
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, IY исходного адреса не задаёт
                ;   начиная с A100 доступны записи с шагом 64, до выхода обязательно достижимы подходящая запись либо маркер конца
                ;   байт 1 записи равен 80 для проверки записи, остальные значения заставляют пропустить её без изменения
                ;   у проверяемой записи байт 0 равен 80 для маркера конца, иначе проверяется и очищается байт 18
                ;   исходный код исполняется в банке 0, записи не пересекают исполняемый код и стек, CPU-стек содержит внешний возврат, IRQ не вмешиваются
                ; Out:
                ;   HL и BC сохраняются, DE=0040, IY адрес принятой записи либо маркера конца
                ;   при маркере A=80, F=42, Z установлен, байт 18 маркера не изменяется
                ;   при найденной записи A равен прежнему байту 18 плюс один, Z сброшен, байт 18 этой записи обнулён
                ;   F найденной записи соответствует INC прежнего байта 18, Carry равен результату сравнения байта 0 с 80
                ;   каждая проверенная запись с прежним байтом 18 равным FF обнуляет этот байт и пропускается
                ;   HL', DE', BC', AF', IX, I, IM и IFF сохраняются, SP=входной SP+2
                ;   R получает 3 M1 подготовки, по 6 M1 на занятую запись, по 16 M1 на запись пропуска FF, 10 M1 на маркер либо 17 M1 на принятую запись
                ; Corrupt:
                ;   DE, AF, IY, R, байты 18 пропущенных по FF и принятой записей
                ; Note:
                ;   ограничителя числа записей нет, 256 записей в модели не являются доказанным пределом массива игры
                ;   процедура не помечает принятую запись занятой и не создаёт объект, последующая инициализация выполняется вызывающим кодом
                ;   80 и FF проверяются как целые байтовые коды, значения отдельных битов им не приписываются
                ;   остальные поля и игровой смысл байта 18 пока неизвестны, стек и порты не записываются
                ; -----------------------------------------
                ; Подготовка поиска с первой записи A100, исходный IY выбран на один шаг раньше.
Entry:          LD IY, #A0C0
                LD DE, #0040
                ; -----------------------------------------
                ; Поиск следующей записи с исходным кодом 80 по смещению 1
                ; Ограничителя массива здесь нет, завершение требует достижимой записи либо маркера.
ScanNext:       ADD IY, DE
                ; Проверка полного байтового кода по смещению 1, отдельные флаговые биты не выделяются.
                LD A, (IY+#01)
                CP #80
                JR NZ, @Action.FindReusableRecord.ScanNext                      ; переход, если байт 1 не равен 80, пропустить запись без изменения

                ; Проверка маркера конца по байту 0 только у записи с байтом 1 равным 80.
                LD A, (IY+#00)
                CP #80
                RET Z                                                           ; выход, если байт 0 равен 80, достигнут маркер конца, Z установлен

                ; -----------------------------------------
                ; Проверка однократного пропуска по байту 18
                ; Чтение прежнего значения и очистка выполняются до принятия решения о пропуске.
                LD A, (IY+#18)
                LD (IY+#18), #00
                ; Расчёт результата и распознавание исходного FF по переполнению в ноль, Carry сохраняется от CP байта 0.
                INC A
                JR Z, @Action.FindReusableRecord.ScanNext                       ; переход, если прежний байт 18 равен FF, пропустить запись с уже очищенным байтом 18

                ; Возврат найденного IY, исходный байт 18 плюс один ненулевой, признак занятой записи не устанавливается.
                RET

                ; -----------------------------------------
                endmodule
                endmodule
