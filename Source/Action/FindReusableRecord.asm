                module Action
                module FindReusableRecord
                ; Документация [алгоритм и проверка](../../Docs/ActionRecordSearch.md)
                ; -----------------------------------------
                ; Поиск первой записи с Component0.High=80, проверка маркера и однократного пропуска ReuseByte=FF
                ; исходная запись 17, код ACTION банка 0, адреса E9A1..E9C1, смещения #89A1..#89C1
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, IY исходного адреса не задаёт
                ;   начиная с Record00 доступны записи с шагом FActionRecord, до выхода обязательно достижимы подходящая запись либо маркер конца
                ;   полный Components.Component0.High=80 разрешает проверку записи, другие значения пропускаются без изменения
                ;   при таком High полный Components.Component0.Low=80 обозначает маркер, иначе ReuseByte доступен для чтения и записи
                ;   исходный код исполняется в банке 0, записи не пересекают исполняемый код и стек, CPU-стек содержит внешний возврат, IRQ не вмешиваются
                ; Out:
                ;   HL сохраняется
                ;   DE=FActionRecord
                ;   BC сохраняется
                ;   AF при маркере содержит A=80/F=42, Z установлен, при принятии A=прежний ReuseByte+1, Z сброшен
                ;   F принятой записи соответствует INC прежнего ReuseByte, Carry равен условию Components.Component0.Low<80
                ;   HL', DE', BC', AF', IX сохраняются, IY указывает принятую запись либо маркер
                ;   I, IM, IFF и paging сохраняются, SP после внешнего RET равен входному SP+2, CPU-стек не записывается
                ;   ReuseByte принятой записи обнулён, каждая проверенная запись с прежним ReuseByte=FF обнуляет его и пропускается, ReuseByte маркера не меняется
                ;   R получает 3 M1 подготовки, по 6 M1 на занятую запись, по 16 M1 на запись пропуска FF, 10 M1 на маркер либо 17 M1 на принятую запись, бит 7 R сохраняется
                ; Corrupt:
                ;   DE, AF, IY, R, байты 18 пропущенных по FF и принятой записей
                ; Note:
                ;   A=80 возможен и при принятии ReuseByte=7F, маркер отличается от этого результата по Z
                ;   в 132096 сценариях сверены полные M1 и 510 найденных записей с A=80/Z=0, не только итоговый R modulo 128
                ;   ограничителя числа записей нет, 256 записей в модели не являются доказанным пределом массива игры
                ;   процедура не помечает принятую запись занятой и не создаёт объект, последующая инициализация выполняется вызывающим кодом
                ;   80 и FF проверяются как целые байтовые коды, значения отдельных битов им не приписываются
                ;   этот вход сравнивает полный код ReuseByte=FF, известные контекстные биты других потребителей в его условии не участвуют, порты не записываются
                ; -----------------------------------------
                ; Подготовка поиска с первой записи A100, исходный IY выбран на один шаг раньше.
Entry:          LD IY, @ActionObjectRecords.Record00 - @FActionRecord
                LD DE, @FActionRecord
                ; -----------------------------------------
                ; Поиск следующей записи с исходным кодом 80 по смещению 1
                ; Ограничителя массива здесь нет, завершение требует достижимой записи либо маркера.
ScanNext:       ADD IY, DE
                ; Проверка полного байтового кода по смещению 1, отдельные флаговые биты не выделяются.
                LD A, (IY + FActionRecord.Components.Component0.High)
                CP #80
                JR NZ, @Action.FindReusableRecord.ScanNext                      ; переход, если байт 1 не равен 80, пропустить запись без изменения

                ; Проверка маркера конца по байту 0 только у записи с байтом 1 равным 80.
                LD A, (IY + FActionRecord.Components.Component0.Low)
                CP #80
                RET Z                                                           ; выход, если байт 0 равен 80, достигнут маркер конца, Z установлен

                ; -----------------------------------------
                ; Проверка однократного пропуска по байту 18
                ; Чтение прежнего значения и очистка выполняются до принятия решения о пропуске.
                LD A, (IY + FActionRecord.ReuseByte)
                LD (IY + FActionRecord.ReuseByte), #00
                ; Расчёт результата и распознавание исходного FF по переполнению в ноль, Carry сохраняется от CP байта 0.
                INC A
                JR Z, @Action.FindReusableRecord.ScanNext                       ; переход, если прежний байт 18 равен FF, пропустить запись с уже очищенным байтом 18

                ; Возврат найденного IY, исходный байт 18 плюс один ненулевой, признак занятой записи не устанавливается.
                RET

                ; -----------------------------------------
                endmodule
                endmodule
