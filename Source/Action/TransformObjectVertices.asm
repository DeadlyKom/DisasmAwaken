                module Action
                module TransformObjectVertices
                ; Документация [алгоритм и проверка](../../Docs/ActionObjectVertices.md)
                ; -----------------------------------------
                ; Копирование потока объекта и преобразование всех его фиксированных групп вершин
                ; исходная запись 17, адреса D5C9..D5F8
                ; In:
                ;   ModelByteOffset содержит байтовое смещение указателя OBJECT3D, штатные указатели чётные, BC допускает любое слово счётчика копировщика
                ;   девять коэффициентов ComposeRenderMatrix и три базы ProjectRenderVertex уже подготовлены
                ;   по указателю банка 4 находится конечный поток CopyObjectData, второй байт заголовка задаёт exponent от 1 до 6
                ;   каждая фиксированная запись содержит ненулевой код группы и три локальных компонента, нуль завершает эту часть
                ;   исходные буфер 9F1C и рабочие записи страницы 8E не должны разрушать код, операнды и CPU-стек
                ;   ACTION доступен в банке 0, paging не заблокирован, IRQ не вмешиваются, на CPU-стеке внешний возврат и шесть дополнительных свободных байтов
                ; Out:
                ;   HL указывает сразу после нулевого маркера фиксированной части в Buffer, то есть 9F1F+4*число групп
                ;   при непустой фиксированной части DE, BC, альтернативные регистры, IX и IY равны выходу последней ProjectRenderVertexGroup
                ;   при пустой фиксированной части DE указывает за всей копией потока, BC равен выходу CopyObjectData, альтернативные регистры, IX и IY сохранены
                ;   A=0 и F=54 от AND нулевого маркера, SP после RET равен входному SP+2
                ;   весь поток скопирован в Buffer, фиксированные группы преобразованы, переменная часть только скопирована и здесь не интерпретируется
                ;   три смещения масштаба перспективы получают 6-exponent, NextOffset начинается с 4 и после каждой группы обновляется её конечным младшим байтом
                ;   для исходных 128 чётных указателей максимум 40 выходных точек, последний NextOffset не превосходит CC
                ;   I, IM и IFF сохраняются, OUT 7FFD получает 14 затем 10, прежняя полная конфигурация не восстанавливается, R меняется
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, R, Buffer по длине потока, рабочие точки, операнды дочерних процедур и шесть байтов CPU-стека
                ; Note:
                ;   первый байт заголовка копируется, но этой процедурой не читается, показатель масштаба берётся только из второго
                ;   ограничитель числа групп и ёмкости выходного буфера отсутствует, перенос через страницу у NextOffset не сохраняется
                ;   нулевой код является маркером здесь и не передаётся генератору, коды 01 и 81 сохраняют особый смысл генератора
                ;   после CALL PrepareRenderVertexProducts исполнение проходит в ProjectRenderVertexGroup, его RET возвращается на D5F5
                ;   2560 композиционных сценариев выполняют настоящий копировщик, банковый селектор, произведения, генератор и перспективу без подмены
                ;   проверены точные регистры и флаги кроме R, вся физическая RAM, кратность записей и последовательность OUT
                ;   границы 40 точек и CC относятся к исходным потокам, произвольные модифицированные потоки этим ограничением не защищены
                ;   все совместные входы, IRQ, точное время, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Копирование потока объекта
                ; Чтение байтового смещения указателя и копирование обеих частей OBJECT3D через настоящий банк 4.
Entry:          LD A, (@ActionObjectVerticesState.ModelByteOffset)
                LD L, A
                CALL @Action.CopyObjectData.Entry
                ; -----------------------------------------
                ; Подготовка масштаба и рабочего стека
                ; Выбор второго байта заголовка, NextOffset=4 означает первую запись с начала страницы 8E.
                LD HL, @ActionObjectCopyState.Buffer+1
                LD A, @ActionObjectVerticesConst.InitialOffset
                LD (@ActionVertexGroupState.NextOffset), A
                ; Расчёт общего смещения трёх JR как 6-exponent, исходный алгоритм диапазон не проверяет.
                LD A, @ActionObjectVerticesConst.ScaleLimit
                SUB (HL)
                ; Обновление одинакового масштаба глубины и двух локальных осей перспективы.
                LD (@ActionPerspectiveState.DepthShiftSkip), A
                LD (@ActionPerspectiveState.FirstShiftSkip), A
                LD (@ActionPerspectiveState.SecondShiftSkip), A
                INC HL
                ; -----------------------------------------
                ; Обход фиксированных групп
                ; Проверка полного первого байта записи, нуль завершает фиксированную часть до вызова генератора.
NextGroup:      LD A, (HL)
                INC HL
                AND A
                RET Z                                                           ; выход, если код группы равен нулю, HL уже указывает за маркером

                ; Чтение кода группы в IXL и трёх локальных компонентов в B, C и D.
                LD IXL, A
                LD B, (HL)
                INC HL
                LD C, (HL)
                INC HL
                LD D, (HL)
                INC HL
                ; Сохранение указателя следующей записи на CPU-стеке, генератор временно переключает SP на рабочую страницу.
                PUSH HL
                ; Преобразование группы, подготовитель последовательно продолжает исполнение в ProjectRenderVertexGroup.
                CALL @Action.PrepareRenderVertexProducts.Entry
                ; Восстановление указателя следующей фиксированной записи после общего RET дочерней цепочки.
                POP HL
                JP @Action.TransformObjectVertices.NextGroup

                ; -----------------------------------------
                endmodule
                endmodule
