                module Action
                module QueueNumberBank1
                ; Документация [межбанковые вызовы очереди](../../Docs/ActionTextQueueCalls.md)
                ; -----------------------------------------
                ; Передача байтового числа A в очередь Controls банка 1 с фиксированным возвратом страницы 10
                ; исходная запись 17, файловые смещения #023D..#024C
                ; In:
                ;   HL сохраняется, DE аргументов не задаёт, BC сохраняется, AF задаёт число A и сохраняемые флаги F
                ;   AF' задаёт сохраняемые F', входной A' не сохраняется
                ;   paging не заблокирован, банк 1 содержит Controls, его очередь и курсор удовлетворяют договору QueueNumber
                ;   код обёртки и SelectMemoryPage находятся ниже C000 и доступны при обоих значениях страницы
                ;   на стеке внешний возврат, доступны восемь дополнительных байтов ниже входного SP, вмешательство ISR не входит в договор
                ; Out:
                ;   HL сохранён, DE=0200 OR входной A, BC сохранён, A=10, F сохранены
                ;   HL', DE', BC' сохраняются, A'=11, F' сохранены, IX, IY, I, IM и IFF сохраняются
                ;   OUT 7FFD получает 11, реальный Controls.QueueNumber исполняется в банке 1, затем OUT 7FFD получает 10
                ;   на выходе выбрана полная страница 10, прежнее значение paging не восстанавливается
                ;   очередь обновлена либо молча отклонила запись по договору производителя, результат не возвращается флагами
                ;   SP после внешнего RET равен входному SP+2, следы CALL и сохранений остаются в RAM стека
                ; Corrupt:
                ;   DE, AF только по A, AF' только по A'
                ;   paging, очередь и курсор банка 1 при успехе, восемь байтов временного стека, R
                ; Note:
                ;   первый EX AF сохраняет число на время выбора банка, второй оставляет значение страницы 11 в альтернативном A
                ;   SelectMemoryPage сохраняет BC и не пишет теневую переменную страницы
                ;   локальная модель использует настоящие восемь банков и реальные вызовы, нативный запуск и IRQ не доказаны
                ; -----------------------------------------
                ; сохранение числа A в альтернативном AF перед загрузкой управляющего байта страницы
Entry:          EX AF, AF'
                ; выбор управляющего байта 11, Controls находится в банке 1
                LD A, @ActionBankPage.Controls
                CALL @Action.SelectMemoryPage.Entry
                ; восстановление числа A, в A′ остаётся 11, F′ сохраняется
                EX AF, AF'
                ; передача числа в настоящий QueueNumber выбранного банка 1
                CALL @Controls.QueueNumber.Entry
                ; фиксированный возврат полной страницы 10, прежний paging не восстанавливается
                LD A, @ActionBankPage.Runtime
                CALL @Action.SelectMemoryPage.Entry
                RET

                endmodule
                endmodule
