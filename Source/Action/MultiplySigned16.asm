                module Action
                module MultiplySigned16
                ; Документация [алгоритм и проверка](../../Docs/ActionSignedMultiply.md)
                ; -----------------------------------------
                ; Знаковое произведение двух слов с тремя ядрами и исходным исключением второго операнда 8000
                ; исходная запись 17, банковое окно ACTION банка 0, адреса C6F4..C88B, смещения #66F4..#688B
                ; In:
                ;   HL и DE задают два signed16 операнда дополнительного кода, BC и AF аргументов не задают
                ;   ACTION находится в банке 0, CPU-стек содержит внешний возврат и допускает два дополнительных байта AF, IRQ не вмешиваются
                ; Out:
                ;   HL содержит старшее слово результата, DE младшее, для второго операнда 8000 действует описанное исходное исключение
                ;   при обычном пути результат равен signed16(HL_вход)*signed16(DE_вход) в 32-разрядном дополнительном коде
                ;   если оба модуля не меньше 256 и DE_вход=8000, модуль результата равен abs(HL_вход)*256, а не abs(HL_вход)*32768
                ;   A равен XOR исходных старших байтов, при одинаковых знаках F равен флагам этого XOR независимо от нулевого результата
                ;   при разных знаках F равен последнему SBC при отрицании старшего слова, BC равно старшему слову модуля до отрицания
                ;   при одинаковых знаках BC сохранён в ядре 8x8, B сохранён и C=0 в ядре 8x16, BC=0 в полном ядре
                ;   HL', DE', BC', AF' сохраняются, IY сохраняется, IX в полном ядре равен младшему слову модуля до отрицания, иначе IX сохранён
                ;   SP после RET равен входному SP+2, I, IM, IFF и paging сохраняются, R меняется, портов нет
                ; Corrupt:
                ;   HL, DE, BC по ядру и знаку, AF, IX только в полном ядре, R и два байта CPU-стека
                ; Note:
                ;   код сначала берёт модули и выбирает ядро 8x8, 8x16 либо 16x16, затем применяет исходный знак ко всем 32 битам
                ;   исключение 8000 асимметрично, при нём первый модуль также должен быть не меньше 256, исправление алгоритма не вносится
                ;   917504 сценария исполняют оригинал ACTION для всех слов против семи граничных значений в обоих порядках
                ;   каждая из 245 инструкций отдельно сверяется с вариантом карты с точной релокацией внутренних целей, общего имени для доказательства недостаточно
                ;   проверены регистры, флаги, вся RAM и кратность стековых записей, R и время отдельно не доказаны
                ;   полная область двух слов, IRQ, сборка и нативный запуск не проверены
                ; -----------------------------------------
                ; -----------------------------------------
                ; Знак и модули входных слов
                ; Расчёт XOR исходных старших байтов, сохранение знака и флагов в AF на CPU-стеке.
Entry:          LD A, H
                XOR D
                ; сохранение знака вместе с точными флагами XOR до выбора числового ядра
                PUSH AF
                ; проверка знака правого операнда перед взятием модуля
                BIT 7, D
                JR Z, @Action.MultiplySigned16.CheckLeftSign                    ; переход, если DE неотрицателен, оставить его модуль без изменений

                ; расчёт модуля отрицательного DE дополнительным кодом, 8000 остаётся 8000
                LD A, E
                CPL
                LD E, A
                LD A, D
                CPL
                LD D, A
                INC DE
                ; проверка знака левого операнда перед взятием модуля
CheckLeftSign:  BIT 7, H
                JR Z, @Action.MultiplySigned16.SelectKernel                     ; переход, если HL неотрицателен, оставить его модуль без изменений

                ; расчёт модуля отрицательного HL дополнительным кодом
                LD A, L
                CPL
                LD L, A
                LD A, H
                CPL
                LD H, A
                INC HL
                ; -----------------------------------------
                ; Выбор разрядности модулей
                ; размещение модуля первого операнда в DE и второго в HL для выбора разрядности ядра
SelectKernel:   EX DE, HL
                ; проверка, помещается ли модуль первого операнда в один байт
                LD A, D
                AND A
                JP Z, @Action.MultiplySigned16.CheckOtherByte                   ; переход, если первый модуль меньше 256, проверить разрядность второго

                ; проверка, помещается ли модуль второго операнда в один байт
                LD A, H
                AND A
                JP Z, @Action.MultiplySigned16.MulByteWord                      ; переход, если второй модуль меньше 256, использовать байтовый множитель

                ; -----------------------------------------
                ; Полное ядро 16x16
                ; обнуление старшей добавки BC и младшего накопителя IX полного произведения
                LD BC, #0000
                LD IX, #0000
                ; пропуск исходного знакового разряда модуля второго операнда, крайний модуль 8000 теряет этот бит
                ADD HL, HL
                ; расчёт первого проверяемого разряда полного ядра, бит 14 выходит в Carry
                ADD HL, HL
                JP C, @Action.MultiplySigned16.AddWide14                        ; переход, если бит 14 второго модуля единичный, начать накопление с него

                ; поиск первого единичного старшего разряда второго модуля с пропуском нулевых слагаемых
                ADD HL, HL
                JP C, @Action.MultiplySigned16.AddWide13                        ; переход, если бит 13 второго модуля единичный, начать накопление с него

                ; поиск первого единичного старшего разряда второго модуля с пропуском нулевых слагаемых
                ADD HL, HL
                JP C, @Action.MultiplySigned16.AddWide12                        ; переход, если бит 12 второго модуля единичный, начать накопление с него

                ; поиск первого единичного старшего разряда второго модуля с пропуском нулевых слагаемых
                ADD HL, HL
                JP C, @Action.MultiplySigned16.AddWide11                        ; переход, если бит 11 второго модуля единичный, начать накопление с него

                ; поиск первого единичного старшего разряда второго модуля с пропуском нулевых слагаемых
                ADD HL, HL
                JP C, @Action.MultiplySigned16.AddWide10                        ; переход, если бит 10 второго модуля единичный, начать накопление с него

                ; поиск первого единичного старшего разряда второго модуля с пропуском нулевых слагаемых
                ADD HL, HL
                JP C, @Action.MultiplySigned16.AddWide09                        ; переход, если бит 9 второго модуля единичный, начать накопление с него

                ADD HL, HL
                ; принудительное начало с бита 8 при отсутствии старших единичных разрядов, источник исключения 8000
                JP @Action.MultiplySigned16.AddWide08

                ; добавление модуля первого операнда для единичного бита 14 второго модуля
AddWide14:      ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 14 в паре HL и IX
                ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Action.MultiplySigned16.ShiftWide13                     ; переход, если бит 13 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 13 второго модуля
AddWide13:      ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 13 в паре HL и IX
ShiftWide13:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Action.MultiplySigned16.ShiftWide12                     ; переход, если бит 12 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 12 второго модуля
AddWide12:      ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 12 в паре HL и IX
ShiftWide12:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Action.MultiplySigned16.ShiftWide11                     ; переход, если бит 11 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 11 второго модуля
AddWide11:      ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 11 в паре HL и IX
ShiftWide11:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Action.MultiplySigned16.ShiftWide10                     ; переход, если бит 10 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 10 второго модуля
AddWide10:      ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 10 в паре HL и IX
ShiftWide10:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Action.MultiplySigned16.ShiftWide09                     ; переход, если бит 9 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 9 второго модуля
AddWide09:      ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 9 в паре HL и IX
ShiftWide09:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Action.MultiplySigned16.ShiftWide08                     ; переход, если бит 8 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 8 второго модуля
AddWide08:      ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 8 в паре HL и IX
ShiftWide08:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Action.MultiplySigned16.ShiftWide07                     ; переход, если бит 7 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 7 второго модуля
                ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 7 в паре HL и IX
ShiftWide07:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Action.MultiplySigned16.ShiftWide06                     ; переход, если бит 6 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 6 второго модуля
                ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 6 в паре HL и IX
ShiftWide06:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Action.MultiplySigned16.ShiftWide05                     ; переход, если бит 5 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 5 второго модуля
                ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 5 в паре HL и IX
ShiftWide05:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Action.MultiplySigned16.ShiftWide04                     ; переход, если бит 4 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 4 второго модуля
                ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 4 в паре HL и IX
ShiftWide04:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Action.MultiplySigned16.ShiftWide03                     ; переход, если бит 3 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 3 второго модуля
                ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 3 в паре HL и IX
ShiftWide03:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Action.MultiplySigned16.ShiftWide02                     ; переход, если бит 2 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 2 второго модуля
                ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 2 в паре HL и IX
ShiftWide02:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Action.MultiplySigned16.ShiftWide01                     ; переход, если бит 1 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 1 второго модуля
                ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 1 в паре HL и IX
ShiftWide01:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Action.MultiplySigned16.TakeWideLow                     ; переход, если бит 0 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 0 второго модуля
                ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; перенос младшего слова модуля произведения из IX в выходной DE
TakeWideLow:    LD D, IXH
                LD E, IXL
                ; -----------------------------------------
                ; Применение знака результата
                ; восстановление исходного знака и флагов XOR после всех арифметических ядер
ApplySign:      POP AF
                RET P                                                           ; выход, если исходные знаки одинаковы, 32-битный модуль уже является результатом

                ; сохранение старшего слова модуля в BC перед отрицанием 32-битного значения
                LD B, H
                LD C, L
                ; расчёт отрицательного младшего слова, Carry от сохранённого XOR равен нулю
                LD HL, #0000
                SBC HL, DE
                EX DE, HL
                ; расчёт отрицательного старшего слова с заёмом от отрицания младшего
                LD HL, #0000
                SBC HL, BC
                RET

                ; проверка второго старшего байта при уже установленном байтовом первом модуле
CheckOtherByte: LD A, H
                AND A
                JR Z, @Action.MultiplySigned16.MulBytes                         ; переход, если оба модуля меньше 256, использовать ядро 8x8

                ; перестановка для размещения байтового множителя в L перед ядром 8x16
                EX DE, HL
                ; -----------------------------------------
                ; Ядро 8x16
                ; создание 24-битного накопителя A и HL из байтового множителя и нулевого младшего слова
MulByteWord:    LD A, L
                LD L, H
                LD C, H
                ; поиск первого единичного разряда байтового множителя сдвигом A
                ADD A, A
                JR C, @Action.MultiplySigned16.AddByteWord7                     ; переход, если бит 7 байтового множителя единичный, начать с его слагаемого

                ; поиск первого единичного разряда байтового множителя сдвигом A
                ADD A, A
                JR C, @Action.MultiplySigned16.AddByteWord6                     ; переход, если бит 6 байтового множителя единичный, начать с его слагаемого

                ; поиск первого единичного разряда байтового множителя сдвигом A
                ADD A, A
                JR C, @Action.MultiplySigned16.AddByteWord5                     ; переход, если бит 5 байтового множителя единичный, начать с его слагаемого

                ; поиск первого единичного разряда байтового множителя сдвигом A
                ADD A, A
                JR C, @Action.MultiplySigned16.AddByteWord4                     ; переход, если бит 4 байтового множителя единичный, начать с его слагаемого

                ; поиск первого единичного разряда байтового множителя сдвигом A
                ADD A, A
                JR C, @Action.MultiplySigned16.AddByteWord3                     ; переход, если бит 3 байтового множителя единичный, начать с его слагаемого

                ; поиск первого единичного разряда байтового множителя сдвигом A
                ADD A, A
                JR C, @Action.MultiplySigned16.AddByteWord2                     ; переход, если бит 2 байтового множителя единичный, начать с его слагаемого

                ; поиск первого единичного разряда байтового множителя сдвигом A
                ADD A, A
                JR C, @Action.MultiplySigned16.AddByteWord1                     ; переход, если бит 1 байтового множителя единичный, начать с его слагаемого

                ; поиск первого единичного разряда байтового множителя сдвигом A
                ADD A, A
                JR C, @Action.MultiplySigned16.AddByteWord0                     ; переход, если бит 0 байтового множителя единичный, начать с его слагаемого

                JP @Action.MultiplySigned16.StoreByteWord

                ; добавление 16-битного модуля для единичного разряда 7 байтового множителя
AddByteWord7:   ADD HL, DE
                ; включение переноса суммы HL в старший байт A с нулевой добавкой C
                ADC A, C
                ; расчёт удвоенного частичного произведения в старшем A и младшем HL для следующего разряда
                ADD HL, HL
                ; сдвиг старшего байта и выдвижение следующего бита множителя в Carry
                ADC A, A
                JR NC, @Action.MultiplySigned16.ShiftByteWord6                  ; переход, если бит 6 байтового множителя нулевой, пропустить его слагаемое

                ; добавление 16-битного модуля для единичного разряда 6 байтового множителя
AddByteWord6:   ADD HL, DE
                ; включение переноса суммы HL в старший байт A с нулевой добавкой C
                ADC A, C
                ; расчёт удвоенного частичного произведения в старшем A и младшем HL для следующего разряда
ShiftByteWord6: ADD HL, HL
                ; сдвиг старшего байта и выдвижение следующего бита множителя в Carry
                ADC A, A
                JR NC, @Action.MultiplySigned16.ShiftByteWord5                  ; переход, если бит 5 байтового множителя нулевой, пропустить его слагаемое

                ; добавление 16-битного модуля для единичного разряда 5 байтового множителя
