                module Action
                module ApplyIndexedDelta
                ; Физические поля [локальный контекст](../../Docs/ActionLocalContextPhysicalData.md)
                ; (1) Жёсткий порядок, общий хвост после ApplyPendingRecordLink.asm
                ; Документация [табличная поправка](../../Docs/ActionTypeDelta.md)
                ; -----------------------------------------
                ; Применение знаковой табличной поправки к байту 9BCD с ограничением и установкой бита 5 по прежнему значению
                ; исходная запись 17, перенесённый код банка 5, адреса 6380..63B5
                ; In:
                ;   HL и DE числовых аргументов не задают, B индекс поправки, C и AF числового смысла не имеют
                ;   ActionFlightStatus.Value.Code содержит исходный байт состояния, Control.TemplateMode задаёт добавку
                ;   доступна исходная таблица ActionTypeDeltas банка 5, на CPU-стеке внешний возврат, IRQ не вмешиваются
                ; Out:
                ;   при B не меньше 16 HL, DE и BC сохраняются, A=входной B, F соответствует CP 16, записей RAM нет
                ;   при B меньше 16 HL адрес записи поправки, DE сохраняется, B старый байт 9BCD, C и A новый байт
                ;   для допустимого индекса F соответствует CP старого байта с 32, флаги не описывают новый результат
                ;   HL', DE', BC', AF', IX, IY, I, IM и IFF сохраняются, SP=входной SP+2
                ;   при допустимом индексе 9BCD получает clamp(signed8(старый байт)+поправка, 0, 127) OR 32 при старом беззнаковом байте меньше 32
                ;   поправка увеличивается на 10 только при ненулевом TemplateMode и неотрицательной исходной поправке
                ;   R получает 3 M1 при недопустимом индексе, точная стоимость остальных путей приведена в документации
                ; Corrupt:
                ;   HL, BC и AF при допустимом индексе, AF при недопустимом, R, байт 9BCD при допустимом индексе
                ; Note:
                ;   байт 9BCD используется и как signed8 при сложении, и как unsigned8 при проверке порога 32
                ;   переполнение исходного ADD обрабатывается SUB и LD 7F, флаг знака остаётся от SUB, исходный алгоритм сохранён
                ;   бит 5 принудительно установлен только при старом значении меньше 32, это не доказательство игрового назначения разряда
                ;   AdjustMode принимает C непосредственно, его отдельный договор и переполнение добавки приведены перед внутренним входом
                ;   ApplyPendingRecordLink может продолжить исполнение в этот вход после условного RET, он также вызывается отдельно из 706C
                ; -----------------------------------------
                ; Проверка допустимости индекса исходной таблицы из 16 поправок.
Entry:          LD A, B
                CP #10
                RET NC                                                          ; выход, если индекс B не меньше 16, состояние не изменяется

                ; -----------------------------------------
                ; Поиск поправки по входному индексу B
                LD L, B
                LD H, #00
                LD BC, @ActionTypeDeltas.Index00
                ADD HL, BC
                LD C, (HL)
                ; -----------------------------------------
                ; Прямой вход готовой поправки без выбора индекса
                ; In:
                ;   HL и DE сохраняемый контекст, BC содержит готовую поправку signed8 в C, входной B не используется
                ;   Control.TemplateMode и ActionFlightStatus.Value.Code доступны, на CPU-стеке внешний возврат, IRQ не вмешивается
                ; Out:
                ;   HL и DE сохранены, B старый байт состояния, C и A новый байт, F соответствует CP старого байта с 32
                ;   HL', DE', BC', AF', IX и IY, I/IM/IFF сохраняются, SP=входной SP+2
                ;   при ненулевом режиме и входном C меньше 80 эффективный байт равен (C+10) modulo 256, иначе он равен C
                ;   результат равен clamp(signed8(старый байт)+signed8(эффективный байт), 0, 127) OR 32 при старом unsigned8 меньше 32
                ; Corrupt:
                ;   BC, AF, R и одна запись ActionFlightStatus.Value.Code, CPU-стек не записывается
                ; Note:
                ;   при C=76..7F добавка превращает положительную поправку в отрицательную, это исходное переполнение байта
                ;   реальные вызовы передают 08 из UpdateObjects и 20 из SweepClass17AndPrepareSpawn, добавка этих значений не переполняется
                ;   134656 сценариев сверили регистры, R, всю RAM и единственную запись, игровой смысл кода не установлен
                ;   стоимость равна 15 M1 плюс ветви режима и ограничения, формула приведена в ActionTypeDelta.md
                ; -----------------------------------------
                ; Проверка шаблонного режима, ненулевой полный код разрешает добавить 10 к неотрицательной поправке.
AdjustMode:     LD A, (@ActionGlyphIndicatorState.Control.TemplateMode)
                AND A
                JR Z, @Action.ApplyIndexedDelta.ApplyDelta                      ; переход, если TemplateMode равен нулю, применить поправку без добавки

                ; Проверка знака исходной поправки, отрицательные значения добавку не получают.
                LD A, C
                AND A
                JP M, @Action.ApplyIndexedDelta.ApplyDelta                      ; переход, если поправка отрицательна, применить её без добавки

                ; Расчёт увеличенной поправки, к неотрицательному значению добавляется 10.
                ADD A, #0A
                LD C, A
                ; -----------------------------------------
                ; Расчёт ограниченной знаковой суммы
                ; Чтение локального кода по смещению станционного статуса, исходное значение сохраняется в B.
ApplyDelta:     LD A, (@ActionFlightStatus.Value.Code)
                LD B, A
                ADD A, C
                JP PO, @Action.ApplyIndexedDelta.ClampSign                      ; переход, если знаковое сложение не переполнилось, проверить знак суммы

                ; Восстановление флагов исходного байта перед ограничением переполнения.
                ; LD A,7F флаги не меняет, следующий JP P проверяет знак результата SUB.
                SUB C
                LD A, #7F
ClampSign:      JP P, @Action.ApplyIndexedDelta.CheckOld                        ; переход, если сумма неотрицательна либо положительное переполнение уже заменено на 7F

                ; Ограничение отрицательной суммы нулём, включая отрицательное переполнение.
                XOR A
                ; -----------------------------------------
                ; Проверка порога по исходному беззнаковому байту
                ; Результат сохраняется в C, проверка определяет необходимость принудительного бита 5.
CheckOld:       LD C, A
                LD A, B
                CP #20
                JR NC, @Action.ApplyIndexedDelta.StoreValue                     ; переход, если исходное значение не меньше 32, сохранить результат без принудительного бита 5

                ; Установка бита 5 результата при исходном значении 00..1F, игровой смысл разряда неизвестен.
                SET 5, C
                ; Обновление исходного байта состояния, флаги остаются от проверки старого значения.
StoreValue:     LD A, C
                LD (@ActionFlightStatus.Value.Code), A
                RET

                ; -----------------------------------------
                endmodule
                endmodule
