                module Action
                module CheckFaceOrientation
                ; Документация [алгоритм и проверка](../../Docs/ActionFaceOrientation.md)
                ; -----------------------------------------
                ; Проверка ориентации выбранной тройки экранных точек по знаку разности двух произведений
                ; исходная запись 17, адреса DFB6..E008
                ; In:
                ;   HL указывает на заголовок списка байтовых смещений точек страницы 8E, BC сохраняется
                ;   A выбирает тройку, при A<5 читаются индексы 0,1,2 списка, иначе 0,2,4
                ;   каждая точка содержит Second и First как два слова, ClipCode здесь не читается
                ;   ACTION находится в банке 0, на CPU-стеке внешний возврат и двенадцать дополнительных свободных байтов, IRQ не вмешиваются
                ; Out:
                ;   HL и BC сохраняются, DE содержит младшее слово разности второго произведения и первого с исходным заёмом
                ;   A равен XOR старших байтов аргументов второго MultiplySigned16, F содержит флаги последнего вычитания старших слов
                ;   Sign от F задаёт результат проверки, отрицательный результат допускает грань в вызывающих обработчиках, A не является булевым кодом
                ;   HL', DE' и BC' содержат соответственно старшее слово, младшее слово и побочный BC первого MultiplySigned16
                ;   AF' и IY сохраняются, IX равен результату последнего достигнутого полного ядра MultiplySigned16 либо сохраняется при двух коротких ядрах
                ;   SP после RET равен входному SP+2, I, IM, IFF и paging сохраняются, R меняется, портов нет
                ; Corrupt:
                ;   DE, AF, HL', DE', BC', IX по ядрам умножения, R, SavedSP и двенадцать байтов CPU-стека
                ; Note:
                ;   после загрузки точек активен альтернативный набор First, четыре SBC обрабатывают сначала First, затем Second с непрерывным заёмом
                ;   первый заём равен A<5 от CP 5, его нельзя обнулять при замене алгоритма формулой определителя
                ;   первое произведение равно vSecond*uFirst, второе vFirst*uSecond, разности u и v указаны в ActionFaceOrientation.md
                ;   младшее слово разности вычитается с Carry второго MultiplySigned16, затем заём передаётся старшему слову
                ;   исходное исключение умножения при втором операнде 8000 сохраняется и проверено, математический определитель неэквивалентен во всех случаях
                ;   4608 сценариев проверяют реальные дочерние вызовы, регистры, флаги, всю RAM и кратность записей, R и время отдельно не доказаны
                ;   все совместные тройки, IRQ, сборка и нативный вывод этим договором не подтверждаются
                ; -----------------------------------------
                ; -----------------------------------------
                ; Выбор тройки
                ; Сохранение BC и HL на CPU-стеке, сравнение A с 5 также задаёт первый заём будущих SBC.
Entry:          PUSH BC
                PUSH HL
                INC HL
                CP #05
                JR NC, @Action.CheckFaceOrientation.Alternate                   ; переход, если A не меньше 5, выбрать индексы 0, 2 и 4

                ; Чтение трёх последовательных индексов 0, 1 и 2.
                LD D, (HL)
                INC HL
                LD E, (HL)
                INC HL
                LD A, (HL)
                JP @Action.CheckFaceOrientation.ReadPoints

                ; Чтение индексов 0, 2 и 4 с пропуском промежуточных байтов.
Alternate:      LD D, (HL)
                INC HL
                INC HL
                LD E, (HL)
                INC HL
                INC HL
                LD A, (HL)
                ; -----------------------------------------
                ; Чтение двух слов каждой точки через рабочий SP
                ; Сохранение CPU SP в операнде, POP читает координаты из существующей страницы 8E.
ReadPoints:     LD H, @ActionVertexGroupConst.WorkHigh
                LD L, D
                LD (@ActionFaceOrientationState.SavedSP), SP
                LD SP, HL
                POP BC
                EXX
                POP BC
                EXX
                LD L, E
                LD SP, HL
                POP DE
                EXX
                POP DE
                EXX
                LD L, A
                LD SP, HL
                POP HL
                EXX
                POP HL
                ; Восстановление CPU-стека, после последнего EXX активны координаты First, не Second.
                LD SP, #0000
                ; -----------------------------------------
                ; Расчёт разностей с непрерывным заёмом
                ; Расчёт uFirst=P2.First-P0.First-(A<5), затем vFirst=P1.First-P0.First-заём.
                SBC HL, BC
                EX DE, HL
                SBC HL, BC
                PUSH HL
                EXX
                ; Расчёт uSecond и vSecond с продолжением заёма предыдущей оси.
                SBC HL, BC
                EX DE, HL
                SBC HL, BC
                ; Обмен временной разности со словом CPU-стека для подготовки первого произведения.
                EX (SP), HL
                EXX
                POP HL
                ; Расчёт первого произведения vSecond*uFirst с исходным исключением 8000.
                CALL @Action.MultiplySigned16.Entry
                ; Сохранение двух слов первого произведения и переключение набора на аргументы второго.
                PUSH HL
                PUSH DE
                EXX
                ; Расчёт второго произведения vFirst*uSecond, его Carry участвует в следующем SBC.
                CALL @Action.MultiplySigned16.Entry
                ; -----------------------------------------
                ; Разность произведений
                ; Расчёт младшего слова второго минус первое с Carry второго умножения, затем старшего слова с заёмом.
                EX DE, HL
                POP BC
                SBC HL, BC
                EX DE, HL
                POP BC
                SBC HL, BC
                ; Восстановление HL и BC без изменения флагов ориентации, основной набор вновь исходный.
                POP HL
                POP BC
                RET

                ; -----------------------------------------
                endmodule
                endmodule
