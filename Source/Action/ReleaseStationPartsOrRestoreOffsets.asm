                module Action
                module ReleaseStationPartsOrRestoreOffsets
                ; Документация [алгоритм и проверка](../../Docs/ActionClassReuse.md)
                ; -----------------------------------------
                ; Освобождение частей станции либо восстановление рабочих смещений
                ; исходная запись 17, адреса E65F..E684
                ; In:
                ;   HL, DE и BC числовых аргументов не задают, IX - читаемая FActionRecord, её ClassCode определяет ветвь
                ;   для класса 12 от A100 с шагом 64 достижим маркер 8080, записи и два байта состояния 9B82/9B83 доступны для записи
                ;   для остальных классов действует договор RestoreHalvedOffsets, при классе 14 сохранены Original0..2
                ;   код ACTION доступен в банке 0, CPU-стек содержит внешний возврат, для класса 12 нужны два дополнительных байта
                ;   CPU-стек, исполняемый код и входная запись не пересекаются с изменяемыми полями, IRQ не вмешивается
                ; Out:
                ;   при классе 12 HL и DE сохранены, BC=0040, AF=8042, IY указывает на маркер, SP после RET равен входному SP+2
                ;   при классе 12 TemplateMode и ThirdGate равны нулю, каждая активная запись класса 12 получает Component0=8000 и ReuseByte=FF
                ;   неактивные записи, маркер и активные записи других классов не меняются, после маркера RestoreHalvedOffsets не вызывается
                ;   для другого класса выполнен хвост RestoreHalvedOffsets, HL и AF определены его договором, DE, BC и IY сохранены
                ;   HL', DE', BC', AF' и IX сохраняются, I/IM/IFF и paging сохраняются
                ;   для списка R получает 23+10*N0+12*N1+21*N2 M1, N0 - пропущенные неактивные записи, N1 - активные другого класса, N2 - активные класса 12
                ;   для класса 14 R получает 15 M1, для остальных кодов вне 12 получает 8 M1, бит 7 R сохраняется
                ; Corrupt:
                ;   HL только для класса 14, BC только для класса 12, AF, IY только для класса 12, R
                ;   для класса 12 два байта состояния, три поля каждой выбранной записи и два временных байта CPU-стека
                ;   для класса 14 шесть байтов Active0..2, остальные коды не записывают RAM
                ; Note:
                ;   полный класс 12 соответствует авторскому T_STATION, часть станции, ветвь остальных классов сохраняет исходный RestoreHalvedOffsets
                ;   (1) жёсткий порядок, сюда продолжается часть (0) RejectRecordUpdate.asm после CALL пометки
                ;   доступность проверяет настоящий NextActiveRecord, High=80 означает пропуск, Low=80 дополнительно завершает проход
                ;   пометка вызывает настоящий MarkIYRecordForReuse, следующий достигший записи поиск доступного места один раз пропустит FF
                ;   полный ClassCode=12 сбрасывает режим шаблонной группы и снимает запрет третьего знака и класса 8
                ;   2129 сценариев проверили все коды класса, все входные F, каждую из 26 позиций в трёх состояниях, 1024 смешанных списка и крайние случаи
                ;   сопоставлены все регистры включая R, восемь банков RAM и кратность записей, реальный итератор и оба дочерних хвоста не подменены
                ;   полное пространство 3^26 состояний списка, порядок шинных циклов стека, IRQ, точные T, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Выбор обработки по полному коду класса
                ; Проверка ClassCode входной записи IX, только TransferClass запускает очистку всего списка.
Entry:          LD A, (IX+FActionRecord.ClassCode)
                CP @ActionCloseRecordConst.TransferClass
                JR NZ, @Action.RestoreHalvedOffsets.Entry                       ; переход, если ClassCode отличается от TransferClass, выполнить общий восстановитель смещений

                ; -----------------------------------------
                ; Состояние класса 12 и начало списка
                ; Сброс шаблонного режима и связанного допуска до обхода записей.
                XOR A
                LD (@ActionGlyphIndicatorState.Control.TemplateMode), A
                LD (@ActionGlyphIndicatorState.Control.ThirdGate), A
                ; Подготовка прохода перед первой физической записью, NextActiveRecord сначала прибавляет размер записи.
                LD IY, @ActionObjectRecords.Record00-FActionRecord
                LD BC, FActionRecord
                ; -----------------------------------------
                ; Поиск и пометка записей
                ; Поиск следующей активной записи с пропуском High=80, маркер 8080 завершает весь хвост.
ScanNext:       CALL @Action.NextActiveRecord.Entry
                RET Z                                                           ; выход, если NextActiveRecord достиг маркера конца, восстановитель смещений обходится

                ; Проверка полного ClassCode найденной активной записи, записи других классов сохраняются.
                LD A, (IY+FActionRecord.ClassCode)
                CP @ActionCloseRecordConst.TransferClass
                JR NZ, @Action.ReleaseStationPartsOrRestoreOffsets.ScanNext     ; переход, если ClassCode найденной записи отличается от TransferClass, искать следующую запись

                ; Пометка выбранной записи кодом 8000 и ReuseByte=FF, сами IX и IY дочерний вызов сохраняет.
                CALL @Action.MarkIYRecordForReuse.Entry
                JP @Action.ReleaseStationPartsOrRestoreOffsets.ScanNext

                ; -----------------------------------------
                endmodule
                endmodule
