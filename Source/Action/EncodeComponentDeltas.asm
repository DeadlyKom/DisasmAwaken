                module Action
                module EncodeComponentDeltas
                ; Документация [алгоритм и проверка](../../Docs/ActionDeltaRatio.md)
                ; -----------------------------------------
                ; Кодирование отношения двух разностей слов с последовательным продолжением в EncodeSignedRatio
                ; исходная запись 17, адреса AE15..AE23
                ; In:
                ;   HL и DE задают два слова первой разности, BC второе слово второй разности, HL' первое слово второй разности
                ;   AF, DE', BC', AF', IX и IY передаются как контекст, числовых аргументов в них нет
                ;   действуют условия EncodeSignedRatio, подготовлены таблицы 9100..93FF и 9A00..9AFF
                ;   код AE24 обязан следовать непосредственно за AE23, на стеке внешний возврат и шесть доступных временных байтов, IRQ не вмешиваются
                ; Out:
                ;   вычислены denominator=wrap16(входной HL−DE) и numerator=wrap16(входной HL'−BC), затем исполнен настоящий EncodeSignedRatio
                ;   HL, DE и AF соответствуют договору EncodeSignedRatio для этих двух разностей, BC равен denominator
                ;   HL', DE', BC', IX, IY, I/IM/IFF и paging сохраняются, AF' содержит выход последнего делителя
                ;   SP после общего RET равен входному SP+2, дополнительного CALL между AE15 и AE24 нет
                ;   R получает стоимость EncodeSignedRatio и ещё пятнадцать M1, записи памяти соответствуют только дочернему договору
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', R, шесть временных байтов стека и операнды делителя
                ; Note:
                ;   обе разности вычисляются с очищенным Carry и оборачиваются до слова, Overflow не проверяется
                ;   EXX используется только для чтения исходного HL', все три альтернативные пары сохраняют исходные слова
                ;   8192 сценария проверили настоящее продолжение, делитель, регистры включая R и точную последовательность всех записей модели
                ;   игровой вызывающий путь не найден, это не доказывает неиспользование, полный набор четырёх слов и нативный запуск не проверены
                ; -----------------------------------------
                ; Расчёт первой разности с очищенным Carry, результат переносится в знаменатель DE.
Entry:          OR A
                SBC HL, DE
                EX DE, HL
                ; Чтение исходного HL' без изменения альтернативных пар, байты переносятся через AF и AF'.
                EXX
                LD A, L
                EX AF, AF'
                LD A, H
                EXX
                LD H, A
                EX AF, AF'
                LD L, A
                ; Расчёт второй разности с очищенным Carry, результат остаётся в числителе HL.
                OR A
                SBC HL, BC
                ; JP @Action.EncodeSignedRatio.Entry, продолжение в EncodeSignedRatio.asm

                endmodule
                endmodule
