                module Action
                module ClipProjectionBounds
                ; Документация [граничный отбор и таблица](../../Docs/ActionProjectionClip.md)
                ; -----------------------------------------
                ; Проверка глубины и двух осей с табличной поправкой масштаба и выбором следующего пути проекции
                ; исходная запись 17, код ACTION банка 0, адреса E213..E298
                ; In:
                ;   HL числовых аргументов не задаёт, DE исходное слово границы, C байтовый параметр табличной поправки, B аргумента не задаёт
                ;   AF числового аргумента не задаёт, A сохраняется только при первом отказе по глубине
                ;   Output0, Output1 и Output2 задают слова X, Y и глубины, таблица 9800 содержит исходные 256 значений нормированного квадрата
                ;   FirstAxisSkip и SecondAxisSkip заранее равны 6-h для одного показателя h от 1 до 6, это договор PrepareProjectionScale
                ;   SkipDetail задаёт полный байт последнего выбора пути, банк 0 ACTION доступен, IRQ не вмешиваются
                ; Out:
                ;   при установленном знаковом бите слова Output2+входной DE исполнение передаётся E0E2, HL сумма, DE и BC сохраняются, A входной, F от ADC без входного переноса
                ;   после допуска глубины IXL получает входной C, старший байт IX сохраняется
                ;   после первой оси BC=Output0, DE табличный допуск X, HL последняя сумма либо разность, A байтовая разность квадратов X, F от соответствующего ADC либо SBC
                ;   после второй оси BC=Output1, DE табличный допуск Y, HL последняя сумма либо разность, A байтовая разность квадратов Y, F от соответствующего ADC либо SBC
                ;   при знаковом бите любой суммы или разности осей исполнение передаётся E0E2, знаковое переполнение отдельно не проверяется
                ;   после допуска обеих осей A=SkipDetail, F соответствует AND A, при A=0 исполнение продолжается E299, иначе передаётся E40F
                ;   HL', DE', BC', AF', IY, SP, I, IM и IFF сохраняются, дополнительных записей CPU-стека, RAM и OUT нет
                ; Corrupt:
                ;   HL, DE, BC, AF, IXL после допуска глубины, R
                ; Note:
                ;   старший бит результата проверяется после каждого оборачивания слова, условие не заменяется неограниченной знаковой арифметикой
                ;   индексы таблицы вычисляются по полным байтам с арифметическим SRA параметра C, отрицательные C имеют исходное особое поведение
                ;   поправка X использует центр 36, поправка Y центр 33, разность отсчётов оборачивается в байт до масштабирования
                ;   для X сначала используется арифметическая половина глубины, для Y её арифметическая четверть, затем после сложения с координатой берётся ещё половина
                ;   это последовательный фрагмент без RET, продолжения E299, E40F и E0E2 локальной моделью не исполняются
                ;   параметр C обычного предшествующего пути ограничен 0..15, локально проверены все 256 исходных байтов, их игровой диапазон не расширяется
                ; -----------------------------------------
                ; -----------------------------------------
                ; Проверка глубины с исходной границей
                ; Расчёт слова Output2 + DE без входного переноса, результат оборачивается в 16 бит.
Entry:          LD HL, (@ActionPatchedVectorState.Output2)
                AND A
                ADC HL, DE
                JP M, @Action.RenderSceneFrame.AdvanceRecord                    ; переход, если знаковый бит полученного слова глубины установлен, продолжить обход по E0E2

                ; -----------------------------------------
                ; Табличная поправка первой оси
                ; Сохранение входного C в IXL и расчёт двух индексов вокруг центра WidthBase DIV 2.
                LD IXL, C
                LD A, @ActionProjectionClipConst.WidthBase
                LD H, @ActionProjectionClipConst.SquarePage
                SRA A
                LD L, C
                SRA L
                SUB L
                LD L, A
                ADD A, C
                ; Чтение двух нормированных квадратов и расчёт их байтовой разности, отрицательная разность оборачивается.
                LD E, (HL)
                LD L, A
                LD A, (HL)
                SUB E
                LD L, A
                LD H, #00
                ; Масштабирование байтовой разности, подготовленный JR оставляет h-1 из пяти удвоений.
ScaleX:         JR @Action.ClipProjectionBounds.ScaleX

                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ; -----------------------------------------
                ; Проверка обеих границ первой оси
                ; Расчёт арифметической половины суммы Output2 DIV 2 и Output0, затем прибавление табличного допуска X.
                EX DE, HL
                LD HL, (@ActionPatchedVectorState.Output2)
                SRA H
                RR L
                LD BC, (@ActionPatchedVectorState.Output0)
                ADD HL, BC
                SRA H
                RR L
                AND A
                ADC HL, DE
                JP M, @Action.RenderSceneFrame.AdvanceRecord                    ; переход, если знаковый бит первой суммы X установлен, продолжить обход по E0E2

                ; Проверка противоположной границы X, из полученного слова вычитается весь Output0 без входного займа.
                OR A
                SBC HL, BC
                JP M, @Action.RenderSceneFrame.AdvanceRecord                    ; переход, если знаковый бит второй разности X установлен, продолжить обход по E0E2

                ; -----------------------------------------
                ; Табличная поправка второй оси
                ; Восстановление исходного C из IXL и расчёт индексов вокруг центра HeightBase DIV 2.
                LD C, IXL
                LD A, @ActionProjectionClipConst.HeightBase
                LD H, @ActionProjectionClipConst.SquarePage
                SRA A
                LD L, C
                SRA L
                SUB L
                LD L, A
                ADD A, C
                ; Чтение двух отсчётов той же таблицы и расчёт байтовой разности для Y.
                LD E, (HL)
                LD L, A
                LD A, (HL)
                SUB E
                LD L, A
                LD H, #00
                ; Масштабирование разности Y тем же числом удвоений h-1.
ScaleY:         JR @Action.ClipProjectionBounds.ScaleY

                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ; -----------------------------------------
                ; Проверка обеих границ второй оси
                ; Расчёт арифметической половины суммы Output2 DIV 4 и Output1, затем прибавление допуска Y.
                EX DE, HL
                LD HL, (@ActionPatchedVectorState.Output2)
                SRA H
                RR L
                SRA H
                RR L
                LD BC, (@ActionPatchedVectorState.Output1)
                ADD HL, BC
                SRA H
                RR L
                AND A
                ADC HL, DE
                JP M, @Action.RenderSceneFrame.AdvanceRecord                    ; переход, если знаковый бит первой суммы Y установлен, продолжить обход по E0E2

                ; Проверка противоположной границы Y, из полученного слова вычитается весь Output1 без входного займа.
                OR A
                SBC HL, BC
                JP M, @Action.RenderSceneFrame.AdvanceRecord                    ; переход, если знаковый бит второй разности Y установлен, продолжить обход по E0E2

                ; -----------------------------------------
                ; Выбор следующего пути
                ; Проверка полного SkipDetail после всех геометрических сравнений, ненулевой байт пропускает PrepareProjectedBounds.
                LD A, (@ActionProjectionClipState.SkipDetail)
                AND A
                JP NZ, @Action.InsertRenderQueue.Entry                          ; переход, если SkipDetail ненулевой, продолжить обработку по E40F

                ; JP @Action.PrepareProjectedBounds.Entry, продолжение в PrepareProjectedBounds.asm

                ; -----------------------------------------
                endmodule
                endmodule
