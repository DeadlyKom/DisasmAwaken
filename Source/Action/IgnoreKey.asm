                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, все регистры сохраняются
                ;   на CPU-стеке адрес продолжения, при вызове из диспетчера это 6F4E
                ; Out:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, I, IM и IFF сохраняются
                ;   SP=входной SP+2, R увеличивается на 1 M1, управление передано по адресу из стека
                ;   RAM и CPU-стек не записываются
                ; Corrupt:
                ;   SP, R
                ; Note:
                ;   исходный байт C9 по 704B также читается последним шагом сканирования как младший байт слова C0C9
                ;   это перекрытие не означает выделения второй копии физического байта
                ;   256 сценариев исполнили весь путь от 6F1D через настоящий RET и RestoreKeyScanFrame, другие обработчики не доказаны
                ; -----------------------------------------
