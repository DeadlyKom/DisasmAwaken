                module Action
                module StepTimedPhasePattern
                ; Документация [алгоритм и проверка](../../Docs/ActionTimedPhaseState.md)
                ; -----------------------------------------
                ; Обновление таймера и двух фаз с переходом к состоянию 10 при истечении
                ; исходная запись 17, адреса F3A1..F3C7
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, входной Carry сохраняется только во временном результате DEC собственного префикса
                ;   IX указывает доступные PhaseMoveTimer, OffsetPhase1, OffsetPhase2 и StateCode записи, действуют условия общего F0F8
                ;   читается Component0.High, для активной записи доступны остальные фазовые поля, класс, состояние и порог
                ;   OffsetScaleLow и OffsetScaleHigh активной записи доступны для записи, ACTION банка 0 и общая RAM доступны
                ;   действует договор ApplyObjectOffsetVector, шесть байтов под SP и внешний возврат не перекрывают его код, таблицы, операнды и результаты
                ;   IRQ и повторный вход исключены
                ; Out:
                ;   при маркере Component0.High=80 после собственного префикса выполняется внешний RET, AF=8042, SP=входной SP+2
                ;   на маркере HL/DE/BC, HL'/DE'/BC', IX/IY сохраняются, A' равен wrap8(прежний OffsetPhase2+2), F' от этого ADD
                ;   маркер не отменяет собственные фазовые и таймерные записи, на активной ветви последующий полный вычислитель заменяет AF и AF альтернативного набора
                ;   на активной ветви нижеследующие результаты вычислителя относятся к V из прежнего OffsetScaleLow и выбранного старшего байта
                ;   HL=(-Q) AND FFFF при бите 7 S=1, иначе HL=Q, DE=Q при бите 7 S=1, иначе DE=abs(V)
                ;   BC - B=W[Offset0], C=0
                ;   AF - A=S, F от 16-разрядного 0-Q при бите 7 S=1, иначе флаги логического XOR с результатом S
                ;   HL', DE', BC' сохраняются
                ;   AF' - A'=U, F'=(U AND 28) OR (40 при U=0) OR (10 при 2*((P SHR 16) AND 0F)+(U AND 1)>0F), остальные биты F' нулевые
                ;   IX восстановлен, IYH сохраняется, IYL=W[(Offset1+64) AND FF]
                ;   Coefficient0..2 содержат результат построителя, Base0..2 содержат три произведения с одним входным V
                ;   SP=входной SP+2, I, IM, IFF и paging сохраняются, порты не используются
                ;   Offset0..2 получают OffsetPhase0, wrap8(OffsetPhase1+80) и OffsetPhase2
                ;   OffsetScaleLow получает wrap8(старое+1), если этот кандидат ниже Phase2OrTarget, иначе сохраняется прежний байт
                ;   OffsetScaleHigh обнулён при ClassCode<10 и StateCode не равном 13, иначе сохранён
                ;   на активной ветви общий хвост добавляет к R 30+Hold+4*Small+2*Small*Different M1 подготовки плюс полный вычислитель, старший бит R сохраняется
                ;   PhaseMoveTimer уменьшается по модулю 256, OffsetPhase1 увеличен на четыре и OffsetPhase2 на два на всех путях
                ;   только при исходном PhaseMoveTimer=1 после записи нуля таймер получает 46 и StateCode получает 10
                ;   при исходном нулевом таймере записывается FF без смены состояния, фазы всё равно изменяются
                ;   общий хвост читает новые фазы и StateCode, сохраняемые слова масштаба обрабатывает по своему полному договору
                ;   собственный префикс имеет 18 M1 без истечения и 23 при исходном таймере 1, к ним прибавляется полный общий хвост
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', IYL, R, Coefficient0..2, Base0..2 и шесть временных байтов CPU-стека, три фазовых операнда и условно OffsetScaleLow/OffsetScaleHigh, PhaseMoveTimer, OffsetPhase1, OffsetPhase2 и условно StateCode
                ;   на маркере изменены AF и AF альтернативного набора, R и собственные поля префикса, вычислитель не вызывается
                ; Note:
                ;   два EX AF, AF' сохраняют флаги DEC до выбора перехода, ADD фаз не выбирает факт истечения таймера
                ;   выход AF' от последнего ADD относится только к границе F0F8 и маркерному пути, активный вычислитель его перезаписывает
                ;   46, 10, FF и 80 здесь шестнадцатеричные, длительность 46 равна 70 вызовам при отсутствии иных писателей, не доказанным секундам
                ;   эффективное слово V перед 6D06 содержит прежний OffsetScaleLow в E и итоговый OffsetScaleHigh в D, это не входное DE всей процедуры
                ;   Hold=1 при сохранении прежнего младшего масштаба, иначе 0, Small=1 при ClassCode<10, Different=1 при StateCode не равном 13, иначе соответствующий признак нулевой
                ;   10, 13 и 80 в условиях полей обозначают шестнадцатеричные коды, числа M1 десятичные
                ;   c2 обозначает третий байтовый коэффициент, m=abs(s8(c2)) AND 7F, P=m*abs(V), Q=floor(P/128), U=P SHR 15, S=c2 XOR HIGH слова V
                ;   нулевой фактор для коэффициента 80 сохранён, знак определяется исходным байтом коэффициента и старшим байтом V
                ;   каждое Base равно -floor((abs(s8(c_i)) AND 7F)*abs(V)/128) при бите 7 c_i XOR HIGH V, иначе положительному частному, всё по модулю 65536
                ;   шесть временных байтов после возврата содержат исходный IX по SP-2, слово V по SP-4 и внутренний возврат 6D0C по SP-6, POP не очищает RAM
                ;   для фактора m>0 умножение даёт 35+floor(log2(m))+2*popcount(m) M1, при m=0 даёт 32 M1
                ;   к каждому умножению добавляются семь M1 при V<0, две при бите 7 коэффициента и четыре при бите 7 его XOR HIGH V
                ;   маркер внутри F0F8 возвращается до записи общих фазовых операндов и не вызывает вычислитель, на активном пути внешний RET выполняет его хвост
                ;   отдельная проверка F0F8, 196608 прежних сценариев останавливаются перед 6D06 либо на раннем RET, новая композиция проверяет 15616 случаев до полного внешнего возврата
                ;   полное произведение всех аргументов, точные T, IRQ и нативная игра не доказаны
                ;   196608 прежних случаев проверяют префикс до F0F8, новая полная композиция добавляет 24576 случаев этого входа до внешнего RET
                ;   полная новая композиция двух таймерных входов имеет 49152 случая, проверены регистры включая R, восемь банков, кратность записей и отсутствие OUT
                ;   полное произведение фаз, таблиц и аргументов, точные T, IRQ и нативный запуск не доказаны
                ; -----------------------------------------
                ; Обновление таймера состояния, ноль оборачивается в FF, истечение наступает только при исходной единице.
Entry:          LD A, (IX + @FActionRecord.PhaseMoveTimer)
                DEC A
                LD (IX + @FActionRecord.PhaseMoveTimer), A
                ; Сохранение результата и флагов декремента в AF' на время расчёта фаз.
                EX AF, AF'
                ; Расчёт следующего индекса второй фазы с шагом четыре по модулю 256.
                LD A, (IX + @FActionRecord.OffsetPhase1)
                ADD A, @ActionTimedPhaseConst.Phase1Step
                LD (IX + @FActionRecord.OffsetPhase1), A
                ; Расчёт следующего индекса третьей фазы с шагом два, её ADD останется в итоговом AF'.
                LD A, (IX + @FActionRecord.OffsetPhase2)
                ADD A, @ActionTimedPhaseConst.Phase2Step
                LD (IX + @FActionRecord.OffsetPhase2), A
                ; Восстановление A и флагов таймера перед условием истечения.
                EX AF, AF'
                JP NZ, @Action.PrepareObjectOffsetTransform.Entry               ; переход, если результат декремента таймера ненулевой, сохранить текущее состояние

                ; Обновление таймера исходной длительностью 70 и установка следующего состояния 10.
                LD (IX + @FActionRecord.PhaseMoveTimer), @ActionTimedPhaseConst.ReloadTimer
                LD (IX + @FActionRecord.StateCode), @ActionTimedPhaseConst.NextState
                JP @Action.PrepareObjectOffsetTransform.Entry

                endmodule
                endmodule
