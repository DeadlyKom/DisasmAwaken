                module Action
                module EncodeSignedComponents
                ; Документация [алгоритм и проверка](../../Docs/ActionComponentEncoding.md)
                ; -----------------------------------------
                ; Кодирование трёх выходных слов в знак и модуль с обратным знаком компоненты 1
                ; исходная запись 17, перенесённый ACTION фиксированного банка 5, смещения #0E80..#0EBA
                ; In:
                ;   HL, DE, BC и A числовых аргументов не задают, DE и BC сохраняются
                ;   входной P/V=1 запрещает обновление после переполнения вычислителя, входной Carry сохраняется в итоговом F
                ;   при P/V=0 Output0..2 доступны в ACTION банка 0, три физических FComponent24 ActionComponentWork доступны для записи
                ;   CPU SP уже восстановлен и содержит внешний возврат, не пересекающийся с изменяемыми полями, IRQ не вмешивается
                ; Out:
                ;   при входном P/V=1 HL, DE, BC и AF сохранены, RAM не меняется
                ;   при допуске Component0 и Component2 получают в Middle/High исходное неотрицательное слово либо ((-word) AND FFFF) OR 8000 для отрицательного
                ;   Component1 получает в Middle/High исходное неотрицательное слово OR 8000 либо (-word) AND FFFF для отрицательного
                ;   Low всех трёх компонент сохраняется, HL содержит закодированное слово Component2, DE и BC сохраняются
                ;   A содержит дополнение старшего байта последней отрицательной входной компоненты, если отрицательных нет, входной A сохранён
                ;   F относится к BIT/CPL последней компоненты, Carry входной, P/V после допуска не является статусом прежнего вычислителя
                ;   HL', DE', BC', AF', IX и IY, I/IM/IFF и paging сохраняются, SP после RET равен входному SP+2
                ;   R получает один M1 при запрете либо 19+9*n0+7*n1+9*n2 M1 при допуске, ni=1 для отрицательного исходного слова i, бит 7 R сохраняется
                ; Corrupt:
                ;   HL и AF только при допуске, R и шесть байтов Middle/High трёх компонент только при допуске
                ; Note:
                ;   (1) жёсткий порядок, сюда продолжается часть (0) RestoreComponentStack.asm после восстановления CPU SP
                ;   High содержит знак в бите 7 и старшие семь битов модуля, Middle содержит младшие восемь битов модуля, значение Low этим фрагментом не интерпретируется
                ;   нулевая Component1 получает слово 8000, отрицательный ноль сохраняется без нормализации
                ;   исходное слово 8000 не помещается в 15-разрядный модуль и тоже даёт код 8000, исправления предела не вводились
                ;   ретранслятор знаков использует SET 7,H у второй компоненты до ветвления, порядок не эквивалентен общему NEG с последующей нормализацией
                ;   65792 сценария проверили все слова каждой компоненты, все входные F, регистры включая R, все банки RAM и кратность записей
                ;   физические девять байтов оформлены существующим FComponent24, промежуточные единицы и общий смысл младшего Low ещё не установлены
                ;   полное произведение слов, порядок шинных циклов записи слов, IRQ, точные T, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Допуск знакового кодирования
                ; Проверка результата предыдущего вычислителя, старые физические компоненты сохраняются при переполнении.
Entry:          RET PE                                                          ; выход, если вычислитель сообщил переполнение, сохранить все три компоненты

                ; -----------------------------------------
                ; Компонента 0
                ; Чтение Output0 и проверка знакового разряда исходного слова.
                LD HL, (@ActionPatchedVectorState.Output0)
                BIT @ActionComponentEncodeConst.SignBit, H
                JR Z, @Action.EncodeSignedComponents.StoreComp0                 ; переход, если Output0 неотрицателен, записать его без перекодирования

                ; Расчёт модуля отрицательного Output0 через дополнение и увеличение слова, затем установка знакового кода.
                LD A, L
                CPL
                LD L, A
                LD A, H
                CPL
                LD H, A
                INC HL
                SET @ActionComponentEncodeConst.SignBit, H
                ; Обновление Middle/High Component0, её отдельный младший байт Low не меняется.
StoreComp0:     LD (@ActionComponentWork.Component0.Middle), HL
                ; -----------------------------------------
                ; Компонента 1 с обратным знаком
                ; Чтение Output1, знак проверяется до безусловной установки бита 7 в кодируемом слове.
                LD HL, (@ActionPatchedVectorState.Output1)
                BIT @ActionComponentEncodeConst.SignBit, H
                SET @ActionComponentEncodeConst.SignBit, H
                JR Z, @Action.EncodeSignedComponents.StoreComp1                 ; переход, если исходный Output1 неотрицателен, сохранить его с установленным знаковым кодом

                ; Расчёт положительного модуля исходного отрицательного Output1, нулевой и предельный коды оригинала не нормализуются.
                LD A, L
                CPL
                LD L, A
                LD A, H
                CPL
                LD H, A
                INC HL
                ; Обновление Middle/High Component1, исходный нуль представлен кодом 8000.
StoreComp1:     LD (@ActionComponentWork.Component1.Middle), HL
                ; -----------------------------------------
                ; Компонента 2
                ; Чтение Output2 и проверка того же знакового разряда для прямого кодирования.
                LD HL, (@ActionPatchedVectorState.Output2)
                BIT @ActionComponentEncodeConst.SignBit, H
                JR Z, @Action.EncodeSignedComponents.StoreComp2                 ; переход, если Output2 неотрицателен, записать его без перекодирования

                ; Расчёт модуля отрицательного Output2 и установка знакового кода, слово 8000 остаётся исходным предельным случаем.
                LD A, L
                CPL
                LD L, A
                LD A, H
                CPL
                LD H, A
                INC HL
                SET @ActionComponentEncodeConst.SignBit, H
                ; Обновление Middle/High Component2, последнее слово также остаётся в HL.
StoreComp2:     LD (@ActionComponentWork.Component2.Middle), HL
                RET

                ; -----------------------------------------
                endmodule
                endmodule
