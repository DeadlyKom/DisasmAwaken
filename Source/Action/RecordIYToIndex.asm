                module Action
                module RecordIYToIndex
                ; Документация [коды и адреса записей](../../Docs/ActionRecordIndex.md)
                ; -----------------------------------------
                ; Расчёт байтового кода записи по IY с сохранением HL
                ; исходная запись 17, код ACTION банка 0, адреса E6BE..E6C6
                ; In:
                ;   HL сохраняется, DE, BC и AF числовых аргументов не задают, IY входной адрес записи
                ;   действует договор RecordAddressToIndex, CPU-стек имеет четыре дополнительных байта, IRQ не вмешиваются
                ; Out:
                ;   HL, DE и BC сохраняются, A и F соответствуют RecordAddressToIndex с входным HL=IY
                ;   HL', DE', BC', AF', IX, IY, I, IM и IFF сохраняются, SP=входной SP+2
                ;   R увеличивается на 16 M1, записываются четыре байта CPU-стека, иной RAM не меняется
                ; Corrupt:
                ;   AF, R, четыре байта CPU-стека
                ; Note:
                ;   перед расчётом исходный HL сохраняется, временный PUSH IY используется только для переноса адреса в HL
                ;   адрес записи не разыменовывается, произвольные значения IY не вызывают отказа
                ; -----------------------------------------
                ; Сохранение исходного HL и перенос IY в HL через CPU-стек.
Entry:          PUSH HL
                PUSH IY
                POP HL
                ; Расчёт кода по адресу IY без чтения содержимого записи.
                CALL @Action.RecordAddressToIndex.Entry
                ; Восстановление исходного HL, эти два байта ранее хранились как необъявленный ресурс.
                POP HL
                RET

                endmodule
                endmodule
