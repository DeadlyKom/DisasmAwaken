                module Action
                module ToggleTargetOverlay
                ; Документация [алгоритм и проверка](../../Docs/ActionOverlayPair.md)
                ; -----------------------------------------
                ; Проекция пары векторов, проверка общего окна и XOR-вывод соединяющего сегмента
                ; исходная запись 17, адреса EB41..EB6D
                ; In:
                ;   HL и HL' задают вертикали, DE и DE' глубины, BC и BC' горизонтали двух signed16-векторов для ProjectOverlayCoordinates
                ;   таблицы проекции и операнды доступны, по EB6E сохранён исходный поток B2,00,05,00 для XOR-линии между индексами 0 и 5
                ;   страница 8E, экран и рабочие буферы рисователей доступны на запись, действуют договоры RenderInsideRecords и RenderClippedRecords
                ;   ACTION банка 0 выбран, внешний CPU-стек не пересекается с рабочими областями детей, IRQ и повторный вход исключены
                ; Out:
                ;   при отказе первой проекции ни одна точка не сохраняется, при отказе второй первая уже записана и обмен EXX не отменяется
                ;   при двух успешных проекциях обновляются Second/First двух FRenderProjectedPoint по 8E00 и 8E05
                ;   ClassifyProjectedPair всегда записывает оба кода, нулевое объединение немедленно завершает вывод
                ;   при общей внешней стороне, то есть ненулевом ((NOT объединение) AND F0), линия не выводится
                ;   при нулевой младшей тетраде вызывается хвост RenderInsideRecords, при ненулевой RenderClippedRecords
                ;   исходный заголовок B2 выбирает открытый XOR-сегмент из двух точек, полный ноль по EB71 завершает поток
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX и IY определяются последним реально достигнутым ребёнком, I/IM/IFF и paging сохраняются
                ;   на пути полного рисователя HL=EB71, A=0, F=54, на ранних возвратах действуют точные результаты проекции либо кодов
                ;   SP после внешнего RET равен входному SP+2, наблюдалось до 22 дополнительных байтов CPU-стека
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, R, две экранные точки, пиксели, буферы, изменяемые операнды и CPU-стек детей, SP внешним RET
                ; Note:
                ;   XOR повторного вывода с теми же исходными координатами переключает тот же сегмент, исходные условия отсечения при этом должны совпадать
                ;   4825 сценариев исполнили настоящие проекции, классификатор, оба рисователя, отсечение и пиксельный вывод
                ;   сверены регистры кроме R на путях растеризатора, все восемь банков и кратность записей, R дополнительно доказан на 2973 ранних путях
                ;   8192 отдельных сценария проекции доказали её R и перенос внешнего SP, не следует распространять этот результат на растеризатор
                ;   полное произведение входов, R растеризатора, точные T, аппаратные IRQ, сборка и нативный вывод не проверялись
                ; -----------------------------------------
                ; Расчёт первой экранной точки по основным BC, HL и DE, исходный табличный делитель сохраняет оба отказа.
Entry:          CALL @Action.ProjectOverlayCoordinates.Entry
                RET NZ                                                          ; выход, если первая проекция вернула NZ, ни одну экранную точку не сохранять

                ; Обновление двух физических слов первой точки, ClipCode пока сохраняется.
                LD (@ActionVertexGroupConst.WorkPage), HL
                LD (@ActionVertexGroupConst.WorkPage + 2), DE
                ; Преобразование альтернативного вектора в основной набор для второй проекции.
                EXX
                CALL @Action.ProjectOverlayCoordinates.Entry
                RET NZ                                                          ; выход, если вторая проекция вернула NZ, первую точку и обмен EXX сохранить

                ; Обновление двух слов второй точки после успешной проекции.
                LD (@ActionVertexGroupConst.WorkPage + 5), HL
                LD (@ActionVertexGroupConst.WorkPage + 7), DE
                ; Восстановление порядка рабочих наборов перед классификацией обеих экранных точек.
                EXX
                ; Расчёт парных кодов границ с локальным нулевым кодом каждого отказа.
                CALL @Action.ClassifyProjectedPair.Entry
                RET Z                                                           ; выход, если объединение кодов равно нулю, обе точки являются маркерами

                ; Проверка общей внешней стороны пары через отрицание старшей тетрады объединения.
                LD B, A
                CPL
                AND #F0
                RET NZ                                                          ; выход, если найдена общая внешняя сторона, сегмент не пересекает окно

                ; Проверка необходимости отсечения, младшая тетрада показывает хотя бы один внешний конец.
                LD A, B
                AND #0F
                ; Выбор исходного потока одной открытой XOR-линии между двумя экранными точками.
                LD HL, @ActionOverlayLineData.Line
                JP NZ, @Action.RenderClippedRecords.Entry                       ; переход, если хотя бы один конец вне окна, выполнить рисователь с отсечением

                JP @Action.RenderInsideRecords.Entry

                endmodule
                endmodule
