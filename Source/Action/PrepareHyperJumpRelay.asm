                module Action
                module PrepareHyperJumpRelay
                ; Документация [подготовка копируемого загрузчика гиперперехода](../../Docs/ActionHyperJumpPreparation.md)
                ; -----------------------------------------
                ; Сообщение гиперперехода, вывод очереди, исходная задержка и перенос загрузчика ACTION в 4200
                ; исходная запись 17, перенесённое ядро банка 5, адреса 7176..71CA
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, пятибайтовый контекст уже скопирован RequestHyperJump
                ;   Controls банка 1 содержит QueueTextItem, ConsumeTextQueue и шрифт, текстовое окно предварительно инициализировано
                ;   Recognition.Value=FF выбирает длинную задержку, любой другой код короткую, paging разблокирован и исходно выбран банк 0
                ;   исходные 99 байтов 71CB..722D доступны для чтения, 4200..4262 и атрибуты 5800..5AFF доступны для записи
                ;   обычный стек и стек прокрутки соответствуют договору ConsumeTextQueue, IRQ в проверке отсутствуют
                ; Out:
                ;   сообщение F37F передаётся через QueueTextItemBank1 с сохранением DE, затем выбирается банк 1
                ;   ConsumeTextQueue вызывается ровно 256 раз с сохранением BC каждого вызова, текст, очередь и прокрутка меняются по его договору
                ;   Recognition.Value, отличный от FF, даёт 64 внешних ожидания, FF даёт 128, каждое содержит 255 на 255 исходных DJNZ
                ;   OUT 7FFD получает 1F, выбран банк 7, теневой экран и ROM 1, paging не блокируется
                ;   768 байтов базовых атрибутов 5800..5AFF обнуляются перекрывающимся LDIR
                ;   99 исходных байтов 71CB..722D переносятся в 4200..4262 и выполняется JP 4200
                ;   на границе 4200 HL=722E, DE=4263, BC=0, A=1F, IX, IY, I, IM и IFF сохранены, SP равен входному
                ;   альтернативные регистры и Carry определены настоящими текстовыми детьми, F после последнего LDIR равен 60 OR Carry
                ;   обычного возврата нет, следующий вход относится к копии загрузчика, его код и ключ ACTION занимают 90 и 9 байтов
                ; Corrupt:
                ;   HL, DE, BC, AF, DE', BC', AF', R, очередь, курсоры и экран текста, базовые атрибуты, 99 байтов копии, paging и временные стеки
                ; Note:
                ;   подготовитель сам не выполняет DI, первый DI находится уже в перенесённом загрузчике
                ;   два сквозных профиля исполняют настоящее сообщение, 256 потребителей, 4161600 либо 8323200 DJNZ без подмены счётчиков
                ;   сверены восемь банков RAM кроме 64 байтов обычного стека и двух байтов SavedSP прокрутки, основные конечные пары и сохранённые IX/IY/SP/I/IM/IFF
                ;   точные регистры текстовых детей, R, такты и общая кратность записей этой серией не доказываются
                ;   граница проверки находится перед первой инструкцией копии 4200, TR-DOS, сборка и нативная игра не исполнялись
                ; -----------------------------------------
                ; Постановка исходного сообщения о разогреве реактора с сохранением DE контекста.
Entry:          PUSH DE
                LD DE, @ControlsFlightText.HyperWarmup
                CALL @Action.QueueTextItemBank1.Entry
                POP DE
                ; Выбор банка 1 для настоящего потребителя текстового окна.
                LD A, #11
                CALL @Action.SelectMemoryPage.Entry
                ; Подготовка 256 вызовов потребителя, начальный B=0 оборачивается через FF.
                LD B, #00
                ; Сохранение внешнего BC вокруг текстового ребёнка, внутренний повтор по CR не является новым вызовом цикла.
ConsumeLoop:    PUSH BC
                CALL @Controls.ConsumeTextQueue.Entry
                POP BC
                DJNZ @Action.PrepareHyperJumpRelay.ConsumeLoop

                ; Проверка Recognition.Value, только полный код FF удваивает число внешних ожиданий.
                LD A, (@ActionShipEquipment.Recognition.Value)
                INC A
                JP Z, @Action.PrepareHyperJumpRelay.LongDelay                   ; переход, если Recognition.Value равен FF, выбрать 128 внешних ожиданий

                ; Выбор 64 внешних ожиданий для остальных значений Recognition.Value.
                LD A, #40
                JP @Action.PrepareHyperJumpRelay.DelayOuter

                ; Выбор 128 внешних ожиданий при Recognition.Value=FF.
LongDelay:      LD A, #80
                ; Сохранение внешнего счётчика на время двух вложенных исходных байтовых ожиданий.
DelayOuter:     PUSH AF
                LD A, #FF
DelayMiddle:    LD B, #FF
DelayInner:     DJNZ @Action.PrepareHyperJumpRelay.DelayInner

                DEC A
                JP NZ, @Action.PrepareHyperJumpRelay.DelayMiddle                ; переход, если средний счётчик A ненулевой, повторить 255 внутренних DJNZ

                POP AF
                DEC A
                JP NZ, @Action.PrepareHyperJumpRelay.DelayOuter                 ; переход, если внешний счётчик A ненулевой, повторить полное ожидание

                ; Выбор банка 7 и теневого экрана перед очисткой базовых атрибутов и переносом загрузчика.
                LD BC, @Hardware.PagingPort
                LD A, #1F
                OUT (C), A
                ; Очистка 768 базовых атрибутов исходным перекрывающимся LDIR.
                LD HL, #5800
                LD DE, #5801
                LD BC, #02FF
                LD (HL), L
                LDIR
                ; Копирование 90 байтов кода и девятибайтового ключа ACTION в существующее окно 4200.
                LD HL, @ActionHyperReloadConst.CodeSource
                LD DE, #4200
                LD BC, @ActionHyperReloadConst.CopyLength
                LDIR
                ; Передача в копию загрузчика по 4200, исходный блок по 71CB не является местом исполнения этой стадии.
                JP @Action.ReloadActionAfterHyperJump.Entry

                endmodule
                endmodule
