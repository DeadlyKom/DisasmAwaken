                module Action
                module CompleteMissileLaunch
                ; Документация [запросы запуска ракет](../../Docs/ActionMissileRequests.md)
                ; -----------------------------------------
                ; Создание ракеты, поправка состояния по классу цели и последующее списание запаса
                ; исходная запись 17, перенесённое ядро банка 5, адреса 705D..7074
                ; In:
                ;   HL не задаёт аргумента, DE сохраняется на пути потерянной цели, C код допустимой записи цели, B сохраняется только на этом отказе
                ;   AF не задаёт условия допуска, общий вход сам не проверяет запас, Z и коды Target и не снимает захват
                ;   действуют договоры CreateMissileForTarget, ApplyIndexedDelta, SelectMissileStock и ConsumeMissileStock
                ;   банк 0 выбран, 7FFD не заблокирован, общая RAM и двадцать дополнительных байтов CPU-стека доступны, IRQ не вмешиваются
                ; Out:
                ;   CursorA получает EDA8 до вызова создания, это поток AY-канала A банка 0, фактического AY-вывода здесь нет
                ;   при потерянной цели HL=EDA8, DE и BC сохраняются, AF=8090, альтернативные регистры и IY сохраняются, передано сообщение F248
                ;   при отсутствии слота HL адрес выбранного поля запаса, DE=0040, B=1A, C код цели, AF=8042, IY маркер, AF'=01 и флаги вычислителя
                ;   при успехе ClassCode исходной цели определяет поправку полётного статуса, класс 10..FF поправки не вызывает
                ;   при успехе HL адрес заново выбранного счётчика, DE=0200 OR отображаемый остаток, A=10, F соответствует AND нового Preferred
                ;   при успехе B старый статус и C новый статус для класса 00..0F, иначе B класс цели и C её код
                ;   после расчёта HL', DE' и BC' содержат компоненты новой записи, при успехе AF'=1144, IY адрес новой записи
                ;   IX, I, IM и IFF сохраняются, SP=входной SP+2, после успеха четыре независимых запроса очереди переключают 7FFD на 11 и 10
                ;   запас и младший байт 9BD2 уменьшаются только после успешного создания, при отказе в слоте OUT отсутствует
                ; Corrupt:
                ;   HL, DE, BC и AF по пути, HL', DE', BC', AF' после расчёта, IY после поиска, R, рамка до двадцати байтов, CursorA, геометрическое состояние и кодовые операнды создания, новая запись, ссылка цели, State, запас, 9BD2, очередь, 7FFD
                ; Note:
                ;   DE после успешного создания указывает LinkedIndex цели, прибавление 7 даёт её ClassCode со смещением 12
                ;   при прямом входе с обоими нулевыми запасами успешное создание приводит к исходному переполнению Fallback из 00 в FF
                ;   при исчерпании Preferred сообщение может показать ненулевой Fallback, каждое сообщение независимо может быть отклонено очередью
                ;   Carry и Z после полного успеха относятся к финальному выбору запаса, они не служат флагом результата создания
                ;   полётный статус возвращается в сценарий штрафов станции, учтённый тоннаж при успехе уменьшает ConsumeMissileStock
                ;   нативное движение ракеты и последующее исполнение AY-потока этой проверкой не подтверждены
                ; -----------------------------------------
                ; -----------------------------------------
                ; Подготовка звука и создание ракеты
                ; Обновление потока AY-канала A в банке 0, это не текстовый курсор Controls банка 1.
Entry:          LD HL, @ActionMissileCreateConst.ActionSound
                LD (@ActionAyEffectState.CursorA), HL
                ; Создание записи и обратной ссылки цели, запас внутри CreateMissileForTarget не уменьшается.
                CALL @Action.CreateMissileForTarget.Entry
                RET NC                                                          ; выход, если цель потеряна или свободный слот не найден, боезапас сохранить

                ; -----------------------------------------
                ; Поправка состояния по классу исходной цели
                ; Расчёт адреса ClassCode цели, DE указывает её LinkedIndex, разность смещений равна 7.
                LD HL, FActionRecord.ClassCode - FActionRecord.LinkedIndex
                ADD HL, DE
                LD B, (HL)
                ; Обновление полётного статуса по классу исходной цели.
                CALL @Action.ApplyIndexedDelta.Entry
                ; -----------------------------------------
                ; Списание боезапаса после создания
                ; Выбор поля запаса заново перед двумя декрементами и четырьмя запросами очереди.
                CALL @Action.SelectMissileStock.Entry
                ; Продолжение без дополнительной рамки CALL, ConsumeMissileStock вернётся внешнему вызывающему коду.
                JP @Action.ConsumeMissileStock.Entry

                ; -----------------------------------------
                endmodule
                endmodule
