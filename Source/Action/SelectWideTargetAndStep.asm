                module Action
                module SelectWideTargetAndStep
                ; Документация [алгоритм и проверка](../../Docs/ActionSelectWideTarget.md)
                ; -----------------------------------------
                ; Выбор первой близкой широкой цели либо первой записи и обновление кодов текущего объекта
                ; исходная запись 17, перенесённое ядро 6000..7F8E, смещения #20DA..#20F3
                ; In:
                ;   HL, DE, BC, AF входных аргументов не задают
                ;   SeedIndex задаёт стабильное число 0..255 FActionWideVector от ActionWideVectors.Vector00, указанные записи читаемы
                ;   IX указывает текущую FActionRecord, для непустого списка выполнены предусловия StepRecordTowardWideVector
                ;   код и CheckThreeUpperWordsNear доступны, CPU-стек содержит внешний возврат, IRQ не вмешиваются
                ; Out:
                ;   при нулевом числе A=0, F=44, HL, DE, BC и альтернативные регистры сохраняются, IY=Vector00
                ;   при ненулевом числе IY указывает первый вектор с верхними signed16 от -60 до 59, иначе первый вектор списка
                ;   непустой путь передаёт выбранный IY в StepRecordTowardWideVector и наследует весь его результат и записи
                ;   IX сохранён, IY не восстанавливается, SP=входной SP+2, I, IM и IFF сохраняются
                ;   пустой путь не пишет RAM и порт, R получает 5 M1, непустой выполняет OUT 11 и 10, финальный 7FFD=10
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IY, R на непустом пути, AF, IY и R на пустом, память и страница по дочернему договору
                ; Note:
                ;   отсутствие близкого вектора при ненулевой длине не отменяет движение, исходный код возвращает IY к первой записи
                ;   путь полного отказа продолжает выполнение в следующем файле, жёсткий include (0), (1) обязателен
                ;   максимум 16 дополнительных байтов стека наследуется от дочерней цепочки, нового внешнего возврата не создаётся
                ;   74493 сценария проверили все значения счётчика, пустой список со всеми AF и 8192 смешанных списка
                ;   сопоставлены регистры кроме R непустого пути, записи и остаток стека, восемь банков RAM и настоящие порты
                ;   R непустого пути, полный набор списков, игровой предел числа целей, IRQ, точные T, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; Создание указателя начала списка, он устанавливается даже при нулевом числе целей.
Entry:          LD IY, @ActionWideVectors.Vector00
                ; Проверка числа широких целей в стабильном операнде SeedIndex.
                LD A, (@ControlsParameterTablesState.SeedIndex)
                OR A
                RET Z                                                           ; выход, если список пуст, оставить IY на первой физической записи

                ; Создание прохода по списку с шагом FActionWideVector.
                LD B, A
                LD DE, @FActionWideVector
                ; Поиск первой цели с тремя близкими верхними словами.
ScanNext:       CALL @Action.CheckThreeUpperWordsNear.Entry
                JR C, @Action.StepRecordTowardWideVector.Entry                  ; переход, если все три слова близки, обновить текущую запись относительно найденного IY

                ; Переход к следующей широкой цели после отказа предиката.
                ADD IY, DE
                DJNZ @Action.SelectWideTargetAndStep.ScanNext

                ; Восстановление первой цели при полном отсутствии близких, движение всё равно выполняется.
                LD IY, @ActionWideVectors.Vector00
                ; JP @Action.StepRecordTowardWideVector.Entry, продолжение в StepRecordTowardWideVector.asm

                endmodule
                endmodule
