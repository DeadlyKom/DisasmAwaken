                ; -----------------------------------------
                ; Восстановление CPU SP после вычисления рабочих компонент перед знаковым кодированием
                ; исходная запись 17, адреса 6C40..6C42
                ; In:
                ;   HL, DE, BC и AF содержат результат ComputePatchedVector, входной SP может быть арифметическим накопителем
                ;   SavedCpuSP заполнен действительным CPU SP с внешним возвратом, код доступен в фиксированном банке 5, IRQ не вмешивается
                ; Out:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX и IY сохраняются
                ;   SP получает SavedCpuSP, исполнение продолжается по 6C43 в EncodeSignedComponents без RET на этом участке
                ;   R получает один M1 с сохранением бита 7, RAM, I/IM/IFF и paging не меняются
                ; Corrupt:
                ;   SP и R
                ; Note:
                ;   (0) жёсткий порядок, следующая часть (1) EncodeSignedComponents.asm начинает с RET PE, стек нужен и при отказе вычислителя
                ;   проверены все 65536 слов сохранённого SP до первого чтения восстановленного стека, допустимость каждого тестового SP для последующего RET не заявляется
                ;   все регистры включая R, восемь банков RAM и отсутствие записей сопоставлены, отдельная память не выделяется
                ;   IRQ, точные T, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Восстановление CPU-стека
                ; Загрузка сохранённого SP до условного RET кодировщика, прежний арифметический SP не разыменовывается.
Entry:          LD SP, #0000
                ; JP @Action.EncodeSignedComponents.Entry, продолжение в EncodeSignedComponents.asm

