                module Action
                module UpdateRecordComponents
                ; Документация [алгоритм и проверка](../../Docs/ActionRecordUpdate.md)
                ; -----------------------------------------
                ; Обновление трёх компонент с проверкой переполнения и границы, обработкой отказа и запросом предупреждения о стыковке
                ; исходная запись 17, окно ACTION банка 0, смещения #85A0..#8654
                ; In:
                ;   HL - начальное слово масштаба, DE и AF числовых аргументов не задают, C сохраняется до возможного поиска класса 12
                ;   IX - FActionRecord в исходном массиве A100..A77F, компоненты доступны для чтения и записи, маркер 8080 достижим по A780
                ;   Base0..2 и Active0..2 задают слова выражения Component+Base-Active, вычитание оборачивается до проверки знакового сложения
                ;   SavedCpuSP содержит CPU SP с внешним возвратом, под ним доступны 18 временных байтов без пересечения с кодом и записями
                ;   при ClassCode=14 сохранены Original0..2 для RestoreHalvedOffsets, 9B82 разрешает проверку предупреждения при любом ненулевом значении
                ;   для запроса сообщения действуют договоры QueueTextItemBank1 и очереди Controls, банк 1 загружен, 7FFD не заблокирован
                ;   вход E5A0 выполняет четыре удвоения HL, внутренние Double3, Double2, Double1 и ComputeLimit выполняют три, два, одно либо ноль
                ;   выбран банк 0, IRQ не вмешивается во временный SP и общие изменяемые операнды
                ; Out:
                ;   HL - последняя вычисленная разность либо сумма, для класса 14 заменён Original2 общим восстановителем
                ;   DE - последнее прочитанное исходное слово компоненты, при поиске класса 12 D заменён на 12, E сохранён
                ;   без поиска и очистки B - рассчитанная граница, C сохранён, поиск без совпадения оставляет BC=0040
                ;   при найденном классе 12 B и C содержат нормализованные старшие байты его Component2 и Component1, при отказе класса 12 BC=0040
                ;   обычное завершение и отказ вне класса 12 дают A=ClassCode и F от CP 14, отказ класса 12 завершает очистку с AF=8042
                ;   HL', DE', BC', AF' и IX сохраняются, IY сохраняется без поиска и очистки, иначе указывает на найденную запись либо маркер
                ;   SP после внешнего RET равен SavedCpuSP+2, входной SP не восстанавливается, I/IM/IFF сохраняются, paging сохранён без запроса и равен 10 после запроса
                ;   принятые компоненты записаны последовательно, при отказе уже изменённые компоненты не откатываются, запись помечена для повторного использования
                ;   для класса 14 Active0..2 восстановлены, другие коды сохраняют эти слова, предупреждение меняет WarningLatch и может обновить очередь банка 1
                ; Corrupt:
                ;   HL, DE, BC, AF, IY при поиске либо очистке, R, SP
                ;   компоненты и поля пометки записей, два байта состояния при отказе класса 12, Active0..2 для класса 14
                ;   WarningLatch, очередь и курсор банка 1 при принятом сообщении, до 18 временных байтов CPU-стека и 7FFD при запросе
                ; Note:
                ;   (0) жёсткий порядок, после CALL очереди исполнение продолжается в FinishRecordWarning.asm, часть (1)
                ;   граница B=(125-H) AND FF вычислена после удвоений, проверяется нормализованный старший байт H для неотрицательных и FF-H для отрицательных сумм
                ;   при первом исходном старшем байте 80 проверки и изменения всех трёх компонент пропущены, но проверка предупреждения остаётся
                ;   переполнение проверяется только у ADC суммы исходной компоненты и уже обёрнутой разности Base-Active, исходное вычитание отдельно не проверяется
                ;   временный SP по IX читает POP и записывает PUSH в физические поля компонент, CPU SP восстанавливается до всех настоящих CALL
                ;   WarningLatch использует бит 7 как разрешение однократного запроса при входе в близкую область, значения 80 и 18 означают вооружённое и сброшенное состояния
                ;   при максимуме нормализованных старших байтов найденного класса 12 не меньше 8 защёлка получает 80, иначе прежний бит 7 разрешает запрос текста F3B9
                ;   текст Controls банка 1 сообщает о зоне стыковки со станцией и предлагает уменьшить скорость, принятие очередью не возвращается в регистрах
                ;   265026 сценариев проверили все слова каждой компоненты, все HL входа E5A0, пять входов, все коды класса и все 26 физических IX
                ;   исполнены настоящие обработчики отказа, поиск, восстановитель и межбанковая очередь, проверены регистры кроме R, все банки RAM, записи и OUT
                ;   полное произведение компонент и пар Base/Active, точный R, T, IRQ, сборка и нативный запуск не доказаны, единицы компонент пока не установлены
                ; -----------------------------------------
                ; -----------------------------------------
                ; Масштаб и граница допустимых компонент
                ; Расчёт четырёх удвоений для входа Entry, PrepareRecordScale может перейти внутрь этой цепи и оставить меньше удвоений.
Entry:          ADD HL, HL
Double3:        ADD HL, HL
Double2:        ADD HL, HL
Double1:        ADD HL, HL
                ; Расчёт байтовой границы LimitBias минус старший байт масштабированного HL с оборачиванием по модулю 256.
ComputeLimit:   LD A, @ActionRecordUpdateConst.LimitBias
                SUB H
                LD B, A
                ; -----------------------------------------
                ; Временный стек компонент
                ; Преобразование IX в SP без записи CPU-стека, POP и PUSH далее обращаются к реальным полям записи.
                LD A, IXL
                LD L, A
                LD A, IXH
                LD H, A
                LD SP, HL
                ; Чтение изменяемого непосредственного Base0, затем Active0 вычитается по модулю 65536.
LoadBase0:      LD HL, #0000
                LD DE, #0000
                ; Расчёт разности Base0-Active0 без входного Carry, переполнение этого вычитания отдельно не проверяется.
                OR A
                SBC HL, DE
                ; Чтение исходной Component0 через временный SP и проверка полного старшего байта 80.
                POP DE
                LD A, D
                CP @ActionReuseConst.ReusableHigh
                JR Z, @Action.UpdateRecordComponents.RestoreCpuSP               ; переход, если исходный старший байт Component0 равен 80, пропустить все изменения компонент

                ; Расчёт Component0 плюс уже обёрнутая разность, Carry сброшен перед ADC.
                AND A
                ADC HL, DE
                JP PE, @Action.RejectRecordUpdate.Entry                         ; переход, если сумма Component0 и разности вызвала знаковое переполнение, отклонить запись

                LD A, H
                JP P, @Action.UpdateRecordComponents.CheckBound0                ; переход, если сумма Component0 неотрицательна, сравнить её старший байт без инверсии

                ; Преобразование отрицательного старшего байта как FF-H, младший байт в проверке границы не участвует.
                CPL
                ; Проверка нормализованного старшего байта Component0 относительно исключённой границы B.
CheckBound0:    CP B
                JP NC, @Action.RejectRecordUpdate.Entry                         ; переход, если нормализованный старший байт Component0 не меньше B, отклонить запись

                ; Обновление принятой Component0 через PUSH, последующий отказ другой компоненты эту запись не откатывает.
                PUSH HL
                ; -----------------------------------------
                ; Вторая компонента
                ; Чтение Base1 и Active1, расчёт второй разности по модулю 65536.
LoadBase1:      LD HL, #0000
                LD DE, #0000
                OR A
                SBC HL, DE
                ; Переход временного SP от уже записанной Component0 к исходной Component1.
                INC SP
                INC SP
                POP DE
                ; Расчёт суммы Component1 и разности с нулевым входным Carry.
                AND A
                ADC HL, DE
                JP PE, @Action.RejectRecordUpdate.Entry                         ; переход, если сумма Component1 и разности вызвала знаковое переполнение, отклонить запись

                LD A, H
                JP P, @Action.UpdateRecordComponents.CheckBound1                ; переход, если сумма Component1 неотрицательна, сравнить старший байт без инверсии

                CPL
                ; Проверка той же границы B для нормализованного старшего байта Component1.
CheckBound1:    CP B
                JR NC, @Action.RejectRecordUpdate.Entry                         ; переход, если нормализованный старший байт Component1 не меньше B, отклонить запись

                ; Обновление принятой Component1 через временный SP, первая компонента уже записана.
                PUSH HL
                ; -----------------------------------------
                ; Третья компонента
                ; Чтение Base2 и Active2, расчёт третьей разности по модулю 65536.
LoadBase2:      LD HL, #0000
                LD DE, #0000
                OR A
                SBC HL, DE
                ; Переход временного SP к исходной Component2 после записи Component1.
                INC SP
                INC SP
                POP DE
                ; Расчёт суммы Component2 и разности с нулевым входным Carry.
                AND A
                ADC HL, DE
                JP PE, @Action.RejectRecordUpdate.Entry                         ; переход, если сумма Component2 и разности вызвала знаковое переполнение, отклонить запись

                LD A, H
                JP P, @Action.UpdateRecordComponents.CheckBound2                ; переход, если сумма Component2 неотрицательна, сравнить старший байт без инверсии

                CPL
                ; Проверка последней компоненты по той же исключённой границе B.
CheckBound2:    CP B
                JR NC, @Action.RejectRecordUpdate.Entry                         ; переход, если нормализованный старший байт Component2 не меньше B, отклонить запись

                ; Обновление принятой Component2, все три результата теперь находятся в записи.
                PUSH HL
                ; -----------------------------------------
                ; CPU-стек и разрешение предупреждения
                ; Восстановление действительного CPU SP из непосредственного операнда SavedCpuSP до первого настоящего CALL.
RestoreCpuSP:   LD SP, #0000
                ; Проверка полного неизвестного байта состояния, ноль отключает поиск записи класса 12.
                LD A, (@ActionParameterActivationState.UnknownByte1)
                AND A
                JP Z, @Action.RestoreHalvedOffsets.Entry                        ; переход, если UnknownByte1 равен нулю, завершить через восстановитель смещений

                ; Поиск первой активной записи TransferClass, это полный код 12, не маска битов.
                LD D, @ActionCloseRecordConst.TransferClass
                CALL @Action.FindRecordByCode.Entry
                JP Z, @Action.RestoreHalvedOffsets.Entry                        ; переход, если поиск класса 12 достиг маркера конца, завершить без предупреждения

                ; -----------------------------------------
                ; Близкая область относительно записи класса 12
                ; Расчёт нормализованного старшего байта Component2, отрицательные значения преобразуются как FF-H.
                LD A, (IY+FActionRecord.Components.Component2.High)
                OR A
                JP P, @Action.UpdateRecordComponents.HoldAbs2                   ; переход, если старший байт Component2 неотрицателен, сохранить его без инверсии

                CPL
HoldAbs2:       LD B, A
                ; Расчёт такого же старшего байта Component1 найденной записи.
                LD A, (IY+FActionRecord.Components.Component1.High)
                OR A
                JP P, @Action.UpdateRecordComponents.HoldAbs1                   ; переход, если старший байт Component1 неотрицателен, сохранить его без инверсии

                CPL
HoldAbs1:       LD C, A
                ; Расчёт нормализованного старшего байта Component0 найденной записи.
                LD A, (IY+FActionRecord.Components.Component0.High)
                OR A
                JP P, @Action.UpdateRecordComponents.MaxWithComp1               ; переход, если старший байт Component0 неотрицателен, сравнить его без инверсии

                CPL
                ; Расчёт максимума нормализованных Component0 и Component1.
MaxWithComp1:   CP C
                JR NC, @Action.UpdateRecordComponents.MaxWithComp2              ; переход, если нормализованный Component0 не меньше Component1, сохранить текущий максимум

                LD A, C
                ; Расчёт максимума всех трёх нормализованных старших байтов с учётом Component2.
MaxWithComp2:   CP B
                JR NC, @Action.UpdateRecordComponents.CheckNearLimit            ; переход, если текущий максимум не меньше Component2, сохранить текущий максимум

                LD A, B
                ; Проверка близкой области, все три нормализованных старших байта должны быть меньше NearLimit.
CheckNearLimit: CP @ActionRecordUpdateConst.NearLimit
                JR C, @Action.UpdateRecordComponents.CheckWarning               ; переход, если максимум меньше NearLimit, проверить разрешение однократного предупреждения

                ; Обновление WarningLatch значением WarningArmed за пределами близкой области, следующий вход внутрь сможет запросить сообщение.
                LD A, @ActionRecordUpdateConst.WarningArmed
                LD (@ActionRecordUpdateState.WarningLatch), A
                JR @Action.RestoreHalvedOffsets.Entry

                ; -----------------------------------------
                ; Защёлка предупреждения о стыковке
                ; Проверка бита 7 существующего непосредственного операнда, остальные семь битов не являются подтверждёнными независимыми флагами.
CheckWarning:   LD A, #00
                AND A
                JP P, @Action.RestoreHalvedOffsets.Entry                        ; переход, если бит 7 WarningLatch сброшен, завершить без повторного запроса сообщения

                ; Обновление WarningLatch значением WarningSent до вызова очереди, отказ очереди не возвращает вооружённое состояние.
                LD A, @ActionRecordUpdateConst.WarningSent
                LD (@ActionRecordUpdateState.WarningLatch), A
                ; Сохранение DE перед его заменой на адрес текста, парный POP расположен в FinishRecordWarning.asm.
                PUSH DE
                ; Поиск текста по адресу DockingText в Controls банка 1, строка сообщает о зоне стыковки и уменьшении скорости.
                LD DE, @ActionRecordUpdateConst.DockingText
                ; Запрос вывода через настоящий межбанковый производитель, очередь может молча отказать при заполнении.
                CALL @Action.QueueTextItemBank1.Entry
                ; JP @Action.FinishRecordWarning.Entry, продолжение в FinishRecordWarning.asm

                ; -----------------------------------------
                endmodule
                endmodule
