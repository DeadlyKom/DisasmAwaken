                module Action
                module SubtractScaledWorkVector
                ; Документация [алгоритм и проверка](../../Docs/ActionSubtractWorkVector.md)
                ; -----------------------------------------
                ; Вычитание трёх знаковых масштабированных слов из рабочего 24-битного вектора до первого переполнения
                ; исходная запись 17, банк 5, перенесённое ядро ACTION 6000..7F8E, вычитаемые операнды доступны в банке 0, смещения #090F..#0963
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, входной B сохраняется
                ;   ActionWorkVector.Value содержит три физические знаковые 24-битные компоненты в дополнительном коде
                ;   ActionScaledVectorState.Component0/1/2 содержат три знаковых слова в операндах кода, выбран банк 0
                ;   CPU-стек содержит внешний возврат и не пересекает рабочий вектор, код и операнды доступны, IRQ не вмешиваются
                ; Out:
                ;   HL содержит младшее слово результата последней обработанной компоненты, DE содержит соответствующее вычитаемое слово
                ;   B сохранён, C=FF для отрицательного вычитаемого либо 00 для неотрицательного
                ;   A содержит вычисленный старший байт последней попытки, F соответствует SBC этого байта с расширением знака и заёмом младшего слова
                ;   P/V установлен при переполнении signed24, тогда старший байт текущей компоненты и все следующие компоненты сохраняются, младшее слово текущей уже записано
                ;   при P/V=0 обновлены все три компоненты, на любом выходе обработанные до текущей компоненты уже полностью записаны
                ;   HL', DE', BC', AF', IX, IY, I, IM, IFF и страница сохраняются, SP=входной SP+2
                ;   R получает 14 M1 на попытку компоненты, ещё один M1 при отрицательном вычитаемом, один при записи старшего байта и один на последний безусловный RET
                ; Corrupt:
                ;   HL, DE, C, AF, R, младшие слова достигнутых компонент и старшие байты только успешных попыток
                ; Note:
                ;   расширение знака вычитаемого происходит до 24 бит, точный знаковый результат вне -8388608..8388607 вызывает ранний RET PE
                ;   процедура не является атомарным обновлением вектора, частичная запись при переполнении является исходным поведением
                ;   существующий CPU-стек только читается для RET, CALL, PUSH, записи в порты и переключения банков отсутствуют
                ;   671232 сценария сопоставляют регистры включая R, восемь банков RAM и кратность всех записей, полный набор троек не исчерпан
                ;   дробный масштаб и игровой смысл рабочего вектора за пределами установленных писателей и потребителей не выдумываются, IRQ, точные такты, сборка и нативный запуск не проверены
                ; -----------------------------------------
                ; Чтение рабочей компоненты 0 и соответствующего масштабированного вычитаемого из существующего операнда кода.
Entry:          LD HL, (@ActionWorkVector.Value.Component0.LowWord)
                LD A, (@ActionWorkVector.Value.Component0.High)
                LD DE, (@ActionScaledVectorState.Component0)
                ; Проверка знака вычитаемого, старший байт расширения C должен стать 00 либо FF.
                BIT 7, D
                LD C, #00
                JR Z, @Action.SubtractScaledWorkVector.Subtract0                ; переход, если вычитаемое неотрицательно, сохранить нулевое расширение знака в C

                DEC C
                ; Расчёт младших шестнадцати бит разности без входного займа, исходный Carry отбрасывается.
Subtract0:      OR A
                SBC HL, DE
                ; Запись младшего слова до проверки signed24 overflow, даже ранний выход не отменит эту запись.
                LD (@ActionWorkVector.Value.Component0.LowWord), HL
                ; Расчёт старшего байта с расширением знака и заёмом младшего слова, P/V проверяет переполнение всего signed24.
                SBC A, C
                RET PE                                                          ; выход, если знаковый 24-битный результат переполнен, старший байт и следующие компоненты не записывать

                ; Запись старшего байта только после успешной проверки, предыдущие компоненты уже полностью обновлены.
                LD (@ActionWorkVector.Value.Component0.High), A
                ; Чтение рабочей компоненты 1 и соответствующего масштабированного вычитаемого из существующего операнда кода.
                LD HL, (@ActionWorkVector.Value.Component1.LowWord)
                LD A, (@ActionWorkVector.Value.Component1.High)
                LD DE, (@ActionScaledVectorState.Component1)
                ; Проверка знака вычитаемого, старший байт расширения C должен стать 00 либо FF.
                BIT 7, D
                LD C, #00
                JR Z, @Action.SubtractScaledWorkVector.Subtract1                ; переход, если вычитаемое неотрицательно, сохранить нулевое расширение знака в C

                DEC C
                ; Расчёт младших шестнадцати бит разности без входного займа, исходный Carry отбрасывается.
Subtract1:      OR A
                SBC HL, DE
                ; Запись младшего слова до проверки signed24 overflow, даже ранний выход не отменит эту запись.
                LD (@ActionWorkVector.Value.Component1.LowWord), HL
                ; Расчёт старшего байта с расширением знака и заёмом младшего слова, P/V проверяет переполнение всего signed24.
                SBC A, C
                RET PE                                                          ; выход, если знаковый 24-битный результат переполнен, старший байт и следующие компоненты не записывать

                ; Запись старшего байта только после успешной проверки, предыдущие компоненты уже полностью обновлены.
                LD (@ActionWorkVector.Value.Component1.High), A
                ; Чтение рабочей компоненты 2 и соответствующего масштабированного вычитаемого из существующего операнда кода.
                LD HL, (@ActionWorkVector.Value.Component2.LowWord)
                LD DE, (@ActionScaledVectorState.Component2)
                LD A, (@ActionWorkVector.Value.Component2.High)
                ; Проверка знака вычитаемого, старший байт расширения C должен стать 00 либо FF.
                BIT 7, D
                LD C, #00
                JR Z, @Action.SubtractScaledWorkVector.Subtract2                ; переход, если вычитаемое неотрицательно, сохранить нулевое расширение знака в C

                DEC C
                ; Расчёт младших шестнадцати бит разности без входного займа, исходный Carry отбрасывается.
Subtract2:      OR A
                SBC HL, DE
                ; Запись младшего слова до проверки signed24 overflow, даже ранний выход не отменит эту запись.
                LD (@ActionWorkVector.Value.Component2.LowWord), HL
                ; Расчёт старшего байта с расширением знака и заёмом младшего слова, P/V проверяет переполнение всего signed24.
                SBC A, C
                RET PE                                                          ; выход, если знаковый 24-битный результат переполнен, старший байт и следующие компоненты не записывать

                ; Запись старшего байта только после успешной проверки, предыдущие компоненты уже полностью обновлены.
                LD (@ActionWorkVector.Value.Component2.High), A
                RET

                endmodule
                endmodule
