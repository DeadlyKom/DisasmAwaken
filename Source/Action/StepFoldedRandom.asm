                module Action
                module StepFoldedRandom
                ; Документация [алгоритм и проверка](../../Docs/ActionFoldedRandom.md)
                ; -----------------------------------------
                ; Обновление трёхбайтового состояния свёрткой переносов и возврат нового 16-битного слова через обратный EXX
                ; исходная запись 17, окно ACTION банка 0, смещения #8C08..#8C53
                ; In:
                ;   HL - адрес FFoldedRandomState, LowWord занимает первые два байта, FoldByte третий, запись не оборачивается в ROM
                ;   DE, BC и AF основного набора входных числовых аргументов не задают
                ;   HL' числового аргумента не задаёт, DE' и BC' станут основными DE и BC после обратного EXX, AF' сохраняется
                ;   в окне C000 выбран банк 0 с ядром ACTION, SP указывает внешний возврат и имеет два свободных байта ниже него
                ;   состояние и стек не пересекаются с исполняемым кодом и друг с другом, IRQ не вмешивается в общий контекст
                ; Out:
                ;   HL - новый LowWord, DE равен входному альтернативному DE', BC равен входному альтернативному BC'
                ;   A - новый FoldByte, F от последнего SBC A,00, его заём равен сравнению младшего смешанного слова n с временным t
                ;   HL' - исходный адрес состояния, DE' - новый LowWord, B'=0, C' - младший байт промежуточного n, AF' сохранён
                ;   IX и IY, I/IM/IFF и paging сохраняются, SP после RET равен входному SP+2
                ;   R увеличен на 63 M1 в младших семи разрядах с сохранением старшего разряда
                ;   LowWord и FoldByte обновлены по рекурсии со свёрткой, два байта ниже SP содержат новый LowWord после передачи PUSH DE и POP HL
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', R, три байта состояния и два временных байта CPU-стека
                ; Note:
                ;   первая низкая смесь n=(75*w-64) modulo 65536, FoldByte накапливает число переносов и popcount верхних шести битов (w-1) modulo 65536
                ;   два последующих вычитания сворачивают старший байт и обе части n, точные заёмы и формула приведены в документации
                ;   последний DEC HL изменяет только младшее слово, заём в FoldByte не передаётся
                ;   LD E,A перед шестью удвоениями не влияет на конечную формулу, после EX DE,HL прежнее DE полностью перекрывается, исходная инструкция сохранена
                ;   при прямом входе ядро меняет роли основных и альтернативных DE и BC, пятнадцать внешних входов заранее выполняют EXX и восстанавливают вызывающий контекст
                ;   218383 сценариев проверили все младшие слова при трёх FoldByte, все FoldByte на границах, ядро и все пятнадцать внешних входов, регистры включая R, RAM и кратность записей
                ;   полный 24-битный домен, период, равномерность, игровые роли отдельных потоков, точные T, IRQ и нативное использование не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Чтение физического состояния
                ; Получение LowWord в BC и FoldByte в A, курсор третьего байта сохраняется до записи результата.
Entry:          LD C, (HL)
                INC HL
                LD B, (HL)
                INC HL
                LD A, (HL)
                PUSH HL
                LD E, A
                LD H, B
                LD L, C
                ; Расчёт u=(LowWord-1) modulo 65536, нулевое слово оборачивается без изменения FoldByte.
                DEC HL
                ; -----------------------------------------
                ; Первая низкая смесь и свёртка переносов
                ; Шесть удвоений дают 64*u modulo 65536, каждый вытесненный старший бит добавляется к FoldByte без удвоения самого FoldByte.
                ADD HL, HL
                ADC A, #00
                ADD HL, HL
                ADC A, #00
                ADD HL, HL
                ADC A, #00
                ADD HL, HL
                ADC A, #00
                ADD HL, HL
                ADC A, #00
                ADD HL, HL
                ADC A, #00
                ; Сохранение первой низкой части, промежуточное старое DE будет целиком заменено исходным LowWord.
                EX DE, HL
                LD H, B
                LD L, C
                ; Расчёт 8*LowWord modulo 65536, переносы этих трёх удвоений не добавляются к FoldByte.
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ; Объединение двух низких частей с накоплением одного переноса в FoldByte.
                ADD HL, DE
                ADC A, #00
                ; Добавление трёх LowWord с отдельным учётом переносов, итоговая низкая часть равна (75*w-64) modulo 65536.
                ADD HL, BC
                ADC A, #00
                ADD HL, BC
                ADC A, #00
                ADD HL, BC
                ADC A, #00
                ; -----------------------------------------
                ; Свёртка байтов и заём
                ; Сохранение n и создание слова из FoldByte и старшего байта n, младший байт n выбирается как вычитаемое.
                LD D, H
                LD E, L
                LD L, H
                LD H, A
                LD B, #00
                LD C, E
                ; Расчёт временного t=256*k+старший байт n-младший байт n, входной Carry предварительно очищается.
                OR A
                SBC HL, BC
                ; Перенос заёма первого вычитания в старший FoldByte.
                SBC A, #00
                EX DE, HL
                ; Расчёт второй разности n-t с независимым очищенным входным Carry.
                OR A
                SBC HL, DE
                ; Получение нового FoldByte с заёмом второй разности, эти флаги остаются выходными.
                SBC A, #00
                ; Завершающее уменьшение только низкого слова modulo 65536, его заём не меняет FoldByte.
                DEC HL
                EX DE, HL
                ; -----------------------------------------
                ; Обновление записи и возврат слова
                ; Восстановление курсора FoldByte и запись всех трёх исходных физических полей в прежнем порядке.
                POP HL
                LD (HL), A
                DEC HL
                LD (HL), D
                DEC HL
                LD (HL), E
                ; Передача нового LowWord в другой набор через CPU-стек, EXX возвращает вызывающий контекст.
                PUSH DE
                EXX
                POP HL
                RET

                ; -----------------------------------------
                endmodule
                endmodule
