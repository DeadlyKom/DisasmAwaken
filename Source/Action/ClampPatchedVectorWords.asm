                module Action
                module ClampPatchedVectorWords
                ; Документация [алгоритм и проверка](../../Docs/ActionClampVectorWords.md)
                ; -----------------------------------------
                ; Сведение трёх изменяемых 32-битных значений к словам с исходным насыщением и знаком по биту 23
                ; исходная запись 17, перенесённое ядро 6000..7F8E, смещения #214B..#21B2
                ; In:
                ;   HL, DE, BC, AF входных аргументов не задают
                ;   FirstHigh/Low, SecondHigh/Low, ThirdHigh/Low содержат три 32-битных значения в операндах LD DE/HL
                ;   операнды стабильны на протяжении вызова, перенесённый код и AbsSigned32 доступны
                ;   CPU-стек допускает шесть дополнительных байтов и содержит внешний возврат, IRQ не вмешиваются
                ; Out:
                ;   HL, DE, BC содержат результаты для первой, второй, третьей компонент соответственно
                ;   для каждого signed32 вычислен модуль по модулю 2^32, модуль от 8000 заменён на 7F00
                ;   затем слово отрицается по модулю 2^16 при исходном бите 23, это не проверка знакового бита 31
                ;   AF определяется третьей компонентой, точные формулы приведены в документации, Carry всегда сброшен
                ;   HL', DE', BC', AF', IX, IY сохраняются, SP=входной SP+2, I, IM, IFF и страница сохраняются
                ;   кроме временных шести байтов CPU-стека RAM не записывается, R имеет точную формулу в документации
                ; Corrupt:
                ;   HL, DE, BC, AF, R, шесть временных байтов CPU-стека
                ; Note:
                ;   порог 8000 и подстановка 7F00 сохранены буквально, минимальный signed32 также попадает под насыщение
                ;   знак читается по младшему байту исходного старшего слова, необычный выбор бита 23 не исправлен
                ;   нулевые литералы LD DE/HL являются исходными изменяемыми операндами, их писатели находятся в StepRecordTowardWideVector
                ;   666296 сценариев проверили реальные три вызова AbsSigned32, все младшие слова при старших 0/FFFF и все старшие слова
                ;   проверены регистры включая R, кратность записей, остаток CPU-стека и все восемь банков RAM
                ;   полное произведение трёх dword, аппаратный порядок байтов записи, IRQ, точные T, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; Чтение первого значения из изменяемых операндов FirstHigh и FirstLow.
Entry:          LD DE, #0000
                LD HL, #0000
                ; Расчёт модуля полного DE:HL с исходной особенностью минимального signed32.
                CALL @Action.AbsSigned32.Entry
                ; Проверка модуля на превышение 7FFF по верхнему слову и биту 15 нижнего.
                LD A, H
                AND @ActionClampWordsConst.HighMask
                OR D
                OR E
                JR Z, @Action.ClampPatchedVectorWords.SaveFirst                 ; переход, если модуль не больше 7FFF, сохранить младшее слово без насыщения

                ; Подстановка исходного насыщения 7F00, более высокое значение 7FFF не используется.
                LD HL, @ActionClampWordsConst.Saturation
                ; Сохранение модуля на CPU-стеке до завершения следующих компонент.
SaveFirst:      PUSH HL
                ; Чтение второго значения из изменяемых операндов SecondHigh и SecondLow.
                LD DE, #0000
                LD HL, #0000
                ; Расчёт модуля полного DE:HL с исходной особенностью минимального signed32.
                CALL @Action.AbsSigned32.Entry
                ; Проверка модуля на превышение 7FFF по верхнему слову и биту 15 нижнего.
                LD A, H
                AND @ActionClampWordsConst.HighMask
                OR D
                OR E
                JR Z, @Action.ClampPatchedVectorWords.SaveSecond                ; переход, если модуль не больше 7FFF, сохранить младшее слово без насыщения

                ; Подстановка исходного насыщения 7F00, более высокое значение 7FFF не используется.
                LD HL, @ActionClampWordsConst.Saturation
                ; Сохранение модуля на CPU-стеке до завершения следующих компонент.
SaveSecond:     PUSH HL
                ; Чтение третьего значения из изменяемых операндов ThirdHigh и ThirdLow.
                LD DE, #0000
                LD HL, #0000
                ; Расчёт модуля полного DE:HL с исходной особенностью минимального signed32.
                CALL @Action.AbsSigned32.Entry
                ; Проверка модуля на превышение 7FFF по верхнему слову и биту 15 нижнего.
                LD A, H
                AND @ActionClampWordsConst.HighMask
                OR D
                OR E
                JR Z, @Action.ClampPatchedVectorWords.CollectWords              ; переход, если модуль не больше 7FFF, сохранить младшее слово без насыщения

                ; Подстановка исходного насыщения 7F00, более высокое значение 7FFF не используется.
                LD HL, @ActionClampWordsConst.Saturation
                ; Преобразование временных модулей в окончательный порядок HL, DE, BC.
CollectWords:   LD B, H
                LD C, L
                POP DE
                POP HL
                ; Проверка бита 23 исходной первой компоненты по младшему байту FirstHigh.
                LD A, (@ActionClampVectorWordsState.FirstHigh)
                OR A
                JP P, @Action.ClampPatchedVectorWords.SignSecond                ; переход, если исходный бит 23 первой компоненты нулевой, сохранить положительное слово

                ; Расчёт отрицательного первого слова по модулю 65536.
                LD A, L
                CPL
                LD L, A
                LD A, H
                CPL
                LD H, A
                INC HL
                ; Проверка бита 23 исходной второй компоненты по младшему байту SecondHigh.
SignSecond:     LD A, (@ActionClampVectorWordsState.SecondHigh)
                OR A
                JP P, @Action.ClampPatchedVectorWords.SignThird                 ; переход, если исходный бит 23 второй компоненты нулевой, сохранить положительное слово

                ; Расчёт отрицательного второго слова по модулю 65536.
                LD A, E
                CPL
                LD E, A
                LD A, D
                CPL
                LD D, A
                INC DE
                ; Проверка бита 23 исходной третьей компоненты по младшему байту ThirdHigh.
SignThird:      LD A, (@ActionClampVectorWordsState.ThirdHigh)
                OR A
                RET P                                                           ; выход, если исходный бит 23 третьей компоненты нулевой, сохранить положительное слово

                ; Расчёт отрицательного третьего слова, конечные флаги остаются после последнего CPL.
                LD A, C
                CPL
                LD C, A
                LD A, B
                CPL
                LD B, A
                INC BC
                RET

                endmodule
                endmodule
