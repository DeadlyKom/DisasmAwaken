                module Action
                module CheckThreeUpperWordsNear
                ; Документация [алгоритм и проверка](../../Docs/ActionFoldedNearWords.md)
                ; -----------------------------------------
                ; Проверка трёх знаковых верхних слов на диапазон от минус 60 до 59
                ; исходная запись 17, перенесённое ядро 6000..7F8E, смещения #0C66..#0CAA
                ; In:
                ;   HL, DE, BC, AF входных аргументов не задают
                ;   IY указывает доступные слова little-endian по смещениям 2, 6, 10, старшие байты по 3, 7, 11
                ;   перенесённый ACTION доступен, CPU-стек содержит внешний возврат, IRQ не вмешиваются
                ; Out:
                ;   Carry установлен тогда и только тогда, когда все три слова как signed16 лежат от -60 до 59 включительно
                ;   HL содержит последнее проверенное слово, отрицательное слово преобразовано через XOR FFFF без прибавления единицы
                ;   DE, BC сохраняются, A равен ненулевому H при раннем отказе по H либо L при сравнении с 60
                ;   F задан OR H при отказе по H либо CP 60 при сравнении младшего байта, Z не является признаком успеха
                ;   HL', DE', BC', AF', IX, IY сохраняются, SP=входной SP+2, I, IM, IFF и страница сохраняются
                ;   RAM и CPU-стек не записываются, R увеличивается по формуле в документации с сохранением бита 7
                ; Corrupt:
                ;   HL, AF, R
                ; Note:
                ;   слова проверяются по порядку, отказ по одному слову не читает следующие компоненты
                ;   инверсия даёт -x-1 для отрицательного signed16, поэтому -60 проходит, а +60 не проходит
                ;   два младших байта каждой четырёхбайтовой компоненты не читаются, единицы координат и полный смысл списка здесь не установлены
                ;   401920 сценариев проверили все значения каждого слова, все входные AF для трёх типов выхода и смешанные слова
                ;   сопоставлены регистры включая R, отсутствие записей и восемь банков RAM, полное произведение трёх слов не перебиралось
                ;   IRQ, точные T, сборка и нативный запуск не выполнялись
                ; -----------------------------------------
                ; Чтение первого верхнего слова, два младших байта компоненты не участвуют.
Entry:          LD H, (IY + @ActionNearWordsConst.Upper0High)
                LD L, (IY + @ActionNearWordsConst.Upper0Low)
                ; Проверка знака слова перед свёрткой отрицательной половины диапазона.
                BIT @ActionNearWordsConst.SignBit, H
                JR Z, @Action.CheckThreeUpperWordsNear.CheckFirst               ; переход, если слово неотрицательное, проверить его без инверсии

                ; Расчёт -слово-1 инверсией двух байтов, прибавления единицы в оригинале нет.
                LD A, H
                CPL
                LD H, A
                LD A, L
                CPL
                LD L, A
                ; Проверка старшего байта свёрнутого слова, ненулевой байт уже исключает близость.
CheckFirst:     LD A, H
                OR A
                RET NZ                                                          ; выход, если старший байт ненулевой, вернуть Carry=0

                ; Проверка младшего байта на строгую границу 60.
                LD A, L
                CP @ActionNearWordsConst.Limit
                RET NC                                                          ; выход, если свёрнутое слово не меньше 60, вернуть Carry=0

                ; Чтение второго верхнего слова, два младших байта компоненты не участвуют.
                LD H, (IY + @ActionNearWordsConst.Upper1High)
                LD L, (IY + @ActionNearWordsConst.Upper1Low)
                ; Проверка знака слова перед свёрткой отрицательной половины диапазона.
                BIT @ActionNearWordsConst.SignBit, H
                JR Z, @Action.CheckThreeUpperWordsNear.CheckSecond              ; переход, если слово неотрицательное, проверить его без инверсии

                ; Расчёт -слово-1 инверсией двух байтов, прибавления единицы в оригинале нет.
                LD A, H
                CPL
                LD H, A
                LD A, L
                CPL
                LD L, A
                ; Проверка старшего байта свёрнутого слова, ненулевой байт уже исключает близость.
CheckSecond:    LD A, H
                OR A
                RET NZ                                                          ; выход, если старший байт ненулевой, вернуть Carry=0

                ; Проверка младшего байта на строгую границу 60.
                LD A, L
                CP @ActionNearWordsConst.Limit
                RET NC                                                          ; выход, если свёрнутое слово не меньше 60, вернуть Carry=0

                ; Чтение третьего верхнего слова, два младших байта компоненты не участвуют.
                LD H, (IY + @ActionNearWordsConst.Upper2High)
                LD L, (IY + @ActionNearWordsConst.Upper2Low)
                ; Проверка знака слова перед свёрткой отрицательной половины диапазона.
                BIT @ActionNearWordsConst.SignBit, H
                JR Z, @Action.CheckThreeUpperWordsNear.CheckThird               ; переход, если слово неотрицательное, проверить его без инверсии

                ; Расчёт -слово-1 инверсией двух байтов, прибавления единицы в оригинале нет.
                LD A, H
                CPL
                LD H, A
                LD A, L
                CPL
                LD L, A
                ; Проверка старшего байта свёрнутого слова, ненулевой байт уже исключает близость.
CheckThird:     LD A, H
                OR A
                RET NZ                                                          ; выход, если старший байт ненулевой, вернуть Carry=0

                ; Проверка младшего байта на строгую границу 60.
                LD A, L
                CP @ActionNearWordsConst.Limit
                RET

                endmodule
                endmodule
