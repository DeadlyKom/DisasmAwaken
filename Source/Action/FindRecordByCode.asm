                module Action
                module FindRecordByCode
                ; Документация [алгоритм и проверка](../../Docs/ActionRecordIterator.md)
                ; -----------------------------------------
                ; Поиск от A100 первой активной записи с байтом 12 равным входному D
                ; исходная запись 17, код ACTION банка 0, адрес E98D, смещения #898D..#89A0
                ; In:
                ;   HL и DE сохраняются, D требуемый полный байтовый код по смещению 12, BC и AF аргументов не задают
                ;   действует договор NextActiveRecord, записи с шагом 64 от A100, достижимы совпадение либо маркер конца
                ;   CPU-стек имеет два дополнительных байта, IRQ не вмешиваются
                ; Out:
                ;   HL и DE сохраняются, BC=0040, IY найденная запись либо маркер конца
                ;   при маркере A=80, F=42, Z установлен
                ;   при совпадении A=(D+1) по модулю 256, F соответствует INC D с Carry=0
                ;   найденный D=FF возвращает A=0 и Z установленным, для найденных D=00..FE Z сброшен
                ;   HL', DE', BC', AF', IX, I, IM и IFF сохраняются, SP=входной SP+2
                ;   R получает 3 M1 подготовки, суммы стоимостей детей и по 6 M1 за несовпадение, 8 M1 за совпадение либо 2 M1 за маркер
                ; Corrupt:
                ;   BC, AF, IY, R, два байта CPU-стека
                ; Note:
                ;   дочерний итератор исполняется настоящим CALL, данные записей не меняются
                ;   Z не является однозначным признаком маркера для входного D=FF, дополнительного отказа для этого кода в оригинале нет
                ;   код по смещению 12 сравнивается целиком, соответствие всем игровым классам пока не доказано
                ; -----------------------------------------
                ; Подготовка поиска с шагом 64, первый вызов проверяет запись A100.
Entry:          LD IY, #A0C0
                LD BC, #0040
                ; -----------------------------------------
                ; Поиск следующей активной записи или маркера
FindNext:       CALL @Action.NextActiveRecord.Entry
                RET Z                                                           ; выход, если дочерний итератор достиг маркера конца, совпадение кода не проверяется

                ; Проверка полного кода байта 12 с требуемым D, игровые значения кодов здесь не угадываются.
                LD A, (IY + FActionRecord.ClassCode)
                CP D
                JP NZ, @Action.FindRecordByCode.FindNext                        ; переход, если код записи не равен D, искать следующую активную запись

                ; Расчёт результата совпадения D+1, исходный D=FF даёт ноль и Z даже при найденной записи.
                INC A
                RET

                ; -----------------------------------------
                endmodule
                endmodule
