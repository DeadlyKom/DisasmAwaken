                module Action
                module DrawBankedGauge
                ; Документация [алгоритм и проверка](../../Docs/ActionGaugeWrapper.md)
                ; -----------------------------------------
                ; Выбор банка 1, вывод шестистрочной шкалы и обязательный выбор банка 0
                ; исходная запись 17, банк 5, перенесённое ядро ACTION #6000..#7F8E, смещения #0876..#0885
                ; In:
                ;   HL адрес верхнего байта шкалы, DE и BC числовых аргументов не задают
                ;   A значение шкалы, AF передаётся в DrawSixRowGauge после восстановления обменом
                ;   код ACTION находится в общей RAM, верхний банк 1 содержит CONTROL, блокировка записи 7FFD сброшена
                ;   действуют условия DrawSixRowGauge для шести строк, таблицы и неперекрывающихся областей записи
                ;   внешний возврат и четыре дополнительных байта CPU-стека находятся в общей RAM, IRQ не вмешиваются
                ; Out:
                ;   HL, DE и BC соответствуют DrawSixRowGauge, A=10, F соответствует результату шкалы
                ;   HL', DE' и BC', IX, IY, I, IM и IFF сохраняются, AF' соответствует результату шкалы
                ;   SP=входной SP+2, R увеличивается на стоимость шкалы и ещё 20 M1
                ;   порт 7FFD последовательно получает 11 и 10, на выходе выбран банк 0, экран банка 5 и ROM 1
                ;   шкала записана в физических банках, выбранных при конфигурации 11, общие банки 5 и 2 сохраняют своё размещение
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', R, выходные байты шкалы, четыре байта CPU-стека, аппаратный регистр 7FFD
                ; Note:
                ;   максимальная глубина дополнительной рамки равна четырём байтам, два CALL селектора временно сохраняют BC
                ;   последние два сохранённых байта BC содержат B=00 и эффективное значение шкалы, это не изменение внешнего возврата
                ;   разбор обёртки композиционный, DrawSixRowGauge и SelectMemoryPage имеют отдельные независимые проверки
                ;   состояние программного зеркала порта не обновляется, заблокированный 7FFD находится вне объявленного контракта
                ; -----------------------------------------
                ; Сохранение входного AF перед выбором банка с кодом CONTROL.
Entry:          EX AF, AF'
                ; Выбор банка 1 при экране банка 5 и ROM 1, аппаратная блокировка должна быть сброшена.
                LD A, #11
                CALL @Action.SelectMemoryPage.Entry
                ; Восстановление исходного значения шкалы и вызов доказанного шестистрочного вывода.
                EX AF, AF'
                CALL @Controls.DrawSixRowGauge.Entry
                ; Выбор банка 0 после вывода, F и результат остальных регистров шкалы сохраняются селектором.
                LD A, #10
                CALL @Action.SelectMemoryPage.Entry
                RET

                endmodule
                endmodule
