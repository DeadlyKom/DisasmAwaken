                module Action
                module SqrtWordCached
                ; Документация [алгоритм и проверка](../../Docs/ActionCachedRoot.md)
                ; -----------------------------------------
                ; Целый корень в области 0000..E8FF и исходное особое поведение E900..FFFF по трём страницам таблиц
                ; исходная запись 17, общая RAM ACTION фиксированного банка 2, смещения #50E9..#516E
                ; In:
                ;   HL - сохраняемое в DE слово только для ветви D=0, DE - беззнаковый вход 0000..FFFF, BC и AF аргументов не задают
                ;   в окне C000 выбран банк 1 с исходными тремя страницами C000..C2FF, код B0E9..B16E доступен в фиксированном банке 2
                ;   CPU-стек содержит внешний возврат, IRQ не вмешивается
                ; Out:
                ;   HL - последний пробный остаток по модулю 65536, при входном D=0 DE получает входной HL, иначе DE сохраняется
                ;   BC - отрицательная нечётная разность последней пробы
                ;   для DE=0000..E8FF A=floor(sqrt(входной DE)), для DE=E900..FFFF A=261-floor(sqrt(входной DE AND FF00))
                ;   F от последнего ADD HL,BC при выходе по заёму либо от последнего INC A при исчерпании развёрнутых проб
                ;   HL', DE', BC' сохраняются, при D=0 AF' сохраняется, иначе A'=байт страницы C1 по входному D, F'=80 либо 81 по переносу подготовки разности
                ;   IX и IY, I/IM/IFF и paging сохраняются, SP после RET равен входному SP+2
                ;   R получает 8+5*A M1 для малого слова с A<15, 80 M1 для A=15, 25+5*k M1 для табличного отказа после k успешных проб либо 52 M1 для шести успешных проб
                ;   бит 7 R сохраняется, RAM, CPU-стек и порты не записываются
                ; Corrupt:
                ;   HL, DE только при входном D=0, BC, AF, AF' только при входном D не равном нулю, R
                ; Note:
                ;   при малом слове выполняется до пятнадцати последовательных вычитаний 1,3,5 и далее, при большом слове исходная таблица задаёт оценку и пробный остаток
                ;   первые 233 строки кодируют дополнение затравки корня и отрицательный квадрат, последние 23 строки содержат затравку и положительный квадрат
                ;   затравки строк 09, A9 и E1 равны 47, 207 и 239, они на единицу ниже точного корня 256*индекс и сохранены буквально
                ;   5888 входов E900..FFFF дают не математический корень, допустимость этого диапазона у игровых вызывающих пока не доказана
                ;   причина особого заполнения таблиц не установлена, исправление таблиц или ограничения входа не вводилось
                ;   все 65536 входных слов проверены числовым эталоном с точными регистрами включая R, всеми банками RAM и отсутствием записей
                ;   этот помощник сам банк не выбирает, тот же адрес C000 в другом банке не удовлетворяет договору
                ;   точные T, IRQ, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Выбор малой либо табличной ветви
                ; Проверка старшего байта исходного беззнакового слова DE.
Entry:          LD A, D
                AND A
                JR Z, @Action.SqrtWordCached.RootSmallWord                      ; переход, если входной DE меньше 256, использовать развёрнутое вычитание нечётных разностей

                ; -----------------------------------------
                ; Табличная начальная оценка
                ; Поиск трёх байтов строки по старшему байту входа, начальная A получается дополнением байта C0.
                LD L, A
                LD H, @ActionRootCacheConst.InitialPage
                LD A, (HL)
                INC H
                LD C, A
                ; Расчёт начальной оценки как дополнения InitialByte, временное сохранение оценки и флагов в AF'.
                CPL
                EX AF, AF'
                ; Расчёт отрицательной нечётной разности для следующего квадрата, два сдвига готовят слово 2*(FF00+InitialByte+1)-1.
                LD B, @ActionRootCacheConst.NegativeHigh
                INC BC
                SLA C
                RL B
                DEC BC
                ; Чтение исходного базового слова из плоскостей C1 и C2, для последних 23 строк оно положительно.
                LD A, (HL)
                INC H
                LD H, (HL)
                LD L, A
                EX AF, AF'
                ; Расчёт пробного остатка из входного DE и буквального базового слова таблицы.
                ADD HL, DE
                ; Проверка первой нечётной разности после табличной оценки, перенос ADD отрицательного слова соответствует отсутствию заёма.
                ADD HL, BC
                RET NC                                                          ; выход, если пробный остаток меньше очередной нечётной разности, оставить текущую оценку A

                ; Расчёт следующей отрицательной нечётной разности и увеличение принятой оценки.
                DEC BC
                DEC BC
                INC A
                ADD HL, BC
                RET NC                                                          ; выход, если пробный остаток меньше очередной нечётной разности, оставить текущую оценку A

                ; Расчёт следующей отрицательной нечётной разности и увеличение принятой оценки.
                DEC BC
                DEC BC
                INC A
                ADD HL, BC
                RET NC                                                          ; выход, если пробный остаток меньше очередной нечётной разности, оставить текущую оценку A

                ; Расчёт следующей отрицательной нечётной разности и увеличение принятой оценки.
                DEC BC
                DEC BC
                INC A
                ADD HL, BC
                RET NC                                                          ; выход, если пробный остаток меньше очередной нечётной разности, оставить текущую оценку A

                ; Расчёт следующей отрицательной нечётной разности и увеличение принятой оценки.
                DEC BC
                DEC BC
                INC A
                ADD HL, BC
                RET NC                                                          ; выход, если пробный остаток меньше очередной нечётной разности, оставить текущую оценку A

                ; Расчёт следующей отрицательной нечётной разности и увеличение принятой оценки.
                DEC BC
                DEC BC
                INC A
                ADD HL, BC
                RET NC                                                          ; выход, если пробный остаток меньше очередной нечётной разности, оставить текущую оценку A

                ; Все шесть проверок приняты, увеличение последней оценки и завершение без седьмой пробы.
                INC A
                RET

                ; -----------------------------------------
                ; Слово меньше 256
                ; Подготовка остатка из DE, прежний HL переносится в DE и не восстанавливается.
RootSmallWord:  EX DE, HL
                LD BC, @ActionRootCacheConst.FirstOddStep
                XOR A
                ; Проверка первого квадрата вычитанием разности 1, A пока равен нулю.
                ADD HL, BC
                RET NC                                                          ; выход, если пробный остаток меньше очередной нечётной разности, оставить текущую оценку A

                ; Увеличение принятой оценки и подготовка следующей отрицательной нечётной разности.
                INC A
                DEC BC
                DEC BC
                ADD HL, BC
                RET NC                                                          ; выход, если пробный остаток меньше очередной нечётной разности, оставить текущую оценку A

                ; Увеличение принятой оценки и подготовка следующей отрицательной нечётной разности.
                INC A
                DEC BC
                DEC BC
                ADD HL, BC
                RET NC                                                          ; выход, если пробный остаток меньше очередной нечётной разности, оставить текущую оценку A

                ; Увеличение принятой оценки и подготовка следующей отрицательной нечётной разности.
                INC A
                DEC BC
                DEC BC
                ADD HL, BC
                RET NC                                                          ; выход, если пробный остаток меньше очередной нечётной разности, оставить текущую оценку A

                ; Увеличение принятой оценки и подготовка следующей отрицательной нечётной разности.
                INC A
                DEC BC
                DEC BC
                ADD HL, BC
                RET NC                                                          ; выход, если пробный остаток меньше очередной нечётной разности, оставить текущую оценку A

                ; Увеличение принятой оценки и подготовка следующей отрицательной нечётной разности.
                INC A
                DEC BC
                DEC BC
                ADD HL, BC
                RET NC                                                          ; выход, если пробный остаток меньше очередной нечётной разности, оставить текущую оценку A

                ; Увеличение принятой оценки и подготовка следующей отрицательной нечётной разности.
                INC A
                DEC BC
                DEC BC
                ADD HL, BC
                RET NC                                                          ; выход, если пробный остаток меньше очередной нечётной разности, оставить текущую оценку A

                ; Увеличение принятой оценки и подготовка следующей отрицательной нечётной разности.
                INC A
                DEC BC
                DEC BC
                ADD HL, BC
                RET NC                                                          ; выход, если пробный остаток меньше очередной нечётной разности, оставить текущую оценку A

                ; Увеличение принятой оценки и подготовка следующей отрицательной нечётной разности.
                INC A
                DEC BC
                DEC BC
                ADD HL, BC
                RET NC                                                          ; выход, если пробный остаток меньше очередной нечётной разности, оставить текущую оценку A

                ; Увеличение принятой оценки и подготовка следующей отрицательной нечётной разности.
                INC A
                DEC BC
                DEC BC
                ADD HL, BC
                RET NC                                                          ; выход, если пробный остаток меньше очередной нечётной разности, оставить текущую оценку A

                ; Увеличение принятой оценки и подготовка следующей отрицательной нечётной разности.
                INC A
                DEC BC
                DEC BC
                ADD HL, BC
                RET NC                                                          ; выход, если пробный остаток меньше очередной нечётной разности, оставить текущую оценку A

                ; Увеличение принятой оценки и подготовка следующей отрицательной нечётной разности.
                INC A
                DEC BC
                DEC BC
                ADD HL, BC
                RET NC                                                          ; выход, если пробный остаток меньше очередной нечётной разности, оставить текущую оценку A

                ; Увеличение принятой оценки и подготовка следующей отрицательной нечётной разности.
                INC A
                DEC BC
                DEC BC
                ADD HL, BC
                RET NC                                                          ; выход, если пробный остаток меньше очередной нечётной разности, оставить текущую оценку A

                ; Увеличение принятой оценки и подготовка следующей отрицательной нечётной разности.
                INC A
                DEC BC
                DEC BC
                ADD HL, BC
                RET NC                                                          ; выход, если пробный остаток меньше очередной нечётной разности, оставить текущую оценку A

                ; Увеличение принятой оценки и подготовка следующей отрицательной нечётной разности.
                INC A
                DEC BC
                DEC BC
                ADD HL, BC
                RET NC                                                          ; выход, если пробный остаток меньше очередной нечётной разности, оставить текущую оценку A

                ; Все пятнадцать проверок приняты, малое слово возвращает оценку 15 без пробы квадрата 16.
                INC A
                RET

