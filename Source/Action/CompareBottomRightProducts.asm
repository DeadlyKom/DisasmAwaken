                module Action
                module CompareBottomRightProducts
                ; Документация [алгоритм и проверка](../../Docs/ActionClipComparisons.md)
                ; -----------------------------------------
                ; Вычитание RightProduct из BottomProduct с передачей заёма младшего слова
                ; исходная запись 17, банковое окно ACTION банка 0, смещения #66A9..#66BC
                ; In:
                ;   физические BottomProduct и RightProduct содержат два 32-битных произведения, значения не изменяются
                ;   ACTION доступен в банке 0, на CPU-стеке внешний возврат, IRQ не вмешиваются
                ; Out:
                ;   HL содержит старшее слово разности первого произведения и второго с заёмом от младших слов
                ;   DE сохраняется, BC содержит старшее слово второго произведения
                ;   A сохраняется, F равен точным флагам последнего SBC HL,BC
                ;   HL', DE', BC', AF', IX и IY сохраняются, I, IM, IFF и paging сохраняются
                ;   SP после RET равен входному SP+2, RAM и порты не записываются, R увеличивается на 12 по модулю младших семи бит
                ; Corrupt:
                ;   HL, BC, F и R
                ; Note:
                ;   Z относится только к старшему вычитанию и не доказывает равенства полных произведений, младшая разность не возвращается
                ;   Overflow не исправляется, Sign не является универсальным математическим сравнением при переполнении
                ;   803012 сценариев общей серии проверяют регистры, флаги, R, SP и отсутствие записей RAM, все совместные входы не исчерпаны
                ;   IRQ, сборка и нативный запуск не проверены
                ; -----------------------------------------
                ; -----------------------------------------
                ; Чтение исходных значений
                ; Подготовка младших слов произведений к вычитанию.
Entry:          LD HL, (@ActionClipProductsData.BottomProduct.LowWord)
                LD BC, (@ActionClipProductsData.RightProduct.LowWord)
                ; Расчёт разности с предварительно очищенным Carry.
                OR A
                SBC HL, BC
                ; Расчёт старшей разности с заёмом младшего вычитания, загрузки слов не меняют Carry.
                LD HL, (@ActionClipProductsData.BottomProduct.HighWord)
                LD BC, (@ActionClipProductsData.RightProduct.HighWord)
                SBC HL, BC
                RET

                endmodule
                endmodule
