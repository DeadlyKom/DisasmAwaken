                module Action
                module EncodeSignedRatio
                ; Документация [алгоритм и проверка](../../Docs/ActionSignedRatioCode.md)
                ; -----------------------------------------
                ; Табличное кодирование знакового отношения с четырьмя смещениями и исходными ограничениями
                ; исходная запись 17, фиксированное окно 8000..BFFF, физический банк 2, смещения #4E24..#4E72
                ; In:
                ;   HL содержит исходный числитель signed16, DE исходный знаменатель signed16, BC и AF аргументов не задают
                ;   действуют условия DivideScaledLogarithmic, страницы логарифмов 9100 и 9200 и обратная таблица 9300 подготовлены
                ;   таблица кодов 9A00..9AFF сохраняет исходные 256 байтов, код и изменяемые операнды делителя доступны для записи
                ;   CPU-стек содержит внешний возврат и допускает шесть дополнительных байтов, IRQ не вмешиваются
                ; Out:
                ;   при табличном выходе HL=9A00 OR индекс, DE=нормализованный логарифм модуля знаменателя, BC=входной DE
                ;   A содержит исходный табличный код плюс смещение 00, 40, 80 либо C0 по двум входным знакам, точные F описаны в документации
                ;   при Carry делителя либо выходе сдвинутого индекса за байт A=40 для равных знаков, C0 для разных, F от исходного XOR старших байтов
                ;   на ограниченном пути HL остаётся выходом делителя при его Carry либо сдвинутым модулем результата при выходе индекса за байт
                ;   HL', DE', BC', IX, IY сохраняются, AF' возвращается от DivideScaledLogarithmic
                ;   SP=входной SP+2, I, IM, IFF и страница сохраняются, Carry исходного делителя наружу не возвращается
                ;   для исходной таблицы выходной Carry всегда нулевой, Z и Sign не являются общими признаками успеха либо знака A
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', R, шесть байтов CPU-стека и один изменяемый сдвиг делителя на обычном пути
                ; Note:
                ;   сначала вычисляется модуль знаменателя, исходное 8000 остаётся 8000, отрицательная нормализация делителя сохранена
                ;   результат делителя трактуется как signed16 перед взятием модуля, затем сдвигается вправо на четыре без округления
                ;   вход 0,0 возвращает исходный код 21, нулевая особая обработка не добавляется
                ;   860385 сценариев исполнили настоящий делитель и исходную таблицу, сопоставлены регистры включая R, восемь банков RAM и кратность записей
                ;   полный набор пар слов, эквивалентность atan2, аппаратный порядок записи слов, IRQ, точные T, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; Расчёт совместного признака знаков из исходных старших байтов знаменателя и числителя.
Entry:          LD A, D
                XOR H
                ; Сохранение исходных XOR-флагов и исходного знаменателя для восстановления BC после делителя.
                PUSH AF
                PUSH DE
                ; Проверка знака знаменателя перед расчётом его модуля.
                BIT @ActionRatioCodeConst.SignBit, D
                JR Z, @Action.EncodeSignedRatio.DivideMagnitude                 ; переход, если знаменатель неотрицателен, делить без его отрицания

                ; Расчёт модуля знаменателя, минимальное 8000 сохраняется по модулю слова.
                LD A, E
                CPL
                LD E, A
                LD A, D
                CPL
                LD D, A
                INC DE
                ; Расчёт исходного приближённого отношения через настоящий логарифмический делитель.
DivideMagnitude:CALL @Action.DivideScaledLogarithmic.Entry
                POP BC
                JR C, @Action.EncodeSignedRatio.RejectCode                      ; переход, если делитель вернул Carry, выдать код ограничения

                ; Проверка знака возвращённого 16-битного отношения перед повторным модулем.
                BIT @ActionRatioCodeConst.SignBit, H
                JR Z, @Action.EncodeSignedRatio.ScaleRatio                      ; переход, если результат делителя неотрицателен, масштабировать его без отрицания

                ; Расчёт модуля результата делителя, минимум 8000 также сохраняется.
                LD A, L
                CPL
                LD L, A
                LD A, H
                CPL
                LD H, A
                INC HL
                ; Расчёт индекса таблицы, логический сдвиг полного слова вправо на четыре.
ScaleRatio:     LD A, L
                SRL H
                RRA
                SRL H
                RRA
                SRL H
                RRA
                SRL H
                RRA
                LD L, A
                ; Проверка выхода индекса за диапазон 0..FF, младший байт не используется как обёрнутый индекс.
                LD A, H
                AND A
                JP NZ, @Action.EncodeSignedRatio.RejectCode                     ; переход, если старший байт сдвинутого модуля ненулевой, выдать код ограничения

                ; Восстановление исходного признака знаков перед чтением таблицы, LD A,(HL) его флаги не меняет.
                POP AF
                LD H, @ActionRatioCodeConst.TableHigh
                LD A, (HL)
                JP P, @Action.EncodeSignedRatio.SameSign                        ; переход, если исходные знаки совпадают, выбрать смещение 00 либо 80

                ; Расчёт смещения 40 для разных знаков, знак исходного знаменателя выбирает дополнительное 80.
                ADD A, @ActionRatioCodeConst.QuarterCode
                BIT @ActionRatioCodeConst.SignBit, B
                RET NZ                                                          ; выход, если исходный знаменатель отрицателен, вернуть табличный код плюс 40

                ; Расчёт смещения C0 для отрицательного числителя и неотрицательного знаменателя.
                ADD A, @ActionRatioCodeConst.HalfCode
                RET

                ; Проверка знака исходного знаменателя для равных знаков аргументов.
SameSign:       BIT @ActionRatioCodeConst.SignBit, B
                RET Z                                                           ; выход, если исходный знаменатель неотрицателен, вернуть табличный код без смещения

                ; Расчёт смещения 80 для двух отрицательных аргументов.
                ADD A, @ActionRatioCodeConst.HalfCode
                RET

                ; Восстановление исходных XOR-флагов, они задают знак ограниченного кода, а не Carry делителя.
RejectCode:     POP AF
                LD A, @ActionRatioCodeConst.QuarterCode
                RET P                                                           ; выход, если исходные знаки совпадают, вернуть код 40

                LD A, @ActionRatioCodeConst.NegativeLimit
                RET

                endmodule
                endmodule
