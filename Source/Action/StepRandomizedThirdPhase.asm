                module Action
                module StepRandomizedThirdPhase
                ; Документация [алгоритм и проверка](../../Docs/ActionRandomPhaseStep.md)
                ; -----------------------------------------
                ; Случайное обновление счётчика направления и знаковый шаг третьей фазы записи
                ; исходная запись 17, адреса 6201..624A
                ; In:
                ;   HL не задаёт аргумента, DE и BC сохраняются, AF начальных условий не задаёт
                ;   IX указывает FActionRecord с OffsetPhase2 и PhaseMoveTimer, доступно состояние потока 0
                ;   перенесённый код банка 5 и ACTION банка 0 доступны, четыре дополнительных байта CPU-стека доступны, IRQ исключены
                ; Out:
                ;   поток 0 обновляется всегда, при H=7F и (L AND 7F)>=10 PhaseMoveTimer получает ((L AND 0F)+20) OR (L AND 80)
                ;   после возможного сброса нулевые младшие семь бит таймера завершают обработку без изменения фазы
                ;   иначе полный таймер уменьшается на один, при отрицательном результате OffsetPhase2 уменьшается на один, при неотрицательном увеличивается
                ;   фаза меняется по модулю 256, её байтовый модуль не меньше 40 переключает бит 7 таймера
                ;   HL содержит новое слово потока, при случайном сбросе H дополнительно заменён положительной частью нового счётчика от 20 до 2F
                ;   A/F определяются нулевым счётчиком, сравнением модуля с 40 либо итоговым XOR бита направления
                ;   HL', DE', BC' содержат побочные результаты потока 0, AF', IX, IY, I/IM/IFF и paging сохраняются
                ;   SP после внешнего RET равен входному SP+2, дополнительных портов нет, R сверяется для каждой ветви независимой моделью
                ; Corrupt:
                ;   HL, AF, HL', DE', BC', R, состояние потока 0, PhaseMoveTimer, OffsetPhase2 и четыре временных байта CPU-стека, SP внешним RET
                ; Note:
                ;   PhaseMoveTimer здесь сочетает младший семибитовый счётчик и старший бит направления, это локальный контекст, другие состояния используют байт иначе
                ;   младший счётчик не уменьшается повторно после достижения нуля, значения 00 и 80 без случайного обновления оставляют фазу на месте
                ;   сравнение модуля является байтовым, исходное отрицание 80 даёт 80, дополнительное насыщение не вводилось
                ;   131072 сценария покрыли все слова потока 0 и все пары таймера/фазы, включая случайное обновление, простой и переключение направления
                ;   сверены точные регистры, флаги, R, восемь банков и кратность записей, настоящий поток исполнен
                ;   полное произведение входов, аппаратные IRQ, время, сборка и нативная игра не проверялись
                ; -----------------------------------------
                ; Обновление отдельного потока 0 перед каждым шагом, даже если младший счётчик остановлен.
Entry:          CALL @Action.NextRandomWord0.Entry
                ; Проверка точного старшего байта случайного слова для обновления счётчика направления.
                LD A, H
                CP #7F
                JR NZ, @Action.StepRandomizedThirdPhase.CheckCount              ; переход, если H нового слова не равен 7F, сохранить прежний счётчик

                ; Проверка младших семи бит случайного L перед заменой счётчика.
                LD A, L
                AND #7F
                CP #10
                JR C, @Action.StepRandomizedThirdPhase.CheckCount               ; переход, если младшая семибитовая часть L меньше 10, сохранить прежний счётчик

                ; Расчёт младшего счётчика от 20 до 2F и перенос случайного знакового бита в направление.
                AND #0F
                ADD A, #20
                LD H, A
                LD A, L
                AND #80
                OR H
                LD (IX + @FActionRecord.PhaseMoveTimer), A
                ; Проверка активности по младшим семи битам после возможного случайного обновления.
CheckCount:     LD A, (IX + @FActionRecord.PhaseMoveTimer)
                AND #7F
                DEC A
                RET M                                                           ; выход, если младший семибитовый счётчик был нулевым, фазу не изменять

                ; Обновление полного счётчика и выбор знака шага по результату его декремента.
                LD A, (IX + @FActionRecord.PhaseMoveTimer)
                DEC A
                LD (IX + @FActionRecord.PhaseMoveTimer), A
                JP P, @Action.StepRandomizedThirdPhase.IncreasePhase            ; переход, если уменьшенный таймер неотрицателен, увеличить третью фазу

                ; Обновление третьей фазы отрицательным единичным шагом по модулю 256.
                DEC (IX + @FActionRecord.OffsetPhase2)
                JP @Action.StepRandomizedThirdPhase.CheckAmplitude

                ; Обновление третьей фазы положительным единичным шагом по модулю 256.
IncreasePhase:  INC (IX + @FActionRecord.OffsetPhase2)
                ; Расчёт байтового модуля третьей фазы для проверки исходной амплитуды.
CheckAmplitude: LD A, (IX + @FActionRecord.OffsetPhase2)
                AND A
                JP P, @Action.StepRandomizedThirdPhase.CheckLimit               ; переход, если фаза неотрицательна, её байтовый модуль уже получен

                NEG
                ; Проверка модуля относительно 40 перед возможным отражением направления.
CheckLimit:     CP #40
                RET C                                                           ; выход, если модуль третьей фазы меньше 40, направление сохранить

                ; Обновление только старшего бита направления, младший счётчик остаётся после декремента.
                LD A, (IX + @FActionRecord.PhaseMoveTimer)
                XOR #80
                LD (IX + @FActionRecord.PhaseMoveTimer), A
                RET

                endmodule
                endmodule
