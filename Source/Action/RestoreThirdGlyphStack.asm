                module RestoreThirdGlyphStack
                ; Документация [алгоритм и проверка](../../Docs/ActionThirdGlyphStack.md)
                ; -----------------------------------------
                ; Восстановление CPU SP после векторного вычислителя перед публикацией третьего знака
                ; исходная запись 17, адреса 6CB1..6CB3
                ; In:
                ;   HL, DE, BC и AF содержат результат ComputePatchedVector, входной SP может быть арифметическим накопителем
                ;   SavedCpuSP уже записан действительным CPU SP с внешним возвратом, это внутреннее продолжение через IY
                ;   код перенесённого ACTION доступен, IRQ не вмешивается
                ; Out:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX и IY сохраняются
                ;   SP получает SavedCpuSP, исполнение последовательно продолжается в PublishThirdGlyphVector по 6CB4, RET здесь нет
                ;   R получает один M1 с сохранением бита 7, I/IM/IFF и paging сохраняются, RAM не меняется
                ; Corrupt:
                ;   SP и R
                ; Note:
                ;   (0) жёсткий порядок, следующая часть (1) PublishThirdGlyphVector.asm начинает с RET PE, обычный стек нужен даже при переполнении
                ;   65536 сценариев проверили все слова SavedCpuSP, регистры включая R, все банки RAM и отсутствие записей
                ;   модель останавливается по 6CB4 до первого чтения восстановленного стека, допустимость каждого тестового SP для последующего RET этим не утверждается
                ;   сохранённое слово является непосредственным операндом кода, отдельная память не выделяется
                ;   IRQ, точные T, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Восстановление CPU-стека
                ; Загрузка действительного SP из ранее записанного операнда, входной SP после арифметического вычислителя не разыменовывается.
Entry:          LD SP, #0000
                ; JP @Action.PublishThirdGlyphVector.Entry, продолжение в PublishThirdGlyphVector.asm

                endmodule
