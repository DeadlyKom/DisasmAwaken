                module Action
                module FindNearestListedRecord
                ; Документация [алгоритм и проверка](../../Docs/ActionNearestCandidate.md)
                ; -----------------------------------------
                ; Выбор ближайшей доступной записи из списка индексов с сохранением первого равенства
                ; исходная запись 17, адреса E9C2..E9FF
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, IX указывает текущую FActionRecord с читаемыми Components
                ;   с A01C достижим FE, FF пропускается, остальные байты считаются полными индексами 00..FD
                ;   действуют договоры RecordIndexToAddress и MaxRecordDeltaHigh, область списка и операнды доступны для записи
                ;   ACTION банка 0 выбран, шесть байтов ниже SP не пересекают запись, список, операнды и поток кода, повторный вход и IRQ исключены
                ; Out:
                ;   HL указывает достигнутый FE, DE и BC сохраняются, A равен текущему ChosenIndex, F=6A от CP FE,FE
                ;   из списка выбирается первая доступная запись с минимальным максимумом старших байтов модулей трёх обёрнутых разностей относительно IX
                ;   Component0.High=80 означает недоступность, соответствующая ячейка списка заменяется FF, младший байт доступности не проверяется
                ;   ClosestHigh сначала получает FF, каждое строгое улучшение обновляет ClosestHigh и ChosenIndex, равенство сохраняет первого кандидата
                ;   если доступных кандидатов нет, ClosestHigh=FF и ChosenIndex сохраняет старое значение, возвращаемый A тогда не подтверждает допустимость цели
                ;   HL' и DE' содержат результаты последнего преобразования либо расстояния, BC' и AF' сохраняются
                ;   IY указывает последнюю доступную просмотренную запись, если таких нет, IY сохраняется
                ;   IX, I/IM/IFF и paging сохраняются, SP после RET увеличен на два, внешний возврат сохраняется
                ;   R добавляет 9 M1 и 6 на каждый FF, 28 на каждый недоступный обычный индекс, 34 плюс стоимость расстояния на доступный и ещё 5 при улучшении
                ; Corrupt:
                ;   HL, AF, HL', DE', IY при доступной записи, R, два существующих операнда, недоступные ячейки списка и шесть временных байтов CPU-стека, SP внешним RET
                ; Note:
                ;   ChosenIndex не инициализируется на входе, пустой список и список только недоступных записей возвращают старый операнд
                ;   расстояние квантовано старшим байтом, не является евклидовым, равенства в пределах одного кванта разрешаются порядком списка
                ;   индекс не ограничивается исходными 25 игровыми слотами, за исходным массивом читаются реальные байты текущего банка
                ;   67541 сценарий проверил реальные дочерние процедуры, точные регистры, флаги, R, все восемь банков и кратность записей
                ;   полное произведение списков, IRQ, точные T, сборка и нативный запуск не проверялись
                ; -----------------------------------------
                ; Обновление начального минимума FF, прежний ChosenIndex намеренно не обнуляется.
Entry:          LD A, #FF
                LD (@ActionNearestCandidateState.ClosestHigh), A
                ; Подготовка курсора перед первым байтом исходного списка кандидатов.
                LD HL, @ActionCandidateListState.BeforeFirst
                ; Поиск следующей ячейки списка и проверка маркера завершения FE.
NextItem:       INC HL
                LD A, (HL)
                CP @ActionCandidateListConst.ListEnd
                JR Z, @Action.FindNearestListedRecord.ReadResult                ; переход, если прочитан FE, вернуть текущий операнд выбранного индекса

                ; Проверка пропуска FF, INC даёт ноль только для этого маркера.
                INC A
                JP Z, @Action.FindNearestListedRecord.NextItem                  ; переход, если ячейка содержит FF, продолжить просмотр списка

                ; Восстановление обычного индекса и сохранение курсора списка в альтернативном HL через EXX.
                DEC A
                EXX
                ; Преобразование полного индекса в адрес, доступность записи проверяется отдельно.
                CALL @Action.RecordIndexToAddress.Entry
                ; Проверка полного старшего байта первой компоненты выбранной записи.
                INC L
                LD A, (HL)
                CP #80
                JR Z, @Action.FindNearestListedRecord.DropStale                 ; переход, если Component0.High равен 80, заменить эту ячейку списка на FF

                ; Подготовка выбранной записи IY для расчёта расстояния относительно текущего IX.
                DEC L
                PUSH HL
                POP IY
                ; Расчёт максимума старших байтов модулей трёх обёрнутых разностей.
                CALL @Action.MaxRecordDeltaHigh.Entry
                ; Проверка строгого улучшения текущего минимума, равенство не заменяет первого кандидата.
                CP #FF
                JR NC, @Action.FindNearestListedRecord.NextLoop                 ; переход, если расстояние не меньше текущего минимума, сохранить прежний выбранный индекс

                ; Обновление минимума в операнде CP, индекс читается через сохранённый курсор списка.
                LD (@ActionNearestCandidateState.ClosestHigh), A
                EXX
                LD A, (HL)
                EXX
                ; Сохранение индекса улучшившего кандидата в операнд заключительного LD A,n.
                LD (@ActionNearestCandidateState.ChosenIndex), A
                ; Восстановление курсора списка для следующей ячейки без изменения минимума.
NextLoop:       EXX
                JP @Action.FindNearestListedRecord.NextItem

                ; Удаление недоступного индекса из текущей ячейки списка заменой на FF.
DropStale:      EXX
                LD (HL), @ActionCandidateListConst.SkippedIndex
                JP @Action.FindNearestListedRecord.NextItem

                ; Чтение текущего выбранного индекса, без доступных кандидатов это прежний результат до вызова.
ReadResult:     LD A, #00
                RET

                endmodule
                endmodule
