                module ClipInsideToTopLeft
                ; Документация [алгоритм и проверка](../../Docs/ActionClipCases.md)
                ; -----------------------------------------
                ; Отсечение ребра, первая точка внутри окна, вторая сверху слева
                ; исходная запись 17, банковое окно ACTION банка 0, смещения #60C9..#60D7
                ; In:
                ;   FirstPoint и SecondPoint содержат согласованные signed16 координаты и парные ClipCode зон имени функции
                ;   SeenFlags по CF07 содержит прежние отметки углов, полный CornerBlock задаёт запрет фактического вывода углов
                ;   геометрический профиль требует OutputSize=0, выходная страница 90 доступна, вызывающий кладёт три слова C993 и внешний возврат
                ;   при клавиатурном входе OutputSize=0..255, верхнее слово равно 6F4E, числовой договор требует согласованных точек
                ;   для каждого достигнутого деления d ненулевой, U=N для N>=0 либо -N-1, требуется U<abs(d)*65536
                ;   ACTION находится в банке 0, CPU-стек допускает временные слова вложенных вызовов, IRQ не вмешиваются
                ; Out:
                ;   порядок пересечений, углов, второй точки и отметок задаётся всеми явными условиями этого входа в ActionClipCases.md
                ;   OutputSize увеличен на два modulo 256 за каждую добавленную точку, SeenFlags меняется только установкой младших четырёх битов
                ;   при обычном полном возврате через C993 A=OutputSize, F от CP размера,4, DE=C993
                ;   при обычном возврате HL, BC, AF' и IX определяются точной последовательностью договоров помощников, числовая композиция приведена в ReferenceActionClipping.py
                ;   HL', DE', BC', IY, I, IM, IFF и paging сохраняются, R меняется, геометрическое завершение даёт SP=входной SP+8
                ;   на клавиатурной рамке обычный RET ведёт на 6F4E с SP=входной SP+2, завершение C993 не исполняется
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', IX по достигнутым помощникам, R, младшие отметки углов, достигнутые произведения, выходные точки, размер и временные слова CPU-стека
                ; Note:
                ;   геометрический и клавиатурный вызывающие используют разные верхние слова CPU-стека, все три пути данного входа заканчиваются обычным RET
                ;   3546 клавиатурных профилей с подготовленными координатами проходят все три пути и возвращаются к затуханию
                ;   все 256 начальных OutputSize проверены, 28 случаев оборачивают индекс, записи выходных пар остаются в странице 90
                ;   нечётный начальный размер подготовлен моделью, его естественная достижимость и игровой смысл скрытого вызова не доказаны
                ;   в семи снимках модели кадра обе точки нулевые, исходное деление с DE=0 оставляет пару 00 00 и ставится отметка верхнего левого угла
                ;   [Клавиатурный вызов и границы проверки](../../Docs/ActionKeyDispatchPrefix.md)
                ;   241 путь для 81 пары выполнен в 176640 сценариях с настоящими помощниками, проверены все регистры кроме R, вся RAM и кратность записей
                ;   независимое геометрическое доказательство не заявляется, числовой эталон является композицией проверенных помощников по исходному графу
                ;   точное приращение R и время, все совместные входы, IRQ, сборка и нативный вывод не доказаны
                ; -----------------------------------------
                ; вход таблицы, первая точка внутри, вторая сверху слева
                ; вычисление кэшированного числителя TopProduct для верхней границы
Entry:          CALL @Action.ComputeTopClipProduct.Entry
                ; вычисление кэшированного числителя LeftProduct для левой границы
NeedLeftForTL:  CALL @Action.ComputeLeftClipProduct.Entry
                ; проверка порядка пересечений по разности TopProduct минус LeftProduct
PickTLExit:     CALL @Action.CompareTopLeftProducts.Entry
                JP M, @Action.AppendTopClipIntersection.Entry                   ; переход, если бит 31 разности TopProduct минус LeftProduct установлен

                CALL @Action.AppendLeftClipIntersection.Entry
                ; JP @Action.ClipLeftToTopLeft.Entry, продолжение в ClipLeftToTopLeft.asm

                endmodule
