                module Action
                module RecordAddressToIndex
                ; Документация [коды и адреса записей](../../Docs/ActionRecordIndex.md)
                ; -----------------------------------------
                ; Расчёт байтового кода записи по HL, младшие шесть битов смещения не участвуют в коде
                ; исходная запись 17, код ACTION банка 0, адреса E6C7..E6D0
                ; In:
                ;   HL входной адрес, DE, BC и AF числовых аргументов не задают
                ;   исполняется код ACTION банка 0, на CPU-стеке внешний возврат, IRQ не вмешиваются
                ; Out:
                ;   H сохраняется, L=входной L*4 по модулю 256, DE и BC сохраняются
                ;   A=(((входной HL-A100) по модулю 65536)/64) по модулю 256, деление целочисленное
                ;   F содержит S, Z и P/V от нового L, биты 5 и 3 от A, Carry равен биту 6 байтовой разности входного H-A1, H и N сброшены
                ;   HL', DE', BC', AF', IX, IY, I, IM и IFF сохраняются, SP=входной SP+2
                ;   R увеличивается на 9 M1, записей RAM и CPU-стека нет
                ; Corrupt:
                ;   L, AF, R
                ; Note:
                ;   проверок диапазона и выравнивания нет, смещения 0..63 в одной записи дают одинаковый A
                ;   обратимость с RecordIndexToAddress доказана для всех кодов, произвольные адреса могут давать тот же байтовый код
                ; -----------------------------------------
                ; Расчёт номера 256-байтовой страницы относительно исходной базы A100.
Entry:          LD A, H
                SUB @ActionRecordIndexConst.BaseHigh
                ; Расчёт двух младших разрядов кода из битов 7 и 6 входного L.
                ; Два сдвига меняют L, младшие шесть битов адреса не участвуют в результате A.
                SLA L
                RLA
                SLA L
                RLA
                RET

                endmodule
                endmodule
