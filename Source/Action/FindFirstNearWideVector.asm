                module Action
                module FindFirstNearWideVector
                ; Документация [алгоритм и проверка](../../Docs/ActionNearVectorSearch.md)
                ; -----------------------------------------
                ; Поиск первого близкого широкого вектора и выбор его наибольшего старшего байта
                ; исходная запись 17, перенесённое ядро 6000..7F8E, смещения #0BFB..#0C65
                ; In:
                ;   HL, DE, BC, AF входных аргументов не задают, сохраняемые части зависят от пути выхода
                ;   ControlsParameterTablesState.SeedIndex задаёт стабильное число 0..255 широких векторов от ActionWideVectors.Vector00
                ;   все указанные счётчиком записи доступны для чтения, CPU-стек допускает четыре дополнительных байта и внешний возврат
                ;   перенесённый код и CheckThreeUpperWordsNear доступны, IRQ не вмешиваются
                ; Out:
                ;   при нулевом числе A=0, F=44, L=7F, H, DE и BC сохраняются
                ;   при ненулевом числе выбирается первый вектор с тремя верхними signed16 от -60 до 59, при отсутствии L=7F
                ;   при успехе A=E=индекс от нуля, B=число оставшихся записей включая выбранную, C сохранён
                ;   для каждого среднего слова биты 8..23 инвертируются при бите 31, выбирается максимальный старший байт, равенство выбирает позднюю компоненту
                ;   L=старший и H=младший байт выбранного среднего слова, D=старший байт свёрнутого среднего слова третьей компоненты
                ;   при успехе F соответствует SUB от числа записей и B, Carry=0, Z установлен только для индекса ноль
                ;   при исчерпании A и H взяты из последнего предиката, DE=12, B=0, C сохранён, флаги уточнены в документации
                ;   HL', DE', BC', AF', IX, IY сохраняются, SP=входной SP+2, I, IM, IFF и страница сохраняются
                ;   кроме четырёх временных байтов CPU-стека RAM не записывается, точный R описан в документации
                ; Corrupt:
                ;   HL, DE, BC, AF, R, четыре временных байта CPU-стека
                ; Note:
                ;   для успеха надёжным признаком является L меньше 60, значение L=7F означает отсутствие результата
                ;   это не максимум трёх полных средних слов, их младшие байты в сравнении не участвуют
                ;   счётчик не ограничивается шестью физическими начальными записями, исходный код защиты диапазона не содержит
                ;   проверены все средние слова каждого знака в каждой позиции, все значения счётчика и смешанные списки
                ;   сопоставлены регистры включая R, кратность записей, остаток стека и все восемь банков RAM
                ;   полное произведение списков, игровой предел числа целей, IRQ, точные T, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; Проверка числа широких векторов, здесь SeedIndex используется как длина списка.
Entry:          LD A, (@ControlsParameterTablesState.SeedIndex)
                OR A
                LD L, @ActionNearSearchConst.NotFoundLow
                RET Z                                                           ; выход, если число векторов нулевое, вернуть L=7F без чтения списка

                ; Сохранение IY и создание прохода по списку с исходным шагом 12.
                PUSH IY
                LD B, A
                LD IY, @ActionWideVectors.Vector00
                LD DE, @FActionWideVector
                ; Поиск первого вектора, все верхние слова которого лежат от -60 до 59.
ScanNext:       CALL @Action.CheckThreeUpperWordsNear.Entry
                JR C, @Action.FindFirstNearWideVector.ReadFirst                 ; переход, если все три верхних слова близки, обработать первый найденный вектор

                ; Переход к следующей широкой записи, оставшееся число хранится в B.
                ADD IY, DE
                DJNZ @Action.FindFirstNearWideVector.ScanNext

                ; Формирование признака отсутствия после исчерпания всех записей.
                LD L, @ActionNearSearchConst.NotFoundLow
                POP IY
                RET

                ; Чтение битов 8..23 первой компоненты, знак берётся из бита 31.
ReadFirst:      LD E, (IY + @FActionWideVector.Component0.Byte1)
                LD D, (IY + @FActionWideVector.Component0.Byte2)
                ; Проверка знака первой полной компоненты перед инверсией среднего слова.
                BIT @ActionAbs32Const.SignBit, (IY + @FActionWideVector.Component0.Byte3)
                JR Z, @Action.FindFirstNearWideVector.SaveFirst                 ; переход, если первая компонента неотрицательная, сохранить среднее слово без инверсии

                ; Расчёт свёрнутого среднего слова через инверсию без прибавления единицы.
                LD A, D
                CPL
                LD D, A
                LD A, E
                CPL
                LD E, A
                ; Сохранение первой компоненты со сменой порядка байтов, L служит сравниваемым старшим байтом.
SaveFirst:      LD L, D
                LD H, E
                ; Чтение среднего слова второй компоненты.
                LD E, (IY + @FActionWideVector.Component1.Byte1)
                LD D, (IY + @FActionWideVector.Component1.Byte2)
                ; Проверка знака второй полной компоненты.
                BIT @ActionAbs32Const.SignBit, (IY + @FActionWideVector.Component1.Byte3)
                JR Z, @Action.FindFirstNearWideVector.CompareSecond             ; переход, если вторая компонента неотрицательная, сравнить без инверсии

                ; Расчёт свёрнутого среднего слова второй компоненты.
                LD A, D
                CPL
                LD D, A
                LD A, E
                CPL
                LD E, A
                ; Проверка только старшего байта, при равенстве выбирается вторая компонента независимо от младшего.
CompareSecond:  LD A, D
                CP L
                JR C, @Action.FindFirstNearWideVector.ReadThird                 ; переход, если старший байт второй компоненты меньше текущего, оставить первую

                LD L, A
                LD H, E
                ; Чтение среднего слова третьей компоненты.
ReadThird:      LD E, (IY + @FActionWideVector.Component2.Byte1)
                LD D, (IY + @FActionWideVector.Component2.Byte2)
                ; Проверка знака третьей полной компоненты.
                BIT @ActionAbs32Const.SignBit, (IY + @FActionWideVector.Component2.Byte3)
                JR Z, @Action.FindFirstNearWideVector.CompareThird              ; переход, если третья компонента неотрицательная, сравнить без инверсии

                ; Расчёт свёрнутого среднего слова третьей компоненты.
                LD A, D
                CPL
                LD D, A
                LD A, E
                CPL
                LD E, A
                ; Проверка только старшего байта третьей компоненты, равенство вновь выбирает более позднюю.
CompareThird:   LD A, D
                CP L
                JR C, @Action.FindFirstNearWideVector.ReturnIndex               ; переход, если старший байт третьей компоненты меньше текущего, сохранить прежний выбор

                LD L, A
                LD H, E
                ; Расчёт индекса выбранного вектора по разности исходного и оставшегося числа записей.
ReturnIndex:    LD A, (@ControlsParameterTablesState.SeedIndex)
                SUB B
                LD E, A
                POP IY
                RET

                endmodule
                endmodule
