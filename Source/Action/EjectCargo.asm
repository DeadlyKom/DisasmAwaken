                module Action
                module EjectCargo
                ; Документация [выброс груза и мины](../../Docs/ActionEjectCommands.md)
                ; -----------------------------------------
                ; Выброс первого ненулевого байта из начала пар груза с сообщением независимо от размещения
                ; исходная запись 17, перенесённое ядро банка 5, адреса 7594..75CE
                ; In:
                ;   HL, DE, BC и AF входных числовых аргументов не задают, C сохраняемый контекст
                ;   CommandDelay допускает обработку только при нуле, банк 0 выбран, paging разблокирован
                ;   особая запись A780 задаёт родительские поля SpawnPrepared, доступны свободные строки и конечный список A01C
                ;   очередь Controls банка 1 соответствует QueueTextItemBank1, доступны восемнадцать дополнительных байтов CPU-стека, IRQ не вмешиваются
                ; Out:
                ;   при ненулевой задержке HL, DE и BC сохраняются, A содержит задержку, F соответствует AND A, память и paging не меняются
                ;   при нулевой задержке CursorA получает EE1B, CommandDelay получает 20 до проверки наличия груза или мин
                ;   при попытке создания IX получает A780 и не восстанавливается, другие результаты общего тела следуют SpawnPrepared
                ;   при отсутствии свободного места уже списанный исходный байт не восстанавливается, сообщение об успешном выбросе всё равно передаётся
                ;   на каждом пути с нулевой задержкой ставится ровно одно сообщение, OUT 7FFD получает 11 и 10, конечная страница 10
                ;   внешний SP после RET равен входному SP+2, максимальная дополнительная глубина восемнадцать байтов, точные R и такты родительской композиции не сверялись
                ;   ищутся первые 30 байтов от Row00.QuantityAndMark, то есть оба поля Row00..Row14, проверяется полный байт, не только количество
                ;   при полностью нулевом префиксе HL=9BF1, DE сохранён, B=0, C сохранён, AF=0054, IX/IY и альтернативные регистры сохраняются, передано F41C
                ;   при найденном байте i он обнуляется целиком до создания, SpawnPrepared получает HL=i и A=исходный байт, передано F3F3
                ;   при создании код списка равен 7C для всех i от 0 до 29, он не заменяется индексом ребёнка, Current по 9BD2 не уменьшается
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, R, CommandDelay, CursorA, исходный байт запаса, создаваемая запись, пометки поиска, список, очередь, paging и восемнадцать временных байтов стека по пути
                ; Note:
                ;   нечётное смещение выбирает Price, следующие пятнадцать записей вообще не сканируются, исходный алгоритм не исправляется
                ;   10664 сценария обеих команд проверяют реальные поиск, подготовленный вход и очередь, отказ размещения и заполнение очереди разделены
                ; -----------------------------------------
                ; Проверка задержки перед поиском выбрасываемого байта груза.
Entry:          LD A, (@ActionMissileLaunchState.CommandDelay)
                AND A
                RET NZ                                                          ; выход, если CommandDelay ненулевой, груз и состояние сохранить

                ; Выбор исходного звукового потока до проверки наличия груза.
                LD HL, @ActionEjectConst.Sound
                LD (@ActionAyEffectState.CursorA), HL
                ; Обновление задержки принятой команды даже при пустом префиксе груза.
                LD A, @ActionEjectConst.Delay
                LD (@ActionMissileLaunchState.CommandDelay), A
                ; Поиск первого ненулевого байта среди обоих полей первых пятнадцати пар груза.
                LD HL, @ActionOwnedCargoRows.Row00 - 1
                LD B, @ActionEjectConst.ScanBytes
NextByte:       INC HL
                LD A, (HL)
                AND A
                JR NZ, @Action.EjectCargo.DropByte                              ; переход, если текущий байт ненулевой, обнулить его и попытаться создать объект

                DJNZ @Action.EjectCargo.NextByte

                ; Передача сообщения об отсутствии груза после тридцати нулевых байтов.
                PUSH DE
                LD DE, @ControlsFlightText.NoCargo
                CALL @Action.QueueTextItemBank1.Entry
                POP DE
                RET

                ; Обнуление выбранного байта до поиска свободного объекта, последующий отказ его не восстановит.
DropByte:       LD (HL), #00
                ; Расчёт байтового индекса от начала пар груза через исходное оборачивание 16-битного адреса.
                LD DE, @ActionEjectConst.CargoIndexBias
                ADD HL, DE
                ; Выбор особой родительской записи для подготовленного создателя класса 19.
                LD IX, @ActionLinkedContextConst.SpecialRecord
                CALL @Action.SpawnClass19AndUpdateList.SpawnPrepared
                ; Передача сообщения о сбросе груза независимо от результата SpawnPrepared.
                PUSH DE
                LD DE, @ControlsFlightText.CargoEjected
                CALL @Action.QueueTextItemBank1.Entry
                POP DE
                RET

                endmodule
                endmodule
