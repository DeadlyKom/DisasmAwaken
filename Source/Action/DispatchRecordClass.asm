                module Action
                module DispatchRecordClass
                ; Документация [алгоритм и проверка](../../Docs/ActionClassDispatch.md)
                ; -----------------------------------------
                ; Косвенный переход по оборачиваемому байтовому индексу класса записи
                ; исходная запись 17, перенесённое ядро 6000..7F8E, смещения #071C..#072C
                ; In:
                ;   HL, DE, BC, AF входных аргументов не задают, IX указывает запись FActionRecord с доступным ClassCode
                ;   исходный перенесённый ACTION и таблица ClassTable доступны в фиксированной RAM, байты таблицы не изменены
                ;   область класса не проверяется диспетчером, для штатных 26 указателей требуется ClassCode AND 7F < 26
                ; Out:
                ;   HL содержит прочитанный адрес и PC получает его после JP (HL), DE сохраняется, BC=ClassTable
                ;   A содержит младший байт адреса, F=20 OR S OR Z OR P от байта (2*ClassCode) AND FF
                ;   HL', DE', BC', AF', IX, IY сохраняются, SP не меняется, I, IM, IFF и страница сохраняются
                ;   R получает 13 M1 с сохранением своего бита 7, RAM и CPU-стек не записываются
                ; Corrupt:
                ;   HL, BC, AF, R, PC
                ; Note:
                ;   индекс вычисляется SLA A и оборачивается до байта, классы c и c+128 выбирают одинаковый адрес
                ;   индексы 26..127 читают следующие байты кода как указатели, исходной проверки верхней границы нет
                ;   6656 сценариев покрыли все 256 классов на всех 26 физических записях, проверка остановлена после JP (HL)
                ;   алгоритмы целевых обработчиков, диапазон всех писателей класса, IRQ, точные T, сборка и нативный запуск этой проверкой не доказаны
                ; -----------------------------------------
                ; Чтение полного ClassCode, старший бит кода не запрещён исходной процедурой.
Entry:          LD A, (IX + @FActionRecord.ClassCode)
                ; Расчёт байтового смещения указателя, SLA теряет разряд 7 класса и не даёт расширенного индекса.
                SLA A
                LD L, A
                LD H, #00
                ; Выбор исходной таблицы из 26 слов, отсутствие проверки пределов сохранено.
                LD BC, @ActionClassDispatchState.ClassTable
                ; Расчёт адреса выбранного слова и чтение двух байтов указателя.
                ADD HL, BC
                LD A, (HL)
                INC HL
                LD H, (HL)
                LD L, A
                ; Передача управления прочитанному адресу без CALL, внешний CPU-стек не изменяется.
                JP (HL)

                endmodule
                endmodule
