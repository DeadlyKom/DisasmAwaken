                module Action
                module PolygonFillRows
                ; Документация [чтения дополнительных пар и наложение рабочих полей](../../Docs/ActionPolygonExtraMaskPairs.md)
                ; Физические таблицы [адресные строки, шаблоны и крайние маски](../../Docs/PolygonFillPhysicalData.md)
                ; Документация [алгоритм и проверка](../../Docs/ActionPolygonFillRows.md)
                ; -----------------------------------------
                ; Строковое ядро линейной заливки с развёрнутой записью, крайними масками и коррекцией двух рёбер
                ; исходная запись 17, адреса D1C0..D267
                ; In:
                ;   основной вход CheckRow по D229 получает состояние PreparePolygonFill, обновление рёбер выполняется исходными переходами
                ;   HL содержит H страницы масок 8C/8D, DE содержит D текущей строки и рабочий E, BC содержит старший байт линейного адреса и рабочий C
                ;   AF содержит A текущей строки перед CheckRow, после подготовки ребра вход DrawRow не требует A номера строки
                ;   HL' содержит две ошибки, DE' шаг правого ребра, BC' шаг левого, AF' содержит шаблон следующей рисуемой строки
                ;   IX и IY упаковывают фазу строки, координату Second и индекс маски, Mode от 0 до 4
                ;   контур выпуклый положительного обхода, 3..60 точек Second 0..255 и First 0..95, исходные маски страниц 8C/8D сохранены
                ;   SP=FFE0, SavedSP указывает на сохранённый HL и затем внешний CPU-возврат, операнды высот, ошибок и RowLimit/RowBranch согласованы с цепочками
                ;   ACTION банка 0 доступен на запись, IRQ не вмешиваются в временный SP и изменяемые операнды
                ;   Entry по D1C0 и SpanN являются внутренними входами развёрнутой записи, для них A содержит шаблон и BC адрес следующего среднего байта
                ; Out:
                ;   HL восстановлен словом по SavedSP, после внешнего RET SP равен SavedSP+4
                ;   DE содержит D=maxFirst и E последнего сохранённого состояния подготовки границ либо однобайтовой маски, E может зависеть от предыдущей строки
                ;   BC содержит B=(#80+minFirst DIV 8+Kcarry) AND #FF, C=((maxFirst-1) AND 7)*32+MAX(xLeft,xRight) DIV 8 для последней строки
                ;   AF содержит A=maxFirst и F=#42 OR (maxFirst AND #28), это итоговое сравнение нижней исключённой строки с собой
                ;   HL' содержит H'=hRight DIV 2 и L'=hLeft DIV 2 для последних рёбер
                ;   DE' равен (#2000+32*stepRight) AND #FFFF, BC' равен (#2000+32*stepLeft) AND #FFFF
                ;   AF' содержит A'=p следующей строки, F'=(p AND #A8) OR #04 OR Zmask, Zmask=#40 только при p=0
                ;   IX=((maxFirst AND 7)*8192+xLeftEnd*32+2*Mode) AND #FFFF, IY=((maxFirst AND 7)*8192+xRightEnd*32+2*Mode+16) AND #FFFF
                ;   пиксели записаны по геометрическим полуинтервалам, верхняя и левая границы включены, нижняя и правая исключены
                ;   сохранены все изменения операндов и дополнительные записи неизменённых значений по ReferenceActionPolygonFill.fill
                ;   I, IM, IFF и paging сохраняются, R меняется, порты не используются
                ; Corrupt:
                ;   DE, BC, AF, HL', DE', BC', AF', IX, IY, R, пиксельный буфер, временный стек и операнды ядра и цепочек, HL восстановлен при окончании
                ; Note:
                ;   Out относится к непустому пути PreparePolygonFill через CheckRow, горизонтальный RET подготовителя не исполняет ядро, несогласованные внутренние входы не проверены
                ;   D22D увеличивает D перед рисованием, после строки D содержит номер следующей строки для проверки предела
                ;   JP по D243 исходно содержит D100 как шаблон, D239 заменяет младший байт перед каждым использованием
                ;   для ширины в байтах n>0 младший адрес равен (-2*n) AND FF, исполняются n-1 средних сохранений и затем правый край
                ;   в профиле Second 0..255 разность байтов не превышает 31, самая первая пара по D1C0 сохраняется, но этим профилем не вызывается
                ;   два крайних адреса в одном байте требуют объединённой маски, обратный порядок байтов пропускает пиксельную запись
                ;   перенос IX увеличивает старший байт адреса до дробной коррекции, исходный дрейф у Second=255 не исправляется
                ;   11572 сценария полного заполнителя сверяют bitmap, все основные, альтернативные и индексные регистры, RAM и кратность записей
                ;   все сочетания контуров, точное R/T, IRQ, сборка и нативное исполнение не доказаны
                ;   minFirst и maxFirst обозначают минимум и максимум First контура, xLeft и xRight границы последней строки maxFirst-1
                ;   hLeft и hRight полные высоты последних рёбер, xLeftEnd и xRightEnd их конечные Second, step=CEIL(deltaSecond/height), но при deltaSecond=0 исходный step=1
                ;   Kcarry число переполнений ADD IX,BC по всем строкам до дробной коррекции, обратная поправка IX на минус 32 не отменяет уже увеличенный B
                ;   p=первый шаблон XOR разность строк при нечётном maxFirst-minFirst, все пять исходных режимов дают чётную битовую сумму и PV=1 в альтернативном F
                ;   смена любой цепочки обновляет E пределом левого ребра, однобайтовая строка заменяет его объединённой маской сохранения, широкая строка может оставить прежний E
                ;   два проверенных треугольника с одинаковыми последними границами 2 и 8 дают E=E3 и E=F1 при совпадающих BC, IX, IY и HL'
                ; -----------------------------------------
                ; -----------------------------------------
                ; Развёрнутая середина строки
                ; Внутренние SpanN записывают N полных байтов шаблона, выбранный адрес зависит от разности крайних байтов.
Entry:          LD (BC), A
                INC C
Span30:         LD (BC), A
                INC C
Span29:         LD (BC), A
                INC C
Span28:         LD (BC), A
                INC C
Span27:         LD (BC), A
                INC C
Span26:         LD (BC), A
                INC C
Span25:         LD (BC), A
                INC C
Span24:         LD (BC), A
                INC C
Span23:         LD (BC), A
                INC C
Span22:         LD (BC), A
                INC C
Span21:         LD (BC), A
                INC C
Span20:         LD (BC), A
                INC C
Span19:         LD (BC), A
                INC C
Span18:         LD (BC), A
                INC C
Span17:         LD (BC), A
                INC C
Span16:         LD (BC), A
                INC C
Span15:         LD (BC), A
                INC C
Span14:         LD (BC), A
                INC C
Span13:         LD (BC), A
                INC C
Span12:         LD (BC), A
                INC C
Span11:         LD (BC), A
                INC C
Span10:         LD (BC), A
                INC C
Span9:          LD (BC), A
                INC C
Span8:          LD (BC), A
                INC C
Span7:          LD (BC), A
                INC C
Span6:          LD (BC), A
                INC C
Span5:          LD (BC), A
                INC C
Span4:          LD (BC), A
                INC C
Span3:          LD (BC), A
                INC C
Span2:          LD (BC), A
                INC C
Span1:          LD (BC), A
                INC C
                ; -----------------------------------------
                ; Правый край широкой строки
                ; Обновление альтернативного шаблона для следующей строки перед чтением правой маски.
FinishWide:     XOR #00
                EX AF, AF'
                ; Запись правого крайнего байта с сохранением пикселей вне границы.
                LD A, IYL
                LD L, A
                LD A, (BC)
                AND (HL)
                INC L
                OR (HL)
                LD (BC), A
                ; -----------------------------------------
                ; Следующая строка и две ошибки
                ; Переключение страниц масок 8C/8D и продвижение упакованной левой границы.
AdvanceRow:     INC H
                RES 1, H
                EXX
                ADD IX, BC
                JR C, @Action.PolygonFillRows.CarryRow                          ; переход, если прибавление левого шага переполнило IX, увеличить старший байт линейного адреса

                ; Расчёт новой ошибки левой границы вычитанием LeftSubtract.
CorrectLeft:    LD A, L
                SUB #00
                JR NC, @Action.PolygonFillRows.KeepLeftError                    ; переход, если левая ошибка не дала заёма, дробная поправка границы не нужна

                ; Коррекция левой ошибки высотой ребра и сдвиг границы на минус один пиксель через SP=FFE0.
                ADD A, #00
                ADD IX, SP
KeepLeftError:  LD L, A
                ; Расчёт следующей правой границы и её дробной ошибки.
                ADD IY, DE
                LD A, H
                SUB #00
                JR NC, @Action.PolygonFillRows.KeepRightError                   ; переход, если правая ошибка не дала заёма, дробная поправка границы не нужна

                ; Коррекция правой ошибки высотой ребра и сдвиг границы на минус один пиксель.
                ADD A, #00
                ADD IY, SP
KeepRightError: LD H, A
                EXX
                ; Проверка текущей строки относительно изменяемого ближайшего предела.
                LD A, D
CheckRow:       CP #00
                JR NC, @Action.PolygonFillRows.RestoreStack                     ; переход, если текущая строка достигла RowLimit, выполнить установленное RowBranch продолжение

                ; -----------------------------------------
                ; Рисование текущей строки
                ; Продвижение счётчика D к следующей строке до обработки текущих IX и IY.
DrawRow:        INC D
                ; Выбор маски и байта левого края из упакованного IX.
                LD A, IXL
                LD L, A
                LD A, IXH
                LD C, A
                ; Расчёт разности адресов крайних байтов для выбора широкой либо однобайтовой записи.
                SUB IYH
                JR NC, @Action.PolygonFillRows.SameByte                         ; переход, если левый байт не предшествует правому, проверить общий байт либо пустую строку

                ; Расчёт младшего адреса развёрнутого продолжения, два байта кода на каждый средний байт.
                ADD A, A
                ; Обновление младшего байта JP по D243 перед исполнением развёрнутой записи.
                LD (#D244), A
                ; Запись левого крайнего байта с сохранением пикселей перед границей.
                LD A, (BC)
                AND (HL)
                INC L
                OR (HL)
                LD (BC), A
                ; Выбор первого среднего байта и перенос шаблона из альтернативного A в основной.
                INC C
                EX AF, AF'
                ; Переход к установленному SpanN либо FinishWide, исходный D100 является неисполняемым до настройки шаблоном операнда.
                JP @ActionPolygonPatterns.Mode0.Pattern

                ; Проверка совпадающего адреса двух крайних байтов.
SameByte:       JR NZ, @Action.PolygonFillRows.FlipNarrow                       ; переход, если левый байт расположен после правого, пропустить пиксели пустой строки

                ; Объединение масок левой и правой границы и формирование единственного изменённого байта.
                LD A, (HL)
                LD E, IYL
                LD L, E
                OR (HL)
                INC L
                LD E, A
                CPL
                AND (HL)
                LD L, A
                LD A, (BC)
                AND E
                OR L
                LD (BC), A
                ; Обновление альтернативного шаблона XOR разностью строк после узкой либо пустой строки.
FlipNarrow:     EX AF, AF'
                XOR #00
                EX AF, AF'
                JP @Action.PolygonFillRows.AdvanceRow

                ; Увеличение старшего байта линейного адреса до дробной коррекции левой границы.
CarryRow:       EXX
                INC B
                EXX
                JP @Action.PolygonFillRows.CorrectLeft

                ; -----------------------------------------
                ; Окончание и CPU-стек
                ; Восстановление сохранённого CPU SP, входного HL и внешнего адреса возврата.
RestoreStack:   LD SP, #0000
                POP HL
                RET

                ; -----------------------------------------
                endmodule
                endmodule
