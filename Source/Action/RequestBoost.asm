                module Action
                module RequestBoost
                ; Документация [проверка пространства перед ускорением](../../Docs/ActionBoostCommand.md)
                ; -----------------------------------------
                ; Запрос ускорения с проверкой классов и квантованных старших байтов координат
                ; исходная запись 17, перенесённое ядро банка 5, адреса 74A3..74FA
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, MotionOpcode=C9 запрещает команду до любых изменений
                ;   список FActionRecord от A100 с шагом 40 имеет достижимый маркер 8080, доступны ClassCode и три старших байта компонент
                ;   действуют договоры ReleaseBoostDebrisRecords и AdvanceBoost, банк 0 выбран, обычный стек допускает тридцать два дополнительных байта
                ;   IRQ и повторный вход исключены, существующие операнды Request и фаз ускорения доступны для изменения
                ; Out:
                ;   при MotionOpcode=C9 HL, DE и BC сохраняются, A=C9, F=42, RAM и paging сохраняются
                ;   иначе Request получает 1 до поиска, код не требует MotionOpcode=3A, остальные опкоды проходят первоначальный запрет
                ;   проверяются активные записи ClassCode<10 либо ClassCode=12, другие классы и свободные записи пропускаются
                ;   для каждой подходящей записи старший байт компоненты сохраняется при бите 7=0 либо инвертируется при бите 7=1
                ;   три результата объединяются OR, значение меньше 30 немедленно передаёт управление ReleaseBoostDebrisRecords
                ;   на этом пути HL указывает High первой компоненты препятствия, E=40, остальные выходы соответствуют ReleaseBoostDebrisRecords
                ;   при конечном маркере управление передаётся AdvanceBoost по 7504, действуют его выходы и побочные эффекты
                ;   сам запрос не записывает координаты просмотренных объектов, отказ не очищает уже установленный Request
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IY, R, Request, память и CPU-стек по выбранному дочернему пути
                ; Note:
                ;   это побитовое объединение квантованных байтов, не точное расстояние и не проверка сферической области
                ;   порог 30 не заменяется сравнением каждого байта по отдельности, исходное OR сохранено
                ;   хвост расположен после самостоятельной SelectFuelStock, переноса кода и новой памяти нет
                ;   69728 сквозных сценариев включают настоящие поиск и освобождение класса 14, создание класса 20 и шестнадцать вызовов шкалы
                ;   сверены регистры кроме R и тактов, все банки RAM и кратность записей вне тридцати двух временных байтов стека
                ;   полное произведение входов, IRQ, сборка и нативная игра не проверялись
                ; -----------------------------------------
                ; Проверка возвратного опкода координатной цепочки перед установкой запроса ускорения.
Entry:          LD A, (@ActionGaugeWordKeysState.MotionOpcode)
                CP #C9
                RET Z                                                           ; выход, если MotionOpcode равен C9, сохранить состояние

                ; Обновление общего Request до проверки пространства и доступного выбранного байта.
                LD A, #01
                LD (@ActionControlDecayState.Request), A
                ; Подготовка адреса перед первой записью списка, шаг равен размеру FActionRecord.
                LD HL, @ActionObjectRecords.Record00.Components.Component0.High - @FActionRecord
                LD DE, @FActionRecord
                JR @Action.RequestBoost.NextRecord

                ; Проверка младшего байта свободной записи, пара 8080 завершает поиск пространства.
CheckMarker:    DEC L
                LD A, (HL)
                INC L
                CP #80
                JR Z, @Action.AdvanceBoost.Entry                                ; переход, если Low свободной записи равен 80, продолжить в AdvanceBoost

                ; Поиск следующей записи, High=80 означает свободный слот.
NextRecord:     ADD HL, DE
                LD A, (HL)
                CP #80
                JR Z, @Action.RequestBoost.CheckMarker                          ; переход, если High равен 80, проверить конечный маркер

                ; Расчёт свёртки старшего байта первой компоненты, отрицательный байт инвертируется без прибавления единицы.
                OR A
                JP P, @Action.RequestBoost.FirstFolded                          ; переход, если старший байт неотрицательный, сохранить его

                CPL
FirstFolded:    LD C, A
                ; Чтение ClassCode через исходное смещение младшего байта адреса.
                LD A, L
                ADD A, #11
                LD L, A
                LD B, (HL)
                SUB #11
                LD L, A
                ; Проверка класса препятствия, допускаются значения меньше 10 и отдельный класс 12.
                LD A, B
                CP #12
                JR Z, @Action.RequestBoost.CheckOtherAxes                       ; переход, если ClassCode равен 12, проверить остальные компоненты

                CP #10
                JR NC, @Action.RequestBoost.NextRecord                          ; переход, если ClassCode не меньше 10 и не равен 12, пропустить запись

                ; Расчёт свёртки второго старшего байта и объединение с первой компонентой.
CheckOtherAxes: INC L
                INC L
                LD A, (HL)
                OR A
                JP P, @Action.RequestBoost.SecondFolded                         ; переход, если второй старший байт неотрицательный, сохранить его

                CPL
SecondFolded:   OR C
                LD C, A
                ; Расчёт свёртки третьего старшего байта и объединение всех трёх результатов.
                INC L
                INC L
                LD A, (HL)
                OR A
                JP P, @Action.RequestBoost.ThirdFolded                          ; переход, если третий старший байт неотрицательный, сохранить его

                CPL
ThirdFolded:    OR C
                LD C, A
                ; Восстановление адреса High первой компоненты и проверка объединённого квантованного признака.
                LD A, L
                SUB #04
                LD L, A
                LD A, C
                CP #30
                JP NC, @Action.RequestBoost.NextRecord                          ; переход, если объединённый байт не меньше 30, продолжить поиск

                ; Передача в освобождение всех записей класса 14, общий Request остаётся установленным.
                JP @Action.ReleaseBoostDebrisRecords.Entry

                endmodule
                endmodule
