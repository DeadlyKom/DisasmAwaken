                module Action
                module ReadWordFromIX
                ; Документация [алгоритм и проверка](../../Docs/ActionParameterActivation.md)
                ; -----------------------------------------
                ; Чтение слова младшим байтом вперёд через IX, продвижение IX на два и копирование C в B
                ; исходная запись 17, общий код фиксированного банка 2, смещения #4C38..#4C43
                ; In:
                ;   HL входных аргументов не задаёт, DE сохраняется, BC задаёт C для копирования в B, AF сохраняется
                ;   IX указывает младший байт читаемого слова, оба байта доступны в текущем отображении, на стеке внешний возврат, IRQ не вмешиваются
                ; Out:
                ;   HL содержит слово из входных (IX) и (IX+1), DE сохраняется, B=входной C, C сохраняется, AF сохраняется
                ;   HL', DE', BC', AF' сохраняются, IX=(входной IX+2) AND FFFF, IY, I, IM и IFF сохраняются
                ;   SP=входной SP+2, R получает 10 M1, RAM не записывается
                ; Corrupt:
                ;   HL, BC в части B, IX, R
                ; Note:
                ;   адрес второго байта и итоговый IX переходят через FFFF по модулю слова, знакового расширения нет
                ;   при совпадении IX с рамкой возврата читаются её фактические байты, чтение их не меняет
                ;   дополнительная рамка CPU-стека не создаётся
                ; -----------------------------------------
                ; восстановление B из сохранённого C перед чтением следующего двухбайтового элемента
Entry:          LD B, C
                ; чтение младшего байта и продвижение к старшему в текущем отображении памяти
                LD L, (IX+#00)
                INC IX
                ; чтение старшего байта и продвижение IX за прочитанное слово
                LD H, (IX+#00)
                INC IX
                RET

                endmodule
                endmodule
