                module Action
                module CheckClass17SpawnWindow
                ; Документация [алгоритм и проверка](../../Docs/ActionSpawnWindow.md)
                ; -----------------------------------------
                ; Проверка случайного окна создания класса 17 и загрузка байта допуска по полному классу
                ; исходная запись 17, адреса F222..F24E
                ; In:
                ;   H задаёт старший байт случайного слова, DE и BC числовых аргументов не задают, A задаёт проверяемый младший байт
                ;   IX указывает текущую FActionRecord с ClassCode, Unknown14 и входами SpawnClass17FromCurrentLink
                ;   действуют договоры общего создателя, доступны реальные байты F280+ClassCode, таблица индексируется без проверки верхней границы
                ;   ACTION банка 0 и перенесённый общий код банка 5 доступны, восемь дополнительных байтов CPU-стека доступны, IRQ исключены
                ; Out:
                ;   если A не равен F0, H меньше 5F, ClassCode равен 9 либо Unknown14 ненулевой, создание пропускается
                ;   после всех допусков выполняется SpawnClass17FromCurrentLink независимо от наличия свободного слота
                ;   после попытки создания Unknown14 получает байт по F280+текущий полный ClassCode, даже при отказе выделения
                ;   на пути попытки HL указывает выбранный байт, DE определён результатом создателя, BC равен полному классу, A прочитанный байт
                ;   F после попытки определяется ADD HL,BC с сохранением S/Z/PV от создателя, ранние F соответствуют последней проверке
                ;   альтернативные пары и IY определяются достигнутым создателем, IX, I/IM/IFF и paging сохраняются
                ;   PC=F0F8, внешний SP сохраняется, R на пути попытки включает 23 M1 собственного кода и полную стоимость создателя
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IY, R и эффекты создателя по достигнутому пути, Unknown14 и CPU-стек
                ; Note:
                ;   девять исходных табличных значений предназначены физическим индексам 0..8, но исходный код принимает все классы кроме 9
                ;   классы 0A..FF читают последующие физические байты, их ограничение либо расширение таблицы изменило бы игру
                ;   131072 сценария покрыли все пары A/H и все пары полного класса/Unknown14, настоящий создатель исполнен до общего продолжения
                ;   сверены точные регистры, флаги, R, восемь банков и кратность записей, общий F0F8 не исполнялся
                ;   полное произведение входов, аппаратные IRQ, точные T, сборка и нативная игра не проверялись
                ; -----------------------------------------
                ; Проверка точного младшего байта случайного слова перед остальными допусками создания.
Entry:          CP #F0
                JP NZ, @Action.PrepareObjectOffsetTransform.Entry               ; переход, если A не равен F0, сохранить Unknown14 и продолжить общий расчёт

                ; Проверка нижней границы старшего байта случайного слова.
                LD A, H
                CP #5F
                JP C, @Action.PrepareObjectOffsetTransform.Entry                ; переход, если H меньше 5F, сохранить Unknown14 и продолжить общий расчёт

                ; Проверка исключённого полного класса 9 без маскирования старшего бита.
                LD A, (IX + @FActionRecord.ClassCode)
                CP #09
                JP Z, @Action.PrepareObjectOffsetTransform.Entry                ; переход, если ClassCode равен 9, пропустить создание

                ; Проверка нулевого Unknown14 перед попыткой выделения связанного ребёнка.
                LD A, (IX + @FActionRecord.Unknown14)
                AND A
                JP NZ, @Action.PrepareObjectOffsetTransform.Entry               ; переход, если Unknown14 ненулевой, пропустить создание

                ; Создание класса 17 из Components и LinkedIndex текущей записи, отказ по слотам не отменяет следующий шаг.
                CALL @Action.SpawnClass17FromCurrentLink.Entry
                ; Расчёт адреса исходного байта допуска по полному классу без ограничения девятью табличными элементами.
                LD C, (IX + @FActionRecord.ClassCode)
                LD B, #00
                LD HL, @ActionClassSpawnValues.Class0.Value
                ADD HL, BC
                ; Обновление Unknown14 прочитанным физическим байтом даже после неудачного выделения.
                LD A, (HL)
                LD (IX + @FActionRecord.Unknown14), A
                JP @Action.PrepareObjectOffsetTransform.Entry

                endmodule
                endmodule
