                module Action
                module CheckCloseRecordBounds
                ; Документация [алгоритм и проверка](../../Docs/ActionCloseBounds.md)
                ; -----------------------------------------
                ; Проверка трёх исходных компонент с цепочкой Carry и условная обработка близкой записи
                ; исходная запись 17, код ACTION банка 0, адреса E1D1..E212, при обычном выходе продолжение в ClipProjectionBounds, смещения #81D1..#8212
                ; In:
                ;   HL исходное слово границы, DE числового аргумента не задаёт, BC сохраняется на обычном выходе
                ;   AF числового аргумента не задаёт, A сохраняется до условного вызова диспетчера
                ;   HL' адрес читаемой FActionRecord для возможного DispatchCloseRecord, остальные альтернативные входы аргументов не задают
                ;   Input0, Input2 и Input1 задают три исходных слова, они проверяются именно в таком порядке
                ;   действует договор DispatchCloseRecord с его дочерними обработчиками, банк 0 выбран, 7FFD не заблокирован
                ;   временная рамка до десяти байтов не перекрывает код и состояние, IRQ не вмешиваются
                ; Out:
                ;   первая проверка использует unsigned-половину исходной границы и Carry от её младшего бита
                ;   для неотрицательной компоненты выполняется SBC границы с компонентой и текущим Carry, для отрицательной ADC с тем же Carry
                ;   вторая и третья проверки восстанавливают полное исходное слово границы, Carry передаётся от предыдущего сравнения
                ;   при установленном знаковом бите результата первой или второй проверки диспетчер не вызывается, третья вызывает его только при Sign=0
                ;   при обычном продолжении PC=E213, SP входной, DE получает исходный HL, BC восстанавливается из рамки
                ;   без вызова диспетчера HL последняя арифметическая сумма или разность, A входной, F от последнего ADC либо SBC
                ;   после вернувшегося диспетчера HL, AF и IX соответствуют его результату, затем DE и BC восстанавливаются
                ;   при передаче класса 12 через диспетчер PC=DCE3 банка 1, SP=входной SP-6, DE=0, BC входной, AF=1142, IX=входной HL'
                ;   HL', DE', BC', AF', IY, I, IM и IFF сохраняются в локальных границах, 7FFD меняется только при передаче следующему режиму
                ; Corrupt:
                ;   HL, DE, AF, IX при допуске диспетчера, R, временная рамка до десяти байтов, состояние диспетчера при инверсии, 7FFD при передаче
                ; Note:
                ;   перенос не сбрасывается между компонентами, заменять алгоритм тремя независимыми сравнениями модулей нельзя
                ;   для исходной границы 1 и Input0=0 первый SBC получает входной заём 1 и возвращает FFFF, условный вызов не выполняется
                ;   при границе 1 и Input0=FFFF первый ADC с Carry=1 даёт 0000 и допускает следующую проверку
                ;   проверяется Sign полученного слова, знаковое переполнение отдельно не исправляется
                ;   обычный путь использует до четырёх байтов рамки без вызова, до шести при запрете диспетчера, до восьми при его обычной обработке
                ;   передача следующему режиму использует до десяти дополнительных байтов, сохранённые BC, граница и E211 не извлекаются
                ;   продолжения E213 и DCE3 не исполнялись локальной моделью, полный обход и дисковая загрузка этим договором не доказываются
                ; -----------------------------------------
                ; Сохранение входного BC и полного слова границы перед тремя проверками.
Entry:          PUSH BC
                PUSH HL
                ; Расчёт unsigned-половины границы, младший бит исходного слова становится Carry первого сравнения.
                SRL H
                RR L
                ; Проверка знака Input0, BIT сохраняет Carry от RR L.
                LD DE, (@ActionPatchedVectorState.Input0)
                BIT 7, D
                JR Z, @Action.CheckCloseRecordBounds.SubtractFirst              ; переход, если Input0 неотрицателен, вычесть его вместе с текущим Carry

                ; Расчёт половины границы плюс отрицательный Input0 и входной Carry, перенос дальше не сбрасывается.
                ADC HL, DE
                JP @Action.CheckCloseRecordBounds.CheckFirst

                ; Расчёт половины границы минус неотрицательный Input0 и входной заём.
SubtractFirst:  SBC HL, DE
                ; Проверка знакового бита первого результата, без отдельной обработки Overflow.
CheckFirst:     JP M, @Action.CheckCloseRecordBounds.RestoreFrame               ; переход, если знаковый бит первой проверки установлен, восстановить рамку без диспетчера

                ; -----------------------------------------
                ; Проверка Input2
                ; Восстановление полной границы, POP и PUSH не изменяют Carry предыдущего сравнения.
                POP HL
                PUSH HL
                ; Проверка знака Input2 с сохранением цепочки Carry.
                LD DE, (@ActionPatchedVectorState.Input2)
                BIT 7, D
                JR Z, @Action.CheckCloseRecordBounds.SubtractThird              ; переход, если Input2 неотрицателен, вычесть его с текущим займом

                ; Расчёт полной границы плюс отрицательный Input2 и текущий Carry.
                ADC HL, DE
                JP @Action.CheckCloseRecordBounds.CheckThird

                ; Расчёт полной границы минус неотрицательный Input2 и текущий заём.
SubtractThird:  SBC HL, DE
CheckThird:     JP M, @Action.CheckCloseRecordBounds.RestoreFrame               ; переход, если знаковый бит проверки Input2 установлен, восстановить рамку без диспетчера

                ; -----------------------------------------
                ; Проверка Input1
                ; Повторное восстановление полной границы с сохранением Carry второй проверки.
                POP HL
                PUSH HL
                ; Проверка знака Input1, текущий Carry поступит в последний ADC либо SBC.
                LD DE, (@ActionPatchedVectorState.Input1)
                BIT 7, D
                JR Z, @Action.CheckCloseRecordBounds.SubtractSecond             ; переход, если Input1 неотрицателен, вычесть его с текущим займом

                ; Расчёт полной границы плюс отрицательный Input1 и текущий Carry.
                ADC HL, DE
                JP @Action.CheckCloseRecordBounds.DispatchRecord

                ; Расчёт полной границы минус неотрицательный Input1 и текущий заём.
SubtractSecond: SBC HL, DE
DispatchRecord: CALL P, @Action.DispatchCloseRecord.Entry                       ; вызов, если знаковый бит третьей проверки сброшен, выполнить DispatchCloseRecord
                ; -----------------------------------------
                ; Обычное продолжение после проверок
                ; Восстановление полной границы в DE и входного BC, путь передачи режима сюда не возвращается.
RestoreFrame:   POP DE
                POP BC
                ; JP @Action.ClipProjectionBounds.Entry, продолжение в ClipProjectionBounds.asm

                ; -----------------------------------------
                endmodule
                endmodule
