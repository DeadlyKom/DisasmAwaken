                module Action
                module FindFilteredRecordOr26
                ; Изменяемый порог [параметры и проверка](../../Docs/ActionParameterThresholds.md)
                ; Документация [алгоритм и проверка](../../Docs/ActionRandomFilteredRecord.md)
                ; -----------------------------------------
                ; Выбор кода 26 по потоку 10 либо поиск активного класса 1..15 или 18
                ; исходная запись 17, адреса E6E2..E70C
                ; In:
                ;   HL, DE, BC, AF аргументов не задают, D сохраняется, действуют условия NextRandomWord10
                ;   в окне C000 выбран банк 0, Stream10 доступен для чтения и записи
                ;   список от Record00 содержит достижимую подходящую активную запись либо маркер 80,80
                ;   на CPU-стеке внешний возврат, шесть байтов ниже доступны вложенным вызовам, IRQ не вмешивается
                ; Out:
                ;   HL содержит новый LowWord потока 10, D сохраняется
                ;   если младший байт нового слова не меньше текущего RandomLowLimit, A=1A, F=0A, DE, BC и IY сохраняются
                ;   иначе BC=FActionRecord, IY указывает найденную запись либо маркер, A и F возвращаются от поиска
                ;   при находке A=индекс, E=ClassCode+1, F от INC E с Carry=0 в проверенной области списка
                ;   при маркере A=80, F=42, E=последний проверенный класс либо входной E при отсутствии активных строк
                ;   HL'=Stream10, DE'=новый LowWord, B'=0, C'=младший байт промежуточного n генератора, AF', IX сохраняются
                ;   SP=входной SP+2, I, IM, IFF и страница сохраняются, Stream10 всегда обновляется
                ;   R получает 73 M1 для кода 26, иначе 76 плюс стоимость поиска, бит 7 сохраняется
                ; Corrupt:
                ;   HL, E, BC, AF, HL', DE', BC', IY, R, три байта Stream10 и до шести байтов CPU-стека
                ; Note:
                ;   код 26 является исходным отдельным результатом и не объявляется найденным индексом, его полная игровая роль ещё не доказана
                ;   поиск исключает класс 0, принимает 1..15 и 18, остальные активные классы пропускает
                ;   пара INC A и DEC A формирует F=0A на пути 1A, Carry остаётся от сравнения нового L с текущим RandomLowLimit
                ;   81745 сценариев включили все слова состояния при FoldByte=0 и все FoldByte на пяти границах слова
                ;   исполнены настоящий генератор, итератор и преобразование индекса, проверены все регистры включая R, восемь банков RAM и кратность записей
                ;   26 исследовательских позиций не задают игровую ёмкость, полный домен состояния и списков, распределение, период, IRQ, точные T, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; Обновление только физического Stream10 и получение нового слова для выбора ветви.
Entry:          CALL @Action.NextRandomWord10.Entry
                LD A, L
                ; Проверка младшего байта нового слова, вероятность из порога без доказанного распределения не выводится.
                CP @ActionRandomRecordConst.Threshold
                ; Подготовка отдельного кода 1A, INC и DEC сохраняют его, но задают исходные флаги.
                LD A, @ActionRandomRecordConst.DefaultCode
                INC A
                DEC A
                RET NC                                                          ; выход, если младший байт нового слова не меньше текущего RandomLowLimit, вернуть код 1A

                ; Выбор позиции перед первой записью и исходного шага FActionRecord.
                LD IY, @ActionObjectRecords.Record00-@FActionRecord
                LD BC, @FActionRecord
                ; Поиск следующей активной строки либо маркера, неактивные строки пропускает сам итератор.
ScanNext:       CALL @Action.NextActiveRecord.Entry
                RET Z                                                           ; выход, если достигнут маркер конца 80,80

                ; Чтение полного числового ClassCode активной строки.
                LD E, (IY + @FActionRecord.ClassCode)
                LD A, E
                ; Проверка исключённого нулевого класса.
                CP @ActionRandomRecordConst.ClassZero
                JR Z, @Action.FindFilteredRecordOr26.ScanNext                   ; переход, если ClassCode равен нулю, продолжить поиск

                ; Проверка отдельного разрешённого класса 18.
                CP @ActionRandomRecordConst.Class18
                JR Z, @Action.FindFilteredRecordOr26.IndexRecord                ; переход, если ClassCode равен 18, получить индекс

                ; Проверка верхней границы остальных разрешённых классов 1..15.
                CP @ActionRandomRecordConst.ClassLimit
                JR NC, @Action.FindFilteredRecordOr26.ScanNext                  ; переход, если ClassCode не меньше 16 и не равен 18, продолжить поиск

                ; Расчёт индекса выбранного IY, новый LowWord в HL сохраняется.
IndexRecord:    CALL @Action.RecordIYToIndex.Entry
                ; Формирование ненулевого результата по принятому ClassCode+1.
                INC E
                RET

                endmodule
                endmodule
