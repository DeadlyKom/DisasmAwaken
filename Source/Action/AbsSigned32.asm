                module Action
                module AbsSigned32
                ; Документация [алгоритм и проверка](../../Docs/ActionAbsSigned32.md)
                ; -----------------------------------------
                ; Модуль знакового 32-битного DE:HL с сохранением исходного переполнения минимального значения
                ; исходная запись 17, перенесённое ядро 6000..7F8E, смещения #21B3..#21CB
                ; In:
                ;   HL содержит младшие 16 бит, DE старшие 16 бит знакового числа DE:HL
                ;   BC сохраняется на неотрицательном пути, AF задаёт сохраняемые A и Carry только этого пути
                ;   на CPU-стеке внешний возврат, исходный перенесённый код доступен, IRQ не вмешиваются
                ; Out:
                ;   если разряд 31 нулевой, HL, DE, BC и A сохранены, F=54 OR (D AND 28) OR входной Carry
                ;   иначе DE:HL=(-входной DE:HL) AND FFFFFFFF, BC=0, A=входной L XOR FF
                ;   на отрицательном пути F соответствует ADC от дополнения входного DE и переноса, равного единице только при входном HL=0
                ;   HL', DE', BC', AF', IX, IY сохраняются, I, IM, IFF и страница сохраняются
                ;   SP=входной SP+2, RAM и CPU-стек не записываются, R получает 3 либо 23 M1 с сохранением бита 7
                ; Corrupt:
                ;   HL, DE, BC и A только при отрицательном входе, F и R на обоих путях
                ; Note:
                ;   число 80000000 остаётся 80000000, финальный ADC возвращает для него F=94 и P/V=1, насыщение не добавляется
                ;   начальный BIT меняет F даже на раннем выходе, сохранение всего AF на неотрицательном пути не обещается
                ;   729088 сценариев проверили все младшие слова на четырёх старших границах и все старшие слова на пяти младших границах
                ;   все входные AF проверены для обоих знаков, сопоставлены регистры включая R, записи RAM отсутствовали во всех сценариях
                ;   все восемь банков после проверки совпали с начальным состоянием, полный 32-битный домен, IRQ, точные T, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; Проверка знака полного 32-битного числа по разряду 7 старшего байта D.
Entry:          BIT @ActionAbs32Const.SignBit, D
                RET Z                                                           ; выход, если DE:HL неотрицателен, сохранить значение, A и BC

                ; Расчёт побитового дополнения всех 32 разрядов перед прибавлением единицы.
                LD A, D
                CPL
                LD D, A
                LD A, E
                CPL
                LD E, A
                LD A, H
                CPL
                LD H, A
                LD A, L
                CPL
                LD L, A
                ; Расчёт младшего слова отрицания, Carry после прибавления единицы передаётся старшему слову.
                LD BC, @ActionAbs32Const.NegateUnit
                ADD HL, BC
                DEC BC
                EX DE, HL
                ; Расчёт старшего слова с переносом младшей части, исходный минимум 80000000 сохраняется с P/V.
                ADC HL, BC
                EX DE, HL
                RET

                endmodule
                endmodule
