                module Action
                module ComputeBottomClipProduct
                ; Документация [алгоритм и проверка](../../Docs/ActionClipProducts.md)
                ; -----------------------------------------
                ; Подготовка числителя пересечения (First.First-95)*(First.Second-Second.Second) исходным знаковым умножителем
                ; исходная запись 17, банковое окно ACTION банка 0, смещения #6496..#64B4
                ; In:
                ;   две исходные точки по CF0B и CF1B содержат signed16 Second и First, ClipCode не читается
                ;   ACTION банка 0 доступен, выходной четырёхбайтовый слот доступен на запись, IRQ не вмешиваются
                ;   на CPU-стеке внешний возврат и четыре дополнительных свободных байта
                ; Out:
                ;   HL содержит старшее слово, DE младшее слово результата (First.First-95)*(First.Second-Second.Second) с особенностями MultiplySigned16
                ;   полный результат записан в BottomProduct, сначала младшее слово, затем старшее
                ;   BC, AF и IX соответствуют MultiplySigned16 с первым HL и вторым DE аргументами, IXH отдельно не сохраняется при полном ядре
                ;   HL', DE', BC', AF', IY, I, IM, IFF и paging сохраняются, SP после RET равен входному SP+2, R меняется
                ; Corrupt:
                ;   HL, DE, BC, AF, IX по ядру умножения, R, выходной слот и четыре байта CPU-стека
                ; Note:
                ;   разности оборачиваются до 16 бит, Carry перед каждым SBC очищается отдельно
                ;   порядок аргументов существенен, второй операнд 8000 наследует исходное исключение полного ядра
                ;   проверены 4140 сценариев этого входа с настоящим дочерним кодом, точные регистры и флаги кроме R, вся RAM и кратность записей
                ;   общая проверка четырёх входов содержит 16560 сценариев, все совместные входы, R/T, IRQ, сборка и нативный вывод не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Подготовка числителя пересечения
                ; Чтение первого вычитания для второго операнда DE, исходный порядок множителей сохраняется.
Entry:          LD BC, (@ActionClipPoints.SecondPoint.Second)
                LD HL, (@ActionClipPoints.FirstPoint.Second)
                ; Расчёт первой разности с очищенным Carry и оборачиванием до слова.
                OR A
                SBC HL, BC
                EX DE, HL
                ; Чтение аргументов второго вычитания для первого операнда HL.
                LD BC, @ActionClipProductConst.FirstMaximum
                LD HL, (@ActionClipPoints.FirstPoint.First)
                OR A
                SBC HL, BC
                ; Расчёт полного произведения настоящим MultiplySigned16 с исходным исключением 8000.
                CALL @Action.MultiplySigned16.Entry
                ; Сохранение младшего слова результата в существующем выходном слоте.
                LD (@ActionClipProductsData.BottomProduct.LowWord), DE
                ; Сохранение старшего слова, четыре исходных байта результата не переставляются.
                LD (@ActionClipProductsData.BottomProduct.HighWord), HL
                RET

                endmodule
                endmodule
