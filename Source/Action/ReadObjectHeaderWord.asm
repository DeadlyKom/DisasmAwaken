                module Action
                module ReadObjectHeaderWord
                ; Документация [алгоритм и проверка](../../Docs/ActionObjectHeader.md)
                ; -----------------------------------------
                ; Чтение слова по указателю страницы 9E из банка OBJECT3D с последующим выбором банка 0
                ; исходная запись 17, общий код фиксированного банка 2, адреса AACC..AAE1, смещения #4ACC..#4AE1
                ; In:
                ;   HL, DE и BC числовых аргументов не задают, DE и BC сохраняются
                ;   A байтовое смещение в странице указателей 9E00, чётность и числовой диапазон процедурой не проверяются
                ;   входной Carry сохраняется в итоговом F, остальные входные флаги аргументов не задают
                ;   банк 4 содержит OBJECT3D, общая страница 9E доступна, 7FFD не заблокирован, IRQ не вмешиваются
                ;   общий CPU-стек содержит внешний возврат и допускает четыре дополнительных байта
                ; Out:
                ;   HL слово little-endian по считанному указателю, первая часть указателя по 9E00+A, вторая по 9E00+((A+1) AND FF)
                ;   чтение второго байта результата использует полный адрес указателя плюс один по модулю 65536, это отличается от оборачивания индекса таблицы
                ;   DE и BC сохраняются, A=10, F соответствует INC входного A с сохранением входного Carry
                ;   HL', DE', BC', AF', IX, IY, I, IM и IFF сохраняются, SP=входной SP+2
                ;   OUT 7FFD получает 14, затем 10, итоговая полная конфигурация 10 выбирает банк 0, входная конфигурация не восстанавливается
                ;   R получает 27 M1, данные объекта и таблица указателей не записываются
                ; Corrupt:
                ;   HL, AF, R, четыре байта временного CPU-стека, регистр 7FFD
                ; Note:
                ;   Z итогового F означает входной индекс FF, он не проверяет нулевой заголовок объекта
                ;   подготовка банка 4 установлена по ключу OBJECT3D загрузчика InitializeFlight, смысл двух байтов заголовка ещё требует полного потребителя
                ;   модель проверяет и нечётные индексы как физическое чтение, это не доказательство их допустимости в игре
                ;   неизвестный хвост банка 4 в модели заполнен A4, результаты чтений вне загруженного файла не выдаются за реальные игровые данные
                ; -----------------------------------------
                ; Поиск двух байтов указателя по входному смещению A, индекс задаёт байт, а не номер объекта.
Entry:          LD L, A
                LD H, @ActionObjectCopyConst.PointerPage
                ; Чтение младшего байта адреса и переход к старшему внутри той же страницы 9E, при FF индекс оборачивается в 00.
                LD A, (HL)
                INC L
                LD H, (HL)
                LD L, A
                ; -----------------------------------------
                ; Чтение слова из контекста банка 4
                ; Выбор полного значения 14 для банка 4 и ROM 1 с сохранением флагов INC L.
                LD A, @ActionObjectCopyConst.DataPage
                CALL @Action.SelectMemoryPage.Entry
                ; Чтение двух байтов результата с полным увеличением адреса, слово может пересечь границу окна.
                LD A, (HL)
                INC HL
                LD H, (HL)
                LD L, A
                ; -----------------------------------------
                ; Возврат к контексту ACTION
                ; Выбор полной конфигурации 10, прежнее отображение не восстанавливается.
                LD A, @ActionBankPage.Runtime
                CALL @Action.SelectMemoryPage.Entry
                RET

                ; -----------------------------------------
                endmodule
                endmodule
