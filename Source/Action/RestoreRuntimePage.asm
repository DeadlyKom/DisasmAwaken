                module Action
                module RestoreRuntimePage
                ; Документация [алгоритм и проверка](../../Docs/ActionBankedCallbackReturn.md)
                ; -----------------------------------------
                ; Выдача конфигурации 10 в 7FFD и возврат внешнему вызывающему после банкового обработчика
                ; исходная запись 17, адреса 6D00..6D05
                ; In:
                ;   HL, DE, BC сохраняются, AF задаёт сохраняемый F, исходный A не используется
                ;   на CPU-стеке внешний возврат после уже снятого обработчиком адреса 6D00, нужны ещё четыре временных байта
                ;   код фиксированного банка 5 и SelectMemoryPage банка 2 доступны, IRQ не вмешиваются
                ; Out:
                ;   HL, DE, BC, F, HL', DE', BC', AF', IX, IY сохраняются, A=10
                ;   в порт 7FFD выдан 10, при исходной блокировке выбранная конфигурация остаётся прежней
                ;   SP=входной SP+2, R получает 9 M1 с сохранением бита 7, I, IM и IFF сохраняются
                ;   четыре временных байта стека содержат сохранённый BC и адрес 6D05, других записей RAM нет
                ; Corrupt:
                ;   A, R, четыре временных байта CPU-стека, 7FFD при незаблокированном переключении
                ; Note:
                ;   входная конфигурация не восстанавливается, выбирается фиксированное значение Runtime
                ;   это отдельно доказанный возвратный хвост, результат произвольного банкового обработчика не моделируется
                ;   393216 сценариев проверили все BC и AF при шести исходных страницах, точные регистры, RAM, записи и настоящий OUT
                ;   полное произведение входных регистров, IRQ, точные T, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; Выбор фиксированной конфигурации ACTION после RET банкового обработчика, прежняя страница не восстанавливается.
Entry:          LD A, @ActionBankPage.Runtime
                ; Обновление настоящего порта 7FFD с сохранением F и остальных регистров через SelectMemoryPage.
                CALL @Action.SelectMemoryPage.Entry
                RET

                endmodule
                endmodule
