                module Intro
                module BuildPairedPointers
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
; -----------------------------------------
; Запись A пар одинаковых указателей в соседние страницы с шагом BC по значению
; исходная запись 3, файловые смещения #06A3..#06B5
; In:
;   HL - таблица, DE - первый указатель, BC - приращение указателя, AF - A число записей
; Out:
;   указатели записаны в HL и HL+#100, DE увеличен на BC для каждой записи, A равен нулю
; Corrupt:
;   HL, DE, AF
; Note:
;   между записями увеличивается только L на четыре, перенос в H отсутствует
;   нулевой A означает 256 итераций, размещение должно выдерживать повторное использование младшего байта
; -----------------------------------------
                ; создание одинакового указателя в двух соседних страницах таблицы
Entry:          LD (HL), E
                INC L
                LD (HL), D
                INC H
                LD (HL), D
                DEC L
                LD (HL), E
                DEC H
                EX DE, HL
                ADD HL, BC
                EX DE, HL
                INC L
                INC L
                INC L
                INC L
                DEC A
                JR NZ, @Intro.BuildPairedPointers.Entry                         ; переход, если остались пары указателей для записи


                RET


                endmodule
                endmodule
