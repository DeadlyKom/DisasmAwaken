                module NextSampledRow
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
; -----------------------------------------
; Продолжение генерируемого обработчика, переход к следующей строке и восстановление SP
; исходная запись 3, файловые смещения #03F3..#03FA
; In:
;   Unknown, регистровый контракт ещё не доказан
; Out:
;   исходный поток управления, включая переходы в соседние фрагменты
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, консервативная верхняя граница
; Note:
;   граница файла не доказывает границу логической процедуры
;   состояние самомодификации и активной страницы учитывается отдельно
;   это продолжение SampleTextureRows, отдельно вызывать через CALL нельзя
;   после 16 строк возвращается первоначальный SP, RET использует исходный адрес возврата
; -----------------------------------------
Entry:          INC D
                EXX
                DJNZ @Intro.SampleTextureRows.Point66E8

                ; восстановление настоящего SP после последней строки выборок
                LD SP, #3131
                RET


                endmodule
                endmodule
