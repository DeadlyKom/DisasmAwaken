                module NextSampledRow
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
                ; Документация [алгоритм и проверка](../../Docs/IntroScrolledSampler.md)
; -----------------------------------------
; Продолжение генерируемого обработчика, переход к следующей строке и восстановление SP
; исходная запись 3, файловые смещения #03F3..#03FA
                ; In:
                ;   HL - последний адрес выборки строки, DE - D текущая страница назначения, E=0, BC - смещение источника
                ;   AF - A последний выбранный байт, Carry от последнего ADD HL,BC
                ;   HL' - курсор следующей страницы указателей, DE' - сохраняемый контекст основного входа, BC' - B' оставшееся число строк 1..16 и C' сохраняемый байт
                ;   SP - временный курсор после 64 слов, SavedSP содержит внешний CPU SP основного входа
                ; Out:
                ;   D увеличен на один до EXX, затем наборы HL/DE/BC меняются местами
                ;   при прежнем B'=1 после EXX B=0, HL и DE восстановлены из входных альтернативных регистров, C сохранён из входного C'
                ;   при прежнем B' больше единицы выполняются оставшиеся строки через ReadNextRow
                ;   при завершении F от последнего INC D, Carry от последнего сложения адреса, SP восстановлен из SavedSP и увеличен RET на два
                ;   AF', IX и IY сохраняются, I/IM/IFF и paging сохраняются
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', назначения оставшихся строк
                ; Note:
                ;   это продолжение JP из последней сгенерированной выборки, обычный CALL недопустим
                ;   DJNZ относится к счётчику основного входа, расположенному до EXX в B', флаги он не меняет
                ;   при окончании собственных записей RAM нет, внешний CPU-стек только читается
                ;   контекст входа проверен в составе всех 16 строк основной модели, отдельный произвольный вход не доказан
                ; -----------------------------------------
Entry:          INC D
                EXX
                DJNZ @Intro.SampleTextureRows.ReadNextRow

                ; восстановление настоящего SP после последней строки выборок
                LD SP, #3131
                RET


                endmodule
                endmodule
