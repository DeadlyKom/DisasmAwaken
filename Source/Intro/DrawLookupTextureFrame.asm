                module DrawLookupTextureFrame
                ; Документация [столбцовый и табличный эффекты](../../Docs/IntroGeneratedEffects.md)
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
; -----------------------------------------
; Ожидание кадра, обновление масштаба и фаз перед формированием текстурного кадра
; исходная запись 3, файловые смещения #0893..#089B
                ; In:
                ;   параметры масштаба и фаз подготовлены, действуют условия RenderLookupTexture для цепочек, таблиц и назначений
                ;   WarmupLeft=1..161, RampLevel=0..63, CycleIndex=0..39, три записи FTexturePhase и страница 64 доступны
                ;   IM=1, выбран проверенный 48K ROM, IY=5C3A либо отдельный профиль 5C0F, клавиши отпущены, обе KSTATE равны FF
                ;   16 байтов ниже входного SP доступны, CPU-стек не пересекается с кодом, системными переменными, таблицами и записями фаз
                ;   источник IRQ работает, после одного IRQ на HALT следующий не вмешивается в обновление фаз и временный SP рендера
                ; Out:
                ;   на границе RenderLookupTexture HL содержит следующий SampleCursor в странице 64, DE эффективный StepDelta третьей фазы, BC её прежний Phase
                ;   AF содержит половину выбранного байта страницы 64 и флаги SRL этого байта
                ;   HL', DE', BC', AF', IX и IY сохраняются, SP равен входному, I сохранён, IM=1, IFF=1 после AdvanceParameters
                ;   обновлены счётчики масштаба, три записи фаз, PointerRow и четыре фазовых операнда
                ;   при IY=5C3A FRAMES увеличен modulo 16777216, при IY=5C0F перенос младшего слова увеличивает 5C4F вместо 5C7A
                ;   после последнего CALL исполнение продолжается в RenderLookupTexture без дополнительного слова возврата
                ;   последующий вывод и возврат определяются отдельными договорами рендера и его продолжения
                ; Corrupt:
                ;   HL, DE, BC, AF, R, IFF, FRAMES, рабочие байты CPU-стека, записи фаз, счётчики масштаба и фазовые операнды
                ;   операнд сохранения SP по 6A47, PointerRow и SampleCursor, при IY=5C0F и переносе младшего слова также 5C4F
                ;   после передачи действуют побочные эффекты RenderLookupTexture и его продолжения
                ; Note:
                ;   512 сценариев проверили вход до рендера, обе ветви масштаба, знаки фаз, перенос курсора, два IY и два FRAMES
                ;   выполнены исходные три CALL и настоящий ROM, принят один IRQ на HALT WaitInterrupt, IFF после него снова разрешается обновлением фаз
                ;   естественная достижимость IY=5C0F на этом входе, R, точное время, другие клавиши и нативный запуск не доказаны
                ;   обычный экранный путь предполагает исходный CALL в 6BDA, зеркальный режим описан отдельно
; -----------------------------------------
Entry:          CALL @Intro.WaitInterrupt.Entry
                CALL @Intro.AdvanceTextureScale.Entry
                CALL @Intro.AdvanceTexturePhases.Entry
                ; JP @Intro.RenderLookupTexture.Entry, продолжение в RenderLookupTexture.asm

