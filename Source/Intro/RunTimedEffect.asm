                module Intro
                module RunTimedEffect
                ; Документация [рамка шага и два выхода](../../Docs/IntroStationTransition.md#счётчик-и-два-выхода-runtimedeffect)
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
                ; Имена внутренних входов [алгоритмы вступления](../../Docs/IntroInternalLabels.md)
; -----------------------------------------
; Повторение обработчика HL в течение BC шагов с проверкой клавиши Space
; исходная запись 3, файловые смещения #074B..#0766
                ; In:
                ;   HL адрес обработчика шага, DE его контекст, BC шестнадцатибитное число шагов, AF передаётся первому вызову после проверки порта
                ;   операнд StepCall доступен для записи, обработчик возвращается обычным RET и не повреждает код контроллера или его сохранённый счётчик
                ;   ниже входного SP доступны четыре байта собственной рамки и дополнительные кадры обработчика и IRQ, они не перекрывают код и bitmap
                ;   обработчик и ISR имеют допустимый контекст, штатный профиль задаёт DrawFinalTextureFrame, BC=300 и фактический IY=5C0F
                ; Out:
                ;   без раннего выхода обработчик вызывается исходное BC раз, при исходном нуле 65536, каждый вызов получает текущий убывающий счётчик BC
                ;   после исчерпания счётчика EI разрешает IRQ, FillBitmap с C=0 очищает 4000..4FFF и возвращается по внешнему адресу
                ;   на обычном возврате HL=5000, DE содержит последний D обработчика и E=E0, BC=0, AF=0041, SP=входной SP+2 и IFF=1 при сохраняющем контекст ISR
                ;   при точном ответе порта BE управление передаётся в 5D3B через EnterStation, AF=BE6A, BC=7FFE, SP=входной SP-4
                ;   ранний путь не исполняет FillBitmap и не снимает внешний возврат, на стеке остаются сохранённые AF и BC
                ;   альтернативные регистры, IX, IY, I и IM определяются обработчиком и ISR, собственный контроллер их не меняет
                ; Corrupt:
                ;   HL, DE, BC, AF, R, IFF, SP по выбранному выходу, два байта операнда StepCall и временные слова CPU-стека
                ;   bitmap 4000..4FFF при обычном завершении, прочая память, регистры и порты по договорам переданного обработчика и ISR
                ; Note:
                ;   нулевой BC даёт 65536 повторений, адрес StepCall записывается в его операнд перед первым шагом
                ;   перед каждым шагом читается порт 7FFE, сравнивается весь байт с BE, другие ответы не завершают контроллер
                ;   перед вызовом обработчика POP AF восстанавливает сохранённые флаги, результат проверки порта ему не передаётся
                ;   после обработчика POP BC восстанавливает счётчик независимо от возвращённого BC, затем он уменьшается и проверяется целиком
                ;   выход по клавиатуре оставляет временную рамку, завершающий загрузчик самостоятельно устанавливает SP
                ;   конец файлового фрагмента переходит в FillBitmap без CALL, Source/Files/03_AWAKEN.inc задаёт жёсткий порядок 0 и 1
                ;   четыре сквозных профиля с BC=300 исполнили 0, 1, 2 и 300 настоящих шагов, проверены последовательность счётчиков и SP
                ;   нулевой входной BC, произвольный обработчик, все моменты IRQ, точный R всего контроллера и нативное нажатие этим прогоном не проверены
; -----------------------------------------
Entry:          LD (@Intro.RunTimedEffect.StepCall + 1), HL
CheckSpace:     PUSH BC
                PUSH AF
                LD BC, #7FFE
                IN A, (C)
                CP #BE
                JP Z, @Intro.InitializeIntro.EnterStation                       ; переход, если строка клавиатуры равна #BE и вступление нужно завершить


                POP AF
                POP BC
                PUSH BC
StepCall:       CALL #CDCD
                POP BC
                DEC BC
                LD A, B
                OR C
                JR NZ, @Intro.RunTimedEffect.CheckSpace                         ; переход, если счётчик шагов эффекта BC ещё не обнулился


                EI
                ; JP @Intro.FillBitmap.Entry, продолжение в FillBitmap.asm

                endmodule
                endmodule
