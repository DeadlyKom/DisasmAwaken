                module Intro
                module BuildAlternatingTexture
                ; Физические параметры [источники и потребители](../../Docs/IntroPhysicalParameters.md)
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
                ; Имена внутренних входов [алгоритмы вступления](../../Docs/IntroInternalLabels.md)
                ; Преобразование после построителя [разбор](../../Docs/IntroGeneratedEffects.md#чередующееся-преобразование-текстуры)
; -----------------------------------------
; Построение текстуры с чередованием исходного байта и байта, уменьшенного в четыре раза, копия в банк 6
; исходная запись 3, файловые смещения #0338..#0362
; In:
;   страница #6400 содержит 256 координат, параметры #6663..#66A1 сохранены в исходном виде
;   7FFD разблокирован, рабочие банки 1, 2 и 6 доступны, код находится в общей RAM
;   внешний возврат и четыре байта под SP расположены ниже #8000 вне кода, координат и параметров
;   локальный договор предполагает отсутствие вмешательства IRQ/NMI, IFF процедура не меняет
; Out:
;   HL - #C000, DE - 0, BC - 0, AF - A=#16, F определяется последними двумя байтами таблицы
;   IX - #6400, IYL - #29 после чтения последнего из 63 исходных параметров
;   IYH, альтернативные регистры, I, IM и IFF сохраняются, SP равен входному SP+2
;   банк 2 содержит преобразованную текстуру, банк 6 её полную копию, выбран банк 6 конфигурацией #16
; Corrupt:
;   HL, DE, BC, AF, IX, IYL, R, банки 1, 2 и 6, изменяемые операнды BuildTextureLookup, четыре байта под SP, управление 7FFD и SP
; Note:
;   BuildTextureLookup сначала получает A=#6F и HL=#6663, IYL определяется параметром, исходный IYL не используется
;   строитель подключает банк 1, два прохода заполнения пропусков могут оставить маркеры #FF
;   снимок S состоит из 16384 байтов построенной таблицы по #A000..#DFFF
;   чётный байт S делится на четыре с отбрасыванием остатка, нечётный копируется без изменения
;   приёмник #8000..#BFFF отстаёт от источника на #2000, запись не опережает чтение исходных байтов
;   результат переносится в банк 6 после записи #16 в #7FFD, банк 1 сохраняет верхнюю часть таблицы
;   для t=(#16+S[16383]) AND #FF конечный F=((S[16382]>>1) AND 1) OR (t AND 8) OR ((t AND 2)<<4)
;   счёт M1 полного входа равен 926424+8*g, g число перенесённых пар двух проходов строителя
;   R увеличивает младшие семь битов на число M1 modulo 128, старший сохраняется
;   под входным SP остаются слово #6660 на глубине два и слово #0100 на глубине четыре
;   отдельные 256 сценариев хвоста #6640 проверяют преобразование всех байтов, шесть полных вызовов проверяют композицию
;   полное совместное пространство координат, IRQ, точные такты и нативный показ этими моделями не доказаны
; -----------------------------------------
Entry:          LD A, #6F
                LD HL, @IntroAlternatingLookup.P00
                CALL @Intro.BuildTextureLookup.Entry
                LD DE, #8000
                LD H, #A0
BeginRow:       LD L, #00
                ; преобразование чётного байта исходной строки, нечётный байт сохраняется
ConvertPair:    LD A, (HL)
                SRL A
                SRL A
                LD (DE), A
                INC L
                INC E
                LD A, (HL)
                LD (DE), A
                INC L
                INC E
                JR NZ, @Intro.BuildAlternatingTexture.ConvertPair               ; переход, если строка приёмника ещё не содержит 256 байтов


                INC H
                INC D
                BIT 6, D
                JR Z, @Intro.BuildAlternatingTexture.BeginRow                   ; переход, если приёмник ещё не достиг #C000


                LD A, #16
                CALL @Intro.SelectMemoryPage.Entry
                JP @Intro.CopyTextureToBank.Entry


                endmodule
                endmodule
