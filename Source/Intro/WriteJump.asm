                module WriteJump
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
; -----------------------------------------
; Создание инструкции JP DE по адресу HL, HL увеличивается на три
; исходная запись 3, файловые смещения #06FE..#0704
; In:
;   HL - адрес создаваемой инструкции, DE - адрес перехода
; Out:
;   HL - адрес после трёхбайтовой инструкции JP
; Corrupt:
;   HL
; Note:
;   записываются #C3, младший и старший байты DE, остальные регистры сохраняются
; -----------------------------------------
Entry:          LD (HL), #C3
                INC HL
                LD (HL), E
                INC HL
                LD (HL), D
                RET


                endmodule
                endmodule
