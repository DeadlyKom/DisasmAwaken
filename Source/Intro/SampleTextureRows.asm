                module SampleTextureRows
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
; -----------------------------------------
; Выборка 16 строк текстуры через генерируемый обработчик в #7E00 и временный SP
; исходная запись 3, файловые смещения #03E2..#03F2
; In:
;   Unknown, регистровый контракт ещё не доказан
; Out:
;   исходный поток управления, включая переходы в соседние фрагменты
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, консервативная верхняя граница
; Note:
;   граница файла не доказывает границу логической процедуры
;   состояние самомодификации и активной страницы учитывается отдельно
;   в первом наборе D задаёт страницу приёмника, во втором HL задаёт таблицу указателей
;   #7E00 содержит 64 копии семибайтового шаблона, продолжение заранее записано как JP #66F3
;   исходный SP сохраняется в непосредственном операнде #66F8, никакой CALL в развёрнутой цепочке нет
; -----------------------------------------
                ; сохранение настоящего стека перед переходом к стеку таблицы указателей
Entry:          LD (#66F8), SP
                LD B, #10
Point66E8:      LD SP, HL
                INC H
                EXX
                LD BC, #8000
                LD E, #C0
                JP #7E00


                endmodule
                endmodule
