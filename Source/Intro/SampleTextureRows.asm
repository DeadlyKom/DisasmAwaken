                module SampleTextureRows
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
                ; Документация [алгоритм и проверка](../../Docs/IntroScrolledSampler.md)
; -----------------------------------------
; Выборка 16 строк текстуры через генерируемый обработчик в #7E00 и временный SP
; исходная запись 3, файловые смещения #03E2..#03F2
                ; In:
                ;   HL - начало 64 слов первой строки указателей, следующая строка начинается в следующей странице с тем же L
                ;   DE и C основного набора - сохраняемый контекст, AF числовых аргументов не задаёт
                ;   DE' - D' первая страница назначения, E' заменяется на C0, AF' сохраняется
                ;   операнд 66EC..66ED задаёт шестнадцатибитное смещение источника, цепочка 7E00..7FC2 создана InitializeScrolledTexture
                ;   SP указывает на внешний адрес возврата, SavedSP доступен для записи, IRQ не вмешивается во временный SP
                ;   таблицы и выбранные источники доступны для чтения, назначения не повреждают код, указатели и CPU-стек
                ; Out:
                ;   HL - входной H увеличен на 16 modulo 256, L сохранён, DE сохранён, B=0, C сохранён
                ;   A - последний выбранный байт, F от последнего INC D, Carry от последнего ADD HL,BC развёрнутой выборки
                ;   HL' - последний адрес источника после сложения и очистки бита 14, D' - входной D'+16 modulo 256, E'=0
                ;   BC' - текущее смещение из операнда 66EC, AF', IX и IY сохранены, I/IM/IFF и paging сохраняются
                ;   16 раз по 64 байта записаны в колонки C0..FF последовательных страниц назначения
                ;   SavedSP содержит входной CPU SP, после восстановления конечный RET даёт входной SP+2
                ; Corrupt:
                ;   HL, BC, только B, AF, HL', DE', BC', SavedSP и 1024 байта назначений
                ; Note:
                ;   основной набор хранит курсор таблиц и счётчик строк B, после EXX используются рабочие HL, DE и BC исходного альтернативного набора
                ;   адрес источника равен (слово указателей плюс операнд 66EC modulo 65536) AND BFFF
                ;   каждая строка читает только 128 байтов указателей, затем INC H переводит курсор на следующую страницу без переноса из L
                ;   внутри строки E идёт от C0 до FF и оборачивается в 00, затем NextSampledRow увеличивает D и возвращает наборы через EXX
                ;   исходное содержимое RAM меняется последовательно, перекрытие с будущими выборками может изменить их результат
                ;   3840 сценариев проверили две области таблиц, три младших смещения таблиц, пять назначений, три смещения источника и все F
                ;   878 сценариев содержат чтение уже перезаписанного источника, регистры кроме R, все банки RAM и кратность записей совпали
                ;   произвольные слова и смещения не исчерпаны, время, аппаратные IRQ и нативный запуск не проверялись
                ; -----------------------------------------
                ; сохранение настоящего стека перед переходом к стеку таблицы указателей
Entry:          LD (@IntroScrolledState.SavedSP), SP
                LD B, @IntroScrolledConst.RowCount
ReadNextRow:    LD SP, HL
                INC H
                EXX
                LD BC, #8000
                LD E, @IntroScrolledConst.FirstColumn
                JP @IntroScrolledConst.ChainEntry


                endmodule
                endmodule
