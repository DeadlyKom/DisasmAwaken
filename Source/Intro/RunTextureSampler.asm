                module RunTextureSampler
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
; -----------------------------------------
; Запуск развёрнутого обработчика #9100 со стеком указателей источников
; исходная запись 3, файловые смещения #08E3..#08EC
; In:
;   Unknown, регистровый контракт ещё не доказан
; Out:
;   исходный поток управления, включая переходы в соседние фрагменты
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, консервативная верхняя граница
; Note:
;   граница файла не доказывает границу логической процедуры
;   состояние самомодификации и активной страницы учитывается отдельно
;   #9100 содержит 64 шестибайтовые выборки POP DE, LD L,E, LD E,(HL), LD A,(DE), LD (BC),A, INC C
;   последний INC C заменяется JP #6BED, число строк задаёт IXL, BC указывает на область назначения
;   H=#93 выбирает таблицу адресов, память по временному SP содержит 64 указателя на строку
; -----------------------------------------
Entry:          LD (#6BF3), SP
                LD SP, HL
                LD H, #93
Point6BEA:      JP #9100


                endmodule
                endmodule
