                module RunTextureSampler
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
                ; Документация [алгоритм и проверка](../../Docs/IntroPointerSampler.md)
; -----------------------------------------
; Запуск развёрнутого обработчика #9100 со стеком указателей источников
; исходная запись 3, файловые смещения #08E3..#08EC
                ; In:
                ;   HL - начало N строк по 64 слова указателей, BC - начальный адрес назначения
                ;   AF - входной Carry сохраняется, IX - IXL число строк N=1..38, IXH сохраняемый контекст
                ;   9300..93FF - таблица замены младшего байта адреса, цепочка 9100..9281 создана InitializeLookupEffect
                ;   SP указывает на внешний адрес возврата, операнд IntroSamplerState.SavedSP доступен для записи
                ;   назначения не пересекаются с кодом, таблицами, будущими источниками и CPU-стеком, IRQ не вмешивается во временный SP
                ; Out:
                ;   HL - H=93, L младший байт последнего прочитанного слова до табличной замены
                ;   DE - последний адрес выборки, D старший байт последнего слова, E=таблица[его младший байт]
                ;   BC - следующий адрес назначения по правилам 63 INC C и одного INC BC на строку
                ;   A - последний выбранный байт, F=42 OR входной Carry
                ;   HL', DE', BC', AF' сохранены, IXH сохранён, IXL=0, IY, I/IM/IFF и paging сохраняются
                ;   записано N*64 байта, SavedSP содержит входной SP, после RET SP равен входному SP+2
                ; Corrupt:
                ;   HL, DE, BC, AF, IX, только IXL, R, SavedSP и N*64 байта назначений
                ; Note:
                ;   POP DE получает слово, LD L,E выбирает индекс страницы 93, LD E,(HL) заменяет только младший байт источника
                ;   первые 63 записи строки выполняют INC C без переноса в B, последняя передаёт управление NextTextureSampleRow
                ;   продолжение выполняет INC BC, перенос в B происходит только при C=FF именно перед этим INC BC
                ;   для выровненного начального C, кратного 64, BC увеличивается на 64*N modulo 65536
                ;   CPU-стек не записывается, временный SP прочитывает 128*N байтов указателей, процедура сама DI не выполняет
                ;   2848 сценариев проверили исходную сгенерированную цепочку, все банки RAM, регистры кроме T, полный M1/R и кратность записей
                ;   нулевой IXL означал бы 256 строк, этот случай, произвольные перекрытия, время, IRQ и нативный запуск не доказаны
                ; -----------------------------------------
Entry:          LD (@IntroSamplerState.SavedSP), SP
                LD SP, HL
                LD H, @IntroSamplerConst.LookupPage
RunChain:       JP @IntroSamplerConst.ChainEntry


                endmodule
                endmodule
