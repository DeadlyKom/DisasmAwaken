;   произошёл выход из HALT, прерывания запрещены через DI
; Corrupt:
;   сами EI, HALT и DI регистров данных не меняют, побочные эффекты IRQ определяет его обработчик
; Note:
;   HALT не является задержкой в фиксированное число тактов, ожидание зависит от фазы входа
; -----------------------------------------
