                module WaitInterrupt
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
                ; Документация [алгоритм и проверка](../../Docs/IntroWaitInterrupt.md)
; -----------------------------------------
; Разрешение прерываний, ожидание HALT и повторный запрет прерываний
; исходная запись 3, файловые смещения #0713..#0716
                ; In:
                ;   HL, DE, BC, AF, альтернативные регистры, IX и I - сохраняемый контекст, IY=5C3A
                ;   IM=1, выбран проверенный 48K ROM, источник периодических IRQ работает, входной IFF может быть любым
                ;   клавиши не нажаты, первые байты двух KSTATE по 5C00 и 5C04 равны FF
                ;   FRAMES по 5C78..5C7A доступен, SP указывает внешний возврат и имеет 14 доступных байтов ниже него
                ;   CPU-стек не пересекается с кодом и системными переменными, NMI не рассматривается
                ; Out:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX и IY сохраняются, I сохраняется, IM остаётся равным единице
                ;   принят один IRQ, FRAMES увеличен на один modulo 16777216, прерывания запрещены конечным DI
                ;   SP после RET равен входному SP+2, внешний возврат снят один раз
                ;   клавиатурный сканер выполнил восемь чтений строк порта FE, записей в порты нет
                ;   в профиле KSTATE=FF состояние клавиш не записывается, временные кадры IRQ и CALL остаются ниже CPU SP
                ; Corrupt:
                ;   R, IFF, FRAMES и временные 14 байтов ниже входного SP
                ; Note:
                ;   EI разрешает IRQ перед HALT, собственные четыре инструкции не меняют регистры данных
                ;   ROM сохраняет AF, HL, BC и DE, увеличивает младшее слово FRAMES и при его переполнении байт по IY+40
                ;   помимо аппаратного возврата используются четыре PUSH регистров и три CALL клавиатурных процедур, два CALL повторно занимают нижнее слово
                ;   HALT не задаёт фиксированного времени ожидания, оно зависит от входной фазы кадра
                ;   3072 сценария покрыли все F, переполнение 16- и 24-битного FRAMES, три исходные фазы времени и три CPU-стека
                ;   выполнялись настоящие ROM-инструкции и штатный планировщик IM 1 модели, независимо сверены регистры кроме R, RAM, стек, порты и кратность записей
                ;   нажатые клавиши, иные KSTATE, другие ROM, иные IM, NMI, полная модель физических банков, точное время и нативное вступление не доказаны
                ; -----------------------------------------
                ; Разрешение периодического IRQ, после следующего HALT обработчик ROM сохранит рабочие регистры.
Entry:          EI
                ; Ожидание фактического прерывания, профиль IM 1 обновляет FRAMES и сканирует клавиатуру.
                HALT
                ; Повторный запрет IRQ перед последующим использованием SP для таблиц и развёрнутых переносов.
                DI
                RET


                endmodule
                endmodule
