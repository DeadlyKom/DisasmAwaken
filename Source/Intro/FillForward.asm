                module FillForward
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
; -----------------------------------------
; Заполнение области через начальный байт A и перекрывающееся копирование LDIR
; исходная запись 3, файловые смещения #0717..#071D
; In:
;   HL - начало области, BC - число байтов после начального, AF - A значение заполнения
; Out:
;   начальный байт и следующие исходные BC байтов содержат A, BC равен нулю
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   DE получает адрес за концом, HL адрес последнего байта, арифметика адресов modulo #10000
;   A сохраняется, при BC=0 LDIR выполняет 65536 переносов, проверять размещение обязан вызывающий код
; -----------------------------------------
Entry:          LD D, H
                LD E, L
                INC DE
                LD (HL), A
                LDIR
                RET


                endmodule
                endmodule
