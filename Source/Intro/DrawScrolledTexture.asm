                module Intro
                module DrawScrolledTexture
                ; Документация [прокручиваемая текстура](../../Docs/IntroScrolledFrame.md)
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
; -----------------------------------------
; Обновление двух смещений modulo 64, выбор строки текстуры и вывод двух половин кадра
; исходная запись 3, файловые смещения #03A3..#03E1
                ; In:
                ;   HL, BC указывают две записи FTexturePhase, DE содержит независимые приращения, D первого смещения и E второго
                ;   AF задаёт полную конфигурацию 7FFD в A, порт разблокирован, проверены страницы 11 и 16
                ;   подготовлены цепочка 7E00, писатель атрибутов, таблицы и назначения по договорам SampleTextureRows и PresentInterlacedFrame
                ;   IM=1, IY=5C3A, выбран проверенный 48K ROM, клавиши отпущены, KSTATE по 5C00 и 5C04 равны FF
                ;   16 байтов ниже входного CPU SP доступны, стек не пересекается с кодом, системными переменными, записями фаз и назначениями
                ;   источник IRQ работает, последующие IRQ не вмешиваются во временные SP обновления параметров, выборки и экранного переноса
                ;   FramePhase равен 00 либо 80, входной IFF в составной модели равен нулю
                ; Out:
                ;   первое смещение равно (прежнее плюс D) AND 3F, второе равно 80 OR ((прежнее плюс E) AND 3F)
                ;   обновлены две записи фаз, указатель выборок имеет L=2*(старший байт первой новой Phase минус 60) modulo 256 и H=старший байт второй новой Phase плюс 50 modulo 256
                ;   две выборки записывают 32 строки по 64 байта в C0..FF страниц 80..9F, вторая продолжает курсор первой
                ;   в проверенном профиле до PresentInterlacedFrame приняты два IRQ, CPU SP восстановлен и IFF=0
                ;   AF', IX, IY и I сохраняются, IM=1, выбранная конфигурация 7FFD остаётся действующей
                ;   последующий PresentInterlacedFrame переключает FramePhase, выводит кадр и возвращается по внешнему адресу, SP после RET равен входному SP+2
                ;   конечные HL, DE, BC, AF, HL', DE', BC' определяются договором PresentInterlacedFrame, на выходе IFF=0
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', R, IFF, FRAMES, фазовые записи, операнды, буфер, экран, стек, 7FFD
                ; Note:
                ;   120 проходов сверили выборки и конечный вывод с настоящим ROM, оба знака фаз, обе раскладки и 12 входов через финальную обёртку
                ;   пары D/E равны 00/00, 01/01, FF/FF, 01/FF и FF/01, разные направления проверяют независимость двух приращений
                ;   таблицы адресов выборок и экранного переноса подготовлены моделью, это не доказывает граф всех исходных игровых указателей
                ;   ненулевые AF альтернативного набора, IX и IY сохраняются до вывода, IM и IFF заданы в модели явно
                ;   произвольные указатели, все пары приращений, времена IRQ, точный R и нативный запуск не входят в проверенный профиль
; -----------------------------------------
Entry:          CALL @Intro.WaitInterrupt.Entry
                PUSH BC
                CALL @Intro.SelectMemoryPage.Entry
                ; расчёт горизонтального смещения по модулю 64, исходный байт меняется в операнде
                LD A, (#66EC)
                ADD A, D
                AND #3F
                LD (#66EC), A
                ; расчёт второго смещения по модулю 64 с сохранением старшего бита страницы #80
                LD A, (#66ED)
                ADD A, E
                AND #3F
                OR #80
                LD (#66ED), A
                ; обновление первого состояния, старший байт задаёт младшую часть адреса выборок
                CALL @Intro.AdvanceParameters.Entry
                SUB #60
                ADD A, A
                LD (#66D4), A
                ; получение второго указателя состояния из сохранённого BC
                POP HL
                CALL @Intro.AdvanceParameters.Entry
                ADD A, #50
                LD (#66D5), A
                LD D, #80
                EXX
                LD HL, #CD40
                CALL @Intro.SampleTextureRows.Entry
                CALL @Intro.WaitInterrupt.Entry
                CALL @Intro.SampleTextureRows.Entry
                JP @Intro.PresentInterlacedFrame.Entry


                endmodule
                endmodule
