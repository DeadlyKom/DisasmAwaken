; -----------------------------------------
; Продолжение после #9100, следующий столбец BC и строка источников до восстановления SP
; исходная запись 3, файловые смещения #08ED..#08F5
; In:
;   Unknown, регистровый контракт ещё не доказан
; Out:
;   исходный поток управления, включая переходы в соседние фрагменты
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, консервативная верхняя граница
; Note:
;   граница файла не доказывает границу логической процедуры
;   состояние самомодификации и активной страницы учитывается отдельно
;   это продолжение RunTextureSampler после JP из развёрнутой цепочки, отдельно CALL недопустим
;   каждая строка содержит 64 байта, INC BC после группы отделяет следующий старт от последнего INC C
; -----------------------------------------
Entry:          INC BC
                DEC IXL
                JR NZ, @Intro.RunTextureSampler.Point6BEA                       ; переход, если остались строки выборок по счётчику IXL


                LD SP, #3131
                RET


                endmodule
                endmodule
