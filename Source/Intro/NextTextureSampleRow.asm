                module NextTextureSampleRow
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
                ; Документация [алгоритм и проверка](../../Docs/IntroPointerSampler.md)
; -----------------------------------------
; Продолжение после #9100, следующий столбец BC и строка источников до восстановления SP
; исходная запись 3, файловые смещения #08ED..#08F5
                ; In:
                ;   HL - H=93, DE - последний адрес выборки строки, BC - адрес последней записи строки после 63 INC C
                ;   AF - A последний байт строки, Carry сохраняется, IX - IXL оставшееся число строк с учётом завершённой, 1..38
                ;   SP указывает сразу после 64 прочитанных слов текущей строки, SavedSP содержит CPU SP основного входа
                ;   цепочка 9100, таблица 9300 и оставшиеся строки соответствуют контракту RunTextureSampler
                ; Out:
                ;   при входном IXL=1 HL и DE сохранены, BC увеличен на один, A сохранён, F=42 OR входной Carry, IXL=0
                ;   при входном IXL больше единицы ещё IXL-1 строк обработаны через RunChain, конечные регистры определяются последней выборкой
                ;   HL', DE', BC', AF' сохранены, IXH, IY, I/IM/IFF и paging сохраняются
                ;   SP восстанавливается из SavedSP, RET снимает внешний адрес возврата основного входа
                ; Corrupt:
                ;   HL, DE, BC, AF, IX, только IXL, R, назначения оставшихся строк
                ; Note:
                ;   дополнительный вход является продолжением JP из последней сгенерированной выборки, обычный CALL недопустим
                ;   INC BC закрывает строку, DEC IXL определяет повторение, регистр B не является счётчиком строк
                ;   основная модель исполняет это продолжение на каждой строке, отдельный произвольный контекст входа не доказан
                ;   при завершении собственных записей RAM нет, сохранённый CPU-стек только читается
                ;   полный аппаратный IRQ и нативный запуск не выполнялись
                ; -----------------------------------------
Entry:          INC BC
                DEC IXL
                JR NZ, @Intro.RunTextureSampler.RunChain                        ; переход, если остались строки выборок по счётчику IXL


                LD SP, #3131
                RET


                endmodule
                endmodule
