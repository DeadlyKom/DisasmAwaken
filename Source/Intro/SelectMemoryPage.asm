                module SelectMemoryPage
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
; -----------------------------------------
; Запись A в порт #7FFD, BC получает номер порта
; исходная запись 3, файловые смещения #070D..#0712
; In:
;   AF - A содержит полный байт управления #7FFD
; Out:
;   BC - #7FFD, остальные регистры сохраняются
; Corrupt:
;   BC
; Note:
;   управление экраном, ПЗУ и страницей определяется исходными битами A
; -----------------------------------------
Entry:          LD BC, #7FFD
                OUT (C), A
                RET


                endmodule
                endmodule
