                module RenderLookupTexture
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
; -----------------------------------------
; Подготовка табличных фаз, исполнение #9900 и перенос результата через генерируемый код #A800
; исходная запись 3, файловые смещения #089C..#08BB
; In:
;   Unknown, регистровый контракт ещё не доказан
; Out:
;   исходный поток управления, включая переходы в соседние фрагменты
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, консервативная верхняя граница
; Note:
;   граница файла не доказывает границу логической процедуры
;   состояние самомодификации и активной страницы учитывается отдельно
;   младшие байты четырёх фаз меняются AdvanceTexturePhases внутри непосредственных операндов
;   #9900 содержит 256 копий 15-байтового сумматора, RET заменяет последний INC E, следующий EXX недостижим
;   #A800 содержит 38 групп по восемь POP HL и LD (nn),HL, переносит 608 байт в #C000..#E50F
;   завершение цепочки выполняется JP #6BBC, где восстанавливается исходный SP
; -----------------------------------------
Entry:          LD DE, #9300
                LD B, #98
                LD HL, #9400
                EXX
                LD BC, #9500
                LD HL, #9600
                LD DE, #9700
                CALL #9900
                LD HL, #2121
                LD (#6BBD), SP
                LD SP, HL
                JP #A800


                endmodule
                endmodule
