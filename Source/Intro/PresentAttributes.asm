                module Intro
                module PresentAttributes
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
; -----------------------------------------
; Ожидание кадра, выбор таблицы #60C0 либо #61C0 и вызов генерируемого писателя
; исходная запись 3, файловые смещения #0683..#0692
; In:
;   Unknown, регистровый контракт ещё не доказан
; Out:
;   исходный поток управления, включая переходы в соседние фрагменты
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, консервативная верхняя граница
; Note:
;   граница файла не доказывает границу логической процедуры
;   состояние самомодификации и активной страницы учитывается отдельно
;   дополнительный вход, не продолжение цикла CombineAttributeNibbles
;   HALT требует разрешённых прерываний на входе, последующий писатель использует SP как указатель данных
; -----------------------------------------
Entry:          HALT
                LD A, (#67F2)
                OR A
                LD HL, #60C0
                JR Z, @Intro.PresentAttributes.Point6990                        ; переход, если фаза #67F2 равна нулю и нужна таблица #60C0


                LD HL, #61C0
Point6990:      JP @Intro.RunAttributeWriter.Entry


                endmodule
                endmodule
