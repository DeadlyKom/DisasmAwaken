                module Intro
                module BuildPhaseTable
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
; -----------------------------------------
; Запись 256 выборок исходной таблицы со сдвигом вправо на два бита и шагом C по индексу
; исходная запись 3, файловые смещения #0A6A..#0A77
; In:
;   HL - исходная 256-байтовая таблица, DE - приёмник, BC - C шаг младшего индекса
; Out:
;   записано 256 минус исходное E байтов, E равен нулю, D увеличен на один modulo 256
; Corrupt:
;   HL, DE, AF
; Note:
;   каждый результат равен исходному байту с логическим сдвигом вправо на два бита
;   H и BC сохраняются, L увеличивается на C modulo 256 после каждой выборки
; -----------------------------------------
                ; выборка исходного байта с фазовым шагом C и деление на четыре
Entry:          LD A, (HL)
                SRL A
                SRL A
                LD (DE), A
                LD A, L
                ADD A, C
                LD L, A
                INC E
                JR NZ, @Intro.BuildPhaseTable.Entry                             ; переход, если младший байт адреса приёмника ещё не обнулился


                INC D
                RET


                endmodule
                endmodule
