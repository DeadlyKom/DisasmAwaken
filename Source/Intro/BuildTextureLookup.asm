                module Intro
                module BuildTextureLookup
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
; -----------------------------------------
; Построение двухбайтовой таблицы выборок по координатам из #6400 и заполнение её пропусков
; исходная запись 3, файловые смещения #0463..#04F0
; In:
;   HL - 63 параметра построителя, AF - A код #6F либо #2C для инструкции с префиксом FD
;   IY - IYL исходное значение для варианта INC IYL, стек расположен ниже #8000
; Out:
;   HL - 0, BC - 0, IX - #6400, память #8000..#FFFF содержит построенную таблицу
; Corrupt:
;   HL, DE, BC, AF, IX, IY
; Note:
;   меняются IXL, IXH и IYL, IYH и альтернативные регистры сохраняются
;   порт #7FFD получает #11, внутренние операнды #6786, #678E, #6793 и #679E изменяются
;   A не сохраняет входной код, зависимость от ПЗУ описана ниже
;   HL задаёт поток 63 параметров, A заменяет второй байт префиксной инструкции #678D
;   A=#6F оставляет LD IYL,A, A=#2C превращает её в INC IYL
;   для каждого параметра растут шаг DE на четыре и старт HL вниз на #100
;   старшие байты 128 накопленных координат помещаются в #8000..#807F
;   из двух сдвинутых на 64 выборок таблицы #6400 получается адрес двухбайтовой записи
;   в запись заносятся индекс и IYL, затем два прохода заменяют незаполненные #FF записями со следующей страницы
;   для последней пары #FFFE..#FFFF следующая страница оборачивается в ПЗУ #00FE..#00FF
;   A после построения не сохраняется, последующий счётчик копирования BuildIntroTexture зависит от результата этого прохода
; -----------------------------------------
                ; настройка указателя параметров и варианта изменения регистра IYL в теле цикла
Entry:          LD (#6786), HL
                LD (#678E), A
                CALL @Intro.SelectIntroPage.Entry
                LD HL, #0000
                LD (#6793), HL
                LD HL, #4000
                LD (#679E), HL
                ; заполнение области #8000..#FFFF маркером #FF, начальный байт и ещё #7FFF байтов через LDIR
                LD HL, #8000
                LD BC, #7FFF
                LD A, C
                CALL @Intro.FillForward.Entry
                LD B, #3F
Point6784:      PUSH BC
                LD HL, #2121
                LD A, (HL)
                INC HL
                LD (#6786), HL
                LD IYL, A
                LD BC, #8000
                LD DE, #0000
                ; расчёт следующего шага координат, DE увеличивается на четыре
                INC E
                INC E
                INC E
                INC DE
                LD (#6793), DE
                LD HL, #4000
                DEC H
                LD (#679E), HL
                ; создание 128 старших байтов последовательности HL с шагом DE
Point67A4:      LD A, H
                LD (BC), A
                ADD HL, DE
                INC C
                BIT 7, C
                JP Z, @Intro.BuildTextureLookup.Point67A4                       ; переход, если ещё не записаны 128 координат


                LD BC, #6400
                LD IX, #6440
                ; поиск двух координат в одной таблице со сдвигом индексов на 64
Point67B4:      LD H, #80
                LD A, (BC)
                LD L, A
                SRL L
                LD E, (HL)
                LD L, (IX + #00)
                SRL L
                LD D, (HL)
                ; расчёт адреса двухбайтовой записи, младшая координата умножается на два
                SLA E
                SET 7, D
                LD A, C
                LD (DE), A
                INC E
                LD A, IYL
                LD (DE), A
                INC IXL
                INC C
                JR NZ, @Intro.BuildTextureLookup.Point67B4                      ; переход, если ещё не обработаны все 256 индексов исходной таблицы


                POP BC
                DJNZ @Intro.BuildTextureLookup.Point6784

                LD IXL, #02
Point67D6:      LD HL, #8100
Point67D9:      INC L
                LD A, (HL)
                CP #FF
                JR NZ, @Intro.BuildTextureLookup.Point67E7                      ; переход, если второй байт записи уже отличается от #FF


                ; восстановление пропуска парой байтов из следующей страницы таблицы
                INC H
                LD D, (HL)
                DEC L
                LD E, (HL)
                DEC H
                LD (HL), E
                INC L
                LD (HL), D
Point67E7:      INC HL
                BIT 7, H
                JR NZ, @Intro.BuildTextureLookup.Point67D9                      ; переход, если адрес таблицы ещё не переполнил #FFFF


                DEC IXL
                JR NZ, @Intro.BuildTextureLookup.Point67D6                      ; переход, если остался второй проход заполнения пропусков


                RET


                endmodule
                endmodule
