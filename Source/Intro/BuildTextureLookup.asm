                module Intro
                module BuildTextureLookup
                ; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
                ; Имена внутренних входов [алгоритмы вступления](../../Docs/IntroInternalLabels.md)
                ; Таблица и пропуски [разбор](../../Docs/IntroGeneratedEffects.md#построение-и-заполнение-таблицы-выборок)
                ; -----------------------------------------
                ; Построение двухбайтовой таблицы выборок по координатам из #6400 и заполнение её пропусков
                ; исходная запись 3, файловые смещения #0463..#04F0
                ; In:
                ;   HL - поток 63 параметров в общей RAM ниже #8000 вне кода, координат и временного стека
                ;   AF - A равен #6F для LD IYL,A либо #2C для INC IYL, IY - исходный IYL второго варианта
                ;   страница #6400 содержит 256 байтов координат, 7FFD разблокирован, банки 1 и 2 доступны
                ;   внешний возврат и два байта под SP находятся в общей RAM ниже #8000 вне изменяемых областей
                ;   локальный договор предполагает отсутствие вмешательства IRQ/NMI, IFF процедура не меняет
                ; Out:
                ;   HL - 0
                ;   DE - последняя пара, перенесённая при заполнении пропусков, D второй байт, E первый
                ;   BC - 0, AF - A равен байту ROM по #00FF, F равен #42 при A=#FF, иначе #43
                ;   HL', DE', BC', AF' сохраняются
                ;   IX - #6400, IYL последний параметр при A входа=#6F, иначе исходный IYL+63 modulo 256, IYH сохраняется
                ;   I, IM и IFF сохраняются, SP равен входному SP+2
                ;   банки 2 и 1 содержат таблицу #8000..#FFFF, выбран банк 1 полным байтом управления #11
                ; Corrupt:
                ;   HL, DE, BC, AF, IX, IYL, R, банки 2 и 1, изменяемые операнды #6786, #678E, #6793, #679E, два байта под SP, управление 7FFD и SP
                ; Note:
                ;   источник параметров читается 63 раза в обоих вариантах, операнд #6786 в конце равен исходному HL+63
                ;   A заменяет второй байт инструкции с префиксом FD по #678D, другие коды входным договором не разрешены
                ;   параметр с номером j=1..63 задаёт шаг 4*j и начало #4000-#100*j
                ;   старшие байты 128 последовательных сумм записываются в #8000..#807F, эта область является рабочей
                ;   для индекса c используются координаты c и c+64 modulo 256, обе предварительно делятся на два
                ;   первый байт целевой пары получает c, второй IYL, при коллизии побеждает более поздняя запись
                ;   два прохода по #8100..#FFFF заменяют пару только при втором байте #FF, в том числе при исходном параметре #FF
                ;   пара берётся со следующей страницы с тем же младшим адресом, для #FFFE это ROM по #00FE..#00FF
                ;   два прохода не гарантируют исчезновения всех маркеров #FF, конечный A зависит от ROM
                ;   конечные операнды #6793=#00FC и #679E=#0100, #678E сохраняет входной код, под входным SP остаётся BC=#0100
                ;   счёт M1 равен 786760+8*g, где g суммарное число перенесённых пар в двух проходах
                ;   R увеличивает младшие семь битов на число M1 modulo 128, старший сохраняется
                ;   36 сценариев проверили оба кода, три страницы координат, исходный поток и постоянные #00/#FF, два ROM
                ;   проверены все физические банки и регистры кроме времени, полный перебор входов, IRQ и нативный показ не заявлены
                ; -----------------------------------------
                ; настройка указателя параметров и варианта изменения регистра IYL в теле цикла
Entry:          LD (#6786), HL
                LD (#678E), A
                CALL @Intro.SelectIntroPage.Entry
                LD HL, #0000
                LD (#6793), HL
                LD HL, #4000
                LD (#679E), HL
                ; заполнение области #8000..#FFFF маркером #FF, начальный байт и ещё #7FFF байтов через LDIR
                LD HL, #8000
                LD BC, #7FFF
                LD A, C
                CALL @Intro.FillForward.Entry
                LD B, #3F
NextParameter:  PUSH BC
                LD HL, #2121
                LD A, (HL)
                INC HL
                LD (#6786), HL
                LD IYL, A
                LD BC, #8000
                LD DE, #0000
                ; расчёт следующего шага координат, DE увеличивается на четыре
                INC E
                INC E
                INC E
                INC DE
                LD (#6793), DE
                LD HL, #4000
                DEC H
                LD (#679E), HL
                ; создание 128 старших байтов последовательности HL с шагом DE
Accumulate:     LD A, H
                LD (BC), A
                ADD HL, DE
                INC C
                BIT 7, C
                JP Z, @Intro.BuildTextureLookup.Accumulate                      ; переход, если ещё не записаны 128 координат


                LD BC, #6400
                LD IX, #6440
                ; поиск двух координат в одной таблице со сдвигом индексов на 64
StoreLookup:    LD H, #80
                LD A, (BC)
                LD L, A
                SRL L
                LD E, (HL)
                LD L, (IX + #00)
                SRL L
                LD D, (HL)
                ; расчёт адреса двухбайтовой записи, младшая координата умножается на два
                SLA E
                SET 7, D
                LD A, C
                LD (DE), A
                INC E
                LD A, IYL
                LD (DE), A
                INC IXL
                INC C
                JR NZ, @Intro.BuildTextureLookup.StoreLookup                    ; переход, если ещё не обработаны все 256 индексов исходной таблицы


                POP BC
                DJNZ @Intro.BuildTextureLookup.NextParameter

                LD IXL, #02
BeginGapPass:   LD HL, #8100
CheckGap:       INC L
                LD A, (HL)
                CP #FF
                JR NZ, @Intro.BuildTextureLookup.NextPair                       ; переход, если второй байт записи уже отличается от #FF


                ; восстановление пропуска парой байтов из следующей страницы таблицы
                INC H
                LD D, (HL)
                DEC L
                LD E, (HL)
                DEC H
                LD (HL), E
                INC L
                LD (HL), D
NextPair:       INC HL
                BIT 7, H
                JR NZ, @Intro.BuildTextureLookup.CheckGap                       ; переход, если адрес таблицы ещё не переполнил #FFFF


                DEC IXL
                JR NZ, @Intro.BuildTextureLookup.BeginGapPass                   ; переход, если остался второй проход заполнения пропусков


                RET


                endmodule
                endmodule
