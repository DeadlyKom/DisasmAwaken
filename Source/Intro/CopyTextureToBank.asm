                module Intro
                module CopyTextureToBank
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
; -----------------------------------------
; Копирование #4000 байт из #8000 в окно текущего банка #C000
; исходная запись 3, файловые смещения #0457..#0462
; In:
;   окно #C000 содержит выбранный вызывающим кодом банк, источник #8000..#BFFF доступен
; Out:
;   HL - #C000, DE - #0000, BC - 0, окно #C000..#FFFF содержит копию источника
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   размер копии #4000, сам банк процедура не переключает
; -----------------------------------------
Entry:          LD BC, #4000
                LD HL, #8000
                LD DE, #C000
                LDIR
                RET


                endmodule
                endmodule
