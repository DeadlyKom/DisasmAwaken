                module Intro
                module PresentLookupTexture
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
                ; Документация [алгоритм и проверка](../../Docs/IntroLookupContinuation.md)
; -----------------------------------------
; Восстановление SP после #A800, две серии выборок и общий вывод кадра
; исходная запись 3, файловые смещения #08BC..#08E2
                ; In:
                ;   IntroLookupState.SavedSP по 6BBD содержит исходный CPU SP с внешним возвратом, текущий SP ещё является курсором переноса A800
                ;   IFF=0, IM=1, IY=5C3A, проверенный 48K ROM, клавиши не нажаты и первые байты KSTATE по 5C00 и 5C04 равны FF
                ;   цепочка 9100 создана, таблица 9300 подготовлена, AD00..BFFF содержит 38 строк по 64 слова источников
                ;   состояние масштаба имеет WarmupLeft=1..161, RampLevel=0..63, CycleIndex=0..39, таблица 6C62 исходная
                ;   две таблицы записей и матрицы соответствуют PresentInterlacedFrame, FramePhase=0 либо 80, писатель создан с исходным IXL=80 либо C0
                ;   16 байтов ниже восстановленного CPU SP доступны, назначения не повреждают код, указатели и CPU-стек
                ; Out:
                ;   HL - последний адрес источника кадровой второй половины плюс один, DE - конец её последней строки, BC=8000
                ;   A=0, F=42 при старой FramePhase=0 либо 43 при старой FramePhase=80
                ;   HL', DE', BC', AF' сохраняются, IXH сохранён, IXL=0, IY и I сохраняются, IM=1, IFF=0
                ;   SP восстановлен из IntroLookupState.SavedSP, после внешнего RET равен этому значению плюс два
                ;   13 строк заполнили 8000..833F, ещё 25 заполнили 8340..897F, всего 2432 байта до последующего вывода кадра
                ;   масштаб обновлён дважды, PointerRow содержит адрес для следующего входа RenderLookupTexture
                ;   FramePhase переключена, обе половины и выбранная матрица выведены по договору PresentInterlacedFrame
                ;   в проверенном профиле FRAMES увеличен на два, все самомодифицируемые операнды и остаточные кадры соответствуют полному порядку вызовов
                ; Corrupt:
                ;   HL, DE, BC, AF, IX, только IXL, R, IFF, буфер выборок, состояние масштаба, кадровые назначения и операнды, FRAMES и 16 временных байтов ниже CPU SP
                ; Note:
                ;   дополнительный вход вызывается завершающим JP созданной цепочки A800, обычный CALL с неподготовленным SavedSP недопустим
                ;   первый HALT выполняется только после 13 строк, второй внутри общего чередующегося кадра, оба WaitInterrupt оставляют IFF=0
                ;   при WarmupLeft=3 первое обновление ещё нарастающее, второе уже циклическое, эта граница проверена
                ;   писатель с исходным IXL=80 после выборок меняет часть 8000..897F, окончательное содержимое буфера учитывает эти записи
                ;   3072 сценария исполнили весь путь и настоящий ROM, четыре состояния начальной фазы масштаба, все уровни нарастания и индексы цикла в сочетаниях
                ;   регистры кроме R, все физические банки RAM, CPU-стек и кратность записей совпали с независимой числовой композицией
                ;   произвольные входные данные, времена, ROM, клавиши, IFF=1 на входе, NMI, точное время и нативный показ не доказаны
                ; -----------------------------------------
                ; операнд восстановления SP заполняется перед переходом в #A800
                ; -----------------------------------------
                ; Возврат к CPU-стеку
                ; Восстановление SP из операнда, заполненного RenderLookupTexture до перехода в A800.
Entry:          LD SP, #3131
                ; -----------------------------------------
                ; Первые тринадцать строк
                ; Выбор первого участка слов источников и начала буфера 8000.
                LD IXL, @IntroLookupRowsConst.FirstRows
                LD HL, @IntroLookupRowsConst.FirstWords
                LD BC, @IntroLookupRowsConst.FirstBuffer
                ; Косвенные выборки заполняют 832 байта до 833F включительно.
                CALL @Intro.RunTextureSampler.Entry
                ; Ожидание кадрового IRQ между двумя участками, ROM сохраняет результаты выборщика.
                CALL @Intro.WaitInterrupt.Entry
                ; Первое обновление масштаба меняет PointerRow следующего кадра, уже выполненный перенос A800 не повторяется.
                CALL @Intro.AdvanceTextureScale.Entry
                ; -----------------------------------------
                ; Следующие двадцать пять строк
                ; Продолжение потока слов с B380 и буфера с 8340, обе границы совпадают с концом первых 13 строк.
                LD IXL, @IntroLookupRowsConst.SecondRows
                LD HL, @IntroLookupRowsConst.SecondWords
                LD BC, @IntroLookupRowsConst.SecondBuffer
                ; Заполнение оставшихся 1600 байтов, полный буфер выборок заканчивается по 897F.
                CALL @Intro.RunTextureSampler.Entry
                ; Второе обновление масштаба, переход на циклическую фазу может произойти именно здесь.
                CALL @Intro.AdvanceTextureScale.Entry
                ; Передача управления целому чередующемуся кадру без дополнительного CALL, его RET снимет внешний возврат.
                JP @Intro.PresentInterlacedFrame.Entry


                endmodule
                endmodule
