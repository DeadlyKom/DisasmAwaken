                module Intro
                module DrawFinalTextureFrame
                ; Физические параметры [источники и потребители](../../Docs/IntroPhysicalParameters.md)
                ; Документация [прокручиваемая текстура](../../Docs/IntroScrolledFrame.md)
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
; -----------------------------------------
; Настройка смещения и параметров последнего текстурного эффекта вступления
; исходная запись 3, файловые смещения #031E..#032B
                ; In:
                ;   числовые регистровые аргументы не нужны, должны выполняться условия DrawScrolledTexture
                ;   IRQ не вмешивается в пять инструкций до хвостового JP, доступен код DrawScrolledTexture
                ; Out:
                ;   перед первой инструкцией DrawScrolledTexture HL=#662C, DE=#FFFF, BC=#6632, A=#16
                ;   F, HL', DE', BC', AF', IX и IY сохраняются, SP, I, IM и IFF не меняются до рисователя
                ;   R увеличен за пять M1, младшие семь битов на 5 modulo 128, бит 7 сохраняется
                ;   RAM до рисователя не записывается, хвостовой JP не создаёт дополнительного слова возврата
                ;   дальнейшие результаты определяются договором DrawScrolledTexture, финальная обёртка задаёт банк 6 и два приращения FF
                ; Corrupt:
                ;   HL, DE, BC, A и R до передачи, затем действует договор DrawScrolledTexture
                ; Note:
                ;   оба смещения уменьшаются на единицу по модулю 64, 12 сценариев выполнены через этот вход
                ;   1024 сценария сверили все F, четыре граничных R, полную RAM и регистры до первой инструкции рисователя
                ;   изолированная передача проверена без IRQ при разных I/IM/IFF, это не расширяет условия общего рисователя на произвольный IM
; -----------------------------------------
Entry:          LD A, #16
                LD DE, #FFFF
                LD HL, @IntroFinalTexturePhases.First
                LD BC, @IntroFinalTexturePhases.Second
                JP @Intro.DrawScrolledTexture.Entry


                endmodule
