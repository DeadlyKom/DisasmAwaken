                module Intro
                module ExpandTextureRows
                ; Документация [разворачивание и точный результат](../../Docs/IntroGeneratedEffects.md#разворачивание-строк-и-добавка-ixl)
; Документация [Intro](../../Docs/FunctionDetails/Intro.md)
                ; Имена внутренних входов [алгоритмы вступления](../../Docs/IntroInternalLabels.md)
; -----------------------------------------
; Добавление IXL к 4096 байтам банка 4 и четырёхкратное повторение каждой 64-байтовой строки
; исходная запись 3, файловые смещения #0429..#0456
                ; In:
                ;   IX содержит байтовую добавку в IXL, IXH сохраняется, банк 4 содержит 4096 байтов текстуры 64 на 64
                ;   банк 2 доступен для записи по 8000..BFFF, код находится в общей RAM, 7FFD не заблокирован
                ;   внешний возврат и два байта под SP находятся в общей RAM ниже 8000 вне кода, источника и назначения
                ;   локальный договор предполагает отсутствие вмешательства IRQ/NMI, процедура сама не меняет IFF
                ; Out:
                ;   HL=C0C0, DE=C000, BC=7FFD, A=11, F=10 OR Carry последнего сложения исходного байта с IXL
                ;   HL', DE', BC', AF', IX и IY, I, IM и IFF сохраняются, SP=входной SP+2
                ;   8000..BFFF банка 2 содержит 64 страницы, каждая состоит из четырёх одинаковых преобразованных 64-байтовых строк
                ;   каждый байт назначения записан один раз, источник банка 4 и остальные физические банки не меняются кроме двух байтов CPU-стека
                ;   7FFD последовательно получает 14 и 11, конечный выбранный банк равен 1, прежние управляющие биты не восстанавливаются
                ;   R увеличивает младшие семь битов на 54096 modulo 128, то есть на 80, бит 7 сохраняется
                ;   две временные записи под входным SP содержат возврат 672E от первого CALL SelectMemoryPage
                ; Corrupt:
                ;   HL, DE, BC, AF, R, 16384 байта банка 2, два байта под входным SP, управление 7FFD и SP снятием внешнего возврата
                ; Note:
                ;   каждый исходный байт увеличивается на IXL modulo 256, перенос влияет только на конечный F, диапазон значений не ограничивается
                ;   первые 64 байта каждой страницы получаются прямыми записями, затем LDIR с расстоянием 40 дописывает оставшиеся 192 байта
                ;   нулевой или отрицательный в signed8 исходный байт не имеет отдельного смысла, здесь используется байтовая сумма
                ;   262 сценария проверили все 256 добавок и шесть постоянных границ, регистры кроме времени, все физические банки и кратность записей
                ;   фиксированный счёт равен 16+64*454+64*391 M1, приращение R сверено для каждого случая
                ;   полное совместное пространство 4096 исходных байтов, время, IRQ и нативная текстура этой моделью не доказаны
; -----------------------------------------
Entry:          LD A, #14
                CALL @Intro.SelectMemoryPage.Entry
                LD D, #80
                LD HL, #C000
BeginRow:       LD E, #00
                LD B, #40
                ; преобразование очередного байта текстуры с добавлением смещения IXL
AddTextureBias: LD A, (HL)
                ADD A, IXL
                LD (DE), A
                INC HL
                INC E
                DJNZ @Intro.ExpandTextureRows.AddTextureBias

                INC D
                BIT 6, D
                JR Z, @Intro.ExpandTextureRows.BeginRow                         ; переход, если ещё не созданы все 64 строки текстуры


                LD H, #80
                LD D, H
RepeatRow:      LD BC, #00C0
                LD L, B
                LD E, #40
                ; повторение 64-байтового образца ещё три раза перекрывающимся копированием
                LDIR
                INC H
                BIT 6, H
                JR Z, @Intro.ExpandTextureRows.RepeatRow                        ; переход, если ещё не повторены строки всех 64 страниц


                JP @Intro.SelectIntroPage.Entry


                endmodule
                endmodule
