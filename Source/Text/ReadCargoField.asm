                module Text
                module ReadCargoField
                ; Документация [Text](../../Docs/FunctionDetails/Text.md)
                ; Подробный разбор [двухбайтовая запись, сохранённый bit7 и различие индексов](../../Docs/CargoField.md)
                ; -----------------------------------------
                ; Чтение первого байта грузовой записи либо её второго байта через суффикс c
                ; исходная запись 5, файловые смещения #030A..#0322
                ; In:
                ;   ScriptSelection.CargoRow и CargoBase доступны, IX у необязательного индекса либо точки
                ;   для обычного возврата суффикс отсутствует либо равен c, действует договор ParseFieldSuffix
                ; Out:
                ;   без точки HL=(#9852+2*индекс) AND #FFFF, DE первый байт целиком с нулевым D
                ;   без точки BC - B=0, C исходная сумма CargoRow+CargoBase по модулю 256
                ;   без точки AF - A первый непрочитанный символ, F от последнего ADD HL,DE с S/Z/PV от разбора
                ;   с точкой DE второй байт, HL его адрес, остальные эффекты по договору GetCargoSecondByte
                ;   HL', DE' сохранены, BC' - B'=1, C' сохранён, AF' сохранён
                ;   IX первый непрочитанный символ, SP равен входному SP+2 при обычном возврате
                ;   IY, I и IFF сохранены, данные записи не изменяются
                ;   FieldSuffixState.DefaultTarget содержит ReadFirstByte
                ; Corrupt:
                ;   HL, DE, BC, AF, BC' только B, IX, SP при ошибке поиска, R, DefaultTarget и временный CPU-стек
                ; Note:
                ;   Entry через ParseFieldSuffix записывает два байта DefaultTarget и временные рамки CPU-стека, POP не очищает RAM
                ;   при ошибке суффикса SkipLine.Entry заменяет SP значением SavedSP, обычный возврат читателя не выполняется
                ;   внутренний ReadFirstByte принимает полный индекс в HL и обычный возврат, сам не пишет RAM и выполняет 6 M1
                ;   границы массива не проверяются, расчёт удваивает полный индекс с оборачиванием слова
                ;   без цифр индекс равен (CargoRow+CargoBase) AND #FF, с цифрами (число-1) AND #FFFF
                ;   прямой путь удваивает полный индекс, суффикс c сначала обрезает его до младшего байта
                ;   bit7 первого байта не маскируется, это отличается от ReadMarketField
                ;   неизвестный суффикс передаёт управление SkipLine без обычного результата
                ;   второй байт FOwnedCargoRow.Price является ценой приобретения, игровой смысл bit7 QuantityAndMark остаётся открытым
                ; -----------------------------------------
                ; установка числа одного суффикса c в альтернативном B
Entry:          EXX
                LD B, #01
                EXX
                ; выбор адреса за одной записью до суффикса второго байта грузовой записи
                LD DE, #CA10
                ; получение исходного байтового индекса по выбранной строке и базе списка
                CALL @Text.GetCargoIndex.Entry
                ; выбор внутреннего прямого чтения для пути без точки
                LD HL, @Text.ReadCargoField.ReadFirstByte
                JP @Text.ParseFieldSuffix.Entry

                ; расчёт двухбайтового смещения по полному слову индекса
ReadFirstByte:  ADD HL, HL
                ; выбор базы первых байтов грузовых записей
                LD DE, #9852
                ; расчёт адреса первого байта с шестнадцатибитным оборачиванием
                ADD HL, DE
                ; чтение первого байта целиком, старший разряд сохраняется
                LD E, (HL)
                ; обнуление старшего байта результата DE без изменения флагов
                LD D, #00
                RET

                endmodule
                endmodule
