                module Text
                module SubtractSaturated
                ; Документация [Text](../../Docs/FunctionDetails/Text.md)
                ; Подробный разбор [эффекты бинарных операторов](../../Docs/ScriptLanguage.md#собственные-эффекты-простых-бинарных-операторов)
                ; -----------------------------------------
                ; Вычитание BC из DE с ограничением результата снизу нулём
                ; исходная запись 5, файловые смещения #0491..#049B
                ; In:
                ;   DE - левый операнд, BC - правый операнд
                ; Out:
                ;   DE - ограниченный результат, HL сохраняется
                ;   AF - A сохраняется, F от оборачиваемой разности до ограничения нулём
                ; Corrupt:
                ;   DE, AF, R
                ; Note:
                ;   собственных записей RAM и CPU-стека нет, RET увеличивает входной SP на два, I и IFF сохраняются без прерываний, R изменяется
                ;   границы ограничены нулём и #FFFF, HL, BC, альтернативные и индексные регистры сохраняются
                ; -----------------------------------------
Entry:          EX DE, HL
                ; сброс входного переноса перед вычитанием правого операнда
                OR A
                ; расчёт разности с проверкой ухода ниже нуля
                SBC HL, BC
                JR NC, @Text.SubtractSaturated.ReturnResult                     ; переход, если левый операнд не меньше правого, ограничение не требуется

                ; ограничение отрицательной беззнаковой разности нулём
                LD HL, #0000
ReturnResult:   EX DE, HL
                RET

                endmodule
                endmodule
