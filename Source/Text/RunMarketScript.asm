                module RunMarketScript
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [команды, стек, CR и условные блоки](../../Docs/ScriptControl.md)
                ; Исходный сценарий [товары, незаконная продажа и границы проверки](../../Docs/OriginalTradeScript.md)
; -----------------------------------------
; Инициализация интерпретатора и последовательный вход в чтение команд
; исходная запись 5, файловые смещения #0000..#000B
; In:
;   CPU-стек содержит возврат вызывающему, LANG выбран в банке 6 и доступен для записи
;   сценарий начинается в исходном CA8F, действуют договоры NextCommand и выбранных команд
; Out:
;   перед последовательным входом NextCommand IX=CA8F, AF=0044, прочие пары сохранены
;   ScriptRuntimeState.SavedSP получает входной SP, StopAtLine обнуляется
;   дальнейшее исполнение и возвращаемые регистры определяются прочитанными командами
;   завершение через NUL, ненулевой StopAtLine после CR или FinishScript использует сохранённый возврат
; Corrupt:
;   AF, IX на инициализации, далее по NextCommand и исполненным командам
; Note:
;   SavedSP и StopAtLine являются операндами инструкций, новый буфер не выделяется
;   сохранённый стек и флаг общие, вложенный запуск перезаписывает контекст предыдущего сценария
; -----------------------------------------
                ; выбор исходного сценария торгового языка, указатель начального текста фиксирован образом
Entry:          LD IX, @MarketScript.Entry
                ; сохранение стека вызывающего в операнде SkipLine.Entry
                LD (@ScriptRuntimeState.SavedSP), SP
                ; сброс режима завершения на следующем конце строки
                XOR A
                LD (@ScriptRuntimeState.StopAtLine), A
                ; JP @Text.NextCommand.Entry, продолжение в NextCommand.asm

                endmodule
                endmodule
