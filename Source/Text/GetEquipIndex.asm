                module GetEquipIndex
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [ScriptLanguage.md](../../Docs/ScriptLanguage.md)
; -----------------------------------------
; Сложение выбранной строки и смещения списка оснащения, байтовый индекс возвращается в BC
; исходная запись 5, файловые смещения #0900..#090B
; In:
;   ScriptSelection.EquipmentRow и EquipmentBase доступны в общей памяти станции
; Out:
;   BC - сумма двух байтов по модулю 256, AF - A та же сумма, флаги восьмибитного сложения
; Corrupt:
;   BC, AF
; Note:
;   HL, DE, альтернативные и индексные регистры сохраняются
;   B обнуляется, перенос за пределы байта не добавляется к результату
;   значение #FF выбранной строки отдельно не проверяется, границы таблицы не проверяются
; -----------------------------------------
                ; чтение выбранной строки и компоненты смещения списка оснащения
Entry:          LD A, (@ScriptSelection.EquipmentRow)
                LD C, A
                LD A, (@ScriptSelection.EquipmentBase)
                ; расчёт байтового индекса оснащения, переполнение не расширяет результат до слова
                ADD A, C
                LD C, A
                LD B, #00
                RET

                endmodule
                endmodule
