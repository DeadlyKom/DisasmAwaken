                module Text
                module SetSecondarySelection
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [режим A альтернативного набора, реальные записи и путь до NextCommand](../../Docs/UnaryModes.md)
; -----------------------------------------
; Выбор вторичной записи по индексу банка 4 либо коду FF
; исходная запись 5, файловые смещения #01A7..#01B4
; In:
;   A' - режим, 0 выбирает FF, любое ненулевое значение индекс SumBank4Index
;   действует договор SumBank4Index с доступным банком 4 и возвратом LANG 6
; Out:
;   HL, DE сохранены, BC - B=0, C сумма компонентов банка 4 по модулю 256
;   AF - A записан в #984A, он равен C при ненулевом режиме либо FF при нуле
;   F от OR режима, Z показывает нулевой режим, а не нулевой записанный индекс
;   AF' содержит финальную страницу и F банкового OR, HL', DE', BC', IX, IY, I и IFF сохранены
;   SP обычного возврата равен входному SP+2, переключения банков выполняются даже при нулевом режиме
; Corrupt:
;   BC, AF, AF'
; Note:
;   байт выбора FF может также получиться из ненулевого режима и суммы FF, отдельного насыщения нет
;   команда числовой аргумент не читает, IX сохраняется
; -----------------------------------------
                ; получение индекса банка 4 для вторичного выбора
Entry:          CALL @Station.SumBank4Index.Entry
                ; получение режима из альтернативного A
                EX AF, AF'
                ; проверка ненулевого режима вторичного выбора
                OR A
                ; выбор C как вторичного индекса без пересчёта флагов
                LD A, C
                JR NZ, @Text.SetSecondarySelection.StoreSelection               ; переход, если режим ненулевой, записать вторичный индекс банка 4

                ; выбор FF для нулевого режима вторичного выбора
                LD A, #FF
                ; обновление вторичного байта выбора
StoreSelection: LD (#984A), A
                RET

                endmodule
                endmodule
