                module Text
                module ReadMarketField
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [путь от выбранной строки через суффикс к исходным обработчикам](../../Docs/MarketField.md)
; -----------------------------------------
; Чтение количества рынка либо точечного свойства c, s, m
; исходная запись 5, файловые смещения #026D..#0288
; In:
;   ScriptSelection.CargoRow и CargoBase доступны, IX у необязательного индекса либо точки
;   для обычного возврата суффикс отсутствует либо равен c, s, m, таблицы и код LANG доступны
;   HL и DE не содержат входных данных, действует договор ParseFieldSuffix и выбранного обработчика
; Out:
;   без суффикса HL=(#9555+2*индекс) AND #FFFF, DE=A количество AND #7F
;   без суффикса BC - B=0, C=(CargoRow+CargoBase) AND #FF, F от AND #7F
;   суффикс c возвращает DE текущую цену, s возвращает DE=1 при снятом bit7, иначе 0
;   суффикс m возвращает DE байтовую взвешенную сумму, его точный договор GetIndexedLoad
;   явный индекс равен (число-1) AND #FFFF, без числа индекс равен исходному C
;   суффиксные обработчики используют только младший байт индекса, прямое чтение количества полное слово
;   IX - первый непрочитанный символ, IY, I и IFF сохранены, SP при обычном возврате увеличен на 2
;   B'=3, C', DE', HL' сохранены, AF' изменяется только на пути взвешенной суммы
;   FieldSuffixState.DefaultTarget содержит ReadStock
; Corrupt:
;   HL, DE, BC, AF, BC' только B, AF' на пути m, IX
; Note:
;   ReadStock является отдельным внутренним входом с HL индексом, он не снимает слово индекса со стека
;   числовой индекс 0 без суффикса читает #9553, с суффиксом c читает #9754 из-за обрезания индекса до #FF
;   при неизвестном суффиксе DispatchToken передаёт управление SkipLine, обычного результата нет
;   полный контракт каждого результата и границы логического массива приведены в MarketField.md
; -----------------------------------------
                ; установка числа трёх суффиксов c, s, m в альтернативном B без изменения остальных пар
Entry:          EXX
                LD B, #03
                EXX
                ; выбор адреса за одной записью до таблицы свойств рынка
                LD DE, #CA13
                ; получение исходного байтового индекса из выбранной строки и смещения списка
                CALL @Text.GetCargoIndex.Entry
                ; выбор внутреннего ReadStock для пути без точки, индекс снимается только суффиксными обработчиками
                LD HL, @Text.ReadMarketField.ReadStock
                JP @Text.ParseFieldSuffix.Entry

                ; расчёт двухбайтового смещения по полному HL без обрезания до байта
ReadStock:      ADD HL, HL
                ; выбор массива текущего рынка для прямого чтения количества
                LD DE, @MarketRows.Row00.StockAndSaleBan
                ; расчёт адреса StockAndSaleBan с шестнадцатибитным оборачиванием
                ADD HL, DE
                LD A, (HL)
                ; удаление bit7 маркера перед возвратом байтового количества
                AND #7F
                ; передача количества в DE как результата выражения языка
                LD E, A
                LD D, #00
                RET

                endmodule
                endmodule
