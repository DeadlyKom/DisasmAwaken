                module Text
                module WriteIndexedPMode
                ; Документация [Text](../../Docs/FunctionDetails/Text.md)
                ; Подробный разбор [режим A альтернативного набора, реальные записи и путь до NextCommand](../../Docs/UnaryModes.md)
                ; -----------------------------------------
                ; Запись байтового режима по базе #9A1D и десятичному смещению
                ; исходная запись 5, файловые смещения #0177..#0180
                ; In:
                ;   AF' - A' записываемый целый байт, F' станет основным F после обмена
                ;   IX у первой проверенной десятичной цифры, выполняется договор ReadDecimal5
                ;   адрес (база 9A1D+число) AND #FFFF доступен для записи
                ; Out:
                ;   HL адрес записи, DE база #9A1D, BC рабочий выход ReadDecimal5
                ;   AF получает исходный AF', A записан в память, F не пересчитывается по записанному байту
                ;   AF' получает рабочий A парсера и F адресного сложения, HL', DE', BC', IY, I и IFF сохранены
                ;   IX первый непрочитанный символ, SP обычного возврата равен входному SP+2
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', IX, R, целевой байт и временный CPU-стек
                ; Note:
                ;   Entry записывает временный возврат ReadDecimal5 в два байта ниже входного SP, при двух и более цифрах ещё два байта занимает расчёт разрядов
                ;   после возврата парсера пишется только один целевой байт, POP и RET не очищают временную RAM, исходное слово возврата сохраняется
                ;   StoreAtBase не читает число и не пишет CPU-стек, принимает готовые HL и DE, выполняет четыре M1, DE и BC сохраняет
                ;   R изменяется при сохранённом старшем бите, число M1 полного Entry зависит от длины числа и пути проверки разделителя
                ;   публичные команды задают 0 либо 1, прямой вход сохраняет любой A целиком, это не битовая маска
                ;   числовое смещение не уменьшается на один, границы массива не проверяются
                ;   общий StoreAtBase принимает HL полное смещение, DE базу и ещё не использованный альтернативный AF
                ; -----------------------------------------
                ; чтение десятичного смещения для унарного поля p
Entry:          CALL @Text.ReadDecimal5.Entry
                ; выбор RecordCount как исходной базы p перед общей записью режима
                LD DE, @ControlOptions.ResourceSelect.RecordCount
                ; расчёт адреса байта без уменьшения числового значения
StoreAtBase:    ADD HL, DE
                ; получение записываемого режима из альтернативного A и сохранение рабочих AF в альтернативном
                EX AF, AF'
                ; обновление всего целевого байта режимом без пересчёта F
                LD (HL), A
                RET

                endmodule
                endmodule
