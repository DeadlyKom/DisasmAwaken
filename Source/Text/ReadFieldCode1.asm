                module Text
                module ReadFieldCode1
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [уже проверенная первая цифра, ширины компонент и стек выражений](../../Docs/NumericFieldReads.md)
; -----------------------------------------
; Чтение десятичного литерала с возвратом курсора на первую цифру и запись слова выражения
; исходная запись 5, файловые смещения #0323..#032B
; In:
;   HL' - два доступных байта следующего слова выражения, без перекрытия кода и CPU-стека
;   IX - байт после уже проверенной первой ASCII-цифры, после DEC IX выполняется договор ReadDecimal5
; Out:
;   HL - прежний рабочий DE выхода ReadDecimal5, DE прочитанное число по модулю 65536, BC рабочий выход парсера
;   AF по выходу ReadDecimal5, IX первый непрочитанный символ после не более пяти цифр
;   HL' увеличен на два, DE' содержит число, BC', AF', IY, I и IFF сохранены
;   число записано младшим байтом первым, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF, HL', DE', IX
; Note:
;   в отличие от ParseFieldSuffix декремента числового значения нет, ноль остаётся нулём
;   переполнение числа оборачивается, 99999 становится 34463
; -----------------------------------------
                ; возврат курсора на уже проверенную первую цифру литерала
Entry:          DEC IX
                ; чтение от одной до пяти цифр без уменьшения числового значения
                CALL @Text.ReadDecimal5.Entry
                ; передача прочитанного слова в DE для общей записи выражения
                EX DE, HL
                JP @Text.PushExpressionWord.Entry

                endmodule
                endmodule
