                module ReadStridedByte
                ; Документация [Text](../../Docs/FunctionDetails/Text.md)
                ; Подробный разбор [стековый договор чтения полей и проверка маркера](../../Docs/MarketAccess.md)
                ; -----------------------------------------
                ; Чтение байта с шагом два по индексу из CPU-стека
                ; исходная запись 5, файловые смещения #04E3..#04EE
                ; In:
                ;   на вершине CPU-стека слово индекса, под ним адрес возврата, старший байт индекса игнорируется
                ;   память по вычисленному адресу читаема, проверка границ массива в исходном коде отсутствует
                ;   вход Entry выбирает базу #95F1, отдельный вход ReadAtBase принимает базу в DE
                ; Out:
                ;   HL=база + 2*индекс по модулю 65536, DE=прочитанный байт с нулевым D, BC сохранён
                ;   AF - A сохранён, S/Z/PV из входного F, H/C от 2*индекс + база, X/Y из старшего байта суммы, N=0
                ;   альтернативные регистры, IX, IY, I и IFF сохранены, память не изменяется
                ; Corrupt:
                ;   HL, DE, AF только F, R
                ; Note:
                ;   собственных записей RAM и CPU-стека нет, снятые POP и RET четыре байта индекса и возврата остаются неизменными в памяти
                ;   Entry выполняет восемь M1, внутренний ReadAtBase семь M1, младшие семь битов R увеличиваются по модулю 128, старший сохраняется
                ;   RET снимает адрес после слова индекса, итоговый SP равен входному SP + 4
                ;   обычный CALL без слова индекса над адресом возврата не соответствует этому договору
                ;   ParseFieldSuffix передаёт индекс через PUSH HL, DispatchToken входит через JP (HL)
                ;   модель исходных байтов описана в MarketAccess.md, IRQ и нативный запуск не проверялись
                ;   EquipmentWeights.Row00.Weight начинает байты колонки «Вес» с шагом два
                ; -----------------------------------------
                ; выбор первого веса из пары порога и веса
Entry:          LD DE, @EquipmentWeights.Row00.Weight
                ; чтение индекса поверх адреса возврата, общий вход получает базу в DE
ReadAtBase:     POP HL
                ; отбрасывание старшего байта стекового индекса
                LD H, #00
                ; расчёт смещения с шагом два даже для байтового результата
                ADD HL, HL
                ; расчёт адреса читаемого байта относительно базы DE
                ADD HL, DE
                ; чтение байта и расширение результата DE нулевым старшим байтом
                LD E, (HL)
                LD D, #00
                RET

                endmodule
                endmodule
