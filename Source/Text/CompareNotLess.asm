                module Text
                module CompareNotLess
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; -----------------------------------------
; Беззнаковая проверка DE не меньше BC, результат ноль или один в DE
; исходная запись 5, файловые смещения #04BC..#04C5
; In:
;   DE - левый операнд, BC - правый операнд, сравнение без знака
; Out:
;   HL - разность операндов по модулю #10000, DE - логическое значение 0 или 1
; Corrupt:
;   HL, DE, AF
; Note:
;   BC, альтернативные и индексные регистры сохраняются
; -----------------------------------------
Entry:          EX DE, HL
                ; сброс входного переноса перед проверкой отношения не меньше
                OR A
                ; расчёт разности, заём исключает отношение не меньше
                SBC HL, BC
                LD DE, #0000
                RET C                                                           ; выход, если левый операнд меньше правого, отношение не меньше ложно

                INC DE
                RET

                endmodule
                endmodule
