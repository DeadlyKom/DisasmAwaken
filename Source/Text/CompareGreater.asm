                module CompareGreater
                ; Документация [Text](../../Docs/FunctionDetails/Text.md)
                ; Подробный разбор [эффекты бинарных операторов](../../Docs/ScriptLanguage.md#собственные-эффекты-простых-бинарных-операторов)
                ; -----------------------------------------
                ; Беззнаковая проверка DE больше BC, результат ноль или один в DE
                ; исходная запись 5, файловые смещения #04A6..#04B0
                ; In:
                ;   DE - левый операнд, BC - правый операнд, сравнение без знака
                ; Out:
                ;   HL - разность операндов по модулю #10000, DE - логическое значение 0 или 1
                ;   AF - A сохраняется, F от оборачиваемой разности левого и правого слов
                ; Corrupt:
                ;   HL, DE, AF, R
                ; Note:
                ;   собственных записей RAM и CPU-стека нет, RET увеличивает входной SP на два, I и IFF сохраняются без прерываний, R изменяется
                ;   BC, альтернативные и индексные регистры сохраняются
                ; -----------------------------------------
Entry:          EX DE, HL
                ; сброс входного переноса перед проверкой строгого превышения
                OR A
                ; расчёт разности для исключения равенства и меньшего левого операнда
                SBC HL, BC
                LD DE, #0000
                RET Z                                                           ; выход, если операнды равны, строгое превышение ложно

                RET C                                                           ; выход, если левый операнд меньше правого, строгое превышение ложно

                INC DE
                RET

                endmodule
                endmodule
