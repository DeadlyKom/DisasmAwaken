                module Text
                module WriteIndexedMMode
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [режим A альтернативного набора, реальные записи и путь до NextCommand](../../Docs/UnaryModes.md)
; -----------------------------------------
; Запись байтового режима по базе #9A32 и десятичному смещению
; исходная запись 5, файловые смещения #0189..#0190
; In:
;   AF' - A' записываемый целый байт, F' станет основным F после обмена
;   IX у первой проверенной десятичной цифры, выполняется договор ReadDecimal5
;   адрес (база 9A32+число) AND #FFFF доступен для записи
; Out:
;   HL адрес записи, DE база #9A32, BC рабочий выход ReadDecimal5
;   AF получает исходный AF', A записан в память, F не пересчитывается по записанному байту
;   AF' получает рабочий A парсера и F адресного сложения, HL', DE', BC', IY, I и IFF сохранены
;   IX первый непрочитанный символ, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF, AF', IX
; Note:
;   публичные команды задают 0 либо 1, прямой вход сохраняет любой A целиком, это не битовая маска
;   числовое смещение не уменьшается на один, границы массива не проверяются
;   общий StoreAtBase принимает HL полное смещение, DE базу и ещё не использованный альтернативный AF
; -----------------------------------------
                ; чтение десятичного смещения для поля m
Entry:          CALL @Text.ReadDecimal5.Entry
                ; выбор базы m перед общей записью режима
                LD DE, #9A32
                JR @Text.WriteIndexedPMode.StoreAtBase

                endmodule
                endmodule
