                module Text
                module TestExpression
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [порядок операций, скобки и границы выражения](../../Docs/ExpressionControl.md)
; -----------------------------------------
; Вычисление условия слева направо до непотреблённого разделителя ветви
; исходная запись 5, файловые смещения #0039..#0056
; In:
;   IX у первого символа поля слева, после него минимум один допустимый оператор и правое поле
;   фиксированный рабочий стек выражений CA67 доступен для записи
;   каждый читатель и оператор соблюдает договор DispatchReadField, EmitOperator и CallExpression
;   читатели добавляют одно слово, оператор возвращает DE через RET и сохраняет указатель выражений
;   впереди существует корректный завершающий символ, CPU-стек допускает вложенные вызовы
; Out:
;   хвостовой вход NextCommand, IX на первом : либо @ после готовой операции, SP перед NextCommand равен входному SP
;   HL'=CA69, по CA67 записано слово результата, прежний указатель HL' не восстанавливается
;   DE и DE альтернативного набора содержат последнее вычисленное слово, BC и HL по последнему оператору
;   AF - A=3A либо 40, F от совпавшего CP разделителя, Z=1
;   BC' и AF', IY, I, IFF и банковое состояние по эффектам выбранных читателей и операторов
;   неудачный поиск поля или операции передаёт SkipLine, обычного числового возврата на этом пути нет
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC' и AF' по выбранным полям, IX
; Note:
;   сначала читается левое поле, затем обязательно оператор и правое поле, одиночное поле не завершает выражение
;   CallExpression заменяет три слова Left, Handler, Right одним результатом после каждой операции
;   цепочка выполняется слева направо, приоритет умножения не выделяется, скобки создают вложенное поле
;   разделители ветви проверяются после операции и не потребляются, их затем читает NextCommand
;   точные эффекты конкретных полей и арифметики берутся из их договоров, общий предел регистра не подменяет их анализ
; -----------------------------------------
                ; выбор альтернативного указателя для сброса временного стека условия
Entry:          EXX
                ; выбор исходного рабочего стека выражений, прежняя вершина не сохраняется
                LD HL, @ExpressionStack.Entry
                EXX
                ; чтение левого поля и запись первого слова результата
                CALL @Text.DispatchReadField.Entry
                ; поиск следующего оператора и добавление его адреса после левого значения
NextOperation:  CALL @Text.EmitOperator.Entry
                ; чтение правого поля, которое может содержать вложенное скобочное выражение
                CALL @Text.DispatchReadField.Entry
                ; свёртка Left, Handler, Right в одно слово результата выбранного оператора
                CALL @Text.CallExpression.Entry
                ; проверка границы готового условного выражения без продвижения курсора
                LD A, (IX + @ScriptConst.Cursor)
                ; проверка разделителя обычной ветви после операции
                CP #3A
                JR Z, @Text.NextCommand.Entry                                   ; переход, если текущий символ двоеточие, передать его следующей команде

                ; проверка разделителя обратной ветви
                CP #40
                JR NZ, @Text.TestExpression.NextOperation                       ; переход, если символ не @ и не двоеточие, продолжить цепочку операций

                JR @Text.NextCommand.Entry

                endmodule
                endmodule
