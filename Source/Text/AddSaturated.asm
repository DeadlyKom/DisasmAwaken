                module Text
                module AddSaturated
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; -----------------------------------------
; Сложение DE и BC с ограничением результата сверху значением #FFFF
; исходная запись 5, файловые смещения #0488..#0490
; In:
;   DE - левый операнд, BC - правый операнд
; Out:
;   DE - ограниченный результат, HL сохраняется
; Corrupt:
;   DE, AF
; Note:
;   границы ограничены нулём и #FFFF, HL, BC, альтернативные и индексные регистры сохраняются
; -----------------------------------------
Entry:          EX DE, HL
                ; расчёт суммы операндов с проверкой выхода за пределы 16 бит
                ADD HL, BC
                JR NC, @Text.AddSaturated.ReturnResult                          ; переход, если сумма не превышает 65535, ограничение не требуется

                ; ограничение переполненной суммы максимальным беззнаковым словом
                LD HL, #FFFF
ReturnResult:   EX DE, HL
                RET

                endmodule
                endmodule
