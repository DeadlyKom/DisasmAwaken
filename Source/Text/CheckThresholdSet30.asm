                module Text
                module CheckThresholdSet30
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [неактивные байты, пороги, второй порядок баз и флаги результата](../../Docs/ThresholdSets.md)
; -----------------------------------------
; Проверка 30 активных строк по числовому признаку L текущего ключа
; исходная запись 5, файловые смещения #04EF..#0519
; In:
;   на вершине CPU-стека слово индекса поверх возврата, оно снимается и дальше не используется
;   текущий ключ SignatureInput.Entry доступен, действует банковый договор DescribeCurrentKeyForLang
;   таблицы порогов #95F0 с шагом два и активности #988E с шагом один читаемы
; Out:
;   HL - адрес первого нарушенного порога либо база порогов + 2*число_строк при успехе
;   DE=A=0 при первом активном пороге больше L характеристики, иначе DE=A=1
;   BC - B число оставшихся строк вместе с нарушенной, при успехе B=0, C сохранён
;   AF - при неуспехе F от CP признака с порогом, Carry=1, Z=0
;   при успехе F от последнего OR A для неактивной строки либо CP последнего активного порога
;   HL', DE', BC', IX, IY, I и IFF сохранены, AF' содержит финальную страницу банкового запроса
;   SP равен входному SP+4, рабочий ключ обновлён, ThresholdSetState.Limit записан признаком L
; Corrupt:
;   HL, DE, BC только B, AF, AF'
; Note:
;   активность определяется кодированным байтом, 0 и FF неактивны, остальные значения активны
;   успех не имеет единственного значения Z, результат берётся из DE либо A
;   общий NextRow принимает HL пороги, DE активность, B число строк, Limit уже настроен
;   порядок баз второго входа сохранён точно, смысл данных нельзя выводить из похожего первого набора
;   игровой смысл ограничения и единицы порогов пока не установлены
; -----------------------------------------
                ; снятие слова индекса со стека, текущий ключ выбирается независимо от этого слова
Entry:          POP HL
                ; получение числовых признаков текущего ключа с возвратом банка LANG
                CALL @Station.DescribeCurrentKeyForLang.Entry
                ; выбор признака L как предела для всех активных строк
                LD A, L
                ; обновление непосредственного операнда Limit в CP-цикле
                LD (@ThresholdSetState.Limit), A
                ; выбор 30 порогов с двухбайтовым шагом
                LD HL, #95F0
                ; выбор последовательных кодированных байтов активности
                LD DE, #988E
                ; выбор числа проверяемых строк первого набора
                LD B, #1E
                ; чтение текущего кодированного байта активности
NextRow:        LD A, (DE)
                ; проверка старшего разряда перед декодированием инверсией
                OR A
                JP P, @Text.CheckThresholdSet30.CheckActive                     ; переход, если bit7 активности снят, использовать исходный байт

                ; декодирование старшего байта инверсией, FF становится нулём
                CPL
                ; проверка неактивного нулевого результата, исходные 0 и FF пропускаются
CheckActive:    OR A
                JR Z, @Text.CheckThresholdSet30.Advance                         ; переход, если строка неактивна, не проверять её порог

                ; чтение самомодифицированного числового предела L
                LD A, #00
                ; проверка текущего порога по отношению к пределу
                CP (HL)
                LD A, #00
                JR C, @Text.CheckThresholdSet30.ReturnResult                    ; переход, если порог активной строки больше предела, вернуть 0

                ; переход к следующему порогу с шагом два и байту активности с шагом один
Advance:        INC HL
                INC HL
                INC DE
                DJNZ @Text.CheckThresholdSet30.NextRow

                ; выбор результата 1 после проверки всех строк без нарушения
                LD A, #01
                ; передача результата в DE с нулевым D, флаги предшествующей проверки сохраняются
ReturnResult:   LD E, A
                LD D, #00
                RET

                endmodule
                endmodule
