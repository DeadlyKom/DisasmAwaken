                module Text
                module SumSecondaryIndex
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [байтовая сумма, прямой вес и флаги инверсии](../../Docs/WeightFields.md)
; -----------------------------------------
; Суммирование двух исходных компонент вторичного индекса по модулю 256
; исходная запись 5, файловые смещения #090C..#0917
; In:
;   доступны два исходных байта по #73D8 и #737D, их игровое назначение ещё не установлено
; Out:
;   HL, DE сохранены, BC - B=0, C=(байт #73D8 + байт #737D) AND #FF
;   AF - A та же сумма, F от восьмибитного сложения второго байта с первым
;   альтернативные и индексные регистры, I и IFF сохранены, SP восстановлен
; Corrupt:
;   BC, AF
; Note:
;   перенос за пределы байта не расширяет индекс, #FF отдельно не проверяется
;   сумма используется двумя обёртками второго набора, имена компонентов не выводятся из предположений о GUI
; -----------------------------------------
                ; чтение первой исходной компоненты вторичного индекса
Entry:          LD A, (#73D8)
                LD C, A
                ; чтение второй компоненты без интерпретации её игрового назначения
                LD A, (#737D)
                ; расчёт суммы двух байтов по модулю 256
                ADD A, C
                LD C, A
                ; создание BC с нулевым B без добавления переноса к старшему байту
                LD B, #00
                RET

                endmodule
                endmodule
