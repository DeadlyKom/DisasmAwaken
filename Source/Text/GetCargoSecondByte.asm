                module GetCargoSecondByte
                ; Документация [Text](../../Docs/FunctionDetails/Text.md)
                ; Подробный разбор [двухбайтовая запись, сохранённый bit7 и различие индексов](../../Docs/CargoField.md)
                ; -----------------------------------------
                ; Чтение второго байта двухбайтовой грузовой записи по стековому индексу
                ; исходная запись 5, файловые смещения #05C1..#05C6
                ; In:
                ;   на вершине CPU-стека слово индекса, под ним возврат, старший байт отбрасывается
                ;   память по #9853+2*младший_индекс читаема, логические границы не проверяются
                ; Out:
                ;   HL=#9853+2*младший_индекс, DE прочитанный байт с нулевым D, BC сохранён
                ;   AF - A сохранён, F от ADD HL,DE общего ядра, S/Z/PV из входного F, H/C от сложения
                ;   N=0, X/Y из старшего байта итогового адреса, SP равен входному SP+4
                ;   альтернативные и индексные регистры, I и IFF сохранены
                ; Corrupt:
                ;   HL, DE, AF только F, R
                ; Note:
                ;   собственных записей RAM и CPU-стека нет, снятые POP и RET четыре байта индекса и возврата остаются неизменными в памяти
                ;   полный путь вместе с общим ReadAtBase выполняет девять M1, младшие семь битов R увеличиваются по модулю 128, старший сохраняется
                ;   используется общий ReadStridedByte.ReadAtBase, другого преобразования поля нет
                ;   второй байт является FOwnedCargoRow.Price, ценой приобретения по подписи TWRI, физический размер записи сохраняется
                ; -----------------------------------------
                ; выбор базы вторых байтов двухбайтовых грузовых записей
Entry:          LD DE, #9853
                JP @Text.ReadStridedByte.ReadAtBase

                endmodule
                endmodule
