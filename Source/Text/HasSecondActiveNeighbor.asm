                module Text
                module HasSecondActiveNeighbor
                ; Документация [Text](../../Docs/FunctionDetails/Text.md)
                ; Подробный разбор [точные границы поиска, пропуск выбранного элемента и флаги](../../Docs/ActiveNeighbors.md)
                ; Достижимые адреса при индексах за таблицей [проверка](../../Docs/SecondaryContextAliases.md)
                ; -----------------------------------------
                ; Поиск активного соседа по границам второго набора
                ; исходная запись 5, файловые смещения #05A9..#05B1
                ; In:
                ;   на вершине CPU-стека слово индекса, под ним возврат, старший байт игнорируется
                ;   Entry выбирает BC базу пар границ #9690 и DE базу значений #98F6
                ;   все адреса в выбранных границах читаемы, логический размер таблиц не проверяется
                ; Out:
                ;   HL - адрес выбранного элемента при найденном левом соседе, иначе найденного правого либо конца правого поиска
                ;   DE - 1 при найденном активном соседе, иначе 0, BC - B старший байт базы границ, C остаток текущего счётчика
                ;   AF - A декодированное ненулевое значение найденного соседа либо 0 при отсутствии
                ;   при успехе F от OR A декодированного значения, Carry=0 и Z=0, при отсутствии у Entry F=#42 и Z=1
                ;   альтернативные и индексные регистры, I и IFF сохранены, SP равен входному SP+4
                ; Corrupt:
                ;   HL, DE, BC, AF, R, снятое слово индекса в CPU-стеке
                ; Note:
                ;   после POP индекса PUSH DE повторно использует его два байта и записывает адрес выбранного элемента, исходный адрес возврата сохраняется
                ;   кроме этой временной пары собственных записей RAM и CPU-стека нет, POP не очищает сохранённый адрес в памяти
                ;   R зависит от числа просмотренных соседей и выполненных CPL, старший бит сохраняется
                ;   у общего входа при двух нулевых границах Carry сохраняется от сложения адреса пары, при его переносе F=#43
                ;   адрес пары границ равен база_границ+((2*младший_индекс) AND #FF), индексы 0 и 128 используют одну пару
                ;   адрес выбранного значения равен база_значений+младший_индекс без этого оборачивания
                ;   левый предел задаёт (-первый_байт) AND #FF шагов, правый предел второй_байт шагов
                ;   выбранный элемент не проверяется, сначала читаются только предыдущие, затем следующие
                ;   активны все байты кроме 0 и FF, bit7 кодируется побитовой инверсией перед OR A
                ;   игровая семантика зависимостей и конкретных пар границ ещё не установлена
                ;   индекс 13 читает два исходных нуля клавиатурного якоря KeyboardCodes.Anchor
                ; -----------------------------------------
                ; выбор второй таблицы пар границ
Entry:          LD BC, @SecondNeighborBounds.Row00.Left
                ; выбор второй базы значений перед общим сканером
                LD DE, @SecondaryEquipmentData.Quantities
                JP @Text.HasActiveNeighbor.ScanAtBases

                endmodule
                endmodule
