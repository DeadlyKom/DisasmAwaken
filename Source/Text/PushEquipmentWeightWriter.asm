                module Text
                module PushEquipmentWeightWriter
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [захват адреса и значения, рамка оператора и точный способ сохранения](../../Docs/IndexedWriters.md)
; -----------------------------------------
; Создание захватывающего писателя кодированного веса через ReadEquipmentWeight
; исходная запись 5, файловые смещения #06BC..#06E3
; In:
;   HL' указывает на два доступных байта следующего слова выражения, действует входной договор ReadEquipmentWeight
;   результат читателя HL должен быть адресом записываемого целевого байта, полученное значение доступно
;   до Invoke нельзя создавать другой писатель того же общего шаблона, захваченные операнды общие
;   Invoke принимает FFieldInvokeFrame и BC правый операнд, оператор возвращает DE через RET в банк LANG 6
; Out:
;   Entry - HL адрес от читателя, DE общий Invoke, BC от читателя, AF от читателя
;   Entry - HL' увеличен на два, DE' содержит Invoke, BC', AF', IX, IY по договору читателя
;   Entry обновляет общие операнды Target и InitialValue, само целевое поле не записывает
;   Invoke передаёт оператору DE захваченное байтовое значение с нулевым D, BC правый операнд
;   перед входом оператора CPU-стек FIndexedOperatorFrame, сохранены StoreReturn, SavedTarget и AfterStore
;   Store возвращает HL адрес цели, BC как у оператора, DE как у оператора, включая D
;   Store - AF A сохранённый байт, F от BIT либо CPL по текущему bit7
;   SP после Entry равен входному SP+2, после Invoke либо отдельного Store входному SP+4
; Corrupt:
;   Entry - HL, DE, BC, AF, HL', DE', BC' только B, AF' и IX по договору читателя
;   Invoke - HL, DE и регистры по договору оператора
;   Store - HL, AF
; Note:
;   целевой адрес и левый операнд захватываются при создании, маркер либо условие инверсии читается из памяти только в Store
;   Invoke добавляет SavedTarget между StoreReturn и AfterStore, Store снимает этот адрес POP HL
;   D результата игнорируется, если E>=128, запись может изменить исходный bit7 несмотря на условие инверсии
;   игровой смысл маркера и физические единицы веса отдельно не доказаны
; -----------------------------------------
                ; получение адреса и декодированного веса оснащения
Entry:          CALL @Text.ReadEquipmentWeight.Entry
                ; обновление захваченного адреса общего писателя кодированных весов
Capture:        LD (@EncodedWriterState.Target), HL
                ; сохранение A читателя как левого операнда веса
                LD (@EncodedWriterState.InitialValue), A
                ; выбор общего Invoke писателя кодированного веса
                LD DE, @Text.PushEquipmentWeightWriter.Invoke
                JP @Text.PushExpressionWord.Entry

                ; снятие адреса оператора из рамки вызова писателя веса
Invoke:         POP DE
                ; чтение захваченного адреса целевого веса
                LD HL, #0000
                ; чтение захваченного левого значения веса
                LD A, #00
                ; сохранение адреса веса для последующего Store
                PUSH HL
                ; выбор Store как возврата оператора веса
                LD HL, @Text.PushEquipmentWeightWriter.Store
                ; создание рамки StoreReturn, SavedTarget, AfterStore
                PUSH HL
                ; создание левого DE с нулевым D из захваченного A
                LD L, A
                LD H, #00
                ; передача оператору HL адреса и DE левого значения
                EX DE, HL
                JP (HL)

                ; восстановление адреса веса после RET оператора
Store:          POP HL
                ; проверка bit7 текущего байта, захваченное прежнее значение тут не используется
                BIT 7, (HL)
                ; выбор только младшего E результата, D не участвует в сохранении
                LD A, E
                JR Z, @Text.PushEquipmentWeightWriter.StoreValue                ; переход, если текущий bit7 цели снят, записать E без инверсии

                ; инверсия младшего E по текущему bit7 цели, старший разряд результата может сменить кодировку
                CPL
                ; запись кодированного веса без отдельного насыщения и без изменения DE
StoreValue:     LD (HL), A
                RET

                endmodule
                endmodule
