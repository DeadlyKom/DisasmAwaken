                module Text
                module CheckEquipmentThreshold
                ; Документация [Text](../../Docs/FunctionDetails/Text.md)
                ; Подробный разбор [сохранённый AF, прямой порог и четыре суффикса](../../Docs/EntryThreshold.md)
                ; -----------------------------------------
                ; Сравнение порога записи оснащения с признаком L текущего ключа
                ; исходная запись 5, файловые смещения #028F..#02B4
                ; In:
                ;   IX - начало необязательного индекса или точки, доступны компоненты индекса соответствующего списка
                ;   первый набор использует GetEquipIndex, второй SumSecondaryIndex, текущий ключ доступен
                ;   при обычном возврате точка отсутствует либо свойство c, v, s, k допустимо, действует договор банковых запросов LANG
                ; Out:
                ;   без точки HL - H прочитанный порог, L флаги сохранённого ADD HL,DE до банкового вызова
                ;   без точки DE=A=1 при L характеристики не меньше порога, иначе DE=A=0
                ;   без точки BC - B=0, C исходный байтовый индекс списка, сохраняемый банковым запросом
                ;   без точки AF - при успехе F=0 после INC A, при отказе F от CP признака с порогом, Carry=1 и Z=0
                ;   с суффиксом результат и регистры определяются соответствующим стековым читателем c, v, s либо k
                ;   HL', DE' сохранены, BC' - B'=4, C' сохранён, AF' прямого пути от возврата банка 6
                ;   IX - первый непрочитанный символ, IY, I и IFF сохранены, SP обычного возврата равен входному SP+2
                ;   на прямом пути рабочий ключ обновлён, аппаратная страница и тень возвращают банк 6
                ;   с суффиксом BC - B число оставшихся записей вместе с найденной, C исходный индекс, AF по договору обработчика
                ; Corrupt:
                ;   HL, DE, BC, AF, BC' только B, AF' на прямом пути, IX, R, DefaultTarget, WorkKey, временный CPU-стек, CurrentPage и порт #7FFD
                ; Note:
                ;   с суффиксами c, v, s, k банковый запрос прямого порога не выполняется, вне CPU-стека меняется только DefaultTarget
                ;   на прямом пути нестековые записи ограничены DefaultTarget, WorkKey и CurrentPage, порт выбирает банки 1, 0 и 6
                ;   PUSH AF и вложенные CALL записывают временный CPU-стек, POP HL не очищает RAM, исходный возврат сохраняется
                ;   R зависит от настоящего банкового запроса, полный счётчик и все суффиксные пути здесь не доказаны
                ;   явный индекс равен (число-1) AND #FFFF, без числа индекс списка уже байтовый
                ;   прямое чтение использует полный индекс, адрес порога равен (база 95F0+2*индекс) AND #FFFF
                ;   PUSH AF сохраняет порог и флаги, POP HL намеренно возвращает их в H и L, адрес записи теряется
                ;   оба прямых результата возвращают Z=0, проверять результат нужно по DE либо A
                ;   общий CheckAtBase принимает полный HL индекс и DE базу порогов, остальные подготовленные данные списка сохраняются
                ;   игровые единицы порога и точные роли дополнительных полей ещё не установлены
                ;   неизвестный суффикс передаёт управление SkipLine без обычного результата
                ; -----------------------------------------
                ; установка числа четырёх свойств c, v, s, k первого набора в альтернативном B
Entry:          EXX
                LD B, #04
                EXX
                ; выбор адреса за одной записью до таблицы свойств первого набора
                LD DE, #C9F8
                ; получение байтового индекса оснащения
                CALL @Text.GetEquipIndex.Entry
                ; выбор прямой проверки порога для отсутствующего суффикса
                LD HL, @Text.CheckEquipmentThreshold.ReadDirect
                JP @Text.ParseFieldSuffix.Entry

                ; выбор базы порогов первого набора
ReadDirect:     LD DE, @EquipmentListData.Weights
                ; расчёт двухбайтового смещения по полному слову индекса
CheckAtBase:    ADD HL, HL
                ; расчёт адреса порога относительно базы DE
                ADD HL, DE
                ; чтение байтового порога без маскирования разрядов
                LD A, (HL)
                ; сохранение порога вместе с флагами адресного сложения на CPU-стеке
                PUSH AF
                ; получение характеристики текущего ключа через настоящую банковую обёртку
                CALL @Station.DescribeCurrentKeyForLang.Entry
                ; выбор признака L как значения для сравнения с сохранённым порогом
                LD A, L
                ; восстановление сохранённого AF в HL, H порог, L прежние флаги
                POP HL
                ; проверка порога относительно признака L текущего ключа
                CP H
                ; выбор результата 0 до условного перехода по отказу
                LD A, #00
                JR C, @Text.CheckEquipmentThreshold.ReturnResult                ; переход, если признак L меньше порога, вернуть 0 с флагами CP

                ; выбор результата 1 при достаточном признаке, INC A задаёт F=0
                INC A
                ; передача результата в DE без изменения его флагов
ReturnResult:   LD E, A
                LD D, #00
                RET

                endmodule
                endmodule
