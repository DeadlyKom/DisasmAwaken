                module Text
                module Property072
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [условия совпадения, код bit7 и два общих стековых входа](../../Docs/MembershipFlags.md)
; -----------------------------------------
; Проверка отсутствия байта #984A в записи таблицы #9484
; исходная запись 5, файловые смещения #05B2..#05BA
; In:
;   на вершине CPU-стека слово индекса, под ним адрес возврата, старший байт индекса отбрасывается
;   Entry читает искомый байт по #984A и выбирает базу #9484
; Out:
;   HL - адрес после совпавшего байта среди первых трёх, либо адрес четвёртого байта записи
;   DE - 0 при совпадении с любым из четырёх байтов, 1 при отсутствии совпадения, BC сохранён
;   AF - A искомый байт, F от последнего CP, Z=1 при совпадении, Z=0 при отсутствии
;   альтернативные и индексные регистры, I и IFF сохранены, SP равен входному SP+4
; Corrupt:
;   HL, DE, AF
; Note:
;   адрес записи равен база+4*младший_индекс, логические границы не проверяются
;   после четвёртого CP нет INC HL, после первых трёх указатель продвигается даже при совпадении
;   игровой смысл байта селектора и физического списка ещё не установлен
;   Property072 сохраняет табличное имя до установления назначения её поля
; -----------------------------------------
                ; выбор второй базы четырёхбайтовых записей
Entry:          LD DE, #9484
                ; чтение искомого байта второго входа из #984A
                LD A, (#984A)
                JP @Text.IsByteMissingFromFour.CheckAtBase

                endmodule
                endmodule
