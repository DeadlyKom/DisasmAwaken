                module Text
                module ReadStrideFiveWord
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [общие входы чтения, пятибайтовый шаг и полный договор флагов](../../Docs/StrideFive.md)
; -----------------------------------------
; Чтение слова по индексу из CPU-стека с шагом пять и базой #9803
; исходная запись 5, файловые смещения #05E9..#05F8
; In:
;   на вершине CPU-стека слово индекса, под ним адрес возврата, старший байт индекса игнорируется
;   вычисленные адреса читаемы, Entry выбирает базу #9803
;   отдельный вход ReadAtBase принимает произвольную базу в DE
; Out:
;   HL=(база+5*индекс+1) AND #FFFF, DE=слово, младший байт первым
;   BC - исходный младший байт индекса с нулевым B, входной BC не сохраняется
;   AF - A сохранён, S/Z/PV из входного F, H/C от база+5*индекс, X/Y из старшего байта суммы, N=0
;   альтернативные и индексные регистры, I и IFF сохранены, память не изменяется
;   SP равен входному SP+4, индекс и адрес возврата потреблены
; Corrupt:
;   HL, DE, BC, AF только F
; Note:
;   индекс не проверяется по числу физических записей, только обрезается до младшего байта
;   PUSH HL и POP BC временно сохраняют индекс для расчёта 4*индекс+индекс
;   игровое назначение самих читаемых полей здесь ещё не доказано, доказаны адреса, ширина и алгоритм чтения
; -----------------------------------------
                ; выбор исходной базы 9803, её игровое поле пока не установлено
Entry:          LD DE, #9803
                ; чтение слова индекса поверх возврата, общий вход принимает базу в DE
ReadAtBase:     POP HL
                ; отбрасывание старшего байта индекса
                LD H, #00
                ; сохранение байтового индекса для сложения с его четырёхкратным значением
                PUSH HL
                ; расчёт четырёхкратного индекса двумя удвоениями
                ADD HL, HL
                ADD HL, HL
                ; восстановление индекса в BC, входной BC заменяется
                POP BC
                ; расчёт пятибайтового смещения как 4*индекс+индекс
                ADD HL, BC
                ; расчёт адреса поля относительно базы DE, итоговые флаги от этого сложения
                ADD HL, DE
                ; чтение младшего байта слова, затем старшего из соседнего адреса
                LD E, (HL)
                INC HL
                LD D, (HL)
                RET

                endmodule
                endmodule
