                module Text
                module EmitOperator
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [ScriptLanguage.md](../../Docs/ScriptLanguage.md)
; -----------------------------------------
; Поиск символа бинарной операции и запись адреса её обработчика по альтернативному HL
; исходная запись 5, файловые смещения #079C..#07B5
; In:
;   HL' - место записи следующего слова выражения, IX - символ бинарного оператора
; Out:
;   при совпадении HL - старший байт указателя в таблице, DE - адрес обработчика, HL' увеличен на два, DE' - тот же адрес, IX увеличен на один
; Corrupt:
;   HL, DE, BC, AF, HL', DE', IX
; Note:
;   символ ищется в одиннадцати записях таблицы операторов, в буфер пишутся младший и старший байты указателя
;   BC', AF' и IY сохраняются на успешном пути, CPU-стек восстанавливается
;   если символ не найден, FindToken передаёт управление SkipLine, обычного возврата с ошибкой нет
; -----------------------------------------
                ; чтение символа операции с продвижением входного курсора
Entry:          LD A, (IX + @ScriptConst.Cursor)
                INC IX
                ; поиск обработчика в таблице одиннадцати бинарных операторов
                LD HL, @ScriptTables.OperatorAnchor
                LD B, @ScriptConst.OperatorCount
                CALL @Text.FindToken.Entry
                INC HL
                LD E, (HL)
                INC HL
                LD D, (HL)
                ; запись указателя обработчика в буфер выражения через альтернативный HL
                PUSH DE
                EXX
                POP DE
                LD (HL), E
                INC HL
                LD (HL), D
                INC HL
                EXX
                RET

                endmodule
                endmodule
