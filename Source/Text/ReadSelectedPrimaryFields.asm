                module Text
                module ReadSelectedPrimaryFields
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [точные c/t/s и c/v, исходный селектор и возврат 127](../../Docs/RecordFieldSelectors.md)
; -----------------------------------------
; Чтение свойств первого набора по байту выбранной записи
; исходная запись 5, файловые смещения #0207..#0220
; In:
;   IX - начало необязательного индекса либо точки, таблицы читаемы, действуют договоры ParseFieldSuffix и стекового чтения
;   индекс по умолчанию равен байту по #9849
;   явное число задаёт (число-1) AND #FFFF, свойства используют младший байт этого индекса
; Out:
;   без точки HL индекс парсера, DE=исходный байт селектора независимо от явного числа
;   без точки BC - B=0, C исходный индекс по умолчанию, AF - A непрочитанный символ, F последнего CP парсера
;   с точкой DE прочитанное поле, HL адрес поля либо его старшего байта, BC младший байт индекса с нулевым B
;   с точкой AF по договору ReadStrideFiveWord либо ReadStrideFiveByte, A младший байт адреса выбранного обработчика
;   HL', DE' сохранены, BC' - B'=3, C' сохранён, AF' и IY, I и IFF сохранены
;   IX первый непрочитанный символ, SP обычного возврата равен входному SP+2
;   переключений банков нет
; Corrupt:
;   HL, DE, BC, AF, BC' только B, IX
; Note:
;   первый набор c читает слово #9803+5*индекс, t байт #9802+5*индекс, s байт #9806+5*индекс
;   второй набор c читает слово #9826+5*индекс, v байт #9829+5*индекс
;   игровые имена и единицы этих физических полей пока не установлены, первичный и вторичный обозначают разные таблицы
;   неизвестный суффикс передаёт управление SkipLine без обычного числового результата
; -----------------------------------------
                ; чтение слова по адресу селектора, следующий байт B сразу отбрасывается
Entry:          LD BC, (#9849)
                ; обнуление B, индекс по умолчанию остаётся в C
                LD B, #00
                ; установка числа свойств в альтернативном B
                EXX
                LD B, #03
                EXX
                ; выбор адреса за одной записью до таблицы свойств набора
                LD DE, #CA1C
                ; выбор локального чтения исходного селектора без точки
                LD HL, @Text.ReadSelectedPrimaryFields.NoSuffix
                JP @Text.ParseFieldSuffix.Entry

                ; повторное чтение байта селектора, явный числовой индекс здесь не используется
NoSuffix:       LD DE, (#9849)
                LD D, #00
                RET

                endmodule
                endmodule
