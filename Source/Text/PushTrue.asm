; Добавление логической единицы в стек выражений без изменения F
; исходная запись 5, файловые смещения #0252..#0256
; In:
;   HL' - адрес следующих двух доступных для записи байтов стека выражений, без перекрытия текущего кода и CPU-стека
;   источник 1 доступен
; Out:
;   HL, DE и BC сохранены, AF - A=1, F сохранён
;   HL' увеличен на два, в прежнюю позицию записано A, затем 0, DE', BC', AF', IX, IY, I и IFF сохранены
;   SP обычного возврата равен входному SP+2
; Corrupt:
;   AF только A, HL'
; Note:
;   байтовый вход не переносит результат в DE альтернативного набора, в отличие от PushExpressionWord
;   запись имеет ширину слова, хотя источник байтовый, старший байт всегда нулевой
; -----------------------------------------
                ; выбор логического значения 1 без пересчёта флагов
Entry:          LD A, #01
                JP @Text.ReadFieldLowerj.AppendByte

