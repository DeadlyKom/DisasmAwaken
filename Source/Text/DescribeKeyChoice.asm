                module Text
                module DescribeKeyChoice
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [условие выбора, изменение C и возврат банка LANG](../../Docs/KeyChoice.md)
; -----------------------------------------
; Характеристика второго ключа при C=1 либо текущего ключа при остальных значениях
; исходная запись 5, файловые смещения #0924..#0934
; In:
;   BC - C код выбора, 1 выбирает ключ #9844..#9848, остальные значения текущий ключ #983F..#9843
;   LANG загружен в банк 6, он выбран в аппаратном порте и тени, bit5 порта снят
;   стек находится вне сменяемого окна, выполняется договор банковых процедур характеристики
; Out:
;   HL, DE и AF содержат характеристику выбранного ключа по WorldSignature.md
;   BC - B сохранён, C=(входной C-1) AND #FF, это изменение сохраняется после банковых вызовов
;   HL', DE', BC', IX, IY, I и IFF сохранены, SP восстановлен относительно обычного CALL
;   AF' содержит финальную страницу с банком 6 и ROM 1 и флаги её OR
;   рабочий ключ изменяется, порт и его тень последовательно выбирают банки 1, 0 и 6
; Corrupt:
;   HL, DE, BC только C, AF, AF'
; Note:
;   C=0 превращается в #FF и выбирает текущий ключ, входной C не сохраняется
;   других сравнений кода выбора нет, значения 2..255 также выбирают текущий ключ
;   игровая роль второго ключа здесь не установлена, его формат подтверждён тремя загрузками
;   основной AF результата не содержит флаги начального DEC C, его определяет выбранная характеристика
; -----------------------------------------
                ; проверка выбора второго ключа вычетом единицы, C изменяется на всех путях
Entry:          DEC C
                JP NZ, @Station.DescribeCurrentKeyForLang.Entry                 ; переход, если входной C отличался от 1, получить характеристику текущего ключа и вернуть банк 6

                ; чтение первого слова второго ключа из существующей области станции
                LD HL, (#9844)
                ; чтение второго слова выбранного ключа
                LD DE, (#9846)
                ; чтение байтового варианта второго ключа
                LD A, (#9848)
                JP @Station.DescribeKeyForLang.Entry

                endmodule
                endmodule
