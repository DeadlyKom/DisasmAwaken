                module Text
                module ReadFieldUpperO
                ; Документация [Text](../../Docs/FunctionDetails/Text.md)
                ; Подробный разбор [композиция CheckEquipmentThreshold и PushExpressionWord](../../Docs/ExpressionPushes.md)
                ; -----------------------------------------
                ; Получение результата через CheckEquipmentThreshold и запись слова в стек выражений
                ; исходная запись 5, файловые смещения #0289..#028E
                ; In:
                ;   HL' - адрес следующих двух доступных для записи байтов стека выражений, без перекрытия текущего кода и CPU-стека
                ;   выполняется входной договор CheckEquipmentThreshold, для обычного результата допустим корректный суффикс
                ;   читатель сохраняет альтернативный HL до записи результата, итоговый адрес остаётся доступным для двух байтов
                ; Out:
                ;   HL, DE, BC и AF по выходному договору CheckEquipmentThreshold, DE дополнительно записан в стек выражений
                ;   HL' увеличен на два относительно исходной позиции, DE' содержит записанный результат
                ;   BC' и AF' по договору читателя, IX и IY также по его договору, I и IFF сохраняются
                ;   SP обычного возврата равен входному SP+2, слово записано младшим байтом первым
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC' только B, AF' по пути читателя, IX, R, два байта выражения, DefaultTarget, WorkKey, временный CPU-стек, CurrentPage и порт #7FFD
                ; Note:
                ;   четыре допустимых суффикса отдельно проверены полной цепочкой, B и AF сохраняют результат соответствующего обработчика
                ;   на прямом пути проверены настоящий пороговый читатель, банковая характеристика и словный писатель выражения
                ;   CALL читателя и PUSH DE писателя повторно используют пару ниже входного SP, исходный возврат обёртки сохраняется
                ;   DefaultTarget меняется на всех путях, WorkKey, CurrentPage и порт меняются прямым путём, полный R не доказан
                ;   CALL читателя получает собственный возврат, затем JP PushExpressionWord использует исходный возврат обёртки
                ;   дополнительных арифметических преобразований и пересчёта F обёртка не выполняет
                ;   если читатель передаёт управление SkipLine вместо возврата, запись результата не достигается
                ; -----------------------------------------
                ; получение результата DE через CheckEquipmentThreshold с его исходными побочными эффектами
Entry:          CALL @Text.CheckEquipmentThreshold.Entry
                ; добавление слова DE через общий PushExpressionWord, новый CALL не создаётся
                JP @Text.PushExpressionWord.Entry

                endmodule
