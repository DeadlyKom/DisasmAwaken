                module ReadSkimmerLoadAddend
                ; Документация [Text](../../Docs/FunctionDetails/Text.md)
                ; Подробный разбор [общие входы чтения, пятибайтовый шаг и полный договор флагов](../../Docs/StrideFive.md)
                ; -----------------------------------------
                ; Чтение байта по индексу из CPU-стека с шагом пять и базой #9829
                ; исходная запись 5, файловые смещения #0615..#061A
                ; In:
                ;   на вершине CPU-стека слово индекса, под ним адрес возврата, старший байт индекса игнорируется
                ;   вычисленные адреса читаемы, Entry выбирает базу #9829
                ; Out:
                ;   HL=(база+5*индекс) AND #FFFF, DE=прочитанный байт с нулевым D
                ;   BC - исходный младший байт индекса с нулевым B, входной BC не сохраняется
                ;   AF - A сохранён, S/Z/PV из входного F, H/C от база+5*индекс, X/Y из старшего байта суммы, N=0
                ;   альтернативные и индексные регистры, I и IFF сохранены, запись RAM ограничена снятым словом индекса
                ;   SP равен входному SP+4, индекс и адрес возврата потреблены
                ; Corrupt:
                ;   HL, DE, BC, AF только F, R и два байта снятого слова индекса на CPU-стеке
                ; Note:
                ;   если читаемый адрес совпадает со снятым словом индекса, результат берётся после PUSH, старший байт уже заменён нулём
                ;   единственный PUSH записывает младший байт индекса и ноль в его исходное слово, адрес возврата под ним сохраняется
                ;   индекс не проверяется по числу физических записей, только обрезается до младшего байта
                ;   PUSH HL и POP BC временно сохраняют индекс для расчёта 4*индекс+индекс
                ;   свойство v читает то же слагаемое, которое ComputeWeightedLoad добавляет для выбранного скимера
                ; -----------------------------------------
                ; выбор базы байтового слагаемого нагрузки скимера перед общим чтением
Entry:          LD DE, @StationSkimmerTradeRows.Skimmer0.LoadAddend
                JP @Text.ReadStrideFiveByte.ReadAtBase

                endmodule
                endmodule
