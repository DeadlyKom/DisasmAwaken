                module Text
                module ReadCurrentKeyParams
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [точные таблицы s/c/u и p/g, явный индекс и путь без точки](../../Docs/KeyFieldSelectors.md)
; -----------------------------------------
; Выбор текущего ключа по умолчанию и группы s, c, u
; исходная запись 5, файловые смещения #0383..#0392
; In:
;   IX - начало необязательного числового выбора либо точки, B сохраняемый контекст до диспетчера
;   без числа используется код выбора 0, явное число преобразуется в (число-1) AND #FFFF
;   LANG находится в банке 6, данные обоих ключей доступны, действуют договоры ParseFieldSuffix и DescribeKeyChoice
; Out:
;   без точки HL полный индекс выбора, DE=#CA25 адрес за одной записью до таблицы свойств
;   без точки BC - B сохранён, C=0, AF - A непрочитанный символ, F последнего CP парсера
;   с точкой DE поле характеристики по выбранному символу, HL и AF по договору соответствующего GetKey обработчика
;   с точкой BC - B старший байт слова выбора, C=(младший_байт_выбора-1) AND #FF
;   HL', DE' сохранены, BC' - B'=3, C' сохранён, AF' меняется при банковом запросе поля
;   IX первый непрочитанный символ, IY, I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF, BC' только B, AF' на пути свойства, IX
; Note:
;   группа s/c/u возвращает Major, Minor, Size
;   младший байт выбора 1 выбирает второй ключ, остальные текущий, значит явное число 2 выбирает второй
;   путь без точки возвращает адрес таблицы в DE, а не числовую характеристику, исходный RET сохранён
;   при неизвестном символе FindToken передаёт управление SkipLine без обычного результата
;   игровые единицы параметров и роль второго ключа здесь не предполагаются
; -----------------------------------------
                ; установка числа 3 свойств выбранной группы в альтернативном B
Entry:          EXX
                LD B, #03
                EXX
                ; выбор кода 0 по умолчанию, текущий ключ
                LD C, #00
                ; выбор адреса за одной записью до группы s/c/u
                LD DE, #CA25
                ; выбор локального RET для пути без точки, DE остаётся адресом таблицы
                LD HL, @Text.ReadCurrentKeyParams.NoSuffix
                JP @Text.ParseFieldSuffix.Entry

                ; возврат без суффикса, поле характеристики не вычислялось
NoSuffix:       RET

                endmodule
                endmodule
