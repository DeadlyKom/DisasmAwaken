                module Text
                module AssignValue
                ; Документация [Text](../../Docs/FunctionDetails/Text.md)
                ; Подробный разбор [все семь писателей, одиннадцать операторов и восстановление указателя выражений](../../Docs/AssignmentPipeline.md)
                ; -----------------------------------------
                ; Присваивание через физическую запись Writer, Operator, Right и возврат к NextCommand
                ; исходная запись 5, файловые смещения #009F..#00D4
                ; In:
                ;   HL' - сохраняемая вершина стека выражений до присваивания, CPU-стек допускает временные рамки
                ;   рабочая область выражения должна вмещать временные слова вложенного RHS без пересечения с сохраняемым сценарием
                ;   IX у поля назначения, далее один допустимый бинарный оператор и одно допустимое поле RHS
                ;   выбранный создатель писателя, EmitOperator и читатель добавляют по одному слову в рабочую запись AssignmentScratch.Entry
                ;   писатель и оператор соблюдают стековые договоры, выполняются договоры выбранных читателей и доступности целевых данных
                ; Out:
                ;   хвостовой вход в NextCommand без собственного RET, IX у первого символа после RHS
                ;   при успешном Resume HL' восстановлен входным значением, DE'=FFFB, BC' и AF' по побочным эффектам выбранных полей
                ;   HL, DE, BC и AF по результату оператора и Store, дополнительного общего пересчёта результата нет
                ;   SP непосредственно перед JP NextCommand равен входному SP, сохранённый первоначальный указатель снят
                ;   физическая запись Writer, Operator, Right остаётся в AssignmentScratch.Entry после исполнения
                ;   IY, I и IFF по договору полей и оператора, сами команды диспетчера их не меняют
                ; Corrupt:
                ;   HL, DE, BC, AF, HL' при ошибке, DE', BC' и AF' по полям, IX, SP при ошибке, R, AssignmentScratch, временный CPU-стек и выбранное поле
                ; Note:
                ;   восстановление прежнего HL' и входного SP гарантируется только успешным проходом через Resume
                ;   на ошибке FindToken SkipLine загружает SavedSP, сохранённый прежний HL' остаётся в RAM, но больше не снимается
                ;   указатель HL' и частично заполненная AssignmentScratch не откатываются, изменяемые операнды выбранных фабрик также не восстанавливаются
                ;   до Invoke собственная рамка содержит Operator, Resume и старый HL', дополнительные временные слова и дочерние вызовы пишут CPU-стек
                ;   сначала сохраняется прежний альтернативный HL, только затем выбирается рабочая запись из трёх слов
                ;   при RHS в скобках Entry.Right временно хранит левый операнд вложенного выражения
                ;   AssignmentScratch.NestedTail принимает адрес его оператора и правый операнд
                ;   для семейства RHS (1+RHS) четвёртая вложенная группа пишет CA8F..CA90 начала MarketScript, проверки границы нет
                ;   перед входом Invoke на CPU-стеке лежит Operator, затем Resume и сохранённый прежний HL альтернативного набора
                ;   оператор получает BC правое значение, писатель добавляет текущее либо захваченное левое значение в DE
                ;   после RET оператора и Store Resume восстанавливает старый указатель выражений и передаёт управление NextCommand
                ;   двоеточие выбирает CopyRightOperand, знак равенства CompareEqual, это разные операции записи
                ;   при ошибке поиска поля либо оператора FindToken уходит в SkipLine, путь Resume не гарантирован
                ;   рабочая запись и изменяемые операнды писателей общие, повторный вход до завершения не поддерживается
                ; -----------------------------------------
                ; переход к сохраняемому указателю стека выражений перед временным присваиванием
Entry:          EXX
                ; сохранение исходного указателя, который восстановит Resume после записи поля
                PUSH HL
                ; выбор физической шестибайтовой записи Writer, Operator, Right
                LD HL, @AssignmentScratch.Entry
                EXX
                ; получение и запись указателя писателя первого слова рабочей записи
                CALL @Text.DispatchWriteField.Entry
                ; поиск оператора и запись его адреса во второе слово
                CALL @Text.EmitOperator.Entry
                ; получение RHS и запись правого значения в третье слово
                CALL @Text.DispatchReadField.Entry
                ; выбор Resume как возврата после Store писателя
                LD HL, @Text.AssignValue.Resume
                ; создание продолжения, которое восстановит прежний стек выражений
                PUSH HL
                EXX
                ; выбор отрицательного размера FAssignmentExpression для возврата к началу записи
                LD DE, -FAssignmentExpression
                ; расчёт адреса Writer из вершины за тремя словами
                ADD HL, DE
                ; чтение младшего и старшего байтов указателя Invoke
                LD E, (HL)
                INC HL
                LD D, (HL)
                INC HL
                ; перенос указателя писателя в основной HL через CPU-стек
                PUSH DE
                EXX
                POP HL
                EXX
                ; чтение адреса оператора из второго слова
                LD E, (HL)
                INC HL
                LD D, (HL)
                INC HL
                ; помещение Operator поверх Resume на CPU-стек для входа Invoke
                PUSH DE
                ; чтение правого числового значения из третьего слова
                LD E, (HL)
                INC HL
                LD D, (HL)
                ; временное помещение RHS на CPU-стек перед переносом в основной BC
                PUSH DE
                ; выбор смещения минус пять от старшего байта Right к началу записи
                LD DE, @AssignmentConst.BackFromHigh
                ; возврат альтернативного указателя к началу рабочей записи
                ADD HL, DE
                EXX
                ; передача правого значения в BC без изменения указателя Invoke в HL
                POP BC
                JP (HL)

                ; возврат после оператора и Store, переход к прежнему указателю выражений
Resume:         EXX
                ; восстановление исходного альтернативного HL, временная запись не становится новым стеком
                POP HL
                EXX
                JP @Text.NextCommand.Entry

                endmodule
                endmodule
