                module ReadStrideFiveByte
                ; Документация [Text](../../Docs/FunctionDetails/Text.md)
                ; Подробный разбор [общие входы чтения, пятибайтовый шаг и полный договор флагов](../../Docs/StrideFive.md)
                ; -----------------------------------------
                ; Чтение байта по индексу из CPU-стека с шагом пять и базой #9802
                ; исходная запись 5, файловые смещения #05F9..#0608
                ; In:
                ;   на вершине CPU-стека слово индекса, под ним адрес возврата, старший байт индекса игнорируется
                ;   вычисленные адреса читаемы, Entry выбирает базу #9802
                ;   отдельный вход ReadAtBase принимает произвольную базу в DE
                ; Out:
                ;   HL=(база+5*индекс) AND #FFFF, DE=прочитанный байт с нулевым D
                ;   BC - исходный младший байт индекса с нулевым B, входной BC не сохраняется
                ;   AF - A сохранён, S/Z/PV из входного F, H/C от база+5*индекс, X/Y из старшего байта суммы, N=0
                ;   альтернативные и индексные регистры, I и IFF сохранены, запись RAM ограничена снятым словом индекса
                ;   SP равен входному SP+4, индекс и адрес возврата потреблены
                ; Corrupt:
                ;   HL, DE, BC, AF только F, R и два байта снятого слова индекса на CPU-стеке
                ; Note:
                ;   при исходной базе Entry индексы 7..10 читают Unknown00 четырёх соседних записей скимера, штатная достижимость таких индексов не установлена
                ;   если читаемый адрес совпадает со снятым словом индекса, результат берётся после PUSH, старший байт уже заменён нулём
                ;   единственный PUSH записывает младший байт индекса и ноль в его исходное слово, адрес возврата под ним сохраняется
                ;   индекс не проверяется по числу физических записей, только обрезается до младшего байта
                ;   PUSH HL и POP BC временно сохраняют индекс для расчёта 4*индекс+индекс
                ;   свойство t читает Capacity корабля, вместимость переносится при покупке
                ; -----------------------------------------
                ; выбор базы поля Capacity корабельной записи
Entry:          LD DE, @StationShipTradeRows.Ship0.Capacity
                ; чтение слова индекса поверх возврата, общий вход принимает базу в DE
ReadAtBase:     POP HL
                ; отбрасывание старшего байта индекса
                LD H, #00
                ; сохранение байтового индекса для сложения с его четырёхкратным значением
                PUSH HL
                ; расчёт четырёхкратного индекса двумя удвоениями
                ADD HL, HL
                ADD HL, HL
                ; восстановление индекса в BC, входной BC заменяется
                POP BC
                ; расчёт пятибайтового смещения как 4*индекс+индекс
                ADD HL, BC
                ; расчёт адреса поля относительно базы DE, итоговые флаги от этого сложения
                ADD HL, DE
                ; чтение байтового значения с последующим обнулением D
                LD E, (HL)
                LD D, #00
                RET

                endmodule
                endmodule
