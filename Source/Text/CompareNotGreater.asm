                module CompareNotGreater
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; -----------------------------------------
; Беззнаковая проверка DE не больше BC, результат ноль или один в DE
; исходная запись 5, файловые смещения #04B1..#04BB
; In:
;   DE - левый операнд, BC - правый операнд, сравнение без знака
; Out:
;   HL - разность операндов по модулю #10000, DE - логическое значение 0 или 1
; Corrupt:
;   HL, DE, AF
; Note:
;   BC, альтернативные и индексные регистры сохраняются
; -----------------------------------------
Entry:          EX DE, HL
                ; сброс входного переноса перед проверкой отношения не больше
                OR A
                ; расчёт разности для проверки меньшего либо равного левого операнда
                SBC HL, BC
                LD DE, #0001
                RET C                                                           ; выход, если левый операнд меньше правого, DE содержит истину

                RET Z                                                           ; выход, если операнды равны, отношение не больше истинно

                DEC DE
                RET

                endmodule
                endmodule
