                module Text
                module GetKeyFingerprint
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [стековый выбор ключа и извлечение одного числового поля](../../Docs/KeyChoice.md)
; -----------------------------------------
; Чтение поля характеристики ключа, исходная свёртка ключа из A
; исходная запись 5, файловые смещения #0632..#0639
; In:
;   на вершине CPU-стека слово выбора ключа, младший байт 1 выбирает второй ключ, остальные текущий
;   старший байт слова становится B и сохраняется, под словом выбора находится адрес возврата
;   действует банковый договор DescribeKeyChoice, LANG находится в банке 6
; Out:
;   HL содержит H:L исходной характеристики
;   DE - исходная свёртка ключа из A, D=0, BC содержит слово выбора с уменьшенным на один C
;   AF сохраняет полный результат DescribeKeyChoice, он не пересчитывается по значению DE
;   HL', DE', BC', IX, IY, I и IFF сохранены, AF' содержит финальную страницу и флаги OR
;   SP равен входному SP+4, рабочий ключ изменён, порт и тень возвращают банк 6
; Corrupt:
;   HL, DE, BC, AF, AF'
; Note:
;   POP BC потребляет слово выбора поверх адреса возврата, обычный CALL без операнда не соответствует договору
;   нулевой DE не определяет Z, флаги относятся к исходной свёртке выбранного ключа
;   числовое поле доказано по ядру характеристики, его более широкая игровая роль не подразумевается
; -----------------------------------------
                ; чтение слова выбора из CPU-стека, младший байт задаёт ключ, старший сохраняется в B
Entry:          POP BC
                ; получение всех признаков выбранного ключа через настоящие банковые обёртки
                CALL @Text.DescribeKeyChoice.Entry
                ; выделение поля результата, исходная свёртка ключа из A, без изменения флагов характеристики
                LD E, A
                LD D, #00
                RET

                endmodule
                endmodule
