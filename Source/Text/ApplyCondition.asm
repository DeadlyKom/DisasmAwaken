                module Text
                module ApplyCondition
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [команды, стек, CR и условные блоки](../../Docs/ScriptControl.md)
; -----------------------------------------
; Продолжение при ненулевом выражении либо пропуск строки или блока
; исходная запись 5, файловые смещения #0057..#007F
; In:
;   HL' у байта сразу после последнего слова выражения, оба байта доступны
;   IX у начала выбранной ветви, при пропуске блока впереди есть закрывающая скобка
; Out:
;   HL, DE, BC, альтернативные пары, IY, I, IFF и SP сохранены до хвостового получателя
;   A=OR двух байтов слова, F от этого OR, указатель выражений не снимает слово
;   при ненулевом слове хвостовой вход NextCommand
;   в противоположном случае вход ApplyCondition.SkipBranch
;   SkipBranch без открывающей скобки передаёт SkipLine.Entry с исходным IX
;   для { либо CR сразу перед { поиск первой } оставляет IX на этой скобке и передаёт SkipLine.Entry
;   при сканировании основной AF заменяется чтением символов и CP, прочие пары сохранены
; Corrupt:
;   AF, IX только на пропуске блока
; Note:
;   вложенность фигурных скобок не учитывается, первая закрывающая завершает поиск
;   CR допускается перед открывающей скобкой ровно один, пробелы перед ней не пропускаются
;   SkipLine затем потребляет остаток строки с закрывающей скобкой до CR
;   условие только проверяет сохранённое слово, стек выражений здесь не обнуляется
; -----------------------------------------
                ; чтение последнего слова выражения через альтернативный указатель без снятия слова
Entry:          EXX
                DEC HL
                LD A, (HL)
                DEC HL
                ; проверка ненулевого значения по обоим байтам выражения
                OR (HL)
                INC HL
                INC HL
                EXX
                JR NZ, @Text.NextCommand.Entry                                  ; переход, если выражение ненулевое, исполнять ветвь

                ; проверка открывающей скобки непосредственно у текущего IX
SkipBranch:     LD A, (IX + @ScriptConst.Cursor)
                CP #7B
                JR Z, @Text.ApplyCondition.FindClose                            ; переход, если текущий символ открывает блок, искать первую закрывающую скобку

                ; проверка единственного допустимого CR перед открывающей скобкой
                CP #0D
                JR NZ, @Text.SkipLine.Entry                                     ; переход, если текущий символ не CR и не открывающая скобка, пропустить строку

                ; проверка символа сразу после CR на открывающую скобку
                LD A, (IX + @ScriptConst.NextChar)
                CP #7B
                JR NZ, @Text.SkipLine.Entry                                     ; переход, если после CR нет открывающей скобки, пропустить строку

                INC IX
                ; поиск первой закрывающей скобки без счётчика вложенности
FindClose:      INC IX
                LD A, (IX + @ScriptConst.Cursor)
                CP #7D
                JR NZ, @Text.ApplyCondition.FindClose                           ; переход, если текущий символ не закрывающая скобка, продолжить поиск

                JR @Text.SkipLine.Entry

                endmodule
                endmodule
