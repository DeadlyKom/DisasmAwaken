                module Text
                module PushSecondQuantityWriter
                ; Документация [Text](../../Docs/FunctionDetails/Text.md)
                ; Подробный разбор [захват адреса и значения, рамка оператора и точный способ сохранения](../../Docs/IndexedWriters.md)
                ; Записи за таблицей при явных индексах [проверка](../../Docs/SecondaryContextAliases.md#явное-присваивание-и-сохранение)
                ; -----------------------------------------
                ; Создание захватывающего писателя кодированного количества через ReadSecondQuantity
                ; исходная запись 5, файловые смещения #06E4..#06E9
                ; In:
                ;   HL' указывает на два доступных байта следующего слова выражения, действует входной договор ReadSecondQuantity
                ;   результат читателя HL должен быть адресом записываемого целевого байта, полученное значение доступно
                ;   до Invoke нельзя создавать другой писатель того же общего шаблона, захваченные операнды общие
                ;   Invoke принимает FFieldInvokeFrame и BC правый операнд, оператор возвращает DE через RET в банк LANG 6
                ; Out:
                ;   Entry - HL адрес от читателя, DE общий Invoke, BC от читателя, AF от читателя
                ;   Entry - HL' увеличен на два, DE' содержит Invoke, BC', AF', IX, IY по договору читателя
                ;   Entry обновляет общие операнды Target и InitialValue, само целевое поле не записывает
                ;   Invoke передаёт оператору DE захваченное байтовое значение с нулевым D, BC правый операнд
                ;   перед входом оператора CPU-стек FIndexedOperatorFrame, сохранены StoreReturn, SavedTarget и AfterStore
                ;   Store возвращает HL адрес цели, BC как у оператора, DE как у оператора, включая D
                ;   Store - AF A сохранённый байт, F от BIT либо CPL по текущему bit7
                ;   SP после Entry равен входному SP+2, после Invoke либо отдельного Store входному SP+4
                ; Corrupt:
                ;   Entry - HL, DE, BC, AF, HL', DE', BC' только B, AF' и IX по договору читателя, R, Target, InitialValue, стек выражений и временный CPU-стек
                ;   Invoke - HL, DE, R, четыре байта CPU-рамки, далее эффекты выбранного оператора и Store
                ;   Store - HL, AF, R, целевой байт
                ; Note:
                ;   Entry записывает два байта Target и один InitialValue, затем Invoke в два байта выражения, временные записи читателя учитываются отдельно
                ;   Invoke записывает SavedTarget и StoreReturn в CPU-стек, остальные байты рамки и исходный AfterStore сохраняются
                ;   Store снимает Target через POP HL и пишет один целевой байт, собственных записей CPU-стека не выполняет
                ;   R изменяется на всех трёх входах, число M1 полного вызова зависит от ветви Store и выбранного оператора
                ;   целевой адрес и левый операнд захватываются при создании, маркер либо условие инверсии читается из памяти только в Store
                ;   Invoke добавляет SavedTarget между StoreReturn и AfterStore, Store снимает этот адрес POP HL
                ;   D результата игнорируется, если E>=128, запись может изменить исходный bit7 несмотря на условие инверсии
                ;   прямой читатель использует код количества, арифметический результат хранится по правилу текущего bit7
                ; -----------------------------------------
                ; получение адреса и декодированного количества второго набора
Entry:          CALL @Text.ReadSecondQuantity.Entry
                JP @Text.PushEquipmentQuantityWriter.Capture

                endmodule
                endmodule
