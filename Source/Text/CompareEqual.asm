                module Text
                module CompareEqual
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; -----------------------------------------
; Сравнение DE и BC на равенство, логический результат возвращается в DE
; исходная запись 5, файловые смещения #03D5..#03DE
; In:
;   DE - левый операнд, BC - правый операнд, сравнение без знака
; Out:
;   HL - разность операндов по модулю #10000, DE - логическое значение 0 или 1
; Corrupt:
;   HL, DE, AF
; Note:
;   BC, альтернативные и индексные регистры сохраняются
; -----------------------------------------
Entry:          EX DE, HL
                ; сброс входного переноса перед проверкой равенства двух слов
                OR A
                ; расчёт разности левого и правого операндов, ноль означает равенство
                SBC HL, BC
                LD DE, #0001
                RET Z                                                           ; выход, если операнды равны, DE содержит истину

                DEC DE
                RET

                endmodule
                endmodule
