; -----------------------------------------
; Запись DE по указателю HL альтернативного набора и продвижение стека выражений
; исходная запись 5, файловые смещения #01B9..#01C1
; In:
;   DE - слово результата, HL' - следующая свободная позиция стека выражений
; Out:
;   DE записан младшим байтом вперёд по HL', HL' увеличен на два, DE' содержит записанное слово
; Corrupt:
;   HL', DE'
; Note:
;   основные HL, DE, BC, AF, альтернативные BC', AF', IX и IY сохраняются
;   CPU-стек временно используется для переноса слова между наборами регистров и восстанавливается
; -----------------------------------------
                ; перенос слова результата в альтернативный набор без изменения основного DE
Entry:          PUSH DE
                EXX
                POP DE
                LD (HL), E
                INC HL
                LD (HL), D
                INC HL
                EXX
                RET

                endmodule
                endmodule
