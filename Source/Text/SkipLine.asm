                module Text
                module SkipLine
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [команды, стек, CR и условные блоки](../../Docs/ScriptControl.md)
; -----------------------------------------
; Пропуск до CR, проверка завершения строки и общий хвост диспетчера
; исходная запись 5, файловые смещения #001B..#0038
; In:
;   IX у первого пропускаемого байта, впереди доступен CR, LANG выбран и операнды инициализированы
;   ScriptRuntimeState.SavedSP содержит стек возврата вызывающему сценарию
; Out:
;   Entry загружает SP из собственного изменённого операнда SavedSP
;   FindCR потребляет все байты вплоть до CR, IX оказывается сразу после CR
;   AfterCR получает A=StopAtLine, F от OR A, HL, DE, BC и альтернативные регистры сохраняются
;   при StopAtLine=0 хвостовой вход NextCommand.ReadCommand с текущим SP
;   при ненулевом StopAtLine RET с SP=SavedSP+2, IY, I и IFF сохранены
;   DispatchCommand является внутренним входом с A уже потреблённым символом
;   для A=CR он входит в AfterCR, иначе ищет 15 команд по договору NextCommand, не восстанавливая SP
; Corrupt:
;   AF, IX, SP на Entry, HL, DE, BC только B на поиске DispatchCommand
; Note:
;   нулевой байт внутри пропускаемой строки не завершает поиск, отсутствие CR не обрабатывается
;   AfterCR и DispatchCommand сами не загружают SavedSP, их вызывают с уже подходящим стеком
;   значение флага трактуется как ноль или неноль, а не только 0 или 1
; -----------------------------------------
                ; восстановление стека из изменяемого операнда перед поиском CR
Entry:          LD SP, #0000
                ; поиск конца пропускаемой строки, нулевой байт не является терминатором этого поиска
FindCR:         LD A, (IX + @ScriptConst.Cursor)
                INC IX
                ; проверка потреблённого символа на CR
                CP #0D
                JR NZ, @Text.SkipLine.FindCR                                    ; переход, если прочитан не CR, продолжить пропуск

                ; чтение изменяемого операнда режима завершения на конце строки
AfterCR:        LD A, #00
                ; проверка режима завершения после CR
                OR A
                JR Z, @Text.NextCommand.ReadCommand                             ; переход, если StopAtLine равен нулю, читать следующую команду

                RET

                ; проверка уже потреблённого символа на конец строки
DispatchCommand:CP #0D
                JR Z, @Text.SkipLine.AfterCR                                    ; переход, если символ CR, проверить режим завершения

                ; выбор якоря перед исходной таблицей команд
                LD HL, #C932
                ; выбор числа физических записей команд, порядок таблицы сохраняется
                LD B, #0F
                JP @Text.DispatchToken.Entry

                endmodule
                endmodule
