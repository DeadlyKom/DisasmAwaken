                module Text
                module ApplyInverseCondition
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [команды, стек, CR и условные блоки](../../Docs/ScriptControl.md)
; -----------------------------------------
; Продолжение при нулевом выражении либо общий пропуск ветви
; исходная запись 5, файловые смещения #0080..#008C
; In:
;   HL' у байта сразу после последнего слова выражения, оба байта доступны
;   IX у начала выбранной ветви, при пропуске блока впереди есть закрывающая скобка
; Out:
;   HL, DE, BC, альтернативные пары, IY, I, IFF и SP сохранены до хвостового получателя
;   A=OR двух байтов слова, F от этого OR, указатель выражений не снимает слово
;   при нулевом слове хвостовой вход NextCommand
;   в противоположном случае вход ApplyCondition.SkipBranch
;   SkipBranch без открывающей скобки передаёт SkipLine.Entry с исходным IX
;   для { либо CR сразу перед { поиск первой } оставляет IX на этой скобке и передаёт SkipLine.Entry
;   при сканировании основной AF заменяется чтением символов и CP, прочие пары сохранены
; Corrupt:
;   AF, IX только на пропуске блока
; Note:
;   вложенность фигурных скобок не учитывается, первая закрывающая завершает поиск
;   CR допускается перед открывающей скобкой ровно один, пробелы перед ней не пропускаются
;   SkipLine затем потребляет остаток строки с закрывающей скобкой до CR
;   условие только проверяет сохранённое слово, стек выражений здесь не обнуляется
; -----------------------------------------
                ; повторное чтение последнего слова для обратной ветви без изменения вершины
Entry:          EXX
                DEC HL
                LD A, (HL)
                DEC HL
                ; проверка нулевого значения по обоим байтам выражения
                OR (HL)
                INC HL
                INC HL
                EXX
                JP Z, @Text.NextCommand.Entry                                   ; переход, если выражение нулевое, исполнять обратную ветвь

                JR @Text.ApplyCondition.SkipBranch

                endmodule
                endmodule
