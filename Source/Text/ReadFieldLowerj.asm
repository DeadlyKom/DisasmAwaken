; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [байтовая и словная запись, альтернативные пары и композиция](../../Docs/ExpressionPushes.md)
; -----------------------------------------
; Добавление байта #9850 в стек выражений через общий байтовый вход
; исходная запись 5, файловые смещения #0241..#024B
; In:
;   HL' - адрес следующих двух доступных для записи байтов стека выражений, без перекрытия текущего кода и CPU-стека
;   источник байт #9850 доступен
;   общий AppendByte принимает A как добавляемое байтовое значение
; Out:
;   HL, DE и BC сохранены, AF - A=байт #9850, F сохранён
;   HL' увеличен на два, в прежнюю позицию записано A, затем 0, DE', BC', AF', IX, IY, I и IFF сохранены
;   SP обычного возврата равен входному SP+2
; Corrupt:
;   AF только A, HL'
; Note:
;   байтовый вход не переносит результат в DE альтернативного набора, в отличие от PushExpressionWord
;   запись имеет ширину слова, хотя источник байтовый, старший байт всегда нулевой
; -----------------------------------------
                ; чтение сохранённого байта взвешенной суммы, единицы ещё не установлены
Entry:          LD A, (#9850)
                ; переход к альтернативному указателю стека выражений без переноса DE
AppendByte:     EXX
                ; запись младшего байта нового слова выражения
                LD (HL), A
                INC HL
                ; запись нулевого старшего байта для байтового результата
                LD (HL), #00
                INC HL
                ; возврат к основным регистрам, альтернативный указатель уже продвинут на два
                EXX
                RET

                endmodule
                endmodule
