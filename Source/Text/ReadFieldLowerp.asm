                module Text
                module ReadFieldLowerp
                ; Документация [Text](../../Docs/FunctionDetails/Text.md)
                ; Подробный разбор [уже проверенная первая цифра, ширины компонент и стек выражений](../../Docs/NumericFieldReads.md)
                ; -----------------------------------------
                ; Чтение байта ресурса по трём десятичным компонентам
                ; исходная запись 5, файловые смещения #0362..#037C
                ; In:
                ;   HL' - два доступных байта следующего слова выражения, без перекрытия кода и CPU-стека
                ;   IX у первой уже проверенной цифры, каждая компонента читается ReadDecimal5
                ;   текст содержит группу, номер записи и смещение, между числами ровно один читаемый байт
                ;   требуемые FF и FE присутствуют, выполняется договор FindDelimitedRecord
                ; Out:
                ;   HL - адрес прочитанного байта после поиска и прибавления смещения, DE смещение по модулю 65536
                ;   BC - B=0, C младший байт второго числа, счётчик FE
                ;   AF - A прочитанный байт, F от финального ADD HL,DE в FindDelimitedRecord, не от значения байта
                ;   HL' увеличен на два, записаны A и нулевой старший байт, DE', BC', AF', IY, I и IFF сохранены
                ;   IX первый непрочитанный символ последней компоненты, SP обычного возврата равен входному SP+2
                ;   операнды GroupCount и RecordCount изменены исходным поиском
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', IX, R, два байта выражения и временные байты CPU-стека, GroupCount и RecordCount
                ; Note:
                ;   поиск изменяет GroupCount и RecordCount, остальная запись вне выражения ограничена временными словами CPU-стека
                ;   R зависит от числа сравнений CPIR и цифр, точная формула проверена на конечных профилях без полного перебора размещений
                ;   счётчики берутся по модулю 256, ноль означает 256 разделителей, смещение полное шестнадцатибитное
                ;   смещение отсчитывается от самого FE, нулевое смещение возвращает FE
                ;   ReadFieldLowerp пропускает по одному байту между числами без проверки разделителя
                ;   игровое назначение групп и записей ресурса ещё не установлено
                ; -----------------------------------------
                ; чтение первой компоненты, числа разделителей FF
Entry:          CALL @Text.ReadDecimal5.Entry
                ; дублирование младшего байта числа в H для последующего POP AF
                LD H, L
                ; сохранение байтового счётчика FF в обоих байтах временного слова
                PUSH HL
                ; пропуск одного байта между первой и второй компонентами без проверки его кода
                INC IX
                ; чтение второй компоненты, числа разделителей FE
                CALL @Text.ReadDecimal5.Entry
                ; дублирование младшего байта второго числа для последующего POP BC
                LD H, L
                ; сохранение байтового счётчика FE
                PUSH HL
                ; пропуск одного байта перед смещением без проверки разделителя
                INC IX
                ; чтение третьей компоненты как шестнадцатибитного смещения
                CALL @Text.ReadDecimal5.Entry
                ; передача смещения в DE без обрезания до байта
                EX DE, HL
                ; восстановление числа FE одновременно в B и C
                POP BC
                ; восстановление числа FF в A, его копия также становится входными флагами
                POP AF
                ; поиск ресурса через оригинальные FF и FE с прибавлением DE
ReadDelimitedAt:CALL @Text.FindDelimitedRecord.Entry
                ; чтение найденного байта для общего добавления в стек выражений
                LD A, (HL)
                JP @Text.PushUsedTonnage.AppendByte

                endmodule
                endmodule
