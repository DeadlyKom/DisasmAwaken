                module Text
                module PushByteUWriter
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [создание указателя, рамка оператора и отдельный вход Store](../../Docs/ScalarWriters.md)
; -----------------------------------------
; Создание указателя писателя байта по #984B
; исходная запись 5, файловые смещения #0657..#066D
; In:
;   Entry принимает HL' следующую позицию стека выражений, доступны два байта записи
;   для Invoke на CPU-стеке FFieldInvokeFrame, Operator адрес операции, AfterStore адрес продолжения
;   Invoke принимает BC правый операнд, поле #984B доступно для чтения и записи
;   оператор получает DE текущее значение, BC правый операнд, возвращает DE через RET с банком LANG 6
;   Store можно вызвать отдельно с DE результатом и обычным адресом возврата
; Out:
;   Entry сохраняет HL, BC и AF, DE адрес Invoke, добавленный в стек выражений
;   Entry увеличивает HL' на два, DE' становится адресом Invoke, BC', AF', IX, IY, I и IFF сохранены
;   Invoke заменяет Operator в FFieldInvokeFrame адресом Store, образуя FFieldOperatorFrame, и входит в оператор через JP (HL)
;   после Invoke и Store поле получает младший E без насыщения, старший D результата не записывается
;   регистры после Invoke определяются оператором и Store, Store устанавливает A=E, F сохраняет
;   SP после Entry либо отдельного Store равен входному SP+2, после полного Invoke равен входному SP+4
; Corrupt:
;   Entry - DE, HL', DE'
;   Invoke - HL, DE и регистры по договору выбранного оператора
;   Store - AF только A
; Note:
;   Entry не записывает целевое поле и не исполняет операцию, только добавляет статический указатель
;   Invoke загружает текущее поле, а не значение на момент создания указателя, код писателя не генерируется заново
;   байтовые Invoke читают слово, но обнуляют H, соседний байт поля не является частью операнда
;   игровые единицы поля не выводятся из этой операции записи
; -----------------------------------------
                ; выбор статического входа Invoke как значения писателя поля
Entry:          LD DE, @Text.PushByteUWriter.Invoke
                ; добавление адреса Invoke в стек выражений без выполнения записи поля
                JP @Text.PushExpressionWord.Entry

                ; снятие адреса оператора из FFieldInvokeFrame в DE
Invoke:         POP DE
                ; выбор Store как возврата оператора
                LD HL, @Text.PushByteUWriter.Store
                ; замена слова Operator адресом Store, остальная рамка сохраняется
                PUSH HL
                ; чтение текущего значения целевого поля в HL перед обменом с адресом оператора
                LD HL, (#984B)
                LD H, #00
                EX DE, HL
                JP (HL)

                ; сохранение младшего E через A без изменения F в исходное поле
Store:          LD A, E
                LD (#984B), A
                RET

                endmodule
                endmodule
