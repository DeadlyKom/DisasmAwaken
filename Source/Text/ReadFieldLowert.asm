                module Text
                module ReadFieldLowert
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [уже проверенная первая цифра, ширины компонент и стек выражений](../../Docs/NumericFieldReads.md)
; -----------------------------------------
; Чтение байта ресурса с сохранёнными счётчиками FF/FE и десятичным смещением
; исходная запись 5, файловые смещения #0355..#0361
; In:
;   HL' - два доступных байта следующего слова выражения, без перекрытия кода и CPU-стека
;   IX у первой уже проверенной цифры, каждая компонента читается ReadDecimal5
;   группа FF и номер FE находятся байтами по #9A1C и #9A1D, текст задаёт только смещение
;   требуемые FF и FE присутствуют, выполняется договор FindDelimitedRecord
; Out:
;   HL - адрес прочитанного байта после поиска и прибавления смещения, DE смещение по модулю 65536
;   BC - B=0, C первый сохранённый счётчик FF
;   AF - A прочитанный байт, F от финального ADD HL,DE в FindDelimitedRecord, не от значения байта
;   HL' увеличен на два, записаны A и нулевой старший байт, DE', BC', AF', IY, I и IFF сохранены
;   IX первый непрочитанный символ последней компоненты, SP обычного возврата равен входному SP+2
;   операнды GroupCount и RecordCount изменены исходным поиском
; Corrupt:
;   HL, DE, BC, AF, HL', IX
; Note:
;   счётчики берутся по модулю 256, ноль означает 256 разделителей, смещение полное шестнадцатибитное
;   смещение отсчитывается от самого FE, нулевое смещение возвращает FE
;   ReadFieldLowerp пропускает по одному байту между числами без проверки разделителя
;   игровое назначение групп и записей ресурса ещё не установлено
; -----------------------------------------
                ; чтение полного смещения внутри выбранной записи ресурса
Entry:          CALL @Text.ReadDecimal5.Entry
                ; передача смещения в DE для исходного поиска разделителей
                EX DE, HL
                ; чтение сохранённого числа разделителей FF
                LD A, (#9A1C)
                ; чтение обоих сохранённых счётчиков, старший байт B задаёт число FE
                LD BC, (#9A1C)
                JR @Text.ReadFieldLowerp.ReadDelimitedAt

                endmodule
                endmodule
