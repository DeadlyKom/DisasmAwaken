                module Text
                module ActivateResourceRecord
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [режим A альтернативного набора, реальные записи и путь до NextCommand](../../Docs/UnaryModes.md)
; -----------------------------------------
; Поиск совпавшего заголовка и запись 1 в ресурс при ненулевом режиме
; исходная запись 5, файловые смещения #010E..#0176
; In:
;   A' - режим, при нуле возврат происходит до чтения аргумента
;   при ненулевом режиме IX у первой проверенной цифры смещения, #9A1C и #9A1D задают счётчики группы и записи
;   в тексте с #CF18 существует совпадающий заголовок с тремя числовыми компонентами и завершающим CR
;   выполняется договор FindDelimitedRecord, найденный байт доступен для записи
; Out:
;   при нулевом режиме HL, DE и BC сохранены, A=0, F=44, IX не продвигается
;   при ненулевом HL у байта после CR найденной текстовой строки, DE полное числовое смещение
;   при ненулевом BC - B=0, C счётчик FF из #9A1C, AF - A=FE, F от адресного ADD HL,DE поиска
;   при ненулевом в вычисленный байт ресурса записано 1, IX у первого непрочитанного символа аргумента
;   AF' содержит входной основной AF, HL', DE', BC', IY, I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF, AF', IX только при ненулевом режиме
; Note:
;   заголовок ищется CPIR по подчёркиванию, следующий один байт пропускается без проверки
;   три числа заголовка сравниваются младшими байтами с группой, записью и младшим E аргумента
;   первый, второй и третий несовпавший компонент возвращают поиск к следующему подчёркиванию
;   полное смещение DE применяется к найденному FE, хотя заголовок сравнивается только по младшему байту
;   нулевой счётчик FF либо FE означает 256 поисков, отсутствие подходящего заголовка не имеет отдельного выхода ошибки
;   нулевой режим не очищает ресурс и оставляет числовой аргумент непрочитанным
; -----------------------------------------
                ; получение режима из альтернативного A, прежний основной AF переходит в альтернативный
Entry:          EX AF, AF'
                ; проверка нулевого режима до чтения числового аргумента
                OR A
                RET Z                                                           ; выход, если режим равен нулю, аргумент и ресурс не изменяются

                ; чтение полного смещения и сохранение его на время поиска заголовка
                CALL @Text.ReadDecimal5.Entry
                PUSH HL
                ; выбор исходного начала текстовых заголовков ресурса
                LD HL, #CF18
                ; создание внутреннего предела CPIR в 65536 сравнений
NextHeader:     LD BC, #0000
                ; выбор подчёркивания как начала следующего заголовка
                LD A, #5F
                ; поиск очередного заголовка без проверки общего числа записей
                CPIR
                ; пропуск одного байта после найденного подчёркивания
                INC HL
                ; сохранение исходного курсора аргумента перед временным чтением ресурса через IX
                PUSH IX
                PUSH HL
                POP IX
                ; чтение первой компоненты текстового заголовка
                CALL @Text.ReadDecimal5.Entry
                LD C, L
                PUSH IX
                POP HL
                POP IX
                ; чтение требуемого номера группы из сохранённого байта
                LD A, (#9A1C)
                ; проверка младшего байта первой компоненты заголовка
                CP C
                JP NZ, @Text.ActivateResourceRecord.NextHeader                  ; переход, если группа заголовка отличается, искать следующее подчёркивание

                ; пропуск одного разделяющего байта перед номером записи
                INC HL
                PUSH IX
                PUSH HL
                POP IX
                ; чтение второй компоненты заголовка
                CALL @Text.ReadDecimal5.Entry
                LD C, L
                PUSH IX
                POP HL
                POP IX
                ; чтение требуемого номера записи
                LD A, (#9A1D)
                ; проверка младшего байта второй компоненты
                CP C
                JP NZ, @Text.ActivateResourceRecord.NextHeader                  ; переход, если номер записи отличается, искать следующий заголовок

                ; пропуск одного разделяющего байта перед третьей компонентой
                INC HL
                PUSH IX
                PUSH HL
                POP IX
                ; чтение третьей компоненты заголовка
                CALL @Text.ReadDecimal5.Entry
                LD C, L
                PUSH IX
                POP HL
                POP IX
                ; чтение исходного полного смещения с последующим сохранением для возможного нового поиска
                POP DE
                PUSH DE
                ; выбор только младшего байта аргумента для сравнения с заголовком
                LD A, E
                ; проверка младшего байта третьей компоненты
                CP C
                JP NZ, @Text.ActivateResourceRecord.NextHeader                  ; переход, если младшие байты смещения отличаются, искать следующий заголовок

                ; снятие найденного полного смещения перед записью ресурса
                POP DE
                ; чтение текстового тела до CR после совпавшего заголовка
SkipPayloadLine:LD A, (HL)
                INC HL
                ; проверка завершения текстовой строки ресурса
                CP @TextConst.CarriageReturn
                JR NZ, @Text.ActivateResourceRecord.SkipPayloadLine             ; переход, если CR ещё не встретился, продолжить пропуск строки

                ; загрузка счётчика FF и пары FF/FE для физического поиска записи
                LD A, (#9A1C)
                LD BC, (#9A1C)
                ; сохранение адреса после CR на время поиска физического байта
                PUSH HL
                ; поиск физического FE и прибавление полного смещения
                CALL @Text.FindDelimitedRecord.Entry
                ; обновление найденного байта ресурса значением 1
                LD (HL), #01
                ; восстановление адреса после найденной текстовой строки
                POP HL
                RET

                endmodule
                endmodule
