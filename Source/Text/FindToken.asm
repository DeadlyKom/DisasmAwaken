                module Text
                module FindToken
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [ScriptLanguage.md](../../Docs/ScriptLanguage.md)
; -----------------------------------------
; Поиск A в B трёхбайтовых записях со смещением на три от HL
; исходная запись 5, файловые смещения #07E3..#07ED
; In:
;   HL - адрес за три байта до первой записи, BC - B записей, AF - A искомый символ
; Out:
;   при совпадении HL - запись найденного символа, DE - размер FScriptToken, A сохраняется, Z установлен
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   при совпадении B содержит число оставшихся записей вместе с найденной, C сохраняется
;   нулевой входной B означает 256 записей, сравнение выполняется до уменьшения счётчика
;   на успешном пути альтернативные и индексные регистры сохраняются, SP восстанавливается
;   при отсутствии символа выполняется хвостовой переход в SkipLine, где меняются IX и SP, обычного возврата с ошибкой нет
; -----------------------------------------
                ; установка шага физической записи FScriptToken
Entry:          LD DE, FScriptToken
                ; поиск следующей записи, начальный HL указывает за три байта до первой
NextBinding:    ADD HL, DE
                ; проверка совпадения искомого символа с полем Symbol текущей записи
                CP (HL)
                RET Z                                                           ; выход, если символ текущей записи совпадает с искомым

                DJNZ @Text.FindToken.NextBinding

                JP @Text.SkipLine.Entry

                endmodule
                endmodule
