                module Command57
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [команда W и переход в фиксированный код](../../Docs/StationTransition.md)
; -----------------------------------------
; Команда W, установка байта события и вход в станционный переход
; исходная запись 5, файловые смещения #0103..#010A
; In:
;   LANG выбран, выполнены предусловия Station.HandleItem08.BeginTransition
;   при обычном диспетчере SP уже восстановлен в сохранённое состояние сценария
; Out:
;   байт 9AB7 установлен FF, затем хвостовой вход Station.HandleItem08.BeginTransition с A=FF
;   до получателя HL, DE, BC, F, альтернативные и индексные регистры сохранены
;   при 9849=FF немедленный RET по текущему стеку, обычный сценарий завершается без NextCommand
;   при 9849 не FF переход в скопированный код 4200 по договору HandleItem08, без возврата в LANG
; Corrupt:
;   AF и эффекты Station.HandleItem08.BeginTransition
; Note:
;   W не вызывает ActivateInterfaceCallback и не создаёт дополнительного адреса возврата
;   назначение байта 9AB7 среди всех потребителей ещё уточняется, установка FF доказана непосредственно
;   передача управления 4200 не доказывает загрузку ACTION либо игровой запуск
; -----------------------------------------
                ; выбор исходного кода события FF перед станционным переходом
Entry:          LD A, #FF
                ; обновление байта события 9AB7 без вызова интерфейсной активации
                LD (@MainLoopState.TransitionCode), A
                JP @Station.HandleItem08.BeginTransition

                endmodule
                endmodule
