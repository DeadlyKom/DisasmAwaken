                module Text
                module IsMarketSaleLegal
                ; Документация [Text](../../Docs/FunctionDetails/Text.md)
                ; Подробный разбор [стековый договор чтения полей и проверка маркера](../../Docs/MarketAccess.md)
                ; -----------------------------------------
                ; Проверка разрешённой продажи товара по снятому bit7 рыночной записи
                ; исходная запись 5, файловые смещения #05CD..#05DE
                ; In:
                ;   на вершине CPU-стека слово индекса, под ним адрес возврата, старший байт индекса игнорируется
                ;   память по вычисленному адресу читаема, проверка границ массива в исходном коде отсутствует
                ;   для строки рынка допустим логический индекс 0..29, проверяется StockAndSaleBan
                ; Out:
                ;   HL=MarketRows.Row00.StockAndSaleBan + 2*индекс, DE=1 при снятом bit7, иначе 0
                ;   AF - A=E, при снятом bit7 F=0, при установленном F=#90 OR (StockAndSaleBan AND #28)
                ;   BC, альтернативные регистры, IX, IY, I и IFF сохранены, память не изменяется
                ; Corrupt:
                ;   HL, DE, AF
                ; Note:
                ;   RET снимает адрес после слова индекса, итоговый SP равен входному SP + 4
                ;   обычный CALL без слова индекса над адресом возврата не соответствует этому договору
                ;   ParseFieldSuffix передаёт индекс через PUSH HL, DispatchToken входит через JP (HL)
                ;   модель исходных байтов описана в MarketAccess.md, IRQ и нативный запуск не проверялись
                ;   Z=0 при обоих результатах, результат запроса нужно брать из DE, а не из Z
                ;   DE=1 означает отсутствие штрафного запрета продажи, исходные события 10 и 11 при DE=0 назначают штраф и списание количества груза
                ;   предметный смысл доказан исполнением исходного сценария, роль старшего разряда грузовой записи этим не приравнивается к рынку
                ;   Сценарий [незаконная продажа и штраф](../../Docs/OriginalTradeScript.md) проверен отдельно
                ; -----------------------------------------
                ; чтение стекового индекса, старший байт затем отбрасывается
Entry:          POP HL
                LD H, #00
                ; выбор поля StockAndSaleBan первой физической строки рынка
                LD DE, @MarketRows.Row00.StockAndSaleBan
                ; расчёт двухбайтового смещения рыночной строки
                ADD HL, HL
                ; расчёт адреса StockAndSaleBan выбранной строки
                ADD HL, DE
                ; выбор результата ложь до проверки старшего маркера
                XOR A
                ; флаг, запрет продажи StockAndSaleBan выбирает ложь для штрафной ветви сценария
                BIT @MarketRowConst.SaleBanBit, (HL)
                JR NZ, @Text.IsMarketSaleLegal.ReturnResult                     ; переход, если bit7 StockAndSaleBan установлен, вернуть нулевой результат

                ; выбор результата истина при снятом старшем маркере
                INC A
                ; возврат логического результата в DE с нулевым D
ReturnResult:   LD E, A
                LD D, #00
                RET

                endmodule
                endmodule
