                module Text
                module GetMarketPrice
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [стековый договор чтения полей и проверка маркера](../../Docs/MarketAccess.md)
; -----------------------------------------
; Чтение текущей цены строки рынка по стековому индексу
; исходная запись 5, файловые смещения #05C7..#05CC
; In:
;   на вершине CPU-стека слово индекса, под ним адрес возврата, старший байт индекса игнорируется
;   память по вычисленному адресу читаема, проверка границ массива в исходном коде отсутствует
;   для рыночной цены допустим логический индекс 0..29, база MarketRows.Row00.Price
; Out:
;   HL=MarketRows.Row00.Price + 2*индекс, DE=байтовая цена с нулевым D
;   AF - A сохранён, S/Z/PV из входного F, H/C от 2*индекс + база, X/Y из старшего байта суммы, N=0
;   BC, альтернативные регистры, IX, IY, I и IFF сохранены, память не изменяется
; Corrupt:
;   HL, DE, AF
; Note:
;   RET снимает адрес после слова индекса, итоговый SP равен входному SP + 4
;   обычный CALL без слова индекса над адресом возврата не соответствует этому договору
;   ParseFieldSuffix передаёт индекс через PUSH HL, DispatchToken входит через JP (HL)
;   модель исходных байтов описана в MarketAccess.md, IRQ и нативный запуск не проверялись
;   общий хвост ReadStridedByte.ReadAtBase использует базу #9556
; -----------------------------------------
                ; выбор поля Price первой физической строки рынка
Entry:          LD DE, @MarketRows.Row00.Price
                JP @Text.ReadStridedByte.ReadAtBase

                endmodule
                endmodule
