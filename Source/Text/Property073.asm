                module Text
                module Property073
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [условия совпадения, код bit7 и два общих стековых входа](../../Docs/MembershipFlags.md)
; -----------------------------------------
; Чтение кода старшего разряда по базе #98F6
; исходная запись 5, файловые смещения #05BB..#05C0
; In:
;   на вершине CPU-стека слово индекса, под ним адрес возврата, старший байт игнорируется
;   Entry выбирает базу #98F6
; Out:
;   HL=(база+младший_индекс) AND #FFFF, DE=A=127 при снятом bit7 либо 1 при установленном, BC сохранён
;   AF - F от BIT 7,(HL), H=1, N=0, S равен bit7, Z и PV равны обратному bit7
;   X/Y из проверенного байта, Carry от прибавления индекса к базе, для штатных баз Carry=0
;   альтернативные и индексные регистры, I и IFF сохранены, SP равен входному SP+4
; Corrupt:
;   HL, DE, AF
; Note:
;   это коды 127 и 1, а не стандартный логический результат 0 и 1
;   F не пересчитывается по возвращаемому A, при A=127 установлен Z, при A=1 Z снят
;   игровое назначение поля и старшего разряда пока не доказано
; -----------------------------------------
                ; выбор второй базы байтовых старших разрядов
Entry:          LD DE, #98F6
                JP @Text.GetHighBitCode.ReadAtBase

                endmodule
                endmodule
