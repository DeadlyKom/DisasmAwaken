                module MarketScript
                ; Документация [исходный сценарий и проверенные события товаров](../../../Docs/OriginalTradeScript.md)
                ; События [кораблей](../../../Docs/ShipTrade.md) и [оснащения](../../../Docs/EquipmentTrade.md)
                ; События [начальной проверки и стоянки](../../../Docs/StationScripts.md)
                ; строки ASCII остаются строками, CP866-пояснения записаны исходными числовыми байтами
                assert $ == #CA8F
                ; исходное пропускаемое пояснение CP866, ПОДСЧЕТ ТОНАЖА
Entry:          DB #20, #8F, #8E, #84, #91, #97, #85, #92, #20, #92, #8E, #8D
                DB #80, #86, #80, #0D
                ; пересчёт исходной байтовой загрузки командой T
                DB "T", #0D
                ; исходное пропускаемое пояснение CP866, ПОКУПКА ТОВАРОВ
                DB #20, #8F, #8E, #8A, #93, #8F, #8A, #80, #20, #92, #8E, #82
                DB #80, #90, #8E, #82, #0D
                ; проверка события покупки одного товара
BuyGoods:       DB "?X=9:{", #0D
                ; исходная проверка остатка с незарегистрированным Q, интерпретатор пропускает строку
                DB "?G=Qn:M09", #0D
                ; отказ покупки при цене больше кредитов
                DB "?G.c>c:M01", #0D
                ; проверка загрузки с добавлением выбранного товара относительно вместимости J
                DB "?G.m>J:M03", #0D
                ; отказ покупки при полном байте груза не меньше 120
                DB "?g]120:M06", #0D
                ; прибавление груза, списание цены, уменьшение рынка, пересчёт загрузки и выход
                DB "=g+1,=c-G.c,=G-1,T,^", #0D
                ; закрывающая скобка исходного блока, сама команда не восстанавливает стек блока
                DB "}", #0D
                DB #0D
                ; исходное пропускаемое пояснение CP866, ПРОДАЖА ТОВАРОВ
                DB #20, #8F, #90, #8E, #84, #80, #86, #80, #20, #92, #8E, #82
                DB #80, #90, #8E, #82, #0D
                ; проверка события продажи одной единицы груза
SellGoods:      DB "?X=10:{", #0D
                ; отказ продажи при нулевом полном байте текущего груза
                DB "?g=n:M09", #0D
                ; незаконная продажа по bit7 рынка, сообщение, штраф до нижней границы ноль и очистка количества груза
                DB "?G.s=n:M10,=c-1000,=g-g,T", #0D
                ; предупреждение о сумме, строчная m не прекращает дальнейшую продажу
                DB "?c+G.c>65000:m11", #0D
                ; уменьшение груза, начисление цены, прибавление рынка, пересчёт загрузки и выход
                DB "=g-1,=c+G.c,=G+1,T,^", #0D
                ; закрывающая скобка исходного блока, сама команда не восстанавливает стек блока
                DB "}", #0D
                DB #0D
                ; исходное пропускаемое пояснение CP866, ПРОДАЖА ВСЕГО ТЕКУЩЕГО ТОВАРА
                DB #20, #8F, #90, #8E, #84, #80, #86, #80, #20, #82, #91, #85
                DB #83, #8E, #20, #92, #85, #8A, #93, #99, #85, #83, #8E, #20
                DB #92, #8E, #82, #80, #90, #80, #0D
                ; проверка события продажи всего текущего груза
SellAllGoods:   DB "?X=11:{", #0D
                ; отказ продажи при нулевом полном байте текущего груза
                DB "?g=n:M09", #0D
                ; незаконная продажа по bit7 рынка, сообщение, штраф до нижней границы ноль и очистка количества груза
                DB "?G.s=n:M10,=c-1000,=g-g,T", #0D
                ; предупреждение о сумме всего груза без прекращения следующей строки
                DB "?g*G.c+c>65000:m11", #0D
                ; начисление стоимости всего полного байта груза, прибавление рынка и очистка количества
                DB "=c+(G.c*g),=G+g,=g-g,T,^", #0D
                ; закрывающая скобка исходного блока, сама команда не восстанавливает стек блока
                DB "}", #0D
                DB #0D
                DB #0D
                ; исходное пропускаемое пояснение CP866, ПОКУПКА КОР-Я
                DB #20, #8F, #8E, #8A, #93, #8F, #8A, #80, #20, #8A, #8E, #90
                DB #2D, #9F, #0D
                ; событие 1, покупка корабля по исходной таблице семи записей
BuyShip:        DB "?X=1:{", #0D
                ; отказ покупки при уже имеющемся корабле, текущий индекс не FF
                DB #3F, #6B, #3C, #32, #35, #35, #3D, #79, #3A, #4D, #30, #32
                DB #20, #AF, #E0, #AE, #A2, #A5, #E0, #A8, #AC, #20, #AD, #A0
                DB #AB, #A8, #E7, #A8, #A5, #20, #AA, #AE, #E0, #A0, #A1, #AB
                DB #EF, #0D
                ; отказ при цене выбранного корабля больше кредитов
                DB "?K.c>c:M01", #0D
                ; отказ при вместимости выбранного корабля меньше пересчитанной загрузки
                DB "?K.t<j:M03", #0D
                ; отказ при нарушении порога одной из тридцати активных строк оснащения
                DB "?o.s=n:M07", #0D
                ; выбор корабля, списание цены, запись вместимости, пересчёт и сообщение успеха
                DB "+K,=c-K.c,=J:K.t,T,M12,^", #0D
                ; закрывающая скобка исходного блока, сама команда не восстанавливает стек блока
                DB "}", #0D
                DB #0D
                ; исходное пропускаемое пояснение CP866, ПРОДАЖА КОР-Я
                DB #20, #8F, #90, #8E, #84, #80, #86, #80, #20, #8A, #8E, #90
                DB #2D, #9F, #0D
                ; событие 2, продажа текущего корабля с отдельной ветвью нулевого k.s
SellShip:       DB "?X=2:{", #0D
                ; отказ продажи при отсутствии текущего корабля
                DB "?k<255=n:M09", #0D
                ; при нулевом k.s сообщение M04, начисление цены текущего корабля и снятие выбора без сброса вместимости
                DB "?k.s=n:M04,=c+k.c,-K,#", #0D
                ; предупреждение проверяет цену выбранной строки K.c, начисление ниже использует текущий корабль k.c
                DB "?c+K.c>65000:m11", #0D
                ; начисление цены текущего корабля, снятие выбора, сброс вместимости, пересчёт и сообщение успеха
                DB "=c+k.c,-K,=J:0,T,M12,^", #0D
                ; закрывающая скобка исходного блока, сама команда не восстанавливает стек блока
                DB "}", #0D
                DB #0D
                DB #0D
                DB #0D
                ; исходное пропускаемое пояснение CP866, ПОКУПКА ОСНАЩЕНИЯ КОР-Я
                DB #20, #8F, #8E, #8A, #93, #8F, #8A, #80, #20, #8E, #91, #8D
                DB #80, #99, #85, #8D, #88, #9F, #20, #8A, #8E, #90, #2D, #9F
                DB #0D
                ; событие 5, последовательные ограничения и покупка одной единицы оснащения
BuyEquipment:   DB "?X=5:{", #0D
                ; отказ при пороге станции больше характеристики L текущего ключа
                DB #3F, #4F, #3D, #6E, #3A, #4D, #30, #38, #20, #A5, #E1, #AB
                DB #A8, #20, #AD, #A5, #20, #E0, #A5, #A0, #AB, #A8, #A7, #E3
                DB #A5, #E2, #E1, #EF, #20, #A7, #A4, #A5, #E1, #EC, #0D
                ; обратное условие через @, сообщение M05 при текущем корабле FF
                DB #3F, #32, #35, #35, #2D, #6B, #40, #4D, #30, #35, #20, #A5
                DB #E1, #E2, #EC, #20, #AB, #A8, #20, #AA, #AE, #E0, #A0, #A1
                DB #AB, #EC, #0D
                ; отказ при совпадении текущего корабля с четырёхбайтовым набором O.s
                DB #3F, #4F, #2E, #73, #3D, #6E, #3A, #4D, #30, #37, #20, #A5
                DB #E1, #AB, #A8, #20, #AD, #A5, #20, #E3, #E1, #E2, #A0, #AD
                DB #A0, #A2, #AB, #2E, #20, #AD, #A0, #20, #AA, #AE, #E0, #A0
                DB #A1, #AB, #EC, #0D
                ; отказ при активном соседе в диапазонах выбранной группы оснащения
                DB #3F, #6F, #2E, #6E, #3D, #79, #3A, #4D, #31, #33, #20, #AF
                DB #AE, #A4, #AE, #A1, #AD, #AE, #A5, #20, #E3, #A6, #A5, #20
                DB #A5, #E1, #E2, #EC, #0D
                ; отказ при количестве не меньше предела 127 либо 1 по прежнему bit7
                DB #3F, #6F, #5D, #4F, #2E, #6B, #3A, #4D, #30, #36, #20, #A5
                DB #E1, #AB, #A8, #20, #AA, #AE, #AB, #2E, #20, #A1, #AE, #AB
                DB #EC, #E8, #A5, #20, #AC, #A0, #AA, #E1, #2E, #0D
                ; отказ при цене оснащения больше кредитов
                DB #3F, #4F, #2E, #63, #3E, #63, #3A, #4D, #30, #31, #20, #A5
                DB #E1, #AB, #A8, #20, #A4, #A5, #AD, #A5, #A3, #20, #AD, #A5
                DB #20, #E5, #A2, #A0, #E2, #A8, #E2, #0D
                ; отказ при сумме текущей загрузки и веса единицы больше вместимости
                DB #3F, #6A, #2B, #4F, #2E, #76, #3E, #4A, #3A, #4D, #30, #33
                DB #20, #E2, #AE, #AD, #A0, #A6, #0D
                ; увеличение кодированного количества, списание цены и пересчёт загрузки
                DB "=o+1,=c-O.c,T,^", #0D
                ; закрывающая скобка исходного блока, сама команда не восстанавливает стек блока
                DB "}", #0D
                DB #0D
                ; исходное пропускаемое пояснение CP866, ПРОДАЖА ОСНАЩЕНИЯ КОР-Я
                DB #20, #8F, #90, #8E, #84, #80, #86, #80, #20, #8E, #91, #8D
                DB #80, #99, #85, #8D, #88, #9F, #20, #8A, #8E, #90, #2D, #9F
                DB #0D
                ; событие 6, продажа одной единицы кодированного количества
SellEquipment:  DB "?X=6:{", #0D
                ; отказ при нулевом декодированном количестве
                DB "?o=n:M09", #0D
                ; предупреждение о сумме больше 65000 без прекращения продажи
                DB "?c+O.c>65000:m11", #0D
                ; уменьшение кодированного количества, начисление цены с насыщением и пересчёт загрузки
                DB "=o-1,=c+O.c,T,^", #0D
                ; закрывающая скобка исходного блока, сама команда не восстанавливает стек блока
                DB "}", #0D
                DB #0D
                DB #0D
                ; исходное пропускаемое пояснение CP866, Взымание платы за стоянку
                DB #20, #82, #A7, #EB, #AC, #A0, #AD, #A8, #A5, #20, #AF, #AB
                DB #A0, #E2, #EB, #20, #A7, #A0, #20, #E1, #E2, #AE, #EF, #AD
                DB #AA, #E3, #0D
                ; событие 16, проверка кредитов относительно размера ключа и плата за стоянку
ParkingFee:     DB "?X=16:{", #0D
                ; при кредитах не больше размера ключа обнулить кредиты, поставить M14 и вызвать переход W
                DB #3F, #63, #2D, #4C, #2E, #75, #3D, #30, #3A, #3D, #63, #3A
                DB #30, #2C, #4D, #31, #34, #2C, #57, #20, #82, #9B, #84, #82
                DB #8E, #90, #85, #8D, #88, #85, #0D
                ; списание пяти размеров ключа с насыщением нулём без повторной проверки W в этом событии
                DB "=c-(L.u*5),^", #0D
                ; закрывающая скобка исходного блока, сама команда не восстанавливает стек блока
                DB "}", #0D
                DB #0D
                DB #0D
                ; исходное пропускаемое пояснение CP866, Взымание платы за стоянку
                DB #20, #82, #A7, #EB, #AC, #A0, #AD, #A8, #A5, #20, #AF, #AB
                DB #A0, #E2, #EB, #20, #A7, #A0, #20, #E1, #E2, #AE, #EF, #AD
                DB #AA, #E3, #0D
                ; событие 17, дополнительный пересчёт загрузки после общего начального T
ParkingCheck:   DB "?X=17:{", #0D
                ; пересчёт загрузки и завершение сценария
                DB "T,^", #0D
                ; закрывающая скобка исходного блока, сама команда не восстанавливает стек блока
                DB "}", #0D
                DB #0D
                DB #0D
                DB #0D
                ; исходное пропускаемое пояснение CP866, Начальная проверка
                DB #20, #8D, #A0, #E7, #A0, #AB, #EC, #AD, #A0, #EF, #20, #AF
                DB #E0, #AE, #A2, #A5, #E0, #AA, #A0, #0D
                ; событие 15, пороги статуса 48 и 64 определяют начальный штраф и очистку оснащения
InitialCheck:   DB "?X=15:{", #0D
                ; завершение начальной проверки без штрафа при статусе меньше 48
                DB "?u<48:^", #0D
                ; для статуса 48..63 сообщение M16 и списание 50, остановка на конце строки
                DB "?u<64:M16,=c-50", #0D
                ; для статуса от 64 сообщение без остановки, списание 1000 и уменьшение статуса на 48
                DB "m15,=c-1000,=u-48", #0D
                ; очистка кодированных количеств оснащения с физическими индексами 5..9
                DB "=o6:0,=o7:0,=o8:0,=o9:0,=o10:0", #0D
                ; очистка индексов 2, 3 и 31, последний пишет 98AD вне первых тридцати строк, затем пересчёт и выход
                DB "=o3:0,=o4:0,=o32:0,T,^", #0D
                ; закрывающая скобка исходного блока, сама команда не восстанавливает стек блока
                DB "}", #0D
                DB #0D
                DB #0D
                DB #0D
                DB #0D
                DB #0D
                DB #0D
Terminator:     DB #00
                assert $ == #CF18
                endmodule
