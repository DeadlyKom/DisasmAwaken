                module Text
                module CompareLess
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; -----------------------------------------
; Беззнаковая проверка DE меньше BC, результат ноль или один в DE
; исходная запись 5, файловые смещения #049C..#04A5
; In:
;   DE - левый операнд, BC - правый операнд, сравнение без знака
; Out:
;   HL - разность операндов по модулю #10000, DE - логическое значение 0 или 1
; Corrupt:
;   HL, DE, AF
; Note:
;   BC, альтернативные и индексные регистры сохраняются
; -----------------------------------------
Entry:          EX DE, HL
                ; сброс входного переноса перед беззнаковым сравнением операндов
                OR A
                ; расчёт разности, заём означает, что левый операнд меньше правого
                SBC HL, BC
                LD DE, #0001
                RET C                                                           ; выход, если левый операнд меньше правого, DE содержит истину

                DEC DE
                RET

                endmodule
                endmodule
