                module Text
                module ReadEquipmentQuantity
                ; Документация [Text](../../Docs/FunctionDetails/Text.md)
                ; Подробный разбор [байтовая сумма, код количества и флаги инверсии](../../Docs/WeightFields.md)
                ; -----------------------------------------
                ; Чтение кодированного количества оснащения либо его свойства s или n
                ; исходная запись 5, файловые смещения #01C8..#01E5
                ; In:
                ;   IX - начало необязательного индекса либо точки, доступна выбранная строка и компонента смещения соответствующего набора
                ;   первый набор использует GetEquipIndex, второй SumSecondaryIndex, индекс по умолчанию их младший байт
                ;   при обычном возврате суффикс отсутствует либо равен s или n, применяется ParseFieldSuffix
                ; Out:
                ;   без точки HL=(база 988E + индекс) AND #FFFF, DE=A декодированное количество 0..127
                ;   без точки BC содержит исходный байтовый индекс с B=0, он не меняется при явном числе
                ;   без точки F от OR A исходного байта при bit7=0, иначе от CPL после OR A исходного байта
                ;   при исходном FF результат ноль, но Z=0, при исходном 00 результат ноль и Z=1
                ;   с суффиксом s результат CheckThresholdSet30 либо CheckThresholdSet14, n результат HasActiveNeighbor либо HasSecondActiveNeighbor
                ;   HL', DE' сохранены, BC' - B'=2, C' сохранён, AF' меняется только при банковом запросе s
                ;   IX - первый непрочитанный символ, IY, I и IFF сохранены, SP обычного возврата равен входному SP+2
                ;   FieldSuffixState.DefaultTarget содержит локальный ReadDirect
                ; Corrupt:
                ;   HL, DE, BC, AF, BC' только B, AF' на пути s, IX, SP при ошибке суффикса, R, DefaultTarget, временный CPU-стек и эффекты банкового s с операндом Limit
                ; Note:
                ;   суффиксы s и n отдельно проверены полным исполнением, s пишет Limit и банковое состояние, n сохраняет собственные BC и F поиска
                ;   на прямом пути постоянные записи ограничены двумя байтами DefaultTarget, временные CALL и разрядные PUSH не меняют исходное слово возврата
                ;   явное число временно использует до восьми байтов ниже входного SP, POP не очищает RAM, без числа сохраняется только временный возврат сумматора индекса
                ;   внутренний ReadAtBase не пишет RAM и CPU-стек, выполняет семь M1 при bit7=0 и восемь при bit7=1
                ;   R меняется при сохранённом старшем бите, дополнительные эффекты суффикса s задаёт соответствующий CheckThresholdSet
                ;   явное число преобразуется в (число-1) AND #FFFF, прямое чтение не обрезает индекс повторно
                ;   для байта с bit7=1 используется XOR FF, не абсолютная величина знакового числа
                ;   CPL сохраняет S/Z/PV от OR исходного байта, устанавливает H/N, X/Y берёт из инвертированного результата
                ;   общий ReadAtBase первого входа принимает полный HL индекс и DE произвольную базу
                ;   неизвестный суффикс передаёт управление SkipLine, полного обычного результата тогда нет
                ;   компоненты вторичного индекса соответствуют Row и младшему байту TopRow второго списка
                ; -----------------------------------------
                ; установка числа двух свойств s и n в альтернативном B
Entry:          EXX
                LD B, #02
                EXX
                ; выбор адреса за одной записью до свойств первого набора
                LD DE, #C9EC
                ; получение байтового индекса оснащения по выбранной строке и базе списка
                CALL @Text.GetEquipIndex.Entry
                ; выбор прямого чтения количества для пути без точки
                LD HL, @Text.ReadEquipmentQuantity.ReadDirect
                JP @Text.ParseFieldSuffix.Entry

                ; выбор базы кодированных количеств первого набора
ReadDirect:     LD DE, @EquipmentQuantityCodes.Item00
                ; расчёт адреса кодированного количества по полному индексу HL
ReadAtBase:     ADD HL, DE
                LD A, (HL)
                ; проверка старшего разряда кодированного количества
                OR A
                JP P, @Text.ReadEquipmentQuantity.ReturnValue                   ; переход, если bit7 снят, вернуть исходный байт

                ; декодирование инверсией с сохранением S/Z/PV исходного байта
                CPL
                ; передача количества в DE без пересчёта флагов
ReturnValue:    LD E, A
                LD D, #00
                RET

                endmodule
                endmodule
