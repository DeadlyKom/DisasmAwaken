                module OrWords
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; -----------------------------------------
; Побитовое OR двух слов DE и BC с результатом в DE
; исходная запись 5, файловые смещения #04CD..#04D3
; In:
;   DE - левый операнд, BC - правый операнд
; Out:
;   DE - результат побитовой операции
; Corrupt:
;   DE, AF
; Note:
;   HL, BC, альтернативные и индексные регистры сохраняются
; -----------------------------------------
Entry:          LD A, D
                ; объединение установленных битов старших байтов двух слов
                OR B
                LD D, A
                LD A, E
                ; объединение установленных битов младших байтов двух слов
                OR C
                LD E, A
                RET

                endmodule
                endmodule
