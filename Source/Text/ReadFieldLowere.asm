                module Text
                module ReadFieldLowere
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [уже проверенная первая цифра, ширины компонент и стек выражений](../../Docs/NumericFieldReads.md)
; -----------------------------------------
; Чтение байта по десятичному смещению от #9A42 и добавление в стек выражений
; исходная запись 5, файловые смещения #0342..#034C
; In:
;   HL' - два доступных байта следующего слова выражения, без перекрытия кода и CPU-стека
;   IX у первой уже проверенной ASCII-цифры, выполняется договор ReadDecimal5
;   память по (база 9A42+число) AND #FFFF читаема
; Out:
;   HL - адрес прочитанного байта, DE база #9A42, BC рабочий выход ReadDecimal5
;   AF - A прочитанный байт, F от ADD HL,DE с S/Z/PV от парсера, H/C по сложению и X/Y по старшему байту адреса
;   HL' увеличен на два, записаны A и нулевой старший байт, DE', BC', AF', IY, I и IFF сохранены
;   IX первый непрочитанный символ, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF, HL', IX
; Note:
;   смещение равно числу по модулю 65536, уменьшения индекса на один нет
;   общий ReadAtBase принимает HL числовое смещение и DE базу, сам цифры не читает
;   физические границы и игровые единицы массивов здесь не установлены
; -----------------------------------------
                ; чтение десятичного смещения первого массива
Entry:          CALL @Text.ReadDecimal5.Entry
                ; выбор исходной базы первого байтового массива
                LD DE, #9A42
                ; расчёт адреса байта по полному смещению без проверки границ
ReadAtBase:     ADD HL, DE
                ; чтение байта перед записью как слова с нулевым старшим байтом
                LD A, (HL)
                JP @Text.ReadFieldLowerj.AppendByte

                endmodule
                endmodule
