                module Text
                module PushCargo7BitWriter
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [захват адреса и значения, рамка оператора и точный способ сохранения](../../Docs/IndexedWriters.md)
; -----------------------------------------
; Создание захватывающего писателя семибитового поля через ReadCargoField
; исходная запись 5, файловые смещения #0685..#06B5
; In:
;   HL' указывает на два доступных байта следующего слова выражения, действует входной договор ReadCargoField
;   результат читателя HL должен быть адресом записываемого целевого байта, полученное значение доступно
;   до Invoke нельзя создавать другой писатель того же общего шаблона, захваченные операнды общие
;   Invoke принимает FFieldInvokeFrame и BC правый операнд, оператор возвращает DE через RET в банк LANG 6
; Out:
;   Entry - HL адрес от читателя, DE общий Invoke, BC от читателя, AF A=E читателя, F сохранён
;   Entry - HL' увеличен на два, DE' содержит Invoke, BC', AF', IX, IY по договору читателя
;   Entry обновляет общие операнды Target и InitialValue, само целевое поле не записывает
;   Invoke передаёт оператору DE захваченное байтовое значение с нулевым D, BC правый операнд
;   перед входом оператора CPU-стек FIndexedOperatorFrame, сохранены StoreReturn, SavedTarget и AfterStore
;   Store возвращает HL адрес цели, BC как у оператора, DE с E=127 при D!=0 либо E AND 127 при D=0, D сохранён
;   Store - AF A сохранённый байт, F от OR маркера с младшими семью разрядами
;   SP после Entry равен входному SP+2, после Invoke либо отдельного Store входному SP+4
; Corrupt:
;   Entry - HL, DE, BC, AF, HL', DE', BC' только B, AF' и IX по договору читателя
;   Invoke - HL, DE и регистры по договору оператора
;   Store - HL, DE только E, AF
; Note:
;   целевой адрес и левый операнд захватываются при создании, маркер либо условие инверсии читается из памяти только в Store
;   Invoke добавляет SavedTarget между StoreReturn и AfterStore, Store снимает этот адрес POP HL
;   D!=0 выбирает E=127, но при D=0 значение E>=128 только маскируется, общего насыщения min(result,127) нет
;   игровой смысл маркера и физические единицы веса отдельно не доказаны
; -----------------------------------------
                ; получение адреса и текущего байта грузовой записи для захвата
Entry:          CALL @Text.ReadCargoField.Entry
                ; выбор E читателя как захваченного левого операнда, для груза bit7 может остаться
Capture:        LD A, E
                ; обновление общего операнда Target адресом целевого байта
                LD (@PackedWriterState.Target), HL
                ; обновление общего InitialValue байтом левого операнда
                LD (@PackedWriterState.InitialValue), A
                ; выбор общего Invoke семибитового писателя
                LD DE, @Text.PushCargo7BitWriter.Invoke
                JP @Text.PushExpressionWord.Entry

                ; снятие адреса оператора из рамки вызова
Invoke:         POP DE
                ; чтение захваченного адреса из изменяемого операнда Target
                LD HL, #0000
                ; чтение захваченного байтового левого операнда InitialValue
                LD A, #00
                ; сохранение Target на CPU-стеке до завершения операции
                PUSH HL
                ; выбор Store как аппаратного возврата оператора
                LD HL, @Text.PushCargo7BitWriter.Store
                ; создание шестибайтовой рамки FIndexedOperatorFrame
                PUSH HL
                ; создание DE из захваченного левого байта с нулевым старшим байтом
                LD L, A
                LD H, #00
                ; передача адреса оператора в HL и левого значения в DE
                EX DE, HL
                JP (HL)

                ; восстановление Target после RET оператора
Store:          POP HL
                LD A, D
                ; проверка ненулевого старшего байта результата перед выбором младших семи разрядов
                OR A
                JR Z, @Text.PushCargo7BitWriter.MaskLow                         ; переход, если D равен нулю, использовать младший E после маскирования

                ; выбор E=127 при любом ненулевом D, старший D не изменяется
                LD E, #7F
                ; выбор младших семи разрядов E, значения 128..255 оборачиваются, не насыщаются
MaskLow:        LD A, E
                AND #7F
                LD E, A
                ; чтение текущего маркера целевого байта в момент сохранения
                LD A, (HL)
                ; выделение bit7 для объединения с новым семибитовым значением
                AND #80
                ; создание записываемого байта и окончательных флагов
                OR E
                LD (HL), A
                RET

                endmodule
                endmodule
