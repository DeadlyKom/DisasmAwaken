                module CallExpression
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [ScriptLanguage.md](../../Docs/ScriptLanguage.md)
; -----------------------------------------
; Извлечение левого операнда, обработчика и правого операнда из стека выражений с возвратом результата через PushExpressionWord
; исходная запись 5, файловые смещения #0825..#0848
; In:
;   HL' - адрес за шестью байтами записи FExpressionCall, на CPU-стеке адрес возврата
; Out:
;   перед входом обработчика DE - Left, HL - Handler, BC - Right, HL' уменьшен на шесть
; Corrupt:
;   HL, DE, BC, AF, HL', DE', дополнительные эффекты определяются выбранным обработчиком
; Note:
;   AF изменяется сложением указателей, A сохраняется до передачи управления обработчику
;   на CPU-стек помещается адрес PushExpressionWord, переход к обработчику выполняется через JP (HL)
;   обработчик обязан вернуть результат в DE через RET и сохранить указатель стека выражений HL'
;   после возврата PushExpressionWord записывает результат вместо Left и продвигает HL' на два, три слова заменены одним
;   при таком обработчике итоговый HL' меньше входного на четыре, CPU-стек восстанавливается
;   BC', AF', IX и IY сохраняются самим диспетчером, ограничения обработчика учитываются отдельно
; -----------------------------------------
                ; создание адреса возврата, который поместит результат DE обратно в стек выражений
Entry:          LD HL, @Text.PushExpressionWord.Entry
                PUSH HL
                ; поиск начала шестибайтовой записи относительно вершины стека в альтернативном HL
                EXX
                LD DE, -FExpressionCall
                ; расчёт начала записи, из указателя вершины вычитается размер FExpressionCall
                ADD HL, DE
                LD E, (HL)
                INC HL
                LD D, (HL)
                INC HL
                ; передача левого операнда из записи в основной DE
                PUSH DE
                EXX
                POP DE
                EXX
                LD E, (HL)
                INC HL
                LD D, (HL)
                INC HL
                ; передача адреса обработчика из записи в основной HL
                PUSH DE
                EXX
                POP HL
                EXX
                LD E, (HL)
                INC HL
                LD D, (HL)
                PUSH DE
                LD DE, 1 - FExpressionCall
                ; расчёт новой вершины, указатель возвращается к началу использованной записи
                ADD HL, DE
                EXX
                ; передача правого операнда в BC и хвостовой вход в обработчик
                POP BC
                JP (HL)

                endmodule
                endmodule
