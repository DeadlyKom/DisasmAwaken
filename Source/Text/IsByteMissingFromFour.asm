                module Text
                module IsByteMissingFromFour
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [условия совпадения, код bit7 и два общих стековых входа](../../Docs/MembershipFlags.md)
; -----------------------------------------
; Проверка отсутствия выбранного байта в четырёхбайтовой записи
; исходная запись 5, файловые смещения #0558..#0576
; In:
;   на вершине CPU-стека слово индекса, под ним адрес возврата, старший байт индекса отбрасывается
;   Entry читает искомый байт по #9849 и выбирает базу #9400
;   общий вход CheckAtBase принимает DE базу и A искомый байт
; Out:
;   HL - адрес после совпавшего байта среди первых трёх, либо адрес четвёртого байта записи
;   DE - 0 при совпадении с любым из четырёх байтов, 1 при отсутствии совпадения, BC сохранён
;   AF - A искомый байт, F от последнего CP, Z=1 при совпадении, Z=0 при отсутствии
;   альтернативные и индексные регистры, I и IFF сохранены, SP равен входному SP+4
; Corrupt:
;   HL, DE, AF
; Note:
;   адрес записи равен база+4*младший_индекс, логические границы не проверяются
;   после четвёртого CP нет INC HL, после первых трёх указатель продвигается даже при совпадении
;   игровой смысл байта селектора и физического списка ещё не установлен
;   Property072 сохраняет табличное имя до установления назначения её поля
; -----------------------------------------
                ; чтение искомого байта из существующего поля #9849
Entry:          LD A, (#9849)
                ; выбор базы четырёхбайтовых записей первого входа
                LD DE, #9400
                ; чтение индекса поверх возврата, общий вход принимает базу в DE и искомый байт в A
CheckAtBase:    POP HL
                ; отбрасывание старшего байта индекса
                LD H, #00
                ; расчёт четырёхбайтового смещения двумя удвоениями
                ADD HL, HL
                ADD HL, HL
                ; расчёт адреса первого байта выбранной записи
                ADD HL, DE
                ; проверка совпадения с первым байтом записи
                CP (HL)
                INC HL
                JR Z, @Text.IsByteMissingFromFour.ReturnResult                  ; переход, если первый байт совпал с искомым, вернуть 0

                ; проверка совпадения со вторым байтом записи
                CP (HL)
                INC HL
                JR Z, @Text.IsByteMissingFromFour.ReturnResult                  ; переход, если второй байт совпал с искомым, вернуть 0

                ; проверка совпадения с третьим байтом записи
                CP (HL)
                INC HL
                JR Z, @Text.IsByteMissingFromFour.ReturnResult                  ; переход, если третий байт совпал с искомым, вернуть 0

                ; проверка четвёртого байта без последующего продвижения HL
                CP (HL)
                ; выбор результата 0 перед условным выходом по совпадению
ReturnResult:   LD DE, #0000
                RET Z                                                           ; выход, если найдено совпадение, DE содержит 0

                ; выбор результата 1 при отсутствии всех четырёх совпадений
                INC DE
                RET

                endmodule
                endmodule
