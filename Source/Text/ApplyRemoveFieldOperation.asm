                module ApplyRemoveFieldOperation
                ; Документация [Text](../../Docs/FunctionDetails/Text.md)
                ; Подробный разбор [режим A альтернативного набора, реальные записи и путь до NextCommand](../../Docs/UnaryModes.md)
                ; -----------------------------------------
                ; Установка режима 0 и вызов унарного поля перед NextCommand
                ; исходная запись 5, файловые смещения #009C..#009E
                ; In:
                ;   IX у допустимого унарного символа, далее корректные данные выбранного обработчика
                ;   выполняются договоры DispatchUnaryField и выбранного унарного обработчика
                ; Out:
                ;   HL, DE, BC и AF по выбранному обработчику, дополнительных преобразований результата нет
                ;   HL', DE', BC' сохраняются при договорах семи исходных обработчиков, AF' меняется обменом в обработчике
                ;   IX по выбранному обработчику, IY, I и IFF сохраняются при договорах семи исходных обработчиков
                ;   перед входом обработчика A'=0, F' сохранён, этот байт служит режимом всей операции
                ;   после обычного возврата обработчика хвостовой вход в NextCommand, SP равен входному SP
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', IX, SP при ошибке поиска, R, временный CPU-стек и память выбранного обработчика
                ; Note:
                ;   собственный CALL DispatchUnaryField записывает два байта возврата, внутри поиска ещё два занимает CALL FindToken
                ;   на входе успешно найденного обработчика SP меньше входного на два, обработчик использует возврат к JP NextCommand
                ;   собственная подготовка режима не пишет постоянные данные, остальные RAM-записи и порты определяет выбранный обработчик
                ;   до обработчика номер k от 1 до 7 даёт 4*k+20 M1 у плюса и 4*k+21 у минуса, старший бит R сохраняется
                ;   общий SetMode принимает A произвольный байтовый режим, Entry плюс задаёт 1, Entry минус 0
                ;   операция не означает универсальное прибавление или вычитание, конкретную запись определяет поле
                ;   при неизвестном символе управление переходит в SkipLine без возврата к хвосту команды
                ; -----------------------------------------
                ; выбор режима 0 с основным F=44 перед общим SetMode
Entry:          XOR A
                JR @Text.ApplyAddFieldOperation.SetMode

