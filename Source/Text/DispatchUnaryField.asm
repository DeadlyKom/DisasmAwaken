                module Text
                module DispatchUnaryField
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [таблицы, первое совпадение y и стек ошибки](../../Docs/FieldDispatchers.md)
; -----------------------------------------
; Выбор одного из семи унарных обработчиков по байту поля
; исходная запись 5, файловые смещения #07B6..#07C2
; In:
;   IX - читаемый байт символа поля, BC - C сохраняемый контекст, CPU-стек допускает CALL FindToken
;   таблица из 7 физических FScriptToken после якоря #CA4F доступна
; Out:
;   при совпадении хвостовой вход в обработчик, HL его адрес, DE=3, BC - B остаток записей вместе с найденной, C сохранён
;   AF - A младший байт адреса обработчика, F от CP символа с совпавшей записью, Z=1
;   IX увеличен на один, SP перед входом обработчика равен входному SP, нового CALL обработчика нет
;   при отсутствии символа вход в SkipLine с A исходным символом, B=0, C сохранён, HL последняя запись, DE=3
;   при отсутствии F от последнего CP, SP равен входному SP-2 с возвратом FindToken в C7DD на вершине
;   альтернативные и индексные регистры кроме IX, I и IFF сохраняются до выбранного получателя
; Corrupt:
;   HL, DE, BC только B, AF, IX, SP на пути отсутствия символа
; Note:
;   описанный выход ограничен входом в обработчик либо SkipLine, дальнейшие эффекты определяет получатель
;   первое совпадение выигрывает, повторный y в таблице чтения затенён прежним y
;   DispatchReadField последовательно входит в DispatchToken, жёсткий порядок include обязателен
; -----------------------------------------
                ; чтение символа поля перед поиском записи выбранной таблицы
Entry:          LD A, (IX + @ScriptConst.Cursor)
                INC IX
                ; выбор якоря за одной записью до соответствующей таблицы полей
                LD HL, @ScriptTables.UnaryAnchor
                ; выбор числа физических записей, поиск остановится на первом совпадении
                LD B, @ScriptConst.UnaryCount
                JP @Text.DispatchToken.Entry

                endmodule
                endmodule
