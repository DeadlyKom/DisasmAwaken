                module Text
                module GetIndexedLoad
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [путь от выбранной строки через суффикс к исходным обработчикам](../../Docs/MarketField.md)
; -----------------------------------------
; Взвешенная сумма с выбранной строкой из младшего байта стекового индекса
; исходная запись 5, файловые смещения #05DF..#05E8
; In:
;   на вершине CPU-стека слово индекса, под ним адрес возврата, старший байт индекса игнорируется
;   действует договор ComputeWeightedLoad с индексом 0..255
; Out:
;   HL и BC по договору ComputeWeightedLoad, DE=A итоговая байтовая сумма с нулевым D
;   AF по договору ComputeWeightedLoad, SP равен входному SP + 4
;   HL', DE', BC', IX, IY, I и IFF сохранены, AF' содержит рабочую сумму ядра
;   три операнда ядра изменяются, дополнительная запись читается по исходному вращаемому смещению
; Corrupt:
;   HL, DE, BC, AF, AF'
; Note:
;   POP HL потребляет индекс, только затем CALL создаёт обычный возврат ядра
;   полный индекс ядра обрезается этим обработчиком до байта, прямой ComputeWeightedLoad его не обрезает
; -----------------------------------------
                ; чтение стекового индекса поверх адреса возврата
Entry:          POP HL
                ; отбрасывание старшего байта перед передачей индекса ядру суммы
                LD H, #00
                ; расчёт суммы через исходное ядро без подмены таблиц или арифметики
                CALL @Text.ComputeWeightedLoad.Entry
                ; передача итогового байта в DE с нулевым старшим байтом
                LD E, A
                LD D, #00
                RET

                endmodule
                endmodule
