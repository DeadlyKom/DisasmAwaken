                module Text
                module ParseFieldSuffix
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [стековый индекс, два выхода и изменяемый JP](../../Docs/FieldSuffix.md)
; -----------------------------------------
; Разбор необязательного индекса и точечного суффикса с хвостовой передачей управления
; исходная запись 5, файловые смещения #07EE..#0824
; In:
;   HL - адрес продолжения при отсутствии точки, DE база за одной записью до таблицы FScriptToken
;   BC - C индекс по умолчанию, B контекст, число записей таблицы находится в B альтернативного набора
;   IX - текущий символ, последовательность читаема, текущая страница содержит изменяемый код LANG
;   SP - стек вызывающего языка, запись слова индекса и временных слов не перекрывает код и текст
; Out:
;   без точки HL содержит индекс, DE и BC сохранены, IX у первого непрочитанного символа
;   без точки AF - A непрочитанный символ, F от последнего CP, затем JP по сохранённому адресу
;   с точкой HL база таблицы, DE индекс, BC - B число записей из альтернативного B, C сохранён
;   с точкой AF - A символ после точки, F=#6A, IX у символа после суффикса
;   с точкой SP уменьшен на 2, индекс помещён поверх прежнего возврата, далее хвостовой DispatchToken
;   альтернативные регистры и IY, I, IFF сохранены до хвостового получателя
;   операнд DefaultTarget обновлён входным HL на обоих путях
; Corrupt:
;   HL, DE, BC, AF, IX, SP только на пути суффикса
; Note:
;   это договор до входа продолжения либо DispatchToken, дальнейшие эффекты определяет получатель
;   явное число содержит от одной до пяти цифр, результат оборачивается до 16 бит и затем уменьшается на один
;   без цифр используется C без уменьшения, число 0 даёт индекс #FFFF
;   шестая цифра не читается и не является точкой, поэтому выбирается продолжение без суффикса
;   самомодификация DefaultTarget запрещает повторный вход с другим продолжением до завершения текущего разбора
;   проверки корректности суффикса здесь нет, поиск выполняется в DispatchToken
; -----------------------------------------
                ; сохранение адреса продолжения в операнде JP до проверки синтаксиса
Entry:          LD (@FieldSuffixState.DefaultTarget), HL
                ; создание исходного индекса из C без уменьшения, он используется при отсутствии цифр
                LD L, C
                LD H, #00
                ; чтение первого символа необязательного индекса либо точки
                LD A, (IX + @ScriptConst.Cursor)
                ; проверка точки без явного числового индекса
                CP #2E
                JR Z, @Text.ParseFieldSuffix.DispatchField                      ; переход, если первый символ является точкой, использовать индекс из C

                ; проверка нижней границы первой десятичной цифры
                CP #30
                JR C, @Text.ParseFieldSuffix.UseDefault                         ; переход, если символ меньше ASCII-цифры 0, выполнить продолжение без суффикса

                ; проверка верхней исключённой границы десятичной цифры
                CP #3A
                JR C, @Text.ParseFieldSuffix.ReadIndex                          ; переход, если символ является ASCII-цифрой 0..9, прочитать явный индекс

                ; передача управления по входному HL, сохранённому в DefaultTarget, новый возврат не создаётся
UseDefault:     JP #0000

                ; сохранение контекста и базы таблицы перед настоящим чтением десятичного числа
ReadIndex:      PUSH BC
                PUSH DE
                CALL @Text.ReadDecimal5.Entry
                POP DE
                POP BC
                ; расчёт индекса с нуля вычетом единицы по модулю 65536
                DEC HL
                ; чтение первого символа после не более пяти цифр
                LD A, (IX + @ScriptConst.Cursor)
                ; проверка точки непосредственно после явного индекса
                CP #2E
                JR NZ, @Text.ParseFieldSuffix.UseDefault                        ; переход, если после числа нет точки, выполнить сохранённое продолжение

                ; пропуск точки и одного байта суффикса перед передачей управления
DispatchField:  INC IX
                INC IX
                ; создание стекового операнда для обработчиков полей, слово лежит поверх возврата
                PUSH HL
                ; передача базы таблицы в HL, текущий индекс переходит в DE
                EX DE, HL
                ; чтение числа записей из альтернативного B без изменения альтернативных регистров
                EXX
                LD A, B
                EXX
                LD B, A
                ; чтение байта суффикса, соответствующий символ ищет DispatchToken
                LD A, (IX - @ScriptConst.SuffixBack)
                JP @Text.DispatchToken.Entry

                endmodule
                endmodule
