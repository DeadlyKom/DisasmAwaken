                module GetCargoIndex
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [ScriptLanguage.md](../../Docs/ScriptLanguage.md)
; -----------------------------------------
; Сложение выбранной строки и смещения списка товаров, байтовый индекс возвращается в BC
; исходная запись 5, файловые смещения #0918..#0923
; In:
;   ScriptSelection.CargoRow и CargoBase доступны в общей памяти станции
; Out:
;   BC - сумма двух байтов по модулю 256, AF - A та же сумма, флаги восьмибитного сложения
; Corrupt:
;   BC, AF
; Note:
;   HL, DE, альтернативные и индексные регистры сохраняются
;   B обнуляется, перенос за пределы байта не добавляется к результату
;   значение #FF выбранной строки отдельно не проверяется, границы таблицы не проверяются
; -----------------------------------------
                ; чтение выбранной строки и компоненты смещения списка товаров
Entry:          LD A, (@ScriptSelection.CargoRow)
                LD C, A
                LD A, (@ScriptSelection.CargoBase)
                ; расчёт байтового индекса товара, переполнение не расширяет результат до слова
                ADD A, C
                LD C, A
                LD B, #00
                RET

                endmodule
                endmodule
