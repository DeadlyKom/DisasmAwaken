                module Text
                module FindDelimitedRecord
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [два уровня CPIR, нулевые счётчики и операнды повторений](../../Docs/DelimitedRecord.md)
; -----------------------------------------
; Поиск записи через заданное число разделителей FF и FE и байтовое смещение
; исходная запись 5, файловые смещения #0849..#086E
; In:
;   DE - шестнадцатибитное смещение от найденного разделителя FE
;   BC - B число разделителей FE, C сохраняемый контекст, AF - A число разделителей FF
;   нулевой A либо B означает 256 повторений соответствующего поиска
;   таблица читается начиная с #9A49, все требуемые разделители должны существовать
;   для обычного табличного поиска каждый разделитель найден до полного оборота адресов и код LANG доступен для записи
; Out:
;   HL - (адрес найденного FE + входной DE) AND #FFFF, DE сохранён
;   BC - B=0, C сохранён, AF - A=#FE, флаги от последнего ADD HL,DE
;   S/Z/PV сохраняются от последнего CPIR, при найденном FE S=0, Z=1
;   PV=1, если после последнего поиска BC ядра не нулевой, H/C от сложения адреса и DE, N=0
;   альтернативные регистры, IX, IY, I и IFF сохранены, SP восстановлен
;   операнды GroupCount и RecordCount содержат исходные A и B
; Corrupt:
;   HL, BC только B, AF
; Note:
;   каждый CPIR начинает с BC=0, внутренний предел составляет 65536 сравнений, внешний B хранится на CPU-стеке
;   при отсутствии разделителя CPIR не возвращает отдельную ошибку, внешний цикл всё равно продолжает поиск
;   требование существования разделителей ограничивает смысл табличного результата, исходный код проверки не добавляет
;   смещение отсчитывается от самого FE после DEC HL, не от следующего байта
;   повторный вход с другими счётчиками до завершения нарушает самомодифицированные операнды
; -----------------------------------------
                ; обновление операнда GroupCount числом разделителей FF
Entry:          LD (@DelimitedRecordState.GroupCount), A
                ; чтение числа разделителей FE до использования B первым циклом
                LD A, B
                ; обновление операнда RecordCount исходным B
                LD (@DelimitedRecordState.RecordCount), A
                ; выбор исходного начала таблицы с двумя уровнями разделителей
                LD HL, #9A49
                ; выбор разделителя первого уровня FF
                LD A, #FF
                ; чтение самомодифицированного числа FF, ноль означает 256 поисков
                LD B, #00
                ; сохранение внешнего счётчика и контекста C перед CPIR
FindGroup:      PUSH BC
                ; создание внутреннего предела 65536 сравнений, BC=0 уменьшится до FFFF на первом шаге
                LD BC, #0000
                ; поиск следующего FF с продвижением HL за найденный байт
                CPIR
                POP BC
                DJNZ @Text.FindDelimitedRecord.FindGroup

                ; выбор разделителя второго уровня FE вычетом единицы из FF
                DEC A
                ; чтение самомодифицированного числа FE, ноль означает 256 поисков
                LD B, #00
                ; сохранение внешнего счётчика FE перед внутренним полным CPIR
FindRecord:     PUSH BC
                ; создание внутреннего предела следующего поиска FE
                LD BC, #0000
                ; поиск следующего FE начиная с позиции после предыдущего разделителя
                CPIR
                POP BC
                DJNZ @Text.FindDelimitedRecord.FindRecord

                ; возврат HL на сам найденный FE, он является базой входного смещения
                DEC HL
                ; расчёт итогового адреса относительно найденного FE с оборачиванием до слова
                ADD HL, DE
                RET

                endmodule
                endmodule
