                module Text
                module QueueTextAndStopAtLine
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [числовой номер строки, M/m и отложенная перерисовка](../../Docs/QueuedText.md)
; -----------------------------------------
; Подготовка строки текста с завершением сценария на следующем CR
; исходная запись 5, файловые смещения #00EC..#00FF
; In:
;   IX у первой проверенной цифры номера строки, действует ReadDecimal5
;   LANG в банке 6, выполнен договор QueueTextRowForLang и исходного элемента/списка
; Out:
;   хвостовой вход в NextCommand, IX после не более пяти цифр номера строки
;   TextRowState.Row=(младший_байт_числа-1) AND FF, вычет не переносится в старший H
;   HL выбранный обработчик, DE индекс обёртки, BC рабочий выход ReadDecimal5
;   AF - финальный банковый результат QueueTextRowForLang, SP перед NextCommand равен входному SP
;   альтернативные регистры, IY, I и IFF сохранены, IX восстановлен после вызова подготовки
;   StopAtLine=1 установлен перед чтением номера
; Corrupt:
;   HL, DE, BC, AF, IX
; Note:
;   числовой ноль и числа с нулевым младшим байтом выбирают строку FF, проверки диапазона ресурса нет
;   M задаёт завершение при следующем CR через StopAtLine, m только сохраняет прежнее значение флага
;   эта команда подготавливает элемент, само рисование требует дальнейшего прохода интерфейса
; -----------------------------------------
                ; выбор завершения сценария на следующем обработанном CR
Entry:          LD A, #01
                ; обновление исходного операнда StopAtLine в SkipLine
                LD (@ScriptRuntimeState.StopAtLine), A
                ; чтение номера строки в диапазоне одной-пяти цифр без насыщения
ReadRow:        CALL @Text.ReadDecimal5.Entry
                ; расчёт нулевого байтового индекса строки, заём в H не переносится
                DEC L
                LD A, L
                ; сохранение курсора после числа перед станционным вызовом
                PUSH IX
                ; подготовка текстовой строки с настоящими переключениями страниц
                CALL @Station.QueueTextRowForLang.Entry
                ; восстановление курсора для следующей команды сценария
                POP IX
                JP @Text.NextCommand.Entry

                endmodule
                endmodule
