                module AndWords
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; -----------------------------------------
; Побитовое AND двух слов DE и BC с результатом в DE
; исходная запись 5, файловые смещения #04C6..#04CC
; In:
;   DE - левый операнд, BC - правый операнд
; Out:
;   DE - результат побитовой операции
; Corrupt:
;   DE, AF
; Note:
;   HL, BC, альтернативные и индексные регистры сохраняются
; -----------------------------------------
Entry:          LD A, D
                ; пересечение установленных битов старших байтов двух слов
                AND B
                LD D, A
                LD A, E
                ; пересечение установленных битов младших байтов двух слов
                AND C
                LD E, A
                RET

                endmodule
                endmodule
