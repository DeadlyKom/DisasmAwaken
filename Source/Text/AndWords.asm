                module AndWords
                ; Документация [Text](../../Docs/FunctionDetails/Text.md)
                ; Подробный разбор [эффекты бинарных операторов](../../Docs/ScriptLanguage.md#собственные-эффекты-простых-бинарных-операторов)
                ; -----------------------------------------
                ; Побитовое AND двух слов DE и BC с результатом в DE
                ; исходная запись 5, файловые смещения #04C6..#04CC
                ; In:
                ;   DE - левый операнд, BC - правый операнд
                ; Out:
                ;   DE - результат побитовой операции
                ;   AF - A младший байт результата, F от побитовой операции только над младшими байтами
                ; Corrupt:
                ;   DE, AF, R
                ; Note:
                ;   собственных записей RAM и CPU-стека нет, RET увеличивает входной SP на два, I и IFF сохраняются без прерываний, R изменяется
                ;   HL, BC, альтернативные и индексные регистры сохраняются
                ; -----------------------------------------
Entry:          LD A, D
                ; пересечение установленных битов старших байтов двух слов
                AND B
                LD D, A
                LD A, E
                ; пересечение установленных битов младших байтов двух слов
                AND C
                LD E, A
                RET

                endmodule
                endmodule
