                module Text
                module ApplyAddFieldOperation
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [режим A альтернативного набора, реальные записи и путь до NextCommand](../../Docs/UnaryModes.md)
; -----------------------------------------
; Установка режима 1 и вызов унарного поля перед NextCommand
; исходная запись 5, файловые смещения #0090..#009B
; In:
;   IX у допустимого унарного символа, далее корректные данные выбранного обработчика
;   выполняются договоры DispatchUnaryField и выбранного унарного обработчика
; Out:
;   перед входом обработчика A'=1, F' сохранён, этот байт служит режимом всей операции
;   после обычного возврата обработчика хвостовой вход в NextCommand, SP равен входному SP
;   HL, DE, BC, AF и IX по выбранному обработчику, дополнительных преобразований результата нет
;   HL', DE', BC', IY, I и IFF сохраняются при договорах семи исходных обработчиков, AF' меняется обменом в обработчике
; Corrupt:
;   HL, DE, BC, AF, AF', IX
; Note:
;   общий SetMode принимает A произвольный байтовый режим, Entry плюс задаёт 1, Entry минус 0
;   операция не означает универсальное прибавление или вычитание, конкретную запись определяет поле
;   при неизвестном символе управление переходит в SkipLine без возврата к хвосту команды
; -----------------------------------------
                ; выбор режима 1 для конкретного унарного обработчика
Entry:          LD A, #01
                ; временное сохранение режима в L перед записью в альтернативный A
SetMode:        LD L, A
                ; обмен AF для изменения только альтернативного A с сохранением его F
                EX AF, AF'
                ; перенос выбранного режима из L в будущий альтернативный A
                LD A, L
                EX AF, AF'
                ; поиск и исполнение унарного поля с подготовленным режимом
                CALL @Text.DispatchUnaryField.Entry
                JP @Text.NextCommand.Entry

                endmodule
                endmodule
