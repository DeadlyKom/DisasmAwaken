                module Text
                module GetHighBitCode
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [условия совпадения, код bit7 и два общих стековых входа](../../Docs/MembershipFlags.md)
; -----------------------------------------
; Возврат кода 127 при снятом bit7 либо 1 при установленном
; исходная запись 5, файловые смещения #0577..#0589
; In:
;   на вершине CPU-стека слово индекса, под ним адрес возврата, старший байт игнорируется
;   Entry выбирает базу #988E
;   общий вход ReadAtBase принимает базу в DE
; Out:
;   HL=(база+младший_индекс) AND #FFFF, DE=A=127 при снятом bit7 либо 1 при установленном, BC сохранён
;   AF - F от BIT 7,(HL), H=1, N=0, S равен bit7, Z и PV равны обратному bit7
;   X/Y из проверенного байта, Carry от прибавления индекса к базе, для штатных баз Carry=0
;   альтернативные и индексные регистры, I и IFF сохранены, SP равен входному SP+4
; Corrupt:
;   HL, DE, AF
; Note:
;   это коды 127 и 1, а не стандартный логический результат 0 и 1
;   F не пересчитывается по возвращаемому A, при A=127 установлен Z, при A=1 Z снят
;   игровое назначение поля и старшего разряда пока не доказано
; -----------------------------------------
                ; выбор базы массива проверяемых старших разрядов
Entry:          LD DE, #988E
                ; чтение индекса поверх возврата, общий вход принимает базу в DE
ReadAtBase:     POP HL
                ; отбрасывание старшего байта индекса
                LD H, #00
                ; расчёт адреса проверяемого байта, Carry этого сложения сохраняется после BIT
                ADD HL, DE
                ; выбор кода 127 для снятого старшего разряда
                LD A, #7F
                ; проверка bit7 исходного байта без изменения возвращаемого кода
                BIT 7, (HL)
                JR Z, @Text.GetHighBitCode.ReturnCode                           ; переход, если bit7 снят, вернуть код 127

                ; выбор кода 1 при установленном bit7
                LD A, #01
                ; передача кода в DE с нулевым D без изменения флагов BIT
ReturnCode:     LD E, A
                LD D, #00
                RET

                endmodule
                endmodule
