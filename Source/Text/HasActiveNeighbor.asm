                module Text
                module HasActiveNeighbor
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [точные границы поиска, пропуск выбранного элемента и флаги](../../Docs/ActiveNeighbors.md)
; -----------------------------------------
; Поиск активного соседа по двум кодированным границам первого набора
; исходная запись 5, файловые смещения #051A..#0557
; In:
;   на вершине CPU-стека слово индекса, под ним возврат, старший байт игнорируется
;   Entry выбирает BC базу пар границ #964E и DE базу значений #988E
;   все адреса в выбранных границах читаемы, логический размер таблиц не проверяется
;   общий ScanAtBases принимает BC базу пар границ, DE базу значений
; Out:
;   HL - адрес выбранного элемента при найденном левом соседе, иначе найденного правого либо конца правого поиска
;   DE - 1 при найденном активном соседе, иначе 0, BC - B старший байт базы границ, C остаток текущего счётчика
;   AF - A декодированное ненулевое значение найденного соседа либо 0 при отсутствии
;   при успехе F от OR A декодированного значения, Carry=0 и Z=0, при отсутствии у Entry F=#42 и Z=1
;   альтернативные и индексные регистры, I и IFF сохранены, SP равен входному SP+4
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   у общего входа при двух нулевых границах Carry от сложения адреса пары может дать F=#43
;   адрес пары границ равен база_границ+((2*младший_индекс) AND #FF), индексы 0 и 128 используют одну пару
;   адрес выбранного значения равен база_значений+младший_индекс без этого оборачивания
;   левый предел задаёт (-первый_байт) AND #FF шагов, правый предел второй_байт шагов
;   выбранный элемент не проверяется, сначала читаются только предыдущие, затем следующие
;   активны все байты кроме 0 и FF, bit7 кодируется побитовой инверсией перед OR A
;   игровая семантика зависимостей и конкретных пар границ ещё не установлена
; -----------------------------------------
                ; выбор первой таблицы пар границ в BC
Entry:          LD BC, #964E
                ; выбор первой базы проверяемых значений в DE
                LD DE, #988E
                ; чтение слова индекса поверх возврата, общий вход принимает две базы
ScanAtBases:    POP HL
                ; отбрасывание старшего байта индекса
                LD H, #00
                ; сохранение байтового индекса в A для отдельного расчёта адреса пары
                LD A, L
                ; расчёт адреса выбранного значения без восьмибитного удвоения
                ADD HL, DE
                EX DE, HL
                ; сохранение адреса выбранного значения для возврата после левого поиска
                PUSH DE
                ; расчёт двухбайтового смещения пары с оборачиванием в A, индекс 128 даёт смещение 0
                ADD A, A
                LD L, A
                LD H, #00
                ; расчёт адреса пары границ относительно исходного BC
                ADD HL, BC
                EX DE, HL
                ; чтение отрицательно кодированного левого предела
                LD A, (DE)
                LD C, A
                ; подготовка счётчика перед первым INC C, исходный ноль пропускает левый поиск
                DEC C
                ; проверка исчерпания отрицательного левого счётчика увеличением к нулю
CheckLeftCount: INC C
                JR Z, @Text.HasActiveNeighbor.BeginRight                        ; переход, если левый счётчик достиг нуля, начать поиск справа

                ; переход к предыдущему значению, выбранный элемент не проверяется
                DEC HL
                LD A, (HL)
                ; проверка старшего разряда кодированного левого значения
                OR A
                JP P, @Text.HasActiveNeighbor.TestLeftValue                     ; переход, если bit7 снят, проверить исходное левое значение

                ; декодирование левого значения инверсией, FF превращается в ноль
                CPL
                ; проверка активности после декодирования
TestLeftValue:  OR A
                JR Z, @Text.HasActiveNeighbor.CheckLeftCount                    ; переход, если левый сосед неактивен, продолжить поиск назад

                ; восстановление адреса выбранного элемента при найденном левом соседе
                POP HL
                JR @Text.HasActiveNeighbor.ReturnResult

                ; восстановление выбранного адреса перед правым поиском
BeginRight:     POP HL
                ; переход к положительно кодированному правому пределу пары
                INC DE
                LD A, (DE)
                LD C, A
                ; подготовка счётчика перед первым DEC C, исходный ноль пропускает правый поиск
                INC C
                ; проверка исчерпания правого счётчика уменьшением к нулю
CheckRightCount:DEC C
                JR Z, @Text.HasActiveNeighbor.ReturnResult                      ; переход, если правый счётчик достиг нуля, вернуть отсутствие активного соседа

                ; переход к следующему значению без проверки выбранного элемента
                INC HL
                LD A, (HL)
                ; проверка старшего разряда кодированного правого значения
                OR A
                JP P, @Text.HasActiveNeighbor.TestRightValue                    ; переход, если bit7 снят, проверить исходное правое значение

                ; декодирование правого значения инверсией
                CPL
                ; проверка активности правого значения после декодирования
TestRightValue: OR A
                JR Z, @Text.HasActiveNeighbor.CheckRightCount                   ; переход, если правый сосед неактивен, продолжить поиск вперёд

                ; выбор результата 0 без изменения флагов последней проверки
ReturnResult:   LD DE, #0000
                RET Z                                                           ; выход, если оба диапазона не содержат активных соседей, DE содержит 0

                ; выбор результата 1 при найденном активном соседе
                INC DE
                RET

                endmodule
                endmodule
