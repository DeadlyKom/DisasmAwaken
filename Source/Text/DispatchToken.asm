; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [ScriptLanguage.md](../../Docs/ScriptLanguage.md)
; -----------------------------------------
; Поиск токена и косвенная передача управления на адрес из таблицы
; исходная запись 5, файловые смещения #07DA..#07E2
; In:
;   HL - адрес за одной FScriptToken до первой записи, BC - B записей, AF - A искомый символ
; Out:
;   хвостовой вход в найденный обработчик через HL, A содержит младший байт адреса обработчика
; Corrupt:
;   HL, DE, BC, AF, дополнительные эффекты определяются выбранным обработчиком
; Note:
;   до входа обработчика DE равен размеру FScriptToken, C сохраняется, B содержит остаток поиска с найденной записью
;   при отсутствии символа FindToken передаёт управление SkipLine, вызов обработчика не выполняется
;   сам диспетчер не меняет альтернативные и индексные регистры на успешном пути
; -----------------------------------------
                ; поиск записи символа перед хвостовой передачей управления её обработчику
Entry:          CALL @Text.FindToken.Entry
                INC HL
                LD A, (HL)
                INC HL
                LD H, (HL)
                LD L, A
                JP (HL)

                endmodule
                endmodule
