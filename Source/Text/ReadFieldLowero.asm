                module Text
                module ReadFieldLowero
                ; Документация [Text](../../Docs/FunctionDetails/Text.md)
                ; Подробный разбор [композиция ReadEquipmentQuantity и PushExpressionWord](../../Docs/ExpressionPushes.md)
                ; -----------------------------------------
                ; Получение результата через ReadEquipmentQuantity и запись слова в стек выражений
                ; исходная запись 5, файловые смещения #01C2..#01C7
                ; In:
                ;   HL' - адрес следующих двух доступных для записи байтов стека выражений, без перекрытия текущего кода и CPU-стека
                ;   выполняется входной договор ReadEquipmentQuantity, для обычного результата допустим корректный суффикс
                ;   читатель сохраняет альтернативный HL до записи результата, итоговый адрес остаётся доступным для двух байтов
                ; Out:
                ;   HL, DE, BC и AF по выходному договору ReadEquipmentQuantity, DE дополнительно записан в стек выражений
                ;   HL' увеличен на два относительно исходной позиции, DE' содержит записанный результат
                ;   BC' и AF' по договору читателя, IX и IY также по его договору, I и IFF сохраняются
                ;   SP обычного возврата равен входному SP+2, слово записано младшим байтом первым
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC' только B, AF' по пути читателя, IX, R, два байта выражения, DefaultTarget, временный CPU-стек и эффекты банкового s с операндом Limit
                ; Note:
                ;   суффиксы s и n отдельно проверены полным исполнением, s пишет Limit и банковое состояние, n сохраняет собственные BC и F поиска
                ;   на прямом пути читатель декодирует байт, затем словный писатель сохраняет количество без нового пересчёта F
                ;   собственный CALL и PUSH DE писателя повторно используют два байта ниже входного SP, исходный возврат сохраняется
                ;   DefaultTarget и прочие эффекты дочернего читателя сохраняются, составной прямой прогон не доказывает суффиксы s и n
                ;   CALL читателя получает собственный возврат, затем JP PushExpressionWord использует исходный возврат обёртки
                ;   дополнительных арифметических преобразований и пересчёта F обёртка не выполняет
                ;   если читатель передаёт управление SkipLine вместо возврата, запись результата не достигается
                ; -----------------------------------------
                ; получение результата DE через ReadEquipmentQuantity с его исходными побочными эффектами
Entry:          CALL @Text.ReadEquipmentQuantity.Entry
                ; добавление слова DE через общий PushExpressionWord, новый CALL не создаётся
                JP @Text.PushExpressionWord.Entry

                endmodule
                endmodule
