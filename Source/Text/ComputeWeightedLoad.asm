                module Text
                module ComputeWeightedLoad
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [формула суммы, коды масштаба, инвертируемые веса и три операнда](../../Docs/WeightedLoad.md)
; -----------------------------------------
; Байтовая взвешенная сумма трёх таблиц с добавлением выбранной строки
; исходная запись 5, файловые смещения #086F..#08FF
; In:
;   HL - полный шестнадцатибитный индекс строки, к которой прибавляется единица до масштабирования
;   таблицы #94FA, #9852, #95F1, #988E, #9633, #98F6 и выбор #984A доступны
;   LANG в текущем банке доступен для записи трёх самомодифицируемых операндов
; Out:
;   HL - #964F при #984A=#FF, иначе #9829+((ROL8(#984A,2)+#984A) AND #FF)
;   DE - #9904 при #984A=#FF, иначе байтовое смещение дополнительной записи с нулевым D
;   BC - B=0, C сумма трёх таблиц по модулю 256 до дополнительного слагаемого
;   AF - A сумма с дополнительным слагаемым по модулю 256, F от последнего ADD A,C
;   HL', DE', BC', IX, IY, I и IFF сохранены, SP восстановлен
;   AF' - A'=C, F' от последнего ADD A,C третьего цикла до дополнительного слагаемого
;   SelectedRow, FirstWeight и SecondWeight содержат последние записанные операнды
; Corrupt:
;   HL, DE, BC, AF, AF'
; Note:
;   индекс не обрезается до байта, адрес выбранной строки равен (#9852+2*HL) AND #FFFF
;   прибавление выбранной строки происходит только при совпадении адреса с одной из 30 строк
;   каждое накопление байтовое, насыщения и ошибки переполнения нет
;   веса #80..#FF инвертируются побитово, это не абсолютное значение знакового байта
;   игровые единицы суммы и полный смысл второго и третьего наборов пока не доказаны
;   код масштаба 0 и #81..#FF оставляет количество, 1 делит его на 16, 2..#80 даёт ноль
; -----------------------------------------
                ; расчёт полного адреса выбранной строки без обрезания входного HL до байта
Entry:          ADD HL, HL
                LD DE, #9852
                ADD HL, DE
                ; обновление операнда SelectedRow, совпавшая строка получает дополнительную единицу
                LD (@WeightedLoadState.SelectedRow), HL
                ; выбор 30 кодов масштаба и обнуление байтового накопителя
                LD HL, #94FA
                LD A, #1E
                LD C, #00
                ; сохранение счётчика строк в альтернативном AF на время расчёта слагаемого
CargoRow:       EX AF, AF'
                LD A, (DE)
                ; удаление старшего маркера количества до проверки выбранной строки
                AND #7F
                PUSH HL
                ; чтение самомодифицированного адреса выбранной строки
                LD HL, #0000
                ; сброс Carry перед сравнением полного адреса строки с SelectedRow
                OR A
                SBC HL, DE
                POP HL
                JR NZ, @Text.ComputeWeightedLoad.ScaleCargo                     ; переход, если адрес строки отличается от выбранного, не прибавлять единицу

                ; расчёт выбранного количества с дополнительной единицей, 127 превращается в 128
                INC A
                ; переход к следующей двухбайтовой записи количества и чтение кода масштаба
ScaleCargo:     INC DE
                INC DE
                LD B, (HL)
                INC HL
                ; проверка кода масштаба через знаковый результат вычета единицы
                DEC B
                JP M, @Text.ComputeWeightedLoad.AddCargo                        ; переход, если код равен 0 либо #81..#FF, добавить количество без деления

                ; расчёт целой шестнадцатой части количества через четыре вращения и AND #0F
                RRCA
                RRCA
                RRCA
                RRCA
                AND #0F
                ; проверка кода 1, для него сохраняется частное от деления на 16
                DEC B
                JP M, @Text.ComputeWeightedLoad.AddCargo                        ; переход, если код масштаба равен 1, добавить шестнадцатую часть количества

                ; обнуление вклада при коде масштаба 2..#80
                XOR A
                ; накопление первого набора с оборачиванием до байта
AddCargo:       ADD A, C
                LD C, A
                EX AF, AF'
                ; проверка числа оставшихся строк первого набора
                DEC A
                JP NZ, @Text.ComputeWeightedLoad.CargoRow                       ; переход, если обработаны не все 30 строк первого набора

                ; выбор 30 байтовых множителей с шагом два и 30 последовательных кодированных весов
                LD HL, #95F1
                LD DE, #988E
                LD A, #1E
WeightRow:      EX AF, AF'
                LD A, (DE)
                INC DE
                ; проверка старшего разряда кодированного веса
                OR A
                JP P, @Text.ComputeWeightedLoad.SetWeight                       ; переход, если bit7 веса снят, использовать исходный байт

                ; преобразование веса с установленным bit7 побитовой инверсией, #FF становится 0
                CPL
                ; обновление операнда FirstWeight для повторных сложений
SetWeight:      LD (@WeightedLoadState.FirstWeight), A
                LD B, (HL)
                INC HL
                INC HL
                ; создание нулевого промежуточного произведения
                XOR A
                ; расчёт произведения повторными сложениями по модулю 256, B=0 даёт 256 шагов и тот же ноль
Multiply:       ADD A, #00
                DJNZ @Text.ComputeWeightedLoad.Multiply

                ; накопление взвешенного вклада второго набора
                ADD A, C
                LD C, A
                EX AF, AF'
                ; проверка числа оставшихся весов второго набора
                DEC A
                JP NZ, @Text.ComputeWeightedLoad.WeightRow                      ; переход, если обработаны не все 30 весов второго набора

                ; выбор 14 множителей с шагом два и 14 последовательных весов третьего набора
                LD HL, #9633
                LD DE, #98F6
                LD A, #0E
SecondRow:      EX AF, AF'
                LD A, (DE)
                INC DE
                ; проверка старшего разряда кодированного веса третьего набора
                OR A
                JP P, @Text.ComputeWeightedLoad.SetSecond                       ; переход, если bit7 веса снят, использовать исходный байт

                ; преобразование веса третьего набора через инверсию
                CPL
                ; обновление операнда SecondWeight перед третьим циклом умножения
SetSecond:      LD (@WeightedLoadState.SecondWeight), A
                LD B, (HL)
                INC HL
                INC HL
                ; создание нулевого промежуточного произведения третьего набора
                XOR A
                ; расчёт произведения третьего набора повторными сложениями
MultiplySecond: ADD A, #00
                DJNZ @Text.ComputeWeightedLoad.MultiplySecond

                ; накопление взвешенного вклада третьего набора
                ADD A, C
                LD C, A
                EX AF, AF'
                ; проверка числа оставшихся строк третьего набора
                DEC A
                JP NZ, @Text.ComputeWeightedLoad.SecondRow                      ; переход, если обработаны не все 14 строк третьего набора

                ; чтение кода дополнительной записи, #FF означает отсутствие слагаемого
                LD A, (#984A)
                INC A
                JR Z, @Text.ComputeWeightedLoad.AddOption                       ; переход, если код дополнительной записи равен #FF, прибавить ноль

                ; восстановление исходного кода после проверки #FF
                DEC A
                LD E, A
                ; расчёт ROL8(код,2), переносимые старшие разряды сохраняются в младших
                RLCA
                RLCA
                ; расчёт байтового смещения как ROL8(код,2)+код, это не общее умножение на пять
                ADD A, E
                LD E, A
                LD D, #00
                LD HL, #9829
                ; расчёт адреса дополнительного байта относительно #9829
                ADD HL, DE
                LD A, (HL)
                ; расчёт окончательной байтовой суммы с дополнительным слагаемым
AddOption:      ADD A, C
                RET

                endmodule
                endmodule
