                module Text
                module NextCommand
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [команды, стек, CR и условные блоки](../../Docs/ScriptControl.md)
; -----------------------------------------
; Восстановление стека сценария, чтение команды и выбор обработчика
; исходная запись 5, файловые смещения #000C..#001A
; In:
;   BC - C сохраняемый контекст, IX у следующего символа сценария
;   ScriptRuntimeState.SavedSP содержит доступный стек с возвратом, LANG выбран
;   при пропуске строки впереди существует CR, при команде действует договор её обработчика
; Out:
;   SP немедленно заменяется SavedSP, временные рамки предыдущей команды отбрасываются
;   NUL не потребляется, возврат с A=0, F=44, SP=SavedSP+2 и сохранёнными остальными парами
;   прочий первый байт потреблён, пробел передаёт управление SkipLine.Entry
;   CR передаёт управление SkipLine.AfterCR, прочий байт ищется среди 15 FScriptToken
;   при найденной команде HL=обработчик, DE=3, B=остаток с найденной записью, C сохранён
;   при совпадении A=младший байт обработчика, F от CP символа с собой, SP=SavedSP
;   неизвестный символ передаёт SkipLine.Entry с A=символ, HL=последняя запись, DE=3, B=0
;   при неизвестном символе F от последнего CP, SP=SavedSP-2 с возвратом FindToken на вершине
;   альтернативные регистры, IY, I и IFF сохранены до получателя управления
; Corrupt:
;   HL, DE, BC только B на поиске, AF, IX, SP
; Note:
;   ReadCommand сохраняет текущий SP, это внутренний вход после уже восстановленного стека
;   здесь описан выход до обработчика, SkipLine либо возврата, эффекты команд задаются отдельно
;   пробел означает пропуск остатка строки, а не обычный игнорируемый разделитель
; -----------------------------------------
                ; восстановление стека сценария с отбрасыванием временных возвратов команды
Entry:          LD SP, (@ScriptRuntimeState.SavedSP)
                ; чтение очередного символа без продвижения до проверки завершения
ReadCommand:    LD A, (IX + @ScriptConst.Cursor)
                ; проверка нулевого терминатора сценария
                OR A
                RET Z                                                           ; выход, если прочитан нулевой терминатор, IX остаётся на нём

                INC IX
                ; проверка признака пропуска остатка строки
                CP #20
                JR NZ, @Text.SkipLine.DispatchCommand                           ; переход, если символ не пробел, проверить CR либо искать команду

                ; JP @Text.SkipLine.Entry, продолжение в SkipLine.asm

                endmodule
                endmodule
