                module Text
                module RecomputeTonnage
; Документация [Text](../../Docs/FunctionDetails/Text.md)
; Подробный разбор [входной HL команды T и сохранение взвешенной суммы](../../Docs/TonnageCommand.md)
; -----------------------------------------
; Запись байтовой взвешенной суммы в поле загрузки и продолжение сценария
; исходная запись 5, файловые смещения #00DB..#00E6
; In:
;   HL - индекс для ComputeWeightedLoad, при обычном выборе команды T содержит адрес обработчика C0DB
;   доступны таблицы и изменяемые операнды по договору ComputeWeightedLoad, LANG выбран
; Out:
;   хвостовой вход NextCommand, байт по 9850 получает вычисленный A
;   HL, DE, BC, AF, AF альтернативного набора и три изменённых операнда по ComputeWeightedLoad
;   HL, DE и BC альтернативного набора, IX, IY, I и IFF сохранены, SP перед NextCommand равен входному
; Corrupt:
;   HL, DE, BC, AF, AF'
; Note:
;   начальный LD DE,67AE не задаёт таблицу, ComputeWeightedLoad заменяет DE до первого использования
;   команда не загружает индекс из текущего выбора, использует исходный полный HL
;   нормальный диспетчер передаёт HL=C0DB, выбранный адрес 9852+2*C0DB равен 1A08 по модулю 65536
;   1A08 не совпадает с 30 строками 9852..988C, поэтому обычная команда не добавляет единицу ни одной строке
;   при прямом входе с иным HL прибавление выбранной строки остаётся действующим
;   сумма байтовая с оборачиванием, игровые единицы трёх таблиц полностью не доказаны
; -----------------------------------------
                ; загрузка исходного DE, который вызываемый ComputeWeightedLoad перезаписывает до использования
Entry:          LD DE, #67AE
                ; расчёт взвешенной суммы по входному HL, обычный диспетчер оставляет здесь адрес команды
                CALL @Text.ComputeWeightedLoad.Entry
                ; сохранение байтовой суммы, переносы выше восьмого разряда не сохраняются
                LD (#9850), A
                JP @Text.NextCommand.Entry

                endmodule
                endmodule
