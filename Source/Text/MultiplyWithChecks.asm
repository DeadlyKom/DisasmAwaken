;   без выявленного переноса DE результат исходной рекурсии по модулю 65536, HL исходное DE, BC=0
;   при выявленном переносе DE=FFFF, HL обёрнутое удвоенное значение, BC сдвинут на число обработанных битов
;   AF - A сохранён, при отказе F от последнего ADD HL,HL с Carry=1
;   без отказа F от последнего ADD HL,DE при младшем бите 1, иначе от последнего RL B
;   альтернативные и индексные регистры, I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF только F
; Note:
;   умножение обрабатывает биты BC от старшего к младшему и разрушает множитель
;   после каждого из первых 15 битов накопитель удваивается, Carry этого удвоения проверяется
;   Carry прибавления DE отдельно не проверяется, последнее прибавление вообще не имеет следующего удвоения
;   при пропущенном переполнении результат может быть меньше FFFF, это не полное насыщающее умножение
;   нулевой результат и FFFF сами по себе не определяют факт отказа, точные флаги зависят от пути
; -----------------------------------------
