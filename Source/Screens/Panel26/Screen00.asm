                module Screen00
                ; Формат [сохранённый конец и общий поток](../../../Docs/PackedResourcePrefix.md)
; -----------------------------------------
; упакованный экран 0, исходное смещение #0000
; 6144 байта пикселей и 768 байт атрибутов после распаковки
; хвост сохраняет физический секторный формат исходного диска
; -----------------------------------------
Header:         FPackedHeader {                                                 ; исходный заголовок ресурса
                #5248,                                                          ; Signature, сигнатура HR
                #1B00,                                                          ; UnpackedSize, размер экрана с атрибутами
                #059C                                                           ; PackedSize, длина файла вместе с заголовком
                }
FinalBytes:     FPackedFinalBytes {                                             ; исходные последние шесть байтов результата
                #0E0E,                                                          ; BytesMinus6, пара финальных байтов результата
                #0E0E,                                                          ; BytesMinus4, пара финальных байтов результата
                #0E0E                                                           ; BytesMinus2, пара финальных байтов результата
                }
Bitstream:      incbin "Screen00.Bitstream.bin"                                 ; общий поток битовых слов и литералов после префикса
Tail:           incbin "Screen00.Tail.bin"                                      ; байты до конца выделенных секторов
                assert $ - Header == #0600
                endmodule
                endmodule
