                module Screen15
                ; Формат [сохранённый конец и общий поток](../../../Docs/PackedResourcePrefix.md)
; -----------------------------------------
; упакованный экран 15, исходное смещение #DB00
; 6144 байта пикселей и 768 байт атрибутов после распаковки
; хвост сохраняет физический секторный формат исходного диска
; -----------------------------------------
Header:         FPackedHeader {                                                 ; исходный заголовок ресурса
                #5248,                                                          ; Signature, сигнатура HR
                #1B00,                                                          ; UnpackedSize, размер экрана с атрибутами
                #134C                                                           ; PackedSize, длина файла вместе с заголовком
                }
FinalBytes:     FPackedFinalBytes {                                             ; исходные последние шесть байтов результата
                #7179,                                                          ; BytesMinus6, пара финальных байтов результата
                #7171,                                                          ; BytesMinus4, пара финальных байтов результата
                #7171                                                           ; BytesMinus2, пара финальных байтов результата
                }
Bitstream:      incbin "Screen15.Bitstream.bin"                                 ; общий поток битовых слов и литералов после префикса
Tail:           incbin "Screen15.Tail.bin"                                      ; байты до конца выделенных секторов
                assert $ - Header == #1400
                endmodule
