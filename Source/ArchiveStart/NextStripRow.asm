                module NextStripRow
                ; Документация [меню BANK](../../Docs/BankStripArchiveConsumer.md)
                ; -----------------------------------------
                ; вычисление следующей строки экранной полосы в раскладке ULA
                ; In:
                ;   DE - адрес байта в текущей строке
                ; Out:
                ;   DE - адрес того же столбца следующей строки
                ; Corrupt:
                ;   DE, AF
                ; Note:
                ;   нижняя граница экрана не проверяется
                ; -----------------------------------------
                ; проверка границы восьми строк знакоместного ряда
Entry:          INC D
                LD A, D
                AND #07
                RET NZ                                                          ; выход, если следующий адрес остаётся в том же ряду

                ; переход к следующему ряду
                LD A, E
                ADD A, #20
                LD E, A
                RET C                                                           ; выход, если перенос уже перевёл адрес в следующую треть

                ; компенсация старшего байта при переходе внутри одной трети
                LD A, D
                SUB #08
                LD D, A
                RET

                endmodule
                endmodule
