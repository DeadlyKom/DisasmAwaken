                module Map
                module DrawArcBothDown
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [входы, байтовые счётчики, общий кадр и границы моделей](../../Docs/ArcKernel.md)
; -----------------------------------------
; Сохранение AF, сброс рекурсии и проход двух краёв вниз
; исходная запись 7, файловые смещения #269D..#26A3
; In:
;   HL, DE, BC задают адреса и маски по договору RasterizeArcEdges.BothEdges
;   E' и C' задают начальные байтовые счётчики рекурсии, для обычного полного края E'=0 и C'=-Radius modulo 256
;   AF' не участвует в выборе симметричных шагов
;   обычный адрес возврата лежит по SP, остальная подготовка границ и режима соответствует RasterizeArcEdges
; Out:
;   AF целиком сохранён, RasterDown=1, перед ядром HL'=0, D'=0, B'=FF, C' и E' сохранены
;   исполнен RasterizeArcEdges.BothEdges с кадром SavedAF и прежним адресом возврата
;   bitmap, RasterStack, основные и альтернативные общие пары изменены по договору ядра
;   AF' целиком сохранён
;   IX, IY, I и IFF сами инструкции сохраняют, SP после обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, HL', DE', BC', bitmap, RasterStack, RasterDown
; Note:
;   PUSH AF формирует внешний кадр до вызова сброса, ResetRasterDown не добавляет постоянного вложенного возврата
;   последний JP передаёт прежний адрес возврата ядру, возврат выполняется через POP AF и RET либо RasterStack
;   геометрические ограничения проверенных профилей перечислены в [разборе рекурсии](../../Docs/ArcRecurrence.md)
; -----------------------------------------
                ; сохранение полного AF перед растровым проходом двух краёв вниз
Entry:          PUSH AF
                ; сброс error и старших байтов счётчиков, начальные C' и E' сохраняются
                CALL @Map.ResetRasterDown.Entry
                ; продолжение нужного входа ядра с одним внешним кадром сохранённого AF
                JP @Map.RasterizeArcEdges.BothEdges

                endmodule
                endmodule
