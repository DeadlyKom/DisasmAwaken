                module Map
                module SelectMapPoint
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [перепаковка координат, половина размеров и исходные особенности отсечения](../../Docs/MapViewCenter.md)
; -----------------------------------------
; Запись выбранного ключа, поиск его пятого байта и центрирование карты
; исходная запись 7, файловые смещения #0325..#0332
; In:
;   HL - второе слово выбираемого ключа, DE - первое слово, KARTA выбран
;   действуют договоры ReadStoredMapVariant и CenterMapView, достижим конец первого списка либо совпадение
; Out:
;   MapSelection.FirstWord получает исходный DE, SecondWord получает исходный HL
;   MapSelection.Variant получает пятый байт первой совпавшей записи либо ноль по ReadStoredMapVariant
;   после поиска исходные HL и DE восстановлены со стека, затем выполняется последовательный CenterMapView
;   x=256*входной E+входной L, y=256*входной D+входной H
;   к каждой координате прибавлено FF00 OR ((0-floor(размер/2)) AND FF), результат обёрнут до 16 бит
;   если Sign соответствующего обёрнутого результата установлен, координата заменена нулём
;   HL упакован как старший Y и старший X, DE как младший Y и младший X
;   OriginLow получает DE, OriginHigh получает HL, размеры Width и Height сохранены
;   BC=FF00 OR ((0-floor(Height/2)) AND FF), A равен младшему байту окончательного Y
;   F от последнего ADC для Y до отсечения, замена HL на 0 флагов не меняет
;   все альтернативные регистры, IY, I и IFF сохранены, SP обычного возврата равен входному SP+2
;   IX у найденной записи либо ограничителя по ReadStoredMapVariant, прочие побочные записи поиска сохранены
; Corrupt:
;   HL, DE, BC, AF, IX
; Note:
;   два PUSH и два POP защищают исходный ключ от рабочих регистров поиска
;   последовательный вход CenterMapView не создаёт нового адреса возврата
;   окончательный F сообщает расчёт Y, его нельзя использовать как результат поиска сохранённой точки
; -----------------------------------------
                ; сохранение первого и второго слов нового выбора в исходных полях MapSelection
Entry:          LD (@MapSelection.FirstWord), DE
                LD (@MapSelection.SecondWord), HL
                ; сохранение исходного ключа вокруг поиска пятого байта в списке точек
                PUSH HL
                PUSH DE
                ; поиск и запись порядкового варианта выбранного пункта
                CALL @Map.ReadStoredMapVariant.Entry
                ; возврат исходных координатных слов перед последовательным центрированием
                POP DE
                POP HL
                ; JP @Map.CenterMapView.Entry, продолжение в CenterMapView.asm

                endmodule
                endmodule
