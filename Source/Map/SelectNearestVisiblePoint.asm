                module Map
                module SelectNearestVisiblePoint
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [границы указателя, старый выбор при пустом списке и восстановление ключа](../../Docs/NearestVisiblePoint.md)
; -----------------------------------------
; Выбор первой ближайшей видимой точки карты и чтение её сохранённого варианта
; исходная запись 7, файловые смещения #038C..#040E
; In:
;   HL - H пиксельный верх области, L пиксельный левый край, StationState.PointerXY содержит пиксельную позицию указателя
;   MapViewState и MapSectorTables подготовлены, действуют требования BuildVisibleMapPoints, включая HALT и временный SP
;   первый сохранённый список имеет достижимое совпадение ключа либо отрицательный не-FF ограничитель по договору ReadStoredMapVariant
;   для обычного выбора видимый список после фильтра не пуст, при пустом списке используются прежние байты SelectedPoint
; Out:
;   BuildVisibleMapPoints выполнен до проверки положения указателя, Minimum по C3D0 предварительно сброшен в FFFF
;   при выходе указателя за область Carry=1, HL восстановлен, MapSelection сохранён, выбранный указатель SelectedPoint не меняется
;   проверки области выполняются в порядке Y ниже начала, Y выше h-1, X левее начала, X правее w-1, вычитания размеров оборачиваются до байта
;   при внутреннем указателе dx=PointerX-left, dy=PointerY-top, найден первый минимум суммы квадратов знаковых байтовых разностей от dx,dy
;   Minimum получает квадрат расстояния, SelectedPoint по C3E8 получает адрес пары в F6, при пустом списке Minimum=FFFF и SelectedPoint сохранён
;   по параллельной ссылке F7 прочитано исходное слово секторной таблицы и записано в MapSelection.SecondWord
;   MapSelection.FirstWord равен OriginHigh с байтовым увеличением X для F3/F5 и Y для F4/F5
;   далее исполнение продолжается в ReadStoredMapVariant без нового CALL, его обычный RET возвращает вызывающему этой процедуры
;   после этого A и Variant, HL, DE, BC, AF и IX соответствуют ReadStoredMapVariant, Carry=0, значение Variant=0 само по себе не означает отсутствие
;   HL', DE', AF' рабочие, B'=0, C'=(1-h)&FF, IY и I сама процедура сохраняет, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX на ветви выбора, рабочие страницы и изменяемые операнды
;   SP временно изменяется вызываемым фильтром
; Note:
;   при раннем выходе A, BC и F относятся к первой проваленной проверке, DE остаётся результатом BuildVisibleMapPoints, IX сохранён
;   при w=0 либо h=0 сравнение соответствующей верхней границы использует FF, пустая геометрическая область не предполагается
;   если список пуст, прежняя SelectedPoint читается без проверки, по исходному нулю она ведёт в область 0100
;   для старой ссылки вне F2/F3/F4 код увеличивает оба байта OriginHigh, это фактическая ветвь по умолчанию, не доказательство корректного сектора
;   нулевой ограничитель F7 и оборачивание фильтра могут создать пустой список при 128, 256, 384 или 512 принятых точках
;   IFF меняется только возможным внешним обработчиком, пробуждение и ISR не проверялись нативно
;   вход восстановлен по [действиям интерфейса](../../Docs/StationEventActions.md), [фильтр](../../Docs/VisibleMapPoints.md) проверен отдельно
; -----------------------------------------
                ; сохранение пиксельного начала области на время построения списка видимых точек
Entry:          PUSH HL
                ; сброс минимального квадрата расстояния без сброса прежнего указателя выбранной точки
                LD HL, @MapMathConst.InitialMinimum
                LD (@MapVisiblePatch.Minimum), HL
                ; обновление страниц координат и ссылок настоящим фильтром четырёх секторов
                CALL @Map.BuildVisibleMapPoints.Entry
                ; чтение текущих пиксельных X,Y и восстановление начала области
                LD BC, (@StationState.PointerXY)
                POP HL
                ; расчёт относительного Y указателя с проверкой займа
                LD A, B
                SUB H
                LD B, A
                RET C                                                           ; выход, если указатель находится выше пиксельного начала области

                ; расчёт последнего допустимого относительного Y как (h-1)&FF
                LD A, (@MapViewState.Height)
                DEC A
                ; проверка относительного Y по последней разрешённой строке
                CP B
                RET C                                                           ; выход, если относительный Y больше (h-1)&FF

                ; расчёт относительного X указателя с проверкой займа
                LD A, C
                SUB L
                LD C, A
                RET C                                                           ; выход, если указатель находится левее пиксельного начала области

                ; расчёт последнего допустимого относительного X как (w-1)&FF
                LD A, (@MapViewState.Width)
                DEC A
                ; проверка относительного X по последней разрешённой колонке
                CP C
                RET C                                                           ; выход, если относительный X больше (w-1)&FF

                ; выбор первой относительной пары после успешной проверки положения указателя
                LD HL, @MapVisibleState.Points
                ; поиск старшего байта параллельной ссылки для проверки конца списка
NextPoint:      INC H
                INC L
                LD A, (HL)
                AND A
                JP Z, @Map.SelectNearestVisiblePoint.ReadSelection              ; переход, если старший байт ссылки нулевой, прочитать сохранённый выбор

                ; возврат к X текущей относительной пары
                DEC L
                DEC H
                LD A, (HL)
                ; расчёт оборачиваемой разности X точки и относительного X указателя
                SUB C
                JP P, @Map.SelectNearestVisiblePoint.AbsoluteX                  ; переход, если байтовая разность X неотрицательна, модуль уже получен

                ; расчёт модуля отрицательной байтовой разности X
                NEG
                ; сохранение модуля X в A' для второго квадрата
AbsoluteX:      EX AF, AF'
                INC L
                LD A, (HL)
                ; расчёт оборачиваемой разности Y точки и относительного Y указателя
                SUB B
                JP P, @Map.SelectNearestVisiblePoint.Measure                    ; переход, если байтовая разность Y неотрицательна, модуль уже получен

                ; расчёт модуля отрицательной байтовой разности Y
                NEG
                ; сохранение указателя текущей пары и целевых координат в альтернативных парах
Measure:        EXX
                ; расчёт суммы квадратов модулей Y и X настоящим SumSquares8
                CALL @Map.SumSquares8.Entry
                ; чтение изменяемого минимума текущего поиска
                LD DE, @MapMathConst.InitialMinimum
                ; сброс переноса перед строгим беззнаковым сравнением расстояния и минимума
                OR A
                ; расчёт разности квадрата расстояния и текущего минимума
                SBC HL, DE
                JR NC, @Map.SelectNearestVisiblePoint.AdvancePoint              ; переход, если расстояние не меньше прежнего минимума, сохранить первый ближайший выбор

                ; восстановление полного нового квадрата расстояния обратным прибавлением
                ADD HL, DE
                ; обновление минимума в операнде следующего сравнения
                LD (@MapVisiblePatch.Minimum), HL
                ; выбор указателя на Y текущей пары для сохранения адреса её X
                EXX
                ; расчёт адреса начала пары и сохранение SelectedPoint в операнде заключительного LD HL,nn
                DEC L
                LD (@MapVisiblePatch.SelectedPoint), HL
                INC L
                EXX
                ; возврат к просмотру списка и переход к следующей двухбайтовой паре
AdvancePoint:   EXX
                INC L
                JP @Map.SelectNearestVisiblePoint.NextPoint

                ; чтение последнего выбранного адреса пары, при пустом списке здесь остаётся прежний указатель
ReadSelection:  LD HL, #0000
                ; поиск соответствующей ссылки в параллельной странице F7
                INC H
                LD A, (HL)
                INC L
                LD H, (HL)
                LD L, A
                ; чтение исходной пары секторной таблицы по выбранной ссылке
                LD E, (HL)
                INC L
                LD D, (HL)
                ; обновление младшего слова выбранного координатного ключа
                LD (@MapSelection.SecondWord), DE
                ; чтение старших координат начала сектора для реконструкции FirstWord
                LD DE, (@MapViewState.OriginHigh)
                LD A, H
                ; проверка принадлежности выбранного исходного слова странице Cell00
                CP #F2
                JR Z, @Map.SelectNearestVisiblePoint.StoreSector                ; переход, если ссылка ведёт в F2, старшие координаты сектора не менять

                ; расчёт старшего X соседнего сектора отдельным байтовым увеличением
                INC E
                ; проверка принадлежности выбранного исходного слова странице Cell10
                CP #F3
                JR Z, @Map.SelectNearestVisiblePoint.StoreSector                ; переход, если ссылка ведёт в F3, сохранить увеличенный X и прежний Y

                ; восстановление прежнего X и расчёт старшего Y соседнего сектора
                DEC E
                INC D
                ; проверка принадлежности выбранного исходного слова странице Cell01
                CP #F4
                JR Z, @Map.SelectNearestVisiblePoint.StoreSector                ; переход, если ссылка ведёт в F4, сохранить прежний X и увеличенный Y

                ; расчёт увеличенного X вместе с Y для F5 либо любой иной старшей страницы ссылки
                INC E
                ; обновление старшего слова ключа перед последовательным входом ReadStoredMapVariant
StoreSector:    LD (@MapSelection.FirstWord), DE
                ; JP @Map.ReadStoredMapVariant.Entry, продолжение в ReadStoredMapVariant.asm

                endmodule
                endmodule
