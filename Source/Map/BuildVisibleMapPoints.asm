                module Map
                module BuildVisibleMapPoints
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [четыре знаковых направления, стековый просмотр и оборачивание страниц](../../Docs/VisibleMapPoints.md)
; -----------------------------------------
; Фильтрация четырёх секторных таблиц в пары относительных координат и ссылки на исходные слова
; исходная запись 7, файловые смещения #04E5..#05E7
; In:
;   MapViewState.OriginLow содержит начало ox,oy, Width и Height содержат байтовые размеры w,h
;   MapSectorTables.Cell00, Cell10, Cell01, Cell11 содержат по 128 доступных слов, младший байт X, старший Y
;   MapVisibleState.Points и Pointers являются доступными страницами F6 и F7, KARTA выбран и доступен для самомодификации
;   Entry начинает HALT, источник пробуждения и сохранение регистров обработчиком обеспечиваются окружением
;   после HALT входной стек содержит обычный адрес возврата, использование SP как указателя таблиц должно быть допустимо
; Out:
;   таблицы просмотрены в порядке Cell00, Cell10, Cell01, Cell11, в каждой ровно 128 слов
;   для прямой оси d=raw-origin принимается при отсутствии займа и d<size
;   для обратной оси d=origin-raw принимается при отсутствии займа и d>=(1-size)&FF, выходной байт равен -d modulo 256
;   оба условия осей обязательны, принятые пары X,Y записаны в Points, адреса исходных слов в Pointers
;   пусть K число принятых пар, j=(2*K)&FF, записи оборачиваются по младшему адресу через каждые 128 пар
;   Pointers[(j+1)&FF]=0 ограничивает список нулевым старшим байтом ссылки, соседний младший байт не очищается
;   HL=F700+j+1, DE последний адрес принятого исходного слова, при K=0 входной DE сохранён, BC сохранён
;   AF - A рабочий, F=((j+1)&A8) OR 1, AF' рабочий и не является результатом фильтра
;   HL' последнее прочитанное слово Cell11, DE'=OriginLow, B'=0, C'=(1-h)&FF
;   IX, IY и I сохранены, SP восстановлен перед RET и после обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE при принятой паре, AF, HL', DE', BC', AF', страницы F6/F7 и восемь байтов операндов
;   SP временно указывает в F200..F600
; Note:
;   IFF сама процедура не меняет, влияние обработчика пробуждения и дальнейших IRQ не входит в проверенную модель
;   при K>=128 нет проверки вместимости, K кратное 128 ставит ограничитель в первую ссылку и даёт видимый пустой список
;   размеры 0 и 1 сохраняют фактические оборачиваемые пороги, обычная геометрическая интерпретация на них не распространяется
;   каждое принятое исходное слово имеет ссылку на собственную физическую ячейку секторной таблицы, не на копию координат
;   модель явно пропускает HALT как пробуждение и не исполняет ISR, исходная HALT в проекте сохранена
;   вход восстановлен по [действиям интерфейса](../../Docs/StationEventActions.md), ближайшая видимая запись выбирается SelectNearestVisiblePoint, её алгоритм описан отдельно
; -----------------------------------------
                ; ожидание события пробуждения перед использованием SP как указателя таблиц
Entry:          HALT
                ; сохранение исходного SP в операнде заключительного восстановления стека
                LD (@MapVisiblePatch.SavedStack), SP
                ; выбор начала страницы относительных пар и перенос выходного контекста в альтернативные пары
                LD HL, @MapVisibleState.Points
                EXX
                ; чтение упакованного начала видимой области ox,oy
                LD DE, (@MapViewState.OriginLow)
                ; обновление обоих прямых порогов ширины w
                LD A, (@MapViewState.Width)
                LD (@MapVisiblePatch.WidthFirst), A
                LD (@MapVisiblePatch.WidthSecond), A
                ; расчёт оборачиваемого обратного порога (1-w)&FF и обновление двух сравнений
                DEC A
                NEG
                LD (@MapVisiblePatch.InverseWidthB), A
                LD (@MapVisiblePatch.InverseWidthA), A
                ; чтение высоты h и обновление прямого порога Y
                LD A, (@MapViewState.Height)
                LD (@MapVisiblePatch.HeightPositive), A
                ; расчёт оборачиваемого обратного порога (1-h)&FF
                DEC A
                NEG
                LD (@MapVisiblePatch.HeightNegative), A
                ; подготовка счётчика 128 слов с предварительным DJNZ и прямого порога высоты в C
                LD BC, #8170
                ; выбор первой секторной таблицы через SP, POP последовательно читает её слова
                LD SP, @MapSectorTables.Cell00
Scan00:         DJNZ @Map.BuildVisibleMapPoints.Read00

                ; продолжение со следующей страницей после всех 128 слов Cell00
                JR @Map.BuildVisibleMapPoints.Begin10

                ; чтение очередной пары X,Y из исходной секторной таблицы через POP
Read00:         POP HL
                LD A, H
                ; расчёт Y-oy с проверкой полного байтового займа
                SUB D
                JP C, @Map.BuildVisibleMapPoints.Scan00                         ; переход, если разность Y дала заём, пропустить точку

                ; проверка прямого порога высоты h по Y
                CP C
                JP NC, @Map.BuildVisibleMapPoints.Scan00                        ; переход, если прямая разность Y не меньше h, пропустить точку

                EX AF, AF'
                LD A, L
                ; расчёт X-ox с проверкой полного байтового займа
                SUB E
                JP C, @Map.BuildVisibleMapPoints.Scan00                         ; переход, если разность X дала заём, пропустить точку

                ; проверка прямого порога ширины w по X
                CP #D0
                JP NC, @Map.BuildVisibleMapPoints.Scan00                        ; переход, если прямая разность X не меньше w, пропустить точку

                EXX
                ; сохранение относительного X в циклическом выходном массиве
                LD (HL), A
                INC L
                EX AF, AF'
                LD (HL), A
                EX DE, HL
                LD HL, #FFFE
                ; расчёт адреса принятого исходного слова как SP-2 для параллельного списка ссылок
                ADD HL, SP
                EX DE, HL
                INC H
                ; сохранение адреса исходной пары в параллельной странице, сначала старший байт ссылки
                LD (HL), D
                DEC L
                LD (HL), E
                INC L
                INC L
                DEC H
                EXX
                JP @Map.BuildVisibleMapPoints.Scan00

                ; сброс счётчика перед Cell10, прямой порог Y в C сохраняется
Begin10:        LD B, #81
Scan10:         DJNZ @Map.BuildVisibleMapPoints.Read10

                ; продолжение с нижней парой секторов после Cell10
                JR @Map.BuildVisibleMapPoints.Begin01

                ; чтение очередной пары X,Y из исходной секторной таблицы через POP
Read10:         POP HL
                LD A, H
                ; расчёт Y-oy с проверкой полного байтового займа
                SUB D
                JP C, @Map.BuildVisibleMapPoints.Scan10                         ; переход, если разность Y дала заём, пропустить точку

                ; проверка прямого порога высоты h по Y
                CP C
                JP NC, @Map.BuildVisibleMapPoints.Scan10                        ; переход, если прямая разность Y не меньше h, пропустить точку

                EX AF, AF'
                LD A, E
                ; расчёт ox-X с проверкой полного байтового займа
                SUB L
                JP C, @Map.BuildVisibleMapPoints.Scan10                         ; переход, если разность X дала заём, пропустить точку

                ; проверка обратного порога (1-w)&FF по X
                CP #31
                JP C, @Map.BuildVisibleMapPoints.Scan10                         ; переход, если обратная разность X меньше порога (1-w)&FF, пропустить точку

                EXX
                ; расчёт относительного X изменением знака принятой обратной разности
                NEG
                ; сохранение относительного X в циклическом выходном массиве
                LD (HL), A
                INC L
                EX AF, AF'
                LD (HL), A
                EX DE, HL
                LD HL, #FFFE
                ; расчёт адреса принятого исходного слова как SP-2 для параллельного списка ссылок
                ADD HL, SP
                EX DE, HL
                INC H
                ; сохранение адреса исходной пары в параллельной странице, сначала старший байт ссылки
                LD (HL), D
                DEC L
                LD (HL), E
                INC L
                INC L
                DEC H
                EXX
                JP @Map.BuildVisibleMapPoints.Scan10

                ; сброс счётчика и загрузка обратного порога Y для Cell01 и Cell11
Begin01:        LD BC, #8191
Scan01:         DJNZ @Map.BuildVisibleMapPoints.Read01

                ; продолжение со страницей Cell11 после Cell01
                JR @Map.BuildVisibleMapPoints.Begin11

                ; чтение очередной пары X,Y из исходной секторной таблицы через POP
Read01:         POP HL
                LD A, D
                ; расчёт oy-Y с проверкой полного байтового займа
                SUB H
                JP C, @Map.BuildVisibleMapPoints.Scan01                         ; переход, если разность Y дала заём, пропустить точку

                ; проверка обратного порога (1-h)&FF по Y
                CP C
                JP C, @Map.BuildVisibleMapPoints.Scan01                         ; переход, если обратная разность Y меньше порога (1-h)&FF, пропустить точку

                EX AF, AF'
                LD A, L
                ; расчёт X-ox с проверкой полного байтового займа
                SUB E
                JP C, @Map.BuildVisibleMapPoints.Scan01                         ; переход, если разность X дала заём, пропустить точку

                ; проверка прямого порога ширины w по X
                CP #D0
                JP NC, @Map.BuildVisibleMapPoints.Scan01                        ; переход, если прямая разность X не меньше w, пропустить точку

                EXX
                ; сохранение относительного X в циклическом выходном массиве
                LD (HL), A
                INC L
                EX AF, AF'
                ; расчёт относительного Y изменением знака принятой обратной разности
                NEG
                LD (HL), A
                EX DE, HL
                LD HL, #FFFE
                ; расчёт адреса принятого исходного слова как SP-2 для параллельного списка ссылок
                ADD HL, SP
                EX DE, HL
                INC H
                ; сохранение адреса исходной пары в параллельной странице, сначала старший байт ссылки
                LD (HL), D
                DEC L
                LD (HL), E
                INC L
                INC L
                DEC H
                EXX
                JP @Map.BuildVisibleMapPoints.Scan01

                ; сброс счётчика перед последними 128 словами Cell11
Begin11:        LD B, #81
Scan11:         DJNZ @Map.BuildVisibleMapPoints.Read11

                ; выбор выходного контекста после просмотра всех четырёх страниц
                EXX
                ; поиск старшего байта следующей ссылки в странице Pointers
                INC H
                INC L
                ; сохранение нулевого старшего байта ограничителя, младший байт остаётся прежним
                LD (HL), #00
                ; восстановление исходного SP из изменённого в начале операнда перед обычным RET
                LD SP, #0000
                RET

                ; чтение очередной пары X,Y из исходной секторной таблицы через POP
Read11:         POP HL
                LD A, D
                ; расчёт oy-Y с проверкой полного байтового займа
                SUB H
                JP C, @Map.BuildVisibleMapPoints.Scan11                         ; переход, если разность Y дала заём, пропустить точку

                ; проверка обратного порога (1-h)&FF по Y
                CP C
                JP C, @Map.BuildVisibleMapPoints.Scan11                         ; переход, если обратная разность Y меньше порога (1-h)&FF, пропустить точку

                EX AF, AF'
                LD A, E
                ; расчёт ox-X с проверкой полного байтового займа
                SUB L
                JP C, @Map.BuildVisibleMapPoints.Scan11                         ; переход, если разность X дала заём, пропустить точку

                ; проверка обратного порога (1-w)&FF по X
                CP #31
                JP C, @Map.BuildVisibleMapPoints.Scan11                         ; переход, если обратная разность X меньше порога (1-w)&FF, пропустить точку

                EXX
                ; расчёт относительного X изменением знака принятой обратной разности
                NEG
                ; сохранение относительного X в циклическом выходном массиве
                LD (HL), A
                INC L
                EX AF, AF'
                ; расчёт относительного Y изменением знака принятой обратной разности
                NEG
                LD (HL), A
                EX DE, HL
                LD HL, #FFFE
                ; расчёт адреса принятого исходного слова как SP-2 для параллельного списка ссылок
                ADD HL, SP
                EX DE, HL
                INC H
                ; сохранение адреса исходной пары в параллельной странице, сначала старший байт ссылки
                LD (HL), D
                DEC L
                LD (HL), E
                INC L
                INC L
                DEC H
                EXX
                JP @Map.BuildVisibleMapPoints.Scan11

                endmodule
