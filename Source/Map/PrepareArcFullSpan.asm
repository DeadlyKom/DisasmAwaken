                module Map
                module PrepareArcFullSpan
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [загрузка полей, точные крайние адреса и побочная запись LeftMask](../../Docs/ArcPreparation.md)
; -----------------------------------------
; Подготовка двух симметричных краёв дуги относительно CenterX
; исходная запись 7, файловые смещения #2208..#2227
; In:
;   MapArcState.RowY, CenterX, QuadrantCode и Radius содержат рабочие байты дуги
;   MapScreenTables построены для текущего окна, действуют требования обоих табличных помощников края
; Out:
;   левый X=(CenterX-Radius)&255, правый X=(CenterX+Radius)&255, общий Y=RowY
;   HL - адрес правого края, DE - D=Radius, E младший адрес левого края
;   BC - B=80 SHR(левый X&7), C=80 SHR(правый X&7)
;   AF - A=левая маска B, F=43 при правом X&7=7, иначе F=42
;   HL', D', B', AF', IX, IY, I и IFF сохранены, C'=(-Radius)&255, E'=0
;   MapState.LeftMask получает рассчитанную левую маску
;   пиксели и входные поля не меняются, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF, C', E'
; Note:
;   в отличие от однокраевых подготовок колонки обоих краёв берутся из рассчитанных координат
;   левый табличный помощник сохраняет Radius в D, поэтому правый X рассчитывается после него без перезагрузки Radius
;   последний JP передаёт обычный адрес возврата правому помощнику, новая инструкция CALL не добавляется
; -----------------------------------------
                ; загрузка общей строки и центра X двух симметричных краёв
Entry:          LD BC, (@MapArcState.RowY)
                LD DE, (@MapArcState.QuadrantCode)
                ; расчёт отрицательного радиуса для альтернативной рекуррентной пары
                LD A, D
                NEG
                ; обновление только C' и E', остальные альтернативные накопители сохраняются
                EXX
                LD C, A
                LD E, #00
                EXX
                ; расчёт левого X как CenterX-Radius с байтовым оборачиванием
                LD A, B
                SUB D
                ; поиск левого адреса и маски, Radius сохраняется в D
                CALL @Map.PrepareLeftRasterPoint.Entry
                ; повторный выбор общей строки для правого края
                LD A, (@MapArcState.RowY)
                LD C, A
                ; расчёт правого X как CenterX+Radius после подготовки левого края
                LD A, (@MapArcState.CenterX)
                ADD A, D
                ; продолжение в правом помощнике, его RET завершает исходный вызов
                JP @Map.PrepareRightRasterPoint.Entry

                endmodule
                endmodule
