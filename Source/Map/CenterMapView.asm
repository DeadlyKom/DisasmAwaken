                module Map
                module CenterMapView
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [перепаковка координат, половина размеров и исходные особенности отсечения](../../Docs/MapViewCenter.md)
; -----------------------------------------
; Центрирование начала карты относительно упакованной точки с исходным отсечением по Sign
; исходная запись 7, файловые смещения #0333..#0367
; In:
;   HL - второе упакованное слово ключа, DE - первое, это порядок SelectMapPoint
;   MapViewState.Width и Height доступны как байтовые размеры отображаемой области
;   6300..6303 доступны для записи после завершения первоначального bootstrap, исходный банк KARTA выбран
; Out:
;   x=256*входной E+входной L, y=256*входной D+входной H
;   к каждой координате прибавлено FF00 OR ((0-floor(размер/2)) AND FF), результат обёрнут до 16 бит
;   если Sign соответствующего обёрнутого результата установлен, координата заменена нулём
;   HL упакован как старший Y и старший X, DE как младший Y и младший X
;   OriginLow получает DE, OriginHigh получает HL, размеры Width и Height сохранены
;   BC=FF00 OR ((0-floor(Height/2)) AND FF), A равен младшему байту окончательного Y
;   F от последнего ADC для Y до отсечения, замена HL на 0 флагов не меняет
;   все альтернативные регистры, IY, I и IFF сохранены, SP обычного возврата равен входному SP+2
;   IX сохранён, искомый ключ и списки сохранённых точек не меняются
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   ширина и высота округляются вниз при делении на два, затем NEG выполняется только над байтом
;   старший байт смещения всегда FF, при размере 0 или 1 получается FF00, то есть вычитание 256 вместо нуля
;   проверяется Sign обёрнутой суммы, перенос и переполнение не используются для отсечения
;   изменён только существующий runtime-контекст поверх отработавшего кода, новой памяти и инициализации нет
; -----------------------------------------
                ; перепаковка координат, в HL получается x=256*E+L, в DE y=256*D+H входного набора
Entry:          LD A, H
                LD H, E
                LD E, A
                ; расчёт смещения X из половины байтовой ширины, старший байт смещения всегда FF
                LD A, (@MapViewState.Width)
                SRL A
                NEG
                LD B, #FF
                LD C, A
                ; очистка Carry перед добавлением смещения X к полной координате
                AND A
                ADC HL, BC
                JP P, @Map.CenterMapView.CenterY                                ; переход, если обёрнутая координата X неотрицательна, сохранить её без отсечения

                ; отсечение отрицательной обёрнутой координаты X нулём без изменения флагов
                LD HL, #0000
                ; перенос рассчитанного X в DE и выбор Y для второго центрирования
CenterY:        EX DE, HL
                ; расчёт смещения Y из половины байтовой высоты с тем же фиксированным старшим FF
                LD A, (@MapViewState.Height)
                SRL A
                NEG
                LD B, #FF
                LD C, A
                ; очистка Carry перед добавлением смещения Y к полной координате
                AND A
                ADC HL, BC
                JP P, @Map.CenterMapView.StoreOrigin                            ; переход, если обёрнутая координата Y неотрицательна, сохранить её без отсечения

                ; отсечение отрицательной обёрнутой координаты Y нулём, F остаётся от ADC
                LD HL, #0000
                ; перепаковка двух координат в пары младших и старших байтов существующего контекста
StoreOrigin:    LD A, L
                LD L, D
                LD D, A
                ; сохранение старших и младших координатных байтов начала отображаемой области
                LD (@MapViewState.OriginHigh), HL
                LD (@MapViewState.OriginLow), DE
                RET

                endmodule
                endmodule
