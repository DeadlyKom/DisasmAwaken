                module Map
                module NextRasterRow
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [MapRaster.md](../../Docs/MapRaster.md)
; -----------------------------------------
; Переход на следующую строку Spectrum с проверкой нижней границы и нелокальным завершением растрового вызова
; исходная запись 7, файловые смещения #25AC..#25D7
; In:
;   HL - байтовый адрес пиксельной строки Spectrum, DE - E адрес второго края с той же группой Y
;   MapState.LowerRow - адрес исключённой нижней строки с обнулённой колонкой, RasterStack - стек внешнего растрового вызова
; Out:
;   при обычном возврате HL указывает на строку ниже, E перенесён в ту же строку, D равен старшему байту LowerRow
; Corrupt:
;   HL, DE, AF
; Note:
;   проверка нижней границы выполняется после перехода, исключённая нижняя строка не рисуется
;   при совпадении границы возврат из этой процедуры отбрасывается, SP восстанавливается из RasterStack
;   затем POP AF восстанавливает AF внешнего вызова и RET завершает его, продолжение после CALL не выполняется
;   BC, альтернативные и индексные регистры сохраняются, входной E должен иметь ту же группу Y, что и L
; -----------------------------------------
                ; расчёт следующей пиксельной строки с учётом чересстрочной раскладки Spectrum
Entry:          INC H
                LD A, H
                AND #07
                JP NZ, @Map.NextRasterRow.CheckLower                            ; переход, если следующая строка остаётся внутри восьмистрочной группы

                ; переход к следующей группе строк, обе колонки переносятся вместе
                LD A, E
                ADD A, #20
                LD E, A
                LD A, L
                ADD A, #20
                LD L, A
                JR C, @Map.NextRasterRow.CheckLower                             ; переход, если сложение шага группы перенеслось в старшую часть адреса

                ; коррекция старшего байта при переходе между восьмистрочными группами
                LD A, H
                SUB #08
                LD H, A
                ; сравнение следующей строки с исключённой нижней границей без учёта колонки
CheckLower:     PUSH HL
                LD A, L
                AND #E0
                LD L, A
                LD A, E
                LD DE, (@MapState.LowerRow)
                OR A
                ; проверка равенства нового адреса строки нижней границе
                SBC HL, DE
                LD E, A
                POP HL
                RET NZ                                                          ; выход, если новая строка ещё не достигла исключённой нижней границы

                ; отмена внутреннего возврата и восстановление стека внешнего растрового вызова
AbortRaster:    POP AF
                LD SP, (@MapState.RasterStack)
                POP AF
                RET

                endmodule
                endmodule
