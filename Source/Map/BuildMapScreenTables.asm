                module Map
                module BuildMapScreenTables
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [четыре выходные страницы и шаг строки Spectrum](../../Docs/MapScreenTables.md)
; -----------------------------------------
; Построение адресов 256 строк карты, горизонтальных колонок и битовых масок
; исходная запись 7, файловые смещения #049B..#04E4
; In:
;   DE - D пиксельный Y и E пиксельный X начала элемента, к ним прибавляются отступы 16 и 8 внутри байтов
;   StationTables.RowHighPage и две следующие страницы содержат исходные таблицы адресации экрана
;   банк KARTA выбран, EE00..F1FF доступны для записи, стек и код не перекрываются этими страницами
;   для экранного смысла стартовые координаты после отступов находятся в bitmap, проверок границ здесь нет
; Out:
;   страницы RowHigh и RowLow содержат 256 старших и младших байтов последовательных экранных строк без горизонтальной колонки
;   ColumnByte[i]=(исходная колонка+floor(i/8)) modulo 256, PixelMask[i]=80 SHR (i AND 7)
;   HL=F000, DE адрес строки после всех 256 переходов, B=0, C сохранён
;   A=исходная колонка+32, F=42, исходная колонка находится в диапазоне 0..31
;   AF'=80A3, HL', DE', BC', IX, IY, I и IFF сохранены, SP обычного возврата равен входному SP+2
;   записаны ровно четыре страницы, пиксели экрана и соседние байты EDFF и F200 не меняются
; Corrupt:
;   HL, DE, BC только B, AF, AF'
; Note:
;   сначала вычисляется экранный адрес через страницы 82,83,84, горизонтальная колонка отделяется маской 1F
;   маска E0 оставляет только строковую часть младшего адресного байта для RowLow
;   адрес строки изменяется исходной схемой INC D, затем при D AND 7=0 добавление 20 к E и условное вычитание 8 из D
;   построение 256 строк не означает допустимость рисования всех 256 строк, видимая высота проверяется потребителями
;   EX AF,AF альтернативного набора хранит отдельно номер колонки и вращаемую маску 80
;   прибавления отступов байтовые с оборачиванием, нештатные входы в модели сохраняют фактические байты исходных lookup-страниц
; -----------------------------------------
                ; расчёт внутреннего пиксельного X с исходным байтовым отступом 8
Entry:          LD A, E
                ADD A, #08
                LD E, A
                ; расчёт внутреннего пиксельного Y с исходным байтовым отступом 16
                LD A, D
                ADD A, #10
                LD L, A
                ; поиск старшего и младшего байтов экранной строки через исходные страницы 82 и 83
                LD H, @StationTables.RowHighPage
                LD D, (HL)
                INC H
                LD A, (HL)
                ; добавление горизонтальной колонки из страницы 84 к строковому адресу через OR
                INC H
                LD L, E
                OR (HL)
                LD E, A
                ; выделение исходной колонки 0..31 для отдельной горизонтальной таблицы
                AND #1F
                ; сохранение колонки во временном AF альтернативного набора
                EX AF, AF'
                ; удаление колонки из младшего байта адреса, остаются только разряды экранной строки
                LD A, E
                AND #E0
                LD E, A
                ; выбор начала двух адресных страниц RowHigh и RowLow
                LD HL, @MapScreenTables.RowHigh
                ; запись старшего и младшего байтов текущей строки в соседние страницы
StoreRow:       LD (HL), D
                INC H
                LD (HL), E
                DEC H
                ; расчёт следующей строки внутри восьмистрочного экранного блока
                INC D
                LD A, D
                AND #07
                JP NZ, @Map.BuildMapScreenTables.NextRow                        ; переход, если младшие три разряда D не обнулились, строка остаётся внутри блока

                ; расчёт следующей символьной строки после восьми пиксельных строк
                LD A, E
                ADD A, #20
                LD E, A
                JR C, @Map.BuildMapScreenTables.NextRow                         ; переход, если добавление 20 переполнило E, высокий адрес уже перешёл в следующую треть

                ; возврат старшей части адреса после перехода строки без переноса младшего байта
                LD A, D
                SUB #08
                LD D, A
                ; продвижение индекса двух адресных страниц до байтового оборачивания
NextRow:        INC L
                JR NZ, @Map.BuildMapScreenTables.StoreRow                       ; переход, если индекс L ещё не обернулся в ноль, записать следующую строку

                ; выбор страниц ColumnByte и PixelMask после завершения RowHigh и RowLow
                INC H
                INC H
                ; подготовка маски старшего пикселя, обмен AF возвращает сохранённую исходную колонку
                LD A, #80
                EX AF, AF'
                ; формирование восьми пиксельных позиций одной горизонтальной колонки
NextColumn:     LD B, #08
                ; запись номера колонки и соответствующей одноразрядной маски в соседние страницы
StorePixel:     LD (HL), A
                EX AF, AF'
                INC H
                LD (HL), A
                ; расчёт маски следующего пикселя циклическим сдвигом, через восемь позиций снова получается 80
                RRCA
                DEC H
                EX AF, AF'
                INC L
                DJNZ @Map.BuildMapScreenTables.StorePixel

                ; расчёт следующей горизонтальной колонки и проверка оборачивания индекса без изменения L
                INC A
                INC L
                DEC L
                JR NZ, @Map.BuildMapScreenTables.NextColumn                     ; переход, если L не равен нулю, сформировать следующие восемь позиций

                RET

                endmodule
                endmodule
