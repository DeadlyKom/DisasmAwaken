                module Map
                module RefreshSecondaryPointOrder
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [различие маркера 7F, нижнее ограничение курсора и плотные смещения](../../Docs/SecondaryPointOrder.md)
; -----------------------------------------
; Нормализация указателя второго списка, пересчёт количества и плотных смещений
; исходная запись 7, файловые смещения #09FB..#0A44
; In:
;   SecondaryPointState.Cursor у первого байта записи, при шагах назад по 5 достижим байт 00..7E
;   доступен второй список StoredMapPointsB с не более десяти записей и достижимым маркером 7F..FE
;   служебный байт 9970 и первые десять смещений по 9971 доступны для записи, KARTA выбран
;   обратный проход до положительного байта не ограничен началом списка, вся фактически посещаемая память читаема
; Out:
;   Cursor движется назад по 5 до первого байта 00..7E, затем ограничивается снизу началом StoredMapPointsB
;   количество N подсчитано по первым байтам 00..7E до первого 7F..FE, FF пропускается
;   служебный байт получает (старое значение AND F0) OR N, при исходной ёмкости 10 это обновляет младшую тетраду
;   при N>0 первые N байтов Order00.. получают 0,5,10,...,5*(N-1), оставшийся хвост сохраняется
;   HL=9971+N, DE=5, BC=00FB, A=5*N, F от последнего ADD A,5 для N>0
;   при N=0 таблица смещений не меняется, HL у записи сразу после ограничителя, DE=5, BC=00FB, AF=0054
;   все альтернативные и индексные регистры, I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   INC A перед проверкой Sign делает 7F завершающим маркером, в отличие от FindSecondaryMapPoint
;   проверка нижней границы курсора выполняется после обратного поиска, она не ограничивает чтение во время поиска
;   верхней границы курсора нет, при достижимом положительном байте выше списка он сохраняется без верхнего отсечения
;   смещения плотные по количеству, реальные позиции непустых записей при наличии дыр не копируются
;   биты 5..4 Layout сохраняют код Clear/Set/Xor, биты 7..6 также сохраняются и остаются Unknown
;   исходный служебный байт равен 22 при пустых записях и нулевой таблице смещений, начальное состояние не нормализуется
; -----------------------------------------
                ; чтение текущего указателя второго списка и подготовка шага назад размером одной записи
Entry:          LD HL, (@SecondaryPointState.Cursor)
                LD BC, #FFFB
                ; поиск назад первого байта 00..7E, INC исключает также исходный 7F
FindPrevious:   LD A, (HL)
                INC A
                JR Z, @Map.RefreshSecondaryPointOrder.PreviousSlot              ; переход, если исходный первый байт равнялся FF, проверить предыдущую запись

                JP P, @Map.RefreshSecondaryPointOrder.ClampCursor               ; переход, если исходный первый байт находится в диапазоне 00..7E, ограничить указатель снизу

                ; переход к предыдущей физической записи без проверки нижней границы чтения
PreviousSlot:   ADD HL, BC
                JP @Map.RefreshSecondaryPointOrder.FindPrevious

                ; сравнение найденного адреса с началом второго списка после завершения обратного поиска
ClampCursor:    LD DE, @StoredMapPointsB.Point00
                OR A
                SBC HL, DE
                JR NC, @Map.RefreshSecondaryPointOrder.RestoreCursor            ; переход, если найденный адрес не ниже начала списка, восстановить его из разности

                ; замена адреса ниже списка его исходной нижней границей
                EX DE, HL
                JR @Map.RefreshSecondaryPointOrder.StoreCursor

                ; восстановление найденного адреса из неотрицательной разности
RestoreCursor:  ADD HL, DE
                ; сохранение ограниченного указателя до пересчёта количества
StoreCursor:    LD (@SecondaryPointState.Cursor), HL
                ; поиск количества записей второго списка с шагом 5 и начальным B=0
                LD HL, @StoredMapPointsB.Point00
                LD DE, @FStoredMapPoint
                LD B, #00
                ; чтение первого байта и продвижение адреса до следующей записи перед проверкой конца
CountNext:      LD A, (HL)
                ADD HL, DE
                INC A
                JP M, @Map.RefreshSecondaryPointOrder.StoreCount                ; переход, если исходный первый байт равен 7F..FE, завершить подсчёт

                JR Z, @Map.RefreshSecondaryPointOrder.CountNext                 ; переход, если исходный первый байт равнялся FF, не увеличивать количество

                ; увеличение количества только для исходных первых байтов 00..7E
                INC B
                JR @Map.RefreshSecondaryPointOrder.CountNext

                ; сохранение старшей тетрады служебного байта и включение нового количества через OR
StoreCount:     LD A, (@StoredMapOrder.Entry.Layout)
                AND #F0
                OR B
                LD (@StoredMapOrder.Entry.Layout), A
                ; проверка нулевого количества перед записью плотных смещений
                LD A, B
                AND A
                RET Z                                                           ; выход, если записей нет, прежняя таблица смещений не меняется

                ; подготовка нулевого начального смещения для N записываемых байтов
                LD HL, @StoredMapOrder.Entry.Order00
                XOR A
                ; запись очередного плотного смещения и расчёт следующего прибавлением физического шага 5
StoreOffset:    LD (HL), A
                INC HL
                ADD A, #05
                DJNZ @Map.RefreshSecondaryPointOrder.StoreOffset

                RET

                endmodule
                endmodule
