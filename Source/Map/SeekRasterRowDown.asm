                module Map
                module SeekRasterRowDown
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [табличные координаты краёв и ограниченный поиск без замены SP](../../Docs/RasterPreparation.md)
; -----------------------------------------
; Обычный поиск до B строк вниз с адресом исключённой нижней границы
; исходная запись 7, файловые смещения #2621..#265C
; In:
;   BC - B максимальное число шагов 0..255, входной C игнорируется, AF - A исходный относительный Y и сохраняемый F
;   RowHigh и RowLow построены для области, Column обозначает операнд OR, исходно 0, D0C3 записывает ColumnByte[MaxX]
;   MapState.LowerRow содержит выровненный по восьми строкам адрес границы с нулевой колонкой
;   Column находится в диапазоне 0..31, нижняя и верхняя границы различаются и выровнены по восьми строкам
;   исходная строка лежит в допустимой области, стек доступен для FBoundedRasterSeekFrame и временного HL
; Out:
;   начальный младший адрес равен RowLow[A] OR Column, Column сохраняется при переходах строк
;   HL - адрес после не более B шагов вниз, при достижении LowerRow возвращён адрес этой исключённой строки
;   DE получает LowerRow при выполнении хотя бы одной проверки границы, иначе сохраняется
;   BC - B исходный, C равен входному A, AF целиком восстановлен
;   все альтернативные и индексные регистры, I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE при проверке границы, BC только C
; Note:
;   при B=0 сразу возвращает исходный табличный адрес, DE не меняется
;   сохранённый BC уже содержит C=исходный A, прежний входной C не восстанавливается
;   проверка границы выполняется только на переходах восьмистрочных блоков
;   это обычный RET с восстановлением AF, MapState.RasterStack не читается и не изменяется
;   настоящий писатель D0C3 и настроенный поиск проверены в [фазах исполнения](../../Docs/MapRuntimeProfiles.md), невыравненные границы и Column>=32 не входят в этот договор
; -----------------------------------------
                ; замена C исходным Y и сохранение AF и BC для поиска вниз
Entry:          LD C, A
                LD A, C
                PUSH AF
                PUSH BC
                ; поиск исходного адреса строки с изменяемым OR Column
                LD L, A
                LD H, @MapMarkerConst.RowHighPage
                LD B, (HL)
                INC H
                LD A, (HL)
                OR #00
                LD L, A
                LD H, B
                ; восстановление исходного счётчика и проверка отсутствия шагов
                POP BC
                PUSH BC
                DEC B
                INC B
                JR Z, @Map.SeekRasterRowDown.RestoreInput                       ; переход, если исходное число шагов B равно нулю, восстановить AF и BC

                ; расчёт следующей пиксельной строки до перехода восьмистрочного блока
StepDown:       INC H
                LD A, H
                AND #07
                JR Z, @Map.SeekRasterRowDown.NextBlock                          ; переход, если младшие три разряда нового H обнулились, перейти к следующему блоку

                DJNZ @Map.SeekRasterRowDown.StepDown

                ; восстановление исходного B, заменённого C и полного входного AF перед обычным RET
RestoreInput:   POP BC
                POP AF
                RET

                ; расчёт младшего адреса следующей символьной строки Spectrum
NextBlock:      LD A, L
                ADD A, #20
                LD L, A
                JR C, @Map.SeekRasterRowDown.TestLower                          ; переход, если прибавление 20 переполнило L, адрес уже перешёл в следующую треть

                ; коррекция H при переходе строки без переноса младшего байта
                LD A, H
                SUB #08
                LD H, A
                ; сравнение рассчитанной строки без колонки с исключённой LowerRow
TestLower:      PUSH HL
                LD A, L
                AND #E0
                LD L, A
                LD DE, (@MapState.LowerRow)
                OR A
                SBC HL, DE
                POP HL
                JR Z, @Map.SeekRasterRowDown.RestoreInput                       ; переход, если рассчитанная строка равна LowerRow, вернуть адрес исключённой границы

                DJNZ @Map.SeekRasterRowDown.StepDown

                JR @Map.SeekRasterRowDown.RestoreInput

                endmodule
                endmodule
