                module Map
                module PrepareVariantResources
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [приоритет категорий, второй список и количество от одного до шести](../../Docs/VariantResources.md)
; -----------------------------------------
; Подготовка до шести изменяемых указателей ресурсов вариантов выбранной точки
; исходная запись 7, файловые смещения #0781..#07B3
                ; In:
                ;   BC содержит сохраняемый C, входной B будет заменён количеством, AF содержит A, исходное количество вариантов
                ;   действует договор SelectVariantResource, шесть операндов Resource0..Resource5 доступны в KARTA
                ; Out:
                ;   MapVariantState.Count получает входной A, B сначала получает то же значение
                ;   для A=1..5 записывается ровно A указателей, для A=0 или A>=6 ровно шесть
                ;   порядковые варианты для записей равны 0..число_указателей-1, их ресурсы определяются SelectVariantResource
                ;   непосещённые операнды при A=1..5 сохраняют прежнее содержимое
                ;   при A=1..5 конечный B=0, F=42 от DEC B, при остальных B=(A-5) modulo 256 и F от последнего выбора ресурса
                ;   HL, DE соответствуют последнему SelectVariantResource, BC содержит конечный B и сохранённый C
                ;   AF содержит A последнего SelectVariantResource, F определяется описанной выше ветвью количества
                ;   HL', DE', BC', AF' сохранены, IX соответствует последнему SelectVariantResource, IY сохранён
                ;   I и IFF сохранены, SP обычного возврата равен входному SP+2
                ; Corrupt:
                ;   HL, DE, BC только B, AF, IX по последнему SelectVariantResource, R
; Note:
;   после шестого выбора B не уменьшается и отдельной проверки количества уже нет
;   нулевое количество не означает пустой список, первый выбор всё равно выполняется и DEC B оборачивает его в FF
;   указатели являются исходными изменяемыми словами в коде потребителя, адреса и исходные байты не меняются
; -----------------------------------------
                ; сохранение исходного количества в B и операнде Count для расчёта порядкового варианта
Entry:          LD B, A
                LD (@MapVariantState.Count), A
                ; выбор ресурса порядкового варианта 0 и запись исходного изменяемого указателя
                CALL @Map.SelectVariantResource.Entry
                LD (@MapVariantState.Resource0), HL
                ; проверка остатка после подготовки очередного указателя
                DEC B
                RET Z                                                           ; выход, если после указателя 0 остаток B стал нулём

                ; выбор ресурса порядкового варианта 1 и запись исходного изменяемого указателя
                CALL @Map.SelectVariantResource.Entry
                LD (@MapVariantState.Resource1), HL
                ; проверка остатка после подготовки очередного указателя
                DEC B
                RET Z                                                           ; выход, если после указателя 1 остаток B стал нулём

                ; выбор ресурса порядкового варианта 2 и запись исходного изменяемого указателя
                CALL @Map.SelectVariantResource.Entry
                LD (@MapVariantState.Resource2), HL
                ; проверка остатка после подготовки очередного указателя
                DEC B
                RET Z                                                           ; выход, если после указателя 2 остаток B стал нулём

                ; выбор ресурса порядкового варианта 3 и запись исходного изменяемого указателя
                CALL @Map.SelectVariantResource.Entry
                LD (@MapVariantState.Resource3), HL
                ; проверка остатка после подготовки очередного указателя
                DEC B
                RET Z                                                           ; выход, если после указателя 3 остаток B стал нулём

                ; выбор ресурса порядкового варианта 4 и запись исходного изменяемого указателя
                CALL @Map.SelectVariantResource.Entry
                LD (@MapVariantState.Resource4), HL
                ; проверка остатка после подготовки очередного указателя
                DEC B
                RET Z                                                           ; выход, если после указателя 4 остаток B стал нулём

                ; выбор ресурса порядкового варианта 5 и запись исходного изменяемого указателя
                CALL @Map.SelectVariantResource.Entry
                LD (@MapVariantState.Resource5), HL
                RET

                endmodule
                endmodule
