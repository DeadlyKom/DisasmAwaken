                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Map.MultiplySigned16.ShiftWide07                        ; переход, если бит 7 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 7 второго модуля
AddWide07:      ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 7 в паре HL и IX
ShiftWide07:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Map.MultiplySigned16.ShiftWide06                        ; переход, если бит 6 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 6 второго модуля
AddWide06:      ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 6 в паре HL и IX
ShiftWide06:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Map.MultiplySigned16.ShiftWide05                        ; переход, если бит 5 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 5 второго модуля
