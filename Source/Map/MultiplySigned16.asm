                module Map
                module MultiplySigned16
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [три ядра, регистры и асимметрия второго операнда 8000](../../Docs/SignedMultiply.md)
; -----------------------------------------
; Знаковое произведение HL и DE с двумя словами результата с тремя ядрами и исходным случаем 8000
; исходная запись 7, файловые смещения #1B63..#1CFA
; In:
;   HL и DE - шестнадцатибитные знаковые операнды дополнительного кода, KARTA доступна в текущем окне
;   CPU-стек допускает временное слово AF поверх адреса возврата
; Out:
;   HL старшее слово, DE младшее слово 32-битного произведения, особый случай второго операнда 8000 указан ниже
;   A=XOR старших байтов исходных HL и DE, независимо от знака и нулевого результата
;   при одинаковых знаках F от XOR этих байтов, флаги не являются проверкой результата произведения
;   при разных знаках F от последнего SBC HL,BC при отрицании старшего слова с переносом от младшего
;   при разных знаках BC равно старшему слову модуля полученного произведения до отрицания
;   при одинаковых знаках и обоих модулях не меньше 256 BC=0
;   при одинаковых знаках и ровно одном модуле меньше 256 B сохранён, C=0
;   при одинаковых знаках и обоих модулях меньше 256 BC сохранён
;   при обоих модулях не меньше 256 IX равно младшему слову модуля произведения до отрицания, иначе IX сохранён
;   альтернативные регистры, IY, I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC в зависимости от ядра и знака, AF, IX только в полном ядре
; Note:
;   сначала берутся модули операндов, исходный знак сохранён через XOR старших байтов в слове AF на стеке
;   для модулей меньше 256 используются ядра 8x8 либо 8x16, иначе полное 16x16 в старшем HL и младшем IX
;   обычный модуль произведения равен abs(HL_вход)*abs(DE_вход), отрицание применяется ко всем 32 разрядам
;   исключение, DE_вход=8000 и abs(HL_вход)>=256 в полном ядре дают модуль abs(HL_вход)*256
;   причина исключения, начальный бит 15 теряется, при нулевых битах 14..8 принудительно выполняется AddWide08
;   перестановка входов может устранить исключение, алгоритм на этой границе не симметричен
;   для отрицательного нулевого произведения A сохраняет знак XOR, флаг Z от последнего SBC может быть установлен
;   нет насыщения, проверки переполнения или записи постоянного состояния, меняются только регистры и временный стек
; -----------------------------------------
                ; расчёт знака произведения по XOR знаковых разрядов двух исходных слов
Entry:          LD A, H
                XOR D
                ; сохранение знака вместе с точными флагами XOR до выбора числового ядра
                PUSH AF
                ; проверка знака правого операнда перед взятием модуля
                BIT 7, D
                JR Z, @Map.MultiplySigned16.CheckLeftSign                       ; переход, если DE неотрицателен, оставить его модуль без изменений

                ; расчёт модуля отрицательного DE дополнительным кодом, 8000 остаётся 8000
                LD A, E
                CPL
                LD E, A
                LD A, D
                CPL
                LD D, A
                INC DE
                ; проверка знака левого операнда перед взятием модуля
CheckLeftSign:  BIT 7, H
                JR Z, @Map.MultiplySigned16.SelectKernel                        ; переход, если HL неотрицателен, оставить его модуль без изменений

                ; расчёт модуля отрицательного HL дополнительным кодом
                LD A, L
                CPL
                LD L, A
                LD A, H
                CPL
                LD H, A
                INC HL
                ; размещение модуля первого операнда в DE и второго в HL для выбора разрядности ядра
SelectKernel:   EX DE, HL
                ; проверка, помещается ли модуль первого операнда в один байт
                LD A, D
                AND A
                JP Z, @Map.MultiplySigned16.CheckOtherByte                      ; переход, если первый модуль меньше 256, проверить разрядность второго

                ; проверка, помещается ли модуль второго операнда в один байт
                LD A, H
                AND A
                JP Z, @Map.MultiplySigned16.MulByteWord                         ; переход, если второй модуль меньше 256, использовать байтовый множитель

                ; обнуление старшей добавки BC и младшего накопителя IX полного произведения
                LD BC, #0000
                LD IX, #0000
                ; пропуск исходного знакового разряда модуля второго операнда, крайний модуль 8000 теряет этот бит
                ADD HL, HL
                ; расчёт первого проверяемого разряда полного ядра, бит 14 выходит в Carry
                ADD HL, HL
                JP C, @Map.MultiplySigned16.AddWide14                           ; переход, если бит 14 второго модуля единичный, начать накопление с него

                ; поиск первого единичного старшего разряда второго модуля с пропуском нулевых слагаемых
                ADD HL, HL
                JP C, @Map.MultiplySigned16.AddWide13                           ; переход, если бит 13 второго модуля единичный, начать накопление с него

                ; поиск первого единичного старшего разряда второго модуля с пропуском нулевых слагаемых
                ADD HL, HL
                JP C, @Map.MultiplySigned16.AddWide12                           ; переход, если бит 12 второго модуля единичный, начать накопление с него

                ; поиск первого единичного старшего разряда второго модуля с пропуском нулевых слагаемых
                ADD HL, HL
                JP C, @Map.MultiplySigned16.AddWide11                           ; переход, если бит 11 второго модуля единичный, начать накопление с него

                ; поиск первого единичного старшего разряда второго модуля с пропуском нулевых слагаемых
                ADD HL, HL
                JP C, @Map.MultiplySigned16.AddWide10                           ; переход, если бит 10 второго модуля единичный, начать накопление с него

                ; поиск первого единичного старшего разряда второго модуля с пропуском нулевых слагаемых
                ADD HL, HL
                JP C, @Map.MultiplySigned16.AddWide09                           ; переход, если бит 9 второго модуля единичный, начать накопление с него

                ADD HL, HL
                ; принудительное начало с бита 8 при отсутствии старших единичных разрядов, источник исключения 8000
                JP @Map.MultiplySigned16.AddWide08

                ; добавление модуля первого операнда для единичного бита 14 второго модуля
AddWide14:      ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 14 в паре HL и IX
ShiftWide14:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Map.MultiplySigned16.ShiftWide13                        ; переход, если бит 13 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 13 второго модуля
AddWide13:      ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 13 в паре HL и IX
ShiftWide13:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Map.MultiplySigned16.ShiftWide12                        ; переход, если бит 12 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 12 второго модуля
AddWide12:      ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 12 в паре HL и IX
ShiftWide12:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Map.MultiplySigned16.ShiftWide11                        ; переход, если бит 11 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 11 второго модуля
