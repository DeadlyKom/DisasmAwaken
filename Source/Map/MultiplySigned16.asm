                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Map.MultiplySigned16.ShiftWide10                        ; переход, если бит 10 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 10 второго модуля
