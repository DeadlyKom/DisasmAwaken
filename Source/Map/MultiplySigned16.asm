                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Map.MultiplySigned16.ShiftWide09                        ; переход, если бит 9 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 9 второго модуля
AddWide09:      ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 9 в паре HL и IX
ShiftWide09:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Map.MultiplySigned16.ShiftWide08                        ; переход, если бит 8 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 8 второго модуля
