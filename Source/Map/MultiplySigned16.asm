                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 5 в паре HL и IX
ShiftWide05:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Map.MultiplySigned16.ShiftWide04                        ; переход, если бит 4 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 4 второго модуля
AddWide04:      ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 4 в паре HL и IX
ShiftWide04:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Map.MultiplySigned16.ShiftWide03                        ; переход, если бит 3 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 3 второго модуля
AddWide03:      ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 3 в паре HL и IX
ShiftWide03:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Map.MultiplySigned16.ShiftWide02                        ; переход, если бит 2 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 2 второго модуля
AddWide02:      ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 2 в паре HL и IX
ShiftWide02:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Map.MultiplySigned16.ShiftWide01                        ; переход, если бит 1 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 1 второго модуля
AddWide01:      ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; расчёт удвоенного частичного произведения после разряда 1 в паре HL и IX
ShiftWide01:    ADD IX, IX
                ; продолжение 32-битного сдвига и получение следующего бита множителя в Carry
                ADC HL, HL
                JR NC, @Map.MultiplySigned16.TakeWideLow                        ; переход, если бит 0 второго модуля нулевой, пропустить его слагаемое

                ; добавление модуля первого операнда для единичного бита 0 второго модуля
AddWide00:      ADD IX, DE
                ; включение переноса младшего слова в старшее с нулевой добавкой BC
                ADC HL, BC
                ; перенос младшего слова модуля произведения из IX в выходной DE
TakeWideLow:    LD D, IXH
                LD E, IXL
                ; восстановление исходного знака и флагов XOR после всех арифметических ядер
ApplySign:      POP AF
                RET P                                                           ; выход, если исходные знаки одинаковы, 32-битный модуль уже является результатом

                ; сохранение старшего слова модуля в BC перед отрицанием 32-битного значения
                LD B, H
                LD C, L
                ; расчёт отрицательного младшего слова, Carry от сохранённого XOR равен нулю
                LD HL, #0000
                SBC HL, DE
                EX DE, HL
                ; расчёт отрицательного старшего слова с заёмом от отрицания младшего
                LD HL, #0000
                SBC HL, BC
                RET

                ; проверка второго старшего байта при уже установленном байтовом первом модуле
CheckOtherByte: LD A, H
                AND A
                JR Z, @Map.MultiplySigned16.MulBytes                            ; переход, если оба модуля меньше 256, использовать ядро 8x8

                ; перестановка для размещения байтового множителя в L перед ядром 8x16
                EX DE, HL
                ; создание 24-битного накопителя A:HL из байтового множителя и нулевого младшего слова
MulByteWord:    LD A, L
                LD L, H
                LD C, H
                ; поиск первого единичного разряда байтового множителя сдвигом A
                ADD A, A
                JR C, @Map.MultiplySigned16.AddByteWord7                        ; переход, если бит 7 байтового множителя единичный, начать с его слагаемого

                ; поиск первого единичного разряда байтового множителя сдвигом A
                ADD A, A
                JR C, @Map.MultiplySigned16.AddByteWord6                        ; переход, если бит 6 байтового множителя единичный, начать с его слагаемого

                ; поиск первого единичного разряда байтового множителя сдвигом A
                ADD A, A
                JR C, @Map.MultiplySigned16.AddByteWord5                        ; переход, если бит 5 байтового множителя единичный, начать с его слагаемого

                ; поиск первого единичного разряда байтового множителя сдвигом A
                ADD A, A
                JR C, @Map.MultiplySigned16.AddByteWord4                        ; переход, если бит 4 байтового множителя единичный, начать с его слагаемого

                ; поиск первого единичного разряда байтового множителя сдвигом A
                ADD A, A
                JR C, @Map.MultiplySigned16.AddByteWord3                        ; переход, если бит 3 байтового множителя единичный, начать с его слагаемого

                ; поиск первого единичного разряда байтового множителя сдвигом A
                ADD A, A
                JR C, @Map.MultiplySigned16.AddByteWord2                        ; переход, если бит 2 байтового множителя единичный, начать с его слагаемого

                ; поиск первого единичного разряда байтового множителя сдвигом A
                ADD A, A
                JR C, @Map.MultiplySigned16.AddByteWord1                        ; переход, если бит 1 байтового множителя единичный, начать с его слагаемого

                ; поиск первого единичного разряда байтового множителя сдвигом A
                ADD A, A
                JR C, @Map.MultiplySigned16.AddByteWord0                        ; переход, если бит 0 байтового множителя единичный, начать с его слагаемого

                JP @Map.MultiplySigned16.StoreByteWord

                ; добавление 16-битного модуля для единичного разряда 7 байтового множителя
