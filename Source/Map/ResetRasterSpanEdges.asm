                module Map
                module ResetRasterSpanEdges
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [табличные координаты краёв и ограниченный поиск без замены SP](../../Docs/RasterPreparation.md)
; -----------------------------------------
; Маски полного растрового пролёта и изменяемая левая колонка
; исходная запись 7, файловые смещения #25D8..#25E2
; In:
;   HL - адрес левого края, D сохраняемый старший адресный контекст
;   LeftColumn обозначает операнд OR по E5DC, исходно 1, D0C3 записывает ColumnByte[0]
; Out:
;   HL и D сохранены, E=(входной L AND E0) OR LeftColumn
;   BC=8001, A=E, F от заключительного OR LeftColumn, начальные альтернативные и индексные регистры сохранены
;   I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   DE только E, BC, AF
; Note:
;   L маскируется через E0 и объединяется OR с LeftColumn, перенос в H не выполняется
;   [фазы исполнения](../../Docs/MapRuntimeProfiles.md) проверены отдельно, для таблиц с входным DE=0 LeftColumn=1
;   маски B=80 и C=01 задают крайние пиксели, bitmap самой процедурой не изменяется
; -----------------------------------------
                ; расчёт младшего адреса изменяемой левой колонки в прежней строковой группе левого края
Entry:          LD A, L
                AND #E0
                OR #01
                LD E, A
                ; подготовка двух крайних одноразрядных масок полного внутреннего пролёта
                LD C, #01
                LD B, #80
                RET

                endmodule
                endmodule
