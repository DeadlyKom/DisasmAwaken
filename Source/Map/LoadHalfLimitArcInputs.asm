                module Map
                module LoadHalfLimitArcInputs
                ; Документация [подготовка альтернативных счётчиков дуги от полуширины окна](../../Docs/ArcHalfLimitInputs.md)
                ; -----------------------------------------
                ; Загрузка смещений и разности полуширины окна для счётчиков дуги
                ; исходная запись 7, образ KARTA по C000, адреса E289..E298
                ; In:
                ;   MapArcState.OffsetX, OffsetY, HalfXLimit и StartY читаемы, на стеке внешний возврат
                ; Out:
                ;   HL, DE сохранены, BC содержит B=OffsetX и C=OffsetY
                ;   AF содержит A=StartY и F от вычитания HalfXLimit минус OffsetX
                ;   E' содержит StartY, C' содержит разность по модулю 256
                ;   SP увеличен на два, R получает десять M1, записей в RAM нет
                ; Corrupt:
                ;   BC, AF, E', C', R
                ; Note:
                ;   остальные альтернативные и индексные регистры, I, IM и IFF сохранены
                ;   арифметика байтовая, Carry от вычитания сохраняется при чтении StartY
                ;   проверены все 65536 пары аргументов, вызывающая цепочка пока не установлена
                ; -----------------------------------------
                ; Загрузка смещений без изменения HL и DE.
Entry:          LD BC, (@MapArcState.OffsetY)
                ; Расчёт разности полуширины окна и горизонтального смещения.
                LD A, (@MapArcState.HalfXLimit)
                SUB B
                ; Подготовка начального горизонтального счётчика в альтернативном C.
                EXX
                LD C, A
                ; Загрузка начальной строки в альтернативный E с сохранением флагов вычитания.
                LD A, (@MapArcState.StartY)
                LD E, A
                EXX
                RET

                endmodule
                endmodule
