                module UnwindClipFrame
                ; Документация [Map](../../Docs/FunctionDetails/Map.md)
                ; Подробный разбор [самостоятельные входы, точные флаги, байтовый курсор и специальный стековый кадр](../../Docs/ClipTail.md)
                ; -----------------------------------------
                ; Специальный возврат со снятием трёх слов и установленным Carry
                ; исходная запись 7, файловые смещения #1B59..#1B62
                ; In:
                ;   SP указывает на FClipUnwindFrame, последовательно три снимаемых слова и настоящий адрес возврата
                ;   FirstWord передаёт A своим старшим байтом, SecondWord передаёт счётчик своим старшим байтом
                ;   ThirdWord является базой для возвращаемого HL, это описание фактического кадра без подмены обычным CALL
                ; Out:
                ;   HL=(ThirdWord+BC)&65535, DE сохранён, BC=(high(SecondWord)-1)&255, AF содержит A=high(FirstWord)
                ;   Carry=1, S/Z/PV соответствуют DEC старшего байта SecondWord, H=N=0, биты 5 и 3 взяты из A
                ;   HL', DE', BC', AF' сохраняются, IX, IY, I, IM и IFF сохраняются
                ;   управление передано по ReturnAddress, SP=входной SP+8, записей RAM нет
                ;   R получает 9 M1 при снятии исходного четырёхсловного кадра
                ; Corrupt:
                ;   HL, BC, AF, SP, R
                ; Note:
                ;   первые три слова намеренно удаляются, они не являются тремя обычными адресами CALL этой процедуры
                ;   DispatchMapClipEdge создаёт кадр с тремя копиями MapClipCases.Entry=D4DD, специальный путь удаляет их сразу
                ;   для такого кадра HL=D5B0, BC=00D3, AF=D481, A=D4 не является OutputSize
                ;   условия геометрического отказа заданы переходами обработчиков, протокол кадра описан в ClipCases.md
                ; -----------------------------------------
                ; снятие первого слова специального кадра, его старший байт становится возвращаемым A
Entry:          POP AF
                ; снятие второго слова, старший байт задаёт оборачиваемое смещение минус один
                POP BC
                ; снятие третьего слова как базы возвращаемого HL
                POP HL
                LD C, B
                ; расчёт байтового смещения из старшего байта второго снятого слова
                DEC C
                LD B, #00
                ; расчёт нового HL с нулевым старшим байтом смещения
                ADD HL, BC
                ; установка специального выходного Carry после вычисления HL
                SCF
                RET

                endmodule
                endmodule
