                module PrintSelectedVariantLabel
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [XOR-класс ключа, число шагов и байтовое оборачивание номера](../../Docs/VariantLabel.md)
; -----------------------------------------
; Чтение выбранного ключа и последовательный вывод подписи его варианта
; исходная запись 7, файловые смещения #08C2..#08C8
; In:
;   MapSelection.FirstWord и SecondWord задают ключ, AF - A порядковый байт варианта
;   действуют договоры StepSignatureKey, DrawGlyph и PrintWord, исходные код, шрифт и окно доступны
;   SignatureState.WorkKey является общей изменяемой памятью, параллельный писатель отсутствует
; Out:
;   перед последовательным PrintVariantLabel HL=MapSelection.FirstWord, DE=MapSelection.SecondWord, остальные регистры сохранены
;   SignatureState.WorkKey сначала получает оба входных слова, затем может измениться через StepSignatureKey
;   если XOR четырёх входных байтов AND 7 равен 0 или 1, печатает только дефис
;   на ветви дефиса HL и DE сохраняют входной ключ, B=(исходный A+1) modulo 256, C=исходный A, AF по DrawGlyph
;   для классов 2..7 исполняет исходный A+1 шагов ключа, при A=FF ровно 256 шагов через DJNZ
;   последняя XOR-свёртка S задаёт код буквы 80+(S AND 0F), затем печатается дефис
;   число после дефиса равно ((S SHR 4)+1+исходный A) modulo 256, выводится PrintWord с бюджетом нулей A=0
;   на числовой ветви HL содержит прежнее SecondWord перед последним шагом, DE новое SecondWord последнего шага
;   BC и AF на числовой ветви соответствуют PrintWord, при полном успешном выводе BC=10, AF=0045
;   все альтернативные и индексные регистры, I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   обёртка из двух LD не создаёт нового адреса возврата
;   код буквы относится к исходной CP866, диапазон 80..8F сохраняется без перекодирования
;   входной вариант не ограничивается числом вариантов ключа, отдельной проверки диапазона в этой процедуре нет
;   номер является байтовой суммой и может обернуться, дополнительный старший разряд не выводится
;   промежуточные отказы буквы или дефиса не прекращают дальнейший вывод, AF этих CALL не проверяется
;   для воспроизводимой подписи рабочий ключ всегда перезаписывается входом до первого шага
; -----------------------------------------
                ; чтение первого и второго слов выбранного пункта перед последовательным выводом варианта
Entry:          LD HL, (@MapSelection.FirstWord)
                LD DE, (@MapSelection.SecondWord)
                ; JP @Map.PrintVariantLabel.Entry, продолжение в PrintVariantLabel.asm

                endmodule
                endmodule
