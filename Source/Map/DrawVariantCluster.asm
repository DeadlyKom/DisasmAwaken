                module Map
                module DrawVariantCluster
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [счётчик в AF', движение курсоров, мигание, шесть потоков и трёхстрочные фазы](../../Docs/AnimatedVariants.md)
; -----------------------------------------
; XOR центральной пятистрочной метки и последовательная анимация не более шести вариантов
; исходная запись 7, файловые смещения #0677..#06BF
; In:
;   DE - E содержит байтовую координату начала X, D содержит Y, оба значения до прибавления 4 и словного масштаба восемь
;   AF - A содержит счётчик, Carry входного F сохраняется в последующих DEC альтернативного счётчика
;   KARTA выбран и доступен для самомодификации, станционные экранные таблицы 8200..84FF подготовлены
;   для обычного пятистрочного центра масштабированное начало имеет нулевую фазу Y, все записываемые экранные адреса доступны
;   действуют договоры AnimateVariant0 и XorVariantPhase для фактически рисуемых вариантов, ресурсы подготовлены
; Out:
;   Count получает входной A, AF' первоначально получает входной AF, затем выполняются счётчик и курсоры обёрток
;   XOR центра использует пять масок 1C,3E,3E,3E,1C, начиная с четвёртого добавления к старшему байту адреса начала
;   BC - Base=(8*(((D+4)&FF)*256+((E+4)&FF))+0603)&FFFF, C есть BaseX, B есть BaseY
;   после центра исполнение без CALL переходит в AnimateVariant0, возвращаемые HL, DE, AF и AF' определяются последним обработанным вариантом
;   обновлены реально прочитанные курсоры, SpriteSource и маска мигания при выбранных ресурсах
;   HL', DE', BC', IX, IY, I и IFF сохраняются инструкциями цепочки, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF, AF', bitmap, Count, курсоры, SpriteSource и маска мигания
; Note:
;   прибавления 4 к E и D выполнены раздельно по байтам, последующее умножение и прибавление 0603 выполняются целым словом
;   при выходе E+4 за диапазон 0..31 после масштаба появляется перенос между упакованными координатами, код не заменён независимыми пиксельными формулами
;   файл является началом жёстко упорядоченной цепочки INCLUDE, настоящая завершающая RET находится в обёртке либо вызываемом пути
;   модель всего C677 использует четыре допустимых начала и все 256 счётчиков, произвольные начала, IRQ и игровой цикл не доказаны
; -----------------------------------------
                ; сохранение исходного количества в общем операнде селектора ресурсов
Entry:          LD (@MapVariantState.Count), A
                ; перенос входного количества и Carry в AF' для счётчика последовательных обёрток
                EX AF, AF'
                ; расчёт младшего байта начала как (E+4)&FF без переноса в Y
                LD A, @MapVariantConst.TileBias
                ADD A, E
                LD L, A
                ; расчёт старшего байта начала как (D+4)&FF перед общим словным масштабом
                LD A, @MapVariantConst.TileBias
                ADD A, D
                LD H, A
                ; масштабирование упакованного слова в восемь раз, переносы между байтами сохраняются
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ; сохранение масштабированного начала до рисования центральной метки
                PUSH HL
                EX DE, HL
                ; поиск экранного адреса по старшему Y и младшему X масштабированного начала
                LD L, D
                LD H, @StationScreenPage.RowHigh
                LD D, (HL)
                INC H
                LD A, (HL)
                INC H
                LD L, E
                OR (HL)
                LD E, A
                EX DE, HL
                ; расчёт первой строки метки четырьмя увеличениями старшего адресного байта
                INC H
                INC H
                INC H
                INC H
                ; добавление верхней маски 1C к пятистрочной центральной метке
                LD A, #1C
                XOR (HL)
                LD (HL), A
                INC H
                ; добавление трёх средних масок 3E на последовательных растровых строках
                LD A, #3E
                XOR (HL)
                LD (HL), A
                INC H
                LD A, #3E
                XOR (HL)
                LD (HL), A
                INC H
                LD A, #3E
                XOR (HL)
                LD (HL), A
                ; расчёт перехода с последней строки знакоместа к следующей строке Spectrum
                INC H
                LD A, L
                ADD A, #20
                LD L, A
                JR C, @Map.DrawVariantCluster.DrawCentreFoot                    ; переход, если прибавление 20 к младшему адресу дало перенос, коррекция старшего байта не нужна

                LD A, H
                SUB #08
                LD H, A
                ; добавление завершающей маски 1C к пятой строке центральной метки
DrawCentreFoot: LD A, #1C
                XOR (HL)
                LD (HL), A
                ; восстановление упакованного масштабированного начала и расчёт Base с добавлением 0603 целым словом
                POP HL
                LD BC, @MapVariantConst.TargetBias
                ADD HL, BC
                LD B, H
                LD C, L
                ; JP @Map.AnimateVariant0.Entry, продолжение в AnimateVariant0.asm

                endmodule
                endmodule
