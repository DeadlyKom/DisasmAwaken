                module Map
                module UpdateMapDistanceMinimum
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [оборачиваемые разности, строгое сравнение и самомодифицируемый минимум](../../Docs/MapDistanceMinimum.md)
; -----------------------------------------
; Обновление минимума квадрата расстояния от пары байтов до целевой точки
; исходная запись 7, файловые смещения #0653..#0676
; In:
;   HL - адрес двух последовательных байтов X,Y, DE - D целевой Y, E целевой X
;   MapDistanceState.Minimum содержит текущее беззнаковое слово минимума в операнде LD DE,nn
;   KARTA выбран и доступен для самомодификации, обычный стек доступен
; Out:
;   dx=(X-E)&FF, dy=(Y-D)&FF, их модули берутся после знаковой интерпретации байтов
;   q=abs(dx)^2+abs(dy)^2, 0<=q<=32768, сумма помещается в слово
;   Carry=1 и Minimum=q только при q<входного Minimum, иначе Carry=0 и Minimum сохранён
;   HL=входной HL+1 modulo 65536, DE и BC сохранены, AF - A=high(abs(dx)^2)
;   при отказе F точно соответствует SBC HL,DE для q-Minimum с Carry=0
;   при обновлении S,Z,P/V остаются от q-Minimum, H=N=0, Carry=1, биты 5 и 3 берутся из A
;   HL'=q при обновлении, иначе (q-Minimum)&FFFF, DE'=входной Minimum, B'=0, C' сохранён
;   AF' - A'=high(abs(dy)^2), F' соответствует логическим флагам low(abs(dy)^2), H=N=Carry=0
;   IX, IY, I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, AF, HL', DE', BC' только B', AF', операнд Minimum при строгом улучшении
; Note:
;   разности оборачиваются до байта перед проверкой знака, это не неограниченное расстояние двух обычных экранных координат
;   NEG от 80 оставляет 80, SumSquares8 принимает этот байт как беззнаковый модуль 128
;   равное расстояние не обновляет минимум, вызывающий сохраняет первый встретившийся вариант
;   HL остаётся на Y той же пары, процедура не переходит к следующей двухбайтовой записи
;   сброс минимума выполняет SelectNearestMapVariant, [достижимость действий](../../Docs/StationEventActions.md)
;   точные регистры и флаги учитывают фактический вызов SumSquares8 без подмены
; -----------------------------------------
                ; чтение X кандидата и переход указателя на Y той же пары
Entry:          LD A, (HL)
                INC HL
                ; расчёт оборачиваемой разности X кандидата и целевого E
                SUB E
                JP P, @Map.UpdateMapDistanceMinimum.AbsoluteX                   ; переход, если байтовая разность X неотрицательна, модуль уже получен

                ; расчёт модуля отрицательной байтовой разности X, 80 остаётся модулем 128
                NEG
                ; сохранение модуля X в альтернативном A для второго квадрата
AbsoluteX:      EX AF, AF'
                LD A, (HL)
                ; расчёт оборачиваемой разности Y кандидата и целевого D
                SUB D
                JP P, @Map.UpdateMapDistanceMinimum.Measure                     ; переход, если байтовая разность Y неотрицательна, модуль уже получен

                ; расчёт модуля отрицательной байтовой разности Y
                NEG
                ; сохранение входных указателя, цели и счётчика в альтернативных парах на время измерения
Measure:        EXX
                ; расчёт квадрата расстояния настоящим SumSquares8, сначала квадрат Y, затем X
                CALL @Map.SumSquares8.Entry
                ; загрузка самомодифицируемого слова текущего минимума
                LD DE, @MapMathConst.InitialMinimum
                ; сброс переноса перед беззнаковым сравнением квадрата расстояния и минимума
                OR A
                ; расчёт q-Minimum, заём означает строго более близкую точку
                SBC HL, DE
                ; восстановление указателя на Y, цели и счётчика без изменения флагов сравнения
                EXX
                RET NC                                                          ; выход, если квадрат расстояния не меньше текущего минимума, равенство сохраняет прежний выбор

                ; выбор вычисленных пар для восстановления q из отрицательной разности
                EXX
                ; расчёт исходного q обратным прибавлением старого минимума
                ADD HL, DE
                ; обновление слова минимума в операнде LD DE следующего вызова
                LD (@MapDistanceState.Minimum), HL
                ; флаг, Carry сообщает вызывающему о строгом улучшении минимума
                SCF
                ; восстановление пар вызывающего с сохранённым Carry обновления
                EXX
                RET

                endmodule
                endmodule
