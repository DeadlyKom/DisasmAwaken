                module Map
                module DrawArcRightUp
                ; Проверка [R и сохранение AF](../../Docs/ArcKernel.md#r-шести-обёрток-направления)
                ; Документация [Map](../../Docs/FunctionDetails/Map.md)
                ; Подробный разбор [входы, байтовые счётчики, общий кадр и границы моделей](../../Docs/ArcKernel.md)
                ; -----------------------------------------
                ; Сохранение AF, сброс рекурсии и проход от правого края вверх
                ; исходная запись 7, файловые смещения #2696..#269C
                ; In:
                ;   HL, DE, BC задают адреса и маски по договору RasterizeArcEdges.RightEdge
                ;   E' и C' задают начальные байтовые счётчики рекурсии, для обычного полного края E'=0 и C'=-Radius modulo 256
                ;   A' задаёт предел C' подключения второго края
                ;   обычный адрес возврата лежит по SP, остальная подготовка границ и режима соответствует RasterizeArcEdges
                ;   IRQ не вмешиваются, стек и bitmap не перекрывают исполняемый код
                ; Out:
                ;   AF целиком сохранён, RasterDown=0, перед ядром HL'=0, D'=0, B'=FF, C' и E' сохранены
                ;   исполнен RasterizeArcEdges.RightEdge с кадром SavedAF и прежним адресом возврата
                ;   bitmap, RasterStack, основные и альтернативные общие пары изменены по договору ядра
                ;   A' сохранён, F' рабочий, при нулевом счётчике возможен возврат с обменёнными парами EXX
                ;   IX, IY, I и IFF сами инструкции сохраняют, SP после обычного возврата равен входному SP+2
                ; Corrupt:
                ;   HL, DE, BC, HL', DE', BC', AF' только F', R, bitmap, RasterStack, RasterDown
                ; Note:
                ;   R меняется, собственная обёртка со сбросом добавляет 11 M1 к достигнутому проходу ядра, внешний CALL не включён
                ;   PUSH AF формирует внешний кадр до вызова сброса, ResetRasterUp не добавляет постоянного вложенного возврата
                ;   последний JP передаёт прежний адрес возврата ядру, возврат выполняется через POP AF и RET либо RasterStack
                ;   геометрические ограничения проверенных профилей перечислены в [разборе рекурсии](../../Docs/ArcRecurrence.md)
                ; -----------------------------------------
                ; сохранение полного AF перед растровым проходом правого края вверх
Entry:          PUSH AF
                ; сброс error и старших байтов счётчиков, начальные C' и E' сохраняются
                CALL @Map.ResetRasterUp.Entry
                ; продолжение нужного входа ядра с одним внешним кадром сохранённого AF
                JP @Map.RasterizeArcEdges.RightEdge

                endmodule
                endmodule
