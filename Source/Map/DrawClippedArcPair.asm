                module Map
                module DrawClippedArcPair
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [входы, байтовые счётчики, общий кадр и границы моделей](../../Docs/ArcKernel.md)
; -----------------------------------------
; Проходы вниз и вверх от исходной строки с выбором начального одиночного края
; исходная запись 7, файловые смещения #2228..#2247
; In:
;   DE - бит 0 E выбирает левый начальный край при единице и правый при нуле, BC - B исходное смещение для предела
;   MapArcState и таблицы подготовлены для PrepareArcLeftEdge и PrepareArcRightEdge, остальные биты входного E игнорируются
;   Entry вычисляет Limit=(B-операнд E22A)&FF, UseLimit по E22B принимает готовый Limit в основном A
;   действуют требования обёрток и RasterizeArcEdges, KARTA выбран, обычный стек доступен
; Out:
;   Limit перенесён в A', затем край подготовлен заново перед каждым проходом
;   первый проход идёт вниз, второй вверх от той же MapArcState.RowY, RasterDown после завершения равен 0
;   при обоих начавшихся проходах исходные граничные пиксели общей начальной строки инвертируются дважды
;   AF равен результату второй PrepareArcLeftEdge либо PrepareArcRightEdge и сохранён обёрткой прохода вверх
;   HL, DE, BC и альтернативные общие пары рабочие, A'=Limit, F' рабочий, LeftMask получает OffsetX на правом пути и сохраняется на левом
;   IX, IY, I и IFF сами инструкции сохраняют, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', bitmap, RasterStack, RasterDown, LeftMask на правом пути
; Note:
;   последний проход вызывается через JP с адресом возврата всей пары, дополнительной CALL не добавлено
;   настройщик D0C3 пишет HalfX-2 modulo 256 в E22A, исходное значение ноль в файле сохранено
;   выбор первого края делается по входному E, его нельзя подменять чтением MapArcState.QuadrantCode
;   [Пределы моделей](../../Docs/ArcRecurrence.md) отделены от общего диспетчера DFC3
; -----------------------------------------
                ; расчёт байтового предела C' из B и изменяемого HalfX-2
Entry:          LD A, B
                SUB @MapArcConst.InitialBias
                ; перенос подготовленного предела в A', общий вход UseLimit принимает его в основном A
UseLimit:       EX AF, AF'
                ; проверка младшего бита именно входного E для выбора начального края
                BIT 0, E
                JR Z, @Map.DrawClippedArcPair.UseRightEdge                      ; переход, если бит 0 входного E сброшен, начать с правого края

                ; подготовка левого края исходной строки для прохода вниз
                CALL @Map.PrepareArcLeftEdge.Entry
                ; инверсия прохода от левого края вниз с сохранением AF подготовки
                CALL @Map.DrawArcLeftDown.Entry
                ; повторная подготовка того же исходного левого края для прохода вверх
                CALL @Map.PrepareArcLeftEdge.Entry
                ; завершение пары проходом вверх с обычным адресом возврата всей процедуры
                JP @Map.DrawArcLeftUp.Entry

                ; подготовка правого края исходной строки для прохода вниз
UseRightEdge:   CALL @Map.PrepareArcRightEdge.Entry
                ; инверсия прохода от правого края вниз
                CALL @Map.DrawArcRightDown.Entry
                ; повторная подготовка исходного правого края перед движением вверх
                CALL @Map.PrepareArcRightEdge.Entry
                ; завершение пары правым проходом вверх без нового адреса возврата
                JP @Map.DrawArcRightUp.Entry

                endmodule
                endmodule
