                module Map
                module SelectNearestMapVariant
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [шесть курсоров, необычные количества и полная арифметика целевой пары](../../Docs/NearestMapVariant.md)
; -----------------------------------------
; Выбор первого ближайшего варианта карты по текущим парам координат
; исходная запись 7, файловые смещения #05E8..#0652
; In:
;   HL - входная упакованная пара Origin, AF - A число вариантов, F не влияет на результат
;   StationState.PointerXY содержит PointerWord, Cursor0..Cursor5 в MapVariantState указывают на доступные пары X,Y
;   KARTA выбран и доступен для самомодификации, MapSelection.Variant доступен для записи, обычный стек доступен
; Out:
;   DE=Target=(PointerWord-(8*((Origin+0404)&FFFF)+0603))&FFFF, D целевой Y, E целевой X
;   N=A при A=1..5, иначе N=6, рассмотрены первые N курсоров в исходном порядке
;   MapDistanceState.Minimum содержит минимальную сумму квадратов знаковых байтовых разностей от Target
;   HL=Cursor[N-1]+1 modulo 65536, BC - C индекс первого минимального варианта 0..N-1
;   B=0 при N<6, иначе B=(входной A-5)&FF, A и MapSelection.Variant равны C
;   при N<6 F=42 OR Carry последнего сравнения, при N=6 F сохранён от последнего UpdateMapDistanceMinimum
;   HL', DE', BC', AF' соответствуют последнему UpdateMapDistanceMinimum, B'=0, C' сохранён
;   IX, IY, I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC' только B', AF', Minimum и MapSelection.Variant
; Note:
;   первый кандидат всегда уменьшает начальное FFFF, поскольку сумма квадратов не превышает 32768
;   при равных расстояниях индекс не меняется, получается первый из ближайших кандидатов
;   количество 0 не означает пустой список, оно и любое A>=6 приводят к рассмотрению шести курсоров
;   Origin складывается и масштабируется целым словом, переносы между координатными байтами не разделяются
;   курсорные операнды и исходные пары не меняются, формат остальной части потоков ещё разбирается
;   помощник расстояния учитывает знаковые байтовые разности, [его отдельный договор](../../Docs/MapDistanceMinimum.md)
;   достижимость восстановлена через [действия интерфейса](../../Docs/StationEventActions.md)
; -----------------------------------------
                ; чтение текущей упакованной позиции указателя для преобразования в координаты вариантов
Entry:          LD DE, (@StationState.PointerXY)
                ; расчёт смещённой входной пары Origin+0404 с общим словным переносом
                LD BC, @MapVariantConst.OriginBias
                ADD HL, BC
                ; масштабирование всей смещённой пары в восемь раз тремя удвоениями слова
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ; расчёт полного смещения вариантов добавлением исходной пары 0603
                LD BC, @MapVariantConst.TargetBias
                ADD HL, BC
                ; расчёт разности текущего указателя и полного смещения после очистки Carry
                EX DE, HL
                OR A
                SBC HL, DE
                EX DE, HL
                ; сброс изменяемого минимума к FFFF, любой первый квадрат расстояния меньше этого слова
                LD HL, @MapMathConst.InitialMinimum
                LD (@MapDistanceState.Minimum), HL
                ; подготовка оставшегося количества, ноль исходным кодом не отсекается
                LD B, A
                ; чтение текущего курсора координат варианта 0
                LD HL, (@MapVariantState.Cursor0)
                ; проверка строгого улучшения текущего минимального расстояния
                CALL @Map.UpdateMapDistanceMinimum.Entry
                JR NC, @Map.SelectNearestMapVariant.AfterFirst                  ; переход, если вариант 0 не ближе прежнего, сохранить выбранный индекс

                ; обновление выбранного индекса после строгого улучшения минимума
                LD C, #00
                ; расчёт оставшегося количества после очередного кандидата
AfterFirst:     DEC B
                JR Z, @Map.SelectNearestMapVariant.StoreChoice                  ; переход, если исходное количество кандидатов исчерпано, сохранить выбранный индекс

                ; чтение текущего курсора координат варианта 1
                LD HL, (@MapVariantState.Cursor1)
                ; проверка строгого улучшения текущего минимального расстояния
                CALL @Map.UpdateMapDistanceMinimum.Entry
                JR NC, @Map.SelectNearestMapVariant.AfterSecond                 ; переход, если вариант 1 не ближе прежнего, сохранить выбранный индекс

                ; обновление выбранного индекса после строгого улучшения минимума
                LD C, #01
                ; расчёт оставшегося количества после очередного кандидата
AfterSecond:    DEC B
                JR Z, @Map.SelectNearestMapVariant.StoreChoice                  ; переход, если исходное количество кандидатов исчерпано, сохранить выбранный индекс

                ; чтение текущего курсора координат варианта 2
                LD HL, (@MapVariantState.Cursor2)
                ; проверка строгого улучшения текущего минимального расстояния
                CALL @Map.UpdateMapDistanceMinimum.Entry
                JR NC, @Map.SelectNearestMapVariant.AfterThird                  ; переход, если вариант 2 не ближе прежнего, сохранить выбранный индекс

                ; обновление выбранного индекса после строгого улучшения минимума
                LD C, #02
                ; расчёт оставшегося количества после очередного кандидата
AfterThird:     DEC B
                JR Z, @Map.SelectNearestMapVariant.StoreChoice                  ; переход, если исходное количество кандидатов исчерпано, сохранить выбранный индекс

                ; чтение текущего курсора координат варианта 3
                LD HL, (@MapVariantState.Cursor3)
                ; проверка строгого улучшения текущего минимального расстояния
                CALL @Map.UpdateMapDistanceMinimum.Entry
                JR NC, @Map.SelectNearestMapVariant.AfterFourth                 ; переход, если вариант 3 не ближе прежнего, сохранить выбранный индекс

                ; обновление выбранного индекса после строгого улучшения минимума
                LD C, #03
                ; расчёт оставшегося количества после очередного кандидата
AfterFourth:    DEC B
                JR Z, @Map.SelectNearestMapVariant.StoreChoice                  ; переход, если исходное количество кандидатов исчерпано, сохранить выбранный индекс

                ; чтение текущего курсора координат варианта 4
                LD HL, (@MapVariantState.Cursor4)
                ; проверка строгого улучшения текущего минимального расстояния
                CALL @Map.UpdateMapDistanceMinimum.Entry
                JR NC, @Map.SelectNearestMapVariant.AfterFifth                  ; переход, если вариант 4 не ближе прежнего, сохранить выбранный индекс

                ; обновление выбранного индекса после строгого улучшения минимума
                LD C, #04
                ; расчёт оставшегося количества после очередного кандидата
AfterFifth:     DEC B
                JR Z, @Map.SelectNearestMapVariant.StoreChoice                  ; переход, если исходное количество кандидатов исчерпано, сохранить выбранный индекс

                ; чтение текущего курсора координат варианта 5
                LD HL, (@MapVariantState.Cursor5)
                ; проверка строгого улучшения текущего минимального расстояния
                CALL @Map.UpdateMapDistanceMinimum.Entry
                JR NC, @Map.SelectNearestMapVariant.StoreChoice                 ; переход, если вариант 5 не ближе прежнего, сохранить выбранный индекс

                ; обновление выбранного индекса после строгого улучшения минимума
                LD C, #05
                ; сохранение индекса первого ближайшего варианта в общем состоянии карты
StoreChoice:    LD A, C
                LD (@MapSelection.Variant), A
                RET

                endmodule
                endmodule
