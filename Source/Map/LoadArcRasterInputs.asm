                module Map
                module LoadArcRasterInputs
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [загрузка полей, точные крайние адреса и побочная запись LeftMask](../../Docs/ArcPreparation.md)
; -----------------------------------------
; Загрузка смещений и радиуса с подготовкой C'=-Radius и E'=0
; исходная запись 7, файловые смещения #2278..#2288
; In:
;   MapArcState.OffsetY, OffsetX, QuadrantCode и Radius содержат рабочие байты дуги, KARTA выбран
; Out:
;   HL сохранён, DE=Radius*256+QuadrantCode, BC=OffsetX*256+OffsetY
;   AF - A=(-Radius)&255, F соответствует NEG исходного Radius, включая особый P/V при Radius=80
;   HL', D', B', AF', IX, IY, I и IFF сохранены, C'=(-Radius)&255, E'=0
;   исходные поля не меняются, SP обычного возврата равен входному SP+2
; Corrupt:
;   DE, BC, AF, C', E'
; Note:
;   C' и E' инициализируются для последующей рекуррентной растровой петли, HL', D', B' здесь не сбрасываются
;   QuadrantCode копируется целиком в E, эта процедура не проверяет его биты
; -----------------------------------------
                ; загрузка горизонтального и вертикального смещений для последующей подготовки края
Entry:          LD BC, (@MapArcState.OffsetY)
                ; загрузка радиуса в D и кода квадранта в E как двух соседних исходных байтов
                LD DE, (@MapArcState.QuadrantCode)
                ; расчёт отрицательного радиуса для начального альтернативного C
                LD A, D
                NEG
                ; обновление только C' и E', альтернативные HL', D', B' принадлежат отдельному сбросу
                EXX
                LD C, A
                LD E, #00
                EXX
                RET

                endmodule
                endmodule
