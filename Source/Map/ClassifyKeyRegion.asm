                module Map
                module ClassifyKeyRegion
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [прямоугольники, числовые признаки и шаг рабочего ключа](../../Docs/WorldSignature.md)
; -----------------------------------------
; Классификация байтов H и L по трём прямоугольникам и внешней области
; исходная запись 7, файловые смещения #2779..#27B9
; In:
;   HL - два независимых беззнаковых байта классифицируемого первого слова
; Out:
;   HL, DE и BC сохранены, A=0 для H=#4A..#4D и L=#36..#39
;   A=1 для H=#47..#49 и L=#34..#37, A=2 для H=#47..#49 и L=#38..#3A, иначе A=3
;   F соответствует последнему CP, точная разбивка приведена в WorldSignature.md
;   альтернативные и индексные регистры, I и IFF сохранены, SP восстановлен
; Corrupt:
;   AF
; Note:
;   старшие границы прямоугольников исключённые, геометрия проверяется во всех 65536 парах
;   числа областей доказаны, их игровые имена и единицы координат здесь не установлены
; -----------------------------------------
                ; проверка верхнего байта на нижнюю границу прямоугольника 0
Entry:          LD A, H
                CP #4A
                JR C, @Map.ClassifyKeyRegion.TryRegion1                         ; переход, если H меньше #4A, проверить область 1

                ; проверка исключённой верхней границы H области 0
                CP #4E
                JR NC, @Map.ClassifyKeyRegion.TryRegion1                        ; переход, если H не меньше #4E, проверить область 1

                ; проверка нижней границы L области 0
                LD A, L
                CP #36
                JR C, @Map.ClassifyKeyRegion.TryRegion1                         ; переход, если L меньше #36, проверить область 1

                ; проверка исключённой верхней границы L области 0
                CP #3A
                LD A, #00
                RET C                                                           ; выход, если L меньше #3A при принятых остальных границах, вернуть область 0

                ; проверка диапазона H области 1
TryRegion1:     LD A, H
                CP #47
                JR C, @Map.ClassifyKeyRegion.TryRegion2                         ; переход, если H меньше #47, проверить область 2

                ; проверка исключённой верхней границы H области 1
                CP #4A
                JR NC, @Map.ClassifyKeyRegion.TryRegion2                        ; переход, если H не меньше #4A, проверить область 2

                ; проверка нижней границы L области 1
                LD A, L
                CP #34
                JR C, @Map.ClassifyKeyRegion.TryRegion2                         ; переход, если L меньше #34, проверить область 2

                ; проверка исключённой верхней границы L области 1
                CP #38
                LD A, #01
                RET C                                                           ; выход, если L меньше #38 при принятых остальных границах, вернуть область 1

                ; проверка нижней границы H области 2
TryRegion2:     LD A, H
                CP #47
                LD A, #03
                RET C                                                           ; выход, если H меньше #47, вернуть внешнюю область 3

                ; проверка исключённой верхней границы H области 2
                LD A, H
                CP #4A
                LD A, #03
                RET NC                                                          ; выход, если H не меньше #4A, вернуть внешнюю область 3

                ; проверка нижней границы L области 2
                LD A, L
                CP #38
                LD A, #03
                RET C                                                           ; выход, если L меньше #38, вернуть внешнюю область 3

                ; проверка исключённой верхней границы L области 2
                LD A, L
                CP #3B
                LD A, #02
                RET C                                                           ; выход, если L меньше #3B при принятых остальных границах, вернуть область 2

                ; выбор внешней области после отказа последнего прямоугольника
                LD A, #03
                RET

                endmodule
                endmodule
