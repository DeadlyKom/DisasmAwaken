                module Map
                module MeasureCoordinateDistance
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [раскладка координат, рамка и полный арифметический путь](../../Docs/CoordinateDistance.md)
; -----------------------------------------
; Расстояние упакованных координат с делением суммы квадратов на 9 и кодом FF
; исходная запись 7, файловые смещения #27BA..#2837
; In:
;   HL сохраняемый контекст, DE - D старший Y0, E старший X0, BC - B младший Y0, C младший X0
;   HL' сохраняемый контекст, DE' - D' старший Y1, E' старший X1, BC' - B' младший Y1, C' младший X1
;   AF и AF' произвольны, IX и IY сохраняемые значения, доступен стек FMapDistanceFrame и временные слова
;   KARTA и исходные страницы SeededSqrt16 доступны, действуют договоры MultiplySigned16 и DivideSigned32To16
; Out:
;   HL сохранён, DE и BC рабочие значения по перечисленным ниже путям
;   AF - A=0 при совпадении координат, A=FF при сумме квадратов больше FFFF
;   для остальных входов A=max(1,floor(sqrt(floor((dx*dx+dy*dy)/9)))), результат 1..85
;   dx и dy модули знаковых 16-битных разностей с оборачиванием, MapState.LastDistance всегда получает A
;   при совпадении DE=Y0, BC=0, F=44
;   при переполнении квадрата dy DE младшее слово вычисленного квадрата, BC=dx, F от OR байтов старшего слова
;   при переполнении квадрата dx DE младшее слово вычисленного квадрата, BC=0, F от OR байтов старшего слова
;   при переносе суммы DE=dx*dx, BC=dx, F от ADD HL,DE, Carry=1
;   при успешной арифметике DE=floor(сумма/9) при частном>=256, иначе DE=9, BC последняя нечётная разность SeededSqrt16
;   при ненулевом корне F от OR A, при принудительном минимуме 1 F=0
;   HL', DE', BC' сохранены, AF' сохранён при совпадении и раннем переполнении
;   при успешной арифметике AF' по DivideSigned32To16 и SeededSqrt16, точный выбор приведён в документации
;   IX, IY, I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   DE, BC, AF, AF' только на успешном арифметическом пути
; Note:
;   из четырёх пар регистров собираются X0=(E<<8)|C, Y0=(D<<8)|B и аналогично X1,Y1 из альтернативного набора
;   знак разности определяется S после 16-битного вычитания, переполнение разности отдельно не проверяется
;   квадраты считаются реальным знаковым ядром, его особый случай 8000 тоже даёт ненулевое старшее слово и выбирает FF
;   сумма проверяется до деления, поэтому FF возможен при математическом расстоянии меньше 255
;   при допустимой сумме положительный числитель делится на положительные 9, частное не больше 7281
;   пограничные верхние строки SeededSqrt16 на этом успешном пути недостижимы
;   Carry и Z не являются единым признаком ошибки, FF устанавливается LD A без пересчёта флагов
;   координатные игровые единицы и все потребители результата ещё требуют отдельной трассировки
; -----------------------------------------
                ; сохранение HL, IX, IY и альтернативного HL в исходном порядке FMapDistanceFrame
Entry:          PUSH HL
                PUSH IX
                PUSH IY
                EXX
                PUSH HL
                EXX
                ; перегруппировка младших байтов точки 0 для формирования X0 в BC и Y0 в DE
                LD A, B
                LD B, E
                LD E, A
                EXX
                ; сборка X1 из альтернативных C и E с сохранением самих альтернативных пар
                LD A, C
                EXX
                LD L, A
                EXX
                LD A, E
                EXX
                LD H, A
                ; сброс Carry перед расчётом разности X1-X0
                OR A
                ; расчёт шестнадцатибитной разности X с исходным оборачиванием
                SBC HL, BC
                JP P, @Map.MeasureCoordinateDistance.DifferenceY                ; переход, если обёрнутая разность X неотрицательна, использовать её без отрицания

                ; расчёт модуля отрицательной обёрнутой разности X дополнительным кодом
                LD A, L
                CPL
                LD L, A
                LD A, H
                CPL
                LD H, A
                INC HL
                ; сохранение модуля dx в BC и сборка Y1 из альтернативных B и D
DifferenceY:    LD B, H
                LD C, L
                EXX
                LD A, B
                EXX
                LD L, A
                EXX
                LD A, D
                EXX
                LD H, A
                ; сброс Carry перед расчётом Y1-Y0
                OR A
                ; расчёт обёрнутой шестнадцатибитной разности Y
                SBC HL, DE
                JP P, @Map.MeasureCoordinateDistance.CheckCoincident            ; переход, если обёрнутая разность Y неотрицательна, использовать её без отрицания

                ; расчёт модуля отрицательной обёрнутой разности Y
                LD A, L
                CPL
                LD L, A
                LD A, H
                CPL
                LD H, A
                INC HL
                ; проверка совпадения точек по обоим байтам dx и dy
CheckCoincident:LD A, L
                OR H
                OR C
                OR B
                JR Z, @Map.MeasureCoordinateDistance.StoreResult                ; переход, если обе разности нулевые, вернуть ноль без арифметических ядер

                ; сохранение dx на время вычисления 32-битного квадрата dy
                PUSH BC
                LD D, H
                LD E, L
                ; расчёт квадрата dy исходным MultiplySigned16
                CALL @Map.MultiplySigned16.Entry
                POP BC
                ; проверка старшего слова квадрата dy до суммирования
                LD A, L
                OR H
                JR NZ, @Map.MeasureCoordinateDistance.Overflow                  ; переход, если квадрат dy не помещается в слово, вернуть FF

                ; сохранение младшего слова квадрата dy перед расчётом квадрата dx
                PUSH DE
                LD D, B
                LD E, C
                LD H, B
                LD L, C
                ; расчёт квадрата dx исходным MultiplySigned16
                CALL @Map.MultiplySigned16.Entry
                ; проверка старшего слова квадрата dx с восстановлением квадрата dy в HL
                LD A, L
                OR H
                POP HL
                JR NZ, @Map.MeasureCoordinateDistance.Overflow                  ; переход, если квадрат dx не помещается в слово, вернуть FF

                ; расчёт суммы двух квадратов в пределах одного слова
                ADD HL, DE
                JR C, @Map.MeasureCoordinateDistance.Overflow                   ; переход, если сумма квадратов превысила FFFF, вернуть FF до деления

                ; выбор положительного знака делителя через исходный F от XOR A
                XOR A
                ; упаковка суммы в A и альтернативный A для 32-битного числителя с нулевым старшим словом
                LD A, H
                EX AF, AF'
                LD A, L
                EX AF, AF'
                ; выбор квадрата масштаба 3, делителя 9
                LD DE, @MapDistanceConst.ScaleSquared
                ; обнуление старших 16 бит числителя, сумма уже ограничена словом
                LD HL, #0000
                ; расчёт целого положительного частного суммы квадратов на 9
                CALL @Map.DivideSigned32To16.Entry
                EX DE, HL
                ; расчёт корня частного, доказанный вход не превышает 7281
                CALL @Map.SeededSqrt16.Entry
                ; проверка нулевого корня при заведомо несовпадающих точках
                OR A
                JR NZ, @Map.MeasureCoordinateDistance.StoreResult               ; переход, если корень ненулевой, сохранить его без минимального ограничения

                ; установка минимального ненулевого расстояния 1 для отличающихся точек
                INC A
                ; восстановление четырёх сохранённых пар из FMapDistanceFrame перед записью результата
StoreResult:    EXX
                POP HL
                EXX
                POP IY
                POP IX
                POP HL
                ; сохранение байтового результата для дальнейших потребителей карты
                LD (@MapState.LastDistance), A
                RET

                ; выбор кода FF при переполнении квадрата либо их суммы без изменения флагов причины
Overflow:       LD A, @MapDistanceConst.OverflowCode
                JR @Map.MeasureCoordinateDistance.StoreResult

                endmodule
                endmodule
