                module Map
                module BuildMapPointOutcodes
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [пятибайтовая точка, разряды границ и оборачивание при количестве 0](../../Docs/MapPointOutcodes.md)
; -----------------------------------------
; Классификация рабочих точек по изменяемым верхним порогам и OR кодов границ
; исходная запись 7, файловые смещения #1430..#148A
; In:
;   StopX и StopY обозначают байты изменяемых CP по D44D и D468, исходно оба FF
;   после D0C3 StopX=(MaxX+1) AND FF, StopY=(MaxY+1) AND FF, минимумы не сдвигают нулевую нижнюю границу
;   HL' - адрес байта описания количества, используется только младшая тетрада
;   MapClipState.Points содержит доступные записи FProjectedPoint по пять байтов, KARTA выбран
;   для обычного прохода количество N=1..15, поля X и Y читаются как знаковые 16-битные координаты
;   при N=0 нужна вся доступная страница F800..F8FF, код обработает её с оборачиванием L
; Out:
;   в ClipCodes каждой обработанной записи записан младший код выхода и дополнение его разрядов в старшей тетраде
;   разряды 0..3 означают соответственно X>=StopX, X<0, Y>=StopY и Y<0
;   разряды 4..7 являются дополнениями соответствующих разрядов 0..3, точка внутри имеет ClipCodes=F0
;   HL=F800+((5*N+1) AND FF), DE сохранён, B=5*N, C младший код последней обработанной точки
;   AF содержит OR всех записанных ClipCodes и логические флаги этого OR
;   HL', DE', BC' сохранены, AF' содержит A'=5*N и F' от CP A',B при равных значениях
;   IX, IY, I и IFF сохранены, SP обычного возврата равен входному SP+2
;   при N=0 обработаны 256 циклических записей, итоговые N в формулах указателя и B остаются нулевыми
; Corrupt:
;   HL, BC, AF, AF'
; Note:
;   при положительных StopX и StopY внутри разрешены X=0..StopX-1 и Y=0..StopY-1, исходный профиль даёт 0..254
;   нулевой Stop исключает все неотрицательные координаты данной оси, Max=255 не задаёт полный диапазон
;   настройка и границы моделей описаны в [фазах исполнения](../../Docs/MapRuntimeProfiles.md)
;   байт ClipCodes не является восемью независимыми флагами, старшая тетрада связана с младшей дополнением
;   нулевой ClipCodes не формируется для обычной координаты, нейтральное DB 00 структуры не означает готовую классификацию
;   при N=0 шаг по L равен пяти, обход посещает все 256 позиций страницы и меняет координаты будущих циклических записей
;   известный прямой вызов из D1AC предварительно возвращается при количестве 0 и 1, другие возможные входы этим не исключаются
;   это классификация рабочих координат, полный алгоритм последующего отсечения и проекции ещё разбирается
; -----------------------------------------
                ; выбор старшего байта X первой рабочей записи FProjectedPoint
Entry:          LD HL, @MapClipState.Points + FProjectedPoint.X + 1
                ; обнуление OR-накопителя в AF альтернативного набора
                XOR A
                EX AF, AF'
                ; чтение младшей тетрады описания через альтернативный HL без изменения самого указателя
                EXX
                LD A, (HL)
                EXX
                ; расчёт конечного байтового смещения как пять полей на каждую рабочую точку
                AND @MapClipConst.CountMask
                LD B, A
                ADD A, A
                ADD A, A
                ADD A, B
                LD B, A
                ; сброс четырёх признаков текущей точки перед проверкой координат
NextPoint:      LD C, #00
                ; проверка старшего байта X для отрицательного либо положительного выхода
                LD A, (HL)
                AND A
                JP M, @Map.BuildMapPointOutcodes.SetLeft                        ; переход, если X отрицателен, установить признак левой стороны

                JP NZ, @Map.BuildMapPointOutcodes.SetRight                      ; переход, если положительный старший байт X ненулевой, установить правую сторону

                ; проверка младшего X относительно изменяемого исключённого порога StopX при нулевом старшем байте
                DEC L
                LD A, (HL)
                INC L
                CP @MapClipConst.ExcludedEnd
                JR NC, @Map.BuildMapPointOutcodes.SetRight                      ; переход, если младший X не меньше StopX, установить признак правой стороны

                JP @Map.BuildMapPointOutcodes.TestY

                ; установка признака X<0 в младшем коде текущей точки
SetLeft:        SET @MapClipBit.Left, C
                JP @Map.BuildMapPointOutcodes.TestY

                ; установка признака X>=StopX в младшем коде текущей точки
SetRight:       SET @MapClipBit.Right, C
                ; переход от старшего X к старшему Y той же пятибайтовой записи
TestY:          INC L
                INC L
                ; проверка старшего байта Y для верхнего либо нижнего выхода
                LD A, (HL)
                AND A
                JP M, @Map.BuildMapPointOutcodes.SetTop                         ; переход, если Y отрицателен, установить признак верхней стороны

                JP NZ, @Map.BuildMapPointOutcodes.SetBottom                     ; переход, если положительный старший байт Y ненулевой, установить нижнюю сторону

                ; проверка младшего Y относительно изменяемого исключённого порога StopY при нулевом старшем байте
                DEC L
                LD A, (HL)
                INC L
                CP @MapClipConst.ExcludedEnd
                JR NC, @Map.BuildMapPointOutcodes.SetBottom                     ; переход, если младший Y не меньше StopY, установить признак нижней стороны

                JP @Map.BuildMapPointOutcodes.StoreBounds

                ; установка признака Y<0 в младшем коде текущей точки
SetTop:         SET @MapClipBit.Top, C
                JP @Map.BuildMapPointOutcodes.StoreBounds

                ; установка признака Y>=StopY в младшем коде текущей точки
SetBottom:      SET @MapClipBit.Bottom, C
                ; расчёт ClipCodes, младшая тетрада содержит код C, старшая его четырёхбитное дополнение
StoreBounds:    INC L
                LD A, C
                RLCA
                RLCA
                RLCA
                RLCA
                XOR @MapClipConst.Complement
                OR C
                ; сохранение ClipCodes и включение его в общий OR-накопитель альтернативного AF
                LD (HL), A
                EX AF, AF'
                OR (HL)
                EX AF, AF'
                ; проверка конца по младшему адресу после записи, следующий HL сразу у старшего X новой записи
                INC L
                LD A, L
                INC L
                CP B
                JP NZ, @Map.BuildMapPointOutcodes.NextPoint                     ; переход, если конечное смещение ещё не достигнуто, обработать следующую циклическую запись

                ; возврат общего OR кодов в основном AF, альтернативный AF получает последнее сравнение конца
                EX AF, AF'
                RET

                endmodule
                endmodule
