                module Map
                module AppendRightClipIntersection
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [полный и кэшированный входы, старое деление и точный байтовый выход](../../Docs/ClipIntersections.md)
; -----------------------------------------
; Добавление пересечения с правой границей окна в выходной список
; исходная запись 7, файловые смещения #1A52..#1AAF
; In:
;   MinX, MinY, MaxX, MaxY обозначают изменяемые операнды границ, исходно 0, 0, 255, 255
;   после D0C3 они равны параметрам установщика, сравнение младшего Y с 192 остаётся неизменным
;   MapClipWork.FirstPoint и SecondPoint содержат координаты, KARTA выбран
;   делитель (SecondPoint.X-FirstPoint.X) modulo 65536 ненулевой, действует ограничение частного DivideSigned32To16
;   полный Entry сначала вызывает ComputeRightClipProduct, UseProduct требует заранее правильного RightProduct
;   для UseProduct BC является исходным контекстом деления, AF - исходный F передаёт Carry альтернативному набору делителя
;   IXH для UseProduct сохраняется делением, полный Entry может предварительно изменить IX через умножение
;   OutputSize является байтовым смещением, оба адресуемых байта страницы MapClipState.Output доступны для записи
; Out:
;   деление получает 32-битный RightProduct и разность X2-X1 с исходными знаками и оборачиванием
;   к частному прибавлено FirstPoint.Y modulo 65536, затем координата преобразована в выходной байт
;   для Y, отрицательное слово даёт MinY, иначе проверяется только младший байт, значения 0..191 сохраняются, 192..255 заменяются на MaxY
;   в выходной список записаны два байта X=MaxX, Y=рассчитанный байт
;   HL=F900 OR новый OutputSize, DE содержит Ybyte в D и исходный FirstPoint.Ylow в E при сохранении младшего Y, при насыщении DE=FirstPoint.Y
;   BC соответствует DivideSigned32To16, его исходный BC берётся от ComputeRightClipProduct либо от вызывающего UseProduct
;   A и OutputSize равны (прежний OutputSize+2) modulo 256, F от второго INC L с сохранённым Carry ветви преобразования
;   Carry равен 1 только на ветви сохранения младшего Y, иначе 0
;   HL', DE', BC' сохранены, AF' соответствует DivideSigned32To16 с Carry от F перед начальным EX AF,AF'
;   IXH сохраняет вход делителя, IXL равно числу отрицательных аргументов деления минус один по модулю 256
;   IY, I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF, AF', IX
; Note:
;   обе фазы проверены отдельно, [изменяемые операнды](../../Docs/MapRuntimeProfiles.md)
;   UseProduct находится сразу после трёхбайтового CALL и не пересчитывает произведение, оба входа используют обычный адрес возврата
;   деление сохраняет свои исходные особенности отрицательных значений, переставлять или упрощать формулу нельзя
;   в вертикальных пересечениях положительный старший байт Y не проверяется отдельно, допустимый младший байт может обернуть большое положительное Y
;   первый и второй выходные байты адресуются через INC L, переход размера через FF не меняет страницу F9
;   полный Entry изменяет только свой слот произведения, UseProduct сохраняет все слоты, координаты и ClipCodes точек не меняются
;   выходные флаги относятся к размеру списка и преобразованию байта, они не являются статусом геометрического принятия сегмента
; -----------------------------------------
                ; расчёт собственного произведения перед последовательным входом UseProduct
Entry:          CALL @Map.ComputeRightClipProduct.Entry
                ; загрузка младшего слова кэшированного произведения в A и альтернативный A для деления
UseProduct:     LD A, (@MapClipWork.RightProduct.LowWord)
                EX AF, AF'
                LD A, (@MapClipWork.RightProduct.LowWord + 1)
                LD HL, (@MapClipWork.SecondPoint.X)
                LD DE, (@MapClipWork.FirstPoint.X)
                ; очистка Carry перед расчётом полной разности координат для делителя
                OR A
                ; расчёт знакового делителя с исходным 16-битным оборачиванием
                SBC HL, DE
                EX DE, HL
                LD HL, (@MapClipWork.RightProduct.HighWord)
                ; вычисление частного настоящим DivideSigned32To16 с его исходной обработкой знаков
                CALL @Map.DivideSigned32To16.Entry
                LD DE, (@MapClipWork.FirstPoint.Y)
                ; прибавление исходной координаты первой точки к частному по модулю 65536
                ADD HL, DE
                ; проверка старшей части рассчитанной координаты перед преобразованием в выходной байт
                LD A, H
                AND A
                JP M, @Map.AppendRightClipIntersection.ClampYBelow              ; переход, если рассчитанное слово Y отрицательно, записать выходной Y=MinY

                LD A, L
                ; проверка только младшего Y относительно 192, положительный старший байт отдельно не сравнивается
                CP @MapClipConst.VisibleYEnd
                JP C, @Map.AppendRightClipIntersection.StoreY                   ; переход, если младший Y меньше 192, записать этот байт без дополнительного ограничения старшего

                ; чтение текущего байтового смещения для добавления двухбайтовой выходной точки
                LD A, (@MapClipWork.OutputSize)
                LD L, A
                LD H, @MapClipConst.OutputPage
                ; выбор изменяемой границы MaxX, исходное значение операнда сохранено
                LD (HL), @MapClipConst.ExcludedEnd
                ; продвижение к байту Y той же выходной точки
                INC L
                ; выбор изменяемой границы MaxY, исходное значение операнда сохранено
                LD (HL), @MapClipConst.ExcludedEnd
                ; расчёт следующего байтового размера с оборачиванием внутри страницы F9
                INC L
                LD A, L
                ; обновление OutputSize после записи двух байтов без проверки ёмкости страницы
                LD (@MapClipWork.OutputSize), A
                RET

                ; чтение текущего байтового смещения для добавления двухбайтовой выходной точки
ClampYBelow:    LD A, (@MapClipWork.OutputSize)
                LD L, A
                LD H, @MapClipConst.OutputPage
                ; выбор изменяемой границы MaxX, исходное значение операнда сохранено
                LD (HL), @MapClipConst.ExcludedEnd
                ; продвижение к байту Y той же выходной точки
                INC L
                ; выбор изменяемой границы MinY, исходное значение операнда сохранено
                LD (HL), @MapClipConst.MinCoordinate
                ; расчёт следующего байтового размера с оборачиванием внутри страницы F9
                INC L
                LD A, L
                ; обновление OutputSize после записи двух байтов без проверки ёмкости страницы
                LD (@MapClipWork.OutputSize), A
                RET

                ; сохранение разрешённого младшего Y для записи выходной точки
StoreY:         LD D, L
                ; чтение текущего байтового смещения для добавления двухбайтовой выходной точки
                LD A, (@MapClipWork.OutputSize)
                LD L, A
                LD H, @MapClipConst.OutputPage
                ; выбор изменяемой границы MaxX, исходное значение операнда сохранено
                LD (HL), @MapClipConst.ExcludedEnd
                ; продвижение к байту Y той же выходной точки
                INC L
                ; запись Y выходной точки, значение рассчитанного байта D
                LD (HL), D
                ; расчёт следующего байтового размера с оборачиванием внутри страницы F9
                INC L
                LD A, L
                ; обновление OutputSize после записи двух байтов без проверки ёмкости страницы
                LD (@MapClipWork.OutputSize), A
                RET

                endmodule
                endmodule
