                module Map
                module SeekRasterRowUp
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [табличные координаты краёв и ограниченный поиск без замены SP](../../Docs/RasterPreparation.md)
; -----------------------------------------
; Обычный поиск до B строк вверх с включённой верхней границей
; исходная запись 7, файловые смещения #25E3..#2620
; In:
;   BC - B максимальное число шагов 0..255, входной C игнорируется, AF - A исходный относительный Y и сохраняемый F
;   RowHigh и RowLow построены для области, Column обозначает операнд OR, исходно 0, D0C3 записывает ColumnByte[MaxX]
;   MapState.UpperRow содержит выровненный по восьми строкам адрес границы с нулевой колонкой
;   Column находится в диапазоне 0..31, нижняя и верхняя границы различаются и выровнены по восьми строкам
;   исходная строка лежит в допустимой области, стек доступен для FBoundedRasterSeekFrame и временного HL
; Out:
;   начальный младший адрес равен RowLow[A] OR Column, Column сохраняется при переходах строк
;   HL - адрес после не более B шагов вверх, остановка на включённой UpperRow без выхода выше неё
;   DE получает UpperRow при выполнении хотя бы одной проверки границы, иначе сохраняется
;   BC - B исходный, C равен входному A, AF целиком восстановлен
;   все альтернативные и индексные регистры, I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE при проверке границы, BC только C
; Note:
;   при B=0 сразу возвращает исходный табличный адрес, DE не меняется
;   сохранённый BC уже содержит C=исходный A, прежний входной C не восстанавливается
;   проверка границы выполняется только на переходах восьмистрочных блоков
;   это обычный RET с восстановлением AF, MapState.RasterStack не читается и не изменяется
;   настоящий писатель D0C3 и настроенный поиск проверены в [фазах исполнения](../../Docs/MapRuntimeProfiles.md), невыравненные границы и Column>=32 не входят в этот договор
; -----------------------------------------
                ; замена C исходным Y и создание кадра сохранённых AF и BC
Entry:          LD C, A
                LD A, C
                PUSH AF
                PUSH BC
                ; поиск исходного адреса строки, изменяемый OR добавляет Column без переноса в старший адрес
                LD L, A
                LD H, @MapMarkerConst.RowHighPage
                LD B, (HL)
                INC H
                LD A, (HL)
                OR #00
                LD L, A
                LD H, B
                ; возврат исходного счётчика B и проверка нулевого количества без изменения B
                POP BC
                PUSH BC
                DEC B
                INC B
                JR Z, @Map.SeekRasterRowUp.RestoreInput                         ; переход, если исходное число шагов B равно нулю, восстановить AF и BC

                ; расчёт предыдущей пиксельной строки, состояние старого H определяет переход блока
StepUp:         LD A, H
                DEC H
                AND #07
                JR Z, @Map.SeekRasterRowUp.TestUpper                            ; переход, если у прежнего H младшие три разряда равнялись нулю, проверить верхнюю границу

                DJNZ @Map.SeekRasterRowUp.StepUp

                ; восстановление исходного B, заменённого C и полного входного AF перед обычным RET
RestoreInput:   POP BC
                POP AF
                RET

                ; возврат прежнего H и сравнение текущей строки без колонки с включённой UpperRow
TestUpper:      INC H
                PUSH HL
                LD A, L
                AND #E0
                LD L, A
                LD DE, (@MapState.UpperRow)
                OR A
                SBC HL, DE
                POP HL
                JR Z, @Map.SeekRasterRowUp.RestoreInput                         ; переход, если текущая строка равна UpperRow, вернуть её без перехода выше

                ; расчёт перехода к предыдущему восьмистрочному блоку после проверки верхней границы
                DEC H
                LD A, L
                SUB #20
                LD L, A
                JR C, @Map.SeekRasterRowUp.CountStep                            ; переход, если вычитание 20 дало заём, адрес уже перешёл в предыдущую треть экрана

                ; коррекция H при переходе строки без займа младшего байта
                LD A, H
                ADD A, #08
                LD H, A
CountStep:      DJNZ @Map.SeekRasterRowUp.StepUp

                JR @Map.SeekRasterRowUp.RestoreInput

                endmodule
                endmodule
