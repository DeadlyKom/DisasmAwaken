                module XorSelectionBand
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [ядро подсветки строк в банке 1](../../Docs/SelectionBand.md)
; -----------------------------------------
; Инверсия восьми пиксельных строк с 0..31 полными байтами и попарными флагами краёв
; исходная запись 7, файловые смещения #0908..#09B8
; In:
;   HL - экранный адрес начала, соответствующий пиксельному Y=0..184 и байтовой колонке X=0..31
;   DE - D сохраняемый контекст, E восемь попарных битов пропуска краёв для четырёх чередующихся строк
;   BC - B число полных байтов 0..31, исходный C не используется
;   в окне #C000 выбран банк 1 с исходным кодом MAP, операнд WidthSkip доступен для записи
;   обычный стек и код не пересекают изменяемый bitmap, повторного входа с изменением WidthSkip нет
; Out:
;   HL - экранный адрес того же X для Y+8, при Y=184 адрес уже относится к атрибутам, но там запись не выполняется
;   DE сохранён, E восстанавливает исходное значение после 16 вращений, B=0, C младший адрес начала восьмой строки
;   A - результат последнего шага экранного адреса, F=#42 OR Carry этого шага
;   для заданных экранных координат итоговый Carry=1 только при начальном Y=56, 120, 184
;   восемь строк изменены через XOR, WidthSkip=4*(31-входной B)
;   альтернативные и индексные регистры, I и IFF сохраняются, SP восстанавливается
; Corrupt:
;   HL, BC, AF
; Note:
;   каждая пара битов E задаёт пропуск левого и правого края, 1 пропускает, 0 применяет частичную маску
;   левый край XOR #1F с увеличением младшего адреса, затем B полных байтов XOR #FF, правый край XOR #F8
;   младший адрес увеличивается через INC L без переноса в H, выход за горизонтальную строку не отсекается этим ядром
;   для обычной полосы каждый проход требует X+B+число_применяемых_краёв<=32, модель отдельно проверяет и физическое оборачивание вне этого условия
;   две RRC E на строку дают повтор четырёхстрочного рисунка краёв дважды, общий сдвиг 16 бит возвращает E
;   самомодифицируемый JR пропускает 4*(31-B) байтов развёрнутого ядра, число строк независимо задаётся значением 8
;   нулевой B пропускает все полные байты, частичные края продолжают работать
;   итоговый Z всегда установлен от DEC B, он не показывает наличие изменённых пикселей
;   на выходе A равен фазе Y AND 7 при ненулевой фазе, иначе младшему адресу после E+32 при переносе либо новому H после коррекции
;   физическое переключение страниц моделью ядра не выполняется, банк 1 является явным входным контекстом
; -----------------------------------------
                ; выбор пятибитового максимума 31 для расчёта пропуска полных байтов
Entry:          LD A, @SelectionBandConst.Low5Mask
                ; расчёт числа пропускаемых четырёхбайтовых участков как 31-B
                SUB B
                ; расчёт байтового смещения JR двумя удвоениями числа пропусков
                ADD A, A
                ADD A, A
                ; обновление одного операнда WidthSkip в банке 1 до начала восьмистрочного прохода
                LD (@MapHighlightState.WidthSkip), A
                ; выбор восьми пиксельных строк независимо от ширины
                LD B, @ScreenConst.PixelsPerChar
                ; сохранение младшего адреса текущей строки перед обработкой её байтов
NextRow:        LD C, L
                ; проверка очередного бита пропуска левого края через RRC E
                RRC E
                JR C, @Map.XorSelectionBand.WidthJump                           ; переход, если бит пропуска левого края равен 1, не применять частичную маску #1F

                ; инверсия пяти младших пикселей левого края и переход к полным байтам
                LD A, @SelectionBandConst.Low5Mask
                XOR (HL)
                LD (HL), A
                INC L
                ; изменяемый JR выбирает вход развёрнутого ядра с требуемым числом полных байтов
WidthJump:      JR @Map.XorSelectionBand.Full31

                ; развёрнутая инверсия 31 полного байта, более короткие входы пропускают начальные участки
Full31:         LD A, (HL)
                CPL
                LD (HL), A
                INC L
Full30:         LD A, (HL)
                CPL
                LD (HL), A
                INC L
