                CPL
                LD (HL), A
                INC L
Full7:          LD A, (HL)
                CPL
                LD (HL), A
                INC L
Full6:          LD A, (HL)
                CPL
                LD (HL), A
                INC L
Full5:          LD A, (HL)
                CPL
                LD (HL), A
                INC L
Full4:          LD A, (HL)
                CPL
                LD (HL), A
                INC L
Full3:          LD A, (HL)
                CPL
                LD (HL), A
                INC L
Full2:          LD A, (HL)
                CPL
                LD (HL), A
                INC L
Full1:          LD A, (HL)
                CPL
                LD (HL), A
                INC L
                ; проверка следующего бита пропуска правого края, даже при нулевом числе полных байтов
RightEdge:      RRC E
                JR C, @Map.XorSelectionBand.AdvanceRow                          ; переход, если бит пропуска правого края равен 1, не применять частичную маску #F8

                ; инверсия пяти старших пикселей правого края без дополнительного шага L
                LD A, @SelectionBandConst.High5Mask
                XOR (HL)
                LD (HL), A
                ; возврат младшего адреса начала строки перед вертикальным переходом
AdvanceRow:     LD L, C
                ; расчёт старшего адреса следующей пиксельной строки
                INC H
                ; проверка окончания восьмистрочного знакоместа по трём младшим разрядам H
                LD A, H
                AND @ScreenConst.PixelOffsetMask
                JP NZ, @Map.XorSelectionBand.CountRows                          ; переход, если новая строка остаётся внутри знакоместа, не корректировать строку знакомест

                ; расчёт младшего адреса следующей строки знакомест через прибавление 32
                LD A, L
                ADD A, @ScreenConst.ByteColumns
                LD L, A
                JR C, @Map.XorSelectionBand.CountRows                           ; переход, если прибавление 32 дало перенос, сохранить уже увеличенный H

                ; расчёт коррекции H на минус восемь при переходе знакоместа без переноса L
                LD A, H
                SUB @ScreenConst.PixelsPerChar
                LD H, A
                ; расчёт оставшегося числа пиксельных строк
CountRows:      DEC B
                JP NZ, @Map.XorSelectionBand.NextRow                            ; переход, если обработаны ещё не все восемь строк, продолжить с очередной парой битов E

                RET

