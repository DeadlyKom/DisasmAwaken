                module Map
                module FindStoredMapPoint
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [пятибайтовые записи, пустоты FF и отрицательный ограничитель](../../Docs/StoredMapPoints.md)
; -----------------------------------------
; Проверка наличия выбранного ключа в первом списке сохранённых точек
; исходная запись 7, файловые смещения #0894..#08C1
; In:
;   MapSelection.FirstWord и SecondWord задают искомый ключ, первый список начинается по 990A
;   достижим отрицательный первый байт не равный FF либо совпадение двух слов, записи доступны по шагу 5
; Out:
;   при совпадении HL=0, DE у старшего байта SecondWord найденной записи, BC=искомый SecondWord, AF=0044
;   при отсутствии DE у первого байта ограничителя, A равен этому байту 80..FE, Sign=1 и Z=0
;   при отсутствии HL и BC остаются от последнего сравнения либо входными, если сравнений не было
;   F отсутствия определяется DEC после INC маркера, Carry сохраняется от предыдущего пути и не является признаком наличия
;   MapSelection.Variant не меняется, пятый байт совпавшей записи не читается
;   все альтернативные и индексные регистры, I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   FF обнаруживается через INC A и пропускается до проверки Sign, возвращается только отрицательный не-FF ограничитель
;   сначала сравнивается FirstWord, затем SecondWord, пять прибавлений DE распределены между общими хвостами
;   здесь результат наличия задают Z и Sign, перенос от вычитания не следует использовать вместо них
;   модель проверяет все первые байты, девять позиций, четыре пятых байта и оба исхода сравнения второго слова
; -----------------------------------------
                ; выбор начала первого списка сохранённых ключей карты
Entry:          LD DE, @StoredMapPointsA.Point00
                ; проверка пустоты FF через оборачивание INC перед проверкой отрицательного конца
ReadMarker:     LD A, (DE)
                INC A
                JR Z, @Map.FindStoredMapPoint.SkipEmpty                         ; переход, если исходный первый байт равнялся FF, пропустить пять байтов записи

                DEC A
                RET M                                                           ; выход, если первый байт отрицательный и не FF, ключ до конца списка не найден

                ; чтение и сравнение первого слова положительной записи
                LD L, A
                INC DE
                LD A, (DE)
                LD H, A
                INC DE
                LD BC, (@MapSelection.FirstWord)
                OR A
                SBC HL, BC
                JR NZ, @Map.FindStoredMapPoint.SkipFirst                        ; переход, если первые слова различаются, пропустить остаток записи

                ; чтение и сравнение второго слова после совпадения первого
                LD A, (DE)
                LD L, A
                INC DE
                LD A, (DE)
                LD H, A
                LD BC, (@MapSelection.SecondWord)
                OR A
                SBC HL, BC
                JR NZ, @Map.FindStoredMapPoint.SkipSecond                       ; переход, если вторые слова различаются, перейти к следующему первому байту

                ; формирование AF=0044 при совпадении обоих слов, поле Variant не читается
                XOR A
                RET

                ; пропуск пустой записи через общие хвосты прибавления указателя
SkipEmpty:      INC DE
                INC DE
SkipFirst:      INC DE
SkipSecond:     INC DE
                INC DE
                JR @Map.FindStoredMapPoint.ReadMarker

                endmodule
                endmodule
