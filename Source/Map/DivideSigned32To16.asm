                module DivideSigned32To16
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [старшее слово и два байта, знак во входном F и точные варианты частного](../../Docs/SignedDivision.md)
; -----------------------------------------
; Деление 32-битного числителя на слово DE с исходной обработкой знака дополнением
; исходная запись 7, файловые смещения #1CFB..#1DAF
; In:
;   HL старшее слово 32-битного N, AF - A следующий байт, AF' - A' младший байт N
;   DE ненулевой знаковый делитель d, входной флаг Sign основного F обязан совпадать со знаком d
;   U=N при N>=0, иначе U=-N-1, требуется U<abs(d)*65536 для допустимого 16-битного частного
;   входные Carry основного F и F' произвольны, влияют на точные выходные флаги, KARTA доступна
; Out:
;   HL частное q=floor(U/abs(d)) при одинаковых знаках, иначе HL=q XOR FFFF
;   DE модуль d, BC исходное старшее слово N при N<0, иначе исходный d при d<0, иначе BC сохранён
;   AF - A старший байт выходного HL, точный F от восьмой попытки старшего байта и восстановления знака
;   HL', DE', BC' сохранены, AF' - A' младший байт выходного HL, точные флаги младшего завершения описаны в документации
;   IX - IXH сохранён, IXL равен числу отрицательных входов минус один по модулю 256
;   IY, I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE на отрицательном d, BC на отрицательном входе, AF, AF', IX только IXL
; Note:
;   первый переход проверяет именно входной Sign, собственная проверка старшего бита D до неё отсутствует
;   отрицательный числитель дополняется побитово целиком, единица не прибавляется, поэтому U=abs(N)-1
;   по очереди обрабатываются восемь битов A и восемь битов A альтернативного набора, остаток ведётся в HL
;   при недостаточном остатке вычитание делителя отменяется, Carry=1 кодирует нулевой бит частного
;   накапливается дополненное частное, при чётном числе отрицательных входов оба его байта инвертируются
;   при нечётном числе отрицательных входов дополненное частное оставляется, это не обычное округление к нулю
;   остаток на выходе не сохраняется, HL заменяется собранными байтами частного
;   деление на ноль и переполнение частного не обрабатываются, находятся за границей доказанного числового договора
; -----------------------------------------
                ; обнуление счётчика отрицательных входов в IXL без проверки знака D
Entry:          LD IXL, #00
                JP P, @Map.DivideSigned32To16.CheckNumerator                    ; переход, если входной Sign сброшен, считать делитель неотрицательным

                ; расчёт модуля отрицательного делителя через временное сохранение его слова в BC
                EX DE, HL
                LD B, H
                LD C, L
                LD HL, #0000
                ; сброс Carry перед отрицанием делителя как 0 минус исходное слово
                OR A
                SBC HL, BC
                EX DE, HL
                ; учёт отрицательного делителя при последующем выборе дополнения частного
                INC IXL
                ; проверка знака числителя по старшему биту его старшего слова
CheckNumerator: BIT 7, H
                JR Z, @Map.DivideSigned32To16.DivideBit15                       ; переход, если числитель неотрицателен, начать побитное деление без его дополнения

                ; дополнение младшего байта числителя через альтернативный AF, Carry сохраняется
                EX AF, AF'
                CPL
                EX AF, AF'
                ; дополнение следующего байта числителя без прибавления единицы
                CPL
                ; расчёт дополненного старшего слова как 0 минус старшее слово минус один
                LD B, H
                LD C, L
                LD HL, #0000
                ; выбор заёма единица для побитового дополнения старшего слова через SBC
                SCF
                SBC HL, BC
                ; учёт отрицательного числителя, полный исходный модуль на единицу меньше abs(N)
                INC IXL
                ; выдвижение бита 15 нижнего слова числителя и накопление предыдущего дополненного бита ответа
DivideBit15:    RLA
                ; расчёт удвоенного остатка с включением очередного входного бита
                ADC HL, HL
                ; проверка возможности вычесть модуль делителя из текущего остатка
                SBC HL, DE
                JR NC, @Map.DivideSigned32To16.DivideBit14                      ; переход, если остаток не меньше делителя, оставить вычитание и нулевой дополненный бит

                ; восстановление остатка после недостаточного вычитания, Carry=1 становится дополненным битом ответа
                ADD HL, DE
                ; выдвижение бита 14 нижнего слова числителя и накопление предыдущего дополненного бита ответа
DivideBit14:    RLA
                ; расчёт удвоенного остатка с включением очередного входного бита
                ADC HL, HL
                ; проверка возможности вычесть модуль делителя из текущего остатка
                SBC HL, DE
                JR NC, @Map.DivideSigned32To16.DivideBit13                      ; переход, если остаток не меньше делителя, оставить вычитание и нулевой дополненный бит

                ; восстановление остатка после недостаточного вычитания, Carry=1 становится дополненным битом ответа
                ADD HL, DE
                ; выдвижение бита 13 нижнего слова числителя и накопление предыдущего дополненного бита ответа
DivideBit13:    RLA
                ; расчёт удвоенного остатка с включением очередного входного бита
                ADC HL, HL
                ; проверка возможности вычесть модуль делителя из текущего остатка
                SBC HL, DE
                JR NC, @Map.DivideSigned32To16.DivideBit12                      ; переход, если остаток не меньше делителя, оставить вычитание и нулевой дополненный бит

                ; восстановление остатка после недостаточного вычитания, Carry=1 становится дополненным битом ответа
                ADD HL, DE
                ; выдвижение бита 12 нижнего слова числителя и накопление предыдущего дополненного бита ответа
DivideBit12:    RLA
                ; расчёт удвоенного остатка с включением очередного входного бита
                ADC HL, HL
                ; проверка возможности вычесть модуль делителя из текущего остатка
                SBC HL, DE
                JR NC, @Map.DivideSigned32To16.DivideBit11                      ; переход, если остаток не меньше делителя, оставить вычитание и нулевой дополненный бит

                ; восстановление остатка после недостаточного вычитания, Carry=1 становится дополненным битом ответа
                ADD HL, DE
                ; выдвижение бита 11 нижнего слова числителя и накопление предыдущего дополненного бита ответа
DivideBit11:    RLA
                ; расчёт удвоенного остатка с включением очередного входного бита
                ADC HL, HL
                ; проверка возможности вычесть модуль делителя из текущего остатка
                SBC HL, DE
                JR NC, @Map.DivideSigned32To16.DivideBit10                      ; переход, если остаток не меньше делителя, оставить вычитание и нулевой дополненный бит

                ; восстановление остатка после недостаточного вычитания, Carry=1 становится дополненным битом ответа
                ADD HL, DE
                ; выдвижение бита 10 нижнего слова числителя и накопление предыдущего дополненного бита ответа
DivideBit10:    RLA
                ; расчёт удвоенного остатка с включением очередного входного бита
                ADC HL, HL
                ; проверка возможности вычесть модуль делителя из текущего остатка
                SBC HL, DE
                JR NC, @Map.DivideSigned32To16.DivideBit09                      ; переход, если остаток не меньше делителя, оставить вычитание и нулевой дополненный бит

                ; восстановление остатка после недостаточного вычитания, Carry=1 становится дополненным битом ответа
                ADD HL, DE
                ; выдвижение бита 9 нижнего слова числителя и накопление предыдущего дополненного бита ответа
DivideBit09:    RLA
                ; расчёт удвоенного остатка с включением очередного входного бита
                ADC HL, HL
                ; проверка возможности вычесть модуль делителя из текущего остатка
                SBC HL, DE
                JR NC, @Map.DivideSigned32To16.DivideBit08                      ; переход, если остаток не меньше делителя, оставить вычитание и нулевой дополненный бит

                ; восстановление остатка после недостаточного вычитания, Carry=1 становится дополненным битом ответа
                ADD HL, DE
                ; выдвижение бита 8 нижнего слова числителя и накопление предыдущего дополненного бита ответа
DivideBit08:    RLA
                ; расчёт удвоенного остатка с включением очередного входного бита
                ADC HL, HL
                ; проверка возможности вычесть модуль делителя из текущего остатка
                SBC HL, DE
                JR NC, @Map.DivideSigned32To16.SwitchLowByte                    ; переход, если остаток не меньше делителя, оставить вычитание и нулевой дополненный бит

                ; восстановление остатка после недостаточного вычитания, Carry=1 становится дополненным битом ответа
                ADD HL, DE
                ; завершение старшего байта дополненного частного последним битом Carry
SwitchLowByte:  RLA
                ; выбор младшего входного байта, старший байт частного остаётся в альтернативном AF
                EX AF, AF'
                ; выдвижение бита 7 нижнего слова числителя и накопление предыдущего дополненного бита ответа
DivideBit07:    RLA
                ; расчёт удвоенного остатка с включением очередного входного бита
                ADC HL, HL
                ; проверка возможности вычесть модуль делителя из текущего остатка
                SBC HL, DE
                JR NC, @Map.DivideSigned32To16.DivideBit06                      ; переход, если остаток не меньше делителя, оставить вычитание и нулевой дополненный бит

                ; восстановление остатка после недостаточного вычитания, Carry=1 становится дополненным битом ответа
                ADD HL, DE
                ; выдвижение бита 6 нижнего слова числителя и накопление предыдущего дополненного бита ответа
DivideBit06:    RLA
                ; расчёт удвоенного остатка с включением очередного входного бита
                ADC HL, HL
                ; проверка возможности вычесть модуль делителя из текущего остатка
                SBC HL, DE
                JR NC, @Map.DivideSigned32To16.DivideBit05                      ; переход, если остаток не меньше делителя, оставить вычитание и нулевой дополненный бит

                ; восстановление остатка после недостаточного вычитания, Carry=1 становится дополненным битом ответа
                ADD HL, DE
                ; выдвижение бита 5 нижнего слова числителя и накопление предыдущего дополненного бита ответа
DivideBit05:    RLA
                ; расчёт удвоенного остатка с включением очередного входного бита
                ADC HL, HL
                ; проверка возможности вычесть модуль делителя из текущего остатка
                SBC HL, DE
                JR NC, @Map.DivideSigned32To16.DivideBit04                      ; переход, если остаток не меньше делителя, оставить вычитание и нулевой дополненный бит

                ; восстановление остатка после недостаточного вычитания, Carry=1 становится дополненным битом ответа
                ADD HL, DE
