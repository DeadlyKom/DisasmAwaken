                ; восстановление остатка после недостаточного вычитания, Carry=1 становится дополненным битом ответа
                ADD HL, DE
                ; выдвижение бита 1 нижнего слова числителя и накопление предыдущего дополненного бита ответа
DivideBit01:    RLA
                ; расчёт удвоенного остатка с включением очередного входного бита
                ADC HL, HL
                ; проверка возможности вычесть модуль делителя из текущего остатка
                SBC HL, DE
                JR NC, @Map.DivideSigned32To16.DivideBit00                      ; переход, если остаток не меньше делителя, оставить вычитание и нулевой дополненный бит

                ; восстановление остатка после недостаточного вычитания, Carry=1 становится дополненным битом ответа
                ADD HL, DE
                ; выдвижение бита 0 нижнего слова числителя и накопление предыдущего дополненного бита ответа
DivideBit00:    RLA
                ; расчёт удвоенного остатка с включением очередного входного бита
                ADC HL, HL
                ; проверка возможности вычесть модуль делителя из текущего остатка
                SBC HL, DE
