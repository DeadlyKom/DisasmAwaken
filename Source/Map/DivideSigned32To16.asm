                ; восстановление остатка после недостаточного вычитания, Carry=1 становится дополненным битом ответа
                ADD HL, DE
                ; завершение младшего байта дополненного частного последним битом Carry
FinishQuotient: RLA
                ; проверка числа отрицательных входов, только один отрицательный вход даёт нулевой IXL
                DEC IXL
                JR NZ, @Map.DivideSigned32To16.ComplementPair                   ; переход, если число отрицательных входов равно нулю или двум, инвертировать оба байта частного

                ; сборка оставленного дополненного частного при одном отрицательном входе
                LD L, A
                EX AF, AF'
                LD H, A
                RET

                ; восстановление обычных битов младшего байта при одинаковых знаках входов
ComplementPair: CPL
                LD L, A
                ; выбор старшего байта частного с его сохранёнными флагами восьмой попытки
                EX AF, AF'
                ; восстановление обычных битов старшего байта при одинаковых знаках входов
                CPL
