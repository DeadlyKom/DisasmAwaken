DivideBit04:    RLA
                ; расчёт удвоенного остатка с включением очередного входного бита
                ADC HL, HL
                ; проверка возможности вычесть модуль делителя из текущего остатка
                SBC HL, DE
                JR NC, @Map.DivideSigned32To16.DivideBit03                      ; переход, если остаток не меньше делителя, оставить вычитание и нулевой дополненный бит

                ; восстановление остатка после недостаточного вычитания, Carry=1 становится дополненным битом ответа
                ADD HL, DE
                ; выдвижение бита 3 нижнего слова числителя и накопление предыдущего дополненного бита ответа
DivideBit03:    RLA
                ; расчёт удвоенного остатка с включением очередного входного бита
                ADC HL, HL
                ; проверка возможности вычесть модуль делителя из текущего остатка
                SBC HL, DE
                JR NC, @Map.DivideSigned32To16.DivideBit02                      ; переход, если остаток не меньше делителя, оставить вычитание и нулевой дополненный бит

                ; восстановление остатка после недостаточного вычитания, Carry=1 становится дополненным битом ответа
                ADD HL, DE
                ; выдвижение бита 2 нижнего слова числителя и накопление предыдущего дополненного бита ответа
DivideBit02:    RLA
                ; расчёт удвоенного остатка с включением очередного входного бита
                ADC HL, HL
                ; проверка возможности вычесть модуль делителя из текущего остатка
                SBC HL, DE
