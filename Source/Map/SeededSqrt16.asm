; Подробный разбор [начальное приближение, нечётные разности и ограничения таблиц](../../Docs/SeededRoot.md)
; -----------------------------------------
; Целый корень через табличное начальное приближение с исходной верхней областью таблиц
; исходная запись 7, файловые смещения #2838..#28BD
; In:
;   HL сохраняемый контекст только для выхода малого входа, DE беззнаковое число N
;   для N>=256 страницы EB, EC, ED содержат фактические исходные таблицы KARTA
;   код карты доступен в текущем банковом окне, CPU-стек содержит возврат
; Out:
;   HL остаток после последней выполненной попытки вычитания нечётной разности, при раннем выходе обёрнут по модулю 65536
;   DE исходное N при N>=256, входной HL при N<256, это следствие EX DE,HL малого пути
;   BC последняя отрицательная нечётная разность, задаваемая текущим приближением
;   AF - A вычисленное приближение корня, F от последнего ADD HL,BC либо заключительного INC A
;   при раннем RET NC Carry=0, при предельном возврате после последнего INC A Carry=1
;   для исходных таблиц A=floor(sqrt(N)) при N=0..59647, для N=59648..65535 значение не совпадает
;   HL', DE', BC' сохранены, AF' сохранён при N<256
;   при N>=256 A'=таблица EC[D_вход], F'=A8 при EB[D_вход]=FF, иначе A9
;   IX, IY, I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE только при N<256, BC, AF, AF' только при N>=256
; Note:
;   малый путь N<256 начинает с нуля и проверяет 15 нечётных разностей, после них возвращает 15
;   для старшего байта d>0 начальное a=255-EB[d], r=(EC[d]+256*ED[d]+N) AND FFFF, b=-(2*a+1)
;   выполняется до шести прибавлений b к r, отсутствие Carry возвращает текущий a
;   между успешными вычитаниями a увеличивается на один, b уменьшается на два
;   если все шесть попыток дали Carry, последнее INC A возвращает начальное a+6 без дополнительного вычитания
;   точные флаги сохраняют особенности INC H и последующих ADD, не являются обычным статусом числового корня
;   изменения этих страниц во время игры и достижимость верхнего диапазона требуют отдельной трассировки, байты не исправлены
; -----------------------------------------
                ; проверка старшего байта беззнакового входа для выбора табличного либо малого пути
Entry:          LD A, D
                AND A
                JR Z, @Map.SeededSqrt16.SmallWord                               ; переход, если N меньше 256, начать последовательное вычитание нечётных чисел с единицы

                ; выбор строки начального приближения по старшему байту N
                LD L, A
                LD H, @MapRootConst.SeedPage
                ; чтение исходного байта, его дополнение задаёт начальное приближение корня
                LD A, (HL)
                ; переход к странице младших байтов начального смещения, INC H задаёт промежуточные флаги
                INC H
                LD C, A
                ; расчёт начального приближения как побитового дополнения прочитанного байта
                CPL
                ; сохранение приближения и его флагов в альтернативном AF на время выбора исходного смещения
                EX AF, AF'
                ; расчёт отрицательной нечётной разности минус два начальных приближения минус один
                LD B, #FF
                INC BC
                SLA C
                RL B
                DEC BC
                ; чтение младшего байта табличного смещения, оно не подменяется идеальным квадратом
                LD A, (HL)
                ; переход к странице старших байтов смещения с сохранением переноса из расчёта BC
                INC H
                LD H, (HL)
                LD L, A
                ; восстановление начального приближения из альтернативного AF
                EX AF, AF'
                ; расчёт начального остатка как вход плюс фактическое табличное смещение по модулю 65536
                ADD HL, DE
                ; проверка следующего квадрата вычитанием нечётной разности из остатка, попытка 1
                ADD HL, BC
                RET NC                                                          ; выход, если остаток меньше очередной нечётной разности, сохранить текущее приближение

                ; расчёт следующей отрицательной разности уменьшением BC на два
