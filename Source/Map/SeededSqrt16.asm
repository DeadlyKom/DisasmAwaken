                DEC BC
                ; расчёт следующего приближения после подтверждённого квадрата
                INC A
                ; проверка следующего квадрата вычитанием нечётной разности из остатка, попытка 2
                ADD HL, BC
                RET NC                                                          ; выход, если остаток меньше очередной нечётной разности, сохранить текущее приближение

