                module Map
                module SetupMapRasterWindow
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [69 изменяемых байтов и проверенные профили потребителей](../../Docs/MapRuntimeProfiles.md)
; -----------------------------------------
; Настройка границ отсечения, половин размеров и крайних адресов растрового окна
; исходная запись 7, файловые смещения #10C3..#11AB
; In:
;   HL - H=MaxY, L=MaxX, DE - D=MinY, E=MinX, параметры беззнаковые байты
;   MapScreenTables по EE00, EF00 и F000 построены, банк KARTA выбран и доступен для самомодификации
;   исходный код, четыре угловые пары и все 69 назначений записей доступны, минимумы и максимумы не проверяются
; Out:
;   четыре угла получают пары MinX/MaxX и MinY/MaxY, произведения и выходные пересечения получают соответствующие границы
;   пороги классификатора равны (MaxX+1)&FF и (MaxY+1)&FF, сравнение младшего Y с 192 в пересечениях не меняется
;   HalfX=((MaxX+1)&FF) SHR 1, HalfY=(((MaxY+1)&FF) SHR 1) OR (80 при HalfX<2)
;   операнды растрового ядра получают HalfX, HalfX-2 modulo 256, HalfY, MaxY и MaxX+1 modulo 256
;   MapState.UpperRow=RowHigh[0]:RowLow[0], LowerRow=RowHigh[(MaxY+1)&FF]:RowLow[(MaxY+1)&FF]
;   левые колонки получают ColumnByte[0], правые и колонки поиска получают ColumnByte[MaxX]
;   HL=F000+MaxX, DE=MapState.UpperRow, BC - B сохранён, C=MaxX
;   AF - A=ColumnByte[MaxX], F=B0 OR ((MaxY+1)&1)
;   HL', DE', BC', AF', IX, IY, I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC только C, AF, 69 байтов операндов и состояния окна
; Note:
;   после SUB 2 перенос не сбрасывается перед RRA для HalfY, при HalfX<2 он устанавливает бит 7
;   проверены все пары максимальных границ при Min=0 и все пары минимальных границ при MaxX=239, MaxY=175
;   механика настройки не доказывает корректность произвольного прямоугольника, классификатор не сдвигает нижний предел с нуля
;   вызов из станционного действия установлен по [новым входам интерфейса](../../Docs/StationEventActions.md)
;   точный каталог назначений, модели потребителей и их ограничения приведены в [фазах исполнения](../../Docs/MapRuntimeProfiles.md)
;   эта процедура не выполняет рисование и не устанавливает режим четырёх изменяемых JR хвостов дуги
; -----------------------------------------
                ; обновление изменяемых пар нижнего правого и верхнего левого углов из входных HL и DE
Entry:          LD (#DAD7), HL
                LD (#DAB6), DE
                ; перестановка только X между двумя парами для нижнего левого и верхнего правого углов
                LD A, L
                LD L, E
                LD E, A
                ; обновление двух оставшихся пар углов без изменения исходных значений Y
                LD (#DACC), HL
                LD (#DAC1), DE
                ; выбор MaxY для нижнего произведения и значений насыщения выходных пересечений
                LD A, H
                LD (#D90D), A
                LD (#D9DA), A
                LD (#D9ED), A
                LD (#DA29), A
                LD (#DA87), A
                ; расчёт исключённого порога Y как MaxY+1 по модулю 256
                INC A
                LD (#D468), A
                ; выбор MinY для верхнего произведения и нижнего насыщения отрицательных Y
                LD A, D
                LD (#D8EE), A
                LD (#D98F), A
                LD (#D9A2), A
                LD (#DA3A), A
                LD (#DA98), A
                ; выбор MaxX для правого произведения и положительного насыщения X
                LD A, E
                LD (#D940), A
                LD (#D997), A
                LD (#D9E2), A
                LD (#DA84), A
                LD (#DA95), A
                LD (#DAA7), A
                ; расчёт исключённого порога X как MaxX+1 по модулю 256
                INC A
                LD (#D44D), A
                ; выбор MinX для левого произведения и отрицательного насыщения X
                LD A, L
                LD (#D921), A
                LD (#D98C), A
                LD (#D9D7), A
                LD (#DA26), A
                LD (#DA37), A
                LD (#DA49), A
                ; расчёт индекса исключённой нижней строки, H=(MaxY+1)&FF
                INC H
                ; восстановление MaxY только в A для изменяемых ограничений растрового ядра
                LD A, H
                DEC A
                LD (#DFBE), A
                LD (#E0ED), A
                LD (#E112), A
                ; расчёт оборачиваемого MaxX+1 для двух ограничений ядра дуги
                LD A, E
                INC A
                LD (#E078), A
                LD (#E1DB), A
                ; сброс переноса перед делением оборачиваемой ширины пополам
                OR A
                ; расчёт HalfX без входного переноса, значение размножается по рабочим операндам
                RRA
                LD (#E109), A
                LD (@MapArcState.ReferenceX), A
                LD (#E00A), A
                LD (#E017), A
                LD (#E021), A
                LD (#E071), A
                LD (#E1BA), A
                LD (#E089), A
                LD (#E1F3), A
                LD (#E07E), A
                LD (#E1E8), A
                LD (#DFC2), A
                LD (#DFC1), A
                LD (#E0E4), A
                ; расчёт HalfX-2 по модулю 256, заём намеренно остаётся входом следующего RRA
                SUB #02
                LD (#E173), A
                LD (#E22A), A
                LD (#E0C3), A
                ; расчёт HalfY из оборачиваемого MaxY+1 и переноса сравнения HalfX с двумя
                LD A, H
                RRA
                LD (#DFC0), A
                LD (#E006), A
                LD (#E094), A
                LD (#E1BE), A
                ; сохранение MaxX в C для заключительного обращения к таблице колонок
                LD C, E
                ; поиск адреса исключённой нижней строки по двум разнесённым таблицам
                LD L, H
                LD H, @MapMarkerConst.RowHighPage
                LD D, (HL)
                INC H
                LD E, (HL)
                ; обновление MapState.LowerRow без добавления горизонтальной колонки
                LD (@MapState.LowerRow), DE
                ; поиск адреса верхней строки с индексом ноль независимо от MinY
                LD HL, #EE00
                LD D, (HL)
                INC H
                LD E, (HL)
                ; выбор страницы ColumnByte и нулевого X для левых колонок
                INC H
                LD L, #00
                ; обновление MapState.UpperRow без горизонтальной колонки
                LD (@MapState.UpperRow), DE
                ; чтение ColumnByte[0] и обновление трёх левых операндов OR
                LD A, (HL)
                LD (#E11A), A
                LD (#E273), A
                LD (#E5DC), A
                ; чтение ColumnByte[MaxX] и обновление правых колонок и обоих поисков строки
                LD L, C
                LD A, (HL)
                LD (#E0F5), A
                LD (#E25B), A
                LD (#E5EE), A
                LD (#E62C), A
                RET

