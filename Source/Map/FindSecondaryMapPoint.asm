                module Map
                module FindSecondaryMapPoint
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [общий поиск с базой второго физического списка](../../Docs/StoredMapPoints.md)
; -----------------------------------------
; Проверка наличия выбранного ключа во втором списке сохранённых точек
; исходная запись 7, файловые смещения #088F..#0893
; In:
;   MapSelection.FirstWord и SecondWord задают искомый ключ, второй список начинается по 993D
;   действуют ограничения общего FindStoredMapPoint.ReadMarker на доступность записей и достижимость конца
; Out:
;   собственный код задаёт DE=993D и хвостовым JR входит в FindStoredMapPoint.ReadMarker
;   при совпадении HL=0, DE у старшего байта SecondWord найденной записи, BC=искомый SecondWord, AF=0044
;   при отсутствии DE у первого байта ограничителя, A равен этому байту 80..FE, Sign=1 и Z=0
;   при отсутствии HL и BC остаются от последнего сравнения либо входными, если сравнений не было
;   F отсутствия определяется DEC после INC маркера, Carry сохраняется от предыдущего пути и не является признаком наличия
;   MapSelection.Variant не меняется, пятый байт совпавшей записи не читается
;   все альтернативные и индексные регистры, I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   код не входит в FindStoredMapPoint.Entry, иначе база была бы заменена первым списком
;   игровое различие двух списков этим общим поиском отдельно не устанавливается
; -----------------------------------------
                ; выбор второго списка без повторной инициализации DE первым списком
Entry:          LD DE, @StoredMapPointsB.Point00
                JR @Map.FindStoredMapPoint.ReadMarker

                endmodule
                endmodule
