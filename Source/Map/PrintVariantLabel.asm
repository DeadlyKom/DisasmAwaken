                module Map
                module PrintVariantLabel
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [XOR-класс ключа, число шагов и байтовое оборачивание номера](../../Docs/VariantLabel.md)
; -----------------------------------------
; Вывод дефиса либо детерминированной буквы и номера варианта ключа
; исходная запись 7, файловые смещения #08C9..#0907
; In:
;   HL - первое слово ключа, DE - второе слово, AF - A порядковый байт варианта 0..255
;   действуют договоры StepSignatureKey, DrawGlyph и PrintWord, исходные код, шрифт и окно доступны
;   SignatureState.WorkKey является общей изменяемой памятью, параллельный писатель отсутствует
; Out:
;   SignatureState.WorkKey сначала получает оба входных слова, затем может измениться через StepSignatureKey
;   если XOR четырёх входных байтов AND 7 равен 0 или 1, печатает только дефис
;   на ветви дефиса HL и DE сохраняют входной ключ, B=(исходный A+1) modulo 256, C=исходный A, AF по DrawGlyph
;   для классов 2..7 исполняет исходный A+1 шагов ключа, при A=FF ровно 256 шагов через DJNZ
;   последняя XOR-свёртка S задаёт код буквы 80+(S AND 0F), затем печатается дефис
;   число после дефиса равно ((S SHR 4)+1+исходный A) modulo 256, выводится PrintWord с бюджетом нулей A=0
;   на числовой ветви HL содержит прежнее SecondWord перед последним шагом, DE новое SecondWord последнего шага
;   BC и AF на числовой ветви соответствуют PrintWord, при полном успешном выводе BC=10, AF=0045
;   все альтернативные и индексные регистры, I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   код буквы относится к исходной CP866, диапазон 80..8F сохраняется без перекодирования
;   входной вариант не ограничивается числом вариантов ключа, отдельной проверки диапазона в этой процедуре нет
;   номер является байтовой суммой и может обернуться, дополнительный старший разряд не выводится
;   промежуточные отказы буквы или дефиса не прекращают дальнейший вывод, AF этих CALL не проверяется
;   для воспроизводимой подписи рабочий ключ всегда перезаписывается входом до первого шага
; -----------------------------------------
                ; создание начального рабочего FSignatureKey из переданного ключа для воспроизводимой подписи
Entry:          LD (@SignatureState.WorkKey + FSignatureKey.FirstWord), HL
                LD (@SignatureState.WorkKey + FSignatureKey.SecondWord), DE
                ; сохранение порядкового байта в C и байтового счётчика A+1 в B, ноль означает 256 шагов
                LD C, A
                INC A
                LD B, A
                ; расчёт XOR-класса исходного ключа по младшим трём разрядам свёртки четырёх байтов
                LD A, L
                XOR D
                XOR E
                XOR H
                AND #07
                DEC A
                JP P, @Map.PrintVariantLabel.TestClass                          ; переход, если исходный XOR-класс был не меньше 1, использовать уменьшенный код

                ; приведение исходного класса 0 к той же ветви дефиса, что и класса 1
                XOR A
TestClass:      JR NZ, @Map.PrintVariantLabel.NextKeyStep                       ; переход, если исходный класс равен 2..7, выполнить шаги ключа и числовую подпись

                ; вывод единственного дефиса для классов 0 и 1 без обновления рабочего ключа
                LD A, #2D
                CALL @Station.DrawGlyph.Entry
                RET

                ; расчёт следующего рабочего ключа, BC со счётчиком и исходным вариантом сохраняется ядром
NextKeyStep:    CALL @Station.StepSignatureKey.Entry
                DJNZ @Map.PrintVariantLabel.NextKeyStep

                ; сохранение последней XOR-свёртки в B и расчёт буквы из её младших четырёх разрядов
                LD B, A
                AND #0F
                ADD A, #80
                CALL @Station.DrawGlyph.Entry
                ; вывод дефиса между буквой и десятичным номером
                LD A, #2D
                CALL @Station.DrawGlyph.Entry
                ; расчёт байтового номера из старшей тетрады свёртки, единицы и исходного варианта
                LD A, B
                AND #F0
                RRCA
                RRCA
                RRCA
                RRCA
                INC A
                ADD A, C
                ; подготовка беззнакового байтового номера в BC без ведущих нулей
                LD C, A
                LD B, #00
                XOR A
                ; хвостовая печать номера с исходным адресом возврата вызывающей стороны
                JP @Station.PrintWord.Entry

                endmodule
                endmodule
