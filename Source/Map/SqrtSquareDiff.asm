                module Map
                module SqrtSquareDiff
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [MapMath.md](../../Docs/MapMath.md)
; -----------------------------------------
; Поразрядный целочисленный корень из 16-битной разности D в квадрате, A в квадрате и входного Carry
; исходная запись 7, файловые смещения #2554..#257D
; In:
;   DE - D беззнаковый первый аргумент, AF - A второй аргумент и Carry дополнительный заём
; Out:
;   AF - A целая часть корня из ((D*D - A*A - Carry) AND #FFFF), F=#45
; Corrupt:
;   AF
; Note:
;   HL, DE, BC, альтернативные и индексные регистры сохраняются, SP восстанавливается
;   MapState.SqrtTarget получает 16-битную разность, процедура не реентерабельна
;   отрицательная математическая разность оборачивается по модулю 65536, ограничения нулём нет
;   восемь пробных битов результата проверяются от #80 до #01 сравнением с квадратом кандидата
; -----------------------------------------
                ; сохранение регистров и входного AF, его Carry участвует в разности квадратов
Entry:          PUSH BC
                PUSH DE
                PUSH HL
                PUSH AF
                ; получение квадрата первого аргумента D
                LD A, D
                CALL @Map.LookupSquare.Entry
                LD H, D
                LD L, E
                ; восстановление второго аргумента A и входного Carry перед его возведением в квадрат
                POP AF
                CALL @Map.LookupSquare.Entry
                ; расчёт разности квадратов с входным заёмом по модулю 65536
                SBC HL, DE
                LD B, #80
                XOR A
                ; сохранение постоянной разности для всех восьми пробных разрядов корня
                LD (@MapState.SqrtTarget), HL
TryBit:         LD HL, (@MapState.SqrtTarget)
                ; расчёт кандидата корня с очередным установленным битом
                ADD A, B
                CALL @Map.LookupSquare.Entry
                ; проверка, помещается ли квадрат кандидата в сохранённую разность
                SBC HL, DE
                JR NC, @Map.SqrtSquareDiff.NextBit                              ; переход, если квадрат кандидата не превышает разность, пробный бит сохраняется

                ; отмена пробного бита, квадрат кандидата оказался слишком большим
                SUB B
                ; выбор следующего младшего разряда результата
NextBit:        SRL B
                JR NC, @Map.SqrtSquareDiff.TryBit                               ; переход, если младший разряд результата ещё не проверен

                POP HL
                POP DE
                POP BC
                RET

                endmodule
                endmodule
