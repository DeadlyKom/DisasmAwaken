                module Map
                module LookupSquare
                ; Документация [Map](../../Docs/FunctionDetails/Map.md)
                ; Подробный разбор [MapMath.md](../../Docs/MapMath.md)
                ; -----------------------------------------
                ; Чтение квадрата A из двух раздельных страниц младших и старших байтов с сохранением Carry
                ; исходная запись 7, файловые смещения #265D..#2665
                ; In:
                ;   AF - A беззнаковое число 0..255, Carry сохраняется, таблица квадратов доступна в страницах #E9 и #EA
                ;   IRQ не вмешиваются, два временных байта CPU-стека не перекрывают код и страницы квадратов
                ; Out:
                ;   DE - квадрат входного A, AF - A сохраняется, F равен #A8 плюс входной Carry
                ;   I, IM и IFF сохраняются
                ; Corrupt:
                ;   DE, AF, R, два временных байта CPU-стека
                ; Note:
                ;   R меняется за восемь M1, младшие семь битов увеличены на 8 по модулю 128, бит 7 сохраняется
                ;   HL, BC, альтернативные и индексные регистры сохраняются, SP после обычного возврата равен входному SP+2
                ;   INC H между чтениями меняет флаги, но сохраняет Carry, последующие SBC учитывают входной заём
                ; -----------------------------------------
                ; сохранение указателя вызывающего кода перед выборкой квадрата
Entry:          PUSH HL
                LD H, @MapConst.SquareLowPage
                ; поиск младшего байта квадрата по входному A
                LD L, A
                LD E, (HL)
                ; выбор следующей страницы со старшими байтами, входной Carry сохраняется
                INC H
                LD D, (HL)
                POP HL
                RET

                endmodule
                endmodule
