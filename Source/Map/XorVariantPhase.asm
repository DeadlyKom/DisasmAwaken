                module Map
                module XorVariantPhase
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [счётчик в AF', движение курсоров, мигание, шесть потоков и трёхстрочные фазы](../../Docs/AnimatedVariants.md)
; -----------------------------------------
; Чтение пары смещений, уменьшение альтернативного счётчика и XOR трёхстрочной фазы
; исходная запись 7, файловые смещения #0827..#088E
; In:
;   HL - указатель пары смещений, AF - A уже содержит первый байт OffsetX
;   BC - B задаёт BaseY, C задаёт BaseX, AF' - A' содержит байтовый счётчик, Carry F' переносится через DEC
;   MapVariantState.SpriteSource задаёт начало восьми фаз по шесть байтов для рисуемого варианта
;   станционные таблицы 8200..84FF подготовлены, допущенные три строки и два соседних байта каждой строки доступны, отдельного отсечения нет
; Out:
;   HL - исходный указатель+2, BC сохраняется, X=(OffsetX+BaseX)&FF
;   если (A'-1)&FF имеет установленный бит 7, рисования нет, AF содержит уменьшенный счётчик и флаги DEC
;   у этого выхода DE сохраняет входной D и получает E=X, AF' содержит исходный OffsetY и флаги ADD OffsetX,BaseX
;   иначе Y=(OffsetY+BaseY)&FF, выбрана фаза 6*(X AND 7), три строки по два байта объединены с bitmap через XOR
;   при рисовании DE=SpriteSource+6*(X AND 7)+5, AF=0044, AF' содержит уменьшенный счётчик и флаги DEC
;   HL', DE', BC', IX, IY, I и IFF сохраняются, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, AF, AF', bitmap
; Note:
;   декремент проверяет Sign, а не ноль, исходные счётчики 0 и 129..255 дают ранний выход, 1..128 рисуют
;   пара смещений потребляется до проверки счётчика, даже при пропуске HL уже увеличен на два
;   нулевой AF нормального выхода нужен RET M обёрток, он не является последним экранным XOR
;   RowLow объединяется с ColumnByte через OR, таблицы должны удовлетворять этому адресному соглашению
; -----------------------------------------
                ; чтение второго байта пары после передачи OffsetX в A
Entry:          INC HL
                ; расчёт X=(OffsetX+BaseX)&FF перед проверкой счётчика
                ADD A, C
                LD E, A
                LD A, (HL)
                INC HL
                ; возврат альтернативного счётчика в основной AF для декремента
                EX AF, AF'
                ; проверка уменьшенного байтового счётчика по его знаковому биту
                DEC A
                RET M                                                           ; выход, если уменьшенный счётчик находится в 80..FF, пару потребить без рисования

                ; возврат OffsetY в A и сохранение уменьшенного счётчика в AF'
                EX AF, AF'
                ; расчёт Y=(OffsetY+BaseY)&FF
                ADD A, B
                LD D, A
                ; сохранение следующей пары потока до табличного расчёта экранного адреса
                PUSH HL
                ; поиск экранной строки и объединение её младшего адреса с колонкой X через OR
                LD L, D
                LD H, @StationScreenPage.RowHigh
                LD D, (HL)
                INC H
                LD A, (HL)
                INC H
                LD L, E
                OR (HL)
                LD E, A
                ; выбор восьмифазного сдвига по младшим трём битам X
                LD A, L
                AND @MapVariantConst.PhaseMask
                ; расчёт смещения фазы 6*(X AND 7) тремя удвоениями и сложением
                ADD A, A
                LD L, A
                ADD A, A
                ADD A, L
                ; чтение изменяемого начала ресурса и расчёт полного адреса его шестибайтовой фазы
                LD HL, #0000
                ADD A, L
                LD L, A
                LD A, H
                ADC A, #00
                LD H, A
                ; перестановка адресов, HL получает bitmap, DE получает фазу ресурса
                EX DE, HL
                ; XOR двух соседних экранных байтов первой строки
                LD A, (DE)
                XOR (HL)
                LD (HL), A
                INC L
                INC DE
                LD A, (DE)
                XOR (HL)
                LD (HL), A
                ; расчёт следующей растровой строки с учётом границы восьмистрочного знакоместа
                DEC L
                INC DE
                INC H
                LD A, H
                ; проверка перехода младших трёх битов старшего адреса через ноль
                AND @MapVariantConst.PhaseMask
                JP NZ, @Map.XorVariantPhase.DrawSecondRow                       ; переход, если строка остаётся внутри восьмистрочного знакоместа, рисовать вторую строку

                LD A, L
                ADD A, #20
                LD L, A
                JR C, @Map.XorVariantPhase.DrawSecondRow                        ; переход, если прибавление 20 к младшему адресу дало перенос, рисовать вторую строку без вычитания 08

                LD A, H
                SUB #08
                LD H, A
                ; XOR двух соседних экранных байтов второй строки
DrawSecondRow:  LD A, (DE)
                XOR (HL)
                LD (HL), A
                INC L
                INC DE
                LD A, (DE)
                XOR (HL)
                LD (HL), A
                ; расчёт третьей растровой строки по тому же переходу знакоместа
                DEC L
                INC DE
                INC H
                LD A, H
                ; проверка границы знакоместа перед третьей строкой
                AND @MapVariantConst.PhaseMask
                JP NZ, @Map.XorVariantPhase.DrawThirdRow                        ; переход, если строка остаётся внутри восьмистрочного знакоместа, рисовать третью строку

                LD A, L
                ADD A, #20
                LD L, A
                JR C, @Map.XorVariantPhase.DrawThirdRow                         ; переход, если прибавление 20 к младшему адресу дало перенос, рисовать третью строку без вычитания 08

                LD A, H
                SUB #08
                LD H, A
                ; XOR двух соседних экранных байтов третьей строки
DrawThirdRow:   LD A, (DE)
                XOR (HL)
                LD (HL), A
                INC L
                INC DE
                LD A, (DE)
                XOR (HL)
                LD (HL), A
                ; восстановление следующей пары и сброс AF для продолжения после RET M обёртки
                POP HL
                XOR A
                RET

                endmodule
                endmodule
