                module Map
                module PrepareLeftRasterPoint
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [табличные координаты краёв и ограниченный поиск без замены SP](../../Docs/RasterPreparation.md)
; -----------------------------------------
; Адрес левой растровой точки и одноразрядная маска в B
; исходная запись 7, файловые смещения #2514..#252D
; In:
;   BC - C относительный Y для RowHigh и RowLow, AF - A относительный X для ColumnByte и маски
;   MapScreenTables построены, KARTA выбран, перенос младшего адресного сложения не должен требовать исправления старшего байта для обычного bitmap
; Out:
;   HL - адрес точки по RowHigh[Y], RowLow[Y]+ColumnByte[X] с байтовым оборачиванием младшей суммы
;   DE - D сохранён, E младший байт рассчитанного адреса
;   BC - B=80 SHR (X AND 7), C=исходный X, A=0, F=43 при X AND 7=0, иначе 42
;   все альтернативные и индексные регистры, I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE только E, BC, AF
; Note:
;   маска формируется RRC из B=1 за (X AND 7)+1 шагов, последний DEC задаёт Z и N
;   пиксели не рисуются, начальный Y в C заменяется на исходный X
; -----------------------------------------
                ; выбор Y из C и сохранение относительного X из A для адреса и маски левого края
Entry:          LD L, C
                LD C, A
                ; поиск старшего и младшего байтов строки, затем прибавление ColumnByte[X]
                LD H, @MapMarkerConst.RowHighPage
                LD B, (HL)
                INC H
                LD A, (HL)
                INC H
                LD L, C
                ADD A, (HL)
                INC H
                LD L, A
                LD H, B
                ; расчёт одноразрядной левой маски из младших трёх разрядов X
                LD A, C
                AND #07
                LD B, #01
                INC A
                ; сдвиг маски к требуемому пикселю, число повторов находится в A
RotateMask:     RRC B
                DEC A
                JR NZ, @Map.PrepareLeftRasterPoint.RotateMask                   ; переход, если остаются сдвиги левой маски, продолжить вращение B

                ; сохранение младшего адреса левой точки в E для второго края растрового пролёта
                LD E, L
                RET

                endmodule
                endmodule
