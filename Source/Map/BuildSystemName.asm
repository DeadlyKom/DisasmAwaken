                module Map
                module BuildSystemName
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [префиксы, упакованные поля, пропущенные нули и выходной обмен регистров](../../Docs/SystemName.md)
; -----------------------------------------
; Формирование LF-имени системы в старом буфере загрузчика с обменом наборов
; исходная запись 7, файловые смещения #26AB..#26F5
; In:
;   HL первое слово ключа, DE второе слово ключа, BC контекст, который перейдёт в альтернативный набор
;   альтернативные HL, DE и BC рабочие значения, AF альтернативного набора сохраняемый контекст
;   KARTA выбрана в банке 1, доступны SystemPrefixes и фиксированный SkipLfRecords станции
;   SystemNameState.Buffer по 630B допускает запись до 18 байтов, первоначальный bootstrap уже завершён
; Out:
;   HL адрес LF исходного выбранного префикса, DE адрес конечного LF построенной строки в Buffer
;   BC - B десятки второго числового поля, C его единицы
;   AF - A=0A, F=80 OR ((исходный D>>4) AND 08), флаги относятся к построению последней буквы
;   HL'=исходный HL AND F0FF, DE'=исходный DE AND FFF0, BC'=исходный BC, AF' сохранён
;   IX, IY, I и IFF сохранены, SP обычного возврата равен входному SP+2
;   в Buffer записаны префикс, дефис, первое число, косая черта, второе число, дефис, буква, LF
;   префикс выбирается E AND 0F, первое число=(E AND F0) OR (H AND 0F)
;   второе число=(H AND F0) OR (D AND 0F), буква=80+(D>>4), исходный L в строке не используется
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC'
; Note:
;   числа записываются настоящим AppendCompactDecimal, его пропуск нулевых десятков является частью имени
;   на возврате активен противоположный набор общих регистров, это не сохраняющий обычные пары вызов
;   AF не обменивается, EXX меняет только HL, DE и BC
;   общий рабочий буфер переиспользует байты первоначального StationBoot.RelocateBootstrap, новая память не выделяется
;   максимум 7 байтов префикса, две группы до 3 цифр и 5 остальных байтов дают предел 18
;   LF записывается без следующего INC DE, DE остаётся на ограничителе, нулевой терминатор не добавляется
; -----------------------------------------
                ; расчёт индекса одного из шестнадцати префиксов по младшему полубайту второго слова
Entry:          LD A, E
                AND @SystemNameConst.LowNibble
                ; выбор рабочего альтернативного набора, исходные слова ключа пока остаются в противоположном наборе
                EXX
                ; поиск выбранного префикса по исходной LF-таблице с начальным ограничителем
                LD HL, @SystemPrefixes.Entry
                CALL @Station.SkipLfRecords.Entry
                ; выбор общего буфера поверх уже отработавшего первоначального загрузчика
                LD DE, @SystemNameState.Buffer
                ; копирование очередного байта непустого префикса, BC уменьшается, но не ограничивает цикл
CopyPrefix:     LDI
                ; проверка следующего исходного байта, ограничитель LF не копируется этим циклом
                LD A, (HL)
                CP #0A
                JR NZ, @Map.BuildSystemName.CopyPrefix                          ; переход, если следующий исходный байт не LF, продолжить копирование префикса

                ; добавление первого дефиса после выбранного префикса
                LD A, @SystemNameConst.Dash
                LD (DE), A
                INC DE
                ; возврат к исходным словам ключа для сборки первого числового поля
                EXX
                ; расчёт первого байта из старшего полубайта E и младшего полубайта H
                LD A, E
                AND @SystemNameConst.HighNibble
                LD E, A
                LD A, H
                AND @SystemNameConst.LowNibble
                OR E
                ; возврат в рабочий набор с указателем буфера в DE
                EXX
                ; запись первого числового поля с исходным подавлением нулевых десятков
                CALL @Map.AppendCompactDecimal.Entry
                ; добавление косой черты между двумя числовыми полями
                LD A, @SystemNameConst.Slash
                LD (DE), A
                INC DE
                ; выбор исходных слов для второго числового поля
                EXX
                ; расчёт второго байта из старшего полубайта H и младшего полубайта D
                LD A, H
                AND @SystemNameConst.HighNibble
                LD H, A
                LD A, D
                AND @SystemNameConst.LowNibble
                OR H
                ; возврат в рабочий набор для продолжения записи строки
                EXX
                ; запись второго числового поля тем же компактным алгоритмом
                CALL @Map.AppendCompactDecimal.Entry
                ; добавление дефиса перед завершающей буквой
                LD A, @SystemNameConst.Dash
                LD (DE), A
                INC DE
                ; выбор исходного D для завершающей буквы системы
                EXX
                ; расчёт кода буквы 80..8F из старшего полубайта D
                LD A, D
                AND @SystemNameConst.HighNibble
                RRCA
                RRCA
                RRCA
                RRCA
                ADD A, @SystemNameConst.FirstLetter
                ; последний обмен в рабочий набор, он останется основным на возврате
                EXX
                ; запись буквы и последующего LF, окончательный DE остаётся на LF
                LD (DE), A
                INC DE
                LD A, @TextConst.LineFeed
                LD (DE), A
                RET

                endmodule
                endmodule
