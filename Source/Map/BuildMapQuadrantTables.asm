                module Map
                module BuildMapQuadrantTables
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [три рабочих слова, порядок четырёх секторов и обмен EXX](../../Docs/MapSectorTables.md)
; -----------------------------------------
; Построение четырёх 256-байтовых таблиц соседних секторов карты
; исходная запись 7, файловые смещения #044A..#0473
; In:
;   MapViewState.OriginHigh содержит байты Xhigh и Yhigh начала области карты
;   банк KARTA 1 выбран в C000, страницы F200..F5FF этого банка доступны для записи
;   стек вне этих таблиц, прерывания сохраняют оба общих набора и страницу во время EXX
; Out:
;   HL, DE и BC сохранены через FMapSectorTablesFrame, входной ключ и размеры области не меняются
;   F200 получает сектор X,Y, F300 сектор X+1,Y, F500 сектор X+1,Y+1, F400 сектор X,Y+1
;   X и Y являются старшими координатными байтами, прибавления соседнего сектора оборачиваются по модулю 256
;   AF содержит последний байт таблицы F400 и F=50 OR Carry последнего сложения генератора
;   HL'=F400, DE', BC', AF', IX, IY, I и IFF сохранены, SP обычного возврата равен входному SP+2
;   каждая таблица содержит 128 пар выходных байтов по независимой рекуррентной формуле MapSectorTables.md
; Corrupt:
;   AF, HL'
; Note:
;   последовательность адресов F200,F300,F500,F400 отражает обход четырёх смежных секторов, порядок сохраняется
;   каждый BuildMapSectorTable меняет активный общий набор, последующий EXX подготавливает следующий вызов
;   внешний кадр снимается уже в исходном общем наборе после четвёртого помощника
;   назначение всех игровых потребителей таблиц ещё требует разбора, математическое содержимое и адреса доказаны
; -----------------------------------------
                ; сохранение исходных DE, HL и BC в FMapSectorTablesFrame
Entry:          PUSH DE
                PUSH HL
                PUSH BC
                ; чтение старших байтов начала области, E=Xhigh, D=Yhigh
                LD DE, (@MapViewState.OriginHigh)
                ; выбор другого общего набора для передачи адреса первой выходной таблицы
                EXX
                ; построение страницы сектора X,Y, помощник вернётся в вычисляющем наборе
                LD HL, @MapSectorTables.Cell00
                CALL @Map.BuildMapSectorTable.Entry
                ; расчёт соседнего X по модулю 256 без переноса в Y
                INC E
                EXX
                ; построение страницы сектора X+1,Y
                LD HL, @MapSectorTables.Cell10
                CALL @Map.BuildMapSectorTable.Entry
                ; расчёт соседнего Y по модулю 256
                INC D
                EXX
                ; построение страницы сектора X+1,Y+1
                LD HL, @MapSectorTables.Cell11
                CALL @Map.BuildMapSectorTable.Entry
                ; возврат X к исходному байту для четвёртого сектора
                DEC E
                EXX
                ; построение страницы сектора X,Y+1
                LD HL, @MapSectorTables.Cell01
                CALL @Map.BuildMapSectorTable.Entry
                ; восстановление исходных BC, HL и DE после всех четырёх обменов
                POP BC
                POP HL
                POP DE
                RET

                endmodule
                endmodule
