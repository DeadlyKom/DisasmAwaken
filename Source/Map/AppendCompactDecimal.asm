                module Map
                module AppendCompactDecimal
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [префиксы, упакованные поля, пропущенные нули и выходной обмен регистров](../../Docs/SystemName.md)
; -----------------------------------------
; Запись байта десятичными разрядами с подавлением нулевых сотен и десятков
; исходная запись 7, файловые смещения #26F6..#2720
; In:
;   DE адрес буфера с местом для трёх байтов, AF - A беззнаковое число 0..255
;   буфер доступен для записи и не пересекает исполняемый код либо стек
; Out:
;   HL сохранён, DE продвинут на 1..3 записанных символа
;   BC - B число десятков остатка после сотен, C число единиц
;   AF - A код последней цифры единиц, F от ADD единицы,30, для входного байта это 20 либо 28
;   сотни записаны только при ненуле, десятки также записаны только при ненуле независимо от наличия сотен
;   единицы записаны всегда, терминатор и ограничитель не добавляются
;   альтернативные и индексные регистры, I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   DE, BC, AF
; Note:
;   для 100..109 и 200..209 нулевой средний разряд пропущен, например 105 превращается в 15
;   это исходный компактный формат, обычная десятичная функция с ведущими нулями вместо него не подставляется
;   счётчики сотен и десятков начинаются с FF, INC перед неудачным вычитанием учитывает последний допустимый разряд
; -----------------------------------------
                ; подготовка счётчика сотен до первого учитываемого вычитания
Entry:          LD B, @CompactDecimalConst.BeforeFirst
                ; расчёт числа сотен последовательными вычитаниями 100
CountHundreds:  INC B
                SUB @CompactDecimalConst.Hundred
                JR NC, @Map.AppendCompactDecimal.CountHundreds                  ; переход, если очередная сотня ещё помещается в остатке, продолжить подсчёт

                ; восстановление остатка после последнего недостаточного вычитания сотни
                ADD A, @CompactDecimalConst.Hundred
                LD C, A
                ; проверка ненулевого числа сотен для его записи
                LD A, B
                OR A
                JR Z, @Map.AppendCompactDecimal.PrepareTens                     ; переход, если сотен нет, не записывать старший нулевой разряд

                ; расчёт ASCII-кода ненулевой цифры сотен
                ADD A, @NumberConst.DigitZero
                LD (DE), A
                INC DE
                ; выбор остатка после сотен для подсчёта десятков
PrepareTens:    LD A, C
                LD B, @CompactDecimalConst.BeforeFirst
                ; расчёт числа десятков последовательными вычитаниями 10
CountTens:      INC B
                SUB @CompactDecimalConst.Ten
                JR NC, @Map.AppendCompactDecimal.CountTens                      ; переход, если очередной десяток ещё помещается в остатке, продолжить подсчёт

                ; восстановление числа единиц после последнего недостаточного вычитания десятка
                ADD A, @CompactDecimalConst.Ten
                LD C, A
                ; проверка ненулевого разряда десятков без учёта уже записанных сотен
                LD A, B
                OR A
                JR Z, @Map.AppendCompactDecimal.WriteUnits                      ; переход, если десятков нет, пропустить этот разряд даже после сотен

                ; расчёт ASCII-кода ненулевой цифры десятков
                ADD A, @NumberConst.DigitZero
                LD (DE), A
                INC DE
                ; обязательная запись цифры единиц, включая ноль
WriteUnits:     LD A, C
                ; расчёт кода единиц, эти флаги остаются окончательным результатом помощника
                ADD A, @NumberConst.DigitZero
                LD (DE), A
                INC DE
                RET

                endmodule
                endmodule
