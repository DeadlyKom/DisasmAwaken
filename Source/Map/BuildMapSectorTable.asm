                module Map
                module BuildMapSectorTable
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [три рабочих слова, порядок четырёх секторов и обмен EXX](../../Docs/MapSectorTables.md)
; -----------------------------------------
; Формирование таблицы одного сектора с возвратом в противоположном общем наборе
; исходная запись 7, файловые смещения #0474..#049A
; In:
;   HL - начало выходной страницы с младшим байтом 0, DE и BC входного активного набора сохраняются как альтернативные результаты
;   DE' - D старший байт координаты Y сектора, E старший байт X, HL' и BC' являются рабочими
;   выходная страница доступна для 256 байтов, стек вне неё, таблица не перекрывает код или сохранение DE
; Out:
;   активный общий набор при возврате противоположен входному, это часть интерфейса помощника
;   HL содержит первое рабочее слово после 128 шагов, DE исходный сектор из входного альтернативного DE, BC последнее смешанное слово
;   A равен второму байту последней пары, F=50 OR Carry последнего ADD HL,BC
;   HL' равен исходному адресу выходной страницы, DE' равен входному активному DE, BC' входному активному BC
;   AF', IX, IY, I и IFF сохранены, SP обычного возврата равен входному SP+2
;   таблица содержит ровно 256 байтов, запись ограничена оборачиванием L после 128 пар
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC' с указанным обменом общих наборов
; Note:
;   начальные рабочие слова равны беззнаковым байтам X,Y и константе 8237
;   формула одного шага, T=((U+V) AND FFFF) XOR 0A00, W=(T+M) AND FFFF
;   в таблицу выводятся старшие байты V и M, следующее состояние U=V, V=M, M=W
;   PUSH DE хранит исходный сектор в вычисляющем наборе до окончания страницы
;   масштабирование координат или статистические свойства генератора этим помощником не доказываются
; -----------------------------------------
                ; выбор вычисляющего набора, исходный активный HL остаётся указателем выхода
Entry:          EXX
                ; сохранение исходного сектора на CPU-стеке до завершения страницы
                PUSH DE
                ; подготовка U=Xhigh, V=Yhigh и начального M=8237 как трёх беззнаковых слов
                LD L, E
                LD E, D
                LD BC, @MapSectorConst.InitialMix
                LD H, #00
                LD D, H
                ; выбор набора указателя, каждый повтор NextPair снова переключится на вычисление
                EXX
                ; расчёт T=((U+V) modulo 65536) XOR 0A00 в вычисляющем наборе
NextPair:       EXX
                ADD HL, DE
                LD A, H
                XOR @MapSectorConst.HighXor
                LD H, A
                ; сохранение прежнего V и расчёт W=T+M с 16-битным оборачиванием
                PUSH DE
                LD D, B
                LD E, C
                ADD HL, BC
                LD B, H
                LD C, L
                POP HL
                ; выбор первого выходного байта из старшей части прежнего V
                LD A, H
                EXX
                ; запись первого байта пары и продвижение только младшего байта адреса
                LD (HL), A
                INC L
                EXX
                ; выбор второго выходного байта из старшей части прежнего M
                LD A, D
                EXX
                ; запись второго байта пары, оборачивание L завершает 256-байтовую страницу
                LD (HL), A
                INC L
                JP NZ, @Map.BuildMapSectorTable.NextPair                        ; переход, если L ещё не обернулся в ноль, рассчитать следующую пару таблицы

                ; возврат в вычисляющий набор и восстановление исходного сектора, итоговый набор отличается от входного
                EXX
                POP DE
                RET

                endmodule
                endmodule
