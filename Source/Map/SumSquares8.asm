                module Map
                module SumSquares8
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [два восьмиразрядных умножения и точные флаги суммы](../../Docs/SumSquares8.md)
; -----------------------------------------
; Сумма квадратов двух беззнаковых байтов из A и A' с 16-битным оборачиванием
; исходная запись 7, файловые смещения #0368..#038B
; In:
;   AF - A=u, AF' - A'=v, оба аргумента беззнаковые байты 0..255, входные F и F' не участвуют в вычислении
;   KARTA выбран, обычный стек доступен, внешние таблицы и память данных не читаются
; Out:
;   HL=(u*u+v*v)&FFFF, DE=v*v, BC - B=0, C сохранён
;   AF - A=high(v*v), Carry=1 только при переполнении полной суммы слова, H перенос из разряда 11, N=0
;   S,Z,P/V основного F относятся к младшему байту v*v после последнего RR E, биты 5 и 3 взяты из старшего байта суммы
;   AF' - A'=high(u*u), F' совпадает с логическими флагами low(u*u), H=N=Carry=0
;   HL', DE', BC', IX, IY, I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, BC только B, AF, AF'
; Note:
;   каждый квадрат вычисляется тем же восьмиразрядным сдвиговым умножением с одинаковыми множителями
;   XOR A перед каждым циклом сбрасывает перенос, поэтому входные флаги не являются частью аргументов
;   последний дополнительный RR E завершает младший байт произведения, его Carry всегда нулевой
;   в общем байтовом договоре сумма может превышать FFFF, перенос не игнорируется в описании результата
;   известный потребитель SelectNearestVisiblePoint передаёт абсолютный байтовый Y в A и X в A', порядок существенен для побочных регистров и флагов
;   достижимость восстановлена через [действия интерфейса](../../Docs/StationEventActions.md), выбор ближайшей видимой точки описан отдельно
; -----------------------------------------
                ; подготовка одинаковых множимого D и множителя E для квадрата первого аргумента u
Entry:          LD E, A
                LD D, A
                LD B, @MapMathConst.ByteBits
                ; сброс старшего накопителя A и переноса перед восемью разрядами первого умножения
                XOR A
                ; выбор очередного младшего бита сдвигаемого множителя первого квадрата
FirstBit:       RR E
                JR NC, @Map.SumSquares8.ShiftFirst                              ; переход, если выбранный бит первого множителя равен нулю, прибавление u не требуется

                ; прибавление первого множимого к старшему накопителю с сохранением переноса для RRA
                ADD A, D
                ; сдвиг составного частичного произведения с передачей младшего бита накопителя в следующий RR E
ShiftFirst:     RRA
                DJNZ @Map.SumSquares8.FirstBit

                ; завершение младшего байта первого квадрата, Carry последнего RR E равен нулю
                RR E
                ; сохранение полного первого квадрата в HL до второго умножения
                LD H, A
                LD L, E
                ; получение второго аргумента v через обмен AF, первый старший байт и его флаги остаются в AF'
                EX AF, AF'
                LD E, A
                LD D, A
                LD B, @MapMathConst.ByteBits
                ; сброс старшего накопителя и переноса второго умножения независимо от входного F'
                XOR A
                ; выбор очередного бита второго множителя для квадрата v
SecondBit:      RR E
                JR NC, @Map.SumSquares8.ShiftSecond                             ; переход, если выбранный бит второго множителя равен нулю, прибавление v не требуется

                ; прибавление второго множимого перед сдвигом составного произведения
                ADD A, D
                ; сдвиг второго частичного произведения с переносом в следующий RR E
ShiftSecond:    RRA
                DJNZ @Map.SumSquares8.SecondBit

                ; завершение младшего байта второго квадрата, S,Z,P/V этого RR E далее сохраняет ADD HL,DE
                RR E
                ; формирование полного второго квадрата в DE с сохранением его старшего байта в A
                LD D, A
                ; расчёт суммы двух 16-битных квадратов с возвратом переноса за пределы слова
                ADD HL, DE
                RET

                endmodule
                endmodule
