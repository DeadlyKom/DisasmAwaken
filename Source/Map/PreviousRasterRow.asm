                module Map
                module PreviousRasterRow
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [MapRaster.md](../../Docs/MapRaster.md)
; -----------------------------------------
; Переход на предыдущую строку Spectrum с проверкой верхней границы и нелокальным завершением растрового вызова
; исходная запись 7, файловые смещения #257E..#25AB
; In:
;   HL - байтовый адрес пиксельной строки Spectrum, DE - E адрес второго края с той же группой Y
;   MapState.UpperRow - адрес верхней строки с обнулённой колонкой, RasterStack - стек внешнего растрового вызова
; Out:
;   при обычном возврате HL указывает на строку выше, E перенесён в ту же строку, D равен старшему байту UpperRow
; Corrupt:
;   HL, DE, AF
; Note:
;   проверка верхней границы выполняется до перехода, сама верхняя строка ещё обрабатывается вызывающим кодом
;   при совпадении границы возврат из этой процедуры отбрасывается, SP восстанавливается из RasterStack
;   затем POP AF восстанавливает AF внешнего вызова и RET завершает его, продолжение после CALL не выполняется
;   BC, альтернативные и индексные регистры сохраняются, входной E должен иметь ту же группу Y, что и L
; -----------------------------------------
                ; сравнение текущей строки с включённой верхней границей, колонка не участвует
Entry:          PUSH HL
                LD A, L
                AND #E0
                LD L, A
                LD A, E
                LD DE, (@MapState.UpperRow)
                OR A
                ; проверка равенства байтового адреса строки верхней границе
                SBC HL, DE
                LD E, A
                POP HL
                JR Z, @Map.PreviousRasterRow.AbortRaster                        ; переход, если текущая строка уже является верхней границей, растровый вызов завершается

                ; расчёт предыдущей пиксельной строки с учётом чересстрочной раскладки Spectrum
                LD A, H
                DEC H
                AND #07
                JP NZ, @Map.PreviousRasterRow.ReturnUp                          ; переход, если предыдущая строка остаётся внутри восьмистрочной группы

                ; переход к предыдущей группе строк, обе колонки переносятся вместе
                LD A, L
                SUB #20
                LD L, A
                LD A, E
                SUB #20
                LD E, A
                JR C, @Map.PreviousRasterRow.ReturnUp                           ; переход, если вычитание шага группы вышло за младший байт адреса

                ; коррекция старшего байта при переходе между восьмистрочными группами
                LD A, H
                ADD A, #08
                LD H, A
ReturnUp:       RET

                ; отмена внутреннего возврата и восстановление стека внешнего растрового вызова
AbortRaster:    POP AF
                LD SP, (@MapState.RasterStack)
                POP AF
                RET

                endmodule
                endmodule
