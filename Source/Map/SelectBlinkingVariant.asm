                module Map
                module SelectBlinkingVariant
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [счётчик в AF', движение курсоров, мигание, шесть потоков и трёхстрочные фазы](../../Docs/AnimatedVariants.md)
; -----------------------------------------
; Циклическое мигание выбранного варианта заменой ресурса по младшему биту маски
; исходная запись 7, файловые смещения #076E..#0780
; In:
;   HL - указатель ресурса, AF - входной A сохраняется, если ресурс не Selected
;   MapVariantState.BlinkMask является доступным изменяемым операндом, KARTA выбран
; Out:
;   DE - MapVariantResources.Selected, BC сохраняется
;   при HL, отличном от Selected, HL и A сохраняются, маска не меняется
;   при Selected маска циклически поворачивается вправо на один бит и сохраняется, A получает повёрнутый байт
;   старый младший бит 1 оставляет Selected, бит 0 заменяет HL на MapVariantResources.Default
;   для несовпавшего HL флаги S,Z,PV берутся от HL-Selected, H,C и разряды 5,3 от восстанавливающего ADD HL,DE, N сброшен
;   при Selected RRCA сохраняет S,Z,PV от сравнения и восстановления, сбрасывает H,N, Carry получает старый младший бит маски
;   все альтернативные и индексные регистры, I и IFF сохранены, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, AF, MapVariantState.BlinkMask
; Note:
;   исходный операнд равен CC, период его циклического вращения восемь шагов, фактическая повторяемость рисунка CC составляет четыре
;   маска поворачивается на каждом выбранном ресурсе, при нескольких таких указателях в одном вызове поворотов тоже несколько
; -----------------------------------------
                ; проверка полного указателя ресурса на совпадение с Selected, SBC временно вычитает адрес
Entry:          LD DE, @MapVariantResources.Selected
                OR A
                SBC HL, DE
                ; восстановление исходного HL, Z от вычитания сохраняется через ADD HL,DE
                ADD HL, DE
                RET NZ                                                          ; выход, если указатель не равен Selected, ресурс и маску не менять

                ; чтение и циклический поворот текущей маски мигания выбранного варианта
                LD A, #CC
                RRCA
                ; сохранение повёрнутой маски в её исходном изменяемом операнде
                LD (@MapVariantState.BlinkMask), A
                RET C                                                           ; выход, если старый младший бит маски равен единице, оставить Selected

                ; выбор обычного ресурса на выключенной фазе мигания
                LD HL, @MapVariantResources.Default
                RET

                endmodule
                endmodule
