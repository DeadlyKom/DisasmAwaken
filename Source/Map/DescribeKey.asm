                module Map
                module DescribeKey
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [прямоугольники, числовые признаки и шаг рабочего ключа](../../Docs/WorldSignature.md)
; -----------------------------------------
; Числовые признаки ключа через область и 1..256 шагов рабочего состояния
; исходная запись 7, файловые смещения #09B9..#09FA
; In:
;   HL - FirstWord, DE - SecondWord, AF - A Variant=0..255, BC сохраняемый контекст
;   в окне #C000 выбран банк 1 с MAP, станционный StepSignatureKey доступен в фиксированной памяти
;   SignatureState.WorkKey доступен для записи, повторного входа с тем же состоянием нет
; Out:
;   HL - H код 0..3 внутри трёх областей либо 4 вне них, L числовой признак 1..16
;   DE - D код геометрической области 0..3, E младший двухбитовый признак 0..3, BC сохранён
;   AF - A=max((((FirstWord.high XOR FirstWord.low XOR SecondWord.high XOR SecondWord.low) AND 7)-1),0)
;   если XOR AND 7 равен 0, F=#44, если 1, F=#42, иначе F=#02, Z означает A=0
;   рабочий FSignatureKey по #631C содержит состояние после Variant+1 шагов
;   HL', DE', BC', IX, IY, I и IFF сохранены, SP восстановлен
;   AF' - A'=E, F' от AND #03 с H=1, входной AF' не сохраняется
; Corrupt:
;   HL, DE, AF, AF'
; Note:
;   Variant задаёт 1..256 шагов, при #FF INC A даёт ноль, но DJNZ выполняет 256 итераций
;   геометрическая область вычисляется до шагов, состояние рабочего ключа сохраняет результат последнего шага
;   итоговый A и F относятся к исходной XOR-свёртке, а H,L,E берутся из инверсии последнего случайного байта
;   код области 3 принудительно задаёт H=4, остальные области разрешают H=0..3
;   обработчик сам не меняет порт страниц, он требует уже выбранного банка 1
; -----------------------------------------
                ; сохранение BC вокруг счётчика шагов и признака внешней области
Entry:          PUSH BC
                ; сохранение Variant перед XOR-свёрткой исходных слов
                EX AF, AF'
                ; расчёт XOR четырёх байтов исходного ключа
                LD A, H
                XOR L
                XOR E
                XOR D
                ; выделение трёх младших битов исходной XOR-свёртки
                AND #07
                ; вычет единицы из трёхбитового кода перед насыщением снизу
                DEC A
                JP P, @Map.DescribeKey.SeedKey                                  ; переход, если исходный трёхбитовый код ненулевой, сохранить результат DEC

                ; замена отрицательного результата нулём с F=#44
                XOR A
                ; возврат Variant и сохранение исходной свёртки в AF'
SeedKey:        EX AF, AF'
                ; инициализация рабочего двухсловного ключа исходными HL и DE
                LD (@SignatureState.WorkKey + FSignatureKey.FirstWord), HL
                LD (@SignatureState.WorkKey + FSignatureKey.SecondWord), DE
                ; расчёт байтового счётчика Variant+1, ноль означает 256 проходов DJNZ
                INC A
                LD B, A
                ; классификация исходных H,L до обновления рабочего ключа
                CALL @Map.ClassifyKeyRegion.Entry
                ; сохранение кода области в старшем байте временной пары стека
                PUSH AF
                ; проверка внешней области с кодом 3
                CP #03
                ; подготовка нулевого признака принудительного H=4
                LD C, #00
                JR NZ, @Map.DescribeKey.NextStep                                ; переход, если область не внешняя, оставить признак равным нулю

                ; установка признака внешней области для последующего H=4
                INC C
                ; очередной шаг рабочего ключа, BC сохраняется исходным StepSignatureKey
NextStep:       CALL @Station.StepSignatureKey.Entry
                DJNZ @Map.DescribeKey.NextStep

                ; восстановление исходного кода области в D
                POP DE
                ; инверсия XOR-свёртки последнего шага перед выделением признаков
                CPL
                ; сохранение полного инвертированного байта во временном E
                LD E, A
                ; выделение четырёх средних битов для числового признака 1..16
                AND #3C
                RRCA
                RRCA
                ; перевод выделенной тетрады из 0..15 в 1..16
                INC A
                LD L, A
                ; расчёт двух старших битов инвертированного байта для обычного H
                LD A, E
                RLCA
                RLCA
                AND #03
                ; проверка сохранённого признака внешней области через DEC C
                DEC C
                JR NZ, @Map.DescribeKey.StoreMajor                              ; переход, если область не внешняя, сохранить двухбитовый H

                ; замена H внешней области специальным кодом 4
                LD A, #04
                ; запись основного числового кода в H
StoreMajor:     LD H, A
                ; выделение двух младших битов для итогового E
                LD A, E
                AND #03
                LD E, A
                ; возврат исходной XOR-свёртки как A и F, признаки в HL и DE уже готовы
                EX AF, AF'
                POP BC
                RET

                endmodule
                endmodule
