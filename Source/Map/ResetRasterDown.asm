                module Map
                module ResetRasterDown
                ; Документация [Map](../../Docs/FunctionDetails/Map.md)
                ; Подробный разбор [MapRaster.md](../../Docs/MapRaster.md)
                ; -----------------------------------------
                ; Сброс альтернативного состояния растрового обхода и выбор движения вниз
                ; исходная запись 7, файловые смещения #2666..#2673
                ; In:
                ;   основные регистры принадлежат вызывающему растровому обработчику
                ;   IRQ не вмешиваются, CPU-стек доступен и не перекрывает исполняемый код
                ; Out:
                ;   AF - A=1, F сохраняется, HL'=0, D'=0, B'=#FF, RasterDown=1
                ; Corrupt:
                ;   AF, HL', DE', BC', R
                ; Note:
                ;   R меняется за восемь M1, младшие семь битов увеличены на 8 по модулю 128, бит 7 сохранён, I, IM и IFF сохраняются
                ;   основные HL, DE, BC, альтернативный AF', IX и IY сохраняются, E' и C' сохраняются
                ;   SP восстанавливается, процедура выбирает NextRasterRow через байт направления
                ; -----------------------------------------
                ; сброс альтернативных накопителей растрового прохода и выбор направления вниз
Entry:          EXX
                LD HL, #0000
                LD D, H
                LD B, #FF
                EXX
                LD A, #01
                LD (@MapState.RasterDown), A
                RET

                endmodule
                endmodule
