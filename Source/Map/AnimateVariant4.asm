                module Map
                module AnimateVariant4
; Документация [Map](../../Docs/FunctionDetails/Map.md)
; Подробный разбор [счётчик в AF', движение курсоров, мигание, шесть потоков и трёхстрочные фазы](../../Docs/AnimatedVariants.md)
; -----------------------------------------
; Анимационный шаг варианта 4 и последующее исполнение оставшихся обёрток
; исходная запись 7, файловые смещения #0734..#0750
; In:
;   BC - B задаёт BaseY, C задаёт BaseX, AF' - A' содержит счётчик, Carry F' сохраняется через DEC
;   операнд Resource4 содержит ресурс, Cursor4 указывает на пару смещений либо байт End=80 соответствующего потока
;   для последовательно исполняемых обёрток подготовлены их курсоры, рисуемые ресурсы и таблицы, действуют договоры SelectBlinkingVariant и XorVariantPhase
; Out:
;   для каждого достигнутого варианта ресурс проходит выбор мигания и записывается в SpriteSource
;   при End=80 курсор сначала возвращается к Point00, затем читается пара, цикл требует первого байта Point00, отличного от 80
;   курсор текущего варианта получает указатель следующей пары и при рисовании, и при раннем пропуске по счётчику
;   после пропуска RET M возвращает, после рисования Sign сброшен и исполнение переходит к следующей обёртке, у последней обычная RET
;   HL, DE, AF, AF' соответствуют последнему XorVariantPhase, BC, HL', DE', BC', IX, IY, I и IFF сохранены
;   последующие недостигнутые курсоры и ресурсы не меняются, SP обычного возврата равен входному SP+2
; Corrupt:
;   HL, DE, AF, AF', bitmap, достигнутые курсоры, SpriteSource и маска мигания
; Note:
;   при положительном счётчике меньше числа оставшихся обёрток после последнего рисунка потребляется ещё одна пара следующего варианта
;   вся цепочка использует один исходный адрес возврата, последовательный переход между INCLUDE не является дополнительным CALL
; -----------------------------------------
                ; чтение изменяемого ресурса варианта 4 перед обработкой мигания
Entry:          LD HL, #0000
                CALL @Map.SelectBlinkingVariant.Entry
                ; обновление общего SpriteSource ресурсом текущей фазы мигания
                LD (@MapVariantState.SpriteSource), HL
                ; чтение изменяемого курсора варианта 4
                LD HL, @MapVariantPaths.Radius19.Point50
ReadPoint:      LD A, (HL)
                ; проверка байта 80, только он завершает циклическую траекторию
                CP @MapVariantConst.EndPath
                JR NZ, @Map.AnimateVariant4.DrawPoint                           ; переход, если первый байт отличается от 80, обработать пару смещений

                ; возврат курсора к первой паре собственной траектории
                LD HL, @MapVariantPaths.Radius19.Point00
                JR @Map.AnimateVariant4.ReadPoint

DrawPoint:      CALL @Map.XorVariantPhase.Entry
                ; сохранение следующей пары, в том числе после пропуска рисования
                LD (@MapVariantState.Cursor4), HL
                RET M                                                           ; выход, если уменьшенный счётчик находится в 80..FF, следующие варианты не обрабатывать

                ; JP @Map.AnimateVariant5.Entry, продолжение в AnimateVariant5.asm

                endmodule
                endmodule
