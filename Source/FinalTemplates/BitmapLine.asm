                module BitmapLine
                ; Документация [исполнение копии без IRQ](../../Docs/FinalCycle.md#договор-копии-bitmapline-без-irq)
; Документация [FinalTemplates](../../Docs/FunctionDetails/FinalTemplates.md)
; -----------------------------------------
; 52-байтовый образец переноса 32 байтов строки через два набора регистров и временный SP
; исходная запись 29, файловые смещения #0247..#027A
                ; In:
                ;   четыре операнда SP задают два читаемых блока по 16 байтов и адреса за концами двух записываемых блоков
                ;   источники в подключённом банке 0, 1 либо 7, приёмник в фиксированном экране банка 5, копия кода в общей RAM
                ;   первая запись не повреждает будущий источник и код, назначения не перекрываются, внешнее исходное значение SP не используется
                ;   для этого локального договора IRQ не вмешиваются, сам шаблон DI не выполняет и входной IFF не меняет
                ; Out:
                ;   две половины по 16 байтов перенесены без изменения порядка, при согласованных операндах это одна строка bitmap из 32 байтов
                ;   HL, DE, BC, AF содержат соответственно слова 0, 2, 1, 7 второго 16-байтового источника, младший байт слова AF попадает в F
                ;   HL', DE', BC' содержат слова 3, 5, 4 того же источника, AF' сохранён, IX содержит слово 6, IY сохранён
                ;   SP равен второму концу приёмника минус 16, внешний CPU SP не восстановлен, исполнение продолжается сразу после 52 байтов копии
                ;   I, IM, IFF и paging сохраняются, R увеличивает младшие семь битов на 44 modulo 128, старший бит сохраняется
                ;   выполнены ровно 32 записи байтов назначения, иных записей RAM и портов нет
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', IX, SP, R и 32 байта назначения
                ; Note:
                ;   SP используется как указатель сначала при POP, затем при PUSH, исходный стек восстанавливает вся цепочка
                ;   две команды EXX в каждой половине возвращают расположение наборов, IY и AF' не используются
                ;   при IRQ под текущим SP появляется четырёхбайтовая рамка, обработчик заменяет BC на #7FFD
                ;   36868 сценариев проверили все 192 на 192 пары строк, четыре несогласованных набора операндов, регистры кроме времени и все банки RAM
                ;   каждая половина занимает 22 M1, весь шаблон 44 M1, две префиксные пары POP IX и PUSH IX считаются по два M1 на каждую команду
                ;   локальная копия не имеет RET, произвольный CALL теряет своё значение SP, восстановление принадлежит завершающему коду всей цепочки
; -----------------------------------------
Entry:          LD SP, #C000
                POP HL
                POP BC
                POP DE
                EXX
                POP HL
                POP BC
                POP DE
                POP IX
                POP AF
WriteFirstHalf: LD SP, #4010
                PUSH AF
                PUSH IX
                PUSH DE
                PUSH BC
                PUSH HL
                EXX
                PUSH DE
                PUSH BC
                PUSH HL
ReadSecondHalf: LD SP, #C010
                POP HL
                POP BC
                POP DE
                EXX
                POP HL
                POP BC
                POP DE
                POP IX
                POP AF
WriteLastHalf:  LD SP, #4020
                PUSH AF
                PUSH IX
                PUSH DE
                PUSH BC
                PUSH HL
                EXX
                PUSH DE
                PUSH BC
                PUSH HL
                endmodule
                endmodule
