                module Controls
                module ReadByteSquare
                ; Документация [алгоритм и проверка](../../Docs/ControlsSquares.md)
                ; -----------------------------------------
                ; Чтение 16-битного квадрата байтового индекса из двух физических плоскостей
                ; исходная запись 22, банк 1, смещения #130B..#1313
                ; In:
                ;   HL сохраняется, DE входных аргументов не задаёт, BC сохраняется, AF задаёт A как индекс 0..255 и входной Carry
                ;   банк 1 выбран, исходные Low00..LowFF и High00..HighFF таблицы квадратов сохранены
                ;   на CPU-стеке внешний возврат, ещё два байта нужны для сохранения HL, IRQ не вмешиваются
                ; Out:
                ;   HL сохраняется, DE=входной A*входной A, BC и A сохраняются
                ;   F=80 OR входной Carry из-за INC H от C3 до C4, это не флаги числа DE
                ;   HL', DE', BC', AF', IX и IY, I, IM и IFF сохраняются, SP=входной SP+2, R получает восемь M1
                ; Corrupt:
                ;   DE, F, два байта CPU-стека, R
                ; Note:
                ;   два байта результата находятся в разных страницах по одному индексу, физически это не таблица слов DW
                ;   Carry сохраняется и используется вызывающим SqrtSquareDiff в исходном SBC
                ; -----------------------------------------
                ; сохранение исходного HL на время обращения к двум разрядным плоскостям
Entry:          PUSH HL
                ; поиск младшего байта квадрата в странице ControlsSquareTable.Low00
                LD H, @ControlsSquareConst.LowPage
                LD L, A
                LD E, (HL)
                ; выбор той же позиции в следующей странице High00, INC H сохраняет входной Carry
                INC H
                LD D, (HL)
                POP HL
                RET

                endmodule
                endmodule
