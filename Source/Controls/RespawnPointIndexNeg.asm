                module Controls
                module RespawnPointIndexNeg
                ; Документация [алгоритм и проверка](../../Docs/ControlsPointRespawn.md)
                ; -----------------------------------------
                ; Возврат точки с противоположным чередованием сторон для отрицательного индекса таблицы
                ; исходная запись 22, банк 1, смещения #0E5D..#0EA3
                ; In:
                ;   HL, DE, BC, AF входных аргументов не задают, используются NegativePhase, NegativeStep и NegativeYOffset
                ;   NegativeStep=1..255, R задаёт начальный байт refresh, включая сохраняемый при увеличении бит 7
                ;   банк 1 выбран, изменяемый фазовый операнд доступен для записи, на CPU-стеке внешний возврат
                ;   формулы R и точные регистровые выходы проверены без вмешательства IRQ
                ; Out:
                ;   HL и B сохранены, DE содержит D=X и E=Y, C=NegativeStep, A=X
                ;   NegativePhase заменён на исходный байт XOR 01, новое нулевое значение выбирает первую ветвь, любое ненулевое вторую
                ;   v=MIN(первое чтение R MOD Step,94), первая ветвь Y=(v+YOffset) AND FF и X=LowX
                ;   вторая ветвь Y=95-v и X=HighX, обе формулы X приведены в ControlsPointRespawn.md
                ;   F соответствует последней проверке CP либо коррекции ADD/SUB координаты X, R включает все выполненные M1
                ;   HL', DE', BC', AF', IX и IY, I, IM и IFF сохраняются, SP=входной SP+2
                ; Corrupt:
                ;   DE, BC в части C, AF, один фазовый байт, R
                ; Note:
                ;   дополнительных PUSH, CALL и портовых операций нет, изменяется только фазовый операнд
                ;   при Step=0 цикл вычитания не продвигается и не возвращает управление, исходный нулевой шаг требует настройки вызывающим кодом
                ;   Phase=00 и 01 чередуют ветви, произвольные старшие биты фазы сохраняются и могут запрещать первую ветвь
                ;   HighX может дать 00 либо FE при произвольном R, границы начальной подготовки 35 точек сюда не переносятся
                ;   название IndexPos/IndexNeg отражает бит 7 байтового индекса (-control) AND FF, а не знак неограниченного математического числа
                ; -----------------------------------------
                ; чтение фазового байта перед переключением младшего бита
Entry:          LD A, #00
                ; переключение только младшего бита фазового селектора
                XOR #01
                ; сохранение новой фазы в исходном операнде LD A,nn
                LD (@ControlsPointRespawnState.NegativePhase), A
                ; чтение шага, нулевой шаг создаёт непродвигающийся цикл
                LD C, #00
                JR NZ, @Controls.RespawnPointIndexNeg.SecondSample              ; переход, если новая фаза ненулевая, выбрать второе сочетание сторон

                ; получение первого байта R для остатка по ненулевому шагу
                LD A, R
                ; проверка остатка относительно шага перед очередным вычитанием
FirstModulo:    CP C
                JR C, @Controls.RespawnPointIndexNeg.CapFirstY                  ; переход, если остаток меньше шага, ограничить вертикальную координату

                SUB C
                JP @Controls.RespawnPointIndexNeg.FirstModulo

                ; проверка ограничения остатка сверху значением 94
CapFirstY:      CP #5E
                JR C, @Controls.RespawnPointIndexNeg.OffsetFirstY               ; переход, если остаток меньше 94, не загружать ограничитель

                LD A, #5E
                ; вычисление Y первой ветви с исходным байтовым смещением
OffsetFirstY:   ADD A, #00
                LD E, A
                ; получение второго R без горизонтального смещения первой ветви
                LD A, R
                ; проверка нулевого X перед заменой на 1
                CP #01
                JR NC, @Controls.RespawnPointIndexNeg.AcceptFirstX              ; переход, если X не равен нулю, не выполнять прибавление 1

                ADD A, #01
                ; возврат горизонтальной координаты в D, вертикальная уже находится в E
AcceptFirstX:   LD D, A
                RET

                ; получение первого R для отражённой вертикальной ветви
SecondSample:   LD A, R
                ; проверка остатка второй ветви относительно шага
SecondModulo:   CP C
                JR C, @Controls.RespawnPointIndexNeg.CapSecondY                 ; переход, если остаток меньше шага, ограничить его перед отражением

                SUB C
                JP @Controls.RespawnPointIndexNeg.SecondModulo

                ; проверка верхнего ограничения 94 для отражённой координаты
CapSecondY:     CP #5E
                JR C, @Controls.RespawnPointIndexNeg.MirrorSecondY              ; переход, если остаток меньше 94, сохранить его без загрузки ограничителя

                LD A, #5E
                ; вычисление отражённой координаты Y=95-остаток
MirrorSecondY:  SUB #5F
                NEG
                LD E, A
                ; получение второго R для второй ветви со смещением X на 128
                LD A, R
                ADD A, #80
                ; проверка верхней границы смещённого X второй ветви
                CP #FE
                JR C, @Controls.RespawnPointIndexNeg.AcceptSecondX              ; переход, если X меньше 254, сохранить координату без коррекции

                SUB #01
                ; возврат второго сочетания X в D и Y в E
AcceptSecondX:  LD D, A
                RET

                endmodule
                endmodule
