                module Controls
                module DrawSixRowGauge
                ; Документация [алгоритм и проверка](../../Docs/ControlsSixRowGauge.md)
                ; -----------------------------------------
                ; Вывод шестистрочной шкалы узором AA, частичного столбца и нулевого хвоста
                ; исходная запись 23, банк 1, смещения #0E1F..#0E94
                ; In:
                ;   HL адрес верхнего байта шкалы, шесть строк находятся в одинаковом L и последовательных H
                ;   DE и BC числовых аргументов не задают
                ;   A значение шкалы, обычный диапазон 0..48, исходные значения 49..255 не ограничиваются
                ;   банк 1 содержит код и неизменённую таблицу E973..E979, области записи, кода, таблицы и внешнего возврата не пересекаются
                ;   все шесть строк доступны как RAM, увеличение H не должно вести в ROM, IRQ не вмешиваются
                ; Out:
                ;   HL сохраняет H и продвигает L без переноса в H на число фактически записанных столбцов
                ;   при очистке хвоста DE=0005, B=00, C содержит эффективное значение, A равен входному H, F соответствует последнему INC L
                ;   без очистки DE=05AA при отсутствии частичного столбца либо E973 плюс остаток, BC содержит B=00 и эффективное значение в C
                ;   без очистки A равен числу округлённых столбцов по модулю 8 минус 6, F соответствует этому SUB
                ;   HL', DE' и BC' сохраняются, AF' содержит результат частичного столбца либо 0054 при его отсутствии
                ;   IX, IY, I, IM и IFF сохраняются, SP=входной SP+2, R учитывает все выбранные столбцы и ветви
                ;   в обычном диапазоне 0..48 обновляются шесть столбцов по шесть байтов, вне диапазона возможно до четырнадцати столбцов
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', R, шесть байтов каждого фактически записанного столбца
                ; Note:
                ;   CPU-стек не записывается, CALL обёртки не входит в этот контракт
                ;   эффективное значение округляется вверх до кратного восьми только при ненулевом A с младшими битами 111
                ;   остаток 1..6 выбирает исходную маску AA с сохранёнными старшими остаток плюс один битами
                ;   столбцы адресуются увеличением только L, значение FF переносится в 00 той же страницы
                ;   полный перебор 256 значений A и 256 значений L проверен на H=49, 51, 80, FA, это не перебор всех HL
                ;   см. Docs/ControlsSixRowGauge.md для точных выражений, условий флагов и M1
                ; -----------------------------------------
                ; Проверка нулевого значения шкалы, заполненные столбцы в этом случае не требуются.
Entry:          LD C, A
                AND A
                JR Z, @Controls.DrawSixRowGauge.PartialByte                     ; переход, если значение нулевое, сразу проверяется частичный столбец

                ; Проверка остатка 7, только этот остаток заранее округляется до следующего полного байта.
                CPL
                AND #07
                LD A, C
                JR NZ, @Controls.DrawSixRowGauge.CountFull                      ; переход, если остаток не равен 7, предварительное округление не требуется

                ; Округление значения с остатком 7, переполнение исходного байта сохраняется.
                ADD A, #08
                AND #F8
                LD C, A
                ; Расчёт числа полных столбцов по младшим шести битам эффективного значения.
CountFull:      RRCA
                RRCA
                RRCA
                AND #07
                JR Z, @Controls.DrawSixRowGauge.PartialByte                     ; переход, если полных столбцов нет, проверяется частичный столбец

                LD B, A
                LD DE, #05AA
                ; Заполнение шести вертикальных байтов узором AA, строки различаются только старшим адресным байтом.
FillColumn:     LD (HL), E
                INC H
                LD (HL), E
                INC H
                LD (HL), E
                INC H
                LD (HL), E
                INC H
                LD (HL), E
                INC H
                LD (HL), E
                LD A, H
                SUB D
                LD H, A
                INC L
                DJNZ @Controls.DrawSixRowGauge.FillColumn

                ; Сохранение эффективного значения в альтернативном A и проверка частичного столбца.
PartialByte:    LD A, C
                EX AF, AF'
                LD A, C
                AND #07
                JR Z, @Controls.DrawSixRowGauge.CountTail                       ; переход, если остаток нулевой, частичный столбец не рисуется

                ; Поиск исходной маски для остатка от 1 до 6, индекс 7 исключён предварительным округлением.
                LD C, A
                LD B, #00
                EX DE, HL
                LD HL, @ControlsGaugeMasks.Index00
                ADD HL, BC
                LD A, (HL)
                ; Обновление всех шести байтов частичного столбца выбранной маской.
                LD (DE), A
                INC D
                LD (DE), A
                INC D
                LD (DE), A
                INC D
                LD (DE), A
                INC D
                LD (DE), A
                INC D
                LD (DE), A
                LD A, D
                SUB #05
                LD D, A
                EX DE, HL
                INC L
                ; Расчёт числа использованных столбцов для очистки остатка шестистолбцовой шкалы.
CountTail:      EX AF, AF'
                LD C, A
                AND #07
                LD A, C
                JR Z, @Controls.DrawSixRowGauge.RoundColumns                    ; переход, если частичного столбца нет, округлять число столбцов не требуется

                ADD A, #08
RoundColumns:   RRCA
                RRCA
                RRCA
                AND #07
                SUB #06
                RET NC                                                          ; выход, если число округлённых столбцов по модулю 8 не меньше 6, хвост не очищается

                ; Расчёт числа нулевых столбцов до номинальной ширины шесть.
                NEG
                LD B, A
                LD DE, #0005
                XOR A
                ; Очистка шести вертикальных байтов очередного столбца, перенос L в H не выполняется.
ClearColumn:    LD (HL), D
                INC H
                LD (HL), D
                INC H
                LD (HL), D
                INC H
                LD (HL), D
                INC H
                LD (HL), D
                INC H
                LD (HL), D
                LD A, H
                SUB E
                LD H, A
                INC L
                DJNZ @Controls.DrawSixRowGauge.ClearColumn

                RET

                endmodule
                endmodule
