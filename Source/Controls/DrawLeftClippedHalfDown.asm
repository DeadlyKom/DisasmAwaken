                module Controls
                module DrawLeftClippedHalfDown
                ; Документация [алгоритм и проверка](../../Docs/ControlsClippedCircleHalf.md)
                ; -----------------------------------------
                ; Рисование нижней половины с неподвижной левой границей и переходом к двум криволинейным краям
                ; исходная запись 22, банк 1, смещения #11B6..#11CA
                ; In:
                ;   HL указывает правый край строки 0..95 линейного растра 8000..8BFF, DE задаёт E как младший адрес левого края, входной D произвольный
                ;   BC задаёт B=0 для неподвижного левого байта столбца 1, C содержит включающую маску правого края CurveX=8..247
                ;   AF произвольный, сохраняется на CPU-стеке и восстанавливается целиком
                ;   C'=(-X) AND FF, X=1..255, E'=Y0 и X*X+Y0*Y0 не больше 65025, A' содержит байтовый порог перехода к обычному ядру
                ;   IX задаёт IXL как рисунок и IXH как XOR-чередование, IY сохраняется
                ;   банк 1 выбран, код и растр доступны, CPU-стек вне них содержит возврат и допускает шесть дополнительных байтов, IRQ не вмешиваются
                ; Out:
                ;   HL, DE, BC содержат конечные адреса и маски, кроме двух исходных выходов с активным EXX, тогда они содержат арифметическое состояние
                ;   AF полностью сохранён, альтернативные HL, DE, BC содержат ошибку, Y и код X либо адреса и маски при выходе с активным EXX
                ;   A' сохранён, F' получает результат последнего сравнения порога с C' либо сохраняется, если сравнения не было
                ;   IXH и IY сохранены, IXL получает XOR IXH после каждой нарисованной строки
                ;   Direction=1, SavedSP=входной SP-2, SP после RET равен входному SP+2
                ;   I, IM, IFF и 7FFD сохраняются, порты не записываются
                ; Corrupt:
                ;   HL, DE, BC, HL', DE', BC', F', IXL, R, растр, Direction, SavedSP, условно записываемые смещения ядер и шесть временных байтов CPU-стека
                ; Note:
                ;   нулевая ошибка, Bprime=FF и Dprime=0 создаются без изменения входных Cprime, Eprime и Aprime
                ;   порог проверяется после первого прибавления BCprime и увеличения Cprime, совпадение передаёт второе прибавление обычному ядру
                ;   быстрое оборачивание Cprime завершает проход до обратного EXX, левый переход при L=E также оставляет пары переставленными
                ;   общая рамка FSingleCircleHalfFrame уже описывает шесть временных байтов и внешний возврат, новая память не выделяется
                ;   297956 сценариев сопоставляют регистры кроме R, все восемь банков RAM, значения и кратность непиксельных записей
                ;   порог проверен для всех байтов на выбранных краях, все AF перебраны на вертикальном выходе каждого входа, полный набор геометрии не исчерпан
                ;   точные состояния и изменяемые адреса перечислены в ControlsClippedCircleHalf.md, R, кратность пиксельных записей, IRQ, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; Сохранение исходного AF для обычного и нелокального выхода, включая пути с активным EXX.
Entry:          PUSH AF
                ; Создание нулевой ошибки, Bprime=FF и Dprime=0 с сохранением входных кода X и начального Y.
                EXX
                LD HL, #0000
                LD D, H
                LD B, @ControlsCircleHalfConst.NegativeXHigh
                EXX
                ; Выбор нижнего направления строк без изменения порога Aprime.
                LD A, @ControlsCircleHalfConst.DirectionDown
                LD (@ControlsCircleWork.Value.Direction), A
                ; Чтение общего Mode перед ядром, исходный AF уже сохранён и будет восстановлен на возврате.
                LD A, (@ControlsCircleWork.Value.Mode)
                AND A
                ; Передача в ядро с неподвижным левым краем, снятие отсечения определяется последующим сравнением Aprime и Cprime.
                JP @Controls.LeftClippedCircleCore.Entry

                endmodule
                endmodule
