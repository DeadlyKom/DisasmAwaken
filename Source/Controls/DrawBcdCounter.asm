                module Controls
                module DrawBcdCounter
                ; Документация [алгоритм и проверка](../../Docs/ControlsBcdCounter.md)
                ; -----------------------------------------
                ; Вывод младшей BCD-пары и старших пар, выбранных цепочкой переносов
                ; исходная запись 23, банк 1, смещения #1664..#16A9
                ; In:
                ;   HL содержит младшие четыре десятичные цифры, DE старшие четыре в упакованном BCD
                ;   BC задаёт B маску продолжения по парам, входной C не используется, AF аргументов не задаёт
                ;   банк 1 выбран, общая таблица знаков C600 и экран доступны, на CPU-стеке внешний возврат
                ; Out:
                ;   HL и DE, B сохранены, младшая пара всегда выведена в колонках 46 и 47
                ;   при B.0=1 дополнительно выведен H в колонках 43 и 44, при B.1=1 после этого E в 40 и 41
                ;   при B.2=1 после обеих старших пар дополнительно выведен D в колонках 38 и 39
                ;   C равен последней левой колонке, 46, 43, 40 либо 38, AF зависит от последнего пиксельного OR и проверки BIT
                ;   IX и IY, I, IM и IFF сохраняются, SP=входной SP+2, портов и переключений банков нет
                ; Corrupt:
                ;   BC в части C, AF, HL', DE', BC', AF', экранные тетрады выбранных цифр, CPU-стек, R
                ; Note:
                ;   биты B не являются независимыми переключателями, нулевой младший бит запрещает все старшие пары
                ;   B=FF рисует все восемь знаков, B=00 только две младшие цифры
                ;   маски не-BCD значений не исправляются, код знака 0A..0F в таблице соответствует пунктуации
                ;   последний вызов заменён в оригинале последовательным исполнением DrawCounterNibble
                ; -----------------------------------------
                ; вывод младшей тетрады L в правой колонке младшей пары
Entry:          LD A, L
                LD C, #2F
                CALL @Controls.DrawCounterNibble.Entry
                ; перестановка тетрад L для вывода старшей цифры той же пары
                LD A, L
                RRCA
                RRCA
                RRCA
                RRCA
                LD C, #2E
                CALL @Controls.DrawCounterNibble.Entry
                ; проверка переноса из младшей пары перед обновлением H
                BIT 0, B
                RET Z                                                           ; выход, если бит 0 маски сброшен, старшие пары не изменились

                LD A, H
                LD C, #2C
                CALL @Controls.DrawCounterNibble.Entry
                LD A, H
                RRCA
                RRCA
                RRCA
                RRCA
                LD C, #2B
                CALL @Controls.DrawCounterNibble.Entry
                ; проверка переноса из второй пары перед обновлением E
                BIT 1, B
                RET Z                                                           ; выход, если бит 1 маски сброшен, две старшие пары не изменились

                LD A, E
                LD C, #29
                CALL @Controls.DrawCounterNibble.Entry
                LD A, E
                RRCA
                RRCA
                RRCA
                RRCA
                LD C, #28
                CALL @Controls.DrawCounterNibble.Entry
                ; проверка переноса из третьей пары перед обновлением D
                BIT 2, B
                RET Z                                                           ; выход, если бит 2 маски сброшен, старшая пара не изменилась

                LD A, D
                LD C, #27
                CALL @Controls.DrawCounterNibble.Entry
                LD A, D
                RRCA
                RRCA
                RRCA
                RRCA
                LD C, #26
                ; JP @Controls.DrawCounterNibble.Entry, продолжение в DrawCounterNibble.asm

                endmodule
                endmodule
