                module Controls
                module ProjectAndDrawBody
                ; Документация [алгоритм и проверка](../../Docs/ProjectedBodyEntry.md)
                ; -----------------------------------------
                ; Проекция тела в режиме 0, допуск компонент и рисование заданным рисунком
                ; исходная запись 22, банк 1, смещения #0EFA..#0F0A
                ; In:
                ;   DE задаёт рисунок и XOR-чередование, Component0..2 содержат физические знаки и модули проекции
                ;   банк 1 выбран, CPU-стек допускает восемнадцать временных байтов, IRQ не вмешиваются
                ; Out:
                ;   Pattern получает входной DE, режим проекции CEF9 становится нулём до её вызова
                ;   при отказе A=0, F=54, частичные изменения проекции сохраняются, при допуске возвращается результат DrawProjectedBody
                ;   SP=входной SP+2, страница сохранена, портов нет
                ; Corrupt:
                ;   регистры и записи проекции и выбранного рисователя, Pattern, CEF9 и временный CPU-стек
                ; Note:
                ;   4959 сценариев исполняют настоящие процедуры, включая отказ проекции и обоих сравнений компонент
                ;   сверены регистры кроме R и память, значения внутренней рамки ProjectAndCheckComponents отдельно не доказаны
                ; -----------------------------------------
                ; Установка общего рисунка для малого профиля и изменяемого операнда IX большого круга.
Entry:          LD (@ControlsSmallBodiesState.Pattern), DE
                ; Выбор режима 0, проекция использует Component2 как глубину.
                XOR A
                LD (@ControlsSmallBodiesState.Mode), A
                CALL @Controls.ProjectAndCheckComponents.Entry
                ; Проверка допуска готовой проекции перед обращением к растру.
                AND A
                RET Z                                                           ; выход, если проекция либо сравнение компонент вернули A=0

                ; Рисование тела по подготовленной проекции с выбором профиля.
                CALL @Controls.DrawProjectedBody.Entry
                RET

                endmodule
                endmodule
