                module Controls
                module TickBcdCounter
                ; Физическое состояние [панель и счётчик](../../Docs/ActionPanelPhysicalData.md)
                ; Документация [алгоритм и проверка](../../Docs/ControlsBcdCounter.md)
                ; -----------------------------------------
                ; Вращение восьмитактового делителя и инкремент четырёх BCD-пар с частичным выводом
                ; исходная запись 23, банк 1, смещения #162F..#1663
                ; In:
                ;   HL, DE, BC, AF входных аргументов не задают
                ;   RotateGate хранится в операнде F10E, четыре байта счётчика содержат корректные BCD-пары 00..99
                ;   банк 1 выбран, код доступен для записи, таблица знаков C600 и экран доступны, на стеке внешний возврат
                ; Out:
                ;   RotateGate циклически сдвинут вправо на один бит, при исходном бите 0 равном нулю счётчик и экран сохраняются
                ;   при исходном бите 0 равном единице счётчик увеличен на один по модулю 100000000
                ;   штатный RotateGate=80 даёт увеличение один раз за восемь вызовов, нулевой делитель остаётся нулевым
                ;   при увеличении HL содержит младшие четыре цифры, DE старшие четыре, B маску переносов, C колонку последней цифры
                ;   IX и IY, I, IM и IFF сохраняются, SP=входной SP+2, банковых переключений и портовых операций нет
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', RotateGate, четыре байта счётчика, экран и CPU-стек при увеличении, R
                ; Note:
                ;   исходный порядок байтов в памяти E,D,L,H, младшая пара находится в 9BBF, старшая в 9BBE
                ;   верхние пары перерисовываются только при переносах, произвольные не-BCD байты моделью не подтверждены
                ;   после сохранения счётчика исполнение физически продолжается в DrawBcdCounter
                ; -----------------------------------------
                ; чтение и циклическое вращение сохраняемого восьмитактового делителя
Entry:          LD A, #80
                RRCA
                LD (@ControlsBcdCounterState.RotateGate), A
                RET NC                                                          ; выход, если исходный младший бит RotateGate равен нулю, пропустить увеличение

                ; подготовка нулевого слагаемого C и пустой маски переносов B
                LD BC, #0000
                ; чтение двух младших BCD-пар в исходном порядке L,H
                LD HL, (@ControlsBcdCounterState.LowPairs)
                LD A, L
                ; увеличение младшей пары на один с десятичной коррекцией
                ADD A, #01
                DAA
                LD L, A
                LD A, H
                JR NC, @Controls.TickBcdCounter.AddSecondPair                   ; переход, если младшая пара не перенесла сотню, не устанавливать бит 0 маски

                SET 0, B
                ; добавление десятичного переноса ко второй паре через нулевое слагаемое C
AddSecondPair:  ADC A, C
                DAA
                LD H, A
                ; чтение двух старших BCD-пар в исходном порядке E,D
                LD DE, (@ControlsBcdCounterState.HighPairs)
                LD A, E
                JR NC, @Controls.TickBcdCounter.AddThirdPair                    ; переход, если вторая пара не перенесла сотню, не устанавливать бит 1 маски

                SET 1, B
                ; добавление десятичного переноса к третьей паре
AddThirdPair:   ADC A, C
                DAA
                LD E, A
                LD A, D
                JR NC, @Controls.TickBcdCounter.AddFourthPair                   ; переход, если третья пара не перенесла сотню, не устанавливать бит 2 маски

                SET 2, B
                ; добавление переноса к старшей паре, переполнение всего счётчика не сохраняется
AddFourthPair:  ADC A, C
                DAA
                LD D, A
                ; сохранение всех четырёх пар перед последовательным исполнением DrawBcdCounter
                LD (@ControlsBcdCounterState.LowPairs), HL
                LD (@ControlsBcdCounterState.HighPairs), DE
                ; JP @Controls.DrawBcdCounter.Entry, продолжение в DrawBcdCounter.asm

                endmodule
                endmodule
