                module Controls
                module PrintTextGlyph
                ; Документация [вывод текстового окна](../../Docs/ControlsTextDisplay.md)
                ; -----------------------------------------
                ; Подготовка вывода знака 4 на 6 пикселей с проверкой правой границы
                ; исходная запись 23, банк 1, смещения #14E6..#1512
                ; In:
                ;   HL, DE, BC входных аргументов не задают, AF задаёт A исходного кода знака
                ;   выбран банк 1 с исходными CONTROL0 и CONTROL, код и экран доступны для записи
                ;   после InitializeTextWindow операнды прокрутки соответствуют окну x=160..255, y=144..189
                ;   на CPU-стеке лежит внешний возврат, вмешательство ISR в модель не включено
                ;   при прокрутке SP временно указывает на экран, обработчик прерываний не должен использовать этот SP
                ; Out:
                ;   при TextColumn>=24 выполнена прокрутка и выбрана колонка 0, иначе используется текущая колонка
                ;   TextColumn=выбранная колонка+1, DE=адрес пары знаков+5, HL=адрес последней строки назначения
                ;   BC содержит B=сохранённая соседняя тетрада последней строки, C=маска F0 либо 0F
                ;   A содержит записанный последний байт, F соответствует последнему OR, IX сохраняется
                ;   HL' и IY сохраняются, I, IM и IFF сохраняются, банковых переключений и портовых операций нет
                ;   внешний RET задаёт SP=входной SP+2, сама процедура DI не выполняет
                ; Corrupt:
                ;   HL, DE, BC, AF, DE', BC', AF', R, шесть байтов экрана, TextColumn и CPU-стек, при прокрутке всё окно
                ; Note:
                ;   вычисление индекса использует (A-20) AND FF, проверка диапазона кодов отсутствует
                ;   чётный индекс берёт старшую тетраду пары, нечётный младшую, каждая пара занимает шесть байтов
                ;   исполнение физически продолжается в DrawGlyphRows, отдельного CALL нет
                ; -----------------------------------------
                ; вычисление байтового индекса знака относительно кода пробела без проверки диапазона
Entry:          SUB #20
                LD L, A
                ; вычисление адреса шестибайтовой пары, соседние знаки занимают разные тетрады
                RES 0, L
                LD H, #00
                LD D, H
                LD E, L
                ADD HL, HL
                ADD HL, DE
                LD BC, #C600
                ADD HL, BC
                EX DE, HL
                ; сохранение чётности индекса в альтернативном A на время подготовки экранного адреса
                EX AF, AF'
                ; проверка изменяемой колонки относительно ширины 24 знака
                LD C, #00
                LD A, C
                CP #18
                JR C, @Controls.PrintTextGlyph.SetDestination                   ; переход, если колонка меньше 24, использовать её без прокрутки

                ; сохранение адреса знака на время стековой прокрутки окна
                PUSH DE
                CALL @Controls.ScrollTextWindow.Entry
                POP DE
                LD C, #00
                ; вычисление экранного байта нижнего ряда, два знака делят один байт
SetDestination: LD B, C
                LD H, #50
                LD A, #F4
                SRL B
                ADD A, B
                LD L, A
                ; обновление колонки для следующего знака до физического продолжения в DrawGlyphRows
                INC C
                LD A, C
                LD (@ControlsTextDisplayState.TextColumn), A
                ; JP @Controls.DrawGlyphRows.Entry, продолжение в DrawGlyphRows.asm

                endmodule
                endmodule
