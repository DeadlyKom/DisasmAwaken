                module Controls
                module BuildAndActivateParameters
                ; Документация [алгоритм и проверка](../../Docs/ControlsParameterActivation.md)
                ; -----------------------------------------
                ; Подготовка параметров в банке 1 и хвостовая активация набора с выбором банка 0
                ; исходная запись 23, банк 1, смещения #032C..#0331
                ; In:
                ;   HL, DE, BC и AF основных числовых аргументов не задают, зерно и управление читаются дочерним входом из существующего контекста
                ;   входной DE' становится основным DE на выходе, IY сохраняется, остальные альтернативные входы не определяют вычисляемые параметры
                ;   в верхнем окне выбран банк 1, запись в 7FFD разрешена, общее ядро ACTION перенесено и доступны исходные таблицы
                ;   внешний возврат и рамка находятся в общей RAM вне переключаемого окна, адрес возврата действителен после выбора банка 0
                ;   нужны десять дополнительных байтов CPU-стека, рамка не перекрывает код, таблицы и рабочие данные, IRQ не вмешиваются
                ; Out:
                ;   HL=0000, DE=входной DE', BC=0000 OR C, где C является средним четырёхбитным индексом зерна, A=00, F=44
                ;   HL'=7BCD, DE'=DEDC+16*G+9, BC'=0006, A' и F' содержат последнее поле параметров и флаги его последнего сложения с шаблоном
                ;   IX=9BB3, IY, I, IM и IFF сохраняются, SP=входной SP+2
                ;   параметры, девять строк, индекс свёртки и состояние генератора подготовлены BuildParameterTables, затем выполнены 15 маршрутов ApplyParameterSet
                ;   курсоры A и B банка 0, TemplateMode и ThirdGate фиксированного банка 2 обнулены
                ;   в порт 7FFD записан 10, верхнее окно банка 0 остаётся выбранным, исходный банк 1 сохраняет все физические байты
                ;   R получает счёт BuildParameterTables плюс 64 M1, включая исходные CALL, JP и всю хвостовую ActivateParameterSet
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, выходные данные подготовки и применения, десять байтов CPU-стека, управление 7FFD, R
                ; Note:
                ;   исходный JP AC44 является настоящим хвостовым переходом, дополнительный адрес возврата для активации не создаётся
                ;   после выбора банка 0 код банка 1 больше не исполняется, внешний возврат берётся из общей рамки
                ;   G=0..4 выбирается подготовителем, при нулевом индексе свёртки заменяется на 3
                ;   проверка всей цепочки композиционная, независимые числовые модели дочерних процедур проверены отдельно
                ;   игровые имена части полей, нативный запуск и аппаратные IRQ этим договором не объявляются доказанными
                ; -----------------------------------------
                ; подготовка пятнадцати параметров, девяти строк и изменяемого индекса настоящей цепочкой банка 1
Entry:          CALL @Controls.BuildParameterTables.Entry
                ; хвостовая активация в общем коде, выбор банка 0 не требует возвращения в переключаемый код банка 1
                JP @Action.ActivateParameterSet.Entry

                endmodule
                endmodule
