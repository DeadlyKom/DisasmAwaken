                ; Mode может сохранять F от AND A в освобождённых байтах CPU-стека
                ; точные PUSH AF и границы парной проверки описаны в ControlsCircleWork.md
                ; исходная физическая запись Value
Value:          FCircleRasterWork {
                    #00,                                                        ; WorkY, рабочее Y, исходно OffsetY, отсечённые ветви могут его менять
                    #00,                                                        ; WorkX, рабочее X, исходно OffsetX, отсечённые ветви могут его менять
                    #00,                                                        ; CenterY, байтовая строка центра сечения
                    #00,                                                        ; CenterX, байтовая горизонтальная координата центра сечения
                    #00,                                                        ; SectionRadius, результат SqrtSquareDiff для отсечённого сечения
                    #0000,                                                      ; SavedSP, сохранённый CPU-стек, указывает SavedAF перед внешним возвратом
                    #0000,                                                      ; SquareDiff, рабочее слово D*D-A*A-Carry по модулю 65536
                    #00,                                                        ; SavedB, сохранённый B помощника правой маски
                    #00,                                                        ; Direction, код направления строк, 0 вверх, 1 вниз, проверка различает ноль и ненулевое
                    #00                                                         ; Mode, авторский SEDETECT, прямые писатели задают 0/1, три чтения сохраняют или возвращают F от AND Mode, общий графический замысел не установлен
                }
