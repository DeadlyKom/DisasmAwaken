                module Controls
                module BuildRightSpanMask
                ; Документация [алгоритм и проверка](../../Docs/ControlsSpanMasks.md)
                ; -----------------------------------------
                ; Вычисление адреса пиксельного байта и маски от X до младшего бита включительно
                ; исходная запись 22, банк 1, смещения #153C..#156B
                ; In:
                ;   HL входных аргументов не задаёт, DE сохраняется целиком
                ;   BC задаёт сохраняемый B и C=Y, AF задаёт A=X и сохраняется только на время записи B
                ;   банк 1 выбран, SavedB по D18A доступен для записи, общая ячейка D18C доступна для чтения
                ;   на CPU-стеке внешний возврат, нужны ещё два байта для сохранённого AF
                ; Out:
                ;   HL=8000+32*Y+(X DIV 8), DE сохранён, B сохранён, C=FF >> (X AND 7)
                ;   A=входной B, F=42, Z и N установлены, остальные биты F сброшены
                ;   SavedB содержит входной B, два байта перед входным SP содержат входные F и A
                ;   HL', DE', BC', AF', IX и IY, I, IM и IFF сохраняются, SP=входной SP+2
                ; Corrupt:
                ;   HL, BC в части C, AF, SavedB, два байта CPU-стека, R
                ; Note:
                ;   маска строится 8-(X AND 7) недокументированными SLL, каждая добавляет младшую единицу
                ;   Y не ограничивается высотой растра, запись по вычисленному HL здесь не выполняется
                ;   значение D18C не влияет на документированные выходы, чтение и исходные инструкции сохранены
                ;   F описывает последнее DEC счётчика сдвигов, возвращаемый A с ним не сравнивается
                ; -----------------------------------------
                ; сохранение входного AF для временного использования A при записи B
Entry:          PUSH AF
                LD A, B
                ; сохранение входного B в существующей ячейке SavedB
                LD (@ControlsSpanMasksState.SavedB), A
                ; восстановление исходного X перед вычислением адреса пиксельного байта
                POP AF
                LD L, C
                LD C, A
                ; вычисление адреса строки 8000+32*Y
                LD H, #04
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ; вычисление номера байта X DIV 8 и добавление его к адресу строки
                SRL C
                SRL C
                SRL C
                LD B, #00
                ADD HL, BC
                ; вычисление числа сдвигов 8-p для включённого правого края
                AND #07
                SUB #08
                NEG
                LD C, A
                ; чтение D18C с последующим перезаписыванием его флагов циклом маски
                LD A, (#D18C)
                AND A
                LD A, C
                LD C, #00
                ; расширение правой маски очередной младшей единицей через SLL
ShiftMask:      SLL C
                DEC A
                JR NZ, @Controls.BuildRightSpanMask.ShiftMask                   ; переход, если остались сдвиги правой маски до полного включения края

                ; восстановление входного B без изменения готовой маски в C и флагов DEC
                LD A, (@ControlsSpanMasksState.SavedB)
                LD B, A
                RET

                endmodule
                endmodule
