                module Controls
                module QueueTextItem
                ; Документация [производитель текстовой очереди](../../Docs/TextQueueProducer.md)
                ; -----------------------------------------
                ; Ограниченный поиск свободной записи очереди и сохранение числа либо указателя строки
                ; исходная запись 23, банк 1, файловые смещения #117B..#11A1
                ; In:
                ;   HL сохраняется, DE задаёт запись, D записывается первым байтом HighKind, E вторым LowValue
                ;   BC сохраняется, AF сохраняется целиком и аргументов не задаёт
                ;   выбран банк 1 с CONTROL0 и CONTROL, код и таблица доступны для записи, WriteCursor указывает Slot00..Slot0F либо End
                ;   HighKind=00 является концом кольца, HighKind=01 свободной записью, поиск ограничен 16 чтениями
                ;   на CPU-стеке находится внешний возврат, требуется ещё шесть байтов для сохранённых HL, BC и AF
                ;   локальный договор не включает вмешательство ISR, процедура сама DI не выполняет
                ; Out:
                ;   HL сохранён, DE сохранён, BC и AF сохранены
                ;   при найденном HighKind=01 записаны D и E, WriteCursor получает адрес после двух байтов записи
                ;   маркер HighKind=00 переносит поиск на Slot00 и тоже расходует одну из 16 попыток
                ;   если за 16 чтений свободная запись не найдена, очередь и WriteCursor не меняются, признака отказа в регистрах нет
                ;   рамка сохранённых регистров остаётся в RAM стека, внешний RET задаёт SP=входной SP+2
                ;   HL', DE', BC', AF', IX, IY, I, IM и IFF сохраняются, портов ввода и вывода нет
                ; Corrupt:
                ;   шесть байтов рамки CPU-стека, найденная запись и WriteCursor при успехе, R
                ; Note:
                ;   запись хранит D перед E, указатель строки физически big endian, это два байтовых поля, не DW little endian
                ;   тип 02 потребитель передаёт десятичному выводу байта, это число с минимальной шириной два знака, не код символа
                ;   D=00 и D=01 не проверяются производителем, такая запись при дальнейшем чтении означает маркер либо свободное место
                ;   при старте на End и единственном свободном Slot0F поиск возвращает отказ, исходная особенность не исправлена
                ;   QueueNumber не делает CALL к QueueTextItem, исполнение продолжается физически, см. TextQueueProducer.md
                ; -----------------------------------------
                ; сохранение регистров, поиск не возвращает в них признак отказа
Entry:          PUSH HL
                PUSH BC
                PUSH AF
                ; чтение изменяемого курсора записи, он может указывать на конечный маркер
                LD HL, @ControlsTextQueue.Slot00
                ; ограничение поиска шестнадцатью чтениями, обход маркера тоже входит в лимит
                LD B, @TextQueueConst.Capacity
                ; проверка HighKind текущего физического элемента на свободное значение 01
FindFree:       LD A, (HL)
                DEC A
                JR Z, @Controls.QueueTextItem.StoreItem                         ; переход, если исходный HighKind равен 01, сохранить запись в свободное место

                ; восстановление HighKind после DEC для проверки конечного значения 00
                INC A
                JR Z, @Controls.QueueTextItem.WrapSearch                        ; переход, если исходный HighKind равен 00, перейти к началу кольца

                ; выбор следующей двухбайтовой записи после занятого элемента
                INC HL
                INC HL
                DJNZ @Controls.QueueTextItem.FindFree

                ; восстановление входных AF, BC и HL, в том числе при молчаливом отказе
RestoreRegs:    POP AF
                POP BC
                POP HL
                RET

                ; возврат к Slot00 после маркера, DJNZ расходует отдельную попытку
WrapSearch:     LD HL, @ControlsTextQueue.Slot00
                DJNZ @Controls.QueueTextItem.FindFree

                JR @Controls.QueueTextItem.RestoreRegs

                ; запись HighKind из D, затем LowValue из E, без проверки зарезервированных значений D
StoreItem:      LD (HL), D
                INC HL
                LD (HL), E
                INC HL
                ; сохранение адреса после записанного элемента в операнде WriteCursor
                LD (@ControlsTextQueueState.WriteCursor), HL
                JR @Controls.QueueTextItem.RestoreRegs

                endmodule
                endmodule
