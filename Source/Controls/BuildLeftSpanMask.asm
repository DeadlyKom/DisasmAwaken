                module Controls
                module BuildLeftSpanMask
                ; Документация [алгоритм и проверка](../../Docs/ControlsSpanMasks.md)
                ; -----------------------------------------
                ; Вычисление адреса пиксельного байта и маски от старшего бита до X включительно
                ; исходная запись 22, банк 1, смещения #1515..#153B
                ; In:
                ;   HL входных аргументов не задаёт, DE задаёт сохраняемый D, входной E не используется
                ;   BC задаёт C=Y, входной B не используется, AF задаёт A=X, входные флаги не влияют на результат
                ;   X и Y байтовые, код банка 1 и общая ячейка D18C доступны, на CPU-стеке внешний возврат
                ; Out:
                ;   HL=8000+32*Y+(X DIV 8), D сохранён, E=LOW(HL)
                ;   B=(FF << (7-(X AND 7))) AND FF, C=X DIV 8, A=B
                ;   F=53 OR (B AND 28), Z,H,N,C установлены, S и PV сброшены, биты 5,3 отражают маску
                ;   HL', DE', BC', AF', IX и IY, I, IM и IFF сохраняются, SP=входной SP+2
                ; Corrupt:
                ;   HL, DE в части E, BC, AF, R
                ; Note:
                ;   RAM не записывается, указатель вычисляется без обращения по нему, Y не ограничивается высотой игрового растра
                ;   общий байт D18C читается, но его влияние на флаги уничтожается циклом маски, назначение этого байта вне помощника остаётся неразобранным
                ;   после CPL Z остаётся установленным вопреки ненулевой маске, это не проверка A
                ; -----------------------------------------
                ; подготовка координаты строки и сохранение X до вычисления линейного адреса
Entry:          LD L, C
                LD C, A
                ; вычисление 8000+32*Y через сдвиг слова 0400+Y
                LD H, #04
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ; вычисление номера байта X DIV 8 и добавление его к адресу строки
                SRL C
                SRL C
                SRL C
                LD B, #00
                ADD HL, BC
                ; вычисление фазы X внутри восьмипиксельного байта
                AND #07
                LD B, A
                ; чтение общего байта D18C, его флаги будут перезаписаны циклом маски
                LD A, (#D18C)
                AND A
                LD A, B
                LD B, #FF
                ; вычисление числа сдвигов маски, p+1 для включённого левого края
                INC A
                ; вычисление младшего остатка маски перед последующей инверсией
ShiftMask:      SRL B
                DEC A
                JR NZ, @Controls.BuildLeftSpanMask.ShiftMask                    ; переход, если остались сдвиги маски до включённого пикселя X

                ; инверсия остатка в старшую маску с сохранением Z и Carry последнего DEC
                LD A, B
                CPL
                LD B, A
                LD E, L
                RET

                endmodule
                endmodule
