                module Controls
                module DrawInteriorCircle
                ; Документация [алгоритм и проверка](../../Docs/ControlsCircleInteriorFull.md)
                ; -----------------------------------------
                ; Рисование верхней и нижней половин большого контура без горизонтального отсечения
                ; исходная запись 22, банк 1, смещения #1314..#131F
                ; In:
                ;   HL, DE, BC, AF числовых аргументов не задают
                ;   Radius=9..119, CenterY=0..95, CenterX-Radius не меньше 8 и CenterX+Radius не больше 248
                ;   IX задаёт IXL как рисунок строки, IXH как XOR-чередование, IY сохраняется
                ;   выбран банк 1, линейный растр 8000..8BFF и изменяемые операнды доступны, IRQ не вмешиваются
                ;   CPU-стек вне растра и кода содержит внешний возврат и допускает восемь дополнительных байтов
                ; Out:
                ;   HL содержит конечный правый адрес нижней половины, E конечный младший левый адрес, B и C рабочие маски последнего достигнутого шага
                ;   D содержит младший адрес правой границы последней нарисованной строки нижней половины
                ;   AF содержит левую включающую маску B исходного центрального сечения и F=42
                ;   HL' содержит конечную ошибку нижней половины, D'=0, E' подготовленный счётчик Y, B'=FF, C' код оставшегося X
                ;   AF', IXH, IY сохраняются, IXL равен исходному рисунку с XOR IXH после каждой нарисованной строки
                ;   открытый интервал каждой строки заполнен рисунком, центральная строка обработана дважды без сброса IXL между половинами
                ;   Direction=1, Mode сохраняется, SavedB равен левой маске, SavedSP=входной SP-2, SP после RET равен входному SP+2
                ;   I, IM, IFF и 7FFD сохраняются, вне растра изменяются только доказанные операнды и временный CPU-стек
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', IXL, R, растр, Direction, SavedB, SavedSP, четыре исходных смещения кода и восемь временных байтов CPU-стека
                ; Note:
                ;   сначала идёт верхняя половина, затем нижняя, исходная перестановка или отдельное обнуление рисунка изменили бы центральную строку
                ;   выход выполняется по вертикальной границе либо совпадению байтов левого и правого краёв, идеальный круг после этого не продолжается
                ;   4941 сценарий и 315225 строк проверяют настоящие дочерние процедуры, четыре положения стека и все байты рисунка
                ;   сопоставлены регистры кроме R, все восемь банков RAM, значения и кратность всех непиксельных записей
                ;   R, кратность пиксельных записей, полное произведение входов, горизонтально отсечённые входы общих ядер, IRQ, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; Создание центрального сечения и включающих масок перед верхней половиной.
Entry:          CALL @Controls.BuildCircleSpan.Entry
                ; Рисование верхней половины, при выходе IXL уже содержит чередование после всех её строк.
                CALL @Controls.DrawCircleHalfUp.Entry
                ; Восстановление центрального сечения без сброса текущего IXL, центральная строка будет обработана повторно.
                CALL @Controls.BuildCircleSpan.Entry
                ; Рисование нижней половины с прямым возвратом внешнему вызывающему через исходный JP.
                JP @Controls.DrawCircleHalfDown.Entry

                endmodule
                endmodule
