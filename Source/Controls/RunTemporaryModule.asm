                module RunTemporaryModule
                ; Документация [банки и ограничения входа](../../Docs/ControlsTemporaryModule.md)
                ; Пары клавиш [проверенная область поиска входа](../../Docs/ControlsTemporaryModule.md#пары-клавиш-в-одном-проходе-сканера)
                ; Документация [работающий предшественник в авторском демо](../../Docs/ControlsAuthorDemoHyperJump.md)
                ; [Косвенные переходы и возвраты по тем же адресам](../../Docs/ControlsTemporaryModule.md#цели-косвенных-переходов-и-возвраты-рисователя)
                ; Документация [Controls](../../Docs/FunctionDetails/Controls.md)
                ; -----------------------------------------
                ; Неиспользуемый блок сохранения памяти, распаковки временного модуля и восстановления полётного кода
                ; исходная запись 23, файловые смещения #0000..#007E
                ; In:
                ;   в прямом префиксе HL, DE, BC и AF входных числовых аргументов не задают, IX содержит слово для сохранения
                ;   для прямого Entry банк 1 выбран без блокировки 7FFD, первые 13 байтов DADE..DAEA сохранены
                ;   два байта ниже входного SP находятся в фиксированной RAM, доступны для записи и не перекрывают 5E33..5E34 либо CurrentPage по 6306
                ;   слово 5E33 доступно для записи, IRQ не вмешивается в прямой префикс
                ;   условный алгоритм после первого OUT требует копии кода в фиксированной RAM, исходных целей CALL в ACTION и неперекрывающихся кода, буферов и CPU-стека
                ;   успешная условная распаковка требует согласованных источника C600 банка 1 и длины, а также действующего договора UnpackResource
                ;   условный путь требует отсутствия вмешательства IRQ до DI после возврата временного кода, обычного RET из 6500 и сохранности кода и резервных данных хвоста
                ;   требования к регистрам и RAM временного кода 6500 задаются его отдельным договором, такой штатный модуль в текущем образе не установлен
                ; Out:
                ;   прямой Entry описан на границе PC=DAEB после первого OUT, до исполнения инструкции уже выбранного банка 6
                ;   HL и DE сохранены, BC=7FFD, AF содержит A=16 и неизменный входной F
                ;   HL', DE', BC', AF', IX, IY, I, IM и IFF сохранены, SP=входной SP-2
                ;   R сохраняет бит 7, младшие семь бит увеличены на 8 M1 по модулю 128, число десятичное
                ;   по выходному SP записан IX, по 5E33 записан адрес этого слова, выбран банк 6, тень CurrentPage по 6306 не обновлена
                ;   в условной перенесённой копии до CALL 6500 область 8C00..BFFF сохранена в банке 6, 6000..7FFF сохранена в E000..FFFF банка 1
                ;   в условной копии после успешной распаковки в 6400 лежит результат, выбран банк 1, SP на входе в 6500 равен 5FFE
                ;   в условной копии слово по 5E33 содержит адрес сохранённого IX, но хвост этим словом SP не восстанавливает
                ;   при условном нормальном возврате временного кода хвост копирует обе области обратно и передаёт управление на 6000
                ;   после такого условного возврата DI сбрасывает IFF перед восстановлением банков, I и IM зависят от неизвестного кода по 6500
                ; Corrupt:
                ;   на прямом префиксе BC, AF только A, SP, R, 7FFD, два байта ниже входного SP и слово по 5E33
                ;   в условном алгоритме HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, SP, I, IM, IFF, R, банковый порт, рамки стека, буферы и операнды
                ;   последствия самого неизвестного кода по 6500 зависят от его содержимого
                ; Note:
                ;   в текущей версии Awakenv02 блок помечен как неиспользуемый, штатный вызов не найден, глобальная недостижимость не доказана
                ;   точный договор прямого префикса не подтверждает штатный вызывающий путь, перенос кода либо источник временного модуля, условная копия не является исполнением исходного прямого входа
                ;   до первого OUT при неперекрывающемся стеке сохраняются IX и все регистры кроме A, BC, SP и R, F остаётся входным
                ;   префикс пишет IX по входному SP-2, затем адрес этого слова по 5E33, A=16, BC=7FFD, SP уменьшен на два, выполнено восемь M1
                ;   первый OUT выбирает банк 6 без записи тени CurrentPage по 6306, следующая инструкция читается из PANEL
                ;   в архивном CONTROL обёртка гиперпрыжка переносилась по 5DA0, брала EFF из C600 банка 1, длина 0535
                ;   архивный хвост продолжался в старом дисковом загрузчике, вставленный JP 6000 разрывает эту цепочку в Awakenv02
                ;   в Awakenv02 по #C600 лежит начало шрифта, с #C870 начинается вывод экрана, архивный EFF отсутствует
                ;   архивный EFF обнуляет оба банка, резерв ядра в банке 1 и вход очистки #D10A в банке 0
                ;   составная архивная модель исполняет возврат по #5DEB и вызов уже заменённого кода по #D10A
                ;   прямой вход из банка 1 после первого OUT начинает читать PANEL из банка 6
                ;   в трёх исходных снимках этот путь проходит до FFFF по байтам банка 6 и оборачивается на 0000 BASIC ROM
                ;   для штатного исполнения нужен подтверждённый перенос кода и источник ненулевой длины
                ;   длина находится в операнде PackedLength, прямых записей именно в эту копию CONTROL не найдено
                ;   20 подставленных HR-потоков прошли настоящий ACTION.UnpackResource до входа 6500
                ;   на входе распаковщика HL=DE=6400, BC=0, A=11, HL' и DE' содержат исходные основные пары, BC'=7FFD, AF' и IX сохранены
                ;   под возвратом распаковщика лежит сохранённое слово IX, его адрес был записан по 5E33
                ;   в условной копии по 5DA0 после запуска ACTION нулевая длина меняет опкод первого LDIR на LD A,B0
                ;   третий LDIR той же копии меняет свой ED на DD, подменённый код AB23 вызывает ROM и достигает RST 08 с байтом ошибки 16
                ;   при длинах #0014..#2B23 шрифт из #C600 даёт ссылку из #6406 на #624F за пределами истории
                ;   при длинах #2B24..#4723 первая копия заменяет начальный опкод распаковщика #AB23 на #C0
                ;   при длинах от #4724 и при слове #0000 третий LDIR заменяет тот же опкод на #77 из ROM через #C723
                ;   условные длины #2B35 и #472F возвращают изменённый распаковщик и приводят к исполнению байтов шрифта по #6500
                ;   при гиперпереходе ROM пишет в #5DC3 байты буфера сектора, операнд PackedLength в банке 1 остаётся нулём
                ;   подстановка наблюдавшихся слов #C4BC и #5103 в условную копию меняет код #AB23 и ведёт в BASIC ROM через RET по #AB4C
                ;   условный хвост перед JP 6000 оставляет SP=5FFE и слово 7FFD на вершине, SavedSP по 5E33 не восстанавливается
                ;   с исходной резервной копией EC56 исполняет байты из 6C56, после 7FFD стек оказывается в ПЗУ, модель достигает второго RST 38
                ; -----------------------------------------
                ; Сохранение IX и адреса его слова на входном стеке.
Entry:          PUSH IX
                LD (@Controls.LoadLegacyPackedBlock.RestoreStack + 1), SP
                LD A, #16
                LD BC, #7FFD
                OUT (C), A
                EXX
                LD HL, #8C00
                LD DE, #C000
                LD BC, #3400
                LDIR
                EXX
                LD A, #11
                OUT (C), A
                EXX
                ; Подготовка переноса временного блока из страницы 1, в раннем CONTROL здесь использовался EFF.
                LD HL, #C600
PackedLength:   LD BC, #0000                                                    ; исходная длина, нуль в LDIR означает 65536 итераций
                LD DE, #8000
                PUSH BC
                PUSH DE
                LDIR
                LD DE, #E000
                LD HL, #6000
                LD BC, #2000
                LDIR
                POP HL
                POP BC
                LD DE, #6400
                PUSH DE
                LDIR
                POP HL
                LD D, H
                LD E, L
                CALL @Action.UnpackResource.Entry
                LD SP, #6000
                CALL #6500
                DI
                LD BC, #7FFD
                LD A, #16
                OUT (C), A
                EXX
                LD HL, #C000
                LD DE, #8C00
                LD BC, #3400
                LDIR
                EXX
                LD A, #10
                OUT (C), A
                EXX
                CALL @Action.ClearWorkBuffer.Entry
                EXX
                LD A, #11
                OUT (C), A
                PUSH BC
                CALL @Controls.CopyViewportToScreen.Entry
                ; Восстановление ядра из сохранённого блока банка 1.
                LD HL, #E000
                LD DE, #6000
                LD BC, #2000
                LDIR
                JP #6000


                endmodule
                endmodule
