                module Controls
                module RunTemporaryModule
                ; Документация [банки и ограничения входа](../../Docs/ControlsTemporaryModule.md)
; Документация [Controls](../../Docs/FunctionDetails/Controls.md)
; -----------------------------------------
; Сохранение памяти по банкам, распаковка временного модуля и восстановление полётного кода
; исходная запись 23, файловые смещения #0000..#007E
; In:
;   Unknown, регистровый контракт ещё не доказан
;   условная модель входит в копию из фиксированной RAM с доступными IX, CPU-стеком и исходным ядром ACTION
;   для успешной распаковки источник C600 банка 1 и длина должны образовывать согласованный поток
; Out:
;   до CALL 6500 область 8C00..BFFF сохранена в банке 6, 6000..7FFF сохранена в E000..FFFF банка 1
;   в 6400 лежит результат распаковки, выбран банк 1, SP на входе в 6500 равен 5FFE
;   слово по 5E33 содержит адрес сохранённого IX, но хвост этим словом SP не восстанавливает
;   при условном нормальном возврате временного кода хвост копирует обе области обратно и передаёт управление на 6000
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, SP, банковый порт, рамки стека, буферы и операнды условного пути
;   последствия самого неизвестного кода по 6500 зависят от его содержимого
; Note:
;   граница файла не доказывает границу логической процедуры
;   прямой вход из банка 1 после первого OUT начинает читать PANEL из банка 6
;   для штатного исполнения нужен подтверждённый перенос кода и источник ненулевой длины
                ;   20 подставленных HR-потоков прошли настоящий ACTION.UnpackResource до входа 6500
                ;   в условной копии по 5DA0 после запуска ACTION нулевая длина меняет опкод первого LDIR на LD A,B0
                ;   третий LDIR той же копии меняет свой ED на DD, вызов AB23 исполняет повреждённый код до входа ROM 0E00
                ;   при длине 0400 исходный шрифт из C600 даёт ссылку из 6406 на 624F за пределами истории распаковки
                ;   условный хвост перед JP 6000 оставляет SP=5FFE и слово 7FFD на вершине, SavedSP по 5E33 не восстанавливается
                ;   при исходной сохранённой копии 6000 соответствует QueueNumberBank1, его исполнение проверкой хвоста не выполняется
; -----------------------------------------
                ; Сохранение IX и адреса его слова на входном стеке.
Entry:          PUSH IX
                LD (@Controls.LoadLegacyPackedBlock.RestoreStack + 1), SP
                LD A, #16
                LD BC, #7FFD
                OUT (C), A
                EXX
                LD HL, #8C00
                LD DE, #C000
                LD BC, #3400
                LDIR
                EXX
                LD A, #11
                OUT (C), A
                EXX
                ; Подготовка переноса исходного блока из страницы 1.
                LD HL, #C600
                LD BC, #0000                                                    ; исходная длина, нуль в LDIR означает 65536 итераций
                LD DE, #8000
                PUSH BC
                PUSH DE
                LDIR
                LD DE, #E000
                LD HL, #6000
                LD BC, #2000
                LDIR
                POP HL
                POP BC
                LD DE, #6400
                PUSH DE
                LDIR
                POP HL
                LD D, H
                LD E, L
                CALL @Action.UnpackResource.Entry
                LD SP, #6000
                CALL #6500
                DI
                LD BC, #7FFD
                LD A, #16
                OUT (C), A
                EXX
                LD HL, #C000
                LD DE, #8C00
                LD BC, #3400
                LDIR
                EXX
                LD A, #10
                OUT (C), A
                EXX
                CALL @Action.ClearWorkBuffer.Entry
                EXX
                LD A, #11
                OUT (C), A
                PUSH BC
                CALL @Controls.CopyViewportToScreen.Entry
                ; Восстановление ядра из сохранённого блока банка 1.
                LD HL, #E000
                LD DE, #6000
                LD BC, #2000
                LDIR
                JP #6000


                endmodule
                endmodule
