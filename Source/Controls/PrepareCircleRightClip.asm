                module Controls
                module PrepareCircleRightClip
                ; Документация [алгоритм и проверка](../../Docs/ControlsCircleSetup.md)
                ; -----------------------------------------
                ; Подготовка левого криволинейного края и фиксированного правого столбца 31
                ; исходная запись 22, банк 1, смещения #14CB..#14E3
                ; In:
                ;   HL, DE, BC и AF входных аргументов не задают
                ;   банк 1 выбран, WorkX, WorkY, CenterY, Radius, Flags и Mode доступны для чтения
                ;   на CPU-стеке внешний возврат, ещё два байта нужны для настоящих CALL, IRQ не вмешиваются
                ; Out:
                ;   для X=(128+WorkX-Radius) AND FF и P=8000+32*CenterY+(X DIV 8)
                ;   HL=(P AND FF00) OR ((LOW P) OR 31), D=Radius, E=LOW P
                ;   B=(FF << (7-(X AND 7))) AND FF, C=FF, A=LOW HL, F соответствует OR этого A
                ;   C'=(-Radius) AND FF, E'=0, остальные альтернативные регистры, IX и IY сохраняются
                ;   I, IM и IFF сохраняются, SP=входной SP+2, R получает 58+4*(X AND 7) M1
                ; Corrupt:
                ;   HL, DE, BC, AF, E', C', два байта CPU-стека, R
                ; Note:
                ;   маска B включает X, правая маска C=FF сохраняет весь фиксированный край в последующем рисователе
                ;   чтение Mode и AND A не влияют на выход, последующий OR полностью заменяет эти флаги
                ;   вычисленный адрес не разыменовывается, пиксели и рабочие поля не записываются
                ;   без ограничений CenterY это лишь байтово-точная адресная формула, а не обещание допустимого растра
                ; -----------------------------------------
                ; подготовка радиуса и альтернативного состояния без рисования
Entry:          CALL @Controls.LoadCircleMidpoint.Entry
                ; выбор центральной строки для левого криволинейного края
                LD A, (@ControlsCircleSetupState.CenterY)
                LD C, A
                ; вычисление X левого края как 128+WorkX-Radius по модулю байта
                LD A, #80
                ADD A, B
                SUB D
                ; построение адреса и включающей маски левого края настоящим помощником
                CALL @Controls.BuildLeftSpanMask.Entry
                ; чтение Mode сохранено, его промежуточные флаги ниже заменяет OR
                LD A, (@ControlsInteriorRowsState.Mode)
                AND A
                ; вычисление адреса фиксированного правого столбца 31 без записи пикселей
                LD A, E
                OR #1F
                LD L, A
                ; выбор полностью сохраняющей маски фиксированного правого края
                LD C, #FF
                RET

                endmodule
                endmodule
