                module Controls
                module NextBufferRandom
                ; Документация [алгоритм и проверка](../../Docs/ControlsBufferPoints.md)
                ; -----------------------------------------
                ; Получение байта из изменяемого 16-битового состояния генератора
                ; исходная запись 22, банк 1, смещения #0A8D..#0AB2
                ; In:
                ;   HL, DE, BC сохраняются, AF входных аргументов не задаёт, Seed читается из операнда CA8F
                ;   HL', DE', BC' используются как рабочие, AF', IX и IY входных аргументов не задают
                ;   банк 1 выбран, изменяемый операнд Seed доступен для записи, на CPU-стеке внешний возврат
                ; Out:
                ;   HL, DE, BC сохранены, A равен младшему байту нового Seed
                ;   t=(7*Seed-4) AND FFFF, u=(HIGH(t)-LOW(t)) AND FFFF, v=(t-u) AND FFFF, новый Seed=(v-1) AND FFFF
                ;   F соответствует 16-битовому SBC t-u до последующего DEC HL, а не проверке возвращаемого A
                ;   HL' равен новому Seed, DE'=u, BC'=LOW(t), AF', IX и IY сохраняются
                ;   I, IM и IFF сохраняются, портов и дополнительных PUSH нет, SP=входной SP+2
                ; Corrupt:
                ;   AF, HL', DE', BC', два байта Seed, R
                ; Note:
                ;   оба OR A сбрасывают Carry перед SBC, входные флаги на результат не влияют
                ;   для исходного Seed=0 до цикла выполняются 59 переходов, затем период равен 387, это не полный 16-битовый цикл
                ; -----------------------------------------
                ; сохранение основных пар через EXX перед вычислением нового состояния генератора
Entry:          EXX
                ; чтение существующего изменяемого 16-битового состояния Seed
                LD BC, #0000
                LD H, B
                LD L, C
                LD D, H
                LD E, L
                ; вычисление промежуточного 4*Seed-4 по модулю 65536
                DEC HL
                ADD HL, HL
                ADD HL, HL
                EX DE, HL
                LD H, B
                LD L, C
                ; вычисление t=7*Seed-4 добавлением удвоенного и исходного Seed
                ADD HL, HL
                ADD HL, DE
                ADD HL, BC
                LD D, H
                LD E, L
                ; вычисление разности старшего и младшего байтов промежуточного t
                LD L, H
                LD H, #00
                LD B, H
                LD C, E
                OR A
                SBC HL, BC
                EX DE, HL
                OR A
                ; вычитание полученной разности из t без входного заёма
                SBC HL, DE
                ; вычисление нового Seed уменьшением промежуточного v на один без изменения флагов SBC
                DEC HL
                LD (@ControlsBufferPointsState.Seed), HL
                LD A, L
                EXX
                RET

                endmodule
                endmodule
