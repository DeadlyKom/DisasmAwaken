                module Controls
                module RelocateStationReload
                ; Документация [алгоритм и проверка](../../Docs/ControlsStationRelocation.md)
                ; -----------------------------------------
                ; Копирование 256 байтов блока загрузки STATIONF в общую RAM и передача управления 4000
                ; исходная запись 23, банк 1, смещения #01BD..#01CA
                ; In:
                ;   HL, DE, BC входных аргументов не задают, AF задаёт сохраняемый A и исходные S/Z/Carry
                ;   банк 1 выбран, участок SourceCode..SourceCode+BlockSize-1 доступен для чтения, RuntimeCode..RuntimeCode+BlockSize-1 доступен для записи
                ;   источник и назначение принадлежат разным физическим банкам 1 и 5, IRQ не вмешиваются, CPU-стек здесь не читается
                ; Out:
                ;   HL=DDA9, DE=4100, BC=0, A сохранён, в 4000..40FF побайтовая копия DCA9..DDA8 банка 1
                ;   F сохраняет входные S/Z/Carry, H/N/PV сброшены, биты 3 и 5 вычислены из A и последнего исходного байта по формуле LDIR
                ;   HL', DE', BC', AF', IX, IY сохраняются, SP не изменён, I, IM, IFF и 7FFD сохраняются
                ;   после JP PC=4000, перенесённая цель ещё не исполнена, внешний адрес возврата не извлекается
                ;   R получает 516 M1 с сохранением бита 7, кроме 256 байтов фиксированного банка 5 RAM не изменяется
                ; Corrupt:
                ;   HL, DE, BC, F, R, 256 байтов общей RAM 4000..40FF
                ; Note:
                ;   назначение лежит в экранной RAM фиксированного банка 5, поэтому переживает последующие переключения верхнего окна
                ;   копирование не выполняет OUT и не вызывает TR-DOS, чтение файла относится к перенесённому коду после этой границы
                ;   копируется фиксированный физический участок с кодом и данными, все 256 байтов исполняемыми не объявляются
                ;   65792 сценария проверили все AF на исходном блоке и все значения каждого копируемого байта на 256 дополнительных рисунках
                ;   сопоставлены регистры включая R, восемь банков RAM, значения и порядок записей модели эмулятора
                ;   полное произведение 256 исходных байтов, аппаратные шинные циклы, TR-DOS, IRQ, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; Выбор исходного банкового участка, содержащего вход перезагрузки станции и соседние данные.
Entry:          LD HL, @ControlsStationRelayConst.SourceCode
                ; Выбор исходного назначения в фиксированной экранной RAM, адрес не переносится и новая область не выделяется.
                LD DE, @ControlsStationRelayConst.RuntimeCode
                ; Создание исходной длины копии в 256 байтов, это размер участка, а не число инструкций.
                LD BC, @ControlsStationRelayConst.BlockSize
                ; Копирование участка по возрастающим адресам из банка 1 в фиксированный банк 5.
                LDIR
                ; Передача управления перенесённому входу без чтения CPU-стека, последующее исполнение цели проверяется отдельно.
                JP @ControlsStationRelayConst.RuntimeCode

                endmodule
                endmodule
