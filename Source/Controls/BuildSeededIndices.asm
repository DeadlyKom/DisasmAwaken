                module Controls
                module BuildSeededIndices
                ; Документация [алгоритм и проверка](../../Docs/ControlsSeededParameters.md)
                ; -----------------------------------------
                ; Формирование четырёх индексов из двухсловного зерна, координатной области и числа шагов генератора
                ; исходная запись 23, банк 1, смещения #03BC..#03FD
                ; In:
                ;   HL задаёт первое слово зерна X, DE задаёт второе слово Y, BC сохраняется
                ;   AF задаёт A как управляющий байт, число шагов K=A+1 в диапазоне 1..256, входной F на выходы не влияет
                ;   банк 1 выбран, общее ядро ACTION перенесено в 6000, физический FWordRandomState доступен для записи
                ;   на стеке внешний возврат, ещё шесть байтов нужны для сохранения BC и настоящих вложенных вызовов, IRQ не вмешиваются
                ; Out:
                ;   при T=(HIGH X XOR LOW X XOR HIGH Y XOR LOW Y) AND 7 и V=NOT выходного байта последнего StepWordRandom
                ;   H=4 при исходном ClassifyCoordinateRegion(X)=OutsideCode, иначе H=V DIV 64, L=((V DIV 4) AND 15)+1
                ;   D=HIGH Second после последнего шага, E=V AND 3, BC сохраняется
                ;   A=MAX(T-1, 0), F=44 при T=0, F=42 при T=1, F=02 при T>=2
                ;   HL', DE', BC' сохраняются, A'=V AND 3, F' соответствует AND этого A' с установленным H и сброшенными N, C
                ;   IX, IY, I, IM и IFF сохраняются, SP=входной SP+2
                ;   физические First и Second содержат состояние после K шагов, исходное состояние заменяется зерном X, Y перед циклом
                ;   R получает 41+M+34*K+(T=0)+2*O M1, M задаёт ClassifyCoordinateRegion(X), O=1 ровно вне трёх областей
                ; Corrupt:
                ;   HL, DE, AF, AF', четыре байта состояния, шесть байтов CPU-стека, R
                ; Note:
                ;   управляющий FF даёт B=0 перед DJNZ и ровно 256 шагов, значение не трактуется как пропуск цикла
                ;   возвращаемый A зависит только от исходного зерна, альтернативный AF хранит два младших разряда инвертированного случайного байта
                ;   основной A не содержит случайный байт на выходе, его восстанавливает последний EX AF, AF'
                ;   поля H, L, E являются числовыми индексами, независимая флаговая схема им не приписывается
                ;   игровые имена областей и конечных параметров ещё не установлены, полный вызывающий UnknownDE10 не доказан
                ; -----------------------------------------
                ; сохранение BC вызывающего кода перед координатным классификатором и счётчиком шагов
Entry:          PUSH BC
                ; временное сохранение входного управляющего A в альтернативном AF
                EX AF, AF'
                ; вычисление трёхбитной свёртки четырёх байтов исходного зерна
                LD A, H
                XOR L
                XOR E
                XOR D
                AND @ControlsSeededParametersConst.HashMask
                ; вычисление индекса MAX(T-1, 0), исходный ноль требует отдельного обнуления
                DEC A
                JP P, @Controls.BuildSeededIndices.SaveSeed                     ; переход, если исходная свёртка T ненулевая, сохранить результат T-1

                ; выбор нулевого индекса при T=0 с исходными флагами XOR
                XOR A
                ; сохранение вычисленного индекса и его F в альтернативном AF, восстановление управляющего A
SaveSeed:       EX AF, AF'
                ; обновление физического состояния генератора двумя входными словами зерна
                LD (@ActionWordRandomState.Value.First), HL
                LD (@ActionWordRandomState.Value.Second), DE
                ; вычисление байтового счётчика шагов, нулевой B после FF означает 256 итераций
                INC A
                LD B, A
                ; определение числового типа области по исходному первому слову зерна
                CALL @Action.ClassifyCoordinateRegion.Entry
                ; проверка OutsideCode перед выбором особого старшего индекса
                LD C, A
                LD A, C
                CP @ActionRegionTypeConst.OutsideCode
                LD C, #00
                JR NZ, @Controls.BuildSeededIndices.StepLoop                    ; переход, если тип области не равен OutsideCode, оставить C=0

                ; выбор C=1 вне трёх координатных областей
                INC C
                ; обновление исходного генератора, он сохраняет счётчик B и признак C
StepLoop:       CALL @Controls.StepWordRandom.Entry
                DJNZ @Controls.BuildSeededIndices.StepLoop

                ; инверсия выходного байта последнего шага перед выделением числовых индексов
                CPL
                LD E, A
                ; вычисление L в диапазоне 1..16 из средних четырёх разрядов инвертированного байта
                AND @ControlsSeededParametersConst.MiddleMask
                RRCA
                RRCA
                INC A
                LD L, A
                ; вычисление старшего индекса из разрядов 7..6 через два циклических сдвига
                LD A, E
                RLCA
                RLCA
                AND @ControlsSeededParametersConst.PairMask
                ; проверка сохранённого признака внешней области, C=1 выделяет особый индекс
                DEC C
                JR NZ, @Controls.BuildSeededIndices.StoreHighIndex              ; переход, если исходный C=0, использовать вычисленный двухбитный индекс

                ; выбор OutsideHigh вместо случайного старшего индекса для внешней области
                LD A, @ControlsSeededParametersConst.OutsideHigh
                ; сохранение старшего индекса в H
StoreHighIndex: LD H, A
                ; вычисление младшего индекса E из разрядов 1..0 инвертированного байта
                LD A, E
                AND @ControlsSeededParametersConst.PairMask
                LD E, A
                ; восстановление индекса зерна и его F, младший индекс и F от AND переходят в альтернативный AF
                EX AF, AF'
                ; восстановление исходного BC без изменения возвращаемого AF
                POP BC
                RET

                endmodule
                endmodule
