                module CallLegacyDosRom
                ; Документация [старое чтение секторов, распаковка и восстановление полётного контекста](../../Docs/ControlsLegacyLoadChain.md)
                ; -----------------------------------------
                ; Передача внутреннему ROM-входу TR-DOS через подготовленный стек
                ; исходная запись 23, согласованные адреса старой копии, фактический перенос игрой неизвестен, адреса 5ED6..5EDA
                ; In:
                ;   IX, адрес внутренней процедуры ROM, прочие регистры по её договору, IRQ не вмешиваются
                ;   слово SP-2..SP-1 доступно для записи в фиксированной RAM и не пересекает исполняемый код 5ED6..5EDA
                ;   условная копия исходных пяти байтов по 5ED6 доступна, по 3D2F выбрано проверенное TR-DOS с NOP и RET
                ; Out:
                ;   PUSH IX и JP 3D2F передают управление в ROM, его NOP и RET снимают IX как адрес исполнения
                ;   на входе 3D2F SP=входной SP-2, слово на вершине равно IX, младшие семь битов R увеличены на три по модулю 128, bit7 сохранён
                ;   после NOP и RET моста PC равен входному IX, SP равен входному, младшие семь битов R увеличены на пять по модулю 128, bit7 сохранён
                ;   до первой команды цели HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, I, IM и IFF сохраняются, портов нет
                ;   возврат самой процедуры ROM использует прежнюю рамку вызывающего, регистры определяются её кодом
                ; Corrupt:
                ;   R, SP временно уменьшен на два, два временных байта CPU-стека с IX, дальнейшие изменения по достигнутой процедуре ROM
                ; Note:
                ;   вход 3D2F требует выбора TR-DOS при выборке команды, CALL на него вместо исходного JP не добавляется
                ; -----------------------------------------
                ; Передача адреса ROM через вершину стека без дополнительной рамки CALL.
Entry:          PUSH IX
                JP @TrDosLegacy.RomReturn

                endmodule
                endmodule
