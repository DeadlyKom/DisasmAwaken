                module Controls
                module BuildSmallBodyMasks
                ; Документация [алгоритм и проверка](../../Docs/ControlsSmallMasks.md)
                ; -----------------------------------------
                ; Подготовка строковых масок малой фигуры из упакованной затравки радиуса
                ; исходная запись 22, банк 1, смещения #19B0..#19DD
                ; In:
                ;   HL и DE входных аргументов не задают, BC задаёт сохраняемый C, AF задаёт A=2..8 как радиус
                ;   AF' задаёт A'=0 для Primary либо ненулевой A' для Alternate, исходный F сохраняется в альтернативном AF
                ;   банк 1 выбран, исходные затравки сохранены, Row00..Row0B доступны для записи
                ;   на CPU-стеке внешний возврат, дополнительный стек не используется, IRQ не вмешиваются
                ; Out:
                ;   HL указывает AlternateR0+радиус, DE содержит D=0 и E=радиус, BC содержит B=0 и исходный C
                ;   A=Packed альтернативной затравки AND PixelsMask, F соответствует AND A с H=1, N=0 и Carry=0
                ;   HL', DE', BC' сохраняются, AF' содержит исходный входной AF, IX и IY, I, IM и IFF сохраняются
                ;   SP=входной SP+2, R получает 20+[исходный селектор ненулевой]+5*t+3*радиус M1, t=Packed AND CountMask
                ;   сначала записаны t арифметически сдвигаемых масок и радиус копий последней, затем Row00 повторно заменена альтернативной маской
                ; Corrupt:
                ;   HL, DE, B, AF, AF', t+радиус байтов Row00..Row0B, R
                ; Note:
                ;   для исходных радиусов 2..8 t=floor(радиус/2), максимум записывается 12 разных байтов и 13 записей с повтором Row00
                ;   SRA сохраняет знаковый разряд маски, замена на SRL меняет исходные формы
                ;   альтернативная маска Row00 загружается независимо от выбранной затравки основной части
                ;   радиусы 0 и 1 вне договора, при B=0 цикл выходит за LA8FA и перекрывает код построителя
                ;   20 байтов после Row0B завершают исходный резерв LA8FA, штатные радиусы их не изменяют
                ;   DrawSmallBody отсекает радиусы вне 2..8 до вызова, A' выбирает затравку после входа D9DE либо D9DF
                ; -----------------------------------------
                ; сохранение радиуса в E для индексации затравок и длины повторяемой части
Entry:          LD E, A
                LD D, #00
                ; выбор базы Primary до проверки альтернативного селектора
                LD HL, @ControlsSmallMaskSeeds.PrimaryR0
                ; сохранение исходного радиуса и F в альтернативном AF, получение селектора из A'
                EX AF, AF'
                ; проверка нулевого селектора для выбора затравки
                AND A
                JR Z, @Controls.BuildSmallBodyMasks.SelectSeed                  ; переход, если селектор равен нулю, использовать Primary через SelectSeed

                ; выбор базы Alternate для любого ненулевого селектора
                LD HL, @ControlsSmallMaskSeeds.AlternateR0
                ; поиск упакованной затравки с исходным радиусом
SelectSeed:     ADD HL, DE
                ; выделение числового количества сдвигов из разрядов 2..0 Packed
                LD A, (HL)
                AND @SmallMaskConst.CountMask
                LD B, A
                ; выделение начальной пиксельной маски из разрядов 7..3 Packed
                LD A, (HL)
                AND @SmallMaskConst.PixelsMask
                LD HL, @ControlsSmallMaskRows.Row00
                ; создание последовательности строк арифметическим сдвигом маски, бит 7 сохраняется
ShiftMask:      LD (HL), A
                INC HL
                SRA A
                DJNZ @Controls.BuildSmallBodyMasks.ShiftMask

                ; подготовка числа повторов последней сдвинутой маски по исходному радиусу
                LD B, E
                ; заполнение продолжающей части неизменной сдвинутой маской
RepeatMask:     LD (HL), A
                INC HL
                DJNZ @Controls.BuildSmallBodyMasks.RepeatMask

                ; поиск альтернативной затравки для обязательной замены Row00 независимо от первого выбора
                LD HL, @ControlsSmallMaskSeeds.AlternateR0
                ADD HL, DE
                LD A, (HL)
                ; выделение пиксельной части альтернативной затравки, эти F возвращаются вызывающему
                AND @SmallMaskConst.PixelsMask
                ; повторное обновление Row00 альтернативной маской после построения остальных строк
                LD (@ControlsSmallMaskRows.Row00), A
                RET

                endmodule
                endmodule
