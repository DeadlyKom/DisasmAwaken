                module Controls
                module CopyViewportToScreen
                ; Документация [алгоритм и проверка](../../Docs/ControlsBufferCopy.md)
                ; -----------------------------------------
                ; Перенос линейного растра 256 на 96 пикселей в верхнюю половину экрана
                ; исходная запись 22, банк 1, смещения #0870..#0881
                ; In:
                ;   HL, DE, BC, AF и альтернативные регистры, IX и IY входных аргументов не задают
                ;   8000..8BFF содержит 96 линейных растровых строк по 32 байта
                ;   банк 1 выбран, CONTROL0 и его изменяемые операнды доступны для записи
                ;   источник, экран и CPU-стек не перекрываются, источник не перекрывает код копировщика
                ;   на CPU-стеке находится внешний возврат, обработчик IRQ не должен использовать временный экранный SP
                ; Out:
                ;   3072 байта исходного растра перенесены в экранные строки y=0..95, все 32 байта каждой строки
                ;   HL=8C00, DE и BC содержат слова 8BF4..8BF5 и 8BF2..8BF3, A=00, F=42 OR (байт 8BF0 AND 01)
                ;   HL'=488F, DE'=F910, BC' содержит слово 8BFA..8BFB, A' содержит байт 8BF9
                ;   F' соответствует последнему ADD HL,F910 с сохранёнными S,Z,PV из байта 8BF8
                ;   IX содержит слово 8BF6..8BF7, IY слово 8BFE..8BFF, I, IM и IFF сохраняются
                ;   SavedStack содержит входной SP, RemainingPages содержит 01, внешний RET даёт SP=входной SP+2
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, 3072 байта экрана, три байта операндов и два байта CPU-стека, R
                ; Note:
                ;   атрибуты и нижние 96 растровых строк экрана сохраняются, пиксельные байты временно используются как F и F'
                ;   первая часть вызывает CopyScreenRows для восьми страниц, вторая продолжает его физически для четырёх
                ;   DI не выполняется, сохранение IFF не доказывает безопасность ISR при экранном SP
                ; -----------------------------------------
                ; подготовка адреса перед первой половиной верхней строки экрана
Entry:          LD HL, #400F
                ; передача экранного адреса в альтернативный HL и выбор линейного источника
                EXX
                LD HL, #8000
                ; выбор восьми 256-байтовых страниц для экранных строк 0..63
                LD A, #08
                CALL @Controls.CopyScreenRows.Entry
                ; обновление только H экранного адреса, L=0F после восьми страниц сохраняется
                EXX
                LD H, #48
                EXX
                ; выбор ещё четырёх страниц для строк 64..95 перед физическим продолжением
                LD A, #04
                ; JP @Controls.CopyScreenRows.Entry, продолжение в CopyScreenRows.asm

                endmodule
                endmodule
