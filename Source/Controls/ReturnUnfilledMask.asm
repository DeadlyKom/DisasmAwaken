                module ReturnUnfilledMask
                ; Документация [вход UNFILLED](../../Docs/ControlsCircleSetup.md#байты-между-подготовителями)
                ; -----------------------------------------
                ; Возврат маски архивной ветви незаполненного контура
                ; исходная запись 22, банк 1, адреса #D501..#D503
                ; In:
                ;   выбран банк 1, на CPU-стеке лежит двухбайтовый адрес продолжения
                ; Out:
                ;   B=#7F, HL, DE, C, AF, HL', DE', BC', AF', IX, IY сохраняются
                ;   PC получает слово с CPU-стека, SP увеличивается на два по модулю 65536
                ;   I, IM и IFF сохраняются, R получает два M1
                ; Corrupt:
                ;   B, SP, R
                ; Note:
                ;   исходная метка L89C0, комментарий UNFILLED
                ;   штатный вызов в Awakenv02 не установлен, RAM не записывается
                ; -----------------------------------------
                ; выбор маски с установленными младшими семью разрядами
Entry:          LD B, #7F
                RET

                endmodule
                endmodule
