                module Controls
                module FillEvenSpanHead
                ; Документация [алгоритм и проверка](../../Docs/ControlsEvenSpan.md)
                ; -----------------------------------------
                ; Первые 12 записей общего 30-байтового хвоста заполнителя
                ; исходная запись 22, банк 1, смещения #0EB7..#0ECE
                ; In:
                ;   HL указывает правую исключённую границу внутри страницы, AF задаёт A как байт заполнения
                ;   банк 1 выбран, на CPU-стеке слово SavedHL, затем внешний возврат
                ;   стек и назначение не перекрываются с кодом, IRQ не вмешиваются
                ; Out:
                ;   HL восстанавливается из SavedHL, DE и BC сохраняются, 30 байтов записаны исходным A справа налево
                ;   AF содержит Mode и F от AND A, младший байт адреса оборачивается без изменения H
                ;   HL', DE', BC', AF', IX и IY, I, IM и IFF сохраняются, SP=входной SP+4, R получает 64 M1
                ; Corrupt:
                ;   HL, AF, 30 байтов назначения, R
                ; Note:
                ;   (0) этот файл исполняет 12 записей, затем без инструкции JP продолжается (1) FillEvenSpanTail.asm
                ;   динамические входы Fill28, Fill26, Fill24, Fill22 и Fill20 уменьшают общее число записей на 2..10
                ; -----------------------------------------
                ; -----------------------------------------
                ; (0) Начало общего хвоста, 12 записей перед FillEvenSpanTail
                ; -----------------------------------------
                ; динамический вход на 30 байтов справа налево, заём младшего адреса не изменяет страницу
Entry:          DEC L
                LD (HL), A
                DEC L
                LD (HL), A
                ; динамический вход на 28 байтов справа налево, заём младшего адреса не изменяет страницу
Fill28:         DEC L
                LD (HL), A
                DEC L
                LD (HL), A
                ; динамический вход на 26 байтов справа налево, заём младшего адреса не изменяет страницу
Fill26:         DEC L
                LD (HL), A
                DEC L
                LD (HL), A
                ; динамический вход на 24 байтов справа налево, заём младшего адреса не изменяет страницу
Fill24:         DEC L
                LD (HL), A
                DEC L
                LD (HL), A
                ; динамический вход на 22 байтов справа налево, заём младшего адреса не изменяет страницу
Fill22:         DEC L
                LD (HL), A
                DEC L
                LD (HL), A
                ; динамический вход на 20 байтов справа налево, заём младшего адреса не изменяет страницу
Fill20:         DEC L
                LD (HL), A
                DEC L
                LD (HL), A
                ; JP @Controls.FillEvenSpanTail.Entry, продолжение в FillEvenSpanTail.asm

                endmodule
                endmodule
