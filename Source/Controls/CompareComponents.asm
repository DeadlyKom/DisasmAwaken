                module Controls
                module CompareComponents
                ; Документация [алгоритм и проверка](../../Docs/ControlsComponentCompare.md)
                ; -----------------------------------------
                ; Сравнение двух компонентов после перехода IY к следующей трёхбайтовой записи
                ; исходная запись 22, банк 1, смещения #1AB9..#1ADD
                ; In:
                ;   HL сохраняется, DE входных аргументов не задаёт, BC сохраняется, AF входных аргументов не задаёт
                ;   IX указывает опорный FComponent24, IY указывает предыдущую запись сравниваемой последовательности
                ;   банк 1 выбран, после IY+3 доступны поля Middle и High текущего FComponent24, индексы оборачиваются по слову
                ;   на CPU-стеке внешний возврат, дополнительный стек не требуется, IRQ не вмешиваются
                ; Out:
                ;   HL сохраняется, DE содержит D=High текущей записи AND HighMask и E=3, BC сохраняется
                ;   NZ возвращается при опорном High AND HighMask меньше DirectLimit либо при опорном 15-битовом ключе не меньше текущего
                ;   Z возвращается только при опорном High не меньше DirectLimit и меньшем опорном ключе, A=0 и F=44
                ;   при прямом допуске A=опорный High OR 01, F от OR, при большем High A=опорный High и F от CP D
                ;   при равных High и не меньшем опорном Middle A=опорный Middle OR 01, F от OR
                ;   HL', DE', BC', AF', IX, I, IM и IFF сохраняются, IY увеличивается на три, SP=входной SP+2
                ;   R получает 14 M1 при прямом допуске, 15 при большем опорном High, 16 при меньшем, 22 при сравнении Middle
                ; Corrupt:
                ;   DE, AF, IY, R
                ; Note:
                ;   ключ равен 256*(High AND HighMask)+Middle, Low и бит 7 High не участвуют в сравнении
                ;   бит 7 High здесь только исключён маской, его общий игровой смысл этим помощником не доказывается
                ;   IY увеличивается до проверки, а не только при принятом компоненте, записи RAM отсутствуют
                ;   ProjectAndCheckComponents проверяет Component0, Component1 и Component2 с постоянной опорой Component2, CALL NZ прекращает цепь при отказе
                ;   причина игрового выбора DirectLimit=0A остаётся вне локального договора
                ; -----------------------------------------
                ; поиск следующей трёхбайтовой записи, исходный IY указывает предыдущую запись последовательности
Entry:          LD DE, @FComponent24
                ADD IY, DE
                ; чтение старшей части текущего компонента без исключённого разряда 7
                LD A, (IY+#02)
                AND @ComponentCompareConst.HighMask
                LD D, A
                ; чтение старшей части опорного компонента с той же числовой маской
                LD A, (IX+#02)
                AND @ComponentCompareConst.HighMask
                ; проверка прямого допуска по малой старшей части опорного компонента
                CP @ComponentCompareConst.DirectLimit
                JR C, @Controls.CompareComponents.AcceptComponent               ; переход, если опорная старшая часть меньше DirectLimit, принять компонент через AcceptComponent

                ; проверка порядка старших частей двух усечённых ключей
                CP D
                JR C, @Controls.CompareComponents.RejectComponent               ; переход, если опорная старшая часть меньше текущей, отклонить компонент через RejectComponent

                RET NZ                                                          ; выход, если опорная старшая часть больше текущей, вернуть NZ и F от CP D

                ; проверка средних байтов только при равных старших частях, младшие байты не читаются
                LD A, (IX+#01)
                CP (IY+#01)
                JR C, @Controls.CompareComponents.RejectComponent               ; переход, если опорный Middle меньше текущего Middle, отклонить компонент через RejectComponent

                ; формирование NZ с нечётным ненулевым A без унификации исходных путей возвращаемых F
AcceptComponent:OR #01
                RET

                ; формирование отказа A=0, F=44, Z установлен
RejectComponent:XOR A
                RET

                endmodule
                endmodule
