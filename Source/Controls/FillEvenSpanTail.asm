                module Controls
                module FillEvenSpanTail
                ; Документация [алгоритм и проверка](../../Docs/ControlsEvenSpan.md)
                ; -----------------------------------------
                ; Последние 18 записей заполнителя, восстановление HL и чтение направления
                ; исходная запись 22, банк 1, смещения #0ECF..#0EF8
                ; In:
                ;   HL указывает правую исключённую границу внутри страницы, AF задаёт A как байт заполнения
                ;   банк 1 выбран, на CPU-стеке слово SavedHL, затем внешний возврат, IRQ не вмешиваются
                ; Out:
                ;   HL восстанавливается из SavedHL, DE и BC сохраняются, 18 байтов записаны исходным A справа налево
                ;   AF содержит Direction и F от AND A, Z установлен только при нулевом Direction
                ;   HL', DE', BC', AF', IX и IY, I, IM и IFF сохраняются, SP=входной SP+4, R получает 40 M1
                ; Corrupt:
                ;   HL, AF, 18 байтов назначения, R
                ; Note:
                ;   (2) порядок после (1) FillEvenSpanHead.asm обязателен при последовательном исполнении
                ;   Fill16..Fill2 являются динамическими входами с длиной из имени и той же рамкой SavedHL
                ;   ReadDirection является самостоятельным входом без SavedHL, только читает Direction и выполняет RET
                ;   ReadDirection сохраняет HL, DE, BC и всю RAM, изменяет AF и R на три M1, SP увеличивается на два
                ; -----------------------------------------
                ; -----------------------------------------
                ; (2) Конец общего хвоста, 18 записей и общий возврат
                ; -----------------------------------------
                ; динамический вход на 18 байтов справа налево, заём младшего адреса не изменяет страницу
Entry:          DEC L
                LD (HL), A
                DEC L
                LD (HL), A
                ; динамический вход на 16 байтов справа налево, заём младшего адреса не изменяет страницу
Fill16:         DEC L
                LD (HL), A
                DEC L
                LD (HL), A
                ; динамический вход на 14 байтов справа налево, заём младшего адреса не изменяет страницу
Fill14:         DEC L
                LD (HL), A
                DEC L
                LD (HL), A
                ; динамический вход на 12 байтов справа налево, заём младшего адреса не изменяет страницу
Fill12:         DEC L
                LD (HL), A
                DEC L
                LD (HL), A
                ; динамический вход на 10 байтов справа налево, заём младшего адреса не изменяет страницу
Fill10:         DEC L
                LD (HL), A
                DEC L
                LD (HL), A
                ; динамический вход на 8 байтов справа налево, заём младшего адреса не изменяет страницу
Fill8:          DEC L
                LD (HL), A
                DEC L
                LD (HL), A
                ; динамический вход на 6 байтов справа налево, заём младшего адреса не изменяет страницу
Fill6:          DEC L
                LD (HL), A
                DEC L
                LD (HL), A
                ; динамический вход на 4 байтов справа налево, заём младшего адреса не изменяет страницу
Fill4:          DEC L
                LD (HL), A
                DEC L
                LD (HL), A
                ; динамический вход на 2 байтов справа налево, заём младшего адреса не изменяет страницу
Fill2:          DEC L
                LD (HL), A
                DEC L
                LD (HL), A
                ; восстановление указателя из SavedHL после последней записи
                POP HL
                ; чтение общего Direction для выбора дальнейшего пути вызывающей процедуры
ReadDirection:  LD A, (@ControlsEvenSpanState.Direction)
                ; проверка нулевого Direction, результат заполнения на Z не влияет
                AND A
                ; -----------------------------------------
                RET

                ; -----------------------------------------
                endmodule
                endmodule
