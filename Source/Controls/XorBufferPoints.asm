                module Controls
                module XorBufferPoints
                ; Документация [алгоритм и проверка](../../Docs/ControlsBufferPoints.md)
                ; Документация [границы собственных записей](../../Docs/ControlsTemporaryModule.md#косвенные-записи-и-процедуры-точек)
                ; -----------------------------------------
                ; Наложение 35 точек на линейный буфер через четыре таблицы адресации
                ; исходная запись 22, банк 1, смещения #0AE3..#0AFF
                ; In:
                ;   HL, DE, BC, AF входных аргументов не задают, 35 записей читаются в порядке Y,X
                ;   банк 1 выбран, четыре страницы таблиц 9400..97FF подготовлены ActionBoot.BuildBitmapTables
                ;   для проверенного договора Y=0..95, X=0..255, линейный буфер 8000..8BFF доступен для записи
                ;   на CPU-стеке внешний возврат, данные точек и таблицы не перекрываются с целями XOR
                ; Out:
                ;   HL=9700+X последней точки, DE её адрес назначения, BC=адрес после Point22, A=46, F=42
                ;   каждая запись накладывает один пиксель через XOR, выполнены ровно 35 записей, совпадения не удаляются
                ;   HL', DE', BC', AF', IX и IY сохраняются, I, IM и IFF сохраняются, SP=входной SP+2
                ; Corrupt:
                ;   HL, DE, BC, AF, 35 записей байтов буфера с возможными совпадениями адресов, R
                ; Note:
                ;   старший байт адреса берётся из 9400+Y, младший складывается по модулю 256 из 9500+Y и 9600+X
                ;   маска пикселя читается из 9700+X, проверок координат внутри потребителя нет
                ;   исходные 35 нулевых записей не пропускаются, при готовых таблицах они 35 раз меняют один пиксель 8000
                ; -----------------------------------------
                ; выбор начала таблицы из 35 пар Y,X
Entry:          LD BC, @ControlsBufferPoints.Point00
                ; получение старшего и младшего байтов адреса строки по координате Y
DrawPoint:      LD H, @BufferPointConst.LineHighPage
                LD A, (BC)
                LD L, A
                INC C
                LD A, (BC)
                INC C
                LD E, A
                LD D, (HL)
                INC H
                ; вычисление младшего байта назначения через таблицу X DIV 8 без переноса в D
                LD A, (HL)
                INC H
                LD L, E
                ADD A, (HL)
                LD E, A
                INC H
                ; наложение битовой маски точки на существующий байт буфера
                LD A, (DE)
                XOR (HL)
                LD (DE), A
                LD A, C
                ; проверка обработки всех 35 записей координат
                CP @BufferPointConst.ByteCount
                JP C, @Controls.XorBufferPoints.DrawPoint                       ; переход, если обработаны не все 70 байтов координат, наложить следующую точку

                RET

                endmodule
                endmodule
