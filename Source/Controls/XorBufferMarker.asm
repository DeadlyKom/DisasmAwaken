                module XorBufferMarker
                ; Документация [алгоритм и проверка](../../Docs/ControlsMarker.md)
                ; -----------------------------------------
                ; Наложение одиннадцати байтов маркера на линейный буфер через XOR
                ; исходная запись 23, банк 1, смещения #15B6..#160E
                ; In:
                ;   HL, DE, BC, AF входных аргументов не задают, Position читается словом из 9B19
                ;   банк 1 выбран, таблица MarkerPhaseMasks доступна, целевые байты буфера доступны для записи
                ;   на CPU-стеке внешний возврат, модель не включает вмешательство ISR
                ; Out:
                ;   HL указывает последний изменённый байт нижнего штриха, DE=Phase00+4*(Position AND 7), BC=0020
                ;   A содержит последний записанный байт, F соответствует последнему XOR
                ;   HL', DE', BC', AF', IX и IY, I, IM и IFF сохраняются, SP=входной SP+2
                ;   выполнены ровно 11 записей XOR, четыре верхние, три центральные и четыре нижние
                ; Corrupt:
                ;   HL, DE, BC, AF, одиннадцать байтов буфера, R
                ; Note:
                ;   база получается как 8000+(Position DIV 8), фаза маски определяется тремя младшими битами Position
                ;   горизонтальные INC L и DEC L не переносятся в H, пограничная адресация оригинала сохранена
                ;   при неизменных Position, масках и фоне повторное наложение восстанавливает исходный буфер
                ;   для произвольного 16-битового Position цель может перекрыть сам Position, второй вызов тогда использует уже изменённое значение
                ; -----------------------------------------
                ; чтение сохраняемого положения маркера из общей RAM
Entry:          LD BC, (@ControlsMarkerState.Position)
                ; вычисление линейного байтового смещения Position DIV 8 тремя сдвигами через Carry
                LD H, B
                LD A, C
                SRL H
                RRA
                SRL H
                RRA
                ; добавление старшего бита базы 8000 при третьем сдвиге
                SCF
                RR H
                RRA
                LD L, A
                EX DE, HL
                ; вычисление номера четырёхбайтового набора масок по Position AND 7
                LD A, C
                AND #07
                RLA
                RLA
                LD L, A
                LD H, #00
                ; выбор физического экземпляра масок без копирования таблицы
                LD BC, @MarkerPhaseMasks.Phase00
                ADD HL, BC
                EX DE, HL
                ; подготовка шага 32 байта между растровыми строками линейного буфера
                LD BC, #0020
                ; выбор байта верхнего штриха, INC L намеренно не переносит переполнение в H
                INC L
                ; наложение верхних четырёх растровых строк одной вертикальной маской
                LD A, (DE)
                XOR (HL)
                LD (HL), A
                ADD HL, BC
                LD A, (DE)
                XOR (HL)
                LD (HL), A
                ADD HL, BC
                LD A, (DE)
                XOR (HL)
                LD (HL), A
                ADD HL, BC
                LD A, (DE)
                XOR (HL)
                LD (HL), A
                ; пропуск одной растровой строки перед центральной тройкой масок
                ADD HL, BC
                ADD HL, BC
                ; выбор левого байта центрального ряда без переноса из L в H
                DEC L
                ; выбор маски CentralLeft и наложение левого байта центрального ряда
                INC DE
                LD A, (DE)
                XOR (HL)
                LD (HL), A
                ; выбор маски CentralMiddle для среднего байта того же ряда
                INC L
                INC DE
                LD A, (DE)
                XOR (HL)
                LD (HL), A
                ; выбор маски CentralRight для правого байта того же ряда
                INC L
                INC DE
                LD A, (DE)
                XOR (HL)
                LD (HL), A
                ; возврат к вертикальной маске и среднему байту перед нижним штрихом
                DEC DE
                DEC DE
                DEC DE
                DEC L
                ; пропуск одной растровой строки после центра перед нижними четырьмя строками
                ADD HL, BC
                ADD HL, BC
                LD A, (DE)
                XOR (HL)
                LD (HL), A
                ADD HL, BC
                LD A, (DE)
                XOR (HL)
                LD (HL), A
                ADD HL, BC
                LD A, (DE)
                XOR (HL)
                LD (HL), A
                ADD HL, BC
                LD A, (DE)
                XOR (HL)
                LD (HL), A
                RET

                endmodule
                endmodule
