                module Controls
                module DivideWordByByte
                ; Документация [алгоритм и проверка](../../Docs/ControlsDivision.md)
                ; -----------------------------------------
                ; Восьмишаговое деление слова A:E на B с частным в D и остатком в A
                ; исходная запись 22, банк 1, смещения #1167..#117C
                ; In:
                ;   HL сохраняется, DE задаёт E младший байт делимого, D не используется как аргумент
                ;   BC задаёт B делитель, C сохраняется, AF задаёт A старший байт делимого
                ;   входные флаги не влияют на арифметический результат, на CPU-стеке внешний возврат
                ; Out:
                ;   HL сохранён, D содержит восьмибитовое частное, E=0, BC сохранён, A содержит байтовый остаток
                ;   при B!=0 и входном A<B результат совпадает с divmod(входные A*256+E,B)
                ;   при B=0 результат D=FF и A=входной E, делитель не вызывает ловушку или бесконечный цикл
                ;   при B!=0 и входном A>=B выполняется исходная восьмишаговая рекурсия с ограничением остатка до байта, точное целочисленное деление не обещается
                ;   F описывает финальный D, S,Z и биты 5,3 берутся из D, PV равен чётности D, H,N,C сброшены
                ;   HL', DE', BC', AF', IX и IY, I, IM и IFF сохраняются, SP=входной SP+2
                ; Corrupt:
                ;   DE, AF, R
                ; Note:
                ;   RAM не записывается, портов и дополнительных PUSH нет, исходный D заменяется маркером FE
                ;   D=11111110 совмещает семь оставшихся единиц маркера и накапливаемые биты частного, восьмой сдвиг выводит начальный нуль в Carry
                ;   все выходы RET NC проверяют конец восьми шагов по маркеру, а не корректность делителя
                ;   доказательство условий B!=0 и входного A<B в вызывающих геометрических процедурах остаётся отдельной задачей
                ; -----------------------------------------
                ; установка маркера восьми шагов в тот же байт D, где собирается частное
Entry:          LD D, #FE
                ; вычисление расширенного остатка из удвоенного A и следующего старшего бита E
ShiftDividend:  SLA E
                RLA
                JR C, @Controls.DivideWordByByte.SubtractDivisor                ; переход, если расширенный остаток содержит девятый бит, он заведомо не меньше байтового делителя

                ; проверка расширенного остатка без девятого бита относительно делителя
                CP B
                JR NC, @Controls.DivideWordByByte.SubtractDivisor               ; переход, если остаток не меньше B, вычесть делитель и записать единичный бит частного

                ; добавление нулевого бита частного и сдвиг маркера оставшихся шагов
                SLA D
                RET NC                                                          ; выход, если начальный нулевой бит маркера вышел в Carry после восьмого шага

                JR @Controls.DivideWordByByte.ShiftDividend

                ; вычисление остатка после принятого вычитания B с исходным ограничением до байта
SubtractDivisor:SUB B
                ; подготовка единичного бита частного перед сдвигом маркера
                SCF
                RL D
                RET NC                                                          ; выход, если начальный нулевой бит маркера вышел в Carry после восьмого шага

                JR @Controls.DivideWordByByte.ShiftDividend

                endmodule
                endmodule
