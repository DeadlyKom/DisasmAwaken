                module Controls
                module LoadCircleMidpoint
                ; Документация [алгоритм и проверка](../../Docs/ControlsCircleSetup.md)
                ; -----------------------------------------
                ; Загрузка рабочих координат, радиуса и начального состояния среднего алгоритма
                ; исходная запись 22, банк 1, смещения #1504..#1514
                ; In:
                ;   HL сохраняется, DE, BC и AF входных аргументов не задают
                ;   банк 1 выбран, WorkY, WorkX и физические FBodyProjection.Flags и Radius доступны для чтения
                ;   на CPU-стеке внешний возврат, IRQ не вмешиваются
                ; Out:
                ;   HL сохраняется, D=Radius, E=Flags, B=WorkX, C=WorkY
                ;   A=(-Radius) AND FF, F соответствует NEG Radius
                ;   C'=(-Radius) AND FF, E'=0, B' и D' сохраняются, начальные B' и D' здесь не обнуляются
                ;   HL', DE', BC' сохраняются кроме C' и E', AF', IX, IY, I, IM и IFF сохраняются
                ;   SP=входной SP+2, R получает 12 M1
                ; Corrupt:
                ;   DE, BC, AF, E', C', R
                ; Note:
                ;   RAM не записывается, флаги Flags переносятся без трактовки отдельных разрядов
                ;   радиус и координаты не ограничиваются, геометрические ограничения принадлежат вызывающему коду
                ; -----------------------------------------
                ; загрузка рабочей пары Y и X без изменения HL
Entry:          LD BC, (@ControlsCircleSetupState.WorkY)
                ; загрузка Flags и Radius из физической записи проекции
                LD DE, (@ControlsBodyProjection.Value.Flags)
                ; вычисление начального отрицательного радиуса среднего алгоритма
                LD A, D
                NEG
                ; обновление только C' и E', остальные альтернативные регистры сохраняются
                EXX
                LD C, A
                LD E, #00
                EXX
                RET

                endmodule
                endmodule
