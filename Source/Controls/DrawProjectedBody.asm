                module Controls
                module DrawProjectedBody
                ; Документация [алгоритм и проверка](../../Docs/ControlsBodyDraw.md)
                ; -----------------------------------------
                ; Выбор малого профиля или большого круга по результату малого рисователя
                ; исходная запись 22, банк 1, смещения #121A..#1226
                ; In:
                ;   готовая FBodyProjection.Value, рисунок в операнде D240 и режим малого рисователя по CEF9
                ;   банк 1 выбран, на CPU-стеке внешний возврат и до шестнадцати временных байтов, IRQ не вмешиваются
                ; Out:
                ;   при результате малого рисователя A<9 регистры соответствуют DrawSmallBody, F заменён результатом CP 09
                ;   при A>=9 обнулён Mode по D18C и возвращено состояние CallLargeCircle
                ;   SP=входной SP+2, страница сохранена, портов нет
                ; Corrupt:
                ;   регистры и память выбранного рисователя, F сравнения, D18C на большом пути и временный CPU-стек
                ; Note:
                ;   выбор выполняется по возвращённому A, проверка радиуса непосредственно из записи не повторяется
                ;   хвостовой JP сохраняет внешний возврат перед настоящим CALL большого рисователя
                ; -----------------------------------------
                ; Вызов малого рисователя, его возвращённый A определяет необходимость большого профиля.
Entry:          CALL @Controls.DrawSmallBody.Entry
                ; Проверка возвращённого A относительно первого большого радиуса.
                CP @SmallBodyConst.RadiusLimit
                RET C                                                           ; выход, если A меньше 9, результат малого пути окончателен

                ; Сброс режима большого растра перед хвостовой передачей.
                XOR A
                LD (@ControlsCircleWork.Value.Mode), A
                JP @Controls.CallLargeCircle.Entry

                endmodule
                endmodule
