                module Controls
                module PrepareStationReload
                ; Документация [алгоритм и проверка](../../Docs/ControlsStationPrepare.md)
                ; -----------------------------------------
                ; Очистка атрибутов, сохранение 512 байтов состояния и перенос следующей стадии загрузки станции
                ; исходная запись 23, банк 1, смещения #0205..#0244
                ; In:
                ;   HL, DE, BC аргументов не задают, AF задаёт только сохраняемые в окончательном F биты S/Z/Carry
                ;   банк 1 выбран, общая область HighPairs..HighPairs+SaveBytes-1 и источник CodeSource доступны
                ;   атрибуты 5800..5AFF, области 4000..42FF и два байта под исходной системной вершиной 5FFF доступны для записи
                ;   IRQ не вмешиваются до явного DI, входной SP не читается и намеренно отбрасывается
                ; Out:
                ;   HL=DE23, DE=4300, BC=0, A=3F, IX и альтернативные регистры сохраняются
                ;   два байта LowPairs переставлены, затем 512 байтов от HighPairs сохранены в 4000..41FF
                ;   все 768 атрибутов 5800..5AFF обнулены исходным перекрывающимся LDIR
                ;   256 байтов DD23..DE22 перенесены в 4200..42FF, PC=4200 после исходного RET, перенесённая цель ещё не исполнялась
                ;   F сохраняет входные S/Z/Carry, остальные биты определяются последним LDIR, точная формула приведена в документации
                ;   IY=5C3A, SP=5FFF, I=3F, IM=1, IFF сброшен, 7FFD сохраняется и порт не записывается
                ;   R получает 3097 M1 с сохранением бита 7, по 5FFD/5FFE остаётся слово 4200
                ; Corrupt:
                ;   HL, DE, BC, AF, IY, SP, I, IM, IFF, R, два байта счётчика, атрибуты, 768 байтов общей RAM и два байта нового CPU-стека
                ; Note:
                ;   первый LDIR намеренно перекрывает источник и назначение, единственный записанный ноль распространяется на все атрибуты
                ;   старый адрес возврата не восстанавливается, эта процедура меняет режим через новый стек и RET к 4200
                ;   8960 сценариев проверили все F при шестнадцати A, все значения исходных байтов и все суммы для недокументированных флагов LDIR
                ;   сопоставлены регистры включая R, восемь банков RAM и кратность всех записей, копия 4200 не исполнялась
                ;   полное произведение блоков данных, реальные IRQ до DI, TR-DOS, загрузка STATIONF, сборка и нативный запуск не доказаны
                ; -----------------------------------------
                ; Выбор атрибутов базового экрана для полного обнуления перед сменой режима.
Entry:          LD HL, @ScreenUpdateConst.BaseAttributes
                LD DE, @ScreenUpdateConst.BaseAttributes + 1
                LD BC, @ScreenUpdateConst.AttributeBytes - 1
                ; Создание первого нулевого атрибута из младшего адресного байта L=0.
                LD (HL), L
                ; Обнуление остальных атрибутов перекрывающимся LDIR, каждый следующий байт читает уже записанный ноль.
                LDIR
                ; Замена входного CPU-стека исходной системной вершиной, прежняя рамка больше не используется.
                LD SP, @LoaderConst.StackTop
                ; Преобразование двух младших BCD-пар к порядку, ожидаемому сохраняемым состоянием станции.
                LD A, (@ControlsBcdCounterState.LowPairs)
                LD B, A
                LD A, (@ControlsBcdCounterState.LowPairs + 1)
                LD (@ControlsBcdCounterState.LowPairs), A
                LD A, B
                LD (@ControlsBcdCounterState.LowPairs + 1), A
                ; Создание общей копии 512 байтов состояния, перестановка счётчика уже отражена в источнике.
                LD HL, @ControlsBcdCounterState.HighPairs
                LD DE, @ScreenUpdateConst.BaseScreen
                LD BC, @ControlsStationPrepareConst.SaveBytes
                LDIR
                ; Подготовка следующей стадии загрузчика к переносу в общую RAM по исходному адресу 4200.
                LD HL, @ControlsStationPrepareConst.CodeSource
                LD DE, @ControlsStationPrepareConst.NextEntry
                ; Создание нового адреса управления 4200 на сброшенном CPU-стеке, это не возврат старому вызывающему.
                PUSH DE
                LD BC, @ControlsStationRelayConst.BlockSize
                ; Копирование фиксированных 256 байтов следующей стадии, код и соседние данные сохраняются буквально.
                LDIR
                ; Запрет IRQ перед окончательной установкой системного контекста Spectrum ROM.
                DI
                ; Установка I, IM 1 и системного IY без изменения флагов последнего LDIR.
                LD A, @SaveSlotConst.RomI
                LD I, A
                IM 1
                LD IY, @LoaderConst.SystemIY
                ; Передача в перенесённый загрузочный блок через заранее помещённый на новый стек адрес.
                RET

                endmodule
                endmodule
