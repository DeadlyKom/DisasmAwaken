                module Controls
                module PrintByteDecimal
                ; Документация [вывод текстового окна](../../Docs/ControlsTextDisplay.md)
                ; -----------------------------------------
                ; Десятичный вывод байта с минимальной шириной два знака
                ; исходная запись 23, банк 1, смещения #1215..#1249
                ; In:
                ;   HL, DE, BC входных аргументов не задают, AF задаёт A=0..255, входные флаги не используются
                ;   выбран банк 1 с исходными CONTROL0 и CONTROL, код и экран доступны для записи
                ;   после InitializeTextWindow операнды прокрутки соответствуют окну x=160..255, y=144..189
                ;   на CPU-стеке лежит внешний возврат, вмешательство ISR в модель не включено
                ;   при прокрутке SP временно указывает на экран, обработчик прерываний не должен использовать этот SP
                ;   CPU-стек допускает восемь временных байтов ниже входного SP, включая рамки цифры и прокрутки
                ; Out:
                ;   HL=#55F4+((c-1) DIV 2), c=конечная TextColumn в 1..24
                ;   DE=#C600+6*((16+u) DIV 2)+5, u=входное A MOD 10, это последняя строка шрифтовой пары единиц
                ;   C=#F0 при нечётном c либо #0F при чётном, B содержит сохранённую соседнюю тетраду последней строки
                ;   A содержит последний записанный пиксельный байт, F соответствует последнему OR, H/N/Carry сброшены
                ;   HL' сохраняется, DE' и BC' сохраняются без прокрутки либо содержат результат последней исполненной ScrollTextWindow
                ;   A'=c, F'=#10 OR (c AND #28) OR (#44 при чётном c, иначе 0), это состояние BIT 0,C последнего глифа
                ;   IX, IY, I, IM и IFF сохраняются, банковых переключений и портовых операций нет
                ;   выведено format(входной A, 02d), для 0..99 две цифры, для 100..255 три
                ;   TextColumn изменён настоящим рисователем, прокрутка возможна перед любой цифрой
                ;   внешний RET задаёт SP=входной SP+2, сама процедура DI не выполняет
                ; Corrupt:
                ;   HL, DE, BC, AF, DE', BC', AF', R, экран, TextColumn, SavedScrollSP при прокрутке и CPU-стек
                ; Note:
                ;   разделитель после числа здесь не добавляется, дополнительную колонку оставляет ConsumeTextQueue
                ;   остаток сохраняется в B через PUSH BC и POP AF между выводом цифр
                ; -----------------------------------------
                ; проверка необходимости третьего десятичного разряда
Entry:          CP #64
                JR C, @Controls.PrintByteDecimal.PrintLastTwo                   ; переход, если число меньше 100, вывести только десятки и единицы

                ; вычисление сотен последовательным вычитанием 100 с восстановлением остатка после заёма
                LD C, #00
                LD B, #64
                SUB B
CountHundreds:  INC C
                SUB B
                JR NC, @Controls.PrintByteDecimal.CountHundreds                 ; переход, если остаток ещё не стал отрицательным, увеличить число сотен

                ADD A, B
                LD B, A
                LD A, C
                ; преобразование количества сотен в код ASCII
                ADD A, #30
                ; сохранение остатка в B на CPU-стеке на время рисования цифры
                PUSH BC
                CALL @Controls.PrintTextGlyph.Entry
                POP AF
                ; вычисление десятков и сохранение исходного остатка для короткого пути
PrintLastTwo:   LD B, A
                CP #0A
                LD C, #00
                JR C, @Controls.PrintByteDecimal.EmitTens                       ; переход, если остаток меньше 10, вывести нулевой разряд десятков

                ; вычисление десятков последовательным вычитанием 10
                LD B, #0A
                SUB B
CountTens:      INC C
                SUB B
                JP NC, @Controls.PrintByteDecimal.CountTens                     ; переход, если остаток ещё не стал отрицательным, увеличить число десятков

                ADD A, B
                LD B, A
                ; вывод десятков, включая ведущий нуль, и сохранение единиц в старшем байте стека
EmitTens:       LD A, C
                ADD A, #30
                PUSH BC
                CALL @Controls.PrintTextGlyph.Entry
                ; получение единиц через POP AF, входные флаги здесь не восстанавливаются
                POP AF
                ADD A, #30
                JP @Controls.PrintTextGlyph.Entry

                endmodule
                endmodule
