                module Controls
                module SqrtSquareDiff
                ; Документация [алгоритм и проверка](../../Docs/ControlsSquares.md)
                ; -----------------------------------------
                ; Целый корень разности квадратов с исходным входным Carry и оборачиванием слова
                ; исходная запись 22, банк 1, смещения #1609..#1632
                ; In:
                ;   HL сохраняется, DE задаёт D как первый множитель, E и BC сохраняются
                ;   AF задаёт A как второй множитель и входной Carry, оба множителя 0..255
                ;   банк 1 выбран, исходная таблица квадратов сохранена, код, рабочее слово и стек доступны
                ;   на CPU-стеке внешний возврат, ещё 12 байтов нужны с учётом настоящего ReadByteSquare, IRQ не вмешиваются
                ; Out:
                ;   HL, DE и BC сохраняются, A=floor(sqrt((входной D*D-входной A*A-входной Carry) AND FFFF))
                ;   F=45 от последнего SRL B, Carry установлен, Z установлен, эти значения не проверяют нулевой корень
                ;   SquareDiff содержит исходную обёрнутую разность, в частности D=0, A=0, Carry=1 возвращает FF
                ;   HL', DE', BC', AF', IX и IY, I, IM и IFF сохраняются, SP=входной SP+2
                ;   R получает 179-popcount(результата) M1, popcount обозначает число единичных разрядов байта
                ; Corrupt:
                ;   AF, SquareDiff, 12 байтов CPU-стека, R
                ; Note:
                ;   восемь проверок по разрядам 7..0 строят максимальное q с q*q не больше SquareDiff
                ;   при отрицательной исходной разности берётся её слово по модулю 65536, это не отказ и не геометрически допустимое пересечение
                ;   соседний вход CircleRasterCore относится к рисованию и не исполняется после исходного RET этой процедуры
                ; -----------------------------------------
                ; сохранение BC, DE, HL и исходного AF перед двумя настоящими вызовами таблицы
Entry:          PUSH BC
                PUSH DE
                PUSH HL
                PUSH AF
                ; получение квадрата первого множителя из входного D
                LD A, D
                CALL @Controls.ReadByteSquare.Entry
                ; сохранение первого квадрата в HL и восстановление второго множителя вместе с исходным Carry
                LD H, D
                LD L, E
                POP AF
                ; получение квадрата исходного A, читатель таблицы сохраняет Carry
                CALL @Controls.ReadByteSquare.Entry
                ; вычисление SquareDiff как D*D-A*A-Carry по модулю 65536
                SBC HL, DE
                ; подготовка старшего проверяемого разряда и нулевого приближения корня
                LD B, #80
                XOR A
                ; сохранение неизменного порога для всех восьми сравнений квадратов
                LD (@ControlsSquaresState.SquareDiff), HL
                ; -----------------------------------------
                ; Восьмишаговый поиск максимального целого корня
                ; -----------------------------------------
                ; чтение полного порога перед проверкой следующего разряда
TryRootBit:     LD HL, (@ControlsSquaresState.SquareDiff)
                ; вычисление кандидата добавлением текущей степени двойки к принятой части корня
                ADD A, B
                ; получение квадрата кандидата через настоящую таблицу
                CALL @Controls.ReadByteSquare.Entry
                ; проверка, не превышает ли квадрат кандидата исходную SquareDiff
                SBC HL, DE
                JR NC, @Controls.SqrtSquareDiff.NextRootBit                     ; переход, если квадрат кандидата не больше SquareDiff, принять разряд в NextRootBit

                ; восстановление прежнего приближения после слишком большого квадрата
                SUB B
                ; выбор следующего младшего разряда, Carry после последнего бита завершает поиск
NextRootBit:    SRL B
                JR NC, @Controls.SqrtSquareDiff.TryRootBit                      ; переход, если последний разряд ещё не обработан, продолжить с TryRootBit

                ; восстановление исходных HL, DE и BC без изменения результата A и F от последнего SRL
                POP HL
                POP DE
                POP BC
                ; -----------------------------------------
                RET

                ; -----------------------------------------
                endmodule
                endmodule
