                module Controls
                module FillInteriorRowsDown
                ; Документация [алгоритм и проверка](../../Docs/ControlsInteriorRows.md)
                ; -----------------------------------------
                ; Заливка внутренних 30 байтов строк вниз с ограничением нижним краем
                ; исходная запись 22, банк 1, смещения #1211..#1219
                ; In:
                ;   HL и DE входного положения не задают, DE сохраняется
                ;   BC задаёт B=0..255 как число строк, исходный C заменяется строкой A
                ;   AF задаёт A=0..95 как первую строку, входные флаги заменяются AND Mode
                ;   IX задаёт IXL как рисунок заполнения и IXH как XOR двух чередующихся рисунков
                ;   банк 1 выбран, код, буфер 8000..8BFF и CPU-стек доступны для записи и не перекрываются
                ;   на CPU-стеке внешний возврат, ещё шесть байтов нужны для SavedDE, SavedAF, SavedBC, IRQ не вмешиваются
                ; Out:
                ;   число заполненных строк n=min(B, 96-A), в каждой меняются только столбцы 1..30
                ;   HL=8000+32*входной A+31+32*n, DE сохраняется, BC=входной B:входной A
                ;   AF содержит входную строку A и F от AND Mode, Z относится к Mode, а не к байту возвращаемого A
                ;   HL', DE', BC', AF' сохраняются, IXH сохраняется, IXL меняется на входной IXL XOR IXH только при нечётном n
                ;   IY, I, IM и IFF сохраняются, SP=входной SP+2
                ;   при B=0 R получает 28 M1, иначе 29+75*n минус один при остановке по краю
                ; Corrupt:
                ;   HL, BC, AF, IXL, RowStep, BoundaryLimit, BoundaryBranch, шесть байтов CPU-стека, внутренние столбцы строк, R
                ; Note:
                ;   при B=0 буфер и IXL не меняются, операнды и сохранённая рамка всё равно записываются
                ;   после последней строки IXL переключается даже при немедленном выходе по границе
                ;   верхняя граница задаётся CP 80 и JR C, нижняя CP 8C и JR NC, это изменение кода, не только числа
                ;   полоса использует линейный растр по 32 байта, преобразование в нелинейный экран выполняется отдельно
                ;   рамка внутренних FillRowsUp/FillRowsDown описана FInteriorRowsFrame, от текущего SP после трёх PUSH идут SavedBC, SavedAF, SavedDE и CallerReturn
                ; -----------------------------------------
                ; сохранение номера первой строки в C перед чтением Mode
Entry:          LD C, A
                LD A, (@ControlsInteriorRowsState.Mode)
                ; проверка нулевого Mode, последующий LD A,C сохраняет эти F
                AND A
                LD A, C
                JP @Controls.PrepareInteriorSpan.FillRowsDown

                endmodule
                endmodule
