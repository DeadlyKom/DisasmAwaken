                ; -----------------------------------------
                ; Вызов большого рисователя с исходной дополнительной рамкой
                ; исходная запись 22, банк 1, смещения #1232..#1235
                ; In:
                ;   готовая проекция с Radius>=9, рисунок в D240 и действующий Mode по D18C
                ;   банк 1 выбран, на CPU-стеке внешний возврат и до шестнадцати временных байтов, IRQ не вмешиваются
                ; Out:
                ;   состояние DrawLargeCircle, SP=входной SP+2, Mode отдельно не сбрасывается
                ;   IY, I, IM, IFF и страница сохраняются, портовых записей нет
                ;   перед входом ребёнка CALL увеличивает младшие семь битов R на один, после его возврата RET добавляет ещё один, bit7 этими командами сохранён
                ; Corrupt:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX, R, рабочая запись круга, растр, изменяемые операнды и до шестнадцати временных байтов CPU-стека
                ; Note:
                ;   CALL записывает D235, затем RET использует исходный возврат
                ;   к приращению R большого рисователя добавляются два M1 этой обёртки
                ; -----------------------------------------
                ; Вызов большого рисователя с отдельным адресом возврата D235.
Entry:          CALL @Controls.DrawLargeCircle.Entry
                RET

