                module Controls
                module FillSpan31
                ; Документация [условное заполнение 31 байта](../../Docs/ControlsEvenSpanPrefix.md)
                ; -----------------------------------------
                ; Обратное заполнение 31 байта при прямом входе
                ; исходная запись 22, CONTROL0 в банке 1, адреса CEB5..CEB6
                ; In:
                ;   HL задаёт страницу и правую исключённую границу, A содержит байт заполнения
                ;   на CPU-стеке SavedHL и внешний возврат, доступна область записи в той же странице
                ;   выбран банк 1, назначение и стек не перекрывают команды и байт режима
                ; Out:
                ;   HL восстановлен из SavedHL, DE и BC сохраняются, AF содержит Direction и флаги AND A
                ;   31 байт записан справа налево, заём из младшего адреса не меняет страницу
                ;   SP увеличен на четыре, альтернативные и индексные регистры, I, IM и IFF сохраняются
                ; Corrupt:
                ;   HL, AF, R и 31 байт назначения
                ; Note:
                ;   общий хвост продолжает заполнение без CALL, R получает 66 M1
                ;   1280 прямых профилей сверили весь результат, флаги, регистры и кратность записей
                ;   смещение штатного JR всегда равно двум по модулю четырёх, этот переход не выбирает CEB5 или CEB6
                ;   штатный вызывающий путь к условному входу не установлен
                ; -----------------------------------------
                ; Выбор первого байта слева от правой исключённой границы внутри страницы.
Entry:          DEC L
                ; Заполнение первого байта перед общим хвостом ещё на тридцать.
                LD (HL), A
                ; JP @Controls.FillEvenSpanHead.Entry, продолжение в FillEvenSpanHead.asm
                endmodule
                endmodule
