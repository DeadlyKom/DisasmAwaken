                module StepWordRandom
                ; Документация [алгоритм и проверка](../../Docs/ControlsWordRandom.md)
                ; -----------------------------------------
                ; Обновление двухсловного состояния генератора и возврат XOR его четырёх байтов
                ; исходная запись 23, банк 1, смещения #027F..#02A8
                ; In:
                ;   HL и DE входных аргументов не задают, BC сохраняется, AF входных аргументов не задаёт
                ;   банк 1 выбран, слова First и Second по 9B15 и 9B17 доступны для чтения и записи
                ;   на стеке внешний возврат, ещё два байта нужны для сохранения BC, IRQ не вмешиваются
                ; Out:
                ;   HL=входной Second, DE=новый Second, BC сохраняется
                ;   First получает входной Second, новый Second вычисляется исходной двухсловной рекурсией, точная формула дана в документации
                ;   A равен XOR четырёх байтов нового состояния, F имеет S,Z и биты 5,3 от A, PV задаёт чётность A, H,N,C сброшены
                ;   HL', DE', BC', AF', IX и IY, I, IM и IFF сохраняются, SP=входной SP+2, R получает 32 M1
                ; Corrupt:
                ;   HL, DE, AF, четыре байта состояния, два байта CPU-стека, R
                ; Note:
                ;   состояние не зависит от R и входного AF, выход детерминирован обоими исходными словами
                ;   перенос первого ADD HL, DE включается в последующий байтовый ADC, перенос второго сложения дальше не используется
                ;   два временных байта стека содержат исходные C и B, код и порты не изменяются
                ;   период, равномерность и криптографические свойства не установлены, полный перебор 2^32 состояний не выполнялся
                ; -----------------------------------------
                ; сохранение BC вызывающего кода перед использованием его байтов для смешивания состояния
Entry:          PUSH BC
                ; загрузка двух исходных слов генератора, значения не берутся из регистра R
                LD HL, (@ActionWordRandomState.Value.First)
                LD DE, (@ActionWordRandomState.Value.Second)
                ; сохранение байтов First в BC перед смешиванием, C ниже заменяется
                LD C, H
                LD B, L
                ; вычисление First+0101 по модулю слова двумя исходными инкрементами
                INC HL
                INC H
                ; вычисление суммы со Second, перенос слова используется следующим ADC
                ADD HL, DE
                ; вычисление младшего смешивающего байта из Second и суммы с переносом
                LD A, E
                ADC A, L
                LD C, A
                ; вычисление второй суммы с младшим First в старшем байте BC
                ADD HL, BC
                ; смешивание младшего результата с младшим байтом BC и постоянной 75
                LD A, L
                XOR C
                XOR #75
                ; перенос младшего байта прежнего Second в будущий First
                LD L, E
                LD E, A
                ; смешивание старшего результата с младшим First и постоянной A7
                LD A, H
                XOR B
                XOR #A7
                ; перенос старшего байта прежнего Second в будущий First
                LD H, D
                LD D, A
                ; обновление физического двухсловного состояния в исходном порядке
                LD (@ActionWordRandomState.Value.First), HL
                LD (@ActionWordRandomState.Value.Second), DE
                ; вычисление выходного байта как XOR четырёх байтов уже обновлённого состояния
                LD A, D
                XOR E
                XOR H
                XOR L
                ; восстановление BC без изменения флагов последнего XOR
                POP BC
                RET

                endmodule
                endmodule
