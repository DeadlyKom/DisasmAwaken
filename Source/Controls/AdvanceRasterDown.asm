                module AdvanceRasterDown
                ; Документация [алгоритм и проверка](../../Docs/ControlsRasterStep.md)
                ; -----------------------------------------
                ; Шаг на строку вниз с чередованием рисунка и нелокальным выходом за нижним краем
                ; исходная запись 22, банк 1, смещения #1940..#195A
                ; In:
                ;   HL задаёт адрес правого края строки, DE задаёт второй младший адрес E, D сохраняется
                ;   BC сохраняется, входной AF не используется, IX задаёт IXL как текущий рисунок и IXH как XOR-чередование
                ;   банк 1 выбран, на CPU-стеке непосредственный возврат помощника
                ;   SavedSP указывает SavedAF и следующий внешний возврат рисователя, при достижении края эта рамка должна быть действительна
                ;   IRQ не вмешиваются, новая память и записи RAM не требуются
                ; Out:
                ;   HL изменён на +32 по модулю слова, E изменён на тот же шаг по модулю байта, D и BC сохраняются
                ;   IXL=входной IXL XOR IXH, IXH сохраняется, переключение выполняется до любой проверки края
                ;   без переноса младшего L A содержит новый L, F соответствует ADD A,20
                ;   при переносе и продолжении A=8C, F соответствует CP между 8C и новым H
                ;   при новом H=8C после переноса A и F восстанавливаются из SavedAF, происходит внешний возврат рисователя
                ;   HL', DE', BC', AF', IY, I, IM и IFF сохраняются
                ;   обычный SP=входной SP+2, при нелокальном выходе SP=SavedSP+4
                ;   R получает 13 M1 без переноса L, 17 при переносе с продолжением, 22 при внешнем возврате
                ; Corrupt:
                ;   HL, E, AF, IXL, SP при внешнем возврате, R
                ; Note:
                ;   обычный Carry от изменения E не влияет на H, перенос страницы определяется только изменением L
                ;   край проверяется на точное равенство новому H=8C, произвольные страницы вне буфера не ограничиваются сравнением диапазона
                ;   на внешнем выходе непосредственный адрес возврата снимается POP AF, затем SP заменяется SavedSP
                ;   ни одна ветвь не записывает RAM, восстановление SP и POP читают существующую рамку
                ; -----------------------------------------
                ; вычисление рисунка следующей строки как IXL XOR IXH перед перемещением указателей
Entry:          LD A, IXL
                XOR IXH
                LD IXL, A
                ; вычисление младшего адреса E соседней строки без переноса в D
                LD A, E
                ADD A, #20
                LD E, A
                ; вычисление адреса HL соседней строки, перенос страницы определяется только младшим L
                LD A, L
                ADD A, #20
                LD L, A
                RET NC                                                          ; выход, если изменение L не пересекло границу страницы, H сохраняется

                ; изменение старшего адреса страницы после переноса L
                INC H
                LD A, #8C
                ; проверка точного достижения страницы 8C вне растра
                CP H
                RET NZ                                                          ; выход, если новая страница H не равна 8C, продолжить вызывающий рисователь

                ; снятие непосредственного возврата помощника перед нелокальным завершением рисования
                POP AF
                ; восстановление сохранённого SP рисователя для чтения исходного SavedAF и внешнего возврата
                LD SP, (@ControlsRasterStepState.SavedSP)
                ; восстановление AF вызвавшей рисование процедуры, промежуточные F больше не используются
                POP AF
                RET

                endmodule
                endmodule
