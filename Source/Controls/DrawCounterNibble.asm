                module Controls
                module DrawCounterNibble
                ; Документация [алгоритм и проверка](../../Docs/ControlsBcdCounter.md)
                ; -----------------------------------------
                ; Рисование младшей тетрады через общую пару знаков с сохранением основных регистров
                ; исходная запись 23, банк 1, смещения #16AA..#16CC
                ; In:
                ;   HL и DE сохраняются, BC задаёт C колонку 0..255 и сохраняется целиком
                ;   AF задаёт младшую тетраду A, старшие четыре бита не используются
                ;   банк 1 выбран, таблица знаков C600 и экран доступны, на CPU-стеке внешний возврат
                ; Out:
                ;   HL, DE, BC сохранены, выбранная тетрада нарисована в шести строках с H=51..56 и L=floor(C/2)
                ;   код пары равен 10+(входной A AND 0F), значения 0..9 дают цифры, 0A..0F пунктуацию
                ;   основные пары сохраняются через EXX, альтернативные пары становятся рабочими и не восстанавливаются
                ;   IX и IY, I, IM и IFF сохраняются, SP=входной SP+2, дополнительные два байта CPU-стека занимает CALL рисователя
                ; Corrupt:
                ;   AF, HL', DE', BC', AF', шесть экранных байтов, два байта CPU-стека, R
                ; Note:
                ;   проверки колонки и прокрутки нет, C=FF оборачивает увеличенный C в нуль и сохраняет правильную чётность маски
                ;   подпрограмма пригодна для тетрады произвольного байта, её имя не обещает шестнадцатеричные буквы A..F
                ; -----------------------------------------
                ; сохранение основных HL, DE и BC обменом с альтернативным набором
Entry:          EXX
                ; выбор младшей тетрады и смещение к парным знакам цифр в общей таблице
                AND #0F
                ADD A, #10
                LD L, A
                RES 0, L
                LD H, #00
                LD D, H
                LD E, L
                ADD HL, HL
                ADD HL, DE
                LD DE, @ControlsTextFont.Pixels
                ADD HL, DE
                EX DE, HL
                ; сохранение чётности индекса знака в альтернативном A для DrawGlyphRows
                EX AF, AF'
                ; выбор верхней растровой строки числового поля, y=129
                LD H, #51
                EXX
                LD A, C
                EXX
                LD C, A
                ; вычисление байта экрана по исходной колонке без изменения основных BC
                SRL A
                LD L, A
                INC C
                ; вызов общего рисователя на альтернативных HL, DE и BC
                CALL @Controls.DrawGlyphRows.Entry
                EXX
                RET

                endmodule
                endmodule
