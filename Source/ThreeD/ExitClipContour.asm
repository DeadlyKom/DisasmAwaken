                module ExitClipContour
                ; Документация [алгоритм и проверка](../../Docs/ThreeDOverlayMirror.md)
                ; -----------------------------------------
                ; Специальное завершение контура со снятием трёх служебных слов
                ; исходная запись 19, банк 0, смещения #06EA..#06F3
                ; In:
                ;   SP указывает на три служебных слова и внешний возврат, формат зависит от одиночного ребра либо полигона
                ;   при проверенной рамке одиночного ребра три слова равны C993, IRQ не вмешиваются
                ; Out:
                ;   HL получает третье снятое слово плюс (старший байт второго снятого слова-1) modulo 65536
                ;   DE сохраняется, B=0, C=(старший байт второго снятого слова-1) AND FF
                ;   A получает старший байт первого слова, F содержит S/Z/PV от DEC C, X/Y от A, Carry=1, H/N=0
                ;   для трёх слов C993 выход HL=CA5B, BC=00C8, AF=C989
                ;   альтернативный набор, IX, IY, I, IM, IFF и paging сохраняются, SP увеличен на восемь, RAM не записывается, R меняется
                ; Corrupt:
                ;   HL, BC, AF, SP и R
                ; Note:
                ;   дисковая копия слота 19 побайтово совпадает с ACTION по исходным смещениям 6000..801F
                ;   перенос доказательств требует тех же внешней RAM, банка 0, состояния входа и договоров общих процедур вне файла
                ;   нативная загрузка отдельного 3DPART не выполнялась, CF08 сохраняет отдельную неоднозначность исполнения
                ;   это не обычный RET, POP AF, POP BC и POP HL снимают служебные слова рамки
                ;   176640 сценариев группы проверяют обычные и специальные рамки C993, полигональный контекст описывается отдельно
                ; -----------------------------------------
                ; -----------------------------------------
                ; Установленный табличный вход
                ; Условия, действия всех путей и границы договора описаны в ActionClipCases.md.
Entry:          POP AF
                POP BC
                POP HL
                LD C, B
                DEC C
                LD B, #00
                ADD HL, BC
                SCF
                RET

                endmodule
                endmodule
