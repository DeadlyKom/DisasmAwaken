                module ThreeD
                module CombineListedVertexCodes
                ; Документация [алгоритм и проверка](../../Docs/ThreeDOverlayMirror.md)
                ; -----------------------------------------
                ; Объединение кодов границ перечисленных точек с ранним выходом по нулевому коду
                ; исходная запись 19, банк 0, смещения #1DD1..#1DEF
                ; In:
                ;   HL указывает на заголовок перед списком, следующие байты задают смещения начала точек внутри страницы 8E
                ;   B задаёт число индексов, B=0 означает 256, слова DE и AF аргументов не задают
                ;   код каждой точки читается по 8E00 плюс ((индекс+FRenderProjectedPoint.ClipCode) AND FF)
                ;   CPU-стек содержит внешний возврат, дополнительно нужны два байта сохранённого HL, IRQ не вмешиваются
                ; Out:
                ;   HL и B сохраняются, DE указывает за последним прочитанным индексом, C содержит OR ненулевых кодов до завершения
                ;   если все коды ненулевые, A=C, F равен флагам логического OR, Carry сброшен, Z сброшен
                ;   если найден нулевой код, A=0, F=45, Carry и Z установлены, нулевой код не включается в C
                ;   HL', DE', BC', AF', IXH и IY сохраняются, IXL получает исходный B, SP после RET равен входному SP+2
                ;   I, IM, IFF и paging сохраняются, R обновляется с сохранением старшего бита, портов нет
                ; Corrupt:
                ;   DE, C, AF, IXL, R и два байта CPU-стека
                ; Note:
                ;   дисковая копия слота 19 побайтово совпадает с ACTION по исходным смещениям 6000..801F
                ;   перенос доказательств требует тех же внешней RAM, банка 0, состояния входа и договоров общих процедур вне файла
                ;   нативная загрузка отдельного 3DPART не выполнялась, CF08 сохраняет отдельную неоднозначность исполнения
                ;   сумма индекса и смещения кода оборачивается внутри страницы, индекс не проверяется на кратность пяти
                ;   нулевой ClipCode не является обычным выходом ClassifyProjectedVertices, этот потребитель всё равно имеет отдельный доказанный путь для нуля
                ;   для k ненулевых элементов полный проход увеличивает R на 11+10*k, при нуле после k ненулевых элементов на 19+10*k
                ;   код завершения не очищает C, поэтому при раннем выходе доступны OR предыдущих точек и указатель после нулевого индекса
                ;   99712 сценариев проверяют все счётчики, каждую позицию нуля, все пары индекс/код, регистры, флаги, R, всю RAM и кратность записей
                ;   полный вывод многоугольника, IRQ, сборка и нативный запуск этой проверкой не подтверждаются
                ; -----------------------------------------
                ; -----------------------------------------
                ; Подготовка списка точек
                ; Сохранение исходного числа индексов в IXL и исходного HL на CPU-стеке.
Entry:          LD IXL, B
                PUSH HL
                ; Создание указателя DE на первый индекс после заголовка и очистка накопителя C.
                EX DE, HL
                INC DE
                LD H, @ActionVertexGroupConst.WorkHigh
                LD C, #00
                ; -----------------------------------------
                ; Объединение кодов
                ; Чтение очередного индекса, расчёт смещения ClipCode с исходным восьмибитовым оборачиванием.
NextIndex:      LD A, (DE)
                INC DE
                ADD A, FRenderProjectedPoint.ClipCode
                LD L, A
                ; Проверка полного кода точки, нуль имеет отдельный результат Carry и не добавляется в накопитель.
                LD A, (HL)
                AND A
                JR Z, @ThreeD.CombineListedVertexCodes.ZeroCode                 ; переход, если прочитанный ClipCode равен нулю, вернуть Carry с прежним накоплением C

                ; Обновление OR-накопителя, каждый ненулевой код оставляет Z сброшенным и Carry сброшенным.
                OR C
                LD C, A
                DJNZ @ThreeD.CombineListedVertexCodes.NextIndex

                ; Восстановление исходного HL и числа индексов без изменения флагов последнего OR.
                POP HL
                LD B, IXL
                RET

                ; -----------------------------------------
                ; Ранний нулевой код
                ; Установка Carry поверх результата AND нуля, накопитель C и предыдущие коды сохраняются.
ZeroCode:       SCF
                POP HL
                LD B, IXL
                RET

                ; -----------------------------------------
                endmodule
                endmodule
