                module ThreeD
                module CompareBottomLeftProducts
                ; Документация [алгоритм и проверка](../../Docs/ThreeDOverlayMirror.md)
                ; -----------------------------------------
                ; Вычитание LeftProduct из BottomProduct с передачей заёма младшего слова
                ; исходная запись 19, банк 0, смещения #0695..#06A8
                ; In:
                ;   физические BottomProduct и LeftProduct содержат два 32-битных произведения, значения не изменяются
                ;   3DPART доступен в банке 0, на CPU-стеке внешний возврат, IRQ не вмешиваются
                ; Out:
                ;   HL содержит старшее слово разности первого произведения и второго с заёмом от младших слов
                ;   DE сохраняется, BC содержит старшее слово второго произведения
                ;   A сохраняется, F равен точным флагам последнего SBC HL,BC
                ;   HL', DE', BC', AF', IX и IY сохраняются, I, IM, IFF и paging сохраняются
                ;   SP после RET равен входному SP+2, RAM и порты не записываются, R увеличивается на 12 по модулю младших семи бит
                ; Corrupt:
                ;   HL, BC, F и R
                ; Note:
                ;   дисковая копия слота 19 побайтово совпадает с ACTION по исходным смещениям 6000..801F
                ;   перенос доказательств требует тех же внешней RAM, банка 0, состояния входа и договоров общих процедур вне файла
                ;   нативная загрузка отдельного 3DPART не выполнялась, CF08 сохраняет отдельную неоднозначность исполнения
                ;   Z относится только к старшему вычитанию и не доказывает равенства полных произведений, младшая разность не возвращается
                ;   Overflow не исправляется, Sign не является универсальным математическим сравнением при переполнении
                ;   803012 сценариев общей серии проверяют регистры, флаги, R, SP и отсутствие записей RAM, все совместные входы не исчерпаны
                ;   IRQ, сборка и нативный запуск не проверены
                ; -----------------------------------------
                ; -----------------------------------------
                ; Чтение исходных значений
                ; Подготовка младших слов произведений к вычитанию.
Entry:          LD HL, (@ThreeDClipProductsData.BottomProduct.LowWord)
                LD BC, (@ThreeDClipProductsData.LeftProduct.LowWord)
                ; Расчёт разности с предварительно очищенным Carry.
                OR A
                SBC HL, BC
                ; Расчёт старшей разности с заёмом младшего вычитания, загрузки слов не меняют Carry.
                LD HL, (@ThreeDClipProductsData.BottomProduct.HighWord)
                LD BC, (@ThreeDClipProductsData.LeftProduct.HighWord)
                SBC HL, BC
                RET

                endmodule
                endmodule
