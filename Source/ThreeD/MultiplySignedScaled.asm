                module ThreeD
                module MultiplySignedScaled
                ; Документация [алгоритм и проверка](../../Docs/ThreeDOverlayMirror.md)
                ; -----------------------------------------
                ; Знаковое произведение DE и байтового коэффициента с усечением к нулю после деления на 128 и выходом через IX
                ; исходная запись 19, банк 0, смещения #112C..#1193
                ; In:
                ;   HL аргумента не задаёт, DE знаковый 16-битный множитель, B сохраняется, C аргумента не задаёт
                ;   A знаковый коэффициент -127..127, входные флаги не влияют на результат, нештатный 80 разобран отдельно
                ;   IX адрес продолжения, IY сохраняется, 3DPART исполняется в банке 0, IRQ не вмешиваются
                ; Out:
                ;   HL знаковое произведение с делением на 128 и усечением к нулю, для коэффициента 80 модуль результата равен нулю
                ;   DE модуль исходного множителя при неотрицательном знаке произведения, модуль усечённого результата при отрицательном знаке
                ;   B сохраняется, C=0, A=входной коэффициент XOR старший байт исходного DE
                ;   при неотрицательном знаке F от XOR знаковых байтов, при отрицательном F от SBC 0, модуль усечённого результата
                ;   HL', DE' и BC' сохраняются, A' равен (abs(DE)*семибитный модуль коэффициента)/32768, F' описан в документации
                ;   IX, IY, I, IM и IFF сохраняются, SP не меняется, PC получает IX без снятия внешнего возврата
                ;   RAM, CPU-стек и порты не записываются, R определяется старшим значащим битом, числом единиц и знаками
                ; Corrupt:
                ;   HL, DE, C, AF, AF', R
                ; Note:
                ;   дисковая копия слота 19 побайтово совпадает с ACTION по исходным смещениям 6000..801F
                ;   перенос доказательств требует тех же внешней RAM, банка 0, состояния входа и договоров общих процедур вне файла
                ;   нативная загрузка отдельного 3DPART не выполнялась, CF08 сохраняет отдельную неоднозначность исполнения
                ;   это переходная процедура, вызывающий код задаёт IX и не должен ожидать обычного RET
                ;   усекается модуль до применения знака, floor для отрицательного произведения неверен
                ;   исходный модуль коэффициента 80 теряет старший разряд, остаётся нулевой модуль, защита здесь не добавляется
                ;   Z и Carry возвращаемого AF не являются универсальными признаками нулевого результата и переполнения
                ; -----------------------------------------
                ; Расчёт знака произведения по исходным старшим байтам, коэффициент временно сохраняется в L.
Entry:          LD L, A
                XOR D
                ; Сохранение знакового байта и точных флагов XOR в альтернативном AF.
                EX AF, AF'
                ; Проверка знака исходного DE перед вычислением беззнакового модуля.
                BIT 7, D
                JR Z, @ThreeD.MultiplySignedScaled.AbsoluteCoeff                ; переход, если исходный DE неотрицателен, оставить его модуль без изменения

                ; Расчёт модуля отрицательного DE, входной 8000 остаётся беззнаковым модулем 8000.
                LD A, E
                CPL
                LD E, A
                LD A, D
                CPL
                LD D, A
                INC DE
                ; Проверка знака сохранённого коэффициента.
AbsoluteCoeff:  LD A, L
                AND A
                JP P, @ThreeD.MultiplySignedScaled.StartProduct                 ; переход, если коэффициент неотрицателен, перейти к накоплению

                ; Расчёт модуля коэффициента, исходный 80 остаётся 80 до отбрасывания старшего бита.
                NEG
                ; -----------------------------------------
                ; Расчёт семибитного произведения
                ; Нулевой C принимает только переносы, накопитель модуля создаётся в A и HL.
StartProduct:   LD C, #00
                LD H, C
                LD L, C
                ; Отбрасывание старшего бита модуля коэффициента, исходный 80 дальше обрабатывается как нулевой модуль.
                ADD A, A
                ADD A, A
                JR C, @ThreeD.MultiplySignedScaled.AddBit6                      ; переход, если бит 6 семибитного модуля коэффициента равен 1, начать накопление

                ADD A, A
                JR C, @ThreeD.MultiplySignedScaled.AddBit5                      ; переход, если бит 5 семибитного модуля коэффициента равен 1, начать накопление

                ADD A, A
                JR C, @ThreeD.MultiplySignedScaled.AddBit4                      ; переход, если бит 4 семибитного модуля коэффициента равен 1, начать накопление

                ADD A, A
                JR C, @ThreeD.MultiplySignedScaled.AddBit3                      ; переход, если бит 3 семибитного модуля коэффициента равен 1, начать накопление

                ADD A, A
                JR C, @ThreeD.MultiplySignedScaled.AddBit2                      ; переход, если бит 2 семибитного модуля коэффициента равен 1, начать накопление

                ADD A, A
                JR C, @ThreeD.MultiplySignedScaled.AddBit1                      ; переход, если бит 1 семибитного модуля коэффициента равен 1, начать накопление

                ADD A, A
                JR C, @ThreeD.MultiplySignedScaled.AddBit0                      ; переход, если бит 0 семибитного модуля коэффициента равен 1, начать накопление

                ; Переход к применению знака при нулевом семибитном модуле, результат HL уже нулевой.
                JP @ThreeD.MultiplySignedScaled.ApplySign

                ; Накопление вклада разряда 6 с переносом в старший байт A.
AddBit6:        ADD HL, DE
                ADC A, C
                ADD HL, HL
                ADC A, A
                JR NC, @ThreeD.MultiplySignedScaled.ShiftBit5                   ; переход, если бит 5 модуля коэффициента равен 0, пропустить его слагаемое

                ; Накопление вклада разряда 5 с переносом в старший байт A.
AddBit5:        ADD HL, DE
                ADC A, C
ShiftBit5:      ADD HL, HL
                ADC A, A
                JR NC, @ThreeD.MultiplySignedScaled.ShiftBit4                   ; переход, если бит 4 модуля коэффициента равен 0, пропустить его слагаемое

                ; Накопление вклада разряда 4 с переносом в старший байт A.
AddBit4:        ADD HL, DE
                ADC A, C
ShiftBit4:      ADD HL, HL
                ADC A, A
                JR NC, @ThreeD.MultiplySignedScaled.ShiftBit3                   ; переход, если бит 3 модуля коэффициента равен 0, пропустить его слагаемое

                ; Накопление вклада разряда 3 с переносом в старший байт A.
AddBit3:        ADD HL, DE
                ADC A, C
ShiftBit3:      ADD HL, HL
                ADC A, A
                JR NC, @ThreeD.MultiplySignedScaled.ShiftBit2                   ; переход, если бит 2 модуля коэффициента равен 0, пропустить его слагаемое

                ; Накопление вклада разряда 2 с переносом в старший байт A.
AddBit2:        ADD HL, DE
                ADC A, C
ShiftBit2:      ADD HL, HL
                ADC A, A
                JR NC, @ThreeD.MultiplySignedScaled.ShiftBit1                   ; переход, если бит 1 модуля коэффициента равен 0, пропустить его слагаемое

                ; Накопление вклада разряда 1 с переносом в старший байт A.
AddBit1:        ADD HL, DE
                ADC A, C
ShiftBit1:      ADD HL, HL
                ADC A, A
                JR NC, @ThreeD.MultiplySignedScaled.ShiftBit0                   ; переход, если бит 0 модуля коэффициента равен 0, пропустить его слагаемое

                ; Накопление вклада разряда 0 с переносом в старший байт A.
AddBit0:        ADD HL, DE
                ADC A, C
ShiftBit0:      ADD HL, HL
                ADC A, A
                ; Усечение младших семи разрядов произведения, после последнего удвоения байты H и A образуют результат.
                LD L, H
                LD H, A
                ; -----------------------------------------
                ; Применение исходного знака к уже усечённому модулю
                ; В основной AF возвращается знаковый XOR, старший накопитель и его флаги остаются в альтернативном AF.
ApplySign:      EX AF, AF'
                JP P, @ThreeD.MultiplySignedScaled.Continue                     ; переход, если исходные знаки совпадают, модуль уже является результатом

                ; Расчёт отрицательного результата с Carry=0 от сохранённого XOR.
                EX DE, HL
                LD HL, #0000
                SBC HL, DE
                ; Передача управления продолжению в IX, SP и память стека не меняются.
Continue:       JP (IX)

                ; -----------------------------------------
                endmodule
                endmodule
