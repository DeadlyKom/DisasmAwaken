                module ThreeD
                module ClearWorkBuffer
                ; Документация [алгоритм и проверка](../../Docs/ThreeDOverlayMirror.md)
                ; -----------------------------------------
                ; Заполнение линейного буфера 8000..8BFF байтами FF через временный SP с восстановлением CPU-стека
                ; исходная запись 19, банк 0, смещения #110A..#112B
                ; In:
                ;   HL, DE, BC и AF числовых аргументов не задают, входные C и AF должны сохраниться
                ;   HL', DE', BC', AF', IX и IY содержат сохраняемый контекст
                ;   буфер 8000..8BFF доступен на запись, 3DPART банка 0 и операнд SavedSP доступны для самомодификации
                ;   SP указывает на внешний адрес возврата, стек не пересекается с очищаемым буфером и кодом процедуры
                ;   аппаратные прерывания не вмешиваются во временный SP, инструкция DI здесь не выполняется
                ; Out:
                ;   HL=FFFF, B=0, DE, C и AF сохраняются
                ;   HL', DE', BC', AF', IX и IY, I/IM/IFF и paging сохраняются
                ;   ровно 3072 байта 8000..8BFF получают FF, каждый записывается один раз
                ;   SavedSP по D129 содержит входной SP, SP восстановлен и после RET равен входному SP+2
                ;   R увеличен на 1639 M1 с сохранением старшего разряда, время без ожиданий памяти и IRQ равно 18206 тактам
                ;   CPU-стек не записывается, кроме использования буфера как временной области PUSH, порты не используются
                ; Corrupt:
                ;   HL, BC, только B, R, SavedSP и 3072 байта линейного буфера
                ; Note:
                ;   дисковая копия слота 19 побайтово совпадает с ACTION по исходным смещениям 6000..801F
                ;   перенос доказательств требует тех же внешней RAM, банка 0, состояния входа и договоров общих процедур вне файла
                ;   нативная загрузка отдельного 3DPART не выполнялась, CF08 сохраняет отдельную неоднозначность исполнения
                ;   каждый из 96 проходов выполняет 16 PUSH HL, то есть ровно 32 байта нисходящей записи
                ;   все инструкции сохраняют AF, DJNZ не меняет флаги, исходное заполнение равно FF
                ;   область 8C00 и выше не заполняется, таблицы масок начинаются сразу после буфера
                ;   1536 сценариев проверяют все значения F, A и C, шесть исходных SP, регистры, R, RAM и кратность записей
                ;   тайминг относится к данному фрагменту от Entry до RET без дополнительных ожиданий, IRQ и нативный запуск не выполнялись
                ; -----------------------------------------
                ; -----------------------------------------
                ; CPU-стек и граница буфера
                ; Сохранение обычного SP перед заменой его на исключённый верхний адрес буфера.
Entry:          LD (@ActionWorkBufferState.SavedSP), SP
                LD SP, @ActionWorkBufferConst.BufferEnd
                ; Выбор исходного слова FF/FF и 96 блоков по 32 байта.
                LD HL, @ActionWorkBufferConst.FillWord
                LD B, @ActionWorkBufferConst.BlockCount
                ; -----------------------------------------
                ; Нисходящая запись одного блока
                ; Шестнадцать PUSH заполняют одну линейную строку, флаги и AF остаются входными.
WriteBlock:     PUSH HL
                PUSH HL
                PUSH HL
                PUSH HL
                PUSH HL
                PUSH HL
                PUSH HL
                PUSH HL
                PUSH HL
                PUSH HL
                PUSH HL
                PUSH HL
                PUSH HL
                PUSH HL
                PUSH HL
                PUSH HL
                DJNZ @ThreeD.ClearWorkBuffer.WriteBlock

                ; -----------------------------------------
                ; Восстановление CPU-возврата
                ; Возврат исходного SP из изменяемого операнда перед RET.
RestoreStack:   LD SP, #0000
                RET

                ; -----------------------------------------
                endmodule
                endmodule
