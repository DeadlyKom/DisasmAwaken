                module ThreeD
                module AppendSecondClipPoint
                ; Документация [алгоритм и проверка](../../Docs/ThreeDOverlayMirror.md)
                ; -----------------------------------------
                ; Добавление младших байтов второй точки с общим входом записи пары DE
                ; исходная запись 19, банк 0, смещения #06D3..#06E9
                ; In:
                ;   Entry читает младшие байты SecondPoint.Second и SecondPoint.First, старшие байты и ClipCode не читаются
                ;   общий вход StorePair получает упакованную пару в DE, E как Second, D как First
                ;   OutputSize задаёт байтовое смещение в странице 90, допускает все 256 значений
                ;   3DPART находится в банке 0, на CPU-стеке внешний возврат, IRQ не вмешиваются
                ; Out:
                ;   HL равен 9000 OR ((OutputSize_вход+2) AND FF), DE содержит записанную упакованную пару, BC сохраняется
                ;   A равен новому OutputSize, F равен флагам последнего INC L с сохранённым входным Carry
                ;   два байта пары записаны через INC L, перенос в старший байт страницы не выполняется
                ;   весь альтернативный набор, IX, IY, I, IM, IFF и paging сохраняются
                ;   SP после RET равен входному SP+2, дополнительный CPU-стек не используется, R увеличивается на 14 для Entry и 10 для StorePair
                ; Corrupt:
                ;   HL, DE только для Entry, AF, R, два байта пары и OutputSize
                ; Note:
                ;   дисковая копия слота 19 побайтово совпадает с ACTION по исходным смещениям 6000..801F
                ;   перенос доказательств требует тех же внешней RAM, банка 0, состояния входа и договоров общих процедур вне файла
                ;   нативная загрузка отдельного 3DPART не выполнялась, CF08 сохраняет отдельную неоднозначность исполнения
                ;   запись не проверяет границы координат и ёмкость буфера, старшие байты исходной точки намеренно игнорируются
                ;   131072 сценария проверяют все упакованные пары при обоих Carry, точные регистры, флаги, R, всю RAM и кратность записей
                ;   StorePair также исполняется настоящими переходами всех четырёх углов, IRQ, сборка и нативный вывод не проверены
                ; -----------------------------------------
                ; -----------------------------------------
                ; Чтение второй точки
                ; Выбор только младших байтов двух координат, без насыщения и проверки ClipCode.
Entry:          LD A, (@ThreeDClipPoints.SecondPoint.Second)
                LD E, A
                LD A, (@ThreeDClipPoints.SecondPoint.First)
                LD D, A
                ; -----------------------------------------
                ; Общая запись пары
                ; Чтение OutputSize и запись E как Second, D как First с байтовым оборачиванием адреса.
StorePair:      LD A, (@ActionClipIntersectionsState.OutputSize)
                LD L, A
                LD H, @ActionClipIntersectionConst.OutputPage
                LD (HL), E
                INC L
                LD (HL), D
                INC L
                LD A, L
                ; Обновление байтового размера без изменения Carry от последнего INC L.
                LD (@ActionClipIntersectionsState.OutputSize), A
                RET

                ; -----------------------------------------
                endmodule
                endmodule
