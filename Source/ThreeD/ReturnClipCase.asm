                ; Завершение текущего табличного случая обычным RET
                ; исходная запись 19, банк 0, смещения #007A..#007A
                ; In:
                ;   на CPU-стеке адрес следующего продолжения, это общий RET для нескольких контекстов
                ; Out:
                ;   HL, DE, BC, AF, альтернативный набор, IX, IY, I, IM, IFF и paging сохраняются
                ;   SP увеличен на два, управление передано снятому адресу, RAM не записывается, R увеличивается на один
                ; Corrupt:
                ;   SP и R
                ; Note:
                ;   дисковая копия слота 19 побайтово совпадает с ACTION по исходным смещениям 6000..801F
                ;   перенос доказательств требует тех же внешней RAM, банка 0, состояния входа и договоров общих процедур вне файла
                ;   нативная загрузка отдельного 3DPART не выполнялась, CF08 сохраняет отдельную неоднозначность исполнения
                ;   при табличной рамке продолжение C993 выполняет свой договор, при NextEdge снят внешний адрес
                ;   одна инструкция RET отдельно не меняет координаты, размер и коды, свойства последующего кода ей не приписываются
                ; -----------------------------------------
                ; вход таблицы, обе точки в одной и той же внешней зоне, новая точка не добавляется
