                module UnknownCF08
                ; Место в странице CF00 [адресные байты и наложенные рабочие записи](../../Docs/ClipTargetLowPhysicalData.md)
                ; Документация [Action](../../Docs/ThreeDOverlayMirror.md)
                ; -----------------------------------------
                ; Unknown, назначение этого фрагмента ещё не установлено
                ; исходная запись 19, банк 0, смещения #0F08..#0F0A
                ; In:
                ;   HL, DE, BC, AF, HL', DE', BC', AF', IX и IY задают произвольный сохраняемый контекст
                ;   этот договор применяется только при условии передачи управления на CF08, игровой вход не доказан
                ;   SP указывает читаемое слово адреса возврата, три исходных байта F3 AF C9 доступны, прерывание не происходит до DI
                ; Out:
                ;   HL, DE и BC сохраняются, A=0, F=44
                ;   HL', DE', BC', AF', IX, IY, I и IM сохраняются, прерывания запрещены инструкцией DI
                ;   R увеличен на три M1 с сохранением бита 7, PC прочитан из исходного слова стека, SP увеличен на два
                ;   RAM, таблицы, страницы и порты не меняются, временных записей CPU-стека нет
                ; Corrupt:
                ;   AF, IFF, R, SP и PC по обычному RET
                ; Note:
                ;   табличная роль байтов CF08..CF0A доказана отдельно, их использование как кода остаётся неизвестным
                ;   7680 сценариев проверили условное исполнение трёх байтов, все регистры кроме T и неизменность всей памяти
                ;   совпадение трёх байтов в ACTION и 3DPART проверено, произвольный игровой вызывающий путь не установлен
                ;   проверка эффекта не заменяет доказательство назначения процедуры, статус Unknown сохраняется
                ;   [Табличная роль и неоднозначность исполнения](../../Docs/ThreeDOverlayMirror.md)
                ; -----------------------------------------
                ; Условное исполнение запрещает прерывания, очищает AF и снимает внешний возврат.
Entry:          DI
                XOR A
                RET


                endmodule
                endmodule
