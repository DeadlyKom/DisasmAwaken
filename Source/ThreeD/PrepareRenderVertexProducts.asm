                module ThreeD
                module PrepareRenderVertexProducts
                ; Документация [алгоритм и проверка](../../Docs/ThreeDOverlayMirror.md)
                ; -----------------------------------------
                ; Подготовка трёх пар координат и трёх глубин табличным произведением матрицы и входных компонентов
                ; исходная запись 19, банк 0, смещения #15F9..#1693
                ; In:
                ;   D содержит третью локальную компоненту signed8, половина получается арифметическим сдвигом с округлением вниз
                ;   BC содержит первую компоненту signed8 в B и вторую signed8 в C, половины округляются вниз
                ;   девять операндов ActionRenderMatrixState.Coeff11..Coeff33 подготовлены ComposeRenderMatrix
                ;   исходная таблица ActionProjectionSquares находится по 9800 и сохраняет все 256 исходных значений
                ;   код 3DPART банка 0 доступен на запись, IRQ не вмешиваются, SP сохраняется до продолжения в генераторе
                ;   IXL и параметры перспективы задают договор следующей ProjectRenderVertexGroup
                ; Out:
                ;   HL=#9800+s для последнего произведения P(Coeff32,D), где s его индекс суммы по формуле Note
                ;   DE сохраняет входной D, E содержит T(d) последнего произведения, d его индекс разности
                ;   BC сохраняется
                ;   AF содержит A=P(Coeff32,D) и F последнего SUB T(s)-T(d), N=1, PV=0, S и Carry совпадают и означают отрицательную разность, Z означает A=0
                ;   HL', DE', BC', AF' сохраняются
                ;   IX и IY сохраняются, SP, I, IM, IFF и paging сохраняются до границы D694
                ;   R получает ровно 127 M1, один от LD H,98 и девять раз по 14, бит 7 R сохраняется
                ;   PackedFirst содержит P(Coeff21,B) младшим байтом и P(Coeff11,B) старшим
                ;   PackedSecond содержит P(Coeff23,C) младшим байтом и P(Coeff13,C) старшим
                ;   PackedThird содержит P(Coeff22,D) младшим байтом и P(Coeff12,D) старшим
                ;   DepthFirst, DepthSecond и DepthThird получают P(Coeff31,B), P(Coeff33,C) и P(Coeff32,D)
                ;   управление последовательно переходит в ProjectRenderVertexGroup без CALL и без RET, его дальнейшие эффекты не включены в состояние границы D694
                ; Corrupt:
                ;   HL, E, AF, R и девять существующих байтов операндов генератора до продолжения, дальнейшие изменения задаёт ProjectRenderVertexGroup
                ; Note:
                ;   дисковая копия слота 19 побайтово совпадает с ACTION по исходным смещениям 6000..801F
                ;   перенос доказательств требует тех же внешней RAM, банка 0, состояния входа и договоров общих процедур вне файла
                ;   нативная загрузка отдельного 3DPART не выполнялась, CF08 сохраняет отдельную неоднозначность исполнения
                ;   результаты этого договора относятся к границе D694, а не к возврату полного вызова
                ;   P(a,b)=wrap8(T(wrap8(floor(signed8(a)/2)-floor(signed8(b)/2)+b))-T(wrap8(floor(signed8(a)/2)-floor(signed8(b)/2))))
                ;   T(i)=floor(min(i,255-i)^2/127), аргументы не переставляются, обычное умножение или округление к нулю неэквивалентно
                ;   физический порядок столбцов 1, 3, 2 сохранён, все девять произведений вычисляются независимо без накопления
                ;   72704 сценария проверяют все пары примитива, независимые срезы коэффициентов и компонентов, точные флаги, R, всю RAM и кратность записей
                ;   T имеет значения 0..127, математическая разность лежит в -127..127, код 80 невозможен у любого из девяти произведений
                ;   проверка останавливается перед генератором, полный проход объекта доказывается отдельно
                ; -----------------------------------------
                ; -----------------------------------------
                ; Строка первой упакованной оси
                ; Подготовка страницы исходной таблицы квадратов, столбцы используются в порядке 1, 3, 2.
Entry:          LD H, @ActionProjectionClipConst.SquarePage
                ; Расчёт P(Coeff11, B), арифметические половины и два чтения таблицы сохраняют исходное округление.
                LD A, #00
                SRA A
                LD L, B
                SRA L
                SUB L
                LD L, A
                ADD A, B
                LD E, (HL)
                LD L, A
                LD A, (HL)
                SUB E
                ; Сохранение результата в PackedFirst старший байт существующего операнда генератора.
                LD (@ActionVertexGroupState.PackedFirst+1), A
                ; Расчёт P(Coeff13, C), арифметические половины и два чтения таблицы сохраняют исходное округление.
                LD A, #00
                SRA A
                LD L, C
                SRA L
                SUB L
                LD L, A
                ADD A, C
                LD E, (HL)
                LD L, A
                LD A, (HL)
                SUB E
                ; Сохранение результата в PackedSecond старший байт существующего операнда генератора.
                LD (@ActionVertexGroupState.PackedSecond+1), A
                ; Расчёт P(Coeff12, D), арифметические половины и два чтения таблицы сохраняют исходное округление.
                LD A, #00
                SRA A
                LD L, D
                SRA L
                SUB L
                LD L, A
                ADD A, D
                LD E, (HL)
                LD L, A
                LD A, (HL)
                SUB E
                ; Сохранение результата в PackedThird старший байт существующего операнда генератора.
                LD (@ActionVertexGroupState.PackedThird+1), A
                ; -----------------------------------------
                ; Строка второй упакованной оси
                ; Расчёт P(Coeff21, B), арифметические половины и два чтения таблицы сохраняют исходное округление.
                LD A, #00
                SRA A
                LD L, B
                SRA L
                SUB L
                LD L, A
                ADD A, B
                LD E, (HL)
                LD L, A
                LD A, (HL)
                SUB E
                ; Сохранение результата в PackedFirst младший байт существующего операнда генератора.
                LD (@ActionVertexGroupState.PackedFirst), A
                ; Расчёт P(Coeff23, C), арифметические половины и два чтения таблицы сохраняют исходное округление.
                LD A, #00
                SRA A
                LD L, C
                SRA L
                SUB L
                LD L, A
                ADD A, C
                LD E, (HL)
                LD L, A
                LD A, (HL)
                SUB E
                ; Сохранение результата в PackedSecond младший байт существующего операнда генератора.
                LD (@ActionVertexGroupState.PackedSecond), A
                ; Расчёт P(Coeff22, D), арифметические половины и два чтения таблицы сохраняют исходное округление.
                LD A, #00
                SRA A
                LD L, D
                SRA L
                SUB L
                LD L, A
                ADD A, D
                LD E, (HL)
                LD L, A
                LD A, (HL)
                SUB E
                ; Сохранение результата в PackedThird младший байт существующего операнда генератора.
                LD (@ActionVertexGroupState.PackedThird), A
                ; -----------------------------------------
                ; Строка глубины
                ; Расчёт P(Coeff31, B), арифметические половины и два чтения таблицы сохраняют исходное округление.
                LD A, #00
                SRA A
                LD L, B
                SRA L
                SUB L
                LD L, A
                ADD A, B
                LD E, (HL)
                LD L, A
                LD A, (HL)
                SUB E
                ; Сохранение результата в DepthFirst существующего операнда генератора.
                LD (@ActionVertexGroupState.DepthFirst), A
                ; Расчёт P(Coeff33, C), арифметические половины и два чтения таблицы сохраняют исходное округление.
                LD A, #00
                SRA A
                LD L, C
                SRA L
                SUB L
                LD L, A
                ADD A, C
                LD E, (HL)
                LD L, A
                LD A, (HL)
                SUB E
                ; Сохранение результата в DepthSecond существующего операнда генератора.
                LD (@ActionVertexGroupState.DepthSecond), A
                ; Расчёт P(Coeff32, D), арифметические половины и два чтения таблицы сохраняют исходное округление.
                LD A, #00
                SRA A
                LD L, D
                SRA L
                SUB L
                LD L, A
                ADD A, D
                LD E, (HL)
                LD L, A
                LD A, (HL)
                SUB E
                ; Сохранение результата в DepthThird существующего операнда генератора.
                LD (@ActionVertexGroupState.DepthThird), A
                ; JP @ThreeD.ProjectRenderVertexGroup.Entry, продолжение в ProjectRenderVertexGroup.asm

                ; -----------------------------------------
                endmodule
