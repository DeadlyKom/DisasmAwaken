                module ThreeD
                module ComputeLeftClipProduct
                ; Документация [алгоритм и проверка](../../Docs/ThreeDOverlayMirror.md)
                ; -----------------------------------------
                ; Подготовка числителя пересечения (FirstPoint.First-SecondPoint.First)*(FirstPoint.Second-0) исходным знаковым умножителем
                ; исходная запись 19, банк 0, смещения #04B5..#04D3
                ; In:
                ;   две исходные точки по CF0B и CF1B содержат signed16 Second и First, ClipCode не читается
                ;   3DPART банка 0 доступен, выходной четырёхбайтовый слот доступен на запись, IRQ не вмешиваются
                ;   на CPU-стеке внешний возврат и четыре дополнительных свободных байта
                ; Out:
                ;   HL содержит старшее слово, DE младшее слово результата (FirstPoint.First-SecondPoint.First)*(FirstPoint.Second-0) с особенностями MultiplySigned16
                ;   OperandHL=wrap16(FirstPoint.First-SecondPoint.First), OperandDE=wrap16(FirstPoint.Second-0), модули берутся как abs(signed16)
                ;   M равен произведению модулей, но при обоих модулях не меньше 256 и OperandDE=8000 второй множитель заменяется на 256
                ;   BC при разных знаках OperandHL и OperandDE равен старшему слову M, иначе при обоих модулях меньше 256 равен SecondPoint.First
                ;   BC при одинаковых знаках и ровно одном модуле не меньше 256 равен (SecondPoint.First) AND FF00, при обоих больших модулях равен нулю
                ;   AF - A равен XOR старших байтов OperandHL и OperandDE, при одинаковых знаках F содержит флаги этого XOR
                ;   при разных знаках F соответствует SBC старшего слова, 0 минус старшее слово M минус заём от отрицания ненулевого младшего слова M
                ;   HL', DE', BC', AF' сохраняются
                ;   IX при обоих модулях не меньше 256 равен младшему слову M до отрицания, иначе сохраняется
                ;   IY, I, IM, IFF и paging сохраняются, SP после RET равен входному SP+2, R меняется
                ;   полный результат записан в LeftProduct, сначала младшее слово, затем старшее
                ; Corrupt:
                ;   HL, DE, BC, AF, IX по ядру умножения, R, выходной слот и четыре байта CPU-стека
                ; Note:
                ;   дисковая копия слота 19 побайтово совпадает с ACTION по исходным смещениям 6000..801F
                ;   перенос доказательств требует тех же внешней RAM, банка 0, состояния входа и договоров общих процедур вне файла
                ;   нативная загрузка отдельного 3DPART не выполнялась, CF08 сохраняет отдельную неоднозначность исполнения
                ;   разности оборачиваются до 16 бит, Carry перед каждым SBC очищается отдельно
                ;   порядок аргументов существенен, второй операнд 8000 наследует исходное исключение полного ядра
                ;   проверены 4140 сценариев этого входа с настоящим дочерним кодом, точные регистры и флаги кроме R, вся RAM и кратность записей
                ;   общая проверка четырёх входов содержит 16560 сценариев, все совместные входы, R/T, IRQ, сборка и нативный вывод не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Подготовка числителя пересечения
                ; Чтение первого вычитания для второго операнда DE, исходный порядок множителей сохраняется.
Entry:          LD BC, @ActionClipProductConst.ZeroBound
                LD HL, (@ThreeDClipPoints.FirstPoint.Second)
                ; Расчёт первой разности с очищенным Carry и оборачиванием до слова.
                OR A
                SBC HL, BC
                EX DE, HL
                ; Чтение аргументов второго вычитания для первого операнда HL.
                LD BC, (@ThreeDClipPoints.SecondPoint.First)
                LD HL, (@ThreeDClipPoints.FirstPoint.First)
                OR A
                SBC HL, BC
                ; Расчёт полного произведения настоящим MultiplySigned16 с исходным исключением 8000.
                CALL @ThreeD.MultiplySigned16.Entry
                ; Сохранение младшего слова результата в существующем выходном слоте.
                LD (@ThreeDClipProductsData.LeftProduct.LowWord), DE
                ; Сохранение старшего слова, четыре исходных байта результата не переставляются.
                LD (@ThreeDClipProductsData.LeftProduct.HighWord), HL
                RET

                endmodule
                endmodule
