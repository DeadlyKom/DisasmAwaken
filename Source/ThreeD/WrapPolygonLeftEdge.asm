                module ThreeD
                module WrapPolygonLeftEdge
                ; Документация [алгоритм и проверка](../../Docs/ThreeDOverlayMirror.md)
                ; Документация [короткий переходник и R](../../Docs/ActionPolygonWrapLeft.md)
                ; -----------------------------------------
                ; Оборачивание обратного поиска к последней First кольца
                ; исходная запись 19, банк 0, смещения #126B..#1271
                ; In:
                ;   HL содержит страницу 90 и нулевой младший индекс после достижения начала кольца
                ;   DE содержит D текущей строки и E первоначальной Second, BC и AF принадлежат обновлению левого ребра
                ;   LastIndex содержит последний нечётный индекс, временный контекст уже сохранён UpdatePolygonLeftEdge
                ; Out:
                ;   HL сохраняет H, L=LastIndex
                ;   DE и BC сохраняются
                ;   AF содержит A=LastIndex и исходный F
                ;   HL', DE', BC', AF' сохраняются
                ;   IX и IY сохраняются, SP, I, IM, IFF и paging сохраняются
                ;   управление передано UpdatePolygonLeftEdge.ReadNextRow, память и порты не записываются
                ;   R добавляет 3 M1, бит 7 R сохраняется
                ; Corrupt:
                ;   HL, только L, AF, только A, R
                ; Note:
                ;   дисковая копия слота 19 побайтово совпадает с ACTION по исходным смещениям 6000..801F
                ;   перенос доказательств требует тех же внешней RAM, банка 0, состояния входа и договоров общих процедур вне файла
                ;   нативная загрузка отдельного 3DPART не выполнялась, CF08 сохраняет отдельную неоднозначность исполнения
                ;   короткий переходник сохраняет исходные адреса и инструкции, новый адрес возврата не создаётся
                ;   проверены точные регистры включая R и отсутствие записей RAM, полное игровое исполнение этим не доказывается
                ;   точные T, IRQ, сборка и нативный запуск не проверены
                ; -----------------------------------------
                ; Чтение последнего нечётного индекса и продолжение обратного поиска в той же странице.
Entry:          LD A, (@ActionPolygonPreparationState.LastIndex)
                LD L, A
                JP @ThreeD.UpdatePolygonLeftEdge.ReadNextRow

                endmodule
                endmodule
