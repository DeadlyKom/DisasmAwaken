                module ThreeD
                module WrapPolygonRightEdge
                ; Документация [алгоритм и проверка](../../Docs/ThreeDOverlayMirror.md)
                ; -----------------------------------------
                ; Оборачивание прямого поиска к первой First кольца
                ; исходная запись 19, банк 0, смещения #13A8..#13AC
                ; In:
                ;   HL содержит страницу 90, прямой поиск достиг последнего нечётного индекса
                ;   DE содержит D текущей строки и E первоначальной Second, временный контекст сохранён UpdatePolygonRightEdge
                ; Out:
                ;   HL сохраняет H, L=1, управление передано UpdatePolygonRightEdge.ReadNextRow
                ;   DE, BC, AF, HL', DE', BC', AF', IX, IY, SP, I/IM/IFF и paging сохраняются, R меняется
                ;   память и порты не записываются
                ; Corrupt:
                ;   HL, только L, R
                ; Note:
                ;   дисковая копия слота 19 побайтово совпадает с ACTION по исходным смещениям 6000..801F
                ;   перенос доказательств требует тех же внешней RAM, банка 0, состояния входа и договоров общих процедур вне файла
                ;   нативная загрузка отдельного 3DPART не выполнялась, CF08 сохраняет отдельную неоднозначность исполнения
                ;   короткий переходник сохраняет исходные адреса и инструкции, новый адрес возврата не создаётся
                ;   проверены точные регистры кроме R и отсутствие записей RAM, полное игровое исполнение этим не доказывается
                ;   R/T, IRQ, сборка и нативный запуск не проверены
                ; -----------------------------------------
                ; Выбор первой First по нечётному индексу 1 без изменения страницы контура.
Entry:          LD L, #01
                JP @ThreeD.UpdatePolygonRightEdge.ReadNextRow

