                module ThreeD
                module ClipPolygon
                ; Документация [алгоритм и проверка](../../Docs/ThreeDOverlayMirror.md)
                ; -----------------------------------------
                ; Обход замкнутого списка вершин с табличным отсечением и ранним завершением контура
                ; исходная запись 19, банк 0, смещения #0000..#0070
                ; In:
                ;   HL указывает на список B байтовых смещений точек в странице 8E, DE и основной AF аргументов не задают
                ;   B от 1 до 15, входной C сохраняется на обычном выходе, B=0 вне доказанного договора
                ;   по каждому индексу доступны пять байтов FRenderProjectedPoint без оборачивания записи за предел страницы, коды согласованы с координатами
                ;   для каждого достигнутого деления знаменатель ненулевой и однокомплементный модуль числителя меньше abs(d)*65536
                ;   3DPART находится в банке 0, выходная страница 90 и слоты отсечения доступны на запись, CPU-стек допускает вложенные рамки, IRQ не вмешиваются
                ; Out:
                ;   HL указывает сразу за всем входным списком при обычном и специальном выходе, BC на обычном выходе содержит B=0 и исходный C
                ;   контур замыкается ребром от последней входной вершины к первой, затем обходятся остальные рёбра
                ;   CornerBlock и SeenFlags сначала обнуляются, OutputSize начинается с нуля, выходные пары добавляются в страницу 90
                ;   при обычном выходе A=OutputSize, F от CP размера,6, Carry=1 означает меньше трёх выходных точек, Z=1 означает ровно три точки
                ;   при специальном выходе A=C0, B=0, C равно числу пропущенных оставшихся индексов, Carry=1, F=41 при нуле оставшихся либо F=01 при ненулевом числе
                ;   DE, AF' и IX соответствуют последней достигнутой цепочке помощников, точные значения задаёт ReferenceActionPolygon.py
                ;   HL', DE', BC', IY, I, IM, IFF и paging сохраняются, SP после полного RET равен входному SP+2, R меняется
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', IX по достигнутым помощникам, R, обе рабочие точки, произведения, размер, отметки углов, выходные пары и временные слова CPU-стека
                ; Note:
                ;   дисковая копия слота 19 побайтово совпадает с ACTION по исходным смещениям 6000..801F
                ;   перенос доказательств требует тех же внешней RAM, банка 0, состояния входа и договоров общих процедур вне файла
                ;   нативная загрузка отдельного 3DPART не выполнялась, CF08 сохраняет отдельную неоднозначность исполнения
                ;   первый и последний индексы читаются полными 16-битными указателями, переход списка через границу страницы сохранён
                ;   счётчик B не проверяется на нуль, общий договор ограничен 1..15, непрерывный размер вывода в этом диапазоне не превосходит 120 байтов по максимуму четырёх точек одного пути
                ;   70 табличных входов имеют отдельные договоры рамки C993, здесь используется собственная рамка C071 со счётчиком и указателем
                ;   5171 сценарий исполняет настоящий цикл и все помощники без подмены, проверены регистры кроме R, вся физическая RAM и кратность записей
                ;   численный эталон композиционный по исходным путям, независимое геометрическое доказательство, точное R/T, все совместные входы, IRQ, сборка и нативный вывод не заявляются
                ; -----------------------------------------
                ; -----------------------------------------
                ; Инициализация контура
                ; Обнуление запрета углов, размера и прежних отметок перед замыканием списка.
Entry:          XOR A
                LD (@ActionClipPointWritersState.CornerBlock), A
                LD (@ActionClipIntersectionsState.OutputSize), A
                LD (@ActionClipCasesState.SeenFlags), A
                ; -----------------------------------------
                ; Замыкание последней вершины на первую
                ; Сохранение начала списка и расчёт полного адреса последнего байтового индекса как HL+B-1.
                PUSH HL
                LD A, B
                DEC A
                ADD A, L
                LD L, A
                LD A, H
                ADC A, #00
                LD H, A
                ; Чтение последнего индекса и двух слов точки с её парным ClipCode.
                LD L, (HL)
                LD H, @ActionVertexGroupConst.WorkHigh
                LD E, (HL)
                INC L
                LD D, (HL)
                INC L
                LD (@ThreeDClipPoints.SecondPoint.Second), DE
                LD E, (HL)
                INC L
                LD D, (HL)
                INC L
                LD (@ThreeDClipPoints.SecondPoint.First), DE
                LD A, (HL)
                LD (@ThreeDClipPoints.SecondPoint.ClipCode), A
                ; -----------------------------------------
                ; Сохранение предыдущей вершины
                ; Копирование текущей SecondPoint в FirstPoint перед чтением следующего входного индекса.
CopyLastPoint:  LD HL, (@ThreeDClipPoints.SecondPoint.Second)
                LD (@ThreeDClipPoints.FirstPoint.Second), HL
                LD HL, (@ThreeDClipPoints.SecondPoint.First)
                LD (@ThreeDClipPoints.FirstPoint.First), HL
                LD A, (@ThreeDClipPoints.SecondPoint.ClipCode)
                LD (@ThreeDClipPoints.FirstPoint.ClipCode), A
                ; Восстановление указателя списка, чтение очередного индекса и сохранение рамки следующего возврата.
                POP HL
                LD A, (HL)
                INC HL
                PUSH HL
                PUSH BC
                ; Чтение новой SecondPoint по байтовому индексу страницы 8E.
                LD L, A
                LD H, @ActionVertexGroupConst.WorkHigh
                LD E, (HL)
                INC L
                LD D, (HL)
                INC L
                LD (@ThreeDClipPoints.SecondPoint.Second), DE
                LD E, (HL)
                INC L
                LD D, (HL)
                INC L
                LD (@ThreeDClipPoints.SecondPoint.First), DE
                LD A, (HL)
                LD (@ThreeDClipPoints.SecondPoint.ClipCode), A
                ; -----------------------------------------
                ; Выбор обработчика ребра
                ; Расчёт индекса по инверсии старшей тетрады первой точки и младшей тетраде второй, обмен точек не выполняется.
                LD A, (@ThreeDClipPoints.FirstPoint.ClipCode)
                CPL
                AND @ActionVertexCodeConst.InverseMask
                LD L, A
                LD A, (@ThreeDClipPoints.SecondPoint.ClipCode)
                AND @ActionPolygonConst.OutsideMask
                OR L
                LD L, A
                ; Чтение младшего и старшего байтов цели из двух исходных страниц CF и D0.
                LD H, @ActionPolygonConst.TableLowPage
                LD E, (HL)
                INC H
                LD D, (HL)
                EX DE, HL
                ; Сохранение единственного возврата ContinueClipPolygon поверх счётчика BC и указателя списка.
                LD DE, @ThreeD.ContinueClipPolygon.Entry
                PUSH DE
                JP (HL)

                ; -----------------------------------------
                endmodule
                endmodule
