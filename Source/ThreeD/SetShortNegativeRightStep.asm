                module ThreeD
                module SetShortNegativeRightStep
                ; Документация [алгоритм и проверка](../../Docs/ThreeDOverlayMirror.md)
                ; -----------------------------------------
                ; Настройка нулевого целого шага короткого отрицательного правого наклона и восстановление временного контекста
                ; исходная запись 19, банк 0, смещения #14F5..#1502
                ; In:
                ;   HL текущий указатель конца ребра будет заменён словом из временного стека
                ;   DE содержит D высоту ребра и E первоначальную Second, BC содержит сохраняемый линейный адрес
                ;   AF содержит A вычитаемой ошибки, в штатном коротком отрицательном пути A=abs(dx)<высоты ребра
                ;   HL', BC', AF', IX и IY сохраняются, DE' будет заменён нулевым целым горизонтальным шагом
                ;   SP=FFDE указывает на сохранённые текущую строку и страницу масок, 3DPART банка 0 доступен на запись
                ; Out:
                ;   HL снят с временного стека, D равен снятому L, E сохраняется, BC и AF сохраняются
                ;   DE'=2000, остальные альтернативные регистры, IX и IY сохраняются
                ;   RightSubtract по D21F равен входному A, это единственная запись RAM
                ;   SP увеличен на два, управление передано SelectPolygonRowLimit.Entry, внешнего RET нет
                ;   I, IM, IFF и paging сохраняются, R меняется, порты не используются
                ; Corrupt:
                ;   HL, DE, только D, DE', R, RightSubtract и SP при снятии сохранённого контекста
                ; Note:
                ;   дисковая копия слота 19 побайтово совпадает с ACTION по исходным смещениям 6000..801F
                ;   перенос доказательств требует тех же внешней RAM, банка 0, состояния входа и договоров общих процедур вне файла
                ;   нативная загрузка отдельного 3DPART не выполнялась, CF08 сохраняет отдельную неоднозначность исполнения
                ;   физический хвост находится после общего выбора предела, обратный JP является частью исходного алгоритма
                ;   65536 сценариев проверяют все комбинации A и F, регистры кроме R и исчерпывающий журнал записей
                ;   разрешение любого A в локальной проверке не расширяет штатный профиль короткого наклона
                ;   R/T, IRQ, сборка и нативное исполнение не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Короткий отрицательный наклон
                ; Обновление вычитаемой ошибки исходным модулем dx.
Entry:          LD (#D21F), A
                ; Установка упакованного шага 2000, горизонтальная целая часть равна нулю.
                EXX
                LD E, #00
                LD D, #20
                EXX
                ; Восстановление страницы масок и текущей строки из существующего временного стека.
                POP HL
                LD D, L
                ; Передача управления общему выбору предела без нового адреса возврата.
                JP @ThreeD.SelectPolygonRowLimit.Entry

                endmodule
                endmodule
