                module ReturnPolygonFill
                ; Документация [алгоритм и проверка](../../Docs/ThreeDOverlayMirror.md)
                ; -----------------------------------------
                ; Восстановление сохранённого HL и внешний возврат плоского контура
                ; исходная запись 19, банк 0, смещения #150F..#1510
                ; In:
                ;   SP указывает на ранее сохранённый HL, следующее слово содержит внешний адрес возврата
                ;   остальные регистры содержат результат раннего пути PreparePolygonFill
                ; Out:
                ;   HL снят с CPU-стека, SP увеличен на четыре и выполнен RET по следующему слову
                ;   DE, BC, AF, HL', DE', BC', AF', IX, IY, I/IM/IFF и paging сохраняются, R меняется
                ;   память и порты не записываются
                ; Corrupt:
                ;   HL, SP при снятии двух слов, R
                ; Note:
                ;   дисковая копия слота 19 побайтово совпадает с ACTION по исходным смещениям 6000..801F
                ;   перенос доказательств требует тех же внешней RAM, банка 0, состояния входа и договоров общих процедур вне файла
                ;   нативная загрузка отдельного 3DPART не выполнялась, CF08 сохраняет отдельную неоднозначность исполнения
                ;   возврат снимает два существующих слова, дополнительная память не выделяется
                ;   проверены точные регистры кроме R и отсутствие записей RAM, полное игровое исполнение этим не доказывается
                ;   R/T, IRQ, сборка и нативный запуск не проверены
                ; -----------------------------------------
                ; Восстановление HL вызывающего и внешнего возврата без смены временного SP.
Entry:          POP HL
                RET

                endmodule
                endmodule
