                module ThreeD
                module UpdatePolygonRightEdge
                ; Документация [алгоритм и проверка](../../Docs/ThreeDOverlayMirror.md)
                ; Документация [граница обновления ребра](../../Docs/ActionPolygonRightEdge.md)
                ; -----------------------------------------
                ; Поиск восходящего правого ребра и вычисление его упакованного шага и дробной ошибки
                ; исходная запись 19, банк 0, смещения #13AD..#14C0
                ; In:
                ;   HL содержит H текущей страницы масок, входной L не используется
                ;   DE содержит D текущей строки, входной E не используется, BC содержит сохраняемый линейный адрес
                ;   AF входных аргументов не задаёт, RightCursor указывает нечётный байт First исходной вершины страницы 90
                ;   LastIndex содержит последний нечётный индекс кольца из 3..60 вершин, вперёд достижима вершина с First строго больше D
                ;   Second от 0 до 255, First от 0 до 95, высота найденного ребра от 1 до 95
                ;   HL' содержит заменяемую ошибку H' и сохраняемый L', DE' заменяется шагом, BC', AF', IX и IY сохраняются
                ;   SP=FFE0, под ним доступны два байта существующего временного стека, 3DPART банка 0 доступен на запись, IRQ не вмешиваются
                ; Out:
                ;   HL сохраняет H, L становится входным D
                ;   DE сохраняет D, E при abs(dx)<Height равен первоначальной Second, при длинном dx>=0 равен (abs(dx) DIV Height) XOR #FF
                ;   при длинном dx<0 E равен ((abs(dx) DIV Height) XOR #FF) DIV 2, исходный последний бит объединяется в A через RLA
                ;   BC сохраняется
                ;   AF при длинном наклоне содержит A=старший байт упакованного шага и F от последнего ADD A,20
                ;   при коротком dx>=0 A=Height-dx и F от NEG разности dx-Height, при коротком dx<0 A=abs(dx) и F от CP abs(dx),Height
                ;   HL' сохраняет L', H'=Height DIV 2
                ;   DE'=(#2000+32*s) AND #FFFF, s=ceil(dx/Height) для ненулевого dx, при dx=0 s=1 с дробной компенсацией, BC' сохраняется
                ;   AF', IX и IY сохраняются
                ;   RightCursor указывает найденный конец, RightEndRow равен его First, Height равен разности First конца и входного D
                ;   dx равен Second найденного конца минус первоначальной Second, пропущенные вершины исходную Second не заменяют
                ;   Subtract при dx<0 равен abs(dx) MOD Height, при неотрицательном точном длинном наклоне равен нулю, иначе Height-(dx MOD Height)
                ;   SP восстановлен до FFE0, два байта под ним содержат входные D и H, управление передано SelectPolygonRowLimit.Entry до его исполнения
                ;   I, IM, IFF и paging сохраняются, R меняется, порты не используются
                ; Corrupt:
                ;   L, E, AF, H', DE', R, RightCursor, Height, Subtract, RightEndRow и два байта под SP
                ; Note:
                ;   дисковая копия слота 19 побайтово совпадает с ACTION по исходным смещениям 6000..801F
                ;   перенос доказательств требует тех же внешней RAM, банка 0, состояния входа и договоров общих процедур вне файла
                ;   нативная загрузка отдельного 3DPART не выполнялась, CF08 сохраняет отдельную неоднозначность исполнения
                ;   контракт заканчивается перед общим SelectPolygonRowLimit, который отдельно меняет L, E, AF и два строковых операнда
                ;   короткий отрицательный наклон идёт через SetShortNegativeRightStep, этот хвост физически расположен после общего выбора предела
                ;   после отрицательного длинного наклона нет завершающего JP, исполнение последовательно продолжается в SelectPolygonRowLimit.asm
                ;   нулевой наклон использует шаг 2020 и Subtract=Height, это исходная комбинация плюс один с коррекцией минус один
                ;   48545 сценариев правой цепочки из общей серии 97090 проверяют все высоты 1..95, наклоны -255..255, пропуски 0..58 и оборачивание
                ;   сверены регистры кроме R, вся физическая RAM и кратность записей, все сочетания произвольных колец не исчерпаны
                ;   строковое ядро целиком, R/T, IRQ, сборка и нативный запуск отдельно не доказаны
                ; -----------------------------------------
                ; -----------------------------------------
                ; Контекст и прямой поиск
                ; Сохранение страницы масок и текущей строки в существующем временном стеке.
Entry:          LD L, D
                PUSH HL
                ; Чтение курсора правой цепочки и первоначальной Second, поиск не перечитывает её при пропуске вершин.
                LD HL, #0000
                DEC L
                LD E, (HL)
                INC L
                ; Проверка достижения последней First перед продвижением вперёд по кольцу.
NextRow:        LD A, L
                CP #00
                JR Z, @ThreeD.WrapPolygonRightEdge.Entry                        ; переход, если достигнут последний нечётный индекс, продолжить с первой First списка

                ; Поиск следующей First в той же странице контура.
                INC L
                INC L
                ; Расчёт высоты кандидата относительно текущей строки.
ReadNextRow:    LD A, (HL)
                SUB D
                JR Z, @ThreeD.UpdatePolygonRightEdge.NextRow                    ; переход, если высота равна нулю, пропустить горизонтальный участок

                JR C, @ThreeD.UpdatePolygonRightEdge.NextRow                    ; переход, если First кандидата меньше текущей строки, продолжить поиск восходящего ребра

                ; Обновление конечной вершины, высоты ребра и его нижнего предела.
                LD (@ActionPolygonPreparationState.RightCursor), HL
                LD D, A
                LD (@ActionPolygonRightEdgeState.Height), A
                ; Расчёт начальной ошибки как половины высоты и сохранение её в H'.
                SRL A
                EXX
                LD H, A
                EXX
                LD A, (HL)
                LD (@ActionPolygonPreparationState.RightEndRow), A
                ; Расчёт знакового горизонтального смещения относительно первоначальной Second.
                DEC L
                LD A, (HL)
                SUB E
                JP C, @ThreeD.UpdatePolygonRightEdge.NegativeSlope              ; переход, если Second конца меньше первоначальной Second, обработать отрицательный наклон

                ; Проверка необходимости деления неотрицательного наклона на высоту.
                CP D
                JP C, @ThreeD.UpdatePolygonRightEdge.ShortPositive              ; переход, если dx меньше высоты, использовать короткую положительную ветвь без деления

                ; -----------------------------------------
                ; Неотрицательное деление
                ; Подготовка модуля dx и нулевого остатка для восьми разрядов частного.
                LD E, A
                XOR A
                ; Расчёт следующего разряда частного по удвоенному остатку и очередному разряду модуля dx.
                RL E
                RLA
                SUB D
                JR NC, @ThreeD.UpdatePolygonRightEdge.PositiveBit0              ; переход, если пробное вычитание высоты не дало заёма, сохранить уменьшенный остаток

                ADD A, D
                ; Расчёт следующего разряда частного по удвоенному остатку и очередному разряду модуля dx.
PositiveBit0:   RL E
                RLA
                SUB D
                JR NC, @ThreeD.UpdatePolygonRightEdge.PositiveBit1              ; переход, если пробное вычитание высоты не дало заёма, сохранить уменьшенный остаток

                ADD A, D
                ; Расчёт следующего разряда частного по удвоенному остатку и очередному разряду модуля dx.
PositiveBit1:   RL E
                RLA
                SUB D
                JR NC, @ThreeD.UpdatePolygonRightEdge.PositiveBit2              ; переход, если пробное вычитание высоты не дало заёма, сохранить уменьшенный остаток

                ADD A, D
                ; Расчёт следующего разряда частного по удвоенному остатку и очередному разряду модуля dx.
PositiveBit2:   RL E
                RLA
                SUB D
                JR NC, @ThreeD.UpdatePolygonRightEdge.PositiveBit3              ; переход, если пробное вычитание высоты не дало заёма, сохранить уменьшенный остаток

                ADD A, D
                ; Расчёт следующего разряда частного по удвоенному остатку и очередному разряду модуля dx.
PositiveBit3:   RL E
                RLA
                SUB D
                JR NC, @ThreeD.UpdatePolygonRightEdge.PositiveBit4              ; переход, если пробное вычитание высоты не дало заёма, сохранить уменьшенный остаток

                ADD A, D
                ; Расчёт следующего разряда частного по удвоенному остатку и очередному разряду модуля dx.
PositiveBit4:   RL E
                RLA
                SUB D
                JR NC, @ThreeD.UpdatePolygonRightEdge.PositiveBit5              ; переход, если пробное вычитание высоты не дало заёма, сохранить уменьшенный остаток

                ADD A, D
                ; Расчёт следующего разряда частного по удвоенному остатку и очередному разряду модуля dx.
PositiveBit5:   RL E
                RLA
                SUB D
                JR NC, @ThreeD.UpdatePolygonRightEdge.PositiveBit6              ; переход, если пробное вычитание высоты не дало заёма, сохранить уменьшенный остаток

                ADD A, D
                ; Расчёт следующего разряда частного по удвоенному остатку и очередному разряду модуля dx.
PositiveBit6:   RL E
                RLA
                SUB D
                JR NC, @ThreeD.UpdatePolygonRightEdge.PositiveBit7              ; переход, если пробное вычитание высоты не дало заёма, сохранить уменьшенный остаток

                ADD A, D
PositiveBit7:   RL E
                ; Проверка точного деления после получения всех разрядов.
                AND A
                JR Z, @ThreeD.UpdatePolygonRightEdge.ExactPositive              ; переход, если остаток равен нулю, вычитаемая ошибка равна нулю

                ; Расчёт дополнения остатка до высоты для Subtract и целого шага с округлением вверх.
                SUB D
                NEG
                LD (@ActionPolygonRightEdgeState.Subtract), A
                LD A, E
                NEG
                SRL A
                ; Упаковка целого шага в DE', один пиксель соответствует 32, строка добавляет 2000.
                EXX
                LD E, #00
                RR E
                RRA
                RR E
                RRA
                RR E
                ADD A, #20
                LD D, A
                EXX
                ; Восстановление страницы масок и текущей строки перед общим выбором предела.
                POP HL
                LD D, L
                JP @ThreeD.SelectPolygonRowLimit.Entry

                ; Точное неотрицательное деление, обновление нулевой ошибки и упаковка целого шага.
ExactPositive:  LD (@ActionPolygonRightEdgeState.Subtract), A
                LD A, E
                CPL
                RRA
                EXX
                LD E, #00
                RR E
                SRA A
                RR E
                SRA A
                RR E
                ADD A, #20
                LD D, A
                EXX
                POP HL
                LD D, L
                JP @ThreeD.SelectPolygonRowLimit.Entry

                ; -----------------------------------------
                ; Короткий неотрицательный наклон
                ; Расчёт вычитаемой ошибки Height-dx при фиксированном шаге плюс один пиксель.
ShortPositive:  SUB D
                NEG
                LD (@ActionPolygonRightEdgeState.Subtract), A
                EXX
                LD E, #20
                LD D, E
                EXX
                POP HL
                LD D, L
                JP @ThreeD.SelectPolygonRowLimit.Entry

                ; -----------------------------------------
                ; Отрицательное деление
                ; Расчёт модуля отрицательного dx и проверка короткой ветви.
NegativeSlope:  NEG
                CP D
                JP C, @ThreeD.SetShortNegativeRightStep.Entry                   ; переход, если abs(dx) меньше высоты, продолжить в вынесенном хвосте короткого отрицательного шага

                ; Подготовка модуля dx и нулевого остатка для отрицательного наклона.
                LD E, A
                XOR A
                ; Расчёт следующего разряда частного по удвоенному остатку и очередному разряду модуля dx.
                RL E
                RLA
                SUB D
                JR NC, @ThreeD.UpdatePolygonRightEdge.NegativeBit0              ; переход, если пробное вычитание высоты не дало заёма, сохранить уменьшенный остаток

                ADD A, D
                ; Расчёт следующего разряда частного по удвоенному остатку и очередному разряду модуля dx.
NegativeBit0:   RL E
                RLA
                SUB D
                JR NC, @ThreeD.UpdatePolygonRightEdge.NegativeBit1              ; переход, если пробное вычитание высоты не дало заёма, сохранить уменьшенный остаток

                ADD A, D
                ; Расчёт следующего разряда частного по удвоенному остатку и очередному разряду модуля dx.
NegativeBit1:   RL E
                RLA
                SUB D
                JR NC, @ThreeD.UpdatePolygonRightEdge.NegativeBit2              ; переход, если пробное вычитание высоты не дало заёма, сохранить уменьшенный остаток

                ADD A, D
                ; Расчёт следующего разряда частного по удвоенному остатку и очередному разряду модуля dx.
NegativeBit2:   RL E
                RLA
                SUB D
                JR NC, @ThreeD.UpdatePolygonRightEdge.NegativeBit3              ; переход, если пробное вычитание высоты не дало заёма, сохранить уменьшенный остаток

                ADD A, D
                ; Расчёт следующего разряда частного по удвоенному остатку и очередному разряду модуля dx.
NegativeBit3:   RL E
                RLA
                SUB D
                JR NC, @ThreeD.UpdatePolygonRightEdge.NegativeBit4              ; переход, если пробное вычитание высоты не дало заёма, сохранить уменьшенный остаток

                ADD A, D
                ; Расчёт следующего разряда частного по удвоенному остатку и очередному разряду модуля dx.
NegativeBit4:   RL E
                RLA
                SUB D
                JR NC, @ThreeD.UpdatePolygonRightEdge.NegativeBit5              ; переход, если пробное вычитание высоты не дало заёма, сохранить уменьшенный остаток

                ADD A, D
                ; Расчёт следующего разряда частного по удвоенному остатку и очередному разряду модуля dx.
NegativeBit5:   RL E
                RLA
                SUB D
                JR NC, @ThreeD.UpdatePolygonRightEdge.NegativeBit6              ; переход, если пробное вычитание высоты не дало заёма, сохранить уменьшенный остаток

                ADD A, D
                ; Расчёт следующего разряда частного по удвоенному остатку и очередному разряду модуля dx.
NegativeBit6:   RL E
                RLA
                SUB D
                JR NC, @ThreeD.UpdatePolygonRightEdge.NegativeBit7              ; переход, если пробное вычитание высоты не дало заёма, сохранить уменьшенный остаток

                ADD A, D
                ; Обновление Subtract остатком отрицательного деления, E сохраняет половинное дополненное частное.
NegativeBit7:   LD (@ActionPolygonRightEdgeState.Subtract), A
                ; Расчёт целого шага из дополненного частного и последнего бита, сохранённого в Carry.
                LD A, E
                RLA
                INC A
                SCF
                RRA
                ; Упаковка отрицательного целого шага в DE'.
                EXX
                LD E, #00
                RR E
                SRA A
                RR E
                SRA A
                RR E
                ADD A, #20
                LD D, A
                ; Восстановление страницы масок и текущей строки перед последовательным общим продолжением.
                EXX
                POP HL
                LD D, L
                ; JP @ThreeD.SelectPolygonRowLimit.Entry, продолжение в SelectPolygonRowLimit.asm

                ; -----------------------------------------
                endmodule
                endmodule
