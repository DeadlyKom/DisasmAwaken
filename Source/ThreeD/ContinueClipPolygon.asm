                module ThreeD
                module ContinueClipPolygon
                ; Документация [алгоритм и проверка](../../Docs/ThreeDOverlayMirror.md)
                ; -----------------------------------------
                ; Восстановление счётчика после ребра и продолжение либо возврат полного полигона
                ; исходная запись 19, банк 0, смещения #0071..#0079
                ; In:
                ;   приватное продолжение ClipPolygon после RET обработчика, SP указывает на сохранённый BC, затем сохранённый указатель и внешний возврат
                ;   остальные состояния, выходная страница и рамка соответствуют уже выполненному ребру ClipPolygon, прямой обычный CALL не соответствует договору
                ; Out:
                ;   BC восстановлен, B уменьшен через DJNZ, при ненуле исполнение продолжается в ClipPolygon.CopyLastPoint
                ;   при исчерпанном B восстанавливается HL за списком, A=OutputSize, F от CP размера,6
                ;   при завершении полного контура выход соответствует ClipPolygon, для непосредственного конца SP увеличен на шесть с учётом снятия двух служебных слов и внешнего RET
                ; Corrupt:
                ;   BC, HL, AF, SP и R на непосредственном конце, при продолжении все изменения ClipPolygon
                ; Note:
                ;   дисковая копия слота 19 побайтово совпадает с ACTION по исходным смещениям 6000..801F
                ;   перенос доказательств требует тех же внешней RAM, банка 0, состояния входа и договоров общих процедур вне файла
                ;   нативная загрузка отдельного 3DPART не выполнялась, CF08 сохраняет отдельную неоднозначность исполнения
                ;   после CP исполнение последовательно идёт в общий ReturnClipCase, добавочная инструкция RET не вводится
                ;   продолжение действительно исполнено в общей серии 5171 сценарий полного полигона, произвольные несогласованные приватные рамки не проверены
                ; -----------------------------------------
                ; -----------------------------------------
                ; Продолжение после обработки ребра
                ; Восстановление счётчика текущего ребра, DJNZ сохраняет флаги обработчика.
Entry:          POP BC
                DJNZ @ThreeD.ClipPolygon.CopyLastPoint

                ; Восстановление конечного указателя и проверка минимального полигона из трёх выходных пар.
                POP HL
                LD A, (@ActionClipIntersectionsState.OutputSize)
                CP @ActionPolygonConst.MinimumBytes
                ; JP @ThreeD.ReturnClipCase.Entry, продолжение в ReturnClipCase.asm

                endmodule
                endmodule
