                module IntroTemplates
                module ScrolledSample
; Документация [IntroTemplates](../../Docs/FunctionDetails/IntroTemplates.md)
; -----------------------------------------
; Семибайтовый образец выборки, 64 копии исполняются по адресу #7E00
; исходная запись 3, файловые смещения #0422..#0428
; In:
;   DE - приёмник, BC - смещение источника, SP - указатель на следующее слово источника
; Out:
;   байт из адреса POP HL плюс BC с очищенным битом 6 H записан в DE, E увеличен на один modulo 256
; Corrupt:
;   HL, DE, AF
; Note:
;   SP увеличивается на два, образец не имеет RET и продолжается следующей копией
;   исполняемый адрес #7E00, после 64 копий создан JP #66F3
; -----------------------------------------
Entry:          POP HL
                ADD HL, BC
                RES 6, H
                LD A, (HL)
                LD (DE), A
                INC E
                endmodule
                endmodule
