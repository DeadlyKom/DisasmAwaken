                module IntroTemplates
                module PhaseSum
; Документация [IntroTemplates](../../Docs/FunctionDetails/IntroTemplates.md)
; -----------------------------------------
; 15-байтовый образец суммы четырёх таблиц, 256 копий по адресу #9900
; исходная запись 3, файловые смещения #0A7E..#0A8C
; In:
;   HL, DE, BC - три исходные выборки, HL', DE', BC' - четвёртая выборка, приёмник и таблица результата
; Out:
;   четыре исходных байта суммируются modulo 256 и через таблицу B' выбирается результат для (DE')
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC'
; Note:
;   EX DE,HL меняет роли двух исходных указателей между соседними копиями
;   индексы увеличиваются только младшими байтами, перенос в старшие отсутствует
;   после 256 копий #9900 последний INC E заменён RET, следующий EXX недостижим
;   последний выход оставляет наборы регистров обменёнными, младший байт приёмника после последней записи не увеличивается
; -----------------------------------------
Entry:          LD A, (BC)
                INC C
                ADD A, (HL)
                INC L
                EX DE, HL
                ADD A, (HL)
                INC L
                EXX
                ADD A, (HL)
                INC L
                LD C, A
                LD A, (BC)
                LD (DE), A
                INC E
                EXX
                endmodule
                endmodule
