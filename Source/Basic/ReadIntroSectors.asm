                module Basic
                module ReadIntroSectors
; Документация [Basic](../../Docs/FunctionDetails/Basic.md)
; Подробный разбор [Loader.md](../../Docs/Loader.md)
; -----------------------------------------
; Чтение 44 физических секторов через TR-DOS с возвратом на #6500
; исходная запись 3, файловые смещения #0006..#001D
; In:
;   LoaderState.NextIntroBlock - слово начальной дорожки и сектора, TR-DOS доступен через #3D13
; Out:
;   перед входом TR-DOS HL=#6400, DE=NextIntroBlock, BC=#2C05, AF содержит прежний A и F=#22 плюс входной Carry, IY=#5C3A
; Corrupt:
;   HL, DE, BC, AF, IY, дальнейшие эффекты определяются TR-DOS
; Note:
;   DI запрещает прерывания, IM и I сам загрузчик не меняет
;   SP получает #5FFF, на стек помещается #6500, при входе TR-DOS SP=#5FFD
;   после чтения 44 физических секторов ожидается RET TR-DOS на InitializeIntro, прежний стек вызывающего кода не используется
;   альтернативные регистры и IX сохраняются до передачи управления TR-DOS, после неё сохранение здесь не утверждается
;   ошибка дискового чтения отдельно не проверяется, реальный ROM TR-DOS в изолированном тесте не исполняется
; -----------------------------------------
                ; отключение прерываний перед заменой стека и чтением вступления
Entry:          DI
                ; установка исходного рабочего стека, прежний стек BASIC больше не используется
                LD SP, @LoaderConst.StackTop
                LD IY, @LoaderConst.SystemIY
                ; создание адреса возврата в начало вступления после дискового чтения
                LD HL, @Intro.InitializeIntro.Entry
                PUSH HL
                ; расчёт адреса загрузки на страницу ниже точки входа вступления
                DEC H
                ; чтение исходного слова дорожки и сектора из состояния загрузки
                LD DE, (@LoaderState.NextIntroBlock)
                LD B, @LoaderConst.IntroSectors
                LD C, @TrDos.ReadSectors
                JP @TrDos.Dispatch

                endmodule
                endmodule
