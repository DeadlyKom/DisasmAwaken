                module Final
                module EmitBitmapLine
; Документация [Final](../../Docs/FunctionDetails/Final.md)
; -----------------------------------------
; Копирование 52-байтового образца переноса строки и обновление четырёх адресов SP
; исходная запись 29, файловые смещения #020E..#0233
; In:
;   DE - приёмник, четыре операнда образца #6247 содержат исходные адреса текущей строки
; Out:
;   DE увеличен на 52, адреса источника и приёмника образца переведены к следующей строке
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   копируется текущий образец до обновления его операндов, вторые половины задаются прибавлением #10
; -----------------------------------------
                ; копирование текущего bitmap-образца перед обновлением его четырёх адресов SP
Entry:          LD HL, #6247
                LD BC, #0034
                LDIR
                LD HL, (#6248)
                CALL @Final.NextBitmapLine.Entry
                LD (#6248), HL
                LD BC, #0010
                ADD HL, BC
                LD (#6262), HL
                LD HL, (#6255)
                CALL @Final.NextBitmapLine.Entry
                LD (#6255), HL
                ADD HL, BC
                LD (#626F), HL
                RET


                endmodule
                endmodule
