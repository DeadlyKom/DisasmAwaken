                module Final
                module EmitBitmapLine
; Документация [Final](../../Docs/FunctionDetails/Final.md)
                ; Подробный разбор [выдача bitmap-строки](../../Docs/FinalBitmapLineEmission.md)
; -----------------------------------------
; Копирование 52-байтового образца переноса строки и обновление четырёх адресов SP
; исходная запись 29, файловые смещения #020E..#0233
                ; In:
                ;   DE указывает 52 свободных байта вне исполняемого кода, шаблона и CPU-стека
                ;   операнд BitmapLine.Entry+1 задаёт SP источника столбца 0 в C000..D7E0, операнд WriteFirstHalf+1 задаёт конец половины столбца 16 в 4010..57F0
                ;   оба адреса принадлежат строкам 0..191, номера строк источника и приёмника могут различаться
                ;   исходный шаблон и NextBitmapLine доступны, SP указывает внешний возврат, два байта под SP свободны, IRQ не вмешиваются
                ; Out:
                ;   HL равен новому WriteLastHalf, DE увеличен на 52, BC=0010, SP увеличен на два при RET
                ;   приёмник содержит прежние 52 байта шаблона, включая прежние операнды, до их обновления
                ;   первые SP источника и приёмника переведены к следующим строкам, вторые SP получают соответствующее новое значение плюс 10
                ;   после строки 191 первый источник переходит в D800, конец первой половины приёмника в 5810, HL=5820
                ;   A равен номеру следующей строки внутри знакоместа, если исходный номер строки имеет остаток 0..6 при делении на 8
                ;   при конце знакоместа A равен 10 для последнего знакоместного ряда трети, иначе старшему байту нового WriteFirstHalf
                ;   флаг, S=Z=N=C=0, P/V задаёт чётность A только внутри знакоместа, на границе знакомест P/V=0
                ;   флаг, H задаёт перенос из разряда 11 последнего сложения с 10, биты 5 и 3 F взяты из H результата
                ;   альтернативные пары, IX, IY, I, IM и IFF сохранены, R меняется, портовых операций нет
                ; Corrupt:
                ;   HL, DE, BC, AF, R, SP снятием возврата, 52 байта приёмника, восемь байтов операндов шаблона и два байта под входным SP
                ; Note:
                ;   два CALL последовательно оставляют под входным SP слова 621C и 622C, перед RET остаётся 622C
                ;   копируется текущий образец до обновления его операндов, несогласованные вторые половины в копии не исправляются
                ;   36864 пары строк сверены с независимой экранной геометрией, все регистры кроме R/T и кратность записей проверены
                ;   исполнение скопированного шаблона, перекрытия, IRQ и произвольные столбцы этой проверкой не подтверждены
; -----------------------------------------
                ; копирование текущего bitmap-образца перед обновлением его четырёх адресов SP
Entry:          LD HL, @FinalTemplates.BitmapLine.Entry
                LD BC, #0034
                LDIR
                LD HL, (@FinalTemplates.BitmapLine.Entry + 1)
                CALL @Final.NextBitmapLine.Entry
                LD (@FinalTemplates.BitmapLine.Entry + 1), HL
                LD BC, #0010
                ADD HL, BC
                LD (@FinalTemplates.BitmapLine.ReadSecondHalf + 1), HL
                LD HL, (@FinalTemplates.BitmapLine.WriteFirstHalf + 1)
                CALL @Final.NextBitmapLine.Entry
                LD (@FinalTemplates.BitmapLine.WriteFirstHalf + 1), HL
                ADD HL, BC
                LD (@FinalTemplates.BitmapLine.WriteLastHalf + 1), HL
                RET


                endmodule
                endmodule
