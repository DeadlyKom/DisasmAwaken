                module Final
                module Interrupt
; Документация [Final](../../Docs/FunctionDetails/Final.md)
; -----------------------------------------
; Обработчик прерывания финальной сцены
; исходная запись 29, файловые смещения #016C..#0179
; In:
;   AF' - сохранённое состояние, #6173 содержит полный байт управления #7FFD
; Out:
;   BC - #7FFD, выбранная страница установлена, прерывания разрешены
; Corrupt:
;   BC
; Note:
;   основной и альтернативный AF сохраняются, остальные регистры данных не используются
;   при входе из вставки HALT временный SP=#6196, адрес возврата занимает #6194..#6195, PUSH AF занимает #6192..#6193
;   выход через EI и RET, инструкция RETI не используется
; -----------------------------------------
                ; сохранение обоих AF через альтернативный набор, BC намеренно занимает номер порта
Entry:          DI
                EX AF, AF'
                PUSH AF
                LD BC, #7FFD
                LD A, #00
                OUT (C), A
                POP AF
                EX AF, AF'
                EI
                RET


                endmodule
                endmodule
