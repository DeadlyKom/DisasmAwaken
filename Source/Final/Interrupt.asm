                module Final
                module Interrupt
; Документация [Final](../../Docs/FunctionDetails/Final.md)
; Подробный разбор [временный стек прерывания](../../Docs/FinalCycle.md)
                ; Проверка [точный контракт IRQ](../../Docs/FinalInterruptContract.md)
; -----------------------------------------
; Обработчик прерывания финальной сцены
; исходная запись 29, файловые смещения #016C..#0179
                ; In:
                ;   HL, DE, BC, AF, альтернативные пары, IX и IY входных аргументов не задают
                ;   PagePatch задаёт полный байт OUT 7FFD, обработчик и CPU-стек доступны без перекрытия кода и операнда
                ;   при входном SP=s по s лежит адрес возврата, два байта s-2..s-1 доступны для PUSH AF
                ;   после OUT сохранённые AF' и адрес возврата читаются из тех же физических байтов, NMI исключён
                ; Out:
                ;   HL, DE сохранены, BC=7FFD, AF, HL', DE', BC', AF', IX, IY, I и IM сохранены
                ;   SP=s+2, PC снят со стека, IFF1 и IFF2 установлены инструкцией EI перед RET
                ;   в 7FFD выдан PagePatch, при исходной блокировке битом 5 конфигурация сохраняется, иначе принимается выданный байт
                ;   два байта s-2..s-1 содержат исходный AF' в младшем и старшем порядке
                ;   R получает 11 M1 с сохранением бита 7, десять инструкций занимают 76 T без аппаратного входа и ожиданий
                ; Corrupt:
                ;   BC, R, SP снятием возврата, IFF, защёлка 7FFD и два байта под входным SP
                ; Note:
                ;   сохранение AF' и возврата требует стабильного отображения CPU-стека через OUT, основной AF не помещается в память
                ;   для стека C000..FFFF смена банка без зеркала читает чужой AF' и чужой адрес возврата, это не допустимый штатный вход
                ;   штатный цикл выбирает 08 затем 00 в первом выводе и 01 затем 01 во втором, младшие три бита банка не меняются
                ;   при входе из HALT аппаратный SP=6194, возврат занимает 6194..6195, PUSH AF занимает 6192..6193
                ;   при IRQ внутри вывода четыре байта аппаратной рамки и AF' могут попасть в ещё не заполненную часть строки
                ;   LD BC,7FFD заменяет пиксельное слово BC, которое может ещё понадобиться следующему PUSH цепочки
                ;   458816 сценариев сверяют все регистры, R/T, две записи стека и OUT, включая рамку на границе 7FFF/8000, аппаратный вход и вложенные IRQ не исполняются
                ;   выход через EI и RET, инструкция RETI не используется
; -----------------------------------------
                ; сохранение обоих AF через альтернативный набор, BC намеренно занимает номер порта
Entry:          DI
                EX AF, AF'
                PUSH AF
                LD BC, #7FFD
PagePatch:      LD A, #00
                OUT (C), A
                POP AF
                EX AF, AF'
                EI
                RET


                endmodule
                endmodule
