                module Final
                module HaltFinal
; Документация [Final](../../Docs/FunctionDetails/Final.md)
                ; Документация [алгоритм и проверка](../../Docs/FinalHalt.md)
; -----------------------------------------
; Выбор страниц и режима IM 0, очистка атрибутов теневого экрана и остановка через DI и HALT
; исходная запись 29, файловые смещения #0148..#016B
                ; In:
                ;   AF - S, Z и Carry входного F сохраняются до конечного состояния, числовые регистры аргументов не задают
                ;   защёлка 7FFD доступна, для штатного теневого экрана её бит 5 должен быть сброшен
                ;   окно D800..DAFF фактически выбранного банка доступно для записи
                ;   аппаратный IRQ не принимается в коротком окне после EI, NMI и внешнее снятие HALT исключены из данного контракта
                ; Out:
                ;   HL=DAFF, DE=DB00, BC=0, A=1F, F=(входной F AND C1) OR 28
                ;   HL', DE', BC', AF', IX и IY сохранены, CPU SP не меняется
                ;   I=3C, IM=0, IFF=0, процессор остановлен на HALT по 616B, возврата через RET нет
                ;   в порт 7FFD последовательно выданы 17 и 1F, при исходной блокировке обе записи игнорируются защёлкой
                ;   при доступном paging итоговая защёлка 1F выбирает банк 7, ROM 1 и теневой экран, блокировка не устанавливается
                ;   768 атрибутов D800..DAFF фактически выбранного банка обнулены, bitmap и CPU-стек не записываются
                ; Corrupt:
                ;   HL, DE, BC, AF, I, IM, IFF, состояние HALT, доступная защёлка 7FFD и 768 байтов атрибутов
                ; Note:
                ;   первый нулевой байт задаётся LD (HL),00, остальные 767 распространяются перекрывающимся LDIR
                ;   конечный LDIR сохраняет S, Z и Carry, сбрасывает H, N и PV, недокументированные биты F получаются из A=1F
                ;   DI после очистки запрещает обычные маскируемые IRQ, код соседнего Interrupt не является обычным продолжением этого пути
                ;   при исходной блокировке 7FFD не гарантируются банк 7 и теневой экран, процедура не проверяет и не снимает блокировку
                ;   16384 сценария исчерпали все F и все шесть битов начальной защёлки, проверены регистры кроме R, все банки RAM, порты и кратность записей
                ;   восемь тысяч сто девяносто два сценария имеют заблокированный paging, инструкция EI исполняется без аппаратного IRQ
                ;   R/T, влияние аппаратного IRQ в окне EI, NMI и нативное завершение игры не доказаны
                ; -----------------------------------------
                ; остановка финальной сцены с чёрными атрибутами теневого экрана
Entry:          IM 0
                LD BC, #7FFD
                LD A, #17
                OUT (C), A
                LD A, #3C
                LD I, A
                EI
                LD A, #1F
                LD BC, #7FFD
                OUT (C), A
                LD HL, #D800
                LD DE, #D801
                LD BC, #02FF
                LD (HL), #00
                LDIR
                DI
                HALT
                ; JP @Final.Interrupt.Entry, продолжение в Interrupt.asm

                endmodule
                endmodule
