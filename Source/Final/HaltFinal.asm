                module Final
                module HaltFinal
; Документация [Final](../../Docs/FunctionDetails/Final.md)
; -----------------------------------------
; Выбор страниц и режима IM 0, очистка атрибутов теневого экрана и остановка через DI и HALT
; исходная запись 29, файловые смещения #0148..#016B
; In:
;   Unknown, регистровый контракт ещё не доказан
; Out:
;   исходный поток управления, включая переходы в соседние фрагменты
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY, консервативная верхняя граница
; Note:
;   граница файла не доказывает границу логической процедуры
;   состояние самомодификации и активной страницы учитывается отдельно
;   устанавливаются IM 0 и I=#3C, затем выбирается теневой экран банка 7 и его атрибуты очищаются
;   последовательность DI и HALT не возвращается без внешнего события, обычное маскируемое IRQ запрещено
; -----------------------------------------
                ; остановка финальной сцены с чёрными атрибутами теневого экрана
Entry:          IM 0
                LD BC, #7FFD
                LD A, #17
                OUT (C), A
                LD A, #3C
                LD I, A
                EI
                LD A, #1F
                LD BC, #7FFD
                OUT (C), A
                LD HL, #D800
                LD DE, #D801
                LD BC, #02FF
                LD (HL), #00
                LDIR
                DI
                HALT
                ; JP @Final.Interrupt.Entry, продолжение в Interrupt.asm

                endmodule
                endmodule
