                module Final
                module BuildDisplayChain
                ; Внутренние входы [алгоритм](../../Docs/ArithmeticFinalInternalLabels.md)
                ; Документация [физические указатели синхронизации](../../Docs/FinalSyncAndPreviewRecord.md)
; Документация [Final](../../Docs/FunctionDetails/Final.md)
                ; Подробный разбор [контракт построителя](../../Docs/FinalChainBuilder.md)
; -----------------------------------------
; Создание 24 групп по восемь bitmap-строк и полосе атрибутов с двумя местами вставки синхронизации
; исходная запись 29, файловые смещения #01DF..#020D
                ; In:
                ;   HL задаёт начало приёмника start, BC задаёт сохраняемый C, остальные регистры входных аргументов не задают
                ;   участок start..start+292F доступен без оборачивания и не перекрывает код, шаблоны, указатели синхронизации и CPU-стек
                ;   PrepareFrame настроил четыре SP bitmap-образца на C000, 4010, C010 и 4020, SP атрибутного образца равен 5820
                ;   EmitAttributeRow выбирает исходный адрес 627D и длину 0017, шаблоны и дочерние процедуры доступны по их договорам
                ;   SP указывает внешний возврат, восемь байтов под входным SP свободны, IRQ не вмешиваются
                ; Out:
                ;   HL=5B20, DE=start+2930, B=0, C сохранён, AF=019B, SP увеличен на два при RET
                ;   созданы 192 bitmap-образца по 52 байта и 24 атрибутных по 23 байта, всего 10536 записанных байтов
                ;   два промежутка по четыре байта после десятого и восемнадцатого знакоместных рядов сохраняют прежнее содержимое
                ;   AfterRow10=start+1126, AfterRow18=start+1EE2, оба указателя записаны в FinalSyncPointers.Value
                ;   четыре SP bitmap-оригинала равны D800, 5810, D810 и 5820, SP атрибутного оригинала равен 5B20
                ;   альтернативные пары, IX, IY, I, IM и IFF сохранены, R меняется, портовых операций нет
                ; Corrupt:
                ;   HL, DE, BC только B, AF, R, SP снятием возврата, приёмник вне двух промежутков, операнды шаблонов, два указателя и восемь байтов под входным SP
                ; Note:
                ;   заголовок сохранения SP и завершающие LD SP,nn и RET добавляет PrepareFrame, этот вход создаёт только тело цепочки
                ;   под входным SP=s остаются слова s-8=622C, s-6=61E9, s-4=61EF и s-2=0100 с исходным C в младшем байте
                ;   восемь байтов двух вставок только пропускаются, ни одна собственная запись построителя их не заполняет
                ;   272 сценария охватывают все C и три положения приёмника, сверены все регистры кроме R/T и все 65536 байтов RAM
                ;   в каждом сценарии проверена кратность 13756 записей по адресам, скопированная цепочка не исполняется, IRQ и перекрытия не проверены
; -----------------------------------------
                ; создание 24 знакоместных рядов, по восемь строк bitmap в каждом
Entry:          LD B, #18
                EX DE, HL
CharacterRow:   PUSH BC
                LD B, #08
BitmapLine:     PUSH BC
                CALL @Final.EmitBitmapLine.Entry
                POP BC
                DJNZ @Final.BuildDisplayChain.BitmapLine

                CALL @Final.EmitAttributeRow.Entry
                POP BC
                LD A, B
                CP #07
                JP NZ, @Final.BuildDisplayChain.CheckFirstSync                  ; переход, если осталось не семь рядов, пропустить место синхронизации после восемнадцатого


                ; Сохранение адреса вставки после восемнадцатого знакоместного ряда.
                LD (@FinalSyncPointers.Value.AfterRow18), DE
                INC DE
                INC DE
                INC DE
                INC DE
CheckFirstSync: CP #0F
                JP NZ, @Final.BuildDisplayChain.CountRows                       ; переход, если осталось не пятнадцать рядов, пропустить место синхронизации после десятого


                ; Сохранение адреса вставки после десятого знакоместного ряда.
                LD (@FinalSyncPointers.Value.AfterRow10), DE
                INC DE
                INC DE
                INC DE
                INC DE
CountRows:      DJNZ @Final.BuildDisplayChain.CharacterRow

                RET


                endmodule
                endmodule
