                module NextBitmapLine
; Документация [Final](../../Docs/FunctionDetails/Final.md)
; -----------------------------------------
; Переход к следующей пиксельной строке в экранной раскладке Spectrum
; исходная запись 29, файловые смещения #0296..#02A4
; In:
;   HL - адрес байта пиксельной строки Spectrum
; Out:
;   HL - байт того же столбца следующей строки, после строки 191 адрес переходит в атрибуты
; Corrupt:
;   HL, AF
; Note:
;   DE, BC, индексные и альтернативные регистры сохраняются, проверены 192 строки и четыре столбца
; -----------------------------------------
                ; расчёт следующей строки в пределах знакоместа и перехода между знакоместами Spectrum
Entry:          INC H
                LD A, H
                AND #07
                RET NZ                                                          ; выход, если флаг Z сброшен

                LD A, L
                ADD A, #20
                LD L, A
                RET C                                                           ; выход, если флаг Carry установлен

                LD A, H
                SUB #08
                LD H, A
                RET


                endmodule
                endmodule
