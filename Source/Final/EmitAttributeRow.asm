                module Final
                module EmitAttributeRow
; Документация [Final](../../Docs/FunctionDetails/Final.md)
                ; Подробный разбор [выдача ряда атрибутов](../../Docs/FinalAttributeRowEmission.md)
; -----------------------------------------
; Копирование 23-байтового образца атрибутов и переход к следующему 32-байтовому ряду
; исходная запись 29, файловые смещения #0234..#0246
                ; In:
                ;   DE указывает 23 свободных байта вне кода, шаблона и CPU-стека, приёмник доступен для записи
                ;   операнд Entry+1 равен 627D, TemplateSize+1 равен 0017, операнд AttributeRow.AttrStack+1 содержит исходный конец ряда
                ;   SP указывает внешний возврат вне приёмника, IRQ не вмешиваются, исходные инструкции и шаблон доступны
                ; Out:
                ;   HL и операнд AttrStack равны исходному концу ряда плюс 20 по модулю 65536, DE увеличен на 23, BC=0020, A сохранён
                ;   приёмник содержит прежние 23 байта шаблона, включая прежний операнд SP, обновление оригинала выполняется после копирования
                ;   флаг, S и Z сохраняются, P/V и N сброшены, H и C задают переносы из разрядов 11 и 15 при сложении с 20
                ;   биты 5 и 3 F равны соответствующим битам H результата
                ;   альтернативные пары, IX, IY, I, IM и IFF сохранены, SP увеличен на два при RET
                ;   R получает 53 M1 с сохранением бита 7, выполнение занимает 561 T без ожиданий и прерываний, портовых операций нет
                ; Corrupt:
                ;   HL, DE, BC, AF только флагами, R, SP снятием возврата, 23 байта приёмника и два байта операнда AttrStack
                ; Note:
                ;   процедура не пишет CPU-стек, внешний адрес возврата и предшествующие ему байты сохраняются
                ;   образец содержит 16 PUSH HL, это 32 байта атрибутов, а не 16 атрибутов
                ;   после копирования последнего штатного ряда с концом 5B00 операнд оригинала становится 5B20, эта следующая строка не выводится
                ;   71680 сценариев охватывают все слова операнда и все 256 значений F для каждого из 24 штатных рядов
                ;   проверка сверяет все регистры, R/T и кратность записей, копия не исполняется, изменённые длины, перекрытия и IRQ не проверены
; -----------------------------------------
                ; копирование атрибутного образца и расчёт конца следующего 32-байтового ряда
Entry:          LD HL, @FinalTemplates.AttributeRow.Entry
TemplateSize:   LD BC, #0017
                LDIR
                LD HL, (@FinalTemplates.AttributeRow.AttrStack + 1)
                LD BC, #0020
                ADD HL, BC
                LD (@FinalTemplates.AttributeRow.AttrStack + 1), HL
                RET


                endmodule
                endmodule
