                module Final
                module PrepareFrame
; Документация [Final](../../Docs/FunctionDetails/Final.md)
; -----------------------------------------
; Подготовка изменяемой цепочки команд финальной анимации
; исходная запись 29, файловые смещения #0196..#01DE
; In:
;   дополнительные параметры не требуются, стек должен находиться вне создаваемой цепочки #8000..#A937
; Out:
;   #8000..#A937 содержат цепочку 10552 байта, #62A5=#9EE6, #62A7=#912A, прерывания запрещены
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   первые четыре байта ED 73 35 A9 сохраняют входной SP в операнде завершающего LD SP,nn
;   два места по четыре байта при построении только пропускаются, до исполнения их заполняет основной цикл
;   два байта операнда восстановления SP до исполнения содержат прежнюю память, заголовок заменяет их настоящим SP
;   IX, IY и альтернативные регистры построитель не использует
;   bitmap-образец копируется 192 раза, исходные образцы не исполняются по адресам #6247 и #627D
;   между каждыми восемью строками помещается один образец 32 атрибутов
;   первый SP сохраняется в операнде #A935, завершающий RET находится по #A937
; -----------------------------------------
                ; создание исполняемой цепочки поверх уже скопированных исходных bitmap
Entry:          DI
                LD HL, #C000
                LD (#6248), HL
                LD HL, #4010
                LD (#6255), HL
                LD HL, #C010
                LD (#6262), HL
                LD HL, #4020
                LD (#626F), HL
                LD HL, #5820
                LD (#6282), HL
                LD HL, #627D
                LD (#6235), HL
                LD HL, #0017
                LD (#6238), HL
                LD HL, #8000
                LD (HL), #ED
                INC HL
                LD (HL), #73
                INC HL
                PUSH HL
                INC HL
                INC HL
                CALL @Final.BuildDisplayChain.Entry
                EX DE, HL
                LD (HL), #31
                INC HL
                EX DE, HL
                POP HL
                LD (HL), E
                INC HL
                LD (HL), D
                EX DE, HL
                INC HL
                INC HL
                LD (HL), #C9
                RET


                endmodule
                endmodule
