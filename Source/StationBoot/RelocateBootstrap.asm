                module StationBoot
                module RelocateBootstrap
                ; Документация [StationBoot](../../Docs/FunctionDetails/StationBoot.md)
                ; Документация [алгоритм и проверка](../../Docs/BootstrapRelocation.md)
                ; -----------------------------------------
                ; Очистка атрибутов и перенос #02B5 байт загрузчика в #4000
                ; исходная запись 4, файловые смещения #0300..#0318
                ; In:
                ;   AF - A и S, Z, Carry сохраняемый контекст, числовые регистры аргументов не задают
                ;   STATIONF загружен по 6000, исходные 6319..65CD доступны для чтения
                ;   4000..42B4 и атрибуты 5800..5AFF доступны для записи, стек не перекрывает их и исходный код
                ;   SP - внешний CPU-стек с двумя доступными байтами ниже него, IRQ не вмешивается
                ; Out:
                ;   HL=65CE, DE=42B5, BC=0, A сохранён
                ;   S, Z и Carry сохранены, H, N и PV сброшены, биты 3 и 5 F от суммы A и последнего переносимого байта по правилам LDIR
                ;   HL', DE', BC', AF', IX и IY, I/IM/IFF и paging сохраняются
                ;   693 байта 6319..65CD скопированы в 4000..42B4, 768 атрибутов 5800..5AFF обнулены
                ;   PC=4000 перед первой инструкцией InitializeStation, SP равен входному, внешний адрес возврата не снят
                ;   слово 4000 остаётся в двух байтах ниже входного SP после PUSH DE и RET
                ;   R сохраняет бит 7, младшие семь бит увеличиваются по модулю 128 на 2929 M1, число десятичное
                ; Corrupt:
                ;   HL, DE, BC, AF только F, R, 693 байта переноса, 768 атрибутов и два байта ниже SP
                ; Note:
                ;   RET снимает внутренний адрес 4000, созданный PUSH DE, это передача управления загрузчику, а не возврат вызывающему
                ;   693 переносимых байта включают код и данные загрузчика, новая область памяти не выбирается
                ;   HL=65CE также указывает начало следующего исходного ядра, его перенос выполняет InitializeStation
                ;   768 сценариев проверили все значения A и F в сочетаниях, три CPU-стека, все банки RAM и кратность записей
                ;   все пары A/F не исчерпаны, перемещённый код, аппаратные IRQ, время и нативная загрузка здесь не исполнялись
                ;   пошагово сверены все начальные R и полное число M1, T и аппаратные IRQ этим не доказаны
                ; -----------------------------------------
                ; Очистка атрибутов до переноса станционного загрузчика.
                ; Начальный ноль распространяется перекрывающимся LDIR по всем 768 знакоместам.
Entry:          LD HL, #5800
                LD DE, #5801
                LD BC, #02FF
                LD (HL), L
                LDIR
                ; -----------------------------------------
                ; Перенос станционного продолжения.
                ; Адрес InitializeStation кладётся поверх внешнего стека как собственный адрес передачи.
                LD DE, @StationBoot.InitializeStation.Entry
                PUSH DE
                ; Копирование исходного кода и данных загрузчика без изменения их порядка и размеров.
                LD BC, @BootstrapMoveConst.StationBytes
                LD HL, @BootstrapMoveConst.StationSource
                LDIR
                ; Переход в перенесённый InitializeStation, внешний адрес возврата остаётся на стеке.
                RET
                ; -----------------------------------------


                endmodule
                endmodule
