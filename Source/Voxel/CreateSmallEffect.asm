                module Voxel
                module CreateSmallEffect
; Документация [Voxel](../../Docs/FunctionDetails/Voxel.md)
; -----------------------------------------
; Инициализация эффекта с ресурсом #D800 и параметрами #0C, #0C, #0D
; исходная запись 21, файловые смещения #0000..#000D
; In:
;   HL', DE', BC' - три сохраняемых слова, AF - A режим, AF' - A состояние, IY - запись перед началом поиска
; Out:
;   HL - #D800, DE - #00C0, BC - #12, IY - выбранная запись либо ограничитель
; Corrupt:
;   HL, DE, BC, AF, AF', IY
; Note:
;   поля +#0D, +#10 и +#11 получают #0D, #0C и #0C, успешная запись содержит 18 байтов
;   при отрицательном State поиск прекращается без заполнения записи, альтернативные HL, DE и BC сохраняются
;   A задаёт Mode поля +6, A альтернативного набора задаёт State поля +7
;   после этого фрагмента исполняется ConfigureSmallEffect без CALL
;   поля +#10 и +#11 получают #0C, это не нулевые счётчики в созданной записи
; -----------------------------------------
Entry:          LD HL, #D800
                LD DE, #00C0
                LD (#EC5A), A
                LD A, #0C
                LD (#EC7D), A
                ; JP @Voxel.ConfigureSmallEffect.Entry, продолжение в ConfigureSmallEffect.asm

                endmodule
                endmodule
