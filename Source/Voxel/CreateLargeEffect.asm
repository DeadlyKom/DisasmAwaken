; Документация [Voxel](../../Docs/FunctionDetails/Voxel.md)
; -----------------------------------------
; Инициализация эффекта с ресурсом #C400 и параметрами #14, #14, #08
; исходная запись 21, файловые смещения #001B..#0032
; In:
;   HL', DE', BC' - три сохраняемых слова, AF - A режим, AF' - A состояние, IY - запись перед началом поиска
; Out:
;   HL - #C400, DE - #0280, BC - #12, IY - выбранная запись либо ограничитель
; Corrupt:
;   HL, DE, BC, AF, AF', IY
; Note:
;   поля +#0D, +#10 и +#11 получают #08, #14 и #14, успешная запись содержит 18 байтов
;   поиск начинается сразу после входного IY и может закончиться на отрицательной завершающей записи
;   A задаёт Mode поля +6, A альтернативного набора задаёт State поля +7
;   ресурс #C400, параметр DE=#0280, поля +#10 и +#11 равны #14, поле +#0D равно #08
;   поиск свободной записи продолжается непосредственно в AllocateEffect без CALL
; -----------------------------------------
Entry:          LD HL, #C400
                LD DE, #0280
                LD (#EC5A), A
                LD A, #14
                LD (#EC7D), A
                LD A, #14
                LD (#EC79), A
                LD A, #08
                LD (#EC6C), A
                ; JP @Voxel.AllocateEffect.Entry, продолжение в AllocateEffect.asm

                endmodule
                endmodule
